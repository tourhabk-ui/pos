/**
 * Гейт согласия — проверяется НАСТОЯЩИМ БРАУЗЕРОМ, а не чтением HTML.
 *
 * ── Почему не хватило проверки прода по HTML ──────────────────────────────
 *
 * 11.09 правовой контур (#1819) поехал на прод: три сторонних скрипта,
 * грузившиеся на каждой странице безусловно, теперь грузятся только после
 * согласия. Утверждение проверяемое — значит обязано быть проверенным там,
 * где живёт. Проверка (prod-check run 50) спросила прод и НЕ ОТВЕТИЛА, по
 * двум причинам сразу:
 *
 *   1. она печатает голову и хвост тела по 1800 байт, а главная весит
 *      145 381 — середина опущена, искать хосты «глазами» не в чем;
 *   2. глубже и важнее: теги вешаются `next/script` со `strategy=
 *      "afterInteractive"`, то есть их нет в SSR-HTML НИ ПРИ КАКОМ согласии.
 *      Отсутствие хоста в разметке ничего не доказывает — так же молчал бы
 *      и полностью сломанный гейт.
 *
 * Отличить «гейт держит» от «инструмент слеп» может только клиент, который
 * действительно исполняет скрипты и делает запросы. Поэтому здесь считаются
 * СЕТЕВЫЕ ЗАПРОСЫ браузера, а не строки в разметке.
 *
 * ── Положительный контроль обязателен ─────────────────────────────────────
 *
 * Проба, которая умеет только не находить, зеленеет и когда сломана. Поэтому
 * вторым тестом идёт ветка СОГЛАСИЯ: Метрика обязана появиться (её id задан
 * в коде запасным значением, то есть не зависит от переменных прода). Первый
 * тест значит что-то лишь потому, что второй доказывает: этот же счётчик
 * запросы видит.
 *
 * Сам счётчик проверен ещё и отдельно, локально, до выкладки: на статичной
 * странице без тегов он отдаёт пустое множество, на такой же странице со
 * ссылкой на mc.yandex.ru — `["mc.yandex.ru"]`. Слепым он не был на входе.
 *
 * ── Третий исход (§4.0) ───────────────────────────────────────────────────
 *
 * «Не смог проверить» здесь КРАСНЫЙ, а не зелёный: прод не открылся — это не
 * «нарушений нет». Сообщение о падении называет, что именно не удалось.
 */
import { test, expect } from '@playwright/test';
import type { BrowserContext } from '@playwright/test';
import { THIRD_PARTIES } from '../../lib/legal/third-party-registry';
import { CONSENT_STORAGE_KEY, CONSENT_VERSION } from '../../lib/legal/consent';

/**
 * Хосты берутся ИЗ РЕЕСТРА, а не переписываются сюда: свой список разошёлся
 * бы с тем, что грузится, — ровно тот дефект, который контур и чинил.
 */
const TRACKED_HOSTS = THIRD_PARTIES.map((tp) => tp.host);

/** Запрос на сам хост или на его поддомен — и то и другое считается. */
function matchHost(url: string): string | null {
  let host: string;
  try {
    host = new URL(url).host.toLowerCase();
  } catch {
    return null;
  }
  return (
    TRACKED_HOSTS.find((h) => host === h || host.endsWith(`.${h}`) || h.endsWith(`.${host}`)) ?? null
  );
}

/** Ловит запросы контекста к хостам реестра и отдаёт множество увиденных. */
function watchTrackers(ctx: BrowserContext): Set<string> {
  const seen = new Set<string>();
  ctx.on('request', (req) => {
    const hit = matchHost(req.url());
    if (hit) seen.add(hit);
  });
  return seen;
}

/**
 * Открыть главную и дать клиенту время сходить наружу. `afterInteractive`
 * ждёт гидратации, а сам тег потом тянет `tag.js` — секундами это мерить
 * нельзя, поэтому запас щедрый: лишние секунды дешевле ложного зелёного.
 */
async function openHome(ctx: BrowserContext, what: string) {
  const page = await ctx.newPage();
  try {
    await page.goto('/', { waitUntil: 'load', timeout: 60_000 });
  } catch (e) {
    throw new Error(
      `НЕ СМОГ ПРОВЕРИТЬ (${what}): главная прода не открылась — ${String(e)}. `
        + 'Это третий исход, а не «нарушений нет».',
    );
  }
  await page.waitForTimeout(8000);
  return page;
}

test.describe('Согласие на трекеры: гейт на живом проде', () => {
  test('анонимный гость: ни один трекер не грузится до согласия', async ({ browser }) => {
    const ctx = await browser.newContext();
    const seen = watchTrackers(ctx);
    const page = await openHome(ctx, 'ветка без согласия');

    // Баннер обязан быть виден: без него человеку нечем ответить, и «не
    // грузится» вышло бы не из решения, а из того, что спросить забыли.
    await expect(
      page.getByRole('dialog').filter({ hasText: 'Аналитика и партнёрские сервисы' }),
      'баннер согласия не показан — спросить человека нечем',
    ).toBeVisible();

    expect(
      [...seen].sort(),
      `данные ушли до согласия: ${[...seen].join(', ')}`,
    ).toEqual([]);

    await ctx.close();
  });

  test('с согласием: аналитика идёт, реклама без erid — по-прежнему нет', async ({ browser }) => {
    const ctx = await browser.newContext();
    // Согласие сажается ДО навигации тем же ключом и той же версией, что
    // читает приложение (`lib/legal/consent`). Разойдись они — проба
    // проверяла бы ветку «не спрашивали» дважды и молчала бы об этом.
    await ctx.addInitScript(
      ([key, value]) => {
        try {
          window.localStorage.setItem(key, value);
        } catch {
          /* приватное окно — тест ниже покажет это отсутствием Метрики */
        }
      },
      [
        CONSENT_STORAGE_KEY,
        JSON.stringify({
          analytics: true,
          advertising: true,
          at: new Date().toISOString(),
          v: CONSENT_VERSION,
        }),
      ] as const,
    );

    const seen = watchTrackers(ctx);
    const page = await openHome(ctx, 'ветка с согласием');

    await expect(
      page.getByRole('dialog').filter({ hasText: 'Аналитика и партнёрские сервисы' }),
      'баннер показан снова, хотя выбор уже сделан',
    ).toHaveCount(0);

    // ПОЛОЖИТЕЛЬНЫЙ КОНТРОЛЬ. Метрика обязана появиться: её id задан в коде
    // запасным значением и от переменных прода не зависит. Если её нет —
    // сломан либо гейт, либо сама проба, и первый тест ничего не значит.
    expect(
      [...seen],
      'Метрика не пошла даже с согласия — либо гейт не пускает никого, либо проба слепа, '
        + 'и тогда зелёный первый тест ничего не доказывает',
    ).toContain('mc.yandex.ru');

    // Реклама без токена erid не грузится ДАЖЕ с согласия (38-ФЗ ст. 18.1):
    // маркировка — требование к размещению, а не к посетителю.
    const ads = THIRD_PARTIES.filter((tp) => tp.isAdvertising && !tp.erid).map((tp) => tp.host);
    for (const host of ads) {
      expect([...seen], `${host}: немаркированная реклама поехала с согласия`).not.toContain(host);
    }

    // Про Microsoft Clarity здесь НЕ утверждается ничего: его загрузка
    // зависит от NEXT_PUBLIC_CLARITY_ID на проде, а значения переменной
    // репозиторий не знает. «Не видели» тут равно «не знаем, задан ли id», и
    // выдавать это за проверку нельзя.
    await ctx.close();
  });
});
