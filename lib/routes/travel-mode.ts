/**
 * lib/routes/travel-mode.ts — чем по этой линии передвигаются.
 *
 * ── Зачем ─────────────────────────────────────────────────────────────────
 *
 * Черта (lib/routes/navigability) отвечает на вопрос «можно ли обещать, что по
 * этой линии человека проведут». Вопрос предполагает, что по линии ИДУТ: сходят
 * с неё, возвращаются, сверяются с путевыми точками.
 *
 * Владелец 18.08, глядя на разбор двадцати расхождений: «облёт это не пеший
 * маршрут». И правда: «Облет Мутновского и Горелого» — вертолётная программа,
 * у неё 655 точек линии и шесть «путевых точек», и черта честно считала её
 * непригодной для ведения. Но причина была названа неверная — «точка стоит в
 * 4.9 км от линии», как будто с курса вертолёта можно свернуть к фумароле.
 *
 * Линию облёта нельзя пройти, с неё нельзя сойти и на неё нельзя вернуться.
 * Мерить её мерками тропы — не строгость, а бессмыслица: она никогда не
 * пройдёт черту и всегда будет отвлекать причиной, которой не существует.
 *
 * ── Что здесь НЕ решается ─────────────────────────────────────────────────
 *
 * Способ передвижения не делает запись хуже или лучше. Сплав идёт по реке,
 * лыжня — по снегу, джип — по грунтовке; по всем трём линию ПРОХОДЯТ, значит
 * обещание ведения имеет смысл, и черта судит их как прежде. Из суждения
 * выпадает единственный род — воздух.
 *
 * Способ определяется по имени и по `activity_type` записи. Слабая улика, и
 * потому она только СНИМАЕТ обещание, никогда его не выдаёт: ошибиться в
 * сторону «не обещаем» дёшево, в обратную — нет.
 */

export type TravelMode =
  /** По линии идут пешком — умолчание платформы. */
  | 'foot'
  /** Сплав: линия идёт по воде, но её проходят. */
  | 'water'
  /** Лыжи, снегоход: линия по снегу, её проходят. */
  | 'snow'
  /** Джип, квадроцикл: линия по грунтовке, её проходят. */
  | 'vehicle'
  /** Воздух: линию НЕ проходят — вертолёт, самолёт, облёт. */
  | 'air';

/**
 * Признаки воздуха в имени записи.
 *
 * Список короткий и состоит из слов, которых у наземного пути не бывает.
 * «Облёт» пишут и через «ё», и через «е» — в базе встречаются оба.
 */
const AIR_MARKERS: RegExp[] = [
  /обл[еёя]т/i,
  /вертол[её]т/i,
  /гелик/i,
  /авиа(?!с)/i,
  /(^|\s)с\s+воздуха($|\s)/i,
  /аэроэкскурс/i,
];

const WATER_MARKERS: RegExp[] = [/сплав/i, /рафтинг/i, /(^|\s)байдар/i, /морская\s+прогулк/i];
const SNOW_MARKERS: RegExp[] = [/лыжн/i, /снегоход/i, /ски-?тур/i];
const VEHICLE_MARKERS: RegExp[] = [/джип/i, /квадроцикл/i, /багги/i, /внедорожн/i];

function matches(text: string, markers: RegExp[]): boolean {
  return markers.some((re) => re.test(text));
}

/**
 * Способ передвижения по записи маршрута.
 *
 * Воздух проверяется ПЕРВЫМ: «Вертолётная экскурсия на сплав по реке» — всё
 * ещё вертолёт, а вот обратное прочтение сделало бы её водной и вернуло бы ей
 * обещание ведения.
 */
export function detectTravelMode(
  title: string | null | undefined,
  activityType?: string | null,
): TravelMode {
  const text = `${title ?? ''} ${activityType ?? ''}`;
  if (matches(text, AIR_MARKERS)) return 'air';
  if (matches(text, WATER_MARKERS)) return 'water';
  if (matches(text, SNOW_MARKERS)) return 'snow';
  if (matches(text, VEHICLE_MARKERS)) return 'vehicle';
  return 'foot';
}

/**
 * Проходят ли линию по поверхности — то есть имеет ли смысл обещание вести.
 *
 * Единственный род, для которого ответ «нет», — воздух.
 */
export function lineIsTraversed(mode: TravelMode): boolean {
  return mode !== 'air';
}
