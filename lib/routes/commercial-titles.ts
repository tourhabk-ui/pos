/**
 * lib/routes/commercial-titles.ts — записи, чьё имя продаёт, а не ведёт.
 *
 * ── Третий класс мусора ───────────────────────────────────────────────────
 *
 * `twins.ts` убирает «маршруты», которые на самом деле МЕСТА. `title-dupes`
 * ловит повторы одной записи. Третьего не ловил никто: запись, названная
 * коммерческим предложением — «Джип-тур на Толбачик», «Вертолётная экскурсия
 * в Долину гейзеров», — лежит в таблице маршрутов наравне с тропами.
 *
 * Владелец 18.08: «есть по названиям коммерция, а не маршрут».
 *
 * Вред двойной. Турист в каталоге маршрутов видит предложение, которого мы
 * не продаём и цены которого не знаем. А платформа считает такие записи
 * маршрутами в собственных цифрах — «411 маршрутов» становится числом ни о
 * чём.
 *
 * ── Почему одного слова мало ──────────────────────────────────────────────
 *
 * Имя — слабая улика. «Однодневный поход к Авачинскому вулкану» звучит как
 * позиция прайса, но если под ним лежит снятый трек и путевые точки, это
 * маршрут, как его ни назови. И наоборот: у настоящего коммерческого
 * предложения пути обычно нет вовсе — есть только имя.
 *
 * Поэтому признак СОСТАВНОЙ, как в twins: коммерческое слово в имени И
 * отсутствие содержимого маршрута. Одного слова недостаточно.
 *
 * ── Модуль ничего не решает ───────────────────────────────────────────────
 *
 * Он называет кандидатов. Судьбу записи решает человек: у части найдётся
 * оператор и её место в `operator_tours`, часть окажется дублем настоящего
 * маршрута, часть — просто неудачным названием тропы. Удалять по совпадению
 * слова нельзя.
 */

/**
 * Слова, которыми называют ПРОДУКТ, а не путь.
 *
 * Список намеренно короткий и состоит из существительных, которых у тропы не
 * бывает. Способ прохождения сюда НЕ входит: «(лыжный)», «(снегоходный)»,
 * «восхождение», «поход», «сплав» — это про то, как идут, а не про то, что
 * продают.
 *
 * Длительность («однодневный», «за 3 дня») тоже не улика: маршрут законно
 * бывает однодневным, и мерить им коммерцию значило бы записать в прайс
 * половину троп края.
 */
const COMMERCIAL_MARKERS: Array<{ re: RegExp; what: string }> = [
  // «тур» отдельным словом или в составе: джип-тур, фототур, тур выходного дня.
  // Граница слова обязательна — иначе под правило попадут «турбаза» и «Турпан».
  { re: /(^|[\s(«"-])тур(а|ы|ов|у|ом)?($|[\s)»".,!:;-])/i, what: 'тур' },
  { re: /[а-яё]+-тур($|[\s)»".,!:;-])/i, what: 'составной тур' },
  { re: /(фото|джип|вело|кино|гастро)тур/i, what: 'составной тур' },
  { re: /экскурс/i, what: 'экскурсия' },
  { re: /джип(инг|-)/i, what: 'джиппинг' },
  { re: /вертол[её]тн/i, what: 'вертолётная программа' },
  { re: /(^|\s)с\s+гидом($|\s)/i, what: 'с гидом' },
  { re: /трансфер/i, what: 'трансфер' },
  { re: /(^|\s)заезд($|[\s)»".,!:;-])/i, what: 'заезд' },
];

export interface CommercialTitleHit {
  /** Что именно опознано — чтобы разбор шёл по причине, а не по догадке. */
  marker: string;
}

/**
 * Похоже ли имя на коммерческое предложение. `null` — нет.
 *
 * Отвечает ТОЛЬКО про имя. Решение о записи принимается вместе с проверкой
 * содержимого — см. `isCommercialRecord`.
 */
export function commercialTitleMarker(title: string | null | undefined): CommercialTitleHit | null {
  if (!title) return null;
  for (const m of COMMERCIAL_MARKERS) {
    if (m.re.test(title)) return { marker: m.what };
  }
  return null;
}

export interface RecordSubstance {
  /** Число вершин линии; меньше двух — линии нет. */
  trackPoints: number;
  /** Число путевых точек с координатами. */
  waypoints: number;
}

/**
 * Кандидат на «это коммерция, а не маршрут».
 *
 * Составной признак: коммерческое имя И пустота вместо пути. Запись с
 * настоящим треком остаётся маршрутом, как бы её ни назвали, — линию, по
 * которой кто-то прошёл, нельзя выбросить из-за слова в заголовке.
 */
export function isCommercialRecord(
  title: string | null | undefined,
  substance: RecordSubstance,
): CommercialTitleHit | null {
  const hit = commercialTitleMarker(title);
  if (!hit) return null;
  const hasPath = substance.trackPoints >= 2 || substance.waypoints >= 2;
  return hasPath ? null : hit;
}
