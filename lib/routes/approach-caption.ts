/**
 * Подпись под картой маршрута, когда в линию влита дорога подъезда
 * (`own_with_approach`, `lib/routes/line-ownership`).
 *
 * До #3568 длина на карточке всегда шла из линии, и подпись говорила «длина
 * считается по всей линии, вместе с дорогой». Теперь у маршрутов, сверенных с
 * официальным паспортом, длина — число паспорта со стороной («17 км в одну
 * сторону», `distance_note`, миграции 1472, 1476, 1477). Пометку стороны пишет
 * только миграция со словами паспорта (`lib/routes/distance-words`), поэтому её
 * наличие и есть признак: длина не из линии. Тогда прежняя фраза была бы
 * неправдой — подпись говорит, откуда число на самом деле.
 */
export function approachCaption(
  tailKm: number | null | undefined,
  distanceNote: string | null | undefined,
): string | null {
  if (tailKm == null || !Number.isFinite(tailKm)) return null;
  const head = `Линия включает подъезд: её дальний конец в ${Math.round(tailKm)} км от места.`;
  return (distanceNote ?? '').trim()
    ? `${head} Длина маршрута на карточке — из официального паспорта, а не по линии.`
    : `${head} Длина считается по всей линии, вместе с дорогой.`;
}
