/**
 * lib/routes/go-verdict.ts
 *
 * Идти / Осторожно / Не сегодня.
 *
 * Редукционная схема, а не оракул. Образец — метод Мунтера в лавинной школе:
 * он даёт уровень опасности ТАМ, ГДЕ ОФИЦИАЛЬНОГО БЮЛЛЕТЕНЯ НЕТ, складывая
 * известные факторы по правилам. Для Камчатки это единственный работающий
 * подход: районных бюллетеней нет и не будет, а решение принимать надо.
 *
 * ── Чем вердикт НЕ является ────────────────────────────────────────────────
 *
 * Первая версия этой схемы требовала для «Идти» всего сразу: снятого трека,
 * скачанного пакета, оформленной регистрации, известной погоды и зелёных
 * кодов у всех вулканов рядом. Владелец остановил её до выката одной фразой:
 * «не пережестить, а то все маршруты станут красными».
 *
 * Он был прав, и проверка это подтвердила. Трек снят не у всех маршрутов —
 * у остальных geometry синтетическая. Пакет при первом открытии не скачан
 * ни у кого. Шивелуч и Ключевской стоят жёлтыми или оранжевыми большую часть
 * года. Погода приходит из внешнего источника, который иногда молчит. То есть
 * «Осторожно» выпадало бы всегда — а вердикт, который всегда одного цвета,
 * перестают читать. Это тот же дефект, что зелёная плашка из нуля данных,
 * только с обратным знаком.
 *
 * Отсюда граница, которая и держит схему полезной:
 *
 *   Вердикт — про УСЛОВИЯ СЕГОДНЯ, а не про готовность человека и не про
 *   полноту наших данных.
 *
 * Не скачан пакет и не оформлена регистрация — это чек-лист сборов, он уже
 * есть на экране планирования. Линия-набросок — постоянное свойство наших
 * данных, оно подписано у самой линии (см. lib/routes/track-fidelity). Ни то
 * ни другое не красит сегодняшний день.
 *
 * ── Что осталось ───────────────────────────────────────────────────────────
 *
 *   1. Считают ПРАВИЛА, не языковая модель. Ответ воспроизводим и объясним.
 *   2. Отсутствие бюллетеня — норма, а не сбой.
 *   3. Незнание НИКОГДА не даёт зелёного — но только по тем источникам,
 *      которые СПОСОБНЫ СКРЫТЬ ЗАПРЕТ. Их два: предупреждения и коды вулканов.
 *   4. «Осторожно» — не среднее между да и нет, а названная причина.
 *
 * Третий пункт сузился намеренно. Погода не критична не потому, что неважна,
 * а потому что опасная погода доходит до нас предупреждением: циклон 10.08
 * пришёл именно так, через external_alerts. Молчание wttr.in не должно красить
 * весь полуостров.
 *
 * Решение принимается ДОМА. Лавинная школа формулирует прямо: решения по
 * рельефу принимают на трезвую голову, а не стоя в зоне зарождения.
 */

export type VerdictStatus = 'go' | 'caution' | 'no';

/** Авиационный цветовой код KVERT. */
export type Acc = 'green' | 'yellow' | 'orange' | 'red' | 'unassigned';

/**
 * Стабильный код причины.
 *
 * Отдельно от текста: текст правится, код живёт. По нему считается, какая
 * ветка правил доминирует, и видно, что какой-то запрет перестал доходить.
 * Свободная строка для этого не годится — она меняется от правки к правке.
 */
export type VerdictReasonCode =
  | 'alert_ban'          // прямой запрет МЧС (severity >= 2)
  | 'volcano_red'        // красный код KVERT на коридоре
  | 'weather_severe'     // опасная погода на окно выхода
  | 'signals_unknown'    // не знаем того, что способно скрыть запрет
  | 'volcano_orange'     // оранжевый код на коридоре
  | 'alert_warning'      // предупреждение важности 1
  | 'out_of_season'      // маршрут вне своего сезона
  | 'clear';             // препятствий на сегодня не найдено

/**
 * Сигналы по маршруту на сегодня.
 *
 * `null` значит «не смогли узнать» и отличается от пустого массива, который
 * значит «узнали, и там ничего нет». Разница решающая: первое запрещает
 * зелёный, второе разрешает.
 */
export interface RouteSignals {
  /** Действующие предупреждения, накрывающие зоны маршрута. */
  alerts: Array<{ title: string; severity: number }> | null;
  /** Коды KVERT вулканов на коридоре маршрута. */
  volcanoes: Array<{ name: string; acc: Acc }> | null;
  /** Маршрут в своём сезоне сейчас. `null` — сезон в данных не задан. */
  inSeason: boolean | null;
  /** Опасная погода на окно выхода. `null` — прогноза нет (не критично). */
  weather: { severe: boolean; note: string } | null;
}

export interface Verdict {
  status: VerdictStatus;
  code: VerdictReasonCode;
  /** Одна строка: почему именно так. Панель из двенадцати метрик — не решение. */
  reason: string;
  /** Источники, способные скрыть запрет, по которым мы ничего не знаем. */
  unknown: string[];
}

export const VERDICT_LABELS: Record<VerdictStatus, string> = {
  go: 'Идти',
  caution: 'Осторожно',
  no: 'Не сегодня',
};

/**
 * Источники, молчание которых способно скрыть ЗАПРЕТ.
 *
 * Только они запрещают зелёный. Погода сюда не входит: опасная погода
 * доезжает до нас предупреждением МЧС, а не собственным прогнозом.
 */
function missingCritical(s: RouteSignals): string[] {
  const gaps: string[] = [];
  if (s.alerts === null) gaps.push('предупреждения');
  if (s.volcanoes === null) gaps.push('вулканы на маршруте');
  return gaps;
}

/**
 * Жёлтый код — это фон Камчатки, а не событие.
 *
 * Шивелуч и Ключевской стоят жёлтыми или оранжевыми большую часть года.
 * Красить из-за жёлтого каждый маршрут в округе значит приучить не смотреть
 * на цвет вовсе. Оранжевый — уже повод сказать, красный — повод не идти.
 */
const ACC_BLOCKING: Acc[] = ['red'];
const ACC_WARNING: Acc[] = ['orange'];

export function goVerdict(s: RouteSignals): Verdict {
  const unknown = missingCritical(s);

  // ── Запреты ─────────────────────────────────────────────────────────────
  // Severity 2 у нас означает прямой запрет либо угрозу жизни: этот порог
  // выставляет классификатор МЧС (см. addressesTouristsWithBan).
  const ban = (s.alerts ?? []).find((a) => a.severity >= 2);
  if (ban) {
    return { status: 'no', code: 'alert_ban', reason: `МЧС: ${ban.title}`, unknown };
  }

  const redVolcano = (s.volcanoes ?? []).find((v) => ACC_BLOCKING.includes(v.acc));
  if (redVolcano) {
    return {
      status: 'no', code: 'volcano_red',
      reason: `${redVolcano.name}: красный код KVERT`, unknown,
    };
  }

  if (s.weather?.severe) {
    return {
      status: 'no', code: 'weather_severe',
      reason: `Погода: ${s.weather.note}`, unknown,
    };
  }

  // ── Сомнения ────────────────────────────────────────────────────────────
  // Незнание идёт первым: это самая частая причина «Осторожно», и называть её
  // надо прямо, а не прятать за общим словом.
  if (unknown.length > 0) {
    return {
      status: 'caution', code: 'signals_unknown',
      reason: `Данных мало: не знаем ${unknown.join(', ')}`, unknown,
    };
  }

  const orangeVolcano = (s.volcanoes ?? []).find((v) => ACC_WARNING.includes(v.acc));
  if (orangeVolcano) {
    return {
      status: 'caution', code: 'volcano_orange',
      reason: `${orangeVolcano.name}: оранжевый код KVERT`, unknown,
    };
  }

  const warn = (s.alerts ?? []).find((a) => a.severity >= 1);
  if (warn) {
    return { status: 'caution', code: 'alert_warning', reason: warn.title, unknown };
  }

  if (s.inSeason === false) {
    return {
      status: 'caution', code: 'out_of_season',
      reason: 'Маршрут вне своего сезона', unknown,
    };
  }

  return {
    status: 'go', code: 'clear',
    reason: 'Предупреждений и опасных кодов на маршруте нет', unknown,
  };
}
