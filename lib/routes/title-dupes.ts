/**
 * lib/routes/title-dupes.ts
 *
 * Записи-близнецы среди самих маршрутов.
 *
 * ── Что уже есть и чего не хватало ────────────────────────────────────────
 *
 * `lib/routes/twins.ts` убирает «маршруты», которые на самом деле МЕСТА:
 * имя совпадает с живым местом, точек нет, дистанции нет. Правило сравнивает
 * маршрут С МЕСТОМ.
 *
 * Маршруты друг с другом не сравнивал никто. Сухой прогон импорта OSM 18.08
 * показал цену: в одной партии из восьми записей рядом стояли
 *
 *     Вулкан Дыгерен-Оленгендэ      (дефис)
 *     Вулкан Дыгерен–Оленгендэ      (тире)
 *
 * — одна сопка двумя записями. Турист видит два одинаковых маршрута и не
 * знает, чем они отличаются; агрегаты («411 маршрутов») врут на величину
 * дублей; работа по разметке точек делается дважды.
 *
 * ── Чем близнец отличается от варианта ────────────────────────────────────
 *
 * Приведение НАМЕРЕННО щадящее. Оно снимает только то, что не несёт смысла:
 * регистр, тип тире, повторные пробелы, ё/е, хвостовую пунктуацию. Всё
 * остальное остаётся значимым — и это принципиально:
 *
 *     Горный массив Вачкажец (лыжный)
 *     Горный массив Вачкажец (снегоходный)
 *
 * — РАЗНЫЕ маршруты по одному массиву, и склеить их значило бы потерять
 * зимний способ прохождения. Скобки, слова, цифры не трогаем.
 *
 * ── Модуль ничего не решает ───────────────────────────────────────────────
 *
 * Он группирует и называет. Какую запись из группы оставить — вопрос данных
 * (у кого линия лучше, у кого точки, к кому привязаны туры), и решается он
 * отдельно, с подтверждением человека. Слияние вслепую по имени — это способ
 * потерять единственную запись с настоящим треком.
 */

/** Приведение имени к сравнимому виду. Снимает только незначащее. */
export function normalizeTitle(title: string): string {
  return title
    .toLowerCase()
    .replace(/ё/g, 'е')
    // Все виды тире и дефисов — одно и то же слово, разбитое типографикой.
    .replace(/[‐-―−-]/g, '-')
    // Пробелы вокруг дефиса ничего не значат: «А - Б» и «А-Б» — одно.
    .replace(/\s*-\s*/g, '-')
    .replace(/[«»"'`]/g, '')
    .replace(/\s+/g, ' ')
    .replace(/[.,;:!]+$/, '')
    .trim();
}

export interface DupeGroup {
  /** Приведённое имя — ключ группы. */
  key: string;
  /** Исходные записи группы: id и имя как оно записано. */
  members: Array<{ id: string; title: string }>;
}

/**
 * Группы записей, чьи имена различаются только незначащим.
 *
 * Возвращаются ТОЛЬКО группы больше одной записи: одиночка близнецом не
 * является, и класть её в отчёт значит топить находку в шуме.
 */
export function findTitleDupes(rows: Array<{ id: string; title: string | null }>): DupeGroup[] {
  const byKey = new Map<string, Array<{ id: string; title: string }>>();
  for (const r of rows) {
    const title = (r.title ?? '').trim();
    if (!title) continue;
    const key = normalizeTitle(title);
    if (!key) continue;
    const arr = byKey.get(key) ?? [];
    arr.push({ id: r.id, title });
    byKey.set(key, arr);
  }
  const groups: DupeGroup[] = [];
  for (const [key, members] of byKey) {
    if (members.length > 1) groups.push({ key, members });
  }
  // Крупные группы вперёд: с них и начинать разбор.
  return groups.sort((a, b) => b.members.length - a.members.length);
}
