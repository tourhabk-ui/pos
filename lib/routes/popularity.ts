/**
 * lib/routes/popularity.ts — что люди на самом деле смотрят.
 *
 * ── Зачем ─────────────────────────────────────────────────────────────────
 *
 * Порядок в четырёхстах записях не наводится разом, и попытка чистить всё
 * подряд — это то, из-за чего работа кажется бесконечной. Решение владельца
 * 17.08: сорок проверенных маршрутов честнее четырёхсот. Значит нужен не
 * список «всего», а список ЯДРА: что разметить в первую очередь.
 *
 * Порядок разметки задаёт не вкус и не алфавит, а спрос. Ошибиться в ядре
 * дорого: время уйдёт на маршрут, который никто не открывает, пока самый
 * ходовой продолжит отказываться вести.
 *
 * ── Чем меряется спрос ────────────────────────────────────────────────────
 *
 * Три независимых сигнала, и они НЕ складываются в один балл. Складывать
 * значило бы выдумать курс обмена между просмотром и бронью — а его нет, и
 * получившееся число нельзя ни проверить, ни объяснить.
 *
 *   просмотры  — page_views: сколько раз открывали карточку и сколько РАЗНЫХ
 *                посетителей (суточный хэш, 152-ФЗ: сырых IP/UA нет)
 *   коммерция  — сколько туров оператора висит на маршруте
 *   брони      — сколько раз этот тур действительно купили
 *
 * Каждый показан отдельно, и человек видит, чем именно запись популярна.
 *
 * ── Главная колонка — не популярность ─────────────────────────────────────
 *
 * Рядом со спросом идёт СОСТОЯНИЕ: сколько у записи путевых точек и проходит
 * ли она черту. Без него список — просто рейтинг; с ним это рабочий лист:
 * видно, какие из ходовых маршрутов платформа сегодня отказывается вести и
 * сколько точек им не хватает.
 */

/** Строка спроса — по одной записи. */
export interface DemandRow {
  id: string;
  title: string;
  /** Открытий карточки за окно наблюдения. */
  views: number;
  /** Разных посетителей (суточный хэш) — устойчивее к перезагрузкам. */
  visitors: number;
  /** Туров оператора на этой записи (только у маршрутов). */
  tours: number;
  /** Оплаченных броней по этим турам. */
  bookings: number;
}

/** Место в списке ядра: спрос рядом с состоянием. */
export interface CoreCandidate extends DemandRow {
  /** Путевых точек сейчас (связи рода `waypoint`/`unknown`). */
  waypoints: number;
  /** Есть ли линия. */
  hasLine: boolean;
  /** Что черта отвечает сегодня. */
  verdict: string;
  /**
   * Чего не хватает до пригодности — словами, без «почини данные».
   * `null` — уже пригоден.
   */
  missing: string | null;
}

/** Путь вида `/routes/<id>` или `/places/<id>` → идентификатор. */
export function idFromPath(path: string, kind: 'routes' | 'places'): string | null {
  const m = new RegExp(`^/${kind}/([^/?#]+)`).exec(path);
  if (!m) return null;
  const raw = decodeURIComponent(m[1]).trim();
  // Служебные подстраницы (`/routes/<id>/prepare`) уже отрезаны группой выше;
  // пустое и слишком длинное значение — не идентификатор.
  if (!raw || raw.length > 120) return null;
  return raw;
}

/**
 * Чего не хватает записи до обещания вести.
 *
 * Формулировка деловая: человек читает её как задачу, а не как приговор.
 * Порядок проверок — от того, что чинится разметкой, к тому, что требует
 * данных со стороны.
 */
export function whatIsMissing(i: {
  verdict: string;
  waypoints: number;
  hasLine: boolean;
}): string | null {
  if (i.verdict === 'navigable') return null;
  if (i.verdict === 'not_on_foot') return null;   // не чинится: это не тропа
  if (!i.hasLine && i.waypoints < 2) return 'нет ни линии, ни точек';
  if (i.waypoints === 0) return 'разметить точки: сейчас ни одной';
  if (i.waypoints === 1) return 'разметить точки: сейчас одна';
  if (!i.hasLine) return 'нет линии маршрута';
  return 'разобрать расхождение точек с линией';
}

/**
 * Сортировка ядра: сначала то, что люди открывают чаще.
 *
 * Ведущий признак — РАЗНЫЕ посетители, а не открытия: одна вкладка,
 * обновлённая двадцать раз, не делает маршрут популярным. Дальше — брони,
 * потом открытия. Ничего не суммируется.
 */
export function byDemand(a: DemandRow, b: DemandRow): number {
  if (b.visitors !== a.visitors) return b.visitors - a.visitors;
  if (b.bookings !== a.bookings) return b.bookings - a.bookings;
  return b.views - a.views;
}
