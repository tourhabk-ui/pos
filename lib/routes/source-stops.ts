/**
 * lib/routes/source-stops.ts — этапы маршрута на странице источника.
 *
 * ── Зачем ─────────────────────────────────────────────────────────────────
 *
 * Перепись 18.08: у 264 маршрутов путь не описан точками — 155 без единой,
 * 109 ровно с одной. Это главная куча, и до сих пор она читалась как «данных
 * нет».
 *
 * Владелец: «мы просто не забрали эти точки, это ошибка при парсинге».
 * Основание у догадки сильное. Связи из источника заводились ДВУМЯ разовыми
 * проходами по «многоэтапным» страницам — 33 связи с 11 маршрутов (миграция
 * 655) и 63 с 19 (656). Тридцать страниц из трёхсот. А сам разбор страницы
 * (`scrapePage`) берёт заголовок, описание, координаты и трек — и не смотрит
 * на этапы вовсе.
 *
 * ── Что здесь есть ────────────────────────────────────────────────────────
 *
 * Только ЧТЕНИЕ разметки: какие ссылки на другие места есть на странице и
 * похоже ли, что это этапы пути, а не «посмотрите также». Ничего не
 * импортирует и ничего не решает — сначала надо увидеть, что там лежит.
 *
 * ── Почему нельзя брать все ссылки подряд ─────────────────────────────────
 *
 * Ровно так была сделана миграция 167: взять всё, что рядом, и записать как
 * путевые точки. Разгребали мы это сегодня весь вечер — краевой музей среди
 * этапов подъёма на вулкан. Ссылка в блоке «рядом» и ссылка в списке этапов
 * выглядят в HTML одинаково; отличает их ОКРУЖЕНИЕ. Поэтому каждая ссылка
 * возвращается с признаком контекста, а решение принимает человек, глядя на
 * образцы разметки.
 */

/** Слова, рядом с которыми ссылка похожа на ЭТАП пути, а не на рекомендацию. */
export const ROUTE_CONTEXT_WORDS = [
  'маршрут', 'этап', 'точк', 'прохо', 'ниткa', 'нитка', 'день', 'старт', 'финиш',
];

/** Слова, которыми подписывают «посмотрите также» — прямая улика ПРОТИВ этапа. */
export const NEARBY_CONTEXT_WORDS = [
  'рядом', 'поблизости', 'похож', 'также', 'смотрите', 'интересн', 'окрестност',
];

export interface StopLink {
  /** id места на источнике. */
  id: string;
  /** Текст ссылки, если удалось прочитать. */
  text: string | null;
  /** Рядом есть слова о маршруте и этапах. */
  routeContext: boolean;
  /** Рядом есть слова «рядом», «также» — улика против этапа. */
  nearbyContext: boolean;
}

/** Ссылки на места: и в HTML, и в JSON-теле, где слэши экранированы. */
const LINK_RE = /\/kam\\?\/places\\?\/(\d+)/g;

/** Сколько символов вокруг ссылки считать её окружением. */
const WINDOW = 240;

function hasAny(text: string, words: string[]): boolean {
  const low = text.toLowerCase();
  return words.some((w) => low.includes(w));
}

/**
 * Ссылки на другие места со страницы маршрута, с признаком окружения.
 *
 * `selfId` исключается: страница ссылается сама на себя в навигации и в
 * разметке, и считать это этапом было бы ошибкой счёта.
 */
export function extractStopLinks(html: string, selfId?: string): StopLink[] {
  const seen = new Map<string, StopLink>();
  LINK_RE.lastIndex = 0;
  let m: RegExpExecArray | null;
  while ((m = LINK_RE.exec(html)) !== null) {
    const id = m[1];
    if (selfId && id === selfId) continue;

    const from = Math.max(0, m.index - WINDOW);
    const around = html.slice(from, m.index + WINDOW);

    // Текст ссылки: ближайший >…< после адреса.
    const after = html.slice(m.index, m.index + 400);
    const textMatch = after.match(/>([^<>{}]{2,80})</);
    const text = textMatch ? textMatch[1].replace(/\s+/g, ' ').trim() : null;

    const link: StopLink = {
      id,
      text: text && text.length > 1 ? text : null,
      routeContext: hasAny(around, ROUTE_CONTEXT_WORDS),
      nearbyContext: hasAny(around, NEARBY_CONTEXT_WORDS),
    };

    // Одна и та же ссылка встречается несколько раз: в списке и в скрипте
    // карты. Признаки объединяем — контекст, найденный хоть раз, остаётся.
    const prev = seen.get(id);
    if (prev) {
      prev.routeContext = prev.routeContext || link.routeContext;
      prev.nearbyContext = prev.nearbyContext || link.nearbyContext;
      prev.text = prev.text ?? link.text;
    } else {
      seen.set(id, link);
    }
  }
  return [...seen.values()];
}

/**
 * Похоже ли, что у страницы вообще есть список этапов.
 *
 * Осторожно и намеренно скупо: две и больше ссылок в контексте маршрута и без
 * подписи «рядом». Одна ссылка этапами не является — это чаще всего сам
 * объект или соседняя достопримечательность.
 */
export function looksLikeStopList(links: StopLink[]): boolean {
  return links.filter((l) => l.routeContext && !l.nearbyContext).length >= 2;
}
