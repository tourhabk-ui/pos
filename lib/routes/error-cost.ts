/**
 * lib/routes/error-cost.ts — Ф5: ядро по цене ошибки.
 *
 * ── Почему не по спросу, как задумывал план ────────────────────────────────
 *
 * Ф5 требовал приоритет «по фактическим открытиям карточек». Замер 19.08:
 * у самой популярной записи ШЕСТЬ открытий и ОДИН посетитель. Отсортировать
 * двадцать маршрутов по такой разнице — значит отсортировать шум и выдать его
 * за приоритет. Механика спроса (lib/routes/popularity.ts) написана и ждёт
 * трафика; пока его нет, порядок задаётся другим.
 *
 * ── Что такое цена ошибки ──────────────────────────────────────────────────
 *
 * Решение владельца 21.08. Ядро — не «что чаще открывают», а «где ошибиться
 * дороже всего». Три признака, и третий неочевиден:
 *
 *   1. Обязательна регистрация в МЧС — государство считает маршрут опасным.
 *   2. Перечислены опасности (hazards) — лавины, камнепад, термальные, звери.
 *   3. НЕТ оператора — и вот это переворачивает первый порыв.
 *
 * Первый порыв — вести ядро по коммерции: где продают тур, туда точно ходят.
 * Но на туре с оператором у человека есть проводник — ЖИВАЯ СТРАХОВКА от
 * нашей ошибки. На самостоятельном выходе у него есть только мы. Значит наша
 * ошибка дороже там, где маршрут опасен И человек идёт один.
 *
 * ── Чего этот модуль НЕ делает ─────────────────────────────────────────────
 *
 * Не складывает признаки в один балл. Складывать — значит выдумать курс обмена
 * между «нужна регистрация МЧС» и «нет оператора»; его нет, и получившееся
 * число нельзя ни проверить, ни объяснить человеку. Признаки сравниваются по
 * очереди, и каждый виден отдельно (тот же принцип, что у спроса).
 *
 * Не решает, ЧТО чинить: это отвечает `whatIsMissing` в popularity.ts. Здесь
 * только очередь.
 */

/** Что известно о маршруте для оценки цены ошибки. */
export interface ErrorCostInput {
  id: string;
  title: string;
  /** Государство требует регистрацию группы — маршрут признан опасным. */
  mchsRequired: boolean;
  /** Названные опасности маршрута. Пустой массив — не то же, что null. */
  hazards: string[] | null;
  /** Сколько туров оператора висит на маршруте. 0 — идут сами. */
  tours: number;
  /** Природный парк: нужен пропуск/согласование, отказ в поле дорог. */
  parkName: string | null;
  /** Вердикт черты сегодня — `navigable` и прочее. */
  verdict: string;
}

export interface ErrorCostRow extends ErrorCostInput {
  /**
   * Идёт ли человек без проводника. Не «нет тура вообще», а именно отсутствие
   * коммерческого сопровождения на этом маршруте.
   */
  unguided: boolean;
  /** Сколько признаков цены ошибки сошлось: 0..4. Для показа, не для сортировки. */
  signals: number;
  /** Почему запись в ядре — словами, для листа проверки. */
  why: string;
}

/**
 * Опасности объявлены?
 *
 * `null` и `[]` — РАЗНЫЕ вещи (CLAUDE.md §4.0). Пустой массив означает «мы
 * смотрели, опасностей не назвали»; null — «не смотрели вовсе». Второе само
 * по себе повод попасть в ядро: непроверенный опасный маршрут выглядит так же,
 * как проверенный безопасный.
 */
export function hazardState(h: string[] | null): 'listed' | 'none' | 'unknown' {
  if (h === null || h === undefined) return 'unknown';
  return h.length > 0 ? 'listed' : 'none';
}

/** Признаки цены ошибки — по одному, без сложения в балл. */
export function errorCostSignals(i: ErrorCostInput): number {
  let n = 0;
  if (i.mchsRequired) n++;
  const hz = hazardState(i.hazards);
  if (hz === 'listed' || hz === 'unknown') n++;
  if (i.tours === 0) n++;
  if (i.parkName) n++;
  return n;
}

/** Человеку — почему запись здесь. Деловая формулировка, без приговора. */
export function whyInCore(i: ErrorCostInput): string {
  const parts: string[] = [];
  if (i.mchsRequired) parts.push('обязательна регистрация МЧС');
  const hz = hazardState(i.hazards);
  if (hz === 'listed') parts.push(`опасности названы (${i.hazards!.length})`);
  if (hz === 'unknown') parts.push('опасности не проверялись');
  if (i.tours === 0) parts.push('идут без оператора');
  if (i.parkName) parts.push(`парк: ${i.parkName}`);
  return parts.length > 0 ? parts.join(' · ') : 'признаков повышенной цены ошибки нет';
}

/**
 * Очередь ядра.
 *
 * Признаки сравниваются ПО ОЧЕРЕДИ, а не суммой:
 *   1. МЧС обязательна — сильнейший признак, это оценка государства;
 *   2. без оператора — мы единственный источник, страховки нет;
 *   3. опасности названы или НЕ ПРОВЕРЯЛИСЬ — непроверенное не лучше опасного;
 *   4. парк — нужен пропуск, отказ на месте дорог;
 *   5. при равенстве — заголовок, чтобы порядок был воспроизводим.
 *
 * Последний ключ обязателен: без него равные записи возвращаются в
 * произвольном порядке, и «ядро» меняется от прогона к прогону.
 */
export function byErrorCost(a: ErrorCostInput, b: ErrorCostInput): number {
  if (a.mchsRequired !== b.mchsRequired) return a.mchsRequired ? -1 : 1;

  const aUnguided = a.tours === 0;
  const bUnguided = b.tours === 0;
  if (aUnguided !== bUnguided) return aUnguided ? -1 : 1;

  const rank = (s: 'listed' | 'none' | 'unknown'): number =>
    s === 'listed' ? 0 : s === 'unknown' ? 1 : 2;
  const ah = rank(hazardState(a.hazards));
  const bh = rank(hazardState(b.hazards));
  if (ah !== bh) return ah - bh;

  const aPark = a.parkName ? 0 : 1;
  const bPark = b.parkName ? 0 : 1;
  if (aPark !== bPark) return aPark - bPark;

  return a.title.localeCompare(b.title, 'ru');
}

/**
 * Ядро: первые `size` записей по цене ошибки.
 *
 * Маршруты, которые черта признала НЕ пешими (`not_on_foot`), в ядро не
 * попадают: это не тропа, и ручная проверка описания тропы для них
 * бессмысленна. Прочие вердикты остаются — непригодный сегодня маршрут может
 * стать пригодным после разметки, ради этого ядро и собирается.
 */
export function buildCore(rows: ErrorCostInput[], size = 20): ErrorCostRow[] {
  return rows
    .filter((r) => r.verdict !== 'not_on_foot')
    .slice()
    .sort(byErrorCost)
    .slice(0, size)
    .map((r) => ({
      ...r,
      unguided: r.tours === 0,
      signals: errorCostSignals(r),
      why: whyInCore(r),
    }));
}
