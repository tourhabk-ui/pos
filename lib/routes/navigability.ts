/**
 * lib/routes/navigability.ts
 *
 * Черта: что платформа имеет право предлагать как ПУТЬ.
 *
 * ── Зачем ──────────────────────────────────────────────────────────────────
 *
 * Перепись 17.08 по живой базе: 411 маршрутов, из них 110 без линии вовсе,
 * 154 с линией и без единой путевой точки, 25 с точками, которые расходятся
 * с собственной линией, 10 — подборки мест, а не пути. Смоук по проду в тот
 * же день: пригодных маршрутов один из пяти. Восемьдесят шесть процентов
 * линий пришли скрейпом с чужого сайта, и никто их не проверял.
 *
 * Решение владельца 17.08: провести черту. Для площадки, которая говорит о
 * безопасности туристов, сорок проверенных маршрутов честнее четырёхсот, где
 * каждый пятый ведёт не туда.
 *
 * ── Что здесь решается, а что нет ──────────────────────────────────────────
 *
 * Здесь решается ОДИН вопрос: можно ли обещать человеку, что по этой записи
 * его проведут. Не «показывать ли её» — описание места остаётся описанием, и
 * прятать знание незачем. Черта проходит по обещанию, а не по видимости.
 *
 * Три исхода:
 *
 *   navigable        — снятый трек, точки на нём, расхождений нет. Можно
 *                      обещать ведение по линии.
 *   orientation_only — данные есть, но пути в них нет: набросок, линия без
 *                      происхождения, одни точки. Направление и расстояние
 *                      честны, «идите по линии» — нет.
 *   not_a_route      — записью нельзя пользоваться как маршрутом вовсе:
 *                      подборка мест по краю, одна точка, пустота.
 *
 * ── Почему правило собрано здесь, а не на экранах ──────────────────────────
 *
 * До этого черта существовала кусками: экран выбора сам проверял разброс и
 * одиночную точку, паспорт отдельно судил род линии, каталог отдельно считал
 * «пригодные». Три проверки одного и того же — это три правила, и они уже
 * расходились (§12 писался ровно про это). Правило одно, живёт здесь,
 * поверхности его спрашивают.
 */

import { projectOnTrack, DATA_CONFLICT_KM, type GeoPoint } from '@/lib/on-route/approach';
import { pointsAreCollection, routeIntegrity } from '@/lib/routes/shape-match';
import type { PassportGrade } from '@/lib/routes/passport';
import type { TrackEvidenceVerdict } from '@/lib/routes/track-evidence';
import type { LatLng } from '@/lib/routes/track-fidelity';
import { isExtendedObject } from '@/lib/places/coord-source';
import { isPathPoint, type LinkKind } from '@/lib/routes/link-kind';
import { lineIsTraversed, type TravelMode } from '@/lib/routes/travel-mode';

/** Линия приходит парами, а меры считают по объектам — приводим в одном месте. */
function trackPoints(track: LatLng[]): GeoPoint[] {
  return track.map(([lat, lng]) => ({ lat, lng }));
}

export type NavigabilityVerdict =
  | 'navigable'
  | 'orientation_only'
  | 'not_a_route'
  /**
   * Линию не проходят по поверхности: облёт, вертолётная программа.
   *
   * Отдельный исход, а не «не маршрут». Запись законная и полезная — просто
   * вопрос черты к ней не относится: с курса вертолёта не сходят и на него не
   * возвращаются. Сваливать её в «маршрутом не является» значило бы смешать
   * исправную запись с битыми данными и потерять обе цифры.
   */
  | 'not_on_foot';

export interface Navigability {
  verdict: NavigabilityVerdict;
  /** Можно ли обещать ведение по линии. */
  canLead: boolean;
  /**
   * Почему не `navigable` — словами, которые можно показать человеку.
   *
   * Пустой список у пригодного маршрута. У остальных причина обязана быть
   * названа: «нельзя» без причины неотличимо от поломки экрана, и человек
   * пойдёт искать, что он сделал не так.
   */
  reasons: string[];
  /**
   * КАКАЯ точка спорит с линией — порядковый номер в `waypoints` и отход.
   *
   * Причина словами называет только расстояние: «точка стоит в 7.9 км от
   * линии». Для счётчика этого хватало, для разбора — нет: чтобы открыть
   * случай, надо знать, ЧТО это за точка. Имена живут у того, кто передал
   * точки сюда, поэтому правило возвращает номер, а называет поимённо
   * вызывающий. Заводить второе вычисление расстояния ради имени значило бы
   * получить два ответа на один вопрос — ровно то, ради чего §12 писался.
   *
   * Отсутствует, когда расхождения нет.
   */
  conflict?: { index: number; offTrackKm: number };
}

export interface NavigabilityInput {
  /** Род линии из паспорта — считать его здесь заново значило бы завести второе правило. */
  grade: PassportGrade;
  /** Линия маршрута парами [широта, долгота]; null — линии нет. */
  track: LatLng[] | null;
  /** Путевые точки С КООРДИНАТАМИ. Точка без координат путём не является. */
  waypoints: GeoPoint[];
  /**
   * Род каждой путевой точки, в том же порядке (`places.location_type`).
   *
   * Нужен ровно для одного: у протяжённого объекта — парк, озеро, пляж —
   * координата это центроид, и расстояние до неё не противоречит ничему.
   * Пусто — родов не спрашивали, и все точки судятся как точечные (прежнее
   * поведение).
   */
  waypointTypes?: Array<string | null>;
  /**
   * Род каждой связи, в том же порядке (`route_waypoints.link_kind`).
   *
   * `nearby` — не точка пути, а контекст «это рядом, загляните» (миграция
   * 874). Такая связь из суждения исключается ЦЕЛИКОМ: ею нельзя ни сверить
   * линию, ни опровергнуть её. Пусто — родов не спрашивали, и все связи
   * судятся как путевые (прежнее поведение).
   *
   * Раньше эти связи давали отказ «точка стоит в N км от линии» — отказ
   * верный по существу, но по неверной причине: Музей лосося не расходится с
   * тропой на Авачинский, он просто не на ней.
   */
  waypointKinds?: LinkKind[];
  /**
   * Способ передвижения (lib/routes/travel-mode).
   *
   * Воздух выводит запись из-под черты: линию облёта не проходят, и «вести по
   * ней» не значит ничего. Не задан — считается пешим, как было раньше.
   */
  mode?: TravelMode;
  /**
   * Улика записи по САМОЙ линии (lib/routes/track-evidence).
   *
   * Считается по сырой геометрии: высота на каждой точке, неровность шага,
   * плотность, непрерывность, границы края. Отсутствует — улику не спрашивали
   * (старый кэш ответа, поверхность без доступа к сырой геометрии); это не то
   * же самое, что «улик нет».
   */
  evidence?: TrackEvidenceVerdict;
}

/** Меньше этого числа точек путь не описан — идти «из точки в неё же» нельзя. */
export const MIN_ROUTE_WAYPOINTS = 2;

export function routeNavigability(i: NavigabilityInput): Navigability {
  const reasons: string[] = [];
  let conflict: { index: number; offTrackKm: number } | undefined;
  const track = i.track ?? [];

  // ── Линию облёта не проходят ──────────────────────────────────────────────
  //
  // Проверяется ПЕРВОЙ и раньше всего остального. Иначе вертолётная программа
  // получает мерки тропы и отказ с несуществующей причиной: «точка стоит в 4.9
  // км от линии» — как будто с курса вертолёта можно свернуть к фумароле.
  //
  // Владелец 18.08: «облёт это не пеший маршрут».
  if (i.mode && !lineIsTraversed(i.mode)) {
    return {
      verdict: 'not_on_foot',
      canLead: false,
      reasons: ['Это облёт: линию не проходят по земле, вести по ней некого'],
    };
  }

  // Индексы точек, описывающих ПУТЬ. Всё остальное — контекст, и в суждении
  // о пути не участвует (см. lib/routes/link-kind).
  const pathIdx = i.waypoints.map((_, idx) => idx).filter(
    (idx) => !i.waypointKinds || isPathPoint(i.waypointKinds[idx] ?? 'unknown'),
  );
  const pathPoints = pathIdx.map((idx) => i.waypoints[idx]);
  const hasLine = track.length >= 2;

  // ── Не маршрут вовсе ──────────────────────────────────────────────────────
  //
  // Подборка мест по краю проверяется ПЕРВОЙ. Иначе объект, у которого пути
  // нет по смыслу, попадёт в «ориентирование» и будет числиться пригодным для
  // похода — а чинить там нечего, там другая сущность.
  // Разброс ТОЧЕК судит только там, где линии нет.
  //
  // Когда сплошная линия есть, разброс точек ею и объяснён: у стокилометрового
  // пути две точки на концах законно стоят в сотне километров друг от друга.
  // Судьёй в этом случае выступает сама линия — её непрерывность и то, лежат ли
  // точки на ней. Проверять вдобавок габарит набора значило бы наказывать
  // маршрут за длину.
  if (!hasLine && pathPoints.length > 0 && pointsAreCollection(pathPoints)) {
    return {
      verdict: 'not_a_route',
      canLead: false,
      reasons: ['Это подборка мест по краю, а не единый путь'],
    };
  }
  // У СПЛОШНОЙ ЛИНИИ ГАБАРИТ НЕ ЗНАЧИТ НИЧЕГО: он равен длине маршрута.
  //
  // Первая редакция этого правила звала здесь `isScatteredCollection`, который
  // объявляет подборкой всё шире 25 км по габариту. Прогон 17.08 показал цену:
  // пригодных вышло 0 из 301, а «маршрутом не являются» — 92. Среди них
  // настоящие длинные пути; накрывать сотню километров — их работа.
  //
  // Урок был записан в трёх строках от того места, куда я смотрел: перепись
  // геометрии судит линию через `routeIntegrity`, а не по габариту, и там же
  // названы «Сплав по реке Камчатка» (габарит 282 км) и «Зимник Анавгай —
  // Тигиль» (192), объявленные подборками по этой самой причине.
  //
  // Подборку от длинного пути отличает НЕПРЕРЫВНОСТЬ: у сплава шаг между
  // точками метры, у подборки — прыжок в десятки километров. Правило одно и
  // живёт в shape-match; заводить здесь второе значило бы повторить ту самую
  // ошибку, ради которой писался §12.
  if (hasLine && routeIntegrity(trackPoints(track), pathPoints).verdict === 'not_a_path') {
    return {
      verdict: 'not_a_route',
      canLead: false,
      reasons: ['Линия рвётся на десятки километров — это не путь, а набор мест'],
    };
  }
  if (!hasLine && pathPoints.length < MIN_ROUTE_WAYPOINTS) {
    return {
      verdict: 'not_a_route',
      canLead: false,
      reasons: pathPoints.length === 0
        ? ['Нет ни линии, ни точек — вести не по чему']
        : ['У записи одна точка: начало и конец совпадают, пути между ними нет'],
    };
  }

  // ── Обещать ведение можно только снятому пути ─────────────────────────────
  //
  // ── Улика о линии старше ярлыка о поставщике ──────────────────────────────
  //
  // Род линии берётся из ЗАПИСАННОГО источника. 17.08 слог скрейпа понижен до
  // «происхождение не подтверждено»: кто по этой линии ходил, сайт-поставщик
  // не доказывал.
  //
  // Прогон 18.08 показал, что доказательство есть в самих данных: 277 линий из
  // 301 несут высоту на каждой точке при НЕРОВНОМ шаге — след живого прибора.
  // Проверка на машинную перерисовку отсеяла две.
  //
  // Источник говорит, КТО принёс линию. Улика говорит, ЧЕМ линия является.
  // Второе о самой линии, первое — о её поставщике, и при споре побеждает
  // второе: обещание даётся пути, а не подрядчику.
  //
  // Улика прощает только НЕЗНАНИЕ (`unknown`), но не знание обратного:
  // `sketch` — это записанный факт «линия построена прямыми между точками», и
  // никакая плотность высот его не отменяет. Иначе синтетика, которой кто-то
  // дописал высоты, вернулась бы в снятые треки — ровно та подмена, ради
  // которой §12 и писался.
  const provenByEvidence = i.grade === 'unknown' && i.evidence === 'recorded';

  if (i.grade !== 'surveyed' && !provenByEvidence) {
    reasons.push(
      i.grade === 'sketch'
        ? 'Линия построена прямыми между точками — тропы по ней никто не снимал'
        : i.grade === 'points_only'
          ? 'Подтверждённой линии нет — только точки'
          // «Не подтверждено», а не «не записано»: с 17.08 сюда попадают и
          // линии с ИЗВЕСТНЫМ источником — скрейп с чужого сайта. Источник у
          // них есть, доказательства, что по линии кто-то прошёл, нет.
          : 'Происхождение линии не подтверждено — по ней никто не проходил',
    );
  }

  if (pathPoints.length < MIN_ROUTE_WAYPOINTS) {
    // Линия без точек не поверяется ничем: сверить её не с чем, этапы
    // показать нечем. Такая линия может быть верной — но проверить это
    // платформа не может, а обещание даётся на проверенном.
    reasons.push('Линию не с чем сверить: путевых точек меньше двух');
  }

  // ── Точки обязаны лежать на линии ─────────────────────────────────────────
  //
  // Порог — общий с полевым экраном (DATA_CONFLICT_KM): там расхождение выше
  // него означает, что точка и линия описывают разные места, и экран
  // перестаёт показывать расстояние. Два порога об одном и том же разошлись
  // бы, а тут расходиться нельзя: это одно и то же утверждение о данных.
  //
  // ── Почему здесь НЕ так строго, как при удалении ──────────────────────────
  //
  // Уборка битых привязок (lib/routes/broken-links) требует, чтобы координата
  // была СНЯТА и объект был точечным: она удаляет данные, и цена ошибки —
  // потеря верной связи навсегда.
  //
  // Черта только придерживает ОБЕЩАНИЕ, и цена ошибки обратная: промолчать
  // дёшево, а пообещать ведение по данным, которые не сходятся, — это полевой
  // скрин 17.08 с «до следующей точки 14 км» на тропе. Поэтому неизвестное
  // происхождение координаты строгость здесь НЕ снимает.
  //
  // Снимает её только род объекта: у парка Налычево центроид в тридцати
  // километрах от любой тропы, и это не противоречие данных, а определение
  // центроида. Наказывать за это значило бы навсегда закрыть черту всем
  // маршрутам, проходящим через крупные объекты.
  if (hasLine && pathPoints.length > 0) {
    const line = trackPoints(track);
    let worstKm = 0;
    let worstIdx = -1;
    for (const idx of pathIdx) {
      const type = i.waypointTypes?.[idx];
      // Род спрошен и оказался протяжённым — расстояние ни о чём не говорит.
      if (i.waypointTypes && isExtendedObject(type)) continue;
      const proj = projectOnTrack(i.waypoints[idx], line);
      if (proj && proj.offTrackKm > worstKm) { worstKm = proj.offTrackKm; worstIdx = idx; }
    }
    if (worstKm > DATA_CONFLICT_KM) {
      reasons.push(`Точка стоит в ${worstKm.toFixed(1)} км от линии — данные маршрута не сходятся`);
      conflict = { index: worstIdx, offTrackKm: worstKm };
    }
  }

  return reasons.length === 0
    ? { verdict: 'navigable', canLead: true, reasons: [] }
    : { verdict: 'orientation_only', canLead: false, reasons, ...(conflict ? { conflict } : {}) };
}

/**
 * Подпись главного действия — по вердикту, а не по роду линии.
 *
 * «Навигатор» обещает ведение по линии. Это обещание есть только у пригодного
 * маршрута: снятый трек, точки на нём, расхождений нет. Всё остальное честно
 * называется ориентированием — направление и точки, не тропа.
 */
export function navigabilityCtaLabel(v: NavigabilityVerdict): string | null {
  switch (v) {
    case 'navigable':        return 'Открыть навигатор';
    case 'orientation_only': return 'Открыть ориентирование';
    case 'not_a_route':      return null;
    // Ни навигатора, ни ориентирования: человек в воздухе, и вести его
    // некуда. Кнопка здесь была бы предложением сойти с вертолёта.
    case 'not_on_foot':      return null;
  }
}
