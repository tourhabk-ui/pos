/**
 * lib/routes/link-kind.ts — что означает связь «маршрут — место».
 *
 * ── Зачем ─────────────────────────────────────────────────────────────────
 *
 * `route_waypoints` использовалась в двух несовместимых смыслах. Миграция 167
 * завела связи как «места в 15 км от центра маршрута» — то есть «что рядом
 * посмотреть», — а платформа читала их как «маршрут здесь проходит».
 *
 * Цена видна на карточках: у «Скал Три Брата» среди путевых точек краевой
 * музей и батарея Максутова, у похода к Авачинскому — Музей лосося и
 * Халактырский пляж, а два авачинских маршрута имеют одинаковый набор точек.
 * Черта при этом отказывалась вести по линии со словами «точка стоит в 10 км»
 * — верный отказ по неверной причине.
 *
 * Смысл разведён (решение владельца 18.08, миграция 874):
 *
 *   waypoint — точка ПУТИ. Ею сверяется линия, ею меряется расхождение.
 *   nearby   — контекст: «это рядом, загляните». Пути не описывает и о нём
 *              ничего не говорит — ни хорошего, ни плохого.
 *   unknown  — не установлено. Ведёт себя как раньше, чтобы разметка не
 *              улучшала показатели молча.
 *
 * ── Почему `nearby` НЕ противоречие ───────────────────────────────────────
 *
 * Соблазн считать далёкую точку «рядом-объектом» автоматически обязан быть
 * отвергнут: тогда любой маршрут пройдёт черту, потому что всё неудобное
 * переименуется. Род связи берётся из её ПРОИСХОЖДЕНИЯ (что за импорт её
 * создал), а не из расстояния, которое потом по ней же и судят.
 */

export type LinkKind = 'waypoint' | 'nearby' | 'unknown';

/** Значение колонки → тип. Незнакомое и пустое честно становится `unknown`. */
export function asLinkKind(raw: string | null | undefined): LinkKind {
  return raw === 'waypoint' || raw === 'nearby' ? raw : 'unknown';
}

/**
 * Описывает ли связь ПУТЬ — то есть можно ли ею сверять линию.
 *
 * `unknown` считается путём намеренно: до разметки платформа вела себя именно
 * так, и внезапное «стало лучше» после появления колонки было бы не
 * улучшением данных, а сменой линейки.
 */
export function isPathPoint(kind: LinkKind): boolean {
  return kind !== 'nearby';
}

/** Подпись для человека: чем эта связь является. */
export function linkKindLabel(kind: LinkKind): string {
  switch (kind) {
    case 'waypoint': return 'Точка маршрута';
    case 'nearby':   return 'Рядом с маршрутом';
    case 'unknown':  return 'Связь не размечена';
  }
}
