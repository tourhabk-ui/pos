/**
 * lib/routes/verdict-presentation.ts
 *
 * Как вердикт ВЫГЛЯДИТ. Один источник на все поверхности: карточка маршрута,
 * строка под кнопкой навигации, полоса на главной.
 *
 * ── Правило одно, облик разный ─────────────────────────────────────────────
 *
 * Соблазн «единого визуального языка» — сделать три статуса одинакового веса,
 * чтобы смотрелись семейством. Это ошибка, и дизайн-язык Ведара формулирует
 * прямо: интерфейс спокоен, пока всё хорошо, и громок только когда опасность.
 *
 * Значит единым должно быть ПРАВИЛО, а не облик:
 *
 *   вес растёт с опасностью.
 *
 *   Идти      — строка. Прочитал и забыл; думать не о чем.
 *   Осторожно — карточка. Есть причина посмотреть, факты открыты.
 *   Не сегодня— карточка с полосой. Мимо не пройти.
 *
 * Три блока одинакового веса дали бы обратное: «Идти» тянуло бы внимание
 * наравне с запретом, и запрет перестал бы отличаться. Тот же дефект, что у
 * вечно красного вердикта, только через типографику.
 *
 * Цвет несёт состояние и берётся токенами. Заливки статусным цветом здесь нет
 * намеренно: текст поверх сплошного --danger пришлось бы красить белым, а
 * белый на сплошных фонах у нас запрещён и в тёмной теме читается плохо.
 * Громкость набирается размером, полосой и чипом — не заливкой.
 */

import type { VerdictStatus } from '@/lib/routes/go-verdict';

/** Насколько блок заметен. Больше — громче. */
export type VerdictProminence = 0 | 1 | 2;

export interface VerdictLook {
  /** Токен цвета состояния. Только var(--…), хардкода тут быть не может. */
  color: string;
  /** Полоса слева: только у запрета. */
  bar: boolean;
  prominence: VerdictProminence;
  /** Показывать ли факты сразу. В спокойный день они убраны под раскрытие. */
  factsOpen: boolean;
  /** Оговорка «это не официальный бюллетень». */
  disclaimer: boolean;
  /** Размер слова статуса. */
  titleClass: string;
}

const LOOKS: Record<VerdictStatus, VerdictLook> = {
  go: {
    color: 'var(--success)',
    bar: false,
    prominence: 0,
    // Спокойный день не должен предъявлять список проверенного: он не про
    // «смотри, как я старался», а про «иди».
    factsOpen: false,
    disclaimer: false,
    titleClass: 'text-base font-semibold',
  },
  caution: {
    color: 'var(--warning)',
    bar: false,
    prominence: 1,
    factsOpen: true,
    disclaimer: true,
    titleClass: 'font-playfair text-xl font-bold',
  },
  no: {
    color: 'var(--danger)',
    bar: true,
    prominence: 2,
    factsOpen: true,
    disclaimer: true,
    titleClass: 'font-playfair text-2xl font-bold',
  },
};

export function verdictLook(status: VerdictStatus): VerdictLook {
  return LOOKS[status] ?? LOOKS.caution;
}

/**
 * Короткая строка о запрете — для мест, где вердикту не место целиком.
 *
 * Пример: под кнопкой «Начать навигацию» на карточке маршрута. Кнопка НЕ
 * запирается: она ведёт на полевой экран, где след, офлайн-карта и связь, а
 * запрет адресован тому, кто ещё дома. Тому, кто уже вышел, отнять эти
 * инструменты нельзя. Поэтому здесь строка, а не блокировка.
 *
 * `null` значит «говорить нечего» — молчание тут законно, потому что полный
 * вердикт уже стоит выше на той же странице.
 */
export function verdictInlineNote(status: VerdictStatus, reason: string): string | null {
  if (status === 'no') return `Сегодня «Не сегодня»: ${reason}`;
  if (status === 'caution') return `Сегодня «Осторожно»: ${reason}`;
  return null;
}
