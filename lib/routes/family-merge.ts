/**
 * lib/routes/family-merge.ts — правила слияния семей маршрутов-тёзок.
 *
 * Перепись 20.08 нашла 49 скрытых маршрутов с настоящими треками, из них
 * 34 — дубли живых записей (тот же объект, то же имя), ещё несколько —
 * перестановки слов («Озеро Курильское» против живого «Курильское озеро»).
 * Восстанавливать таких нельзя: витрина получила бы два «Вулкана Горелых».
 * Их судьба — слияние: живой записи достаётся лучший трек и путевые точки,
 * скрытая помечается merged_into_id и перестаёт участвовать в переписях.
 *
 * Правила честности:
 *  - сливаются ТОЛЬКО настоящие тёзки: равенство множества значимых слов
 *    после нормализации инбокса. «Вилючинский водопад» и «Вулкан
 *    Вилючинский» множествами не совпадают — и не сольются: это разные
 *    объекты одной семьи имён;
 *  - трек переезжает живой записи только поверх пустоты или перезаписываемых
 *    источников (синтетика, прежний kml_inbox) — снятое у живой не
 *    перетирается никогда, даже если у скрытой точек больше.
 */

import { normalizeTitle } from '@/lib/import/kml-inbox';

/** Поверх чего живой записи можно писать трек скрытой. Правило инбокса. */
export const TRANSFER_OVERWRITABLE = new Set(['waypoints_synthetic', 'kml_inbox']);

/**
 * Значимые слова имени: нормализация инбокса + разбиение по пробелам/дефисам.
 * Пунктуация по краям слова срезается отдельно: normalizeTitle чистит только
 * края всей строки, и «Вачкажец. Горный массив» оставлял токен «вачкажец.»,
 * который не совпадал с «вачкажец».
 */
export function nameTokens(title: string): string[] {
  return normalizeTitle(title)
    .split(/[\s-]+/)
    .map(t => t.replace(/^[^\p{L}\p{N}]+|[^\p{L}\p{N}]+$/gu, ''))
    .filter(t => t.length > 0)
    .sort();
}

/**
 * Одна ли это семья имён: множества слов равны, порядок не важен.
 * «озеро курильское» и «курильское озеро» — одна; «водопад спокойный
 * (косы вероники)» и «водопад на ручье спокойный» — нет.
 */
export function sameNameFamily(a: string, b: string): boolean {
  const ta = nameTokens(a);
  const tb = nameTokens(b);
  if (ta.length === 0 || ta.length !== tb.length) return false;
  return ta.every((t, i) => t === tb[i]);
}

/** Можно ли отдать живой записи трек скрытой. */
export function canTransferTrack(liveGeometrySource: string | null, liveHasGeometry: boolean): boolean {
  if (!liveHasGeometry) return true;
  return liveGeometrySource !== null && TRANSFER_OVERWRITABLE.has(liveGeometrySource);
}
