export function fishArticleJsonLd(site: string = SITE): Record<string, unknown> {
  const url = `${site}/fish`;
  const published = recordDateIso(FISH_TEXT_REVISION);
  const modified = recordDateIso(FISH_PAGE_DATE);
  const org = { '@type': 'Organization', '@id': `${site}/#organization`, name: 'Ведар Камчатка', url: site };
  return {
    '@context': 'https://schema.org',
    '@type': 'Article',
    '@id': `${url}#article`,
    headline: FISH_PAGE_H1,
    description: FISH_PAGE_DESCRIPTION,
    inLanguage: 'ru',
    mainEntityOfPage: { '@type': 'WebPage', '@id': url },
    url,
    image: `${site}${DEFAULT_OG_IMAGE}`,
    author: { '@type': 'Organization', name: FISH_AUTHOR, url: site },
    publisher: org,
    datePublished: published,
    dateModified: modified,
  };
}

export function fishVisibleText(): string {
  const parts = [
    FISH_PAGE_H1,
    FISH_LEAD,
    FISH_AUTHOR,
    ...FISH_SECTIONS.flatMap((s) => [s.heading, ...s.paragraphs]),
    FISH_FAQ_HEADING,
    ...FISH_FAQ.flatMap((f) => [f.question, f.answer]),
    FISH_RELATED_HEADING,
    FISH_RELATED_INTRO,
    ...FISH_RELATED_LINKS.map((l) => l.label),
    FISH_SOURCES_HEADING,
    ...FISH_SOURCES.map((s) => s.label),
  ];
  return parts.join(' ');
}

export function fishWordCount(text: string = fishVisibleText()): number {
  return text.split(/\s+/).filter((w) => /[A-Za-zА-Яа-я0-9]/.test(w)).length;
}
