/**
 * lib/seo/json-ld-html.ts — содержимое `<script type="application/ld+json">`.
 *
 * `JSON.stringify` не экранирует «<»: строка `</script><script>…</script>` в
 * названии или описании тура, в отзыве туриста, в имени оператора или гида
 * закрыла бы тег разметки и выполнилась у КАЖДОГО посетителя страницы — с его
 * сессией. Эти строки пишут роли с самостоятельной регистрацией.
 *
 * Компонент `JsonLd` с экранированием в репозитории был, и его докстрока
 * просила новые страницы брать его, — но двенадцать страниц и корневой шаблон
 * вставляли голый `JSON.stringify`, пятнадцать мест (разбор 06.11). Правило без сторожа не держится: запрет
 * голого `JSON.stringify` в `__html` теперь держит
 * tests/unit/json-ld-escaped.test.tsx, а экранирование — эта функция одна.
 *
 * U+2028 и U+2029 — тоже: внутри `<script>` старые движки читают их как
 * перевод строки посреди литерала.
 */
export function jsonLdHtml(data: unknown): string {
  return (JSON.stringify(data) ?? 'null')
    .replace(/</g, '\\u003c')
    .replace(/\u2028/g, '\\u2028')
    .replace(/\u2029/g, '\\u2029');
}
