/** Видимый русский текст страницы «О Кузьмиче»: заголовок, лид, разделы, FAQ и ссылки. */
export function kuzmichVisibleText(): string {
  const parts = [
    KUZMICH_ABOUT_H1,
    KUZMICH_LEAD,
    ...KUZMICH_SECTIONS.flatMap((s) => [s.heading, ...s.paragraphs]),
    KUZMICH_FAQ_HEADING,
    ...KUZMICH_FAQ.flatMap((f) => [f.question, f.answer]),
    KUZMICH_RELATED_HEADING,
    KUZMICH_RELATED_INTRO,
    ...KUZMICH_RELATED_LINKS.map((l) => l.label),
  ];
  return parts.join(' ');
}

export function kuzmichWordCount(text: string = kuzmichVisibleText()): number {
  return text.split(/\s+/).filter((w) => /[A-Za-zА-Яа-я0-9]/.test(w)).length;
}
