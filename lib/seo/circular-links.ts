/**
 * Перелинковка по кругу: следующие n страниц после текущей, с переходом через конец.
 *
 * Перепись sitemap 14.10 (прогон 10) нашла 52 страницы с одной входящей
 * ссылкой — с хаба своего раздела и ни с одной соседней страницы. Две причины,
 * и обе — в форме отбора соседей:
 *
 *   - у статей блока «читайте дальше» не было вовсе (27 страниц);
 *   - у планов блок был, но брал ПЕРВЫЕ шесть: на планы с седьмого и дальше
 *     не вёл ни один другой план (9 страниц), а первые шесть получали ссылку
 *     с каждой страницы раздела.
 *
 * Следующие по кругу дают каждой странице ровно n входящих ссылок от n
 * предшественников — поровну, без любимчиков и без сирот. Порядок — тот же,
 * что в оглавлении раздела, поэтому соседи обычно и по теме соседние.
 */
export function circularNext<T>(items: readonly T[], isCurrent: (item: T) => boolean, n: number): T[] {
  if (n <= 0 || items.length === 0) return [];
  const at = items.findIndex(isCurrent);
  // Текущей в списке нет (скрыта, удалена) — первые n: блок не пропадает.
  if (at < 0) return items.slice(0, n);
  const out: T[] = [];
  for (let step = 1; step < items.length && out.length < n; step++) {
    out.push(items[(at + step) % items.length]);
  }
  return out;
}
