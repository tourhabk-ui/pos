/**
 * Переаттестация инструкторов-проводников — детерминированный расчёт.
 *
 * Основание: официальное разъяснение (июль 2026): включённые в Единый
 * федеральный реестр ДО 1 июля 2024 обязаны пройти переаттестацию по новым
 * правилам до 1 октября — иначе исключение из реестра, запрет выхода на
 * сложные маршруты и штрафы за работу без подтверждённой квалификации.
 *
 * Почему это дело платформы: у нас ~112 аттестованных гидов, и бейдж
 * «аттестован» — часть контура доверия. После срока показывать его гиду с
 * аннулированной аттестацией — значит врать туристу ровно там, где платформа
 * обещает не врать (vedar §7: статус безопасности — из данных).
 *
 * Расчёт чистый и намеренно консервативный: судим ТОЛЬКО по датам выдачи в
 * guide_certifications. Аттестация после порога = переаттестация пройдена.
 * Нет ни одной даты — не пугаем: честно «нет данных», а не «нарушитель».
 */

/** Порог из разъяснения: в реестре до этой даты — переаттестация обязательна. */
export const REGISTRY_CUTOFF = '2024-07-01';

/**
 * Дедлайн «до 1 октября». Год в разъяснении не назван; сообщение циркулирует
 * в июле 2026, читаем как 1 октября 2026. Если уточнится иное — поменять
 * ТОЛЬКО здесь.
 */
export const REATTESTATION_DEADLINE = '2026-10-01';

/** Федерации из разъяснения — куда подавать документы (по виду туризма). */
export const FEDERATIONS: Array<{ name: string; scope: string }> = [
  { name: 'Федерация спортивного туризма России', scope: 'водный, пешеходный, горный, спелео, лыжный туризм' },
  { name: 'Федерация альпинизма России', scope: 'горный и альпинистский туризм' },
  { name: 'Федерация подводного спорта России', scope: 'подводный туризм' },
];

export type ReattestationStatus =
  /** Есть аттестация до порога и ни одной после — надо переаттестоваться. */
  | 'needed'
  /** Есть аттестация после порога — требование закрыто. */
  | 'done'
  /** Все аттестации без дат — судить не по чему, честно говорим «нет данных». */
  | 'unknown'
  /** Аттестаций нет вообще — требование не про этого гида. */
  | 'not_applicable';

export interface CertLike {
  issue_date: string | null;
}

export function reattestationStatus(certs: readonly CertLike[]): ReattestationStatus {
  if (certs.length === 0) return 'not_applicable';
  const dated = certs.filter((c) => c.issue_date !== null);
  if (dated.length === 0) return 'unknown';
  if (dated.some((c) => (c.issue_date as string) >= REGISTRY_CUTOFF)) return 'done';
  return 'needed';
}

/** Дедлайн прошёл? (сравнение дат строками — ISO YYYY-MM-DD упорядочен лексикографически) */
export function deadlinePassed(todayIso: string): boolean {
  return todayIso >= REATTESTATION_DEADLINE;
}
