/**
 * Готовность гида к AI-визитке — одно правило, отдельно от переписи.
 *
 * ── Зачем эта цифра (19.09, #1926) ─────────────────────────────────────────
 *
 * Находка разведки просит дать гидам публичную страницу, где ассистент
 * отвечает туристу «строго на данных партнёра из его профиля и маршрутов».
 * Страница гида у нас есть (`app/guides/[id]/page.tsx`), Кузьмич есть,
 * партнёрская область видимости тоже есть и работает — `lib/kuzmich/
 * operator-chat.ts` отвечает оператору про ЕГО туры и брони, отбирая по
 * `operator_id` в каждом запросе.
 *
 * Неизвестно другое: **чем такой ассистент будет отвечать.** У гидов нет
 * своих туров — туры принадлежат оператору (`operator_tours.operator_id`), а
 * гид связан с ним полем `partners.guide_operator_id` (так и работает
 * `app/api/guide/tours/route.ts`). В базе 13 операторов и 112 гидов, и
 * сколько гидов к оператору ПРИВЯЗАНО, не считала ещё ни одна перепись:
 * `catalog-census` считает аттестованных, `partner-junk-census` — туры,
 * брони и аттестаты, `guide_operator_id` не смотрит никто.
 *
 * Если привязанных единицы, то сто двенадцать страниц получат ассистента,
 * который умеет пересказать профиль, — это хуже его отсутствия. Цифру берут
 * ДО работы, а не после: на завышенных догадках репозиторий уже обжигался
 * дважды («778 мест» вместо 379, «20 туров» вместо 8), и оба раза работа
 * считалась сделанной там, где не начиналась.
 *
 * ── Почему блокирует именно это ────────────────────────────────────────────
 *
 * Три условия, и каждое следует из решения владельца 19.09, а не из вкуса:
 *
 *  1. **Гид привязан к оператору.** Владелец решил: заявка со страницы гида
 *     принадлежит оператору, гид записывается источником. Не привязан —
 *     заявку отдать некому, и это не полбеды, а отсутствие механизма.
 *  2. **У оператора есть активный тур.** Привязка без туров — та же пустота
 *     этажом ниже: ассистент доведёт разговор до брони, которой нет.
 *  3. **Описание гида не пустое.** Ассистенту, которому не дали ничего о
 *     человеке, останется единственный способ ответить — выдумать (§4.0,
 *     случай Ключевской: требование, которое нечем выполнить, выполняется
 *     выдумкой).
 *
 * **Порога длины описания здесь НЕТ, и это намеренно.** У туров он есть (300
 * знаков) и взят не с потолка — по нему работает Editor. Для профиля гида
 * такого числа в платформе не существует, и придумать его значило бы
 * записать решение там, где его не принимали. Перепись отдаёт длину каждого
 * описания; понадобится порог — назовёт владелец, глядя на распределение.
 *
 * Аттестаты, отзывы и фото считаются, но не блокируют: без них страница
 * беднее, а ассистент всё ещё имеет что сказать.
 */

export interface GuideReadinessRow {
  id: string;
  name: string;
  /** Оператор, к которому привязан гид (partners.guide_operator_id). */
  operator_id: string | null;
  operator_name: string | null;
  /** Активных неудалённых туров у ЭТОГО оператора. */
  operator_active_tours: number;
  description_chars: number;
  verified_certs: number;
  public_reviews: number;
  has_photo: boolean;
  languages_count: number;
  specializations_count: number;
}

/** Что мешает завести ассистента на странице этого гида. Пусто — ничего. */
export function blockingGaps(r: GuideReadinessRow): string[] {
  const gaps: string[] = [];
  if (!r.operator_id) gaps.push('operator_not_linked');
  else if (r.operator_active_tours === 0) gaps.push('operator_has_no_active_tours');
  if (r.description_chars === 0) gaps.push('description_empty');
  return gaps;
}

/**
 * Чем страница богата сверх обязательного. Не блокирует — показывает, где
 * ассистенту будет о чём говорить, а где он ограничится сухой справкой.
 */
export function contentSignals(r: GuideReadinessRow): string[] {
  const has: string[] = [];
  if (r.verified_certs > 0) has.push('certs');
  if (r.public_reviews > 0) has.push('reviews');
  if (r.has_photo) has.push('photo');
  if (r.languages_count > 0) has.push('languages');
  if (r.specializations_count > 0) has.push('specializations');
  return has;
}
