/** Куда физически уходят данные — это факт о юрисдикции, а не о бренде. */
export type Jurisdiction = 'RU' | 'US' | 'EU' | 'unknown';

export interface ThirdParty {
  /** Ключ = имя компонента-загрузчика, чтобы сторож сверял связку. */
  id: string;
  /** Как называть человеку в политике. */
  title: string;
  /** Юрлицо, если известно; null — «не установлено», а не «нет». */
  entity: string | null;
  /** Хост, с которого реально грузится скрипт. */
  host: string;
  jurisdiction: Jurisdiction;
  /** Зачем — словами для человека, не «для улучшения сервиса». */
  purpose: string;
  /**
   * Является ли размещение РЕКЛАМОЙ по 38-ФЗ. Если да — нужен erid, и без
   * него грузить нельзя: токен выдаёт ОРД, выдумать его невозможно.
   */
  isAdvertising: boolean;
  /** Токен erid, если получен. null — не получен, и это блокирует загрузку. */
  erid: string | null;
  /**
   * Категория согласия. `analytics` и `advertising` грузятся только после
   * согласия; `essential` — то, без чего сервис не работает (таких здесь нет).
   */
  consentCategory: 'essential' | 'analytics' | 'advertising';
}

