/** Загружать ли сервис при данном согласии — и почему нет, если нет. */
export function loadDecision(
  tp: ThirdParty,
  consent: { analytics: boolean; advertising: boolean },
): { load: true } | { load: false; reason: string } {
  // Реклама без токена не грузится НИКОГДА, даже с согласия: маркировка —
  // требование закона к размещению, а не к посетителю. Токен выдаёт ОРД;
  // подставить сюда выдуманную строку значит подделать маркировку.
  if (tp.isAdvertising && !tp.erid) {
    return {
      load: false,
      reason: `${tp.title}: рекламное размещение без токена erid (38-ФЗ ст. 18.1) — токен получают в ОРД, выдумать его нельзя`,
    };
  }
  if (tp.consentCategory === 'essential') return { load: true };
  if (tp.consentCategory === 'analytics' && consent.analytics) return { load: true };
  if (tp.consentCategory === 'advertising' && consent.advertising) return { load: true };
  return { load: false, reason: `${tp.title}: согласие на «${tp.consentCategory}» не дано` };
}

/** Уходят ли данные за пределы РФ — фактический вопрос для политики. */
export function crossBorderRecipients(): ThirdParty[] {
  return THIRD_PARTIES.filter((t) => t.jurisdiction !== 'RU');
}
