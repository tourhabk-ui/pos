/**
 * Согласие на обработку персональных данных — единый источник.
 *
 * Формулировка и её ВЕРСИЯ живут здесь, потому что записывать надо не факт
 * «галочка стояла», а текст, под которым человек подписался. Политика со
 * временем меняется; согласие, записанное как булево, через год не докажет
 * ничего — непонятно, на что именно человек соглашался.
 *
 * Форма показывает PD_CONSENT_TEXT, сервер записывает PD_CONSENT_VERSION рядом
 * с временем и адресом. Две копии формулировки — в компоненте и в записи — со
 * временем разошлись бы; поэтому копия одна.
 */

/** Версия формулировки. Меняется вместе с текстом, НИКОГДА не задним числом. */
export const PD_CONSENT_VERSION = '2026-10-08';

/**
 * Что человек видит рядом с галочкой (ссылка на политику — отдельным узлом).
 *
 * С 08.10 текст называет передачу оператору (решение владельца): платформа —
 * информационная система, и её работа по заявке и есть передача контактов
 * туроператору. Согласие, которое молчит о главной передаче, не покрывает её.
 * Версия 2026-08-23 — прежний текст без передачи; записи под ней остаются как
 * были, задним числом не переписываются.
 */
export const PD_CONSENT_TEXT =
  'Согласен на обработку персональных данных и их передачу туроператору для связи по заявке';

/**
 * Вариант для жилья (10.10, заявка хозяину через форму карточки, 1206).
 * Телефон туриста там уходит не туроператору, а хозяину гостевого дома, и
 * согласие обязано назвать именно его: формулировка, которая молчит о главной
 * передаче, её не покрывает (то же правило, что 08.10). Отдельная версия —
 * чтобы по записи было видно, под каким из двух текстов человек согласился.
 */
export const PD_CONSENT_STAY_TEXT =
  'Согласен на обработку персональных данных и их передачу владельцу жилья для связи по заявке';
export const PD_CONSENT_STAY_VERSION = '2026-10-10-stay';

/** Кому передаются данные по заявке: туроператору (по умолчанию) или владельцу жилья. */
export type PdConsentPurpose = 'operator' | 'stay';

/** Текст и версия согласия для цели заявки — единственный выбор между ними. */
export function consentWording(purpose: PdConsentPurpose = 'operator'): { text: string; version: string } {
  return purpose === 'stay'
    ? { text: PD_CONSENT_STAY_TEXT, version: PD_CONSENT_STAY_VERSION }
    : { text: PD_CONSENT_TEXT, version: PD_CONSENT_VERSION };
}

/** Куда ведёт ссылка рядом с галочкой. */
export const PD_CONSENT_POLICY_URL = '/legal/privacy';

/**
 * Запись согласия. Три поля обязательны вместе: время без адреса и без версии
 * текста — не доказательство, а видимость.
 */
export interface PdConsentRecord {
  at: Date;
  ip: string;
  /** Откуда пришло согласие: 'web-form', 'widget', 'operator-signup'. */
  source: string;
  version: string;
}

/**
 * Собрать запись согласия. Возвращает null, если согласия НЕ БЫЛО — это
 * третье состояние, а не отказ: лид может прийти из бота или MCP, где формы с
 * галочкой нет вовсе. «Отказано» и «не спрашивали» — разные вещи, и в базе они
 * тоже разные.
 */
export function buildConsentRecord(
  given: boolean | undefined,
  ip: string | null | undefined,
  source: string,
  purpose: PdConsentPurpose = 'operator',
): PdConsentRecord | null {
  if (given !== true) return null;
  return {
    at: new Date(),
    ip: (ip ?? '').slice(0, 64) || 'неизвестен',
    source,
    version: consentWording(purpose).version,
  };
}
