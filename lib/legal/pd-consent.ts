/**
 * Согласие на обработку персональных данных — единый источник.
 *
 * Формулировка и её ВЕРСИЯ живут здесь, потому что записывать надо не факт
 * «галочка стояла», а текст, под которым человек подписался. Политика со
 * временем меняется; согласие, записанное как булево, через год не докажет
 * ничего — непонятно, на что именно человек соглашался.
 *
 * Форма показывает PD_CONSENT_TEXT, сервер записывает PD_CONSENT_VERSION рядом
 * с временем и адресом. Две копии формулировки — в компоненте и в записи — со
 * временем разошлись бы; поэтому копия одна.
 */

/** Версия формулировки. Меняется вместе с текстом, НИКОГДА не задним числом. */
export const PD_CONSENT_VERSION = '2026-10-08';

/**
 * Что человек видит рядом с галочкой (ссылка на политику — отдельным узлом).
 *
 * С 08.10 текст называет передачу оператору (решение владельца): платформа —
 * информационная система, и её работа по заявке и есть передача контактов
 * туроператору. Согласие, которое молчит о главной передаче, не покрывает её.
 * Версия 2026-08-23 — прежний текст без передачи; записи под ней остаются как
 * были, задним числом не переписываются.
 */
export const PD_CONSENT_TEXT =
  'Согласен на обработку персональных данных и их передачу туроператору для связи по заявке';

/**
 * Вариант для жилья (10.10, заявка хозяину через форму карточки, 1206).
 * Телефон туриста там уходит не туроператору, а хозяину гостевого дома, и
 * согласие обязано назвать именно его: формулировка, которая молчит о главной
 * передаче, её не покрывает (то же правило, что 08.10). Отдельная версия —
 * чтобы по записи было видно, под каким из двух текстов человек согласился.
 */
export const PD_CONSENT_STAY_TEXT =
  'Согласен на обработку персональных данных и их передачу владельцу жилья для связи по заявке';
export const PD_CONSENT_STAY_VERSION = '2026-10-10-stay';

/**
 * Вариант для заявки на машину перевозчику (13.10, стандарт карточки
 * трансфера): телефон уходит перевозчику, а не туроператору. До 13.10 заявка
 * на машину через MCP записывала версию «туроператору» — согласие молчало о
 * настоящем получателе (то же правило, что 08.10 и 10.10).
 */
export const PD_CONSENT_CARRIER_TEXT =
  'Согласен на обработку персональных данных и их передачу перевозчику для связи по заявке';
export const PD_CONSENT_CARRIER_VERSION = '2026-10-13-carrier';

/**
 * Вариант для заявки на аренду снаряжения (аудит 15.10, находка A13): имя,
 * телефон и почта уходят прокату — партнёру платформы, а не туроператору.
 * До 15.10 форма проката не спрашивала согласия вовсе, и данные вошедшего
 * уходили прокату без текста, называющего получателя (то же правило, что
 * 08.10, 10.10 и 13.10).
 */
export const PD_CONSENT_GEAR_TEXT =
  'Согласен на обработку персональных данных и их передачу прокату снаряжения для связи по заявке';
export const PD_CONSENT_GEAR_VERSION = '2026-10-15-gear';

/**
 * Вариант для заявки на прокат автомобиля (23.10, решение владельца «пока
 * берем аренду автомобилей и трансфер», витрина /car-rental, схема 1317):
 * телефон арендатора уходит прокату автомобилей — не туроператору и не
 * перевозчику, хотя партнёр может быть одним и тем же юрлицом. Согласие
 * называет получателя по роду заявки, а не по карточке партнёра: человек
 * соглашался на передачу тому, у кого берёт машину (то же правило, что
 * 08.10, 10.10, 13.10 и 15.10).
 */
export const PD_CONSENT_RENTAL_TEXT =
  'Согласен на обработку персональных данных и их передачу прокату автомобилей для связи по заявке';
export const PD_CONSENT_RENTAL_VERSION = '2026-10-23-rental';

/**
 * Вариант для подписанта согласия партнёра на материалы (23.10, миграция
 * 1321): имя и должность представителя партнёра — его персональные данные.
 * Они не передаются никому: нужны, чтобы согласие партнёра было чьим-то, а не
 * анонимным. Поэтому текст говорит об учёте, а не о передаче.
 */
export const PD_CONSENT_PARTNER_SIGNER_TEXT =
  'Согласен на обработку моих персональных данных (имя и должность) для учёта согласия партнёра на использование материалов';
export const PD_CONSENT_PARTNER_SIGNER_VERSION = '2026-10-23-partner-signer';

/**
 * Для чего согласие: передача по заявке туроператору (по умолчанию), владельцу
 * жилья, перевозчику, прокату снаряжения или прокату автомобилей — либо учёт
 * подписанта согласия партнёра на материалы.
 */
export type PdConsentPurpose = 'operator' | 'stay' | 'carrier' | 'gear' | 'rental' | 'partner-signer';

/** Текст и версия согласия для цели заявки — единственный выбор между ними. */
export function consentWording(purpose: PdConsentPurpose = 'operator'): { text: string; version: string } {
  // Исчерпывающий выбор: новый purpose без своей ветки — ошибка tsc, а не
  // тихий текст «туроператору» с его версией в записи.
  switch (purpose) {
    case 'operator': return { text: PD_CONSENT_TEXT, version: PD_CONSENT_VERSION };
    case 'stay': return { text: PD_CONSENT_STAY_TEXT, version: PD_CONSENT_STAY_VERSION };
    case 'carrier': return { text: PD_CONSENT_CARRIER_TEXT, version: PD_CONSENT_CARRIER_VERSION };
    case 'gear': return { text: PD_CONSENT_GEAR_TEXT, version: PD_CONSENT_GEAR_VERSION };
    case 'rental': return { text: PD_CONSENT_RENTAL_TEXT, version: PD_CONSENT_RENTAL_VERSION };
    case 'partner-signer': return { text: PD_CONSENT_PARTNER_SIGNER_TEXT, version: PD_CONSENT_PARTNER_SIGNER_VERSION };
    default: {
      const never: never = purpose;
      return never;
    }
  }
}

/** Куда ведёт ссылка рядом с галочкой. */
export const PD_CONSENT_POLICY_URL = '/legal/privacy';

/**
 * Запись согласия. Три поля обязательны вместе: время без адреса и без версии
 * текста — не доказательство, а видимость.
 */
export interface PdConsentRecord {
  at: Date;
  ip: string;
  /** Откуда пришло согласие: 'web-form', 'widget', 'operator-signup'. */
  source: string;
  version: string;
}

/**
 * Собрать запись согласия. Возвращает null, если согласия НЕ БЫЛО — это
 * третье состояние, а не отказ: лид может прийти из бота или MCP, где формы с
 * галочкой нет вовсе. «Отказано» и «не спрашивали» — разные вещи, и в базе они
 * тоже разные.
 */
export function buildConsentRecord(
  given: boolean | undefined,
  ip: string | null | undefined,
  source: string,
  purpose: PdConsentPurpose = 'operator',
): PdConsentRecord | null {
  if (given !== true) return null;
  return {
    at: new Date(),
    ip: (ip ?? '').slice(0, 64) || 'неизвестен',
    source,
    version: consentWording(purpose).version,
  };
}
