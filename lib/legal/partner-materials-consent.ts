/**
 * Согласие партнёра на использование материалов его сайта на Ведаре —
 * единый источник текста и версии (решение владельца 23.10: «нужна форма
 * согласия об использовании матерьялов сайтов партнеров на нашем сайте»;
 * запись — миграция 1321).
 *
 * Текст и версия меняются вместе и никогда задним числом. В базу пишется сам
 * текст (`signed_text`), собранный сервером, а не галочка и не одна версия:
 * текст зависит от имени партнёра и его сайтов, и по версии восстановить, что
 * человек прочёл, было бы нечем. Страница показывает тот же текст
 * (`consentDocument`), сервер сверяет его со своим — разошлись, подписи нет.
 *
 * Объём один для всех и назван так, как платформа делает на самом деле
 * (ревью 23.10). Выбора «где показывать» и «какие материалы» нет намеренно:
 * ни одна витрина, ни Кузьмич, ни MCP, ни выгрузки площадкам не сверяются с
 * согласием, и галочка, которую нечем исполнить, — обещание без исполнителя
 * (§10.09) в юридическом тексте. Где материалы на деле бывают — перепись
 * путей 23.10 по коду (PR согласия).
 *
 * Согласие не даёт места выше в общих списках (CLAUDE.md §0): порядок там
 * один для всех, платное поднятие — только реклама с маркировкой.
 */

export const PARTNER_MATERIALS_CONSENT_VERSION = '2026-10-23';

/** Согласие на экране — без имени подписанта: его видит только администратор. */
export interface MaterialsConsentPublic {
  /** YYYY-MM-DD по Камчатке. */
  grantedOn: string;
  sites: string[];
}

/** Адрес сайта без протокола и хвостового слэша: «лагунапрокат.рф». */
export function siteWords(site: string): string {
  return site.trim().replace(/^https?:\/\//i, '').replace(/\/+$/, '');
}

export interface MaterialsConsentParties {
  partnerName: string;
  sites: readonly string[];
}

/**
 * Текст согласия — его партнёр читает и под ним подписывается. Абзацы —
 * массивом: так их рисует страница и так их сверяют сторожа.
 */
export function materialsConsentParagraphs(s: MaterialsConsentParties): string[] {
  const sites = s.sites.length > 0
    ? `своих сайтов и страниц (${s.sites.map(siteWords).join(', ')})`
    : 'своих сайтов и страниц';
  return [
    `«${s.partnerName}» разрешает Ведару (vedarai.ru) безвозмездно и на неисключительной основе использовать материалы ${sites} — фотографии, видео, логотип, описания услуг и условий, цены, — чтобы рассказывать туристам о своих услугах.`,
    'Где Ведар их использует: на странице партнёра и в карточках его предложений; на общих страницах Ведара — главной, в каталоге, в списках трансферов и проката, в карточках мест и маршрутов, в плане поездки, на страницах на китайском языке; в виджете Ведара на сайте партнёра, если он установлен; в ответах помощника Кузьмича на сайте, в Telegram и MAX; в публикациях Ведара в Telegram и MAX; в ответах ИИ-агентам и сервисам, подключённым к Ведару; в выгрузках предложений для площадок объявлений.',
    'Как: снимки уменьшаются и кадрируются для показа; тексты могут сокращаться и переводиться на другие языки машинным переводом с пометкой об этом; чтобы отвечать туристам и переводить, тексты и цены обрабатывают языковые модели, в том числе зарубежные.',
    'Права на материалы остаются у партнёра. Согласие не даёт ему места выше других в общих списках Ведара: порядок там один для всех.',
    'Согласие действует, пока партнёр его не отзовёт. Отозвать можно сообщением менеджеру Ведара в MAX или Telegram. После отзыва менеджер Ведара снимает с показа материалы, взятые с сайта партнёра; копии, которые уже забрали площадки объявлений и ИИ-агенты, Ведар отозвать у них не может.',
  ];
}

/** Подтверждение полномочий — отдельной строкой рядом с галочкой. */
export function authorityStatement(partnerName: string): string {
  return `Подтверждаю, что вправе дать это согласие от имени «${partnerName}»: материалы принадлежат партнёру или он вправе ими распоряжаться, а люди, узнаваемые на снимках, согласны на их показ.`;
}

/**
 * Документ целиком — абзацы и подтверждение полномочий через пустую строку.
 * Ровно это пишется в `signed_text` и ровно это страница присылает на сверку.
 */
export function consentDocument(s: MaterialsConsentParties): string {
  return [...materialsConsentParagraphs(s), authorityStatement(s.partnerName)].join('\n\n');
}

/** «2026-10-23» → «23.10.2026»; не разобралось — как есть. */
export function consentDateWords(iso: string): string {
  const m = /^(\d{4})-(\d{2})-(\d{2})$/.exec(iso);
  return m ? `${m[3]}.${m[2]}.${m[1]}` : iso;
}

/**
 * Строка на собственной странице партнёра — факт записи, а не происхождение
 * показанного (ревью 23.10): откуда взят каждый снимок, система не знает, и
 * «фотографии — с сайта» на странице без фотографий было бы неправдой.
 * Только при записанном неотозванном согласии — без записи строки нет вовсе
 * (§4.0), и на общих витринах её нет никогда (§0: знак на общей витрине был
 * бы выделением, а не правдой о себе).
 */
export function materialsConsentLine(c: { grantedOn: string; sites: readonly string[] }): string {
  const what = c.sites.length === 0
    ? 'своих сайтов'
    : c.sites.length === 1
      ? `своего сайта ${siteWords(c.sites[0]!)}`
      : `своих сайтов ${c.sites.map(siteWords).join(', ')}`;
  return `Партнёр разрешил Ведару показывать материалы ${what}: согласие от ${consentDateWords(c.grantedOn)}.`;
}
