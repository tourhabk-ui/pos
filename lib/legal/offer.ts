/**
 * Просьба принять оферту — партнёру, заведённому до отметки на регистрации,
 * и тому, кто принимал прежнюю редакцию. Слово владельца 24.11: «Партнёры,
 * заведённые до оферты, принимают её при следующем входе в кабинет, до
 * сезона». У «до сезона» даты нет — её и не называем; кабинет просьба не
 * запирает, заявки идут как шли.
 *
 *   accepted   — действующая редакция принята;
 *   needed     — не принята, принять может тот, кто смотрит (владелец кабинета);
 *   owner_only — не принята, а смотрит менеджер команды: принять может владелец;
 *   not_needed — роль не сторона оферты (агент);
 *   unknown    — журнал не прочитался: это не «не принята» (§4.0).
 */
export type OfferAskState = 'accepted' | 'needed' | 'owner_only' | 'not_needed' | 'unknown';

export const OFFER_ASK_STATES: readonly OfferAskState[] = ['accepted', 'needed', 'owner_only', 'not_needed', 'unknown'];

/** Подпись пункта оферты в чек-листе, пока она не принята. */
export const OFFER_ASK_TAG = 'просим до начала сезона';

/**
 * Слова просьбы. `previous` — партнёр принимал прежнюю редакцию: ему сказано,
 * что оферта обновилась, а не что отметки нет.
 */
export function offerAskWords(state: 'needed' | 'owner_only', previous: boolean): string {
  // Редакция кончается на «г.» — второй точки после неё не ставим.
  const what = previous
    ? `Оферта для партнёров обновилась: действует редакция от ${OFFER_EDITION}`
    : `Примите оферту для партнёров — редакция от ${OFFER_EDITION}`;
  if (state === 'owner_only') {
    return `${previous ? what : `Оферта для партнёров (редакция от ${OFFER_EDITION}) ещё не принята.`} Принять её может владелец кабинета — напомните ему. Заявки приходят как раньше.`;
  }
  return `${what} Просим ${previous ? 'принять её' : 'сделать это'} до начала сезона. Заявки приходят вам как раньше.`;
}

