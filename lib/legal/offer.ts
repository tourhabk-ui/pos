/**
 * Роли — стороны оферты: Платформа размещает их услуги и передаёт им заявки
 * (п. 1 оферты). Тот же список, что «роли с заявками». Агент услуг не
 * размещает и заявок не получает — отметка ему не нужна.
 */
export const OFFER_ROLES: readonly string[] = REQUEST_RECEIVING_CATEGORIES;

export function isOfferRole(role: string | null | undefined): boolean {
  return typeof role === 'string' && OFFER_ROLES.includes(role);
}

/** Нужна ли отметка при регистрации с этим набором ролей. */
export function offerRequiredFor(roles: readonly string[]): boolean {
  return roles.some(isOfferRole);
}

