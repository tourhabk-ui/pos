/**
 * Короткий адрес партнёра: vedarai.ru/<slug> (решение владельца 13.10).
 *
 * Страница app/[slug] — верхний динамический сегмент, и Next отдаёт ему всё,
 * чего не нашёл среди статических маршрутов: и /mestechko, и /foo.png. Чтобы
 * каждая опечатка не ходила в базу, сюда пускается только форма slug
 * партнёра: латиница, цифры, дефис, от 2 до 100 знаков, без точек.
 * Статические маршруты (/catalog, /about, …) Next выбирает раньше, поэтому
 * партнёр со slug, равным имени раздела, короткого адреса не получит —
 * сторож partner-short-address держит, что у известных партнёров таких нет.
 */
export const SHORT_SLUG_RE = /^[a-z0-9][a-z0-9-]{1,99}$/;

export function isShortSlug(slug: string): boolean {
  return SHORT_SLUG_RE.test(slug);
}
