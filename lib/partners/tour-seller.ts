/**
 * Продаёт ли партнёр свои туры — один ответ на все двери чата кабинета.
 *
 * Свои туры продаёт туроператор и, с 28.10, гид с авторскими турами (1338):
 * они лежат в `operator_tours` с `operator_id` его карточки гида. Гид из
 * команды оператора без своих туров — не продавец: ему сводка туров и
 * инструмент расписания дали бы пустое «туров не найдено» на каждый вопрос,
 * а таких гидов на платформе больше сотни.
 *
 * Признак у гида — `sellsTours`: `findPartnerByChat` читает его тем же
 * запросом, что карточку (EXISTS по неудалённым турам, черновики считаются —
 * это его туры). Поля нет (старый вызов, мок без колонки) — не продаёт: так
 * гид остаётся ровно тем, кем был до 29.10, а не получает пустые сводки.
 *
 * Туроператор — продавец по категории, как было до 29.10, и без своих туров:
 * его «туров нет» — правда о его кабинете, а не чужая роль.
 */

export interface TourSellerFacts {
  /** `partners.category` как записан. */
  category: string | null | undefined;
  /** Есть ли у карточки неудалённый тур в `operator_tours`. Нет поля — нет. */
  sellsTours?: boolean;
}

export function sellsOwnTours(p: TourSellerFacts): boolean {
  if (p.category === 'operator') return true;
  return p.category === 'guide' && p.sellsTours === true;
}
