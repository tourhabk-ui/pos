/** Роды, заведённые генераторами изображений. Список может только сокращаться. */
export const GENERATED_MODELS = ['qwen-image', 'pollinations-flux'] as const;

export type GeneratedModel = (typeof GENERATED_MODELS)[number];

/** Сгенерирован ли снимок. NULL и незнакомое имя — нет (см. шапку). */
export function isGenerated(model: string | null | undefined): boolean {
  return model != null && (GENERATED_MODELS as readonly string[]).includes(model);
}
