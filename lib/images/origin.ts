/**
 * Происхождение снимка места: сгенерирован или снят.
 *
 * Список ЗАМОРОЖЕН и живёт в коде, а не в теле запроса. Это главное свойство
 * безопасности обоих разборов: удаляющий роут не принимает «что удалять»
 * снаружи — он знает это сам. Опечатка в параметре не может стереть
 * `real-photo`, потому что параметра нет.
 *
 * Перепись 09.09 (`GET /api/cron/images-oversize` с прода) назвала восемь
 * родов на 657 строк:
 *
 *   qwen-image          98 строк · 189,9 МБ · ~1985 КБ в среднем — генерация
 *   real-photo          87 · 93,0 МБ · ~1095 КБ
 *   idilesom-search    191 · 69,4 МБ · ~372 КБ
 *   idilesom-photo     149 · 52,4 МБ · ~360 КБ
 *   pollinations-flux   75 · 7,2 МБ · ~99 КБ — генерация
 *   wikimedia-commons   23 · 4,8 МБ
 *   manual-upload       33 · 4,2 МБ
 *   wikimedia            1 · 0,3 МБ
 *
 * Почему генерация удаляется, а не сжимается: решение владельца 2026-07-17 —
 * «честный градиент вместо AI-фото». Картинка, которую нельзя показывать,
 * не становится нужнее оттого, что стала легче.
 *
 * Незнакомый род НЕ считается генерацией. Умолчание здесь одностороннее
 * намеренно: ошибиться в сторону «оставить лишнее» можно, в сторону
 * «удалить снятое» — нельзя (§4.0, третий исход у списка есть, и он
 * консервативный).
 */

/** Роды, заведённые генераторами изображений. Список может только сокращаться. */
export const GENERATED_MODELS = ['qwen-image', 'pollinations-flux'] as const;

export type GeneratedModel = (typeof GENERATED_MODELS)[number];

/** Сгенерирован ли снимок. NULL и незнакомое имя — нет (см. шапку). */
export function isGenerated(model: string | null | undefined): boolean {
  return model != null && (GENERATED_MODELS as readonly string[]).includes(model);
}

/**
 * Роды снимков, которые карточка ПОКАЗЫВАЕТ.
 *
 * ── Почему список один, а не тринадцать ───────────────────────────────────
 *
 * До 18.09 условие показа было написано литералом
 * `model IN ('wikimedia','manual-upload')` в ТРИНАДЦАТИ файлах: карточка
 * места и её серверная страница, лента, тренды, раздача картинки, коллекции,
 * каталог маршрутов, карточка маршрута, страница брони, две переписи. Правило,
 * повторённое тринадцать раз, — это тринадцать правил, и разойтись им ничто
 * не мешало.
 *
 * Разошлись они не между собой, а с ДАННЫМИ. Комментарий у фильтра говорил
 * «AI-генерации не показываем» (решение владельца 17.07), и это правда лишь
 * наполовину: заодно он прятал 103 настоящие фотографии, чей род просто не
 * совпал со строкой — `real-photo` (81) и `wikimedia-commons` (22). Перепись
 * 14.09 это назвала, но исправить было нечем: у скрытых снимков пусты автор
 * и лицензия, а без них публиковать нельзя.
 *
 * ── Почему `real-photo` теперь показывается ───────────────────────────────
 *
 * 18.09 владелец на прямой вопрос о правах ответил: «это мои фото влиты».
 * Источник прав назван человеком, которому они принадлежат; миграция 978
 * проставляет ему авторство там, где его не было.
 *
 * `wikimedia-commons` в список НЕ внесён и это не забывчивость: те 22 снимка
 * чужие, их лицензия требует указания автора, а автора у строк нет. Пока
 * подписать нечем — показывать нельзя. Разные права — разные решения.
 *
 * ── Почему список вшит в SQL, а не передаётся параметром ──────────────────
 *
 * Значения здесь — замороженные константы кода, а не ввод: снаружи в этот
 * список попасть нечем. Форму держит сторож `photo-shown-single-source`: имена
 * обязаны быть из латиницы и дефиса, иначе тест краснеет, и почвы для
 * подстановки не остаётся по построению.
 */
export const SHOWN_MODELS = ['wikimedia', 'manual-upload', 'real-photo'] as const;

/**
 * Условие показа для SQL. `modelExpr` — выражение с родом снимка в запросе,
 * например `ai.model`. Возвращает готовый предикат.
 */
export function shownPhotoSql(modelExpr: string): string {
  return `${modelExpr} IN (${SHOWN_MODELS.map((m) => `'${m}'`).join(', ')})`;
}
