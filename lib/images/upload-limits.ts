/**
 * lib/images/upload-limits.ts — пределы и подсказка загрузки снимков.
 * Без серверных импортов: этот файл читают и формы в браузере, и роуты.
 * Подготовка снимка — lib/images/upload-photo.ts.
 */

/** Предел файла до подготовки, МБ. Снимок с телефона весит 3–12 МБ; прежние 5 МБ отказывали обычному снимку. */
export const UPLOAD_PHOTO_MAX_MB = 20;
export const UPLOAD_PHOTO_MAX_BYTES = UPLOAD_PHOTO_MAX_MB * 1024 * 1024;

/** Подсказка у полей загрузки: что сайт сделает со снимком. */
export const PHOTO_UPLOAD_HINT =
  'Сайт сам уменьшит снимок до размера сайта и уберёт из файла место съёмки. Кадр не обрезается.';

/**
 * Отказ по размеру — одна строка у сервера и у форм. Формы проверяют размер
 * ещё в браузере: по мобильной связи не гнать 25 МБ ради отказа. Сервер
 * проверяет то же сам — форма могла быть старой, запрос мог прийти не из неё.
 */
export const PHOTO_TOO_LARGE =
  `Файл больше ${UPLOAD_PHOTO_MAX_MB} МБ — сайт такой не примет. Сохраните копию снимка поменьше и загрузите её.`;

export function photoTooLarge(size: number): boolean {
  return size > UPLOAD_PHOTO_MAX_BYTES;
}
