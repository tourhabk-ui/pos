/**
 * Один день занят бронью, если он ВНУТРИ её интервала — а не равен её началу.
 *
 * ── Что нашлось 15.09, и как ──────────────────────────────────────────────
 *
 * Найдено не чтением кода, а вопросом к живому проду через MCP. Спросил
 * свободные даты у тура «Многодневный летний тур (5 дней)» — витрина
 * предложила пятнадцатое, шестнадцатое, семнадцатое, восемнадцатое и
 * девятнадцатое, каждую по десять мест. Хотя тур, начатый пятнадцатого,
 * занимает всё это окно целиком.
 *
 * Перепись того же дня: из ДЕВЯТИ живых туров ШЕСТЬ многодневные, включая
 * пятидневный и два недельных по 140-196 тысяч за человека. То есть речь не
 * про край каталога, а про две трети.
 *
 * ── Почему это стало видно только сейчас ──────────────────────────────────
 *
 * До 14.09 врали одинаково обе половины: гейт (`reserveBooking`) записывал
 * многодневную бронь как однодневную, а витрина её так же и считала.
 * Согласованная ложь не бросается в глаза — обе стороны показывали «свободно»
 * и обе пропускали бронь. Цена была тихой: перепродажа тех же мест.
 *
 * #1894 научил гейт считать интервалом. Ложь перестала быть согласованной:
 * теперь витрина предлагает дату, а гейт на ней отказывает. Это строго лучше
 * (отказ дешевле двойной продажи), но человек видит свободное и упирается в
 * стену — и починка не закончена, пока обе половины не считают одинаково.
 *
 * ── Почему функция, а не правка на месте ──────────────────────────────────
 *
 * Мест с этим предикатом ОДИННАДЦАТЬ: витрина дат, два листинга доступности,
 * публичное «сейчас», два календаря оператора, поиск туров, планер,
 * агентский подбор, диагностика и внешний канал. Правило, переписанное
 * одиннадцать раз, — это одиннадцать правил, и они уже разошлись: часть
 * забывает `deleted_at IS NULL`, часть нет.
 *
 * ── Что именно считается занятым ──────────────────────────────────────────
 *
 * `день BETWEEN booking_date И COALESCE(end_date, booking_date)` — та же
 * форма, что в гейте (`lib/bookings/reserve.ts`) и в виде
 * `v_tour_daily_occupancy` (миграция 140). `COALESCE` обязателен: пустой
 * `end_date` означает «ровно один день», а не «неизвестно», и брони, заведённые
 * до #1894, обязаны читаться по-прежнему однодневными.
 *
 * Предикат статусов — `NOT IN ('cancelled','rejected')`, как у гейта, а НЕ
 * `IN ('new','confirmed')`, как у вида: `pending_payment` (оплата начата)
 * место держит. Взять предикат вида значило бы показать свободным место, за
 * которое человек в эту минуту платит.
 */

/** Статусы, при которых бронь места НЕ держит. */
export const FREEING_BOOKING_STATUSES = ['cancelled', 'rejected'] as const;

/**
 * Условие «бронь `booking` занимает день `day`».
 *
 * @param booking алиас `operator_bookings` в запросе (например `ob`)
 * @param day     выражение дня — колонка (`ta.date`) или параметр (`$2::date`)
 */
export function bookingCoversDaySql(booking: string, day: string): string {
  return `${day} BETWEEN ${booking}.booking_date
                     AND COALESCE(${booking}.end_date, ${booking}.booking_date)`;
}

/**
 * Готовый подзапрос «сколько человек занято на день `day`».
 *
 * Возвращает `0`, а не NULL, когда броней нет: вызывающие сравнивают число с
 * вместимостью, и NULL в этом сравнении дал бы «мест нет» вместо «все
 * свободны» — отказ там, где всё в порядке.
 *
 * `deleted_at IS NULL` включён здесь ОДИН раз: снятая бронь места не держит,
 * и забыть это условие больше негде.
 */
export function occupiedOnDaySql(opts: {
  /** Алиас `operator_bookings` внутри подзапроса. */
  booking: string;
  /** Выражение дня, считается снаружи подзапроса. */
  day: string;
  /** Выражение id тура, считается снаружи подзапроса. */
  tourId: string;
}): string {
  const { booking: b, day, tourId } = opts;
  return `SELECT COALESCE(SUM(${b}.participants), 0)::int AS taken
            FROM operator_bookings ${b}
           WHERE ${b}.operator_tour_id = ${tourId}
             AND ${b}.booking_status NOT IN ('cancelled', 'rejected')
             AND ${b}.deleted_at IS NULL
             AND ${bookingCoversDaySql(b, day)}`;
}
