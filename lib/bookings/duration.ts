/**
 * Сколько ДНЕЙ занимает тур и какой датой он кончается.
 *
 * Правило одно на обе двери бронирования. Раньше оно жило только за одной:
 * `app/api/bookings/tour` (вошедший турист, оплата картой) считал длительность
 * и писал `end_date`/`duration_days`, а `lib/bookings/reserve.ts` — общий
 * модуль, которым бронируют веб-форма заявки и чат Кузьмича, — не знал о
 * многодневности вовсе и заводил любой тур как однодневный.
 *
 * ── Чем это кончалось ─────────────────────────────────────────────────────
 *
 * `v_tour_daily_occupancy` (миграция 140) разворачивает бронь в дни так:
 *
 *     generate_series(b.booking_date, COALESCE(b.end_date, b.booking_date))
 *
 * То есть `end_date IS NULL` — это не «неизвестно сколько», а «ровно один
 * день». Группа, забронировавшая пятидневный тур через форму, занимала первый
 * день и исчезала из всех остальных. Вид читают пятеро: кабинет оператора,
 * динамическое ценообразование, планер (данные и движок) и гейт оплаченной
 * брони. Все пятеро видели дни 2..N свободными и продавали их снова.
 *
 * Слепота была двусторонней: собственный счёт занятости в `reserve.ts` искал
 * брони по `booking_date = $2`, то есть не видел уже существующую многодневную
 * бронь, накрывающую запрошенную дату своей серединой.
 *
 * ── Почему модуль, а не копия ─────────────────────────────────────────────
 *
 * Потому что копий уже было две и они уже разошлись — об этом вся шапка
 * `reserve.ts`. Правило, записанное дважды, — это два правила.
 *
 * Сторож: `tests/unit/booking-duration.test.ts`.
 */

/** Поля тура, из которых выводится длительность. Имена — как в БД. */
export interface TourDurationSource {
  /** Явное число дней у многодневного тура (`operator_tours.multi_day_count`). */
  multi_day_count: number | null;
  /** Длительность в часах — запасной путь, когда дни не проставлены. */
  duration_hours: number | null;
}

/**
 * Длительность тура в днях. Минимум — 1: тур короче дня всё равно занимает
 * день календаря.
 *
 * Порядок источников намеренный. `multi_day_count` — то, что оператор указал
 * СЛОВАМИ; `duration_hours` — производная, и ею считают только когда первого
 * нет. Часы округляются ВВЕРХ: тур на 30 часов занимает два дня календаря, а
 * не полтора — половины дня в календаре не бывает.
 */
export function tourDurationDays(tour: TourDurationSource): number {
  if (tour.multi_day_count != null && tour.multi_day_count > 1) {
    return tour.multi_day_count;
  }
  if (tour.duration_hours != null && tour.duration_hours >= 24) {
    return Math.ceil(tour.duration_hours / 24);
  }
  return 1;
}

/**
 * Прибавить дни к `YYYY-MM-DD`, считая в UTC.
 *
 * UTC здесь не придирчивость: локальная арифметика дат в зоне с переходом на
 * летнее время даёт сдвиг на сутки дважды в год, и бронь уезжает на день.
 */
export function addDays(dateStr: string, days: number): string {
  const d = new Date(`${dateStr}T00:00:00Z`);
  d.setUTCDate(d.getUTCDate() + days);
  return d.toISOString().slice(0, 10);
}

/**
 * Последний день тура, начатого `startDate`.
 *
 * Граница ВКЛЮЧИТЕЛЬНАЯ: однодневный тур кончается в день старта, а не на
 * следующий. Ровно так её понимает `generate_series` в
 * `v_tour_daily_occupancy` — считать иначе значило бы занимать лишний день.
 */
export function tourEndDate(startDate: string, durationDays: number): string {
  return addDays(startDate, Math.max(1, durationDays) - 1);
}
