/**
 * Право открыть бронь: один ключ, одна проверка, три исхода.
 *
 * ── Что чинится ───────────────────────────────────────────────────────────
 *
 * `GET /api/hub/bookings/[id]` объявлен публичным (гостевая бронь по
 * устройству) и до 08.09 сверял ровно ничего: `WHERE b.id = $1` при
 * BIGSERIAL-номере. Перебор 1, 2, 3 отдавал имя туриста, дату, цену и статус
 * оплаты чужой заявки, а вместе с ними — `pdf_token`, которым PDF-роут
 * защищался ОТ ЭТОГО САМОГО ПЕРЕБОРА. По выданному токену уходил договор с
 * телефоном и почтой.
 *
 * ── Почему проверка живёт здесь, а не в каждом роуте ──────────────────────
 *
 * Роутов у брони гостя два — JSON подтверждения и PDF, — и правило у них
 * обязано быть одно. Две копии одного правила расходятся: это уже случалось
 * со сравнением секрета рассылки и со старшинством линии маршрута. Здесь
 * копий нет по построению: оба роута зовут `verifyBookingAccess`.
 *
 * ── Три исхода (§4.0) ─────────────────────────────────────────────────────
 *
 * `ok`       — ключ предъявлен и совпал;
 * `denied`   — ключа нет или он чужой. Наружу это 404, а не 403: 403 сообщил
 *              бы, что бронь с таким номером существует, и вернул бы
 *              перебору половину его добычи;
 * `unknown`  — спросить не смогли (отказ БД). Не «нет доступа» и не «есть»:
 *              вызывающий отвечает 503 и пишет причину в лог, потому что
 *              «не смог проверить» не равно «проверил и запретил».
 *
 * Сравнение — по постоянному времени: обычное `!==` выходит на первом
 * несовпавшем байте, и ключ подбирается побайтно по времени ответа.
 */

import { pool } from '@/lib/db-pool';
import { timingSafeCompare } from '@/lib/security/timing-safe';

export type BookingAccess =
  | { state: 'ok' }
  | { state: 'denied' }
  | { state: 'unknown'; reason: string };

/** UUID v4 в каноническом виде — форма ключа проверяется до похода в базу. */
const UUID_RE = /^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$/i;

/**
 * Ключ доступа из запроса: `?token=` или заголовок `X-Booking-Token`.
 *
 * Query-параметр здесь допустим и не противоречит правилу «секреты только
 * заголовком»: это не общий секрет платформы, а ключ ОДНОЙ брони, который по
 * замыслу живёт в ссылке — иначе гость не откроет своё подтверждение из
 * письма. Заголовок поддержан для клиентского fetch, где ссылка не нужна.
 */
export function bookingTokenFrom(url: URL, headers: Headers): string {
  return url.searchParams.get('token')
    ?? headers.get('X-Booking-Token')
    ?? '';
}

/**
 * Совпадает ли предъявленный ключ с ключом этой брони.
 *
 * Не сообщает, существует ли бронь: у несуществующего номера и у чужого
 * ключа исход один — `denied`.
 */
export async function verifyBookingAccess(
  bookingId: number,
  token: string,
): Promise<BookingAccess> {
  if (!UUID_RE.test(token)) return { state: 'denied' };

  try {
    const { rows } = await pool.query<{ access_token: string }>(
      `SELECT access_token::text AS access_token FROM operator_bookings WHERE id = $1`,
      [bookingId],
    );
    const expected = rows[0]?.access_token;
    if (!expected) return { state: 'denied' };
    return timingSafeCompare(token.toLowerCase(), expected.toLowerCase())
      ? { state: 'ok' }
      : { state: 'denied' };
  } catch (err) {
    // Отказ не глушится: без этой строки поломка проверки выглядела бы как
    // «ключ не подошёл», и разбирались бы не с базой, а с туристом.
    const code = (err as { code?: string }).code ?? 'нет SQLSTATE';
    console.error(`[booking-access] не смог сверить ключ брони ${bookingId}, SQLSTATE ${code}:`, err);
    return { state: 'unknown', reason: 'проверка доступа недоступна' };
  }
}
