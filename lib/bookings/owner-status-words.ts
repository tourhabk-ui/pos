/**
 * Слова исхода, когда продавец тура ставит брони статус, который у неё уже
 * есть (`changed: false` из lib/bookings/owner-status). Одни для кабинета
 * оператора, раздела «Свои туры» гида и кнопок в мессенджере: повторное
 * нажатие — не новое действие, и человеку нельзя сказать «подтверждено», как
 * будто туристу только что ушло письмо.
 *
 * Модуль без базы и сети — его импортируют и клиентские экраны.
 */

const ALREADY: Readonly<Record<string, string>> = {
  new: 'уже ждёт ответа',
  confirmed: 'уже подтверждена',
  cancelled: 'уже отменена',
  completed: 'уже отмечена: тур прошёл',
  no_show: 'уже отмечена: турист не пришёл',
};

/** «Бронь №7001 уже подтверждена — туристу повторно ничего не отправлено.» */
export function alreadyInStatusText(bookingId: string, status: string): string {
  const word = ALREADY[status] ?? `уже в статусе «${status}»`;
  return `Бронь №${bookingId} ${word} — туристу повторно ничего не отправлено.`;
}
