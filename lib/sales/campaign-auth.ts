/**
 * Кто имеет право запускать рассылку кампании.
 *
 * ── Что было ──────────────────────────────────────────────────────────────
 *
 * Оба роута кампании сверяли заголовок `X-CEO-Secret` с `CRON_SECRET`
 * оператором `!==`. Три беды в одной строке:
 *
 *   1. ОБЩИЙ СЕКРЕТ СВЯЗАЛ НЕСВЯЗАННОЕ. Поворот секрета кронов ломал бы
 *      рассылку, а утечка одного секрета давала бы и запуск кронов, и запуск
 *      кампании по чужим контактам. Ровно то же, что сегодня убрано из соли
 *      публичного MCP, и по той же причине.
 *   2. СРАВНЕНИЕ `!==` ПО ВРЕМЕНИ. Обычное сравнение строк выходит на первом
 *      несовпавшем байте, и по времени ответа секрет подбирается побайтно.
 *      Для запуска рассылки это дорогая мелочь.
 *   3. GET БЫЛ ШПАРГАЛКОЙ: без всякой проверки отвечал, какой нужен заголовок
 *      и что секрет берётся из `CRON_SECRET`. Подсказка тому, кто ищет.
 *
 * ── Три исхода, а не два (§4.0) ───────────────────────────────────────────
 *
 * «Секрет не настроен» — не то же, что «секрет неверен». Первое про нас,
 * второе про вызывающего, и ответы обязаны быть разными: 503 против 401.
 * Иначе владелец, забывший завести переменную, будет искать ошибку у себя в
 * заголовках, а не в панели.
 *
 * Отката на `CRON_SECRET` нет намеренно. Пока `SALES_CAMPAIGN_SECRET` не
 * заведён, рассылка не запускается — и это верное поведение: автоматических
 * вызывающих у неё нет (проверено, зовут только руками), значит ломать
 * нечего, а запускать рассылку по чужим контактам ключом от кронов нельзя.
 */

import { timingSafeCompare } from '@/lib/security/timing-safe';

/** Заголовок, которым приносят секрет. Имя историческое, менять незачем. */
export const CAMPAIGN_SECRET_HEADER = 'X-CEO-Secret';

export type CampaignAuth =
  | { ok: true }
  | { ok: false; status: 401 | 503; error: string };

/**
 * Проверка права запустить кампанию. Ничего не логирует и не отправляет —
 * только судит.
 */
export function verifyCampaignSecret(headers: Headers): CampaignAuth {
  const expected = process.env.SALES_CAMPAIGN_SECRET;
  if (!expected) {
    return {
      ok: false,
      status: 503,
      error:
        'Рассылка не настроена: не задан SALES_CAMPAIGN_SECRET. '
        + 'Это про настройку сервера, а не про ваш запрос.',
    };
  }
  if (!timingSafeCompare(headers.get(CAMPAIGN_SECRET_HEADER), expected)) {
    // Что именно не так — не уточняем: подсказывать подбирающему нечего.
    return { ok: false, status: 401, error: 'Unauthorized' };
  }
  return { ok: true };
}
