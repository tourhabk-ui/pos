/**
 * lib/stay/pay-on-site.ts — как платится жильё (решение владельца 26.09).
 *
 * Гость бронирует, владелец подтверждает, гость платит владельцу при
 * заселении. Платформа денег за проживание не принимает — значит, не
 * предлагает «Оплатить», не выдаёт ссылку на оплату и не возвращает деньги.
 * Онлайн-оплата жилья может появиться позже отдельным шагом.
 *
 * Модуль чистый (без БД и сети): его читают и серверные письма, и экраны.
 */
export const STAY_PAY_ON_SITE = 'Оплата — владельцу при заселении, после подтверждения брони';

/** Подпись способа оплаты по payment_status брони — для гостя и владельца. */
export function stayPaymentLabel(paymentStatus: string): string {
  switch (paymentStatus) {
    case 'pending': return 'оплата на месте';
    case 'paid': return 'оплачено через платформу';
    case 'refunded': return 'возвращено';
    case 'partially_refunded': return 'возвращено частично';
    default: return paymentStatus;
  }
}
