/**
 * Строка «Что меняет план» — только тип, без импортов. Отдельным файлом, чтобы
 * клиентская лента (DeskChangeRows) брала форму строки, не дотягиваясь цепочкой
 * импортов до серверной сводки (сторожа client-no-node-builtins и
 * client-regex-no-lookbehind идут по импортам, типовые тоже).
 */

export type ChangeKind = 'road' | 'volcano' | 'water' | 'snow' | 'weather' | 'bear' | 'park' | 'other';

export interface PlanChange {
  /** Где — часть заголовка до двоеточия или тире; null — заголовок не делится. */
  place: string | null;
  /** Что — остаток заголовка, иначе описание; не пустая строка. */
  what: string;
  kind: ChangeKind;
  /** Род тревоги словом: «дороги», «паводок». */
  kindLabel: string;
  /**
   * Подпись срока по правилу ленты (lib/safety/alert-dates, #2495):
   * «до 5 октября» — срок из источника; «в ленте до 1 января 2027 г.» — ручная
   * запись, её срок ставит человек; «сообщение от 8 октября» — срок жизни
   * записи задали мы; null — срока нет.
   */
  term: string | null;
  /** Откуда строка. Не узнали — так и сказано, не ближайшая правдоподобная лента. */
  origin: string;
  /**
   * Ключ записи для одноразовой подсветки нового (12.11, `alertKey`): исходный
   * заголовок и время публикации. Не показывается — по нему браузер узнаёт,
   * видел ли он эту строку.
   */
  key: string;
}
