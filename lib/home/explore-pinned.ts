/**
 * Лента целиком: сначала места владельца, затем места каталога без тех, что
 * уже стоят впереди. `pickRest` раскладывает остаток (у главной —
 * varietyByType с пределом ленты); повтор убирается ДО раскладки, чтобы
 * остаток не стал короче предела из-за совпадения.
 */
export function exploreWithPinned<T extends { id: string }>(
  pinned: readonly T[],
  pool: readonly T[],
  pickRest: (rest: T[]) => T[],
): T[] {
  const taken = new Set(pinned.map((p) => p.id));
  return [...pinned, ...pickRest(pool.filter((p) => !taken.has(p.id)))];
}
