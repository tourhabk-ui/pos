/**
 * Счёт предупреждений на главной.
 *
 * До вечера 26.09 здесь жили и строки раскрытой плитки «Радар» (сводка:
 * предупреждения, вулканы). Владелец: «по кнопке радар должен открываться наш
 * радар» и «сводка и безопасность дублируется?» — сводка повторяла блок
 * «Перед выходом» и пилюлю шапки. Плитка стала дверью на /safety#radar, а
 * строки сводки сняты вместе с ней: функция без потребителя — провод в никуда.
 */

/**
 * Сколько предупреждений главная берёт из ленты. Лента — выборка с потолком,
 * поэтому число на потолке значит «столько или больше», а не «ровно столько».
 */
export const HOME_ALERTS_LIMIT = 5;

/** «5» при потолке — «5 и больше»: иначе потолок выборки выдавался бы за счёт. */
export function alertsCountLabel(n: number): string {
  return n >= HOME_ALERTS_LIMIT ? `${HOME_ALERTS_LIMIT} и больше` : String(n);
}
