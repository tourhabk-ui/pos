/**
 * Прямой запрет туристам — шаблоны классификатора и тот же признак в SQL.
 *
 * Шаблоны живут здесь, а не в seismic-parser, чтобы ими пользовались и
 * классификатор (уровень 2 для запрета, seismic-parser), и правила цвета
 * (статус места — safety-ingest, вердикт маршрута — collect-signals), не
 * таща за собой парсер с базой. Источник один — разойтись нечему.
 *
 * Зачем SQL-признак (03.10, поправка к #2195): региональное предупреждение
 * уровня 2 стало жёлтым. Прямой запрет выхода туристам тоже уровень 2, но
 * понижать его нельзя — это ошибка в опасную сторону. Отдельной пометки в
 * external_alerts нет, поэтому признак считается по тексту ТЕМИ ЖЕ
 * шаблонами (PostgreSQL понимает их опережающие и ретроспективные проверки).
 * Разница одна и осознанная: здесь текст целиком, а не окно в две фразы —
 * ошибиться можно только в сторону красного. Шаблоны в долларовых кавычках:
 * обратная косая черта доходит до сервера как есть.
 *
 * Сторож: tests/unit/tourist-ban-sql.test.ts.
 */
export const BAN_AUDIENCE = /тургрупп|турист|охотник|маломерн|рыбак|восходител|сплав|рафт/;
// Основа, а не словарная форма: «воздержаться» и «воздержитесь» — одно
// повеление. «Не рекомендуется выход на маршруты» — самая частая формула МЧС.
export const BAN_VERB = /воздерж|не рекоменду|не выходить|не выезжать|не выход[аи]|не совершать|не планировать|отказаться от|не подниматься|не приближ|запрещ|не выпускать|не выходите|(?<!не\s)исключить(?![а-яё])/;

/** Текст алерта (ea.title + ea.description) прямо запрещает выход туристам. */
export const TOURIST_BAN_SQL = `(
  lower(COALESCE(ea.title, '') || ' ' || COALESCE(ea.description, '')) ~ $ban_a$${BAN_AUDIENCE.source}$ban_a$
  AND lower(COALESCE(ea.title, '') || ' ' || COALESCE(ea.description, '')) ~ $ban_v$${BAN_VERB.source}$ban_v$
)`;
