/**
 * lib/services/safety/push-copy.ts
 *
 * Текст пуша по типу тревоги.
 *
 * Раньше это была лестница из трёх `?:` внутри крона: цунами, пожар, дорога —
 * и ВСЁ ОСТАЛЬНОЕ уезжало заголовком «Землетрясение M? — Камчатка» с телом
 * «Если у берега — немедленно вверх ≥30 м». То есть предупреждение о вулкане,
 * паводке или метели приходило человеку как землетрясение с командой бежать
 * от воды.
 *
 * Это не опечатка в копирайте. Инструкция в пуше — это действие, которое
 * человек совершит, не открывая приложение. Ошибиться в ней хуже, чем
 * промолчать: в метель «уходите вверх от воды» уводит с маршрута в склон.
 *
 * Отсюда правило, ради которого модуль вообще отдельный: **у неизвестного
 * типа НЕТ инструкции**. Заголовок нейтральный, тело — заголовок самой
 * тревоги, и ни слова о том, что делать. Придуманное действие опаснее
 * отсутствующего, а список типов будет расти (сегодня добавился `weather`) —
 * и каждый новый обязан попадать в безопасную ветку по умолчанию, а не
 * наследовать чужую команду.
 *
 * Чистая функция: тестируется без сети и без БД.
 */

export interface PushCopy {
  title: string;
  body: string;
}

/** Обрезка описания до размера, который переживёт уведомление на телефоне. */
function short(text: string | null | undefined, limit = 100): string {
  const t = (text ?? '').trim();
  return t.length > limit ? t.slice(0, limit) : t;
}

/**
 * Заголовок и тело пуша.
 *
 * `magnitude` нужна только землетрясениям; для остальных типов игнорируется.
 */
export function pushCopy(params: {
  alertType: string | null;
  title: string;
  description?: string | null;
  magnitude?: number | null;
}): PushCopy {
  const { alertType, title } = params;
  const type = (alertType ?? '').toLowerCase();
  const detail = short(params.description) || title;

  switch (type) {
    case 'tsunami_warning':
      return {
        title: 'УГРОЗА ЦУНАМИ — Камчатка',
        body: `${detail}. Уходите вверх ≥30 м от воды.`,
      };

    case 'earthquake':
      return {
        title: `Землетрясение M${
          params.magnitude != null && Number.isFinite(params.magnitude)
            ? params.magnitude.toFixed(1)
            : '?'
        } — Камчатка`,
        body: `${title}. Если у берега — немедленно вверх ≥30 м.`,
      };

    case 'volcanic_eruption':
    case 'ash_cloud':
      return {
        title: 'Вулканическая опасность — Камчатка',
        body: `${title}. Не приближайтесь к вулкану, сверьте маршрут.`,
      };

    // Погода — та самая ветка, которой не было. Команда одна и та же и для
    // циклона с ливнем, и для метели: не выходить и переждать. Разделять по
    // явлению нельзя — в пуше нет места на разбор, а «переждать» верно для
    // обоих.
    case 'weather':
      return {
        title: 'Опасная погода — Камчатка',
        body: `${title}. Не выходите на маршрут, переждите в укрытии.`,
      };

    case 'flood':
      return {
        title: 'Паводок — Камчатка',
        body: `${title}. Не пересекайте реки вброд.`,
      };

    case 'fire_danger':
      return {
        title: 'Природный пожар — Камчатка',
        body: `${title}. Сверьте маршрут — возможны перекрытия и задымление.`,
      };

    case 'road_closure':
      return {
        title: 'Ограничение проезда — Камчатка',
        body: `${title}. Проверьте подъезд до выезда.`,
      };

    case 'avalanche':
      return {
        title: 'Лавинная опасность — Камчатка',
        body: `${title}. Не выходите на склоны и под них.`,
      };

    case 'landslide':
      return {
        title: 'Сход грунта — Камчатка',
        body: `${title}. Обойдите склон, не вставайте лагерем под ним.`,
      };

    default:
      // Ни слова об инструкции. Мы не знаем, что это за опасность, и
      // придумывать действие человеку в поле не имеем права.
      return {
        title: 'Предупреждение МЧС — Камчатка',
        body: title,
      };
  }
}

/**
 * Типы, для которых у нас есть своя инструкция.
 *
 * Нужен сторожу: классификатор умеет выдавать типы, и каждый новый обязан
 * либо попасть сюда, либо осознанно уйти в нейтральную ветку. Молчаливое
 * наследование чужой команды — то, что этот модуль и лечит.
 */
export const PUSH_TYPES_WITH_INSTRUCTION = [
  'tsunami_warning', 'earthquake', 'volcanic_eruption', 'ash_cloud',
  'weather', 'flood', 'fire_danger', 'road_closure', 'avalanche', 'landslide',
] as const;
