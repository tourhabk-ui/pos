/**
 * lib/services/safety/seismic-zones.ts
 *
 * К каким туристическим зонам относится эпицентр — и к каким НЕ относится.
 *
 * ── Что было ───────────────────────────────────────────────────────────────
 *
 * В `ingestUsgs` зона выводилась делением координат пополам:
 *
 *   zones = lat >= 55.5 ? ['northern'] : lng >= 161 ? ['eastern'] : ['avachinsky']
 *
 * Расстояние не учитывалось вовсе. Событие в 450 км от ближайшего маршрута
 * получало зону так же уверенно, как событие в двадцати. Пустого исхода не
 * существовало: любая точка внутри запроса обязательно становилась чьей-то.
 *
 * Цена не теоретическая. `affected_zones` кормит `location_real_time_status`,
 * а тот красит карточки маршрутов. 11.08 одна протухшая запись держала 137
 * маршрутов из 421 в статусе «Не сегодня» — сцепка сильная, и ложная привязка
 * доезжает до экрана туриста.
 *
 * ── Что делает эта функция ─────────────────────────────────────────────────
 *
 * Отвечает на вопрос, который прежний код не задавал: а близко ли вообще? Если
 * эпицентр дальше MAX_RELEVANT_KM от ВСЕХ известных туристических районов —
 * зон нет. Событие при этом никуда не пропадает: оно сохраняется, видно в
 * сейсмоленте, просто не красит маршруты, до которых ему сотни километров.
 *
 * ── Чего она НЕ делает, и почему ───────────────────────────────────────────
 *
 * Не улучшает само деление на три зоны. У тревожных зон (avachinsky / western /
 * eastern / northern) координат в проекте нет — есть только у погодных зон,
 * а это другой словарь из шести конкретных мест. Придумать якорь для «западной
 * зоны» протяжённостью шестьсот километров значило бы выдать догадку за
 * геодезию, причём в системе безопасности. Поэтому близкие события делятся
 * по-старому, а правка снимает ровно то, что доказуемо неверно: привязку
 * далёкого события к зоне, до которой оно не достаёт.
 */

import { ZONES } from '@/lib/services/safety/zone-weather';

/**
 * Радиус, в пределах которого землетрясение имеет отношение к району.
 *
 * 250 км — порядок, на котором толчок M5–6 ещё может отозваться на склоне
 * (камнепад, подвижка снега). Это оценка сверху, а не сейсмологический
 * норматив: точного порога «где перестаёт быть опасно» не существует, он
 * зависит от магнитуды, глубины и грунта. Взято с запасом в сторону
 * ОСТОРОЖНОСТИ — лучше привязать лишнее близкое, чем отбросить настоящее.
 */
export const MAX_RELEVANT_KM = 250;

/** Расстояние по большому кругу, км. */
export function distanceKm(lat1: number, lng1: number, lat2: number, lng2: number): number {
  const R = 6371;
  const toRad = (d: number) => (d * Math.PI) / 180;
  const dLat = toRad(lat2 - lat1);
  const dLng = toRad(lng2 - lng1);
  const a =
    Math.sin(dLat / 2) ** 2 +
    Math.cos(toRad(lat1)) * Math.cos(toRad(lat2)) * Math.sin(dLng / 2) ** 2;
  return 2 * R * Math.asin(Math.sqrt(a));
}

/** Насколько эпицентр далёк от ближайшего туристического района, км. */
export function kmToNearestTouristArea(lat: number, lng: number): number {
  let best = Infinity;
  for (const z of Object.values(ZONES)) {
    const d = distanceKm(lat, lng, z.lat, z.lon);
    if (d < best) best = d;
  }
  return best;
}

/**
 * Зоны для эпицентра. Пустой массив — законный ответ: «событие есть, но к
 * туристическим зонам оно отношения не имеет».
 */
export function zonesForEpicenter(lat: number, lng: number): string[] {
  if (kmToNearestTouristArea(lat, lng) > MAX_RELEVANT_KM) return [];
  // Деление близких событий оставлено прежним — см. шапку модуля.
  if (lat >= 55.5) return ['northern'];
  if (lng >= 161) return ['eastern'];
  return ['avachinsky'];
}
