import { ROAD_ALERT_RADIUS_KM } from '@/lib/safety/alert-anchor';
import { CORRIDOR_VOLCANO_KM } from '@/lib/routes/collect-signals';
import { shakingIntensitySql, SEISMIC_PLACE_MIN_INTENSITY } from '@/lib/services/safety/shaking';

/**
 * Когда у события и у точки есть координаты И тип события таков, что
 * расстояние вообще что-то значит.
 *
 * Условие написано ОДИН раз и подставляется в обе ветки: в первой редакции
 * оно было продублировано с отрицанием, и любая правка радиусных типов
 * требовала помнить про второй экземпляр. Точка, не попавшая ни в одну
 * ветку, теряет очистку `active_alerts` и остаётся со вчерашним значением —
 * то есть цена расхождения здесь не косметическая.
 */
/**
 * Расстояние между двумя точками в километрах — ОДНО выражение на модуль.
 *
 * Формула стояла здесь дважды: против координат самого события и против
 * координат вулкана. Разные аргументы, один и тот же haversine — и ровно тот
 * риск, из-за которого сторож `fire-alert-radius` держит правило «формула
 * объявлена один раз, а не трижды» (#897): вторая копия расходится с первой
 * молча, и половина алертов начинает мериться иначе.
 *
 * Имена колонок подставляются в текст запроса, поэтому принимаются ТОЛЬКО
 * из кода этого модуля — ни одного значения из запроса или из базы здесь быть
 * не может (§4: никакой конкатенации внешних данных в SQL).
 */
export function distanceKmSql(aLat: string, aLng: string, bLat: string, bLng: string): string {
  return `2 * 6371 * asin(sqrt(
          power(sin(radians((${aLat} - ${bLat}) / 2)), 2)
          + cos(radians(${bLat})) * cos(radians(${aLat}))
            * power(sin(radians((${aLng} - ${bLng}) / 2)), 2)
        ))`;
}

export const GEO_SCOPED_SQL = `
  ea.alert_type IN ('fire_danger', 'road_closure')
  AND ea.lat IS NOT NULL AND ea.lng IS NOT NULL
  AND ark.lat IS NOT NULL AND ark.lng IS NOT NULL
`;

/**
 * Рода событий, у которых МЕСТО известно точно, — и потому зона им не замена.
 *
 * `road_closure` и `fire_danger` привязываются координатой (первый — по имени
 * объекта в заголовке, второй — термоточкой FIRMS), `volcanic_eruption` —
 * вулканом. Если привязать не удалось, такое событие НЕ красит места вовсе:
 * «не установлено» ≠ «везде» (§4.0, решение владельца 27.09). Оно остаётся в
 * общекраевой ленте (`/safety`, `safety_status`), где и читается как «где-то
 * в крае».
 *
 * До 27.09 неприбитый дорожный алерт падал в зональную ветку: «Вилючинский
 * перевал — проезд по пропускам» висел на Курильском озере, в Быстринском
 * парке и на Безымянном — за 250-500 км. Замер владельца, дайджест 27.09.
 *
 * Остальные рода (землетрясение, паводок, погода, лавина, оползень, медведь)
 * продолжают судиться зоной, даже когда координата есть. Сузить их — значит
 * назвать расстояние, на котором событие перестаёт иметь значение, а такого
 * числа у нас нет: у землетрясения оно зависит от магнитуды и глубины.
 * Придуманный радиус здесь опаснее широкой зоны — он ГАСИТ настоящий сигнал
 * (§4.0: не знаем — не гадаем).
 */
export const PLACE_SCOPED_TYPES = ['road_closure', 'fire_danger', 'volcanic_eruption', 'park_closure'] as const;
export const PLACE_SCOPED_SQL = `ea.alert_type IN (${PLACE_SCOPED_TYPES.map((t) => `'${t}'`).join(', ')})`;

/**
 * Вулканическое событие накрывает то, что связано с ВУЛКАНОМ, а не зону.
 *
 * Три честных способа быть «при этом вулкане», и ни одного придуманного:
 *   1. место и есть этот вулкан;
 *   2. место привязано к нему поимённо — `place_volcano_links`, миграция 1029,
 *      решение владельца 26.09 («Скитур на Мутновский» зелёный при жёлтом
 *      Мутновском). Тот же список, по которому уже поднимается статус места
 *      по шкалам вулкана;
 *   3. место ближе `CORRIDOR_VOLCANO_KM` к вулкану — число не новое, оно уже
 *      решено для вулканов на коридоре маршрута (lib/routes/collect-signals).
 *
 * Зона в этой ветке не участвует: северная зона — это Шивелуч, Ключевской,
 * Безымянный и Толбачик разом, и именно так пепел одного получал красный
 * статус у всех.
 */
export const VOLCANO_SCOPED_SQL = `
  ea.alert_type = 'volcanic_eruption'
  AND ea.volcano_ark_id IS NOT NULL
  AND (
    ark.id = ea.volcano_ark_id
    OR EXISTS (
      SELECT 1
        FROM places vp
        JOIN place_volcano_links pvl ON pvl.volcano_place_id = vp.id::text
        JOIN places lp ON lp.id::text = pvl.place_id
       WHERE vp.ark_id = ea.volcano_ark_id
         AND lp.ark_id = ark.id
    )
    OR EXISTS (
      SELECT 1
        FROM places vp
       WHERE vp.ark_id = ea.volcano_ark_id
         AND vp.lat IS NOT NULL AND vp.lng IS NOT NULL
         AND ark.lat IS NOT NULL AND ark.lng IS NOT NULL
         AND ${distanceKmSql('ark.lat', 'ark.lng', 'vp.lat', 'vp.lng')} <= ${CORRIDOR_VOLCANO_KM}
    )
  )
`;

/**
 * Закрытие маршрутов парка накрывает то, что ЛЕЖИТ В ПАРКЕ (#2133).
 *
 * Парк называет тревога (`affected_parks`, слаги справочника `parks`), а что
 * в парке — справочник маршрутов: `kamchatka_routes.park_name` против
 * `parks.search_term`, тем же ILIKE, что связывает парк с маршрутами на его
 * странице (миграция 712). Честных способов быть «в парке» три:
 *   1. это маршрут, чей `park_name` называет парк;
 *   2. это место, через которое ИДЁТ такой маршрут (связь рода не `nearby`:
 *      «рядом, загляните» в парке не лежит, §4.1);
 *   3. имя места называет парк («Природный парк Налычево»).
 *
 * Зона здесь не участвует: «avachinsky» — это и Налычево, и город. Парк
 * тревогой не назван — она не красит никого (род в PLACE_SCOPED_TYPES).
 * `parks.is_active` не смотрится: закрытый парк закрыт и без своей страницы.
 */
export const PARK_SCOPED_SQL = `
  ea.alert_type = 'park_closure'
  AND ea.affected_parks IS NOT NULL
  AND EXISTS (
    SELECT 1
      FROM parks pk
     WHERE pk.slug = ANY(ea.affected_parks)
       AND (
         ark.title ILIKE '%' || pk.search_term || '%'
         OR EXISTS (
           SELECT 1 FROM kamchatka_routes kr
            WHERE COALESCE(kr.ark_id, kr.id) = ark.id
              AND kr.park_name ILIKE '%' || pk.search_term || '%'
         )
         OR EXISTS (
           SELECT 1
             FROM places pl
             JOIN route_waypoints rw ON rw.place_id = pl.id
             JOIN kamchatka_routes kr ON kr.id = rw.route_id
            WHERE pl.ark_id = ark.id
              AND COALESCE(to_jsonb(rw)->>'link_kind', 'unknown') <> 'nearby'
              AND kr.park_name ILIKE '%' || pk.search_term || '%'
         )
       )
  )
`;

/**
 * Землетрясение накрывает место, где ТРЯХНЁТ, а не всю зону (03.10, #2195).
 *
 * Карточка Никольской сопки в Петропавловске: «Сегодня сюда — нет» из-за ML
 * 6.2 в океане за 182 км — по зоне «avachinsky», в которую попадает всё в 250
 * км от туристических районов. Теперь, когда у события есть координата и
 * магнитуда, место накрывается только при расчётном сотрясении не ниже
 * SEISMIC_PLACE_MIN_INTENSITY (lib/services/safety/shaking.ts): сила тряски
 * растёт с магнитудой сама, придуманного радиуса здесь нет.
 *
 * Без координаты или магнитуды землетрясение судится зоной, как раньше:
 * «не смогли измерить» не равно «далеко» (§4.0).
 */
export const QUAKE_SCOPED_SQL = `
  ea.alert_type = 'earthquake'
  AND ea.lat IS NOT NULL AND ea.lng IS NOT NULL AND ea.magnitude IS NOT NULL
  AND ark.lat IS NOT NULL AND ark.lng IS NOT NULL
`;

/**
 * Радиус по роду события, км.
 *
 * Пожар — 50: шире 10-километрового кластера FIRMS, уже зоны (инженерная
 * оценка #861, не замер).
 *
 * Дорожное ограничение — 30: решение владельца 15.09 («30 км от вилючинского
 * вулкана достаточно») после карточки «Раздолья», где предупреждение о
 * Вилючинском перевале висело за шестьдесят километров. Число хранится в
 * `ROAD_ALERT_RADIUS_KM` и подставляется отсюда, чтобы у радиуса не завелось
 * второго значения в SQL.
 */
export const ALERT_MATCH_SQL = `
  (
    ${GEO_SCOPED_SQL}
    AND ${distanceKmSql('ark.lat', 'ark.lng', 'ea.lat', 'ea.lng')} <= CASE ea.alert_type
                WHEN 'road_closure' THEN ${ROAD_ALERT_RADIUS_KM}
                ELSE 50
              END
  )
  OR (
    ${QUAKE_SCOPED_SQL}
    AND ${shakingIntensitySql('ea.magnitude', distanceKmSql('ark.lat', 'ark.lng', 'ea.lat', 'ea.lng'))} >= ${SEISMIC_PLACE_MIN_INTENSITY}
  )
  OR (
    ${VOLCANO_SCOPED_SQL}
  )
  OR (
    ${PARK_SCOPED_SQL}
  )
  OR (
    NOT (${GEO_SCOPED_SQL})
    -- Рода из PLACE_SCOPED_TYPES в зональную ветку НЕ падают: у них место
    -- известно точно, а если привязать не удалось — они не красят никого
    -- (решение владельца 27.09, см. шапку PLACE_SCOPED_SQL). До этого
    -- неприбитый дорожный алерт шумел на всю зону.
    AND NOT (${PLACE_SCOPED_SQL})
    -- Землетрясение с координатой и магнитудой судится силой сотрясения
    -- выше (QUAKE_SCOPED_SQL), в зональную ветку не падает (#2195).
    AND NOT (${QUAKE_SCOPED_SQL})
    -- Пустые/NULL зоны совпадают НИ С КЕМ (17.09). Раньше здесь стояло
    -- «IS NULL OR = '{}' OR …» — пустота читалась как «весь край», и любое
    -- предупреждение, у которого зона не распозналась, красило каждое место
    -- (паводок в Соболевском округе → красный на сопках в центре города).
    -- Та же ошибка сводила на нет лечение USGS в seismic-zones.ts: далёкое
    -- землетрясение сохранялось с [] и по этому предикату красило всех.
    -- «Не установлено» ≠ «везде» (§4.0). Событие с пустыми зонами остаётся в
    -- общекраевой ленте (/safety, safety_status); явно общекраевые тексты
    -- получают все четыре зоны в mchs_zones по слову источника.
    -- Зеркальный предикат — lib/routes/collect-signals.ts; сторож
    -- tests/unit/alert-zone-unknown.test.ts держит их вместе.
    AND ark.zone = ANY(ea.affected_zones)
  )
`;

/**
 * Алерт пришёл к месту ТОЛЬКО по зоне края — не по координате, не по силе
 * сотрясения, не по вулкану или парку (решение владельца 03.10, вариант 2,
 * #2195). Тот же предикат, что открывает зональную ветку ALERT_MATCH_SQL,
 * без самого совпадения зоны: ветки взаимоисключающие по типу, и совпавший
 * алерт с этим признаком мог прийти только через зону.
 *
 * Зачем: экстренное предупреждение МЧС о дожде по зоне красило КРАСНЫМ все
 * горы этой зоны разом — владелец 03.10 на Горе Замок: «статус опасности не
 * снят». Когда красное всё, настоящий красный (Шивелуч под оранжевым KVERT)
 * не выделяется. Зональный алерт уровня 2 теперь даёт жёлтый, уровня 3
 * (цунами) — по-прежнему красный. Текст алерта в карточке остаётся.
 */
export const ALERT_ZONAL_ONLY_SQL = `(
  NOT (${GEO_SCOPED_SQL})
  AND NOT (${PLACE_SCOPED_SQL})
  AND NOT (${QUAKE_SCOPED_SQL})
)`;


