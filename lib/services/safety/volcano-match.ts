/**
 * Сопоставление вулкана KVERT с точкой каталога.
 *
 * ── Что было сломано (02.09) ───────────────────────────────────────────────
 *
 * Владелец: «почему на радаре нет вулканов?». Слой на радаре есть, крон KVERT
 * жив и отвечает 200, но его последний прогон: `fetched: 68, matched: 8`.
 * KLYUCHEVSKOY — среди несопоставленных, при пепловом выбросе до 6 км.
 *
 * Причина не в KVERT и не в алиасах: `klyuchevskoy → «Ключевской»` в таблице
 * есть и срабатывает. Падал следующий шаг — поиск точки. Он искал имя,
 * РАВНОЕ или НАЧИНАЮЩЕЕСЯ с русского имени, а в каталоге записано иначе:
 *
 *   KVERT «Ключевской»  →  places «Вулкан Ключевская сопка»
 *   KVERT «Горелый»     →  places «Вулкан Горелый»
 *   KVERT «Кизимен»     →  places «Вулкан Кизимен (Щапинская сопка)»
 *   KVERT «Кроноцкий»   →  places «Вулкан Кроноцкий (Кроноцкая сопка)»
 *
 * Приставка «Вулкан » ломала префиксное совпадение почти у всех; у
 * Ключевского вдобавок другая форма слова — «Ключевской» против
 * «Ключевская».
 *
 * Статус при этом писался в `volcano_status` — но без `place_ark_id`. А
 * радар соединяет статус с местом именно через него. Данные о работающем
 * вулкане лежали в базе и не имели способа попасть на экран.
 *
 * ── Почему нельзя просто «искать похожее» ──────────────────────────────────
 *
 * Привязать статус к ЧУЖОМУ вулкану хуже, чем не привязать: человек увидит
 * оранжевый код не над тем конусом и построит по нему решение. Поэтому
 * здесь нет нечёткого поиска. Сравниваются ОСНОВЫ — детерминированно, — а
 * неоднозначность считается отказом, а не поводом угадать (§4.0).
 *
 * «Толбачик» тому пример: в каталоге три записи — Толбачик, Плоский
 * Толбачик, Острый Толбачик. Основа у всех трёх разная («толбачик»,
 * «плоск толбачик», «остр толбачик»), поэтому KVERT «Plosky Tolbachik»
 * при точном алиасе попадёт в Плоский и ни в кого больше. А если алиас
 * даст просто «Толбачик» — совпадёт ровно одна запись, тоже верно.
 *
 * ── Опечатка в каталоге отказом и остаётся ─────────────────────────────────
 *
 * Крашенинников записан у нас как «Вулкан Крашенникова» — без «ин». Основы
 * «крашенников» и «крашенинников» не совпадают, и сопоставление честно
 * отказывает. Это ПРАВИЛЬНО: смягчать сравнение до «похоже» значит открыть
 * дорогу привязке к соседу. Чинится опечатка в данных, а не в правиле.
 */

/** Слова-родовые, которые в имени ничего не различают. */
const GENERIC = ['вулкан', 'вулканическая', 'сопка', 'влк', 'гора', 'группа', 'кальдера'];

/**
 * Окончания прилагательных, которыми одно и то же имя пишут по-разному:
 * «Ключевской» / «Ключевская», «Кроноцкий» / «Кроноцкая».
 *
 * Порядок важен: длинные раньше коротких, иначе «ская» срежется как «ая» и
 * оставит «ключевс» вместо «ключевск».
 */
const ADJ_ENDINGS = [
  'ского', 'ская', 'ский', 'ской', 'скую', 'ские',
  'ого', 'его', 'ому', 'ая', 'яя', 'ий', 'ый', 'ой', 'ое', 'ее', 'ые', 'ие', 'ым', 'ом',
  /**
   * Родительный падеж фамилии: «Вулкан Крашенинникова» — это вулкан ЧЬЙ,
   * а KVERT называет его «Крашенинников». Без этой пары они не сходятся.
   *
   * Стоит последним и с тем же порогом длины: срезается только у длинных
   * слов, и обе стороны проходят через одну функцию, поэтому симметрия
   * сохраняется. Риск склеить двух разных вулканов держит отдельный сторож
   * — «разные вулканы не схлопываются в одну основу».
   */
  'а', 'я',
];

/** Одно слово → основа. Короткие слова не трогаем: там резать нечего. */
function stemWord(w: string): string {
  if (w.length <= 4) return w;
  for (const end of ADJ_ENDINGS) {
    if (w.length - end.length >= 4 && w.endsWith(end)) {
      return w.slice(0, w.length - end.length);
    }
  }
  return w;
}

/**
 * Имя вулкана → основа для сравнения.
 *
 * Детерминированно и в обе стороны одинаково: и имя из KVERT, и имя из
 * каталога проходят через эту же функцию. Двух разных нормализаций быть не
 * должно — это ровно тот класс, из-за которого §12 писался.
 *
 * Скобки срезаются целиком: «Вулкан Кизимен (Щапинская сопка)» — это одно
 * место с уточнением, а не два имени.
 */
export function volcanoStem(name: string): string {
  const words = name
    .toLowerCase()
    .replace(/\(.*?\)/g, ' ')
    .replace(/[«»"'.,]/g, ' ')
    .replace(/ё/g, 'е')
    .split(/\s+/)
    .map((w) => w.trim())
    .filter((w) => w.length > 0 && !GENERIC.includes(w))
    .map(stemWord)
    .filter((w) => w.length > 0);
  return words.join(' ');
}

export interface VolcanoPlace {
  arkId: string;
  name: string;
}

/** Основа → все точки с такой основой. Несколько — повод отказаться, не гадать. */
export type VolcanoIndex = Map<string, VolcanoPlace[]>;

export function buildVolcanoIndex(places: VolcanoPlace[]): VolcanoIndex {
  const idx: VolcanoIndex = new Map();
  for (const p of places) {
    const stem = volcanoStem(p.name);
    if (!stem) continue;
    const list = idx.get(stem);
    if (list) list.push(p); else idx.set(stem, [p]);
  }
  return idx;
}

export type VolcanoMatch =
  | { kind: 'matched'; arkId: string; placeName: string }
  /** Основа совпала с несколькими точками: какая из них — неизвестно. */
  | { kind: 'ambiguous'; candidates: string[] }
  /** Такой точки в каталоге нет. Не ошибка синка — пробел каталога. */
  | { kind: 'no_place' };

/**
 * Найти точку по русскому имени вулкана.
 *
 * Три исхода, а не два: «нашли», «в каталоге нет» и «кандидатов несколько».
 * Последнее НЕ равно первым двум: пробел каталога чинится заведением места,
 * неоднозначность — уточнением имени, и путать их значит чинить не то.
 */
export function matchVolcanoPlace(index: VolcanoIndex, nameRu: string): VolcanoMatch {
  const stem = volcanoStem(nameRu);
  if (!stem) return { kind: 'no_place' };
  const found = index.get(stem);
  if (!found || found.length === 0) return { kind: 'no_place' };
  if (found.length > 1) {
    return { kind: 'ambiguous', candidates: found.map((p) => p.name) };
  }
  return { kind: 'matched', arkId: found[0].arkId, placeName: found[0].name };
}
