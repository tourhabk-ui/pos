/**
 * Когда прежний звонок заглушает новый: правило «один звонок на тип, пока
 * прежний действует» (миграция 957, dispatchPushAlerts) — для закрытия парка
 * с поправкой на парки (ревью 06.11).
 *
 * Тип один, а парки разные. Сезонное закрытие держится 21 сутки
 * (park-closure-terms), и «Ключевской закрыт на зимний сезон», о котором
 * позвонили неделю назад, глушило бы звонок о том, что закрыли Налычево.
 * Новое закрытие глушится только тогда, когда разосланное уже накрывает все
 * его парки: тогда второй звонок правда не несёт нового.
 */

/** Условие на строку прежнего звонка; `param` — номер параметра с парками нового алерта. */
export function sameParksSql(param: string): string {
  return `(${param}::text[] IS NULL OR affected_parks @> ${param}::text[])`;
}

/** Парки нового алерта для условия, или null — правило парков к роду не относится. */
export function sameParksParam(alert: { alert_type: string; affected_parks: string[] | null }): string[] | null {
  return alert.alert_type === 'park_closure' ? (alert.affected_parks ?? []) : null;
}
