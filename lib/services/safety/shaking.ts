/**
 * lib/services/safety/shaking.ts — насколько тряхнёт в точке. Одно правило
 * на платформу: им судят и риск зоны (danger-analyst), и то, какие места
 * накрывает землетрясение (alert-place-scope).
 *
 * ── Повод (03.10) ──────────────────────────────────────────────────────────
 *
 * Вопрос владельца 02.10 «как считает 100?» — рой в океане за 170-200 км
 * поставил Авачинской зоне «Немедленная эвакуацию». Наутро — карточка
 * Никольской сопки посреди Петропавловска: «Сегодня сюда — нет» из-за того же
 * ML 6.2 за 182 км (#2195). Причина одна: землетрясение судилось ЗОНОЙ, а
 * Авачинская зона — это и вулканы, и город, и всё в 250 км от них.
 *
 * Прежде зону здесь оставляли сознательно: «сузить — значит назвать
 * расстояние, на котором событие перестаёт иметь значение, а такого числа нет:
 * у землетрясения оно зависит от магнитуды и глубины». Это верно про РАДИУС.
 * Здесь не радиус, а сила сотрясения, которая сама растёт с магнитудой.
 */

/** Ближе этого расстояние не берётся: формула на нуле уходит в бесконечность. */
export const MIN_INTENSITY_KM = 10;

/**
 * С какого расчётного балла землетрясение касается места: MSK-64 6 — испуг,
 * лёгкие повреждения, на склонах возможны камнепады. Ниже — ощутимо, но
 * решения «идти ли сюда сегодня» не меняет. Порог в сторону осторожности:
 * глубина очага не учитывается, балл выходит выше настоящего.
 */
export const SEISMIC_PLACE_MIN_INTENSITY = 6;

/**
 * Балл сотрясения (MSK-64) на расстоянии `km` от эпицентра: уравнение
 * макросейсмического поля Шебалина в общем виде, I = 1.5M − 3.5·lg R + 3.0.
 * Коэффициенты общие, не калиброванные под Камчатку, а R берётся
 * эпицентральным, то есть меньше настоящего — балл выходит ВЫШЕ: ошибка в
 * сторону осторожности. Это оценка для сравнения, не прогноз тряски.
 */
export function shakingIntensity(magnitude: number, km: number): number {
  const r = Math.max(km, MIN_INTENSITY_KM);
  return 1.5 * magnitude - 3.5 * Math.log10(r) + 3.0;
}

/**
 * То же выражение для SQL. Аргументы — выражения из кода вызывающего модуля
 * (имена колонок), не данные: значения из запроса сюда не попадают (§4).
 * `log(x)` у PostgreSQL для double precision — десятичный.
 */
export function shakingIntensitySql(magnitudeExpr: string, distanceKmExpr: string): string {
  return `(1.5 * (${magnitudeExpr})::float8 - 3.5 * log(GREATEST((${distanceKmExpr})::float8, ${MIN_INTENSITY_KM})) + 3.0)`;
}
