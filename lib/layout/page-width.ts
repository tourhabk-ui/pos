/**
 * Ширина страницы на компьютере — одно правило на три рода (владелец 14.11:
 * «почему в десктопной версии много страниц не по формату», на «делать?» —
 * «do it»).
 *
 * ── Что было ────────────────────────────────────────────────────────────
 *
 * Перепись 14.11: у публичных страниц десять разных ширин — от 512 до 1280
 * пикселей, и каждая страница писала свой `max-w-*` и свои поля. Китайская
 * витрина /zh со списком из 77 туров стояла колонкой в 768 px посреди
 * монитора в 1920, список трансферов — в 672 при карточке перевозчика в
 * 1152, а /fish не имела ни ширины, ни полей: сетка видов шла от края до
 * края окна. Общая ширина была только у главной и каталога
 * (HOME_CONTAINER, 25.09) — и до остальных не дошла.
 *
 * ── Правило ─────────────────────────────────────────────────────────────
 *
 *   showcase — витрины и списки (главная, каталог, /zh, трансферы, рыбы):
 *              1280, как у главной;
 *   card     — карточка одной вещи (тур, место, маршрут, перевозчик): 1152;
 *   reading  — чтение и формы (статья, FAQ, оферта, регистрация выхода):
 *              768. Узко намеренно: строка на весь монитор не читается.
 *
 * Внутри витрины длинный текст сам держится в ширине чтения
 * (`READING_MEASURE`), а списки раскладываются сеткой.
 *
 * Сторож: tests/unit/page-width.test.tsx — рендер страниц, переведённых на
 * правило, и запрет вернуть им собственную ширину.
 */

export type PageWidth = 'showcase' | 'card' | 'reading';

/** Максимальная ширина рода — класс Tailwind. */
export const PAGE_MAX: Record<PageWidth, string> = {
  showcase: 'max-w-[1280px]',
  card: 'max-w-6xl',
  reading: 'max-w-3xl',
};

/** Поля по бокам — одни на все роды. */
export const PAGE_GUTTER = 'px-4 sm:px-6 xl:px-8';

/** Контейнер страницы: по центру, во всю доступную ширину до потолка рода. */
export function pageContainer(width: PageWidth): string {
  return `mx-auto w-full ${PAGE_MAX[width]} ${PAGE_GUTTER}`;
}

/** Длинный текст внутри витрины или карточки — в ширине чтения. */
export const READING_MEASURE = 'max-w-3xl';
