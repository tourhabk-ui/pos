/**
 * lib/safety/dated-warning.ts
 *
 * Предупреждение, которое само называет свой день, живёт до конца этого дня.
 *
 * ── Что случилось ──────────────────────────────────────────────────────────
 *
 * 03.10 владелец: «на Камчатке выглянуло солнце, но запрет не снят». На ленте
 * верхним стояло «Экстренное предупреждение на 3 октября 2026 г. (сильный
 * дождь)», классификатор отнёс его к паводку (в тексте был подъём уровня
 * воды), а паводку положено 120 часов. То есть предупреждение, которое МЧС
 * выпустило НА ОДИН ДЕНЬ, мы держали бы пять суток, до 7–8 октября.
 *
 * Срок считался от даты публикации поста, а дату из заголовка не читал никто.
 * Читала её только ветка закрытия парков («до 1 октября», park-closure.ts).
 *
 * ── Чего здесь нет намеренно ───────────────────────────────────────────────
 *
 * Наш прогноз погоды предупреждение НЕ снимает. Солнце в 16 часов не значит,
 * что ливня не будет вечером, а прогноз wttr.in/open-meteo по точке слабее
 * предупреждения Гидрометцентра по краю. Снимает автор — МЧС — и он назвал
 * срок сам: этот день. Подъём воды на реках после дождя МЧС публикует
 * отдельными постами без даты, и у них остаётся свой паводковый срок.
 *
 * Дата не найдена, уже прошла или дальше недели — `null`: «не знаю», и срок
 * остаётся прежним (§4.0). Ошибиться в сторону «дольше» безопаснее.
 */

const MONTHS: Record<string, number> = {
  января: 0, февраля: 1, марта: 2, апреля: 3, мая: 4, июня: 5,
  июля: 6, августа: 7, сентября: 8, октября: 9, ноября: 10, декабря: 11,
};

const PART = '(?:(?:ночь|день|утро|вечер|сутки)\\s+)?';
const MONTH = '(января|февраля|марта|апреля|мая|июня|июля|августа|сентября|октября|ноября|декабря)';

/**
 * «на 3 октября», «на ночь 3 октября», «на 3-4 октября», «на ночь 3 и день
 * 4 октября». Берётся ПОСЛЕДНИЙ названный день.
 */
const DATED_RE = new RegExp(
  `(?:^|[^а-яё])на\\s+${PART}(\\d{1,2})(?:\\s*(?:[-–—]|и)\\s*${PART}(\\d{1,2}))?\\s+${MONTH}`,
);

/** Названная дата дальше недели — скорее не про срок предупреждения. */
export const DATED_WARNING_MAX_HOURS = 7 * 24;

/**
 * Конец названного дня по Камчатке (UTC+12, без летнего времени) — 12:00 UTC
 * того же числа. `null` — даты нет, она до публикации или дальше недели.
 */
export function datedWarningEnd(title: string, publishedAt: Date): Date | null {
  if (Number.isNaN(publishedAt.getTime())) return null;
  const m = title.toLowerCase().match(DATED_RE);
  if (!m) return null;
  const day = Number(m[2] ?? m[1]);
  const month = MONTHS[m[3]];
  if (day < 1 || day > 31 || month === undefined) return null;

  let year = publishedAt.getUTCFullYear();
  let end = Date.UTC(year, month, day, 12, 0, 0);
  // «На 1 января», опубликовано 31 декабря — следующий год.
  if (end < publishedAt.getTime() - 30 * 86_400_000) {
    year += 1;
    end = Date.UTC(year, month, day, 12, 0, 0);
  }
  const hours = (end - publishedAt.getTime()) / 3_600_000;
  if (hours <= 0 || hours > DATED_WARNING_MAX_HOURS) return null;
  return new Date(end);
}

/** То же в часах от публикации (для `expires_hours` классификатора). */
export function datedWarningHours(title: string, publishedAt: Date): number | null {
  const end = datedWarningEnd(title, publishedAt);
  if (!end) return null;
  return Math.ceil((end.getTime() - publishedAt.getTime()) / 3_600_000);
}

/** Категории, к которым правило применяется: погодное окно МЧС. */
export const DATED_WARNING_TYPES = ['weather', 'flood'] as const;
