/**
 * lib/safety/alert-anchor.ts
 *
 * Куда именно относится дорожное предупреждение.
 *
 * ── Что было сломано ──────────────────────────────────────────────────────
 *
 * Дорожные ограничения приходят из ленты МЧС без координат, и привязывались
 * они ЗОНОЙ. Зона Камчатки — это сотни километров. Владелец увидел итог на
 * карточке «Раздолья Камчатки» 15.09: «Активное предупреждение: Вилючинский
 * перевал — проезд по пропускам», при том что перевал за шестьдесят
 * километров и к купанию в Раздолье отношения не имеет.
 *
 * Это ровно тот случай, который уже разбирали на пожарах (issue #861):
 * одиночная термоточка зажигала карточки ВСЕХ маршрутов зоны, включая
 * лежащие в 300 км. Там лечение нашлось координатами события — у FIRMS они
 * есть. Здесь их нет, и взять их можно только из НАШЕГО каталога: имя
 * объекта в тексте предупреждения.
 *
 * ── Радиус — решение владельца 15.09 ──────────────────────────────────────
 *
 * «30 км от вилючинского вулкана достаточно». Тридцать километров — это не
 * замер и не вывод из данных, а назначенная человеком граница: дальше неё
 * ограничение проезда перестаёт быть фактом О ЭТОМ МЕСТЕ.
 *
 * Предупреждение при этом НЕ исчезает из платформы: строка в
 * `external_alerts` не трогается, лента `/safety` показывает её по-прежнему.
 * Меняется только `location_real_time_status.active_alerts` — то есть ответ
 * на вопрос «что происходит ЗДЕСЬ», а не «что происходит в крае».
 *
 * ── Почему привязка ищется, а не назначается списком ──────────────────────
 *
 * Соблазн был завести реестр «текст → точка» и вписать туда Вилючинский
 * перевал. Но реестр из одной строки — это не механизм, а разовая заплатка
 * под один экран: следующее ограничение (Мутновка, Малки, Ганалы) снова
 * повесилось бы на всю зону, и никто бы этого не заметил.
 *
 * ── Почему НЕ «похожее имя», а точная основа ──────────────────────────────
 *
 * Правило §4.1 от 23.08 оплачено делом: из 24 мест с сильным совпадением
 * имён настоящей ошибкой координаты оказались ТРИ, остальные — тёзки.
 * Поэтому здесь нет нечёткого поиска. Сравниваются ОСНОВЫ (общая
 * нормализация `nameStem`), и три исхода вместо двух:
 *
 *   matched   — основа совпала ровно с одной точкой каталога;
 *   ambiguous — совпала с несколькими: какая имелась в виду, неизвестно;
 *   none      — такой точки у нас нет.
 *
 * Неоднозначность и отсутствие — НЕ привязка. Тогда предупреждение остаётся
 * зонным, как было: широко, но честно. Привязать к чужой точке хуже, чем не
 * привязать, — человек примет решение по координате, которую мы угадали.
 */

import { nameStem } from '@/lib/services/safety/volcano-match';

/**
 * Радиус дорожного ограничения вокруг точки привязки, км.
 *
 * Решение владельца 15.09 («30 км от вилючинского вулкана достаточно»), а не
 * вывод из данных. Меняется таким же решением, а не подгонкой под случай.
 */
export const ROAD_ALERT_RADIUS_KM = 30;

/**
 * Родовые слова ландшафта: в имени они ничего не различают.
 *
 * Список свой, не общий с вулканами, и это не дубль. «Перевал» обязан
 * срезаться здесь (чтобы «Вилючинский перевал» сошёлся с «Вулкан
 * Вилючинский») и обязан НЕ срезаться у вулканов — иначе авиационный код
 * KVERT уедет с конуса на перевал.
 */
const LANDMARK_GENERIC = [
  'вулкан', 'вулканическая', 'сопка', 'влк', 'гора', 'группа', 'кальдера',
  'перевал', 'река', 'р', 'озеро', 'оз', 'бухта', 'мыс', 'источники',
  'источник', 'водопад', 'ручей', 'долина', 'посёлок', 'поселок', 'село',
  'город', 'дорога', 'трасса', 'участок', 'км',
];

/** Точка каталога, к которой можно привязать предупреждение. */
export interface AnchorPlace {
  id: string;
  name: string;
  lat: number;
  lng: number;
}

/** Основа имени → точки с такой основой. Несколько — повод отказаться. */
export type AnchorIndex = Map<string, AnchorPlace[]>;

export function landmarkStem(name: string): string {
  return nameStem(name, LANDMARK_GENERIC);
}

export function buildAnchorIndex(places: readonly AnchorPlace[]): AnchorIndex {
  const idx: AnchorIndex = new Map();
  for (const p of places) {
    const stem = landmarkStem(p.name);
    // Односложные и пустые основы отбрасываются: основа из одной буквы или
    // из общего слова совпадёт со случайным текстом и привяжет что угодно.
    if (stem.length < 4) continue;
    const list = idx.get(stem);
    if (list) list.push(p); else idx.set(stem, [p]);
  }
  return idx;
}

export type AnchorMatch =
  | { kind: 'matched'; place: AnchorPlace }
  /** Основа совпала с несколькими точками — какая имелась в виду, неизвестно. */
  | { kind: 'ambiguous'; candidates: string[] }
  /** Такой точки в каталоге нет. Пробел каталога, а не ошибка привязки. */
  | { kind: 'none' };

/**
 * Найти точку, о которой говорит предупреждение.
 *
 * Ищется по ЗАГОЛОВКУ, а не по всему тексту. Описание дорожной сводки МЧС —
 * это абзацы на 400-600 символов, где перечислены попутные посёлки, объезды
 * и телефоны; любое из тех имён дало бы привязку, и привязка получилась бы
 * не к месту ограничения, а к первому попавшемуся упоминанию.
 *
 * Скользящее окно по словам: имя объекта в заголовке стоит не с начала
 * («Закрыт проезд через Вилючинский перевал»), и длинные окна пробуются
 * раньше коротких — «Малкинские горячие источники» должны выиграть у
 * «Малкинские».
 */
export function matchAlertAnchor(index: AnchorIndex, title: string): AnchorMatch {
  const words = title
    .toLowerCase()
    .replace(/[«»"'.,;:()]/g, ' ')
    .split(/\s+/)
    .filter(w => w.length > 0);

  const MAX_WINDOW = 3;
  let ambiguous: string[] | null = null;

  for (let size = MAX_WINDOW; size >= 1; size--) {
    for (let i = 0; i + size <= words.length; i++) {
      const stem = landmarkStem(words.slice(i, i + size).join(' '));
      if (stem.length < 4) continue;
      const found = index.get(stem);
      if (!found || found.length === 0) continue;
      if (found.length === 1) return { kind: 'matched', place: found[0]! };
      // Неоднозначность запоминается, но поиск продолжается: более короткое
      // окно может дать однозначное совпадение. Отдаётся она только если
      // однозначного не нашлось вовсе — иначе «несколько кандидатов» съело
      // бы верный ответ.
      if (!ambiguous) ambiguous = found.map(p => p.name);
    }
  }

  return ambiguous ? { kind: 'ambiguous', candidates: ambiguous } : { kind: 'none' };
}
