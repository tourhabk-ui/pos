/**
 * Вулканы под видеонаблюдением КФ ФИЦ ЕГС РАН (нормализованные ключи).
 * Подтверждены 01.08.2026. Ключ — основа названия без «вулкан/сопка/влк».
 */
const COVERED = new Set<string>([
  'шивелуч', 'ключевск', 'безымянн', 'кизимен', 'толбачик',
  'корякск', 'авачинск', 'жупановск', 'горел', 'мутновск', 'эбеко',
]);

/**
 * Нормализация имени точки к ключу вулкана: нижний регистр, снятие служебных
 * слов и пунктуации. «Авачинская Сопка», «влк. Авачинский», «Авачинский
 * вулкан» → «авачинск». Матч по префиксу ключа (падежи: -ий/-ая/-ой).
 */
export function hasVolcanoCamera(name: string | null | undefined): boolean {
  if (!name) return false;
  const n = name
    .toLowerCase()
    .replace(/вулкан|сопка|влк\.?|гора/g, ' ')
    .replace(/[^а-яё]/g, ' ')
    .trim();
  if (!n) return false;
  for (const key of COVERED) {
    if (n.includes(key)) return true;
  }
  return false;
}
