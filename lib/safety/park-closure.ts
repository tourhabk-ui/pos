/** Решение о посещении: приостановлено, закрыто, запрещено. */
const CLOSURE_RE = new RegExp(
  [
    '(?:приостановлен|закрыт|запрещ[её]н|прекращ[её]н)[а-яё]*\\s+(?:[а-яё]+\\s+)?(?:посещени|доступ|выход[а-яё]*\\s+на\\s+маршрут|маршрут)',
    // Граница слова — явная по кириллице: `\b` в JS знает только латиницу, и
    // «маршруты закрыты на зимний сезон» (сводка 21.10, парк «Ключевской»)
    // с `закрыт[ыао]?\b` не совпадало никогда — строка уходила дорожной веткой.
    '(?:посещени[ея]|маршрут[а-яё]*|доступ)[\\s\\S]{0,60}?(?:приостановлен|временно\\s+закрыт|закрыт[ыао]?(?![а-яё])|запрещ[её]н)',
    'временно\\s+закрыл[аи]?\\s+(?:туристическ[а-яё]*\\s+)?маршрут',
  ].join('|'),
);

/**
 * Не закрытие ВСЕГО парка.
 *
 * Открытие («возобновлено посещение»). И частичное закрытие: сводка Минтура
 * 11.09 — «В парке „Налычево“ летние маршруты открыты… закрыты автомобильный
 * маршрут „Радыгино — Центральный“ и транзитный пеший маршрут». Первая
 * редакция правила приняла её за закрытие парка, и красным стало бы всё
 * Налычево при открытых летних маршрутах. Закрыт конкретный маршрут —
 * это его закрытие, а не парка: такой текст остаётся прежним веткам
 * (паводок, дороги) со своей зоной.
 */
const REOPEN_RE = new RegExp(
  [
    'возобновл[её]н[а-яё]*\\s+(?:посещени|работ)',
    'вновь\\s+открыт',
    'снят[ыо]?\\s+ограничени',
    'открыт[ыо]?\\s+для\\s+посещени',
    // «летние маршруты открыты», «маршруты парка открыты». Граница слова
    // явная: «маршруты до открытия сезона закрыты» — не открытие (ревью 06.11).
    'маршрут[а-яё]*\\s+(?:[а-яё]+\\s+)?открыт[ыоа]?(?![а-яё])',
  ].join('|'),
);
/**
 * Открытие в будущем — не открытие (06.11). «Закрыты на период межсезонья,
 * зимние маршруты будут открыты с 1 декабря» — это объявление закрытия с
 * датой конца, а не отмена закрытия. Ветка `маршрут… открыт` ловила «будут
 * открыты», и такой текст уходил мимо парка в дорожную ветку — то есть
 * закрытие всех маршрутов парка не красило ни одного его места.
 *
 * Вычёркивается сам оборот будущего, а не всё предложение: «посещение вновь
 * открыто, а маршрут на Корякский вулкан откроется позже» — открытие сейчас,
 * и оговорка о другом маршруте его не отменяет (ревью 06.11).
 */
const FUTURE_OPENING_SRC =
  '(?:будут|будет|планиру[а-яё]*|намечен[а-яё]*)\\s+(?:[а-яё]+\\s+)?(?:открыт|возобновл)[а-яё]*|откро(?:ют|ет|ется|ются)(?![а-яё])';
const FUTURE_OPENING_G = new RegExp(FUTURE_OPENING_SRC, 'g');

/** Предложения текста: граница — точка, «!», «?», «;» и перевод строки. */
function sentencesOf(lower: string): string[] {
  return lower.split(/[.!?;\n]+/);
}

/** Есть ли в тексте открытие, случившееся сейчас (будущее время вычеркнуто). */
function isReopeningNow(lower: string): boolean {
  return sentencesOf(lower).some((s) => REOPEN_RE.test(s.replace(FUTURE_OPENING_G, ' ')));
}

/**
 * Закрыт конкретный маршрут: «закрыты автомобильный маршрут „…“». Фраза «на
 * всех территориях природных парков» этим правилом не отменяется: в сводке
 * 02.11 кавычки после «маршрутов» — имя источника («Закрытие маршрутов
 * «Вулканы Камчатки» сообщают…»), а не маршрута, и правило сочло закрытие
 * всех парков частичным — 05.11 Налычево стояло ЗЕЛЁНЫМ при закрытии в ленте (#2980).
 */
const ONE_ROUTE_RE = /закрыт[а-яё]*\s+(?:[а-яё]+\s+){0,2}маршрут[а-яё]*\s+[«"„]/;

/**
 * Природные парки края (не заповедники): «на всех территориях природных
 * парков» (сводка 02.11) закрывает каждый из них. Кроноцкий и Командорский —
 * заповедники, Вачкажец — памятник природы: такая фраза их не называет.
 */
export const NATURAL_PARK_SLUGS: readonly string[] = [
  'nalychevo', 'yuzhno-kamchatsky', 'bystrinskiy', 'klyuchevskoy', 'vilyuchinsky',
];
const ALL_NATURAL_PARKS_RE = /(?:всех|все|всем)\s+(?:территори[а-яё]*\s+|маршрут[а-яё]*\s+)?природн(?:ых|ые|ым)\s+парк/;

export interface ParkClosure {
  /** Слаги парков, названных в тексте; не пусто. */
  parks: string[];
}

/** Закрытие парка в тексте или null. Текст — уже в нижнем регистре или любом. */
export function detectParkClosure(text: string): ParkClosure | null {
  const lower = text.toLowerCase();
  if (!/парк|заповедник/.test(lower)) return null;
  if (isReopeningNow(lower)) return null;
  const allNaturalParks = ALL_NATURAL_PARKS_RE.test(lower);
  if (!allNaturalParks && ONE_ROUTE_RE.test(lower)) return null;
  if (!CLOSURE_RE.test(lower)) return null;
  const parks = PARK_NAME_PATTERNS.filter((p) => p.re.test(lower)).map((p) => p.slug);
  if (allNaturalParks) {
    for (const slug of NATURAL_PARK_SLUGS) if (!parks.includes(slug)) parks.push(slug);
  }
  return parks.length > 0 ? { parks } : null;
}

