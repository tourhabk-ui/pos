// ── Сводка об ОТКРЫТИИ парка (решение владельца 06.11, «1 да») ──────────────
//
// Закрытие на межсезонье без даты держится до сводки об открытии. Значит,
// открытие нужно распознавать — и строже, чем закрытие. Цена ошибок
// неравная: ложное открытие гасит настоящее закрытие, и место становится
// ЗЕЛЁНЫМ; пропущенное лишь держит его красным до предела, а после — «статус
// не известен». Поэтому распознаватель не разбирает сложное предложение, а
// отказывается от него:
//  - судится ПРЕДЛОЖЕНИЕ, и парк назван в нём же (или «все природные парки»);
//    парк из соседнего предложения или из заголовка поста не засчитывается;
//  - предложение с глаголом закрытия (CLOSURE_RE) открытием не считается:
//    смешанное решается в пользу закрытия;
//  - любое слово из NOT_OPENING_RE снимает предложение ЦЕЛИКОМ: исключение
//    («кроме», «за исключением»), отрицание где угодно, условие («только
//    после», «если»), расписание и реклама («летом», «круглый год», месяц без
//    числа, «по 30 сентября»), будущее и прошлое, служебный объект
//    («возобновлено движение автобусов», «работа визит-центра», «приём
//    заявок»), опасный или промысловый сезон («пожароопасный», «охоты»).
//    Ревью 06.11: прежняя редакция вычёркивала отрицаемый оборот и оставляла
//    парк из него («в «Налычево» маршруты не открыты» открывало Налычево);
//  - «только» при двух и больше парках — тоже отказ: «из всех парков открыт
//    только …» назвал бы открытыми все пять;
//  - «с 1 декабря открыты» — открытие с даты: сейчас только если день уже
//    наступил по Камчатке; дня публикации нет — не открытие.
//
// Известный пропуск, записанный, а не скрытый (tests/unit/park-closure.test.ts):
// сезонный пост сети парков «Зимние маршруты открылись на территориях Сети
// природных парков» (t.me/visitkamchatka41/3971, 23.12.2025) называет парки
// только в шапках блоков, и правило «парк в том же предложении» его не берёт.
// «Сеть природных парков» за все пять не считается: в блоках того же поста
// бывает «в парке X маршруты пока не открыты».

/**
 * Определения перед подлежащим: «летние», «все», «туристические», «для
 * посещения». Не любое слово: «Открыта регистрация групп на маршруты» —
 * открыта регистрация, а не маршруты.
 */
const ADJ = '(?:для\\s+посещения\\s+|для\\s+туристов\\s+)?(?:(?:все|[а-яё-]+(?:ые|ие|ый|ий|ой|ая|яя|ое|ее))\\s+){0,3}';
/** Дополнение после сказуемого: до шести слов. */
const GAP = '(?:\\s+[^\\s]+){0,6}?\\s+(?:вновь\\s+|снова\\s+|также\\s+|уже\\s+)?';
/** Сезон, начало которого — открытие для туриста: не охоты, не дождей, не пожароопасный. */
const SEASON_ADJ = '(?:туристическ|зимн|летн|снегоходн|лыжн|горнолыжн|пешеходн|треккингов)[а-яё]*\\s+(?:[а-яё]+\\s+)?сезон';

/**
 * Оборот открытия сейчас — настоящее или прошедшее время, сказуемое
 * согласовано с подлежащим: «маршруты … открыты», а не «регистрация на
 * маршруты … открыта». Один маршрут («открыт маршрут „…“») — не открытие
 * парка: так открывают по одному, когда остальное закрыто.
 */
const OPEN_NOW_RE = new RegExp(
  [
    // «маршруты парка «Налычево» открыты», «летние маршруты также открыты»,
    // «зимние маршруты в парке «Налычево» открылись», «все природные парки открыты».
    `(?:маршруты|тропы|парки)${GAP}(?:открыты|доступны|открылись)(?![а-яё])`,
    `маршруты${GAP}возобновлены(?![а-яё])`,
    `посещени[ея]${GAP}(?:открыто|доступно|возобновлено|разрешено)(?![а-яё])`,
    `территори[яи]${GAP}(?:открыта|доступна|открыты|доступны)(?![а-яё])`,
    `${SEASON_ADJ}${GAP}(?:открыт|начался|стартовал)(?![а-яё])`,
    // Сказуемое впереди: «Открыты летние маршруты природного парка
    // «Быстринский»», «Открылись зимние маршруты …», «Доступны маршруты …».
    `(?:^|[^а-яё])(?:вновь\\s+|снова\\s+)?(?:открыты|доступны|открылись)\\s+${ADJ}(?:маршруты|тропы|парки)(?![а-яё])`,
    `(?:^|[^а-яё])(?:вновь\\s+|снова\\s+)?(?:открыто|доступно|возобновлено|разрешено)\\s+${ADJ}посещени`,
    // Причастие — только при посещении или маршрутах: «возобновлено движение
    // автобусов» и «возобновлён приём заявок» — не открытие парка.
    'возобновл[её]н[оыа]?\\s+(?:[а-яё]+\\s+)?(?:посещени|маршрут)',
    // Парк подлежащим: «Природный парк «Вилючинский» открыт!», «…открылся для
    // посещения», «Сейчас доступен только «Вилючинский» природный парк».
    'парк\\s+[«"„][^»"“]{2,40}[»"“]\\s+(?:вновь\\s+|снова\\s+)?(?:открыт|доступен|открылся)(?![а-яё])',
    '(?:^|[^а-яё])(?:открыт|доступен|открылся)\\s+(?:только\\s+)?(?:[«"„][^»"“]{2,40}[»"“]\\s+)?(?:природн|национальн)[а-яё]*\\s+парк(?![а-яё])',
    // «Сеть парков открывает туристические маршруты», «вновь открываем для вас маршруты».
    `открыва(?:ет|ем|ют)\\s+(?:для\\s+вас\\s+)?${ADJ}(?:маршрут|троп|сезон|посещени)`,
    'снят[ыо]?\\s+(?:все\\s+)?ограничени[яй]\\s+(?:на\\s+)?посещени',
    // «начинается снегоходный сезон», «начался зимний туристический сезон».
    `(?:начина(?:ет|ют)ся|начал(?:ся|ось|ись)|стартовал|открыл(?:ся|ась|ось|ись))\\s+${SEASON_ADJ}`,
  ].join('|'),
);

/**
 * Слова, при которых предложение открытием НЕ считается — целиком, без
 * попытки разобрать, что именно открыто. Граница слова — явная по кириллице:
 * `\b` в JS знает только латиницу.
 */
const NOT_OPENING_RE = new RegExp(
  [
    // Исключение и неполнота: «кроме «Налычево»», «за исключением», «лишь частично».
    '(?:^|[^а-яё])(?:кроме|помимо|исключая|исключени[а-яё]*|лишь|частичн[а-яё]*|некотор[а-яё]*|отдельн[а-яё]*)(?![а-яё])',
    // Отрицание где угодно: «в «Налычево» маршруты не открыты».
    '(?:^|[^а-яё])(?:не|нет|ни|нельзя)(?![а-яё])',
    // Условие и порядок: «только после установления снежного покрова», «если».
    '(?:^|[^а-яё])только\\s+(?:после|при|для|с|со|по|в\\s+сопровождени|организованн|в\\s+составе)',
    '(?:^|[^а-яё])после\\s+(?:установлени|схода|того|окончани|завершени|открыти|сняти|получени|согласовани|регистрац)',
    '(?:^|[^а-яё])(?:при\\s+условии|при\\s+наличии|в\\s+случае|если|когда|как\\s+только|по\\s+мере)(?![а-яё])',
    // Расписание и реклама: «обычно», «круглый год», «летом», «в зимний период».
    '(?:^|[^а-яё])(?:обычно|как\\s+правило|традиционно|ежегодно|каждый\\s+год|круглый\\s+год|круглогодичн[а-яё]*|всегда|летом|зимой|весной|осенью)(?![а-яё])',
    '(?:^|[^а-яё])в\\s+(?:летн|зимн|осенн|весенн)[а-яё]*\\s+(?:сезон|период|месяц)',
    // Будущее, ожидание, возможность и прошлое: «будут открыты», «скоро»,
    // «могут быть открыты», «были открыты», «в прошлом сезоне».
    FUTURE_OPENING_SRC,
    '(?:^|[^а-яё])(?:будут|будет|станут|станет|скоро|вскоре|завтра|послезавтра|ожида[а-яё]*|ждём|ждем|могут|может|должн[а-яё]*|был[аио]?|были|ранее|раньше|прошл[а-яё]*)(?![а-яё])',
    // Служебный объект открыт, а не парк: визит-центр, КПП, дорога, автобус,
    // приём заявок, регистрация, кордон, стройка.
    '(?:^|[^а-яё])(?:визит-?\\s?центр|офис|кпп|касс|музе|кордон|приют|домик|парковк|стоянк|туалет|автобус|рейс|движени|автодорог|трасс|проезд|перевал|переправ|мост|строительств|ремонт|работ|заяв|регистрац|запис|бронир|продаж|при[её]м|пропуск|разрешени|экскурси)[а-яё]*',
    '(?:^|[^а-яё])дорог(?:а|и|е|у|ой|ам|ах|ами)?(?![а-яё])',
    // Опасный или промысловый сезон: «начался пожароопасный сезон», «сезон охоты».
    '(?:пожар|паводк|лавин|циклон|шторм|нерест|клещ)',
    '(?:^|[^а-яё])(?:охот|дожд|рыбал|рыболов|ураган|непогод)[а-яё]*',
    // Дата, которую не с чем сверить: «с 01.12», «в 2026 году».
    '\\d{1,2}[./]\\d{1,2}',
    '(?:^|[^0-9])20\\d\\d(?![0-9])',
    // Конец открытия, а не начало: «открыты по 30 сентября».
    `(?:^|[^а-яё])по\\s+\\d{1,2}\\s+(?:${MONTH_ALT})`,
  ].join('|'),
);

/** Следующая строка начинается исключением: «кроме», «за исключением», «но». */
const EXCEPTION_NEXT_RE = /^(?:кроме|за\s+исключением|исключая|помимо|но|однако|а\s+также\s+закрыт)(?![а-яё])/;

/** «только» — словом. */
const ONLY_RE = /(?:^|[^а-яё])только(?![а-яё])/;

/** Название месяца любым падежом. */
const MONTH_WORD_G = /(?:^|[^а-яё])(январ|феврал|март|апрел|ма[йяе]|июн|июл|август|сентябр|октябр|ноябр|декабр)[а-яё]*/g;

const DATE_IN_SENTENCE_G = new RegExp(`(\\d{1,2})\\s+(${MONTH_ALT})`, 'g');

/** День по Камчатке (UTC+12, без перехода на летнее время) — полночь, мс UTC. */
function kamchatkaDay(ms: number): number {
  const local = new Date(ms + 12 * 3_600_000);
  return Date.UTC(local.getUTCFullYear(), local.getUTCMonth(), local.getUTCDate());
}

/**
 * Месяц без числа — расписание, а не сегодняшнее состояние: «открыты с
 * декабря по апрель», «в ноябре». Месяц с числом («с 1 декабря») судит
 * `openingNotNow`.
 */
function monthWithoutDay(sentence: string): boolean {
  for (const m of sentence.matchAll(MONTH_WORD_G)) {
    const stemAt = (m.index ?? 0) + m[0].length - m[0].replace(/^[^а-яё]/, '').length;
    if (!/\d{1,2}\s+$/.test(sentence.slice(Math.max(0, stemAt - 4), stemAt))) return true;
  }
  return false;
}

/**
 * Открытие с датой — сейчас ли оно. «С 1 декабря открыты» — только если этот
 * день по Камчатке уже наступил; «открыты до 1 ноября» — нет (за ним
 * объявлено закрытие, и сводка о нём придёт отдельно); дня публикации нет —
 * дату не с чем сравнить, и такое открытие не засчитывается.
 */
function openingNotNow(sentence: string, publishedAt: Date | undefined): boolean {
  const pub = publishedAt?.getTime();
  for (const m of sentence.matchAll(DATE_IN_SENTENCE_G)) {
    const before = sentence.slice(Math.max(0, (m.index ?? 0) - 4), m.index ?? 0);
    if (/до\s+$/.test(before)) return true;
    if (pub === undefined || Number.isNaN(pub)) return true;
    const pubDay = kamchatkaDay(pub);
    const year = new Date(pubDay).getUTCFullYear();
    let day = Date.UTC(year, MONTHS[m[2]], Number(m[1]));
    // «с 10 января» в декабре — следующий год.
    if (day < pubDay - 183 * 86_400_000) day = Date.UTC(year + 1, MONTHS[m[2]], Number(m[1]));
    if (day > pubDay) return true;
  }
  return false;
}

/** Парки, названные в куске текста (нижний регистр); «все природные парки» — пять. */
function parksNamedIn(lower: string): string[] {
  const parks = PARK_NAME_PATTERNS.filter((p) => p.re.test(lower)).map((p) => p.slug);
  if (ALL_NATURAL_PARKS_RE.test(lower)) {
    for (const slug of NATURAL_PARK_SLUGS) if (!parks.includes(slug)) parks.push(slug);
  }
  return parks;
}

export interface ParkReopening {
  /** Слаги парков, открытых сейчас; не пусто. */
  parks: string[];
}

/**
 * Открытие парка в тексте или null. `publishedAt` нужен оборотам «с 1 декабря
 * открыты»: без него такое открытие не засчитывается.
 */
export function detectParkReopening(text: string, publishedAt?: Date): ParkReopening | null {
  const lower = text.toLowerCase();
  if (parksNamedIn(lower).length === 0) return null;
  const opened: string[] = [];
  // Граница предложения остаётся в его конце: вопрос открытием не бывает.
  // Точка между цифрами («с 01.12») — не граница: иначе дата распалась бы на
  // два куска, и сторож дат её бы не увидел.
  const chunks = lower.split(/(?<=[!?;\n])|(?<=\.)(?!\d)|(?<=[^\d]\.)/);
  for (let i = 0; i < chunks.length; i++) {
    const sentence = chunks[i].trim();
    if (!sentence || /\?$/.test(sentence)) continue;
    // Исключение строкой ниже: «открыты все маршруты» / «кроме:» / список
    // (страница КГБУ 25.06.2026) — предложение то же, перенос строки его не
    // разрывает.
    const next = chunks.slice(i + 1).find((c) => c.trim() !== '')?.trim() ?? '';
    if (EXCEPTION_NEXT_RE.test(next) || /:$/.test(sentence.replace(/[.!;\s]+$/, ''))) continue;
    if (CLOSURE_RE.test(sentence)) continue;
    const parks = parksNamedIn(sentence);
    if (parks.length === 0) continue;
    if (!OPEN_NOW_RE.test(sentence)) continue;
    if (NOT_OPENING_RE.test(sentence)) continue;
    if (parks.length > 1 && ONLY_RE.test(sentence)) continue;
    if (monthWithoutDay(sentence)) continue;
    if (openingNotNow(sentence, publishedAt)) continue;
    for (const slug of parks) if (!opened.includes(slug)) opened.push(slug);
  }
  return opened.length > 0 ? { parks: opened } : null;
}

export { PARK_CLOSURE_DEFAULT_HOURS, PARK_CLOSURE_MAX_HOURS, PARK_CLOSURE_HOLD_HOURS };

/**
 * Обороты закрытия без даты конца. Судятся в том же предложении, что и
 * глагол закрытия и сам парк: «из-за циклона приостановлено посещение
 * парка… Напоминаем, что в зимний период выход на маршруты без регистрации
 * запрещён» — оперативное закрытие с правилом посещения, а не сезонное
 * (ревью 06.11). Во втором предложении есть и «запрещён», и «зимний
 * период», но парка нет — это правило, а не решение о парке.
 */
const INDEFINITE_RE = new RegExp(
  [
    'межсезон',
    '(?:на|в)\\s+(?:период\\s+)?(?:зимн|летн|осенн|весенн)[а-яё-]*\\s+(?:сезон|период)',
    'до\\s+(?:открыти|начал)[а-яё]*\\s+(?:[а-яё]+\\s+){0,2}сезон',
    'до\\s+установлени[а-яё]*\\s+(?:[а-яё]+\\s+)?снежн[а-яё]*\\s+покров',
    'до\\s+особого\\s+распоряжени',
    'до\\s+(?:дальнейш|отдельн)[а-яё]*\\s+(?:уведомлени|распоряжени|решени)',
  ].join('|'),
);

/** Закрытие без даты конца: оборот стоит в предложении с глаголом закрытия и парком. */
export function isIndefiniteClosure(text: string): boolean {
  return sentencesOf(text.toLowerCase())
    .some((s) => /парк|заповедник/.test(s) && CLOSURE_RE.test(s) && INDEFINITE_RE.test(s));
}

/** Полдень UTC названного дня = конец этого дня по Камчатке (UTC+12). */
function kamchatkaDayEndUtc(year: number, month: number, day: number): number {
  return Date.UTC(year, month, day, 12, 0, 0);
}

/** Дальше полугода дата, перенесённая на следующий год, — прошедшая. */
const ROLLED_FUTURE_MAX_HOURS = 183 * 24;

interface NamedEnd {
  /** Конец закрытия, мс UTC. */
  end: number;
  /** Дата перенесена на следующий год («до 5 января» в декабре). */
  rolled: boolean;
}

function endOf(day: number, month: number, shift: number, publishedMs: number): NamedEnd {
  const year = new Date(publishedMs).getUTCFullYear();
  const end = kamchatkaDayEndUtc(year, month, day + shift);
  if (end < publishedMs - 30 * 86_400_000) {
    return { end: kamchatkaDayEndUtc(year + 1, month, day + shift), rolled: true };
  }
  return { end, rolled: false };
}

/** Оборот о маршрутах, посещении или сезоне — дата открытия должна быть о них. */
const OPENING_SUBJECT_RE = /маршрут|посещени|сезон/;
/** Открытие, объявленное вперёд: «будут открыты», «откроются», «открытие». */
const OPENING_AHEAD_RE = new RegExp(`${FUTURE_OPENING_SRC}|открыти[еяю]`);
const DATE_RE = new RegExp(`(\\d{1,2})\\s+(${MONTH_ALT})`, 'g');

/**
 * Конец закрытия, названный в тексте, или null.
 *
 *  - «до 1 октября» — включительно: до конца этого дня по Камчатке;
 *  - дата объявленного открытия маршрутов, посещения или сезона — закрыто
 *    до начала этого дня: «будут открыты с 1 декабря», «С 1 декабря
 *    откроются зимние маршруты», «откроются 1 декабря», «открытие зимних
 *    маршрутов — 1 декабря». Дата из того же предложения, что и оборот
 *    открытия: «визит-центр парка открыт с 7 ноября» — не про маршруты и
 *    срок закрытия не задаёт (ревью 06.11).
 */
function namedClosureEnd(lower: string, publishedMs: number): NamedEnd | null {
  const until = lower.match(new RegExp(`до\\s+(\\d{1,2})\\s+(${MONTH_ALT})`));
  if (until) return endOf(Number(until[1]), MONTHS[until[2]], 0, publishedMs);
  for (const s of sentencesOf(lower)) {
    if (!OPENING_AHEAD_RE.test(s) || !OPENING_SUBJECT_RE.test(s)) continue;
    for (const m of s.matchAll(DATE_RE)) {
      const before = s.slice(Math.max(0, (m.index ?? 0) - 4), m.index ?? 0);
      if (/до\s+$/.test(before)) continue;
      return endOf(Number(m[1]), MONTHS[m[2]], -1, publishedMs);
    }
  }
  return null;
}

/**
 * Сколько часов держать закрытие от момента публикации.
 *
 *  - названная дата в пределах 60 суток — до неё;
 *  - дата дальше потолка — закрытие держится как сезонное; но если она
 *    ушла переносом на следующий год дальше чем на полгода, это дата в
 *    прошлом;
 *  - дата в прошлом (конец, названный источником, уже наступил, в том числе
 *    объявленное открытие) — двое суток, как было до правила 06.11;
 *  - даты нет, закрытие сезонное или «до особого распоряжения» — 21 сутки
 *    (`PARK_CLOSURE_HOLD_HOURS`), продлевается каждой сводкой с ним;
 *  - даты нет, закрытие оперативное (циклон) — 48 ч; у недельной сводки
 *    его поднимает до 168 ч seismic-parser.
 */
export function parkClosureHours(text: string, publishedAt: Date): number {
  const lower = text.toLowerCase();
  const publishedMs = publishedAt.getTime();
  const indefinite = isIndefiniteClosure(lower);
  if (Number.isNaN(publishedMs)) return indefinite ? PARK_CLOSURE_HOLD_HOURS : PARK_CLOSURE_DEFAULT_HOURS;
  const named = namedClosureEnd(lower, publishedMs);
  if (named === null) return indefinite ? PARK_CLOSURE_HOLD_HOURS : PARK_CLOSURE_DEFAULT_HOURS;
  const hours = Math.ceil((named.end - publishedMs) / 3_600_000);
  if (hours <= 0) return PARK_CLOSURE_DEFAULT_HOURS;
  // Дальше потолка. Перенос на следующий год больше чем на полгода — это
  // прошедшая дата («ранее был закрыт до 1 октября» в ноябре), а не
  // закрытие на год вперёд; «до 1 марта» в ноябре — длинное закрытие.
  if (hours > PARK_CLOSURE_MAX_HOURS) {
    return named.rolled && hours > ROLLED_FUTURE_MAX_HOURS ? PARK_CLOSURE_DEFAULT_HOURS : PARK_CLOSURE_HOLD_HOURS;
  }
  return hours;
}
