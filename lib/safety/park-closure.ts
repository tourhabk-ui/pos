/**
 * Закрытие маршрутов природного парка — распознавание из текста (#2133).
 *
 * 30.09 «до 1 октября приостановлено посещение маршрутов в природных парках
 * „Налычево“ и „Южно-Камчатский“» (циклон, порывы до 32 м/с) не дошло до
 * статуса ни одного места: Ведар отвечал по Налычево [ЗЕЛЁНЫЙ]. У
 * классификатора не было ветки для такого текста, а у тревоги — способа
 * сказать, КАКОЙ парк закрыт.
 *
 * Модуль чистый: он только читает текст. Какие места и маршруты лежат в
 * парке, решает привязка (`PARK_SCOPED_SQL` в alert-place-scope) по
 * справочнику `parks` — здесь об этом ничего не знают.
 *
 * Правило узкое намеренно. Закрытием считается решение о ПОСЕЩЕНИИ парка или
 * его маршрутов («приостановлено посещение», «закрыты маршруты», «запрещён
 * выход на маршруты»), рядом с которым назван парк из справочника. Парк не
 * назван — это не закрытие парка (общий запрет тургруппам ловят другие
 * ветки), и угадывать парк по зоне здесь нельзя: зона «avachinsky» — это и
 * Налычево, и город.
 */

/**
 * Слаг парка из справочника `parks` → как парк называют в новостях.
 *
 * Название засчитывается в одной из трёх форм: рядом со словом «парк» /
 * «заповедник», в кавычках («„Южно-Камчатский“» — после «в парках
 * „Налычево“ и …» слово «парк» стоит только перед первым) или, для
 * однозначных имён, само по себе. Однозначное — то, что больше ничего на
 * Камчатке не называет: «Налычево», «Вачкажец». «Ключевская» без кавычек и
 * без «парка» — это сопка, «Быстринский» — ещё и район, «Южно-Камчатский» —
 * ещё и заказник; им нужна одна из двух первых форм.
 */
const Q = '[«"„]';
const QE = '[»"“]';
function named(stem: string, opts: { bare?: boolean } = {}): RegExp {
  const parts = [
    `${stem}[а-яё]*\\s+(?:природн[а-яё]*\\s+)?(?:парк|заповедник)`,
    `(?:парк|заповедник)[а-яё]*\\s+${Q}?${stem}`,
    `${Q}${stem}[а-яё]*${QE}`,
  ];
  if (opts.bare) parts.push(stem);
  return new RegExp(parts.join('|'));
}

export const PARK_NAME_PATTERNS: ReadonlyArray<{ slug: string; re: RegExp }> = [
  { slug: 'nalychevo', re: named('налычев', { bare: true }) },
  { slug: 'yuzhno-kamchatsky', re: named('южно-?\\s?камчатск') },
  { slug: 'bystrinskiy', re: named('быстринск') },
  { slug: 'klyuchevskoy', re: named('ключевск') },
  { slug: 'kronotsky', re: named('кроноцк') },
  { slug: 'vachkazhets', re: named('вачкажец', { bare: true }) },
  { slug: 'komandorskiy', re: named('командорск') },
];

/** Решение о посещении: приостановлено, закрыто, запрещено. */
const CLOSURE_RE = new RegExp(
  [
    '(?:приостановлен|закрыт|запрещ[её]н|прекращ[её]н)[а-яё]*\\s+(?:[а-яё]+\\s+)?(?:посещени|доступ|выход[а-яё]*\\s+на\\s+маршрут|маршрут)',
    '(?:посещени[ея]|маршрут[а-яё]*|доступ)[\\s\\S]{0,60}?(?:приостановлен|временно\\s+закрыт|закрыт[ыао]?\\b|запрещ[её]н)',
    'временно\\s+закрыл[аи]?\\s+(?:туристическ[а-яё]*\\s+)?маршрут',
  ].join('|'),
);

/**
 * Не закрытие ВСЕГО парка.
 *
 * Открытие («возобновлено посещение»). И частичное закрытие: сводка Минтура
 * 11.09 — «В парке „Налычево“ летние маршруты открыты… закрыты автомобильный
 * маршрут „Радыгино — Центральный“ и транзитный пеший маршрут». Первая
 * редакция правила приняла её за закрытие парка, и красным стало бы всё
 * Налычево при открытых летних маршрутах. Закрыт конкретный маршрут —
 * это его закрытие, а не парка: такой текст остаётся прежним веткам
 * (паводок, дороги) со своей зоной.
 */
const NOT_WHOLE_PARK_RE = new RegExp(
  [
    'возобновл[её]н[а-яё]*\\s+(?:посещени|работ)',
    'вновь\\s+открыт',
    'снят[ыо]?\\s+ограничени',
    'открыт[ыо]?\\s+для\\s+посещени',
    // «летние маршруты открыты», «маршруты парка открыты»
    'маршрут[а-яё]*\\s+(?:[а-яё]+\\s+)?открыт',
    // закрыт конкретный маршрут: «закрыты автомобильный маршрут „…“»
    'закрыт[а-яё]*\\s+(?:[а-яё]+\\s+){0,2}маршрут[а-яё]*\\s+[«"„]',
  ].join('|'),
);

export interface ParkClosure {
  /** Слаги парков, названных в тексте; не пусто. */
  parks: string[];
}

/** Закрытие парка в тексте или null. Текст — уже в нижнем регистре или любом. */
export function detectParkClosure(text: string): ParkClosure | null {
  const lower = text.toLowerCase();
  if (!/парк|заповедник/.test(lower)) return null;
  if (NOT_WHOLE_PARK_RE.test(lower)) return null;
  if (!CLOSURE_RE.test(lower)) return null;
  const parks = PARK_NAME_PATTERNS.filter((p) => p.re.test(lower)).map((p) => p.slug);
  return parks.length > 0 ? { parks } : null;
}

const MONTHS: Record<string, number> = {
  января: 0, февраля: 1, марта: 2, апреля: 3, мая: 4, июня: 5,
  июля: 6, августа: 7, сентября: 8, октября: 9, ноября: 10, декабря: 11,
};

/** Срок без названной даты: решение переиздают, двое суток хватает до следующего. */
export const PARK_CLOSURE_DEFAULT_HOURS = 48;
/** Потолок: названная дата дальше двух недель — скорее опечатка, чем решение. */
export const PARK_CLOSURE_MAX_HOURS = 14 * 24;

/**
 * Сколько часов держать закрытие от момента публикации.
 *
 * «До 1 октября» — включительно: закрытие живёт до конца этого дня по
 * Камчатке (UTC+12). Даты нет, она в прошлом или дальше потолка — срок по
 * умолчанию. Ошибиться в сторону «закрыто дольше» безопаснее, но потолок
 * держит опечатку от недели красного статуса.
 */
export function parkClosureHours(text: string, publishedAt: Date): number {
  const m = text.toLowerCase().match(/до\s+(\d{1,2})\s+(января|февраля|марта|апреля|мая|июня|июля|августа|сентября|октября|ноября|декабря)/);
  if (!m || Number.isNaN(publishedAt.getTime())) return PARK_CLOSURE_DEFAULT_HOURS;
  const day = Number(m[1]);
  const month = MONTHS[m[2]];
  // Конец названного дня по Камчатке (UTC+12) — это 12:00 UTC того же дня.
  let year = publishedAt.getUTCFullYear();
  let end = Date.UTC(year, month, day, 12, 0, 0);
  // «До 5 января», опубликовано в декабре — это следующий год.
  if (end < publishedAt.getTime() - 30 * 86_400_000) {
    year += 1;
    end = Date.UTC(year, month, day, 12, 0, 0);
  }
  const hours = Math.ceil((end - publishedAt.getTime()) / 3_600_000);
  if (hours <= 0 || hours > PARK_CLOSURE_MAX_HOURS) return PARK_CLOSURE_DEFAULT_HOURS;
  return hours;
}
