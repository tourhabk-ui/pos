/**
 * Кнопка «Обновить данные» на экране безопасности — правило, когда она
 * вправе опросить источники.
 *
 * ПОВОД (владелец 26.09): «обновить данные мне кажется не работает, очень
 * быстро обновляет, вряд ли за это время он обходит сайты». Он был прав:
 * кнопка перечитывала нашу базу, а к источникам шла только погода — и при
 * этом писала «Спрашиваем источники...» и «Проверено только что». Владелец
 * выбрал вариант, где кнопка действительно запускает сбор.
 *
 * Сбор — тот же, что каждые 5 минут зовёт супервизор (`start.js` →
 * GET /api/cron/safety-ingest): МЧС, КБГС и EQKam, emsd.ru, USGS, новостные
 * ленты, FIRMS. Своей копии обхода нет — иначе кнопка и крон разошлись бы
 * в том, что считают «источниками».
 *
 * Экран публичный, значит кнопку может жать кто угодно и сколько угодно.
 * Потолок поэтому ОБЩИЙ, а не на человека: не чаще раза в MIN_INTERVAL на
 * весь инстанс. Иначе сто нетерпеливых пальцев — это сто обходов чужих
 * сайтов, бан по адресу и пустой экран у того, кому он нужен в поле.
 * Сбор, прошедший меньше MIN_INTERVAL назад, не повторяется: его результат
 * и есть ответ.
 */

/** Не опрашивать источники чаще, чем раз в две минуты, на весь инстанс. */
export const MANUAL_REFRESH_MIN_INTERVAL_MS = 2 * 60_000;

/** Сколько кнопка ждёт сбор, прежде чем честно сказать «долго». */
export const MANUAL_REFRESH_WAIT_MS = 60_000;

/**
 * Исход нажатия. Не два, а пять (§4.0):
 *   ran     — сбор прошёл, источники опрошены сейчас;
 *   partial — сбор прошёл, но часть источников не ответила;
 *   recent  — сбор был меньше двух минут назад, повторять не стали;
 *   timeout — сбор идёт дольше минуты; он не отменён, данные придут позже;
 *   failed  — сбор запустить не удалось или он упал.
 */
export type ManualRefreshOutcome = 'ran' | 'partial' | 'recent' | 'timeout' | 'failed';

/**
 * Идти ли к источникам. `lastRunMs` — последний сбор, известный нам (из
 * журнала или от самой кнопки); null — не знаем. Незнание не повод ни
 * запретить сбор, ни разрешить его без потолка: потолок держит отдельный
 * ограничитель (lib/safety/refresh-throttle) в вызывающем коде.
 */
export function manualRefreshDecision(lastRunMs: number | null, now: number): 'run' | 'recent' {
  if (lastRunMs === null) return 'run';
  return now - lastRunMs < MANUAL_REFRESH_MIN_INTERVAL_MS ? 'recent' : 'run';
}

/** Строка рядом с кнопкой — одна на каждый исход, без «проверено» там, где не проверяли. */
export function manualRefreshNote(outcome: ManualRefreshOutcome): string | null {
  switch (outcome) {
    case 'ran': return null; // время проверки скажет само
    case 'partial': return 'Часть источников не ответила';
    // Время опроса уже стоит рядом («опрошены 2 мин назад»); вторая строка
    // о том же («опрашивали меньше 2 мин назад») читалась как сбой (снимок
    // владельца 01.10). Экран при этом перечитан — кнопка своё сделала.
    case 'recent': return null;
    case 'timeout': return 'Источники отвечают долго — данные обновятся сами';
    case 'failed': return 'Источники опросить не удалось';
  }
}

// ── «Данные обновятся сами» — чем это обеспечено (01.10) ───────────────────
//
// Строка исхода `timeout` обещала обновление, а производителя у обещания не
// было: экран перечитывал базу один раз, сразу после ответа кнопки, то есть
// ДО того, как продолжавшийся сбор что-то записал. Дальше не перечитывал
// никто (§10.09: объявленный исход без источника).
//
// Теперь экран дожидается конца сбора: раз в FOLLOWUP_MS спрашивает, когда
// приём отработал в последний раз, и перечитывает экран, как только это
// время ушло дальше того, что было до нажатия. Попыток конечное число —
// бесконечный опрос с телефона в поле стоит батареи.

/** Как часто экран спрашивает, закончился ли сбор после «долго». */
export const MANUAL_REFRESH_FOLLOWUP_MS = 15_000;

/** Сколько раз спрашивает: 8 × 15 с — ещё две минуты после минуты ожидания. */
export const MANUAL_REFRESH_FOLLOWUP_TRIES = 8;

/** Строка, когда сбор так и не отчитался за отведённое время. */
export const MANUAL_REFRESH_GAVE_UP_NOTE = 'Сбор не закончился за три минуты — нажмите ещё раз позже';

/**
 * Закончился ли сбор, начатый после отметки `before`.
 *
 * `before` — время последнего сбора ДО нажатия (из ответа кнопки); null —
 * его не знали. `checkedAt` — последний сбор сейчас. Нечитаемое время —
 * «не знаем», а не «закончился» (§4.0).
 */
export function ingestFinishedSince(before: string | null, checkedAt: string | null): boolean {
  if (!checkedAt) return false;
  const after = Date.parse(checkedAt);
  if (Number.isNaN(after)) return false;
  if (before === null) return true;
  const was = Date.parse(before);
  if (Number.isNaN(was)) return true;
  return after > was;
}

// ── Экран, оставленный открытым ────────────────────────────────────────────
//
// Радар, лента и пульсы приходят серверным рендером. Вкладка, открытая
// утром, днём показывает утро, пока её не перезагрузят, — а телефон держит
// вкладку часами. Экран старше SCREEN_STALE_MS перечитывается сам: пока на
// него смотрят — по тику SCREEN_AUTO_CHECK_MS, при возврате на вкладку —
// сразу. Пять минут — шаг самого сбора (супервизор зовёт safety-ingest раз
// в 5 минут): чаще перечитывать нечего, реже — толчок висит невидимым.

/** Сколько экран живёт без перечитывания, прежде чем перечитаться сам. */
export const SCREEN_STALE_MS = 5 * 60_000;

/** Как часто открытый экран спрашивает себя, не устарел ли он. */
export const SCREEN_AUTO_CHECK_MS = 60_000;

export function screenIsStale(lastLoadMs: number, now: number): boolean {
  return now - lastLoadMs >= SCREEN_STALE_MS;
}
