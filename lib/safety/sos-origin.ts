/**
 * Что известно об источнике SOS-сигнала.
 *
 * ── Случай 02.09 ───────────────────────────────────────────────────────────
 *
 * В канал пришло: «SOS! ЭКСТРЕННЫЙ СИГНАЛ. Имя: не указано. Тел: не указан.
 * Координаты: нет координат. Тип: не указан. IP: 74.235.134.163» — адрес
 * дата-центра в США. Сигнал лёг в `sos_events` активным, и с этой минуты
 * Watchdog каждые полчаса требует звонить в МЧС по поводу, о котором мы не
 * знаем даже, человек ли его послал.
 *
 * Это не первый раз. Миграция 123 закрывала РУКАМИ такой же анонимный
 * сигнал, провисевший 22 дня.
 *
 * ── Почему нельзя просто отклонять пустые ──────────────────────────────────
 *
 * Наша собственная страница `/sos` при отказе GPS и незаполненных полях шлёт
 * РОВНО ТАКОЕ ЖЕ тело: `{lat: null, lng: null, accuracy: null,
 * tourist_name: null, tourist_phone: null}`. По содержимому человек в беде
 * без спутников и слепая проба эндпоинта неотличимы.
 *
 * Значит содержимое судить не может. Отклонять пустое — потерять того самого
 * человека, ради которого всё это писалось.
 *
 * ── Что различает на самом деле ────────────────────────────────────────────
 *
 * Не текст, а происхождение запроса:
 *
 *   - авторизован             — знаем, кто;
 *   - `Sec-Fetch-Site` от нас — браузер сам проставляет этот заголовок, и
 *                               скрипт страницы его подделать не может;
 *   - `Referer` на нашем хосте — то же слабее, для старых браузеров;
 *   - меш-ретрансляция        — пришло через наш же узел (серверный вызов,
 *                               браузерных заголовков там нет по построению);
 *   - хоть что-то по делу     — координаты, имя, телефон, тип, сообщение,
 *                               идентификатор сессии.
 *
 * Слепая проба публичного эндпоинта не даёт НИ ОДНОГО из этих признаков.
 *
 * ── Три названных владельцем признака, и что с каждым можно ────────────────
 *
 *   «анонимный»        — признак, не приговор: наша страница анонимна для
 *                        незалогиненного, и таких большинство;
 *   «без координат»    — признак, не приговор: спутники не ловятся именно
 *                        там, где случается беда;
 *   «не с Камчатки»    — судится ТОЛЬКО по координатам (конверт края,
 *                        lib/geo/krai-envelope). По IP не судится вовсе:
 *                        адрес говорит, откуда пришёл запрос, а не где
 *                        человек. Роуминг, спутниковый терминал и VPN дают
 *                        чужой адрес при человеке в кальдере.
 *
 * Каждый по отдельности — свойство обычного настоящего сигнала. Приговор
 * выносит только их ПОЛНОЕ отсутствие вместе с отсутствием происхождения.
 *
 * ── Приговор здесь не выносится ────────────────────────────────────────────
 *
 * `unattributed` — это «не установлено», а НЕ «ложная тревога». Сигнал всё
 * равно принимается, всё равно пишется, всё равно уходит в канал. Меняется
 * одно: тревога называет, что о ней известно, и человек решает, на что
 * тратить силы. Автоматически закрывать такое ЗАПРЕЩЕНО — именно так
 * настоящий SOS и превратится в тишину (§4.0).
 *
 * Против решительного самозванца это не защита: кто хочет подделать сигнал,
 * подделает и заголовки. Задача другая — отделить слепую пробу от нашего
 * приложения, потому что первая приходит регулярно и сама собой.
 */

import { insideKrai } from '@/lib/geo/krai-envelope';

export type SosOriginClass =
  /** Авторизованный пользователь: знаем, кто послал. */
  | 'authenticated'
  /** Не авторизован, но пришёл из нашего приложения или через наш меш. */
  | 'from_app'
  /** Не из приложения, но в сигнале есть содержание — координаты, контакт, текст. */
  | 'has_content'
  /** Ни одного признака: сказать, что сигнал послал человек, нечем. */
  | 'unattributed';

export interface SosOriginEvidence {
  userId: string | null;
  /** Заголовок Sec-Fetch-Site: браузер ставит сам, страница подделать не может. */
  secFetchSite: string | null;
  referer: string | null;
  userAgent: string | null;
  /** 'mesh_relay' — сигнал форварднул наш собственный узел. */
  source: string | null;
  sessionId: string | null;
  lat: number | null | undefined;
  lng: number | null | undefined;
  touristName: string | null | undefined;
  touristPhone: string | null | undefined;
  emergencyType: string | null | undefined;
  message: string | null | undefined;
}

export interface SosOrigin {
  klass: SosOriginClass;
  /** Признаки, по которым вынесено решение — для строки в тревоге. */
  signals: string[];
  /** Одна фраза человеку в канал. */
  words: string;
}

/** Хосты, `Referer` с которых считается «от нас». */
const OWN_HOSTS = ['vedarai.ru', 'www.vedarai.ru', 'localhost'];

function refererIsOurs(referer: string | null): boolean {
  if (!referer) return false;
  try {
    return OWN_HOSTS.includes(new URL(referer).hostname);
  } catch {
    // Кривой Referer — не признак «от нас» и не признак обратного.
    return false;
  }
}

function hasText(v: string | null | undefined): boolean {
  return typeof v === 'string' && v.trim().length > 0;
}

export function classifySosOrigin(e: SosOriginEvidence): SosOrigin {
  const signals: string[] = [];

  if (e.userId) signals.push('авторизован');

  const fromApp =
    e.secFetchSite === 'same-origin' ||
    e.secFetchSite === 'same-site' ||
    refererIsOurs(e.referer) ||
    e.source === 'mesh_relay';

  if (e.secFetchSite === 'same-origin' || e.secFetchSite === 'same-site') {
    signals.push(`Sec-Fetch-Site: ${e.secFetchSite}`);
  }
  if (refererIsOurs(e.referer)) signals.push('Referer с нашего хоста');
  if (e.source === 'mesh_relay') signals.push('ретрансляция через меш');

  const content: string[] = [];
  if (e.lat != null && e.lng != null) content.push('координаты');
  if (hasText(e.touristName)) content.push('имя');
  if (hasText(e.touristPhone)) content.push('телефон');
  if (hasText(e.emergencyType)) content.push('тип ситуации');
  if (hasText(e.message)) content.push('сообщение');
  if (hasText(e.sessionId)) content.push('идентификатор сессии');
  signals.push(...content);

  // «SOS не с Камчатки» — признак настоящий, но судить им можно ТОЛЬКО по
  // координатам. По IP нельзя: адрес говорит, откуда пришёл ЗАПРОС, а не где
  // человек. Турист в роуминге, через спутниковый терминал или VPN даёт «не
  // наш» адрес, находясь в кальдере; гео-базы у нас нет, а догадка «IP чужой
  // — сигнал чужой» на этом слое стоит человека.
  //
  // Класс сигнала это НЕ меняет: координаты за краем — всё равно координаты,
  // и человек по ним находится. Меняется одно — тревога говорит, что искать
  // придётся не силами камчатского МЧС.
  if (insideKrai(e.lat, e.lng) === false) {
    signals.push('координаты ВНЕ Камчатского края');
  }

  if (!hasText(e.userAgent)) signals.push('user-agent пуст');

  const klass: SosOriginClass = e.userId
    ? 'authenticated'
    : fromApp
      ? 'from_app'
      : content.length > 0
        ? 'has_content'
        : 'unattributed';

  return { klass, signals, words: ORIGIN_WORDS[klass] };
}

/**
 * Слова в канал. Про `unattributed` сказано ровно то, что известно, и ни
 * слова сверх: «похоже на пробу» — уже догадка, а решение принимает человек.
 */
export const ORIGIN_WORDS: Record<SosOriginClass, string> = {
  authenticated: 'Источник: авторизованный пользователь — известно, кто послал',
  from_app: 'Источник: наше приложение (заголовки браузера на месте), пользователь не авторизован',
  has_content: 'Источник: не из приложения, но в сигнале есть данные — считать настоящим',
  unattributed:
    'Источник НЕ УСТАНОВЛЕН: ни авторизации, ни заголовков браузера, ни единого поля. '
    + 'Сказать, что сигнал послал человек, нечем — но и обратного тоже. Проверить, не закрывать молча',
};

/**
 * Нужна ли этому сигналу эскалация «звоните 112» в тревоге Watchdog.
 *
 * Единственный класс, где эскалация звучит вхолостую, — `unattributed`: там
 * некому звонить и не о ком сообщать, ни имени, ни координат. Сигнал при этом
 * из списка НЕ пропадает и «ложной тревогой» не становится — он остаётся
 * висеть отдельной строкой, потому что «не знаю» не равно «всё хорошо».
 */
export function needsEscalation(klass: SosOriginClass | null): boolean {
  return klass !== 'unattributed';
}
