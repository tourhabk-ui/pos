/**
 * lib/safety/krai-far.ts — дальние округа края в предупреждениях МЧС: охват
 * по координатам места, а не зоной (#2293).
 *
 * ── Что случилось ──────────────────────────────────────────────────────────
 *
 * Гидро-тревога 7–12.10 называла Пенжинский и Олюторский районы. Карта
 * округов приёма относила Пенжинский к `northern`, Олюторский — к `eastern`,
 * и тревога легла на все 355 мест (alert-scope-census, prod-check 98): на
 * Ключевскую, Шивелуч и Кроноцкий — за 500–750 км, хотя их округ
 * (Усть-Камчатский) в тексте не назван. Так же волнение моря у Командоров
 * (Алеутский округ → `northern`) ложилось на Ключевскую группу. Четыре наши
 * зоны дальний север не выражают: «северная» — это и Ключи, и Каменское.
 *
 * ── Решение владельца 09.10 ────────────────────────────────────────────────
 *
 * «По координатам места», как «юг до Петропавловска» 04.10
 * (lib/safety/krai-south.ts): Пенжинский, Олюторский, Карагинский и
 * Тигильский округа накрывают места севернее KRAI_KORYAK_MIN_LAT, Алеутский —
 * только Командорские острова. Метки кладутся в affected_zones вместо зон и
 * читаются зональной веткой ALERT_MATCH_SQL (alert-place-scope.ts). Место без
 * координат не накрывается: «не измерили» ≠ «там» (§4.0).
 */

/** Метка охвата «Корякский округ». Ни с одной настоящей зоной не совпадает. */
export const KRAI_KORYAK_ZONE = 'krai_koryak';

/**
 * Южная черта охвата Корякского округа, градусы с. ш.
 *
 * Сама граница округа идёт не по параллели, поэтому число — черта между
 * известными точками по обе стороны: все сёла Тигильского района севернее
 * (самое южное — Усть-Хайрюзово, около 57,1), Шивелуч (56,65), Ключи (56,3)
 * и Эссо (55,93) — южнее.
 */
export const KRAI_KORYAK_MIN_LAT = 57.0;

/** Метка охвата «Командорские острова» (Алеутский округ). */
export const KRAI_COMMANDER_ZONE = 'krai_commander';

/**
 * Прямоугольник Командорских островов: остров Беринга (Никольское —
 * 55,20 / 165,99) и остров Медный (около 54,7 / 167,6). Материк на этих
 * широтах восточнее 162,1° не заходит (Кроноцкий полуостров), так что
 * прямоугольник не задевает ни одного материкового места.
 */
export const COMMANDER_BOX = { minLat: 54.3, maxLat: 55.6, minLng: 165.5, maxLng: 168.2 } as const;

/** Все метки охвата дальних округов — для читателей, сравнивающих зоны. */
export const KRAI_FAR_ZONES: readonly string[] = [KRAI_KORYAK_ZONE, KRAI_COMMANDER_ZONE];

/**
 * Зональная ветка SQL для меток дальних округов: место накрыто, если у
 * тревоги метка и место лежит в её охвате. Колонки — `ea` (external_alerts)
 * и `ark` (место); числа — константы этого модуля, не данные запроса.
 */
export const KRAI_FAR_MATCH_SQL = `(
  ('${KRAI_KORYAK_ZONE}' = ANY(ea.affected_zones)
    AND ark.lat IS NOT NULL AND ark.lat::float8 >= ${KRAI_KORYAK_MIN_LAT})
  OR ('${KRAI_COMMANDER_ZONE}' = ANY(ea.affected_zones)
    AND ark.lat IS NOT NULL AND ark.lng IS NOT NULL
    AND ark.lat::float8 BETWEEN ${COMMANDER_BOX.minLat} AND ${COMMANDER_BOX.maxLat}
    AND ark.lng::float8 BETWEEN ${COMMANDER_BOX.minLng} AND ${COMMANDER_BOX.maxLng})
)`;
