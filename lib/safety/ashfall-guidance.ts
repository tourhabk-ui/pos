/**
 * Правила поведения при пеплопаде — детерминированный справочник (МЧС России по
 * Камчатскому краю). Показываются на карточке вулкана, когда его авиационный код
 * повышен (оранжевый/красный) — тогда выброс пепла реален или уже идёт.
 *
 * Это свойство места в опасном состоянии, а не выдуманный AI-текст: правила
 * статичны и авторитетны (§7 дизайн-языка — безопасность из данных, не декор).
 * Аэро-код KVERT говорит «активность высокая», а этот блок — «что делать
 * человеку внизу, если пепел дойдёт до тебя».
 */

/** Правила МЧС при пеплопаде в населённой местности. Порядок = приоритет действий. */
export const ASHFALL_RULES: readonly string[] = [
  'Закройте окна и двери, без необходимости не выходите на улицу — вдыхание пепла опасно для лёгких.',
  'Если пепел проникает в помещение — наденьте респиратор или хлопчатобумажную повязку, смоченную содовым раствором.',
  'Укройте компьютер, технику и оборудование плёнкой или плотной тканью, не используйте во время пеплопада.',
  'Если были на улице во время пеплопада — не вносите одежду в дом.',
  'Убирать пепел выходите только в респираторе и очках.',
  'Очистите крышу, водосточные жёлоба и другие места, где скапливается пепел.',
  'Пополните запас воды, еды, лекарств и средств защиты дыхания.',
] as const;

/**
 * Показывать ли блок правил пеплопада для данного аэро-кода. Оранжевый/красный —
 * повышенная активность, пепел вероятен. Жёлтый/зелёный — не показываем, чтобы не
 * плодить тревожный шум там, где угрозы нет.
 */
export function shouldShowAshfallGuidance(colorCode: string | null | undefined): boolean {
  return colorCode === 'orange' || colorCode === 'red';
}

/**
 * Строка о пепле для зоны вулкана в геофенсе (#1428, «пеплопады Шивелуча»).
 *
 * Правила выше написаны для населённого пункта («закройте окна») и в поле
 * дословно не ложатся, а сочинять свои полевые правила безопасности нельзя
 * (§8: критичные факты — из справочника, не из головы). Поэтому зона говорит
 * только то, что из справочника следует: при оранжевом/красном коде пепел
 * вероятен, опасен для лёгких (правило 1), защита — повязка с содовым
 * раствором (правило 2) и очки (правило 5). Жёлтый и
 * зелёный — null: там строки нет, как нет и блока на карточке вулкана.
 */
export function ashfallZoneNote(colorCode: string | null | undefined): string | null {
  if (!shouldShowAshfallGuidance(colorCode)) return null;
  return 'Выброс пепла вероятен: вдыхание пепла опасно для лёгких — респиратор или повязка, смоченная содовым раствором, и очки.';
}
