/**
 * Показывать ли блок правил пеплопада для данного аэро-кода. Оранжевый/красный —
 * повышенная активность, пепел вероятен. Жёлтый/зелёный — не показываем, чтобы не
 * плодить тревожный шум там, где угрозы нет.
 */
export function shouldShowAshfallGuidance(colorCode: string | null | undefined): boolean {
  return colorCode === 'orange' || colorCode === 'red';
}
