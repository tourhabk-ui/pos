/**
 * Название опасности с заглавной. Неизвестный ключ возвращается КАК ЕСТЬ —
 * это прежнее поведение всех шести копий (`MAP[h] ?? h`), и менять его здесь
 * нельзя: сырой ключ на экране виден и чинится, а молчание скрыло бы, что у
 * места есть опасность, которую мы не умеем назвать.
 */
export function hazardLabel(key: string): string {
  return HAZARDS[key]?.label ?? key;
}

/**
 * ВАЖНО: исход для неизвестного ключа выбирает ПОВЕРХНОСТЬ, а не этот файл.
 *
 * Здесь сырой ключ возвращается как есть — так вели себя все экранные копии, и
 * на экране это правильно: `bears` посреди списка видно, и это чинится.
 *
 * У советов Кузьмича (`lib/kuzmich/place-advisory.ts`) решение ОБРАТНОЕ и
 * записано сторожем: неизвестная опасность молча пропускается, потому что
 * фразу произносят человеку, и английское слово внутри русского совета хуже
 * пропуска. Попытка привести оба поведения к одному сломала тот сторож — и
 * правильно сломала.
 */

/** То же строчными — для мест, где название вставляется внутрь предложения. */
export function hazardLabelLower(key: string): string {
  const label = HAZARDS[key]?.label;
  return label ? label.toLocaleLowerCase('ru-RU') : key;
}

/** Обычная речь. Неизвестный ключ — `null`: выдумывать фразу не из чего. */
export function hazardPhrase(key: string): string | null {
  return HAZARDS[key]?.phrase ?? null;
}
