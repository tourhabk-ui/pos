/**
 * Детерминированный детектор ОТКАЗА модели.
 *
 * ── Зачем (issue #1730) ───────────────────────────────────────────────────
 *
 * Оценка ответа Кузьмича пропускала всё короче 50 знаков — порог заводился
 * против обрывов связи, и для них он верен. Но ОТКАЗ короток по природе: «не
 * могу помочь с этим вопросом» — меньше пятидесяти. Значит отказ не попадал в
 * оценку вовсе: ни балла, ни записи, ни следа, и он был неотличим от того,
 * что ответа не было (§4.0 — два разных состояния сливались в одно).
 *
 * Своего списка запрещённых тем у платформы НЕТ (проверено: ни в lib/kuzmich,
 * ни в lib/safety, ни в lib/ai/prompts.ts). Значит отказ выносит провайдер, а
 * водопад меняет провайдера молча — поведение отказа может меняться от ответа
 * к ответу. С #1729 провайдер записывается; этот модуль добавляет второе, чего
 * не хватало, — сам факт отказа.
 *
 * Цена именно у нас выше обычной: Кузьмич советует человеку в поле, и законные
 * вопросы лежат ровно в темах, по которым модели отказывают целиком, — медведь
 * рядом, фальшфейер, травма и кровь, переохлаждение.
 *
 * ── Чего модуль НЕ делает ─────────────────────────────────────────────────
 *
 * Не мешает отказу дойти до туриста и не переписывает ответ. Он только НАЗЫВАЕТ
 * состояние, чтобы оно попало в журнал вместе с именем провайдера. Что с этим
 * делать — решение владельца, и принимать его надо по замеру, а не по догадке:
 * отказывает ли кто-то из наших провайдеров на этих темах, НЕ ПРОВЕРЕНО.
 *
 * ── Настройка баланса ─────────────────────────────────────────────────────
 *
 * Как и у sos-detector, баланс в сторону точности, но по обратной причине:
 * там ложное срабатывание — шумный блок телефонов, здесь — ложная запись
 * «модель отказала» в журнале качества. Поэтому обороты требуют формы ПЕРВОГО
 * ЛИЦА о себе («я не могу», «не могу помочь») и не ловят пересказ правил
 * («в парке нельзя разводить костёр») и честное незнание из данных («у меня
 * нет подтверждённой информации» — это ПРАВИЛЬНЫЙ ответ по промпту, а не
 * отказ, и он отдельно исключён).
 */

export interface RefusalDetection {
  /** Ответ выглядит отказом отвечать. */
  refused: boolean;
  /** Какие обороты сработали — для журнала, чтобы вердикт был разбираем. */
  markers: string[];
}

// \b в JS не знает кириллицу (\w = [A-Za-z0-9_]) — границы делаем lookaround'ами.
const B = '(?<![а-яёa-z0-9])';
const E = '(?![а-яёa-z0-9])';
const re = (pattern: string) => new RegExp(`${B}(?:${pattern})${E}`, 'i');

/**
 * Обороты отказа. Каждый — о СЕБЕ и в первом лице либо безличная формула
 * помощника; правила места и незнание фактов сюда не входят намеренно.
 */
const REFUSAL_PATTERNS: Array<[string, RegExp]> = [
  ['не могу помочь',      re('не могу (вам )?(с этим )?помочь')],
  ['не могу обсуждать',   re('не могу (обсуждать|говорить|рассказывать|отвечать|предоставить|дать)')],
  ['не буду',             re('не буду (это )?(обсуждать|отвечать|помогать)')],
  ['не в состоянии',      re('не (могу|в состоянии) выполнить (этот|ваш) запрос')],
  ['вне моей роли',       re('(это )?(выходит за рамки|вне) (моей|моих) (роли|компетенц|возможност|инструкц)')],
  ['не предназначен',     re('я не предназначен')],
  ['как ии не могу',      re('как (ии|ai|языковая модель|искусственный интеллект)[^.!?\\n]*не (могу|буду)')],
  ['политика запрещает',  re('(моя |мои )?(политика|правила|ограничения)[^.!?\\n]*(не позволя|запреща)')],
  ['извините, не могу',   re('(извините|простите)[^.!?\\n]*не могу')],
  // Англоязычные: провайдеры водопада отвечают на русском не всегда, а отказ
  // особенно часто приходит шаблоном на английском.
  ['cannot help',         re("i (can'?t|cannot|am unable to) (help|assist|provide|answer)")],
  ['as an ai',            re("as an ai[^.!?\\n]*(can'?t|cannot|unable)")],
  ['against policy',      re('(against|violates)[^.!?\\n]*(policy|guidelines)')],
];

/**
 * Честное «не знаю» — НЕ отказ.
 *
 * Промпт Кузьмича прямо требует говорить «у меня нет подтверждённой
 * информации», когда события нет в данных. Считать это отказом значило бы
 * штрафовать за выполнение правила — и заодно утопить настоящие отказы в шуме.
 */
const HONEST_UNKNOWN: RegExp[] = [
  re('нет подтвержд(ённой|енной) информаци'),
  re('(этого|такого) нет в (моих )?данных'),
  re('не нашл(ось|и|а)[^.!?\\n]*в (базе|данных)'),
];

export function detectRefusal(text: string): RefusalDetection {
  const body = text.trim();
  if (!body) return { refused: false, markers: [] };

  // Честное незнание перебивает: оно бывает в одном предложении с «не могу
  // сказать точно», и это по-прежнему правильный ответ, а не отказ.
  if (HONEST_UNKNOWN.some(p => p.test(body))) return { refused: false, markers: [] };

  const markers = REFUSAL_PATTERNS.filter(([, p]) => p.test(body)).map(([name]) => name);
  return { refused: markers.length > 0, markers };
}
