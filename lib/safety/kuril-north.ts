/**
 * lib/safety/kuril-north.ts — Северные Курилы: соседи края, но не край
 * (16.10, #83, карт-бланш владельца).
 *
 * ── Что было ──────────────────────────────────────────────────────────────
 *
 * Перепись районов по контурам OSM нашла 12 мест Северо-Курильского округа —
 * Парамушир и Шумшу, Эбеко, Алаид, Северо-Курильск. Это Сахалинская
 * область: камчатские сводки (Росгидромет Камчатки, МЧС края) о них не
 * говорят. А район у них стоял камчатский — семь «Западная», пять
 * «Авачинская», — и тревоги Петропавловска и западного побережья ложились
 * на Парамушир, а «юг края до Петропавловска» доставал их ещё и по широте.
 * Разбор приёма относил Эбеко и Алаид к «северной» зоне — сводка МЧС о них
 * красила бы Ключи и Усть-Камчатск.
 *
 * ── Правило ───────────────────────────────────────────────────────────────
 *
 *   - район мест — метка KURIL_NORTH_ZONE, не одна из четырёх зон края:
 *     камчатские погодные сводки до них не доходят;
 *   - цунами — доходит: волна у Лопатки — это и Северо-Курильск (1952).
 *     Угроза КБГС и МЧС без названного округа несёт и эту метку
 *     (TSUNAMI_WIDE_ZONES, seismic-parser);
 *   - тревога, называющая Эбеко или Алаид, — их метка, а не «северная»;
 *   - «юг края» по широте их не накрывает: прямоугольник KURIL_NORTH_BOX
 *     вычитается из широтного охвата (ALERT_MATCH_SQL);
 *   - землетрясения и извержения приходят как и прежде — силой сотрясения и
 *     по вулкану, район их не решает;
 *   - карточка не пишет «предупреждений нет»: сахалинских сводок у нас нет,
 *     и обстановку там мы не знаем (KURIL_NORTH_NOTE, place-day-status).
 */

/** Метка района «Северные Курилы». Ни с одной зоной края не совпадает. */
export const KURIL_NORTH_ZONE = 'kuril_north';

/**
 * Прямоугольник Парамушира, Шумшу и Атласова (Алаид). Мыс Лопатка — 50,87 /
 * 156,67 — восточнее рамки: Первый Курильский пролив проходит между 156,5 и
 * 156,6, и южная оконечность Камчатки остаётся в крае.
 */
export const KURIL_NORTH_BOX = { minLat: 49.5, maxLat: 51.0, minLng: 154.0, maxLng: 156.55 } as const;

/** Что сказать о месте вместо цвета: сводок этой области у нас нет. */
export const KURIL_NORTH_NOTE =
  'Это Сахалинская область: камчатские сводки сюда не относятся, а сахалинских у нас нет. Обстановку перед выходом уточните в МЧС Сахалинской области или по 112.';

/** Точка `ark` лежит в прямоугольнике Северных Курил. */
export const KURIL_NORTH_BOX_SQL = `(
  ark.lat IS NOT NULL AND ark.lng IS NOT NULL
  AND ark.lat::float8 BETWEEN ${KURIL_NORTH_BOX.minLat} AND ${KURIL_NORTH_BOX.maxLat}
  AND ark.lng::float8 BETWEEN ${KURIL_NORTH_BOX.minLng} AND ${KURIL_NORTH_BOX.maxLng}
)`;

/** Место вне сводок края — Северные Курилы. */
export function isOutsideKraiSources(zone: string | null | undefined): boolean {
  return zone?.trim() === KURIL_NORTH_ZONE;
}
