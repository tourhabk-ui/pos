/**
 * lib/safety/alert-guidance.ts — что делать при тревоге, в поле и без сети.
 *
 * ── Разрыв, который это закрывает ─────────────────────────────────────────
 *
 * Issue #1485: «Тревоги о вулкане и землетрясении формируются, но не доходят
 * ни до кого». Разбор 01.09 показал, что первая половина работает целиком:
 * сейсмика идёт из USGS с привязкой зон по расстоянию, вулканы — из КВЕРТ,
 * пеплопад разобран, крон `safety-alert` считает, `SafetyWarnings` рисует.
 *
 * Не работает вторая половина. Офлайн-снимок в полевом пакете
 * (`PackSafetySnapshot`) несёт `hasAlert`, `maxSeverity` и заголовок — то
 * есть ЧТО случилось. Не несёт, ЧТО ДЕЛАТЬ: руководство осталось онлайн,
 * а тревога застаёт человека там, где сети нет по определению.
 *
 * Худшая половина пары: тревогу донесли, ответ на неё оставили в интернете.
 *
 * ── Почему справочник, а не модель ────────────────────────────────────────
 *
 * Такой текст читает человек, стоящий на склоне при землетрясении. Здесь
 * нет места ни выдумке, ни вариативности формулировок: правила статичны и
 * авторитетны, как и `ASHFALL_RULES`, откуда взят образец. Платформа это уже
 * решила — «критичные факты только из инструментов/БД, самоотчётам модели не
 * верить» (§8), и §4.0 отдельно запрещает просить у модели то, чего нет в
 * данных.
 *
 * ── Третий исход ─────────────────────────────────────────────────────────
 *
 * Неизвестный тип тревоги НЕ получает общих слов вроде «будьте осторожны».
 * Он получает честное «руководства для этого типа не записано» — потому что
 * успокоительная пустышка на экране неотличима от настоящего указания, а
 * цена ошибки здесь измеряется не удобством.
 */

import { ASHFALL_RULES } from '@/lib/safety/ashfall-guidance';

export interface AlertGuidance {
  /** Тип, для которого руководство найдено. */
  type: string;
  /** Шаги по приоритету. Пусто не бывает: либо шаги, либо `known: false`. */
  steps: readonly string[];
  /** Есть ли записанное руководство. false — мы не знаем, и говорим это. */
  known: boolean;
}

