/** Синонимы типов из разных источников — к одному ключу справочника. */
const ALIASES: Record<string, string> = {
  tsunami_warning: 'tsunami',
  ashfall: 'volcano',
  eruption: 'volcano',
  seismic: 'earthquake',
  quake: 'earthquake',
};

/**
 * Руководство по типу тревоги. Чистая функция — проверяется тестом целиком.
 *
 * Неизвестный тип отдаёт `known: false` и ПУСТЫЕ шаги. Заполнять их общими
 * словами нельзя: «будьте осторожны» на экране выглядит указанием, ничего не
 * указывая, и вытесняет собой поиск настоящего ответа.
 */
export function alertGuidance(alertType: string | null | undefined): AlertGuidance {
  const raw = (alertType ?? '').trim().toLowerCase();
  if (!raw) return { type: '', steps: [], known: false };
  const key = ALIASES[raw] ?? raw;
  const steps = GUIDANCE[key];
  return steps
    ? { type: key, steps, known: true }
    : { type: raw, steps: [], known: false };
}

/** Строка для человека, когда руководства нет. Одна на все такие случаи. */
export const NO_GUIDANCE_TEXT =
  'Что делать при этой тревоге — у нас не записано. Свяжитесь с МЧС (112), когда появится связь.';

/** Типы, для которых руководство есть. Для переписи покрытия. */
export function guidedAlertTypes(): string[] {
  return Object.keys(GUIDANCE).sort();
}
