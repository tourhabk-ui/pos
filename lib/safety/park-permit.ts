/**
 * Зоны свободного посещения: разрешение НЕ требуется.
 *
 * Список короткий и намеренно поимённый. Соблазн вывести правило «перевалы
 * можно» здесь был бы ровно тем сочинением, от которого предостерегает §4.0:
 * парк называет одну такую территорию, её и называем.
 */
export const FREE_VISIT_AREAS: readonly string[] = ['Авачинский перевал'];

/** Свободная ли это зона — сверка по названию маршрута или места. */
export function isFreeVisitArea(title: string | null | undefined): boolean {
  if (!title) return false;
  const t = title.toLowerCase();
  return FREE_VISIT_AREAS.some((area) => t.includes(area.toLowerCase()));
}
