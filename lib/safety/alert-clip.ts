/**
 * Обрезка текста предупреждения — одна на все поверхности (лента /safety,
 * бегущая строка v8, карточка сводки десктопной главной). Две поверхности об
 * одном предупреждении обязаны говорить одинаково.
 *
 * Бегущая строка — поверхность одного взгляда, а дорожные ограничения
 * приходят абзацами на 400-600 символов: целиком они не читаются ни в
 * прокрутке, ни в раскрытом списке (владелец увидел два экрана текста).
 * Полный текст живёт на карточке маршрута, тут — суть.
 *
 * Отдельный модуль без 'use client': серверный компонент не может звать
 * функцию из клиентского модуля (components/safety/LiveStatus), 30.09.
 */
export function clip(text: string, max = 140): string {
  const t = text.trim();
  if (t.length <= max) return t;
  const cut = t.slice(0, max);
  const space = cut.lastIndexOf(' ');
  return `${(space > max * 0.6 ? cut.slice(0, space) : cut).replace(/[\s.,;:—-]+$/, '')}…`;
}
