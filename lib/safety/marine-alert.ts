/**
 * lib/safety/marine-alert.ts — морская тревога не висит на горных местах
 * (#2293).
 *
 * ── Что случилось ──────────────────────────────────────────────────────────
 *
 * «Экстренное предупреждение на 8-9 октября (опасное волнение моря)» МЧС
 * называло подрайоны акватории у Елизовского и Усть-Камчатского округов, и
 * зона довела его до Ключевской и Шивелуча — вулканов в сотне километров от
 * берега. Так же «Росгидромет: прибрежные события» ложился на каждый вулкан
 * края. Шум на каждом вулкане прячет настоящий сигнал (дайджест 08.10).
 *
 * ── Решение владельца 09.10 ────────────────────────────────────────────────
 *
 * «Не вешать на горные места»: вулканы, горы, перевалы, ледники, плато,
 * гейзеры и термальные поля морскую тревогу не получают (пещеры — с 16.10,
 * см. MOUNTAIN_PLACE_TYPES). С 26.11 (слово владельца «2в», #3859) — и
 * внутренние: озёра, горячие источники, смотровые, исторические места
 * (INLAND_PLACE_TYPES). Бухты, пляжи, мысы, острова, сёла, места без типа и
 * остальные — получают, как раньше. В общей ленте (/safety, safety_status)
 * тревога остаётся. Маршруты правило не трогает: оно про места.
 *
 * ── Что считается морской тревогой ─────────────────────────────────────────
 *
 * Только погодная (`weather`), и только по ЗАГОЛОВКУ: он называет морское
 * явление и не называет сухопутного. МЧС перечисляет явления в скобках
 * заголовка — «(сильный ветер, опасное волнение моря)» морской не считается:
 * ветер вулкана касается. Ошибиться здесь можно только в сторону охвата: не
 * узнали морское — тревога остаётся на месте, как было до 09.10. Цунами —
 * свой род (`tsunami_warning`), это правило его не трогает.
 *
 * Шаблоны — строчными: SQL сравнивает с `lower(...)`, как TOURIST_BAN_SQL.
 */

/**
 * Морское явление в заголовке.
 *
 * С 26.11 (#3859) — и перелив кос: «Экстренное предупреждение на 27 ноября
 * (переливание песчаных кос морской водой)» шаблон не узнавал, тревога
 * считалась не морской и легла на «Кальдеру Курильское озеро» с типом
 * `volcano`. «Морская вода» — тоже морское явление: вода моря выходит на берег.
 */
export const MARINE_TITLE = /волнени[а-яё]*\s+мор|прибрежн[а-яё]*\s+событи|тягун|нагонн|морск[а-яё]*\s+вод|перелив[а-яё]*\s+(?:[а-яё]+\s+){0,2}кос/;

/**
 * Сухопутное явление в заголовке — тогда тревога не морская. Список
 * намеренно широкий: лишнее совпадение лишь оставляет тревогу на месте.
 * «Уровень» сюда не входит: в нём жёлтый уровень Росгидромета, а не вода.
 */
export const LAND_TITLE = /ветер|ветр|шквал|ураган|смерч|метел|снег|дожд|ливн|осадк|гроз|град|гололед|гололёд|налипан|туман|мороз|заморозк|холод|жар|зной|пожар|павод|половод|наводн|лавин|сел[ьяеи]|оползн|камнепад|землетрясен|цунами|извержен|пепл|пепел|вулкан/;

/**
 * Горные места: морская тревога их не касается (решение владельца 09.10).
 *
 * Пещеры — с 16.10 (карт-бланш владельца, #2522): обе пещеры базы — лавовые
 * трубы на вулканах, Горелом и Толбачике, в 45 и 100 км от моря (проба 981).
 * До 851 они числились вулканами и морскую тревогу не получали; новый вид
 * вернул им «прибрежные события». Морской грот, если появится, — не «cave»,
 * а свой вид: у берега волнение моря его касается.
 */
export const MOUNTAIN_PLACE_TYPES = ['volcano', 'mountain', 'pass', 'glacier', 'plateau', 'geyser', 'thermal', 'cave'] as const;

/**
 * Внутренние места: морская тревога их тоже не касается (слово владельца 26.11
 * «2в», #3859).
 *
 * Перелив кос 27.11 лёг на горячие источники и Шаманскую поляну Эссо, на
 * смотровую «Вид на Эссо» и на Курильское озеро — за сотню километров от моря,
 * через зону края. Расстояния до берега в данных нет, поэтому правило — по
 * типу, как у горных мест. Цена названа владельцу: озеро у самого берега,
 * прибрежный источник или смотровая на мысу морскую тревогу тоже больше не
 * получают. В общей ленте края она остаётся.
 */
export const INLAND_PLACE_TYPES = ['lake', 'hot_spring', 'viewpoint', 'historical'] as const;

/** Места без морской тревоги: горные (09.10) и внутренние (26.11). */
export const MARINE_EXEMPT_PLACE_TYPES = [...MOUNTAIN_PLACE_TYPES, ...INLAND_PLACE_TYPES] as const;

/** Морская ли тревога — то же правило, что MARINE_ALERT_SQL. */
export function isMarineAlert(alertType: string | null | undefined, title: string | null | undefined): boolean {
  const t = (title ?? '').toLowerCase();
  return alertType === 'weather' && MARINE_TITLE.test(t) && !LAND_TITLE.test(t);
}

/** Тревога `ea` морская. Шаблоны в долларовых кавычках: обратная косая доходит до сервера как есть. */
export const MARINE_ALERT_SQL = `(
  ea.alert_type = 'weather'
  AND lower(COALESCE(ea.title, '')) ~ $marine$${MARINE_TITLE.source}$marine$
  AND lower(COALESCE(ea.title, '')) !~ $land$${LAND_TITLE.source}$land$
)`;

/** Место `ark` морской тревоги не получает: горное или внутреннее. Место без типа — получает. */
export const MARINE_EXEMPT_PLACE_SQL =
  `COALESCE(ark.location_type, '') IN (${MARINE_EXEMPT_PLACE_TYPES.map((t) => `'${t}'`).join(', ')})`;
