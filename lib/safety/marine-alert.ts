/**
 * lib/safety/marine-alert.ts — морская тревога не висит на горных местах
 * (#2293).
 *
 * ── Что случилось ──────────────────────────────────────────────────────────
 *
 * «Экстренное предупреждение на 8-9 октября (опасное волнение моря)» МЧС
 * называло подрайоны акватории у Елизовского и Усть-Камчатского округов, и
 * зона довела его до Ключевской и Шивелуча — вулканов в сотне километров от
 * берега. Так же «Росгидромет: прибрежные события» ложился на каждый вулкан
 * края. Шум на каждом вулкане прячет настоящий сигнал (дайджест 08.10).
 *
 * ── Решение владельца 09.10 ────────────────────────────────────────────────
 *
 * «Не вешать на горные места»: вулканы, горы, перевалы, ледники, плато,
 * гейзеры и термальные поля морскую тревогу не получают. Бухты, пляжи, мысы,
 * острова, сёла, места без типа и остальные — получают, как раньше. В общей
 * ленте (/safety, safety_status) тревога остаётся. Маршруты правило не
 * трогает: оно про места.
 *
 * ── Что считается морской тревогой ─────────────────────────────────────────
 *
 * Только погодная (`weather`), и только по ЗАГОЛОВКУ: он называет морское
 * явление и не называет сухопутного. МЧС перечисляет явления в скобках
 * заголовка — «(сильный ветер, опасное волнение моря)» морской не считается:
 * ветер вулкана касается. Ошибиться здесь можно только в сторону охвата: не
 * узнали морское — тревога остаётся на месте, как было до 09.10. Цунами —
 * свой род (`tsunami_warning`), это правило его не трогает.
 *
 * Шаблоны — строчными: SQL сравнивает с `lower(...)`, как TOURIST_BAN_SQL.
 */

/** Морское явление в заголовке. */
export const MARINE_TITLE = /волнени[а-яё]*\s+мор|прибрежн[а-яё]*\s+событи|тягун|нагонн/;

/**
 * Сухопутное явление в заголовке — тогда тревога не морская. Список
 * намеренно широкий: лишнее совпадение лишь оставляет тревогу на месте.
 * «Уровень» сюда не входит: в нём жёлтый уровень Росгидромета, а не вода.
 */
export const LAND_TITLE = /ветер|ветр|шквал|ураган|смерч|метел|снег|дожд|ливн|осадк|гроз|град|гололед|гололёд|налипан|туман|мороз|заморозк|холод|жар|зной|пожар|павод|половод|наводн|лавин|сел[ьяеи]|оползн|камнепад|землетрясен|цунами|извержен|пепл|пепел|вулкан/;

/** Горные места: морская тревога их не касается (решение владельца 09.10). */
export const MOUNTAIN_PLACE_TYPES = ['volcano', 'mountain', 'pass', 'glacier', 'plateau', 'geyser', 'thermal'] as const;

/** Морская ли тревога — то же правило, что MARINE_ALERT_SQL. */
export function isMarineAlert(alertType: string | null | undefined, title: string | null | undefined): boolean {
  const t = (title ?? '').toLowerCase();
  return alertType === 'weather' && MARINE_TITLE.test(t) && !LAND_TITLE.test(t);
}

/** Тревога `ea` морская. Шаблоны в долларовых кавычках: обратная косая доходит до сервера как есть. */
export const MARINE_ALERT_SQL = `(
  ea.alert_type = 'weather'
  AND lower(COALESCE(ea.title, '')) ~ $marine$${MARINE_TITLE.source}$marine$
  AND lower(COALESCE(ea.title, '')) !~ $land$${LAND_TITLE.source}$land$
)`;

/** Место `ark` горное. Место без типа горным не считается. */
export const MOUNTAIN_PLACE_SQL =
  `COALESCE(ark.location_type, '') IN (${MOUNTAIN_PLACE_TYPES.map((t) => `'${t}'`).join(', ')})`;
