/**
 * Сроки закрытия парка — числа без правил текста.
 *
 * Отдельным модулем, потому что срок нужен и клиентской ленте
 * (`lib/safety/alert-dates.ts` → `components/safety/LiveStatus.tsx`), а
 * классификатор закрытий (`lib/safety/park-closure.ts`) с его регулярками в
 * браузере не нужен (ревью 06.11).
 */

/** Срок без названной даты: решение переиздают, двое суток хватает до следующего. */
export const PARK_CLOSURE_DEFAULT_HOURS = 48;

/**
 * Потолок названной даты — 60 суток. До 06.11 он был 14: «названная дата
 * дальше двух недель — скорее опечатка». Для циклона это верно, для сезона —
 * нет: «закрыты до 1 декабря», опубликованное 6 ноября, отрезалось до 48 ч,
 * и закрытие с датой гасло раньше закрытия без даты. Два месяца — окно
 * межсезонья; дальше дата всё же скорее опечатка, и закрытие держится как
 * сезонное (`PARK_CLOSURE_HOLD_HOURS`).
 */
export const PARK_CLOSURE_MAX_HOURS = 60 * 24;

/**
 * Сезонное закрытие без даты (решение владельца 06.11, ответ «1 да» на п. 1
 * раздела 9 docs/agents/LEAD_PLAN.md): «на период межсезонья», «на зимний
 * сезон», «до особого распоряжения».
 *
 * Держится 21 сутки от последней сводки. Повтор той же сводки продлевает
 * срок (saveEvent, GREATEST). 21 сутки — тот же порог, после которого
 * источник visitkamchatka считается замолчавшим (source-health): три недели
 * без подтверждения — это уже не знание, а память о нём.
 *
 * Раньше предела закрытие гасит сводка об открытии (applyParkReopenings), а
 * после предела без неё место не зеленеет, а становится «статус парка не
 * известен» — жёлтым, с датой последней сводки (markParkStatusUnknown,
 * lib/services/safety/park-reopening.ts).
 */
export const PARK_CLOSURE_HOLD_HOURS = 21 * 24;

/**
 * Предел «статус парка не известен»: дольше 120 суток от последней сводки о
 * сезонном закрытии строка не держится. Межсезонье на Камчатке — октябрь–ноябрь
 * и май–июнь; через четыре месяца сводка о закрытии говорит уже о прошлом
 * сезоне. Читают проход «не знаю» (lib/services/safety/park-reopening.ts) и
 * строка ленты для агентов (lib/safety/current-status.ts) — одним числом.
 */
export const PARK_UNKNOWN_MAX_DAYS = 120;
