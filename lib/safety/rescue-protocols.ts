/**
 * Локальный ответ. `earlier` — прежние реплики человека в этом чате (не
 * ответы спасателя): без них короткая «Потеряли рюкзак» после «Мы
 * заблудились» выглядела бы чистой утерей вещи.
 */
export function getLocalProtocol(text: string, earlier: readonly string[] = []): string | null {
  if (isPureItemLoss(text, earlier)) return ITEM_LOSS_PROTOCOL;
  for (const [pattern, response] of LOCAL_PROTOCOLS) {
    if (pattern.test(text)) return response;
  }
  return null;
}

/** Нет протокола и нет сети — ответ без выдумки. */
