/**
 * lib/safety/sos-status.ts
 *
 * Словарь статусов SOS — ОДИН на платформу.
 *
 * ── Зачем (находка аудита 08.09) ────────────────────────────────────────────
 *
 * Условие «сигнал ещё висит» было написано словами `status NOT IN ('resolved',
 * 'false_alarm')` в четырёх местах: сводка спасателя (дважды), Watchdog и
 * перепись SOS. Список терминальных значений при этом жил только в этих
 * строках — то есть нигде.
 *
 * Цена вскрылась на пятом месте: исполнитель `archive_sos` ставит
 * `status = 'archived'`, а ни один из четырёх фильтров такого значения не
 * знает. Заархивированный сигнал остаётся «активным» ВЕЧНО и звучит критом
 * каждые полчаса. Сторож, который кричит о том, что уже разобрано, приучает
 * не смотреть на сторожа — а это дороже, чем молчание.
 *
 * Само действие `archive_sos` политика запрещает («SOS-эффекты исключены из
 * автономии, решение владельца 27.08»), но строки, созданные до запрета, в
 * базе остаются, и читать их нужно правильно.
 *
 * ── Почему archived терминален, но не невидим ───────────────────────────────
 *
 * Терминальный здесь значит «не поднимает тревогу», а не «исчез». Архивацию
 * делает человек, разобравший висящий сигнал; поднимать по нему крит второй
 * раз незачем. Но в переписи он обязан быть виден отдельным числом — иначе
 * архивация станет способом прятать сигналы, а не закрывать их.
 */

/** Исходы, при которых сигнал больше НЕ считается висящим. */
export const SOS_TERMINAL_STATUSES = ['resolved', 'false_alarm', 'archived'] as const;

export type SosTerminalStatus = (typeof SOS_TERMINAL_STATUSES)[number];

/**
 * SQL-условие «сигнал ещё висит».
 *
 * Возвращает готовый фрагмент, а не список: собирать его на месте — значит
 * снова развести четыре копии. Значения здесь наши собственные константы, не
 * данные запроса.
 */
export const SOS_ACTIVE_SQL =
  `status NOT IN (${SOS_TERMINAL_STATUSES.map((s) => `'${s}'`).join(', ')})`;

/** Тот же вопрос в TypeScript — для фильтрации уже прочитанных строк. */
export function isSosActive(status: string | null | undefined): boolean {
  if (!status) return true; // статуса нет — сигнал не закрыт, это не «всё хорошо»
  return !(SOS_TERMINAL_STATUSES as readonly string[]).includes(status);
}
