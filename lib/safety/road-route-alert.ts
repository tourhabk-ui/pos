/**
 * lib/safety/road-route-alert.ts — дорожное ограничение, которое называет
 * дорогу самого маршрута (#3858, разбор очереди 26.11).
 *
 * ── Что случилось ──────────────────────────────────────────────────────────
 *
 * 26.11 Турпортал края закрыл проезд по автозимнику Анавгай — Палана: «Временно
 * закрыт проезд для легкового транспорта на участке с 230-го по 435-й км
 * автозимника, между селом Тигиль и посёлком Палана», метель. Маршрут каталога
 * «Зимник Анавгай - Тигиль» — это та же дорога, а страж отвечал о нём «Идти:
 * предупреждений и опасных кодов на маршруте нет».
 *
 * Дорожное ограничение доходит до мест и маршрутов координатой: имя объекта
 * в заголовке ищется в каталоге мест (`lib/safety/alert-anchor.ts`), дальше
 * судит радиус 30 км. Сёл Тигиль, Палана и Анавгай в каталоге мест нет, и
 * привязка не нашла ничего. По правилу 27.09 «не установлено ≠ везде»
 * непривязанное ограничение не красит никого. Это правило верно, но здесь
 * место установлено: заголовок называет дорогу, которой и является маршрут.
 *
 * ── Правило ────────────────────────────────────────────────────────────────
 *
 * Ограничение относится к маршруту, когда:
 *   1. род тревоги — `road_closure`;
 *   2. название маршрута называет дорогу (`ROAD_KINDS`), и заголовок тревоги
 *      называет дорогу того же рода;
 *   3. заголовок называет хотя бы одно селение или объект из названия
 *      маршрута — по основе слова, в любом падеже («Тигиль», «Тигиля»).
 *
 * Тревога без названия места («Проезд закрыт в связи с метелью») маршрут не
 * накрывает: какую дорогу она закрыла, из заголовка не видно. Она остаётся в
 * общекраевой ленте, как и раньше.
 *
 * «Дорога» в список родов не входит намеренно: «Дорога к водопаду» — тропа, а
 * не автодорога, и «дорога со стороны Дальнего перекрыта» легла бы на неё по
 * одному общему слову.
 *
 * У мест этого правила нет: место — не дорога. Маршруты к Палане («Озеро
 * Паланское») ограничение тоже не получают: их названия не называют дорогу,
 * а «паланск» — это прилагательное от посёлка, не сама дорога.
 */

import { stemRu } from '@/lib/search/query-words';

/** Род дороги в названии маршрута и в заголовке тревоги. */
export const ROAD_KINDS: ReadonlyArray<{ readonly kind: string; readonly re: RegExp }> = [
  // «автозимник» тоже содержит «зимник».
  { kind: 'зимник', re: /зимник/ },
  { kind: 'автодорога', re: /автодорог/ },
];

/**
 * Слова названия, которые не называют место: род дороги, служебные слова и
 * родовые слова ландшафта.
 */
const NOT_A_PLACE = new Set([
  'зимник', 'автозимник', 'автодорога', 'дорога', 'трасса', 'участок', 'маршрут',
  // Сравнивается после замены «ё» на «е»: «посёлок» здесь — «поселок».
  'село', 'поселок', 'город', 'река', 'озеро', 'через', 'между',
]);

/** Короче основа не сравнивается: совпала бы со случайным словом. */
const MIN_STEM = 4;

function words(text: string): string[] {
  return text.toLowerCase().replace(/ё/g, 'е').split(/[^а-яa-z0-9]+/).filter(Boolean);
}

/** Род дороги, которой назван маршрут, или null — маршрут не дорога. */
export function routeRoadKind(routeTitle: string | null | undefined): string | null {
  const t = (routeTitle ?? '').toLowerCase();
  return ROAD_KINDS.find((k) => k.re.test(t))?.kind ?? null;
}

/** Основы мест из названия маршрута-дороги: «Зимник Анавгай - Тигиль» → анавг, тиги. */
export function routePlaceStems(routeTitle: string): string[] {
  return words(routeTitle)
    .filter((w) => !NOT_A_PLACE.has(w) && !/^(авто)?зимник/.test(w) && !/^автодорог/.test(w))
    .map(stemRu)
    .filter((s) => s.length >= MIN_STEM);
}

/** Тревога `road_closure` называет дорогу этого маршрута. */
export function roadAlertNamesRoute(
  routeTitle: string | null | undefined,
  alertType: string | null | undefined,
  alertTitle: string | null | undefined,
): boolean {
  if (alertType !== 'road_closure' || !routeTitle || !alertTitle) return false;
  const kind = routeRoadKind(routeTitle);
  if (!kind) return false;
  const alertLower = alertTitle.toLowerCase();
  if (!ROAD_KINDS.find((k) => k.kind === kind)!.re.test(alertLower)) return false;
  const stems = routePlaceStems(routeTitle);
  if (stems.length === 0) return false;
  return words(alertTitle).some((w) => stems.some((s) => w.startsWith(s)));
}
