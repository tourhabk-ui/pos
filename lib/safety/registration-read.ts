/**
 * Кто вправе ЧИТАТЬ регистрацию маршрута целиком (ФИО и телефоны группы,
 * экстренный контакт, PDF заявления в МЧС).
 *
 * Проверка безопасности 29.09 (#2073): GET /api/safety/register/[id] отдавал
 * всё это любому залогиненному, знающему UUID. Правило чтения отдельно от
 * `registration-gate`: там — право ПОСТАВИТЬ ОТМЕТКУ («вернулись»,
 * «на маршруте»), и второй ключ (телефон руководителя) у него законен —
 * контакт знает номер. Здесь ключ по телефону не годится: получив номер
 * руководителя, нельзя получать номера всей группы.
 *
 * Читает владелец регистрации и администратор. Регистрация без аккаунта
 * (`user_id` NULL) получает заявление сразу при создании — читать её потом
 * по UUID не может никто, кроме администратора.
 */

export interface Reader {
  userId: string;
  role: string;
}

export function canReadRegistration(reader: Reader, ownerUserId: string | null): boolean {
  if (reader.role === 'admin') return true;
  return ownerUserId !== null && ownerUserId === reader.userId;
}
