/** Слова в названии места, по которым оно считается лежбищем или местом скопления. */
export const MARINE_PLACE_PATTERN = /лежбищ|сивуч|морж|калан/i;

/**
 * Место — про морских млекопитающих? Только по названию: у каталога нет
 * отдельного признака, а гадать по типу нельзя. Ложное «нет» лишь не добавит
 * блок правил; ложное «да» добавит строку правил к месту, где они не нужны, —
 * поэтому список слов узкий и явный.
 */
export function isMarineMammalPlace(name: string | null | undefined): boolean {
  return !!name && MARINE_PLACE_PATTERN.test(name);
}

const fmt = (n: number) => n.toLocaleString('ru-RU');

