/**
 * lib/safety/warning-system-test.ts — плановая проверка систем оповещения.
 *
 * Решение владельца 08.10 (разведданные Evo Judge, #1428): туриста нужно
 * заранее предупредить о проверке сирен и сигнала «Внимание всем!», чтобы
 * учебную сирену не приняли за тревогу. Обратная ошибка опаснее: человек,
 * которому однажды сказали «это проверка», может не поверить настоящей сирене.
 * Поэтому руководство к типу говорит про ВРЕМЯ: проверка — только в
 * объявленное окно, вне его сирена настоящая (lib/safety/alert-guidance).
 *
 * До этой правки такие посты МЧС не доходили ни до кого: если в тексте была
 * «тренировка», фильтр учений выбрасывал пост, а без неё он не подходил ни
 * под одну категорию и отбрасывался как «не интересно».
 *
 * Исходов три:
 *   - `planned` — проверка объявлена впереди: тревога `warning_test`,
 *     severity 0. Это не опасность, она не меняет статус края и вердикт
 *     маршрута и не шлёт пуш, но видна в ленте и у агентов;
 *   - `report`  — отчёт о прошедшей проверке: в ленту не идёт;
 *   - `null`    — пост не о проверке оповещения.
 *
 * Сторож: tests/unit/warning-system-test.test.ts.
 */

const MONTHS: Record<string, number> = {
  января: 0, февраля: 1, марта: 2, апреля: 3, мая: 4, июня: 5,
  июля: 6, августа: 7, сентября: 8, октября: 9, ноября: 10, декабря: 11,
};

/** Слова проверки системы оповещения. Текст — в нижнем регистре. */
const TEST_RE = new RegExp([
  // «проверка (комплексная, техническая) (готовности) (региональной) системы оповещения»
  'провер[а-яё]*\\s+(?:[а-яё-]+\\s+){0,4}систем[а-яё]*\\s+(?:[а-яё-]+\\s+){0,3}оповещени',
  // «систем(ы) оповещения ... будут проверены / пройдёт проверка»
  'систем[а-яё]*\\s+(?:[а-яё-]+\\s+){0,3}оповещени[а-яё]*[\\s\\S]{0,80}провер',
  // «включение (электро)сирен», «запуск сирен»
  '(?:включени|запуск)[а-яё]*\\s+(?:[а-яё-]+\\s+){0,2}(?:электро)?сирен',
  // сигнал «Внимание всем!» в связке с проверкой — отдельно от сирен
  'внимание\\s+всем[\\s\\S]{0,120}провер|провер[\\s\\S]{0,120}внимание\\s+всем',
  'расцо|ксэон',
].join('|'));

/** Пост отчитывается о прошедшей проверке, а не объявляет её. */
const REPORT_RE = /(^|[^а-яё])(прошл[аи]|проведен[аы]|состоял[аи]сь|провели|завершил[аи]сь)(?![а-яё])/;
const FUTURE_RE = /пройд[её]т|состоится|будет провед|будут провер|будет провер|запланирован|планиру|проведут|включат|прозвуч/;

export type WarningTestKind = 'planned' | 'report';

export function warningSystemTest(text: string): WarningTestKind | null {
  const t = text.toLowerCase();
  if (!TEST_RE.test(t)) return null;
  if (REPORT_RE.test(t) && !FUTURE_RE.test(t)) return 'report';
  return 'planned';
}

/** Срок, если дата проверки в тексте не найдена: объявляют за день-два. */
export const WARNING_TEST_FALLBACK_HOURS = 72;
/** Дальше двух недель дата скорее не про эту проверку. */
const MAX_AHEAD_HOURS = 14 * 24;

/**
 * Сколько часов от публикации держать объявление: до конца названного дня по
 * Камчатке (UTC+12, 12:00 UTC того же числа). Дата — первая «N месяца» в
 * тексте. Не нашли или дальше двух недель — запасной срок. Названный день уже
 * прошёл — `null`: объявлять нечего.
 */
export function warningTestHours(text: string, publishedAt: Date): number | null {
  const pub = publishedAt.getTime();
  if (!Number.isFinite(pub)) return WARNING_TEST_FALLBACK_HOURS;
  const m = text.toLowerCase().match(
    /(?:^|[^\d])(\d{1,2})\s+(января|февраля|марта|апреля|мая|июня|июля|августа|сентября|октября|ноября|декабря)/,
  );
  if (!m) {
    // «Сегодня в 10:40», «завтра» — день считается от публикации по Камчатке.
    const rel = /(^|[^а-яё])(сегодня|завтра)(?![а-яё])/.exec(text.toLowerCase());
    if (!rel) return WARNING_TEST_FALLBACK_HOURS;
    const local = new Date(pub + 12 * 3_600_000);
    const endToday = Date.UTC(local.getUTCFullYear(), local.getUTCMonth(), local.getUTCDate(), 12, 0, 0);
    const relEnd = endToday + (rel[2] === 'завтра' ? 86_400_000 : 0);
    return Math.max(1, Math.ceil((relEnd - pub) / 3_600_000));
  }
  const day = Number(m[1]);
  const month = MONTHS[m[2]];
  if (day < 1 || day > 31 || month === undefined) return WARNING_TEST_FALLBACK_HOURS;
  let year = publishedAt.getUTCFullYear();
  let end = Date.UTC(year, month, day, 12, 0, 0);
  // «1 января», опубликовано 30 декабря — следующий год.
  if (end < pub - 30 * 86_400_000) {
    year += 1;
    end = Date.UTC(year, month, day, 12, 0, 0);
  }
  const hours = (end - pub) / 3_600_000;
  if (hours <= 0) return null;
  if (hours > MAX_AHEAD_HOURS) return WARNING_TEST_FALLBACK_HOURS;
  return Math.ceil(hours);
}
