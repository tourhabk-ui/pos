/**
 * Детерминированный детектор ЧП в сообщениях пользователя.
 *
 * Экстренный триггер Кузьмича живёт в промпте — это просьба к модели,
 * а не гарантия (внутреннее состояние LLM может расходиться с ответом,
 * а при отказе AI-конвейера промпт не работает вовсе). Этот модуль —
 * серверная страховка: при признаках ЧП телефоны 112/МЧС добавляются
 * к ответу независимо от того, что сказала (или не сказала) модель.
 *
 * Баланс настроен в сторону точности: ложное срабатывание — шумный
 * SOS-блок на невинном вопросе, ложный пропуск подстрахован промптом.
 * Поэтому «опасные» слова, встречающиеся в информационных вопросах
 * (медведь, лавина, камнепад), требуют контекста угрозы в той же фразе.
 */

export type EmergencyCategory =
  | 'lost'
  | 'injury'
  | 'bear'
  | 'ice'
  | 'avalanche'
  | 'group_missing'
  | 'freezing'
  | 'distress';

export interface EmergencyDetection {
  detected: boolean;
  categories: EmergencyCategory[];
}

// Внутри одной фразы (без границы предложения) — иначе «медведи. А какой
// маршрут рядом?» склеивается в ложное срабатывание.
const PHRASE = '[^.!?\\n]*';

// \b в JS не знает кириллицу (\w = [A-Za-z0-9_]) — границы слов делаем
// lookaround'ами. B — «здесь не середина слова».
const B = '(?<![а-яёa-z0-9])';
const E = '(?![а-яёa-z0-9])';
const re = (pattern: string) => new RegExp(`${B}(?:${pattern})${E}`, 'i');

const CATEGORY_PATTERNS: Record<EmergencyCategory, RegExp[]> = {
  lost: [
    re('потерял(ся|ась|ись)'),
    re('заблудил(ся|ась|ись)'),
    re('сбил(ся|ась|ись) с (тропы|маршрута|пути)'),
    re('не (знаю|понимаю),? где (я|мы|нахожусь|находимся)'),
  ],
  injury: [
    re('(травм|травмирован|перелом|вывих|кровотеч|обморожен|обморозил)[а-яё]*'),
    re('сломал[аи]? (ногу|руку|ребро|лодыжку)'),
    re('(идёт|течёт|хлещет) кровь'),
    re('без сознания'),
    re('подвернул[аи]? ногу'),
  ],
  bear: [
    re(`медвед[^.!?\\n]*?(рядом|близко|напал|атаку|преследу|вышел (на|к)|идёт (к|на|за)|окружил|не уходит)`),
    re(`(рядом|близко|напал|атаковал|преследует)${PHRASE}медвед[а-яё]*`),
  ],
  ice: [
    re('провалил(ся|ась|ись)'),
    re('под л(ё|е)д'),
    re(`л(ё|е)д${PHRASE}(трещит|треснул|проваливается|тонк[а-яё]*)`),
  ],
  avalanche: [
    re(`лавин[^.!?\\n]*?(сошла|сходит|накрыло|попал|унесло|засыпало)`),
    re(`(попал[аи]?|накрыло|засыпало|унесло)${PHRASE}лавин[а-яё]*`),
    re(`камнепад${PHRASE}(попал|накрыло|ранил|идёт)`),
    re(`(попал[аи]?|накрыло|ранило)${PHRASE}камнепад[а-яё]*`),
  ],
  group_missing: [
    re(`(группа|муж|жена|сын|дочь|друг|подруга|товарищ|напарник)${PHRASE}не вернул(ся|ась|ись)`),
    re(`не вернул(ся|ась|ись)${PHRASE}(группа|муж|жена|сын|дочь|друг|подруга|с маршрута|с восхождения)`),
    re('пропал[аи]? (группа|человек|турист|муж|жена|сын|дочь|друг)'),
  ],
  freezing: [
    re('замерза(ю|ем|ет)'),
    re('переохлаждение'),
    re(`застигла${PHRASE}(пурга|метель|буря|непогода)`),
    re(`(пурга|метель|буря)${PHRASE}(застигла|накрыла|не можем идти)`),
  ],
  distress: [
    re('спасите'),
    re('sos'),
    re('терплю бедствие'),
    re('(случил(ось|ась)|произошл[оа]) (чп|беда|несчастный случай)'),
    re('нужна (срочная|экстренная) помощь'),
    re('вызовите (спасателей|мчс|скорую)'),
  ],
};

const CATEGORY_ADVICE: Record<EmergencyCategory, string> = {
  lost: 'Оставайтесь на месте, экономьте заряд телефона, по возможности выйдите на открытое место — так вас быстрее найдут.',
  injury: 'Остановите кровотечение давлением на рану, утеплите пострадавшего, не перемещайте его при подозрении на травму позвоночника.',
  bear: 'Не бегите и не поворачивайтесь спиной. Говорите громко и низким голосом, медленно отходите, увеличивая дистанцию.',
  ice: 'Раскиньте руки на кромку льда, выбирайтесь в ту сторону, откуда шли, затем откатитесь от полыньи, не вставая.',
  avalanche: 'Не выходите на лавиноопасный склон повторно. Если кого-то засыпало — запомните точку исчезновения и начинайте поиск оттуда.',
  group_missing: 'Сообщите МЧС маршрут, контрольное время и число людей в группе. Не начинайте самостоятельный поиск в темноте.',
  freezing: 'Ищите укрытие от ветра, утеплитесь всем что есть, двигайте конечностями. Не садитесь на снег и камни без изоляции.',
  distress: 'Сообщите спасателям ваши координаты или заметные ориентиры и число людей рядом с вами.',
};

/** Ищет признаки чрезвычайной ситуации в тексте пользователя. */
export function detectEmergency(text: string): EmergencyDetection {
  if (!text || text.length < 4) return { detected: false, categories: [] };
  const categories: EmergencyCategory[] = [];
  for (const [category, patterns] of Object.entries(CATEGORY_PATTERNS) as [EmergencyCategory, RegExp[]][]) {
    if (patterns.some((re) => re.test(text))) categories.push(category);
  }
  return { detected: categories.length > 0, categories };
}

/**
 * Готовый SOS-блок для префикса к ответу ассистента. Обычный текст —
 * рендерится и в веб-чате (whitespace-pre-wrap), и в Telegram/MAX.
 */
export function buildSosBlock(categories: EmergencyCategory[]): string {
  const lines = [
    'ЕСЛИ ЭТО ЧРЕЗВЫЧАЙНАЯ СИТУАЦИЯ:',
    'Звоните 112 — работает без SIM-карты при наличии любой сети.',
    'МЧС Камчатки: 8-415-2-11-05-05. Кнопка SOS: vedarai.ru/sos',
  ];
  for (const category of categories.slice(0, 3)) {
    lines.push(CATEGORY_ADVICE[category]);
  }
  return lines.join('\n');
}

/**
 * Добавляет SOS-блок к ответу, если в вопросе есть признаки ЧП, а ответ
 * ещё не содержит экстренных телефонов (модель могла дать их сама).
 */
export function withSosBlock(answer: string, userText: string): { text: string; emergency: boolean } {
  const detection = detectEmergency(userText);
  if (!detection.detected) return { text: answer, emergency: false };
  if (answer.includes('112')) return { text: answer, emergency: true };
  return { text: `${buildSosBlock(detection.categories)}\n\n${answer}`, emergency: true };
}
