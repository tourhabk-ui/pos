/**
 * lib/safety/profile-source.ts — ЧТО МОЖНО ГОВОРИТЬ ПРО БЕЗОПАСНОСТЬ МЕСТА.
 * Одно правило на всю платформу.
 *
 * ── Почему это существует ─────────────────────────────────────────────────
 *
 * Слой безопасности мест завела миграция 070 одним запросом, выводя всё из
 * `location_type`: вулкан — «лавины, камнепад, термальные, высота», сложность
 * 4, лимит 30 человек в сутки; горячий источник — «термальные, химические»,
 * лимит 100. Ни одно из этих значений не измерено.
 *
 * Дальше эти значения расходятся по поверхностям как ФАКТЫ: бейджи в блоке
 * «Что знать» на карточке места (§9), строка «Лимит посещения — 30 человек в
 * сутки» рядом с высотой, фразы Кузьмича («Есть лавинная опасность»), PDF,
 * который человек берёт в поле. Чем дальше от базы, тем сильнее звучит
 * утверждение и тем меньше видно, что за ним ничего нет.
 *
 * Счёт уже выставляли поимённо: миграции 972-974 снимали с Сопки Никольской —
 * стометрового холма с городским парком в центре Петропавловска — лавины,
 * камнепад, термальные поля и высотную болезнь. Четыре ложных утверждения из
 * одного шаблона, на платформе, которая существует ради безопасности.
 *
 * ── Правило ───────────────────────────────────────────────────────────────
 *
 * Миграция 1036 записала происхождение строки в `profile_source`. Значение,
 * доказанно пришедшее шаблоном (`type_template`), НЕ ПРОИЗНОСИТСЯ как факт:
 * поверхность говорит «у нас не записано» — это уже принятый на карточке
 * способ отвечать про сложность и расстояние до медпомощи (§4.0, третье
 * состояние).
 *
 * Прячется только доказанное: строка, у которой хоть одно поле отличается от
 * шаблона, считается `unknown` и показывается как раньше. Ошибка в эту
 * сторону стоит надписи «не записано» вместо верного значения; ошибка в
 * другую — человека, поверившего лавинам в городском парке.
 *
 * Правило живёт ЗДЕСЬ, а не на каждом экране: слова об опасностях уже
 * расходились по шести файлам (см. шапку `hazard-labels.ts`), и правило,
 * написанное шесть раз, — это шесть правил.
 *
 * Не трогаются поля, которых в шаблоне не было: высота, расстояние до
 * медпомощи, требование спутникового связиста, даты открытия. Их шаблон не
 * выдумывал, и молчать о них было бы своей выдумкой наоборот.
 */

/** Словарь происхождения. Расширять — вместе с производителем (§10.09). */
export const SAFETY_PROFILE_SOURCES = ['type_template', 'manual', 'unknown'] as const;
export type SafetyProfileSource = (typeof SAFETY_PROFILE_SOURCES)[number];

/** Неизвестное значение колонки — тоже «не установлено», а не «шаблон». */
export function asProfileSource(raw: unknown): SafetyProfileSource | null {
  if (typeof raw !== 'string') return null;
  return (SAFETY_PROFILE_SOURCES as readonly string[]).includes(raw)
    ? (raw as SafetyProfileSource)
    : null;
}

/**
 * Можно ли произносить значения профиля как факты о месте.
 *
 * `null` (источник не записан) — МОЖНО: это старые строки и строки будущих
 * писателей, про которые мы не знаем ничего плохого. Запрет только на
 * доказанный шаблон.
 */
export function mayStateAsFact(source: SafetyProfileSource | null): boolean {
  return source !== 'type_template';
}

/** Поля, которые выдумывал шаблон 070/0645 — и только они. */
export interface TemplatedSafetyFields {
  hazardTypes: string[];
  capacityPerDay: number | null;
  optimalGroupSize: number | null;
  difficultyLevel: number | null;
  terrainType: string | null;
}

/**
 * Вычистить из профиля то, что пришло шаблоном.
 *
 * Возвращает НОВЫЙ объект: вызывающий не обязан помнить, какие именно поля
 * шаблонные, и не может забыть одно из пяти.
 */
export function honestSafetyFields<T extends TemplatedSafetyFields>(
  fields: T,
  source: SafetyProfileSource | null,
): T {
  if (mayStateAsFact(source)) return fields;
  return {
    ...fields,
    hazardTypes: [],
    capacityPerDay: null,
    optimalGroupSize: null,
    difficultyLevel: null,
    terrainType: null,
  };
}

/**
 * Загрузка места по шкале 1-5, прочитанная честно.
 *
 * До миграции 1100 у всех строк стоял DEFAULT 0, производителя у колонки нет
 * ни одного, а единственный читатель отвечал на ноль зелёным «Свободно» —
 * рядом со временем последней проверки тревог, из-за чего выдумка выглядела
 * свежим измерением. Ноль и всё, что вне шкалы, — «не измеряли».
 */
export function crowdsOnScale(raw: unknown): number | null {
  const n = typeof raw === 'number' ? raw : Number(raw);
  if (!Number.isFinite(n)) return null;
  const i = Math.trunc(n);
  return i >= 1 && i <= 5 ? i : null;
}
