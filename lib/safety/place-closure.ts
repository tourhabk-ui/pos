/**
 * «Закрыто» в попапе точки на карте — онлайн и в скачанном пакете.
 *
 * Повод — issue #2079 (29.09): статус `is_open` у точки был, карточка точки
 * его показывала, а карта — нет. В попапе стоял только список ограничений
 * (`active_alerts`), и точка, закрытая администратором по сводке парка или
 * МЧС, выглядела на карте как любая другая.
 *
 * Закрытие ставится ПЕРВЫМ в блок ограничений: в поле «закрыто» решает
 * больше любой подробности. `null` — статус не записан; это не «открыто»,
 * но и не повод писать «закрыто», поэтому список не меняется.
 */

export const CLOSED_LABEL = 'Закрыто';

export function withClosure(restrictions: readonly string[], isOpen: boolean | null | undefined): string[] {
  return isOpen === false ? [CLOSED_LABEL, ...restrictions] : [...restrictions];
}
