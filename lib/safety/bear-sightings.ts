/**
 * lib/safety/bear-sightings.ts
 *
 * Наблюдения медведя, сообщённые туристами, — единственный источник медвежьих
 * зон геофенса. Один на всех потребителей.
 *
 * ── Почему источник именно этот ────────────────────────────────────────────
 *
 * `ZoneHazard` объявляет род `wildlife` с самого начала, а производил его
 * никто: `GET /api/safety/geofence-zones` выдавал вулканы, источники, гейзеры
 * и цунами-зоны. Объявленный исход без источника (§4) — тот же дефект, что
 * тип тревоги `avalanche`, который лента пропускала, инструкция ждала, а
 * классификатор не выдавал ни разу (#1763).
 *
 * Производить его можно ровно из того, что в базе есть. Тревога МЧС о
 * медведях называет СЕЛО словами («в селе Соболево введён режим повышенной
 * готовности»), координат в ней нет, и выводить их из текста значило бы
 * рисовать зону опасности по догадке. А `trail_reports` — это координата,
 * время и ручная модерация владельца.
 *
 * ── Наблюдение — не зона ───────────────────────────────────────────────────
 *
 * Медведь, которого видели во вторник, не создаёт вокруг себя границу. Отсюда
 * три ограничения, и каждое названо, а не подразумевается:
 *
 *  1. **Срок годности.** Зона живёт столько же, сколько точка на радаре, —
 *     окно одно на обоих (`SIGHTING_WINDOW_DAYS`). Дальше `expiresAt` гасит
 *     её и в кэше телефона: кэш зон намеренно переживает любую давность
 *     («вулкан не переедет за 10 минут»), и без срока наблюдение
 *     предупреждало бы вечно.
 *  2. **Уровень — `warning`, не `danger`.** Уровень геофенса упорядочивает
 *     ЖИВЫЕ тревоги в поле, и рядом с ним стоит вулкан с красным кодом
 *     KVERT. Непроверенное наблюдение туриста не должно заслонять его собой;
 *     роут geofence-zones бережёт себя ровно от этого в случае потухших
 *     сопок. На радаре главной у медведя `danger`, и это не расхождение:
 *     там уровень — цвет точки на карте, здесь — очередь тревог.
 *  3. **Подпись говорит, чьё это слово и какой оно давности.** Тем же
 *     языком, каким радар уже это говорит.
 *
 * Радиус — не утверждение о медведе, а расстояние, с которого об этом
 * наблюдении стоит сказать идущему. Полтора-два километра пешком — это
 * примерно полчаса хода вперёд. Биологии в этом числе нет, и менять его —
 * решение владельца, а не побочный эффект правки.
 */
import { alertGuidance } from './alert-guidance';
import type { GeofenceZone } from './geofence';

/**
 * Окно свежести наблюдения. Семь суток взяты не заново: столько же живёт
 * точка на радаре главной (`app/_home/data.ts`), и её подпись объясняет
 * почему — «медведь, замеченный неделю назад, уже не точка на радаре, а
 * свойство района». Два окна разошлись бы молча, и карта с геофенсом
 * говорили бы о разной Камчатке.
 */
export const SIGHTING_WINDOW_DAYS = 7;

export const SIGHTING_WINDOW_MS = SIGHTING_WINDOW_DAYS * 24 * 60 * 60 * 1_000;

/** См. шапку: расстояние оповещения, а не радиус зверя. */
export const SIGHTING_RADIUS_M = 2_000;

/**
 * Предикат свежего наблюдения, прошедшего модерацию. `$1` — окно в сутках.
 *
 * Интервал приходит параметром (`INTERVAL '1 day' * $1`), а не склейкой:
 * см. `tests/unit/sql-interval-not-concatenated.test.ts`.
 */
export const FRESH_APPROVED_SQL = `status = 'approved'
   AND created_at > NOW() - INTERVAL '1 day' * $1`;

export interface BearSighting {
  id: string;
  lat: number;
  lng: number;
  /** Может быть пустым у старых записей — зона тогда без цитаты, но с возрастом. */
  text: string | null;
  /** Часов с момента наблюдения. Считает база, а не клиент. */
  hoursAgo: number;
}

/** «3 ч назад» / «2 дн назад» — та же форма, что на радаре. */
export function sightingAgeLabel(hoursAgo: number): string {
  return hoursAgo < 24
    ? `${Math.max(1, Math.round(hoursAgo))} ч назад`
    : `${Math.round(hoursAgo / 24)} дн назад`;
}

/**
 * Зона из наблюдения. Чистая функция: её и проверяют, роут только подаёт
 * строки.
 *
 * `expiresAt` считается от времени НАБЛЮДЕНИЯ, а не от времени ответа: иначе
 * каждое обновление зон продлевало бы старое наблюдение ещё на неделю, и
 * зона, однажды появившись, не исчезла бы никогда.
 */
export function bearSightingZone(s: BearSighting, now: number = Date.now()): GeofenceZone {
  const observedAt = now - s.hoursAgo * 3_600_000;
  const note = (s.text ?? '').trim().slice(0, 90);
  return {
    id: `bear_${s.id}`,
    name: 'Наблюдение медведя',
    lat: s.lat,
    lng: s.lng,
    radiusM: SIGHTING_RADIUS_M,
    hazard: 'wildlife',
    level: 'warning',
    // Что делать — из общего справочника, а не своими словами. Медвежья
    // тактика на платформе одна, и держит её сторож bear-protocol-unified:
    // расхождение в safety-контенте стоит жизни, и расходилось уже дважды.
    // Пустая цитата не подменяется придуманной: «здесь видели медведя» без
    // подробностей честнее сочинённой подробности (§4.0).
    message:
      `Здесь видели медведя${note ? `: ${note}` : ''} · ${sightingAgeLabel(s.hoursAgo)} · ` +
      `наблюдение туриста, прошло модерацию. ${alertGuidance('bear').steps[0]}`,
    expiresAt: observedAt + SIGHTING_WINDOW_MS,
  };
}
