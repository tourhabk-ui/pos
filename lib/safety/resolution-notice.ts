/**
 * Отбой — сообщение о том, что опасность СНЯТА, а не о том, что она есть.
 *
 * `external_alerts` пока не различает вид записи колонкой (issue #1984 —
 * заведение `alert_kind`/`is_resolution` требует миграции и отдельного
 * решения о том, как её проставлять на ingest). До тех пор отбой узнаётся
 * по формулировке: тревога объявляет явление («паводковая обстановка
 * ожидается»), отбой — его окончание («стабилизировалась», «снят режим»).
 *
 * Используется, чтобы отбой не занимал строку «Наиболее значимое» в
 * `safety_status` — самое заметное место ответа, которое турист читает
 * первым, — вместо реальной действующей тревоги.
 */
/**
 * Источник строки — один на JS-проверку и на SQL (`~*`, регистр не важен
 * там и там). Две нормализации одного правила — ровно тот класс, из-за
 * которого §12 писался: разойдутся при первой правке.
 *
 * ── Отрицание — не отбой ────────────────────────────────────────────────
 *
 * Первая редакция (#1984) искала слово окончания и не смотрела на слово
 * перед ним. «Паводковая обстановка не стабилизировалась», «Угроза не
 * устранена», «Не снят режим» читались отбоем, и ДЕЙСТВУЮЩАЯ тревога
 * уходила вниз «Наиболее значимого» — ровно та подмена, против которой
 * правило заводилось, только с обратным знаком. Отсюда `(?<!не\s)` перед
 * глаголами окончания и отказ отбою, который только обещан («Отбой угрозы
 * цунами будет объявлен дополнительно» — это тревога, отбоя ещё нет).
 * Тот же приём у `tsunamiStatus` в `seismic-parser.ts`.
 *
 * «миновал» отрицанием не защищается: «не миновала» не совпадает с
 * «опасность миновал» / «угроза миновал» — между ними стоит «не».
 *
 * «Отмен…» в правило не входит намеренно: «Авиарейсы отменены из-за
 * метели» — тревога, а не отбой.
 *
 * Просмотр назад и вперёд PostgreSQL понимает (ARE, с 9.6); шаблон сверен
 * на PostgreSQL 16 и в JS на одном наборе фраз — ответы совпали.
 */
/**
 * Предупреждение, само объявившее о своём окончании, — не «улика», а слово
 * автора (04.10, #2195).
 *
 * Верхней строкой ленты сайта и `safety_status` стояло «Экстренное
 * предупреждение по возможному подъёму уровней воды на реках южной половины
 * края прекратило свое действие» — паводком на 120 часов. Приём узнал явление
 * («уровней воды») и не спросил, объявлено оно или закончилось.
 *
 * Широкое правило выше остаётся уликой: «стабилизировалась обстановка» в
 * одном округе ещё не значит, что в соседнем всё кончилось. Здесь же предмет
 * назван самим текстом — ПРЕДУПРЕЖДЕНИЕ — и сказано, что его действие
 * прекращено. Поэтому только эта форма снимает запись на приёме и в чистке;
 * отрицание («не прекратило») её не снимает.
 */
export const WARNING_ENDED_SQL_PATTERN =
  'предупреждени[а-яё]*(?:\\s+[^.]{0,160})?\\s(?<!не\\s)прекратил[а-яё]*\\s+(?:сво[её]\\s+)?действи' +
  '|(?<!не\\s)прекращен[а-яё]*\\s+действи[а-яё]*\\s+[^.]{0,40}предупреждени' +
  '|действи[а-яё]*\\s+[^.]{0,40}предупреждени[а-яё]*\\s+(?<!не\\s)прекращен';

export const RESOLUTION_SQL_PATTERN =
  '(?<!не\\s)(стабилизировал|нормализовал|ликвидирован|устран[её]н)' +
  '|(?<!не\\s)снят[а-яё]*\\s+(режим|угроз|предупрежд)' +
  '|(?<!не\\s)отбой(?![^.]{0,40}(будет|последует|дополнительно|позже))' +
  '|опасност[а-яё]*\\s+миновал|угроза\\s+миновал' +
  `|${WARNING_ENDED_SQL_PATTERN}`;

const RESOLUTION_PATTERN = new RegExp(RESOLUTION_SQL_PATTERN, 'i');
const WARNING_ENDED_PATTERN = new RegExp(WARNING_ENDED_SQL_PATTERN, 'i');

export function isResolutionNotice(title: string | null | undefined): boolean {
  if (!title) return false;
  return RESOLUTION_PATTERN.test(title);
}

/** Предупреждение объявило о своём окончании (см. WARNING_ENDED_SQL_PATTERN). */
export function isWarningEnded(title: string | null | undefined): boolean {
  if (!title) return false;
  return WARNING_ENDED_PATTERN.test(title);
}

/**
 * Прогноз, пересказанный в прошедшем времени: «Прогнозировался подъём уровней
 * воды на реках южной половины края» (04.10, #2195, лента сайта). Это отчёт о
 * том, что предупреждение БЫЛО, а не предупреждение: срок прогноза прошёл, и
 * действующая угроза в тексте не названа.
 *
 * Судится только начало заголовка: «как и прогнозировалось, вода продолжает
 * прибывать» — тревога, и прошедшее время там стоит не главным глаголом.
 * Взгляд вперёд или действие в настоящем рядом отменяют вердикт.
 */
const PAST_FORECAST_HEAD = /^\s*(?:ранее\s+)?прогнозировал(?:ся|ась|ось|ись)(?![а-яё])/i;
const PRESENT_OR_FORWARD = /ожидает|прогнозирует|сохраняет|продолжает|возможн|не рекоменд|запрещ|воздерж|будьте|опасност|действует/i;

export function isPastForecast(title: string | null | undefined, description = ''): boolean {
  if (!title || !PAST_FORECAST_HEAD.test(title)) return false;
  return !PRESENT_OR_FORWARD.test(`${title} ${description}`);
}
