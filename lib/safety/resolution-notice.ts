/**
 * Отбой — сообщение о том, что опасность СНЯТА, а не о том, что она есть.
 *
 * `external_alerts` пока не различает вид записи колонкой (issue #1984 —
 * заведение `alert_kind`/`is_resolution` требует миграции и отдельного
 * решения о том, как её проставлять на ingest). До тех пор отбой узнаётся
 * по формулировке: тревога объявляет явление («паводковая обстановка
 * ожидается»), отбой — его окончание («стабилизировалась», «снят режим»).
 *
 * Используется, чтобы отбой не занимал строку «Наиболее значимое» в
 * `safety_status` — самое заметное место ответа, которое турист читает
 * первым, — вместо реальной действующей тревоги.
 */
/**
 * Источник строки — один на JS-проверку и на SQL (`~*`, регистр не важен
 * там и там). Две нормализации одного правила — ровно тот класс, из-за
 * которого §12 писался: разойдутся при первой правке.
 *
 * ── Отрицание — не отбой ────────────────────────────────────────────────
 *
 * Первая редакция (#1984) искала слово окончания и не смотрела на слово
 * перед ним. «Паводковая обстановка не стабилизировалась», «Угроза не
 * устранена», «Не снят режим» читались отбоем, и ДЕЙСТВУЮЩАЯ тревога
 * уходила вниз «Наиболее значимого» — ровно та подмена, против которой
 * правило заводилось, только с обратным знаком. Отсюда `(?<!не\s)` перед
 * глаголами окончания и отказ отбою, который только обещан («Отбой угрозы
 * цунами будет объявлен дополнительно» — это тревога, отбоя ещё нет).
 * Тот же приём у `tsunamiStatus` в `seismic-parser.ts`.
 *
 * «миновал» отрицанием не защищается: «не миновала» не совпадает с
 * «опасность миновал» / «угроза миновал» — между ними стоит «не».
 *
 * «Отмен…» в правило не входит намеренно: «Авиарейсы отменены из-за
 * метели» — тревога, а не отбой.
 *
 * Просмотр назад и вперёд PostgreSQL понимает (ARE, с 9.6); шаблон сверен
 * на PostgreSQL 16 и в JS на одном наборе фраз — ответы совпали.
 */
export const RESOLUTION_SQL_PATTERN =
  '(?<!не\\s)(стабилизировал|нормализовал|ликвидирован|устран[её]н)' +
  '|(?<!не\\s)снят[а-яё]*\\s+(режим|угроз|предупрежд)' +
  '|(?<!не\\s)отбой(?![^.]{0,40}(будет|последует|дополнительно|позже))' +
  '|опасност[а-яё]*\\s+миновал|угроза\\s+миновал';

const RESOLUTION_PATTERN = new RegExp(RESOLUTION_SQL_PATTERN, 'i');

export function isResolutionNotice(title: string | null | undefined): boolean {
  if (!title) return false;
  return RESOLUTION_PATTERN.test(title);
}
