/**
 * SMS на 112 с экрана SOS — подпись кнопки и текст сообщения.
 *
 * Повод — проверка /sos на проде 21.11 (экран в машине): шаг «Что делать»
 * звал кнопку «Без интернета», а такой подписи на экране не было. Кнопка SMS
 * называлась «SMS с координатами (без интернета)» и появлялась только после
 * того, как нашлись координаты. Человек без голоса и без координат её не
 * видел вовсе, хотя SMS на 112 уходит и без них.
 *
 * Теперь кнопка есть всегда, подпись одна — та, что названа в шаге, а текст
 * без координат просит дописать ориентиры: дежурному нужно место, а не
 * адрес сайта. Сторож — tests/unit/sos-sms-button.test.tsx.
 */

/** Подпись кнопки — её же называет шаг «Что делать». */
export const SOS_SMS_LABEL = 'SMS на 112';

/** Шаг «Что делать» о SMS — с подписью кнопки слово в слово. */
export const SOS_SMS_STEP = `Нет голоса — отправь SMS кнопкой «${SOS_SMS_LABEL}»`;

/** Строка под подписью кнопки: что уйдёт в сообщении. */
export function sosSmsHint(hasCoords: boolean): string {
  return hasCoords
    ? 'Координаты уже в сообщении'
    : 'Координаты не определились — допишите в сообщении, где вы';
}

/** Текст SMS. Без координат — просьба дописать ориентиры, курсор в конце. */
export function sosSmsBody(coords: { lat: number; lng: number } | null): string {
  if (coords) {
    return `SOS! Мне нужна помощь. Мои координаты: ${coords.lat.toFixed(5)}, ${coords.lng.toFixed(5)} — vedarai.ru`;
  }
  return 'SOS! Мне нужна помощь. Координаты не определились. Где я: ';
}

/** Адрес ссылки SMS на 112. */
export function sosSmsHref(coords: { lat: number; lng: number } | null): string {
  return `sms:112?body=${encodeURIComponent(sosSmsBody(coords))}`;
}
