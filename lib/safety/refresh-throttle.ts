/**
 * Кнопка «обновить» ходит к чужим источникам — значит её надо придержать.
 *
 * Экран безопасности публичный: кнопку жмёт человек в поле, но нажать её
 * может кто угодно и сколько угодно раз. Без ограничителя один нетерпеливый
 * палец (или скрипт) превращается в поток запросов к wttr.in и USGS, а те
 * отвечают на это баном по адресу — и тогда данных не будет ни у кого,
 * включая того, кому они нужны на маршруте.
 *
 * Ограничитель НЕ обманывает: когда обращение к источнику придержано, ответ
 * приходит из кэша и честно помечен `from_cache`, с временем, когда источник
 * спрашивали на самом деле. Молчаливая подмена свежего ответа старым — это
 * ровно то, за что мы весь день ловили другие места (§4.0).
 *
 * Память процесса, а не БД: ограничение защищает ЧУЖОЙ сервис от нашего
 * инстанса, и переживать деплой ему незачем.
 */

const lastHit = new Map<string, number>();

/** Минимальный промежуток между настоящими обращениями к одному источнику. */
export const FRESH_MIN_INTERVAL_MS = 20_000;

/**
 * Можно ли сейчас идти к источнику. Разрешив, СРАЗУ засчитывает попытку:
 * два одновременных запроса не пройдут оба.
 */
export function allowFresh(key: string, minIntervalMs = FRESH_MIN_INTERVAL_MS, now = Date.now()): boolean {
  const prev = lastHit.get(key);
  if (prev !== undefined && now - prev < minIntervalMs) return false;
  lastHit.set(key, now);
  return true;
}

/** Когда к источнику ходили в последний раз; null — ни разу за жизнь процесса. */
export function lastFreshAt(key: string): number | null {
  return lastHit.get(key) ?? null;
}

/** Только для тестов: забыть историю обращений. */
export function resetThrottle(): void {
  lastHit.clear();
}
