/**
 * Нерабочие праздничные дни по ст. 112 ТК РФ, «ММ-ДД». Даты закреплены
 * законом и от года не зависят, поэтому считаются без внешнего календаря.
 */
export const RU_FIXED_HOLIDAYS: ReadonlySet<string> = new Set([
  '01-01', '01-02', '01-03', '01-04', '01-05', '01-06', '01-07', '01-08',
  '02-23', '03-08', '05-01', '05-09', '06-12', '11-04',
]);

function isWorkingDay(d: Date): boolean {
  const wd = d.getUTCDay();
  if (wd === 0 || wd === 6) return false;
  const md = `${String(d.getUTCMonth() + 1).padStart(2, '0')}-${String(d.getUTCDate()).padStart(2, '0')}`;
  return !RU_FIXED_HOLIDAYS.has(md);
}

/**
 * Рабочих дней между двумя датами (не считая день начала маршрута).
 *
 * Выпадают суббота, воскресенье и праздники ст. 112 ТК РФ (с 10.11; до того
 * праздники не считались вовсе, и в январе срок выходил на неделю длиннее
 * правды). Переносы выходных постановлением Правительства на каждый год здесь
 * НЕ учтены: праздник, выпавший на выходной, переносится на будний день, и
 * этот будний день мы считаем рабочим. Значит настоящих рабочих дней может
 * оказаться МЕНЬШЕ, чем вернёт функция (рабочая суббота, наоборот, только
 * добавляет запаса), поэтому запас `registrationVerdict` остаётся.
 */
export function workingDaysBetween(from: Date, to: Date): number {
  const start = new Date(Date.UTC(from.getUTCFullYear(), from.getUTCMonth(), from.getUTCDate()));
  const end = new Date(Date.UTC(to.getUTCFullYear(), to.getUTCMonth(), to.getUTCDate()));
  if (end <= start) return 0;
  let days = 0;
  const cur = new Date(start);
  cur.setUTCDate(cur.getUTCDate() + 1);
  while (cur < end) {
    if (isWorkingDay(cur)) days += 1;
    cur.setUTCDate(cur.getUTCDate() + 1);
  }
  return days;
}

export type MchsVerdict = 'in_time' | 'tight' | 'too_late';

export interface MchsVerdictResult {
  verdict: MchsVerdict;
  workingDays: number;
  text: string;
}

/**
 * Успевает ли турист подать заявку к этой дате выхода.
 *
 * Три исхода, а не два, и средний — из-за переносов выходных: праздники ст.
 * 112 счёт уже вычитает, а дни, на которые их переносит постановление
 * Правительства, — нет. Запас в три рабочих дня покрывает самые длинные
 * переносы (майские); при таком остатке честный ответ — «может не хватить»,
 * а не «успеваете».
 */
export function registrationVerdict(startsAt: Date, now: Date): MchsVerdictResult {
  const workingDays = workingDaysBetween(now, startsAt);
  if (workingDays < MCHS_LEAD_WORKING_DAYS) {
    return {
      verdict: 'too_late',
      workingDays,
      text:
        `До выхода ${workingDays} раб. дн. — срок подачи в МЧС ` +
        `(${MCHS_LEAD_WORKING_DAYS} раб. дн.) уже не выдержать.`,
    };
  }
  if (workingDays < MCHS_LEAD_WORKING_DAYS + 3) {
    return {
      verdict: 'tight',
      workingDays,
      text:
        `До выхода ${workingDays} раб. дн. при норме ${MCHS_LEAD_WORKING_DAYS}. ` +
        'Впритык: переносы выходных в этот счёт не входят, подавайте сегодня.',
    };
  }
  return {
    verdict: 'in_time',
    workingDays,
    text: `До выхода ${workingDays} раб. дн. — срок подачи (${MCHS_LEAD_WORKING_DAYS} раб. дн.) выдерживается.`,
  };
}

