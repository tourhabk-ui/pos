/**
 * lib/safety/krai-south.ts — «южная половина края» в предупреждениях МЧС.
 *
 * ── Что случилось ──────────────────────────────────────────────────────────
 *
 * С 29.09 по 04.10 лента несла «Прогнозируется подъем уровней воды на реках
 * южной половины края», и разбор зон этой фразы не знал: запись ложилась с
 * пустыми зонами и не доходила НИ ДО ОДНОГО места (prod-check run 89) — ни
 * до Шивелуча, где ей не место (#2195), ни до Паратунки, где ей место.
 *
 * ── Решение владельца 04.10 ────────────────────────────────────────────────
 *
 * «По районам это юг Камчатки до Петропавловска». Четыре наши зоны этого не
 * выражают: западная тянется от Усть-Большерецка до Тигиля, Авачинская — от
 * Мутновского до Налычева. Поэтому охват — ШИРОТОЙ места, а не зоной: место
 * южнее северной окраины Петропавловска (KRAI_SOUTH_MAX_LAT) — в охвате.
 *
 * Метка `KRAI_SOUTH_ZONE` кладётся в affected_zones вместо настоящих зон и
 * читается зональной веткой ALERT_MATCH_SQL (alert-place-scope.ts) — одной
 * для мест и маршрутов. Место без широты не накрывается: «не измерили» ≠
 * «южнее» (§4.0).
 */

/** Метка охвата в affected_zones. Ни с одной настоящей зоной не совпадает. */
export const KRAI_SOUTH_ZONE = 'krai_south';

/**
 * Северная граница «юга до Петропавловска», градусы с. ш.: северная окраина
 * города (центр 53.02). Елизово (53.19) и Налычево (53.5) — за ней.
 */
export const KRAI_SOUTH_MAX_LAT = 53.10;

/**
 * «южной половины края», «южная часть Камчатского края», «на юге края /
 * Камчатки / полуострова», «реки юга Камчатки».
 */
const KRAI_SOUTH_RE = /южн[а-яё]*\s+(?:половин[а-яё]*|част[а-яё]*)\s+(?:камчатского\s+)?края|южн[а-яё]*\s+(?:половин[а-яё]*|част[а-яё]*)\s+(?:камчатки|полуострова)|на\s+юге\s+(?:камчатского\s+)?(?:края|камчатки|полуострова)|юга\s+камчатки/i;

export function namesKraiSouth(text: string): boolean {
  return KRAI_SOUTH_RE.test(text);
}
