/**
 * lib/db/like.ts — подстановочный шаблон для LIKE/ILIKE из чужой строки.
 *
 * ── Зачем ─────────────────────────────────────────────────────────────────
 *
 * Параметризация ($1) защищает от подмены ЗАПРОСА, но не от подмены ШАБЛОНА.
 * `%${q}%` с `q = '%'` превращается в `%%%` и совпадает со всем подряд; `_`
 * совпадает с любым одиночным символом. Инъекции SQL здесь нет — есть тихая
 * подмена смысла поиска, и снаружи она выглядит как «поиск работает странно».
 *
 * Найдено Evo Judge в `lib/kuzmich/gear-search.ts`: `args.query` приходит
 * аргументом инструмента Кузьмича, то есть его содержимое диктует человек в
 * переписке (и модель, которая этот аргумент составляет).
 *
 * ── Почему без ESCAPE-клаузы ──────────────────────────────────────────────
 *
 * У LIKE в PostgreSQL символ экранирования по умолчанию — обратная косая,
 * и отдельная `ESCAPE '\'` ничего не меняет. Экранируем сам `\` первым,
 * иначе он съел бы экранирование следующего за ним символа.
 *
 * ── Границы ───────────────────────────────────────────────────────────────
 *
 * Применено ТОЛЬКО там, где подстановка приходит от пользователя и шаблон
 * задуман как «содержит текст». Остальные ~20 файлов с ILIKE не переведены
 * скопом намеренно: часть из них ищет по маске осознанно, и замена вслепую
 * поломала бы поиск, не починив ничего. Каждое место — отдельное решение.
 */

/** Экранирует спецсимволы шаблона LIKE/ILIKE, оставляя текст как есть. */
export function escapeLike(value: string): string {
  return value.replace(/\\/g, '\\\\').replace(/%/g, '\\%').replace(/_/g, '\\_');
}

/** `%текст%` для поиска «содержит», где текст ищется буквально. */
export function containsPattern(value: string): string {
  return `%${escapeLike(value)}%`;
}
