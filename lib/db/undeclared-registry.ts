/**
 * Объявленные миграцией, но под сомнением: их объявление ССЫЛАЕТСЯ на таблицу,
 * которой на проде нет.
 *
 * ── Откуда взялось ─────────────────────────────────────────────────────────
 *
 * Замороженный список выше стережёт ОБЪЯВЛЕННОСТЬ: имя, к которому код
 * обращается, должно иметь `CREATE TABLE` в миграциях или baseline. Он ничего
 * не говорит о ПРИМЕНЁННОСТИ — и 01.09 нашёлся зазор между этими двумя вещами.
 *
 * Миграция 081 объявляет `reference_tours` и `composite_bookings`, и в самом
 * `CREATE TABLE` стоит `operator_id INT NOT NULL REFERENCES operators(id)`.
 * Таблицы `operators` на проде нет (перепись, прогон 2, канарейка видна), а
 * CREATE TABLE с внешним ключом на несуществующую таблицу не выполняется вовсе.
 *
 * ── Почему это ВОПРОС, а не вывод ──────────────────────────────────────────
 *
 * Два мира одинаково согласуются с кодом:
 *   1) 081 не применялась никогда — тогда обеих таблиц на проде нет, и код,
 *      который их читает, мёртв;
 *   2) 081 применилась, когда `operators` ещё существовала, а позже ту снесли
 *      через CASCADE — тогда таблицы живы, просто без внешнего ключа.
 *
 * Статикой их не различить: порядок событий в прошлом репозиторий не хранит.
 * Различает только прод, поэтому имена стоят здесь и попадают в перепись
 * отдельным множеством — не сливаясь с замороженным списком, у которого другой
 * смысл и другое правило выхода.
 */
