export type UndeclaredTable = (typeof UNDECLARED_TABLES)[number];

/** Исход переписи по одному пункту. `unknown` — «не смогли спросить», не «нет». */
export type RegistryState =
  | 'absent'
  | 'present_empty'
  | 'present_with_rows'
  | 'unknown';

export interface RegistryCensusRow {
  table: string;
  state: RegistryState;
  /** Строк в таблице. null — не считали (таблицы нет либо счёт не выполнился). */
  rows: number | null;
  /** Колонки с типами — материал для захвата DDL. Пусто, если таблицы нет. */
  columns: Array<{ name: string; type: string; nullable: boolean }>;
  /** Почему состояние `unknown`. Пусто у остальных. */
  reason?: string;
}
