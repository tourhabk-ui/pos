/**
 * Замороженный список таблиц вне реестра схемы + словарь их состояний.
 *
 * ── Почему список переехал сюда из теста ───────────────────────────────────
 *
 * Он был константой внутри `tests/unit/schema-coverage.test.ts`, и этого
 * хватало, пока его читал только сторож. Теперь его должен читать и прод:
 * перепись спрашивает базу, в каком состоянии каждый пункт. Держать два
 * списка нельзя — разойдутся, и перепись начнёт молчать ровно о том, что
 * сторож считает проблемой.
 *
 * Модуль намеренно БЕЗ файловых зависимостей: `lib/db/schema-coverage.ts`
 * читает диск (`readdirSync`, `execSync`) и на проде неработоспособен —
 * standalone-бандл едет без исходников.
 *
 * ── Почему исходов пять, а не два ──────────────────────────────────────────
 *
 * «Есть в списке» — не диагноз, а признание незнания. Разбор 31.08 показал,
 * что за одним пунктом стоят разные беды с разными способами закрытия, и
 * сваливать их в одно «не учтено» значит обречь следующего читающего повторить
 * весь разбор заново.
 *
 * Два состояния уже установлены фактами:
 *   `absent`          — таблицы на проде нет вовсе (`transfer_bookings`:
 *                       Watchdog получил 42P01). Код, который её читает, мёртв.
 *   `dead_file_only`  — таблица есть, DDL описан только в неприменяемом файле
 *                       `lib/database/*_schema.sql`. Их пятнадцать, и на прод
 *                       их не накатывает ничто: единственный читатель ради
 *                       исполнения — `scripts/migrate.js`, не подключённый ни
 *                       к одной npm-команде. Но НЕ мёртвые вовсе: их разбирает
 *                       `lib/database/schema-registry.ts` для гарда фантомных
 *                       колонок. Отсюда два разных смысла слова «объявлена»:
 *                       для гарда фантомов — да, для `schema-coverage` (только
 *                       `migrations/` + baseline) — нет. Расхождение намеренное
 *                       и стоило дорого 22.08: мёртвый файл ручался за живые
 *                       колонки `tour_availability`, и гард молчал на
 *                       `ta.tour_id` в двух местах.
 *
 * Три предложены владельцем как различимые исходы, которых перепись обязана
 * не смешивать:
 *   `present_empty`   — схема есть, жизни нет. Ни мёртвый код, ни живая
 *                       подсистема: судьбу пустой схемы решают отдельно.
 *   `drifted`         — есть, но колонки расходятся и с файлом, и с кодом.
 *                       Тогда источник истины ни файл, ни код — только прод,
 *                       и захват DDL обязателен. О таком дрейфе предупреждает
 *                       шапка миграции 713.
 *   `outside_registry`— есть, DDL нет нигде в репозитории. У схемы есть
 *                       история вне реестра, и пункт закрывается её
 *                       восстановлением, а не техникой.
 *
 * И шестой, обязательный по §4.0: `unknown` — спросить не смогли. Он не равен
 * `absent`: «таблицы нет» и «мы не дозвонились» — разные утверждения, и
 * сливать их значит повторить дефект, который весь этот разбор и породил.
 */

