/**
 * Заглушка в начале описания маршрута — снимается при показе.
 *
 * Описания, скачанные со стороннего сайта, начинаются с шаблона «Это Бухта
 * Русская в Камчатском крае. Место, которое стоит посмотреть.» (вариант —
 * «… в Камчатском крае — место, которое стоит посмотреть.»), а настоящий
 * текст идёт дальше. Аудит vedarai.ru 01.10: у 21 маршрута шаблон стал и
 * описанием в выдаче — metaDescription режет по концу предложения, и в
 * снипет попадала одна заглушка.
 *
 * Снимается только шаблон целиком и только в начале. «Это Зеленовские
 * озерки в Камчатском крае — природный комплекс…» — уже настоящий текст, он
 * остаётся. Ничего после заглушки нет — пустая строка: пустое описание
 * честнее шаблона (§4.0), подпись решает вызывающий.
 *
 * Тот же шаблон ловит валидатор постов канала (lib/notifications/
 * post-validation, FILLER_DESCRIPTION): там он запрещает вести на карточку.
 */
const FILLER_LEAD =
  /^\s*это\s+[^.\n]{2,80}?\s+в\s+камчатском\s+крае\s*(?:\.|[—–-])\s*мест[оа],?\s+котор[а-яё]*\s+стоит\s+(?:посмотреть|увидеть|посетить)\s*\.?/i;

export function stripFillerLead(text: string | null | undefined): string {
  if (!text) return '';
  if (!FILLER_LEAD.test(text)) return text;
  return text.replace(FILLER_LEAD, '').replace(/^\s+/, '');
}
