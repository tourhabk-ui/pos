/**
 * Обрезка текста для тесного места (попап на карте, подпись) — по границе
 * слова и с многоточием.
 *
 * Повод (02.09.2026, скрин владельца): попап карты у озера Синичкино кончался
 * на «…но дно илис» — `slice(0, 120)` резал по байту, и человек в поле читал
 * обрывок слова, не понимая, оборвался ли текст или так и написано. Обрыв
 * без знака выглядит как полный текст, а полный текст с обрывком слова —
 * как опечатка. Многоточие говорит правду: «дальше есть, но не влезло».
 *
 * Правила:
 *   - текст короче лимита возвращается как есть, без многоточия;
 *   - иначе режется по последнему пробелу до лимита, чтобы слово не рвалось;
 *     если пробела в пределах лимита нет (одно длинное слово) — режется по
 *     лимиту, но всё равно с многоточием;
 *   - висячая пунктуация перед многоточием («тишина, …») снимается.
 */
export function clipAtWord(text: string, max: number): string {
  const s = text.trim();
  if (s.length <= max) return s;
  const head = s.slice(0, max);
  const lastSpace = head.lastIndexOf(' ');
  const cut = lastSpace > 0 ? head.slice(0, lastSpace) : head;
  return `${cut.replace(/[\s,;:—–-]+$/u, '')}…`;
}
