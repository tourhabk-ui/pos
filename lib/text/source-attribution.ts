/**
 * Детерминированная зачистка утечки источника из турист-facing контента.
 *
 * Проблема (кейс владельца «Бухта Асача», /routes/604f8c47-…): при скрейпе
 * idilesom.com в описание/заголовок попадала атрибуция стороннего сайта —
 * «Маршрут и все подробности на ИдиЛесом», суффикс « — ИдиЛесом» и голое
 * упоминание. Турист на карточке видел рекламу конкурента, а не факт о месте.
 *
 * Это ОДИН инструмент (а не абзац в промпте агента, см. CLAUDE.md §8):
 *   - read-time: карточка маршрута/места чистит description перед показом;
 *   - write-time: импортёр idilesom чистит title/description при записи;
 *   - guard:     валидатор постов канала ловит утечку до публикации;
 *   - миграция:  разово чистит уже испорченные строки в БД.
 *
 * Чистое, без сети — покрыто tests/unit/source-attribution.test.ts.
 */

// Название источника во всех виданных формах: «ИдиЛесом», «Иди Лесом»,
// «идилесом» (домен-подобное). ё/е и регистр — через флаги.
const SOURCE_NAME = String.raw`иди\s*лесом|идилесом`;

/** Есть ли в тексте утечка атрибуции стороннего источника. */
export function hasSourceAttribution(text: string | null | undefined): boolean {
  if (!text) return false;
  return new RegExp(SOURCE_NAME, 'i').test(text);
}

/**
 * Убирает атрибуцию источника, СОХРАНЯЯ полезный текст вокруг.
 * Порядок правил важен: сначала целые рекламные хвосты, потом сепараторы,
 * потом голое упоминание, в конце — уборка пунктуации/пробелов.
 */
export function stripSourceAttribution(text: string | null | undefined): string {
  if (!text) return '';
  let out = text;

  // NB: JS \b — ASCII-only (кириллица = не-word), поэтому границы слова НЕ
  // используем; имя источника само по себе достаточно специфично.

  // A. Рекламный хвост-предложение: «Маршрут и все подробности на ИдиЛесом.»
  //    Забираем ведущую точку/запятую, чтобы не осталось «посмотреть. .»
  out = out.replace(
    new RegExp(String.raw`[.,;!?]?\s*маршрут\s+и\s+вс[её]\s+подробност[а-яё]*\s+на\s+(?:${SOURCE_NAME})\.?`, 'gi'),
    '.',
  );

  // B. Узкий хвост «(все )подробности на ИдиЛесом» — только само словосочетание,
  //    предшествующий полезный текст не трогаем.
  out = out.replace(
    new RegExp(String.raw`[.,;!?]?\s*(?:вс[её]\s+)?подробност[а-яё]*\s+на\s+(?:${SOURCE_NAME})\.?`, 'gi'),
    '.',
  );

  // C. Голый хвост «… на ИдиЛесом»
  out = out.replace(new RegExp(String.raw`\s*на\s+(?:${SOURCE_NAME})`, 'gi'), '');

  // D. Сепаратор + имя в заголовке/строке: « — ИдиЛесом», « | ИдиЛесом», « · ИдиЛесом»
  out = out.replace(new RegExp(String.raw`\s*[—\-|·:]\s*(?:${SOURCE_NAME})`, 'gi'), '');

  // E. Любое остаточное голое упоминание
  out = out.replace(new RegExp(String.raw`(?:${SOURCE_NAME})`, 'gi'), '');

  // F. Уборка: схлопнуть пробелы, убрать пробел перед пунктуацией, снять
  //    висящую пунктуацию/сепараторы по краям, дубли точек.
  out = out
    .replace(/[ \t]{2,}/g, ' ')
    .replace(/\s+([.,;:!?…])/g, '$1')
    .replace(/\.{2,}/g, '.')
    .replace(/^[\s.,;:—\-|·]+/, '')
    .replace(/[\s.,;:—\-|·]+$/, (m) => (/[.!?…]/.test(m) ? '.' : ''))
    .trim();

  return out;
}
