/**
 * Снятие HTML-тегов для мест, где угловых скобок не должно остаться ВООБЩЕ:
 * JSON-LD структурированных данных тура (lib/seo/tour-structured-data).
 *
 * Само снятие — общее (lib/html/text). Здесь только добавка: остаточные
 * одинокие `<` и `>` тоже убираются. Для структурированных данных это верно,
 * для обычного текста — нет: там «1 < 2» должно остаться «1 < 2», и потому
 * общая функция скобки не трогает.
 *
 * Прежняя шапка этого файла обещала, что `<scr<script>ipt>` после одного
 * прохода оставляет `<script>`. Проверено 23.08.2026 — не оставляет: даёт
 * `ipt>`, потому что `<[^>]*>` всегда начинает совпадение с самого левого `<`
 * и склейки не выходит. Пример был неверен; повтор до неподвижной точки
 * оставлен, поскольку сам по себе он не вредит, но выдавать неверный пример
 * за обоснование нельзя.
 */

import { stripTags } from '@/lib/html/text';

export function stripHtmlTags(input: string | null | undefined): string {
  if (!input) return '';
  return stripTags(String(input))
    .replace(/[<>]/g, '')
    .replace(/\s+/g, ' ')
    .trim();
}
