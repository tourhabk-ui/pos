/**
 * lib/text/escape-html.ts — одно экранирование на платформу.
 *
 * В репозитории семнадцать своих `esc`/`escapeHtml`, и они не одинаковы:
 * часть закрывает только `& < >`, часть ещё кавычки. Пока правило написано
 * семнадцать раз, это семнадцать правил, и расходятся они молча (§12).
 *
 * Заведено 08.09 по находке судьи эволюции: в письмах (`lib/notifications/
 * email.ts`) экранирования не было ВОВСЕ — маршрут, имя водителя и телефон
 * подставлялись в HTML и в `href="tel:"` как есть. Значения приходят из брони,
 * то есть в конечном счёте от человека, а письмо читает другой человек.
 *
 * Здесь закрываются и кавычки: значение может стоять внутри атрибута, и
 * `&<>` там мало. Апостроф — числовой мнемоникой (`&#39;`), а не `&apos;`:
 * последняя не входит в HTML 4 и старые почтовые клиенты её не разбирают.
 */
export function escapeHtml(value: unknown): string {
  return String(value ?? '')
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;')
    .replace(/'/g, '&#39;');
}

/**
 * Значение внутри `href="tel:"`. Экранирования мало: в телефон можно
 * подставить `javascript:`-мусор или пробелы с переносами. Оставляем только
 * то, из чего состоит настоящий номер.
 */
export function telHref(phone: unknown): string {
  const cleaned = String(phone ?? '').replace(/[^\d+()\-\s]/g, '').trim();
  // Мало вычистить буквы: из «javascript:alert(1)» так получается «(1)» —
  // мусор в ссылке, по которому человек нажмёт. Ссылка ставится, только если
  // на телефон это похоже: пять цифр и больше.
  return (cleaned.match(/\d/g)?.length ?? 0) >= 5 ? cleaned : '';
}

/**
 * Тема письма — заголовок, а не HTML. Экранировать её `&lt;` значит показать
 * человеку мусор; опасны здесь переводы строки, которыми в заголовок
 * дописывают СВОИ заголовки (Bcc, Content-Type). Их и убираем.
 */
export function safeSubject(value: unknown): string {
  return String(value ?? '').replace(/[\r\n]+/g, ' ').trim().slice(0, 200);
}
