/**
 * Очистка ответа модели до чистого текста для экранов платформы.
 *
 * Живой случай 28.07: AI Спасатель на странице безопасности показывал
 * «**Алло, это AI Спасатель Камчатки!**» — со звёздочками — и красные кружки
 * эмодзи. Пузырь чата рендерит текст как есть (whitespace-pre-wrap), а модель
 * отвечала в markdown.
 *
 * Чинить это абзацем в промпте нельзя: просьбу «не используй markdown» модель
 * иногда выполняет, а иногда нет, и на экране экстренной помощи «иногда» не
 * годится. Поэтому детерминированный гард на рендере — по тому же принципу,
 * по которому у платформы устроена SOS-страховка.
 *
 * Эмодзи убираются отдельно: они запрещены в UI платформы, а в аварийном
 * интерфейсе ещё и мешают — красный кружок рядом с «Кровотечение есть?»
 * читается как украшение там, где нужен только смысл.
 */

/** Снимает markdown-выделение, оставляя сам текст. */
export function stripMarkdownEmphasis(text: string): string {
  return text
    // Жирный/курсив: **текст**, __текст__, *текст*, _текст_.
    .replace(/\*\*([^*]+)\*\*/g, '$1')
    .replace(/__([^_]+)__/g, '$1')
    .replace(/(^|[\s(])\*([^*\n]+)\*(?=[\s).,!?:;]|$)/g, '$1$2')
    .replace(/(^|[\s(])_([^_\n]+)_(?=[\s).,!?:;]|$)/g, '$1$2')
    // Заголовки в начале строки: «## Что делать» → «Что делать».
    .replace(/^#{1,6}\s+/gm, '')
    // Маркер списка «- » и «* » в начале строки → тире (нумерацию не трогаем:
    // «1. Тип травмы» — это порядок действий, он значим).
    .replace(/^\s*[*+]\s+/gm, '— ')
    // Осиротевшие звёздочки, если разметка пришла рваной.
    .replace(/\*/g, '');
}

/** Убирает эмодзи и вариационные селекторы. */
export function stripEmoji(text: string): string {
  return text
    .replace(/[\p{Extended_Pictographic}\u{1F3FB}-\u{1F3FF}\u{FE0F}\u{20E3}]/gu, '')
    // После вырезанного эмодзи остаются двойные пробелы — схлопываем, но
    // переводы строк сохраняем: структура ответа несёт смысл.
    .replace(/[ \t]{2,}/g, ' ')
    .replace(/[ \t]+$/gm, '');
}

/** Полная подготовка ответа модели к показу в чате платформы. */
export function plainResponse(text: string): string {
  return stripEmoji(stripMarkdownEmphasis(text)).trim();
}
