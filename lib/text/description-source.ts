/**
 * Атрибуция ТЕКСТА описания места (#1830, шаг 4).
 *
 * Не путать с `places.source_url` / `places.source_name`: те говорят, откуда
 * взялась ЗАПИСЬ места, и на экран намеренно не выводятся (решение владельца
 * 17.08, §4.1 — там источником был конкурент). Здесь другое: откуда взят
 * конкретный абзац, который человек читает. 13.09 в `places.description`
 * легли 23 текста, переведённых с Remarks Смитсоновского института, и этот
 * факт заслуживает видимой пометки — не ради формальности, а потому что
 * научный источник отвечает за содержание, а мы только за перевод.
 *
 * ПОЧЕМУ БЕЗ ССЫЛКИ. Ссылка на страницу вулкана напрашивалась, и адрес такого
 * вида, вероятно, существует, — но проба 499 (13.09) с раннера получила
 * **HTTP 403 на все три адреса** volcano.si.edu и si.edu: Смитсоновский
 * закрывает запросы из датацентра. То есть формат адреса ПРОВЕРИТЬ НЕ УДАЛОСЬ.
 * Это третий исход (§4.0) — не «ссылки нет» и не «ссылка рабочая», а «не смог
 * убедиться»; ставить на карточку непроверенный путь значит обещать человеку
 * дорогу, которой мы не видели. Подпись работает и текстом: она называет
 * источник, а найти Global Volcanism Program по имени может кто угодно.
 * Ссылка добавляется одной строкой, когда адрес подтвердится из браузера.
 *
 * ЧТО ЗДЕСЬ НЕ РЕШАЕТСЯ. Признак «текст действительно из ГВП» берётся из БД
 * (черновик со статусом `approved`, чей перевод посимвольно совпадает с живой
 * колонкой) — см. запрос в `app/api/places/[id]/route.ts`. Здесь только
 * ФОРМУЛИРОВКА, в одном экземпляре на платформу: разойдясь, две подписи под
 * одним источником стали бы двумя разными утверждениями о нём.
 */

/** Источники, у которых текст описания может быть подписан. */
export type DescriptionSourceKind = 'gvp';

export interface DescriptionSource {
  kind: DescriptionSourceKind;
  /** Строка под описанием. */
  label: string;
}

/**
 * Формулировка из issue #1830 дословно. Полное имя института, а не
 * аббревиатура: «ГВП» человеку в поле не говорит ничего, а подпись ставится
 * ради него, не ради нас.
 */
const GVP_LABEL = 'По данным Global Volcanism Program, Смитсоновский институт';

/**
 * Подпись под описанием — или null, если подписывать нечего.
 *
 * `sourceRef` приходит из БД и равен null, когда текст описания РАЗОШЁЛСЯ с
 * одобренным переводом (или его там никогда не было). Тогда подписи нет, и
 * это правильный исход, а не потеря: под переписанным текстом имя источника
 * было бы ложью.
 */
export function describeDescriptionSource(
  sourceRef: string | null | undefined,
): DescriptionSource | null {
  if (!sourceRef) return null;
  return { kind: 'gvp', label: GVP_LABEL };
}
