/** Источники, у которых текст описания может быть подписан. */
export type DescriptionSourceKind = 'gvp';

export interface DescriptionSource {
  kind: DescriptionSourceKind;
  /** Строка под описанием. Читается самостоятельно, без ссылки. */
  label: string;
  /** Страница объекта у источника; null — опознание не похоже на адресуемое. */
  url: string | null;
}

/**
 * Формулировка из issue #1830 дословно. Полное имя института, а не
 * аббревиатура: «ГВП» человеку в поле не говорит ничего, а подпись ставится
 * ради него, не ради нас.
 */
const GVP_LABEL = 'По данным Global Volcanism Program, Смитсоновский институт';

/**
 * Публичная страница вулкана. `source_ref` черновика — это VolcanoNumber,
 * стабильное опознание объекта в базе ГВП: имя транслитерируется по-разному
 * (Sheveluch / Shiveluch / Шивелуч), номер — нет.
 *
 * Шестизначность проверяется, а не предполагается: чужая строка в адресе дала
 * бы битую ссылку, а подпись без ссылки честнее ссылки в никуда.
 */
function gvpUrl(volcanoNumber: string): string | null {
  const vn = volcanoNumber.trim();
  return /^\d{6}$/.test(vn) ? `https://volcano.si.edu/volcano.cfm?vn=${vn}` : null;
}

/**
 * Подпись под описанием — или null, если подписывать нечего.
 *
 * `sourceRef` приходит из БД и равен null, когда текст описания РАЗОШЁЛСЯ с
 * одобренным переводом (или его там никогда не было). Тогда подписи нет, и
 * это правильный исход, а не потеря: под переписанным текстом имя источника
 * было бы ложью.
 */
export function describeDescriptionSource(
  sourceRef: string | null | undefined,
): DescriptionSource | null {
  // trim ДО проверки на пустоту: иначе `''` давало бы «подписи нет», а `'  '`
  // — подпись, и одно и то же «опознания нет» вело бы себя двумя способами.
  const ref = (sourceRef ?? '').trim();
  if (!ref) return null;
  return { kind: 'gvp', label: GVP_LABEL, url: gvpUrl(ref) };
}
