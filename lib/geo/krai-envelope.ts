/**
 * Грубый конверт Камчатского края с Курилами и Командорами.
 *
 * Жил в `app/api/cron/place-coords/route.ts`, откуда его импортировал импорт
 * маршрутов. Переехал сюда, когда понадобился третьему месту — приёмнику SOS:
 * зависимость «критичный роут → крон-роут» неправильна по направлению, а
 * скопировать четыре числа значило бы завести второе правило (§12: правило,
 * реализованное дважды, — это два правила, и они разойдутся).
 *
 * ── Что он НЕ значит ───────────────────────────────────────────────────────
 *
 * Конверт — фильтр от нулей и перепутанных широты с долготой, а НЕ проверка
 * правды: 156.2 на широте 54.6 лежит внутри конверта и при этом в Охотском
 * море (случай Тюшевских источников, 23.08). Внутри конверта — «не бред»;
 * снаружи — «точно не край».
 */

export const KRAI_LAT_MIN = 50.0;
export const KRAI_LAT_MAX = 65.5;
export const KRAI_LNG_MIN = 155.0;
export const KRAI_LNG_MAX = 174.0;

/**
 * Точка внутри конверта края.
 *
 * `null` — «не знаю»: координат нет, и утверждать что-либо об их положении
 * нельзя. Отсутствие координат НЕ равно «снаружи» — на слое безопасности эта
 * подмена стоила бы человека без спутников.
 */
export function insideKrai(
  lat: number | null | undefined,
  lng: number | null | undefined,
): boolean | null {
  if (lat == null || lng == null) return null;
  if (!Number.isFinite(lat) || !Number.isFinite(lng)) return null;
  return lat >= KRAI_LAT_MIN && lat <= KRAI_LAT_MAX
      && lng >= KRAI_LNG_MIN && lng <= KRAI_LNG_MAX;
}

/**
 * ── Конвертов было три, и они не совпадали (19.09, #1961) ──────────────────
 *
 * Шапка выше говорит: «скопировать четыре числа значило бы завести второе
 * правило». К 19.09 правил было ТРИ, и два из них носили одно и то же имя
 * `KAMCHATKA_BOUNDS` с разными числами:
 *
 *   | где жил                            | широта    | долгота     |
 *   |------------------------------------|-----------|-------------|
 *   | lib/geo/krai-envelope.ts (KRAI_*)  | 50 – 65.5 | 155 – 174   |
 *   | lib/services/routes/geocode.ts     | 50 – 64   | 155 – 167   |
 *   | lib/routes/track.ts (свой const)   | 50 – 66   | 154 – 175   |
 *
 * Следствие не умозрительное: приёмник SOS принимает сигнал с точки 65°с.ш.,
 * а приёмник наблюдений (`/api/safety/reports`, гейт `withinKamchatka`) в той
 * же точке отвечает «координаты вне Камчатки». Платформа не согласна сама с
 * собой в том, где кончается край.
 *
 * ЧИСЛА ЗДЕСЬ НЕ СВЕДЕНЫ — сведены ОБЪЯВЛЕНИЯ. Разными они стали не
 * случайно: поле трека шире намеренно («отсечь мусор и перепутанные оси, а не
 * подрезать настоящие треки»), а геокодер уже, потому что защищается от
 * Nominatim. Выбор одного набора меняет, какие координаты платформа считает
 * своими, — и на пути SOS это решение владельца, а не побочный эффект правки.
 *
 * Что даёт переезд в один файл: расхождение видно одним взглядом, у каждого
 * конверта написано ЗАЧЕМ он такой, и четвёртый не заведётся молча —
 * `tests/unit/krai-envelopes-single-source.test.ts` не пропустит новый bbox
 * Камчатки мимо этого модуля.
 */

/**
 * Конверт ПАРСЕРА ТРЕКА. Самый широкий: задача — отсечь мусор и переставленные
 * оси, а не подрезать настоящие треки по краям (полевой случай 17.08 —
 * горизонталь через весь экран от Магаданской области).
 */
export const TRACK_ENVELOPE = { latMin: 50, latMax: 66, lngMin: 154, lngMax: 175 } as const;

/**
 * Конверт ГЕОКОДЕРА. Самый узкий: защита от того, что Nominatim примет
 * название места за что-то за пределами края. Им же судят сверки с OSM и GVP
 * и ремонт данных.
 */
export const GEOCODE_ENVELOPE = { latMin: 50, latMax: 64, lngMin: 155, lngMax: 167 } as const;
