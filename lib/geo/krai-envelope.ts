/**
 * Грубый конверт Камчатского края с Курилами и Командорами.
 *
 * Жил в `app/api/cron/place-coords/route.ts`, откуда его импортировал импорт
 * маршрутов. Переехал сюда, когда понадобился третьему месту — приёмнику SOS:
 * зависимость «критичный роут → крон-роут» неправильна по направлению, а
 * скопировать четыре числа значило бы завести второе правило (§12: правило,
 * реализованное дважды, — это два правила, и они разойдутся).
 *
 * ── Что он НЕ значит ───────────────────────────────────────────────────────
 *
 * Конверт — фильтр от нулей и перепутанных широты с долготой, а НЕ проверка
 * правды: 156.2 на широте 54.6 лежит внутри конверта и при этом в Охотском
 * море (случай Тюшевских источников, 23.08). Внутри конверта — «не бред»;
 * снаружи — «точно не край».
 */

export const KRAI_LAT_MIN = 50.0;
export const KRAI_LAT_MAX = 65.5;
export const KRAI_LNG_MIN = 155.0;
export const KRAI_LNG_MAX = 174.0;

/**
 * Точка внутри конверта края.
 *
 * `null` — «не знаю»: координат нет, и утверждать что-либо об их положении
 * нельзя. Отсутствие координат НЕ равно «снаружи» — на слое безопасности эта
 * подмена стоила бы человека без спутников.
 */
export function insideKrai(
  lat: number | null | undefined,
  lng: number | null | undefined,
): boolean | null {
  if (lat == null || lng == null) return null;
  if (!Number.isFinite(lat) || !Number.isFinite(lng)) return null;
  return lat >= KRAI_LAT_MIN && lat <= KRAI_LAT_MAX
      && lng >= KRAI_LNG_MIN && lng <= KRAI_LNG_MAX;
}
