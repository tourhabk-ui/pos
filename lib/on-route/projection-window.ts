/**
 * lib/on-route/projection-window.ts
 *
 * Положение вдоль маршрута держится состоянием, а не ищется заново.
 *
 * ── Что ломается без этого ─────────────────────────────────────────────────
 *
 * `projectOnTrack` ищет глобально ближайшее звено на каждом фиксе GPS. На
 * радиальном маршруте — а в схеме есть `route_type` «радиальный», и такие у нас
 * есть — трек идёт туда и обратно, и обе ветки лежат в десятках метров друг от
 * друга. Шум позиционирования в двадцать метров перекидывает проекцию с ветки
 * «туда» на ветку «обратно», и «осталось 3 км» превращается в «осталось 17 км»
 * у НЕПОДВИЖНОГО человека.
 *
 * Это не неточность. Прибор, чьи показания скачут втрое, пока стоишь на месте,
 * перестают читать — и тогда неважно, насколько он точен в остальном.
 *
 * ── Как решают навигаторы ──────────────────────────────────────────────────
 *
 * OsmAnd и Locus держат положение вдоль маршрута как состояние: следующая
 * проекция ищется в окне вокруг предыдущей, а не по всему треку. Идея простая
 * и старая: человек за секунду между фиксами не мог переместиться на километр,
 * значит и проекция не могла.
 *
 * ── Что здесь ──────────────────────────────────────────────────────────────
 *
 * Окно в метрах вдоль трека от прошлого положения. Внутри окна берётся
 * ближайшее звено; за окном ничего не рассматривается, даже если оно ближе по
 * прямой. Возврат к глобальному поиску разрешён только в двух случаях, и оба
 * названы явно: положения ещё нет (первый фикс) и человек ушёл от трека
 * дальше, чем окно вообще имеет смысл (сошёл с маршрута — тогда прежнее
 * состояние не помогает, а мешает).
 *
 * Состояние — не оптимизация. Это признание того, что путь имеет направление,
 * а положение вдоль него — величина со своей историей.
 */

import { projectOnTrack, straightKm, type GeoPoint, type TrackProjection } from '@/lib/on-route/approach';

/**
 * Окно поиска вдоль трека, метры.
 *
 * Пешком быстрее пяти километров в час по камчатской тропе не ходят, между
 * фиксами проходит секунда-другая; триста метров с большим запасом покрывают и
 * потерю сигнала на несколько минут, и остановку с дрейфом. Дальше окно
 * расширять нельзя: на радиальном маршруте противоположная ветка окажется
 * внутри, и вернётся ровно тот перескок, ради которого всё написано.
 */
export const WINDOW_M = 300;

/**
 * Насколько далеко от трека человек считается сошедшим с маршрута.
 *
 * За этой границей держаться прежнего положения бессмысленно: он уже не идёт
 * по треку, и следующая проекция должна искаться честно, глобально.
 */
export const RESET_OFF_TRACK_KM = 1;

export interface AlongState {
  /** Метры вдоль трека от начала. Величина с историей. */
  alongM: number;
  /** Проекция, которой это положение соответствует. */
  projection: TrackProjection;
}

/** Накопленные расстояния по звеньям — считаются один раз на трек. */
function cumulative(track: GeoPoint[]): number[] {
  const cum = [0];
  for (let i = 1; i < track.length; i++) {
    cum[i] = cum[i - 1] + straightKm(track[i - 1], track[i]) * 1000;
  }
  return cum;
}

/** Метры вдоль трека до проекции. */
function alongMeters(track: GeoPoint[], cum: number[], pr: TrackProjection): number {
  const a = cum[pr.segment];
  const b = cum[Math.min(pr.segment + 1, cum.length - 1)];
  return a + (b - a) * pr.t;
}

/**
 * Следующее положение вдоль трека.
 *
 * `prev === null` — первый фикс, ищем глобально. Иначе ищем только в окне и
 * возвращаемся к глобальному поиску, лишь когда человек ушёл от трека дальше
 * `RESET_OFF_TRACK_KM`: там прежнее состояние уже не про него.
 */
export function advanceAlong(
  user: GeoPoint,
  track: GeoPoint[],
  prev: AlongState | null,
  windowM = WINDOW_M,
): AlongState | null {
  if (track.length < 2) return null;
  const cum = cumulative(track);

  const global = projectOnTrack(user, track);
  if (!global) return null;

  // Первый фикс — истории нет, брать неоткуда.
  if (!prev) return { alongM: alongMeters(track, cum, global), projection: global };

  // Сошёл с маршрута — держаться прошлого положения незачем.
  if (global.offTrackKm > RESET_OFF_TRACK_KM) {
    return { alongM: alongMeters(track, cum, global), projection: global };
  }

  // Окно: только те звенья, что лежат в пределах windowM вдоль трека от
  // прошлого положения. Ближайшее по прямой за окном не рассматривается вовсе —
  // именно в этом и состоит защита от перескока на встречную ветку.
  let best: TrackProjection | null = null;
  let bestAlong = prev.alongM;
  for (let i = 0; i < track.length - 1; i++) {
    const segStart = cum[i];
    const segEnd = cum[i + 1];
    if (segEnd < prev.alongM - windowM || segStart > prev.alongM + windowM) continue;

    const local = projectOnTrack(user, [track[i], track[i + 1]]);
    if (!local) continue;
    if (!best || local.offTrackKm < best.offTrackKm) {
      best = { ...local, segment: i };
      bestAlong = segStart + (segEnd - segStart) * local.t;
    }
  }

  // В окно не попало ни одно звено (трек короче окна и человек у края) —
  // остаёмся там, где были: выдумывать перемещение не из чего.
  if (!best) return prev;

  return { alongM: bestAlong, projection: best };
}
