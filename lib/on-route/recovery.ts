/**
 * Восстановление: что делать, когда реальность разошлась с планом.
 *
 * План FCN, этап 6. Математика уже была — порог отхода от точности фикса,
 * dataConflict, состояния фикса, — но выходила к человеку техническим
 * текстом и в момент, когда думать труднее всего. Здесь она превращается
 * в СОСТОЯНИЕ экрана с одним понятным действием.
 *
 * Три правила, ради которых модуль отдельный и чистый:
 *
 *  1. «Вернитесь к линии» говорится ТОЛЬКО про снятый трек. У наброска
 *     линия построена прямыми между точками: звать на неё — звать в
 *     каньон. Там другое состояние и другие слова.
 *  2. Устаревший фикс не превращается в тревогу «вы сбились»: мы не знаем,
 *     где человек, и обязаны сказать именно это.
 *  3. Восстановление не прячет компас и не блокирует экран. Это смена
 *     главной задачи, а не модальное окно поверх приборов.
 */

import type { TrackFidelity } from '@/lib/routes/track-fidelity';
import type { FixInfo } from '@/lib/on-route/fix-quality';

export type RecoveryKind =
  /** Всё в порядке: карточки нет. */
  | 'none'
  /** Ушли с ПОДТВЕРЖДЁННОЙ линии — можно звать обратно. */
  | 'off_track'
  /** Вне линии-ориентира: подтверждённого пути нет, звать некуда. */
  | 'off_sketch'
  /** Положение устарело: цифры заморожены. */
  | 'stale_fix'
  /** Линия и точки маршрута описывают разное. */
  | 'data_conflict'
  /** Карты в телефоне нет, а связи может не быть. */
  | 'no_offline_map';

export interface RecoveryAction {
  kind: 'open_map' | 'dismiss' | 'open_pack' | 'open_conditions';
  label: string;
}

export interface RecoveryState {
  kind: RecoveryKind;
  title: string;
  /** Что происходит и что делать — человеческим языком, без терминов. */
  text: string;
  /** Ведущее действие. */
  primary: RecoveryAction | null;
  /** «Продолжить намеренно» — приглушает карточку, не отменяя состояния. */
  dismissible: boolean;
  /** Тон: предупреждение или просто пояснение. */
  tone: 'warn' | 'info';
}

export interface RecoveryInput {
  fidelity: TrackFidelity;
  hasTrack: boolean;
  /** Человек в стороне от линии (approach.userOffTrack). */
  userOffTrack: boolean;
  /** Насколько в стороне, км (approach.approachKm). */
  offTrackKm: number | null;
  dataConflict: boolean;
  fix: FixInfo;
  /** Карта маршрута сохранена в телефоне. */
  mapSaved: boolean;
  /** Сейчас нет сети. */
  offline: boolean;
}

function fmtM(km: number | null): string {
  if (km === null || !Number.isFinite(km)) return '';
  const m = Math.round(km * 1000);
  return m < 1000 ? `${m} м` : `${km.toFixed(1)} км`;
}

/**
 * Одно состояние на экран. Порядок ветвей — это порядок важности: сначала
 * то, что делает цифры бессмысленными (конфликт данных, мёртвый фикс),
 * потом отклонение, потом готовность карты.
 */
export function recoveryState(i: RecoveryInput): RecoveryState {
  // 1. Данные не сходятся: считать нечего, и это не про положение человека.
  if (i.dataConflict) {
    return {
      kind: 'data_conflict',
      title: 'Линия и точки маршрута расходятся',
      text: 'Расстояние и время не показываем: по этим данным неизвестно, как идут к точке. '
        + 'Ориентируйтесь по карте и местности, компас и SOS работают.',
      primary: { kind: 'open_map', label: 'Открыть карту' },
      dismissible: false,
      tone: 'warn',
    };
  }

  // 2. Положение устарело. «Вы сбились» тут сказать нельзя — мы не знаем,
  // где человек; знаем только, что давно не слышали GPS.
  if (i.fix.state === 'dead' || i.fix.state === 'none') {
    return {
      kind: 'stale_fix',
      title: i.fix.state === 'none' ? 'Положение неизвестно' : 'Сигнал GPS потерян',
      text: 'Цифры на экране — последнее, что мы знали, и они не обновляются. '
        + 'Выйдите на открытое место и подождите минуту; направление по компасу работает без GPS.',
      primary: { kind: 'open_map', label: 'Открыть карту' },
      dismissible: true,
      tone: 'warn',
    };
  }

  // 3. Отклонение. Разница между треком и наброском здесь решающая.
  if (i.userOffTrack && i.hasTrack) {
    if (i.fidelity === 'surveyed') {
      return {
        kind: 'off_track',
        title: `Вы в стороне от линии${i.offTrackKm !== null ? ` на ${fmtM(i.offTrackKm)}` : ''}`,
        text: 'Вернитесь к отмеченной линии — направление показано пунктиром на карте. '
          + 'Не идите по прямой через рельеф: прямая короче на экране, а не на земле.',
        primary: { kind: 'open_map', label: 'Показать возврат' },
        dismissible: true,
        tone: 'warn',
      };
    }
    // Набросок или неизвестное происхождение: возвращать НЕ К ЧЕМУ.
    return {
      kind: 'off_sketch',
      title: 'Подтверждённой линии рядом нет',
      // Отрицания здесь быть не должно: фразу вроде «возвращаться на неё
      // смысла не имеет» уставший человек прочтёт до середины и пойдёт на
      // линию. Говорим только то, что делать.
      text: 'Линия маршрута построена прямыми между точками — это ориентир, а не тропа. '
        + 'Идите к следующей точке по компасу, сверяясь с местностью.',
      primary: { kind: 'open_map', label: 'Открыть карту' },
      dismissible: true,
      tone: 'warn',
    };
  }

  // 4. Карты нет в телефоне, а связь может пропасть в любой момент.
  if (!i.mapSaved) {
    return {
      kind: 'no_offline_map',
      title: i.offline ? 'Карта не сохранена, а связи нет' : 'Карта не сохранена',
      text: i.offline
        ? 'Тайлы карты не в телефоне и подгрузить их нечем. Остаются точки маршрута, компас и координаты.'
        : 'Пока есть связь — сохраните полевой пакет: без него карта в поле не откроется.',
      primary: i.offline
        ? { kind: 'open_map', label: 'Точки и компас' }
        : { kind: 'open_pack', label: 'Сохранить пакет' },
      dismissible: true,
      tone: i.offline ? 'warn' : 'info',
    };
  }

  return {
    kind: 'none', title: '', text: '', primary: null, dismissible: false, tone: 'info',
  };
}
