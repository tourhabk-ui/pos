/**
 * Азимут на цель — главное число полевого компаса.
 *
 * Компас показывает не «где север», а «куда идти»: стрелка смотрит на
 * следующую точку, а кольцо сторон света держит землю. Для этого нужен
 * истинный азимут от человека к точке — он и считается здесь.
 *
 * Функция чистая и отдельная: её же читает подпись «На точку: 042°», и
 * два разных вычисления одного азимута разошлись бы так же, как в своё
 * время разошлись копии SOS.
 */

export interface GeoPointLite { lat: number; lng: number }

/**
 * Истинный азимут (0–360°, 0 = север) по большому кругу.
 *
 * Формула сферическая, не плоская: на широте Камчатки (53°) плоское
 * приближение уводит стрелку на несколько градусов уже на десятке
 * километров — в тумане этого хватает, чтобы промахнуться мимо седловины.
 */
export function bearingDeg(from: GeoPointLite, to: GeoPointLite): number {
  const rad = Math.PI / 180;
  const φ1 = from.lat * rad;
  const φ2 = to.lat * rad;
  const Δλ = (to.lng - from.lng) * rad;

  const y = Math.sin(Δλ) * Math.cos(φ2);
  const x = Math.cos(φ1) * Math.sin(φ2) - Math.sin(φ1) * Math.cos(φ2) * Math.cos(Δλ);
  const θ = Math.atan2(y, x) / rad;
  return (θ + 360) % 360;
}

/** Три знака с ведущими нулями — «042°», как на приборе. */
export function formatBearing(deg: number): string {
  return `${String(Math.round(deg) % 360).padStart(3, '0')}°`;
}
