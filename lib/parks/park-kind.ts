/**
 * Род территории для подписи над заголовком карточки — по слову в имени
 * справочника `parks`. До 14.10 подпись была одна на всех: «Природный парк»,
 * и над «Кроноцким заповедником» стояло «Природный парк · Камчатка». Заповедник,
 * заказник и природный парк — разные режимы охраны (разное и разрешение), и
 * имя справочника это уже говорит: «Кроноцкий заповедник», «Природный парк
 * „Налычево“».
 */
export function parkKindLabel(displayName: string): 'Заповедник' | 'Заказник' | 'Природный парк' {
  const n = displayName.toLowerCase();
  if (n.includes('заповедник')) return 'Заповедник';
  if (n.includes('заказник')) return 'Заказник';
  return 'Природный парк';
}
