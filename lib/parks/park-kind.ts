/**
 * Род территории для подписи над заголовком карточки — по слову в имени
 * справочника `parks`. До 14.10 подпись была одна на всех: «Природный парк»,
 * и над «Кроноцким заповедником» стояло «Природный парк · Камчатка». Заповедник,
 * заказник и природный парк — разные режимы охраны (разное и разрешение), и
 * имя справочника это уже говорит: «Кроноцкий заповедник», «Природный парк
 * „Налычево“».
 *
 * «Национальный парк» — 14.10: Командорский заповедник с 2022 года национальный
 * парк «Командорские острова» (постановление Правительства № 720), и над его
 * страницей стояло бы «Природный парк» — региональный режим вместо
 * федерального. Проверяется раньше «заповедника»: имя может назвать оба.
 *
 * «Памятник природы» — 14.10, «Вачкажец» (миграция 1244): справочник зовёт
 * его «Памятник природы «Вачкажец»», а подпись говорила «Природный парк» —
 * другой режим, и у парка разрешение есть, а у памятника его нет.
 */
export function parkKindLabel(displayName: string): 'Национальный парк' | 'Заповедник' | 'Заказник' | 'Памятник природы' | 'Природный парк' {
  const n = displayName.toLowerCase();
  if (n.includes('национальный парк')) return 'Национальный парк';
  if (n.includes('заповедник')) return 'Заповедник';
  if (n.includes('заказник')) return 'Заказник';
  if (n.includes('памятник природы')) return 'Памятник природы';
  return 'Природный парк';
}
