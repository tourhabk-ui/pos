/**
 * Маршрут относится к парку справочника — одно правило для страницы парка
 * (/park/[slug]) и для ссылки «страница парка» на карточке маршрута.
 *
 * Связь держится на `kamchatka_routes.park_name`, который импорт заполнял
 * свободным текстом, и на `parks.search_term` — корне имени (миграция 712).
 * Корень «Южно-Камчат» одинаково находит «Южно-Камчатский» — бывший
 * природный парк, с 9 октября 2026 года кластер национального парка
 * «Вулканы Камчатки», — и «Южно-Камчатский заказник федерального значения»
 * у Курильского озера: другую территорию, другое ведомство, другое
 * разрешение (проба 876, 14.10: четыре маршрута заказника из одиннадцати
 * с этим корнем). Слово «заказник» в имени называет заказник: на страницу
 * парка, который заказником не является, такой маршрут не попадает — то же
 * правило, что у оговорки о федеральном парке (federalizedPark).
 *
 * Правило симметрично (миграция 1252, страница заказника): у заказника
 * справочника корень тот же — «Южно-Камчат», — и без второй половины его
 * страница взяла бы маршруты к Мутновскому и Горелому. Заказник берёт только
 * маршруты со словом «заказник», парк — только без него.
 *
 * Тревоги о закрытии парков (alert-place-scope) берут это правило с 13.11
 * (#3335, слово владельца «развести»). До этого не брали намеренно — лишний
 * охват считался дешевле молчания, — и Курильское озеро в заказнике стояло
 * красным по закрытию природного парка, которое заказник не называет:
 * ложный красный учит не верить настоящему.
 */
export function routeInParkSql(routeParkName: string, searchTerm: string, parkDisplayName: string): string {
  return `(${routeParkName} ILIKE '%' || ${searchTerm} || '%'
       AND (${routeParkName} ILIKE '%заказник%') = (${parkDisplayName} ILIKE '%заказник%'))`;
}
