/**
 * Расстояние и время в пути, названные без источника, помечаются вслух.
 *
 * ПОВОД (#1883, решение владельца 14.09 — вариант Б). Кузьмич уверенно
 * отвечает «до Паратунки примерно 60 км», «Малкинские — примерно 200 км»,
 * «до Курильского около 400 км, через Елизово и Сокоч». Ни одного из этих
 * чисел в данных платформы нет: поля «расстояние от Петропавловска» не
 * существует ни в `places`, ни в `kamchatka_routes` (`distance_km` маршрута —
 * это ДЛИНА трека, а не путь до его начала).
 *
 * Промпт это запрещает ПРЯМО (`core.ts`, «ГЕОГРАФИЯ И ЛОГИСТИКА — НЕ
 * ВЫДУМЫВАЙ… километраж трассы… бери ТОЛЬКО из инструментов»), и всё равно
 * нарушается на трёх вопросах из трёх в двух прогонах подряд. Значит строкой
 * в промпте не чинится — нужен серверный guard (§8, тот же вывод, что привёл
 * к `lib/safety/sos-detector.ts`).
 *
 * ПОЧЕМУ ПОМЕТКА, А НЕ ВЫРЕЗАНИЕ. В том же прогоне Кузьмич сказал «около
 * 25 км от города» про Авачинский — и это ВЕРНО. Резать по факту нельзя:
 * правильные общеизвестные числа исчезали бы наравне с выдуманными, а ответ
 * рвался бы посреди фразы.
 *
 * Судить надо не «правда ли это», а «есть ли у нас источник» — ровно §4.0.
 * Верное, но неподтверждённое число остаётся в ответе И получает пометку: для
 * туриста оба случая неотличимы, и следующее такое число окажется неверным.
 *
 * ЧТО СЧИТАЕТСЯ ИСТОЧНИКОМ. То же число в ТОЙ ЖЕ единице в контексте, который
 * платформа дала модели (выводы инструментов, карточка места, маршрут).
 * Совпадения голого числа мало: «25» в контексте может быть ценой, вместимостью
 * или высотой, и засчитывать его за подтверждение расстояния значило бы
 * заземлять ответ чем попало.
 */

/** Названное в ответе расстояние или время в пути. */
export interface DistanceClaim {
  /** Как оно написано в ответе — для отладки и тестов. */
  text: string;
  /** Числовое значение; у диапазона «3-4 часа» берётся первое. */
  value: number;
  unit: 'km' | 'hour';
}

/**
 * Слова, рядом с которыми «часы» означают ПУТЬ, а не что-то иное.
 * Без этого «работает с 9 часов» и «источник остывает за 2 часа» попали бы
 * в находки, и пометка появлялась бы на ровном месте — а пометка, которая
 * лепится ко всему, перестаёт читаться.
 */
const TRAVEL_WORDS = /(?:на машине|на авто|на автомобиле|езды|в пути|ехать|доехать|добираться|добраться|дорог)/i;

/*
 * NB: `\b` здесь НЕ используется, и это не небрежность.
 *
 * В JS граница слова ASCII-only: кириллическая «м» для неё не буква, поэтому
 * `км\b` не совпадает с «60 км.» — граница уже стоит ПЕРЕД «к». Первая
 * редакция этого файла (14.09) так и не находила ни одного километра, и
 * сторож зеленел бы, проверяя пустоту.
 *
 * Та же ловушка записана в `lib/text/source-attribution.ts` теми же словами —
 * значит платформа платит за неё второй раз. Вместо границы — запрет
 * кириллической буквы следом: он отсекает «километраж» от «километр», не
 * полагаясь на ASCII.
 */
/** «60 км», «примерно 200 километров», «400-450 км». */
const KM_RE = /(\d+(?:[.,]\d+)?)\s*(?:[–—-]\s*\d+(?:[.,]\d+)?\s*)?(?:км|километр[а-яё]*)(?![а-яё])/gi;
/** «3-4 часа на машине» — только рядом со словом пути (см. TRAVEL_WORDS). */
const HOUR_RE = /(\d+(?:[.,]\d+)?)\s*(?:[–—-]\s*\d+(?:[.,]\d+)?\s*)?(?:час[а-яё]*|ч)(?![а-яё])/gi;

/** Сколько знаков вокруг числа считаем «рядом» при проверке слова пути. */
const NEAR = 40;

function num(raw: string): number {
  return Number.parseFloat(raw.replace(',', '.'));
}

/** Найти в тексте все названные расстояния и времена в пути. */
export function findDistanceClaims(text: string): DistanceClaim[] {
  const out: DistanceClaim[] = [];
  for (const m of text.matchAll(KM_RE)) {
    out.push({ text: m[0].trim(), value: num(m[1]), unit: 'km' });
  }
  for (const m of text.matchAll(HOUR_RE)) {
    const at = m.index ?? 0;
    const around = text.slice(Math.max(0, at - NEAR), at + m[0].length + NEAR);
    if (!TRAVEL_WORDS.test(around)) continue;
    out.push({ text: m[0].trim(), value: num(m[1]), unit: 'hour' });
  }
  return out;
}

/**
 * Есть ли у числа источник в контексте платформы.
 *
 * Требуется совпадение ЗНАЧЕНИЯ И ЕДИНИЦЫ. Для километров допускается разница
 * в округлении до целого: контекст может нести «18.2 км», ответ — «18 км», и
 * считать это выдумкой было бы придиркой к пересказу.
 */
function isSourced(claim: DistanceClaim, context: string): boolean {
  const inContext = findDistanceClaims(context).filter(c => c.unit === claim.unit);
  return inContext.some(c => Math.abs(c.value - claim.value) < 1);
}

/** Числа, названные без источника. Пустой список — всё подтверждено. */
export function unsourcedClaims(answer: string, context: string): DistanceClaim[] {
  return findDistanceClaims(answer).filter(c => !isSourced(c, context));
}

/**
 * Пометка. Называет ровно то, что произошло: числа не из данных платформы.
 *
 * Не извинение и не отказ от ответа — турист получает и число, и знание о
 * том, чего это число стоит. Формулировка одна на платформу: две разошлись бы
 * при первой правке.
 */
export const DISTANCE_CAVEAT =
  'Расстояния и время в пути выше я назвал по памяти — проверенных цифр по этому '
  + 'объекту в данных платформы нет. Сверьтесь с картой или спросите оператора: '
  + 'ошибка в точке старта на маршруте стоит дороже неточности в километрах.';

/**
 * Добавить пометку, если в ответе есть неподтверждённые числа.
 *
 * Пустой контекст (инструменты ничего не принесли) — это НЕ «всё
 * неподтверждено по умолчанию», а буквально оно и есть: подтверждать нечем,
 * значит каждое число неподтверждено. Отдельной ветки тут не нужно, но
 * оговорка стоит здесь, чтобы её не «оптимизировали» позже.
 */
export function withDistanceCaveat(
  answer: string,
  context: string,
): { text: string; unsourced: DistanceClaim[] } {
  const unsourced = unsourcedClaims(answer, context);
  if (unsourced.length === 0) return { text: answer, unsourced };
  // Пометка уже стоит (повторный проход, склейка ответов) — не дублируем.
  if (answer.includes('назвал по памяти')) return { text: answer, unsourced };
  return { text: `${answer}\n\n${DISTANCE_CAVEAT}`, unsourced };
}
