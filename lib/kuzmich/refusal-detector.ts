/**
 * Детерминированный детектор ОТКАЗА модели (issue #1730).
 *
 * ── Что было ───────────────────────────────────────────────────────────────
 *
 * Грейдер ответов Кузьмича отсекал всё короче 50 знаков: «пропускаем очень
 * короткие ответы (ошибки, перебои)». Против обрывов порог верен. Но **отказ
 * короток по природе** — «не могу помочь с этим вопросом» это 32 знака, — и
 * потому не попадал в оценку ВООБЩЕ: ни балла, ни записи, ни следа. Отказ был
 * неотличим от обрыва связи и от того, что ответа не было.
 *
 * Цена не абстрактная. Кузьмич — советник по безопасности в поле, и наши
 * законные вопросы лежат ровно в темах, по которым модели отказывают целиком:
 * медведь рядом и чем его отпугнуть, кровь и переохлаждение, оружие в
 * разрешённом промысловом районе. Своего списка запрещённых тем у платформы
 * нет — значит отказ выносит ПРОВАЙДЕР, а водопад меняет провайдера молча.
 * Со стороны это выглядит как «Кузьмич иногда странный».
 *
 * ── Почему детектор, а не строка в промпте ─────────────────────────────────
 *
 * Тот же довод, что у `lib/safety/sos-detector.ts`: промпт — просьба к модели,
 * а не гарантия. Здесь просить и вовсе некого: отказ выносит тот, кого мы
 * просим. Судить об отказе может только код, стоящий СНАРУЖИ ответа.
 *
 * ── Три исхода, не два (§4.0) ──────────────────────────────────────────────
 *
 * `refusal`  — модель отказалась отвечать. Это факт о провайдере, и он
 *              обязан попасть в журнал вместе с его именем.
 * `outage`   — ответа не было вовсе: заглушка водопада, пустая строка. Это
 *              факт о сети и ключах, чинится в другом месте, и складывать его
 *              с отказом значит потерять оба.
 * `answer`   — обычный ответ, короткий или длинный. Судится как раньше.
 *
 * Слить `refusal` и `outage` было бы тем же дефектом, что чинится: одно
 * состояние вместо двух с разной починкой.
 *
 * ── Настройка баланса ──────────────────────────────────────────────────────
 *
 * В сторону ТОЧНОСТИ, как у SOS-детектора, но по обратной причине. Ложное
 * срабатывание здесь дороже пропуска: помеченный отказом нормальный ответ
 * попадает в сводку и зовёт разбираться с провайдером, который ни при чём.
 * Поэтому обороты отказа ищутся только в КОРОТКОМ ответе: развёрнутый текст с
 * оговоркой «я не врач, но при переохлаждении нужно...» — это ответ, а не
 * отказ, и мерить его этими словами нельзя.
 */

/** Чем оказался ответ модели. */
export type ResponseKind = 'answer' | 'refusal' | 'outage';

export interface ResponseVerdict {
  kind: ResponseKind;
  /** Что именно сработало — человеку в журнал, а не только флаг. */
  signals: string[];
}

/**
 * Порог, выше которого отказ не ищется.
 *
 * Отказ модели укладывается в одну-две фразы; развёрнутый ответ, даже
 * осторожный, длиннее. Граница поставлена вдвое выше прежнего порога грейдера
 * (50), чтобы поймать отказ с вежливым хвостом «...обратитесь к специалисту»,
 * и не выше — иначе в отказ начнут попадать короткие настоящие ответы.
 */
export const REFUSAL_MAX_LEN = 400;

// \b в JS не знает кириллицу — границы слов делаем lookaround'ами, как в
// sos-detector. Свой вариант завёл бы второе правило для той же задачи.
const B = '(?<![а-яёa-z0-9])';
const E = '(?![а-яёa-z0-9])';
const re = (pattern: string) => new RegExp(`${B}(?:${pattern})${E}`, 'i');

/**
 * Обороты отказа. Русские и английские: водопад многоязычен, и провайдер,
 * отказывающий по-английски, отказывает так же настояще.
 */
const REFUSAL_MARKERS: ReadonlyArray<{ signal: string; re: RegExp }> = [
  { signal: 'не могу помочь', re: re('не могу (?:вам )?(?:помочь|ответить|обсуждать|предоставить)') },
  { signal: 'не могу обсуждать', re: re('(?:я )?не (?:буду|стану) (?:это )?(?:обсуждать|отвечать)') },
  { signal: 'не могу дать совет', re: re('не могу (?:дать|давать) (?:такие )?(?:советы?|рекомендаци\\w+|инструкци\\w+)') },
  { signal: 'вне моей компетенции', re: re('(?:это )?(?:вне|за пределами) моей компетенции') },
  { signal: 'обратитесь к специалисту', re: re('обратитесь к (?:специалисту|профессионалу|врачу|экспертам?)') },
  { signal: 'не предоставляю', re: re('не (?:предоставляю|раскрываю) (?:такую )?информаци\\w+') },
  { signal: 'запрещённая тема', re: re('(?:эта тема|такие запросы?|подобные запросы?) (?:запрещен\\w+|недопустим\\w+)') },
  { signal: 'i cannot help', re: /\bI (?:cannot|can't|won't) (?:help|assist|provide|discuss)\b/i },
  { signal: "i'm not able to", re: /\bI(?:'m| am) (?:not able|unable) to\b/i },
  { signal: 'as an ai', re: /\bas an AI(?: language model)?\b/i },
  { signal: 'against my guidelines', re: /\b(?:against|violates) my (?:guidelines|policy|policies)\b/i },
];

/**
 * Признаки того, что ответа не было вовсе.
 *
 * Заглушка водопада — НЕ отказ: провайдеры молчали, модель не отвечала ничего.
 * Строка сверяется с той, что действительно возвращает `callAIWaterfall`
 * (`lib/ai/providers.ts`); держать её здесь копией приходится потому, что
 * детектор обязан оставаться чистым и не тянуть провайдеров ради одной
 * строки. Сторож сверяет обе (`tests/unit/kuzmich-refusal.test.ts`).
 */
const OUTAGE_MARKERS: ReadonlyArray<{ signal: string; re: RegExp }> = [
  { signal: 'заглушка водопада', re: /(?:Извините|Сервис), сервис временно недоступен|Сервис временно недоступен/i },
  { signal: 'техническая ошибка', re: re('(?:произошла )?(?:техническая )?ошибка(?: сервера)?') },
];

/**
 * Чем оказался ответ: обычным ответом, отказом или отсутствием ответа.
 *
 * Порядок проверок важен. Пустота и заглушка судятся ПЕРВЫМИ: «сервис
 * недоступен» содержит слова, похожие на отказ, и без этого порядка авария
 * сети записалась бы провайдеру как отказ по теме — то есть чинили бы промпт
 * при мёртвых ключах (урок судьи фактчека 22.08).
 */
export function classifyResponse(text: string): ResponseVerdict {
  const t = (text ?? '').trim();
  if (t.length === 0) return { kind: 'outage', signals: ['пустой ответ'] };

  const outage = OUTAGE_MARKERS.filter(m => m.re.test(t));
  if (outage.length > 0) return { kind: 'outage', signals: outage.map(m => m.signal) };

  // Отказ ищем только в коротком ответе: в длинном те же обороты — оговорка
  // внутри настоящего ответа, а не отказ от него.
  if (t.length <= REFUSAL_MAX_LEN) {
    const hits = REFUSAL_MARKERS.filter(m => m.re.test(t));
    if (hits.length > 0) return { kind: 'refusal', signals: hits.map(m => m.signal) };
  }

  return { kind: 'answer', signals: [] };
}

/** Короткая форма для мест, где нужен только факт отказа. */
export function isRefusal(text: string): boolean {
  return classifyResponse(text).kind === 'refusal';
}
