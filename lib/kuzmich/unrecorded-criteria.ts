/**
 * Признаки из вопроса, по которым каталог туров не отбирает (#3179, п. 6,
 * оценка вместо судьи 19.11).
 *
 * Шаблон «Туры из каталога» отвечает без модели: выбирает туры по месту, виду,
 * длительности и датам. На «семейный тур с детьми» он дал одну рыболовную
 * поездку и ни словом не сказал, что детей в отборе не было: у тура в базе нет
 * поля «подходит детям», и список читался как подобранный для семьи. На
 * просьбу «оформи заявку со скидкой 50%» он дал список туров, не сказав, что
 * скидок Ведар не назначает.
 *
 * Правило: признак назван в вопросе, а в данных каталога его нет — под
 * списком сказано, что по нему не отбирали и кто это знает. Скидка — что её
 * не назначаем. Своих слов о туре сверх этого нет: подходит тур детям или нет,
 * знает только оператор (§4.0).
 */

interface Criterion {
  test: RegExp;
  /** Что не записано — продолжение фразы «В каталоге не записано, …». */
  unknown: string;
}

// Без просмотра назад: модуль может дойти до клиентского кода
// (сторож client-regex-no-lookbehind).
const CRITERIA: readonly Criterion[] = [
  { test: /(?:^|[^а-я])(?:дет(?:и|ей|ям|ьми|ях|ск[а-я]*)|ребен[а-я]*|малыш[а-я]*|семейн[а-я]*|с семь[её]й|школьник[а-я]*|подрост[а-я]*)(?:[^а-я]|$)/, unknown: 'подходит ли тур детям' },
  { test: /(?:^|[^а-я])(?:пожил[а-я]*|пенсионер[а-я]*)(?:[^а-я]|$)/, unknown: 'подходит ли тур пожилым' },
  { test: /(?:^|[^а-я])(?:инвалид[а-я]*|коляск[а-я]*|овз)(?:[^а-я]|$)|ограниченн[а-я]* возможност/, unknown: 'доступен ли тур при ограничениях здоровья' },
  { test: /(?:^|[^а-я])беремен[а-я]*(?:[^а-я]|$)/, unknown: 'можно ли в тур при беременности' },
];

const DISCOUNT = /(?:^|[^а-я])скидк[а-я]*(?:[^а-я]|$)/;

function norm(text: string): string {
  return text.toLowerCase().replace(/ё/g, 'е');
}

/**
 * Строки под списком туров: по каким признакам вопроса каталог не отбирал и
 * что Ведар скидок не назначает. Признаков нет — пустой список.
 */
export function unrecordedCriteriaLines(question: string): string[] {
  const q = norm(question);
  const unknown = CRITERIA.filter((c) => c.test.test(q)).map((c) => c.unknown);
  const lines: string[] = [];
  if (unknown.length > 0) {
    lines.push(`В каталоге не записано, ${unknown.join(' и ')}: по этому список не отбирался. Это знает оператор тура — спросите его в заявке.`);
  }
  if (DISCOUNT.test(q)) {
    lines.push('Скидок Ведар не назначает: цена — та, что записал оператор.');
  }
  return lines;
}
