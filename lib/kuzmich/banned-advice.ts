/**
 * Опасные советы, которые не уходят туристу ни на одной поверхности.
 * Проверка перед отправкой: предложение с таким советом вырезается,
 * а в конец ответа ставится проверенный номер 112.
 *
 * Экзамен 22.10.2026 (#26) и eval-kuzmich 19.10 (bear-encounter): Кузьмич
 * советовал при нападении медведя «притворись мёртвым». Тот же запрет есть
 * в lib/kuzmich/safety-eval.ts (GOLDEN_CASES), здесь он применяется к живому
 * ответу. Отрицание («не притворяйся мёртвым») не вырезается.
 *
 * Второй запрет — выдуманная оценка безопасности способа или тура (ночной
 * эвал 17.11, commercial-op-mestechko-tolbachik): «вертолётный облёт — это
 * пока единственный безопасный способ увидеть Толбачик». Такой оценки нет ни
 * в одной сводке и ни в одной строке тура: сравнивать туры по безопасности
 * Ведару не по чему, а человек выберет по ней. Предложение вырезается без
 * строки взамен — остальной ответ (закрытый парк, опасность) остаётся.
 * Отрицание («не самый безопасный способ») — предупреждение, оно остаётся.
 */
const PLAY_DEAD = /(?<!не\s)притвор(?:ись|итесь|иться|яйся|яйтесь|яться)\s+(?:м[её]ртв|трупом)/iu;

/**
 * «Единственный / самый / наиболее безопасный способ (вариант, тур, маршрут…)»,
 * в том числе с одним прилагательным через «и» или запятую: «самый надёжный и
 * безопасный способ», «самый надёжный, безопасный способ» (#3494, 28.11).
 * Граница слова — руками: JS \b кириллицу не знает.
 */
const SAFETY_RANKING_RE = /(?<![а-яё])(?<!не\s)(?:единственн|сам|наиболее)[а-яё]*\s+(?:[а-яё]+(?:ый|ий|ой|ая|яя|ое|ее|ые|ие|ых|их|ым|им|ыми|ими|ому|ему|ую|юю|ою|ею|ого|его|ом|ем)(?:\s+и|,)\s+)?безопасн[а-яё]*\s+(?:способ|вариант|путь|тур|маршрут|выбор|решени|возможност)[а-яё]*(?![а-яё])/giu;

/**
 * «Самый безопасный из туров — облёт» (#3494, 28.11). Совпадение забирает и
 * оборот после «из» — до тире или двоеточия: предмет оценки стоит за ними, и
 * осторожный совет проверяется там. «Самый безопасный из вариантов —
 * переждать непогоду» — совет, он остаётся (доработка 28.11).
 */
const SAFEST_OF_RE = /(?<![а-яё])(?<!не\s)(?:единственн|сам|наиболее)[а-яё]*\s+безопасн[а-яё]*\s+из(?![а-яё])(?:(?!\s-\s)[^—–:.!?\n])*/giu;

/**
 * Превосходная степень со связкой (#3494, 28.11): «самым безопасным (здесь)
 * будет вертолётный тур». Связки — «будет / станет / окажется / является»;
 * голое «самый безопасный» без них и без тире — не обязательно оценка способа.
 */
const SAFEST_PREDICATE_RE = /(?<![а-яё])(?<!не\s)(?:единственн|сам|наиболее)[а-яё]*\s+безопасн[а-яё]*\s+(?:(?:здесь|тут|там|сейчас)\s+)?(?:будет|станет|окажется|является)(?![а-яё])/giu;

/** «Самый безопасный — облёт» (доработка 28.11): за тире или двоеточием — предмет оценки. */
const SAFEST_DASH_RE = /(?<![а-яё])(?<!не\s)(?:единственн|сам|наиболее)[а-яё]*\s+безопасн[а-яё]*(?=\s*[—–:])/giu;

/** «Наиболее безопасен облёт» (доработка 28.11): краткая форма. */
const MOST_SAFE_SHORT_RE = /(?<![а-яё])(?<!не\s)наиболее\s+безопас(?:ен|на|но|ны)(?![а-яё])/giu;

/** «Безопаснее всего / всех …» (#3494, 28.11). */
const SAFEST_OF_ALL_RE = /(?<![а-яё])(?<!не\s)безопаснее\s+(?:всего|всех)(?![а-яё])/giu;

/**
 * «Только вертолётом / облётом / на вертолёте / с вертолёта / туром … безопасно»
 * и обратный порядок «безопасно только вертолётом» (#3494, 28.11). Список
 * ЗАКРЫТЫЙ: «только с гидом … безопасно» — осторожный совет, он остаётся.
 */
const ONLY_HOW = String.raw`только\s+(?:вертол[её]том|обл[её]том|на\s+вертол[её]те|с\s+вертол[её]та|туром)(?![а-яё])`;
const ONLY_SAFE_RE = new RegExp(String.raw`(?<![а-яё])(?<!не\s)${ONLY_HOW}[^.!?\n]*?(?<![а-яё])безопас(?:н|ен)[а-яё]*`, 'giu');
const SAFE_ONLY_RE = new RegExp(String.raw`(?<![а-яё])(?<!не\s)безопас(?:н|ен)[а-яё]*(?![а-яё])[^.!?\n]*?(?<![а-яё])${ONLY_HOW}`, 'giu');

/**
 * Осторожный совет — не оценка тура: «самый безопасный вариант — отложить
 * поход», «… сейчас — остаться в укрытии и звонить 112». Он защищает, и он
 * остаётся. Осторожным считается только САМ предмет оценки — действие сразу
 * после тире или двоеточия. Осторожное слово дальше в предложении оценку не
 * спасает: «единственный безопасный способ увидеть Толбачик, пешком туда не
 * поднимаются» — выдумка (ревью безопасности PR #3495).
 *
 * С 28.11 (доработка #3886) осторожное — и «пойти с гидом», «сообщить о
 * маршруте в МЧС», «зарегистрировать группу», «держаться тропы»: «безопаснее
 * всего пойти с гидом» — совет, а не оценка тура.
 */
const WHEN = String.raw`(?:сейчас|теперь|пока|здесь|сегодня)?`;
const CAUTION_ACTION = String.raw`(?:это\s+)?(?:отлож|отказ|остат|остан|переждат|подожд|дожд|вернут|перенест|укрыт|(?:никуда\s+)?не\s+(?:выход|ход|ехат|езди|подним)|(?:по)?звони|(?:(?:пойти|идти|ходить)\s+)?с\s+гидом|сообщ[а-яё]*[^.!?\n]{0,40}?мчс|(?:за)?регистрир|держат[а-яё]*\s+(?:троп|маршрут)[а-яё]*)`;
const CAUTION_AFTER = new RegExp(String.raw`^\s*${WHEN}\s*[—–:-]\s*${CAUTION_ACTION}`, 'iu');
/**
 * У «безопаснее всего …» и «самым безопасным будет …» предмет оценки стоит
 * сразу за ними и без тире: «безопаснее всего остаться в укрытии», «самым
 * безопасным будет отложить поход» — тоже осторожный совет.
 */
const CAUTION_NEXT = new RegExp(String.raw`^\s*${WHEN}\s*(?:[—–:-]\s*)?${CAUTION_ACTION}`, 'iu');

/**
 * Все формы оценки и проверка осторожного совета после каждой. Отрицание
 * («не самый безопасный способ», «не только вертолётом») стоит в каждом
 * выражении — `(?<!не\s)`.
 */
const SAFETY_RANKINGS: ReadonlyArray<{ re: RegExp; caution: RegExp }> = [
  { re: SAFETY_RANKING_RE, caution: CAUTION_AFTER },
  { re: SAFEST_OF_RE, caution: CAUTION_AFTER },
  { re: SAFEST_PREDICATE_RE, caution: CAUTION_NEXT },
  { re: SAFEST_DASH_RE, caution: CAUTION_AFTER },
  { re: MOST_SAFE_SHORT_RE, caution: CAUTION_NEXT },
  { re: SAFEST_OF_ALL_RE, caution: CAUTION_NEXT },
  { re: ONLY_SAFE_RE, caution: CAUTION_AFTER },
  { re: SAFE_ONLY_RE, caution: CAUTION_AFTER },
];

/** Есть ли в тексте выдуманная оценка безопасности способа или тура (не осторожный совет). */
export function hasSafetyRanking(text: string): boolean {
  for (const { re, caution } of SAFETY_RANKINGS) {
    for (const m of text.matchAll(re)) {
      const after = text.slice((m.index ?? 0) + m[0].length);
      if (!caution.test(after)) return true;
    }
  }
  return false;
}

/**
 * Третий запрет — SMS на 112 как совет (разбор 19.11, #3179 п.4): «СМС на 112
 * доходит при слабом сигнале лучше звонка». Работает ли SMS-112 на Камчатке,
 * не подтверждено — вопрос ждёт ответа МЧС (.claude/MEMORY.md). Человек в беде
 * отправит сообщение и будет ждать ответа, которого может не быть. Вырезается
 * предложение, где SMS и 112 стоят рядом; оговорка «не работает», «не
 * подтверждено» — не совет, она остаётся. Звонок 112 в ответе остаётся.
 */
const SMS_112_RE = /(?<![а-яёa-z])(?:смс|sms|эсэмэс)[^.!?\n]{0,60}112|112[^.!?\n]{0,60}(?<![а-яёa-z])(?:смс|sms|эсэмэс)/iu;
const SMS_112_CAVEAT = /не\s+(?:работ|доход|подтвержд|проверен|гарантир)|неизвестно|не\s+знаем/iu;

export function hasSms112Advice(sentence: string): boolean {
  return SMS_112_RE.test(sentence) && !SMS_112_CAVEAT.test(sentence);
}

export const BANNED_ADVICE_NOTE = 'При нападении зверя звони 112: это работает без баланса и SIM.';

export interface BannedAdviceResult {
  text: string;
  /** Вырезанный совет «притворись мёртвым» — к ответу дописан 112. */
  removed: string[];
  /** Вырезанная выдуманная оценка безопасности способа или тура. */
  ranking: string[];
  /** Вырезанный совет писать SMS на 112 (работает ли на Камчатке — не подтверждено). */
  sms112: string[];
}

function cut(answer: string, banned: (sentence: string) => boolean, into: string[]): string {
  return answer
    .split('\n')
    .map((line) => line
      .split(/(?<=[.!?…])\s+/u)
      .filter((s) => {
        if (banned(s)) { into.push(s); return false; }
        return true;
      })
      .join(' '))
    .join('\n')
    .replace(/\n{3,}/g, '\n\n')
    .trim();
}

export function stripBannedAdvice(answer: string): BannedAdviceResult {
  const hasPlayDead = PLAY_DEAD.test(answer);
  const hasRanking = hasSafetyRanking(answer);
  const hasSms = SMS_112_RE.test(answer);
  if (!hasPlayDead && !hasRanking && !hasSms) return { text: answer, removed: [], ranking: [], sms112: [] };
  const removed: string[] = [];
  const ranking: string[] = [];
  const sms112: string[] = [];
  // Режем по предложениям, сохраняя абзацы.
  let text = hasPlayDead ? cut(answer, (x) => PLAY_DEAD.test(x), removed) : answer;
  if (hasRanking) text = cut(text, hasSafetyRanking, ranking);
  if (hasSms) text = cut(text, hasSms112Advice, sms112);
  return { text: removed.length > 0 ? `${text}\n\n${BANNED_ADVICE_NOTE}` : text, removed, ranking, sms112 };
}
