/**
 * Какие записи agent_knowledge Кузьмич отдаёт наружу — разрешённым списком.
 *
 * Проверка MCP 29.09. Три читателя (контекст промпта каждого чата,
 * get_place_info, get_guardian_context) отсекали только `type <> 'outcome'`,
 * а в той же таблице Кузьмич копит ещё два рода, которых человеку показывать
 * нельзя:
 *   - `search_result` — заголовок = сообщение туриста как есть (core.ts,
 *     saveSearchResultToKB с userContent), тело — сниппет веб-поиска;
 *   - `auto_gap` — заголовок = тема из вопросов туристов, при отказе
 *     AI-дедупа — сам вопрос дословно (крон kb-gap).
 * Совпадение по ILIKE отдавало вопрос одного туриста анонимному MCP-клиенту
 * (поиск по «+79», «меня зовут»), а пятьдесят свежих таких строк шли в
 * системный промпт КАЖДОГО чата — в зарубежную модель и в ответы другим
 * людям (152-ФЗ). Запрет по одному роду ломался с каждым новым родом, как
 * сломался с этими двумя; разрешённый список держит новое снаружи, пока его
 * не внесли сюда осознанно.
 *
 * В списке только курируемое: миграции 141 (place/faq/transport) и 669
 * (indigenous). `pattern` — служебная статистика броней, `outcome` — оценки
 * ответов; ни то, ни другое не знание о крае.
 */
export const KUZMICH_KNOWLEDGE_TYPES = ['place', 'faq', 'transport', 'indigenous'] as const;

export const KUZMICH_KNOWLEDGE_SCOPE_SQL =
  `agent_id = 'kuzmich' AND type IN (${KUZMICH_KNOWLEDGE_TYPES.map((t) => `'${t}'`).join(', ')})`;
