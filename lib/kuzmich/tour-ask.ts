/**
 * lib/kuzmich/tour-ask.ts
 *
 * Вопрос про ОДИН названный тур — не просьба показать список туров.
 *
 * Кнопка «Спросить Кузьмича» на карточке тура (§11) шлёт в чат
 * `tourAskQuestion(title)`. До 07.11 сборщик витрины (`composeCommercial`)
 * принимал этот вопрос за «какие туры идут сегодня». Зимний тур вне сезона
 * получал ответ «На сегодня в каталоге нет тура, который идёт. Цену не
 * называю» — о самом туре ни слова, хотя программа, состав и «что взять»
 * лежат в его карточке. Случай — чат гостя 07.11, тур «К Домашним вулканам на
 * вездеходе Sever Truck».
 *
 * На такой вопрос отвечает модель с инструментом `get_tour_details`. Цены в её
 * ответе сверяются с выводом инструментов (`dropUnsourcedPrices`), так что
 * правило «цену — только из источника» остаётся в силе.
 */

/** Вопрос кнопки «Спросить Кузьмича» на карточке тура. */
export function tourAskQuestion(title: string): string {
  return `Расскажи про тур «${title}»: подходит ли он мне, что взять и как оставить заявку?`;
}

/**
 * Название тура, если вопрос — про один тур, названный в кавычках сразу после
 * слова «тур» (в любом падеже единственного числа). Иначе null.
 * «Какие туры есть, кроме «…»» — список, а не один тур: null.
 */
export function namedTourInQuestion(text: string): string | null {
  // Без lookbehind: модуль читает и карточка тура в браузере, а Safari < 16.4
  // падает на нём при загрузке (client-regex-no-lookbehind).
  const m = /(?:^|[^а-яёa-z0-9])тур(?:а|е|у|ом)?\s*[«"„“]([^»"”“]{3,160})[»"”“]/iu.exec(text);
  return m ? m[1].trim() : null;
}

/** Слово «тур» в любом падеже и числе — само слово, а не начало «туриста». */
const TOUR_WORD = /(?:^|[^а-яёa-z0-9])тур(?:ы|а|ов|ам|ами|ах|е|у|ом)?(?![а-яёa-z0-9])/iu;
/** Глагол или существительное сравнения: «сравни», «сравнить», «сравнение», но не «сравнительно». */
const COMPARE_WORD = /(?:^|[^а-яёa-z0-9])(?:сравн(?:и|ите|ить|им|ение|ения|ению|ением)(?![а-яё])|чем\s+(?:они\s+)?отлича|в\s+ч[её]м\s+разниц|разниц[аеуы]\s+между)/iu;
/** «Что лучше», «какой выбрать» — выбор между названными. */
const CHOOSE_WORD = /(?:^|[^а-яёa-z0-9])(?:что|какой|какую|какое)\s+(?:(?:из\s+них|тур)\s+)?(?:лучше|выбрать)/iu;
/** Название в кавычках. */
const QUOTED = /[«"„“][^»"”“]{3,160}[»"”“]/g;

/**
 * Просьба сравнить туры — не просьба показать список туров.
 *
 * ai-debug run 23 (07.11): на «Сравни туры «Трекинг к подножию вулкана
 * Ключевская Сопка» и «К Домашним вулканам на вездеходе Sever Truck»: чем
 * отличаются?» ответила витрина: «На сегодня в каталоге нет тура, который
 * идёт. Цену не называю». `namedTourInQuestion` ловит один тур после слова
 * «тур», а здесь «туры» и два названия. Сравнение собирает модель инструментом
 * `compare_tours` — цены и даты в нём из базы, по одному правилу с карточкой.
 *
 * Сравнение — если есть слово сравнения и слово «тур» либо два названия в
 * кавычках; выбор («что лучше: «…» или «…»») — если слово «тур» и два
 * названия. «Какие туры сравнительно недорогие» — список: «сравнительно» не
 * сравнение.
 */
export function asksTourComparison(text: string): boolean {
  const quoted = (text.match(QUOTED) ?? []).length;
  const tour = TOUR_WORD.test(text);
  if (COMPARE_WORD.test(text) && (tour || quoted >= 2)) return true;
  return CHOOSE_WORD.test(text) && tour && quoted >= 2;
}

/** Человек спрашивает, как подать заявку или записаться. */
const ASKS_HOW_TO_APPLY = /как\s+(?:мне\s+)?(?:оставить|подать|отправить|оформить)\s+заявк|как\s+(?:мне\s+)?(?:записаться|забронировать|заказать)/i;

/** Адрес карточки тура в выводе инструмента (`get_tour_details`, `get_tour_availability`). */
const TOUR_CARD_URL = /https?:\/\/[^\s"'<>)]+\/catalog\/tours\/[A-Za-z0-9_-]+/g;

/**
 * Ссылка на заявку под ответом о названном туре (07.11, чат гостя о туре
 * «Трекинг к подножию вулкана Ключевская Сопка»): человек спросил «как
 * оставить заявку», модель ответила про безопасность, снаряжение и опыт, а на
 * третий вопрос — ни слова. Сторож дописывает адрес, только если:
 * - вопрос о ОДНОМ названном туре и о заявке;
 * - ответ адреса карточки не назвал;
 * - адрес ровно один в выводе инструментов хода — своего сервер не сочиняет.
 */
export function appendTourApplyLink(
  answer: string,
  question: string,
  toolRuns: ReadonlyArray<{ output?: string }> | null,
): string {
  if (!answer.trim() || namedTourInQuestion(question) === null || !ASKS_HOW_TO_APPLY.test(question)) return answer;
  if (/\/catalog\/tours\//.test(answer)) return answer;
  const urls = new Set<string>();
  for (const run of toolRuns ?? []) for (const m of (run.output ?? '').matchAll(TOUR_CARD_URL)) urls.add(m[0]);
  if (urls.size !== 1) return answer;
  const [url] = [...urls];
  return `${answer.trim()}\n\nЗаявка — на странице тура: ${url}#booking. Это заявка, не бронь: даты и места подтверждает оператор.`;
}
