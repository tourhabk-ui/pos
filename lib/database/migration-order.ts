/**
 * lib/database/migration-order.ts
 *
 * Порядок миграций — по ЧИСЛУ, а не по строке.
 *
 * ── Повод (20.09, на пороге тысячной миграции) ────────────────────────────
 *
 * Имена миграций везде сортировались обычным `.sort()`, то есть посимвольно.
 * Пока номеров было три знака, посимвольный порядок совпадал с числовым, и
 * никто не замечал разницы. На 1000-й они расходятся: `'1000_'` меньше
 * `'999_'` (`'1' < '9'`) и меньше `'100_'` — на четвёртом символе `'0' < '_'`.
 * То есть тысячная миграция встала бы перед ВСЕМИ от сотой до девятьсот
 * девяносто девятой, включая те, что заводят сами таблицы.
 *
 * Это не косметика. `scripts/migrate-standalone.js` — боевой раннер: его
 * зовёт `start.js` при каждом выкате на Timeweb. На проде, где всё до 999
 * уже применено, беда не видна (в очереди одна миграция, порядок
 * бессмысленен), и именно поэтому ошибка дожила бы до первого чистого
 * инстанса — или до дня, когда в очередь разом попадут 999-я и 1000-я.
 *
 * ── Почему отдельный модуль, а не аккуратный компаратор на каждом месте ───
 *
 * Мест, полагавшихся на порядок или на трёхзначность номера, нашлось
 * тринадцать, и правило, написанное тринадцать раз, — это тринадцать правил
 * (тот же довод, что у §12 про вид линии).
 * Здесь оно одно, и сторож `tests/unit/migration-order.test.ts` держит
 * связку: новый `.sort()` по именам миграций краснеет.
 *
 * ── Третий исход ──────────────────────────────────────────────────────────
 *
 * Имя без числового префикса — это НЕ «номер ноль» и не «в конец молча».
 * `migrationNumber` возвращает `null`, `sortMigrations` уводит такие файлы в
 * хвост в алфавитном порядке, а `unnumberedMigrations` даёт их списком —
 * чтобы вызывающий мог сказать вслух, что разобрать не смог (§4.0).
 */

/**
 * `1000_name.sql` → 1000, `144a_name.sql` → 144. Нет префикса — `null`, не 0.
 *
 * Буквенный суффикс — не выдумка на будущее: в каталоге лежат `144a`, `144b`
 * и `144c` (создание таблицы, индекс, посев — разнесены по файлам, потому что
 * их нельзя было катить одной транзакцией). Первая редакция этого модуля их
 * не разбирала и молча уводила в хвост, то есть посев прошёл бы раньше
 * создания таблицы. Нашёл это собственный сторож, а не прод.
 */
export function migrationNumber(file: string): number | null {
  const m = /^(\d+)[a-z]*_/i.exec(file);
  if (!m) return null;
  const n = Number(m[1]);
  return Number.isSafeInteger(n) ? n : null;
}

/** Буква после номера: `144a` → `'a'`, `999` → `''`. Порядок внутри номера. */
export function migrationSuffix(file: string): string {
  const m = /^\d+([a-z]*)_/i.exec(file);
  return m ? m[1].toLowerCase() : '';
}

/**
 * Порядок применения: по номеру, при равном номере — по имени.
 *
 * Равные номера — не выдумка: коллизии уже случались трижды за один день
 * (три миграции 991 от трёх сессий). Их ловит `migration-number-unique`, а
 * здесь важно лишь, чтобы порядок был ОДИНАКОВЫМ у всех читателей, а не
 * зависел от того, в каком порядке файловая система отдала каталог.
 */
export function compareMigrations(a: string, b: string): number {
  const na = migrationNumber(a);
  const nb = migrationNumber(b);
  if (na === null && nb === null) return a < b ? -1 : a > b ? 1 : 0;
  if (na === null) return 1;   // безномерные — в хвост
  if (nb === null) return -1;
  if (na !== nb) return na - nb;
  // Один номер, разные буквы: `144a` раньше `144b`. Буква значима — она и
  // заводит порядок внутри номера (таблица, потом индекс, потом посев).
  const sa = migrationSuffix(a);
  const sb = migrationSuffix(b);
  if (sa !== sb) return sa < sb ? -1 : 1;
  return a < b ? -1 : a > b ? 1 : 0;
}

/** Новый массив в порядке применения. Исходный не меняется. */
export function sortMigrations(files: readonly string[]): string[] {
  return [...files].sort(compareMigrations);
}

/** Файлы без числового префикса — «не смог разобрать», а не «ноль». */
export function unnumberedMigrations(files: readonly string[]): string[] {
  return files.filter((f) => migrationNumber(f) === null);
}

/**
 * Миграция новее baseline?
 *
 * Заменяет строковое `name >= '863'`, которое на четырёхзначном номере даёт
 * ЛОЖЬ (`'1' < '8'`): интеграционные тесты сбрасывают `_migrations` именно
 * этим предикатом, и тысячная миграция осталась бы помеченной применённой,
 * не переигравшись в тестовой базе. Файл без номера новее baseline НЕ
 * считается: неизвестное не выдаётся за известное.
 */
export function isAfterBaseline(file: string, baseline: number): boolean {
  const n = migrationNumber(file);
  return n !== null && n >= baseline;
}

/** Последняя по порядку применения. Пусто — `null`, а не выдуманное имя. */
export function lastMigration(files: readonly string[]): string | null {
  const sorted = sortMigrations(files);
  return sorted.length > 0 ? sorted[sorted.length - 1]! : null;
}
