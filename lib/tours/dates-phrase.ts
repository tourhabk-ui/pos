/**
 * Фраза про даты тура: просят ли в ней ОТКРЫТЬ даты, и какие (22.10, «Открой
 * даты словами»). Чистые функции, без базы.
 *
 * Помощник кабинета (`OperatorAgency.addSlots`) получает фразу по ключу
 * классификатора — «слоты на», «новые слоты», «открой даты», «добавь даты».
 * Ключ не видит, чего человек хочет на самом деле: «закрой слоты на 5 июля,
 * группа набрана» содержит «слоты на» и до 22.10 открывала дату на 8 мест —
 * ровно обратное просьбе, и туристы бронировали сверх группы, набранной вне
 * платформы. Чат кабинета (этап C) разбирает фразы тем же правилом: одна
 * функция, а не две похожие регулярки, которые разойдутся.
 *
 * Опасное направление закрыто РАЗРЕШАЮЩИМ списком, а не запретным (ревью
 * 22.10). Список глаголов закрытия всегда неполон: «заблокируй», «скрой»,
 * «стоп» его обходили и открывали дату. Поэтому открывается только фраза, где
 * есть глагол открытия («открой», «добавь», «выставь»), нет закрытия,
 * отрицания или исключения и которая не вопрос: «есть ли свободные слоты на
 * 5 июля для 8 человек?» — вопрос, а не просьба. Список закрытия остаётся —
 * он даёт понятный ответ («закрывают в кабинете»), а не защиту.
 *
 * `\b` в регулярках JavaScript кириллицу не знает (граница слова там — по
 * ASCII), поэтому границы — через `\p{L}` с флагом `u`.
 */

/** Почему фразу нельзя исполнить как «открыть даты». */
export type DatesPhraseRefusal =
  /** Просят закрыть, убрать, снять, скрыть, остановить, уменьшить — это делается в кабинете. */
  | { kind: 'close'; word: string }
  /** «не открывай», «не надо открывать». */
  | { kind: 'negation'; word: string }
  /** «кроме 17-го», «без 5», «не считая» — исключение из перечня. */
  | { kind: 'exception'; word: string }
  /** Вопрос («?», «есть ли», «сколько»): спрашивают, а не просят открыть. */
  | { kind: 'question'; word: string }
  /** Нет глагола открытия: «новые слоты на …», «слоты на … 8 человек». */
  | { kind: 'no_open_verb' };

const NOT_LETTER_BEFORE = '(?<![\\p{L}\\p{N}])';

/**
 * Глаголы закрытия и уменьшения: закрой, убери/убрать, удали, сними/снять,
 * отмени, заблокируй/блокируй, скрой/скрыть, отключи, выключи, останови,
 * приостанови, стоп, прекрати, уменьши, сократи, убавь. «Остановка» (место
 * сбора) — не глагол: у «останов» только формы просьбы.
 */
const CLOSE = new RegExp(
  `${NOT_LETTER_BEFORE}(закр|убер|убир|убра|удал|сним|снят|отмен|заблок|блок|скро|скры|отключ|выключ` +
  '|останов(?:и|ить|ите)|останавлив|приостан|стоп|прекрат|уменьш|сократ|убав)\\p{L}*',
  'iu',
);
/** Отрицание открытия: «не открывай», «не надо открывать», «нельзя добавлять». */
const NEGATION = new RegExp(
  `${NOT_LETTER_BEFORE}(?:не|нельзя)\\s+(?:(?:надо|нужно|стоит|будем|буду|могу)\\s+)?(?:откр|добав|выстав|став|вывод)\\p{L}*`,
  'iu',
);
/** Исключения из перечня дат. */
const EXCEPTION = new RegExp(
  `${NOT_LETTER_BEFORE}(?:кроме|исключая|за\\s+исключением|не\\s+считая)(?![\\p{L}])|${NOT_LETTER_BEFORE}без\\s+\\d+(?:-?\\p{L}+)?`,
  'iu',
);
/** Вопрос: знак вопроса, частица «ли», «сколько», «покажи». */
const QUESTION = new RegExp(`\\?|${NOT_LETTER_BEFORE}(?:ли|сколько|покаж\\p{L}*)(?![\\p{L}])`, 'iu');
/**
 * Глагол открытия — формы просьбы и неопределённая форма («нужно открыть»):
 * открой/откройте/открыть/открывай, добавь/добавить/добавляй,
 * выставь/выставить/выставляй. «Открыты» и «открытые» — не просьба.
 */
const OPEN_VERB = new RegExp(
  `${NOT_LETTER_BEFORE}(?:откр(?:ой|ойте|ыть|ывай|ывайте)|добав(?:ь|ьте|ить|ляй|ляйте)|выстав(?:ь|ьте|ить|ляй|ляйте))(?![\\p{L}])`,
  'iu',
);

/**
 * Отказ для фразы — или null, если по ней можно открывать. Ложный отказ
 * дешевле ложного открытия: отказ ничего не пишет, человек переформулирует;
 * открытие, о котором не просили, продаёт места, которых нет.
 */
export function datesPhraseRefusal(text: string): DatesPhraseRefusal | null {
  const t = text.replace(/ё/gi, 'е');
  const neg = t.match(NEGATION);
  if (neg) return { kind: 'negation', word: neg[0] };
  const close = t.match(CLOSE);
  if (close) return { kind: 'close', word: close[0] };
  const exc = t.match(EXCEPTION);
  if (exc) return { kind: 'exception', word: exc[0] };
  const q = t.match(QUESTION);
  if (q) return { kind: 'question', word: q[0] };
  if (!OPEN_VERB.test(t)) return { kind: 'no_open_verb' };
  return null;
}

/**
 * Ограничение днями недели или периодичностью: «по субботам», «выходные»,
 * «будни», «сб», «через день», «по чётным», «раз в неделю». Слово — или null.
 *
 * Помощник кабинета разбирает только даты числами (ISO) и диапазон между
 * ними; ограничение днём он не применит, а молча открыл бы каждый день
 * диапазона: «добавь слоты по субботам с 1 по 31 июля» открывала 31 дату
 * вместо пяти (ревью 22.10). Чат кабинета (этап C) дни недели разбирает сам и
 * этой функцией не отказывает.
 */
export function dayFilterWord(text: string): string | null {
  const t = text.replace(/ё/gi, 'е');
  const m = t.match(DAY_FILTER);
  return m ? m[0] : null;
}

const DAY_FILTER = new RegExp(
  `${NOT_LETTER_BEFORE}(?:понедельн\\p{L}*|вторник\\p{L}*|сред(?:а|у|ы|ам|ами|ах)|четверг\\p{L}*|пятниц\\p{L}*` +
  '|суббот\\p{L}*|воскресен\\p{L}*|выходн\\p{L}*|будн\\p{L}*|(?:пн|вт|ср|чт|пт|сб|вс)' +
  '|через\\s+(?:день|\\d+\\s*дн\\p{L}*)|нечетн\\p{L}*|четн\\p{L}*|еженедельн\\p{L}*|кажд\\p{L}*\\s+недел\\p{L}*|раз\\s+в\\s+недел\\p{L}*)(?![\\p{L}])',
  'iu',
);

/** Дата ISO во фразе — целиком, не кусок длинного числа. Перед ней может стоять дефис: «2027-07-01-2027-07-31». */
export const ISO_DATE_IN_PHRASE = /(?<![\d.])(\d{4}-\d{2}-\d{2})(?![\d.])/g;

/** Что стоит между двумя датами, чтобы это был диапазон: «по», «до», тире, дефис. */
const RANGE_LINK = /^(?:по|до|-|–|—|…|\.\.\.?)$/iu;
/** Что стоит между датами перечня: запятая, «и», «, и», точка с запятой. */
const LIST_LINK = /^(?:,|;|и|,\s*и)$/iu;
/** Одна дата после слова начала или конца диапазона: «с 2027-07-01», «до 2027-07-31». */
const HALF_RANGE = /(?:^|[^\p{L}])(?:с|со|от|по|до|начиная\s+с)\s*$/iu;

/** Даты ISO во фразе и как они связаны. */
export type IsoDatesInPhrase =
  | { kind: 'none' }
  /** «с A по B», «A — B», «A-B»: все дни между ними. */
  | { kind: 'range'; from: string; to: string }
  /** Одна дата или перечень через запятую или «и»: ровно эти даты. */
  | { kind: 'list'; dates: string[] }
  /**
   * Связь не названа: «A B», «A или B», «с A, B по C», одна дата после «с»
   * или «до». Догадка здесь — открыть лишнее или не то, поэтому вопрос.
   */
  | { kind: 'unclear'; dates: string[] };

/**
 * Даты ISO и их связь. Диапазон — только при явной связке между ДВУМЯ датами;
 * до 22.10 любые две даты читались диапазоном, и «2027-08-05 и 2027-08-12»
 * открывала восемь дат вместо двух (ревью 22.10).
 */
export function isoDatesInPhrase(text: string): IsoDatesInPhrase {
  const t = text.replace(/ё/gi, 'е');
  const found = [...t.matchAll(ISO_DATE_IN_PHRASE)].map((m) => ({ date: m[1]!, start: m.index!, end: m.index! + m[0].length }));
  if (found.length === 0) return { kind: 'none' };
  const dates = found.map((f) => f.date);
  if (found.length === 1) {
    return HALF_RANGE.test(t.slice(0, found[0]!.start)) ? { kind: 'unclear', dates } : { kind: 'list', dates };
  }
  const links = found.slice(1).map((f, i) => t.slice(found[i]!.end, f.start).trim());
  if (found.length === 2 && RANGE_LINK.test(links[0]!)) return { kind: 'range', from: dates[0]!, to: dates[1]! };
  if (links.every((l) => LIST_LINK.test(l))) return { kind: 'list', dates: [...new Set(dates)].sort() };
  return { kind: 'unclear', dates };
}

/**
 * Есть ли во фразе цена. Числа, которые уже съедены (даты, номер тура,
 * места), вызывающий вырезает сам: голое число от 1000 в остатке — цена
 * («по 15000», «15 000»), а «2027» из даты ценой не считается.
 */
export function phraseMentionsPrice(rest: string): boolean {
  const t = rest.replace(/ё/gi, 'е');
  if (t.includes('₽')) return true;
  // Перед «руб»/«р.» может стоять число («500р.»), но не буква: «Горелый» не цена.
  if (/(?<!\p{L})(?:руб|р\.|цен[аеуыо]|стоимост)/iu.test(t)) return true;
  const nums = t.match(/(?<![\d.,])\d{1,3}(?:[  ]\d{3})+(?![\d.,])|(?<![\d.,])\d+(?![\d.,])/gu) ?? [];
  return nums.some((n) => Number(n.replace(/[  ]/g, '')) >= 1000);
}
