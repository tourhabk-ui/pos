/**
 * Фраза про даты тура: что в ней не даёт ОТКРЫВАТЬ даты (22.10, «Открой даты
 * словами»). Чистые функции, без базы.
 *
 * Помощник кабинета (`OperatorAgency.addSlots`) получает фразу по ключу
 * классификатора — «слоты на», «открой даты», «добавь даты». Ключ не видит,
 * чего человек хочет на самом деле: «закрой слоты на 5 июля, группа набрана»
 * содержит «слоты на» и до 22.10 открывала дату на 8 мест — ровно обратное
 * просьбе, и туристы бронировали сверх группы, набранной вне платформы.
 * Чат кабинета (этап C) разбирает фразы тем же правилом: одна функция, а не
 * две похожие регулярки, которые разойдутся.
 *
 * `\b` в регулярках JavaScript кириллицу не знает (граница слова там — по
 * ASCII), поэтому границы — через `\p{L}` с флагом `u`.
 */

/** Почему фразу нельзя исполнить как «открыть даты». */
export type DatesPhraseRefusal =
  /** Просят закрыть, убрать, снять, отменить — закрывают в кабинете. */
  | { kind: 'close'; word: string }
  /** «не открывай», «не надо открывать». */
  | { kind: 'negation'; word: string }
  /** «кроме 17-го», «без 5», «не считая» — исключение из перечня. */
  | { kind: 'exception'; word: string };

const NOT_LETTER_BEFORE = '(?<![\\p{L}\\p{N}])';

/** Глаголы закрытия: закрой/закрыть, убери/убрать/убирай, удали, сними/снять, отмени. */
const CLOSE = new RegExp(`${NOT_LETTER_BEFORE}(закр|убер|убир|убра|удал|сним|снят|отмен)\\p{L}*`, 'iu');
/** Отрицание открытия: «не открывай», «не надо открывать», «нельзя добавлять». */
const NEGATION = new RegExp(
  `${NOT_LETTER_BEFORE}(?:не|нельзя)\\s+(?:(?:надо|нужно|стоит|будем|буду|могу)\\s+)?(?:откр|добав|став|вывод)\\p{L}*`,
  'iu',
);
/** Исключения из перечня дат. */
const EXCEPTION = new RegExp(
  `${NOT_LETTER_BEFORE}(?:кроме|исключая|за\\s+исключением|не\\s+считая)(?![\\p{L}])|${NOT_LETTER_BEFORE}без\\s+\\d+(?:-?\\p{L}+)?`,
  'iu',
);

/**
 * Отказ для фразы — или null, если открывать по ней можно. Ложный отказ
 * дешевле ложного открытия: отказ ничего не пишет, человек переформулирует;
 * открытие, о котором не просили, продаёт места, которых нет.
 */
export function datesPhraseRefusal(text: string): DatesPhraseRefusal | null {
  const t = text.replace(/ё/gi, 'е');
  const neg = t.match(NEGATION);
  if (neg) return { kind: 'negation', word: neg[0] };
  const close = t.match(CLOSE);
  if (close) return { kind: 'close', word: close[0] };
  const exc = t.match(EXCEPTION);
  if (exc) return { kind: 'exception', word: exc[0] };
  return null;
}

/**
 * Есть ли во фразе цена. Числа, которые уже съедены (даты, номер тура,
 * места), вызывающий вырезает сам: голое число от 1000 в остатке — цена
 * («по 15000», «15 000»), а «2027» из даты ценой не считается.
 */
export function phraseMentionsPrice(rest: string): boolean {
  const t = rest.replace(/ё/gi, 'е');
  if (t.includes('₽')) return true;
  // Перед «руб»/«р.» может стоять число («500р.»), но не буква: «Горелый» не цена.
  if (/(?<!\p{L})(?:руб|р\.|цен[аеуыо]|стоимост)/iu.test(t)) return true;
  const nums = t.match(/(?<![\d.,])\d{1,3}(?:[ \u00a0]\d{3})+(?![\d.,])|(?<![\d.,])\d+(?![\d.,])/gu) ?? [];
  return nums.some((n) => Number(n.replace(/[ \u00a0]/g, '')) >= 1000);
}
