/**
 * Адрес снимка тура: что можно сохранить и что можно открыть (план готовности
 * 23.11, этап 4; находка ревью безопасности).
 *
 * Адрес снимка приходит от партнёра строкой. Очередь администратора показывает
 * его превью и даёт открыть целиком — то есть ставит строку в `href`. Строка
 * `javascript:…` в ссылке админки выполнилась бы от имени администратора,
 * стоит ему нажать на «снимок». Гиду дверь адреса проверяла и раньше
 * (lib/guides/own-tour-edit), оператору — нет: он вправе вставить ссылку на
 * снимок со своего сайта.
 *
 * Два правила, оба здесь:
 *  - сохранить нельзя адрес с чужой схемой (`photoAddressHasForeignScheme`);
 *  - открыть и показать можно только путь нашего сайта или http(s)
 *    (`openablePhotoAddress`); всё остальное экран показывает текстом.
 *
 * Второе правило не зависит от первого: в базе могут лежать адреса, записанные
 * до проверки, автоматами или импортом.
 *
 * Чистый модуль — его читает и экран (клиентский код).
 */
import { externalHref, internalHref } from '@/lib/analytics/traffic-links';

/** Адрес, который можно поставить в ссылку и в `src`: путь сайта или http(s). Иначе null. */
export function openablePhotoAddress(url: unknown): string | null {
  if (typeof url !== 'string') return null;
  return internalHref(url) ?? externalHref(url);
}

/**
 * У адреса чужая схема: `javascript:`, `data:`, `vbscript:`, `file:` и любая
 * другая, кроме http(s). Разбор — тем же `URL`, каким адрес читает браузер:
 * пробелы и табуляции внутри схемы («java\tscript:») он выбрасывает так же.
 * Строка без схемы (путь сайта, имя файла из старых записей) чужой схемы не
 * несёт — её судит уже экран.
 */
export function photoAddressHasForeignScheme(url: string): boolean {
  let parsed: URL;
  try {
    parsed = new URL(url);
  } catch {
    return false;
  }
  return parsed.protocol !== 'https:' && parsed.protocol !== 'http:';
}

