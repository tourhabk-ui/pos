/**
 * Причина отказа задаче A2A — машинным кодом в журнале и словами в админке
 * (слово владельца 13.11: «посмотрел журнал запросов A2A… попытка бронирования
 * — отклонены по причине нет согласия человека. Может, согласие не доходит?»).
 *
 * ── Что было ──────────────────────────────────────────────────────────────
 *
 * Журнал A2A (`a2a_requests`) знал только состояние задачи: `rejected`. Отчего
 * — не знал: под таблицей стояла общая подпись «нет согласия, нет мест, лимит,
 * несуществующий инструмент», и прочитать по ней, какой из четырёх случаев
 * перед глазами, было нельзя. Причина при этом уже называлась — кодом отказа
 * инструмента (`McpUserError.code`), но доходила только до журнала MCP.
 *
 * ── Что здесь ─────────────────────────────────────────────────────────────
 *
 * Код причины идёт той же дорогой, что вид входа и имя инструмента: в
 * `metadata` задачи (его видит и сам агент — по коду он чинит запрос, не
 * разбирая текст) и из неё — в журнал. Здесь два правила:
 *
 *  · что годится в журнал: короткий код из своих знаков, иначе `other` —
 *    в код не попадёт ни текст агента, ни значение аргумента;
 *  · как код называется человеку в админке.
 *
 * Код без своей строки показывается как есть: «неизвестная причина» скрыла бы
 * то, что журнал знает (§4.0).
 *
 * Чистый модуль. Сторож: tests/unit/a2a-reject-reason.test.ts.
 */

export const REJECT_CODE_MAX = 40;

const CODE = /^[a-z0-9_]{1,24}(:[a-z0-9_]{1,20})?$/;

/** Код причины для журнала; null — причины нет, `other` — пришло не то. */
export function safeRejectCode(raw: unknown): string | null {
  if (typeof raw !== 'string' || !raw.trim()) return null;
  const code = raw.trim().slice(0, REJECT_CODE_MAX);
  return CODE.test(code) ? code : 'other';
}

const LABEL: Record<string, string> = {
  no_consent: 'нет согласия человека на обработку данных',
  bad_phone: 'телефон не похож на номер',
  implausible_phone: 'телефона с таким номером не бывает',
  write_guard: 'лимит заявок, повтор или карантин адреса',
  rate_limited: 'слишком много запросов с адреса',
  unknown_tool: 'нет такого инструмента',
  key_not_found: 'ключ заявки не найден',
  status_only_key: 'ключ только для чтения статуса',
  test_key: 'ключ пробной заявки',
  date_not_in_calendar: 'даты нет в календаре тура',
  invalid_date: 'дата не годится',
  not_found: 'не найдено по запросу',
  save_failed: 'заявка не сохранилась — сбой у нас',
  confirm_unavailable: 'код подтверждения проката не выдан — сбой у нас',
  refused: 'отказ инструмента без названной причины',
  other: 'причина записана не кодом',
};

/** Причина словами для админки. */
export function rejectReasonLabel(code: string | null | undefined): string {
  if (!code) return 'причина не записана';
  const own = LABEL[code];
  if (own) return own;
  const [kind, field] = code.split(':');
  if (kind === 'invalid_args') return field ? `не то в поле ${field}` : 'не те поля запроса';
  if (kind.endsWith('_lookup_failed')) return 'данные не прочитались — сбой у нас';
  return code;
}
