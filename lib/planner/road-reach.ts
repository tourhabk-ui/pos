/**
 * lib/planner/road-reach.ts — СКОЛЬКО ЕХАТЬ ДО МЕСТА ДНЯ. Чистый модуль.
 *
 * ── Зачем (вопрос владельца 22.11: «а ты взял в расчёт расстояние между
 * точками, не везде есть дороги и ночёвки») ────────────────────────────────
 *
 * Аудит 22.11 (planner-test-2026-11-21/roads-audit.md): движок мерил дорогу
 * только между пятью зонами. Тур без маршрута каталога считался «городским»
 * и вставал однодневным выездом в Авачинской зоне, где бы ни стояла его
 * точка. Пруф с прода: «Зимняя рыбалка» (ID36) и «Летняя рыбалка на чавычу
 * и нерку» (ID5) — база на реке Камчатке, 410 км и ≈6,3 ч по дороге от
 * Петропавловска в одну сторону, — стояли одним днём между днями в городе.
 *
 * ── Правило ─────────────────────────────────────────────────────────────
 *
 * Однодневный выезд — это дорога туда, занятие и дорога обратно в один день.
 * Дальше DAY_TRIP_MAX_ROAD_HOURS в одну сторону однодневным днём не ставится:
 * нужен день дороги туда и день обратно (или ночь на месте) — и это сказано
 * числом. Часы — ОЦЕНКА нашего дорожного графа (OSM, миграция 760, скорости
 * A* не откалиброваны по полю) и так и называются в каждой строке.
 *
 * Сезонности дорог здесь нет: зимники и перевалы — только из официальных
 * сообщений с датой (тревоги о дорогах), иначе «не знаем».
 *
 * ЗДЕСЬ НЕ ДОЛЖНО БЫТЬ ИМПОРТОВ: модуль проверяется чистыми тестами.
 */

/**
 * Порог однодневного выезда: часов по дороге В ОДНУ СТОРОНУ. Решение
 * владельца 22.11 — 3 ч; поменять — только здесь, одно число на весь планер.
 */
export const DAY_TRIP_MAX_ROAD_HOURS = 3;

/**
 * Ближе этого по прямой дорогу не считаем: до 40 км по прямой камчатская
 * дорога не тянет на три часа, а граф для такой пары — лишний запрос.
 */
export const ROAD_CHECK_MIN_KM = 40;

/** Оценка дороги между двумя точками. */
export type RoadEstimate =
  | { kind: 'road'; km: number; hours: number }
  /** Граф есть, но проезжей дороги между точками в нём нет. */
  | { kind: 'no_road' }
  /** Посчитать не вышло (граф не прочитался, таймаут) — «не знаем». */
  | { kind: 'unread' };

/** «≈6,3 ч», «≈3 ч». */
export function hoursRu(h: number): string {
  const r = Math.round(h * 10) / 10;
  return `≈${Number.isInteger(r) ? String(r) : r.toFixed(1).replace('.', ',')} ч`;
}

/** «410 км, ≈6,3 ч по дороге в одну сторону (оценка)». */
export function roadLegRu(e: { km: number; hours: number }): string {
  return `${Math.round(e.km)} км, ${hoursRu(e.hours)} по дороге в одну сторону (оценка по нашему дорожному графу)`;
}

/**
 * Строка дня: сколько ехать до места тура и что о сезонности дороги мы не
 * знаем (п. 4 аудита 22.11). Сезонные ограничения — только из официальных
 * сообщений с датой; они приходят на день тревогами о дорогах, если есть.
 * Своей таблицы зимников и перевалов без источника план не заводит.
 */
export function roadDayLine(e: { km: number; hours: number }, self = false): string {
  const who = self ? 'проверьте перед выездом (сводки МЧС и дорожной службы края)' : 'проверьте перед выездом у оператора';
  return `Дорога до места от Петропавловска: ${roadLegRu(e)}. Сезонных ограничений этой дороги (зимник, перевал, закрытие) в официальных источниках у нас нет — ${who}.`;
}

/** Однодневным днём не успеть. */
export function tooFarForDayTrip(e: RoadEstimate): e is { kind: 'road'; km: number; hours: number } {
  return e.kind === 'road' && e.hours > DAY_TRIP_MAX_ROAD_HOURS;
}

/** Строка плана: однодневный тур не поставлен — место далеко. */
export function farDayTourLine(title: string, e: { km: number; hours: number }, from = 'Петропавловска'): string {
  return `«${title}» — однодневный тур, а до его места от ${from} ${roadLegRu(e)}. `
    + `Одним днём не успеть: нужен день дороги туда и день обратно или ночь на месте — `
    + `поэтому одним днём в план не поставлен. Трансфер и ночёвку уточните у оператора.`;
}

/** Строка плана: самостоятельный маршрут не поставлен днём — до него далеко. */
export function farSelfRouteLine(title: string, e: { km: number; hours: number }, from = 'Петропавловска'): string {
  return `Маршрут «${title}» (самостоятельно): до него от ${from} ${roadLegRu(e)}. `
    + `Одним днём с возвращением не успеть — поэтому днём в план не поставлен. Нужна ночёвка у маршрута или тур оператора с заброской.`;
}

/** День дороги к месту далёкого тура (связка, этап 3). Трансфер не обещаем. */
export function roadToTourText(title: string, e: { km: number; hours: number }): string {
  return `Дорога к месту тура «${title}»: ${roadLegRu(e)}. Трансфер план не бронирует и не обещает — как и на чём добраться, уточните у оператора. `
    + 'Ночь — у места: проживание есть в составе тура; сколько ночей входит в цену, уточните у оператора.';
}

/** День дороги обратно от далёкого тура (связка, этап 3). */
export function roadBackText(title: string, e: { km: number; hours: number }): string {
  return `Дорога обратно от места тура «${title}» в Петропавловск: ${roadLegRu(e)}. Трансфер план не бронирует и не обещает — уточните у оператора.`;
}

/** Строка плана: далёкий тур поставлен связкой. */
export function farBundleLine(title: string, e: { km: number; hours: number }): string {
  return `«${title}» стоит связкой из трёх дней: день дороги туда, день тура, день дороги обратно — до места ${roadLegRu(e)}. Ночёвки — у места (проживание в составе тура). Трансфер план не бронирует.`;
}

/** Связка не поместилась в оставшиеся дни. */
export function farBundleNoRoomLine(title: string, e: { km: number; hours: number }, need: number): string {
  return `«${title}» — до места ${roadLegRu(e)}: нужна связка из ${need} дней (дорога туда, тур, дорога обратно), а в поездке на неё дней не осталось — в план не поставлен. Добавьте дни к поездке.`;
}

/** Ночлега у места нет — связку не ставим; рядом найденное жильё называем. */
export function farNoNightLine(title: string, e: { km: number; hours: number }, near: readonly { name: string; km: number }[]): string {
  const nearText = near.length > 0
    ? ` На платформе рядом с местом есть жильё: ${near.map((n) => `«${n.name}» (≈${Math.round(n.km)} км)`).join(', ')} — связку с ним план сам не собирает, спросите оператора.`
    : ' Жилья на платформе в 30 км от места тоже нет.';
  return `«${title}» — однодневный тур, а до его места от Петропавловска ${roadLegRu(e)}. Одним днём не успеть, а ночлега у места в составе тура нет — поэтому в план не поставлен.${nearText}`;
}

/** Причина пропуска по интересу (коротко, для «почему не вошло»). */
export function farDayTourReason(title: string, e: { km: number; hours: number }): string {
  return `«${title}» — ${Math.round(e.km)} км и ${hoursRu(e.hours)} по дороге в одну сторону (оценка), одним днём не успеть`;
}

/** Дороги до места в графе нет — тур везёт оператор своим транспортом. */
export function noRoadLine(title: string): string {
  return `До места тура «${title}» проезжей дороги в нашем дорожном графе нет — добираются транспортом оператора (вездеход, катер, вертолёт). Как и сколько ехать, уточните у оператора.`;
}

/** Дорогу посчитать не вышло — время в пути не проверено. */
export function roadUnreadLine(titles: readonly string[]): string {
  return `Время в пути до места не проверено (дорожный граф не ответил): ${titles.map((t) => `«${t}»`).join(', ')}. Сколько ехать, уточните у оператора тура, а для самостоятельного маршрута — по карте и сводкам дорожной службы края.`;
}

/** У тура нет точки места в данных — расстояние до него не проверено. */
export function pointUnknownLine(titles: readonly string[]): string {
  const list = titles.map((t) => `«${t}»`).join(', ');
  return titles.length === 1
    ? `У тура ${list} в наших данных нет точки места: на карте он стоит у Петропавловска, расстояние и дорога до него не проверены. Где сбор и сколько ехать, уточните у оператора.`
    : `У туров ${list} в наших данных нет точки места: на карте они стоят у Петропавловска, расстояние и дорога до них не проверены. Где сбор и сколько ехать, уточните у операторов.`;
}

/** Соседние туры: от места вчерашнего до места сегодняшнего далеко. */
export function adjacentToursLine(prevTitle: string, e: { km: number; hours: number }): string {
  return `Накануне — «${prevTitle}», от его места сюда ${roadLegRu(e)}. Если оператор не вернёт группу в город накануне, утром к началу не успеть — согласуйте трансфер с обоими операторами или переставьте дни.`;
}

/** Вертолётный тур: дорога до места ему не нужна. */
export function isAirTour(t: { title: string; activityType?: string | null; included?: readonly string[] | null }): boolean {
  if (t.activityType === 'helicopter') return true;
  const text = [t.title, ...(t.included ?? [])].join(' ').toLowerCase();
  return /вертол|облёт|облет/.test(text);
}
