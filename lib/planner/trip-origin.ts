/**
 * lib/planner/trip-origin.ts — ОТКУДА ЧЕЛОВЕК ЕДЕТ.
 *
 * ── Что нашлось 27.09 (владелец: «есть же туристы, живущие на Камчатке») ───
 *
 * Планер считал прилёт на самолёте единственным способом попасть в край.
 * В коде это стояло двумя безусловными числами и двумя безусловными днями:
 *
 *   const departureDays = 1;
 *   const activeBudget = tripDays - 1 - departureDays;
 *
 *   день 1: «Прилёт утром. Размещение, отдых» + описание «Перелёт 8-9 часов.
 *           Разница с Москвой +9 часов. Акклиматизация обязательна»;
 *   день N: «Сборы утром. Трансфер в аэропорт» + «Аэропорт Елизово (PKC)».
 *
 * Жителю края это стоит ДВА дня из скольких бы ни было — и он читает про
 * свою акклиматизацию в родном городе. На пяти днях у него оставалось три
 * рабочих вместо пяти, то есть планер отнимал 40% поездки на перелёт,
 * которого нет.
 *
 * ── Правило ───────────────────────────────────────────────────────────────
 *
 * Служебные дни — следствие происхождения, а не свойство поездки. Решается
 * это ОДИН раз здесь (`framingDays`), и движок спрашивает правило, а не
 * пишет `- 1` в четырнадцати местах, где стоит граница `tripDays -
 * departureDays`.
 *
 * Про местного платформа знает ровно одно: он живёт в крае. НЕ знает, в каком
 * городе — Петропавловск, Елизово, Вилючинск или Козыревск в Северной зоне.
 * Поэтому «возвращение домой» здесь НЕ сочиняется: день возвращения
 * по-прежнему называет зоны (это факт о раскладке), а не чей-то дом. Выдумать
 * человеку место жительства ради красивой строки — ровно то, от чего
 * предостерегает §4.0.
 *
 * Спрашивается это в форме планера явно (решение владельца 27.09), а не
 * выводится из часового пояса или адреса: догадка о том, где человек живёт,
 * в лучшем случае верна, а в худшем отнимает у него два дня молча.
 */

import type { ZoneId } from '@/lib/planner/constants';

/** Откуда человек едет: прилетает в край или живёт в нём. */
export type TripOrigin = 'visitor' | 'local';

export const TRIP_ORIGINS: readonly TripOrigin[] = ['visitor', 'local'] as const;

/** Подписи одни для формы и для экрана результата. */
export const TRIP_ORIGIN_LABEL: Record<TripOrigin, { label: string; hint: string }> = {
  visitor: { label: 'Прилетаю', hint: 'День прилёта на акклиматизацию и день вылета — в плане' },
  local: { label: 'Живу на Камчатке', hint: 'Без дней на самолёт: все дни поездки рабочие' },
};

export function asTripOrigin(v: unknown): TripOrigin {
  return v === 'local' ? 'local' : 'visitor';
}

/**
 * Служебные дни, которые съедает дорога В край и ИЗ края.
 *
 * У местного их нет ни одного — не «ноль по умолчанию», а потому что
 * дороги в край он не совершает вовсе. Переезды ВНУТРИ края к этому
 * отношения не имеют: их считает `lib/planner/zone-leg`.
 */
export interface FramingDays {
  /** Дней на прибытие в край (день прилёта с акклиматизацией). */
  arrival: number;
  /** Дней на отъезд из края (сборы и трансфер в аэропорт). */
  departure: number;
}

export function framingDays(origin: TripOrigin): FramingDays {
  return origin === 'local' ? { arrival: 0, departure: 0 } : { arrival: 1, departure: 1 };
}

/**
 * Сколько дней поездки остаётся на дела.
 *
 * Никогда не меньше нуля: поездка на один день у прилетающего целиком уходит
 * на дорогу, и отрицательный бюджет в арифметике раскладки дал бы дни с
 * номерами меньше единицы.
 */
export function activeBudget(tripDays: number, origin: TripOrigin): number {
  const f = framingDays(origin);
  return Math.max(0, tripDays - f.arrival - f.departure);
}

/** Строка дня прибытия. `null` — такого дня в плане нет (местный). */
export function arrivalDayText(
  origin: TripOrigin,
  flightArrivalTime?: string,
): { title: string; description: string } | null {
  if (origin === 'local') return null;
  const hour = flightArrivalTime ? parseInt(flightArrivalTime.split(':')[0], 10) : 14;
  const title = hour < 12
    ? 'Прилёт утром. Размещение, отдых. Вечер: термальные источники Паратунки'
    : hour < 17
      ? 'Прилёт днём. Размещение, акклиматизация. Прогулка по городу'
      : 'Прилёт вечером. Размещение, ужин, отдых с дороги';
  return {
    title,
    description: 'Перелёт 8-9 часов. Разница с Москвой +9 часов. Акклиматизация обязательна.',
  };
}

/** Строка дня отъезда. `null` — такого дня в плане нет (местный). */
export function departureDayText(
  origin: TripOrigin,
  flightDepartureTime?: string,
): { title: string; description: string } | null {
  if (origin === 'local') return null;
  const hour = flightDepartureTime ? parseInt(flightDepartureTime.split(':')[0], 10) : 12;
  const title = hour >= 17
    ? 'Утро свободно. Лёгкая прогулка. Трансфер в аэропорт, вылет вечером'
    : hour >= 12
      ? 'Сборы утром. Трансфер в аэропорт, вылет днём'
      : 'Ранний подъём. Трансфер в аэропорт, вылет утром';
  return { title, description: 'Аэропорт Елизово (PKC). Трансфер 30 мин из Петропавловска.' };
}

/**
 * Зона, где план предполагает дом местного.
 *
 * Это ДОПУЩЕНИЕ, а не знание: платформа спрашивает «живёте ли в крае», а не
 * «в каком районе». Авачинская зона взята потому, что план по построению из
 * неё исходит и в неё возвращается, — а не потому, что мы знаем адрес.
 * Допущение обязано быть сказано вслух (`HOME_NIGHTS_ASSUMPTION`): молча
 * занижать счёт на догадке о чужом доме нельзя.
 */
export const LOCAL_HOME_ZONE: ZoneId = 'avachinsky';

/**
 * Ночь в этой зоне местный не оплачивает?
 *
 * Прилетающий платит за каждую ночь — жить ему негде. Местный в своей зоне
 * ночует у себя, в дальней — платит так же, как приезжий.
 *
 * Замер 27.09: `calculatePriceBreakdown` считал ночь за каждый не-отъездный
 * день безусловно. Житель Петропавловска, собравший однодневный выход на
 * Авачинский, видел в оценке ночь размещения в своём же городе — при comfort
 * это 8 000-12 000 ₽ поверх цены дня.
 */
export function nightIsAtHome(origin: TripOrigin, sleepZone: ZoneId): boolean {
  return origin === 'local' && sleepZone === LOCAL_HOME_ZONE;
}

/**
 * Трансферы в аэропорт и из аэропорта.
 *
 * `calculatePriceBreakdown` прибавлял 2 500-5 000 ₽ безусловной строкой с
 * комментарием `// arrival transfer`. Местный в аэропорт не едет.
 */
export function paysAirportTransfers(origin: TripOrigin): boolean {
  return origin !== 'local';
}

