/**
 * Род активного дня плана: с оператором, сам или на выбор.
 *
 * Владелец 25.09: «можно же самому подобрать план — сегодня сам, завтра с
 * одним оператором, потом отдых, и так на всё время на Камчатке». Движок
 * (`recommendTrip`) так и собирает поездку: на день берётся живой тур
 * оператора, при его отсутствии — место или маршрут для самостоятельного
 * выхода, при отсутствии обоих — один общий день «зона + активность». Дни
 * отдыха и резерва — отдельные `DayType`.
 *
 * Человеку это не было видно: активный день во всех трёх случаях выглядел
 * одинаково, и план не говорил, где его ведут, а где он идёт сам. Род
 * выводится здесь ОДНИМ правилом из того, что движок реально поставил на
 * день, — не из интереса и не из типа активности.
 *
 * `open` — честное «под этот день готового нет»: ни тура, ни маршрута в базе
 * не нашлось. Называть такой день «сам» значило бы обещать маршрут, которого
 * нет (§4.0).
 */

export type ActivityMode = 'operator' | 'self' | 'open';

export function activityMode(material: { realTour: unknown; route: unknown }): ActivityMode {
  if (material.realTour) return 'operator';
  if (material.route) return 'self';
  return 'open';
}

