/**
 * Сколько ДНЕЙ плана занимает тур. Чистый модуль.
 *
 * ── Зачем (замер с прода 20.09) ──────────────────────────────────────────
 *
 * У «Камчатской рыбалки» семь живых туров из восьми, и главные из них —
 * многодневные: «Многодневный летний тур (5 дней)» за 140 000 ₽,
 * «Недельный рыболовный тур (7 дней)» за 196 000 ₽. В плане каждый из них
 * занимал ОДИН день: цикл сборки устроен как «день = одна итерация», а
 * `durationHours` читался из базы и не использовался нигде.
 *
 * То есть семидневная поездка показывалась как один день с туром за 140
 * тысяч плюс шесть дней, которые движок заполнял чем придётся. Главный
 * продукт оператора план не мог представить в принципе.
 *
 * ── Почему в часах и почему порог ────────────────────────────────────────
 *
 * В схеме есть только `operator_tours.duration_hours` (миграция 040,
 * DECIMAL, примеры в комментарии — «2.5, 8, 24, 72»), поля в днях нет.
 * Значит длительность выводится, и вывод обязан быть осторожным: делить
 * на 24 без порога — значит сделать восьмичасовой тур «нулём дней», а
 * суточный — «одним», хотя ночует человек в обоих случаях один раз.
 *
 * Правило: всё до суток включительно — один день плана; дальше — по
 * суткам вверх (25 ч → 2, 72 ч → 3, 120 ч → 5).
 *
 * ── Третий исход обязателен ──────────────────────────────────────────────
 *
 * `null` — длительность не заполнена, и это НЕ «однодневный». План поставит
 * такой тур одним днём (прежнее поведение, без регрессии), но вызывающий
 * обязан сказать вслух: под ним может лежать пятидневка, и тогда расписание
 * неверно. Выдать незнание за «один день» — ровно та подмена, из-за которой
 * пятидневный тур и стоял одним днём (§4.0).
 *
 * ЗДЕСЬ НЕ ДОЛЖНО БЫТЬ ИМПОРТОВ.
 */

/** Сутки в часах. Порог, а не единица измерения: см. шапку. */
const HOURS_IN_DAY = 24;

/** Разумный потолок: тур длиннее трёх недель — почти наверняка битое поле. */
export const MAX_TOUR_DAYS = 21;

/**
 * `durationHours` → дней плана. `null` — судить не о чем.
 *
 * Ноль, отрицательное и нечисловое — тоже `null`: это не «нулевой тур», это
 * незаполненное или испорченное поле.
 */
export function tourDaySpan(durationHours: number | null | undefined): number | null {
  if (durationHours === null || durationHours === undefined) return null;
  const hours = Number(durationHours);
  if (!Number.isFinite(hours) || hours <= 0) return null;

  if (hours <= HOURS_IN_DAY) return 1;

  const days = Math.ceil(hours / HOURS_IN_DAY);
  // Потолок не «исправляет» данные молча — он их отвергает: вернуть 21 при
  // 5000 часах значило бы выдать догадку за длительность.
  return days > MAX_TOUR_DAYS ? null : days;
}
