/**
 * Потолок взрослых в плане — одно число на сайт, чат, MCP и сохранённую
 * поездку (разбор 14.11, Кузьмич-9).
 *
 * Было три: форма и ссылка сайта — 1–8, роут сборки — 1–20, Кузьмич, MCP и
 * схема сохранённой поездки — 1–30. План Кузьмича на 25 человек сохранялся,
 * а «Собрать заново» открывало планировщик на двоих молча: ссылку с
 * `adults=25` экран отбрасывал. Тридцать — потолок заявки на бронь; группу
 * больше собирает оператор по заявке.
 *
 * Модуль без базы: его читает и экран.
 */
export const MAX_ADULTS = 30;

/** Взрослые из ссылки: целое 1..MAX_ADULTS, иначе null (берётся обычное «двое»). */
export function adultsFromParam(raw: string | null): number | null {
  if (!raw || !/^\d{1,2}$/.test(raw)) return null;
  const n = Number(raw);
  return n >= 1 && n <= MAX_ADULTS ? n : null;
}
