/**
 * lib/planner/zone-leg.ts — ПОЕЗДКА В ДАЛЬНЮЮ ЗОНУ СТОИТ НЕ ОДИН ДЕНЬ.
 *
 * ── Что нашлось 27.09 (владелец: «planner как-то очень не продуманная логика») ─
 *
 * Прогон живого движка на четырёх длительностях показал две поломки, и корень
 * у них один: движок решал про ОДИН день, а поездка в чужую зону — связка.
 *
 *   • поездка 5-6 дней: план получал день «Переезд: Авачинская → Западная
 *     зона» за 5 000-8 000 ₽ — и ни одного дня в Западной зоне. Человек
 *     платит за дорогу и теряет день, чтобы попасть туда, где по плану ничего
 *     не происходит, а вылетает из Петропавловска;
 *
 *   • поездка 7 дней: переезд туда (день 5), рыбалка там (день 6), вылет из
 *     Петропавловска (день 7). Дня на возвращение в плане НЕТ, цена его не
 *     посчитана. План физически невыполним, и ни одного предупреждения.
 *
 * В коде это было видно построчно: проверка «хватает ли дней» стояла ПОСЛЕ
 * того, как день переезда уже добавлен (`days.push` и следом
 * `if (dayNum > tripDays - departureDays) break;`), а обратный переезд
 * пропускался тем же условием молча.
 *
 * ── Правило ───────────────────────────────────────────────────────────────
 *
 * Связка считается ЦЕЛИКОМ и до того, как в план попадёт первый её день:
 * переезд туда + минимум один день в зоне + возвращение. Не влезает — зона в
 * план не берётся вовсе, а причина называется словами и числом (решение
 * владельца 27.09: «не ездить и сказать словами»).
 *
 * Молчание здесь было бы хуже отказа: интерес человека («рыбалка») исчезал из
 * плана, и он не мог понять, почему — сезон, отсутствие туров или арифметика
 * дней. Это тот же третий исход §4.0, только про календарь.
 *
 * Один день в зоне — минимум по смыслу, а не по вкусу: ехать семь часов, чтобы
 * там не провести ни дня, незачем. Ночёвки дороги считаются отдельно (цена
 * ребра графа), здесь только ДНИ.
 */
import { ZONE_GRAPH } from '@/lib/planner/zone-graph';
import { ZONE_NAMES, type ZoneId } from '@/lib/planner/constants';

/** Минимум дней В зоне, иначе переезд бессмыслен. */
export const MIN_DAYS_IN_ZONE = 1;

export interface ZoneLegCost {
  /** Дней на дорогу туда: 0, если переезд не требует отдельного дня. */
  travelIn: number;
  /** Дней в самой зоне (не меньше MIN_DAYS_IN_ZONE). */
  stay: number;
  /** Дней на возвращение в Авачинскую зону. */
  travelBack: number;
  /** Сколько дней займёт связка целиком. */
  total: number;
  /**
   * Дорога вообще есть?
   *
   * `false` — ребра в графе нет, и это НЕ «ноль дней»: в зону не попасть, и
   * ставить её в план нельзя ни при какой длительности поездки.
   */
  reachable: boolean;
}

/**
 * Во сколько дней встанет заход в зону `to` из зоны `from` и возвращение
 * оттуда в Авачинскую (откуда вылет).
 *
 * Возвращение считается от `to`, а не от `from`: план после этой связки может
 * пойти дальше, но в худшем случае человеку придётся возвращаться именно из
 * `to`, и день на это должен быть предусмотрен заранее.
 */
export function zoneLegCost(from: ZoneId, to: ZoneId, stayDays = MIN_DAYS_IN_ZONE): ZoneLegCost {
  const stay = Math.max(MIN_DAYS_IN_ZONE, stayDays);
  if (from === to) {
    // Своя зона: ни дороги, ни возвращения. Это не «связка не влезла», а
    // «связки нет вовсе».
    return { travelIn: 0, stay, travelBack: 0, total: stay, reachable: true };
  }
  const edgeIn = ZONE_GRAPH[from]?.[to];
  if (!edgeIn) {
    return { travelIn: 0, stay, travelBack: 0, total: 0, reachable: false };
  }
  const travelIn = edgeIn.needsTravelDay ? 1 : 0;
  const edgeBack = to === 'avachinsky' ? undefined : ZONE_GRAPH[to]?.['avachinsky'];
  // Из зоны нет дороги в Авачинскую — туда нельзя, как бы ни манил интерес:
  // человека некому и нечем вернуть к самолёту.
  if (to !== 'avachinsky' && !edgeBack) {
    return { travelIn, stay, travelBack: 0, total: 0, reachable: false };
  }
  const travelBack = edgeBack?.needsTravelDay ? 1 : 0;
  return { travelIn, stay, travelBack, total: travelIn + stay + travelBack, reachable: true };
}

/** Влезает ли связка в остаток дней (день вылета в остаток НЕ входит). */
export function legFits(cost: ZoneLegCost, daysLeft: number): boolean {
  return cost.reachable && cost.total <= daysLeft;
}

/**
 * Почему зона не взята — словами и числом.
 *
 * Текст идёт туристу в предупреждения, поэтому называет и нужное, и
 * имеющееся: «нужно три дня, свободных два» проверяемо, а «не хватило дней» —
 * нет.
 */
export function legShortfallMessage(
  to: ZoneId,
  cost: ZoneLegCost,
  daysLeft: number,
  interestNames: string[],
): string {
  const zone = ZONE_NAMES[to] ?? to;
  const what = interestNames.length > 0 ? `${interestNames.join(', ')} — ` : '';
  if (!cost.reachable) {
    return `${what}${zone}: дороги отсюда нет в нашем графе зон, поэтому в план её не поставили. `
      + 'Спросите оператора: вертолётный заход может существовать вне наших данных.';
  }
  const parts = [
    cost.travelIn > 0 ? 'день на переезд' : null,
    `${cost.stay} ${cost.stay === 1 ? 'день' : 'дня'} на месте`,
    cost.travelBack > 0 ? 'день на возвращение' : null,
  ].filter(Boolean).join(' + ');
  return `${what}${zone} в план не вошла: на неё нужно ${cost.total} ${cost.total === 1 ? 'день' : 'дня'} `
    + `(${parts}), а свободных осталось ${daysLeft}. Добавьте дни к поездке или выберите занятие ближе к городу.`;
}
