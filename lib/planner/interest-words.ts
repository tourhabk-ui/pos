/**
 * Русские слова туриста → ключи интересов движка. Чистый модуль.
 *
 * ── Почему отдельным файлом, а не там, где он жил ────────────────────────
 *
 * Словарь родился в `lib/kuzmich/trip-plan-tool.ts`, а тот импортирует
 * `recommendTrip` и через него `pool`. Пока читал его один Кузьмич на
 * сервере, это не мешало. С 20.09 те же слова нужны экрану планировщика:
 * внешняя модель через MCP отдаёт туриста на `/planner?interests=вулканы и
 * медведи`, и клиент обязан их понять. Импортировать туда `trip-plan-tool`
 * значит утащить в браузерный бандл пул PostgreSQL.
 *
 * Второй словарь завести было нельзя: два перевода одних и тех же слов
 * расходятся — это уже случалось с `INTEREST_NAME` против `ACTIVITY_NAMES`
 * (19.09). Поэтому не копия, а переезд: единственное место осталось
 * единственным, просто без зависимостей.
 *
 * ЗДЕСЬ НЕ ДОЛЖНО БЫТЬ НИ ОДНОГО ИМПОРТА. Любая зависимость, добавленная
 * сюда, попадёт в клиентский бандл вместе со словарём.
 */

/**
 * Подстрока в тексте туриста → ключ активности движка.
 *
 * Ключи — те же, что у `ACTIVITY_CONSTRAINTS`, а не отдельный алфавит.
 * Корни, а не целые слова: «морск» нужен потому, что сезонная подсказка
 * предлагает «морские прогулки», и без корня турист, повторивший наш же
 * совет, получал «не разобрал» (найдено сторожем 19.09).
 */
export const INTEREST_WORDS: Record<string, string> = {
  'вулкан': 'volcano', 'вулканы': 'volcano',
  'рыбалка': 'fishing', 'рыба': 'fishing',
  'медвед': 'bears',
  'вертолет': 'helicopter', 'вертолёт': 'helicopter',
  'термал': 'thermal', 'источник': 'thermal',
  'треккинг': 'trekking', 'поход': 'trekking',
  'море': 'boat_trip', 'морск': 'boat_trip', 'океан': 'boat_trip', 'катер': 'boat_trip',
  'гейзер': 'geyser',
  'снегоход': 'snowmobile',
};

/**
 * Свободный текст → ключи движка по словарю. Порядок — как в словаре,
 * повторов нет. Пусто — значит не разобрали НИ ОДНОГО слова, и это отдельный
 * исход: вызывающий решает, подставлять ли своё умолчание (§4.0).
 */
export function parseInterestWords(raw: string): string[] {
  const text = (raw || '').toLowerCase();
  const found = new Set<string>();
  for (const [word, key] of Object.entries(INTEREST_WORDS)) {
    if (text.includes(word)) found.add(key);
  }
  return [...found];
}
