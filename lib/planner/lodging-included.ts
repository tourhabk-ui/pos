/**
 * Включено ли проживание в тур. Чистый модуль.
 *
 * ── Зачем (замер с прода 20.09) ──────────────────────────────────────────
 *
 * У тура ID9 «Многодневный летний тур (5 дней)» оператора «Камчатская
 * рыбалка» в составе прямым текстом: **«Проживание на базе 5 ночей»**,
 * цена 140 000 ₽. А `calculatePriceBreakdown` прибавлял цену ночи за
 * КАЖДЫЙ не-отъездный день безусловно, не глядя на состав тура. Западная
 * зона при `comfort` — 20 000 ₽/ночь; семидневный план с этим туром
 * показывал бы ещё 96 000–160 000 ₽ «проживания», которого турист не
 * платит. Сумма, которой нет.
 *
 * ── Почему три исхода, а не два ──────────────────────────────────────────
 *
 * Состав тура — ТЕКСТ, написанный человеком. Разбирать его можно только
 * осторожно, и «не поняли» обязано отличаться от «не включено»: в первом
 * случае ночь считается и об этом говорится вслух, во втором считается
 * молча и правильно. Свести их значило бы либо занижать счёт на догадке,
 * либо завышать молча (§4.0).
 *
 * ЗДЕСЬ НЕ ДОЛЖНО БЫТЬ ИМПОРТОВ: модуль обязан оставаться проверяемым
 * чистыми тестами, без базы и без движка.
 */

/**
 * Корни, по которым узнаётся ночлег в строке состава.
 *
 * Список намеренно КОРОТКИЙ и однозначный. Соблазн добавить «номер»,
 * «база», «корпус» велик, но каждое из них значит ночлег далеко не всегда:
 * «номер телефона», «база отдыха как точка сбора», «корпус катера». Лишнее
 * слово здесь не расширяет распознавание, а превращает «не включено» в
 * ложное «включено» — то есть занижает счёт туристу.
 */
const LODGING_STEMS = ['прожив', 'ночлег', 'ночёв', 'ночев', 'размещен', 'размещён'];

/**
 * `true` — ночлег в составе; `false` — состав есть, ночлега в нём нет;
 * `null` — состава нет вовсе, и судить не о чем.
 */
export function lodgingIncluded(included: readonly string[] | null | undefined): boolean | null {
  if (!included || included.length === 0) return null;

  const meaningful = included.map((s) => (s ?? '').toLowerCase().trim()).filter(Boolean);
  if (meaningful.length === 0) return null;

  return meaningful.some((line) => LODGING_STEMS.some((stem) => line.includes(stem)));
}
