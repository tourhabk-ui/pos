/**
 * Летопись Камчатки — статьи об истории края (решение владельца 03.10:
 * «большую полную статью, чтоб можно было открыть по ссылке, как и описание
 * рыб; будем потихоньку собирать летопись Камчатки»).
 *
 * Статья — справка, не пересказ «от себя». Каждое число и имя берётся из
 * названного источника; где источники расходятся, текст говорит об этом и
 * даёт оба числа, а не выбирает удобное (§4.0). Источники перечислены в
 * конце статьи и показываются на странице.
 *
 * Статья может быть связана с местами каталога (`placeIds`): на карточке
 * такого места появляется ссылка на неё. Связь — по id места, не по имени:
 * имена в каталоге меняются, а «Батарея Максутова» и «Никольская сопка»
 * существуют в нескольких записях.
 */

export interface ChronicleSection {
  heading: string;
  /** Абзацы. Цитата — абзац, начинающийся с «» и помеченный quote. */
  paragraphs: Array<string | { quote: string; by: string }>;
}

export interface ChronicleSource {
  title: string;
  url: string;
}

/**
 * Веха ленты над текстом статьи. Лента — оглавление по годам, не второй
 * текст: каждая веха пересказывает то, что уже сказано в разделах, и год
 * обязан стоять в тексте статьи (сторож chronicle-articles).
 */
export interface ChronicleDate {
  /** Год или промежуток, как в тексте: «1882», «1992–1993». */
  year: string;
  event: string;
}

/**
 * Главный кадр статьи — снимок из хранилища под `photos/` (media-to-s3) со
 * свободной лицензией или снимок партнёра с его разрешения. Подпись
 * обязательна целиком: без автора и лицензии (или разрешения) чужой снимок
 * не показывается (тот же закон, что у снимков мест).
 *
 * Свои и партнёрские снимки — прежде Commons (владелец 14.10: «Только
 * используй наши фотографии или фото партнеров по возможности»). У снимка
 * партнёра нет страницы лицензии: в `license` — словами, чьё разрешение,
 * `licenseUrl` пуст, `sourceUrl` — страница партнёра на платформе.
 */
export interface ChronicleHero {
  /** Ключ в хранилище: `photos/…jpg`; адрес собирает lib/images/photo-key. */
  key: string;
  /** Что видно на снимке — для того, кто его не видит. */
  alt: string;
  /** Название снимка у автора. */
  caption: string;
  author: string;
  license: string;
  /** Страница лицензии; у снимка партнёра её нет — подпись без ссылки. */
  licenseUrl?: string;
  /** Страница файла у источника (Wikimedia Commons) или страница партнёра на платформе. */
  sourceUrl: string;
  width: number;
  height: number;
}

/** Куда дальше на платформе — внутренний адрес по slug (/places/…, /park/…). */
export interface ChronicleLink {
  href: string;
  label: string;
  /** Одна строка под названием: что человек там найдёт. */
  hint: string;
}

export interface ChronicleArticle {
  slug: string;
  title: string;
  /** Годы или дата — строкой, как их пишут в оглавлении. */
  period: string;
  /** Одна-две фразы для оглавления и выдачи. */
  lead: string;
  sections: ChronicleSection[];
  sources: ChronicleSource[];
  /** Места каталога, на карточках которых стоит ссылка на статью. */
  placeIds: string[];
  /**
   * Страницы справочника парков (/park/<slug>), на которых стоит переход к
   * статье (14.10, владелец: «на странице парка нужен переход для летописи»).
   * Связь — по slug справочника `parks`, как у мест — по id.
   */
  parkSlugs?: string[];
  /** Когда статья последний раз сверялась с источниками (ISO-дата). */
  checkedAt: string;
  /** Ключевые даты — лентой над текстом (14.10, «сделай красивую страницу»). */
  timeline?: ChronicleDate[];
  /** Карточка места, маршруты — переходы со страницы статьи. */
  links?: ChronicleLink[];
  /** Главный кадр над заголовком (14.10, «сделай красивую страницу»). */
  hero?: ChronicleHero;
}

