/**
 * Роды статей летописи и каркас серии (решение владельца 03.10: «нужен каркас
 * для статей»). Род — не рубрика ради красоты: у каждого рода свой набор
 * обязательных секций и свой сторож тона.
 *
 *   event   — событие (оборона 1854, цунами 1952, гибель «Ниитаки»);
 *   person  — человек (Беринг, Крашенинников);
 *   place   — место и его история (маяк, Никольское, Северо-Курильск);
 *   toponym — что значит имя: коренные названия мест. Здесь версия — не
 *             факт, поэтому текст ОБЯЗАН содержать слово-ограничитель
 *             («предположительно», «по одной из версий», «неизвестно») —
 *             уверенный тон в этимологии и есть выдумка (урок «Авачи» 03.10:
 *             «версия Стеллера» не нашлась ни на одной открытой странице).
 */

export type ArticleKind = 'event' | 'person' | 'place' | 'toponym';

export const ARTICLE_KINDS: Record<ArticleKind, { label: string; order: number }> = {
  event: { label: 'События', order: 1 },
  person: { label: 'Люди', order: 2 },
  place: { label: 'Места', order: 3 },
  toponym: { label: 'Что значит имя', order: 4 },
};

/** Обязательные секции статьи-топонима — в этом порядке. */
export const TOPONYM_SECTIONS = ['Как звучит и у кого', 'Версии', 'Что носит это имя'] as const;

/** Необязательная секция топонима: старые написания на картах — только из источника. */
export const TOPONYM_OPTIONAL_SECTION = 'На старых картах';

/**
 * Слова, которыми источник ограничивает уверенность. Хотя бы одно обязано
 * стоять в тексте статьи-топонима; их отсутствие — сторож краснеет.
 */
export const HEDGE_RE =
  /предположительн|по одной из версий|по другой версии|по третьей версии|по версии|неизвестн|не установлен|единого мнения нет|возможно,|оспарива/iu;

export function isHedged(text: string): boolean {
  return HEDGE_RE.test(text);
}

export function kindLabel(kind: ArticleKind): string {
  return ARTICLE_KINDS[kind].label;
}
