export interface ZhWrongName {
  wrong: string;
  right: string;
  /** Почему написание ошибочно — чтобы список не рос догадками. */
  why: string;
}

/** Написания, встреченные в ответах моделей и известные как ошибочные. */
export const ZH_WRONG_NAMES: readonly ZhWrongName[] = [
  { wrong: '库页湖', right: '库里尔湖', why: '«库页» — китайское имя Сахалина (库页岛); Курильское озеро — 库里尔湖 (офлайн-тест 14.11, #3382)' },
];

/** Названия мест, встретившиеся в русском тексте, в порядке списка. */
export function zhPlaceNamesIn(text: string): ZhPlaceName[] {
  return ZH_PLACE_NAMES.filter((p) => p.re.test(text));
}

/**
 * Строка клиенту MCP после ответа на китайский вопрос: как писать по-китайски
 * названия мест из этого ответа. Мест из списка нет — пусто.
 */
export function zhPlaceNamesNote(text: string): string {
  const found = zhPlaceNamesIn(text);
  if (found.length === 0) return '';
  const wrongFor = (zh: string) => ZH_WRONG_NAMES.filter((w) => w.right === zh).map((w) => w.wrong);
  const pairs = found.map((p) => {
    const not = wrongFor(p.zh);
    return `${p.ru} = ${p.zh}${not.length ? ` (not ${not.join(', ')})` : ''}`;
  });
  return `\n[Chinese names of places in this answer: ${pairs.join('; ')}.]`;
}

export interface ZhNameFix {
  text: string;
  /** Что заменено — для лога. */
  fixed: Array<{ wrong: string; right: string }>;
}

/** Ошибочные китайские написания мест → правильные. Текст без них не меняется. */
export function fixWrongZhPlaceNames(text: string): ZhNameFix {
  let out = text;
  const fixed: ZhNameFix['fixed'] = [];
  for (const w of ZH_WRONG_NAMES) {
    if (out.includes(w.wrong)) {
      out = out.split(w.wrong).join(w.right);
      fixed.push({ wrong: w.wrong, right: w.right });
    }
  }
  return { text: out, fixed };
}
