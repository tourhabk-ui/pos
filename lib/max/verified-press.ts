/**
 * Задан ли ключ подписки — та же проверка, что в `isVerifiedMaxWebhook`
 * (`lib/max/webhook-url`): пустая строка — не ключ.
 */
export function maxWebhookKeyConfigured(): boolean {
  return Boolean(process.env.MAX_WEBHOOK_SECRET);
}

