/**
 * lib/max/verified-press.ts — что вебхук MAX делает только по заверенному апдейту.
 *
 * Адрес `/api/max/kuzmich` публичный: тело апдейта — чат, кнопку, «контакт»,
 * ссылку старта — может прислать кто угодно. Заверенным апдейт делает только
 * серверный флаг `verifiedOrigin`: запрос пришёл на адрес подписки с нашим
 * секретом (`lib/max/webhook-url`) или апдейт забран опросом по токену бота.
 *
 * Правило (план мини-приложения, §6.5, этап 0; слово владельца 22.10 «а да»):
 *  - всё, что меняет что-то за пределами ответа в этот чат, — только по
 *    заверенному апдейту: вход, подключение чата по ссылке, ответ на запрос
 *    мест, кнопки лида, заявка из присланного номера, помощник кабинета,
 *    бронь в чате, `/reset`;
 *  - чат для кнопки-действия берётся только из сообщения с кнопкой
 *    (`message.recipient.chat_id`), без отката на `user_id` из тела;
 *  - на незаверенное бот не молчит: говорит, что проверить не смог, что
 *    ничего не изменено, и где сделать то же самое (§4.0, третий исход);
 *  - вопросы Кузьмичу и кнопки тем доступны из любого источника.
 *
 * Здесь — только разбор вида действия и тексты отказа: одно правило на
 * вебхук и на мозг Кузьмича (`lib/kuzmich/core`), а не две копии.
 */

/** Кнопка под сообщением, нажатие которой что-то меняет. */
export type MaxPressAction = 'seat' | 'lead';

/** Ссылка старта бота, по которой что-то меняется. */
export type MaxStartAction = 'login' | 'link';

/** Действие текстом или вложением в чате. */
export type MaxChatAction = 'contact' | 'partner' | 'booking' | 'reset';

/**
 * Вид кнопки-действия по payload. `sr:` — ответ оператора на запрос мест
 * (`lib/seat-requests/core`, `answerPayload`), `lead_` — кнопки лида
 * (`lib/leads/status-action`, `lead_ai`, `lead_send`). Прочие кнопки (темы,
 * «Оформить заявку», «Другой вариант») только отвечают в чат.
 */
export function pressActionOf(payload: string): MaxPressAction | null {
  if (payload.startsWith('sr:')) return 'seat';
  if (payload.startsWith('lead_')) return 'lead';
  return null;
}

/**
 * Вид ссылки старта: `login-` — вход на сайт через MAX
 * (`lib/auth/max-login`); `sr_` — чат туриста к запросу мест, `op_` — чат
 * кабинета партнёра, `om_` — чат менеджера команды. Форму токена здесь не
 * проверяем: это делают сами разборщики и только по заверенному апдейту.
 */
export function startActionOf(payload: unknown): MaxStartAction | null {
  if (typeof payload !== 'string') return null;
  if (payload.startsWith('login-')) return 'login';
  if (payload.startsWith('sr_') || payload.startsWith('op_') || payload.startsWith('om_')) return 'link';
  return null;
}

