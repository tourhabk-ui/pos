/**
 * lib/max/verified-press.ts — что вебхук MAX делает только по заверенному апдейту.
 *
 * Адрес `/api/max/kuzmich` публичный: тело апдейта — чат, кнопку, «контакт»,
 * ссылку старта — может прислать кто угодно. Заверенным апдейт делает только
 * серверный флаг `verifiedOrigin`: запрос пришёл на адрес подписки с нашим
 * секретом (`lib/max/webhook-url`) или апдейт забран опросом по токену бота.
 *
 * Правило (план мини-приложения, §6.5, этап 0; слово владельца 22.10 «а да»):
 *  - ключ подписки задан (`MAX_WEBHOOK_SECRET`) — запрос без него не
 *    обрабатывается вовсе: MAX зовёт адрес с ключом, а без ключа приходят
 *    только подделка или старая подписка без ключа (вторая, которую крон
 *    видит с 30.09). Отвечать на такую копию нечего: настоящая копия того же
 *    апдейта пришла по ключу, и второй ответ спорил бы с первым. В лог —
 *    хост и путь запроса, чтобы старую подписку было видно;
 *  - ключа нет — вопросы Кузьмичу из любого источника, но по одному апдейту
 *    на запрос и без записи в историю и память чата; всё, что меняет что-то
 *    за пределами ответа в этот чат, — вход, подключение чата по ссылке,
 *    ответ на запрос мест, кнопки лида, «Выполнено» под напоминанием о
 *    задаче, заявка из присланного номера, помощник кабинета, бронь в чате,
 *    `/reset`, — не применяется;
 *  - чат для кнопки-действия берётся только из сообщения с кнопкой
 *    (`message.recipient.chat_id`), без отката на `user_id` из тела. Это
 *    защита для ЗАВЕРЕННОГО апдейта: там чат сообщения назвал MAX, и по нему
 *    решается право нажатия (рабочий чат, чат оператора запроса);
 *  - на неприменённое действие бот не молчит: говорит, что это не засчитано
 *    и где сделать то же самое (§4.0, третий исход).
 *
 * Чего режим без ключа НЕ даёт, сказано прямо. Без ключа бот — открытый
 * ответчик: ответ уходит в чат, названный телом апдейта, а
 * `message.recipient.chat_id` подделывается так же легко, как `user_id`.
 * Кто угодно может заставить бота написать в любой чат, где он есть, — ответ
 * Кузьмича или текст «не засчитано»; ограничение — один апдейт на запрос.
 * Поэтому без ключа закрыто всё, что пишет или меняет, а не то, куда уходит
 * ответ. На проде ключ задан, и такие запросы отбрасываются до разбора.
 *
 * Тексты ниже звучат только без ключа: при ключе незаверенный апдейт до них
 * не доходит, а опрос по токену заверен по построению. Без ключа заверенным
 * не бывает ни один апдейт вебхука, поэтому тексты не зовут повторить —
 * повтор дал бы тот же отказ, — а говорят, что через MAX это сейчас
 * недоступно, и где сделать то же самое.
 *
 * Здесь — только разбор вида действия и тексты: одно правило на вебхук и на
 * мозг Кузьмича (`lib/kuzmich/core`), а не две копии.
 */

