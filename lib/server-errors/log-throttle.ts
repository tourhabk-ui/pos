/**
 * lib/server-errors/log-throttle.ts — сколько молчит журнал серверных ошибок
 * после записи об ошибке на том же маршруте.
 *
 * Число вынесено из `instrumentation.ts`, потому что у него теперь два
 * читателя (находка аудита 15.10 P4-17): перехватчик `onRequestError`, который
 * по нему глушит повторы, и суточный дайджест владельцу
 * (`lib/server-errors/digest.ts`), который обязан сказать словами, что его
 * счётчики — нижняя граница. Две копии числа разошлись бы молча, и дайджест
 * называл бы не то окно, что действует.
 *
 * Модуль без импортов намеренно: `instrumentation.ts` собирается и для
 * edge-рантайма, и любой серверный модуль здесь утащил бы его в edge-бандл.
 */

/** Повтор ошибки на одном маршруте в пределах этого окна в журнал не пишется. */
export const ERROR_LOG_THROTTLE_MS = 60_000;
