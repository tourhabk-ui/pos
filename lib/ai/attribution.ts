/**
 * lib/ai/attribution.ts — чьи это токены на витрине OpenRouter.
 *
 * ── Повод (07.09) ─────────────────────────────────────────────────────────
 *
 * Владелец показал два экрана рядом. На первом — консоль OpenRouter:
 * приложение `vedarai.ru`, 1,12 млн токенов за две недели, ровные 50-90 тыс.
 * в сутки. На втором — наш собственный алерт: «OpenRouter недоступен».
 *
 * Противоречия в фактах нет: с прода OpenRouter действительно отвечает 403
 * (край сети режет по нашему адресу), а те миллион токенов жжёт раннер
 * GitHub — evo-judge, evo-review, editor-runner, astra-probe. Противоречие в
 * ПОДПИСИ: заголовок `HTTP-Referer` был захардкожен строкой `https://vedarai.ru`
 * во всех шестнадцати местах вызова, а OpenRouter группирует приложения именно
 * по нему. Две поверхности с двумя разными ключами (секреты GitHub против
 * переменных Timeweb) сливались в одну строку витрины.
 *
 * Цена: на вопрос «кто сжёг миллион — прод или агенты CI» консоль ответить не
 * могла. Ключи заводились РАЗНЫМИ ровно ради адресности отказа (см. §8
 * CLAUDE.md), и эта адресность терялась на последнем шаге — в подписи.
 *
 * ── Что здесь ─────────────────────────────────────────────────────────────
 *
 * Одна функция, дающая пару заголовков по месту запуска. Место берётся из
 * `runPlace()` (lib/ai/key-identity) — той же функции, что уже отвечает «откуда
 * спросили» в диагностике ключей. Второй копии этого знания не заводим: копия
 * разошлась бы, и витрина снова начала бы врать, только тоньше.
 *
 * Прод сохраняет прежний `https://vedarai.ru` НАМЕРЕННО: у приложения на
 * витрине есть история с 5 июня (App ID 3981361), и смена адреса разорвала бы
 * её пополам. Новые строки заводят только остальные поверхности.
 *
 * `unknown` не сваливается в «прод»: место, которого мы не определили, обязано
 * называться так вслух (§4.0). Тихо приписать его проду значит снова получить
 * цифру, за которой не видно источника.
 *
 * Значения заголовков — ТОЛЬКО ASCII. Кириллица в значении HTTP-заголовка
 * роняет fetch (undici проверяет байты Latin-1), и «красивая» подпись стоила бы
 * отказа всех вызовов провайдера.
 */

import { runPlace, type RunPlace } from '@/lib/ai/key-identity';

/** Адрес приложения на витрине OpenRouter. Группировка идёт по нему. */
const REFERER_BY_PLACE: Record<RunPlace, string> = {
  // Не менять: разорвёт историю приложения 3981361, копившуюся с 5 июня.
  prod: 'https://vedarai.ru',
  'github-actions': 'https://vedarai.ru/ci',
  local: 'https://vedarai.ru/local',
  unknown: 'https://vedarai.ru/unknown-place',
};

/** Отображаемое имя. ASCII — см. шапку файла. */
const TITLE_BY_PLACE: Record<RunPlace, string> = {
  prod: 'Vedar prod',
  'github-actions': 'Vedar CI (github runner)',
  local: 'Vedar local',
  unknown: 'Vedar (place undetermined)',
};

/**
 * Заголовки атрибуции для запроса к OpenRouter.
 *
 * @param role — необязательная роль вызова (`editor`, `judge`, `probe`).
 *   Уходит в имя, но НЕ в адрес: адрес держит поверхность, иначе витрина
 *   рассыплется на десяток строк и снова перестанет отвечать на главный
 *   вопрос — прод или CI.
 */
export function openRouterAttribution(role?: string): {
  'HTTP-Referer': string;
  'X-Title': string;
} {
  const place = runPlace();
  const title = TITLE_BY_PLACE[place];
  // Роль чистится до ASCII по той же причине, что и сами подписи. Разделитель
  // тоже ASCII: середина точка (U+00B7) пережила бы fetch, но не эту чистку.
  const suffix = role ? ` - ${role}`.replace(/[^\x20-\x7E]/g, '') : '';
  return {
    'HTTP-Referer': REFERER_BY_PLACE[place],
    'X-Title': `${title}${suffix}`,
  };
}
