/**
 * Чей расход LLM считает суточный стоп (слово владельца 23.11 «1 да»).
 *
 * Стоп (`lib/ai/daily-spend-gate.ts`, `AI_DAILY_BUDGET_USD`) закрывает новые
 * вызовы моделей на сайте, и Кузьмич отвечает туристу «на сегодня отдыхает».
 * 23.11 он закрылся на $7,60 при пороге $5, а $7,02 из них дала проверка
 * безопасности PR на раннере GitHub. Туристы молчали из-за трат, к которым
 * отношения не имеют. Теперь стоп считает только расход сайта.
 *
 * Где потрачено, пишет колонка `llm_usage_log.spent_where` (миграция 1510):
 * - 'prod' — сайт (умолчание колонки: logLLMUsage и прямой INSERT);
 * - 'runner' — раннер GitHub; ставит приём POST /api/admin/llm-usage/report;
 * - NULL — строка до миграции, место не записано. Стоп считает её вместе с
 *   сайтом: так он считал до этого дня, и пропуск строки занизил бы сумму.
 *
 * Расход раннера стоп не закрывает ничем. Его сумму крон
 * `/api/cron/llm-budget-check` называет отдельной строкой.
 */

/** Значение колонки у расхода, пришедшего с раннера. */
export const SPENT_ON_RUNNER = 'runner' as const;

/** Строки, которые считает стоп: всё, кроме расхода раннера. */
export const STOP_SPEND_SQL = `spent_where IS DISTINCT FROM '${SPENT_ON_RUNNER}'`;

/** Строки расхода раннера GitHub. */
export const RUNNER_SPEND_SQL = `spent_where = '${SPENT_ON_RUNNER}'`;

/** Окно стопа и крона: сутки UTC. */
export const SPEND_TODAY_SQL = `created_at >= DATE_TRUNC('day', NOW())`;
