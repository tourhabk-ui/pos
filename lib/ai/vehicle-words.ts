/**
 * Вид машины в просьбе об аренде — один словарь на два решения (находка 24.10):
 *
 *   - `isCarRentalAsk` (lib/ai/booking-intent): это аренда машины без
 *     водителя, и пока прокат на паузе, туристу называют паузу, а не туры;
 *   - `boundChatLane` (lib/kuzmich/bound-chat-route): просьба туриста в
 *     привязанном чате партнёра.
 *
 * До 24.10 у них было по своему списку. Первое знало только «авто / машин /
 * автомобил», второе — ещё джип, внедорожник, suv, вездеход. «Хочу арендовать
 * джип» второе считало просьбой туриста, первое арендой не считало, и паузу
 * проката турист не слышал.
 *
 * Слово целиком: «авто» не находит «автобус» и «авторский маршрут». `\b` в JS
 * кириллицу не видит, отсюда границы по \p{L}.
 */

export const VEHICLE_WORDS = [
  'автомобил\\p{L}*',
  'автомашин\\p{L}*',
  'машин\\p{L}*',
  'авто',
  'автопрокат\\p{L}*',
  'микроавтобус\\p{L}*',
  'джип\\p{L}*',
  'jeep',
  'внедорожник\\p{L}*',
  'suv',
  'вездеход\\p{L}*',
  '4x4',
  '4х4',
  '4wd',
  'car',
  'cars',
].join('|');

const VEHICLE = new RegExp(`(?<![\\p{L}\\p{N}])(?:${VEHICLE_WORDS})(?![\\p{L}\\p{N}])`, 'u');

/** В тексте назван вид машины. Текст — уже в нижнем регистре, «ё» как «е». */
export function namesVehicle(lower: string): boolean {
  return VEHICLE.test(lower);
}
