/**
 * lib/ai/deepseek-peak.ts
 *
 * Когда у DeepSeek пик, а когда скидка. ОДНО место на всю платформу.
 *
 * До 09.09 окно скидки было записано словами в четырёх файлах — трёх workflow
 * и CLAUDE.md — и во всех четырёх стояло «16:30–00:30 UTC». Уведомление
 * DeepSeek от 09.09 (в силе с 10.09 04:00 UTC) называет ПИК, а не скидку:
 * 1:00–4:00 и 6:00–10:00 UTC по будням; всё остальное — off-peak, включая
 * выходные целиком. То есть окно скидки не сдвинулось, а стало ШИРЕ, и
 * четыре записи разом устарели молча. Расписания, поставленные «ради
 * скидки» на 17/20/22/23, остались верны — но по неверной причине, и
 * следующий, кто двигал бы крон, поехал бы по устаревшей карте.
 *
 * Здесь записан факт; комментарии в workflow ссылаются сюда, а не
 * повторяют часы. Повторённый четырежды факт — это четыре факта (§12).
 *
 * Пиковые окна — по данным вендора, не по нашему замеру. Сменит вендор
 * тариф — менять здесь, и только здесь.
 */

/** Пиковые окна по UTC, [от, до) в часах, только по будням (пн–пт). */
export const DEEPSEEK_PEAK_WINDOWS_UTC: ReadonlyArray<readonly [number, number]> = [
  [1, 4],
  [6, 10],
];

/** Источник и дата — чтобы через полгода было видно, чему верить. */
export const DEEPSEEK_PEAK_SOURCE =
  'уведомления DeepSeek 09.09 и 10.09.2026: тариф V4.1 Flash с окнами пика в силе с 10.09.2026 04:00 UTC; '
  + 'V4 Pro отключается 14.09.2026 04:00 UTC (перенос с 10.09), запросы к Pro пойдут в V4.1 Flash по цене Flash';

/**
 * Пик ли сейчас у DeepSeek. Считается по UTC-часу и дню недели:
 * суббота и воскресенье — off-peak весь день.
 */
export function isDeepSeekPeak(at: Date): boolean {
  const day = at.getUTCDay(); // 0 — вс, 6 — сб
  if (day === 0 || day === 6) return false;
  const h = at.getUTCHours() + at.getUTCMinutes() / 60;
  return DEEPSEEK_PEAK_WINDOWS_UTC.some(([from, to]) => h >= from && h < to);
}

/** Пик ли для крона «минута час * * *» — по часу и минуте запуска в будний день. */
export function isPeakCronSlot(hourUtc: number, minute = 0): boolean {
  const h = hourUtc + minute / 60;
  return DEEPSEEK_PEAK_WINDOWS_UTC.some(([from, to]) => h >= from && h < to);
}
