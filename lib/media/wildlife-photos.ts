/** Фамилия и инициалы — для тесной подписи на карточке: «Сладченко В. Л.». */
export function shortCredit(full: string): string {
  const [surname, ...rest] = full.trim().split(/\s+/);
  if (!surname) return full;
  const initials = rest.map((p) => `${p.charAt(0).toUpperCase()}.`).join(' ');
  return initials ? `${surname} ${initials}` : surname;
}
