  66: 'слабый ледяной дождь', 67: 'ледяной дождь',
  71: 'слабый снег', 73: 'снег', 75: 'сильный снег', 77: 'снежные зёрна',
  80: 'слабый ливень', 81: 'ливень', 82: 'очень сильный ливень',
  85: 'снегопад', 86: 'сильный снегопад',
