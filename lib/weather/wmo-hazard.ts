/**
 * lib/weather/wmo-hazard.ts
 *
 * Какие коды погоды WMO считаются опасными для тура — ОДИН список на
 * платформу. До 10.09 он лежал приватным множеством внутри
 * `lib/agents/evo/rescue-agent.ts`, и второму читателю (вероятностный
 * прогноз, `lib/weather/ensemble.ts`) пришлось бы завести свою копию.
 * Правило, написанное дважды, — это два правила, и они расходятся (§12):
 * детерминированный прогон считал бы грозу опасной, а ансамбль — нет.
 *
 * Список НЕ полный перечень погодных кодов: описание любого кода даёт
 * `wmoDescription` в `lib/planner/intelligence.ts`. Здесь только те, из-за
 * которых тур переносят.
 */

/** Коды WMO, при которых тур под угрозой (дождь, снег, ливень, гроза). */
export const DANGEROUS_WMO_CODES: ReadonlySet<number> = new Set([
  63, 65,      // дождь
  73, 75,      // снег
  80, 81, 82,  // ливень
  85, 86,      // снегопад
  95, 96, 99,  // гроза
]);

const LABELS: Record<number, string> = {
  63: 'дождь', 65: 'сильный дождь',
  73: 'снег', 75: 'сильный снег',
  80: 'ливень', 81: 'сильный ливень', 82: 'шквал',
  85: 'снегопад', 86: 'сильный снегопад',
  95: 'гроза', 96: 'гроза с градом', 99: 'сильная гроза',
};

/**
 * Название опасности по коду. `null` — код не из опасных ЛИБО опасен, но
 * без имени: и то и другое лучше пустоты, выдуманной за него вызывающим.
 */
export function wmoHazardLabel(code: number): string | null {
  return LABELS[code] ?? null;
}
