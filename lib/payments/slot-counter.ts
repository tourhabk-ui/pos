/**
 * Счётчик занятых мест уменьшается при отмене — ровно один раз на отмену.
 *
 * ── Почему это срочно (#1816, воспроизведено 11.09) ───────────────────────
 *
 * `tour_availability.booked_slots` увеличивали два платёжных вебхука.
 * Уменьшал НИКТО. А на таблице висит
 *
 *     CHECK (booked_slots >= 0 AND booked_slots <= available_slots)
 *
 * Прогон на реальном определении таблицы (temp-копия с теми же ограничениями,
 * всё в транзакции с откатом):
 *
 *     оплачено 10 из 10  -> booked_slots = 10
 *     все 10 отменены    -> booked_slots = 10   (уменьшать некому)
 *     следующая оплата   -> ERROR: violates check constraint "booked_valid"
 *
 * То есть ОДНОГО цикла «дату выкупили — дату отменили» хватает, чтобы эта
 * дата тура больше не приняла ни одной оплаты: инкремент стоит ВНУТРИ
 * транзакции оплаты, и его отказ роняет всю обработку — бронь не помечена
 * оплаченной, `tour_payments` не создан, банк повторяет вебхук по кругу.
 *
 * Заметить это по экранам нельзя: все витрины считают занятость из реальных
 * броней (`SUM(participants) ... NOT IN ('cancelled','rejected')`), поэтому
 * дата выглядит свободной и при этом мертва. Узнают о ней на первой
 * сорвавшейся оплате.
 *
 * Прошлый раз этот CHECK уже ронял оплату — из-за двойного инкремента
 * (комментарий в `app/api/bookings/tour/route.ts`). Тогда убрали двойной
 * счёт, то есть замедлили переполнение, но не сделали счётчик двусторонним.
 *
 * ── Ровно один раз на отмену ──────────────────────────────────────────────
 *
 * Вычитать по факту вызова нельзя: повторная отмена (двойной клик, повтор
 * вебхука, две вкладки) вычла бы дважды, и счётчик ушёл бы в минус — а там
 * тот же CHECK с другой стороны. Поэтому вычитание привязано к ПЕРЕХОДУ:
 * зовётся только когда UPDATE брони реально изменил строку, то есть статус
 * действительно стал отменённым, а не был им.
 *
 * `GREATEST(0, ...)` — вторая линия: если переход всё же посчитали дважды,
 * счётчик упрётся в ноль, а не свалит транзакцию отмены. Отмена не должна
 * падать из-за учёта мест; место — следствие отмены, а не её условие.
 *
 * ── Что вычитается ────────────────────────────────────────────────────────
 *
 * Только у ОПЛАЧЕННЫХ броней: счётчик наполняют платёжные вебхуки, и его
 * смысл — «оплаченные участники». Отмена неоплаченной заявки в нём и не
 * учитывалась, вычитать нечего.
 */

import type { PoolClient } from 'pg';

/**
 * Вернуть места отменённой брони в `tour_availability`.
 *
 * Зовётся ВНУТРИ той же транзакции, что и смена статуса брони, и только
 * после того, как переход действительно произошёл (UPDATE изменил строку).
 *
 * Возвращает число изменённых строк доступности: 0 — законное состояние
 * (бронь не была оплачена, или слота на эту дату нет), а не отказ.
 */
export async function releaseSlotsForCancelledBooking(
  client: PoolClient,
  bookingId: string | number | bigint,
): Promise<number> {
  const res = await client.query(
    `UPDATE tour_availability ta
        SET booked_slots = GREATEST(0, ta.booked_slots - b.participants),
            updated_at   = NOW()
       FROM operator_bookings b
      WHERE b.id = $1
        AND b.payment_status = 'paid'
        AND ta.operator_tour_id = b.operator_tour_id
        AND ta.date = b.booking_date`,
    [bookingId],
  );
  return res.rowCount ?? 0;
}
