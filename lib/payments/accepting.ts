/**
 * lib/payments/accepting.ts — принимает ли платформа оплату сейчас.
 *
 * ── Решение владельца 05.10 ────────────────────────────────────────────────
 *
 * «Пока уберём оплату» — чтобы не попасть на штрафы, пока не подано
 * уведомление в Роскомнадзор и не выверена схема приёма денег. Ведар на это
 * время — информационный сервис и площадка заявок: бронь остаётся заявкой,
 * которую подтверждает оператор, а платит турист оператору напрямую.
 *
 * Выключатель — константа в коде, а не переменная окружения, намеренно.
 * Переменную на проде меняют молча, и следующий читатель кода не узнает, что
 * оплата снова открыта; включение обратно должно быть видимым коммитом —
 * вместе с текстами оферты и условий, которые сейчас говорят «оплату не
 * принимает».
 *
 * Что выключено через этот флаг (сторож tests/unit/payments-paused.test.ts):
 *   - `paymentAvailability()` не отдаёт ни ключ карты, ни СБП — страница брони
 *     не рисует ни виджет CloudPayments, ни QR;
 *   - `isTochkaConfigured()` ложна — приёмник QR (`/api/payments/tochka/qr`,
 *     зона §7, не правится) и оплата мест у перевозчика отвечают отказом;
 *   - `/api/tours/[id]/book` не выставляет счёт CloudPayments;
 *   - тексты туристу (страница брони, письма, Кузьмич, справка) говорят
 *     «оплата напрямую оператору».
 *
 * Приёмники вебхуков не тронуты: если банк пришлёт уведомление по платежу,
 * начатому ДО выключения, оно обработается как раньше.
 */

export const PLATFORM_ACCEPTS_PAYMENTS = false;

export function platformAcceptsPayments(): boolean {
  return PLATFORM_ACCEPTS_PAYMENTS;
}
