/**
 * Деньги за ОТМЕНЁННУЮ бронь не уезжают оператору сами.
 *
 * ── Что нашлось на разборе денежного пути 11.09 (#1813) ───────────────────
 *
 * `tour_payments.status` пишут ровно три места, и все три двигают деньги
 * только вперёд: `PENDING → HELD` при оплате и `HELD → RELEASED` при выплате.
 * Отмена брони не трогает платёж НИГДЕ. Значит:
 *
 *   1. турист платит — платёж в `HELD`, `release_after` = конец тура + 36 ч;
 *   2. бронь отменяют — `booking_status` меняется, платёж остаётся `HELD`;
 *   3. наступает `release_after` — часовой релиз выбирает платежи
 *      `WHERE status = 'HELD' AND release_after <= NOW()` и НЕ СПРАШИВАЕТ
 *      бронь вообще. Деньги уходят оператору за тур, который отменён.
 *
 * Возврата в платформе нет ни одного: `REFUNDED` встречается в репозитории
 * единственный раз — счётчиком на админском экране финансов, у которого нет
 * писателя. Это отдельный вопрос к владельцу (#1813), и здесь он не решается.
 *
 * ── Что решается здесь, и почему без спроса ───────────────────────────────
 *
 * «Сколько вернуть туристу» — решение владельца. «Не платить автоматически за
 * отменённое» — не решение, а отсутствовавшая проверка. Разница в
 * необратимости: пропущенная выплата чинится следующим прогоном, ушедшая
 * чужому — перепиской и доверием.
 *
 * Поэтому предикат ниже только ПРИДЕРЖИВАЕТ платёж, не меняя ни его статус,
 * ни сумму. А чтобы придержанное не стало новым молчанием, у него есть
 * отдельное имя и отдельная тревога Watchdog: деньги туриста лежат у нас, и
 * это должно быть видно, а не выводиться вычитанием (§4.0).
 *
 * ── Почему список статусов шире, чем пишет живой код ──────────────────────
 *
 * Сегодня в `operator_bookings.booking_status` живой код пишет только
 * `cancelled`. Но тип `BookingStatus` в интерфейсе туриста уже знает
 * `cancelled_by_tourist`, `cancelled_by_operator` и `refunded`, а
 * `lib/bookings/booking.service.ts` пытается их писать (#1814). CHECK на
 * колонке нет — записаться может любая строка.
 *
 * Здесь взят СУПЕРСЕТ намеренно: ошибка в сторону «придержали лишнее»
 * обратима, ошибка в сторону «заплатили за отменённое» — нет.
 */

/** Статусы брони, при которых платёж не уходит оператору сам. */
export const CANCELLED_BOOKING_STATUSES = [
  'cancelled',
  'cancelled_by_tourist',
  'cancelled_by_operator',
  'refunded',
] as const;

/**
 * SQL-условие «у этого платежа бронь НЕ отменена».
 *
 * `$${n}` подставляется вызывающим: параметр — массив статусов, а не склейка
 * строк. `alias` — как назван `tour_payments` в запросе.
 */
export function notCancelledBookingSql(alias: string, paramIndex: number): string {
  return `NOT EXISTS (
    SELECT 1 FROM operator_bookings ob
     WHERE ob.id = ${alias}.booking_id
       AND ob.booking_status = ANY($${paramIndex}::text[])
  )`;
}

/** Обратное условие — для переписи придержанных. */
export function cancelledBookingSql(alias: string, paramIndex: number): string {
  return `EXISTS (
    SELECT 1 FROM operator_bookings ob
     WHERE ob.id = ${alias}.booking_id
       AND ob.booking_status = ANY($${paramIndex}::text[])
  )`;
}

/** Значение параметра для обоих условий выше. */
export const CANCELLED_STATUS_PARAM: string[] = [...CANCELLED_BOOKING_STATUSES];
