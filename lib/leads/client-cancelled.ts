/**
 * Заявку отменил клиент (`leads.status = 'cancelled'`, миграция 1427).
 *
 * Отмена — слово самого человека, и ни один автомат её не отменяет: конвейер
 * разбора не подбирает по ней туры, крон добивки не передаёт её другим
 * операторам, бронь из неё не заводят, статус вручную не возвращают. Здесь —
 * общее для этих мест: условие запроса, ошибка, которой конвейер говорит «не
 * сбой, а отменённая заявка», и слова продавцу.
 */

import { LEAD_CLIENT_CANCELLED } from '@/lib/types/statuses';

/**
 * Условие «заявку не отменил клиент» для запроса по таблице `leads` без
 * псевдонима. Поиск «прежней» заявки (lib/leads/create) обязан его ставить:
 * иначе новая заявка в течение суток после отмены вернула бы отменённую с
 * ответом «принята» — и человек остался бы без заявки, думая, что она есть.
 */
export const NOT_CLIENT_CANCELLED_SQL = `status <> '${LEAD_CLIENT_CANCELLED}'`;

/** Продавцу и администратору, который меняет статус такой заявки: одно и то же на сайте и в чате. */
export const LEAD_CANCELLED_STATUS_TEXT = 'Заявку отменил клиент — статус не меняется';

/** Продавцу, ответившему кнопкой на заявку, которую клиент уже отменил. */
export const LEAD_CANCELLED_ANSWER_TEXT = 'Клиент отменил эту заявку — она закрыта. Отвечать по ней и держать места не нужно.';

/** Конвейер разбора встретил заявку, отменённую клиентом: подбирать по ней не для кого. */
export class LeadCancelledByClientError extends Error {
  constructor() {
    super('Заявку отменил клиент — туры к ней не подбираются.');
    this.name = 'LeadCancelledByClientError';
  }
}
