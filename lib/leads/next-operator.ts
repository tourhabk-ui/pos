/**
 * lib/leads/next-operator.ts — кому из операторов добивка отдаёт лид следующим.
 *
 * Слово владельца 12.11: «жребий дня». До этого дня оба запроса крона
 * (`/api/cron/leads-followup`) кончались `LIMIT 1` без `ORDER BY`: следующим
 * становился тот, чью строку база вернула первой, — на деле один и тот же
 * оператор изо дня в день. Клиент доставался ему не по правилу, а по
 * устройству таблицы, и назвать это правило было нельзя (CLAUDE.md §0: общие
 * поверхности упорядочиваются одним правилом для всех, без ручных поднятий).
 *
 * Правило — тот же жребий дня компании, что у витрин (правило 1в,
 * lib/tours/offer-order, `companyLot`): один билет на компанию в день по
 * Камчатке, воспроизводимый по дате и id партнёра. Своего жребия здесь нет:
 * второе правило разошлось бы с первым. Очередь по кругу не взята, потому что
 * ей нужно хранимое состояние и новое правило, а жребий уже назван туристу.
 *
 * Свойство, о котором надо знать: в один календарный день первым идёт один
 * и тот же оператор для всех лидов дня — среди подходящих и ещё не
 * получавших этот лид; назавтра первым будет другой. Ступень «по интересам»
 * стоит в кроне раньше жребия: совпадение с запросом — первый ключ, жребий
 * решает ничью внутри ступени.
 *
 * Модуль чистый, без базы. Сторож: tests/unit/leads-next-operator.test.ts.
 */

import { companyLot } from '@/lib/tours/offer-order';

/**
 * Победитель жребия дня среди кандидатов: наименьший билет, при равных
 * билетах — меньший id (устойчивость, а не ранг). Порядок кандидатов на
 * входе на исход не влияет — в этом и состоит отличие от первой строки базы.
 * Пустой список — null.
 */
export function pickNextOperator<T extends { id: string }>(candidates: readonly T[], day: string): T | null {
  let best: T | null = null;
  let bestLot = 0;
  for (const c of candidates) {
    const lot = companyLot(day, c.id);
    if (best === null || lot < bestLot || (lot === bestLot && c.id < best.id)) {
      best = c;
      bestLot = lot;
    }
  }
  return best;
}
