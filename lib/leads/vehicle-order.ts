/**
 * Заявка на машину, а не на подбор тура.
 *
 * Повод — тестовая заявка владельца 10.10: ассистент оформил заказ двух
 * вахтовок на Горелый через create_lead, а не через request_charter. AI Lead
 * Processor принял её за подбор тура: подобрал многодневные туры «с Горелым»
 * по 115–140 тыс. на человека и написал предложение о них. Заявке на машину
 * подбор туров не нужен. Её ведёт менеджер с перевозчиком, как и заявку из
 * request_charter (там skip_ai_processing стоит с 10.10).
 *
 * Признак узкий намеренно: машина названа предметом заказа («заказ целой
 * машины», «2 вахтовки», «трансфер на вахтовке»), и тур при этом не упомянут.
 * «Тур на Горелый на вахтовке» — по-прежнему подбор тура: вахтовка там способ
 * доехать, а не то, что покупают.
 */

const VEHICLE_ORDER_RE = new RegExp([
  // «заказ целой машины», «заказать вахтовку», «заказ автобуса»
  'заказ[а-яё]*\\s+(?:цел[а-яё]+\\s+|всей\\s+)?(?:машин|вахтовк|автобус|микроавтобус|транспорт)',
  // «2 вахтовки», «две вахтовки»
  '(?:\\d+|одн[ау]|две|два|три)\\s+вахтов',
  // «трансфер на вахтовке»
  'трансфер[а-яё]*\\s+на\\s+вахтовк',
  // «аренда вахтовки», «арендовать автобус»
  'аренд[а-яё]*\\s+(?:вахтовк|автобус|микроавтобус|машин)',
  // «нужна вахтовка»
  'нуж[а-яё]*\\s+(?:вахтовк|автобус|микроавтобус)',
].join('|'), 'iu');

// Тур упомянут: «тур», «туры», «тура», «экскурсия». «Туристы» туром не
// считаются — про людей в машине так тоже говорят.
const TOUR_RE = /(?<![а-яё])(?:тур|тура|туры|туров|туру|туре|туром|турами|экскурси[а-яё]*)(?![а-яё])/iu;

export function isVehicleOrder(text: string | null | undefined): boolean {
  if (!text) return false;
  return VEHICLE_ORDER_RE.test(text) && !TOUR_RE.test(text);
}

/** Ответ на попытку подобрать туры к заявке на машину. */
export class LeadIsVehicleOrderError extends Error {
  constructor() {
    super('Это заявка на машину (вахтовка, трансфер), а не на подбор тура — туры к ней не подбираются. '
      + 'Свяжитесь с клиентом и перевозчиком сами.');
    this.name = 'LeadIsVehicleOrderError';
  }
}
