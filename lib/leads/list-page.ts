/**
 * Страница списка лидов: одно число на роут и на доску.
 *
 * GET /api/leads отдаёт не больше LEADS_PAGE_MAX лидов за запрос, а канбан
 * (у администратора и у оператора) просил `limit=200`. Схема роута отвечала на
 * это 400, каждая колонка падала, и доска показывала ошибку загрузки с того
 * дня, как появилась (аудит 22.10). Тест доски подменял fetch ответом 200 —
 * расхождение двух чисел в двух файлах видно не было.
 *
 * Теперь потолок один — здесь, — и доска читает колонку страницами до счёта
 * `total`, а не первой сотней: молча обрезанная колонка была бы той же
 * неправдой, что и пустая.
 */
export const LEADS_PAGE_MAX = 100;

/** Адрес страницы колонки — тот, что доска отдаёт роуту. */
export function leadsPageUrl(status: string, offset: number): string {
  const qs = new URLSearchParams({ status, limit: String(LEADS_PAGE_MAX), offset: String(offset) });
  return `/api/leads?${qs.toString()}`;
}
