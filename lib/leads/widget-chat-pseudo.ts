/**
 * lib/leads/widget-chat-pseudo.ts — «лиды» чата виджета партнёра, записанные
 * до 15.10: не заявки, а первое сообщение посетителя.
 *
 * До 15.10 `POST /api/widget/chat` на первое же сообщение звал `createLead`:
 * имя `Widget: <slug>`, телефона нет, согласия на ПД нет, адресата нет,
 * `source_data.type = 'widget'`. Через 2 часа крон добивки отдавал такой «лид»
 * первому свободному оператору как «горячий» — вопрос с сайта партнёра уходил
 * конкуренту, — а сторож лидов (watchdog, «лиды >2ч») считал его неотвеченной
 * заявкой. Каждая перезагрузка страницы партнёра давала новый (аудит 15.10,
 * WID-safety).
 *
 * Чат больше лидов не создаёт: заявка — только формой с телефоном и
 * согласием (`/widget/lead-form/<slug>`). Записанные строки не удаляются и не
 * правятся — это след того, что люди спрашивали, — а исключаются предикатом
 * там, где они врут, то есть порождают передачу, тревогу или работу модели:
 *  - передача другому партнёру — отбор добивки (`lib/leads/followup-scope`);
 *  - тревоги — сторож «лиды >2ч» (watchdog), «лидов без обработки > 6ч» у
 *    крона health и команды /health админ-бота, «лидов без ответа >24ч» у
 *    рассылки bulk_notify, очередь «Новые (не обработаны)» в дайджесте;
 *  - работа модели — конвейер `leads-process`, пакет
 *    `/api/admin/leads/process-batch`, квалификация `LeadAgency`
 *    (аудит 15.10, W3-pseudo).
 * Переписи и отчёты, которые считают их отдельной строкой (перепись
 * виджетов `lib/analytics/widget-census`), и списки заявок у админа их
 * по-прежнему видят: прятать след оттуда — значит врать о прошлом.
 *
 * Предикат узкий намеренно: все три признака сразу. Заявка с формы виджета
 * (`source_data.source = 'partner_widget'`, телефон, согласие) под него не
 * попадает, и лид с типом `widget`, у которого телефон есть, — тоже.
 * COALESCE у каждого признака: строка с NULL в `source_data`, `phone` или
 * `name` иначе дала бы NULL под NOT и выпала бы из отбора молча.
 *
 * Сторож: tests/integration/leads-followup.pg.test.ts — отбор добивки, крон,
 * счёт watchdog, сам предикат на строках с NULL и каждый читатель из списка
 * выше вызовом, на настоящем PostgreSQL.
 */

/** Условие «это псевдолид чата виджета». Колонки таблицы `leads` без алиаса. */
export const WIDGET_CHAT_PSEUDO_LEAD_SQL =
  `(COALESCE(source_data->>'type', '') = 'widget'`
  + ` AND COALESCE(phone, '') = ''`
  + ` AND COALESCE(name, '') LIKE 'Widget: %')`;
