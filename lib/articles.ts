export interface ArticleSection {
  heading: string;
  paragraphs: string[];
}

export interface Article {
  /** Он же адрес: /articles/[id]. Поле названо как у рыб — справочники зеркальны. */
  id: string;
  title: string;
  /**
   * Короткий ответ на вопрос статьи. Живёт в первом экране: SEO-аудит 06.08 —
   * AI-поиск берёт около 44% цитат из первых 30% страницы, и цитировать он
   * должен ответ, а не подводку.
   */
  lead: string;
  category: ArticleCategory;
  /** Дата последней правки текста, ISO. Показывается читателю. */
  updated: string;
  sections: ArticleSection[];
  keywords: string[];
  /**
   * Упоминания в чужих текстах превращаются в ссылку сюда.
   *
   * Только явные кириллические классы: `\w` в JS — это [A-Za-z0-9_], русских
   * окончаний он не берёт, и паттерн вида `регистрац\w*` молча не совпадает
   * ни с чем. Справочник рыб обходит это так же ([аыуией]).
   */
  patterns: RegExp[];
}

