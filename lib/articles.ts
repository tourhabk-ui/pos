/**
 * Справочник статей — единый источник, по образцу lib/fish-species.ts.
 *
 * Устроен так же и по той же причине. У рыб справочник кормит сразу три
 * поверхности: витрину /fish, ссылки в чужих описаниях и сезонную сетку на
 * карточке тура. Второй список видов завести нельзя — расхождение копий стоит
 * дороже любой экономии (tests/unit/fish-season-card.test.ts). Статьи живут по
 * тем же правилам: один массив здесь, страницы и подсветка читают его.
 *
 * ── Почему в коде, а не в базе ─────────────────────────────────────────────
 *
 * Статья тут — не запись блога, а справочная тема, на которую ссылаются другие
 * тексты платформы. Таких тем немного и они меняются редко, зато их содержание
 * обязано пережить любой сбой БД: человек читает «что взять» и «как
 * зарегистрироваться» ровно тогда, когда собирается в место без связи.
 * Справочник в коде рендерится статически и работает офлайн — как и /fish.
 *
 * Ленту машинных дайджестов это не заменяет: она живёт в agent_knowledge и
 * рендерится на /blog. Там поток, здесь — то, что стоит на месте.
 *
 * ── Чего здесь быть не должно ──────────────────────────────────────────────
 *
 * Цифр, которых нет в наших данных или в названном документе. Срок подачи
 * заявки в МЧС, размер штрафа, высота перевала — это факты, у которых есть
 * владелец, и выдумывать их в статье нельзя (CLAUDE.md §8: критичные факты —
 * из инструментов и БД, самоотчётам модели не верить). Где источник внешний и
 * непроверенный — это сказано прямо в тексте статьи.
 *
 * Второго списка видов рыб, снаряжения или маршрутов. У них свои справочники,
 * статья на них ссылается.
 */

