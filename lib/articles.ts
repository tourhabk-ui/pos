/** Быстрый доступ по id. */
export const ARTICLE_BY_ID: Record<string, Article> = Object.fromEntries(
  ARTICLES.map(a => [a.id, a]),
);

/** Весь текст статьи одной строкой — для оценки объёма и поиска. */
export function articleFullText(a: Article): string {
  return [a.title, a.lead, ...a.sections.flatMap(s => [s.heading, ...s.paragraphs])].join(' ');
}

/** Средняя скорость чтения по-русски — 180 слов в минуту, округляем вверх. */
export function readingMinutes(a: Article): number {
  const words = articleFullText(a).split(/\s+/).filter(Boolean).length;
  return Math.max(1, Math.ceil(words / 180));
}

/**
 * Какие статьи упомянуты в тексте.
 *
 * Те же паттерны, что у подсветки ссылок: блок «по теме» обязан появляться
 * ровно тогда, когда упоминание подсветилось бы ссылкой. Разъехавшиеся детект
 * и подсветка дают экран, где слово подчёркнуто, а блока нет, — или наоборот.
 */
export function detectArticles(text: string): Article[] {
  return detectLinkables(text, ARTICLES);
}

/** Нарезка текста со ссылками на статьи. Общий матчер, тот же что у рыб. */
export function linkifyArticles(text: string, excludeId?: string): LinkedChunk<Article>[] {
  return linkifyText(text, ARTICLES, excludeId);
}
