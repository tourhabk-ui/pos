/**
 * Протокол решения — то, что код уже решил, в виде, пригодном для пересказа.
 *
 * ── Зачем это заведено (21.09) ────────────────────────────────────────────
 *
 * Владелец спросил, нельзя ли сделать так, чтобы проект сам был ИИ и любое
 * действие на проде было живым промптом. В чистом виде нельзя: полевой контур
 * обязан работать без связи, деньги и безопасность не терпят
 * недетерминированности, а §4.0 прямо говорит, чем кончается место, где
 * нельзя сказать «не знаю».
 *
 * Но есть сторона, где модель уместна и безопасна: не РЕШАТЬ, а ОБЪЯСНЯТЬ
 * уже принятое решение. Человек на экране планирования читает сухое «Точка
 * стоит в 7.9 км от линии — данные маршрута не сходятся» и не понимает
 * главного: идти ему или нет и чем это грозит.
 *
 * Отсюда разделение, которое держит весь механизм:
 *
 *   решает код — объясняет модель — проверяет снова код.
 *
 * ── Что здесь есть ────────────────────────────────────────────────────────
 *
 * Снимок решения: вердикт, право вести, причины словами и проверяемые факты.
 * Ничего не вычисляется: запись СОБИРАЕТСЯ из готового решения. Считать
 * вердикт здесь заново значило бы завести второе правило (§12) — и второе
 * могло бы разойтись с тем, что человек видит на экране.
 *
 * ── Чего здесь нет ────────────────────────────────────────────────────────
 *
 * Текста для человека. Слова — дело модели, и ровно потому им нельзя верить
 * на слово: проверяет их `no-invention` по этой же записи.
 */

import { createHash } from 'node:crypto';

/** Один проверяемый факт, из которых собран вердикт. */
export interface DecisionFact {
  /** Машинное имя: `off_track_km`, `line_kind`, `waypoints`. */
  key: string;
  /** Что это значит словами — формулировка кода, не модели. */
  label: string;
  /** Значение как строка. Только эти числа модель вправе называть. */
  value: string;
}

export interface DecisionRecord {
  /** Какое решение объясняем. Пока одно: `route_navigability`. */
  kind: 'route_navigability';
  /** Вердикт кода. Модель его не меняет и не оспаривает. */
  verdict: string;
  /** Вправе ли платформа обещать ведение по линии. */
  canLead: boolean;
  /**
   * Причины словами — то, что человек видит и БЕЗ объяснения.
   *
   * Они же фолбэк: модель молчит или соврала — на экране остаётся это.
   * Поэтому запись годна сама по себе, а не только как корм для промпта.
   */
  reasons: string[];
  facts: DecisionFact[];
}

/**
 * Все числа, которые запись содержит, — то, что модели разрешено называть.
 *
 * Берутся из причин и значений фактов, потому что и там и там числа пришли
 * из кода. Пересказ вправе повторить число записи и не вправе принести своё:
 * «примерно восемь километров» вместо 7.9 — уже не пересказ, а редактура
 * факта, которую никто не проверял.
 */
export function recordNumbers(rec: DecisionRecord): Set<string> {
  const out = new Set<string>();
  const add = (s: string) => {
    for (const m of s.matchAll(/\d+(?:[.,]\d+)?/g)) out.add(m[0].replace(',', '.'));
  };
  rec.reasons.forEach(add);
  rec.facts.forEach((f) => { add(f.value); add(f.label); });
  return out;
}

/**
 * Отпечаток решения — ключ кэша объяснений.
 *
 * Считается от СОДЕРЖАНИЯ, а не от id маршрута: пока вердикт и факты те же,
 * объяснение то же, и платить за него второй раз незачем. Изменились данные
 * маршрута — изменился отпечаток, и объяснение пересобирается само.
 */
export function decisionFingerprint(rec: DecisionRecord): string {
  const canon = JSON.stringify({
    kind: rec.kind,
    verdict: rec.verdict,
    canLead: rec.canLead,
    reasons: [...rec.reasons],
    facts: rec.facts.map((f) => [f.key, f.value]),
  });
  return createHash('sha256').update(canon).digest('hex').slice(0, 16);
}
