/**
 * Объяснение проверяется кодом — иначе это не объяснение, а вторая версия
 * правды.
 *
 * ── Почему проверка обязательна (21.09) ───────────────────────────────────
 *
 * Модель пересказывает решение о маршруте человеку, который по этому решению
 * пойдёт или не пойдёт в поле. Ошибка пересказа здесь не косметическая:
 * «ничего страшного, линия почти совпадает» поверх вердикта «вести нельзя»
 * отправляет человека туда, куда платформа идти не обещала.
 *
 * Выдумку как таковую детерминированно не поймать — это уже записано в
 * `desc-facts`. Ловится ПРОТИВОРЕЧИЕ тому, что платформа знает сама, и здесь
 * знание особенно чёткое: есть протокол решения, и всё, что пересказ вправе
 * назвать, лежит в нём.
 *
 * ── Что проверяется ───────────────────────────────────────────────────────
 *
 *  - число, которого нет в протоколе (включая «округлённое» до соседнего) —
 *    отказ: пересказ повторяет факт, а не редактирует его;
 *  - совет сойти с тропы — отказ, правило берётся из `post-validation`, а не
 *    пишется заново (§12);
 *  - обещание трека там, где вести нельзя, — отказ;
 *  - эмодзи и длина сверх меры — отказ: это правила проекта, и объяснение им
 *    подчиняется наравне с остальным текстом.
 *
 * ── Три исхода, а не два ──────────────────────────────────────────────────
 *
 * `unavailable` (модель не ответила) — НЕ то же, что `rejected` (ответила и
 * соврала). Первое означает «объяснения нет», второе — «объяснению нельзя
 * верить»; и то и другое возвращает человека к сухим причинам из протокола,
 * но в журнале это разные строки, и смешивать их значило бы потерять вид
 * отказа (§4.0).
 *
 * ── Чего проверка НЕ ловит, и это названо честно ──────────────────────────
 *
 * Число, написанное словами: «примерно восемь километров» пройдёт, потому что
 * цифры в тексте нет. Заводить словарь числительных ради этого — отдельная
 * работа; пока промпт прямо требует цифр, а не слов, и это условие держит
 * сторож.
 */

import { advisesLeavingTrail } from '@/lib/notifications/post-validation';
import { claimsTrack } from '@/lib/routes/desc-facts';
import { recordNumbers, type DecisionRecord } from '@/lib/explain/decision-record';

/** Объяснение — одна-две фразы. Длиннее человек на экране выбора не читает. */
export const MAX_EXPLANATION_CHARS = 400;
/** Короче этого — не пересказ, а обрывок. */
export const MIN_EXPLANATION_CHARS = 20;

export type ExplanationCheck =
  /** Пересказ не противоречит протоколу — можно показывать. */
  | { state: 'accepted'; text: string }
  /** Ответ был, но ему нельзя верить. `why` — для журнала, не для экрана. */
  | { state: 'rejected'; why: string }
  /** Ответа не было вовсе: нет связи, нет ключа, провайдер молчит. */
  | { state: 'unavailable'; why: string };

/** Числа текста в том же виде, в каком их знает протокол. */
function textNumbers(text: string): string[] {
  return [...text.matchAll(/\d+(?:[.,]\d+)?/g)].map((m) => m[0].replace(',', '.'));
}

export function checkExplanation(
  text: string | null,
  rec: DecisionRecord,
): ExplanationCheck {
  if (text === null) return { state: 'unavailable', why: 'модель не ответила' };

  const t = text.trim();
  if (t.length < MIN_EXPLANATION_CHARS) return { state: 'rejected', why: 'ответ пуст или обрывок' };
  if (t.length > MAX_EXPLANATION_CHARS) return { state: 'rejected', why: 'ответ длиннее меры' };
  if (/\p{Extended_Pictographic}/u.test(t)) return { state: 'rejected', why: 'эмодзи' };
  if (advisesLeavingTrail(t)) return { state: 'rejected', why: 'совет сойти с тропы' };
  if (!rec.canLead && claimsTrack(t)) {
    return { state: 'rejected', why: 'обещание трека там, где вести нельзя' };
  }

  const known = recordNumbers(rec);
  for (const n of textNumbers(t)) {
    if (!known.has(n)) return { state: 'rejected', why: `число ${n} не из протокола` };
  }

  return { state: 'accepted', text: t };
}
