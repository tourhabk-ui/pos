/**
 * Пресеты программатик-страниц планов (/plans/[slug]).
 *
 * «Мой план 2.0», этап A-1 (владелец 08.08: «план мне нравится, реализуем»).
 * Разведка по TAAFT: 84 планировщика, ни одной индексируемой страницы про
 * Камчатку с реальной бронью — ниша пустая. Каждый пресет — готовый план
 * «Камчатка за N дней под интересы X»: движок recommendTrip собирает дни,
 * страница выглядит как публичный план и ведёт к брони реальных туров.
 *
 * Гард от thin content (seo-programmatic): интро КАЖДОГО пресета написано
 * руками и уникально — страницы различаются не только числом в заголовке.
 * Интересы — только ключи INTEREST_TO_ZONES движка (сторож проверяет).
 */

export interface PlanPreset {
  /** URL-слаг: kamchatka-za-7-dney-vulkany */
  slug: string;
  /** H1 и заголовок вкладки */
  title: string;
  /** Число дней поездки (длина плана движка) */
  days: number;
  /** Интересы для recommendTrip — ключи INTEREST_TO_ZONES */
  interests: string[];
  /** Рукописное интро страницы, 2–4 предложения, уникальное */
  intro: string;
  /** Meta description */
  description: string;
  /**
   * Поля посадочного кластера (стратегия 14.08): высокоинтентная страница
   * обязана называть дату ревизии текста, источник условий и честные
   * ограничения — иначе она неотличима от случайной статьи, а в
   * safety-first продукте устаревшая страница вредит сильнее отсутствующей.
   * У обычных «N дней» пресетов полей нет — их актуальность несёт движок.
   */
  cluster?: {
    /** Дата последней ревизии текста, YYYY-MM-DD — видна читателю */
    updated: string;
    /** Откуда взяты условия (словами, не ссылкой на всё подряд) */
    sourceNote: string;
    /** Честные ограничения формата/сезона — по одному предложению */
    limitations: string[];
  };
}

