/**
 * Вопросы-ответы хаба /plans — из данных пресетов, не из головы.
 *
 * Зачем: запрос «Камчатка туры план» в AI-ответе с веб-поиском получает
 * цитату из страницы, которая отвечает на вопрос прямо, в первом экране, и
 * размечена как FAQPage. До 18.09 хаб отвечал «Готовые планы поездок» и
 * списком ссылок — цитировать было нечего.
 *
 * Правило §4.0: числа считаются из PLAN_PRESETS, а не печатаются руками;
 * про цены сказано, откуда они берутся, а не «от 50 000 ₽». Ответы
 * повторяют то, что страницы планов и так обещают (интро и ограничения
 * кластеров), — новых утверждений о Камчатке здесь нет.
 */

import { PLAN_PRESETS } from '@/lib/plans/presets';

export interface PlanFaqItem {
  question: string;
  answer: string;
}

const dayList = (): string => {
  const days = [...new Set(PLAN_PRESETS.map((p) => p.days))].sort((a, b) => a - b);
  return days.join(', ').replace(/, (\d+)$/, ' и $1');
};

const seasonal = PLAN_PRESETS.filter((p) => /^kamchatka-v-|^kamchatka-zimoy$/.test(p.slug));

export function buildPlansFaq(): PlanFaqItem[] {
  const minDays = Math.min(...PLAN_PRESETS.map((p) => p.days));
  return [
    {
      question: 'Сколько дней нужно на поездку по Камчатке?',
      answer:
        `Готовые планы рассчитаны на ${dayList()} дней. Минимум — ${minDays}: акклиматизация, один полноценный выход и день в термальной воде. ` +
        `Неделя даёт запасной день на погоду, десять дней и больше — вертолётные дни и дальние зоны.`,
    },
    {
      question: 'Сколько стоит тур на Камчатку по готовому плану?',
      answer:
        'На странице каждого плана строка «активности от … ₽ на человека» считается из живого каталога туров операторов на ближайшие даты, ' +
        'а у каждого дня показан конкретный тур с ценой. Перелёт и жильё в эту сумму не входят.',
    },
    {
      question: 'Когда лучше ехать на Камчатку?',
      answer:
        `Зависит от цели: ${seasonal.map((p) => `«${p.title}»`).join(', ')} — отдельные планы с честными оговорками по сезону. ` +
        'Высокие маршруты открыты с июля по сентябрь, медведи лучше всего видны с июля по сентябрь на нерестовых реках.',
    },
    {
      question: 'Можно ли забронировать туры прямо из плана?',
      answer:
        'Да: каждый день плана ведёт на тур оператора с ценой и датой. Заявку на бронь подтверждает оператор по телефону, мгновенной оплаты нет.',
    },
    {
      question: 'Насколько это безопасно?',
      answer:
        'План собирается только из маршрутов с профилем безопасности, на каждый день показан статус обстановки в крае, ' +
        'а планировщик напоминает о регистрации в МЧС по вашим датам. Медвежьи районы — только с гидом.',
    },
  ];
}
