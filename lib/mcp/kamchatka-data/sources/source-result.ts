/**
 * Ответ источника, у которого есть третий исход.
 *
 * ── Что чинится ────────────────────────────────────────────────────────────
 *
 * Все три источника MCP-сервера собирают данные по нескольким каналам, ловят
 * отказ каждого и продолжают со следующим. Ловить правильно: падение одного
 * канала МЧС не должно ронять сбор остальных. Но возвращали они `unknown[]`,
 * и при отказе ВСЕХ каналов наверх уходил пустой массив.
 *
 * Пустой массив читается как «предупреждений нет». На слое безопасности это
 * худший вид тишины: он выглядит как спокойствие. Клиент MCP — в том числе
 * Кузьмич, отвечающий человеку в поле, — не мог отличить «МЧС молчит, всё
 * тихо» от «t.me недоступен с хостинга».
 *
 * Отказ при этом ЗАПИСЫВАЛСЯ — `console.error` с именем канала стоит в каждом
 * источнике. Но лог уходит в контейнер Timeweb и не читается никем, а тип
 * возврата говорил «список», и только «список».
 *
 * Это §4.0 в чистом виде: место, где нельзя сказать «не смог», заполняется
 * пустотой, а пустота выдаётся за ответ. Третий исход обязан жить в ТИПЕ, а
 * не в логе: тип читают все вызывающие, лог — никто.
 *
 * Находка эволюции (#1494) называла причиной пустой `catch`. Его там нет с
 * тех пор, как §4.0 прошёлся по этим файлам, — судья это отметил отдельно.
 * Но починка тогда дошла до лога и остановилась перед типом.
 */

/** Канал, который не ответил, и почему. */
export interface SourceFailure {
  /** Имя канала/источника — без него «не ответил» неотличимо от «нет данных». */
  source: string;
  error: string;
}

export interface SourceResult<T> {
  items: T[];
  /** Каналы, которые не ответили. Пусто — спросили всех и все ответили. */
  unavailable: SourceFailure[];
  /**
   * Не ответил НИ ОДИН канал: пустой `items` здесь значит «не смогли
   * спросить», а не «нечего сообщить».
   *
   * Отдельный флаг, а не вывод по `unavailable.length`: вызывающий не обязан
   * знать, сколько каналов у источника, и не должен это выяснять, чтобы
   * прочитать ответ.
   */
  refused: boolean;
}

/**
 * Собрать ответ. `asked` — сколько каналов пытались спросить.
 *
 * Ноль опрошенных каналов — тоже отказ: источник без каналов не «пустой», он
 * несобранный, и молча выдавать его за тишину нельзя.
 */
export function sourceResult<T>(
  items: T[],
  unavailable: SourceFailure[],
  asked: number,
): SourceResult<T> {
  return {
    items,
    unavailable,
    refused: asked === 0 || unavailable.length >= asked,
  };
}
