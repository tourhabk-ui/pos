/**
 * lib/mcp/server-instructions.ts — инструкция хосту в ответ на initialize.
 *
 * Поле `instructions` хост может положить в контекст модели (спецификация MCP:
 * «MAY be added to the system prompt»; Claude Code кладёт). До
 * 29.10 там была одна фраза — описание сервера, «данные из базы», прокат и
 * 112, — и внешний агент, не найдя сквозных правил у нас, написал свои. Из
 * них верными оказались не все: «календарь только у одного тура», «медведи —
 * значит регистрация в МЧС обязательна», «прокат не подключён ни один»
 * (ловушки MCP 29.10, часть 4).
 *
 * Сюда — только СКВОЗНЫЕ правила: то, что видно из нескольких ответов
 * разом и чего нет в схеме одного инструмента. Лимиты, дни погоды, возрасты
 * детей, два шага проката — в описаниях инструментов; второй источник того же
 * текста разошёлся бы с первым.
 *
 * Каждая цитата здесь — фраза, которую на деле печатает инструмент; сторож
 * (tests/unit/mcp-server-instructions.test.ts) зовёт производителя каждой и
 * краснеет, когда фраза в ответе поменялась, а здесь нет.
 *
 * Модуль читается страницей /mcp, которая собирается на сборке без базы:
 * импорты — только чистые модули (сторож no-build-time-db).
 */

import { MCP_SERVER_INFO } from '@/lib/mcp/public-tools';
import { TOURS_PAGE_SIZE } from '@/lib/kuzmich/tour-filter';
import { platformAcceptsPayments } from '@/lib/payments/accepting';
import { paymentRule } from '@/lib/mcp/payment-rule';

// Правило оплаты — общее с /llms-*.txt (lib/mcp/payment-rule): один текст,
// а не две копии, которые разойдутся при включении оплаты.
export { paymentRule };

export function buildServerInstructions(opts: { acceptsPayments: boolean }): string {
  return [
    MCP_SERVER_INFO.description,
    'Правила:',
    '1. Факты — только из ответов инструментов; чего в базе нет, ответ так и говорит — передай как есть, не дополняй догадкой.',
    `2. get_tours отдаёт по ${TOURS_PAGE_SIZE} туров на страницу: листай page, пока ответ не скажет «Это последняя» или «Других страниц нет» либо не придёт без туров. Туры компании или гида — get_tour_details с их именем: get_tours имён не ищет.`,
    '3. Строка каталога у тура с календарём — «Мест: …», без календаря — «Расписания в системе нет»: тогда места не обещай, их подтверждает оператор.',
    '4. «свободных мест с … по … нет» в get_tour_availability — только про окно date_from + days; ближайшую свободную дату вне окна ответ назовёт сам или скажет, что её нет либо проверить не смог.',
    '5. «ЗЕЛЁНЫЙ» в скобках у названия места — статус места для выхода, а не «безопасно»: предупреждения и опасности из ответа передай. KVERT и КФ ЕГС — шкалы вулкана, не места. МЧС-регистрацию называй обязательной, только где так сказано в ответе: не записана — не значит «не нужна». Экстренный вызов — 112.',
    '6. Заявка — не бронь. Имя и телефон спроси у человека; consent: true — только после его согласия на обработку и передачу данных.',
    '7. Ключ статуса — для get_request_status; ссылку на страницу статуса дай человеку: там он сам подтверждает согласие. Ключ и ссылку не публикуй.',
    `8. ${paymentRule(opts.acceptsPayments)}`,
    'Аренда машины без водителя (аренда авто, внедорожника, 4x4, прокат, rent a car, car rental) — сначала search_car_rental.',
  ].join('\n');
}

export const SERVER_INSTRUCTIONS = buildServerInstructions({ acceptsPayments: platformAcceptsPayments() });
