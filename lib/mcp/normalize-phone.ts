/**
 * Нормализация телефона в заявках MCP (аудит 08.08, замечание 2: телефон
 * принимался любой строкой ≥5 символов — «привет» прошёл бы как номер).
 *
 * Мягкая валидация, не строго-РФ: платформа российская, но турист бывает
 * иностранным. Правила: только цифры (+ ведущий плюс), 10–15 цифр (E.164),
 * российский 8XXXXXXXXXX приводится к +7XXXXXXXXXX, 7XXXXXXXXXX — к +7…
 * Мусор → null, заявка не создаётся с внятной ошибкой.
 */
/**
 * Номер, которого не бывает (ревью MCP 08.11): внешний агент на живой проверке
 * оставил заявку с +70000000000, и она ушла настоящему менеджеру. Формат E.164
 * такой номер проходит, позвонить по нему нельзя.
 *
 * Правила узкие, чтобы не отвергнуть настоящий номер:
 *   - +7 и следом 0, 1 или 2 — в зоне +7 таких кодов нет (Россия — 3, 4, 8,
 *     9; Казахстан — 6, 7);
 *   - все цифры одинаковые (+1111111111, +5555555555).
 * «Красивые» номера вроде +7 914 777-77-77 продаются операторами и настоящие —
 * повтор цифр внутри номера не приговор.
 *
 * Только для заявок — нормализация номера в CRM этим не судится: там номер
 * уже записан, и отвергнуть его значило бы потерять контакт.
 */
export function implausiblePhone(e164: string): boolean {
  if (/^\+7[012]/.test(e164)) return true;
  return /^\+(\d)\1+$/.test(e164);
}

export function normalizePhone(raw: string): string | null {
  const digits = raw.replace(/[^\d+]/g, '');
  const hasPlus = digits.startsWith('+');
  const bare = digits.replace(/^\+/, '');
  if (!/^\d{10,15}$/.test(bare)) return null;
  if (/^8\d{10}$/.test(bare)) return `+7${bare.slice(1)}`;
  // Десять цифр без плюса («900 123-45-67») — российский номер без кода
  // страны. Прежде он становился «+9001234567», по которому оператору нечем
  // позвонить (проверка MCP 29.09; то же правило жило только в запросе мест).
  if (!hasPlus && bare.length === 10) return `+7${bare}`;
  return `+${bare}`;
}
