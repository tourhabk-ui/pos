/**
 * Пул базы для dev-tools MCP: ленивый и с названной причиной отказа.
 *
 * ── Что было ───────────────────────────────────────────────────────────────
 *
 *   const dbPool = new Pool({ connectionString: process.env.DATABASE_URL });
 *
 * Находка судьи (#1428) назвала это «невнятной ошибкой». Замер показал, что
 * хуже: конструктор `pg` НЕ БРОСАЕТ на `undefined` вовсе. Он молча подставляет
 * умолчания libpq и идёт на локальную базу — проверено:
 *
 *   connect ECONNREFUSED 127.0.0.1:5432
 *
 * То есть вызывающий получает сообщение про то, что ЛОКАЛЬНАЯ база отказала, и
 * ни слова про незаданную переменную. Это §4.0 в чистом виде: «мы не знаем,
 * куда подключаться» выдаётся за «база отказала».
 *
 * И это ещё удачный исход. На машине, где локальный Postgres поднят и в нём
 * есть база с именем пользователя, подключение УДАСТСЯ — к чужой базе. Тогда
 * инструмент ответит не ошибкой, а неверными данными, и молча.
 *
 * ── Почему лениво, а не бросить при загрузке ───────────────────────────────
 *
 * Из восьми инструментов сервера трое базы не трогают вовсе:
 * `next_migration_id` читает каталог миграций, `sql_rules` и `check_protected`
 * — CLAUDE.md. Бросок при импорте убил бы процесс целиком и лишил бы их
 * работы из-за переменной, которая им не нужна.
 *
 * Ошибка, брошенная отсюда во время вызова, доезжает до вызывающего как
 * JSON-RPC error с этим самым текстом — общий `catch` в server.ts её ловит.
 */
import { Pool } from 'pg';

let pool: Pool | null = null;

/**
 * Пул или ВНЯТНЫЙ отказ. Первый вызов создаёт, последующие переиспользуют.
 *
 * Текст отказа называет переменную и файл, где её ждут, — иначе он повторит
 * ту же беду, от которой заводился: скажет, что что-то не так, и не скажет
 * что именно.
 */
export function devToolsDb(): Pool {
  if (pool) return pool;

  const url = process.env.DATABASE_URL?.trim();
  if (!url) {
    throw new Error(
      'DATABASE_URL не задан — подключаться некуда. Инструменты brain_* работают '
      + 'с базой; остальные (next_migration_id, sql_rules, check_protected) от неё '
      + 'не зависят и доступны. Переменная берётся из .env.local в корне репозитория.',
    );
  }

  pool = new Pool({ connectionString: url });
  return pool;
}

/** Только для тестов: забыть созданный пул. */
export function resetDevToolsDb(): void {
  pool = null;
}
