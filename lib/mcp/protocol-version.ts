/**
 * Версия протокола MCP, которую сервер называет на рукопожатии.
 *
 * ── Что было ──────────────────────────────────────────────────────────────
 *
 * `initialize` отвечал константой `2024-11-05` — ревизией эпохи HTTP+SSE.
 * Сервер при этом с 27.07 живёт на Streamable HTTP, который появился только в
 * ревизии `2025-03-26`. То есть мы называли версию, которой не соответствуем,
 * и не называли ту, по которой реально работаем. Клиент, строго следующий
 * спеке, вправе на такой ответ отключиться: он попросил новую, получил
 * старую и не обязан её уметь.
 *
 * ── Правило спеки ─────────────────────────────────────────────────────────
 *
 * Клиент присылает в `initialize` версию, которую хочет. Сервер отвечает ЕЮ,
 * если поддерживает, иначе — самой новой из своих. Решение «жить с этим или
 * отключиться» принимает клиент. Сервер не угадывает и не завышает.
 *
 * ── Почему список кончается на 2025-06-18 ─────────────────────────────────
 *
 * Актуальная ревизия — `2026-07-28`. Её текст в этом репозитории никто не
 * читал, и заявить её поддержку значило бы объявить исход без источника
 * (правило 10.09): клиент поверит объявлению и упрётся в то, чего в сервере
 * нет. Ревизии ниже прочитаны, и от сервера, который отдаёт только
 * `tools/*` одиночными JSON-ответами, они требуют ровно то, что он делает:
 *   · 2025-03-26 — Streamable HTTP: один POST-эндпоинт, JSON-RPC в теле;
 *   · 2025-06-18 — заголовок `MCP-Protocol-Version` от клиента на
 *     последующих запросах; сервер, не ветвящийся по версии, его не читает,
 *     структурный вывод и elicitation необязательны.
 * Появится прочитанная ревизия — добавляется в голову списка вместе с тем,
 * что она потребовала от кода. Список без причины не растёт.
 */

/** От новой к старой. Первая — та, что называется незнакомому клиенту. */
export const SUPPORTED_PROTOCOL_VERSIONS = ['2025-06-18', '2025-03-26', '2024-11-05'] as const;

export const LATEST_PROTOCOL_VERSION = SUPPORTED_PROTOCOL_VERSIONS[0];

/**
 * Версия для ответа на `initialize`.
 *
 * Запрошенная и поддерживаемая — она же. Незнакомая, пустая или не строка —
 * самая новая из наших: спека велит отвечать версией, которую сервер умеет,
 * а не молчать и не выдумывать.
 */
export function negotiateProtocolVersion(requested: unknown): string {
  if (typeof requested === 'string') {
    const wanted = requested.trim();
    if ((SUPPORTED_PROTOCOL_VERSIONS as readonly string[]).includes(wanted)) return wanted;
  }
  return LATEST_PROTOCOL_VERSION;
}
