/** Нижний регистр, ё → е, тире → дефис, «3-го» и «3го» → «3», кавычки и лишние пробелы прочь. */
export function normalizePhrase(text: string): string {
  return text
    .toLowerCase()
    .replace(/ё/g, 'е')
    .replace(/[–—]/g, '-')
    .replace(/[«»"“”„]/g, ' ')
    .replace(/…/g, '.')
    .replace(/(\d)(?:\s*-\s*|)(?:го|ое|ее|е|й|ого|ему|м)(?![\p{L}])/gu, '$1')
    .replace(/\s+/g, ' ')
    .trim();
}

/**
 * Знаки, которые фраза может нести (пятый ревью 22.10): буквы, цифры,
 * пробелы и `. , ; : - – — / ( ) ! ? « » " “ ” „ … ₽`. Любой другой — отказ:
 * «❌», «🚫», «~~», «−» (минус), «≠», «\», «+», «#», «@», «$» несут смысл
 * («кроме», «минус»), которого разбор не знает, и молча выпасть не могут.
 */
const ALLOWED_CHAR = /[\p{L}\p{Nd}\s.,;:\-–—/()!?«»"“”„…₽]/u;

const B = '(?<![\\p{L}\\p{N}])';
const E = '(?![\\p{L}])';
/**
 * Месяц — только формы существительного и сокращения (пятый ревью: «Июльский
 * сплав», «Августовская рыбалка» — названия туров, а не июль и август).
 */
const SOFT_MONTHS = ['январ', 'феврал', 'апрел', 'июн', 'июл', 'сентябр', 'октябр', 'ноябр', 'декабр'];
const MONTH_NOUN = [
  ...SOFT_MONTHS.map((s) => `${s}(?:ь|я|е|ю|ем)`), 'март(?:а|е|у|ом)?', 'август(?:а|е|у|ом)?', 'ма(?:й|я|е|ю|ем)',
].join('|');
const MONTH_WORD = `${MONTH_NOUN}|янв|февр?|мар|апр|авг|сент?|окт|нояб?|дек`;
/**
 * День недели — формы существительного («субботний сплав» — тур, а не
 * суббота), «выходные» — только множественное («выходной» — выходной у
 * оператора), «будни» и «будний день».
 */
const WEEKDAY_WORD = 'понедельник(?:а|у|ом|е|и|ов|ам|ами|ах)?|вторник(?:а|у|ом|е|и|ов|ам|ами|ах)?|сред(?:а|у|ы|е|ой|ам|ами|ах)?' +
  '|четверг(?:а|у|ом|е|и|ов|ам|ами|ах)?|пятниц(?:а|у|ы|е|ей|ам|ами|ах)?|суббот(?:а|у|ы|е|ой|ам|ами|ах)?' +
  '|воскресень(?:е|я|ю|ем|и|ям|ями|ях)|воскресени(?:е|я|ю|ем|и|й)|воскресений' +
  '|выходн(?:ые|ых|ым|ыми)|будн(?:и|ей|ям|ями|ях|ий|ие|их|им|ими)|пн|вт|ср|чт|пт|сб|вс';
const DATE_SIGN = new RegExp(
  `${B}(?:${MONTH_WORD}|${WEEKDAY_WORD}|сегодня|завтра|послезавтра|весь|всю|целиком|ежедневно` +
  '|праздн\\p{L}*|майск\\p{L}*|новогодн\\p{L}*|сезон\\p{L}*)' + E +
  '|(?<![\\d.])\\d{1,2}\\.\\d{1,2}(?![\\d])|\\d{4}-\\d{2}-\\d{2}',
  'u',
);

/** Ответ на число мест к черновику: «8», «8 мест», «по 8 человек». */
const SEATS_ONLY = /^(?:по|на)?\s*(\d{1,4})\s*(?:мест\p{L}*|чел(?:овек\p{L}*)?\.?)?\s*[.!]?$/u;
/** Отмена словом — «отмена», «стоп», «не надо» и только оно: гасит действующее предложение чата. */
const CANCEL_ONLY = /^(?:отмена|отмени(?:те)?|стоп|не надо|не нужно|отбой|нет|не открывай(?:те)?|передумал\p{L}*)[.!]*$/u;

/** Дела помощника кабинета (CRM). Список всегда неполон — главная защита разрешающая. */
const CRM_WORD = new RegExp(
  `${B}(?:(?:задач|касани|напомн|клиент|звон|позвон|перезвон|созвон|счет|брон|заявк|отзыв|сообщени|письм|отчет` +
  '|входящ|карточк|договор|оплат|диалог|контакт|лид|переписк|обращени|запрос|статист|чат)\\p{L}*' +
  `|гост(?:ь|я|ю|ем|и|ей|ям|ями|ях)|доступ(?:а|у|ом|е|ы|ов)?)${E}`,
  'u',
);
/** Предмет назван прямо: «даты», «слоты», «выезды». */
const OBJECT_WORD = new RegExp(`${B}(?:дат(?:а|ы|у|е|ам|ами|ах)|слот\\p{L}*|выезд\\p{L}*)${E}`, 'u');
/** «Открой» — глагол дат в этом чате; «добавь» и «выставь» берут любой предмет. */
const OPEN_ITSELF = new RegExp(`${B}откр(?:ой|ойте|ыть|ывай|ывайте)${E}`, 'u');
const ADD_FORMS = new RegExp(`${B}(?:добав(?:ь|ьте|ить|ляй|ляйте|лять)|выстав(?:ь|ьте|ить|ляй|ляйте|лять))${E}`, 'u');
const OPEN_FORMS_SRC =
  `${B}(?:откр(?:ой|ойте|ыть|ывай|ывайте|ывать)|добав(?:ь|ьте|ить|ляй|ляйте|лять)|выстав(?:ь|ьте|ить|ляй|ляйте|лять))${E}`;
const OPEN_FORMS = new RegExp(OPEN_FORMS_SRC, 'gu');
const OPEN_FORM_WORD = /^(?:откр(?:ой|ойте|ыть|ывай|ывайте|ывать)|добав(?:ь|ьте|ить|ляй|ляйте|лять)|выстав(?:ь|ьте|ить|ляй|ляйте|лять))$/u;
/** Между глаголом и предметом: обращение, вежливость, наречия. */
const OPEN_FILLER = new Set([
  'ка', 'мне', 'нам', 'пожалуйста', 'плиз', 'еще', 'тоже', 'также', 'уже', 'срочно', 'сразу', 'кузьмич',
  'только', 'тогда', 'теперь', 'пока', 'там',
]);
const ADD_PREPOSITIONS = new Set(['на', 'в', 'во', 'по', 'с', 'со', 'от', 'до', 'для', 'к']);
/** Порядковое слово. Окончания перечислены: «вторник» — не «второй». */
const ORDINAL_SRC = 'перв\\p{L}*|втор(?:ой|ая|ую|ое|ые|ых|ого|ым|ыми|ом)|трет(?:ий|ья|ью|ье|ьи|ьих|ьего|ьим|ьей)' +
  '|четв[её]рт\\p{L}*|пят(?:ый|ая|ую|ое|ые|ых|ого|ом|ой)|шест(?:ой|ая|ую|ое|ые|ых)|последн\\p{L}*|предпоследн\\p{L}*' +
  '|ближайш\\p{L}*|следующ\\p{L}*|след';
const ORDINAL = new RegExp(`^(?:${ORDINAL_SRC})$`, 'u');
const NUMBER_WORD_SRC = 'один|одну|одна|одно|одни|два|две|три|четыре|пять|шесть|семь|восемь|девять|десять|пару|пара|полтора|полторы';
const NUMBER_WORD = new RegExp(`^(?:${NUMBER_WORD_SRC})$`, 'u');
/**
 * Слова отношения к дате (пятый ревью 22.10): «к 3 августа» — срок, «после
 * 3 августа», «между 3 и 10» — окрестность, «примерно 3 августа» — не дата.
 * Рядом с датой — отказ до выбора тура: иначе слово ушло бы в название тура
 * («Прогулка после обеда», «Поход к водопадам», «Между двух вулканов»).
 */
const RELATION_SRC = 'после|перед|между|к|ко|около|вокруг|примерно|приблизительно|ориентировочно|раньше|позже|позднее' +
  '|накануне|вместо|кажд(?:ый|ую|ое|ые|ого|ой|ым|ом|ому)';
const RELATION = new RegExp(`^(?:${RELATION_SRC})$`, 'u');
/**
 * Длительность рядом с датой: «5 августа на неделю», «3 августа на ночь» —
 * выезд на неделю или семь выездов, не угадываем. В названии тура вдали от
 * даты («на Мутновский 5 дней») — слово тура.
 */
const DURATION = /^(?:недел[юияе]|дн(?:я|ей)|ноч(?:ь|и|ей)|сут(?:ки|ок)|месяц(?:а|ев)?|час(?:а|ов)?|лето|лета|зиму|зима|осень|весну|весна)$/u;
/** Предмет «открой», похожий на даты (плюс порядковые, числа словами и слова отношения — на них отказ). */
const OPEN_OBJECT = new RegExp(
  `^(?:${MONTH_WORD}|${WEEKDAY_WORD}|сегодня|завтра|послезавтра|вс[еяю]\\p{L}*|весь|целый|целую|целиком|ежедневно` +
  '|с|со|от|по|до|на|в|во|начиная|без|вне|кроме|дат(?:а|ы|у|е|ам|ами|ах)|слот\\p{L}*|выезд\\p{L}*|мест\\p{L}*' +
  '|групп\\p{L}*|продаж\\p{L}*|запис\\p{L}*|набор\\p{L}*|тур|тура|туры|туру|туров|нов(?:ые|ых|ую|ый)|праздн\\p{L}*|майск\\p{L}*' +
  `|новогодн\\p{L}*|начал\\p{L}*|конец|конц\\p{L}*|середин\\p{L}*|половин\\p{L}*|пол|сезон\\p{L}*|рабоч\\p{L}*` +
  `|${ORDINAL_SRC}|${NUMBER_WORD_SRC}|${RELATION_SRC})$`,
  'u',
);
/** Предмет «добавь» и «выставь» после предлогов — только даты. */
const ADD_OBJECT = new RegExp(
  `^(?:${MONTH_WORD}|${WEEKDAY_WORD}|сегодня|завтра|послезавтра|вс[еяю]\\p{L}*|весь|целый|целую|кажд\\p{L}*|ежедневно` +
  `|дат(?:а|ы|у|е|ам|ами|ах)|слот\\p{L}*|выезд\\p{L}*|мест\\p{L}*|нов(?:ые|ых|ую|ый)|${ORDINAL_SRC})$`,
  'u',
);
/**
 * Предмет каждого «открой», «добавь», «выставь» похож на даты — или на тур
 * оператора (`tourWord`): «Выставь Горелый на 5 августа». Туры не прочитаны
 * (`tourWord` = null, выбор двери в роуте) — слово не отвергается: решит
 * поток, прочитав туры.
 */
function openObjectsOk(t: string, tourWord: ((w: string) => boolean) | null): boolean {
  for (const m of t.matchAll(OPEN_FORMS)) {
    const add = !m[0].startsWith('откр');
    const rest = t.slice((m.index ?? 0) + m[0].length);
    const next = [...rest.matchAll(/\p{L}+|\d+/gu)].map((x) => x[0])
      .find((w) => !OPEN_FILLER.has(w) && !(add && ADD_PREPOSITIONS.has(w)));
    if (next === undefined || /^\d/.test(next)) continue;
    if ((add ? ADD_OBJECT : OPEN_OBJECT).test(next)) continue;
    if (tourWord === null || tourWord(next)) continue;
    return false;
  }
  return true;
}
/** Закрытие — просьбой, а не рассказом. */
const CLOSE_REQUEST = new RegExp(
  `${B}(?:закр(?:ой|ойте|ыть|ывай|ывайте)|убер(?:и|ите)|убрать|удал(?:и|ите|ить)|сним(?:и|ите)|снять` +
  '|отмен(?:и|ите|ить)|заблокир(?:уй|уйте|овать)|блокир(?:уй|уйте)|скр(?:ой|ойте|ыть)|останов(?:и|ите|ить)' +
  `|приостанов(?:и|ите|ить)|стоп|прекрат(?:и|ите|ить)|уменьш(?:и|ите|ить)|сократ(?:и|ите|ить)|убав(?:ь|ьте|ить))${E}`,
  'u',
);
/** Похоже на дату, но разбор её не знает: «3/08», «3 и 5 числа». */
const NEAR_DATE = new RegExp(`(?<![\\d.])\\d{1,2}\\s*/\\s*\\d{1,2}(?!\\d)|${B}числ\\p{L}*`, 'u');

/** Исключение дня недели в начале строки: «без выходных», «кроме суббот». */
const WD_EXCLUSION_AT = new RegExp(
  `^(?:без|вне|кроме|исключая|за\\s+исключением)\\s+(?:(?:по|в|во)\\s+)?(?:${WEEKDAY_WORD})${E}`,
  'u',
);
const EXCEPTION_ANY = new RegExp(
  `${B}(?:кроме|исключая|за\\s+исключением|не\\s+считая|не|нет|минус)${E}|${B}(?:пропус|занят)\\p{L}*|${B}без\\s+\\d+`,
  'gu',
);

type Intent = 'not_dates' | 'open' | 'close' | 'mixed' | 'negated' | 'exclusion' | 'question' | 'unparsed';

function namedAsDates(t: string): boolean {
  return OBJECT_WORD.test(t) || seatsNamed(t) || NEAR_DATE.test(t);
}

/** Исключения во фразе — только дни недели («кроме суббот»)? */
function onlyWeekdayExclusions(t: string): boolean {
  const all = [...t.matchAll(EXCEPTION_ANY)];
  return all.length > 0 && all.every((m) => WD_EXCLUSION_AT.test(t.slice(m.index ?? 0)));
}

/**
 * Намерение фразы (шапка, «Чьё это сообщение»). `masked` — та же фраза, где
 * слова названий туров партнёра заменены на «тур»: по ней судят только
 * закрытие, отрицание и исключения (седьмой ревью, m4: «на Закрытую бухту»
 * — не «закрой», «на Занятия на вулкане» — не «занято»).
 */
function intentOf(t: string, tourWord: ((w: string) => boolean) | null, masked: string = t): { intent: Intent; word?: string } {
  if (CRM_WORD.test(t) || !openObjectsOk(t, tourWord)) return { intent: 'not_dates' };
  const aboutDates = OPEN_ITSELF.test(t) || OBJECT_WORD.test(t) || seatsWordNamed(t);
  const openVerb = hasOpenVerb(t);
  const r = datesPhraseRefusal(masked);
  if (!DATE_SIGN.test(t)) {
    return aboutDates && openVerb && r === null && namedAsDates(t) ? { intent: 'unparsed' } : { intent: 'not_dates' };
  }
  if (r === null) return aboutDates ? { intent: 'open' } : { intent: 'not_dates' };
  switch (r.kind) {
    case 'close':
      if (openVerb) return aboutDates ? { intent: 'mixed' } : { intent: 'not_dates' };
      if (isQuestionPhrase(t) || !CLOSE_REQUEST.test(t)) return { intent: 'not_dates' };
      return { intent: 'close' };
    case 'negation':
      return /откр/u.test(r.word) || aboutDates ? { intent: 'negated', word: r.word } : { intent: 'not_dates' };
    case 'exception':
      if (!(openVerb && aboutDates)) return { intent: 'not_dates' };
      return onlyWeekdayExclusions(masked) && datesPhraseRefusal(masked.replace(EXCEPTION_ANY, ' ')) === null
        ? { intent: 'open' }
        : { intent: 'exclusion', word: r.word };
    case 'question':
      return openVerb && aboutDates ? { intent: 'question' } : { intent: 'not_dates' };
    case 'no_open_verb':
      return { intent: 'not_dates' };
  }
}

/**
 * Касается ли сообщение дат — без туров и без базы: выбор двери в роуте.
 * Слово, которое может оказаться туром, не отвергается — решит поток,
 * прочитав туры (`parseDatesPhrase` с турами). `seats` — голое число мест;
 * `cancel` — «отмена», «стоп», «не надо».
 */
export function chatDatesIntent(text: string, nowMs: number = Date.now(), strict = false): 'dates' | 'seats' | 'cancel' | null {
  const t = normalizePhrase(text);
  if (SEATS_ONLY.test(t)) return 'seats';
  if (CANCEL_ONLY.test(t)) return 'cancel';
  // `strict` — предмет только из разрешающего списка, без слов, которые могут
  // оказаться туром: так поток решает, отвечать ли отказом гейта, не читая туров.
  if (intentOf(t, strict ? () => false : null).intent === 'not_dates') return null;
  return parseDatesPhrase(text, nowMs, null).kind === 'not_dates' ? null : 'dates';
}

/** Есть ли во фразе слово названия одного из туров (признак поправки «не Горелый, а Авачинский»). */
export function mentionsTour(text: string, tours: ChatTour[]): boolean {
  const titles = tours.map((t) => titleWordsOf(t.title));
  return [...normalizePhrase(text).matchAll(/\p{L}+/gu)].some((m) => m[0].length >= 4 && titles.some((tw) => wordInTitle(m[0], tw)));
}

/**
 * Признак поправки к предложению (пятый ревью 22.10): цифры, слово даты,
 * «мест», «не»/«нет». Такое сообщение при действующем предложении снимает
 * его, даже если ушло помощнику: «нет, 4 места», «не 8, а 4».
 */
export function correctionSign(text: string): boolean {
  const t = normalizePhrase(text);
  return /\d/.test(t) || DATE_SIGN.test(t) || /(?<![\p{L}])мест\p{L}*/u.test(t) || /(?<![\p{L}])(?:не|нет)(?![\p{L}])/u.test(t)
    || CORRECTION_WORD.test(t);
}
/** «ошибся», «погоди», «подожди», «стой», «неправильно», «неверно» — тоже поправка (шестой ревью). */
const CORRECTION_WORD = /(?<![\p{L}])(?:ошиб\p{L}*|погод\p{L}*|подожд\p{L}*|стой(?:те)?|неправильн\p{L}*|неверн\p{L}*|отставить)(?![\p{L}])/u;

/** Число мест из ответа на вопрос о местах; null — не ответ числом. */
export function seatsReply(text: string): number | null {
  const m = normalizePhrase(text).match(SEATS_ONLY);
  return m ? Number(m[1]) : null;
}

// ── Места ──────────────────────────────────────────────────────────────────

const MONTH_AHEAD = `(?:-|\\.\\d|(?:\\s*(?:,|;|и|или)\\s*\\d{1,2})*\\s*(?:${MONTH_WORD})(?![\\p{L}]))`;
const SEATS_NUM = '(\\d{1,3}(?: \\d{3})+|\\d+)';
const SEATS_PREP = '(?:(?<![\\p{L}])(?:по|на|до|для)\\s+)?';
const SEATS_UNIT = '(?:мест\\p{L}*|чел(?:овек\\p{L}*)?\\.?(?![\\p{L}])|туристов|участник\\p{L}*)';
/** «по 8 мест на каждую дату» — места (пятый ревью). */
const SEATS_EACH = '(?:\\s+на\\s+(?:кажд(?:ую|ый|ое)\\s+)?(?:дату|выезд|день))?';
const SEATS_FWD = new RegExp(`${SEATS_PREP}(?<![\\d.,:-])${SEATS_NUM}(?![\\d.,:])\\s*${SEATS_UNIT}${SEATS_EACH}`, 'gu');
const SEATS_BACK = new RegExp(`(?<![\\p{L}])мест[аоу]?\\s*[:-]?\\s*${SEATS_NUM}(?![\\d.,:])(?!${MONTH_AHEAD})`, 'gu');
const SEATS_RANGE = new RegExp(
  `${SEATS_PREP}(?<![\\d.,:-])${SEATS_NUM}\\s*-\\s*${SEATS_NUM}(?![\\d.,:])\\s*${SEATS_UNIT}${SEATS_EACH}`,
  'gu',
);
const SEATS_MEST = new RegExp(`(?<![\\d.,:-])${SEATS_NUM}(?![\\d.,:])\\s*мест\\p{L}*`, 'u');

function seatsNamed(t: string): boolean {
  return new RegExp(SEATS_FWD.source, 'u').test(t) || new RegExp(SEATS_BACK.source, 'u').test(t)
    || new RegExp(SEATS_RANGE.source, 'u').test(t);
}
function seatsWordNamed(t: string): boolean {
  return SEATS_MEST.test(t) || new RegExp(SEATS_BACK.source, 'u').test(t);
}

/** Места вырезаются; `ranges` — где они стояли (знаки в нормализованной фразе). */
function cutSeats(t: string): { rest: string; values: number[]; ranges: Array<[number, number]> } {
  const values: number[] = [];
  const ranges: Array<[number, number]> = [];
  const blank = (all: string, at: number, ...ns: string[]): string => {
    values.push(...ns.map((n) => Number(n.replace(/ /g, ''))));
    ranges.push([at, at + all.length]);
    return ' '.repeat(all.length);
  };
  let rest = t.replace(SEATS_RANGE, (all: string, a: string, b: string, at: number) => blank(all, at, a, b));
  rest = rest.replace(SEATS_FWD, (all: string, n: string, at: number) => blank(all, at, n));
  rest = rest.replace(SEATS_BACK, (all: string, n: string, at: number) => blank(all, at, n));
  return { rest, values, ranges: ranges.sort((a, b) => a[0] - b[0]) };
}

