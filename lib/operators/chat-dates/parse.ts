type Tok =
  | { t: 'iso'; d: number; m: number; y: number; raw: string; pos: number }
  | { t: 'ndate'; d: number; m: number; y: number | null; raw: string; pos: number }
  | { t: 'num'; v: number; digits: number; raw: string; pos: number }
  | { t: 'word'; w: string; pos: number }
  /** `glue` — дефис внутри слова («открой-ка», «Петропавловск-Камчатский»): часть слова. */
  | { t: 'punct'; p: string; pos: number; glue?: boolean };

const TOKEN = /(?<![\d.])(\d{4})-(\d{1,2})-(\d{1,2})(?![\d])|(?<![\d.])(\d{1,2})\.(\d{1,2})(?:\.(\d{4}|\d{2}))?(?!\d|\.\d)|(?<![\d.,])\d{1,3}(?: \d{3})+(?![\d.,])|\d+|\p{L}+|[,;\-/]|₽/gu;

function tokenize(t: string): Tok[] {
  const out: Tok[] = [];
  for (const m of t.matchAll(TOKEN)) {
    const pos = m.index ?? 0;
    if (m[1]) out.push({ t: 'iso', y: Number(m[1]), m: Number(m[2]), d: Number(m[3]), raw: m[0], pos });
    else if (m[4]) {
      const y = m[6] ? (m[6].length === 2 ? 2000 + Number(m[6]) : Number(m[6])) : null;
      out.push({ t: 'ndate', d: Number(m[4]), m: Number(m[5]), y, raw: m[0], pos });
    } else if (/^\d/.test(m[0])) {
      const digits = m[0].replace(/ /g, '');
      out.push({ t: 'num', v: Number(digits), digits: digits.length, raw: m[0], pos });
    } else if (/^\p{L}/u.test(m[0])) out.push({ t: 'word', w: m[0], pos });
    else {
      const glue = m[0] === '-' && /\p{L}/u.test(t[pos - 1] ?? '') && /\p{L}/u.test(t[pos + 1] ?? '');
      out.push(glue ? { t: 'punct', p: m[0], pos, glue: true } : { t: 'punct', p: m[0], pos });
    }
  }
  return out;
}

