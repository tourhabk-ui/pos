/**
 * «Открой даты словами» (решение владельца 22.10, вариант а; этап C
 * спецификации): разбор фразы оператора в чате кабинета MAX. Чистая функция,
 * без базы и без модели — правила, а не догадка.
 *
 * ── Что разбирается ───────────────────────────────────────────────────────
 *
 *   «открой субботы июля, 8 мест»
 *   «открой 3, 5 и 7 августа на Горелый, 6 мест», «Открой Горелый на субботы июля»
 *   «открой с 1 по 10 июля», «1-10 июля», «с 28 декабря по 3 января»
 *   «03.08», «3.8.2027», «03.08.27», «2027-08-03»
 *   «по субботам в июле и августе», «сб и вс с 1 по 15 июля», «будни ноября»
 *   «с понедельника по пятницу в июле», «пн-пт июля», «пт-вс в августе»
 *   «субботы с июля по сентябрь», «весь июль», «июль целиком», «сегодня»
 *
 * Итог — точный список дат с годом, число мест и тур; записи здесь нет.
 * Запись — только по кнопке «Открыть» (lib/operators/chat-dates/flow).
 *
 * ── Принимает язык (шестой ревью 22.10) ───────────────────────────────────
 *
 * Предложение получает только фраза, целиком легшая в закрытую позиционную
 * грамматику — lib/operators/chat-dates/grammar.ts, язык читается в её
 * шапке. Здесь — смысл разобранного: год (каждой следующей группы — от
 * предыдущей), прошедшие дни, тур по цепочке слов названия, дата дважды —
 * отказ. Всё, что ниже в этой шапке про связки, примыкание и разделители,
 * — устройство ДИАГНОСТА (`diagnosePhrase`): у фразы вне языка он называет
 * причину отказа или задаёт вопрос; если бы он её «понял», ответ — «не по
 * образцу» (`off_pattern`) с образцом, а не угаданные даты.
 *
 * ── Каждое слово и каждый знак на своём месте (ревью 22.10, круги 4 и 5) ──
 *
 * Три круга ревью подряд находили фразы, которые разбор понимал тихо неверно,
 * и корень у всех был один: правила «неизвестное — отказ» не было. Тот же
 * урок оплачен в #2527 (мешок слов заменили грамматикой). Теперь разбор
 * исчерпывающий:
 *   - знак — из закрытого списка (`ALLOWED_CHAR`): буквы, цифры, пробел,
 *     `. , ; : - – — / ( ) ! ? « » " ₽`. Любой другой («❌», «🚫», «~~», «−»,
 *     «≠», «\», «+», «#») — отказ «не понял знак»: «весь июль 🚫 выходные»
 *     открывала выходные. Дефис, не съеденный грамматикой («весь июль -сб»),
 *     — тот же отказ; дефис внутри слова («открой-ка») и перед числом мест
 *     («17.08 — 8 мест») — на месте;
 *   - слово съедено одним из: грамматикой дат (числа, месяцы — только формы
 *     существительного, «с … по», «и», «весь», «целиком»; дни недели —
 *     группой в узнанной конструкции, `wdGroupAt`), числом мест, ценой,
 *     закрытым списком связок `CONNECTORS` (снимок — в стороже), цепочкой
 *     слов названия ОДНОГО тура (шапка, «Тур»). Остаток — отказ
 *     `unknown_words` с непонятыми словами и примером фразы целиком;
 *   - группы дат связаны явно: между ними «,», «;», «и» или конец
 *     предложения. «продажи 1 августа на 5 сентября», «3 августа на 5
 *     августа» — отказ, а не две даты; вторая дата под своим словом («тур 5
 *     сентября», «выезд 5 августа»), места или тур между датами — тоже отказ.
 *
 * ── Отказ дешевле ошибки ──────────────────────────────────────────────────
 *
 * Открытие, о котором не просили, продаёт места, которых нет. Поэтому всё
 * сомнительное — отказ или вопрос, а не догадка. Самые частые — с подсказкой:
 *   - отрицание («не открывай»), исключения («кроме 17-го»), два действия
 *     («открой 3, а 5 закрой») — правило общее с помощником кабинета
 *     (lib/tours/dates-phrase);
 *   - исключение дня недели («без выходных», «кроме суббот», «суббота
 *     выходной») — подсказка называет оставшиеся дни;
 *   - «или», «либо»; порядковые («первую», «последнюю»); числа словами;
 *     год словами («следующего года», «27 года»); «и т.д.»; добавка к местам
 *     («ещё 2 места», «доп. места 2»); «уже 8 мест»; «всего 8 мест» на две
 *     даты и больше (места — на каждый выезд);
 *   - слова отношения к дате (`RELATION`: после, перед, между, к, около,
 *     вокруг, примерно, раньше, позже, накануне, вместо, каждый) и
 *     длительность («на неделю», «на ночь») рядом с датой — отказ до выбора
 *     тура: «к 3 августа» — срок, а не выезд. Кроме слова, с которого после
 *     «на», «по», «тур» начинается название тура («на Между двух вулканов»);
 *   - «каждый», «все» — только согласованно с днём недели («каждую
 *     субботу», «все субботы»): «каждый субботы», «каждый по субботам»,
 *     «каждый дни» не съедаются; «каждый вторник» у отдельной даты без
 *     области — отказ: какие вторники, не сказано;
 *   - отрезок не тянется через конец предложения («3 августа. - 10
 *     августа»); отрезок короче недели с днями недели — его концы обязаны
 *     быть этими днями («выходные 2-4 июля»: пятница выпала бы молча);
 *   - число, которое грамматика не съела («с 10:00», телефон) — «не понял»;
 *   - месяц без дней, дни недели без месяца — вопрос; «майские» — числами;
 *   - «по 12 тысяч» после даты — цена; голое «3 августа по 8» — отказ;
 *   - дата внутри раскрытия той же фразы — исключение, отказ;
 *   - дни недели ложатся на область, только если она — один непрерывный
 *     перечень месяцев или отрезок рядом с группой и у другой области нет
 *     «весь», «целиком», «а», «тоже»: «весь июль, а в августе субботы» —
 *     отказ, а не субботы везде; день недели у отдельной даты («субботу 17
 *     июля») рядом с отрезком — после сверки дня отказ, а не фильтр отрезка;
 *   - «сегодня» рядом с другими датами, «в 9.05», половина диапазона, конец
 *     раньше начала, «на неделю», периодичность — отказ или вопрос.
 *
 * ── Тур ───────────────────────────────────────────────────────────────────
 *
 * Слова тура съедаются только НЕПРЕРЫВНОЙ цепочкой (`tourChains`), и цепочка
 * засчитывается, если стоит после «на», «по», «тур», «для», сразу после
 * глагола («Открой Горелый на субботы июля»), называет тур целиком или
 * состоит из слов названия буквально («5 августа Горелый»). Разрозненное
 * совпадение по основе («вечером» при туре «Вечерний Петропавловск») — не
 * тур, а непонятое слово. Каждое слово цепочки обязано быть в названии;
 * короткие («за» в «Горелый за 1 день») — буквально, число названия — только
 * сразу после слова этого названия («Мутновский 5 дней»), иначе оно
 * осталось бы датой. Фамилия, совпавшая с туром по основе («Горелову»,
 * «Быстровой»), — не тур. Слово, ушедшее в дату, которое стоит в названии
 * тура рядом («на Выходные на Авачинском»), — отказ «тур — кнопкой». Восьмой
 * ревью: в языке слово дня недели, месяца, «сегодня» в любом месте названия
 * («Горелый по субботам») — тур только после «тур»; слово закрытия в
 * названии («Закрытая бухта») не читается как «закрой», если название стоит
 * целиком или двумя словами подряд; слово исключения («Минус тридцать»,
 * «Занятия на вулкане») — только в названии целиком после «тур».
 * Вопрос «какой тур?» — только при ничьей; слова разных туров раздельно —
 * отказ «по одному туру за раз».
 *
 * ── Чьё это сообщение ─────────────────────────────────────────────────────
 *
 * Тот же чат — помощник кабинета (CRM). Фраза про даты — только та, где даты
 * и есть предмет:
 *   - слова дел CRM (задача, касание, клиент, счёт, бронь, заявка, контакт,
 *     лид, чат…) — помощнику, даже с датой и глаголом;
 *   - предмет «открой» — первое слово после глагола — судится разрешающим
 *     списком `OPEN_OBJECT`, предмет «добавь»/«выставь» — первое значимое
 *     слово после предлогов — списком `ADD_OBJECT`. Слово вне списка,
 *     совпавшее с туром оператора, — тоже предмет («Выставь Горелый на 5
 *     августа»); решает это поток, прочитав туры: до чтения туров (выбор
 *     двери в роуте) такое слово не отвергается;
 *   - граница по непонятому слову: несъеденное слово не там, где пишут тур,
 *     при глаголе «добавь»/«выставь», рядом с «для» или с большой буквы не в
 *     начале предложения («Иванову», «Горелову») — сообщение помощнику, а не
 *     отказ «не понял». Без признака — отказ: у «открой» в этом чате предмет
 *     — даты, и непонятое там — условие, которое молча выбросить нельзя;
 *   - «закрой» — только просьбой, а не рассказом;
 *   - ничего похожего на дату — помощнику; предмет назван («даты», «8
 *     мест»), а дат не разобрать, — «не понял».
 *
 * ── Год ───────────────────────────────────────────────────────────────────
 *
 * Год выбирается по МЕСЯЦУ: месяц позже текущего и текущий — этот год,
 * раньше — следующий. Прошедший день, названный отдельно, называется
 * прошедшим; прошедшие дни раскрытия не попадают в список. Диапазон через
 * Новый год — конец в году после начала; диапазон месяцев — подряд от года
 * первого месяца. Седьмой ревью: каждая следующая группа идёт по порядку от
 * предыдущей, и если так выходит другой год, чем сам по себе («5 ноября и
 * 22 октября»: 2027 по порядку, 2026 сам), — отказ «уточните год», а не
 * год по порядку молча. «31 декабря и 1 января» — оба правила дают одно.
 *
 * Сторожа: tests/unit/chat-open-dates-parse.test.ts (поведение),
 * tests/unit/chat-open-dates-grammar.test.ts (язык: снимок списков, каждая
 * форма, фразы ревьюеров кругов 4–8, вставка слова и знака в любое место,
 * сверка с 114bd9e4f и таблица цены).
 */

