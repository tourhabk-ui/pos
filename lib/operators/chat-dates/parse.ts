const CLOSE_TITLE_WORD = /^(?:закр|убер|убир|убра|удал|сним|снят|отмен|заблок|блок|скро|скры|отключ|выключ|останов|останавлив|приостан|стоп|прекрат|уменьш|сократ|убав)/u;
