/**
 * Фраза для проверок закрытия, отрицания и исключений: слова названий туров
 * партнёра, стоящих во фразе, — «тур» (восьмой ревью, S2).
 *   - `strict` — проверяет намерение. Слово закрытия скрыто, если во фразе
 *     стоит название целиком или два его слова подряд («на Закрытую
 *     бухту»). Слово исключения и отрицания — только в названии целиком
 *     сразу после слова «тур» («тур Занятия на вулкане»): одно «минус» при
 *     туре «Минус тридцать» — исключение, и 17 августа не открывается.
 *     Глаголы открытия не скрываются никогда («нужно открыть» при туре
 *     «Открытое море»).
 *   - `lenient` — ещё и исключения в названии целиком без «тур»: если только
 *     так фраза становится просьбой открыть, отказ называет тур (`hit`).
 */
function maskTourWords(norm: string, tours: ChatTour[] | null): { strict: string; lenient: string; hit: { word: string; title: string } | null } {
  if (!tours || tours.length === 0) return { strict: norm, lenient: norm, hit: null };
  const toks = [...norm.matchAll(/\p{L}+/gu)].map((m) => ({ w: m[0], at: m.index ?? 0 }));
  const near = (i: number): boolean => /^[ -]+$/u.test(norm.slice(toks[i]!.at + toks[i]!.w.length, toks[i + 1]!.at));
  const strict = new Set<number>();
  const lenient = new Set<number>();
  let hit: { word: string; title: string } | null = null;
  for (const t of tours) {
    const tw = titleWordsOf(t.title);
    for (let s = 0; s < toks.length; s++) {
      const fits = (k: number, j: number): boolean => s + k < toks.length && formMatch(toks[s + k]!.w, tw[j]!) && (k === 0 || near(s + k - 1));
      // Два слова названия подряд — закрытие скрыто.
      for (let j = 0; j + 1 < tw.length; j++) {
        if (fits(0, j) && fits(1, j + 1)) for (const k of [s, s + 1]) if (CLOSE_TITLE_WORD.test(toks[k]!.w)) strict.add(k);
      }
      if (tw.length === 0 || !tw.every((_, j) => fits(j, j))) continue;
      const afterTour = s > 0 && toks[s - 1]!.w === 'тур' && near(s - 1);
      for (let k = s; k < s + tw.length; k++) {
        const w = toks[k]!.w;
        if (CLOSE_TITLE_WORD.test(w) || (afterTour && EXCEPT_TITLE_WORD.test(w))) strict.add(k);
        else if (EXCEPT_TITLE_WORD.test(w)) { lenient.add(k); hit ??= { word: w, title: t.title }; }
      }
    }
  }
  const build = (set: Set<number>): string => {
    let out = '';
    let at = 0;
    toks.forEach((x, i) => { if (set.has(i)) { out += `${norm.slice(at, x.at)}тур`; at = x.at + x.w.length; } });
    return out + norm.slice(at);
  };
  return { strict: build(strict), lenient: build(new Set([...strict, ...lenient])), hit };
}

/** Даты фразы словами оператора — по первому разбору языка; null — фраза вне языка. */
function phraseDates(src: string, nowMs: number, tours: ChatTour[] | null): string | null {
  const titled: Titled = (tours ?? []).map((t) => ({ t, tw: titleWordsOf(t.title) }));
  const chainOk = tours === null ? chainOkUnread : (ws: string[]) => chainHits(ws, titled).length > 0 || chainHalves(ws, titled) !== null;
  const lp = languageParses(src, chainOk)[0];
  return lp ? datesHint(src, lp, nowMs, tours) : null;
}
/**
 * Даты фразы для образца отказа — только если «открой <даты>» разбор примет
 * сам («с 3 до 4 июля» — отказ «до», такой образец не годится).
 */
function datesHint(src: string, lp: LParse, nowMs: number, tours: ChatTour[] | null): string | null {
  const dates = displaySlice(src, lp.dates.at, lp.dates.end);
  return dates !== null && parsePhrase(`открой ${dates}`, nowMs, tours, false).kind === 'proposal' ? dates : null;
}
/** Кусок фразы с регистром оператора; null — если строчные буквы изменили бы длину. */
function displaySlice(src: string, at: number, end: number): string | null {
  const display = languageDisplay(src);
  return display.toLowerCase().replace(/ё/g, 'е') === languageText(src) ? display.slice(at, end) : null;
}

// ── Язык: смысл разбора ───────────────────────────────────────────────────

/**
 * Окончания, которыми слово фразы может отличаться от слова названия:
 * «Горелого» — «Горелый», «Быструю» — «Быстрая», «рыбалку» — «рыбалка».
 * Суффиксов здесь нет: «вечером» — не «Вечерняя», «Авачинскому» — не
 * «Авача», «Горелову» — не «Горелый» (фамилия).
 */
const ENDINGS = new Set([
  '', 'а', 'я', 'о', 'е', 'и', 'ы', 'у', 'ю', 'ь', 'й', 'ой', 'ей', 'ый', 'ий', 'ая', 'яя', 'ое', 'ее', 'ые', 'ие', 'ую', 'юю',
  'ого', 'его', 'ому', 'ему', 'ым', 'им', 'ом', 'ем', 'ых', 'их', 'ыми', 'ими', 'ам', 'ям', 'ами', 'ями', 'ах', 'ях', 'ью',
  'ья', 'ье', 'ьи', 'ов', 'ев', 'ии', 'ия', 'ию',
]);
function formMatch(w: string, tw: string): boolean {
  if (w === tw) return true;
  if (!/^\p{L}{4,}$/u.test(w) || !/^\p{L}{4,}$/u.test(tw)) return false;
  let p = 0;
  while (p < w.length && p < tw.length && w[p] === tw[p]) p++;
  return p >= 3 && ENDINGS.has(w.slice(p)) && ENDINGS.has(tw.slice(p)) && !surnameLike(w, tw);
}
/** Цепочка — название целиком (`whole`), его непрерывный кусок (`part`) или нет. */
function pieceOf(chain: string[], tw: string[]): 'whole' | 'part' | null {
  for (let j = 0; j + chain.length <= tw.length; j++) {
    if (chain.every((c, i) => formMatch(c, tw[j + i]!))) return j === 0 && chain.length === tw.length ? 'whole' : 'part';
  }
  return null;
}
/**
 * Слова, с которых кусок названия не начинается: даты, дни недели,
 * длительность, время суток, отношение к дате, порядковые («на неделю» при
 * «Неделе на Камчатке», «после обеда», «на выходные»). Тур, название
 * которого с такого слова начинается, называется целиком.
 */
const RISKY = new RegExp(
  `^(?:${MONTH_WORD}|${WEEKDAY_WORD}|сегодня|завтра|послезавтра|${RELATION_SRC}|${ORDINAL_SRC}|${NUMBER_WORD_SRC}` +
  '|недел\\p{L}*|день|дн(?:я|ей|и)|ноч\\p{L}*|сут\\p{L}*|месяц\\p{L}*|час\\p{L}*|лет[оа]|зим[аеуы]|осен\\p{L}*|весн\\p{L}*' +
  '|утр\\p{L}*|вечер|вечера|вечером|обед\\p{L}*|вс[еяю]|весь|целиком|только|через|без|кроме|ежедневн\\p{L}*)$',
  'u',
);
const naming = (w: string): boolean => /^\p{L}{4,}$/u.test(w) && !RISKY.test(w);

type Titled = Array<{ t: ChatTour; tw: string[] }>;
/**
 * Туры, которые называет цепочка: название целиком — любое; кусок —
 * начинается называющим словом и кончается словом, а не числом и не
 * предлогом («Горелый на» при «Горелый на закате» съел бы «на 8 мест»,
 * «Мутновский 5» — дату).
 */
function chainHits(chainIn: string[], titled: Titled): ChatTour[] {
  // Дефис в цепочке — только там, где он есть в названии («Петропавловск-Камчатский»).
  const dashes = chainIn.flatMap((w, i) => (w === '-' ? [`${chainIn[i - 1]}-${chainIn[i + 1]}`] : []));
  const chain = chainIn.filter((w) => w !== '-');
  if (chain.length === 0) return [];
  const edgesOk = naming(chain[0]!) && /^\p{L}{3,}$/u.test(chain[chain.length - 1]!);
  return titled.filter((e) => {
    if (dashes.some((d) => !normalizePhrase(e.t.title).includes(d))) return false;
    const p = pieceOf(chain, e.tw);
    return p === 'whole' || (p === 'part' && edgesOk);
  }).map((e) => e.t);
}
/** «Горелый и Мутновский»: половины цепочки по «и», если обе называют туры. */
function chainHalves(chainIn: string[], titled: Titled): [ChatTour[], ChatTour[], string] | null {
  const chain = chainIn.filter((w) => w !== '-');
  const k = chain.indexOf('и');
  if (k <= 0 || k >= chain.length - 1) return null;
  const a = chainHits(chain.slice(0, k), titled);
  const b = chainHits(chain.slice(k + 1), titled);
  return a.length > 0 && b.length > 0 ? [a, b, chain[0]!] : null;
}
/** Слова языка: туром, которого не прочитали, они быть не могут. */
const RESERVED = new Set<string>([
  ...Object.values(LANGUAGE).flatMap((v) => (Array.isArray(v) ? (v as string[]).flatMap((x) => x.split(' ')) : Object.keys(v))),
  'на', 'по', 'до', 'с', 'со', 'в', 'во', 'и', 'за', 'от', 'для', 'весь', 'все', 'всем', 'каждый', 'каждую', 'каждое', 'каждые',
  'целиком', 'полностью', 'день', 'дни', 'будний', 'будние', 'выходные', 'будни', 'включительно', 'года', 'году', 'г', 'к',
]);
/** Туры не прочитаны: цепочка — слова вне языка с называющими по краям (решит поток, прочитав туры). */
function chainOkUnread(chain: string[]): boolean {
  return chain.every((x) => /^\p{L}+$/u.test(x) && !RESERVED.has(x)) && naming(chain[0]!) && naming(chain[chain.length - 1]!);
}

function pickOf(cands: ChatTour[]): TourPick {
  const act = cands.filter((t) => t.active);
  const hid = cands.filter((t) => !t.active).map((t) => t.title);
  if (act.length === 0) return { kind: 'hidden', titles: hid };
  if (act.length === 1 && hid.length === 0) return { kind: 'one', id: act[0]!.id };
  const ids = act.slice(0, MAX_TOUR_BUTTONS).map((t) => t.id);
  return hid.length > 0 ? { kind: 'choose', ids, hidden: hid } : { kind: 'choose', ids };
}

/**
 * Где во фразе править подсказку: место для спорного года и что спорно —
 * дата, начало отрезка или месяц; место «до» и дня конца отрезка.
 */
interface YearSide { yi: YearIns | null; unit: 'day' | 'span' | 'month'; until: UntilAt | null }

/** Фраза языка — предложение или отказ по смыслу; null — фраза вне языка. */
function byLanguage(src: string, nowMs: number, tours: ChatTour[] | null, hints: boolean): DatesParse | null {
  const titled: Titled = (tours ?? []).map((t) => ({ t, tw: titleWordsOf(t.title) }));
  const chainOk = tours === null
    ? chainOkUnread
    : (ws: string[]) => chainHits(ws, titled).length > 0 || chainHalves(ws, titled) !== null;
  const parses = languageParses(src, chainOk);
  if (parses.length === 0) return null;
  const results = parses.map((lp) => {
    const side: YearSide = { yi: null, unit: 'day', until: null };
    return { lp, side, r: resolveLanguage(lp, nowMs, tours, titled, side) };
  });
  // Слово даты в названии тура без «тур» — отказ, даже если у фразы есть и
  // прочтение датами («на выходные с 1 по 31 июля» при туре «Выходные»).
  for (const { lp, r } of results) {
    if (r.kind === 'refused' && r.reason === 'date_word_in_title') {
      return hints ? { ...r, dates: datesHint(src, lp, nowMs, tours) } : r;
    }
  }
  const distinct = new Set(results.map((x) => JSON.stringify(x.r)));
  if (distinct.size === 1) {
    const { r, side } = results[0]!;
    if (hints && r.kind === 'refused' && r.reason === 'year_order') return { ...r, variants: yearVariants(r, side, src, nowMs, tours) };
    if (hints && r.kind === 'refused' && r.reason === 'range_until') return { ...r, variants: untilVariants(r, side, src, nowMs, tours) };
    return r;
  }
  // Два разных смысла одной фразы — не угадываем.
  return { kind: 'refused', reason: 'off_pattern', seats: parses[0]!.seats };
}

/**
 * Варианты «уточните год» — вся фраза оператора с годом у спорной даты,
 * отрезка или месяца (восьмой ревью, S3: прежняя подсказка «открой 20
 * октября 2027» теряла остальную фразу). Вариант — только год в окне продаж:
 * разбор его фразы — предложение с теми же местами и с днями спорной части
 * в этом году. Остальное по построению то же: в фразу вписан только год.
 */
function yearVariants(
  r: Extract<DatesRefusal, { reason: 'year_order' }>, side: YearSide, src: string, nowMs: number, tours: ChatTour[] | null,
): Array<{ year: number; text: string }> {
  const yi = side.yi;
  if (!yi || displaySlice(src, 0, 0) === null) return [];
  const display = languageDisplay(src);
  const years = [...new Set([Number(r.other.slice(0, 4)), Number(r.date.slice(0, 4))])].sort((a, b) => a - b);
  return years.flatMap((year) => {
    const text = `${display.slice(0, yi.at)}${yi.sep}${year}${display.slice(yi.at)}`;
    const p = parsePhrase(text, nowMs, tours, false);
    if (p.kind !== 'proposal' || p.seats !== r.seats) return [];
    const want = side.unit === 'day' ? `${year}${r.date.slice(4)}` : `${year}${r.date.slice(4, 7)}`;
    return p.dates.some((d) => d.startsWith(want)) ? [{ year, text }] : [];
  });
}

/**
 * Варианты для «до» в конце отрезка — вся фраза оператора с «по»: с тем же
 * днём конца и с днём раньше (так «до» тоже пишут). Только те, что разбор
 * примет: предложение с теми же местами («с 1 до 2 июля» днём раньше — уже
 * не отрезок, такого варианта нет). Своё «сб и вс» оператора остаётся его
 * словами: «выходные» при туре «Выходные» был бы отказом.
 */
function untilVariants(
  r: Extract<DatesRefusal, { reason: 'range_until' }>, side: YearSide, src: string, nowMs: number, tours: ChatTour[] | null,
): Array<{ inclusive: boolean; text: string }> {
  const u = side.until;
  if (!u || displaySlice(src, 0, 0) === null) return [];
  const display = languageDisplay(src);
  const day = display.slice(u.dayAt, u.dayEnd);
  const digits = /^\d+/.exec(day)?.[0] ?? '';
  const n = Number(digits);
  // «10.07» → «09.07», «10» → «9», «10-го» → «9-го».
  const width = digits.startsWith('0') || day.includes('.') ? digits.length : 1;
  const earlier = n > 1 ? `${String(n - 1).padStart(width, '0')}${day.slice(digits.length)}` : null;
  const edit = (d: string): string => `${display.slice(0, u.till)}по${display.slice(u.till + 2, u.dayAt)}${d}${display.slice(u.dayEnd)}`;
  return [{ inclusive: true, text: edit(day) }, ...(earlier ? [{ inclusive: false, text: edit(earlier) }] : [])].filter((v) => {
    const p = parsePhrase(v.text, nowMs, tours, false);
    return p.kind === 'proposal' && p.seats === r.seats;
  });
}

/**
 * Слова дня недели, месяца и «сегодня», «завтра» в названии тура: тур с
 * ними — только после слова «тур», где бы в названии они ни стояли
 * («Горелый по субботам», «Авача в выходные» — восьмой ревью, S1).
 */
const DATE_WORD = new RegExp(`^(?:${MONTH_WORD}|${WEEKDAY_WORD}|сегодня|завтра|послезавтра)$`, 'u');

function resolveLanguage(lp: LParse, nowMs: number, tours: ChatTour[] | null, titled: Titled, side: YearSide): DatesParse {
  const seats = lp.seats;
  if (seats !== null && (!Number.isInteger(seats) || seats < 1 || seats > MAX_SLOTS_PER_DATE)) {
    return { kind: 'refused', reason: 'bad_seats', value: seats };
  }
  // «ещё» вставкой при местах — добавка или итог? Не угадываем (седьмой ревью, m1).
  if (seats !== null && lp.fillers.includes('еще')) return { kind: 'refused', reason: 'seats_delta', word: 'еще' };
  const today = kamchatkaDate(new Date(nowMs));
  const [Y0, M0] = today.split('-').map(Number) as [number, number, number];

  // Тур.
  let tour: TourPick;
  if (tours === null) tour = { kind: 'unread' };
  else if (lp.tour === null) {
    const m = matchTours([], tours);
    tour = m.kind === 'pick' ? m.pick : { kind: 'unread' };
  } else {
    const words = lp.tour.words;
    const hits = chainHits(words, titled);
    // Название целиком, начатое словом даты или отношения к дате («Выходные на
    // Авачинском», «Каждый день на вулкане»), и название со словом дня недели,
    // месяца, «сегодня» где угодно («Горелый по субботам») — только после
    // слова «тур»: голое и после «на», «для» оно съело бы дни недели фразы
    // (седьмой ревью, M1; восьмой, S1).
    const dateWord = RISKY.test(words[0]!) ? words[0]! : words.find((x) => DATE_WORD.test(x));
    if (hits.length > 0 && dateWord !== undefined && lp.tour.slot !== 'тур') {
      return { kind: 'refused', reason: 'date_word_in_title', word: dateWord, title: hits[0]!.title, dates: null, seats };
    }
    const whole = titled.some((e) => pieceOf(words.filter((w) => w !== '-'), e.tw) === 'whole');
    const halves = whole ? null : chainHalves(words, titled);
    if (halves && hits.length === 0) {
      return { kind: 'refused', reason: 'two_tours', titles: [halves[0][0]!.title, halves[1][0]!.title], word: halves[2], seats };
    }
    // Тур «Горелый и Мутновский» рядом с «Горелым» и «Мутновским» — выбор кнопками, а не молча составной.
    tour = pickOf(halves ? [...new Set([...hits, ...halves[0], ...halves[1]])] : hits);
  }

  // Даты по порядку групп: год каждой следующей — от предыдущей (шестой ревью).
  const yearFor = (m: number): number => (m >= M0 ? Y0 : Y0 + 1);
  let cursor: { y: number; m: number } | null = null;
  const yearOf = (m: number): number => (cursor === null ? yearFor(m) : m >= cursor.m ? cursor.y : cursor.y + 1);
  /**
   * Год без явного: по порядку групп и сам по себе — один и тот же, иначе
   * отказ «уточните год» (седьмой ревью, M2: «5 ноября и 22 октября» давало
   * 22 октября 2027, а «22 октября и 5 ноября» — 2026).
   */
  const ordered = (
    y: number, m: number, d: number, yi: YearIns | null, unit: YearSide['unit'], month: { wd: number[] | null } | null = null,
  ): DatesRefusal | null => {
    if (y === yearFor(m)) return null;
    side.yi = yi;
    side.unit = unit;
    return { kind: 'refused', reason: 'year_order', date: iso(y, m, d), other: iso(yearFor(m), m, d), seats, month, variants: [] };
  };
  /** «3 августа», с годом — только если разбор сам выбрал бы другой: образец отказа. */
  const dayWords = (date: string): string => {
    const [y, m, d] = date.split('-').map(Number) as [number, number, number];
    return `${d} ${GEN_MONTH[m - 1]}${y === yearFor(m) ? '' : ` ${y}`}`;
  };
  const singles: string[] = [];
  const expanded: string[] = [];
  const ruleParts: Array<{ kind: 'span'; from: string; to: string } | { kind: 'month'; y: number; m: number; whole: boolean }> = [];
  let wd: { days: number[]; named: boolean } | null = null;
  for (const g of lp.groups) {
    if (g.k === 'rel') {
      for (const o of g.offsets) singles.push(shiftDay(today, o));
      continue;
    }
    if (g.k === 'days') {
      for (const p of g.points) {
        if (p.y === null && p.m >= 1 && p.m <= 12) {
          const off = ordered(yearOf(p.m), p.m, p.d, p.yi, 'day');
          if (off) return off;
        }
        const r = resolvePoint({ d: p.d, m: p.m, y: p.y, raw: p.raw }, yearOf);
        if ('bad' in r) return { kind: 'refused', reason: 'bad_date', text: r.bad };
        if (g.check !== null && weekdayOf(r.date) !== g.check) return { kind: 'refused', reason: 'weekday_mismatch', date: r.date };
        singles.push(r.date);
        cursor = { y: Number(r.date.slice(0, 4)), m: p.m };
      }
      continue;
    }
    const filter = g.wd ? g.wd.days : undefined;
    if (g.wd) wd = g.wd;
    if (g.k === 'span') {
      let fromYear = g.from.y;
      if (fromYear === null && g.to.y !== null) {
        const fm = g.from.m;
        const tm = g.to.m;
        fromYear = fm < tm || (fm === tm && g.from.d <= g.to.d) ? g.to.y : g.to.y - 1;
      }
      if (fromYear === null && g.from.m >= 1 && g.from.m <= 12) {
        const off = ordered(yearOf(g.from.m), g.from.m, g.from.d, g.from.yi, 'span');
        if (off) return off;
      }
      const a = resolvePoint({ ...g.from, y: fromYear }, yearOf);
      if ('bad' in a) return { kind: 'refused', reason: 'bad_date', text: a.bad };
      const toYear = g.to.y ?? Number(a.date.slice(0, 4));
      let b = resolvePoint({ ...g.to, y: toYear }, yearOf);
      if ('bad' in b) return { kind: 'refused', reason: 'bad_date', text: b.bad };
      if (g.to.y === null && b.date < a.date && g.to.m < Number(a.date.slice(5, 7))) {
        b = resolvePoint({ ...g.to, y: toYear + 1 }, yearOf);
        if ('bad' in b) return { kind: 'refused', reason: 'bad_date', text: b.bad };
      }
      if (b.date < a.date) {
        return { kind: 'refused', reason: 'range_reversed', from: a.date, to: b.date, seats, startMonthInherited: g.fromInherited };
      }
      // Одинаковые концы — что открыть, не сказано (седьмой ревью, m3); образец — тот же день
      // или те же дни недели без отрезка (восьмой ревью, m2).
      if (b.date === a.date) return { kind: 'refused', reason: 'range_same', hint: dayWords(a.date), seats };
      if (g.wd?.same) {
        const span = a.date.slice(0, 7) === b.date.slice(0, 7)
          ? `с ${Number(a.date.slice(8))} по ${dayWords(b.date)}` : `с ${dayWords(a.date)} по ${dayWords(b.date)}`;
        return { kind: 'refused', reason: 'range_same', hint: `${weekdaysPlural(g.wd.days)} ${span}`, seats };
      }
      const n = Math.round((Date.parse(b.date) - Date.parse(a.date)) / 86_400_000) + 1;
      if (n > 366) return { kind: 'refused', reason: 'too_many', count: n, seats, parts: [] };
      // Отрезок короче недели с днями недели: концы названы — и обязаны быть этими днями.
      if (filter && n < 7) {
        const off = [a.date, b.date].find((d) => !filter.includes(weekdayOf(d)));
        if (off) return { kind: 'refused', reason: 'weekday_mismatch', date: off };
      }
      // «с 1 до 10 июля»: входит ли 10-е — по-русски по-разному (седьмой ревью, m2).
      if (g.until) {
        side.until = g.until;
        return { kind: 'refused', reason: 'range_until', from: a.date, to: b.date, seats, variants: [] };
      }
      expanded.push(...datesInRange(a.date, b.date, filter));
      ruleParts.push({ kind: 'span', from: a.date, to: b.date });
      cursor = { y: Number(b.date.slice(0, 4)), m: Number(b.date.slice(5, 7)) };
      continue;
    }
    // «сб-сб в июле», «субботы с октября по октябрь» — образец: «субботы июля», «субботы октября».
    if (g.wd?.same || g.same) {
      const first = g.months[0]!;
      const y = first.y ?? yearOf(first.m);
      const year = g.months.length === 1 && y !== yearFor(first.m) ? ` ${y}` : '';
      const hint = g.wd ? `${weekdaysPlural(g.wd.days)} ${g.months.map((x) => GEN_MONTH[x.m - 1]).join(' и ')}${year}` : null;
      return { kind: 'refused', reason: 'range_same', hint, seats };
    }
    let prev: { y: number; m: number } | null = null;
    for (const mm of g.months) {
      const y: number = mm.y ?? (prev === null ? yearOf(mm.m) : mm.m >= prev.m ? prev.y : prev.y + 1);
      // Перечень месяцев сверяется весь; отрезок («с ноября по февраль») — только началом.
      if (mm.y === null && (prev === null || !g.range)) {
        const off = ordered(y, mm.m, 1, mm.yi, 'month', { wd: g.wd ? g.wd.days : null });
        if (off) return off;
      }
      expanded.push(...datesInRange(iso(y, mm.m, 1), iso(y, mm.m, daysIn(y, mm.m)), filter));
      ruleParts.push({ kind: 'month', y, m: mm.m, whole: g.wd === null });
      prev = { y, m: mm.m };
    }
    cursor = prev;
  }

  // Дата дважды — чьи места, не угадываем (шестой ревью: «3 и 5 августа, 5 августа — 6 мест»).
  const seen = new Set<string>();
  for (const d of [...singles, ...expanded]) {
    if (seen.has(d)) return { kind: 'refused', reason: 'repeated_date', date: d, seats };
    seen.add(d);
  }

  const pastNamed = [...new Set(singles.filter((d) => d < today))].sort();
  const pastDropped = [...new Set(expanded.filter((d) => d < today))].sort();
  const dates = [...new Set([...singles, ...expanded].filter((d) => d >= today))].sort();
  if (dates.length === 0) {
    if (pastNamed.length > 0 || pastDropped.length > 0) {
      return { kind: 'refused', reason: 'past_only', named: pastNamed, dropped: pastDropped, today, seats };
    }
    return { kind: 'refused', reason: 'not_understood' };
  }
  const lastDate = horizonLastDate(today);
  const far = dates.find((d) => d > lastDate);
  if (far) return { kind: 'refused', reason: 'too_far', date: far, lastDate };
  if (dates.length > MAX_DATES_PER_PROPOSAL) {
    return { kind: 'refused', reason: 'too_many', count: dates.length, seats, parts: splitByMonth(dates, today, wd?.days) };
  }
  const rule = ruleText(ruleParts, wd ? wd.days : null, singles.filter((d) => d >= today));
  return {
    kind: 'proposal', dates, pastDropped, pastNamed, seats, tour, priceMentioned: lp.price, weekdayWords: wd !== null && wd.named, rule,
  };
}

/** Прежний разбор — диагност фраз вне языка (шапка `parseDatesPhrase`). */
function diagnosePhrase(text: string, nowMs: number, tours: ChatTour[] | null): DatesParse {
  const norm = normalizePhrase(text);
  const titles = (tours ?? []).map((t) => ({ t, words: titleWordsOf(t.title) }));
  const tourWord = tours === null ? null : (w: string) => titles.some((e) => wordInTitle(w, e.words));
  const intent = intentOf(norm, tourWord);
  switch (intent.intent) {
    case 'not_dates': return { kind: 'not_dates' };
    case 'close': return { kind: 'close_intent' };
    case 'mixed': return { kind: 'refused', reason: 'mixed_actions' };
    case 'negated': return { kind: 'refused', reason: 'negated', word: intent.word ?? '' };
    case 'exclusion': return { kind: 'refused', reason: 'exclusion', word: intent.word ?? '' };
    case 'question': return { kind: 'refused', reason: 'question' };
    case 'unparsed': return { kind: 'refused', reason: 'not_understood' };
    case 'open': break;
  }

  // 1. Добавка к местам — до мест: «ещё 2 места» не итог на дату.
  const delta = norm.match(SEATS_DELTA);
  if (delta) return { kind: 'refused', reason: 'seats_delta', word: delta[0].trim() };

  // 2. Места.
  const seatsCut = cutSeats(norm);
  const seatValues = [...new Set(seatsCut.values)];
  if (seatValues.length > 1) return { kind: 'refused', reason: 'two_seat_numbers', values: seatValues };
  const seats = seatValues.length === 1 ? seatValues[0]! : null;
  if (seats !== null && (!Number.isInteger(seats) || seats < 1 || seats > MAX_SLOTS_PER_DATE)) {
    return { kind: 'refused', reason: 'bad_seats', value: seats };
  }
  const month0 = firstMonth(norm);

  // 3. Знак вне закрытого списка — отказ (пятый ревью: «весь июль 🚫 выходные»).
  const badChar = [...text].find((ch) => !ALLOWED_CHAR.test(ch));
  if (badChar !== undefined) return { kind: 'refused', reason: 'bad_char', char: badChar, seats };

  // 4. Слова, у которых свой отказ с подсказкой.
  const period = periodicityWord(norm);
  if (period !== null) return { kind: 'refused', reason: 'periodicity', word: period, month: month0, seats };
  const etc = norm.match(ETC);
  if (etc) return { kind: 'refused', reason: 'etc', word: etc[0].trim(), seats };
  const yearWords = norm.match(YEAR_WORDS);
  if (yearWords) return { kind: 'refused', reason: 'year_words', word: yearWords[0].trim(), seats };
  const alt = norm.match(ALTERNATIVE);
  if (alt) return { kind: 'refused', reason: 'alternative', word: alt[0], month: month0, seats };

  const toks = tokenize(seatsCut.rest);
  const used = new Array<boolean>(toks.length).fill(false);
  toks.forEach((k, i) => { if (k.t === 'punct' && k.glue) used[i] = true; });
  const word = (i: number): string | null => { const k = toks[i]; return k && k.t === 'word' ? k.w : null; };
  const pricedAfter = (i: number): boolean => {
    const k = toks[i];
    const n = toks[i + 1];
    if (!k || !n || k.t !== 'num') return false;
    if (n.t === 'punct') return n.p === '₽';
    if (n.t !== 'word') return false;
    return PRICE_WORD.test(n.w) || (n.w === 'к' && n.pos === k.pos + k.raw.length);
  };

  // 5. Расплывчатые периоды — вопрос; время через точку — не дата.
  for (const k of toks) {
    if (k.t === 'word' && k.w !== 'начиная' && VAGUE.test(k.w)) return { kind: 'ask', what: 'vague_period', word: k.w };
  }
  for (let i = 0; i < toks.length; i++) {
    const k = toks[i]!;
    if (k.t !== 'ndate' || k.y !== null) continue;
    const prev = word(i - 1);
    if (k.m > 12 || (prev !== null && (TIME_BEFORE.has(prev) || TIME_WORD.test(prev)))) {
      return { kind: 'refused', reason: 'time_like', token: k.raw };
    }
  }

  const today = kamchatkaDate(new Date(nowMs));
  const [Y0, M0, D0] = today.split('-').map(Number) as [number, number, number];
  const yearFor = (m: number): number => (m >= M0 ? Y0 : Y0 + 1);

  const monthYear = new Map<number, number>();
  toks.forEach((k, i) => {
    if (k.t !== 'word' || monthOf(k.w) === null) return;
    const n = toks[i + 1];
    if (n && n.t === 'num' && n.digits === 4 && n.v >= 2000 && n.v <= 2100) {
      monthYear.set(i, n.v);
      used[i + 1] = true;
      if (word(i + 2) !== null && YEAR_WORD.has(word(i + 2)!)) used[i + 2] = true;
    }
  });

  // 6. Дни недели — только группой в узнанной конструкции.
  const isWd = (i: number): boolean => { const w = word(i); return w !== null && !used[i] && weekdaysOf(w) !== null; };
  const isJoiner = (i: number): number => {
    const k = toks[i];
    if (!k) return 0;
    if (k.t === 'punct' && (k.p === ',' || k.p === ';')) return word(i + 1) === 'и' ? 2 : 1;
    if (k.t === 'word' && k.w === 'и') return 1;
    return 0;
  };
  const wdRange = (a: number, b: number): number[] => {
    const out: number[] = [];
    for (let d = a; ; d = (d + 1) % 7) { out.push(d); if (d === b || out.length === 7) break; }
    return out;
  };
  const single = (i: number): number | null => { const d = weekdaysOf(word(i) ?? ''); return d && d.length === 1 ? d[0]! : null; };
  const isDash = (i: number): boolean => { const k = toks[i]; return !!k && k.t === 'punct' && k.p === '-' && !k.glue; };
  /** Дефис и внутри «пн-пт», «июль-сентябрь» (там он слитный). */
  const anyDash = (i: number): boolean => { const k = toks[i]; return !!k && k.t === 'punct' && k.p === '-'; };
  const wdGroupAt = (i: number): WdGroup | null => {
    let j = i;
    let excluded = false;
    const lead = word(j);
    if (lead !== null && WD_EXCLUDE.has(lead)) { excluded = true; j++; }
    else if (lead === 'за' && word(j + 1) === 'исключением') { excluded = true; j += 2; }
    if (WD_PREP.has(word(j) ?? '') && (isWd(j + 1) || WD_QUANT.has(word(j + 1) ?? ''))) j++;
    let quant = false;
    if (WD_QUANT.has(word(j) ?? '') && isWd(j + 1) && quantAgrees(word(j)!, word(j + 1)!)) { j++; quant = true; }
    let half = false;
    if (word(j) === 'начиная' && (word(j + 1) === 'с' || word(j + 1) === 'со') && isWd(j + 2)) { j++; half = true; }
    const days = new Set<number>();
    let n = 0;
    let firstWord = '';
    let named = false;
    for (;;) {
      if (WD_PREP.has(word(j) ?? '') && isWd(j + 1)) j++;
      if ((word(j) === 'с' || word(j) === 'со') && isWd(j + 1)) {
        const a = single(j + 1);
        const b = RANGE_END.has(word(j + 2) ?? '') && isWd(j + 3) ? single(j + 3) : null;
        if (a !== null && b !== null && !half) {
          wdRange(a, b).forEach((d) => days.add(d));
          firstWord ||= word(j + 1)!;
          j += 4;
        } else {
          half = true;
          firstWord ||= word(j + 1)!;
          weekdaysOf(word(j + 1)!)!.forEach((d) => days.add(d));
          j += 2;
        }
      } else if (word(j) === 'до' && isWd(j + 1) && n === 0) {
        half = true;
        firstWord ||= word(j + 1)!;
        weekdaysOf(word(j + 1)!)!.forEach((d) => days.add(d));
        j += 2;
      } else if (isWd(j) && anyDash(j + 1) && isWd(j + 2) && single(j) !== null && single(j + 2) !== null) {
        wdRange(single(j)!, single(j + 2)!).forEach((d) => days.add(d));
        firstWord ||= word(j)!;
        j += 3;
      } else if (isWd(j)) {
        const w = word(j)!;
        weekdaysOf(w)!.forEach((d) => days.add(d));
        firstWord ||= w;
        if (/^(?:будн|выходн)/u.test(w)) named = true;
        j++;
        if (/^(?:будн|выходн)/u.test(w) && WD_DAY_NOUN.has(word(j) ?? '')) j++;
      } else break;
      n++;
      const jn = isJoiner(j);
      const after = j + jn;
      const nextWd = isWd(after) || (WD_PREP.has(word(after) ?? '') && isWd(after + 1))
        || ((word(after) === 'с' || word(after) === 'со') && isWd(after + 1));
      if (jn === 0 || !nextWd) break;
      j = after;
    }
    if (n === 0) return null;
    return { days: [...days].sort((a, b) => a - b), from: i, to: j, excluded, half, word: firstWord, named, quant };
  };
  const groups: WdGroup[] = [];
  for (let i = 0; i < toks.length; i++) {
    if (used[i]) continue;
    const g = wdGroupAt(i);
    if (!g) continue;
    groups.push(g);
    for (let j = g.from; j < g.to; j++) used[j] = true;
    i = g.to - 1;
  }
  const dayOffWords: string[] = [];
  toks.forEach((k, i) => {
    if (used[i] || k.t !== 'word' || !DAY_OFF.test(k.w)) return;
    const near = groups.find((g) => (i >= g.to && i - g.to <= 1) || (g.from > i && g.from - i <= 2));
    if (!near) return;
    near.excluded = true;
    used[i] = true;
    if (isDash(i - 1)) used[i - 1] = true;
    dayOffWords.push(k.w);
  });

  const point = (i: number): { p: Point; next: number } | null => {
    const k = toks[i];
    if (!k || used[i]) return null;
    if (k.t === 'iso' || k.t === 'ndate') {
      const yw = word(i + 1);
      const next = k.y !== null && yw !== null && YEAR_WORD.has(yw) ? i + 2 : i + 1;
      return { p: { d: k.d, m: k.m, y: k.y, raw: k.raw }, next };
    }
    if (k.t !== 'num' || k.digits > 2 || pricedAfter(i)) return null;
    const mw = word(i + 1);
    const m = mw !== null && !used[i + 1] ? monthOf(mw) : null;
    if (m !== null) {
      const y = monthYear.get(i + 1) ?? null;
      const next = y !== null ? (word(i + 3) !== null && YEAR_WORD.has(word(i + 3)!) ? i + 4 : i + 3) : i + 2;
      return { p: { d: k.v, m, y, raw: `${k.v} ${mw}` }, next };
    }
    return { p: { d: k.v, m: null, y: null, raw: k.raw }, next: i + 1 };
  };
  const monthAt = (i: number): { m: number; y: number | null; next: number } | null => {
    const w = word(i);
    if (w === null || used[i]) return null;
    const m = monthOf(w);
    if (m === null) return null;
    const y = monthYear.get(i) ?? null;
    const next = y !== null ? (word(i + 2) !== null && YEAR_WORD.has(word(i + 2)!) ? i + 3 : i + 2) : i + 1;
    return { m, y, next };
  };
  const constructs: Construct[] = [];
  const markUsed = (from: number, to: number) => { for (let j = from; j < to; j++) used[j] = true; };
  const adjacent = (a: number, b: number): boolean => {
    const x = toks[a];
    const y = toks[b];
    if (!x || !y) return false;
    const end = x.pos + (x.t === 'word' ? x.w.length : x.t === 'punct' ? x.p.length : x.raw.length);
    return /^\s{0,2}$/.test(seatsCut.rest.slice(end, y.pos));
  };
  const endOf = (x: Tok): number => x.pos + (x.t === 'word' ? x.w.length : x.t === 'punct' ? x.p.length : x.raw.length);
  /** Конец предложения вокруг связки: отрезок через «.», «!», «?» не тянется («3 августа. - 10 августа»). */
  const breakAround = (i: number): boolean => {
    const prev = toks[i - 1];
    const next = toks[i + 1];
    return (!!prev && /[.!?]/.test(seatsCut.rest.slice(endOf(prev), toks[i]!.pos)))
      || (!!next && /[.!?]/.test(seatsCut.rest.slice(endOf(toks[i]!), next.pos)));
  };
  const isRangeLink = (i: number): boolean => {
    const k = toks[i];
    return !!k && !used[i] && !breakAround(i) && ((k.t === 'punct' && k.p === '-' && !k.glue) || (k.t === 'word' && RANGE_END.has(k.w)));
  };
  /** «включительно» после отрезка — часть отрезка. */
  const inclusive = (i: number): number => (word(i) === 'включительно' ? i + 1 : i);

  const singles: Point[] = [];
  const spans: Span[] = [];
  const relative: Array<{ date: string; word: string }> = [];
  const bareMonths: BareMonth[] = [];
  const monthRange = (a: { m: number; y: number | null }, b: { m: number; y: number | null }, at: number): void => {
    let y = a.y ?? yearFor(a.m);
    let m = a.m;
    for (let n = 0; n < 14; n++) {
      bareMonths.push({ m, y, whole: true, at });
      if (m === b.m && (b.y === null || y === b.y)) break;
      if (m === 12) { m = 1; y++; } else m++;
    }
  };

  for (let i = 0; i < toks.length; i++) {
    if (used[i]) continue;
    const k = toks[i]!;
    if (k.t === 'word' && k.w in RELATIVE) {
      relative.push({ date: shiftDay(today, RELATIVE[k.w]!), word: k.w });
      markUsed(i, i + 1);
      constructs.push({ kind: 'single', from: i, to: i + 1, whole: false });
      continue;
    }
    if (k.t === 'word' && RANGE_START.has(k.w)) {
      const at = k.w === 'начиная' && (word(i + 1) === 'с' || word(i + 1) === 'со') ? i + 2 : i + 1;
      const ma = monthAt(at);
      if (ma) {
        const mb = isRangeLink(ma.next) ? monthAt(ma.next + 1) : null;
        if (mb) {
          monthRange(ma, mb, i);
          markUsed(i, mb.next);
          constructs.push({ kind: 'month', from: i, to: mb.next, whole: true });
          i = mb.next - 1;
          continue;
        }
        return { kind: 'ask', what: 'half_range', seats };
      }
      const a = point(at);
      if (!a) continue;
      if (isRangeLink(a.next)) {
        const b = point(a.next + 1);
        if (b) {
          const end = inclusive(b.next);
          spans.push({ from: a.p, to: b.p, at: i });
          markUsed(i, end);
          constructs.push({ kind: 'span', from: i, to: end, whole: false });
          i = end - 1;
          continue;
        }
      }
      if (a.p.m !== null) return { kind: 'ask', what: 'half_range', seats };
      continue;
    }
    const mm = monthAt(i);
    if (mm && anyDash(mm.next) && !breakAround(mm.next)) {
      const mb = monthAt(mm.next + 1);
      if (mb) {
        monthRange(mm, mb, i);
        markUsed(i, mb.next);
        constructs.push({ kind: 'month', from: i, to: mb.next, whole: true });
        i = mb.next - 1;
        continue;
      }
    }
    const a = point(i);
    if (!a) continue;
    if (a.p.m !== null && i > 0 && !used[i - 1] && RANGE_END.has(word(i - 1) ?? '') && adjacent(i - 1, i)) {
      return { kind: 'ask', what: 'half_range', seats };
    }
    if (isRangeLink(a.next)) {
      const b = point(a.next + 1);
      if (b) {
        const end = inclusive(b.next);
        spans.push({ from: a.p, to: b.p, at: i });
        markUsed(i, end);
        constructs.push({ kind: 'span', from: i, to: end, whole: false });
        i = end - 1;
        continue;
      }
    }
    const list: Array<{ p: Point; from: number; next: number }> = [{ p: a.p, from: i, next: a.next }];
    let j = a.next;
    for (;;) {
      const jn = isJoiner(j);
      if (!jn) break;
      const b = point(j + jn);
      if (!b || (isRangeLink(b.next) && point(b.next + 1) !== null)) break;
      list.push({ p: b.p, from: j + jn, next: b.next });
      j = b.next;
    }
    for (let x = list.length - 1, m: number | null = null, y: number | null = null; x >= 0; x--) {
      const it = list[x]!;
      if (it.p.m !== null) { m = it.p.m; y = it.p.y; continue; }
      if (m !== null) { it.p.m = m; it.p.y = y; }
    }
    const resolved = list.filter((it) => it.p.m !== null);
    if (resolved.length === 0) continue;
    const lastResolved = list.lastIndexOf(resolved[resolved.length - 1]!);
    for (let x = 0; x <= lastResolved; x++) {
      const it = list[x]!;
      if (it.p.m !== null) singles.push(it.p);
    }
    markUsed(i, list[lastResolved]!.next);
    constructs.push({ kind: 'single', from: i, to: list[lastResolved]!.next, whole: false });
    i = list[lastResolved]!.next - 1;
  }

  for (const s of spans) {
    if (s.to.m === null) return { kind: 'refused', reason: 'range_end', from: s.from.raw, to: s.to.raw };
    if (s.from.m === null) { s.from.m = s.to.m; s.fromInherited = true; }
  }

  // Месяцы, не съеденные точками: «субботы июля», «весь июль», «в июле и августе».
  const bareAt = new Map<number, BareMonth>();
  toks.forEach((k, i) => {
    if (used[i] || k.t !== 'word') return;
    const m = monthOf(k.w);
    if (m === null) return;
    const prev = used[i - 1] ? null : word(i - 1);
    const prev2 = used[i - 2] ? null : word(i - 2);
    const joinedTo = isJoiner(i - 1) ? bareAt.get(i - 2) ?? (word(i - 1) === 'и' && isJoiner(i - 2) ? bareAt.get(i - 3) : undefined) : undefined;
    const wholeBefore = prev !== null && WHOLE_BEFORE.has(prev);
    // «каждый день», «все дни» — согласованно; «каждый дни» — нет (пятый ревью).
    const everyDay = prev !== null && prev2 !== null
      && ((prev === 'день' && prev2 === 'каждый') || (prev === 'дни' && (prev2 === 'все' || prev2 === 'каждые')));
    const wholeAfter = word(i + 1) === 'целиком' || word(i + 1) === 'полностью';
    const whole = wholeBefore || everyDay || wholeAfter || joinedTo?.whole === true;
    const from = everyDay ? i - 2 : wholeBefore ? i - 1 : i;
    let to = monthYear.has(i) ? (word(i + 2) !== null && YEAR_WORD.has(word(i + 2)!) ? i + 3 : i + 2) : i + 1;
    if (wholeAfter) to = i + 2;
    const bm: BareMonth = { m, y: monthYear.get(i) ?? null, whole, at: i };
    bareMonths.push(bm);
    bareAt.set(monthYear.has(i) ? i + 1 : i, bm);
    markUsed(from, Math.max(to, i + 1));
    constructs.push({ kind: 'month', from, to: Math.max(to, i + 1), whole: wholeBefore || everyDay || wholeAfter });
  });
  constructs.sort((a, b) => a.from - b.from);
  const scoped = bareMonths.length > 0 || spans.length > 0;
  // «ежедневно» — только при отрезке или месяце и без дней недели: «ежедневно 3
  // августа» — с 3 августа каждый день или один день, не угадываем.
  toks.forEach((k, i) => {
    if (!used[i] && k.t === 'word' && k.w === 'ежедневно' && scoped && groups.length === 0) used[i] = true;
  });

  /**
   * Число из названия тура — не дата и не остаток, только когда стоит сразу
   * после слова этого названия: «Налычево 5 дней», «Горелый за 1 день». «3
   * августа и 5 мутновский» — 5 могло быть датой: остаток, отказ.
   */
  const titleNum = new Array<boolean>(toks.length).fill(false);
  const titleNumberAt = (i: number, v: number): boolean => {
    const prev = word(i - 1);
    if (prev === null || used[i - 1] || !adjacent(i - 1, i)) return false;
    return titles.some((e) => e.words.includes(String(v)) && wordInTitle(prev, e.words));
  };

  // 7. Цена и остаток чисел. Число цены — до семи цифр: телефон — не цена.
  let priceMentioned = /₽/.test(norm) || /(?<![\p{L}])(?:руб|р\.|цен[аеуыо]|стоимост)/u.test(norm);
  for (let i = 0; i < toks.length; i++) {
    const k = toks[i]!;
    if (used[i]) continue;
    if (k.t === 'word' && PRICE_WORD.test(k.w)) {
      used[i] = true;
      if (PRICE_WORD_LONG.test(k.w)) priceMentioned = true;
      continue;
    }
    if (k.t === 'punct' && k.p === '₽') { used[i] = true; priceMentioned = true; continue; }
    if (k.t === 'punct' && k.p === '/') {
      return { kind: 'refused', reason: 'leftover_number', token: chunkAt(seatsCut.rest, k.pos), yearLike: false };
    }
    if (k.t !== 'num' && k.t !== 'ndate' && k.t !== 'iso') continue;
    if (k.t === 'num') {
      const yearLike = k.digits === 4 && k.v >= 2024 && k.v <= 2035;
      if (pricedAfter(i) || (k.v >= 1000 && !yearLike && k.digits <= 7)) {
        priceMentioned = true;
        used[i] = true;
        if (pricedAfter(i) && toks[i + 1]?.t === 'word') used[i + 1] = true;
        continue;
      }
      if (titleNumberAt(i, k.v)) { used[i] = true; titleNum[i] = true; continue; }
      return { kind: 'refused', reason: 'leftover_number', token: chunkAt(seatsCut.rest, k.pos), yearLike };
    }
    return { kind: 'refused', reason: 'leftover_number', token: chunkAt(seatsCut.rest, k.pos), yearLike: false };
  }

  if (singles.length === 0 && spans.length === 0 && bareMonths.length === 0 && relative.length === 0 && groups.length === 0) {
    return namedAsDates(norm) ? { kind: 'refused', reason: 'not_understood' } : { kind: 'not_dates' };
  }

  // 8. Исключение дня недели — отказ с оставшимися днями.
  const excludedGroups = groups.filter((g) => g.excluded);
  if (excludedGroups.length > 0) {
    const base = groups.filter((g) => !g.excluded);
    const all = base.length > 0 ? new Set(base.flatMap((g) => g.days)) : new Set([0, 1, 2, 3, 4, 5, 6]);
    excludedGroups.forEach((g) => g.days.forEach((d) => all.delete(d)));
    const keep = [...all].sort((a, b) => a - b);
    const word0 = dayOffWords[0] ?? toks.slice(excludedGroups[0]!.from, excludedGroups[0]!.to)
      .map((k) => (k.t === 'word' ? k.w : '')).filter(Boolean).join(' ');
    return {
      kind: 'refused', reason: 'weekday_exclusion', word: word0,
      keep: keep.length > 0 && keep.length < 7 ? keep : null, scope: scopeWords(spans, bareMonths, Y0, M0), seats,
    };
  }

  // 9. Дефис, не съеденный грамматикой («весь июль -сб», «-17 июля»), — отказ,
  //    как «/»; перед числом мест («17.08 — 8 мест») он разделитель.
  const seatsAfter = (pos: number): boolean => seatsCut.ranges.some(([a]) => a > pos && /^[\s-]*$/.test(norm.slice(pos + 1, a)));
  for (let i = 0; i < toks.length; i++) {
    if (isDash(i) && !used[i] && !seatsAfter(toks[i]!.pos)) return { kind: 'refused', reason: 'bad_char', char: '-', seats };
  }

  // 10. Слово отношения к дате или длительность рядом с датой — отказ до
  //     выбора тура: «к 3 августа» — срок, «5 августа на неделю» — не семь выездов.
  const constructAt = (i: number): Construct | null => constructs.find((c) => i >= c.from && i < c.to) ?? null;
  const groupAt = (i: number): WdGroup | null => groups.find((g) => i >= g.from && i < g.to) ?? null;
  const nextSignificant = (i: number, step: 1 | -1): number => {
    for (let j = i; j >= 0 && j < toks.length; j += step) {
      const k = toks[j]!;
      if (k.t === 'punct') continue;
      if (k.t === 'word' && !used[j] && CONNECTORS.has(k.w)) continue;
      return j;
    }
    return -1;
  };
  // Исключение — слово, с которого после «на», «по», «тур» начинается название
  // тура («на Между двух вулканов»): его судит цепочка тура ниже.
  const opensTitle = (i: number, w: string): boolean => {
    const p = word(i - 1);
    return p !== null && !used[i - 1] && TOUR_SLOT.has(p) && titles.some((e) => e.words[0] === w);
  };
  for (let i = 0; i < toks.length; i++) {
    const w = word(i);
    if (w === null || used[i] || !(RELATION.test(w) || DURATION.test(w)) || opensTitle(i, w)) continue;
    const near = [nextSignificant(i + 1, 1), nextSignificant(i - 1, -1)].some((j) => j >= 0 && (constructAt(j) || groupAt(j)));
    if (near) return { kind: 'refused', reason: 'date_relation', word: w, month: month0, seats };
  }
  // «Сегодня» и «завтра» — дата, только когда других дат нет.
  if (relative.length > 0 && (singles.length > 0 || spans.length > 0 || bareMonths.length > 0 || groups.some((g) => !g.excluded))) {
    return { kind: 'refused', reason: 'relative_mixed', word: relative[0]!.word };
  }

  // 11. Группы дат связаны явно (пятый ревью: «продажи 1 августа на 5 сентября»
  //     открывала обе даты): между группами «,», «;», «и» или конец
  //     предложения; вторая группа под своим словом роли — отказ.
  const constructText = (c: Construct): string => {
    const a = toks[c.from]!;
    const z = toks[c.to - 1]!;
    return seatsCut.rest.slice(a.pos, z.pos + (z.t === 'word' ? z.w.length : z.t === 'punct' ? z.p.length : z.raw.length))
      .replace(/\s+/g, ' ').replace(/ ,/g, ',').trim();
  };
  const unjoined = (): DatesRefusal => ({ kind: 'refused', reason: 'unjoined_dates', parts: constructs.map(constructText), seats });
  for (let x = 1; x < constructs.length; x++) {
    const a = constructs[x - 1]!;
    const b = constructs[x]!;
    const gap = toks.slice(a.to, b.from);
    const tokSep = gap.some((k, n) => (k.t === 'punct' && (k.p === ',' || k.p === ';')) || (k.t === 'word' && k.w === 'и' && !used[a.to + n]));
    const lastA = toks[a.to - 1]!;
    const endA = lastA.pos + (lastA.t === 'word' ? lastA.w.length : lastA.t === 'punct' ? lastA.p.length : lastA.raw.length);
    const textSep = /[.!?]/.test(seatsCut.rest.slice(endA, toks[b.from]!.pos));
    if (!tokSep && !textSep) return unjoined();
    let r = b.from - 1;
    while (r > a.to - 1 && word(r) !== null && !used[r] && (word(r) === 'на' || word(r) === 'в')) r--;
    if (r > a.to - 1 && word(r) !== null && !used[r] && ROLE_NOUN.test(word(r)!)) return unjoined();
  }

  // «уже 8 мест» — уже есть, а не открыть (пятый ревью).
  for (let i = 0; i < toks.length; i++) {
    if (word(i) === 'уже' && !used[i] && seatsAfter(toks[i]!.pos + 'уже'.length - 1)) {
      return { kind: 'refused', reason: 'unknown_words', words: ['уже'], tourLike: false, seats };
    }
  }

  // 12. Слова, которые не съела грамматика: связки, приветствие, тур — или непонятое.
  const greeting = new Array<boolean>(toks.length).fill(false);
  toks.forEach((k, i) => {
    const pair = k.t === 'word' ? GREETING[k.w] : undefined;
    if (pair && !used[i] && pair.has(word(i + 1) ?? '') && !used[i + 1]) { greeting[i] = true; greeting[i + 1] = true; }
  });
  const isCandidate = (i: number): boolean => {
    const k = toks[i];
    return !!k && k.t === 'word' && !used[i] && !greeting[i] && !CONNECTORS.has(k.w);
  };
  const names = properNames(text);
  const addVerb = ADD_FORMS.test(norm) && !OPEN_ITSELF.test(norm);
  /** Слово стоит там, где пишут тур: после «на», «по», «тур», «для» — через другие слова и «и». */
  const inTourSlot = (i: number): boolean => {
    for (let j = i - 1; j >= 0; j--) {
      const k = toks[j]!;
      if (k.t !== 'word' || used[j]) return false;
      if (TOUR_SLOT.has(k.w)) return true;
      if (k.w === 'и' || !CONNECTORS.has(k.w)) continue;
      return false;
    }
    return false;
  };
  const ordinal = toks.find((k, i) => isCandidate(i) && ORDINAL.test((k as { w: string }).w)) as { w: string } | undefined;
  const numberWord = toks.find((k, i) => isCandidate(i) && NUMBER_WORD.test((k as { w: string }).w)) as { w: string } | undefined;
  const relation = toks.find((k, i) => isCandidate(i) && RELATION.test((k as { w: string }).w)) as { w: string } | undefined;
  const special = (w: string): boolean => ORDINAL.test(w) || NUMBER_WORD.test(w) || RELATION.test(w);

  let tour: TourPick;
  if (tours === null) {
    // Туры не прочитаны: любое слово может оказаться туром — решит поток.
    if (relation) return { kind: 'refused', reason: 'date_relation', word: relation.w, month: month0, seats };
    if (ordinal) return { kind: 'refused', reason: 'ordinal', word: ordinal.w, month: month0, seats };
    if (numberWord) return { kind: 'refused', reason: 'number_word', word: numberWord.w, month: month0, seats };
    tour = { kind: 'unread' };
  } else {
    const chains = tourChains(toks, used, titleNum, isCandidate, special, titles);
    const unknown: Array<{ w: string; i: number }> = [];
    const chainWords: Array<{ w: string; i: number }> = [];
    for (const c of chains) {
      const startsAfterVerb = (() => {
        for (let j = c.from - 1; j >= 0; j--) {
          const k = toks[j]!;
          if (k.t === 'word' && OPEN_FORM_WORD.test(k.w)) return true;
          if (k.t === 'word' && !used[j] && CONNECTORS.has(k.w)) continue;
          if (k.t === 'punct' && k.glue) continue;
          return false;
        }
        return false;
      })();
      const slot = c.from > 0 && word(c.from - 1) !== null && !used[c.from - 1] && TOUR_SLOT.has(word(c.from - 1)!);
      const ws = c.words;
      const exact = ws.every((x) => titles.some((e) => e.words.includes(x.w)));
      const full = titles.some((e) => {
        const sig = e.words.filter((tw) => tw.length >= 4 && !CONNECTORS.has(tw) && !/^\d+$/.test(tw));
        return sig.length > 0 && sig.every((tw) => ws.some((x) => x.w === tw || (x.w.length >= 4 && sameStem(x.w, tw) && !surnameLike(x.w, tw))));
      });
      if (slot || startsAfterVerb || exact || full) {
        chainWords.push(...ws);
        if (slot && word(c.from - 1) === 'для') used[c.from - 1] = true;
      } else unknown.push(...ws);
    }
    toks.forEach((k, i) => {
      if (isCandidate(i) && !chainWords.some((x) => x.i === i) && !unknown.some((x) => x.i === i)) unknown.push({ w: (k as { w: string }).w, i });
    });
    const m = matchTours(chainWords, tours);
    if (m.kind === 'unknown') unknown.push(...m.words);
    unknown.sort((a, b) => a.i - b.i);
    const plain = unknown.filter((x) => !special(x.w));
    // Граница с делами помощника: непонятое слово не там, где пишут тур, и
    // признак дела CRM — сообщение помощнику.
    const crm = plain.some((x) => !inTourSlot(x.i)
      && (addVerb || names.has(x.w) || x.w === 'для' || word(x.i - 1) === 'для'))
      || plain.some((x) => names.has(x.w) && titles.some((e) => e.words.some((tw) => surnameLike(x.w, tw))));
    if (crm) return { kind: 'not_dates' };
    // Порядковое, число словом, слово отношения — если не съедены названием тура.
    const ordinalU = unknown.find((x) => ORDINAL.test(x.w));
    const numberU = unknown.find((x) => NUMBER_WORD.test(x.w));
    const relationU = unknown.find((x) => RELATION.test(x.w));
    if (ordinalU) return { kind: 'refused', reason: 'ordinal', word: ordinalU.w, month: month0, seats };
    if (numberU) return { kind: 'refused', reason: 'number_word', word: numberU.w, month: month0, seats };
    if (relationU) return { kind: 'refused', reason: 'date_relation', word: relationU.w, month: month0, seats };
    if (plain.length > 0) {
      return {
        kind: 'refused', reason: 'unknown_words', words: [...new Set(plain.map((x) => x.w))],
        tourLike: plain.some((x) => inTourSlot(x.i)), seats,
      };
    }
    if (m.kind === 'two') return { kind: 'refused', reason: 'two_tours', titles: m.titles, word: m.word, seats };
    if (m.kind === 'pick') {
      // Слово, ушедшее в дату, стоит в названии тура рядом или в названии
      // тура-кандидата («на Выходные на Авачинском»): тур — кнопкой.
      const candidates = m.candidates;
      const chainIdx = new Set(chainWords.map((x) => x.i));
      for (let i = 0; i < toks.length; i++) {
        const w = word(i);
        if (w === null || !used[i] || (!groupAt(i) && !constructAt(i))) continue;
        // Предлог («по субботам» при «Сплаве по реке») туром не называет (седьмой ревью).
        const inTitle = w.length < 3 ? [] : titles.filter((e) => e.words.includes(w));
        if (inTitle.length === 0) continue;
        const slotBefore = i > 0 && word(i - 1) !== null && !used[i - 1] && TOUR_SLOT.has(word(i - 1)!);
        const nearChain = [nextSignificant(i + 1, 1), nextSignificant(i - 1, -1)].some((j) => j >= 0 && chainIdx.has(j))
          || (i + 1 < toks.length && TOUR_SLOT.has(word(i + 1) ?? '') && chainIdx.has(i + 2));
        const inCandidate = inTitle.find((e) => candidates.includes(e.t));
        if (slotBefore || nearChain || inCandidate) {
          return { kind: 'refused', reason: 'date_word_in_title', word: w, title: (inCandidate ?? inTitle[0]!).t.title, dates: null, seats };
        }
      }
    }
    tour = m.kind === 'pick' ? m.pick : { kind: 'unread' };
  }

  const active = groups.filter((g) => !g.excluded);

  // Места и тур — общие для всех дат: стоят между группами дат — отказ («3
  // августа на 8 мест, 5 сентября на Горелый»).
  // Внутри перечня тоже: «3 августа на 8 мест, 5 сентября» — один перечень.
  const datePos = toks.filter((_, i) => constructAt(i) !== null).map((k) => k.pos);
  if (datePos.length > 1) {
    const first = Math.min(...datePos);
    const last = Math.max(...datePos);
    const between = seatsCut.ranges.some(([a]) => a > first && a < last)
      || toks.some((k, i) => k.t === 'word' && !CONNECTORS.has(k.w) && !used[i] && k.pos > first && k.pos < last && !greeting[i]);
    if (between) return unjoined();
  }

  // 14. Дни недели: одна группа на фразу. Группа ложится на область, только
  //     если она примыкает к ней (через связки, но не через «,», «и», «а»,
  //     «тоже»), область — непрерывный перечень месяцев или один отрезок, и
  //     других областей нет; у отдельной даты — уточнение к ней (пятый ревью).
  if (active.length > 1) return { kind: 'refused', reason: 'weekday_scope', seats };
  const wd = active[0] ?? null;
  if (wd?.half) return { kind: 'ask', what: 'half_range', seats };
  const scopes = constructs.filter((c) => c.kind !== 'single');
  if (wd) {
    const attach = (start: number, step: 1 | -1): Construct | null => {
      for (let j = start; j >= 0 && j < toks.length; j += step) {
        const k = toks[j]!;
        if (k.t === 'punct') { if (k.glue) continue; return null; }
        if (k.t === 'word' && !used[j] && (k.w === 'и' || JOIN_BREAK.has(k.w))) return null;
        if (k.t === 'word' && !used[j] && CONNECTORS.has(k.w)) continue;
        return constructAt(j);
      }
      return null;
    };
    const near = [attach(wd.from - 1, -1), attach(wd.to, 1)];
    const scopeNear = near.find((c) => c && c.kind !== 'single') ?? null;
    const singleNear = near.find((c) => c && c.kind === 'single') ?? null;
    if (scopeNear) {
      // Непрерывный перечень областей вокруг примыкающей: связаны только «,» и «и».
      const idx = constructs.indexOf(scopeNear);
      const linked = (a: Construct, b: Construct): boolean => toks.slice(a.to, b.from).every((k, n) => {
        const j = a.to + n;
        if (k.t === 'punct') return k.p === ',' || k.p === ';' || !!k.glue;
        return k.t === 'word' && !used[j] && CONNECTORS.has(k.w) && !JOIN_BREAK.has(k.w);
      });
      let lo = idx;
      let hi = idx;
      while (lo > 0 && constructs[lo - 1]!.kind !== 'single' && linked(constructs[lo - 1]!, constructs[lo]!)) lo--;
      while (hi < constructs.length - 1 && constructs[hi + 1]!.kind !== 'single' && linked(constructs[hi]!, constructs[hi + 1]!)) hi++;
      const run = constructs.slice(lo, hi + 1);
      if (wd.from > run[0]!.from && wd.to <= run[run.length - 1]!.from) return { kind: 'refused', reason: 'weekday_scope', seats };
      if (scopes.some((c) => !run.includes(c))) return { kind: 'refused', reason: 'weekday_scope', seats };
      if (run.length > 1 && (run.some((c) => c.kind === 'span') || run.some((c) => c.whole))) {
        return { kind: 'refused', reason: 'weekday_scope', seats };
      }
    } else if (wd.quant && singles.length > 0) {
      // «3 августа, каждый вторник» — правило без области рядом с датой, а не
      // уточнение к ней: какие вторники, не сказано.
      return { kind: 'refused', reason: 'weekday_scope', seats };
    } else if (scopes.length > 0) {
      // День недели у отдельной даты (или ни у чего) рядом с отрезком/месяцем.
      if (singleNear) {
        for (const p of singles) {
          const r = resolvePoint(p, yearFor);
          if ('date' in r && !wd.days.includes(weekdayOf(r.date))) return { kind: 'refused', reason: 'weekday_mismatch', date: r.date };
        }
      }
      return { kind: 'refused', reason: 'weekday_scope', seats };
    }
  }

  // 15. Вопросы: месяц без дней и без дней недели; дни недели без месяца.
  if (!wd) {
    const vagueMonth = bareMonths.find((b) => !b.whole);
    if (vagueMonth) {
      const year = vagueMonth.y ?? yearFor(vagueMonth.m);
      const fromDay = year === Y0 && vagueMonth.m === M0 ? D0 : 1;
      return { kind: 'ask', what: 'month_scope', month: vagueMonth.m, year, fromDay, seats };
    }
  }
  if (wd && !scoped && singles.length === 0) {
    return { kind: 'ask', what: 'weekday_month', days: wd.days, seats };
  }

  // 16. Даты с годом.
  const singleDates: string[] = [];
  for (const p of singles) {
    const r = resolvePoint(p, yearFor);
    if ('bad' in r) return { kind: 'refused', reason: 'bad_date', text: r.bad };
    singleDates.push(r.date);
  }
  singleDates.push(...relative.map((r) => r.date));
  const expanded: string[] = [];
  const filter = wd ? wd.days : undefined;
  const ruleParts: Array<{ kind: 'span'; from: string; to: string } | { kind: 'month'; y: number; m: number; whole: boolean }> = [];
  for (const s of spans) {
    let fromYear = s.from.y;
    if (fromYear === null && s.to.y !== null) {
      const fm = s.from.m!;
      const tm = s.to.m!;
      fromYear = fm < tm || (fm === tm && s.from.d <= s.to.d) ? s.to.y : s.to.y - 1;
    }
    const a = resolvePoint({ ...s.from, y: fromYear }, yearFor);
    if ('bad' in a) return { kind: 'refused', reason: 'bad_date', text: a.bad };
    const toYear = s.to.y ?? Number(a.date.slice(0, 4));
    let b = resolvePoint({ ...s.to, y: toYear }, yearFor);
    if ('bad' in b) return { kind: 'refused', reason: 'bad_date', text: b.bad };
    if (s.to.y === null && b.date < a.date && s.to.m! < Number(a.date.slice(5, 7))) {
      b = resolvePoint({ ...s.to, y: toYear + 1 }, yearFor);
      if ('bad' in b) return { kind: 'refused', reason: 'bad_date', text: b.bad };
    }
    if (b.date < a.date) {
      return { kind: 'refused', reason: 'range_reversed', from: a.date, to: b.date, seats, startMonthInherited: s.fromInherited === true };
    }
    const days = Math.round((Date.parse(b.date) - Date.parse(a.date)) / 86_400_000) + 1;
    if (days > 366) return { kind: 'refused', reason: 'too_many', count: days, seats, parts: [] };
    // Отрезок короче недели с днями недели: его концы названы, и они обязаны
    // быть этими днями («выходные 2-4 июля» — пятница выпала бы молча).
    if (filter && days < 7) {
      const off = [a.date, b.date].find((d) => !filter.includes(weekdayOf(d)));
      if (off) return { kind: 'refused', reason: 'weekday_mismatch', date: off };
    }
    expanded.push(...datesInRange(a.date, b.date, filter));
    ruleParts.push({ kind: 'span', from: a.date, to: b.date });
  }
  for (const bm of bareMonths) {
    const y = bm.y ?? yearFor(bm.m);
    expanded.push(...datesInRange(iso(y, bm.m, 1), iso(y, bm.m, daysIn(y, bm.m)), filter));
    ruleParts.push({ kind: 'month', y, m: bm.m, whole: bm.whole });
  }

  if (filter && !scoped) {
    for (const d of singleDates) {
      if (!filter.includes(weekdayOf(d))) return { kind: 'refused', reason: 'weekday_mismatch', date: d };
    }
  }

  const expandedSet = new Set(expanded);
  const inside = singleDates.find((d) => expandedSet.has(d));
  if (inside) return { kind: 'refused', reason: 'exclusion', word: inside };

  // 17. Прошедшее: раскрытия молча сужаются, названные даты называются.
  const pastNamed = [...new Set(singleDates.filter((d) => d < today))].sort();
  const pastDropped = [...new Set(expanded.filter((d) => d < today))].sort();
  const dates = [...new Set([...singleDates, ...expanded].filter((d) => d >= today))].sort();
  if (dates.length === 0) {
    if (pastNamed.length > 0 || pastDropped.length > 0) {
      return { kind: 'refused', reason: 'past_only', named: pastNamed, dropped: pastDropped, today, seats };
    }
    return { kind: 'refused', reason: 'not_understood' };
  }

  // 18. Пределы.
  const lastDate = horizonLastDate(today);
  const far = dates.find((d) => d > lastDate);
  if (far) return { kind: 'refused', reason: 'too_far', date: far, lastDate };
  if (dates.length > MAX_DATES_PER_PROPOSAL) {
    return { kind: 'refused', reason: 'too_many', count: dates.length, seats, parts: splitByMonth(dates, today, filter) };
  }
  // «всего 8 мест» на две даты и больше: места ставятся на каждый выезд.
  if (seats !== null && dates.length > 1 && toks.some((k) => k.t === 'word' && k.w === 'всего')) {
    return { kind: 'refused', reason: 'seats_total', seats, count: dates.length };
  }

  const weekdayWords = wd !== null && wd.named;
  const rule = ruleText(ruleParts, wd ? wd.days : null, singleDates.filter((d) => d >= today));
  return { kind: 'proposal', dates, pastDropped, pastNamed, seats, tour, priceMentioned, weekdayWords, rule };
}

/**
 * Цепочки слов тура: подряд идущие несъеденные слова (между ними — связки,
 * дефис внутри слова, число названия), начало и конец — слово-кандидат.
 * Запятая, дата, место разрывают цепочку.
 */
function tourChains(
  toks: Tok[], used: boolean[], titleNum: boolean[], isCandidate: (i: number) => boolean,
  special: (w: string) => boolean, titles: Array<{ t: ChatTour; words: string[] }>,
): Array<{ from: number; to: number; words: Array<{ w: string; i: number }> }> {
  const out: Array<{ from: number; to: number; words: Array<{ w: string; i: number }> }> = [];
  let cur: { from: number; to: number; words: Array<{ w: string; i: number }> } | null = null;
  const inChain = (i: number): 'word' | 'glue' | null => {
    const k = toks[i]!;
    // «для» — место тура перед цепочкой («для Горелого»), а не её слово.
    if (k.t === 'word' && k.w === 'для') return null;
    // Порядковое, число словом, «после», «к» — слово цепочки, только если оно
    // буквально в названии («Поход к водопадам», «Прогулка после обеда»).
    if (isCandidate(i)) {
      const w = (k as { w: string }).w;
      if (!special(w) || titles.some((e) => e.words.includes(w))) return 'word';
    }
    if (k.t === 'punct' && k.glue) return 'glue';
    if (titleNum[i]) return 'glue';
    // Связка внутри цепочки — только та, что есть в названии («Сплав по реке Быстрая»).
    if (k.t === 'word' && !used[i] && CONNECTORS.has(k.w) && titles.some((e) => e.words.includes(k.w))) return 'glue';
    if (k.t === 'word' && !used[i] && k.w === 'и') return 'glue';
    return null;
  };
  for (let i = 0; i <= toks.length; i++) {
    const role = i < toks.length ? inChain(i) : null;
    if (role === 'word') {
      if (!cur) cur = { from: i, to: i + 1, words: [] };
      cur.words.push({ w: (toks[i] as { w: string }).w, i });
      cur.to = i + 1;
      continue;
    }
    if (role === 'glue' && cur) continue;
    if (cur) { out.push(cur); cur = null; }
  }
  return out;
}

/** Область фразы словами для подсказки исключения; несколько или ни одной — null. */
function scopeWords(spans: Span[], months: BareMonth[], y0: number, m0: number): string | null {
  if (spans.length + months.length !== 1) return null;
  const yr = (m: number, y: number | null): string => (y !== null && y !== (m >= m0 ? y0 : y0 + 1) ? ` ${y}` : '');
  if (months.length === 1) {
    const bm = months[0]!;
    return `${GEN_MONTH[bm.m - 1]}${yr(bm.m, bm.y)}`;
  }
  const s = spans[0]!;
  if (s.from.m === null || s.to.m === null) return null;
  return s.from.m === s.to.m && s.from.y === s.to.y
    ? `с ${s.from.d} по ${s.to.d} ${GEN_MONTH[s.to.m - 1]}${yr(s.to.m, s.to.y)}`
    : `с ${s.from.d} ${GEN_MONTH[s.from.m - 1]}${yr(s.from.m, s.from.y)} по ${s.to.d} ${GEN_MONTH[s.to.m - 1]}${yr(s.to.m, s.to.y)}`;
}

/** Правило фразы словами (`DatesProposal.rule`); только перечень дат — null. Месяц не повторяется. */
function ruleText(
  partsIn: Array<{ kind: 'span'; from: string; to: string } | { kind: 'month'; y: number; m: number; whole: boolean }>,
  days: number[] | null, singles: string[],
): string | null {
  const seen = new Set<string>();
  const parts = partsIn.filter((p) => {
    const key = p.kind === 'span' ? `${p.from}/${p.to}` : `${p.y}-${p.m}`;
    if (seen.has(key)) return false;
    seen.add(key);
    return true;
  });
  if (parts.length === 0) return null;
  const dayWords = (d: string): string => {
    const [y, m, dd] = d.split('-').map(Number) as [number, number, number];
    return `${dd} ${GEN_MONTH[m - 1]} ${y}`;
  };
  const span = (from: string, to: string): string => {
    const [y1, m1, d1] = from.split('-').map(Number) as [number, number, number];
    const [y2, m2, d2] = to.split('-').map(Number) as [number, number, number];
    if (y1 === y2 && m1 === m2) return `с ${d1} по ${d2} ${GEN_MONTH[m2 - 1]} ${y2}`;
    return `с ${d1} ${GEN_MONTH[m1 - 1]}${y1 === y2 ? '' : ` ${y1}`} по ${d2} ${GEN_MONTH[m2 - 1]} ${y2}`;
  };
  const months = parts.filter((p): p is { kind: 'month'; y: number; m: number; whole: boolean } => p.kind === 'month');
  let scope: string;
  if (days === null && parts.every((p) => p.kind === 'month')) {
    scope = months.map((p) => `весь ${NOM_MONTH[p.m - 1]} ${p.y}`).join(' и ');
  } else if (months.length === parts.length && new Set(months.map((p) => p.y)).size === 1) {
    const names = months.map((p) => GEN_MONTH[p.m - 1]!);
    const list = names.length === 1 ? names[0]! : `${names.slice(0, -1).join(', ')} и ${names[names.length - 1]}`;
    scope = `${list} ${months[0]!.y}`;
  } else {
    scope = parts.map((p) => (p.kind === 'span' ? span(p.from, p.to) : `${days === null ? `весь ${NOM_MONTH[p.m - 1]}` : GEN_MONTH[p.m - 1]} ${p.y}`))
      .join(' и ');
  }
  const head = days === null ? scope : `${weekdaysPlural(days)} ${scope}`;
  return singles.length > 0 ? `${head}; отдельно: ${singles.map(dayWords).join(', ')}` : head;
}

/** Длинный список дат — по месяцам, словами, которые разбор понимает; не назвать — пусто. */
function splitByMonth(dates: string[], today: string, filter?: number[]): string[] {
  const [y0, m0, d0] = today.split('-').map(Number) as [number, number, number];
  const byMonth = new Map<string, number[]>();
  for (const d of dates) byMonth.set(d.slice(0, 7), [...(byMonth.get(d.slice(0, 7)) ?? []), Number(d.slice(8, 10))]);
  const parts: string[] = [];
  for (const [key, days] of byMonth) {
    const [y, m] = key.split('-').map(Number) as [number, number];
    const first = days[0]!;
    const last = days[days.length - 1]!;
    const yr = y === (m >= m0 ? y0 : y0 + 1) ? '' : ` ${y}`;
    const from = y === y0 && m === m0 ? d0 : 1;
    const gen = GEN_MONTH[m - 1]!;
    const same = (a: number, b: number): boolean =>
      datesInRange(iso(y, m, a), iso(y, m, b), filter).join() === days.map((d) => iso(y, m, d)).join();
    if (filter) {
      const wd = weekdaysPlural(filter);
      if (same(from, daysIn(y, m))) parts.push(`${wd} ${gen}${yr}`);
      else if (first === last) parts.push(`${first} ${gen}${yr}`);
      else if (same(first, last)) parts.push(`${wd} с ${first} по ${last} ${gen}${yr}`);
      else return [];
      continue;
    }
    if (!same(first, last)) return [];
    if (first === from && last === daysIn(y, m)) parts.push(`весь ${NOM_MONTH[m - 1]}${yr}`);
    else if (first === last) parts.push(`${first} ${gen}${yr}`);
    else parts.push(`с ${first} по ${last} ${gen}${yr}`);
  }
  return parts;
}

/** Дни недели для подсказки: «субботы», «выходные», «будни», «вторники и четверги». 0 = пн … 6 = вс. */
const WEEKDAY_PLURAL = ['понедельники', 'вторники', 'среды', 'четверги', 'пятницы', 'субботы', 'воскресенья'];
export function weekdaysPlural(days: number[]): string {
  const set = [...new Set(days)].sort((a, b) => a - b);
  if (set.join() === '5,6') return 'выходные';
  if (set.join() === '0,1,2,3,4') return 'будни';
  const names = set.map((d) => WEEKDAY_PLURAL[d]!);
  return names.length <= 1 ? (names[0] ?? 'субботы') : `${names.slice(0, -1).join(', ')} и ${names[names.length - 1]}`;
}

function resolvePoint(p: Point, yearFor: (m: number) => number): { date: string } | { bad: string } {
  const m = p.m ?? 0;
  if (m < 1 || m > 12) return { bad: p.raw };
  const y = p.y ?? yearFor(m);
  const date = iso(y, m, p.d);
  if (!isCalendarDate(date)) {
    return { bad: /^\d+$/.test(p.raw) || /^\d+ \p{L}/u.test(p.raw) ? `${p.d} ${GEN_MONTH[m - 1]} ${y}` : p.raw };
  }
  return { date };
}

/** День недели даты: 0 = пн … 6 = вс. */
export function weekdayOf(date: string): number {
  const js = new Date(`${date}T00:00:00Z`).getUTCDay();
  return js === 0 ? 6 : js - 1;
}

function shiftDay(date: string, n: number): string {
  return new Date(Date.parse(`${date}T00:00:00Z`) + n * 86_400_000).toISOString().slice(0, 10);
}

function chunkAt(text: string, pos: number): string {
  let a = pos;
  let b = pos;
  while (a > 0 && !/\s/.test(text[a - 1]!)) a--;
  while (b < text.length && !/\s/.test(text[b]!)) b++;
  return text.slice(a, b).replace(/^[,;.]+|[,;.]+$/g, '').slice(0, 40);
}

/**
 * Одно ли это слово во фразе и в названии тура: общее начало в пять букв, а у
 * коротких — все буквы, кроме последней, но не меньше четырёх.
 */
function sameStem(a: string, b: string): boolean {
  const n = Math.min(5, Math.max(4, Math.min(a.length, b.length) - 1));
  return a.length >= n && b.length >= n && a.slice(0, n) === b.slice(0, n);
}

/**
 * Фамилия от слова названия: после общей основы — «ов», «ев», «ин», «ын»,
 * которых в названии нет («Горелову» — «Горелый», «Быстровой» — «Быстрая»,
 * «Авачёву» — «Авачинский»). Это не тур, а человек (пятый ревью).
 */
function surnameLike(w: string, tw: string): boolean {
  let n = 0;
  while (n < w.length && n < tw.length && w[n] === tw[n]) n++;
  if (n < 4) return false;
  // Суффикс фамилии и падежное окончание — и всё: «Авачинскому» (-инск-) —
  // прилагательное места, а не фамилия.
  return /^(?:ов|ев|ин|ын)(?:а|у|ым|ой|ою|ых|ыми|е|ом|ы)?$/u.test(w.slice(n)) && !/^(?:ов|ев|ин|ын)/u.test(tw.slice(n));
}

function titleWordsOf(title: string): string[] {
  return normalizePhrase(title).split(/[^\p{L}\p{N}]+/u).filter(Boolean);
}
/** Слово фразы есть в названии: буквально, а от четырёх букв — и с другим окончанием, но не фамилией. */
function wordInTitle(w: string, titleWords: string[]): boolean {
  return titleWords.includes(w)
    || (w.length >= 4 && titleWords.some((t) => t.length >= 4 && sameStem(w, t) && !surnameLike(w, t)));
}

export type TourMatch =
  | { kind: 'pick'; pick: TourPick; candidates: ChatTour[] }
  | { kind: 'unknown'; words: Array<{ w: string; i: number }> }
  | { kind: 'two'; titles: string[]; word: string };

/**
 * Тур по словам цепочек (шапка, «Тур»). Каждое слово обязано быть в
 * названии; слова от четырёх букв называют тур, короткие только дописывают
 * название. Туры, где есть все называющие слова, — кандидаты.
 */
export function matchTours(words: Array<{ w: string; i: number }>, tours: ChatTour[]): TourMatch {
  const active = tours.filter((t) => t.active);
  if (words.length === 0) {
    if (active.length === 0) return { kind: 'pick', pick: { kind: 'no_tours' }, candidates: [] };
    if (active.length === 1) return { kind: 'pick', pick: { kind: 'one', id: active[0]!.id }, candidates: [] };
    if (active.length > MAX_TOUR_BUTTONS) return { kind: 'pick', pick: { kind: 'name_needed' }, candidates: [] };
    return { kind: 'pick', pick: { kind: 'choose', ids: active.map((t) => t.id) }, candidates: [] };
  }
  const titled = tours.map((t) => ({ t, tw: titleWordsOf(t.title) }));
  const sets = words.map((x) => ({ x, ts: titled.filter((e) => wordInTitle(x.w, e.tw)).map((e) => e.t) }));
  const unknown = sets.filter((s) => s.ts.length === 0).map((s) => s.x);
  if (unknown.length > 0) return { kind: 'unknown', words: unknown };
  const naming = sets.filter((s) => s.x.w.length >= 4);
  let cand = naming.length > 0
    ? naming.reduce((acc, s) => acc.filter((t) => s.ts.includes(t)), naming[0]!.ts)
    : tours.slice();
  if (cand.length === 0) {
    const titlesOut = [...new Set(naming.flatMap((s) => s.ts.map((t) => t.title)))].slice(0, 4);
    const first = naming.find((s) => s.ts.length === 1) ?? naming[0]!;
    return { kind: 'two', titles: titlesOut, word: first.x.w };
  }
  const short = sets.filter((s) => s.x.w.length < 4);
  const withShort = cand.filter((t) => short.every((s) => s.ts.includes(t)));
  if (withShort.length === 0) {
    return { kind: 'unknown', words: short.filter((s) => !cand.some((t) => s.ts.includes(t))).map((s) => s.x) };
  }
  cand = withShort;
  const topActive = cand.filter((t) => t.active);
  const topHidden = cand.filter((t) => !t.active).map((t) => t.title);
  if (topActive.length === 0) return { kind: 'pick', pick: { kind: 'hidden', titles: topHidden }, candidates: cand };
  if (topActive.length === 1 && topHidden.length === 0) return { kind: 'pick', pick: { kind: 'one', id: topActive[0]!.id }, candidates: cand };
  const ids = topActive.slice(0, MAX_TOUR_BUTTONS).map((t) => t.id);
  return { kind: 'pick', pick: topHidden.length > 0 ? { kind: 'choose', ids, hidden: topHidden } : { kind: 'choose', ids }, candidates: cand };
}
