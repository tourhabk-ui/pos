export interface FishSpecies {
  id: string;
  name: string;
  nameLatin: string;
  color: string;
  shortDesc: string;
  season: string;
  seasonMonths: number[]; // 1-12
  recordKg: string;
  methods: string[];
  habitat: string;
  funFact: string;
  patterns: RegExp[];
  /**
   * Изображение вида для описания — только из public/images (CLAUDE.md §3),
   * чужие хосты запрещены. Нет изображения — поля нет, и страница показывает
   * значок, а не заглушку с чужой рыбой. `alt` называет, ЧТО на картинке,
   * включая род изображения: рисунок не выдаётся за снимок с реки.
   */
  image?: { src: string; alt: string };
  /**
   * Подробный разбор вида: разделы с подзаголовками и абзацами (12.11,
   * владелец прислал разбор кеты). Нет разбора — поля нет, страница вида
   * показывает только карточку. Текст — из присланного, не дописывается.
   */
  guide?: FishGuideSection[];
}

export interface FishGuideSection {
  heading: string;
  /** Пункт раздела: подзаголовок (если есть) и текст. */
  items: Array<{ title?: string; text: string }>;
  /** Список советов вместо подзаголовков — нумерованным перечнем. */
  list?: boolean;
}

