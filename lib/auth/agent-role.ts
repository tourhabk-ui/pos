export const AGENT_MONEY_CLOSED =
  'Раздел закрыт: роль агента заморожена, вознаграждение не начисляется, пока Ведар не принимает оплату.';

/** Просит ли регистрация роль агента — одной ролью или среди нескольких. */
export function requestsAgentRole(role: string | undefined, roles: readonly string[] | undefined): boolean {
  return role === 'agent' || (roles ?? []).includes('agent');
}
