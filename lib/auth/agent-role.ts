/**
 * Открыта ли роль агента — одно правило на регистрацию и кабинет (#3212,
 * слово владельца 10.11: «агента заморозить до включения оплаты»).
 *
 * Агент продаёт туры за вознаграждение, а вознаграждение начисляется только с
 * оплаты через платформу. Пока Ведар оплату не принимает
 * (`platformAcceptsPayments()`, решение владельца 05.10), начислять нечего:
 * роль, обещающая деньги, обещала бы то, чего нет. Поэтому правило выведено
 * из выключателя оплаты, а не заведено своим флагом — откроют оплату, и роль
 * откроется тем же коммитом, без правок кода роли.
 *
 * Что закрыто, пока роль заморожена:
 *  - новая регистрация агентом (пункта нет на странице входа, сервер
 *    отвечает отказом с причиной);
 *  - в кабинете действующего агента — всё, что говорит о вознаграждении:
 *    плитки, столбцы, подписи, разделы «Комиссии» и «Рефералы» (и по
 *    прямому адресу).
 * Что остаётся: вход и кабинет у уже зарегистрированных, поиск туров,
 * клиенты, задачи и бронь за клиента («Сделки»).
 */
import { platformAcceptsPayments } from '@/lib/payments/accepting';

export function agentRoleOpen(): boolean {
  return platformAcceptsPayments();
}

