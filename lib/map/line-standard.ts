/**
 * Четвёртый род линии — рассчитанный автомобильный путь (владелец 28.08,
 * PR после bake-off по маршрутизации). Сознательно ВНЕ `TrackFidelity`/
 * `trackLine()`/`gradeFromSource()`: это не снятый трек (никто не шёл), не
 * набросок по путевым точкам (не построен по places), не служебная связка
 * (это настоящий маршрут доехать) — а результат расчёта маршрутизатора для
 * конкретной пары «откуда → куда» в конкретный момент. У существующих трёх
 * родов линия называет ПРОИСХОЖДЕНИЕ геометрии маршрута в базе; здесь линия
 * называет, что её только что посчитал внешний сервис, а не сняли ногами.
 *
 * Сплошная — line действительно идёт по дорожному графу, это не догадка и
 * не прямая между точками. Синяя — не пересекается ни с зелёным (снятый
 * трек), ни с серым пунктиром (набросок/связка), и по конвенции карт читается
 * как «дорожное направление», не как «пешая тропа, по которой кто-то шёл».
 * Подпись обязательна и НЕИЗМЕННА — экран может дополнить её временем и
 * трафиком, но не вправе укоротить или снять: без слов вид один в один
 * похож на самый доверенный род линии из трёх (толстая сплошная).
 */
export interface CalculatedCarLine {
  kind: 'calculated_car';
  style: LineStyle;
  title: 'Автомобильный путь, рассчитанный по дорожной сети';
  caption: string;
}

const CALCULATED_CAR_CAPTION =
  'Автомобильный путь рассчитан по дорожной сети. Это не снятый трек и не пеший маршрут.';

export function calculatedCarLine(): CalculatedCarLine {
  return {
    kind: 'calculated_car',
    style: { color: '#2563EB', weight: 4 },
    title: 'Автомобильный путь, рассчитанный по дорожной сети',
    caption: CALCULATED_CAR_CAPTION,
  };
}
