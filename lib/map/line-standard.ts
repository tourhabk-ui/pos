/**
 * lib/map/line-standard.ts
 *
 * Стандарт линии на карте: линия называет своё происхождение видом.
 *
 * ── Зачем ──────────────────────────────────────────────────────────────────
 *
 * На карте линия — это обещание. Сплошная зелёная в четыре пикселя читается
 * как «здесь идут», и человек по ней пойдёт. Поэтому вид линии обязан
 * соответствовать тому, откуда она взялась, а не тому, на каком экране
 * нарисована.
 *
 * До этого правило жило на одном экране из трёх. «На маршруте» уже различал
 * снятый трек и набросок (миграция 168 строит geometry прямыми между точками
 * у полутора сотен маршрутов), а карточка маршрута рисовала ту же ломаную
 * сплошной красной в четыре пикселя, и планер соединял дни плана в разных
 * зонах — сотни километров по прямой через хребты — сплошной оранжевой,
 * подписанной «Маршрут».
 *
 * Одно правило на трёх экранах, реализованное трижды, — это три правила.
 * Разошлись они предсказуемо.
 *
 * ── Три рода линий ─────────────────────────────────────────────────────────
 *
 *   ТРЕК       — снятый путь. Сплошная, зелёная, толстая. По ней можно идти.
 *   НАБРОСОК   — та же геометрия маршрута, но прямыми между точками.
 *                Пунктир, приглушённая, тонкая. Идти по ней нельзя.
 *   ПОСТРОЕНИЕ — линия, которую никто не снимал и которая путём не является:
 *                подход от человека до тропы, порядок дней плана, связка.
 *                Пунктир, серая, тонкая — и НЕ называется маршрутом.
 *
 * Между вторым и третьим разница не в виде, а в природе: набросок обещает
 * маршрут и лжёт о его форме; построение маршрутом быть и не пытается.
 * Поэтому у построения отдельная функция и обязательное честное имя.
 */

import {
  trackFidelity, trackFidelityLabel, trackFidelityStyle,
  type LatLng, type TrackFidelity,
} from '@/lib/routes/track-fidelity';

export interface LineStyle {
  color: string;
  weight: number;
  dashArray?: string;
}

export interface TrackLine {
  style: LineStyle;
  fidelity: TrackFidelity;
  /**
   * Что сказать словами под картой. Пустая строка — говорить нечего:
   * снятый трек не нуждается в оговорке.
   *
   * Вид линии несёт то же самое, но вид читается не всеми и не всегда:
   * на маленькой карточке пунктир от сплошной отличит не каждый глаз.
   * Подпись — не дубль, а второй канал того же факта.
   */
  caption: string;
}

/**
 * Линия маршрута: вид и подпись по происхождению геометрии.
 *
 * Единственный способ нарисовать геометрию маршрута. Собирать стиль руками
 * запрещено — именно так правило и разъехалось по экранам.
 */
/**
 * Источники, которые по своей природе НЕ являются снятым путём.
 *
 * `waypoints_synthetic` — миграция 168: линия построена прямыми между
 * путевыми точками. Это набросок по определению, сколько бы точек в нём ни
 * оказалось.
 */
export const SYNTHETIC_SOURCES = new Set([
  'waypoints_synthetic', 'synthetic',
  // Проложено A* по графу дорог (`/api/cron/route-lay`). Это ПОСТРОЕНИЕ:
  // алгоритм соединил точки по дорожному графу, никто по нему не шёл.
  //
  // Перепись 17.08 нашла две такие линии — и нашла заодно расхождение: в
  // lib/routes/twins.ts этот слог уже считался синтетикой, а здесь был
  // неизвестен и попадал под плотностную эвристику. У линии с частыми
  // вершинами эвристика даёт «снятый трек», то есть сплошную зелёную в
  // четыре пикселя — приглашение идти по дороге, которую никто не проверял.
  //
  // Один слог, два модуля, два ответа — ровно тот класс, ради которого §12 и
  // писался. Реестр здесь один, twins берёт его отсюда.
  'road_graph_astar',
]);

/**
 * Источники снятого пути: кто-то прошёл и записал.
 *
 * Список замкнутый: неизвестное имя источника НЕ считается треком. Ошибиться
 * в эту сторону дороже — сплошная линия зовёт идти.
 */
const SURVEYED_SOURCES = new Set([
  'osm', 'visitkamchatka', 'kml_inbox', 'gpx',
  // Публичная GPS-запись туриста с openstreetmap.org/traces. Её приносит
  // ежедневный `cron-osm-traces` и кладёт скрытой на ревью.
  //
  // Это самое честное, что платформа получает: человек прошёл и записал.
  // Слог при этом стандарту известен НЕ БЫЛ — он писался «osm-trace», а здесь
  // значился «osm». Незнакомое имя проваливалось в плотностную эвристику, то
  // есть род настоящего трека определялся догадкой при наличии записи.
  // Тот же класс, что `road_graph_astar` выше, только ценой наоборот:
  // там гадание завышало набросок, здесь — могло занизить настоящий путь.
  'osm-trace',
]);

/**
 * Источник ЗАПИСАН, но снятым путём не является: линия пришла импортом с
 * чужого сайта, и никто по ней не шёл.
 *
 * ── Решение владельца 17.08 ────────────────────────────────────────────────
 *
 * До этого дня `external` (и его прежний слог `idilesom`) числился снятым
 * треком — 259 линий из 301, то есть восемь маршрутов из десяти получали
 * право обещать ведение по линии просто потому, что их скачал скрейпер.
 * Доказательства, что по ним кто-то прошёл, у платформы нет.
 *
 * Цена ошибки несимметрична. Занижение стоит того, что человек пойдёт
 * осторожнее; завышение — сплошной зелёной в четыре пикселя через весь край,
 * какую владелец увидел на Козельском.
 *
 * ── Почему это отдельное множество, а не просто «убрать из снятых» ─────────
 *
 * Убрать было бы мало: неизвестный слог проваливается в плотностную
 * эвристику, а у плотной скрейп-линии она отвечает «снятый трек». То есть
 * понижение отменил бы угадыватель. Здесь род назначается ЯВНО — `unknown`,
 * и гадать не о чем.
 *
 * И это не то же самое, что «источника нет»: источник есть, мы его знаем, мы
 * просто не считаем его доказательством. Разницу обязаны слышать и слова —
 * см. `geometrySourceLabel`.
 */
export const UNVERIFIED_SOURCES = new Set([
  'external',
  // Прежний слог того же поставщика. Миграция 871 обезличила значения в базе,
  // но в полевых пакетах на телефонах лежат снимки, снятые ДО неё, и слог в
  // них уже не изменится. Забыв его здесь, мы дали бы сохранённой линии род
  // по плотности — то есть ровно то обещание, которое здесь снимается, и
  // именно там, где связи нет и переспросить нечего.
  'idilesom',
]);

/**
 * Вид линии по её геометрии и, если он записан, по ЗАПИСАННОМУ источнику.
 *
 * ── Почему источник важнее плотности ───────────────────────────────────────
 *
 * До 11.08 род линии определяла одна эвристика — плотность точек: часто
 * стоят, значит снимали. Замер (проба 55) показал, чего она стоит:
 *
 *   источник записан у 295 записей из 301 — idilesom 257, waypoints_synthetic
 *   19, osm 13, visitkamchatka 6, не указан 6;
 *   эвристика расходится с записью в СЕМИ случаях.
 *
 * Из этих семи один опасен: «Вулкан Жупановский» — синтетика, но точек в ней
 * столько, что плотность выдаёт набросок за снятый трек. Сплошная зелёная в
 * четыре пикселя означает «здесь идут», и это ровно та ложь, ради которой
 * писался §12. Остальные шесть — настоящие треки, нарисованные пунктиром из-за
 * редких точек: ошибка в сторону осторожности, но всё равно ошибка.
 *
 * Эвристика в целом работает — 294 из 301. Но она гадает там, где можно
 * ЗНАТЬ, и одной опасной ошибки достаточно, чтобы спрашивать запись.
 *
 * ── Три исхода вместо двух ─────────────────────────────────────────────────
 *
 * Источник известен и синтетический  → набросок, чем бы ни была плотность
 * Источник известен и снятый         → трек
 * Источника нет (шесть записей)      → эвристика, но сказать словами, что
 *                                      происхождение неизвестно
 *
 * Третий исход — не лишняя вежливость. Два вида линии на три состояния
 * означали бы, что «неизвестно» рисуется как одно из известных, то есть
 * неизвестность выдаётся за знание. Тот же класс, что `Number(null) === 0`.
 */
export function trackLine(
  coords: LatLng[] | null | undefined,
  source?: string | null,
): TrackLine | null {
  if (!coords || coords.length < 2) return null;

  if (source && SYNTHETIC_SOURCES.has(source)) {
    return {
      style: trackFidelityStyle('sketch'),
      fidelity: 'sketch',
      caption: 'Набросок: линия построена прямыми между точками',
    };
  }
  if (source && SURVEYED_SOURCES.has(source)) {
    return { style: trackFidelityStyle('surveyed'), fidelity: 'surveyed', caption: '' };
  }
  // Источник записан, но доказательством не служит. Род назначается ЯВНО:
  // отдать такую линию плотностной эвристике значило бы вернуть ей звание
  // трека — у скрейпа вершины частые, и угадыватель отвечает «снятый».
  if (source && UNVERIFIED_SOURCES.has(source)) {
    return {
      style: trackFidelityStyle('unknown'),
      fidelity: 'unknown',
      caption: 'Линия пришла импортом — что по ней ходят, никто не подтверждал',
    };
  }

  // Источника нет или он незнаком. Плотность — единственное, что осталось.
  const fidelity = trackFidelity(coords);

  // Разница между «спросили и не нашли» и «не спрашивали» — не педантизм.
  // Пока экраны не начнут передавать источник, аргумента не будет вовсе, и
  // подпись «происхождение не записано» появилась бы у ВСЕХ линий, включая
  // 295 записей, у которых источник есть. Это объявило бы неизвестным то,
  // чего мы просто не спросили, — тот же класс, что `Number(null) === 0`,
  // только наоборот: догадка о незнании вместо догадки о знании.
  //
  //   undefined — вызывающий не спрашивал: ведём себя как прежде
  //   null      — спросили, записи нет: говорим об этом словами
  const askedAndMissing = source === null;

  return {
    style: trackFidelityStyle(fidelity),
    fidelity,
    caption: fidelity === 'sketch'
      ? trackFidelityLabel(fidelity)
      : askedAndMissing
        ? 'Происхождение линии не записано — вид выбран по плотности точек'
        : '',
  };
}

/**
 * Род линии ТОЛЬКО по записанному источнику — для списков.
 *
 * В списке выбора маршрута (каталог, поиск) координаты линии не загружаются —
 * судить по плотности нечем. Источник же дешёв: он лежит строкой в записи.
 *
 * `null` — источник не записан или незнаком: судить нечем, и это состояние
 * обязано остаться видимым, а не притвориться одним из известных. Замкнутые
 * множества источников — те же, что у trackLine: правило одно.
 *
 * `'unknown'` — источник записан и знаком, но снятым путём не является
 * (`UNVERIFIED_SOURCES`). Это ЗНАНИЕ, а не его отсутствие: мы знаем, откуда
 * линия, и знаем, что доказательством она не служит. `null` здесь читался бы
 * как «не спрашивали».
 */
export function gradeFromSource(source: string | null | undefined): TrackFidelity | null {
  if (!source) return null;
  if (SYNTHETIC_SOURCES.has(source)) return 'sketch';
  if (SURVEYED_SOURCES.has(source)) return 'surveyed';
  if (UNVERIFIED_SOURCES.has(source)) return 'unknown';
  return null;
}

/**
 * Как назвать происхождение линии ЧЕЛОВЕКУ.
 *
 * Карточка качества данных печатала записанный источник как есть: «источник:
 * idilesom». Владелец увидел это в поле 17.08 и потребовал убрать. Требование
 * справедливо вдвойне.
 *
 * Во-первых, это имя чужого сайта внутри нашего экрана. Турист не покупал у
 * них, не знает их и не должен читать их название, стоя на тропе.
 *
 * Во-вторых — и это важнее — слово `idilesom` не отвечает на вопрос, ради
 * которого карточка существует. Человек спрашивает: можно ли идти по этой
 * линии. Ответ на него — род линии, а не поставщик: снятый путь или прямые
 * между точками. Слог из внутреннего справочника не говорит ни того, ни
 * другого; он говорит только, что кто-то что-то импортировал.
 *
 * Поэтому наружу идёт РОД, а слог остаётся внутри — он ключ классификации
 * (`gradeFromSource`) и диагностика для админки, а не текст для поля.
 */
export function geometrySourceLabel(source: string | null | undefined): string {
  const grade = gradeFromSource(source);
  if (grade === 'surveyed') return 'снятый трек — кто-то прошёл и записал';
  if (grade === 'sketch') return 'набросок: прямые между точками маршрута';
  // «Записан, но не доказательство» и «не записан вовсе» — разные состояния,
  // и человеку они говорят разное. Первому есть что предъявить (линия откуда-то
  // взялась, её можно проверить и повысить), второму — нечего. Слить их в одну
  // фразу значило бы соврать в обе стороны сразу.
  if (source && UNVERIFIED_SOURCES.has(source)) {
    return 'линия пришла импортом — что по ней ходят, никто не подтверждал';
  }
  return 'источник не записан — вид выбран по плотности точек';
}

