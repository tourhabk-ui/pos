/**
 * lib/map/line-standard.ts
 *
 * Стандарт линии на карте: линия называет своё происхождение видом.
 *
 * ── Зачем ──────────────────────────────────────────────────────────────────
 *
 * На карте линия — это обещание. Сплошная зелёная в четыре пикселя читается
 * как «здесь идут», и человек по ней пойдёт. Поэтому вид линии обязан
 * соответствовать тому, откуда она взялась, а не тому, на каком экране
 * нарисована.
 *
 * До этого правило жило на одном экране из трёх. «На маршруте» уже различал
 * снятый трек и набросок (миграция 168 строит geometry прямыми между точками
 * у полутора сотен маршрутов), а карточка маршрута рисовала ту же ломаную
 * сплошной красной в четыре пикселя, и планер соединял дни плана в разных
 * зонах — сотни километров по прямой через хребты — сплошной оранжевой,
 * подписанной «Маршрут».
 *
 * Одно правило на трёх экранах, реализованное трижды, — это три правила.
 * Разошлись они предсказуемо.
 *
 * ── Три рода линий ─────────────────────────────────────────────────────────
 *
 *   ТРЕК       — снятый путь. Сплошная, зелёная, толстая. По ней можно идти.
 *   НАБРОСОК   — та же геометрия маршрута, но прямыми между точками.
 *                Пунктир, приглушённая, тонкая. Идти по ней нельзя.
 *   ПОСТРОЕНИЕ — линия, которую никто не снимал и которая путём не является:
 *                подход от человека до тропы, порядок дней плана, связка.
 *                Пунктир, серая, тонкая — и НЕ называется маршрутом.
 *
 * Между вторым и третьим разница не в виде, а в природе: набросок обещает
 * маршрут и лжёт о его форме; построение маршрутом быть и не пытается.
 * Поэтому у построения отдельная функция и обязательное честное имя.
 */

import {
  trackFidelity, trackFidelityLabel, trackFidelityStyle,
  type LatLng, type TrackFidelity,
} from '@/lib/routes/track-fidelity';

export interface LineStyle {
  color: string;
  weight: number;
  dashArray?: string;
}

export interface TrackLine {
  style: LineStyle;
  fidelity: TrackFidelity;
  /**
   * Что сказать словами под картой. Пустая строка — говорить нечего:
   * снятый трек не нуждается в оговорке.
   *
   * Вид линии несёт то же самое, но вид читается не всеми и не всегда:
   * на маленькой карточке пунктир от сплошной отличит не каждый глаз.
   * Подпись — не дубль, а второй канал того же факта.
   */
  caption: string;
}

/**
 * Линия маршрута: вид и подпись по происхождению геометрии.
 *
 * Единственный способ нарисовать геометрию маршрута. Собирать стиль руками
 * запрещено — именно так правило и разъехалось по экранам.
 */
export function trackLine(coords: LatLng[] | null | undefined): TrackLine | null {
  if (!coords || coords.length < 2) return null;
  const fidelity = trackFidelity(coords);
  return {
    style: trackFidelityStyle(fidelity),
    fidelity,
    caption: trackFidelityLabel(fidelity),
  };
}

/**
 * Вид линии-построения.
 *
 * Серая, тонкая, пунктиром — и это не «менее важная» линия, а линия ДРУГОЙ
 * природы. Подход к тропе идёт по азимуту, порядок дней плана вообще не путь;
 * рисовать их так же, как снятый трек, значило бы обещать проход там, где его
 * никто не проверял.
 */
export function connectorLine(): LineStyle {
  return { color: '#9A9590', weight: 2, dashArray: '6 6' };
}

/**
 * Честное имя для линии-построения.
 *
 * Планер подписывал линию между днями плана словом «Маршрут». Слово решает
 * не меньше вида: человек, увидевший «Маршрут» между Петропавловском и
 * Ключами, поймёт это как путь, а там триста километров и хребет.
 */
export const CONNECTOR_TITLES = {
  approach: 'Выход на тропу',
  planOrder: 'Порядок дней — не маршрут',
} as const;
