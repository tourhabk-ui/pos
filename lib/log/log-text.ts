/**
 * Значение из запроса — в строку лога без переводов строки.
 *
 * CodeQL (js/log-injection, PR #2109, 29.09): имя инструмента из тела
 * запроса MCP печаталось в лог как есть, и «\n[mcp] ...» подделывал бы
 * следующую строку лога. Переводы строки и разделители строк заменяются
 * пробелом, длина ограничена — лог не место для чужого текста целиком.
 *
 * Вторая замена — форма, которую CodeQL узнаёт как очистку лога («\n|\r →
 * пустая строка», #2132, 30.09): замену на пробел он санитайзером не считает
 * и продолжал помечать каждый вызов. После первой замены вторая ничего не
 * меняет — она для анализатора, а не для текста.
 */
export function logText(value: unknown, max = 120): string {
  return String(value ?? '')
    .replace(/[\r\n\u2028\u2029]+/g, ' ')
    .replace(/\n|\r/g, '')
    .slice(0, max);
}
