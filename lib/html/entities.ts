/**
 * lib/html/entities.ts — разворот HTML-сущностей ЗА ОДИН проход.
 *
 * Цепочка из `.replace()` по одной сущности разворачивает текст ДВАЖДЫ: сперва
 * `&amp;` превращается в `&`, а следующий шаг видит уже готовое `&lt;` и делает
 * из него `<`. Исходное `&amp;lt;` — экранированная запись строки `&lt;` —
 * незаметно становится символом `<`. Автор написал ПРО тег, а мы записали тег.
 *
 * Один проход снимает вопрос: то, что появилось при разворачивании, повторно
 * не читается.
 *
 * 23.08.2026 CodeQL напечатал пять находок js/double-escaping — по одной на
 * каждую копию цепочки: паспорта маршрутов, письма, фото Викимедии, импорт
 * операторов, разбор сейсмосводки. Правильная реализация к тому дню уже
 * существовала — внутри lib/services/safety/kvert-vona.ts, не вынесенная
 * наружу, и потому её переписали цепочкой ещё пять раз.
 *
 * Набор сущностей — РОВНО объединение того, что эти шесть мест обрабатывали до
 * выноса. Ничего не добавлено: расширять список надо осознанно, а не заодно с
 * починкой.
 *
 * Неизвестная сущность остаётся как написана. Это третий исход: мы не знаем,
 * что это, и молча выбросить её значило бы потерять текст (§4.0).
 */

const ENTITIES: Record<string, string> = {
  nbsp: ' ',
  amp: '&',
  lt: '<',
  gt: '>',
  quot: '"',
  apos: "'",
  '#39': "'",
  '#039': "'",
  '#33': '!',
  laquo: '«',
  raquo: '»',
  '#171': '«',
  '#187': '»',
  mdash: '—',
  ndash: '–',
};

const ENTITY_RE = /&(nbsp|amp|lt|gt|quot|apos|laquo|raquo|mdash|ndash|#39|#039|#33|#171|#187);/gi;

export function decodeHtmlEntities(s: string): string {
  return s.replace(ENTITY_RE, (whole, name: string) => ENTITIES[name.toLowerCase()] ?? whole);
}

/**
 * Кавычки-ёлочки и длинные тире — к простым знакам.
 *
 * Отдельно от разворота намеренно: это НОРМАЛИЗАЦИЯ, а не декодирование.
 * Паспорта маршрутов приводили «» и — к " и - прямо в цепочке сущностей, из-за
 * чего два разных решения выглядели одним.
 */
export function normalizePunctuation(s: string): string {
  return s.replace(/[«»]/g, '"').replace(/[—–]/g, '-');
}
