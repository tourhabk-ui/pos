/**
 * Стоки эко — исчерпывающий список того, на что польза может быть потрачена.
 *
 * Здесь живёт Закон 6 из docs/ECO.md: **безопасность не продаётся.** Это тот
 * случай, когда токеномика способна убить человека: если за накопленные эко
 * можно снять требование гида, обойти регистрацию в МЧС, попасть на закрытый
 * маршрут или поднять непроверенного оператора в выдаче — платформа начинает
 * продавать риск, оставаясь при этом «платформой безопасности».
 *
 * Поэтому запрет не в промпте и не в договорённости, а в коде: списание
 * возможно только через сток из реестра ниже, а реестр проверяется
 * детерминированным гвардом. Сток, чьё описание задевает контур безопасности,
 * не проходит — тест падает, и мерж не состоится.
 *
 * Логика та же, что у остальных сторожей репо (CLAUDE.md §8): инструмент
 * вместо правила в документе.
 */

export interface EcoSink {
  /** Ключ — попадает в журнал как source списания. */
  key: string;
  label: string;
  /** Что именно получает держатель. */
  description: string;
  /**
   * Максимальная доля чека, которую можно закрыть эко. Ограничение защищает
   * маржу оператора: без потолка эмиссия съедает того, кто её обеспечивает
   * (Закон 5 — эмиссия обеспечена стоком, а сток должен кто-то выдержать).
   */
  maxShareOfCheck: number;
}

export const ECO_SINKS: Record<string, EcoSink> = {
  tour_discount: {
    key: 'tour_discount',
    label: 'Скидка на тур',
    description: 'Часть стоимости тура оператора оплачивается накопленной пользой',
    maxShareOfCheck: 0.3,
  },
  stay_discount: {
    key: 'stay_discount',
    label: 'Скидка на жильё',
    description: 'Часть стоимости проживания оплачивается накопленной пользой',
    maxShareOfCheck: 0.3,
  },
  gear_discount: {
    key: 'gear_discount',
    label: 'Скидка на прокат снаряжения',
    description: 'Часть стоимости аренды снаряжения оплачивается накопленной пользой',
    maxShareOfCheck: 0.5,
  },
};

/**
 * Слова контура безопасности. Сток, который их задевает, отвергается —
 * лучше ложный отказ в новом стоке, чем проданная безопасность.
 *
 * Список намеренно широкий и намеренно про СУТЬ, а не про формулировку:
 * обойти его переименованием — значит осознанно врать, и это уже вопрос не к
 * гварду.
 */
const SAFETY_SENSITIVE = new RegExp(
  [
    'мчс', 'спасат', 'регистрац', 'сос\\b', '\\bsos\\b',
    'гид[а-яё]*\\s+(?:не|без)', 'без\\s+гид', 'сопровожд',
    'закрыт', 'опасн', 'предупрежд', 'тревог', 'алерт',
    'страхов', 'инструктаж', 'допуск', 'проверк[аи]\\s+безопасн',
    'верификац', 'модерац', 'приоритет\\s+в\\s+выдаче', 'подн[а-яё]*\\s+в\\s+выдаче',
  ].join('|'),
  'i',
);

export type SinkVerdict = { ok: true } | { ok: false; reason: string };

/**
 * Проверка стока на совместимость с Законом 6. Чистая функция — под тестом,
 * гоняется по всему реестру, поэтому опасный сток нельзя добавить незаметно.
 */
export function validateSink(sink: EcoSink): SinkVerdict {
  const text = `${sink.key} ${sink.label} ${sink.description}`;
  const hit = text.match(SAFETY_SENSITIVE);
  if (hit) {
    return {
      ok: false,
      reason: `Сток «${sink.label}» задевает контур безопасности («${hit[0]}»). Закон 6: безопасность не продаётся.`,
    };
  }
  if (sink.maxShareOfCheck <= 0 || sink.maxShareOfCheck > 1) {
    return { ok: false, reason: `Некорректная доля чека у стока «${sink.label}»` };
  }
  return { ok: true };
}

/** Известен ли сток и допустим ли он. */
export function resolveSink(key: string): { ok: true; sink: EcoSink } | { ok: false; reason: string } {
  const sink = ECO_SINKS[key];
  if (!sink) {
    return { ok: false, reason: 'Неизвестный способ траты эко' };
  }
  const verdict = validateSink(sink);
  if (!verdict.ok) return { ok: false, reason: verdict.reason };
  return { ok: true, sink };
}

/**
 * Сколько эко примет чек. Потолок доли — не украшение: без него скидка
 * съедает маржу того, кто её обеспечивает.
 */
export function maxEcoForCheck(sink: EcoSink, checkAmountRub: number): number {
  if (checkAmountRub <= 0) return 0;
  return Math.floor(checkAmountRub * sink.maxShareOfCheck);
}
