/**
 * lib/agents/scout-silence.ts — сколько прогонов подряд разведчик молчит.
 *
 * ── Почему одного «причина названа» оказалось мало ────────────────────────
 *
 * У дайджеста восемь точек выхода, где он законно НЕ публикуется: нет свежих
 * RSS, синтез не удался, разделы пусты, проценты без источника, фактчек
 * заглушил, утверждения не подтверждены, близкий повтор, Telegram не принял.
 * Каждая по отдельности — осторожность, а не поломка: лучше промолчать, чем
 * выпустить непроверенное.
 *
 * Но крон при этом возвращает успех. 1–8.08 это уже стоило недели тишины:
 * «крон success ежедневно, а последний дайджест — недельной давности». Тогда
 * починили половину — причину стали писать в журнал и называть в алерте
 * здоровья. 18.08 владелец показал скрин: «Разведчик молчит: последний
 * дайджест 2026-08-01 (17 дн назад)». Семнадцать. При зелёных прогонах.
 *
 * Значит названной причины недостаточно: предупреждение в Telegram читают,
 * когда оно уже среди других, а красный прогон в Actions требует ответа.
 *
 * ── Что здесь считается ───────────────────────────────────────────────────
 *
 * Число прогонов подряд, закончившихся без публикации. Один-два — рабочая
 * осторожность агента. Три подряд означают, что ворота держат его
 * систематически, и разбираться должен человек.
 *
 * Функция ЧИСТАЯ: журнал читает вызывающий. Так её можно проверить без БД, а
 * порог остаётся одним числом в одном месте.
 */

/** Запись журнала прогонов в том виде, в каком её отдаёт agent_run_history. */
export interface RunRow {
  /** 'success' — выпуск ушёл; 'partial' — прогон был, публикации не было. */
  status: string;
}

/**
 * Сколько прогонов подряд (считая с самого свежего) закончились без выпуска.
 *
 * Строки ожидаются в порядке «свежие первыми». Пустой журнал — ноль: «не
 * запускался ни разу» это другая беда, и у неё свой сторож (liveness кронов).
 */
export function countLeadingSkips(rows: RunRow[]): number {
  let n = 0;
  for (const r of rows) {
    if (r.status === 'success') break;
    n += 1;
  }
  return n;
}

/**
 * Сколько молчаний подряд терпим, прежде чем красить прогон.
 *
 * Дайджест суточный, значит три — это трое суток тишины. Меньше нельзя:
 * фактчек-ворота законно срабатывают и два дня подряд, и красный прогон за
 * честную осторожность отучил бы верить красному. Больше — и повторится
 * август: семнадцать дней при зелёных галочках.
 */
export const MAX_SILENT_RUNS = 3;

/**
 * Пора ли краснеть. `sentNow` — ушёл ли выпуск в ЭТОМ прогоне.
 *
 * Текущий прогон считается отдельно от журнала: запись о нём пишется
 * фоново и к моменту ответа может там ещё не появиться. Складывать «что было»
 * и «что сейчас» надёжнее, чем ждать своей же строки.
 */
export function silenceIsCritical(previousSkips: number, sentNow: boolean): boolean {
  if (sentNow) return false;
  return previousSkips + 1 >= MAX_SILENT_RUNS;
}
