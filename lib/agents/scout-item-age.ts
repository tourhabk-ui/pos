/**
 * Возраст материала — ТРИ исхода, а не два (§4.0).
 *
 * 07.09: в выпуск попал релиз DeepSeek R1 (январь 2025) — двадцатимесячная
 * новость под шапкой «AI-дайджест · 7 сентября». Факты верные, ложью была
 * подача. Механизм: разбор ленты брал у элемента ТОЛЬКО заголовок и ссылку,
 * поэтому архивная страница была неотличима от сегодняшней новости, и место,
 * где нельзя сказать «не знаю, когда это вышло», заполнялось допущением «раз
 * в ленте — значит свежее».
 *
 * Асимметрия, которую нельзя «упростить» потом: выбрасываем только то, про
 * что ЗНАЕМ, что оно старое. Дата не пришла или не разобралась — материал
 * остаётся: у телеграм-превью и части фидов даты нет вовсе, и отсев по
 * незнанию молча обезглавил бы эти источники.
 *
 * Дата из будущего доверия не заслуживает (кривой часовой пояс, опечатка в
 * фиде) — это тоже «не знаю», а не «самое свежее».
 */
export type ItemAge = 'fresh' | 'stale' | 'unknown';

/** Окно свежести материала. Дайджест выходит дважды в сутки; две недели — запас для медленных блогов. */
export const MAX_ITEM_AGE_DAYS = 14;

export function classifyItemAge(
  publishedAt: string | undefined,
  nowMs: number,
  maxAgeDays: number = MAX_ITEM_AGE_DAYS,
): ItemAge {
  if (!publishedAt) return 'unknown';
  const t = Date.parse(publishedAt);
  if (!Number.isFinite(t)) return 'unknown';
  if (t > nowMs + 3600_000) return 'unknown';
  return nowMs - t <= maxAgeDays * 86_400_000 ? 'fresh' : 'stale';
}
