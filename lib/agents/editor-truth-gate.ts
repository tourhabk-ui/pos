/** Нижний регистр и «ё» → «е»: основы сравниваются без них. */
function normWord(w: string): string {
  return w.toLowerCase().replace(/ё/g, 'е');
}

const RETELLING_SET: ReadonlySet<string> = new Set(RETELLING_WORDS.map(normWord));

function cyrillicWords(text: string): string[] {
  return (normWord(text).match(/[а-я]+(?:-[а-я]+)*/g) ?? []).flatMap((w) => w.split('-')).filter(Boolean);
}

/**
 * Одна основа у двух слов: общее начало длиной min(5, короткое − 1), но не
 * меньше трёх букв. «Летом» и «лето», «озёрный» и «озеро», «лавины» и
 * «лавин» — одна основа; «камни» и «камчатка», «склон» и «сколько» — нет.
 * Слово из четырёх букв даёт основу только словам своей длины с окончанием
 * (разница не больше трёх букв): иначе «путь» узаконил бы «путешествие».
 */
function sameStem(a: string, b: string): boolean {
  const shorter = Math.min(a.length, b.length);
  const k = Math.min(5, shorter - 1);
  if (k < 3) return false;
  if (shorter <= 4 && Math.abs(a.length - b.length) > 3) return false;
  return a.slice(0, k) === b.slice(0, k);
}

/**
 * Слова текста от пяти букв, у которых нет основы в источнике и которых нет
 * среди слов пересказа. По одному разу, в порядке появления.
 */
export function novelContentWords(text: string, sourceText: string): string[] {
  const source = [...new Set(cyrillicWords(sourceText))];
  const out: string[] = [];
  for (const w of cyrillicWords(text)) {
    if (w.length < 5 || out.includes(w)) continue;
    if (RETELLING_SET.has(w)) continue;
    if (source.some((s) => sameStem(w, s))) continue;
    out.push(w);
  }
  return out;
}

/** Сколько новых слов на текст допускается: одна связка, но не второй факт. */
export const MAX_NOVEL_WORDS = 1;

export function judgeGeneratedDescription(
  text: string,
  source: { facts: string[]; title: string; previous: string | null },
): TruthVerdict {
  const reasons: string[] = [];
  const sourceText = [source.title, ...source.facts, source.previous ?? ''].join('\n');

  const voice = descriptionVoice(text);
  if (voice.voice !== 'plain') {
    reasons.push(`голос «${voice.voice === 'diary' ? 'путевая заметка' : 'впечатление'}»: ${voice.markers.slice(0, 3).join(', ')}`);
  }

  const sourceNumbers = new Set(extractNumbers(sourceText));
  const invented = [...new Set(extractNumbers(text).filter((n) => !numberInSource(n, sourceNumbers)))];
  if (invented.length > 0) {
    reasons.push(`числа не из источника: ${invented.slice(0, 5).join(', ')}`);
  }

  const hazards = HAZARD_STEMS
    .filter((h) => hasStem(text, h.stem) && !hasStem(sourceText, h.stem))
    .map((h) => h.label);
  if (hazards.length > 0) {
    reasons.push(`безопасность не из источника: ${hazards.join(', ')}`);
  }

  const epithets = BANNED_EPITHETS.filter((e) => hasStem(text, e));
  if (epithets.length > 0) {
    reasons.push(`рекламные эпитеты: ${epithets.join(', ')}`);
  }

  const novel = novelContentWords(text, sourceText);
  if (novel.length > MAX_NOVEL_WORDS) {
    reasons.push(`слова не из источника: ${novel.slice(0, 8).join(', ')}`);
  }

  return { ok: reasons.length === 0, reasons };
}
