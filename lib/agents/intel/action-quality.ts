/**
 * Разведка: действие или размышление.
 *
 * ── Откуда правило ─────────────────────────────────────────────────────────
 *
 * Владелец 23.08 прислал выпуск разведки. Находка: демонстрация того, что
 * BLIP замечает на картинке первым — крокодила, лодку или силуэт. Отчёт
 * приписал ей «решает задачу валидации восприятия изображений в туристических
 * маршрутах» и предложил распознавать медведей и камни на фото. Связи с
 * платформой в самой новости нет — она сочинена.
 *
 * Сочинена не моделью, а ПРОМПТОМ. Он требует: «найти фичи, которые можно
 * реализовать у себя», «какую пользовательскую боль это решает», «конкретное
 * действие для TourHab». На вход подаётся что угодно, а ответ обязан быть
 * применимым — это заказ на выдумку (§4.0: промпт не требует того, чего нет
 * в данных).
 *
 * Второй след того же — сами пункты. Два разбора находок эволюции подряд дали
 * 34 из 48 и 33 из 47 вердиктов «шум», и почти все шумные начинались одинаково:
 * «Проанализировать возможность...», «Исследовать применение...», «Оценить
 * стоимость...». Это не действия. Находка САМА уже есть предложение подумать;
 * пункт «подумать над находкой» не добавляет к ней ничего и создаёт вид работы.
 *
 * ── Что здесь считается ────────────────────────────────────────────────────
 *
 * Род пункта по ВЕДУЩЕМУ ГЛАГОЛУ, детерминированно, без модели:
 *
 *   actionable — называет изменение: добавить, включить, перенести, починить;
 *   research   — называет размышление: изучить, исследовать, оценить;
 *   unclear    — глагол не опознан.
 *
 * Третий исход не равен второму и НЕ отбрасывается: незнакомая формулировка
 * может нести дело, и глушить её молча значит повторять ту же беду с другой
 * стороны. Решает вызывающий.
 *
 * Предложить новое («добавить дашборд», «внедрить модуль») разведке МОЖНО и
 * нужно — это её работа. Отсекается только «давайте подумаем».
 */

export type ActionKind = 'actionable' | 'research' | 'unclear';

/**
 * Глаголы размышления. Список явный и закрытый: это судья, а не эвристика,
 * и он должен объяснять свой вердикт одним словом.
 */
const RESEARCH_VERBS = [
  'изучить', 'исследовать', 'проанализировать', 'анализировать',
  'оценить', 'рассмотреть', 'проработать', 'обсудить',
  'ознакомиться', 'сравнить', 'промониторить', 'отслеживать',
] as const;

/** Глаголы дела. Не исчерпывающий — незнакомое уходит в `unclear`, не в шум. */
const ACTION_VERBS = [
  'добавить', 'внедрить', 'реализовать', 'сделать', 'написать', 'завести',
  'починить', 'исправить', 'заменить', 'перенести', 'вынести', 'убрать',
  'удалить', 'включить', 'выключить', 'настроить', 'обновить', 'поднять',
  'ограничить', 'закрыть', 'открыть', 'разметить', 'переименовать',
  'протестировать', 'проверить', 'запустить', 'опубликовать', 'разработать',
  'создать', 'построить', 'интегрировать', 'подключить', 'документировать',
] as const;

/** Снимает приоритет в скобках: «[средний] — Изучить...» → «Изучить...». */
export function stripPriority(raw: string): string {
  return raw
    .replace(/^\s*\[[^\]]*\]\s*/, '')
    .replace(/^\s*[—–-]\s*/, '')
    .trim();
}

/** Первое слово в нижнем регистре, без пунктуации. */
function leadVerb(text: string): string {
  const first = stripPriority(text).split(/[\s,.:;!?()«"]+/).find(Boolean) ?? '';
  return first.toLowerCase().replace(/ё/g, 'е');
}

/**
 * Род пункта. Чистая функция: ни базы, ни модели, ни сети.
 *
 * «Проанализировать возможность интеграции» — размышление, даже если дальше
 * названы наши агенты: возможность анализируют, а не делают.
 */
export function classifyActionItem(raw: string): ActionKind {
  const verb = leadVerb(raw);
  if (!verb) return 'unclear';
  if ((RESEARCH_VERBS as readonly string[]).includes(verb)) return 'research';
  if ((ACTION_VERBS as readonly string[]).includes(verb)) {
    // «Протестировать ВОЗМОЖНОСТЬ интеграции» — то же размышление, только
    // одетое глаголом дела. Судим по дополнению, а не по одному слову.
    // Без \b: в JS граница слова знает только [A-Za-z0-9_], и с кириллицей
    // /\bвозможност/ не совпадает НИКОГДА. Та же грабля описана в
    // unsourcedPercents и claim-signature — третий раз в одном репозитории.
    const body = stripPriority(raw).toLowerCase().replace(/ё/g, 'е');
    if (body.includes('возможност') || body.includes('целесообразност')) return 'research';
    return 'actionable';
  }
  return 'unclear';
}

export interface ActionTriage {
  /** Пункты, которые останутся в выпуске: дело и непонятое. */
  kept: string[];
  /** Отсеянные размышления — считаются и называются, а не исчезают. */
  dropped: string[];
  /** Все пункты были размышлениями: находке нечего предложить. */
  allResearch: boolean;
}

/**
 * Отбор пунктов выпуска.
 *
 * Отсев ВИДЕН: `dropped` возвращается вызывающему, чтобы «пусто» никогда не
 * было неотличимо от «отсеяли всё» (§4.0). Пустой вход — не «всё размышления»:
 * пунктов не было вовсе, и это другое состояние.
 */
export function triageActionItems(items: string[]): ActionTriage {
  const kept: string[] = [];
  const dropped: string[] = [];
  for (const item of items) {
    if (classifyActionItem(item) === 'research') dropped.push(item);
    else kept.push(item);
  }
  return { kept, dropped, allResearch: items.length > 0 && kept.length === 0 };
}
