/**
 * Страж памяти эволюции — детерминированная проверка текста, который едет
 * ИЗ БД В ПРОМПТ решателя (OWASP ASI06, отравление памяти агента).
 *
 * С #904 эволюция читает собственную память: уроки и стратегия из
 * evo_feedback / evo_agent_state подмешиваются в промпт ревью каждый прогон,
 * intel-мост скармливает решателю текст дайджеста, сваренного из внешних RSS.
 * Выход давно под стражей (finding-guard), вход не проверял никто: строка,
 * попавшая в память (через дайджест, вердикт, миграцию данных), ехала в
 * промпт как «выученный урок» без вопросов.
 *
 * Принципы, не кейсы (§8): урок эволюции — короткая внутренняя заметка.
 * Императив «проигнорируй/выполни», URL, секрет или code fence в уроке —
 * это не форма урока, а чужой текст. Такой фрагмент отбрасывается целиком.
 * Для документов-источников (дайджест), где URL легитимны, есть построчный
 * скраб только императивов.
 */

/** Невидимые символы — классический способ спрятать императив от regex. */
const ZERO_WIDTH = /[\u200B-\u200F\u2060\uFEFF\u00AD]/g;

/**
 * Императивы перехвата управления. Ловим КЛАСС (глагол управления промптом/
 * исполнением), а не конкретные фразы.
 */
const INJECTION = new RegExp(
  [
    /ignore\s+(?:(?:all|previous|the|any|your)\s+)*(instructions?|prompts?|rules?)/.source,
    /disregard\s+(all|previous|your)/.source,
    /(про)?игнорируй\s+(?:(?:все|прошлые|свои|любые)\s+)*(инструкци|правил|промпт)/.source,
    /забудь\s+(все\s+|свои\s+)?(инструкци|правил|что)/.source,
    /(выполни|запусти|исполни)\s+(команд|код|скрипт|shell)/.source,
    /(скачай|установи|загрузи)\s/.source,
    /(добавь|вставь|внедри)\s+(в\s+)?(код|файл|промпт)/.source,
    /(отключи|обойди|сними)\s+(проверк|гард|страж|защит|лимит)/.source,
    /system\s+prompt/.source,
  ].join('|'),
  'i',
);

/** Секретоподобное присваивание: ключам/токенам в памяти взяться неоткуда. */
const SECRET_LIKE = /(api[_-]?key|secret|token|password|пароль|bearer)\s*[:=]\s*\S{6,}/i;

/** Потолок по умолчанию: урок длиннее — уже не урок, а вклейка документа. */
export const MAX_MEMORY_ITEM_CHARS = 600;

/**
 * Гард ФРАГМЕНТА памяти (урок, стратегия): чужеродный текст отбрасывается
 * целиком (null), нормальный — возвращается очищенным от невидимых символов
 * и усечённым по потолку. Усечение только для длины, не для лечения:
 * фрагмент с императивом не «подрезается до безопасного», а не допускается.
 */
export function guardMemoryText(raw: unknown, maxChars = MAX_MEMORY_ITEM_CHARS): string | null {
  if (typeof raw !== 'string') return null;
  const text = raw.replace(ZERO_WIDTH, '').trim();
  if (!text) return null;
  if (INJECTION.test(text)) return null;
  if (SECRET_LIKE.test(text)) return null;
  if (/https?:\/\//i.test(text)) return null;
  if (text.includes('```') || /<script/i.test(text)) return null;
  return text.length > maxChars ? `${text.slice(0, maxChars - 1)}…` : text;
}

/**
 * Построчный скраб ДОКУМЕНТА-источника (дайджест intel): URL и длина там
 * легитимны, выбрасывать документ целиком нельзя — но строка с императивом
 * перехвата управления легитимной не бывает и снимается.
 */
export function scrubInjectionLines(doc: string): string {
  return doc
    .replace(ZERO_WIDTH, '')
    .split('\n')
    .filter((line) => !INJECTION.test(line))
    .join('\n');
}
