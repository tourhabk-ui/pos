/**
 * lib/agents/cron-lease.ts — один прогон в окне, сколько бы ни было планировщиков.
 *
 * ── Зачем ────────────────────────────────────────────────────────────────
 *
 * У safety-кронов с 29.08 три возможных источника запуска:
 *
 *  1. расписание GitHub Actions — доставляет 1-4% от запрошенного
 *     (замер 29.08: `safety-ingest` просит 288 прогонов в сутки, получал 2-4);
 *  2. внешний планировщик cron-job.org — заведён владельцем;
 *  3. супервизор контейнера (`start.js`) — всегда жив, пока жив прод.
 *
 * Опираться на первый нельзя: он и есть причина, по которой четыре
 * safety-крона молчали по 4-6 часов. Но просто добавить источников тоже
 * нельзя — Watchdog разошлёт алерт дважды, а sos-events-bridge дважды
 * выпустит одно событие.
 *
 * Аренда решает это на стороне СЕРВЕРА, а не договорённостью между
 * планировщиками: кто первым занял окно, тот и работает. Договорённость
 * держится, пока её помнят и пока никто не завёл четвёртый планировщик;
 * ключ в таблице держится всегда.
 *
 * ── Отказ БД: почему «не смог» здесь значит «работай» ────────────────────
 *
 * §4.0 требует третьего исхода, но не предписывает, что с ним делать —
 * это решает вызывающий, и решает по цене ошибки. Здесь цена
 * несимметрична: лишний прогон сейсмо-ингеста стоит одного HTTP-запроса,
 * пропущенный — незамеченного цунами. Поэтому `unknown` пропускает к
 * работе, и это записано, а не подразумевается.
 *
 * Обратный выбор был бы тихой отменой всей safety-цепочки при первом же
 * сбое соединения с БД — то есть отказ вспомогательного механизма ронял бы
 * основной.
 *
 * ── Чего аренда НЕ делает ────────────────────────────────────────────────
 *
 * Не пишет в `agent_run_history`. Пропуск по занятому окну — не прогон:
 * работу сделал другой планировщик, и его строка уже есть. Своя строка
 * здесь дала бы `cron-idle` серию успехов с нулём сделанного и ложную
 * тревогу «крон работает вхолостую».
 */

import { pool } from '@/lib/db-pool';

/** Исход попытки занять окно. Три, и третий — отдельный (§4.0). */
export type LeaseOutcome =
  /** Окно наше: работать. */
  | 'claimed'
  /** Окно уже занято другим планировщиком: работу делает он, уходим. */
  | 'held'
  /** Проверить не смогли (отказ БД). Работаем — см. разбор в шапке. */
  | 'unknown';

/** Кто пытается занять окно — для разбора, почему сработал не тот, на кого думали. */
export type LeaseClaimant = 'supervisor' | 'external' | 'workflow' | 'manual';

/** Сколько держим историю аренд. Уборка идёт тем же запросом, что и захват. */
export const LEASE_RETENTION_DAYS = 7;

/**
 * Начало окна, выровненное по его длине. Оба планировщика, сработавшие в
 * пределах одного окна, получают ОДИН И ТОТ ЖЕ ключ — на этом и держится
 * замок. Выравнивание от эпохи, а не от первого запуска: иначе у каждого
 * планировщика была бы своя сетка окон и они не пересеклись бы никогда.
 */
export function windowStart(nowMs: number, windowMin: number): Date {
  const ms = Math.max(1, windowMin) * 60_000;
  return new Date(Math.floor(nowMs / ms) * ms);
}

/**
 * Занять окно агента.
 *
 * @param agentId   идентификатор агента (тот же, что в agent_run_history)
 * @param windowMin длина окна в минутах — обычно период расписания
 * @param claimant  кто пытается занять
 */
export async function claimCronWindow(
  agentId: string,
  windowMin: number,
  claimant: LeaseClaimant,
  nowMs: number = Date.now(),
): Promise<LeaseOutcome> {
  const start = windowStart(nowMs, windowMin);
  try {
    // Уборка и захват одним запросом: отдельный крон уборки — ещё одна
    // сущность, которая может встать и оставить таблицу расти молча.
    // DELETE идёт по индексу и почти всегда убирает ноль строк.
    const { rowCount } = await pool.query(
      `WITH swept AS (
         DELETE FROM cron_leases
          WHERE window_start < NOW() - ($4 || ' days')::INTERVAL
       )
       INSERT INTO cron_leases (agent_id, window_start, claimed_by)
       VALUES ($1, $2, $3)
       ON CONFLICT (agent_id, window_start) DO NOTHING`,
      [agentId, start, claimant, String(LEASE_RETENTION_DAYS)],
    );
    return rowCount === 1 ? 'claimed' : 'held';
  } catch (err) {
    // §4.0: отказ не глушится. Имя проверки и текст ошибки — в лог, иначе
    // поломка аренды выглядит как «планировщики договорились».
    console.error(
      `[cron-lease] claim failed for ${agentId}:`,
      err instanceof Error ? err.message : err,
    );
    return 'unknown';
  }
}

/**
 * Работать ли. Отдельная функция, потому что решение по `unknown` — это
 * решение по цене ошибки, и оно должно читаться в одном месте, а не
 * повторяться шестью `!== 'held'` по роутам.
 */
export function shouldRun(outcome: LeaseOutcome): boolean {
  return outcome !== 'held';
}

/** Тело ответа при пропуске. Пропуск обязан называть себя, а не молчать 200. */
export function leaseSkipBody(agentId: string, windowMin: number) {
  return {
    success: true,
    skipped: 'lease_held' as const,
    agent_id: agentId,
    window_min: windowMin,
    note: 'окно уже занято другим планировщиком — работу делает он, дубля не будет',
  };
}
