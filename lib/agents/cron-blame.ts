/**
 * lib/agents/cron-blame.ts — КТО виноват в молчании крона.
 *
 * ── Что случилось 29.08 ───────────────────────────────────────────────────
 *
 * Watchdog прислал КРИТ: четыре safety-крона не отмечались 4-6 часов, и
 * совет к нему — «Проверь GitHub Actions и CRON_SECRET». Совет отправил в
 * два места, где всё было исправно:
 *
 *  - в GitHub Actions ВСЕ прогоны этих воркфлоу зелёные, ни одного падения;
 *  - CRON_SECRET цел — им же в это самое время успешно ходили другие кроны.
 *
 * Сломана была ДОСТАВКА РАСПИСАНИЯ: планировщик GitHub просто не запускал
 * джобы. `safety-ingest` просит `*\/5` (288 прогонов в сутки) и получал
 * два-четыре. Push-триггеры при этом шли нормально весь день — то есть ни
 * биллинг, ни раннеры, ни секрет ни при чём.
 *
 * ── Почему совет был неверен по построению ────────────────────────────────
 *
 * Он выводился из ЧИСЛА МИНУТ: до 6 часов — «наверное, задержка GitHub»,
 * дольше — «проверь секрет». За порогом стояла посылка «столько штатная
 * задержка не длится», и в июле она была верна. К концу августа перестала:
 * наблюдаемая задержка выросла до суток. Посылка устарела молча, а совет
 * продолжал звучать уверенно.
 *
 * Длительность молчания не говорит О ПРИЧИНЕ молчания ничего. Гадание по
 * порогу — это третье состояние (§4.0), выданное за первые два.
 *
 * ── Что РЕАЛЬНО различает причины ─────────────────────────────────────────
 *
 * `CRON_SECRET` один на весь префикс `/api/cron/*`. Отсюда свидетель:
 * **если недавно отметился крон, которого нельзя запустить руками, секрет и
 * эндпоинт заведомо исправны**, и искать надо в планировщике. И наоборот:
 * если молчат ВСЕ такие, — это общий отказ, и вот тогда секрет и доступность
 * прода под подозрением по делу.
 *
 * Оговорка «которого нельзя запустить руками» появилась 08.09 по находке
 * аудита и она существенная: в историю прогонов пишет не только запрос с
 * секретом (см. `witnessEligibleAgentIds`).
 *
 * Это не эвристика по времени, а вывод из общего ресурса: одно доказательство
 * работоспособности секрета закрывает вопрос о секрете для всех кронов сразу.
 *
 * ── Чего здесь нет намеренно ──────────────────────────────────────────────
 *
 * Различения «GitHub не запустил» и «GitHub запустил, но получил 401».
 * Изнутри прода они неразличимы: при 401 запрос отбивается на авторизации,
 * до агента, и строки в `agent_run_history` не остаётся — ровно как при
 * незапуске. Свидетель выше снимает этот вопрос целиком (при живом секрете
 * 401 невозможен), но там, где свидетеля нет, честный ответ — «оба
 * подозреваемых на месте», а не выбор одного из них наугад.
 */

/** Кто виноват. Три исхода, и «не смог установить» — отдельный (§4.0). */
export type CronBlame =
  /**
   * Секрет и эндпоинт доказанно живы: есть свежий прогон другого крона.
   * Молчат именно запуски — виноват планировщик.
   */
  | { kind: 'scheduler'; witnessAgent: string; witnessMinAgo: number }
  /**
   * Не отметился НИ ОДИН крон. Общий отказ: секрет, доступность прода и
   * планировщик — все под подозрением, ни одного нельзя снять.
   */
  | { kind: 'platform'; observedMin: number }
  /** Судить не по чему: истории прогонов нет вовсе. */
  | { kind: 'unknown'; reason: string };

/** Самый свежий прогон ЛЮБОГО крона — свидетель работоспособности секрета. */
export interface CronWitness {
  agentId: string;
  minutesAgo: number;
}

/**
 * Окно свежести свидетеля: час.
 *
 * Прежняя редакция объясняла его так: «за час успевает отработать ЛЮБОЙ из
 * кронов реестра, самый редкий из которых ходит раз в час». Это неверно — в
 * реестре есть и суточные, и недельные. Держит окно другое: годных в
 * свидетели кронов, ходящих не реже часа, десять (safety-ingest каждые пять
 * минут, sos-bridge, danger-analysis, kernel-worker и прочие по получасу).
 * Пока хоть один из них жив, свидетель за час найдётся.
 */
export const WITNESS_FRESH_MIN = 60;

/**
 * Кто ГОДИТСЯ в свидетели секрета.
 *
 * Находка аудита 08.09: свидетелем бралась свежая запись ЛЮБОГО агента, и из
 * неё делался вывод «CRON_SECRET и эндпоинт исправны». Вывод не следует:
 * в `agent_run_history` пишут не только запросы к `/api/cron/*` с секретом.
 * Туда же попадают прогоны, начатые человеком из админки через
 * `/api/admin/agents/trigger` — там admin-JWT, а не `CRON_SECRET`, — и
 * стадии, которые оркестратор пишет сам. Такая строка о секрете не говорит
 * ничего, а вердикт по ней звучал уверенно и заканчивался советом «секрет
 * проверять незачем».
 *
 * Различитель уже был в реестре: `triggerable` — «можно ли запустить вручную
 * через /api/admin/agents/trigger». У НЕтриггерного крона свежая строка может
 * взяться только от workflow, который ходит на эндпоинт с секретом. Он и
 * свидетель.
 *
 * Новой схемы это не требует. Точный ответ дала бы запись способа вызова в
 * саму строку прогона — но это миграция и правка всех мест, где пишется
 * история; пока хватает того, что уже объявлено.
 */
export function witnessEligibleAgentIds(
  entries: readonly { agentId: string | null; triggerable: boolean }[],
): string[] {
  return entries
    .filter((e) => e.agentId !== null && !e.triggerable)
    .map((e) => e.agentId as string);
}

/**
 * @param witness   самый свежий прогон любого крона, либо null если истории нет
 * @param observedMin сколько минут наблюдаем (для отчёта при общем отказе)
 */
export function blameSilentCrons(witness: CronWitness | null, observedMin: number): CronBlame {
  if (!witness) {
    return {
      kind: 'unknown',
      reason: 'ни один крон, ходящий ТОЛЬКО по расписанию, не отмечался — '
        + 'подтвердить секрет нечем (запуски из админки свидетелями не считаются)',
    };
  }
  if (witness.minutesAgo <= WITNESS_FRESH_MIN) {
    return { kind: 'scheduler', witnessAgent: witness.agentId, witnessMinAgo: witness.minutesAgo };
  }
  return { kind: 'platform', observedMin: Math.max(observedMin, witness.minutesAgo) };
}

/**
 * Совет человеку. Именно совет ошибался 29.08, поэтому он выводится из
 * вердикта, а не из числа минут, и НЕ называет виноватым того, кто доказанно
 * исправен.
 */
export function describeBlame(b: CronBlame): string {
  switch (b.kind) {
    case 'scheduler':
      return (
        `CRON_SECRET и эндпоинт исправны — ${b.witnessAgent} отработал ${b.witnessMinAgo} мин назад ` +
        `тем же секретом (руками его не запустить, значит ходил workflow). ` +
        `Молчат ЗАПУСКИ: планировщик GitHub не стартовал джобы ` +
        `(прогоны, которые доходят, зелёные). Секрет проверять незачем.`
      );
    case 'platform':
      return (
        `Молчат ВСЕ кроны, не только safety: ни одного прогона за ${b.observedMin} мин. ` +
        `Это общий отказ — под подозрением CRON_SECRET, доступность vedarai.ru и сам прод.`
      );
    case 'unknown':
      return `Причину установить не смог: ${b.reason}. Виноватого не называю — данных нет.`;
  }
}
