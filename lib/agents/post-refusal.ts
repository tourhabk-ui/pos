/**
 * lib/agents/post-refusal.ts — «модель ответила не постом, а запиской».
 *
 * ── Что случилось 04.09 ────────────────────────────────────────────────────
 *
 * В канал (1.8К подписчиков) ушёл текст:
 *
 *   «Не вижу текста статьи в сигнале — только HTML-обёртка Telegram-виджета
 *    без содержимого поста. Не могу написать пост по этому материалу…
 *    Пришли, пожалуйста, выдержки из статей».
 *
 * Это не пост, это реплика модели ОПЕРАТОРУ, попавшая на витрину. Ворота
 * дайджеста её пропустили честно: они проверяют, подтверждены ли
 * утверждения источниками, а в отказе утверждений нет вовсе — проверять
 * нечего, значит «не подтверждённых» ноль.
 *
 * ── Почему отдельная проверка, а не абзац в промпте ────────────────────────
 *
 * Промпт уже просил писать пост, и модель его прочитала — она отказалась
 * ОСОЗНАННО, потому что материала не было. Просьба «не отказывайся» лечила
 * бы симптом и толкала к выдумке: отказ при пустом материале честнее
 * сочинения. Лечить надо две вещи, и обе снаружи модели: дать материал
 * (см. telegramPostText) и не публиковать записку, если материала не было.
 * §8: «правки промптов — принципы, а не перечни; растущий список исключений
 * значит, что нужен детерминированный guard».
 *
 * ── Цена ошибки несимметрична ──────────────────────────────────────────────
 *
 * Ложное срабатывание стоит одного невышедшего поста, и оно ВИДНО: причина
 * уходит в журнал прогона под своим кодом. Пропуск стоит записки на витрине
 * с подписчиками. Поэтому детектор намеренно строгий.
 */

/**
 * Буква слова — с кириллицей. `\b` в JS считает буквой только латиницу
 * (`\w` = `[A-Za-z0-9_]`), поэтому `/\bне могу\b/` на русском тексте не
 * срабатывает НИКОГДА: перед «н» и после «у» нет ни одного `\w`, значит нет
 * и границы. Первая редакция этого модуля была написана именно так, и из
 * трёх семей признаков живой оставалась одна — латинская `html-обёртка`.
 * Ровно та немота, против которой заведён сам модуль.
 */
const W = '[A-Za-z\\u0400-\\u04FF0-9_]';

/** Совпадение по целому слову — с границами, понимающими кириллицу. */
function word(source: string): RegExp {
  return new RegExp(`(?<!${W})(?:${source})(?!${W})`, 'i');
}

/** То же, но только в начале строки текста (первая фраза ответа). */
function lineStart(source: string): RegExp {
  return new RegExp(`^\\s*(?:${source})(?!${W})`, 'im');
}

/** Обращение к оператору: пост так не пишут — так пишут заказчику. */
const ADDRESSES_OPERATOR = [
  word('пришл(и|ите)(,? пожалуйста)?[^.]{0,40}(выдержк|текст|ссылк|материал)'),
  word('скинь(те)? мне'),
  word('предостав(ь|ьте|и мне)'),
  word('дай(те)? мне'),
  word('отправь(те)? мне'),
  word('уточни(те)?[^.]{0,40} и я'),
];

/** Заявление о невозможности: «не могу», «не вижу», «нечего». */
const DECLARES_INABILITY = [
  lineStart('не\\s+(вижу|могу|нашёл|нашел|получил|располагаю)'),
  word('не могу (написать|составить|собрать|сделать|подготовить)'),
  word('нет ни одного (фактического )?сигнала'),
  word('нечего (синтезировать|обобщать|писать)'),
  word('материала? (нет|недостаточно)'),
];

/** Разговор о самом конвейере: пост о новостях так не выглядит. */
const TALKS_ABOUT_PIPELINE = [
  /html-?обёртк/i,
  word('содержимого поста'),
  word('в сигнале[^.]{0,40} нет'),
  word('по этому материалу'),
  word('соберу дайджест'),
];

export interface RefusalVerdict {
  /** Отказ ли это. */
  refused: boolean;
  /** Чем распознан — для журнала; пусто, когда отказа нет. */
  reason: string;
}

/**
 * Читается ли текст как записка оператору, а не как пост (чистая).
 *
 * Достаточно ОДНОГО признака: заявление о невозможности, обращение к
 * оператору или разговор о внутренностях конвейера. Настоящий пост о
 * вайб-кодинге не содержит ни того, ни другого, ни третьего.
 */
export function judgePostRefusal(text: string): RefusalVerdict {
  const t = (text ?? '').trim();
  if (!t) return { refused: false, reason: '' };
  // В причину уходит НАЙДЕННАЯ фраза, а не исходник регулярки: чинят по
  // тексту ответа модели, а не по выражению, которое его поймало.
  const hit = (list: RegExp[]): string | null => {
    for (const re of list) {
      const m = re.exec(t);
      if (m) return m[0].replace(/\s+/g, ' ').trim().slice(0, 80);
    }
    return null;
  };

  const inability = hit(DECLARES_INABILITY);
  if (inability) return { refused: true, reason: `заявлена невозможность: «${inability}»` };

  const address = hit(ADDRESSES_OPERATOR);
  if (address) return { refused: true, reason: `обращение к оператору: «${address}»` };

  const pipeline = hit(TALKS_ABOUT_PIPELINE);
  if (pipeline) return { refused: true, reason: `текст про конвейер, а не про новость: «${pipeline}»` };

  return { refused: false, reason: '' };
}
