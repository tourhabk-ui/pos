/**
 * Фактчек публикуемых текстов — общий для ВСЕХ публикаторов в каналы.
 *
 * История: гейты родились в scout-digest после инцидента 25.07 («Claude
 * Opus 5 — без изменения цены», хотя цена изменилась вдвое) и жили только
 * там. 31.07 в AI-канал ушёл пост из ДРУГОГО конвейера
 * (intelligence-monitor → postAINewsToChannel) с перенесёнными числами
 * («YDB ускоряет в 3 раза», «llama.cpp: прирост качества до 300%») —
 * тот путь гейтов не имел вовсе. Лекарство одно, пациентов много — модуль
 * общий, публикаторы обязаны звать его перед отправкой.
 *
 * Два эшелона:
 *   · unsourcedPercents — детерминированный: проценты и кратности («в N раз»),
 *     чисел которых нет в источниках;
 *   · unsupportedClaims — семантический judge (LLM): факты поста, которых
 *     нет в источниках или которые им противоречат.
 * Принцип: лучше не выпустить пост, чем выпустить с выдумкой.
 */

import { callAIQualityOrNull } from '@/lib/ai/providers';
import type { ChatMessage } from '@/lib/ai/prompts';
import { describeRecentAiFailures } from '@/lib/ai/failure-trace';

/**
 * Инструкция судье. Вынесена в константу: её читают два места.
 *
 * Мера строгости — ПРИНЦИП, не список кейсов (02.09). До этого дня судья
 * считал выдумкой всё, чего нет в источниках ДОСЛОВНО, включая то, что из
 * них выводится: «Anthropic анонсировала Claude Fable 5.1» браковалось с
 * пояснением «в источниках нет указания на анонс от Anthropic» — хотя
 * производитель названной модели общеизвестен и ничего нового пост не
 * добавил. На синтезе такой брак срабатывал на 10 из 10 утверждений, каждый
 * прогон, и выпуск не выходил ни разу с 17.08. Строгость, при которой
 * не проходит ничего, ничего и не защищает: она лишь переносит выдумку
 * из текста в отчёт «всё выдумано».
 *
 * Черта теперь проходит так: неподтверждённое — то, что ПРОТИВОРЕЧИТ
 * источникам или ДОБАВЛЯЕТ новый факт, которого из них не вывести. Связка
 * разных материалов, следствие и приписывание действия лицу, которого
 * источник в этой роли не называет, — по-прежнему новые факты. Пересказ
 * своими словами и общеизвестный производитель названного продукта — нет.
 */
const JUDGE_SYSTEM = 'Ты строгий фактчекер. Сверь ПРОВЕРЯЕМЫЕ факты поста (цифры, проценты, версии, названия фич/моделей, технический механизм) с источниками. НЕПОДТВЕРЖДЁННЫМ считается утверждение, которое ПРОТИВОРЕЧИТ источникам или ДОБАВЛЯЕТ НОВЫЙ ФАКТ, которого из источников не вывести. Новый факт — это: (1) СВЯЗЬ между фактами — причинность, обобщение «доказал/подтвердил/показал, что…», объединение РАЗНЫХ материалов в один сюжет или общий вывод; (2) ЭКОНОМИЧЕСКОЕ или ПРАКТИЧЕСКОЕ СЛЕДСТВИЕ — «без затрат на персонал», «экономит N», «заменяет сотрудников», «окупается за…» — если источник такого вывода не делает, это выдумка, а не оценка; (3) АТРИБУЦИЯ — действие приписано лицу или компании, которых источник в этой роли не называет; (4) цифра, дата, цена, версия или механизм, которых в источниках нет. НЕ считается новым фактом и НЕ записывается в неподтверждённые: пересказ утверждения самого источника своими словами; общеизвестный производитель или категория названного в источнике продукта (модели Claude выпускает Anthropic, GPT — OpenAI, Gemini — Google; вулкан — это вулкан); уточнение раздела или темы; чисто оценочные суждения вкуса («это красиво», «полезно инженеру»). Сомнение толкуй в пользу поста, если утверждение выводится из источника без новой информации. Верни ТОЛЬКО JSON: {"unsupported":["«дословная цитата фразы поста» — чего именно нет в источниках или чему противоречит"]}. Цитата обязана быть дословной, чтобы фразу можно было найти в тексте. Если всё подтверждено — {"unsupported":[]}.';

/**
 * Детерминированный гейт: проценты и кратности из текста, чисел которых НЕТ
 * в источнике. Кратности («в 3 раза», «3x») добавлены после инцидента 31.07 —
 * перенос «ускорения 3x» с одного предмета на другой процентом не был и
 * проходил мимо. Число, присутствующее в источнике в другом контексте,
 * гейт пропустит — это floor, семантику держит unsupportedClaims.
 */
export function unsourcedPercents(post: string, source: string): string[] {
  // \b не работает с кириллицей (JS считает словом только [A-Za-z0-9_]) —
  // граница «раза» держится lookahead'ом, та же грабля, что в claim-signature.
  //
  // Валюта добавлена 01.08: цена DeepSeek «$0.27» в дайджесте (реально $0.28)
  // прошла мимо — проценты/кратности гейт ловил, деньги нет. Цена — такой же
  // проверяемый факт, а ошибка на цент в публичном посте про экономику модели
  // подрывает доверие. Форматы: «$0.27», «0.27$», «68 000 ₽», «990 руб», «€15».
  // Пробелы-разделители тысяч допускаются (\d[\d  ]* с NBSP и обычным).
  const NUM = String.raw`\d+(?:[   ]?\d{3})*(?:[.,]\d+)?`;
  const claims = post.match(new RegExp(
    String.raw`${NUM}\s*[–-]\s*${NUM}\s*%` +           // диапазон процентов
    String.raw`|${NUM}\s*%` +                          // процент
    String.raw`|(?:в\s+)?${NUM}\s*раз(?:а|у)?(?![а-яё])` + // кратность словом
    String.raw`|${NUM}x\b` +                           // кратность «3x»
    String.raw`|[$€£]\s?${NUM}|${NUM}\s?[$€£]` +       // валюта символом
    String.raw`|${NUM}\s?(?:₽|руб(?:\.|лей|ля)?|долл(?:\.|аров)?|евро)(?![а-яё])`, // валюта словом
    'giu',
  )) ?? [];
  // Нормализация числа: убрать разделители тысяч (пробел/NBSP), запятую → точка.
  // Иначе «68 000» дробится на «68» и «000», а «000» collides с любым «N 000».
  const norm = (n: string) => n.replace(/[   ]/g, '').replace(',', '.');
  const NUM_G = new RegExp(NUM, 'gu');
  const srcNums = new Set((source.match(NUM_G) ?? []).map(norm));
  return claims.filter(claim => {
    const nums = claim.match(NUM_G) ?? [];
    return !nums.some(n => srcNums.has(norm(n)));
  });
}

/**
 * Семантический фактчек: AI сверяет проверяемые факты поста с источниками.
 *
 * Возврат — ТРИ состояния, не два (изменено 01.08 после инцидента
 * GPT-Realtime): [] — судья ответил, всё подтверждено; [...] — нашёл выдумки;
 * null — СУДЬЯ НЕ ОТВЕТИЛ (провайдер молчит/ответ не распарсился). Раньше сбой
 * возвращал [] и был неотличим от «чисто» — гейт становился сквозным ровно
 * когда переставал работать. Теперь null = «проверить не смогли», и
 * публикатор обязан ОТМЕНИТЬ пост, а не пропустить: лучше не выпустить, чем
 * выпустить непроверенным.
 *
 * Выдуманной считается и СВЯЗКА между источниками (инцидент 01.08: агент
 * Ouroboros и индексация Яндекса сшиты в один сюжет), и ЭКОНОМИЧЕСКОЕ/
 * практическое СЛЕДСТВИЕ, которого в источнике нет («без затрат на персонал»
 * поверх новости про агента поддержки — инцидент GPT-Realtime 01.08). Это
 * принцип судьи, не список кейсов.
 */
/**
 * Почему судья не дал ответа. Четыре РАЗНЫЕ беды, а не одна.
 *
 * До 18.08 все они возвращались как `null` и печатались одним сообщением
 * «проверяющая модель не ответила». Владелец видел его семнадцать дней подряд
 * и искал причину в блокировке провайдера — а «не ответила» из четырёх
 * случаев верно ровно в одном.
 *
 *   silent      — провайдер вернул пустоту: молчание модели;
 *   unavailable — не ответил НИ ОДИН провайдер (22.08);
 *   unparseable — ответ есть, но JSON в нём не нашёлся (модель ответила прозой);
 *   truncated   — JSON начался и оборвался: не хватило потолка токенов;
 *   bad_shape   — JSON есть, а поля `unsupported` в нём нет или оно не список;
 *   threw       — запрос упал с исключением (сеть, ключ, таймаут).
 *
 * Первый, второй и пятый чинятся у провайдера, третий и четвёртый — в промпте
 * или разборе. Одно слово на всех отправляет чинить не туда.
 *
 * `unavailable` заведён 22.08 по живому случаю. `callAIFast` при отказе ВСЕХ
 * провайдеров возвращает не пустоту и не исключение, а строку-заглушку
 * «Сервис временно недоступен.». Судья видел непустой текст без фигурных
 * скобок и объявлял `unparseable`, то есть «сбой в промпте, НЕ в провайдере».
 * Владелец три недели читал в алерте предложение чинить промпт, пока молчали
 * провайдеры. Заглушка — это ответ вызывающему «я не смог», и путать её с
 * ответом модели нельзя: `callAIQualityOrNull` отдаёт то же самое честным `null`.
 */
export type JudgeFailure =
  | 'silent' | 'unavailable' | 'unparseable' | 'truncated' | 'bad_shape' | 'threw';

export type JudgeOutcome =
  | { ok: true; unsupported: string[] }
  /**
   * `sample` — начало ответа, который не разобрался. Без него «ответила прозой»
   * называет КЛАСС беды, но не саму беду: чинить приходится вслепую. Режется до
   * 200 символов и уходит только в лог/алерт владельцу, не в публикацию.
   */
  | { ok: false; why: JudgeFailure; sample?: string };

/**
 * Судья фактгейта: какие утверждения поста НЕ подтверждаются источниками.
 *
 * Отдаёт причину отказа, а не просто отказ. Единственная реализация; тонкая
 * обёртка `unsupportedClaims` ниже оставлена для вызывающих, которым причина
 * не нужна.
 */
/** Начало ответа для диагноза: не «проза», а какая именно проза. */
function sampleOf(raw: string): string {
  return raw.trim().replace(/\s+/g, ' ').slice(0, 200);
}

/**
 * Достаёт объект JSON из ответа модели.
 *
 * Не жадной регуляркой `/\{[\s\S]*\}/`: та берёт от ПЕРВОЙ скобки до
 * ПОСЛЕДНЕЙ, и ответ вида «вот разбор {…} а вот пример {…}» склеивался в
 * заведомо битую строку. Сканируем со счётчиком скобок и берём первый
 * сбалансированный объект, игнорируя скобки внутри строк.
 */
function extractJsonObject(raw: string): string | null {
  const text = raw.replace(/```(?:json)?/gi, ' ');
  for (let start = text.indexOf('{'); start !== -1; start = text.indexOf('{', start + 1)) {
    let depth = 0;
    let inStr = false;
    let esc = false;
    for (let i = start; i < text.length; i++) {
      const c = text[i];
      if (esc) { esc = false; continue; }
      if (c === '\\') { esc = true; continue; }
      if (c === '"') { inStr = !inStr; continue; }
      if (inStr) continue;
      if (c === '{') depth++;
      else if (c === '}') {
        depth--;
        if (depth === 0) return text.slice(start, i + 1);
      }
    }
  }
  return null;
}

/**
 * Потолок ответа судьи.
 *
 * У ног быстрой ветки по умолчанию 600-800 токенов. Судья обязан ЦИТИРОВАТЬ
 * неподтверждённые утверждения, и на длинном выпуске ответ обрывался на
 * середине. У оборванного JSON нет закрывающей скобки, разбор его не берёт —
 * и отказ назывался «ответила прозой», хотя модель отвечала верно и просто
 * не поместилась. Проба 22.08: прогон дошёл до судьи (52 сигнала, синтез
 * состоялся, все 10 источников живы) и встал именно здесь.
 */
const JUDGE_MAX_TOKENS = 1600;

/**
 * Предел ожидания судьи больше не задаётся здесь — и это не потеря.
 *
 * Он появился 22.08, когда судья ходил быстрой веткой: у её ног 20 секунд, а
 * судья получает до 16000 знаков источников плюс сам выпуск и не укладывался.
 * Прогон того дня показал это в паре: синтез на ТЕХ ЖЕ провайдерах прошёл, а
 * судья вернул «не ответил никто» — вся разница была в пределе ожидания.
 *
 * 23.08 судья переведён на качественный путь, у которого свои 45 секунд —
 * ровно та величина, что стояла здесь константой. Оставлять её значило бы
 * держать в файле число, которое ничем не управляет и врёт об этом.
 */

/** Одна попытка: спросить судью и разобрать ответ. */
async function judgeOnce(messages: ChatMessage[]): Promise<JudgeOutcome> {
  let raw: string | null;
  try {
    // КАЧЕСТВЕННЫЙ путь, а не гонка (23.08). Судья единственный в разведчике
    // ходил через callAIFast — гонку дешёвых провайдеров, где побеждает самый
    // быстрый. Сам выпуск при этом синтезируется через callAIQuality, то есть
    // DeepSeek. Разница видна в переписи прогонов: с 18 по 22.08 шесть раз
    // подряд `judge_unparseable` — «ответила прозой вместо JSON». Проза берётся
    // оттуда, что гонку выигрывала модель, которая response_format не
    // поддерживает: формат просили, а гарантии не было. Ровно то, о чём
    // предупреждает шапка providers.ts — «гонку выигрывала самая быстрая
    // мелкая модель, и публичные тексты писала она».
    //
    // Гейт публикации — не место для гонки: здесь важна не скорость ответа, а
    // то, что ответ вообще разберут. Порядок теперь тот же, что у выпуска:
    // DeepSeek, затем Qwen, оба формат понимают.
    //
    // json: формат просим у ПРОВАЙДЕРА, а не уговариваем словами в промпте.
    // «Верни ТОЛЬКО JSON» — просьба, response_format — гарантия. Разбор и
    // повтор ниже остаются страховкой на случай запасного пути водопада.
    raw = await callAIQualityOrNull(messages, {
      maxTokens: JUDGE_MAX_TOKENS,
      json: true,
      // Судья цитирует утверждения дословно и должен быть буквален:
      // выдумывать формулировки ему нечего.
      temperature: 0,
    });
  } catch {
    return { ok: false, why: 'threw' };
  }
  // Ни один провайдер не ответил. Это отказ ИНФРАСТРУКТУРЫ, и путать его с
  // ответом модели нельзя: чинить придётся в разных местах.
  //
  // 23.08: к коду прикладывается СЛЕД — кто именно и с чем отказал. Без него
  // «чинить у провайдера» — совет, по которому нельзя сделать ни одного шага:
  // владелец видел ключ DeepSeek на месте и упирался в тупик, а причина могла
  // быть у любой из четырёх ног гонки и любой из трёх ступеней водопада.
  if (raw === null) {
    const trace = describeRecentAiFailures();
    return { ok: false, why: 'unavailable', ...(trace ? { sample: trace } : {}) };
  }
  // Пустой ответ провайдера (молчит) — это НЕ «чисто», это сбой судьи.
  if (!raw.trim()) return { ok: false, why: 'silent' };

  const body = extractJsonObject(raw);
  if (!body) {
    // Открытая скобка без закрывающей — это ОБРЫВ, а не проза. Лечится
    // потолком токенов, а не промптом, и путать их нельзя: один и тот же
    // код отправлял чинить не туда три недели.
    const why: JudgeFailure = raw.includes('{') ? 'truncated' : 'unparseable';
    return { ok: false, why, sample: sampleOf(raw) };
  }
  try {
    const parsed = JSON.parse(body) as { unsupported?: unknown };
    if (!Array.isArray(parsed.unsupported)) {
      return { ok: false, why: 'bad_shape', sample: sampleOf(raw) };
    }
    return { ok: true, unsupported: parsed.unsupported.filter((x): x is string => typeof x === 'string') };
  } catch {
    // Скобки нашлись, но внутри не JSON — та же беда, что «ответила прозой».
    return { ok: false, why: 'unparseable', sample: sampleOf(raw) };
  }
}

/**
 * Сколько источников доезжает до судьи.
 *
 * 9000 → 16000 (24.08): дайджест подмешивает в источники текст статей на
 * часть сигналов, и старый потолок резал ровно тот текст, ради которого его
 * добавили.
 *
 * 16000 → 32000 (29.08). Расчёт в scout-digest обещал «11200 худшего
 * случая, запас остаётся» — но считал ТОЛЬКО текст обогащённых статей и
 * забыл заголовки остальных сигналов. Список строится по ВСЕМ сигналам: при
 * 53 (максимум из журнала прогонов) шестнадцать обогащённых дают около
 * 13000 знаков, плюс тридцать семь голых заголовков ещё около 3900 — итог
 * порядка 16900, то есть за прежним потолком.
 *
 * Чем это плохо: писатель видит источники ЦЕЛИКОМ, судья — усечённые. Тогда
 * утверждение, опирающееся на хвост списка, честно не находит подтверждения,
 * и выпуск держится за «выдумку», которой не было. Судья при этом прав по
 * своим данным — неправ вход.
 */
export const JUDGE_SOURCES_LIMIT = 32_000;

export async function judgeClaims(post: string, sources: string): Promise<JudgeOutcome> {
  // Усечение, если оно всё же случилось, названо ВСЛУХ и внутри промпта.
  // Молчаливый обрез — это ложь про полноту источников: судья считал бы, что
  // видит всё, и «нет подтверждения» звучало бы увереннее, чем есть.
  const truncated = sources.length > JUDGE_SOURCES_LIMIT;
  const sourcesBlock = truncated
    ? `${sources.slice(0, JUDGE_SOURCES_LIMIT)}\n\n[ИСТОЧНИКИ ОБРЕЗАНЫ: показано ${JUDGE_SOURCES_LIMIT} из ${sources.length} знаков. Если утверждение выглядит правдоподобным для этой темы, но подтверждения ему в тексте выше НЕТ, не записывай его в неподтверждённые — оно могло опираться на обрезанную часть.]`
    : sources;

  const messages: ChatMessage[] = [
    { role: 'system', content: JUDGE_SYSTEM },
    { role: 'user', content: `ИСТОЧНИКИ:\n${sourcesBlock}\n\nПОСТ:\n${post}` },
  ];
  const first = await judgeOnce(messages);
  // Проза вместо JSON лечится прямым указанием, а не ожиданием. Повтор ТОЛЬКО
  // на беде разбора: молчащего провайдера вторым запросом не оживить, а гейт
  // публикации не место для долбёжки.
  const fixableByAsking: JudgeFailure[] = ['unparseable', 'truncated', 'bad_shape'];
  if (first.ok || !fixableByAsking.includes(first.why)) return first;
  const retry = await judgeOnce([
    ...messages,
    { role: 'assistant', content: first.sample ?? '' },
    {
      role: 'user',
      content: 'Ответ не разобран. Верни ТОЛЬКО объект JSON вида {"unsupported":[]} — без пояснений, без markdown, без текста до и после. Формулировки в списке сокращай до сути, чтобы ответ поместился целиком.',
    },
  ]);
  // Вернуть исход повтора, но снимок оставить ПЕРВЫЙ: он показывает, с чего
  // всё началось, а второй — уже реакцию на упрёк.
  return retry.ok ? retry : { ...retry, sample: first.sample ?? retry.sample };
}

/** Прежняя форма ответа: список или `null`. Причину см. в `judgeClaims`. */
export async function unsupportedClaims(post: string, sources: string): Promise<string[] | null> {
  const r = await judgeClaims(post, sources);
  return r.ok ? r.unsupported : null;
}

/**
 * Вычёркивание неподтверждённых фраз из текста — детерминированное, без
 * модели (02.09).
 *
 * Зачем. Публикатор просил писателя переписать выпуск до двух раз, и если
 * судья после этого всё ещё находил хоть одно утверждение, выпуск отменялся
 * ЦЕЛИКОМ — вместе с девятью подтверждёнными пунктами. Так молчание длилось
 * с 17.08: писатель убирал одни связки и добавлял другие, судья находил
 * новые, и на третьем круге всё шло в корзину. Отмена целого выпуска из-за
 * одной фразы — это не строгость, а выключенный канал.
 *
 * Что делает. Для каждого утверждения судьи ищет СТРОКУ текста (пункт
 * дайджеста — одна строка), которая его несёт, и убирает строку целиком.
 * Матч — по совпадению значимых слов цитаты со словами строки: судью просят
 * цитировать дословно, но модели пересказывают, и точное вхождение ловило
 * бы не всё. Пояснение судьи после « — » в сравнении не участвует: там его
 * слова, а не слова поста.
 *
 * Три исхода, не два (§4.0): `dropped` — нашли и убрали; `unmatched` —
 * судья назвал фразу, которой в тексте не нашлось. Второе — НЕ «значит, её
 * там нет»: это «не смогли проверить, что убрали», и публикатор обязан
 * остановиться, а не выпускать. Пустая строка вместо пункта лучше пункта с
 * выдумкой; выпуск без пунктов вовсе не выпуск — это тоже решает публикатор
 * по `hasSubstance`.
 */
export interface StripResult {
  text: string;
  /** Утверждения, для которых строка нашлась и убрана. */
  dropped: string[];
  /** Утверждения, которых в тексте не нашлось: убрать не смогли. */
  unmatched: string[];
  /** Разделы, оставшиеся без пунктов и потому убранные из выпуска. */
  emptied: string[];
}

/**
 * Раздел без пунктов убирается ЦЕЛИКОМ — заголовок вместе с пустотой.
 *
 * До 06.09 сюда подставлялась строка «Нет значимых сигналов за сегодня», и
 * рассуждение было «читателю нужна строка, а не дыра». Но эта строка —
 * УТВЕРЖДЕНИЕ о предмете раздела: она говорит, что за сутки по Камчатке
 * ничего значимого не случилось. Проверить его нечем: в разделе «Камчатка»
 * материал в тот день БЫЛ (safety-слой, три события), просто пункт про него
 * не пережил фактчек. Читатель получал вывод о регионе там, где мы вычеркнули
 * собственную строку.
 *
 * Отсутствие раздела утверждением не является — поэтому пустой раздел
 * исчезает. Пустота при этом не пропадает из виду: имена убранных разделов
 * возвращаются наверх и попадают в журнал прогона (§4.0 — «не знаю» должно
 * быть слышно нам, а не выдаваться читателю за факт).
 */
export function dropEmptySections(lines: string[]): { lines: string[]; emptied: string[] } {
  const isSection = (l: string) => /^<b>[^<]*<\/b>\s*$/.test(l.trim());
  const out: string[] = [];
  const emptied: string[] = [];
  for (let i = 0; i < lines.length; i++) {
    if (!isSection(lines[i]) || i === 0) { out.push(lines[i]); continue; }
    let j = i + 1;
    while (j < lines.length && lines[j].trim() === '') j++;
    if (j >= lines.length || isSection(lines[j])) {
      emptied.push(lines[i].replace(/<\/?b>/g, '').trim());
      // Заголовок и пустые строки под ним не переносим.
      i = j - 1;
      continue;
    }
    out.push(lines[i]);
  }
  return { lines: out, emptied };
}

/** Порог совпадения значимых слов цитаты со строкой текста. */
const STRIP_MIN_COVERAGE = 0.5;
/** Меньше двух значимых слов — совпадение случайно, а не по смыслу. */
const STRIP_MIN_TOKENS = 2;

/** Цитата поста из формулировки судьи: часть до « — », кавычки сняты. */
function quoteOf(claim: string): string {
  const inGuillemets = /«([^»]{6,})»/.exec(claim)?.[1];
  const base = inGuillemets ?? claim.split(/\s[—–]\s/)[0];
  return base.replace(/^["'«»]+|["'«»]+$/g, '').trim();
}

/**
 * Значимые слова: буквы и цифры, от трёх знаков, без служебных. Слова длиннее
 * пяти знаков режутся до пяти — грубая замена стемминга, чтобы «анонсировала»
 * и «анонсировали» считались одним словом.
 */
const STOP = new Set(['это', 'что', 'как', 'для', 'при', 'или', 'его', 'их', 'она', 'они', 'the', 'and', 'for', 'with', 'без', 'уже', 'ещё', 'все', 'всё', 'так', 'только']);
function tokensOf(s: string): Set<string> {
  const out = new Set<string>();
  for (const m of s.toLowerCase().matchAll(/[\p{L}\p{N}]+(?:\.[\p{N}]+)?/gu)) {
    const w = m[0];
    if (w.length < 3 || STOP.has(w)) continue;
    out.add(w.length > 5 ? w.slice(0, 5) : w);
  }
  return out;
}

/** Строка-заголовок раздела (`<b>…</b>` и ничего больше) — её не вычёркивают. */
function isHeaderLine(line: string): boolean {
  const t = line.trim();
  return t === '' || /^<b>[^<]*<\/b>\s*$/.test(t);
}

export function stripUnsupported(text: string, claims: string[]): StripResult {
  const lines = text.split('\n');
  const removed = new Set<number>();
  const dropped: string[] = [];
  const unmatched: string[] = [];

  for (const claim of claims) {
    const want = tokensOf(quoteOf(claim));
    if (want.size < STRIP_MIN_TOKENS) { unmatched.push(claim); continue; }
    let best = -1;
    let bestCoverage = 0;
    lines.forEach((line, i) => {
      if (removed.has(i) || isHeaderLine(line)) return;
      const have = tokensOf(line);
      let hit = 0;
      for (const w of want) if (have.has(w)) hit++;
      const coverage = hit / want.size;
      if (coverage > bestCoverage) { bestCoverage = coverage; best = i; }
    });
    if (best >= 0 && bestCoverage >= STRIP_MIN_COVERAGE) {
      removed.add(best);
      dropped.push(claim);
    } else {
      unmatched.push(claim);
    }
  }

  const kept = lines.filter((_, i) => !removed.has(i));
  const { lines: out, emptied } = dropEmptySections(kept);
  return { text: out.join('\n').replace(/\n{3,}/g, '\n\n'), dropped, unmatched, emptied };
}

/**
 * Осталось ли в тексте хоть что-то, кроме заголовков и строк «нет сигналов».
 * Выпуск, из которого вычеркнули всё, — не выпуск; публиковать его нельзя.
 */
/**
 * Убрать заглушки и опустевшие разделы из готового текста выпуска.
 *
 * Промпт с 06.09 просит модель не писать пустой раздел вовсе, но промпт — это
 * просьба, а не гарантия: заглушка приходила от модели и раньше, и правило
 * обязано держаться детерминированно. Поэтому строка «Нет значимых сигналов за
 * сегодня» вычёркивается здесь, а оставшийся без пунктов заголовок исчезает
 * вместе с ней.
 */
export function tidySections(text: string): { text: string; emptied: string[] } {
  const kept = text.split('\n').filter((l) => !/Нет значимых сигналов за сегодня/.test(l));
  const { lines, emptied } = dropEmptySections(kept);
  return { text: lines.join('\n').replace(/\n{3,}/g, '\n\n').trim(), emptied };
}

export function hasSubstance(text: string): boolean {
  // Строка-заглушка больше не ставится (06.09), но старые выпуски и ответы
  // модели её ещё содержат — сущностью она не была и не станет.
  return text.split('\n').some(l =>
    !isHeaderLine(l) && !/Нет значимых сигналов за сегодня/.test(l) && l.trim().length > 0,
  );
}
