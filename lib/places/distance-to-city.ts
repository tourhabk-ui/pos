/**
 * lib/places/distance-to-city.ts — «сколько отсюда до города».
 *
 * ── Зачем ─────────────────────────────────────────────────────────────────
 *
 * Разбор чужих карточек (14.09) дал приём, который у нас производим ДЛЯ ВСЕХ
 * мест, в отличие от цены, часов работы и рейтинга: строка «столько-то
 * километров от Петропавловска». У Туристера она стоит у каждого природного
 * объекта («в 130 км от Петропавловска-Камчатского»), и это единственный
 * факт первого экрана, который не надо ни у кого спрашивать — координаты у
 * `places` NOT NULL по построению.
 *
 * ── Почему «по прямой» написано словами ───────────────────────────────────
 *
 * Миграция 925 намеренно НЕ писала расстояние до города в описании
 * «Раздолья»: бальнеозаключение говорило 22 км, сетевые справочники 45, а по
 * координатам выходило 36. Три числа на один факт — это «не знаю», и выдавать
 * одно за правду нельзя (CLAUDE.md §4.0).
 *
 * Здесь противоречия нет, потому что число не берётся из источника, а
 * СЧИТАЕТСЯ, и вместе с ним всегда едет способ подсчёта. «36 км по прямой» —
 * проверяемое утверждение о двух координатах. «36 км» без оговорки было бы
 * обещанием дороги, которой мы не мерили: на Камчатке дорога до точки в
 * тридцати километрах по прямой бывает и вдвое длиннее, и вовсе отсутствует.
 *
 * Дорожное расстояние у платформы есть (свой граф, `roadGraphCarProvider`),
 * но считается от ЖИВОГО положения человека и только по запросу — это другой
 * ответ на другой вопрос, и подменять им прямую нельзя.
 */

import { distanceKm } from '@/lib/geo/kamchatka';

/**
 * Петропавловск-Камчатский, центр. Тот же ориентир, от которого считает
 * планер (`PKC_COORDS` в lib/planner/engine.ts) — второй точки отсчёта в
 * платформе заводить нельзя, иначе одно место получит два разных расстояния.
 */
export const PKC = { lat: 53.01, lng: 158.65 } as const;

export interface CityDistance {
  km: number;
  /** Готовая подпись человеку, всегда со способом подсчёта. */
  label: string;
}

/**
 * Расстояние до Петропавловска по прямой.
 *
 * `null` — когда считать не от чего или число уже ничего не говорит: это
 * третий исход, и он выражается отсутствием строки, а не прочерком.
 */
export function distanceToCity(
  lat: number | null | undefined,
  lng: number | null | undefined,
): CityDistance | null {
  if (typeof lat !== 'number' || typeof lng !== 'number') return null;
  if (!Number.isFinite(lat) || !Number.isFinite(lng)) return null;

  const km = distanceKm({ lat, lng }, PKC);
  if (!Number.isFinite(km)) return null;

  // Верхнего порога намеренно НЕТ. Мысль «дальше N километров цифра
  // бесполезна» не выдержала проверки: полуостров тянется на тысячу с лишним
  // километров, и «810 км от Петропавловска» — именно то, что нужно знать
  // про север края. А если координата сломана, большое число это и покажет —
  // молчание спрятало бы улику.

  // Ближе километра округление до целых дало бы «0 км» — это выглядит как
  // сбой, а не как «вы на месте».
  const rounded = km < 1 ? Math.round(km * 10) / 10 : Math.round(km);

  return { km, label: `${rounded.toLocaleString('ru-RU')} км по прямой` };
}
