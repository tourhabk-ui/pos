/**
 * lib/places/activity-name-judge.ts — имя места не должно называть активность.
 *
 * Найдено 07.09: точка «Река Авача — рыбалка» лежала в `places` (проходила
 * фильтр `kind=place` через VIEW agent_route_knowledge, §4.1) и попадала на
 * `/map` наравне с настоящими местами — хотя сама рыбалка идёт на другой
 * реке, а название описывает КОММЕРЧЕСКУЮ АКТИВНОСТЬ, не географический
 * факт. Ровно смешение, которое запрещает §9 CLAUDE.md: «Точка = место.
 * Тур = коммерция. Не смешивать».
 *
 * У маршрутов (`kamchatka_routes`) активность в имени — часть стандарта
 * (§13: «Сплав по реке Быстрая» — активность впереди, когда она суть).
 * У мест (`places`) она означает ОБРАТНОЕ: имя обещает то, чем место не
 * является. Отсюда отдельный, более строгий судья — не переиспользование
 * title-standard.ts, у которого другая полярность правила.
 *
 * Судья не удаляет и не решает — только называет подозрение по проверяемому
 * признаку (слово из списка активностей где-либо в имени). Решает человек,
 * глазами: активность в скобках уточнением («Водопад (сплав)») и настоящая
 * ошибка данных выглядят по-разному, а признак у обоих один и тот же.
 */

/** Слова, которые описывают КОММЕРЧЕСКУЮ АКТИВНОСТЬ, а не место. */
const ACTIVITY_WORDS = new Set([
  'рыбалка', 'рыбалку', 'рыбалки', 'рыбалке',
  'сплав', 'сплава', 'сплаву',
  'экскурсия', 'экскурсию', 'экскурсии', 'экскурсией',
  'поход', 'похода', 'походу',
  'восхождение', 'восхождения', 'восхождению',
  'прогулка', 'прогулку', 'прогулки',
  'катание', 'катания',
  'дайвинг', 'дайвинга',
  'сафари',
  'охота', 'охоту', 'охоты',
  'тур', 'тура', 'туры', 'туром',
]);

export interface ActivityNameVerdict {
  ok: boolean;
  /** Слова из ACTIVITY_WORDS, найденные в имени — материал для ручного разбора. */
  matched: string[];
}

/** То же извлечение слов, что у title-standard.ts — пробелы, пунктуация по краям. */
function words(name: string): string[] {
  return name
    .toLowerCase()
    .split(/[\s]+/)
    .map(t => t.replace(/^[^\p{L}\p{N}]+|[^\p{L}\p{N}]+$/gu, ''))
    .filter(t => t.length > 0);
}

export function judgePlaceActivityName(name: string): ActivityNameVerdict {
  const matched = [...new Set(words(name).filter(w => ACTIVITY_WORDS.has(w)))];
  return { ok: matched.length === 0, matched };
}
