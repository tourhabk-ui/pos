/**
 * Голос описания места: справка или путевая заметка (26.09).
 *
 * Повод. Внешняя проверка MCP спросила об Авачинском и получила «Вчера
 * поднялся на Авачинский… фумаролы работают исправно» — дневник от первого
 * лица вместо справки. Происхождение то же, что у Ключевской 19.09 (миграция
 * 987): промпт «напиши так, как будто ты только что вернулся оттуда». В
 * админском роуте его тогда переписали, а в скрипте
 * `scripts/enrich-place-descriptions.ts` он остался (скрипт удалён 26.09: он
 * дублировал роут и не вёл журнал происхождения) — и тексты, написанные им
 * раньше, остались в базе.
 *
 * Чем опасен голос, а не только слог. «Вчера», «фумаролы работают исправно»,
 * «тропа сухая» читаются как НАБЛЮДЕНИЕ о текущем состоянии места, а
 * наблюдения не было. На платформе, где турист решает по карточке, идти или
 * нет, это выдуманный статус безопасности.
 *
 * Функция сообщает ФАКТ о тексте — какие приметы найдены, — а не приговор о
 * правде: «запах серы» у фумарольного поля бывает верен. Решение, что
 * переписать, принимает человек по переписи (`GET /api/cron/place-description-geo`,
 * блок `voice`). Автомат, переписывающий по примете, испортил бы и верное.
 *
 * Три исхода:
 *   diary      — первое лицо или «вчера/сегодня»: рассказ о поездке, которой
 *                не было. Как справку не отдаём;
 *   impression — ощущения без рассказчика («запах», «тишина», «чувствуешь»):
 *                может быть верно, может быть сочинено — отдаём с пометкой;
 *   plain      — примет нет. Это не «проверено», а «голос справочный».
 */

import { stripTags } from '@/lib/html/text';

export type DescriptionVoice = 'diary' | 'impression' | 'plain';

export interface VoiceVerdict {
  voice: DescriptionVoice;
  /** Найденные приметы — дословно, как в тексте, в нижнем регистре. */
  markers: string[];
}

// Границы слова для кириллицы: \b в JS знает только латиницу.
const L = '(?<![а-яёa-z])';
const R = '(?![а-яёa-z])';

/**
 * Рассказчик и время рассказа. Глаголы — прошедшее время единственного
 * числа и «мы»-формы, какими пишут отчёт о походе («шли», «дошли»,
 * «увидели» не взяты: «туристы шли» — справочный оборот); местоимения — только
 * личные первого лица. «Наш/наши» сюда не входят намеренно: «наши данные»,
 * «наш край» — обычный справочный оборот.
 */
const DIARY = new RegExp(
  L + '(' + [
    'я', 'мы', 'мне', 'меня', 'нам', 'нас',
    'вчера', 'позавчера', 'сегодня утром', 'этим утром',
    'поднял(?:ся|ась|ись)', 'вернул(?:ся|ась|ись)', 'спустил(?:ся|ась|ись)',
    'добрал(?:ся|ась|ись)', 'дош[её]л', 'ночевал[иа]?', 'поднимались', 'увидел[а]?',
  ].join('|') + ')' + R,
  'giu',
);

/** Ощущения и обращение к читателю — то, что промпт 19.09 запретил писать без источника. */
const IMPRESSION = new RegExp(
  L + '(' + [
    'запах\\p{L}*', 'пахн\\p{L}*', 'тишин\\p{L}*', 'слышн\\p{L}*', 'слышен',
    'чувству\\p{L}*', 'дышит', 'ты',
  ].join('|') + ')' + R,
  'giu',
);

function collect(re: RegExp, text: string): string[] {
  const out = new Set<string>();
  for (const m of text.matchAll(re)) out.add(m[1].toLocaleLowerCase('ru-RU'));
  return [...out];
}

export function descriptionVoice(text: string | null | undefined): VoiceVerdict {
  const t = stripTags(text ?? '');
  const diary = collect(DIARY, t);
  if (diary.length > 0) return { voice: 'diary', markers: diary };
  const impression = collect(IMPRESSION, t);
  if (impression.length > 0) return { voice: 'impression', markers: impression };
  return { voice: 'plain', markers: [] };
}
