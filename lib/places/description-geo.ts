/**
 * lib/places/description-geo.ts — описание называет одно, координата говорит
 * другое.
 *
 * ── Повод (20.09) ─────────────────────────────────────────────────────────
 *
 * За два дня сочинённое описание нашлось у ЧЕТЫРЁХ мест подряд:
 *
 *   «Каньон Опасный»        — «у подножия вулкана Карымский», стоя у Мутновского;
 *   «Крылья Гамулов»        — «в окрестностях Мутновского», будучи на Шивелуче;
 *   «Каньон Сноубордистов»  — «на реке Половинка в 30 км от Петропавловска»,
 *                             будучи перевалом над Эссо за пятьсот километров;
 *   «Сопка Никольская»      — городской холм с профилем вулкана (миграции 972-974).
 *
 * Все четыре нашлись СЛУЧАЙНО, по ходу другой работы. Значит их больше, а
 * способ поиска — «наткнуться глазами» — находит не худшее, а то, куда
 * посмотрели. Тот же урок, что с координатами до сверки с OSM: платит за
 * находку человек в поле.
 *
 * ── Улика ─────────────────────────────────────────────────────────────────
 *
 * У всех четырёх одна форма: описание НАЗЫВАЕТ географический объект, который
 * мы знаем по имени и координате, и утверждает, что место рядом с ним, — а
 * координата самого места далеко. Проверяется это своими данными, без сети:
 * имена и координаты у нас есть.
 *
 * Приём тот же, что у подсказчика связей (`lib/routes/place-link`): совпадение
 * имени — УЛИКА, а не приговор. Здесь она слабее, чем там, и это сказано
 * прямо ниже.
 *
 * ── Чего эта перепись НЕ умеет, и это не мелочь ───────────────────────────
 *
 *   - она видит только объекты, которые есть В НАШЕЙ базе. «Река Половинка»
 *     у нас местом не записана, и выдумку про Сноубордистов перепись бы не
 *     нашла по этой фразе (нашла бы по «Петропавловска», если бы рядом не
 *     стояло расстояние). Описание, сочинённое про неизвестный нам объект,
 *     невидимо ПО ПОСТРОЕНИЮ — это «проверить нечем», и такие места считаются
 *     отдельно, а не записываются в чистые;
 *   - русское склонение разбирается грубо, по основе слова. «Карымский»,
 *     «Карымского», «Карымская» дают одну основу — это и нужно; но основа
 *     короче шести букв отбрасывается, иначе «Горелый» ловил бы «горы»;
 *   - упоминание С РАССТОЯНИЕМ («в 40 км от Петропавловска») — законное:
 *     описание не утверждает, что место ТАМ, оно говорит, как далеко. Такие
 *     считаются отдельно и в улики не идут.
 *
 * Поэтому исход у переписи три, а не два: «улика есть», «улик нет», «сверить
 * не с чем» (§4.0).
 */

/** Слова-роды в начале имени: они не опознают объект, а называют его вид. */
const TYPE_WORDS = [
  'вулкан', 'сопка', 'гора', 'озеро', 'река', 'ручей', 'бухта', 'мыс',
  'остров', 'пляж', 'водопад', 'каньон', 'перевал', 'долина', 'плато',
  'ледник', 'источник', 'источники', 'парк', 'заповедник', 'кальдера',
  'урочище', 'скала', 'скалы', 'музей', 'посёлок', 'поселок', 'село',
];

/**
 * Окончания, которые снимаются, чтобы «Карымский» и «Карымская» сошлись.
 *
 * Суффикс `-ск-` НЕ снимается, и это не оплошность. Первая редакция резала
 * «ский» целиком, «Мутновский» давал основу «мутнов», и она находилась в
 * слове «мутноватый» — собственный сторож поймал это на первом же прогоне.
 * Отсюда правило: режем только падежное окончание («ий», «ая», «ого»),
 * оставляя «мутновск» — кусок, который в обычном слове не встречается.
 *
 * Порядок — от длинного к короткому: иначе «ого» никогда не снялось бы,
 * потому что раньше сработало бы «о».
 */
const ENDINGS = [
  'ого', 'ому', 'ыми', 'ими', 'ая', 'ое', 'ые', 'ие', 'ий', 'ый', 'ой', 'ую',
  'ам', 'ах', 'ов', 'ев', 'ым', 'им', 'ем', 'ом', 'у', 'ю', 'а', 'я', 'е', 'и', 'ы', 'о',
];

/** Основа короче этого не ищется: слишком много ложных совпадений. */
export const MIN_STEM = 6;

/**
 * Опознавательная основа имени места: без рода, без скобок, приведённая к
 * нижнему регистру и обрезанная по окончанию. `null` — имя слишком короткое
 * или состоит из одного рода, опознавать нечем.
 */
export function nameStem(name: string): string | null {
  const bare = String(name || '')
    .replace(/\([^)]*\)/g, ' ')
    .replace(/[«»"']/g, ' ')
    .toLocaleLowerCase('ru-RU')
    .replace(/ё/g, 'е');

  // Дефис — разделитель, а не часть слова: «Петропавловск-Камчатский» в
  // тексте склоняется обеими половинами («Петропавловска-Камчатского»), и
  // опознавать его надо по первой — «петропавловск». Со склеенной основой
  // упоминание не находилось вовсе.
  const words = bare.split(/[^a-zа-я0-9]+/i).filter(Boolean);
  // Первое слово, которое не род. Если все слова — роды, опознавать нечего.
  const core = words.find((w) => !TYPE_WORDS.includes(w));
  if (!core || core.length < MIN_STEM) return null;

  for (const end of ENDINGS) {
    if (core.length - end.length >= MIN_STEM && core.endsWith(end)) {
      return core.slice(0, core.length - end.length);
    }
  }
  return core;
}

/** Известный объект: чем опознаём и где он стоит. */
export interface Landmark {
  id: string;
  name: string;
  stem: string;
  lat: number;
  lng: number;
}

/** Упоминание объекта в описании. */
export interface Mention {
  landmark: Landmark;
  /**
   * `stated_distance` — рядом стоит расстояние («в 40 км от Петропавловска»):
   * описание не утверждает, что место ТАМ. `implied_location` — утверждает.
   */
  kind: 'stated_distance' | 'implied_location';
  /** Кусок текста вокруг упоминания — чтобы человек судил словами, а не кодом. */
  quote: string;
}

/** Сколько знаков перед именем смотрим в поисках расстояния. */
const DISTANCE_WINDOW = 48;
const DISTANCE_RE = /\d+\s*(?:км|килом)/i;

/**
 * Упоминания известных объектов в описании (чистая, без сети и базы).
 *
 * `selfStem` — основа имени САМОГО места: собственное имя в описании не улика.
 */
export function findMentions(description: string, gazetteer: Landmark[], selfStem: string | null): Mention[] {
  const text = String(description || '').replace(/ё/g, 'е');
  const hay = text.toLocaleLowerCase('ru-RU');
  const out: Mention[] = [];
  const seen = new Set<string>();

  for (const lm of gazetteer) {
    if (!lm.stem || lm.stem === selfStem) continue;
    if (seen.has(lm.stem)) continue;

    // Основа ищется как НАЧАЛО слова: «карымск» найдёт «карымский» и
    // «карымская», но не часть другого слова.
    const at = hay.search(new RegExp(`(?:^|[^a-zа-я])${escapeRe(lm.stem)}[a-zа-я]*`, 'i'));
    if (at < 0) continue;

    const before = text.slice(Math.max(0, at - DISTANCE_WINDOW), at);
    out.push({
      landmark: lm,
      kind: DISTANCE_RE.test(before) ? 'stated_distance' : 'implied_location',
      quote: text.slice(Math.max(0, at - 60), Math.min(text.length, at + 60)).replace(/\s+/g, ' ').trim(),
    });
    seen.add(lm.stem);
  }
  return out;
}

function escapeRe(s: string): string {
  return s.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
}
