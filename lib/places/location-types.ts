/**
 * Название типа. Неизвестный ключ — `fallback`, а если его не дали, сам ключ.
 *
 * Сырой ключ наружу — прежнее поведение всех пяти копий, и на экране оно
 * правильное: `pass` видно и чинится, а молчание скрыло бы, что у точки
 * вообще есть тип.
 */
export function locationTypeLabel(type: string | null | undefined, fallback?: string): string {
  if (!type) return fallback ?? LOCATION_TYPES.other;
  return LOCATION_TYPES[type] ?? fallback ?? type;
}

/** То же строчными — для мест, где подпись стоит внутри предложения. */
export function locationTypeLabelLower(type: string | null | undefined, fallback?: string): string {
  return locationTypeLabel(type, fallback).toLocaleLowerCase('ru-RU');
}
