/**
 * lib/places/coord-source.ts — откуда у места координата и что по ней можно
 * утверждать.
 *
 * ── Зачем ──────────────────────────────────────────────────────────────────
 *
 * Ночь 17–18.08 ушла на то, чтобы ЛИНИЯ называла своё происхождение: снята
 * прибором, построена прямыми, пришла импортом. У ТОЧКИ такого не было вовсе.
 *
 * Геокодер поднимает места без GPS в координаты по НАЗВАНИЮ через Nominatim и
 * пишет их в `lat/lng`, ничем не помечая. Снятая точка и угаданная лежали в
 * базе неотличимо.
 *
 * Цена вскрылась на уборке битых привязок: правило объявляло ложью связь
 * «маршрут — точка», если точка дальше двух километров от трека, и в списке
 * на снятие оказались парк Налычево (32 км), Халактырский пляж (4.5), озеро
 * Паланское (3.4). Все три — верные привязки: у протяжённого объекта
 * координата это центроид, и расстояние до неё ничего не говорит.
 *
 * ── Два независимых вопроса ────────────────────────────────────────────────
 *
 * Отсюда правило: расстояние до точки становится ПРИГОВОРОМ только когда
 * известны оба ответа.
 *
 *   1. Точна ли координата?      — `coord_source`
 *   2. Точечный ли сам объект?   — `location_type`
 *
 * Парк с идеально снятой координатой всё равно остаётся парком: его центроид
 * в тридцати километрах от тропы — норма, а не ошибка данных.
 */

/** Откуда взялась координата места. */
export type CoordSource = 'surveyed' | 'geocoded' | 'placeholder' | 'unknown';

/** Как объяснить происхождение координаты человеку. */
export function coordSourceLabel(source: CoordSource): string {
  switch (source) {
    case 'surveyed':    return 'снята на месте';
    case 'geocoded':    return 'угадана по названию';
    case 'placeholder': return 'заглушка вместо координаты';
    case 'unknown':     return 'происхождение не записано';
  }
}

/**
 * Можно ли строить УТВЕРЖДЕНИЕ на этой координате.
 *
 * Только снятая. `unknown` сюда не входит намеренно: для существующих строк
 * это честный ответ «не знаем», а решать по незнанию — то же самое, что
 * решать по догадке. Пока происхождение не проставлено, суждения «точка не на
 * маршруте» просто не выносятся.
 */
export function coordIsTrustworthy(source: CoordSource): boolean {
  return source === 'surveyed';
}

/**
 * Типы мест, которые ТОЧКОЙ и являются.
 *
 * Список намеренно перевёрнут: перечислены точечные, а протяжённым считается
 * всё остальное, включая незнакомый и незаписанный род. Осторожность здесь
 * дешевле — объявив связь ложью, мы удаляем верную привязку; пропустив
 * лишнюю, только оставляем её человеку на разбор.
 *
 * Первая редакция перечисляла наоборот, протяжённые, и незнакомый род
 * молча получал право судить. Поймал собственный сторож.
 *
 * Вулкана здесь нет намеренно: «Вулкан Мутновский» разошёлся со своим же
 * треком на 3.5 км, «Вулкан Толбачик» на 2.4 — конус с полями лавы и
 * подходами шире любого разумного порога, а координата ставится на вершину.
 */
const POINT_TYPES = new Set([
  'hot_spring', 'geyser', 'waterfall', 'viewpoint', 'cabin', 'shelter',
  'spring', 'monument', 'cave', 'camp', 'parking', 'trailhead',
]);

/**
 * Протяжённый ли объект: расстояние до его точки — слабый признак.
 *
 * `null`, пустой и незнакомый род — протяжённые. См. пояснение к POINT_TYPES:
 * ошибиться в эту сторону дешевле.
 */
export function isExtendedObject(locationType: string | null | undefined): boolean {
  if (!locationType) return true;
  return !POINT_TYPES.has(locationType.toLowerCase());
}

/**
 * Можно ли по расстоянию до этой точки судить, проходит ли через неё маршрут.
 *
 * Оба условия сразу: координата снята И объект точечный. Иначе расстояние
 * остаётся подсказкой для человека, но не основанием что-либо удалять.
 */
export function distanceIsMeaningful(
  source: CoordSource,
  locationType: string | null | undefined,
): boolean {
  return coordIsTrustworthy(source) && !isExtendedObject(locationType);
}
