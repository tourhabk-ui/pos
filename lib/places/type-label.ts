export const PLACE_TYPE_LABEL: Record<string, string> = {
  volcano: 'Вулкан', geyser: 'Гейзер', hot_spring: 'Термальный источник',
  lake: 'Озеро', mountain: 'Гора', bay: 'Бухта', river: 'Река',
  waterfall: 'Водопад', beach: 'Пляж', forest: 'Лес',
  historical: 'Историческое место', museum: 'Музей',
  viewpoint: 'Смотровая площадка', cape: 'Мыс', island: 'Остров',
  valley: 'Долина', cave: 'Пещера', rock: 'Скала', other: 'Место',
};

/**
 * Три исхода (§4.0): известный тип → русское имя; тип записан, но слова для
 * него нет → сам слаг (мы ЗНАЕМ значение, не знаем лишь как назвать — это не
 * повод молчать); типа нет → null, и вызывающий не печатает ничего.
 * Умолчания «Место» здесь НЕТ намеренно: оно превращает «не записано» в
 * уверенную категорию.
 */
export function placeTypeLabel(type: string | null | undefined): string | null {
  if (!type) return null;
  return PLACE_TYPE_LABEL[type] ?? type;
}
