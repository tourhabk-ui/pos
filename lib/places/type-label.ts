import { LOCATION_TYPES } from '@/lib/places/location-types';

/**
 * Сохранено как имя: на него ссылаются перепись копий и вызывающие. Это тот
 * же объект, а не его снимок, — копии не создаётся по построению.
 */
export const PLACE_TYPE_LABEL: Record<string, string> = LOCATION_TYPES;

/**
 * Три исхода (§4.0): известный тип → русское имя; тип записан, но слова для
 * него нет → сам слаг (мы ЗНАЕМ значение, не знаем лишь как назвать — это не
 * повод молчать); типа нет → null, и вызывающий не печатает ничего.
 * Умолчания «Место» здесь НЕТ намеренно: оно превращает «не записано» в
 * уверенную категорию.
 */
export function placeTypeLabel(type: string | null | undefined): string | null {
  if (!type) return null;
  return PLACE_TYPE_LABEL[type] ?? type;
}
