/**
 * Описание, записанное по решению владельца, машины не переписывают (27.09).
 *
 * Повод. 26.09 миграция 1034 положила озеру Микижа текст из слова владельца и
 * его снимков: 235 знаков, пять фактов, журнал происхождения `owner-decision`.
 * К утру на проде лежал другой текст — те же факты, дописанные моделью:
 * «добраться можно на автомобиле», «подходит для прогулок и рыбалки»,
 * «комфортнее в тёплое время года». Ни одного из этих утверждений владелец не
 * делал, рыбу на снимках не видно.
 *
 * Механизм тот же, что описан в шапке `app/api/admin/enrich-places`, только
 * замкнулся он на чужом тексте: очереди на описание берут КОРОТКОЕ как
 * недописанное (`enrich-places` — короче 250 знаков, Editor — короче 300 после
 * недели покоя), а свой собственный прежний текст каждая очередь исключала,
 * решение же человека — ни одна. Короткий текст по слову владельца — ответ, а
 * не недоработка, и дописать его модель может только выдумкой (§4.0).
 *
 * Условие одно на обе очереди: разойдись они — одна переписывала бы то, что
 * другая бережёт.
 */

/** Имя писателя в `description_provenance` для текста по решению владельца. */
export const OWNER_DECISION_WRITER = 'owner-decision';

/**
 * SQL-условие «у записи нет описания по решению владельца». `entityIdExpr` —
 * выражение с ark_id записи (uuid): `p.ark_id` для places, `ark.id` для VIEW
 * agent_route_knowledge. Подставляется выражение кода, не ввод.
 */
export function notOwnerDecidedSql(entityIdExpr: string): string {
  return `NOT EXISTS (
         SELECT 1 FROM description_provenance dp_owner
          WHERE dp_owner.entity_id = ${entityIdExpr}
            AND dp_owner.written_by = '${OWNER_DECISION_WRITER}'
       )`;
}
