/**
 * Сколько нажатие кнопки ждёт отправку сообщения человеку.
 *
 * Обычная отправка — доли секунды; зависший канал держал бы ответ партнёру до
 * двух минут (все ноги по своему сроку): сайт показал бы «нет связи» по
 * ответу, который записан, а вебхук мессенджера ждал бы ответа. После срока
 * работа не отменяется: исход запишется в строку сообщения, обрыв подберёт
 * добивка, повторное нажатие его назовёт.
 *
 * Сначала срок был только у «Не могу» перевозчика и прокатчика (2б-2); с 2в
 * он один и у нажатия туроператора: проверка дат после отказа по погоде
 * добавила к ожиданию ещё до десяти секунд (ревью 2в, п. 6).
 */
export const NOTICE_PRESS_BUDGET_MS = 20_000;

/** Итог работы, если она уложилась в срок нажатия; иначе `late`. Работа после срока идёт сама. */
export async function withinPress<T>(work: Promise<T>, late: T, ms: number = NOTICE_PRESS_BUDGET_MS): Promise<T> {
  let timer: ReturnType<typeof setTimeout> | undefined;
  const expired = new Promise<T>((resolve) => { timer = setTimeout(() => resolve(late), ms); });
  try {
    return await Promise.race([work, expired]);
  } finally {
    clearTimeout(timer);
  }
}
