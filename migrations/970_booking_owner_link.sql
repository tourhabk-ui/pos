-- 970: бронь находится в личном кабинете — обе привязки к человеку заполнены
--
-- Слово владельца 14.09: «бронь в любом случае должна сохраняться в личном
-- кабинете». Проверка показала, что это не пожелание, а описание дефекта.
--
-- ЧТО НАШЛОСЬ. Платформа привязывает бронь к человеку ДВУМЯ способами, и
-- читатели разделились ровно пополам:
--
--   metadata->>'user_id' (JSONB)        колонка user_id
--   ────────────────────────────        ──────────────────────────────
--   ЛК туриста (/api/bookings)          экспорт ПД (/api/user/export)
--   отмена брони                        операторская статистика
--   админка пользователей               операторские финансы
--   админка броней                      карточка клиента у оператора
--   админский дашборд                   список броней оператора
--
-- `app/api/bookings/tour` пишет ОБЕ — там это сделано явно, с комментарием
-- «user_id и в колонку (не только в metadata)», ссылающимся на PR #321 и на
-- `/api/hub/bookings/create` как на образец. Но в самом create этого больше
-- нет: бронь заводит общий `reserveBooking`, а он пишет ТОЛЬКО колонку.
--
-- Значит бронь, оставленная вошедшим человеком через форму заявки на тур или
-- через Кузьмича, в его личном кабинете НЕ ПОЯВЛЯЕТСЯ и отменить её оттуда
-- нельзя. Оператор её видит, турист — нет.
--
-- Это тот же класс, что уже описан в шапке lib/bookings/reserve.ts: «бронь,
-- которой для платформы не существует». Тогда расходились статус и user_id
-- между двумя копиями кода; теперь разошлись две записи ОДНОГО факта внутри
-- одной строки.
--
-- ЧТО ДЕЛАЕТ ЭТА МИГРАЦИЯ. Выравнивает уже созданные брони в ОБЕ стороны:
-- где заполнена колонка, но пуст metadata — дописывает metadata; где наоборот
-- — заполняет колонку. Односторонний бэкфилл чинил бы только половину
-- читателей, а вторая продолжала бы терять те же самые брони.
--
-- Идемпотентна: оба UPDATE ограничены условием «там, где пусто», и повторный
-- прогон не тронет ни строки. Ничего не удаляет и не перезаписывает
-- существующие значения — при расхождении (в колонке один человек, в metadata
-- другой) строка НЕ трогается вовсе: такое расхождение — не пустота, его
-- нельзя чинить автоматом, не зная, какая из двух записей верна.
--
-- Дубль на этом не исчезает, и это сказано вслух: свести читателей к одному
-- источнику — отдельная работа, здесь она не делается. Сторож
-- tests/unit/booking-owner-link.test.ts держит реестр читателей обеих
-- привязок; он может только сокращаться.

-- 1. metadata из колонки — чинит ЛК и отмену для броней из формы и Кузьмича.
UPDATE operator_bookings
   SET metadata = COALESCE(metadata, '{}'::jsonb) || jsonb_build_object('user_id', user_id::text)
 WHERE user_id IS NOT NULL
   AND (metadata IS NULL OR metadata->>'user_id' IS NULL);

-- 2. Колонка из metadata — чинит экспорт ПД и операторскую сторону для
--    старых броней, заведённых до того, как колонка появилась.
--
--    ПРИВЕДЕНИЯ К uuid ЗДЕСЬ НЕТ ВОВСЕ, и это не осторожность, а починка.
--    Первая редакция писала `SET user_id = (metadata->>'user_id')::uuid` с
--    regex-фильтром в том же WHERE — и была неверна дважды.
--
--    Во-первых, порядок вычисления условий в WHERE НЕ ГАРАНТИРОВАН: планировщик
--    вправе выполнить приведение раньше фильтра, и первая же кривая запись
--    уронила бы всю миграцию. Сторож tests/unit/migration-id-type-domain.test.ts
--    запрещает `::uuid` ровно по этой причине — там же записана история
--    миграции 874, не применявшейся на проде шесть попыток подряд.
--
--    Во-вторых, `metadata` была НЕ КВАЛИФИЦИРОВАНА. У `users` есть своя колонка
--    `metadata`, и в коррелированном подзапросе имя разрешалось во ВНУТРЕННЮЮ
--    область — в `users.metadata`, а не в бронь. Ошибки при этом нет:
--    неоднозначности нет, внутренняя область просто побеждает, условие всегда
--    ложно, миграция тихо не делает ничего. Поймано прогоном на настоящем
--    PostgreSQL; моки этого не ловят — разрешение имён делает сервер.
--
--    Обе болезни лечит одно: значение берётся ИЗ users, а не приводится к его
--    типу. Сравнение идёт в тексте (обе стороны — текст, как требует тот же
--    сторож), алиасы снимают захват имени, а regex стал не нужен: мусор просто
--    не совпадёт ни с одним настоящим id.
UPDATE operator_bookings b
   SET user_id = u.id
  FROM users u
 WHERE b.user_id IS NULL
   AND b.metadata->>'user_id' IS NOT NULL
   AND u.id::text = b.metadata->>'user_id';
