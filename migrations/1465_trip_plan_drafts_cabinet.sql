-- Сохранённая поездка перепроверяется на странице кабинета («Сейчас на ваши
-- даты», #3533). Когда у дня появилось новое предупреждение, человек может
-- подобрать замену дня — она ложится НОВЫМ черновиком плана (1182), а
-- сохранённая поездка не меняется (#3347, рек. 2: «при новом предупреждении —
-- предложить замену дня как новый черновик»).
--
-- Черновик тот же, что у Кузьмича и MCP: без пользователя, 7 дней, доступ по
-- знанию id; открывается на /trip/<id>. Поверхность 'cabinet' нужна странице
-- черновика, чтобы сказать человеку правду о происхождении: прежний текст
-- «план собран в чате, изменить — попросите в том же чате» к нему не подходит.
--
-- Ограничение пересобирается целиком, как в 1184: удалить, если есть, и
-- поставить заново — повторный прогон даёт то же. Транзакцию держит
-- раннер миграций.

ALTER TABLE trip_plan_drafts DROP CONSTRAINT IF EXISTS trip_plan_drafts_surface_check;
ALTER TABLE trip_plan_drafts ADD CONSTRAINT trip_plan_drafts_surface_check
  CHECK (surface IN ('chat', 'mcp', 'group', 'cabinet'));

