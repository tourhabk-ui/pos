-- 13.10 (решение владельца «согласен, перенеси в S3»): байты снимков вынесены в
-- хранилище — ключ migrations/photos/<sha256>.jpg из маркера
-- .github/triggers/migration-photos-to-s3.json (sha256 тех же байтов). Миграция
-- пишет s3_key, image_data пуст; прод переведён по хэшу байтов миграцией 1228.
--
-- 1001: Алаид — снимок Склярова всё-таки встаёт. Разбор, почему 996 не сработала.
--
-- ── Что случилось ─────────────────────────────────────────────────────────
--
-- Миграция 996 положила кадр Андрея Склярова на карточку Алаида и НЕ положила.
-- Отчитался я тогда словом, а не проверкой; проверка пришла позже (проба 556)
-- и сказала прямо: карточка отдаёт 93 627 байт из хранилища, а в 996 записано
-- 144 728 байт. Числа разные — значит на карточке лежит ПРЕЖНИЙ снимок.
--
-- Сработало условие, которое я сам же в 996 и написал:
--
--   WHERE ai_route_images.model NOT IN ('wikimedia', 'manual-upload')
--
-- то есть «машинную картинку заменяем, чужой РУЧНОЙ снимок — нет». Строка на
-- Алаиде была `manual-upload`, и замена не состоялась. Предупреждение об этом
-- миграция честно написала в лог выката — я в него не посмотрел.
--
-- ── Почему условие было неправо именно здесь ──────────────────────────────
--
-- Правило защищает РАБОТУ НАЗВАННОГО ЧЕЛОВЕКА: не затирать чужой кадр своим.
-- Но у лежащей строки `author` пуст — проба 555 показала
-- `photoAttribution: null` на живой карточке. Строка без автора не называет
-- никого: защищать ею нечего, а закрывать ею подписанный кадр не за что.
--
-- Это тот же разбор, по которому 22 снимка с Викимедии до сих пор СКРЫТЫ:
-- без автора публиковать нельзя. Здесь та же посылка дала обратный вывод —
-- неподписанный кадр уступает подписанному, а не наоборот.
--
-- Поэтому в условие добавлена ветвь `author IS NULL` (впервые применена в
-- миграции 1000). Граница «чужой ручной снимок не трогаем» никуда не делась:
-- строка с ИМЕНЕМ по-прежнему неприкосновенна.
--
-- ── Основание публикации то же, что в 996 ─────────────────────────────────
--
-- Владелец 20.09, дословно: «Алаид Фото Андрея Склярова / публиковать можно».
-- Автор назван, разрешение дал владелец. Письменного слова самого автора у
-- меня нет, и вид, что оно есть, я не делаю.
--
-- Лицензия не ставится: её никто не называл.
--
-- ── Что на кадре и размер ─────────────────────────────────────────────────
--
-- Симметричный снежный конус над водой, птицы, тёмная полоса берега — вид с
-- моря, а других способов увидеть Алаид у туриста почти нет. Исходник
-- 1280x960, окно 16:9 полной ширины со смещением 90 пикселей сверху (срезан
-- чёрный угол иллюминатора). Записывается 1280x720, ровно канон.
--
-- Байты те же, что в 996: файл не переделывался, менялось только условие.
--
-- IDEMPOTENT

BEGIN;

INSERT INTO ai_route_images (route_id, image_data, mime_type, prompt, model, width, height, author, s3_key)
SELECT p.ark_id,
       NULL::bytea,
       'image/jpeg',
       'снимок Андрея Склярова: Алаид с моря (миграция 996)',
       'manual-upload',
       1280,
       720,
       'Андрей Скляров',
       'migrations/photos/6b4c7452bce2806b480474c175439d67649c6e24237a615f5b253fda78e1c799.jpg'
  FROM places p
 WHERE p.id::text = 'c962d02c-ce85-4d9f-aa54-272944de56f2'
   AND p.ark_id IS NOT NULL
 LIMIT 1
ON CONFLICT (route_id) DO UPDATE
   SET image_data = EXCLUDED.image_data,
       mime_type  = EXCLUDED.mime_type,
       prompt     = EXCLUDED.prompt,
       model      = EXCLUDED.model,
       width      = EXCLUDED.width,
       height     = EXCLUDED.height,
       author     = EXCLUDED.author,
       s3_url     = NULL,
       s3_key     = EXCLUDED.s3_key,
       created_at = NOW()
 WHERE ai_route_images.model NOT IN ('wikimedia', 'manual-upload')
    OR ai_route_images.author IS NULL
    OR ai_route_images.prompt = 'снимок Андрея Склярова: Алаид с моря (миграция 996)';

-- ── Отказ называется вслух ────────────────────────────────────────────────
DO $$
DECLARE
  v_ark    uuid;
  v_author text;
BEGIN
  SELECT ark_id INTO v_ark FROM places WHERE id::text = 'c962d02c-ce85-4d9f-aa54-272944de56f2';

  IF v_ark IS NULL THEN
    RAISE WARNING '[1001] у «Алаида» нет ark_id — снимок НЕ лёг, карточка осталась без фото';
    RETURN;
  END IF;

  SELECT author INTO v_author FROM ai_route_images WHERE route_id = v_ark;

  IF v_author IS DISTINCT FROM 'Андрей Скляров' THEN
    RAISE WARNING '[1001] герой «Алаида» ВТОРОЙ РАЗ не стал снимком Склярова: там %', COALESCE('автор «' || v_author || '»', 'строки снимка нет');
  END IF;
END $$;

COMMIT;
