DO $$
DECLARE
  v_reserve int;
  v_dead int;
  v_lake boolean;
BEGIN
  SELECT count(*) INTO v_reserve FROM places
   WHERE eco_zone = 'federal_reserve'
     AND eco_permit_url = 'https://kronoki.ru/ru/visit/requests/'
     AND id::text IN ('796c18b3-e199-4ac6-bbd6-de50d560ff40', '5957e702-652f-4c8f-8fbd-96b5625272e0',
                      'a3ffa47b-2d9c-4d0e-a9f8-7c594b4f4041', '44be8f5a-809d-47aa-bfa9-858e65cdfe77',
                      '4dbbbef6-100b-46fa-8721-41ed9fe377a4');
  SELECT count(*) INTO v_dead FROM places
   WHERE is_visible = TRUE AND merged_into_id IS NULL
     AND eco_permit_url IN ('https://kronoki.ru/visit/', 'https://kamchatkaparks.ru/');
  SELECT description LIKE 'Кроноцкое — самое большое пресноводное озеро Камчатки%' INTO v_lake
    FROM places WHERE id::text = 'a3ffa47b-2d9c-4d0e-a9f8-7c594b4f4041';
  RAISE NOTICE '[1274] мест Кроноцкого заповедника с режимом по контуру: % из 5; видимых мест с мёртвым адресом разрешения: %; Кроноцкое озеро по источнику: %',
    v_reserve, v_dead, COALESCE(v_lake::text, 'места нет');
  IF v_dead > 0 THEN
    RAISE WARNING '[1274] мёртвый адрес разрешения остался у % видимых мест — режим правили рукой или место вне этого списка', v_dead;
  END IF;
END $$;

COMMIT;

