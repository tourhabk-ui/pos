-- 1274: Режим мест, поставленный по ILIKE 169/170, — по контуру охраняемой
--       территории; мёртвые адреса разрешения сняты; Кроноцкое озеро — по
--       источнику вместо очерка с нерпой.
-- Created: 2026-10-15
--
-- ── Почему ────────────────────────────────────────────────────────────────
--
-- Владелец 15.10: «что по остальным местам — там много неправды» (§0
-- «честность»). 1273 сняла с десяти мест шаблонные правила 169/170; род
-- территории и пропуск им ставил тот же ILIKE: «кроноцк» в описании —
-- заповедник, «unesco» — ЮНЕСКО, «быстрин» или «налычево» в зоне — природный
-- парк. Перепись place-eco-census назвала их поимённо (пробы 947, 948).
--
-- Сверка показала три рода неправды:
--   * адрес разрешения мёртв: kronoki.ru/visit/ отвечает 404 (проба 948), а
--     kamchatkaparks.ru не ответил ни разу за 59 попыток (проба 947). Кнопка
--     «Как получить разрешение» вела в никуда у девяти мест;
--   * род территории чужой: Ново-Бакенинг — не природный парк, а Тимоновский
--     заказник; «Голая», Асача, вулкан Академии Наук и кратер Троицкого не
--     лежат ни в одной охраняемой территории, а карточки звали за пропуском в
--     заповедник, парк и заказник;
--   * «ЮНЕСКО» — статус, а не режим: Долина гейзеров — в Кроноцком
--     заповеднике, и разрешение у неё заповедника.
--
-- ── Как решено — по контуру, не по имени (как 1252) ──────────────────────
--
-- Overpass is_in на точке каждого места, фильтр областей boundary=protected_area,
-- leisure=nature_reserve, boundary=national_park (пробы 950, 951; 949 и
-- часть 950 — отказ зеркал, переспрошено):
--
--   Кроноцкий заповедник (отношение OSM 2800189, protect_class 1a):
--     796c18b3 Долина гейзеров, 5957e702 Вид на гейзер Большой,
--     a3ffa47b Озеро Кроноцкое, 44be8f5a Вулкан Кроноцкий,
--     4dbbbef6 Вид на вулкан Шмидта с Гамченского дола;
--   Тимоновский заказник (отношение OSM 10254493, protect_class 4,
--     «Государственный природный заказник», региональный):
--     9c5b9b5c Ново-Бакенинг. Сам заказник называет и Википедия
--     («Тимоновские источники»: «Тимоновский государственный зоологический
--     заказник», миграция 1257);
--   ни одной охраняемой территории:
--     f4fa9a04 Вулкан Академии Наук, d9cc68bc Голая, ce3db5c5 Асача (проба
--     952), 0cc4d973 Кратер Троицкого. Точка кратера — та же, что у объекта
--     OSM «Кратер Троицкого» (Nominatim, проба 952), то есть стоит на самом
--     кратере, а не мимо него.
--
-- Режим пишется ТОЛЬКО поверх состояния 169/170: шаблон снят 1273, свои
-- правила не записаны, адрес — один из шаблонных (у Асачи — никакого).
-- Правленное рукой не трогается.
--
-- ── Правила заповедника ──────────────────────────────────────────────────
--
-- Те же, что у карточки «Кроноцкий заповедник» (1240), и с теми же
-- источниками: порядок посещения — kronoki.ru/ru/visit/requests/ и
-- tourism@kronoki.ru (сверено владельцем 27.07, миграция 781; страница жива —
-- проба 949, «Заявки на посещение территорий Кроноцкого и Корякского
-- заповедников, Южно-Камчатского заказника»); группы с гидом и регистрация в
-- МЧС — паспорта маршрутов заповедника; телефон службы охраны — подвал сайта
-- kronoki.ru (1252). Режим территории — это режим каждой её точки, поэтому
-- правила у мест внутри контура те же, что у заповедника.
--
-- ── Кроноцкое озеро ──────────────────────────────────────────────────────
--
-- Описание — очерк без источника, и он спорит с источником трижды: «озеро,
-- скованное кальдерой древнего вулкана» — по Википедии кальдерное
-- происхождение опровергнуто, озеро подпружено лавой около 10 000 лет назад;
-- «дно видно на десятки метров» — прозрачность до 6 м; «плеск нерпы» — в
-- озере две рыбы, кокани и голец, нерпы в описании фауны нет. Заметка
-- Кузьмича пересказывает ту же нерпу. Очерк — в архив description_withdrawn
-- («прячем, не удаляем»), справка — по статье «Кроноцкое» русской Википедии
-- (проба 951); заметка Кузьмича — пустая строка, как в 1244, 1246, 1252.
-- Глубину статья называет дважды по-разному (148 и 136 м) — текст называет оба.
--
-- ПОСЛЕ ВЫКАТА: полевая карта читает статичные пакеты мест — нужен перезалив
-- map-places-build (upload:true).
--
-- IDEMPOTENT: каждое UPDATE стоит на условии прежнего состояния.

