-- 919: у бассейна с термальной водой было описание, но не было имени.
--
-- Владелец 30.08, стоя рядом (форма /field-check «Что рядом», 0.1 км от его
-- живого GPS): запись «Большой плавательный бассейн с термальной водой»
-- (53.28768, 158.34904) — это «Раздолье Камчатки». Источник — тот, кто
-- физически на месте, сверено вживую, не по памяти.
--
-- Описание не трогаем: оно про сам бассейн (вода, запах, зимний пар) и
-- остаётся верным под правильным именем. Правим только name — единственное,
-- что было неточным.
--
-- Идемпотентна: WHERE бьёт по старому имени + координатам (допуск ~55 м на
-- каждую ось) — второй прогон не находит строку (имя уже новое) и ничего
-- не делает.

BEGIN;

UPDATE places
SET name = 'Раздолье Камчатки',
    updated_at = now()
WHERE name = 'Большой плавательный бассейн с термальной водой'
  AND lat BETWEEN 53.28718 AND 53.28818
  AND lng BETWEEN 158.34854 AND 158.34954
  AND is_visible = TRUE;

COMMIT;
