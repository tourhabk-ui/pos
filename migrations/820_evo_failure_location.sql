-- Migration 820: где именно сломалось — ребро и виновная сторона
--
-- Схема из «Model or Harness?» (Scale AI, arXiv:2607.28802): единица анализа не
-- компонент, а РЕБРО между двумя компонентами плюс сторона, подлежащая починке.
--
-- Зачем колонки. Точность эволюции считалась одним числом на все находки и
-- понималась как «врёт ли модель». Но половина находок — про инфраструктуру:
-- сборку, деплой, сеть, наши же сторожа. Отвергнутая инфраструктурная находка
-- тянула вниз общий порог, из-под которого гаснут КОД-находки: модель получала
-- штраф за то, к чему отношения не имеет, и замолкала.
--
-- Значения не ограничиваем CHECK'ом жёстко к списку: словарь компонентов живёт
-- в lib/agents/evo/failure-taxonomy.ts и будет уточняться по мере того, как мы
-- разбираем собственные сбои. Ограничение в схеме потребовало бы миграции на
-- каждое уточнение словаря, а несогласованную метку и так режет код (проверка
-- isConsistent: сторона обязана участвовать в ребре).
--
-- Старые записи остаются с NULL и это осмысленно: «не размечено» — не то же
-- самое, что «виновата модель». Метрика на NULL падает на прежнее правило по
-- категории, поэтому смысл уже накопленных данных не меняется задним числом.
--
-- Идемпотентна.

ALTER TABLE evo_growth_issues
  ADD COLUMN IF NOT EXISTS edge       VARCHAR(64),
  ADD COLUMN IF NOT EXISTS fault_side VARCHAR(32);

COMMENT ON COLUMN evo_growth_issues.edge IS
  'Ребро взаимодействия «a—b» (стороны отсортированы), где возник отказ. Словарь: lib/agents/evo/failure-taxonomy.ts';
COMMENT ON COLUMN evo_growth_issues.fault_side IS
  'Компонент, который надо чинить. NULL = не размечено, НЕ «виновата модель».';

-- Точность считается в разрезе стороны, поэтому индекс по ней и статусу.
CREATE INDEX IF NOT EXISTS idx_evo_issues_fault_side
  ON evo_growth_issues(fault_side, status);
