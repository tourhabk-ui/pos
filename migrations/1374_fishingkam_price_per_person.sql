-- 1374: цены «Камчатской рыбалки» 7, 9, 10, 11 — за человека, не за группу.
--
-- Слово владельца 03.11.2026: «цена за 1 человека»; группа — до числа мест
-- тура. В базе у этих туров стояло per_tour, и каталог/агенты печатали
-- «45 000 ₽/группа» (а #3005 делил цену на группу — для них неверно).
--
-- Сверка с fishingkam.ru (03.11.2026): на сайте цены «за 1 сутки
-- пребывания» 18–28 тыс. ₽, минимальная группа 5 человек; многодневных
-- сумм 45/140/150/196 тыс. на странице нет. 140 000 = 5 × 28 000 и
-- 196 000 = 7 × 28 000 — сходится с ценой с человека за сутки. Числа цен
-- НЕ меняются, меняется только единица. max_participants не трогаем.
--
-- Якорь — id + оператор (как 837/914/916); только поверх per_tour, идемпотентно.
UPDATE operator_tours ot
   SET price_unit = 'per_person',
       updated_at = NOW()
 WHERE ot.id IN (7, 9, 10, 11)
   AND ot.deleted_at IS NULL
   AND ot.price_unit = 'per_tour'
   AND ot.operator_id = (SELECT id FROM partners WHERE name ILIKE '%камчатская рыбалка%' LIMIT 1);
