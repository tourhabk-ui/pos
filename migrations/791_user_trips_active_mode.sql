-- Migration 791: явно выбранная активная поездка
--
-- Режим главной «я в поездке» включается кнопкой, а не датами (решение
-- владельца 29.07.2026): даты сдвигаются, и автопереключение показало бы
-- режим маршрута тому, кто ещё не вышел, или спрятало бы его у вышедшего
-- раньше срока.
--
-- Хранить один только момент включения недостаточно. У человека может быть
-- несколько сохранённых поездок, и timestamp не отвечает на главный вопрос —
-- КАКОЙ маршрут показывать. Поэтому храним саму поездку.
--
-- ON DELETE SET NULL, а не CASCADE: физическое удаление поездки должно гасить
-- режим, а не удалять пользователя.
--
-- ВАЖНО: рабочий путь удаления поездки — МЯГКИЙ (DELETE /api/trips/[id]
-- проставляет deleted_at, строка остаётся). На него каскад не срабатывает
-- вовсе, поэтому режим там гасится явно, в одной транзакции с удалением.
-- Этот внешний ключ — страховка на случай физической чистки, а не основной
-- механизм. Полагаться на него одного значит однажды получить «призрачный»
-- режим: поездки в списке нет, а главная показывает маршрут.
--
-- Уникальность не нужна отдельным индексом: колонка на стороне users, у
-- пользователя одна строка — «не более одной активной поездки» выполняется
-- by construction. Инвариант записан здесь, чтобы его не пытались обеспечить
-- второй раз таблицей-связкой.
--
-- Идемпотентна.

ALTER TABLE users
  ADD COLUMN IF NOT EXISTS active_trip_id UUID,
  ADD COLUMN IF NOT EXISTS active_trip_since TIMESTAMPTZ;

DO $$
BEGIN
  IF NOT EXISTS (
    SELECT 1 FROM pg_constraint WHERE conname = 'users_active_trip_id_fkey'
  ) THEN
    ALTER TABLE users
      ADD CONSTRAINT users_active_trip_id_fkey
      FOREIGN KEY (active_trip_id) REFERENCES user_trips(id) ON DELETE SET NULL;
  END IF;
END $$;

-- Частичный индекс: строк с включённым режимом мало, полный индекс не нужен.
CREATE INDEX IF NOT EXISTS idx_users_active_trip
  ON users(active_trip_id)
  WHERE active_trip_id IS NOT NULL;

COMMENT ON COLUMN users.active_trip_id IS
  'Поездка, для которой включён режим «на маршруте». NULL — гостевая главная. Включается только явным действием пользователя.';
COMMENT ON COLUMN users.active_trip_since IS
  'Когда режим включили. Справочно: решение о показе принимает active_trip_id, не эта колонка.';
