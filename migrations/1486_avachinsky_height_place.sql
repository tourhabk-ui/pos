-- 1486: Высота на карточке Авачинского вулкана — 2751 м по KVERT.
-- Created: 2026-11-21
--
-- Проверка прода 21.11 (Сыщик): в справке /places/vulkan-avachinskij (1253,
-- сайт парка «Вулканы Камчатки») высоты нет вовсе — ни 2751, ни 2741, хотя
-- планы, тур, статья и летопись уже говорят 2751 м (1479). Решение по высоте —
-- одно значение по KVERT; атрибуция названа в самой фразе, потому что
-- источник карточки — сайт парка, а высота — из KVERT.
--
-- IDEMPOTENT: только если в описании ещё нет «2751» и стоит фраза из 1253.

BEGIN;

UPDATE places
   SET description = replace(
         description,
         'Это сложно построенный вулкан типа Сомма-Везувий с правильным конусом.',
         'Это сложно построенный вулкан типа Сомма-Везувий с правильным конусом; высота — 2751 м '
         || '(по данным KVERT, Камчатской группы реагирования на вулканические извержения).'),
       updated_at = NOW()
 WHERE (id::text = '3a98a68d-76c8-4835-8d6d-24f7dd867cb8' OR slug = 'vulkan-avachinskij')
   AND position('2751' in description) = 0
   AND position('Это сложно построенный вулкан типа Сомма-Везувий с правильным конусом.' in description) > 0;

COMMIT;
