--
-- ЧТО ПРОИЗОШЛО. 30.08 подряд легли две миграции:
--
--   919 — по слову владельца, стоявшего НА МЕСТЕ (форма /field-check, 0.1 км
--         от его живого GPS), ПЕРЕИМЕНОВАЛА существующую запись «Большой
--         плавательный бассейн с термальной водой» в «Раздолье Камчатки».
--         Переименовала только name: ни slug, ни location_type, ни описание.
--
--   925 — завела «Зеленовские озерки» и «Раздолье Камчатки» как две записи,
--         со скважиной № 23, бальнеозаключением, типом hot_spring и профилем
--         безопасности. Вставка Раздолья защищена гардом
--         `WHERE NOT EXISTS (SELECT 1 FROM places WHERE name ILIKE '%раздолье камчатки%')`.
--
-- Гард сработал ровно так, как написан: к моменту 925 имя уже стояло — его
-- поставила 919 шестью номерами раньше. Вставка НЕ прошла, и вместе с ней
-- молча не прошло всё, что было привязано к её ark_id b2f6d8e4…:
--
--   * сама запись с описанием скважины и типом hot_spring;
--   * слаг `razdolie-kamchatki`;
--   * профиль безопасности (режим ванн, противопоказания) — у него
--     `AND EXISTS (SELECT 1 FROM places WHERE ark_id = …)`;
--   * снимок владельца (миграция 964) — у него `FROM places p WHERE p.id = …`.
--
-- Четыре молчаливых отказа подряд: каждый гард честно проверил условие и
-- честно ничего не сделал. Никто не соврал — и именно поэтому никто не
-- закричал. Ровно §4.0 наоборот: «не смог» здесь выглядел как «нечего делать».
--
-- ПОЧЕМУ ПОЧИНКА ИДЁТ ПО ИМЕНИ, А НЕ ПО UUID. UUID b2f6d8e4… на проде не
-- существует и не появится: 925 уже отмечена применённой. Живая запись — та,
-- которую переименовала 919, и её id нам неизвестен. Поэтому всё ниже ищет
-- строку по ИМЕНИ и правит только то, что ещё не починено.
--
-- КООРДИНАТЫ НЕ ТРОГАЕМ. У живой записи 53.28768 / 158.34904 — это замер
-- владельца на месте; у 2ГИС 53.288365 / 158.350074, между ними около 100 м.
-- Полевой замер сильнее карточки справочника (правило 23.08: улика — не
-- приговор, координату без источника не двигают).
--
-- ОПИСАНИЕ ЗАМЕНЯЕТСЯ. Старый текст про бассейн пришёл импортом и источника
-- не называет; текст 925 опирается на бальнеозаключение НИИ медицинской
-- климатологии по скважине № 23. Замена идёт только если починки ещё не было.
--
-- IDEMPOTENT

BEGIN;

-- ── 1. Тип места ─────────────────────────────────────────────────────────
-- Без него карточка пишет «МЕСТО» и берёт заглушку вместо фото.
UPDATE places
   SET location_type = 'hot_spring',
       category      = COALESCE(category, 'hot_spring'),
       updated_at    = now()
 WHERE name = 'Раздолье Камчатки'
   AND location_type IS DISTINCT FROM 'hot_spring';

-- ── 2. Описание и источник ───────────────────────────────────────────────
UPDATE places
   SET description = '«Раздолье Камчатки» — база отдыха с термальными ваннами у посёлка Раздольный в Елизовском районе, на территории Зеленовских озёр. Вторая, более новая база этого места: соседние «Зеленовские озерки» стоят примерно в ста метрах.

База работает на собственной скважине № 23 Кеткинского месторождения. Скважина пробурена в 1986 году на глубину 341 м и стоит на левом берегу реки Зеленовушки, в 45 метрах от уреза воды; водоносный горизонт вскрыт в интервале 199–329,7 м. Дебит 16,3–20,3 л/с.

Вода по бальнеологическому заключению НИИ медицинской климатологии — слабосероводородная, высокотермальная, хлоридная натриевая, кремнистая, борная. Температура на выходе от +49,2 до +58,5 °C. Минерализация 8,0–8,7 г/дм³, сероводород 18,32–39,2 мг/дм³, метакремниевая кислота 48,8–173,8 мг/дм³, ортоборная кислота 94,6–168,74 мг/дм³, хлорид-ион 4822,56–5448,3 мг/дм³, натрий с калием 2771,8–2797,46 мг/дм³, pH 7,8–8,5.

Скважина здесь другая, чем у соседних Зеленовских озерков, поэтому и анализ воды у двух баз разный — сравнивать их по одному документу нельзя.',
       source_url  = 'https://2gis.ru/p_kamchatskiy/geo/70000001066008836',
       source_name = '2gis+бальнеозаключение НИИ мед. климатологии',
       updated_at  = now()
 WHERE name = 'Раздолье Камчатки'
   AND (description IS NULL OR description NOT LIKE '%скважине № 23%');

-- ── 3. Адрес страницы ────────────────────────────────────────────────────
-- Слаг остался от прежнего имени: ссылка обещает бассейн, открывается
-- «Раздолье Камчатки». Меняем, только если слаг свободен глобально.
UPDATE places
   SET slug = 'razdolie-kamchatki',
       updated_at = now()
 WHERE name = 'Раздолье Камчатки'
   AND (slug IS NULL OR slug <> 'razdolie-kamchatki')
   AND NOT EXISTS (SELECT 1 FROM places WHERE slug = 'razdolie-kamchatki')
   AND NOT EXISTS (SELECT 1 FROM kamchatka_routes WHERE slug = 'razdolie-kamchatki');

-- ── 4. Профиль безопасности ──────────────────────────────────────────────
-- Тот же текст, что 925 писала мёртвому ark_id.
INSERT INTO location_safety_profile
  (agent_route_id, capacity_per_day, difficulty_level, hazard_types, medical_info)
SELECT p.ark_id,
       NULL,
       1,
       ARRAY['thermal']::text[],
       'Сероводородные ванны, вода скважины № 23 на выходе +49,2…+58,5 °C. Рекомендуемая температура ванны 35–38 °C, продолжительность от 5 до 12 минут (максимум 15), начинать с 5–7 минут; курс 12–15 ванн, через день. Детям — с трёх лет, 4–10 минут при 36–37 °C, курс 8–10 ванн; не купать сразу после еды и натощак. Противопоказания: болезни почек и печени, туберкулёз лёгких в активной форме, острые воспалительные процессы (включая ОРЗ), выраженный атеросклероз, гипертоническая болезнь III степени, инфаркт миокарда, сердечная астма, склонность к кровотечениям, тяжёлая форма сахарного диабета, эпилепсия, вторая половина беременности, грибковые заболевания, тяжёлая форма стенокардии.'
  FROM places p
 WHERE p.name = 'Раздолье Камчатки'
   AND p.ark_id IS NOT NULL
   AND NOT EXISTS (
     SELECT 1 FROM location_safety_profile s WHERE s.agent_route_id = p.ark_id
   )
 LIMIT 1;

-- ── 5. Снимок владельца ──────────────────────────────────────────────────
-- Те же байты, что миграция 964 клала мёртвому ark_id. Идемпотентно:
