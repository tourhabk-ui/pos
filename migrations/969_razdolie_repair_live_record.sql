-- 969: «Раздолье Камчатки» — карточка на проде пустая, и это не вёрстка.
--
-- ПОВОД. Владелец 14.09 прислал снимок карточки с телефона и адрес:
--   https://vedarai.ru/places/bolshoj-plavatelnyj-bassejn-s-termalnoj-vodoj
-- В адресе — старое имя записи, на экране «МЕСТО» вместо типа, серая
