-- Migration 775: Вачкажец — проезд открыт ДОСРОЧНО (25.07 вместо 27.07)
--
-- Официальное сообщение Камчатского ЛПУМГ ООО «Газпром трансгаз Томск»,
-- 25.07.2026: движение в охранной зоне газопровода «УКПГ Нижне-Квакчикского
-- ГКМ — АГРС г. Петропавловска-Камчатского» на участке 306-311 км
-- ВОССТАНОВЛЕНО. Это та самая дорога к памятнику природы «Горный массив
-- Вачкажец», закрытие которой заведено миграцией 718 со сроком до 18:00
-- 27.07 (06:00 27.07 UTC).
--
-- Без этой миграции платформа ещё двое суток показывала бы «проезд закрыт»
-- на открытую дорогу — в мобильном баннере, на карточке места и у Кузьмича.
-- Осторожная ложь — всё равно ложь: турист, попавший на открытую дорогу
-- вопреки нашему «закрыто», в следующий раз не поверит и настоящему запрету.
--
-- Вилючинский перевал НЕ трогаем: сообщение подрядчика касается только
-- участка 306-311 км (Вачкажец), пропускной режим перевала действует.
--
-- Идемпотентна: LEAST() не двигает срок повторным прогоном, UPDATE карточки
-- сужен до точного текста, заведённого 718-й, — более новое сообщение,
-- если оно появится, не затрётся.

BEGIN;

-- 1) Гасим алерт: витрины фильтруют expires_at > NOW(), прошедший срок
--    убирает его отовсюду разом. Время — момент официального сообщения,
--    25.07.2026 (23:00 камчатского = 11:00 UTC).
UPDATE external_alerts
SET expires_at = LEAST(expires_at, TIMESTAMP '2026-07-25 11:00:00'),
    description = description || ' ОБНОВЛЕНИЕ 25.07: движение восстановлено досрочно (сообщение Камчатского ЛПУМГ), ограничение снято.'
WHERE external_id = 'manual-vachkazhets-road-2026-07'
  AND description NOT LIKE '%движение восстановлено досрочно%';

-- 2) Снимаем точечное сообщение с карточки места. Только если там всё ещё
--    текст закрытия из 718-й: чужое/более новое сообщение не трогаем.
UPDATE location_real_time_status lrts
SET alert_message    = NULL,
    alert_source     = NULL,
    alert_expires_at = NULL,
    updated_at       = NOW()
FROM places p
WHERE p.ark_id = lrts.agent_route_id
  AND p.name ILIKE '%вачкажец%'
  AND lrts.alert_source = 'manual'
  AND lrts.alert_message LIKE 'Проезд закрыт с 08:00 20.07%';

COMMIT;
