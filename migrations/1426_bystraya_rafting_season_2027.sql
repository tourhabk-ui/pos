-- 1426: сезон тура «Сплав по реке Быстрая» (ID 27, «Камчатка Семейный
-- Рафтинг») — июль — октябрь 2027.
--
-- Источник — анонс самого партнёра, который владелец переслал 12.11.2026
-- (сторис Катерины, соорганизатора, «Лето 2027 · июль — октябрь»). До этого
-- сезон у тура не был записан (955: «сплав, значит лето» — вывод, а не факт),
-- и туристу его не называл ни Ведар, ни Кузьмич. Слово владельца: «да,
-- добавь сезон рафтингу».
--
-- Пишется только в пустые поля: записанный партнёром или кабинетом сезон
-- миграция не перетирает. Идемпотентно.

UPDATE operator_tours
   SET season_start = DATE '2027-07-01',
       season_end   = DATE '2027-10-31',
       updated_at   = NOW()
 WHERE slug = 'splav-bystraya'
   AND deleted_at IS NULL
   AND season_start IS NULL
   AND season_end IS NULL
   AND operator_id::text IN (SELECT id::text FROM partners WHERE slug = 'kamchatka-rafting');
