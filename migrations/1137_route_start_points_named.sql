-- 1137: два места «Точка маршрута (начало)» получают имя своего маршрута.
--
-- Аудит vedarai.ru 01.10: две разные страницы мест выходили в выдачу под
-- одним заголовком «Точка маршрута (начало)» — служебным именем, которое
-- ничего не говорит человеку. Это точки старта двух маршрутов массива
-- Вачкажец (снегоходного и лыжного); к ним ведёт «Пройти сюда с компасом»,
-- поэтому прятать их нельзя.
--
-- Имя не сочиняется: оно берётся из связи, которая есть в данных, — какой
-- маршрут здесь начинается. Описания (честное «точных данных нет») не
-- трогаются. Решение владельца 01.10 («действуй»).
--
-- Идемпотентна: меняет имя, только пока оно служебное.

UPDATE places
   SET name = 'Старт маршрута Вачкажец (снегоходный)',
       updated_at = NOW()
 WHERE ark_id = 'ce16faff-a43c-89bf-a665-9ac7221eb263'::uuid
   AND name = 'Точка маршрута (начало)';

UPDATE places
   SET name = 'Старт маршрута Вачкажец (лыжный)',
       updated_at = NOW()
 WHERE ark_id = '719b7a73-2e99-515a-3cca-7c36748df3b2'::uuid
   AND name = 'Точка маршрута (начало)';
