-- 741_places_geocode_failed_flag.sql
-- «Порядок с местами», шаг 2: флаг неудачного геокодинга плейсхолдер-мест.
--
-- Геокодер (/api/cron/places-geocode) поднимает места без GPS (0,0 или
-- плейсхолдер 53.0444/158.6483) в реальные координаты по названию через
-- Nominatim. Успех убирает место из плейсхолдер-множества. Неудачу помечаем
-- сюда, чтобы не пытаться геокодить одно и то же в каждой партии (иначе
-- цикл-раннер зациклится на нерешаемых). Сброс поля = повторная попытка.

ALTER TABLE places ADD COLUMN IF NOT EXISTS geocode_failed_at TIMESTAMPTZ;
