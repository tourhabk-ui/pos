-- Migration 785: уведомления и связь тура с маршрутом
--
-- Закрывает два последних расхождения схемы с кодом, которые раньше выглядели
-- как «нужно продуктовое решение». Оба разрешились фактами, а не вкусом.
--
-- 1. СВЯЗЬ ТУРА С МАРШРУТОМ. Казалось, что в коде две конкурирующие связи:
--    operator_tours.route_id и operator_tours.agent_route_id. На деле выбора нет:
--    route_id читают живые страницы — карточка точки (JOIN kamchatka_routes kr ON
--    ot.route_id = kr.id), листинг туров оператора, короткие ссылки /p/[code].
--    Если бы колонки не было, эти страницы отдавали бы ошибку, а они работают.
--    Значит route_id в проде есть и просто не объявлен — тот же случай, что
--    telegram_id из миграции 783. Объявляем и индексируем.
--
--    agent_route_id остаётся: это связь с legacy-слоем agent_route_knowledge,
--    у неё своя история и свои читатели. Внешний ключ намеренно НЕ добавляем:
--    на живых данных возможны осиротевшие ссылки, и миграция, которая падает
--    из-за старых записей, хуже отсутствующего ограничения.
--
-- 2. УВЕДОМЛЕНИЯ. Сервис уведомлений писал и читал колонку payload, которой нет
--    ни в одном файле схемы, а таблица держит title и message отдельными
--    NOT NULL. То есть работать он не мог вовсе — и не работал: create ловил
--    ошибку и ВОЗВРАЩАЛ ВЫДУМАННЫЙ ОБЪЕКТ с новым UUID, будто уведомление
--    создано. Вызывающая сторона видела успех, пользователь не получал ничего.
--
--    Выбрана модель таблицы, а не сервиса: отдельные колонки дают NOT NULL,
--    индексы и внятные запросы, а JSON-мешок не даёт ничего из этого и молча
--    теряет форму. Сервис переписан под неё; здесь добавляется единственное,
--    чего таблице действительно не хватало, — updated_at.
--
-- ВАЖНО: выражения с CONCURRENTLY здесь не цитируются. Раннер определяет
-- транзакционность регуляркой по всему тексту файла, комментарии тоже попадают.

-- ── Связь тура с маршрутом ───────────────────────────────────────────────
ALTER TABLE operator_tours
  ADD COLUMN IF NOT EXISTS route_id UUID,
  ADD COLUMN IF NOT EXISTS ai_tags  JSONB DEFAULT '[]'::jsonb;

CREATE INDEX IF NOT EXISTS idx_operator_tours_route_id
  ON operator_tours (route_id) WHERE route_id IS NOT NULL;

-- ── Уведомления ──────────────────────────────────────────────────────────
ALTER TABLE notifications
  ADD COLUMN IF NOT EXISTS updated_at TIMESTAMPTZ DEFAULT NOW();
