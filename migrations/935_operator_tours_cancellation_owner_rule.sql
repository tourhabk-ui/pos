-- 935: условия отмены — правило витрины от владельца.
--
-- После 934 перепись готовности (prod-check run 10, 05.09) назвала у всех
-- восьми живых туров ОДИН оставшийся блокер выкладки на Авито и Яндекс:
-- cancellation_policy пуст. Поле — свободный текст оператора (931), и
-- сочинить его нельзя. Владелец 05.09 дал правило одной фразой:
-- «бесплатная отмена за 3 дня до тура, позже удерживается 50%».
--
-- Пишется ТОЛЬКО в пустое: оператор, уже записавший свои условия в
-- кабинете, их сохраняет. Только живые туры. Формулировка — дословно
-- владельца, без приписок: карточка показывает её как есть, Кузьмич
-- отвечает по ней на «а если отменю».

UPDATE operator_tours
   SET cancellation_policy = 'Бесплатная отмена за 3 дня до тура, позже удерживается 50%.'
 WHERE (cancellation_policy IS NULL OR LENGTH(TRIM(cancellation_policy)) = 0)
   AND deleted_at IS NULL
   AND is_active = TRUE;

