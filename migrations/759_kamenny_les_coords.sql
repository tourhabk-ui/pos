-- 759: «Каменный лес с кустами княженики» — вернуть координату первоисточника.
--
-- Скрин владельца 2026-07-19: в планировщике точка 1 однодневного похода к
-- Авачинскому вулкану лежит в 284.9 км («от меня до Авачинского 20 км»).
-- Координата места в БД уехала на север (след геокодера-заглушки), а в
-- описании при создании (миграции 099/101) задано: «участок смешанного леса
-- у тихоокеанского побережья Авачинского залива (53.13°N, 158.74°E)» — это
-- согласуется и со связкой с однодневкой к Авачинскому. Возвращаем 53.13,
-- 158.74. Диагностика Шага 10 это место не видела: у маршрута NULL-координата
-- (слепое пятно закрыто в этом же PR — медиана waypoints как опорная точка).
--
-- Идемпотентно: guard 30 км — повторный прогон и ручная правка рядом
-- не перетираются.

BEGIN;

UPDATE places
SET lat = 53.13, lng = 158.74, updated_at = NOW()
WHERE name ILIKE '%княженик%'
  AND (
    lat IS NULL OR lng IS NULL
    OR 6371 * acos(least(1.0,
         cos(radians(53.13)) * cos(radians(lat)) * cos(radians(lng) - radians(158.74))
         + sin(radians(53.13)) * sin(radians(lat)))) > 30
  );

COMMIT;
