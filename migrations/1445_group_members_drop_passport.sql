-- 1445: у участника группы больше нет колонок паспорта.
--
-- Аудит схемы #3388, п.1 (слово владельца 15.11 «3388»; к п.1 — «у нас нет
-- реальных клиентов, данные пусты»). В booking_group_members лежали две
-- колонки паспорта: номер открытым текстом (passport_number) и шифрованный
-- (passport_encrypted). Ни одна строка кода их не писала и не читала —
-- только обнуляла при удалении аккаунта (lib/account/erase.ts). Колонка ПД,
-- которую никто не наполняет, — место, куда паспорт однажды ляжет без
-- правила хранения, без шифрования и без согласия на эту цель.
--
-- Понадобится паспорт участника (регистрация группы, договор) — колонку
-- заводят заново вместе с тем, кто её пишет, сроком хранения и согласием.
--
-- Идемпотентна: DROP COLUMN IF EXISTS.

ALTER TABLE booking_group_members
  DROP COLUMN IF EXISTS passport_number,
  DROP COLUMN IF EXISTS passport_encrypted;
