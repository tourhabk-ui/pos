-- 971_nikolskaya_sopka_not_volcano.sql
--
-- «Сопка Никольская» (51598b80-6b92-48d9-beb4-019f824524c9) несла
-- location_type = 'volcano' и показывала на карточке бейдж «ВУЛКАН» —
-- ровно такой же, как у Авачинского. Владелец увидел это на карте 15.09.
--
-- ── Почему это неверно, хотя геологически она вулканического рода ─────────
--
-- Оговорка важная, иначе правка выглядит как спор с фактом: Никольская
-- ДЕЙСТВИТЕЛЬНО старый экструзивный купол, и наше собственное описание
-- называет её так («старый вулканический купол»). Этот факт не трогаем — он
-- остаётся в description, где ему и место.
--
-- Неверен не факт, а КАТЕГОРИЯ. `location_type` на этой платформе работает
-- навигационным разделом, а не геологическим вердиктом: по нему собирается
-- каталог, фильтр и бейдж карточки (app/places/[id]/_PlaceDetailClient.tsx —
-- place.locationType === 'volcano'). Турист, открывший «вулканы», ищет
-- Авачинский, Мутновский, Горелый — восхождение с регистрацией в МЧС. Он
-- получает мемориальный холм ста метров над бухтой в черте
-- Петропавловска-Камчатского, с тем же словом на бейдже и без единой
-- оговорки. Это обещание, которого место не держит.
--
-- Что Никольская на самом деле для туриста, видно по соседям в наших же
-- данных: миграция 103 завела отдельную запись «Никольская сопка — мемориал
-- Петропавловской обороны 1854» с location_type='historical', а миграция 847
-- поставила на её седловину Батарею Максутова (53.0203, 158.6422 — центр
-- города). Смотровая над Авачинской бухтой и памятник, а не вулкан.
--
-- ── Почему 'mountain', а не 'historical' ─────────────────────────────────
--
-- Мемориал уже описан ОТДЕЛЬНОЙ записью (103). Сделать historical и эту —
-- значит завести второй экземпляр одного смысла. Здесь остаётся природный
-- объект: сопка. 'mountain' — ближайший честный раздел из существующих
-- (PLACE_TYPE_LABEL: volcano/geyser/hot_spring/lake/mountain/bay/...).
--
-- ── Чего эта миграция НЕ делает, и почему ────────────────────────────────
--
-- 1. НЕ трогает Сопку Мишенную и остальные 116 записей location_type='volcano'.
--    Соблазн был: обе всплыли вместе в миграции 098 как городские сопки с
--    битыми координатами. Но включение потухших построек в раздел вулканов
--    здесь СОЗНАТЕЛЬНОЕ, а не случайное: app/api/safety/geofence-zones
--    прямо называет Мишенную потухшей сопкой внутри набора вулканов и
--    отдельно оговаривает, что красной зоны она не получает. Мишенная —
--    380-метровый конус, а не стометровый купол в парке; это другой случай,
--    и решать его надо своей уликой, а не заодно.
-- 2. НЕ правит тип по маске имени («сопка» → не вулкан). На Камчатке «сопка»
--    и есть обиходное имя вулкана: Ключевская, Корякская, Карымская,
--    Камбальная, Желтовская сопки — все настоящие вулканы и все в
--    lib/geo/gvp-confirmed-pairs.ts. Маска по имени снесла бы их разом.
-- 3. НЕ судит по расстоянию до каталога ГВП. Шапка gvp-confirmed-pairs
--    предупреждает: из 117 записей 65 законно без пары — спутниковые пики и
--    кратеры внутри комплексов, иные за 40-70 км от «родителя». Никольская
--    стоит ~25 км от Авачинского, то есть БЛИЖЕ иных настоящих. Расстоянием
--    её от вулкана не отличить, и порог тут выдумал бы разделитель, которого
--    в данных нет.
--
-- Полная перепись 117 записей раздела (prod-check run 52) идёт отдельно; её
-- ответ — материал для решения владельца, а не повод править вслепую сейчас.
--
-- ── Безопасность правки ──────────────────────────────────────────────────
--
-- Геофенс (app/api/safety/geofence-zones) строит вулканическую зону
-- INNER JOIN'ом к volcano_status с повышенным кодом KVERT. У Никольской
-- записи в volcano_status нет (её никто не мониторит), поэтому зоны она не
-- давала и не даёт — смена типа там не меняет ничего.
--
-- Идемпотентно и обратимо: правим ТОЛЬКО если сейчас стоит 'volcano'.
-- Повторный прогон — no-op. Чужая более поздняя правка типа не затирается.

DO $$
DECLARE
  pid       text := '51598b80-6b92-48d9-beb4-019f824524c9';
  pname     text;
  ptype     text;
BEGIN
  SELECT name, location_type INTO pname, ptype FROM places WHERE id = pid;

  IF pname IS NULL THEN
    RAISE NOTICE '[971] % — записи нет в places, делать нечего', pid;
    RETURN;
  END IF;

  IF ptype IS DISTINCT FROM 'volcano' THEN
    RAISE NOTICE '[971] % (%) — тип уже % , не трогаем', pname, pid, COALESCE(ptype, 'NULL');
    RETURN;
  END IF;

  UPDATE places
     SET location_type = 'mountain',
         updated_at    = NOW()
   WHERE id = pid;

  RAISE NOTICE '[971] % (%) — location_type: volcano -> mountain', pname, pid;
END $$;

INSERT INTO _migrations (name)
VALUES ('971_nikolskaya_sopka_not_volcano.sql')
ON CONFLICT (name) DO NOTHING;
