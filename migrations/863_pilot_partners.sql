-- Аудит пилота (пробы 106-107) нашёл две дыры в данных:
--  1. Виджет лидов выключен у ОБОИХ: /api/widget/lead.js отвечал
--     «partner not found or widget disabled». Виджет — самый чистый канал
--     атрибуции (partner_slug -> operator_id гарантированно), без него
--     отчёт по лидам партнёра почти пуст.
--  2. «Камчатка Семейный Рафтинг» отсутствует в публичном списке
--     операторов (is_public = false): тур ID27 продаётся, а страницы
--     оператора у туриста нет — «Оп: ...» ведёт в никуда.
--
-- Точечно и идемпотентно, гейт по id (id из живого каталога туров).

-- Камчатская рыбалка (fishingkam): включить виджет лидов.
UPDATE partners
   SET widget_enabled = true
 WHERE id = '0aaa4f05-b479-418b-9d54-2b909783dfd7';

-- Камчатка Семейный Рафтинг: публичная страница + slug + виджет.
UPDATE partners
   SET is_public = true,
       slug = COALESCE(slug, 'kamchatka-semeyny-rafting'),
       widget_enabled = true
 WHERE id = 'ead39acc-85c8-41c9-8f75-3a7092f7f699';
