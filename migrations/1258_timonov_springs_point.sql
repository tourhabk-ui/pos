-- 1258: Тимоновские источники — точка статьи вместо точки без источника
-- Created: 2026-10-14
--
-- ── Почему ────────────────────────────────────────────────────────────────
--
-- 1257 переписала карточку «Тимоновские» по статье Википедии, а точку
-- оставила на сверку: карточка стояла в 53.8032775, 158.1567997, статья даёт
-- 53.8089, 158.1644 — в 770 м к северо-востоку. В OSM объекта нет (Nominatim,
-- проба 924), так что сверялись тем, что статья говорит сама: источники «на
-- высоте 700 м над уровнем моря», «по обоим берегам долины левого истока реки
-- Падь Тимоновская».
--
-- Высоты обеих точек по двум цифровым моделям рельефа (opentopodata, проба
-- 925): точка статьи — 661 м по SRTM и 652 м по ASTER, точка карточки — 588 и
-- 585 м, на сотню метров ниже по долине. До 700 м ближе точка статьи. Вторая
-- улика — история записи: ровно в точке статьи стоит скрытый дубль
-- «Тимоновский» (0ab94acc), слитый с этой карточкой; при слиянии осталась
-- точка карточки, у которой источника нет.
--
-- Координата меняется только с прежнего точного значения; старая — в этом
-- заголовке, откат — обратный UPDATE.
--
-- ПОСЛЕ ВЫКАТА: новая точка появится на полевой карте после
-- map-places-build (upload:true).

BEGIN;

UPDATE places
   SET lat = 53.8089, lng = 158.1644,
       coord_source = 'external', coord_source_at = NOW(), updated_at = NOW()
 WHERE id::text = '15bf29b0-9b1b-49c5-be1f-4c8d5d185f4e'
   AND abs(lat - 53.8032775) < 0.000001 AND abs(lng - 158.1567997) < 0.000001;

DO $$
DECLARE
  v_point record;
BEGIN
  SELECT round(lat::numeric, 4) AS lat, round(lng::numeric, 4) AS lng INTO v_point
    FROM places WHERE id::text = '15bf29b0-9b1b-49c5-be1f-4c8d5d185f4e';
  IF v_point.lat IS DISTINCT FROM 53.8089 OR v_point.lng IS DISTINCT FROM 158.1644 THEN
    RAISE WARNING '[1258] точка Тимоновских источников не на точке статьи: % / % (ждали 53.8089 / 158.1644)', v_point.lat, v_point.lng;
  END IF;
END $$;

COMMIT;

