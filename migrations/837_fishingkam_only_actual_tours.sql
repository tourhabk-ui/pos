-- 837: На витрине — только актуальные туры «Камчатской рыбалки».
--
-- Источник: владелец, 07.08.2026 — «давай оставим пока только актуальные
-- туры камчатской рыбалки»; в опросе выбрал оставить туры 5 («Летняя:
-- чавыча и нерка») и 6 («Летняя: кижуч»). Остальные пять (4 осенняя,
-- 7 семейный день, 9-11 многодневные) — скрыть.
--
-- Скрыть, НЕ удалить: в отличие от демо-мусора (808, deleted_at), это
-- настоящие продукты партнёра — они вернутся, когда партнёр подтвердит
-- сезонные окна по анкете. is_published = FALSE снимает тур с витрины и
-- из sitemap, но оставляет в кабинете оператора — обратно одной галочкой.
--
-- Идемпотентна; чужих операторов не трогает.

UPDATE operator_tours ot
   SET is_published = FALSE,
       updated_at   = NOW()
 WHERE ot.id IN (4, 7, 9, 10, 11)
   AND ot.deleted_at IS NULL
   AND ot.is_published = TRUE
   AND ot.operator_id = (SELECT id FROM partners WHERE name ILIKE 'камчатская рыбалка' LIMIT 1);
