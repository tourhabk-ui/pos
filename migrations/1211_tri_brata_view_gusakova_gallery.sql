-- 13.10 (решение владельца «согласен, перенеси в S3»): байты снимков вынесены в
-- хранилище — ключ migrations/photos/<sha256>.jpg из маркера
-- .github/triggers/migration-photos-to-s3.json (sha256 тех же байтов). Миграция
-- пишет s3_key, image_data пуст; прод переведён по хэшу байтов миграцией 1228.
--
-- 1211: «Смотровая над Авачинской бухтой» — второй кадр Алины Гусаковой, вид на скалы Три брата.
-- Created: 2026-10-10
--
-- Владелец 10.10 прислал кадр с подписью «Три брата вид со смотровой, красивое
-- фото» и на вопрос об авторе и месте ответил: «Алина Гусакова на смотровой».
-- Права и порядок те же, что у всей серии (1115–1140): автор Алина Гусакова,
-- `license` не ставится — разрешение на публикацию не лицензия.
--
-- Куда: на карточку «Смотровая на обрыве над Авачинской бухтой» (60b06659), как
-- в 1140, а не на «Скалы Три Брата» (fd3feffa): владелец назвал смотровую.
-- Кадр показывает сами скалы и бухту, но снят со смотровой — это её вид.
-- Герой у смотровой уже занят кадром Алины из 1140 (или чужим ручным снимком,
-- если 1140 уложила её кадр в галерею), поэтому этот — в ГАЛЕРЕЮ, на следующую
-- свободную позицию; героя не трогаем.
--
-- Файл: исходник 1080x1338 (4:5) с серой полосой интерфейса телефона сверху
-- (~12 px). Срезана полоса (14 px сверху), окно 3:4 по центру — 993x1324,
-- затем 720x960, JPEG q72, без EXIF (вместе с ним ушли бы координаты съёмки и
-- данные камеры). Скалы целиком в кадре, людей нет.
--
-- Повторный прогон кадр не дублирует: ключ — подпись на этом месте.
-- s3_url не ставится — байты увезёт cron-images-to-s3 (§4.1).
--
-- IDEMPOTENT

BEGIN;

INSERT INTO place_gallery_photos (ark_id, position, image_data, mime_type, width, height, caption, author, s3_key)
SELECT p.ark_id,
       COALESCE((SELECT max(g.position) FROM place_gallery_photos g WHERE g.ark_id = p.ark_id), 0) + 1,
       NULL::bytea,
       'image/jpeg',
       720,
       960,
       'Скалы Три брата в Авачинской бухте, вид со смотровой',
       'Алина Гусакова',
       'migrations/photos/c5a5a8d79baf32d42ef026408fe84dc95dec79fa859c2a9bdc1a2e24f0c088a1.jpg'
  FROM places p
 WHERE p.id::text = '60b06659-f636-43b7-8b18-0601d8744739'
   AND p.ark_id IS NOT NULL
   AND NOT EXISTS (SELECT 1 FROM place_gallery_photos g
                    WHERE g.ark_id = p.ark_id AND g.caption = 'Скалы Три брата в Авачинской бухте, вид со смотровой')
 LIMIT 1;

-- ── Исход называется вслух ────────────────────────────────────────────────
DO $$
DECLARE
  v_ark uuid;
  v_n   int;
BEGIN
  SELECT ark_id INTO v_ark FROM places
   WHERE id::text = '60b06659-f636-43b7-8b18-0601d8744739' AND is_visible AND merged_into_id IS NULL;

  IF v_ark IS NULL THEN
    RAISE WARNING '[1211] живой записи «Смотровая над Авачинской бухтой» нет — кадр не лёг';
    RETURN;
  END IF;

  SELECT count(*) INTO v_n FROM place_gallery_photos
   WHERE ark_id = v_ark AND caption = 'Скалы Три брата в Авачинской бухте, вид со смотровой' AND author = 'Алина Гусакова';
  IF v_n <> 1 THEN
    RAISE WARNING '[1211] кадров «Скалы Три брата в Авачинской бухте, вид со смотровой» у смотровой % вместо 1', v_n;
  END IF;
END $$;

COMMIT;
