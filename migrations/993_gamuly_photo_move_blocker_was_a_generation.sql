-- 993: переезд снимка каньона — третья попытка, теперь без препятствия.
--
-- ── Что мешало, и почему это стало видно только сегодня ───────────────────
--
-- Миграция 988 не смогла перевезти геройский снимок с дубля «Каньон на
-- Шивелуче» на настоящую запись «Каньон Крылья Гамулов»: у
-- `ai_route_images.route_id` уникальность, слот целевой записи был занят, и
-- UPDATE получил 23505. Накатчик счёл duplicate key идемпотентностью и
-- записал `[skip-exists]` — разбор этого лежит в шапке 990.
--
-- 990 убирала препятствие, но только ПУСТУЮ строку: без байтов, без ключа и
-- без ссылки на объект. Дубль после неё остался видимым — значит строка на
-- слоте пустой не была.
--
-- ЧТО ЕЮ БЫЛО, я НЕ ЗНАЮ НАВЕРНЯКА и не выдаю догадку за факт. Наиболее
-- вероятное объяснение: сгенерированная картинка (qwen-image или
-- pollinations-flux), уже уехавшая в хранилище переездом 18-19.09 — у такой
-- `image_data` обнулён, а `s3_key` записан, и под предикат 990 «ни байтов,
-- ни ключа, ни ссылки» она не подходит. Это сходится со всем, что известно:
-- слот был занят чем-то, что не показывалось на карточке (photoUrl у
-- Гамулов был NULL при занятом слоте), и занято оно было до 984.
--
-- Если так, препятствия больше нет: 19.09 в 23:17 UTC боевой прогон
-- `images-generated` удалил все 173 генерации — и строки, и объекты. Но 990
-- к тому времени уже применилась и повторно не пойдёт: накатчик помнит имена
-- применённых файлов, а не их исход.
--
-- ── Почему эта миграция безопасна при ЛЮБОМ объяснении ───────────────────
--
-- Она ничего не удаляет. Переезд защищён `NOT EXISTS` по целевому слоту — то
-- есть выражение физически не может получить duplicate key и быть молча
-- пропущенным (урок 988). Если слот всё-таки занят — настоящей чужой
-- фотографией, строкой, о которой я не знаю, чем угодно, — UPDATE честно не
-- делает ничего, дубль остаётся видимым, и проверка в конце называет, ЧТО
-- именно на слоте лежит. Тогда это уже другой разговор и другая правка.
--
-- Скрытие дубля, как и в 988 и 990, условно и идёт ТОЛЬКО после
-- подтверждённого переезда: иначе кадр остался бы на скрытой карточке, то
-- есть исчез бы с глаз, оставаясь в базе.
--
-- Отбор строки — по ark дубля и автору, а не по `prompt`: подпись может
-- переписать любой следующий шаг, а происхождение снимка — нет. Это решение
-- 990, и оно здесь не переигрывается.
--
-- ── После выката ─────────────────────────────────────────────────────────
--
-- Нужен перезалив пакетов карты (`map-places-build.yml`, upload:true).
-- Полевая карта читает статичные пакеты из хранилища, а не живую таблицу:
-- пока перезалива не было, на телефоне остаются два каньона в 780 метрах
-- друг от друга, сколько бы миграций ни прошло.
--
-- IDEMPOTENT

BEGIN;

-- ── 1. Снимок Андрея переезжает с дубля на настоящую запись ──────────────
--
-- `NOT EXISTS` по целевому слоту обязателен: выражение, которое МОЖЕТ
-- получить duplicate key, будет молча пропущено накатчиком — ровно так
-- потерялся шаг 988.
UPDATE ai_route_images
   SET route_id = (SELECT ark_id FROM places WHERE id::text = 'c03b364f-55c3-4944-8505-3e86058999fa')
 WHERE route_id = 'b3d7eb6c-2ac4-41d9-89fe-52d073c3488d'
   AND author = 'Андрей Запорожец'
   AND (SELECT ark_id FROM places WHERE id::text = 'c03b364f-55c3-4944-8505-3e86058999fa') IS NOT NULL
   AND NOT EXISTS (
         SELECT 1 FROM ai_route_images busy
          WHERE busy.route_id = (SELECT ark_id FROM places WHERE id::text = 'c03b364f-55c3-4944-8505-3e86058999fa')
       );

-- ── 2. Дубль скрывается — только при подтверждённом переезде ─────────────
UPDATE places
   SET is_visible     = FALSE,
       merged_into_id = 'c03b364f-55c3-4944-8505-3e86058999fa',
       merged_at      = NOW(),
       updated_at     = NOW()
 WHERE id::text = '002f9a4f-8833-4ee7-8dc4-290b30092cb7'
   AND (is_visible OR merged_into_id IS NULL)
   AND EXISTS (
         SELECT 1 FROM ai_route_images ai
          WHERE ai.route_id = (SELECT ark_id FROM places WHERE id::text = 'c03b364f-55c3-4944-8505-3e86058999fa')
            AND ai.author = 'Андрей Запорожец'
       );

-- ── Исход называется вслух, и отдельно — ЧТО на слоте ────────────────────
--
-- Третья попытка подряд: если и она не прошла, следующему читателю нужен не
-- факт «не прошла», а имя препятствия. Иначе четвёртая миграция будет писаться
-- теми же догадками, что и эта.
DO $$
DECLARE
  v_gam_ark  uuid;
  v_author   text;
  v_model    text;
  v_dup_live boolean;
BEGIN
  SELECT ark_id INTO v_gam_ark FROM places WHERE id::text = 'c03b364f-55c3-4944-8505-3e86058999fa';

  IF v_gam_ark IS NULL THEN
    RAISE WARNING '[993] у «Крыльев Гамулов» нет ark_id — снимку ехать некуда, дубль ОСТАЁТСЯ видимым';
    RETURN;
  END IF;

  SELECT author, model INTO v_author, v_model
    FROM ai_route_images WHERE route_id = v_gam_ark;
  SELECT is_visible INTO v_dup_live
    FROM places WHERE id::text = '002f9a4f-8833-4ee7-8dc4-290b30092cb7';

  IF v_author IS DISTINCT FROM 'Андрей Запорожец' THEN
    RAISE WARNING '[993] снимок НЕ переехал. На слоте «Крыльев Гамулов» сейчас: %. Дубль намеренно оставлен видимым — кадр не должен оказаться на скрытой карточке.',
      COALESCE('автор «' || COALESCE(v_author, '(не записан)') || '», род «' || COALESCE(v_model, '(не записан)') || '»',
               'строки снимка нет вовсе');
  END IF;

  IF v_dup_live IS TRUE THEN
    RAISE WARNING '[993] дубль «Каньон на Шивелуче» всё ещё видим — перезалив пакетов карты ничего не исправит, пока это так';
  ELSE
    RAISE NOTICE '[993] дубль снят с витрины. Дальше — перезалив пакетов карты (map-places-build.yml, upload:true), иначе на телефоне останутся два каньона.';
  END IF;
END $$;

COMMIT;
