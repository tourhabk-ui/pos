-- 13.10 (решение владельца «согласен, перенеси в S3»): байты снимков вынесены в
-- хранилище — ключ migrations/photos/<sha256>.jpg из маркера
-- .github/triggers/migration-photos-to-s3.json (sha256 тех же байтов). Миграция
-- пишет s3_key, image_data пуст; прод переведён по хэшу байтов миграцией 1228.
--
-- 989: «Шивелуч» — снимок владельца, дорога на вулкан.
--
-- ── Чей кадр и что о нём известно ─────────────────────────────────────────
--
-- 19.09 владелец прислал снимок со словами, записанными дословно:
--
--   «нашел это я снимал очень давно»
--
-- Значит автор — он сам, как в миграциях 979/981/983/985, и `author` —
-- «владелец платформы». Но в отличие от тех кадров этот НЕ сегодняшний, и
-- дату я назвать не могу: EXIF в присланном файле нет вовсе (мессенджер
-- срезает метки), а «очень давно» — не дата. Поэтому в подписи её нет.
-- Написать «снято 19.09» было бы ровно тем сочинением, от которого
-- предостерегает §4.0: обязательное поле заполняется выдумкой.
--
-- Объект назвал владелец — Шивелуч; предыдущие его сообщения того вечера об
-- этом же вулкане. Кадр с названием согласуется: широкий заснеженный массив
-- с острой вершиной справа и парящий шлейф у левого плеча — живой конус.
-- Но это СОГЛАСИЕ, а не проверка: по фотографии гору не опознать приборно, и
-- ровно сегодня я уже ошибся, объявив по памяти, где стоят «Крылья Гамулов»
-- (разбор — в шапке миграции 988). Поэтому источник имени здесь один и
-- назван прямо: слово владельца.
--
-- ── Почему карточка стоит пустой ──────────────────────────────────────────
--
-- Миграция 988 увезла кадр Андрея Запорожца с карточки вулкана на карточку
-- каньона «Крылья Гамулов», которому он и принадлежит. Следствие было
-- названо вслух заранее: у самого вулкана фотографии не осталось, карточка
-- 77e5d9e1 показывает градиентную заглушку. Этот снимок её закрывает.
--
-- Двумя другими кадрами того же вечера она закрыта НЕ была, и это записано,
-- чтобы к вопросу не возвращались: у одного на картинке стоит водяной знак
-- «© Petr Ushanov, 2023 / petrushanov.com» — автор назван на самом кадре, и
-- подписать его «из открытых источников» значило бы выдумать происхождение
-- права. Решение по нему за владельцем, оно открыто.
--
-- ── Обрезка ───────────────────────────────────────────────────────────────
--
-- Исходник 2000x1500. Окно 16:9 полной ширины (2000x1125) со смещением 255
-- пикселей сверху: срезаны пустое небо вверху и капот машины внизу — кадр
-- снят через лобовое стекло. Внутри окна остаётся всё, ради чего он снят:
-- гравийка, уходящая к вулкану, полосы сухого ольшаника по обочинам и массив
-- со шлейфом на горизонте.
--
-- Записывается РОДНОЙ размер 2000x1125, а не канонные 1280x720: уменьшать
-- резкий кадр незачем, а канон описывает потолок, а не обязанность
-- подгонять (тот же довод, что в 984, только с другой стороны).
--
-- ── Как ложится ───────────────────────────────────────────────────────────
--
-- Герой карточки. Чужой РУЧНОЙ снимок не перезаписывается: если 988 почему-то
-- не увезла кадр Андрея, строка остаётся за ним, а эта миграция молча ничего
-- не сделает — и потому в конце проверка, называющая такой исход словами.
-- Машинная картинка и скрейп заменяются.
--
-- Байты пишутся в базу, а не в хранилище: миграция накатывается при старте
-- сервера, и сетевой вызов оттуда стопорил бы весь накат. Увезёт уборщик
-- cron-images-to-s3 — правило §4.1.
--
-- Лицензия не ставится: снимок собственный, никто её не называл.
--
-- IDEMPOTENT

BEGIN;

INSERT INTO ai_route_images (route_id, image_data, mime_type, prompt, model, width, height, author, s3_key)
SELECT p.ark_id,
       NULL::bytea,
       'image/jpeg',
       'снимок владельца: Шивелуч с дороги (миграция 989)',
       'manual-upload',
       2000,
       1125,
       'владелец платформы',
       'migrations/photos/9fd5bab784b534df8d4d08c6e46d39ba391dbed6bbcdd8142b30e8c35e981f82.jpg'
  FROM places p
 WHERE p.id::text = '77e5d9e1-4746-45fc-bb1a-8527003edf5f'
   AND p.ark_id IS NOT NULL
 LIMIT 1
ON CONFLICT (route_id) DO UPDATE
   SET image_data = EXCLUDED.image_data,
       mime_type  = EXCLUDED.mime_type,
       prompt     = EXCLUDED.prompt,
       model      = EXCLUDED.model,
       width      = EXCLUDED.width,
       height     = EXCLUDED.height,
       author     = EXCLUDED.author,
       s3_url     = NULL,
       s3_key     = EXCLUDED.s3_key,
       created_at = NOW()
 WHERE ai_route_images.model NOT IN ('wikimedia', 'manual-upload')
    OR ai_route_images.prompt = 'снимок владельца: Шивелуч с дороги (миграция 989)';

-- ── Отказ называется вслух ────────────────────────────────────────────────
DO $$
DECLARE
  v_ark    uuid;
  v_prompt text;
BEGIN
  SELECT ark_id INTO v_ark FROM places WHERE id::text = '77e5d9e1-4746-45fc-bb1a-8527003edf5f';

  IF v_ark IS NULL THEN
    RAISE WARNING '[989] у «Шивелуча» нет ark_id — снимок владельца НЕ лёг, карточка осталась без фото';
    RETURN;
  END IF;

  SELECT prompt INTO v_prompt FROM ai_route_images WHERE route_id = v_ark;

  IF v_prompt IS NULL THEN
    RAISE WARNING '[989] у «Шивелуча» нет строки снимка ВООБЩЕ — вставка не состоялась';
  ELSIF v_prompt IS DISTINCT FROM 'снимок владельца: Шивелуч с дороги (миграция 989)' THEN
    RAISE WARNING '[989] герой Шивелуча НЕ стал снимком владельца: строку держит другой ручной снимок (prompt=%)', v_prompt;
  END IF;
END $$;

COMMIT;
