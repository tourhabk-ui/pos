-- Migration 1417: ключ повтора формы у контроля выхода
-- Created: 2026-11-10
--
-- Форма /register узнаёт собственный повтор (двойное нажатие, ответ,
-- потерянный на плохой связи) и возвращает номер прежней записи вместо второй
-- (lib/safety/trip-watch, createTripWatchOnce; docs/safety/MCHS_PLAN.md, С1).
--
-- Узнавать повтор по одним введённым данным нельзя (ревью безопасности PR 3197):
-- тот, кто знает поля чужой записи, получил бы её номер, а номер вместе с
-- телефоном руководителя закрывает контроль. Поэтому повтор узнаётся по тому,
-- чего посторонний не знает: по входу в аккаунт либо по ключу, который форма
-- создаёт на устройстве и присылает с запросом.
--
-- submit_key_hash — SHA-256 этого ключа. Сам ключ в базе не лежит: по строке
-- таблицы его не восстановить и чужой номер записи с ним не получить. Ключ —
-- случайное число устройства, не данные человека. NULL — запись из чата
-- (source = 'max'), запись до этой миграции или форма без ключа.
--
-- Идемпотентно: IF NOT EXISTS.

ALTER TABLE route_registrations ADD COLUMN IF NOT EXISTS submit_key_hash TEXT;

COMMENT ON COLUMN route_registrations.submit_key_hash IS
  'SHA-256 ключа повтора формы /register: по нему (или по входу в аккаунт) повтор той же формы узнаёт свою открытую запись. Сам ключ не хранится.';

-- Поиск своей открытой записи по ключу: открытых записей мало, с ключом — ещё меньше.
CREATE INDEX IF NOT EXISTS route_registrations_submit_key_open_idx
  ON route_registrations (submit_key_hash)
  WHERE completed_at IS NULL AND submit_key_hash IS NOT NULL;
