--
-- Крон теперь пропускает шаблонные опасности через honestSafetyFields (тот же
-- фильтр, что у карточки), поэтому пустое поле он заполнит по честным данным.
-- Снимается только этот текст и только если в нём шаблонные лавины или
-- камнепады: авторский текст владельца или уже переписанный не трогаются.

