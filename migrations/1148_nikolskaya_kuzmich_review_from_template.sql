--
-- Скрин владельца 03.10: на карточке городской сопки в центре
-- Петропавловска «Кузьмич о месте» пишет про «сход лавин, камнепады, жар».
-- Сопка числилась вулканом (исправлено в 972), профиль безопасности получил
-- шаблон вулкана, и крон kuzmich-places отдал этот шаблон модели как факт —
-- модель его честно пересказала. Профиль очищен миграцией 973, а текст
