   SET kuzmich_review = NULL,
       updated_at = NOW()
 WHERE id::text = '51598b80-6b92-48d9-beb4-019f824524c9'
   AND (kuzmich_review ILIKE '%лавин%' OR kuzmich_review ILIKE '%камнепад%');
