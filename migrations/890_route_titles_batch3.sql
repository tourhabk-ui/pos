-- 890: переименование маршрутов, партия 3 (3 имени, выведенные из описаний) —
-- «отлично и все названия маршрутов привести к стандарту» (владелец 20.08).
--
-- Канон взят из ОПИСАНИЙ маршрутов (перепись v6, проба 112), не сочинён:
--   «Там, за туманами»          — «однодневная пешеходная экскурсия к подножию
--                                  вулкана Мутновский, ~12 км»;
--   «Магия зимы»                — «треккинговый маршрут в районе
--                                  Мутновско-Гореловской группы, зимой»;
--   «Камчатка. Рискни покорить!» — «треккинговый маршрут по природному парку,
--                                  Мутновско-Гореловская группа».
-- Судья (lib/routes/title-standard.ts) прогнан по новым именам заранее.
-- Guard по старому имени — идемпотентно; живость строгая.

UPDATE kamchatka_routes r
SET title = p.new_title, updated_at = NOW()
FROM (VALUES
  ('8e05bc58-bba4-49f6-9ee4-05a28b533dbb', '«Там, за туманами»', 'К подножию вулкана Мутновский'),
  ('751d9830-5d4f-4191-9138-45f344830bdb', 'Магия зимы', 'Мутновско-Гореловская группа (зимний)'),
  ('a84b7f41-ede3-4d47-b90e-3195a0e5a145', 'Камчатка. Рискни покорить!', 'Мутновско-Гореловская группа (треккинг)')
) AS p(route_id, old_title, new_title)
WHERE r.id::text = p.route_id
  AND r.title = p.old_title
  AND r.is_visible = true
  AND r.merged_into_id IS NULL;
