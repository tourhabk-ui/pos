-- ЧТО ПОКАЗАЛА ПЕРЕПИСЬ ПРОДА (проба 186, 23.08 23:20 UTC, e019409b).
-- Судья смотрел окно семи дней и видел 41 запись. Панель окна не имеет и
-- показывает всё в статусах open/suggested — за 90 дней ответ упёрся в
-- собственный потолок роута: 100 записей, из них 60 разведки. Сколько их
-- на самом деле, роут сказать не может, и выдавать «100» за полное число
-- нельзя. Отсюда устройство миграции: поимённо закрывается разобранное,
-- а всё прочее закрывается ОДНИМ условием по статусу, без списка id.
--
-- КАКОЕ СЛОВО СТАВИТСЯ И ПОЧЕМУ. Статусы здесь не оформление: 'accepted'
-- и 'rejected' — это счёт точности эволюции (evo-report), а 'rejected' и
-- 'ignored' — ещё и вечный стоп-лист класса претензии (growth-agent).
--   * уже починено -> accepted. Претензия была справедлива, работа сделана.
--     Записывать её отказом значит наказать модель за верную находку.
--   * шум -> rejected. Претензия ложна, и её класс на этом файле обязан
--     замолчать навсегда — ровно для этого стоп-лист и заведён.
--   * мало данных -> ignored. Судья НЕ СМОГ проверить (в куске кода нет
--     самого запроса), и это третий исход, а не «хорошо» и не «плохо».
--     Слова «не судили» в словаре статусов нет, поэтому ставится «не берём
--     в работу» — оговорка записана здесь, чтобы позже не читалась как
--     доказанная ложь находки.
--   * всё остальное (разведка и неразобранное) -> ignored. Владелец не
--     объявлял их ложными, он отказался держать их в списке. 'ignored'
--     говорит ровно это, 'rejected' сказал бы больше правды, чем есть.
--
-- ЦЕНА, КОТОРУЮ ЭТО СТОИТ, НАЗВАНА ВСЛУХ. Точность эволюции считается по
-- ОПУБЛИКОВАННЫМ находкам (github_issue_url не пуст), и 'ignored' идёт в
-- ней на сторону отвергнутых. Значит после этой миграции точность просядет
-- и догадки модели (код-ревью и разведка) публиковаться перестанут, кроме
-- одного пробника за прогон. Детерминированные находки идут по-прежнему.
-- Это поведение тормоза по замыслу, а не поломка: сотня находок, которые
-- человек не взял, — ровно тот сигнал, ради которого он написан. Сколько
-- именно записей опубликовано, репозиторий не знает — цифра будет видна в
-- ближайшем отчёте evo-report.
--
-- Идемпотентно: условие статуса после прогона никого не находит.

