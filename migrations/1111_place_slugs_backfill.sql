-- 1111_place_slugs_backfill.sql
--
-- Адрес по имени (ЧПУ) для видимых мест, у которых его нет.
--
-- ── Повод (аудит SEO 29.09) ───────────────────────────────────────────────
--
-- В sitemap 33 места открываются по UUID: /places/6e3a46a9-… вместо
-- /places/vulkan-ksudach. Поисковику такой адрес ничего не говорит, и по
-- запросу «Ксудач» карточки места в выдаче Яндекса нет.
--
-- Причин две, и они разные:
--   — 26 мест заведены ПОСЛЕ миграции 779, которая раздала адреса разом, а
--     пишущие пути адрес новым местам не выдают. Их адрес свободен;
--   — у 7 мест адрес занят живым маршрутом с тем же именем (Ксудач,
--     Толбачик, Курильское озеро, Скалы Три Брата, Дачные, Карымшинские,
--     Нальчевские источники). 779 пропустила их намеренно: адрес уникален
--     между местами и маршрутами.
--
-- ── Что делает миграция ───────────────────────────────────────────────────
--
-- Раздаёт адрес по ПРАВИЛУ, а не по списку, тем же `translit_ru_slug`, что
-- 779 (и lib/text/slugify.ts): только видимому и не слитому месту, только
-- если адрес свободен и среди мест, и среди маршрутов, и только если его не
-- претендует получить другое место из того же прогона. Второе условие не
-- даёт двум тёзкам поделить адрес «кто первый» — оба остаются по UUID.
--
-- Семь мест с занятым адресом НЕ трогаются. Кому принадлежит
-- `vulkan-ksudach` — месту или маршруту — решение владельца, а не
-- миграции: отдать адрес месту значит превратить маршрут в двойника, и
-- /routes/vulkan-ksudach начал бы уводить 308 на место (правило двойников
-- 29.09). Числовой суффикс (`vulkan-ksudach-2`) хуже UUID для поиска не
-- был бы, но выглядел бы как починка, не будучи ею.
--
-- «Точка маршрута (начало)» — служебные имена, их не называют адресом:
-- `tochka-marshruta-nachalo` у двух разных мест обещал бы, что это одно.
--
-- Идемпотентна: трогает только slug IS NULL. Повторный прогон подхватит
-- места, заведённые после этой миграции, — пока пишущие пути не выдают адрес
-- сами.

WITH candidates AS (
  SELECT p.id, translit_ru_slug(p.name) AS base
    FROM places p
   WHERE p.slug IS NULL
     AND p.is_visible = TRUE
     AND p.merged_into_id IS NULL
     AND p.name IS NOT NULL
     AND p.name NOT ILIKE 'Точка маршрута%'
),
usable AS (
  SELECT c.id, c.base
    FROM candidates c
   WHERE c.base <> ''
     AND NOT EXISTS (SELECT 1 FROM places x WHERE x.slug = c.base)
     AND NOT EXISTS (SELECT 1 FROM kamchatka_routes r WHERE r.slug = c.base)
     -- двое претендентов на один адрес — не получает никто
     AND (SELECT count(*) FROM candidates c2 WHERE c2.base = c.base) = 1
)
UPDATE places p
   SET slug = u.base
  FROM usable u
 WHERE p.id::text = u.id::text
   AND p.slug IS NULL;
