-- Migration 809: стандарт карточки тура — программа дня и правила безопасности
--
-- Владелец утвердил эталон карточки тура (03.08): программа дня аккордеоном и
-- блок правил безопасности. В operator_tours таких полей не было — раньше
-- программа жила текстом внутри description, а правила были захардкожены в
-- макете (что враньё для другого типа тура: правила сплава != правила рыбалки).
--
-- Добавляем per-tour поля:
--   • program JSONB      — массив шагов [{title, text}] (аккордеон «Программа дня»)
--   • safety_notes TEXT[] — правила безопасности КОНКРЕТНОГО тура от оператора
--
-- Заполняем ТОЛЬКО сплав по Быстрой — его программа подтверждена анонсом
-- оператора (миграции 060/802), правила — эталоном владельца (03.08).
-- Турам рыбалки поля НЕ выдумываем (§8): пока оператор не пришлёт — блоки
-- на карточке просто не рендерятся (fail-soft).
--
-- Матч по содержанию (как 806), не по id. Идемпотентна.

ALTER TABLE operator_tours ADD COLUMN IF NOT EXISTS program JSONB;
ALTER TABLE operator_tours ADD COLUMN IF NOT EXISTS safety_notes TEXT[];

UPDATE operator_tours ot
   SET program = '[
         {"title": "Выезд из Петропавловска-Камчатского", "text": "Сбор в Паратунской зоне отдыха, выезд на комфортном транспорте."},
         {"title": "Посёлок Сокочи", "text": "Короткая остановка: знаменитые пирожки (самооплата)."},
         {"title": "Река Быстрая: инструктаж", "text": "Инструктаж по технике безопасности, получение снаряжения и экипировки."},
         {"title": "Сплав с гидом и рыбалка", "text": "Спокойный семейный сплав — не спортивный рафтинг. По пути рыбалка и шанс фотоохоты на бурого медведя."},
         {"title": "Обед на берегу", "text": "Уха из лосося, нарезки, чай, кофе — готовит повар."},
         {"title": "Малкинские термальные источники", "text": "Купание в горячих источниках (купальные принадлежности обязательно)."},
         {"title": "Возвращение", "text": "Трансфер к месту проживания."}
       ]'::jsonb,
       safety_notes = ARRAY[
         'Перед стартом — инструктаж, на воде — спасательные жилеты',
         'Алкоголь до и во время маршрута запрещён',
         'Дети — только в сопровождении взрослых',
         'Диких животных не кормить и не приближаться',
         'Маршрут может измениться из-за погоды и уровня воды',
         'Наблюдение за медведями — только с безопасной дистанции и по указанию гида'
       ],
       updated_at = NOW()
 WHERE ot.deleted_at IS NULL
   AND ot.title ILIKE '%быстр%'
   AND (ot.title ILIKE '%сплав%' OR ot.activity_type = 'rafting')
   AND ot.program IS NULL;
