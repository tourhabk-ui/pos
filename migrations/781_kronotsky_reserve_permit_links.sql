-- Migration 781: Кроноцкий заповедник в справочнике parks + ссылки на
-- оформление разрешений для парков сети «Вулканы Камчатки»
--
-- Источники (27.07.2026, сходятся):
-- 1. Владелец платформы передал официальные ссылки на порядок оформления:
--    https://vulcanikamchatki.ru/novosti/20222029/ (сеть «Вулканы Камчатки»:
--    приложение «Зелёная кнопка», портал «Госуслуги», офис парка) и
--    https://kronoki.ru/ru/visit/requests/ (Кроноцкий: заявка с сайта на почту).
-- 2. Официальный сайт kronoki.ru подтверждает: заявка скачивается на странице
--    /ru/visit/requests/, заполняется и отправляется на tourism@kronoki.ru;
--    страница покрывает Кроноцкий, Корякский заповедники и Южно-Камчатский
--    заказник. Заявка включает группу в план посещения, разрешение выдаётся
--    отдельно — поэтому в описании «по заявке», а не «по клику».
-- 3. Каналы сети совпадают с перечнем visitkamchatka.ru из issue #367
--    (миграция 723), где колонки оставлены пустыми до подтверждённых ссылок.
--
-- Чего здесь НЕТ (правило НЕ ВРАТЬ): ссылки на приложение «Зелёная кнопка»
-- и точный URL услуги на Госуслугах владельцем не передавались — колонки
-- permit_online_url / permit_gosuslugi_url не заполняются, UI показывает
-- только непустые каналы.
--
-- Идемпотентна: safe to run multiple times.

BEGIN;

-- Кроноцкий заповедник: восточное побережье Камчатки, в справочнике не было.
-- Телефон МЧС не передавался — NULL, а не скопированный чужой номер.
INSERT INTO parks (slug, display_name, description, zone, mchs_phone, permit_url, permit_email, search_term)
SELECT
  'kronotsky',
  'Кроноцкий заповедник',
  'Государственный биосферный заповедник на восточном побережье Камчатки: Долина гейзеров, кальдера вулкана Узон, Кроноцкое озеро. Посещение только по разрешению: заявка скачивается на сайте заповедника, заполняется и отправляется на почту. Заявка включает группу в план посещения, разрешение оформляется отдельно.',
  'eastern',
  NULL,
  'https://kronoki.ru/ru/visit/requests/',
  'tourism@kronoki.ru',
  'Кроноцк'
WHERE EXISTS (
  SELECT 1 FROM information_schema.columns
  WHERE table_name = 'parks' AND column_name = 'permit_email'
)
ON CONFLICT (slug) DO NOTHING;

-- Парки сети «Вулканы Камчатки» без ссылки на оформление разрешения:
-- ведём на официальную инструкцию сети (три канала: «Зелёная кнопка»,
-- Госуслуги, офис). Налычево не трогаем — у него ссылка уже есть.
UPDATE parks
SET permit_url = 'https://vulcanikamchatki.ru/novosti/20222029/',
    updated_at = NOW()
WHERE slug IN ('bystrinskiy', 'klyuchevskoy')
  AND permit_url IS NULL;

COMMIT;
