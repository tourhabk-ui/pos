-- 13.10 (решение владельца «согласен, перенеси в S3»): байты снимков вынесены в
-- хранилище — ключ migrations/photos/<sha256>.jpg из маркера
-- .github/triggers/migration-photos-to-s3.json (sha256 тех же байтов). Миграция
-- пишет s3_key, image_data пуст; прод переведён по хэшу байтов миграцией 1228.
--
-- 1000: «Озеро Большой Кар» — снимок Валентины Жуковой.
--
-- ── Чей кадр и на каком основании публикуется ─────────────────────────────
--
-- 20.09 владелец прислал снимок со словами, записанными дословно:
--
--   «Озеро Кар фото Валентина Жукова согласие на публикацию есть»
--
-- и отдельным сообщением уточнил имя: «Валентина это полное имя от Вали».
-- Подписью идёт полная форма.
--
-- Согласие объявил ВЛАДЕЛЕЦ. Письменного слова самой Валентины Жуковой у
-- меня нет, и делать вид, что оно есть, я не буду — здесь записано решение
-- владельца публиковать с указанием автора, как в 984, 988 и 996. Появится
-- слово автора — дописывается сюда, а не заменяет это.
--
-- Лицензия не ставится: её никто не называл. Пустое поле честнее выдуманной
-- строки — то же правило, по которому 22 снимка с Викимедии до сих пор
-- скрыты.
--
-- ── Куда ложится ──────────────────────────────────────────────────────────
--
-- Запись 56d16421 «Озеро Большой Кар», lake, 53.06664/157.98225, живая.
-- Проверено на проде перед этой миграцией (проба 557): `photoCount: 0`,
-- `photoUrl: null` — фотографии у карточки НЕТ ВОВСЕ. Значит замещать
-- нечего и спор о чужом снимке здесь не возникает.
--
-- ── Почему именно эта запись, а не соседняя ───────────────────────────────
--
-- Владелец прислал экран Organic Maps: «Озеро Большой Кар (Затерянное)»,
-- 53.064902/157.985195. Ровно эта координата, до шестого знака, стоит у
-- записи 9c2ead2c — но та СКРЫТА и слита в 56d16421. Снимок ложится на
-- живую, а не на дубль.
--
-- Координату мастера (53.06664/157.98225) НЕ трогаю. Она в 280 метрах от
-- OSM-точки, а это для озера — вопрос «с какого берега мерили», не
-- доказательство ошибки. §4.1: улика не приговор, без источника координату
-- не двигают.
--
-- Что на кадре, сходится с описанием записи дословно: та говорит «спускался
-- в цирк Вачкажца к Большому Кару», и на снимке именно каровое озеро в
-- ледниковой чаше — тёмно-синяя вода, осыпи и снежники по бортам.
--
-- ── Размер ────────────────────────────────────────────────────────────────
--
-- Пришло скриншотом из «истории», поэтому кадр обрезан по содержимому: сняты
-- интерфейс приложения, подпись и эмодзи. Записывается 1080x800 — то, что
-- осталось от самого снимка, без растягивания до канона 16:9. Растянуть до
-- широкой полосы значило бы дорисовать то, чего в кадре нет.
--
-- ── Как ложится ───────────────────────────────────────────────────────────
--
-- Герой карточки. Машинная картинка заменяется, чужой РУЧНОЙ снимок — нет
-- (граница та же, что в 981/983/984/994/996). Байты пишутся в базу, а не в
-- хранилище: миграция накатывается при старте сервера, и сетевой вызов
-- оттуда стопорил бы весь накат; увезёт уборщик cron-images-to-s3 (§4.1).
--
-- Третий исход назван вслух: нет ark_id или строку занял чужой ручной кадр
-- — RAISE WARNING в лог выката, а не молчание и не падение.
--
-- IDEMPOTENT

BEGIN;

INSERT INTO ai_route_images (route_id, image_data, mime_type, prompt, model, width, height, author, s3_key)
SELECT p.ark_id,
       NULL::bytea,
       'image/jpeg',
       'снимок Валентины Жуковой: озеро Большой Кар в цирке Вачкажца (миграция 1000)',
       'manual-upload',
       1080,
       800,
       'Валентина Жукова',
       'migrations/photos/35abcb1cd064cd7dfa14a14e2e43275919da06d9310753f4455a974f2a0630b0.jpg'
  FROM places p
 WHERE p.id::text = '56d16421-ed6c-4650-af9e-1919fbae949f'
   AND p.ark_id IS NOT NULL
 LIMIT 1
ON CONFLICT (route_id) DO UPDATE
   SET image_data = EXCLUDED.image_data,
       mime_type  = EXCLUDED.mime_type,
       prompt     = EXCLUDED.prompt,
       model      = EXCLUDED.model,
       width      = EXCLUDED.width,
       height     = EXCLUDED.height,
       author     = EXCLUDED.author,
       s3_url     = NULL,
       s3_key     = EXCLUDED.s3_key,
       created_at = NOW()
 WHERE ai_route_images.model NOT IN ('wikimedia', 'manual-upload')
    OR ai_route_images.author IS NULL
    OR ai_route_images.prompt = 'снимок Валентины Жуковой: озеро Большой Кар в цирке Вачкажца (миграция 1000)';

-- ── Отказ называется вслух ────────────────────────────────────────────────
DO $$
DECLARE
  v_ark    uuid;
  v_author text;
BEGIN
  SELECT ark_id INTO v_ark FROM places WHERE id::text = '56d16421-ed6c-4650-af9e-1919fbae949f';

  IF v_ark IS NULL THEN
    RAISE WARNING '[1000] у «Озера Большой Кар» нет ark_id — снимок НЕ лёг, карточка осталась без фото';
    RETURN;
  END IF;

  SELECT author INTO v_author FROM ai_route_images WHERE route_id = v_ark;

  IF v_author IS DISTINCT FROM 'Валентина Жукова' THEN
    RAISE WARNING '[1000] герой «Озера Большой Кар» НЕ стал снимком Жуковой: там %', COALESCE('автор «' || v_author || '»', 'строки снимка нет');
  END IF;
END $$;

COMMIT;
