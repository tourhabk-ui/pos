-- 740_hide_non_place_junk.sql
-- «Порядок с местами», шаг 1: скрыть из публички (is_visible=false) однозначный
-- мусор в places. Обратимо (как migration 173), ничего не удаляем — админ-
-- инструменты (search/duplicates) продолжают видеть эти строки для разбора.
--
-- Скрываем ТОЛЬКО две однозначные категории:
--   1) имена-НЕместа: активности/туры/SEO-заголовки, не географические точки
--      («Восхождение на…», «Поход…», «Сплав…», «…: путь на вершину»,
--       «…: где находится», «…: как добраться», «… в 2025»).
--   2) координаты ВНЕ Камчатки (реальные, не 0,0 и не плейсхолдер), напр.
--      «Плато Антарктида» — на платформе Камчатки таким местам не место.
--
-- Плейсхолдер-места (0,0 и 53.0444/158.6483 — центр Петропавловска, куда сажали
-- точки без известного GPS, см. migration 660) здесь НЕ трогаем: среди них есть
-- реальные объекты, которым нужен догеокод, а не скрытие. Их считает
-- GET /api/admin/places/audit — решение по ним принимается вручную.

-- 1) Имена-НЕместа
UPDATE places
SET is_visible = false
WHERE is_visible = true
  AND merged_into_id IS NULL
  AND name ~* '(^\s*(восхождение|поход|сплав|путешествие|трекинг|скитур|джип-тур|вертолётн|экскурсия|тур\s))|(:\s*(путь на вершину|где находится|как добраться|маршрут))|(\s(где находится|как добраться)($|[:,]))|(\sв\s20[0-9][0-9]($|[^0-9]))';

-- 2) Координаты вне Камчатки (bbox 50–62°N, 155–175°E; lib/geo/kamchatka.ts).
--    Исключаем 0,0 и плейсхолдер ПКЦ — это «нет координат», а не «вне Камчатки».
UPDATE places
SET is_visible = false
WHERE is_visible = true
  AND merged_into_id IS NULL
  AND lat IS NOT NULL AND lng IS NOT NULL
  AND NOT (lat = 0 AND lng = 0)
  AND NOT (ROUND(lat::numeric, 4) = 53.0444 AND ROUND(lng::numeric, 4) = 158.6483)
  AND (lat < 50.0 OR lat > 62.0 OR lng < 155.0 OR lng > 175.0);
