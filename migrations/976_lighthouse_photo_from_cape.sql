-- 976: снимок владельца — и на карточку «Маяк Петропавловский».
--
-- ── Что увидел владелец ───────────────────────────────────────────────────
--
-- 18.09, снимок экрана 15:45: карточка «Маяк Петропавловский» открывается
-- пустой, с серой заглушкой вместо фотографии. Слова владельца: «без фото
-- хотя там лично мои фотографии были».
--
-- Фотографии никуда не делись. В каталоге ДВЕ записи об одном месте:
--
--   «Мыс Маячный»          3268583a-05e0-4f59-8d2c-a87a69be14a6  cape
--   «Маяк Петропавловский» 0aa97c3c-c4d7-496d-a879-7fa065d7f8de  historical
--
-- Кадры владельца легли миграцией 962 на ПЕРВУЮ, а открыл он ВТОРУЮ. Снимок
-- при этом ровно про неё: в шапке 962 записано, какой из пяти выбран —
-- «кадр маяка в его ландшафте: горящий огонь, склон, постройки поста».
--
-- ── Почему копия, а не перенос ────────────────────────────────────────────
--
-- Мыс и стоящая на нём башня — разные объекты, и обе записи остаются: в OSM
-- они тоже живут порознь (natural=cape и man_made=lighthouse). Снять снимок
-- с мыса значило бы обнулить карточку, которая сейчас работает.
--
-- ── Почему байты берутся из базы, а не вклеиваются сюда ───────────────────
--
-- В 962 снимок лежит четырьмя сотнями килобайт hex. Второй такой блок — это
-- две копии одного файла в репозитории, которые дальше расходятся правками.
-- Здесь INSERT ... SELECT переносит те же байты из строки мыса: один
-- источник, и если снимок мыса когда-нибудь заменят, эта миграция на чистой
-- базе перенесёт новый, а не воскресит старый.
--
-- Права переносятся вместе с байтами (author, license, source_url): снимок
-- без автора подписывать нечем, а приписывать чужое имя нельзя (14.09).
--
-- Переносится и `s3_url`: после переезда в хранилище (944) байты в базе
-- могут быть пусты, и раздача /api/images/route отдаёт редирект на объект —
-- без этого поля копия оказалась бы пустой карточкой. `s3_key` НЕ копируется
-- намеренно: это рукоять владения объектом, и две строки с одной рукоятью
-- означали бы, что удаление одной уносит снимок у другой. Обе строки читают
-- один объект; это названо здесь, чтобы следующий не счёл совпадение адресов
-- случайностью.
--
-- ── Ничего не делает, если делать нечего ──────────────────────────────────
--
-- SELECT не вернёт ни строки, если у мыса снимка нет или записи маяка нет —
-- миграция тогда пустая, а не падает. ON CONFLICT (route_id) DO NOTHING:
-- если у маяка уже есть своё фото, оно сильнее нашей копии и не трогается.
--
-- IDEMPOTENT

BEGIN;

INSERT INTO ai_route_images (
  route_id, image_data, mime_type, prompt, model, width, height,
  author, license, license_url, source_url, s3_url
)
SELECT lighthouse.ark_id,
       src.image_data,
       src.mime_type,
       'снимок владельца: маяк на мысе Маячном, копия с карточки мыса (миграция 976)'::text,
       src.model,
       src.width,
       src.height,
       src.author,
       src.license,
       src.license_url,
       src.source_url,
       src.s3_url
  FROM places lighthouse
  JOIN places cape
    ON cape.id::text = '3268583a-05e0-4f59-8d2c-a87a69be14a6'
  JOIN ai_route_images src
    ON src.route_id::text = cape.ark_id::text
 WHERE lighthouse.id::text = '0aa97c3c-c4d7-496d-a879-7fa065d7f8de'
   AND lighthouse.ark_id IS NOT NULL
   AND src.model IN ('manual-upload', 'wikimedia')
 LIMIT 1
ON CONFLICT (route_id) DO NOTHING;

COMMIT;
