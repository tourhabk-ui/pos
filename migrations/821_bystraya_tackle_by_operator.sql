-- Migration 821: снасти — повторно, теперь по оператору, а не по одному туру
--
-- 819 не сработала на живых данных: владелец 05.08 прислал карточку, где в
-- «не входит» по-прежнему «Рыболовные снасти (аренда 500 руб)». При этом
-- соседняя миграция 815 применилась (имя оператора в чате стало верным), то
-- есть деплой и раннер миграций работают.
--
-- Что было не так у 819. Она выбирала ОДИН «канонический» тур подзапросом
-- `ORDER BY ... LIMIT 1`. Такой выбор молча промахивается: у оператора может
-- быть несколько записей, подходящих под «быстр%», и первая по created_at —
-- не обязательно та, что видит турист. Ноль изменённых строк неотличим от
-- успеха: миграция «применилась», а данные прежние.
--
-- Здесь выбора нет: правим ВСЕ активные туры оператора «Камчатка Рафтинг».
-- Ограничение по оператору обязательно — у «Камчатской Рыбалки» в «не входит»
-- честно стоит «Аренда снастей (по договорённости)», и это ИХ условия, трогать
-- их нельзя.
--
-- Правило от Катерины («Камчатка Рафтинг», 05.08): снасти входят в стоимость,
-- аренды за 500 рублей нет. Цена ошибки прямая — турист платит на месте за уже
-- оплаченное.
--
-- Массивы не переписываются целиком: убираем только строки про аренду и прокат
-- снастей, порядок остальных сохраняем. Идемпотентна.

UPDATE operator_tours ot
   SET not_included = COALESCE((
         SELECT array_agg(x ORDER BY ord)
           FROM unnest(COALESCE(ot.not_included, ARRAY[]::text[])) WITH ORDINALITY AS t(x, ord)
          WHERE x !~* '(аренд|прокат)'
             OR x !~* '(снаст|удоч|спиннинг)'
       ), ARRAY[]::text[]),
       included = CASE
         WHEN NOT EXISTS (
           SELECT 1
             FROM unnest(COALESCE(ot.included, ARRAY[]::text[])) AS y
            WHERE y ILIKE '%снаст%' OR y ILIKE '%удочк%'
         )
         THEN COALESCE(ot.included, ARRAY[]::text[]) || 'Рыболовные снасти'::text
         ELSE ot.included
       END,
       updated_at = NOW()
  FROM partners p
 WHERE p.id = ot.operator_id
   AND p.slug = 'kamchatka-rafting'
   AND ot.deleted_at IS NULL
   AND (
     EXISTS (
       SELECT 1
         FROM unnest(COALESCE(ot.not_included, ARRAY[]::text[])) AS x
        WHERE x ~* '(аренд|прокат)' AND x ~* '(снаст|удоч|спиннинг)'
     )
     OR NOT EXISTS (
       SELECT 1
         FROM unnest(COALESCE(ot.included, ARRAY[]::text[])) AS y
        WHERE y ILIKE '%снаст%' OR y ILIKE '%удочк%'
     )
   );
