-- 1105: чат Telegram оператора — в колонку, которую читает доставка броней.
--
-- У оператора было ДВА места для чата Telegram, и читатели разошлись по ним:
--   - колонка partners.telegram_chat_id — уведомление о брони (notifyNewBooking
--     через lib/partners/reach) и перепись operator-reach;
--   - ключ contacts->>'telegram_chat_id' — раздача горячих лидов, напоминания
--     по лидам, приёмник оплат оператора и ручное поле в админке.
-- Администратор вписывал чат в админке — он ложился только в JSONB. Лиды до
-- оператора доходили, брони — нет, и перепись называла его «недостижимым».
--
-- С 29.09 оба пути записи (ссылка привязки и ручное поле) пишут в оба места.
-- Эта миграция сводит то, что успело накопиться: переносит чат из JSONB в
-- колонку, где колонка пуста. Только числовые значения — всё прочее (username,
-- мусор) не угадывается и остаётся как есть. Уже записанная колонка не
-- трогается: её писал бот по нажатию самого оператора, это более сильная
-- улика, чем ручной ввод.
--
-- Идемпотентна: второй прогон ничего не находит.

UPDATE partners
   SET telegram_chat_id = (contacts->>'telegram_chat_id')::bigint,
       updated_at = NOW()
 WHERE telegram_chat_id IS NULL
   AND contacts->>'telegram_chat_id' ~ '^-?[0-9]{1,18}$';
