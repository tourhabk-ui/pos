-- 1003: «Здесь начинается Россия» — свожу двойника, которого сам и завёл.
--
-- ── Что я сделал не так ───────────────────────────────────────────────────
--
-- Миграцией 997 я завёл место «Камчатский медведь (Здесь начинается Россия)»
-- по координате узла OpenStreetMap, не проверив, нет ли такого в каталоге.
-- Есть: `b7491ee7` «Здесь начинается Россия», 53.1673183 / 158.4196544 —
-- в двух с половиной километрах от той же стелы, в том же Елизове. Вылезло
-- это не поиском, а блоком «рядом» на собственной же новой карточке.
--
-- ── Почему это ОДИН объект, а не два ──────────────────────────────────────
--
-- Владелец 20.09 сказал прямо: «„Здесь начинается Россия“ это в Елизово
-- стелла». Обе записи стоят в Елизове и носят одно имя — надпись на камне.
--
-- Возражение, которое надо снять честно: текст старой записи описывает НЕ
-- Елизово. Он говорит про «южный мыс Камчатки», «линию Шумшу», «дыхание двух
-- морей» — это мыс Лопатка, триста семьдесят километров южнее, и там
-- действительно стоит свой знак с той же надписью. То есть по тексту это
-- другое место.
--
-- Решает не текст, а то, ЧЕМ он является. Описание у старой записи
-- сочинённое — тот же голос, что у «Снежной долины» (миграция 1002), где
-- выдумка опровергалась собственной координатой записи. Координата же —
-- записанный факт. Верю факту, а не сочинению: 53.167 / 158.420 — это
-- Елизово, и ничего от Лопатки там нет.
--
-- ── Кто из двух главный ───────────────────────────────────────────────────
--
-- Главной остаётся новая (`7c1f0a53`, ark `9a4c7e61`), и не потому что моя:
--
--   • координата взята с КОНКРЕТНОГО узла OSM, и он записан в `source_url`;
--     у старой `source_url` пуст вовсе;
--   • описание называет то, что на камне, и не сочиняет мысов;
--   • на ней стоит снимок владельца, у старой фотографии нет (`photoCount 0`).
--
-- Старая не удаляется, а СКРЫВАЕТСЯ со ссылкой на новую: страница дубля
-- уводит на главную запись, API отвечает «не найдено». Ссылки, если они
-- где-то есть, не обрываются.
--
-- Сочинённое описание у дубля не правится: скрытая запись не показывается
-- человеку и не попадает в поиск Кузьмича (там `merged_into_id IS NULL`).
-- Править текст, который никто не прочтёт, — работа ради вида.
--
-- ── Третий исход ──────────────────────────────────────────────────────────
--
-- Свожу ТОЛЬКО если главная запись жива и на ней действительно стоит снимок
-- владельца: иначе скрытие дубля оставило бы в каталоге ничего. Не сошлось —
-- RAISE WARNING в лог выката, дубль остаётся видимым.
--
-- IDEMPOTENT

BEGIN;

UPDATE places
   SET is_visible     = FALSE,
       -- ID МЕСТА, а не ark_id: так устроены прежние сведения (994, и то же
       -- видно у дубля «Большого Кара» — там в поле стоит id мастера).
       -- Колонка UUID, литерал типизируется присваиванием, приведение не нужно.
       merged_into_id = '7c1f0a53-2f4e-4c7a-9b6d-0e5a1d8c4b21',
       merged_at      = NOW(),
       updated_at     = NOW()
 WHERE id::text = 'b7491ee7-1ca2-4e39-a86d-39e56a9d17b4'
   AND (is_visible OR merged_into_id IS NULL)
   AND EXISTS (
         SELECT 1
           FROM places m
           JOIN ai_route_images ai ON ai.route_id = m.ark_id
          WHERE m.id::text = '7c1f0a53-2f4e-4c7a-9b6d-0e5a1d8c4b21'
            AND m.is_visible
            AND m.merged_into_id IS NULL
            AND ai.author = 'владелец платформы'
       );

-- ── Исход называется вслух ────────────────────────────────────────────────
DO $$
DECLARE
  v_twin_visible boolean;
  v_twin_merged  uuid;
  v_master_ok    boolean;
BEGIN
  SELECT is_visible, merged_into_id INTO v_twin_visible, v_twin_merged
    FROM places WHERE id::text = 'b7491ee7-1ca2-4e39-a86d-39e56a9d17b4';

  SELECT EXISTS (
    SELECT 1 FROM places m JOIN ai_route_images ai ON ai.route_id = m.ark_id
     WHERE m.id::text = '7c1f0a53-2f4e-4c7a-9b6d-0e5a1d8c4b21'
       AND m.is_visible AND m.merged_into_id IS NULL
       AND ai.author = 'владелец платформы'
  ) INTO v_master_ok;

  IF v_twin_visible IS NULL THEN
    RAISE WARNING '[1003] записи-двойника b7491ee7 нет — сводить нечего';
    RETURN;
  END IF;

  IF NOT v_master_ok THEN
    RAISE WARNING '[1003] главная запись стелы не готова (нет, скрыта или без снимка владельца) — дубль ОСТАЁТСЯ видимым';
    RETURN;
  END IF;

  IF v_twin_visible OR v_twin_merged IS NULL THEN
    RAISE WARNING '[1003] двойник НЕ сведён: is_visible=%, merged_into_id=%', v_twin_visible, v_twin_merged;
  END IF;
END $$;

COMMIT;
