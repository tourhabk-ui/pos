-- 1395: предмет заявки в журнале попыток записи MCP (аудит планировщика
-- 07.11, M5 и M6).
--
-- Порог «одна принятая заявка на номер за сутки» стоял на паре «телефон +
-- инструмент», без тура и даты. Второй тур того же плана получал «на этот
-- номер уже есть такая заявка… менеджер свяжется по первой» — а такой
-- заявки не было. Предмет (тур и дата, перевозчик и направление с датой,
-- машина и даты) отличает повтор той же заявки от следующей.
--
-- Персональных данных здесь по-прежнему нет: предмет — отпечаток с той же
-- солью, что телефон и адрес, а не номер тура и дата открытым текстом.
--
-- Исходы (outcome) прибавились: repeat — повтор той же заявки, второй лид не
-- создаётся; save_failed — допуск был, а заявка не сохранилась, и суточный
-- слот номера не сгорает. CHECK на колонке нет и не было (940).

ALTER TABLE mcp_write_attempts ADD COLUMN IF NOT EXISTS subject_hash CHAR(64);

CREATE INDEX IF NOT EXISTS idx_mcp_write_attempts_phone_subject
  ON mcp_write_attempts (phone_hash, subject_hash, created_at DESC)
  WHERE phone_hash IS NOT NULL AND subject_hash IS NOT NULL;
