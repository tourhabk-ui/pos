-- 877: якорь ставится по точке ПУТИ, а не по ближайшей к центру.
--
-- ── Что вскрылось ──────────────────────────────────────────────────────────
--
-- Миграция 847 выводила якорь безкоординатных маршрутов из их путевых точек и
-- брала ПЕРВУЮ по `position`. Обоснование записано в ней самой:
--
--   «Берётся ПЕРВАЯ точка по position (position 0 = старт, миграция 167):
--    якорь — это место, куда центрировать карту, и центрировать её логично
--    на начале пути»
--
-- Рассуждение верное, посылка — нет. У миграции 167 `position` это НЕ порядок
-- прохождения, а ранг по удалённости от ЦЕНТРА маршрута: она заводила связи
-- как «места в 15 км от центра» и нумеровала их по близости к нему. Значит
-- 847 брала не начало пути, а место, ближайшее к середине, — и у «Скал Три
-- Брата» это оказался бы краевой музей.
--
-- Разметка 874 сделала разницу видимой: связь рода `nearby` не описывает путь
-- вовсе. Теперь можно спросить не «какая точка первая», а «есть ли у маршрута
-- точка ПУТИ» — и ответить обеим группам по-разному.
--
-- ── Что делается ───────────────────────────────────────────────────────────
--
-- Трогаются ТОЛЬКО записи с `anchor_source = 'waypoint_first'` — те самые,
-- что поставила 847. Чужие якоря (`place_same_name`, ручные) не её дело.
--
--   есть точка пути  → якорь переставляется на первую ТАКУЮ точку,
--                      источник становится `waypoint_path_first`
--   точки пути нет   → координата ОСТАЁТСЯ, меняется её имя:
--                      `place_nearby_unverified`
--
-- Координата не стирается намеренно. Якорь — не путевая точка: по нему никто
-- не идёт, он центрирует карту и отвечает на «что рядом со мной». Стереть его
-- значит убрать запись с карты целиком ради того, чтобы не соврать на
-- пятнадцать километров. Поэтому здесь тот же выбор, что во всей Ф4: меняется
-- КЛАССИФИКАЦИЯ и причина, а не факт существования. Перепись теперь может
-- назвать такие якоря поимённо, а карточка — не выдавать их за точные.
--
-- Идемпотентна: второй прогон не найдёт `waypoint_first` ни у одной записи.
-- Идентификаторы сверяются как текст (см. 874: в этой схеме один и тот же id
-- живёт в разных типах, и route_waypoints.place_id — text при uuid у route_id).

BEGIN;

-- Есть точка пути: якорь переставляется на первую из них.
UPDATE kamchatka_routes r
   SET lat = w.lat,
       lng = w.lng,
       metadata = COALESCE(r.metadata, '{}'::jsonb)
                  || jsonb_build_object('anchor_source', 'waypoint_path_first'),
       updated_at = NOW()
  FROM (
    SELECT DISTINCT ON (rw.route_id)
           rw.route_id::text AS route_id, p.lat, p.lng
      FROM route_waypoints rw
      JOIN places p ON p.id::text = rw.place_id::text
     WHERE p.lat IS NOT NULL AND p.lng IS NOT NULL
       -- Только путь. «Рядом» — контекст, и якорь по нему это ровно та
       -- ошибка, которую чинит эта миграция.
       AND COALESCE(to_jsonb(rw)->>'link_kind', 'unknown') = 'waypoint'
     ORDER BY rw.route_id, rw.position, rw.id
  ) w
 WHERE w.route_id::text = r.id::text
   AND r.metadata->>'anchor_source' = 'waypoint_first';

-- Точки пути нет: координата остаётся, но перестаёт называться путевой.
UPDATE kamchatka_routes r
   SET metadata = COALESCE(r.metadata, '{}'::jsonb)
                  || jsonb_build_object('anchor_source', 'place_nearby_unverified'),
       updated_at = NOW()
 WHERE r.metadata->>'anchor_source' = 'waypoint_first';

COMMIT;

INSERT INTO _migrations (name)
VALUES ('877_anchor_from_path_points.sql')
ON CONFLICT (name) DO NOTHING;
