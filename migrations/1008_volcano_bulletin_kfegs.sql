-- 1008: суточная сводка КФ ФИЦ ЕГС РАН о состоянии вулканов (www.emsd.ru/vmon)
--
-- Решение владельца 24.09: «да, показывай обе шкалы на радаре».
--
-- Радар знал о вулканах только от KVERT (volcano_status, миграция 728), а у
-- KVERT шкала авиационная — код ICAO про пепел для самолётов. Сводка КФ ЕГС
-- ведёт СВОЮ шкалу, и её легенда стоит в самой сводке: жёлтый — «слабые
-- локальные землетрясения, повышенный уровень эмиссии вулканических газов,
-- сейсмичность выше фоновой». 22.09 так стояли Мутновский (255 событий за
-- сутки) и Горелый (221 и непрерывное дрожание) — пешие маршруты, — а KVERT
-- держал их зелёными, и на радаре их не было вовсе.
--
-- Отдельная таблица, а не колонка в volcano_status, намеренно. Слова цветов
-- у двух шкал совпадают, определения — нет; положить их в одно поле значило
-- бы решить за читателя, что это одно и то же, и перезаписывать одну шкалу
-- другой при каждом синке.
--
-- Строка — один вулкан в сводке одних суток. Сводка выходит раз в сутки «за
-- прошедшие сутки», и повторное чтение той же сводки попадает на тот же ключ.
--
-- color NULL — код не разобран (например «Белый»: в легенде источника его
-- нет, значение неизвестно). Приводить его к зелёному запрещено — зелёный
-- при неработающем мониторинге читается как «спокоен» там, где обсерватория
-- сказала «не вижу». Причина — в color_unknown_reason, дословный код — в
-- color_raw, всегда.

CREATE TABLE IF NOT EXISTS volcano_bulletin_kfegs (
  id                   BIGSERIAL PRIMARY KEY,
  -- Сутки, ЗА которые сводка, — из её заголовка, а не время чтения.
  observed_date        DATE NOT NULL,
  volcano_name         TEXT NOT NULL,
  volcano_name_en      TEXT,
  -- Место в каталоге; NULL — не сопоставилось (нет в каталоге или несколько
  -- кандидатов). Радар без места вулкан не нарисует, и это видно по счёту.
  place_ark_id         UUID,
  color                TEXT CHECK (color IN ('green', 'yellow', 'orange', 'red')),
  color_raw            TEXT NOT NULL,
  color_unknown_reason TEXT,
  -- Графа «Сейсмичность» дословно: в ней причина цвета («выше фона,
  -- событий 255, дрожание до 0.13 мкм/сек»), и её турист читает на радаре.
  seismicity           TEXT,
  fetched_at           TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  UNIQUE (observed_date, volcano_name)
);

CREATE INDEX IF NOT EXISTS idx_volcano_bulletin_kfegs_date
  ON volcano_bulletin_kfegs (observed_date DESC);
