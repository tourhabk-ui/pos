-- Инвентаризация (run 8) показала ~20 пар видимых РАЗНОимённых мест,
-- сидящих на одной точке (km=0.00-0.01) — след сломанного геокодинга:
-- «Вулкан Острый Толбачик»/«Водопад Фобос», «Вулкан Шивелуч»/«Каньон
-- Крылья Гамулов» и т.д. Партия 1: знаменитые объекты с публично
-- верифицируемыми координатами. Обновляем ТОЛЬКО если текущая координата
-- дальше ~2 км от верифицированной — ручные правки админкой не перетираем.
--
-- Партнёров по кластерам (Водопад Фобос, Каньон Крылья Гамулов,
-- Войновские ист., кластер Эссо: Дыгерен-Оленгенде/Черный замок/Галямаки/
-- Каньон Сноубордистов/Тупикин ключ и др.) НЕ трогаем: их точных координат
-- в открытых источниках нет, а их «одна точка» может быть и приблизительно
-- верной географией (Войновские реально у ГеоЭС). Следующая партия — после
-- ручной сверки или находки источников.
--
-- Источники координат:
--   Острый Толбачик  55°50'N 160°20'E — ru.wikipedia, kamchatsky-krai.ru
--   Овальная Зимина  55.86N 160.60E   — Global Volcanism Program (Zimina)
--   Шивелуч          56°38'N 161°19'E — kamchatsky-krai.ru (активный кратер)
--   Мутновская ГеоЭС 52°32'19"N 158°12'06"E — РУВИКИ
--   Шишель           57.45N 160.37E   — Global Volcanism Program
-- Идемпотентна.

UPDATE places SET lat = 55.8333, lng = 160.3333, updated_at = NOW()
 WHERE name = 'Вулкан Острый Толбачик'
   AND (lat IS NULL OR abs(lat - 55.8333) > 0.02 OR abs(lng - 160.3333) > 0.035);

UPDATE places SET lat = 55.8600, lng = 160.6000, updated_at = NOW()
 WHERE name = 'Вулкан Овальная Зимина'
   AND (lat IS NULL OR abs(lat - 55.8600) > 0.02 OR abs(lng - 160.6000) > 0.035);

UPDATE places SET lat = 56.6333, lng = 161.3167, updated_at = NOW()
 WHERE name = 'Вулкан Шивелуч'
   AND (lat IS NULL OR abs(lat - 56.6333) > 0.02 OR abs(lng - 161.3167) > 0.035);

UPDATE places SET lat = 52.5386, lng = 158.2018, updated_at = NOW()
 WHERE name = 'Мутновская ГеоЭС'
   AND (lat IS NULL OR abs(lat - 52.5386) > 0.02 OR abs(lng - 158.2018) > 0.033);

-- «Шишель» и «Гора Шишель» — один щитовой вулкан Срединного хребта, два
-- записи на одной (битой) точке. Ставим обеим верную координату и один
-- location_type: Шаг 8 ремонта данных (строгое вложение имени + <150 м +
-- один тип) сольёт их автоматически на следующем прогоне — со штатным
-- переносом waypoints, который в миграции городить не надо.
UPDATE places SET lat = 57.4500, lng = 160.3700, location_type = 'volcano', updated_at = NOW()
 WHERE name IN ('Шишель', 'Гора Шишель');
