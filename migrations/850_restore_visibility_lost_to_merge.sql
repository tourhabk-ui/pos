-- Migration 850: вернуть видимость там, где её отняло слияние
-- Created: 2026-08-14
--
-- ── Что произошло ───────────────────────────────────────────────────────────
--
-- Правило выбора оставляемого места при слиянии (`/api/cron/places-dedup`)
-- взвешивало фото и профиль безопасности — и НЕ смотрело на видимость. Поэтому
-- оно могло оставить скрытую запись, убрав видимую.
--
-- 14.08 это случилось с Авачинским: среди 145 записей типа «вулкан» не
-- осталось ни одной видимой записи Авачинского. Скрытая запись «Вулкан
-- Авачинский» стала главной, видимая ушла в дубли.
--
-- Похоже, к этому привели ДВА механизма дедупликации, работающие по разным
-- правилам: шаг дублей в `lib/services/data-repair.ts` ПРЯЧЕТ дубль
-- (`is_visible = false`), а `places-dedup` СЛИВАЕТ его (`merged_into_id`).
-- Спрятанное первым механизмом стало «оставленным» вторым.
--
-- ── Что делает эта миграция ─────────────────────────────────────────────────
--
-- Возвращает видимость оставшемуся месту РОВНО ТАМ, где слитое было видимым.
-- Условие точное, а не «раскрыть всех keeper-ов»: если обе записи были скрыты
-- намеренно (имена-неместа вроде «Скитур на Мутновский вулкан» скрыты по
-- делу), раскрывать их — значит вывести мусор на витрину.
--
-- Формулировка «публика видела это место до слияния — должна видеть и после»
-- проверяема по данным: is_visible слитой строки сохранён, слияние его не
-- трогает.
--
-- Правило на будущее живёт в коде (`keepScore`: видимость весит больше фото и
-- профиля), эта миграция — разовый ремонт уже случившегося.

BEGIN;

UPDATE places k
   SET is_visible = true
  FROM places m
 WHERE m.merged_into_id IS NOT NULL
   AND k.id = m.merged_into_id::text
   AND k.merged_into_id IS NULL
   AND k.is_visible = false
   AND m.is_visible = true;

COMMIT;

