-- 13.10 (решение владельца «согласен, перенеси в S3»): байты снимков вынесены в
-- хранилище — ключ migrations/photos/<sha256>.jpg из маркера
-- .github/triggers/migration-photos-to-s3.json (sha256 тех же байтов). Миграция
-- пишет s3_key, image_data пуст; прод переведён по хэшу байтов миграцией 1228.
--
-- 999: «Вулкан Ключевская сопка» — снимок владельца.
--
-- ── Чей кадр ──────────────────────────────────────────────────────────────
--
-- 20.09 владелец прислал снимок со словами, записанными дословно:
--
--   «Ключевской мое старое фото»
--
-- Автор — владелец платформы, он же принял решение публиковать. Подписью
-- ставится «владелец платформы» — то же, что у кадра шевелучской дороги
-- (989) и у стелы в Елизово (997). Имени владелец не называл, и подставлять
-- его я не буду.
--
-- ДАТА НЕ ЗАПИСЫВАЕТСЯ, хотя владелец сказал «старое». «Старое» — это не
-- дата, а оценка; превратить её в год значило бы выдумать факт (§4.0).
-- EXIF из файла снят целиком: там были съёмочные данные, которых владелец
-- не объявлял, и публиковать их вместе с кадром — не его решение.
--
-- ── Куда ложится ──────────────────────────────────────────────────────────
--
-- Запись есть и живая (проба 554): 54b106de «Вулкан Ключевская сопка»,
-- volcano, 56.056418/160.642299. Описание вулканологическое, подробное;
-- фотографии не было.
--
-- Рядом в каталоге лежат ещё две записи с тем же корнем, и обе НЕ подходят:
-- «Вид на долину у Ключевских вулканов» (viewpoint, 55.653/160.225) — это
-- отдельная видовая точка, а «Ключевская группа вулканов» (6f685f53) скрыта.
-- Снимок про сам вулкан, значит и ложится на вулкан.
--
-- Откуда СНЯТ кадр, здесь не объявляется. По виду это низина к западу от
-- конуса, но владелец точки съёмки не называл, EXIF снят, и координату
-- съёмки пришлось бы угадывать — а угаданное место на карточке читается
-- как факт.
--
-- ── Что на кадре ──────────────────────────────────────────────────────────
--
-- Конус Ключевской с парящей вершиной, справа — снежный массив соседних
-- вулканов группы, внизу осеннее поле и лиственничный подлесок. Это ровно
-- тот вид, которым вулкан виден человеку с земли: подняться на него могут
-- единицы, увидеть издали — все.
--
-- ── Размер ────────────────────────────────────────────────────────────────
--
-- Исходник 4032x3024 (4:3). Окно 16:9 полной ширины со смещением 150
-- пикселей сверху — срезана часть солнечного засвета в левом верхнем углу,
-- содержимое не менялось. Записывается 2000x1125: уменьшение, не
-- растягивание.
--
-- ── Как ложится ───────────────────────────────────────────────────────────
--
-- Герой карточки. Машинная картинка заменяется, чужой РУЧНОЙ снимок — нет
-- (граница та же, что в 981/983/984/994/996). Байты пишутся в базу, а не в
-- хранилище: миграция накатывается при старте сервера, и сетевой вызов
-- оттуда стопорил бы весь накат; увезёт уборщик cron-images-to-s3 (§4.1).
--
-- Третий исход назван вслух: нет ark_id или строку держит чужой ручной
-- кадр — RAISE WARNING в лог выката, а не молчание и не падение.
--
-- IDEMPOTENT

BEGIN;

INSERT INTO ai_route_images (route_id, image_data, mime_type, prompt, model, width, height, author, s3_key)
SELECT p.ark_id,
       NULL::bytea,
       'image/jpeg',
       'снимок владельца: Ключевская сопка с поля, парящая вершина (миграция 999)',
       'manual-upload',
       2000,
       1125,
       'владелец платформы',
       'migrations/photos/49fa3135f34aef99411ce172b422999a421dc8e31cf1f01706b8e6cc794270a0.jpg'
  FROM places p
 WHERE p.id::text = '54b106de-d81a-42af-9a41-32ee49604309'
   AND p.ark_id IS NOT NULL
 LIMIT 1
ON CONFLICT (route_id) DO UPDATE
   SET image_data = EXCLUDED.image_data,
       mime_type  = EXCLUDED.mime_type,
       prompt     = EXCLUDED.prompt,
       model      = EXCLUDED.model,
       width      = EXCLUDED.width,
       height     = EXCLUDED.height,
       author     = EXCLUDED.author,
       s3_url     = NULL,
       s3_key     = EXCLUDED.s3_key,
       created_at = NOW()
 WHERE ai_route_images.model NOT IN ('wikimedia', 'manual-upload')
    OR ai_route_images.prompt = 'снимок владельца: Ключевская сопка с поля, парящая вершина (миграция 999)';

-- ── Отказ называется вслух ────────────────────────────────────────────────
DO $$
DECLARE
  v_ark    uuid;
  v_author text;
BEGIN
  SELECT ark_id INTO v_ark FROM places WHERE id::text = '54b106de-d81a-42af-9a41-32ee49604309';

  IF v_ark IS NULL THEN
    RAISE WARNING '[999] у «Ключевской сопки» нет ark_id — снимок НЕ лёг, карточка осталась без фото';
    RETURN;
  END IF;

  SELECT author INTO v_author FROM ai_route_images WHERE route_id = v_ark;

  IF v_author IS DISTINCT FROM 'владелец платформы' THEN
    RAISE WARNING '[999] герой «Ключевской сопки» НЕ стал снимком владельца: там %', COALESCE('автор «' || v_author || '»', 'строки снимка нет');
  END IF;
END $$;

COMMIT;
