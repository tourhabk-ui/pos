-- Партия 3 уборки маршрутов: паутины уходят с витрины (решение владельца
-- 15.08: «паутины удалять»).
--
-- Перепись (проба 51) нашла 15 «маршрутов»-коллекций с разлётом путевых
-- точек до 397 км. Шесть из них — бесспорный мусор одного помёта: у всех
-- размах ровно 397 км, имена — темы, а не пути («Горные вершины»,
-- «Побережье Тихого океана», «Рыбалка на Камчатке»), и три из них сидят
-- на одном якоре 53.0, 158.5 (круглые числа — заглушка). По такой линии
-- идти нельзя, и линией она не является.
--
-- Девять пограничных (25–61 км) НЕ трогаем: «Однодневный поход к
-- Авачинскому вулкану» с разлётом 27 км — это похоже на честный маршрут
-- с подъездом, и критерий «span > 20 км» его от паутины не отличает.
-- Их разбор — построчно, в партии 6 (см. routes-pain-map).
--
-- «Удаление» выполнено скрытием, а не DELETE, сознательно: на
-- kamchatka_routes смотрят FK (route_waypoints, operator_tours.route_id),
-- и физическое удаление строк без проверки ссылок может уронить тур.
-- Скрытие убирает паутину из каталога, карты и поиска (витрина читает
-- только is_visible=true) и обратимо. Если владелец хочет стереть строки
-- физически — отдельной миграцией после проверки ссылок.
--
-- Идемпотентна: только пока запись видима.

UPDATE kamchatka_routes SET is_visible = false, updated_at = NOW()
 WHERE (id::text IN (
     '82ed6f99-bf81-404b-a7ee-e7f62a3386aa',  -- Озеро Приливное – Халактырский пляж (397 км, 35 wp)
     '9d4c1a6c-5091-408c-b1f3-4db1b41656d0',  -- Авачинская бухта (397 км, 31 wp)
     'ae251e80-9620-474f-ba32-7a7282b6e200',  -- Горные вершины (397 км, 21 wp)
     'b6429ce0-1c2c-42ef-87af-b44366f3d81b',  -- Побережье Тихого океана (397 км, 21 wp)
     'bc314f94-c58d-4618-b748-09943918f04d',  -- Смотровая с видом на Тихий океан (397 км, 35 wp)
     'ec54754e-ffcb-4ab4-9300-2e92d7352cd5'   -- Рыбалка на Камчатке (397 км, 21 wp)
   ) OR ark_id::text IN (
     '82ed6f99-bf81-404b-a7ee-e7f62a3386aa',
     '9d4c1a6c-5091-408c-b1f3-4db1b41656d0',
     'ae251e80-9620-474f-ba32-7a7282b6e200',
     'b6429ce0-1c2c-42ef-87af-b44366f3d81b',
     'bc314f94-c58d-4618-b748-09943918f04d',
     'ec54754e-ffcb-4ab4-9300-2e92d7352cd5'
   ))
   AND is_visible = true;

