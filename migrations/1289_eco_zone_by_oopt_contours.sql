-- 1289: Режим мест по контурам охраняемых территорий OSM — 21 место внутри
--       Кроноцкого заповедника, 4 — Тимоновского заказника, 2 — парка
--       «Налычево», 2 — Командорского заповедника.
-- Created: 2026-10-15
--
-- ── Почему ───────────────────────────────────────────────────────────
--
-- Перепись режима по схеме парков (владелец 14.10: «Бери по порядку схему…
-- делаешь без моих потверждений»). У 259 видимых мест режим не записан:
-- 161 «нет» проставила 170 одним UPDATE всем оставшимся, без сверки, ещё 98
-- «не записано» (перепись place-eco-census, проба 957). Партии по
-- территориям 1240–1274 брали места списком, найденным тогда, и часть точек
-- внутри тех же границ осталась без режима — среди них Узон, Кихпиныч,
-- Долина смерти, Гейзер Красный, вулканы Крашенинникова и Большой Семячик.
-- На карточке Узона, внутри заповедника, о разрешении не было ни слова.
--
-- ── Как найдено ─────────────────────────────────────────────────────────
--
-- Сверка place-oopt-contours (прогон 2): точки всех 259 мест против
-- контуров охраняемых территорий из выгрузки Geofabrik (`osmium`, 14
-- контуров по краю). Контроль сошёлся: Долина гейзеров — внутри Кроноцкого,
-- Голая — вне. На 16 точках партии 3 ответ совпал с is_in Overpass (проба
-- 964) — два независимых пути. Внутри хотя бы одного контура — 40 мест,
-- вне всех — 221; «вне» не значит «не охраняется»: памятников природы в OSM
-- края нет ни одного.
--
-- ── Что ставится ─────────────────────────────────────────────────────────
--
-- Режим территории — это режим каждой её точки, поэтому правила те же, что
-- у мест той же территории в прежних партиях, и с теми же источниками:
--   Кроноцкий заповедник (отношение 2800189) — как пять мест 1274: заявка
--     на kronoki.ru/ru/visit/requests/, только с гидом, регистрация в МЧС,
--     служба охраны; 21 место;
--   Тимоновский заказник (отношение 10254493) — как Ново-Бакенинг (1274):
--     положения заказника на платформе нет, разрешение «не записано»;
--     4 места (Костакан — в партии 3, 1288);
--   природный парк «Налычево» (отношение 3978019) — правила 1248; обе точки
--     у Авачинского перевала, а граница зоны свободного посещения у нас не
--     размечена — поэтому разрешение «не записано» и это сказано словами;
--   Командорский заповедник, с 2022 года национальный парк «Командорские
--     острова» (отношение 5576397) — как у карточки парка (1243) и Арки
--     Стеллера (1288); 2 места.
--
-- ── Чего здесь нет — и почему ───────────────────────────────────────────
--
--   шесть точек острова Беринга внутри только второго контура (отношение
--     1962840, «ФГУ заповедник «Командорский»») — лежбища, Чёртова яма и три
--     постройки Никольского. Совпадает ли этот контур с границей
--     национального парка, источником не подтверждено, а постройки стоят в
--     селе;
--   две точки в самом Эссо внутри контура парка «Быстринский» — источники и
--     Шаманская поляна: село лежит внутри парка, но нужно ли разрешение
--     парка на улице районного центра, источники не говорят — 1246 решила
--     так же.
-- Их режим не ставится, пока это не сверено по положению.
--
-- Пишется ТОЛЬКО поверх пустоты или «нет» 170-й и без своих правил: что
-- записано рукой, не трогается.
--
-- ПОСЛЕ ВЫКАТА перезалив пакетов карты не нужен: режима в пакетах нет.
--
