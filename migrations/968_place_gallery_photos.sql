-- 968: галерея места — вторая и последующие фотографии.
--
-- ── Зачем отдельная таблица, а не вторая строка в ai_route_images ─────────
--
-- У ai_route_images уникальный индекс по route_id с миграции 107: одно место —
-- одна фотография. Естественное решение — снять индекс и добавить position —
-- ЗАПРЕЩЕНО следствием, которое видно только в чужом коде: `ON CONFLICT
-- (route_id)` стоит в двадцати одном месте, включая ДЕСЯТЬ УЖЕ ПРИМЕНЁННЫХ
-- миграций (930, 958-967).
--
-- Вывод типов ON CONFLICT требует уникального индекса ровно по указанным
-- колонкам: с индексом по (route_id, position) все эти запросы ответят
-- 42P10 «no unique or exclusion constraint matching the ON CONFLICT
-- specification». Живой код можно поправить; применённые миграции — нельзя,
-- они идут только вперёд, и на чистой базе переиграются и упадут. Тот же
-- 42P10, который разбирался сегодня утром в очереди обзвона операторов.
--
-- Поэтому герой остаётся там, где был, нетронутым, а галерея живёт рядом.
-- Цена решения названа честно: снимки места лежат в двух таблицах, и
-- читающий обязан помнить обе. Взамен ни одна существующая запись и ни один
-- существующий писатель не трогаются вовсе.
--
-- ── Почему это вообще нужно ───────────────────────────────────────────────
--
-- Галерея на карточке УЖЕ НАПИСАНА: components/places/PlaceHero.tsx умеет
-- свайп, снаппинг и счётчик «3/7», включается при images.length > 1. Кормится
-- она из places.images — списка ССЫЛОК, — а наши снимки лежат байтами в
-- ai_route_images, по одному на место. То есть механизм есть, а производителя
-- у него для наших фотографий нет: правило 10.09 в чистом виде.
--
-- 14.09 это стало стоить дела: из двадцати присланных владельцем кадров на
-- карточки попало одиннадцать, остальные девять класть было некуда.
--
-- ── Поля ──────────────────────────────────────────────────────────────────
--
-- ark_id — тот же ключ, что route_id у ai_route_images (places.ark_id).
-- Внешнего ключа нет намеренно: у ai_route_images его тоже нет, а FK на
-- places.ark_id (не PK, nullable) пришлось бы заводить с уникальным индексом
-- на чужую таблицу — правка шире задачи.
--
-- position — порядок в галерее. Герой из ai_route_images всегда идёт первым и
-- позиции не занимает; здесь нумерация с 1, чтобы «первый» и «второй» в коде
-- и на экране значили одно и то же.
--
-- s3_url — переезд в объектное хранилище (миграция 944) идёт и здесь; поле
-- заведено сразу, чтобы галерея не оказалась единственным местом, откуда
-- байты нельзя убрать.
--
-- Права — те же четыре поля, что у ai_route_images: снимок без автора и
-- лицензии подписывать нечем, а приписывать чужое имя нельзя (правка 14.09).
--
-- IDEMPOTENT

BEGIN;

CREATE TABLE IF NOT EXISTS place_gallery_photos (
  id          UUID         PRIMARY KEY DEFAULT gen_random_uuid(),
  ark_id      UUID         NOT NULL,
  position    INT          NOT NULL,
  image_data  BYTEA,
  s3_url      TEXT,
  mime_type   VARCHAR(20)  NOT NULL DEFAULT 'image/jpeg',
  width       INT          NOT NULL,
  height      INT          NOT NULL,
  caption     TEXT,
  author      TEXT,
  license     TEXT,
  license_url TEXT,
  source_url  TEXT,
  created_at  TIMESTAMPTZ  NOT NULL DEFAULT NOW(),
  -- Строка без байтов И без ссылки — это не снимок, а запись о его отсутствии.
  -- Такую в галерее показывать нечем, и заводить её незачем.
  CONSTRAINT place_gallery_photos_has_image
    CHECK (image_data IS NOT NULL OR s3_url IS NOT NULL)
);

-- Порядок в пределах места однозначен: две фотографии не могут быть обе
-- второй. Он же служит ключом ON CONFLICT для повторной укладки.
CREATE UNIQUE INDEX IF NOT EXISTS place_gallery_photos_ark_position_idx
  ON place_gallery_photos (ark_id, position);

COMMENT ON TABLE place_gallery_photos IS
  'Вторая и последующие фотографии места. Первая (герой) — в ai_route_images, где уникальный индекс по route_id снять нельзя: ON CONFLICT (route_id) стоит в уже применённых миграциях.';
COMMENT ON COLUMN place_gallery_photos.position IS
  'Порядок в галерее, с 1. Ноль не используется: нулевая позиция — это герой, и он лежит в другой таблице.';

COMMIT;
