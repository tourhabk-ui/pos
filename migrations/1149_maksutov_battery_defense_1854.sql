-- 1149: Батарея Максутова — справка об обороне 1854 года вместо выдуманной заметки
--
-- ── Повод (03.10) ──────────────────────────────────────────────────────────
--
-- Владелец: «я хочу статью про героическую оборону 1854; там написан бред».
-- На проде лежала путевая заметка от первого лица: «Поднимаешься от ключевой
-- пади к Красному Яру — и океанский ветер бьёт в лицо… Чугунная плита на
-- гранитном валуне… "Лейтенант Максутов и 12 нижних чинов"…». MCP уже
-- отказывался её приводить (lib/places/description-voice). Ни «плиты на
-- валуне», ни «12 нижних чинов» в источниках нет, а Красный Яр — место
-- батареи № 4, не № 3. Исходная запись 103 тоже путала: называла погибшим
-- «Петра Александровича», а командование — перешедшим к брату.
--
-- ── Из чего новый текст ───────────────────────────────────────────────────
--
-- Только из двух статей Википедии, снятых с раннера пробами 645-646:
-- «Петропавловская оборона» и «Максутов, Александр Петрович». Числа, где
-- источники расходятся (потери союзников), даны вилкой, а не одним числом.
-- Чугунные пушки на снимках владельца (1147) — макет батареи 1967 года,
-- поставленный на её месте (та же статья о Максутове).
--
-- ── Границы правки ─────────────────────────────────────────────────────────
--
-- Правится только запись, где лежит та самая заметка (отбор по её обороту).
-- Успел кто-то поправить раньше — миграция не делает ничего. Старый текст
-- дословно не приводится целиком: его начало выше, а длина пишется в
-- description_provenance.previous_chars. Идемпотентна.

WITH old AS (
  SELECT id, LENGTH(description) AS prev_chars
    FROM places
   WHERE id::text = 'a2b3c4d5-e6f7-4890-bcde-f01234567890'
     AND description LIKE '%Поднимаешься от ключевой пади%'
),
upd AS (
  UPDATE places p
     SET description = 'Батарея № 3, «Перешеечная», — одна из семи береговых батарей, которыми Петропавловский порт встретил англо-французскую эскадру в августе 1854 года, в Крымскую войну. Она стояла на перешейке, в седловине между Сигнальной и Никольской сопками: пять 24-фунтовых орудий, снятых с фрегата «Аврора», и 52 человека. Командовал ею 24-летний лейтенант князь Александр Петрович Максутов, офицер «Авроры».

Эскадра контр-адмиралов Дэвида Прайса и Фебврье-Деспуанта — шесть кораблей, около 200 орудий и 2700 человек — вошла в Авачинскую бухту 18 (30) августа. Гарнизон военного губернатора В. С. Завойко вместе с экипажами «Авроры» и транспорта «Двина» насчитывал 988 человек. Перед первым штурмом адмирал Прайс погиб; обстоятельства его смерти источники толкуют по-разному.

20 августа (1 сентября) батарея № 3 первой открыла огонь по эскадре. Союзники в тот день подавили батареи № 1 и № 4 и высадили десант у «Кладбищенской» батареи, но отряд из 130 человек заставил его вернуться на корабли.

24 августа (5 сентября) главный удар пришёлся на батареи № 3 и № 7. Батарея № 3 почти не была прикрыта бруствером: четыре орудия из пяти были разбиты, больше половины прислуги ранены и убиты. Максутов сам заряжал и наводил последнее орудие, потопил катер с десантом и был тяжело ранен — ему оторвало руку. После боя батарею назвали «Смертельной».

На Никольскую сопку поднялось около тысячи десантников. Около 350 защитников, собранных Завойко со всех позиций, контратаковали вверх по склону и сбросили десант; часть его сорвалась с обрыва к морю. Трофеями стали знамя, семь офицерских сабель и 56 ружей. Русские потеряли в этот день 34 человека. Потери союзников в источниках расходятся: от 210 убитых и раненых за всю экспедицию до около 400 убитых в этом бою. 27 августа (8 сентября) эскадра покинула бухту.

Александр Максутов умер от ран 10 (22) сентября 1854 года и посмертно награждён орденом Святого Георгия IV степени. В 1954 году здесь открыт памятник «Героям III батареи лейтенанта А. П. Максутова» — объект культурного наследия федерального значения. В 1959 году на месте батареи поставили деревянный макет, в 1967 году его сменили чугунные пушки.

Источник: статьи Википедии «Петропавловская оборона» и «Максутов, Александр Петрович».',
         updated_at = NOW()
    FROM old
   WHERE p.id::text = old.id::text
  RETURNING p.ark_id, p.name, p.description, old.prev_chars
)
INSERT INTO description_provenance
  (entity_id, entity_kind, entity_title, written_by, facts_given, facts_count,
   chars, previous_chars)
SELECT
  upd.ark_id,
  'place',
  upd.name,
  'owner-decision',
  '["батарея № 3 «Перешеечная»: перешеек между Сигнальной и Никольской сопками, 5 × 24-фунтовых орудий с «Авроры», 52 человека, командир лейтенант А. П. Максутов (Википедия, «Петропавловская оборона»)","эскадра Прайса и Фебврье-Деспуанта: 6 кораблей, ~200 орудий, ~2700 человек; гарнизон 988 человек (там же)","20 августа (1 сентября): батарея № 3 первой открыла огонь; десант у батареи № 4 отбит отрядом в 130 человек (там же; «Максутов, Александр Петрович»)","24 августа (5 сентября): 4 из 5 орудий разбиты, Максутов потопил катер с десантом, ранен; батарея названа «Смертельной» (обе статьи)","бой на Никольской сопке: ~1000 десантников против ~350 защитников; трофеи — знамя, 7 сабель, 56 ружей; русские потери 34; потери союзников 210 за экспедицию либо ~400 убитых (Википедия)","Максутов умер 10 (22) сентября 1854, орден Святого Георгия IV степени посмертно; памятник 1954, макет 1959, чугунные пушки 1967 («Максутов, Александр Петрович»)"]'::jsonb,
  6,
  LENGTH(upd.description),
  upd.prev_chars
FROM upd
WHERE upd.ark_id IS NOT NULL;
