-- 923: аренда окна прогона — один крон в окне, сколько бы ни было планировщиков.
--
-- Зачем. У safety-кронов теперь три возможных источника запуска: расписание
-- GitHub Actions, внешний планировщик cron-job.org (заведён владельцем 29.08)
-- и супервизор самого контейнера (start.js). Первый доставляет 1-4% от
-- запрошенного, поэтому опираться на него нельзя; но и просто добавить
-- четвёртый источник нельзя тоже — Watchdog разошлёт алерт дважды, а
-- sos-events-bridge дважды выпустит одно событие.
--
-- Аренда решает это на стороне сервера, а не договорённостью между
-- планировщиками: кто первым занял окно, тот и работает, остальные уходят
-- с названной причиной. Договорённость держится, пока её помнят; ключ в
-- таблице держится всегда.
--
-- window_start — начало окна, выровненное по длине окна агента (см.
-- lib/agents/cron-lease.ts). Первичный ключ и есть замок: второй INSERT в то
-- же окно не проходит.

CREATE TABLE IF NOT EXISTS cron_leases (
  agent_id     TEXT        NOT NULL,
  window_start TIMESTAMPTZ NOT NULL,
  claimed_at   TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  -- Кто занял: 'supervisor' (start.js), 'external' — для разбора, почему в
  -- окне сработал не тот, на кого думали.
  claimed_by   TEXT,
  PRIMARY KEY (agent_id, window_start)
);

-- Для уборки старых аренд диапазоном (идёт тем же запросом, что и захват).
CREATE INDEX IF NOT EXISTS idx_cron_leases_window ON cron_leases (window_start);
