-- Migration 1393: закрытие «на всех территориях природных парков» — парки у
-- уже записанной тревоги (#2980, 05.11).
--
-- Сводка 02.11 («Закрытие маршрутов «Вулканы Камчатки» сообщают о закрытии
-- туристических маршрутов на всех территориях природных парков на период
-- межсезонья») стоит в ленте до 9 ноября, но парков у неё нет: правило
-- «закрыт конкретный маршрут „…“» приняло кавычки после «маршрутов» за имя
-- маршрута и сочло закрытие частичным. Пока держалась тревога 29.10 с
-- названными парками, этого не было видно; 05.11 она вышла из ленты, и
-- Налычево стало ЗЕЛЁНЫМ при закрытии всех парков.
--
-- Правило исправлено в lib/safety/park-closure.ts, но запись тревоги — ON
-- CONFLICT DO NOTHING, и уже записанную строку повторный приход не исправит.
-- Здесь — та же разметка, что дал бы исправленный код (род park_closure,
-- пять природных парков, без зон: привязка по парку): только действующие
-- тревоги без парков, в тексте которых закрытие на всех территориях
-- природных парков и нет открытия. Заповедники (Кроноцкий, Командорский)
-- такая фраза не называет — их здесь нет.
--
-- Повтор — без изменений: строка с парками условию не отвечает.

BEGIN;

UPDATE external_alerts
   SET alert_type     = 'park_closure',
       affected_parks = ARRAY['nalychevo', 'yuzhno-kamchatsky', 'bystrinskiy', 'klyuchevskoy', 'vilyuchinsky'],
       affected_zones = '{}'
 WHERE affected_parks IS NULL
   AND expires_at > (NOW() AT TIME ZONE 'UTC')  -- время тревог — стенное UTC (#2495)
   AND lower(title || ' ' || COALESCE(description, '')) ~ '(всех|все|всем)\s+(территори[а-яё]*\s+|маршрут[а-яё]*\s+)?природн(ых|ые|ым)\s+парк'
   AND lower(title || ' ' || COALESCE(description, '')) ~ '(закрыт|приостановлен|запрещ[её]н|прекращ[её]н)'
   AND lower(title || ' ' || COALESCE(description, '')) !~ '(возобновл[её]н|вновь\s+открыт|снят[ыо]?\s+ограничени|открыт[ыо]?\s+для\s+посещени)';

COMMIT;

