-- Migration 991: объявить три колонки профиля гида, которые на проде есть,
-- а в миграциях не объявлены ни разу.
--
-- ── Как нашлись (20.09) ────────────────────────────────────────────────────
--
-- Перепись готовности гидов (#1926) прочитала partners.languages,
-- partners.specializations и partners.photo_url — и сторож
-- `sql-phantom-columns` не пустил её в main: в DDL репозитория этих колонок
-- нет.
--
-- ── ПОПРАВКА к первой редакции этой шапки ─────────────────────────────────
--
-- Сначала здесь было написано: «колонки настоящие, кто-то добавил их на проде
-- руками». Это было ДОГАДКОЙ, и она не подтвердилась. Проверка на поднятом
-- PostgreSQL 16.13 (baseline прода 2026-08-15 + все миграции новее) показала:
-- у `partners` 77 колонок, и ни одной из этих трёх среди них нет. В baseline
-- их нет, ни одна миграция их не добавляет.
--
-- ── Что это значит на самом деле ──────────────────────────────────────────
--
-- Страница гида НЕ МОЖЕТ РАБОТАТЬ. `app/guides/[id]/page.tsx` выбирает
-- двенадцать колонок, и пять из них не существуют: languages,
-- specializations, photo_url, experience_years, phone. PostgreSQL отвечает
-- 42703, а запрос обёрнут в пустой `catch { return null; }` — и `null` из
-- `getGuide` означает «Гид не найден».
--
-- То есть все 112 страниц гидов показывают «не найден», всегда, и никто об
-- этом не узнаёт: отказ проглочен (§4.0 — молчащий catch превращает поломку
-- в «данных нет»).
--
-- Сторож фантомных колонок этого не ловил, потому что сканирует
-- `app/**/*.ts` и `lib/**/*.ts`, а страница — `.tsx`. Проверка половины
-- поверхности зеленеет ровно там, где отвалилась вторая.
--
-- Поэтому миграция объявляет ПЯТЬ колонок, а не три: меньшим числом страница
-- останется мёртвой. Те же поля правит кабинет гида
-- (`_GuideProfileClient.tsx`) и читает `lib/auth/guide-helpers.ts` — то есть
-- функция написана целиком, ей просто никогда не создали место в схеме.
--
-- ── Почему это чинится миграцией, а не записью в список исключений ─────────
--
-- Базовая линия сторожа заморожена и «может только сокращаться»; новая запись
-- в ней запрещена без миграции. Сам сторож называет верный путь первым:
-- «реальная колонка, добавленная в прод руками → миграция». Запись в список
-- оставила бы схему-источник неполной, а именно из-за её неполноты ошибка в
-- колонке доживает до прода.
--
-- Поэтому вместе с этой миграцией из базовой линии УБИРАЮТСЯ три записи,
-- которые она покрывает (guide-helpers × languages/specializations,
-- guide/map × specializations): долг сокращается, а не растёт.
--
-- ── Почему это безопасно ───────────────────────────────────────────────────
--
-- `ADD COLUMN IF NOT EXISTS` существующую колонку НЕ трогает: ни тип, ни
-- данные. На проде миграция — no-op и нужна ровно затем, чтобы схема
-- репозитория совпала с действительностью. На чистом инстансе она создаёт
-- колонки в том виде, в каком их уже читает код.
--
-- Типы взяты из употребления кода, а не из догадки. `GuideProfile` в
-- `app/guides/[id]/page.tsx`: `languages: string[] | null`,
-- `specializations: string[] | null` (и считаются через ARRAY_LENGTH) —
-- массив текста; `photo_url: string | null` идёт в `src` изображения —
-- текст; `experience_years: number | null` — целое; `phone: string | null` —
-- короткая строка. Прецедент формы — миграция 694, так же доописывавшая
-- partners по факту обращений кода.
--
-- Данных миграция не пишет: колонки заводятся пустыми. Заполняет их кабинет
-- гида, и пустое поле страница уже умеет не показывать.

ALTER TABLE partners
  ADD COLUMN IF NOT EXISTS languages        TEXT[],
  ADD COLUMN IF NOT EXISTS specializations  TEXT[],
  ADD COLUMN IF NOT EXISTS photo_url        TEXT,
  ADD COLUMN IF NOT EXISTS experience_years INTEGER,
  ADD COLUMN IF NOT EXISTS phone            VARCHAR(50);
