-- 873: откуда у места координата.
--
-- Ночь 17–18.08 ушла на то, чтобы линия маршрута называла своё происхождение:
-- снята прибором, построена прямыми, пришла импортом. У ТОЧКИ такого не было
-- вовсе.
--
-- Геокодер (/api/cron/places-geocode) поднимает места без GPS в координаты по
-- НАЗВАНИЮ через Nominatim и пишет их в lat/lng, ничем не помечая. Снятая с
-- прибора точка и точка, угаданная по имени, лежат в базе неотличимо.
--
-- Цена этого вскрылась 18.08. Уборка битых привязок объявляла ложью связь
-- «маршрут — точка», если точка дальше двух километров от трека. А среди
-- «лжи» оказались: парк Налычево (32 км), Халактырский пляж (4.5), озеро
-- Паланское (3.4) — протяжённые объекты, у которых координата это центроид
-- Nominatim, и расстояние до неё не значит ничего.
--
-- Значения:
--   surveyed    — координата снята на месте (GPS, официальный паспорт)
--   geocoded    — угадана по названию (Nominatim и подобные)
--   placeholder — заглушка (0,0 или центр Петропавловска)
--   unknown     — не записано; для существующих строк это ЧЕСТНЫЙ ответ
--
-- Backfill намеренно скупой: помечаем только то, что видно из самих данных —
-- плейсхолдеры. Всё остальное остаётся `unknown`, потому что объявить
-- существующие координаты снятыми было бы той же выдумкой, ради которой эта
-- колонка и заводится.

ALTER TABLE places ADD COLUMN IF NOT EXISTS coord_source VARCHAR(24) NOT NULL DEFAULT 'unknown';
ALTER TABLE places ADD COLUMN IF NOT EXISTS coord_source_at TIMESTAMPTZ;

-- Плейсхолдеры видны по значению: нули и центр Петропавловска, которым
-- импорт затыкал отсутствие координат (см. 741).
UPDATE places
   SET coord_source = 'placeholder',
       coord_source_at = NOW()
 WHERE coord_source = 'unknown'
   AND (
     (lat = 0 AND lng = 0)
     OR (ROUND(lat::numeric, 4) = 53.0444 AND ROUND(lng::numeric, 4) = 158.6483)
   );

CREATE INDEX IF NOT EXISTS idx_places_coord_source ON places (coord_source);
