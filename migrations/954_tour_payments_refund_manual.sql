-- 954: ручной возврат tour_payments — кто оформил, помимо когда и сколько
--
-- Решение владельца 11.09 (#1813): возврат туристу при отмене — 100%, пока без
-- исключений по срокам. Схема уже несла `refunded_at`, `refund_amount`,
-- `refund_reason` (миграция 051) — писателя у них не было ни одного, только
-- вопрос «сколько возвращать» оставался открытым. Он закрыт; технический
-- возврат через API CloudPayments/Точки НЕ подключён (отдельное решение,
-- не сегодняшнее), поэтому запись остаётся ручной: администратор переводит
-- деньги за пределами платформы и фиксирует факт здесь.
--
-- Ручной факт без автора — это ровно то же самое анонимное `commission_rate`
-- без источника, за которое отдельно разбирались 11.09 (§7 CLAUDE.md). У
-- `operator_payouts.created_by` такой автор есть; у возврата — тоже должен
-- быть, тем же способом (REFERENCES users(id), как у `cancelled_by` в
-- миграции 019).

ALTER TABLE tour_payments
  ADD COLUMN IF NOT EXISTS refunded_by UUID REFERENCES users(id);

COMMENT ON COLUMN tour_payments.refunded_by IS
  'Админ, отметивший возврат сделанным. NULL до первого возврата — не значит «сделал никто», значит «возврата ещё не было».';
