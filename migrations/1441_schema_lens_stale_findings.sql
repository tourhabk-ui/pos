-- 1441: снять с очереди находки объектива схемы, заведённые до его починки.
--
-- Слово владельца 14.11 «делай» — на вопрос, брать ли задачу #3343
-- «Обращение к несуществующей колонке». Задача оказалась ложной, третьей
-- подряд (до неё #2891 и #3268), и причина у всех одна: объектив схемы
-- (lib/agents/evo/schema-lens) судил по модели, которая не понимала
-- переименование таблицы (миграция 1350). Замер 14.11 на коде main: 119
-- находок, из них настоящих 2 — обе об одной колонке.
--
-- Объектив починен тем же PR. Но находки, записанные до починки, лежат в
-- очереди (`open`, `suggested`) и выходили бы задачами дальше — по одной раз
-- в несколько дней, каждая «critical». Здесь они снимаются с очереди.
--
-- ЧТО СНИМАЕТСЯ. Только находки самого объектива: его заголовок и его
-- дословная фраза в описании. Находку модели с похожим заголовком условие
-- не заденет — у неё другое описание.
--
-- ЧТО НЕ ТРОГАЕТСЯ. Находки, по которым задача уже заведена
-- (github_issue_url не пуст): их вердикт — закрытие задачи человеком, и он
-- доезжает сам (evo-report). Уже разобранные (accepted, rejected, ignored).
--
-- КАКОЕ СЛОВО СТАВИТСЯ. `ignored`, не `rejected` (тот же довод, что в 912):
-- `rejected` навсегда заглушил бы класс «колонки нет» на этом файле, а
-- настоящая такая находка там возможна. `ignored` в стоп-лист не идёт и
-- повторной записи не мешает: если находка настоящая, следующий прогон
-- починенного объектива запишет её заново. В счёт точности эти строки не
-- входят — он считается по опубликованным.
--
-- Идемпотентна: повторный запуск ничего не находит.

BEGIN;

UPDATE evo_growth_issues
   SET status = 'ignored', resolved_at = NOW()
 WHERE status IN ('open', 'suggested')
   AND github_issue_url IS NULL
   AND (
     (title = 'Обращение к несуществующей колонке'
       AND description ~ '^в таблице \S+ нет колонки \S+ — запрос упадёт$')
     OR
     (title = 'Соединение мимо внешнего ключа'
       AND description ~ '^\S+ ссылается на \S+ внешним ключом, а соединяется с \S+ — совпадений не будет$')
   );

COMMIT;

