-- Migration 797: точка сбора тура (meeting_point) + логистика сплава по Быстрой
--
-- У туров не было структурного поля «где собираемся / старт / забор». Владелец
-- дал точные ориентиры по сплаву на трассе А4 (Петропавловск — Мильково):
--   • старт сплава — 147-й км трассы А4;
--   • стоянка и забор трансфера — 139-й км трассы А4.
-- Для safety-платформы это важная логистика — показываем как есть, без выдумок.
--
-- Добавляем общий столбец meeting_point (TEXT) для всех операторов и заполняем
-- его для тура по Быстрой. Идемпотентна.

ALTER TABLE operator_tours ADD COLUMN IF NOT EXISTS meeting_point TEXT;

UPDATE operator_tours t
   SET meeting_point = E'Старт сплава — 147-й км трассы А4.\nСтоянка и забор трансфера — 139-й км трассы А4.\nВыезд из Петропавловска-Камчатского, возможен забор из Паратунской зоны отдыха.',
       updated_at = NOW()
  FROM partners p
 WHERE p.id = t.operator_id
   AND p.slug = 'kamchatka-rafting'
   AND t.title = 'Однодневная экскурсия СПЛАВ ПО РЕКЕ БЫСТРАЯ'
   AND t.deleted_at IS NULL
   AND t.meeting_point IS DISTINCT FROM E'Старт сплава — 147-й км трассы А4.\nСтоянка и забор трансфера — 139-й км трассы А4.\nВыезд из Петропавловска-Камчатского, возможен забор из Паратунской зоны отдыха.';
