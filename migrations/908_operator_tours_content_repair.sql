-- Migration 908: вернуть operator_tours.excludes и itinerary.
--
-- ФАКТ (перепись /api/cron/schema-drift на проде, 23.08.2026 00:55 UTC):
-- `operator_tours.excludes` и `operator_tours.itinerary` объявлены миграцией
-- 114 и на боевой базе отсутствуют.
--
-- ЧЕМ ЭТО СТОИТ СЕЙЧАС. `GET /api/operator/tours` — список собственных туров
-- в кабинете оператора — селектит `t.excludes` и `t.itinerary`. Обеих колонок
-- нет, значит запрос падает на разборе (42703 undefined column), и оператор
-- вместо своих туров получает ошибку. Не редкий путь и не служебный: это
-- главный экран кабинета.
--
-- ПОЧЕМУ 114 НЕ ЛЕГЛА. Файл идёт одной транзакцией, и первыми тремя строками
-- он трогает `tours`:
--
--   ALTER TABLE tours ADD COLUMN IF NOT EXISTS includes  TEXT[] ...
--   ALTER TABLE tours ADD COLUMN IF NOT EXISTS excludes  TEXT[] ...
--   ALTER TABLE tours ADD COLUMN IF NOT EXISTS itinerary JSONB  ...
--
-- Отказ на любой строке откатывает ВЕСЬ файл, а запись в `_migrations`
-- делалась всё равно (задача #58). Улика, что откатился именно весь файл:
-- `operator_tours.includes` на проде ЕСТЬ, а `excludes` и `itinerary` — нет.
-- Из 114 не легло ничего; `includes` пришёл позже из 690 — и пришёл как
-- TEXT, тогда как 114 объявлял TEXT[]. Расхождение объявлений видно в
-- `type_conflicts` той же переписи.
--
-- НА КАКОЙ ИМЕННО СТРОКЕ 114 УМЕРЛА — НЕ ЗНАЮ. Напрашивается `tours`, но у
-- этой версии есть прямое опровержение: миграция 042 добавляет в `tours`
-- колонку `tour_image`, и на проде она ЕСТЬ. Значит `ALTER TABLE tours`
-- в тот период проходил, и объяснять им отказ 114 нельзя. Проверить нечем:
-- текста ошибки того прогона не сохранилось. Так и записано — вместо
-- правдоподобной догадки, которая через месяц читалась бы как факт.
--
-- ЗДЕСЬ НЕ ПОВТОРЯЕТСЯ 114 — но не потому, что причина известна, а потому
-- что она НЕ известна. Файл, отказ которого не объяснён, повторять целиком
-- нельзя: повтор либо снова упадёт, либо тронет `tours`, чей род на этой
-- базе не установлен (перепись /api/cron/legacy-tours-census). Трогается
-- только `operator_tours` — таблица, ради которой 114 и писалась, и та, из-за
-- которой падает кабинет.
--
-- `includes` НЕ ТРОГАЕТСЯ СОЗНАТЕЛЬНО. Колонка на проде есть, но её тип не
-- совпадает с объявленным, и какой из двух там лежит — вопрос к базе, а не к
-- репозиторию. Приводить тип вслепую (`ALTER ... TYPE TEXT[] USING ...`)
-- значит рисковать данными двадцати живых туров ради опрятности. Тип
-- измеряется отдельно, и решение по нему принимается отдельно — с фактом на
-- руках, а не с догадкой. Пока колонка остаётся как есть: список туров от
-- этого работает, а `includes` показывается тем, чем является.
--
-- Типы взяты по коду, который их читает (`app/api/operator/tours/route.ts`):
-- `excludes` разворачивается как массив строк, `itinerary` — как массив
-- объектов дня. Это совпадает с объявлением 114 и не спорит с ним.

ALTER TABLE operator_tours ADD COLUMN IF NOT EXISTS excludes  TEXT[] DEFAULT '{}';
ALTER TABLE operator_tours ADD COLUMN IF NOT EXISTS itinerary JSONB  DEFAULT '[]';

COMMENT ON COLUMN operator_tours.excludes  IS 'Что НЕ включено в тур (список строк). Восстановлено миграцией 908: 114 откатилась целиком на ALTER TABLE tours.';
COMMENT ON COLUMN operator_tours.itinerary IS 'Программа по дням: [{day, title, description}]. Восстановлено миграцией 908.';
