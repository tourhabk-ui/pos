DO $$
DECLARE
  v_live boolean;
  v_slug text;
  v_aliases int;
  v_profile int;
BEGIN
  SELECT is_visible, slug INTO v_live, v_slug FROM places WHERE id::text = '4f1217e7-31a4-4d21-bc98-3d46aaba122e';
  SELECT count(*) INTO v_aliases FROM place_aliases WHERE place_id = '4f1217e7-31a4-4d21-bc98-3d46aaba122e';
  SELECT count(*) INTO v_profile FROM location_safety_profile WHERE agent_route_id::text = '0c0aa41c-fd40-4f97-ac35-56f10bf94b69';
  IF v_live IS NULL THEN
    RAISE WARNING '[1240] «Кроноцкий заповедник» не заведён — живое место с этим именем уже есть?';
  ELSE
    IF v_slug IS NULL THEN
      RAISE WARNING '[1240] «Кроноцкий заповедник» заведён без slug — адрес занят, карточка откроется по id';
    END IF;
    IF v_aliases < 5 THEN
      RAISE WARNING '[1240] другие имена заповедника легли не все: % из 5', v_aliases;
    END IF;
    IF v_profile = 0 THEN
      RAISE WARNING '[1240] профиль безопасности заповедника не заведён';
    END IF;
  END IF;
END $$;

