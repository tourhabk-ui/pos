-- ── Откуда координата ────────────────────────────────────────────────────
--
-- Заповедник — территория, у неё нет одной точки. Берётся точка, которую
-- OpenStreetMap отдаёт для отношения 2800189 «Кроноцкий заповедник»
-- (Nominatim, проба 798): 54.6245727 / 160.8792322. Проверено, что это суша
-- внутри границы, а не трёхмильная полоса океана, которая в границу входит:
-- Overpass is_in (проба 801) — точка лежит в областях «Кроноцкий
-- заповедник» и «полуостров Камчатка»; ближайшая береговая линия (way
-- 185545401, суша слева по ходу линии) проходит в ~6 км южнее. Это точка
-- ВНУТРИ заповедника, не вход и не центр — описание и «Как добраться»
-- говорят, как туда попадают на самом деле. coord_source = 'external'.
--
-- ── Откуда текст ─────────────────────────────────────────────────────────
--
