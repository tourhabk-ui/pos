-- ═══ 4. Свободные даты под новые сезоны ═════════════════════════════════
--
-- Даты тура — только строки tour_availability: /slots сезон не читает и на
-- следующий год ничего не переносит. Открываем каждый день сезона (для
-- многодневных — дни старта, при которых тур кончается в сезоне), мест —
-- max_participants, как 812. Даты вне нового сезона закрываются, но
-- ТОЛЬКО без броней (booked_slots = 0): чужую бронь миграция не трогает.

INSERT INTO tour_availability (operator_tour_id, date, day_of_week, available_slots, booked_slots, created_at)
SELECT t.id, d.day::date, EXTRACT(ISODOW FROM d.day)::int - 1,
       GREATEST(COALESCE(t.max_participants, 1), 1), 0, NOW()
  FROM operator_tours t
 CROSS JOIN LATERAL generate_series(
         GREATEST(t.season_start, CURRENT_DATE)::timestamp,
         (t.season_end - (COALESCE(t.multi_day_count, 1) - 1))::timestamp,
         INTERVAL '1 day') AS d(day)
 WHERE t.operator_id::text = '0aaa4f05-b479-418b-9d54-2b909783dfd7'
   AND (t.id IN (4, 5, 6, 9, 11)
        OR t.slug IN ('zimnyaya-rybalka-noyabr-yanvar', 'zimnyaya-rybalka-yanvar-mart', 'zimnyaya-rybalka-fevral-aprel'))
   AND t.deleted_at IS NULL AND t.is_active = TRUE AND t.is_published = TRUE
   AND t.season_start IS NOT NULL AND t.season_end IS NOT NULL
ON CONFLICT (operator_tour_id, date) DO NOTHING;

UPDATE tour_availability ta
   SET is_cancelled = true,
       cancellation_reason = 'Вне сезона тура по карточкам партнёра (1106)',
       updated_at = NOW()
  FROM operator_tours t
 WHERE ta.operator_tour_id::text = t.id::text
   AND t.operator_id::text = '0aaa4f05-b479-418b-9d54-2b909783dfd7'
   AND t.id IN (4, 5, 6, 9, 11)
   AND ta.date >= CURRENT_DATE
   AND COALESCE(ta.is_cancelled, false) = false
   AND COALESCE(ta.booked_slots, 0) = 0
   AND (ta.date < t.season_start
        OR ta.date > t.season_end - (COALESCE(t.multi_day_count, 1) - 1));
