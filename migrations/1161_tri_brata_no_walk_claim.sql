-- Created: 2026-10-04
--
-- В описании стояло: «Доступны пешком от набережной: 30–40 мин вдоль
-- берега». Скалы стоят в воде у входа в Авачинскую бухту; от какой
-- набережной и какой тропой — фраза не говорит, источника у неё нет.
-- Владелец 04.10 на вопрос о ней: «ты правильно сомневаешься».
-- Отзыв Кузьмича («тридцатиминутный береговой переход от Петропавловска»)
-- пересказывал ту же фразу.
--
-- Из описания убирается одно это предложение, остальное не трогается.
-- Отзыв Кузьмича — пустая строка, не NULL: kuzmich-place-enricher берёт
-- только NULL и написал бы его заново по тому же описанию (§4.0).
-- Отбор — по id и самой фразе: убрано раньше — no-op.

BEGIN;

UPDATE places
   SET description = replace(description, ' Доступны пешком от набережной: 30–40 мин вдоль берега.', ''),
       updated_at = NOW()
 WHERE id::text = 'e265d0f0-8187-4d7a-b0e4-fe9be5a2d9e0'
   AND description LIKE '% Доступны пешком от набережной: 30–40 мин вдоль берега.%';

UPDATE places
   SET kuzmich_review = '', updated_at = NOW()
 WHERE id::text = 'e265d0f0-8187-4d7a-b0e4-fe9be5a2d9e0'
   AND kuzmich_review LIKE '%тридцатиминутный береговой переход%';

