-- 1117: «Река Амчигача» — новое место.
--
-- ── Почему ────────────────────────────────────────────────────────────────
--
-- 30.09 владелец попросил собрать сведения о рыболовной базе «Амчигача»
-- (Усть-Большерецкий район) и на предложение завести реку ответил «да,
-- заведи реку». В справочнике платформы её нет: MCP get_place_info по
-- «Амчигача» отвечает «места нет в справочнике».
--
-- Заводится РЕКА, а не база: точка — географический факт (§9), база — чужое
-- коммерческое предложение, и на карточке места ей не место. Партнёром база
-- не является; сведения о ней собраны отдельно и сюда не переносятся.
--
-- ── Откуда координата ─────────────────────────────────────────────────────
--
-- OpenStreetMap, поиск Nominatim (30.09): у реки два участка русла —
-- way 112653668 (нижнее течение у Усть-Большерецка) и way 130539767 (выше по
-- течению). Взята точка way 112653668, 52.8562884 / 156.3300371: это нижний
-- участок у села, куда реально едут, а не средняя точка всей реки.
-- `coord_source` = 'external'. Устье по Википедии — 52°45′47″ с.ш.,
-- 156°11′43″ в.д. (Микояновский лиман); точка не устья, а русла у села.
--
-- ── Что в описании и почему только это ────────────────────────────────────
--
-- Только гидрография из статьи «Амчигача» (ru.wikipedia): длина 82 км,
-- бассейн 286 км², исток из болотных озёр на высоте около 119 м, протоки к
-- реке Большой, впадение в Микояновский лиман, село Усть-Большерецк. Виды
-- рыбы и сроки хода в описание НЕ взяты: их называют только рекламные
-- страницы базы, а у места источник должен быть независимым (§4.0).
--
-- IDEMPOTENT

BEGIN;

INSERT INTO places (id, name, ark_id, lat, lng, location_type,
                    is_visible, description, coord_source, coord_source_at,
                    source_name, source_url, created_at, updated_at)
SELECT '15a9e853-29b1-47f3-a12f-58f8f22f7b7a',
       'Река Амчигача',
       '3f383c45-a447-44e7-8aa0-3c0d2e2f0cbe',
       52.8562884, 156.3300371,
       'river',
       TRUE,
       'Амчигача — река на западе Камчатки, в Усть-Большерецком районе. Длина — 82 км, площадь бассейна — 286 км². '
       || 'Начинается из болотных озёр на высоте около 119 м и течёт сначала на северо-восток, затем на юг и '
       || 'юго-запад. Перед устьем соединяется протоками с рекой Большой и впадает в Микояновский лиман. '
       || 'Нижнее течение проходит рядом с селом Усть-Большерецк.',
       'external', NOW(),
       'OpenStreetMap',
       'https://www.openstreetmap.org/way/112653668',
       NOW(), NOW()
 WHERE NOT EXISTS (
         SELECT 1 FROM places q
          WHERE q.id::text <> '15a9e853-29b1-47f3-a12f-58f8f22f7b7a'
            AND q.merged_into_id IS NULL
            AND q.is_visible
            AND q.name ILIKE '%Амчигач%'
       )
ON CONFLICT (id) DO NOTHING;

-- Адрес карточки: /places/reka-amchigacha, если такой slug свободен.
UPDATE places p
   SET slug = translit_ru_slug(p.name)
 WHERE p.id::text = '15a9e853-29b1-47f3-a12f-58f8f22f7b7a'
   AND p.slug IS NULL
   AND NOT EXISTS (SELECT 1 FROM places x WHERE x.slug = translit_ru_slug(p.name))
   AND NOT EXISTS (SELECT 1 FROM kamchatka_routes r WHERE r.slug = translit_ru_slug(p.name));

-- ── Исход называется вслух ────────────────────────────────────────────────
DO $$
DECLARE
  v_live boolean;
  v_slug text;
BEGIN
  SELECT is_visible, slug INTO v_live, v_slug FROM places
   WHERE id::text = '15a9e853-29b1-47f3-a12f-58f8f22f7b7a';
  IF v_live IS NULL THEN
    RAISE WARNING '[1117] «Река Амчигача» не заведена — живое место с этим именем уже есть?';
  ELSIF v_slug IS NULL THEN
    RAISE WARNING '[1117] «Река Амчигача» заведена без slug — адрес занят, карточка откроется по id';
  END IF;
END $$;

COMMIT;
