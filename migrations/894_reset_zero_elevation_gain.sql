-- 894: сброс нулевого набора высоты — «0 м» и «не знаю» разошлись.
--
-- Проба 121: бэкфилл (проба 120) записал «0 м» трекам с КОНСТАНТНОЙ
-- высотой — у «Авачинского перевала (база Три вулкана)» все точки osm-линии
-- несут одно и то же число, это след заполнения поля, а не измерений, но
-- стопроцентное покрытие проходило порог достоверности. Ноль в колонке
-- неотличим от этой фальши, поэтому все нули бэкфилла возвращаются в NULL,
-- а актуатор с новым правилом (lib/routes/relief: константная высота — не
-- рельеф) перезаполнит только те, где высоты настоящие: честный ноль
-- равнины с живым шумом прибора вернётся, константа останется NULL.
--
-- Идемпотентно: после отката нулей повторный прогон не находит строк.

UPDATE kamchatka_routes
SET elevation_gain_m = NULL, updated_at = NOW()
WHERE elevation_gain_m = 0
  AND is_visible = true
  AND merged_into_id IS NULL
  AND geometry IS NOT NULL;
