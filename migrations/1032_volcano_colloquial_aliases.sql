-- 1032: разговорные имена трёх вулканов — псевдонимами места (issue #2063).
--
-- Дайджест 26.09: «Ключевской», «Ключевской вулкан», «Вулкан Ключевской» не
-- находили «Вулкан Ключевская сопка» — страж отдавал только этнографическую
-- заметку, без цвета, KVERT и опасностей, в дни извержения соседнего
-- Шивелуча. Проба с прода того же дня нашла тот же дефект у двух соседей:
-- «Корякский вулкан» (записан «Корякская сопка») и «Авачинская сопка»
-- (записан «Вулкан Авачинский»).
--
-- Сравнивать по основе слова нельзя: «Авачинский» по основе совпал бы с
-- «Авачинская бухта», у которой имя короче, чем у вулкана, — данные залива
-- ушли бы как данные вулкана. Разговорное имя — решение о конкретном месте,
-- и живёт оно в place_aliases (849), поимённо. Поиск стража и get_place_info
-- с этой же правкой читают псевдонимы.
--
-- Имена общеупотребительны: «Ключевской вулкан» — в новостях о текущем
-- извержении (trtrussian.com, issue #2065), «Корякский вулкан» и «Авачинская
-- сопка» — так же, как «Ключевская сопка», у самих вулканологов.
--
-- Строка ложится, только если id и название места совпали с ожидаемыми, —
-- тот же приём, что в 1029: переименованная или слитая запись не получит
-- чужое имя молча.

WITH wanted(place_id, place_name, alias) AS (
  VALUES
    ('54b106de-d81a-42af-9a41-32ee49604309', 'Вулкан Ключевская сопка', 'Ключевской вулкан'),
    ('dea99549-5ecb-41fe-af19-15f216eeac68', 'Корякская сопка', 'Корякский вулкан'),
    ('3a98a68d-76c8-4835-8d6d-24f7dd867cb8', 'Вулкан Авачинский', 'Авачинская сопка')
)
INSERT INTO place_aliases (place_id, alias, source_name)
SELECT w.place_id, w.alias, 'разговорное название вулкана (issue #2063)'
  FROM wanted w
  JOIN places p ON p.id::text = w.place_id::text AND p.name = w.place_name
 WHERE p.merged_into_id IS NULL
ON CONFLICT (place_id, LOWER(TRIM(alias))) DO NOTHING;

-- Не легло — не молчим: имя сменилось или записи нет (§4.0).
DO $$
DECLARE n int;
BEGIN
  SELECT count(*) INTO n
    FROM place_aliases
   WHERE (place_id, LOWER(alias)) IN (
     ('54b106de-d81a-42af-9a41-32ee49604309', 'ключевской вулкан'),
     ('dea99549-5ecb-41fe-af19-15f216eeac68', 'корякский вулкан'),
     ('3a98a68d-76c8-4835-8d6d-24f7dd867cb8', 'авачинская сопка')
   );
  IF n < 3 THEN
    RAISE WARNING '[1032] псевдонимов % из 3 — часть мест не найдена или переименована', n;
  ELSE
    RAISE NOTICE '[1032] псевдонимов: %', n;
  END IF;
END $$;
