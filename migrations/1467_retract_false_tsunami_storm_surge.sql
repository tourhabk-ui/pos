-- 1467: Снять ложную «угрозу цунами» с постов МЧС о сгонно-нагонных явлениях.
-- Created: 2026-11-20
--
-- ── Слово владельца ──────────────────────────────────────────────────
--
-- 19.11: «Почему мне пришло уведомление угроза цунами?» — и «да исправь».
-- 20.11 (11:42 по Камчатке) пришло второе такое уведомление: «УГРОЗА
-- ЦУНАМИ — Камчатка. По данным Камчатского управления по гидрометеорологии…
-- 21 ноября…».
--
-- ── Что случилось ────────────────────────────────────────────────────
--
-- Лента экстренных предупреждений МЧС Камчатки отдала два поста о
-- сгонно-нагонных явлениях (подъём воды у берега от ветра):
--   «Экстренное предупреждение на 5 декабря 2025 г. (сгонно - нагонные
--    явления)» — прошлогодний, с датой публикации нынешних суток;
--   «Экстренное предупреждение на 21 ноября 2026 г. (сгонно - нагонные
--    явления)» — настоящий, на завтра.
-- Разбор (lib/services/safety/seismic-parser, classifyMchsItem) взял оба как
-- tsunami_warning уровня 3: широкое правило цунами нашло в тексте слово
-- «цунами» рядом с признаком опасности, а год из заголовка не читал никто.
-- Ушли уведомления «угроза цунами».
--
-- Правка разбора (тот же PR) прошедший день и нагон больше не путает. Но
-- запись ленты делается ON CONFLICT DO NOTHING — уже записанные строки
-- повторное чтение ленты не перепишет. Поэтому здесь:
--   1. прошлогодний пост гасится тем же способом, что DELETE администратора:
--      срок «сейчас» и ended_by = 'admin' (снято человеком, 1394);
--   2. пост о нагоне на 21 ноября — то, чем его теперь делает разбор:
--      морское погодное предупреждение (weather, уровень 1) до конца
--      21 ноября по Камчатке (12:00 UTC 21.11, lib/safety/dated-warning).
--      Морская тревога не висит на горных местах (lib/safety/marine-alert).
--   Трогаются только эти две строки, по заголовкам. Общего правила здесь нет
--   намеренно: ревью безопасности #3546 показало, что правило, повторённое в
--   SQL, отпустило бы настоящую тревогу цунами в посте о нагоне. Строка,
--   которую лента успеет записать до выката, истечёт сама через 12 часов.
--
-- Пуш эта миграция не шлёт: уведомления уходят только при вставке строки.
-- Идемпотентна: повтор ничего не меняет. Время тревог — стенное UTC (#2495).

UPDATE external_alerts
   SET expires_at = (NOW() AT TIME ZONE 'UTC'),
       ended_by   = 'admin',
       updated_at = (NOW() AT TIME ZONE 'UTC')
 WHERE alert_type = 'tsunami_warning'
   AND title ILIKE 'Экстренное предупреждение на 5 декабря 2025%'
   AND ended_by IS NULL
   AND expires_at > (NOW() AT TIME ZONE 'UTC');

UPDATE external_alerts
   SET alert_type = 'weather',
       severity   = 1,
       expires_at = GREATEST(expires_at, TIMESTAMP '2026-11-21 12:00:00'),
       updated_at = (NOW() AT TIME ZONE 'UTC')
 WHERE alert_type = 'tsunami_warning'
   AND ended_by IS NULL
   AND title ILIKE 'Экстренное предупреждение на 21 ноября 2026%нагонн%';

