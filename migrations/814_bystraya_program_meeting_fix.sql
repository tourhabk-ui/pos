-- Migration 814: программа дня сплава — убрать противоречие о месте сбора
--
-- Владелец на живой карточке: шаг 1 называется «Выезд из Петропавловска-
-- Камчатского», а в тексте под ним — «Сбор в Паратунской зоне отдыха». Это
-- разные места, между ними около 50 км. Турист по такому шагу не понимает,
-- куда ему приезжать.
--
-- Откуда взялось: текст шага писал я в миграции 809. Источник правды —
-- operator_tours.meeting_point, заполненный со слов оператора (миграция 797):
--   «Старт сплава — 147-й км трассы А4. Стоянка и забор трансфера — 139-й км
--    трассы А4. Выезд из Петропавловска-Камчатского, ВОЗМОЖЕН ЗАБОР из
--    Паратунской зоны отдыха.»
-- То есть забор из Паратунки — ВОЗМОЖНОСТЬ по договорённости, а я превратил её
-- в место сбора. Для safety-платформы это не стилистика: человек может уехать
-- за 50 км не туда и опоздать к выезду.
--
-- Заодно убираем «знаменитые пирожки» из шага 2: в анонсе оператора сказано
-- «п. Сокочи (пирожковый перекус)», эпитет добавил я. Мелочь, но выдуманная.
--
-- Точные километры трассы здесь НЕ повторяем: у них своё место на карточке —
-- блок «Точка сбора». Дублировать факт в двух местах мы сегодня уже разучились.
--
-- Матч по содержанию, ровно один тур, без INSERT. Идемпотентна.

WITH canonical AS (
  SELECT ot.id
    FROM operator_tours ot
   WHERE ot.deleted_at IS NULL
     AND ot.title ILIKE '%быстр%'
     AND (ot.title ILIKE '%сплав%' OR ot.activity_type IN ('rafting', 'boat_trip'))
   ORDER BY
     CASE WHEN ot.title = 'Сплав по реке Быстрая' THEN 0 ELSE 1 END,
     ot.created_at ASC
   LIMIT 1
)
UPDATE operator_tours ot
   SET program = '[
         {"title": "Выезд из Петропавловска-Камчатского", "text": "Выезд на комфортном транспорте. По договорённости возможен забор из Паратунской зоны отдыха — точное место и время оператор подтверждает при бронировании."},
         {"title": "Посёлок Сокочи", "text": "Короткая остановка на пирожковый перекус (самооплата)."},
         {"title": "Река Быстрая: инструктаж", "text": "Инструктаж по технике безопасности, получение снаряжения и экипировки."},
         {"title": "Сплав с гидом и рыбалка", "text": "Спокойный семейный сплав — не спортивный рафтинг. По пути рыбалка и шанс фотоохоты на бурого медведя."},
         {"title": "Обед на берегу", "text": "Уха из лосося, нарезки, чай, кофе — готовит повар."},
         {"title": "Малкинские термальные источники", "text": "Купание в горячих источниках (купальные принадлежности обязательно)."},
         {"title": "Возвращение", "text": "Трансфер к месту проживания."}
       ]'::jsonb,
       updated_at = NOW()
  FROM canonical c
 WHERE ot.id = c.id
   AND ot.program::text LIKE '%Сбор в Паратунской%';
