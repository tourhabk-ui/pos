-- 983_tracker_links.sql
--
-- Точка со СПУТНИКОВОГО ТРЕКЕРА доходит до регистрации маршрута.
--
-- ── Зачем (решение владельца 19.09: «делай пок 3») ───────────────────────
--
-- Разбор «как сделать, чтоб связь работала» дал четыре разные задачи, и три
-- из них у платформы уже закрыты: хватятся при невозврате
-- (`checkin-watchdog`), сообщение уйдёт при первом коннекте (офлайн-очередь
-- и QR-эстафета), группа слышит друг друга — радио, которого у нас нет.
--
-- Четвёртая — «спасатели видят точку, пока связи нет» — не закрыта ничем.
-- `POST /api/safety/position` принимает координату ТОЛЬКО с телефона под
-- авторизацией, то есть ровно тогда, когда связь есть. Трекер, который несёт
-- турист или гид, к нам не доходит никак — при том что `location_safety_
-- profile.sat_communicator_required` уже говорит «сюда нужен спутник». То
-- есть мы требуем устройство и не умеем его слушать.
--
-- ── Что заводится ────────────────────────────────────────────────────────
--
-- `tracker_links` — связка «регистрация маршрута ↔ устройство». Трекер (или
-- шлюз вендора) шлёт точку на адрес с секретным токеном; токен — ЕДИНСТВЕННОЕ
-- доказательство права писать, потому что спутниковый передатчик не умеет ни
-- JWT, ни OAuth. Отсюда требования к нему: 32 байта энтропии, уникальность,
-- возможность отозвать не удаляя (история приёма остаётся).
--
-- Счётчики (`points_total`, `last_point_at`) и последний отказ
-- (`last_error`, `last_error_at`) лежат в той же строке НАМЕРЕННО. Связка,
-- заведённая и молчащая, и связка, которой шлют мусор, — разные состояния, и
-- отличить их должно быть можно, не читая логи (§4.0). Без этого «трекер
-- подключён» стало бы объявлением без источника (§10.09).
--
-- ── Почему источник точки — отдельная колонка ────────────────────────────
--
-- `route_registrations.last_position_*` до сих пор мог заполнить только
-- телефон. Теперь писателей два, и они значат РАЗНОЕ для того, кто ищет
-- человека: точка с телефона говорит «час назад у него была связь», точка с
-- трекера — «час назад было живо устройство». Слить их в одну строку значило
-- бы потерять именно то, ради чего трекер и подключают.
--
-- NULL в источнике — не «телефон»: это записи, сделанные до этой миграции, и
-- врать про них задним числом нельзя.

CREATE TABLE IF NOT EXISTS tracker_links (
  id              UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  registration_id UUID NOT NULL REFERENCES route_registrations(id) ON DELETE CASCADE,

  -- Секрет в адресе. UNIQUE обязателен: по нему ищется связка, и коллизия
  -- означала бы запись чужой точки в чужой маршрут.
  token           TEXT NOT NULL UNIQUE CHECK (char_length(token) >= 32),

  -- Как человек назвал устройство («inReach гида»). Пусто — не назвал.
  label           TEXT CHECK (label IS NULL OR char_length(label) <= 120),
  -- Что за устройство, со слов человека. Свободный текст и NULL намеренно:
  -- список вендоров, которых мы «поддерживаем», был бы обещанием, которого
  -- приёмник не даёт — он принимает нормализованную точку от кого угодно.
  vendor          TEXT CHECK (vendor IS NULL OR char_length(vendor) <= 60),

  created_at      TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  created_by      UUID REFERENCES users(id) ON DELETE SET NULL,
  -- Отзыв не удаляет строку: счётчики приёма — улика для разбора «почему
  -- точки перестали приходить», и терять её вместе с токеном нельзя.
  revoked_at      TIMESTAMPTZ,

  points_total    INTEGER NOT NULL DEFAULT 0,
  last_point_at   TIMESTAMPTZ,
  -- Последний ОТКАЗ приёма и когда он был. Молчащая связка и связка, в
  -- которую шлют мусор, — разные беды с разным лечением.
  last_error      TEXT CHECK (last_error IS NULL OR char_length(last_error) <= 300),
  last_error_at   TIMESTAMPTZ
);

-- Поиск по токену — на каждой входящей точке. UNIQUE выше уже даёт индекс.
CREATE INDEX IF NOT EXISTS idx_tracker_links_registration
  ON tracker_links (registration_id);

-- Живые связки регистрации — их читает экран и создание новой.
CREATE INDEX IF NOT EXISTS idx_tracker_links_active
  ON tracker_links (registration_id)
  WHERE revoked_at IS NULL;

ALTER TABLE route_registrations
  ADD COLUMN IF NOT EXISTS last_position_source TEXT;

COMMENT ON COLUMN route_registrations.last_position_source IS
  'Откуда последняя точка: phone (телефон под авторизацией) или tracker '
  '(спутниковый трекер через tracker_links). NULL — записи до миграции 983, '
  'источник не установлен; догадываться задним числом нельзя.';

COMMENT ON TABLE tracker_links IS
  'Связка регистрации маршрута со спутниковым трекером. Токен — единственное '
  'доказательство права писать точку: передатчик не умеет JWT.';
