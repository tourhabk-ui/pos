-- 1268: «Местечко Камчатка» — пять вертолётных туров закреплены наверху его
--       страницы на Ведаре (vedarai.ru/mestechko).
--
-- Оператор через владельца 15.10: «нужен упор на вертолётные экскурсии»;
-- владелец: «закрепить ему пять вертолётных туров миграцией, без его
-- участия». Механизм закрепления — 1267 (operator_tours.pinned_at); дальше
-- оператор сам снимает и закрепляет туры галочкой в редакторе.
--
-- Порядок на странице — по моменту закрепления, поэтому моменты разнесены
-- на секунду: сначала большие дневные программы (Долина гейзеров, Курильское
-- озеро, Толбачик), затем короткие облёты (три вулкана юга — 4 часа;
-- Корякский и Авачинский с Налычевскими источниками).
--
-- Только поверх незакреплённых: если оператор уже закрепил тур сам, его
-- выбор и порядок не трогаются. Гейт — по slug партнёра и slug тура (как в
-- 1217/1221). Шестой вертолётный тур «Долина гейзеров и вулкан Толбачик»
-- (mestechko-dolina-geyzerov-tolbachik) не закрепляется: на странице его нет,
-- это черновик до подтверждения цены оператором.
--
-- Применяется один раз (журнал _migrations). Повторный прогон не меняет
-- закреплённое, но снова закрепил бы тур, с которого оператор снял галочку,
-- поэтому вручную его не повторять.

UPDATE operator_tours ot
   SET pinned_at = v.pinned_at,
       updated_at = NOW()
  FROM partners p,
       (VALUES
         ('mestechko-dolina-geyzerov',                     TIMESTAMPTZ '2026-10-15 09:00:01+00'),
         ('mestechko-kurilskoe-ozero',                     TIMESTAMPTZ '2026-10-15 09:00:02+00'),
         ('mestechko-vertolet-tolbachik',                  TIMESTAMPTZ '2026-10-15 09:00:03+00'),
         ('mestechko-oblet-vilyuchinskiy-mutnovskiy-gorelyy', TIMESTAMPTZ '2026-10-15 09:00:04+00'),
         ('mestechko-oblet-koryakskiy-avachinskiy',        TIMESTAMPTZ '2026-10-15 09:00:05+00')
       ) AS v(slug, pinned_at)
 WHERE p.slug = 'mestechko'
   AND ot.operator_id = p.id
   AND ot.slug = v.slug
   AND ot.pinned_at IS NULL
   AND ot.deleted_at IS NULL;
