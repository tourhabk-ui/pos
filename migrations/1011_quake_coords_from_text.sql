-- 1011: координаты землетрясений, лежащие в тексте, — в колонки lat/lng
--
-- Владелец 24.09: «на радаре их нет и данные устаревшие». Проба 572: лента
-- /api/safety/seismic отдаёт три толчка за 48 часов (Ml 5.2 и 4.0 за 22.09,
-- 4.0 за 23.09), и у всех трёх lat/lng = NULL. Радар рисует только то, у чего
-- есть координата, — отсюда пустой круг при живой ленте.
--
-- Координата при этом НЕ неизвестна: сообщение EQKam несёт строку
-- «Координаты: 51.27, 159.73», и парсер её разбирал — но до 24.09 только для
-- выбора зоны, а в колонки не писал (правка парсера #1983 чинит новые строки,
-- старые остаются как были). Эта миграция переносит в колонки то, что уже
-- записано в description, — ничего не выводя и не угадывая.
--
-- Границы намеренно узкие:
--  * только earthquake и только там, где lat И lng пусты — заполненное не
--    трогается никогда;
--  * только точная форма «Координаты: <число>, <число>» — та же, что у
--    парсера (classifyEqkam);
--  * только внутри грубого конверта региона (45–65 с.ш., 150–175 в.д.):
--    перепутанные широта и долгота или обрезанное число в поле не попадут —
--    выдуманная точка на карте хуже её отсутствия (§4.0).
--
-- Идемпотентна: второй прогон не найдёт строк с пустыми координатами и
-- нужным текстом.

UPDATE external_alerts ea
   SET lat = c.lat,
       lng = c.lng
  FROM (
    SELECT id,
           (m)[1]::numeric AS lat,
           (m)[2]::numeric AS lng
      FROM (
        SELECT id,
               regexp_match(description, 'Координаты:\s*([0-9]{1,2}\.[0-9]+),\s*([0-9]{2,3}\.[0-9]+)') AS m
          FROM external_alerts
         WHERE alert_type = 'earthquake'
           AND lat IS NULL
           AND lng IS NULL
           AND description LIKE '%Координаты:%'
      ) s
     WHERE m IS NOT NULL
  ) c
 WHERE ea.id = c.id
   AND c.lat BETWEEN 45 AND 65
   AND c.lng BETWEEN 150 AND 175;
