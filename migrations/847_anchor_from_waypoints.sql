-- Migration 847: якорь маршрута выводится из его же путевых точек
--
-- ── Что измерено ────────────────────────────────────────────────────────────
--
-- Перепись 11.08 (пробы 43-49): из 421 маршрута 112 не имеют координат вовсе.
-- Такую запись нельзя показать на карте и нельзя найти «рядом со мной».
-- Разбор улик:
--
--   nothing_at_all  97   ни координат, ни линии, ни путевых точек
--   has_waypoints   15   путевые точки ЕСТЬ
--   has_geometry     0   линии нет ни у одной
--
-- Пятнадцать записей знают, где они, — просто знание лежит в другой таблице.
-- Точки маршрута связаны с `places`, а у тех координаты NOT NULL по схеме.
--
-- ── Почему это вывод, а не выдумка ──────────────────────────────────────────
--
-- Разница принципиальная и ровно та, из-за которой два дня ушло на нерабочую
-- схему. Привязка трека «по близости к якорю» ПРЕДПОЛАГАЛА, что близкий
-- маршрут — тот самый; это была догадка, и она ошибалась в девяти случаях из
-- десяти. Здесь ничего не предполагается: если маршрут проходит через точку,
-- то он находится там, где эта точка. Связь route_waypoints → places уже
-- утверждена в данных, мы её только читаем.
--
-- Берётся ПЕРВАЯ точка по position (position 0 = старт, миграция 167): якорь —
-- это место, куда центрировать карту, и центрировать её логично на начале
-- пути, а не на середине отрезка между разными местами. Средняя точка двух
-- концов маршрута может лежать в море или на леднике, где маршрута нет.
--
-- ── Что НЕ делается ─────────────────────────────────────────────────────────
--
-- Не трогаются записи, у которых координата уже есть: `lat IS NULL`. Живое
-- значение важнее выведенного, даже если выведенное кажется точнее.
--
-- Не трогаются 97 записей без единой улики. Среди них и статьи сайта («Флора
-- Камчатки», «Рельеф Камчатки»), и населённые пункты («Поселок Эссо»), и
-- настоящие маршруты («Восхождение на Плоский Толбачик»). Отсутствие данных
-- не отличает одно от другого, и придумывать им координату — значит ставить
-- на карту точку, за которую никто не отвечает. Это разбор человека.
--
-- Идемпотентна: второй прогон не найдёт ни одной строки под условие.

BEGIN;

UPDATE kamchatka_routes r
   SET lat = w.lat,
       lng = w.lng,
       metadata = COALESCE(r.metadata, '{}'::jsonb)
                  || jsonb_build_object('anchor_source', 'waypoint_first'),
       updated_at = NOW()
  FROM (
    SELECT DISTINCT ON (rw.route_id)
           rw.route_id, p.lat, p.lng
      FROM route_waypoints rw
      JOIN places p ON p.id = rw.place_id
     WHERE p.lat IS NOT NULL AND p.lng IS NOT NULL
     ORDER BY rw.route_id, rw.position, rw.id
  ) w
 WHERE w.route_id = r.id
   AND (r.lat IS NULL OR r.lng IS NULL);

COMMIT;
