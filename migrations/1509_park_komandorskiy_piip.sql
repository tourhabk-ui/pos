-- 1509: вулкан Пийпа на странице /park/komandorskiy (GSC 18–21.11:
-- викторина «какой национальный парк расположен рядом с вулканом пийпа?»,
-- 6 показов, позиция 8, 0 кликов; отдельный URL не заводим).
--
-- Источники:
--   геопортал ИВиС ДВО РАН, «Вулкан Пийпа. Описание вулкана»
--     http://geoportal.kscnet.ru/volcanoes/volc.php?lang=ru&name=Piip
--     (регион — Командорские острова; в южной части Командорской котловины,
--     примерно в 70 км к северо-востоку от о. Беринга; абсолютная высота −300 м);
--   сайт национального парка «Командорские острова», «Территория»
--     https://commanderislands.ru/territoriya/
--     (в 1984 г. в 70 км к северо-востоку от острова Беринга в Командорской
--     котловине обнаружен массив Вулканологов с действующим подводным вулканом Пийпа).
--
-- Не утверждаем, что вулкан лежит внутри границ парка: акватория парка —
-- 30 морских миль (~55,6 км), а Пийпа — примерно в 70 км от о. Беринга.
-- Первый абзац описания не меняется: новый абзац дописывается через перевод
-- строки, страница парка рисует абзацы отдельно. Повторный прогон ничего
-- не меняет.

WITH src(slug, txt) AS (VALUES
  ('komandorskiy',
   'Рядом с парком, в Командорской котловине примерно в 70 км к северо-востоку от острова Беринга, находится подводный вулкан Пийпа: его вершина примерно на 300 м ниже уровня моря. Вулкан обнаружили в 1984 году в массиве Вулканологов.')
)
UPDATE parks p
   SET description = btrim(p.description) || E'\n' || src.txt,
       updated_at = NOW()
  FROM src
 WHERE p.slug = src.slug
   AND p.description IS NOT NULL
   AND char_length(btrim(p.description)) > 0
   AND position(src.txt IN p.description) = 0;
