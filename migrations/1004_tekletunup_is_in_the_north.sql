-- 1004: «Теклетунуп» — вулкан на севере, а описание поселило его под городом.
--
-- ── Как нашлось ───────────────────────────────────────────────────────────
--
-- Это ПЕРВАЯ находка переписи `place-description-geo` (#1975), а не случайная
-- встреча глазами. Прежние пять выдуманных описаний — «Каньон Опасный»,
-- «Крылья Гамулов», «Каньон Сноубордистов», «Сопка Никольская», «Сопка
-- Петровская» — нашлись по ходу другой работы, то есть способом, который
-- находит не худшее, а то, куда посмотрели.
--
-- Перепись назвала пару «Теклетунуп → Вулкан Мутновский, 601 км» с цитатой:
-- «с вершины открывается панорама на вулканы Вилючинский, Мутновский и
-- Авачинский».
--
-- ── Кто из двух врёт, установлено источником, а не рассуждением ────────────
--
-- Улика говорит только, что описание и координата не сходятся; который из
-- них неверен, она не знает (§4.0). Ответ дал владелец 20.09, прислав экран
-- Organic Maps: «Теклетунуп, Вулкан, 1290 m, 57.709221, 160.33362».
--
-- Это север Камчатки. От этой точки до Мутновского (52.4483 / 158.1992 —
-- тем же экраном подтверждено, что наша запись о Мутновском верна) по
-- широте 5.26° ≈ 585 км, по долготе 2.13° ≈ 136 км, итого около 601 км —
-- ровно то расстояние, которое вернула перепись. Значит КООРДИНАТА У НАС
-- ВЕРНА, и правки через `place-coords` не требуется.
--
-- Совпала и высота: 1290 метров и на экране, и в нашем описании. Это
-- единственное, что в нём было правдой.
--
-- ── Что именно снимается ──────────────────────────────────────────────────
--
--   «расположенный в южной части полуострова, в 50 км к юго-западу от
--    Петропавловска-Камчатского» — до города около 530 км по прямой;
--   «с вершины открывается панорама на вулканы Вилючинский, Мутновский и
--    Авачинский» — до них шестьсот километров, их оттуда не видно ни в
--    какую погоду;
--   «в ясную погоду виден Тихий океан» — то же самое.
--
-- Остальной текст (курумники, базальты, «давно потух», отсутствие троп,
-- июль-сентябрь, список снаряжения) снимается НЕ потому, что опровергнут, а
-- потому, что источника у него нет, а проверяемая его часть оказалась
-- ложной. Текст, чьи проверяемые утверждения не выдержали проверки, не
-- заслуживает доверия в непроверяемых: оставить их значило бы отобрать
-- ровно те фразы, которые нечем опровергнуть, — и выдать их за уцелевшее
-- знание.
--
-- Особенно это касается сезона и снаряжения: «лучшее время июль-сентябрь»
-- и «треккинговые ботинки с жёсткой подошвой» человек читает как
-- инструкцию. Выдуманная инструкция опаснее её отсутствия — тот же довод,
-- что в шапке 1002.
--
-- ── Чего эта миграция НЕ делает ───────────────────────────────────────────
--
-- Не трогает `hazard_types` («лавины, камнепад, термальные зоны, высота»).
-- У Никольской (973) и Петровской (974) шаблон вулкана снимали потому, что
-- сами они вулканами НЕ БЫЛИ — городские холмы. Теклетунуп вулкан и есть,
-- это подтверждено тем же экраном. Шаблон по типу остаётся ровно тем, чем
-- был; заменить его на «настоящие» опасности этого вулкана я не могу —
-- источника нет, а выдуманная опасность на safety-поле ничем не лучше
-- выдуманной лёгкости (довод 992).
--
-- Не трогает координату: она верна, см. выше.
--
-- Не трогает тип: `volcano` подтверждён.
--
-- ── На чём стоит новое описание ───────────────────────────────────────────
--
-- Только на двух источниках: экран владельца (вулкан, 1290 м, координата) и
-- арифметика по нашим же координатам (расстояние до Петропавловска —
-- 57.7092/160.3336 против 53.0244/158.6431, около 530 км; экран владельца
-- показал 529 км от места съёмки). Ни сезона, ни подходов, ни состояния
-- вулкана в нём нет — их у нас нет.
--
-- Последняя фраза описания обязательна и не является украшением: пустое
-- место в карточке читается как «ничего сложного» (§4.0), и незнание
-- названо словами, чтобы не успокаивать молчанием.
--
-- Идемпотентно: правится только запись, где ещё лежит ложная география.

UPDATE places
   SET description = 'Вулкан высотой 1290 метров на севере Камчатки, в глубине полуострова: до Петропавловска-Камчатского отсюда около 530 километров по прямой.

Больше о нём у нас не записано — ни состояния вулкана, ни подходов, ни сезона. Это пробел в наших данных, а не признак того, что подойти сюда просто.',
       updated_at = NOW()
 WHERE name ILIKE 'теклетунуп'
   AND merged_into_id IS NULL
   AND description IS NOT NULL
   AND (description LIKE '%юго-западу от Петропавловска%'
        OR description LIKE '%панорама на вулканы Вилючинский%');

DO $$
DECLARE
  touched INT;
BEGIN
  SELECT count(*) INTO touched
  FROM places
  WHERE name ILIKE 'теклетунуп'
    AND merged_into_id IS NULL
    AND description LIKE '%530 километров%';

  IF touched = 0 THEN
    -- Не «всё хорошо»: либо записи нет, либо текст уже другой. Молчание
    -- здесь выдало бы «не смог» за «сделано» (§4.0).
    RAISE WARNING '[1004] описание «Теклетунупа» не заменено — записи с ложной географией не нашлось; проверьте имя и текст вручную';
  ELSE
    RAISE NOTICE '[1004] описание «Теклетунупа» заменено, записей: %', touched;
  END IF;
END $$;
