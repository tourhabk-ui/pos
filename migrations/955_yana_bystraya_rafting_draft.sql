--
-- Источник — материалы, присланные владельцем 11.09.2026: три изображения
-- (программа трёхдневного сплава, программа двухдневного, список снаряжения)
-- и телефон +79246882092. Всё, что записано ниже, взято ОТТУДА. Ничего,
-- чего в материалах нет, здесь не появилось — см. блок «Чего мы не знаем».
--
-- ── Черновик, а не выкладка ───────────────────────────────────────────────
--
-- Слово владельца: «пока черновик сделаем». Прячет тур `is_published = FALSE`,
-- и это проверено, а не предположено: витрина (`lib/search/tour-search.ts`),
-- главная (`app/_home/data.ts`), карточка места, планер и агентские роуты —
-- все требуют `is_published = true`. Партнёр закрыт вторым рычагом:
-- `is_public = FALSE`.
--
-- ── Почему не копия миграции 060/806 ──────────────────────────────────────
--
-- Соблазн был: там ровно такой же INSERT партнёра-рафтера. Но миграции 800 и
-- 806 падали на проде 15 и 12 раз подряд с «null value in column "category"
-- of relation "partners"» (разбор — 825). Они не указывали `category`, а
-- колонка NOT NULL без умолчания. Шаблон, скопированный не глядя, повторил бы
-- отказ буква в букву.
--
-- ── Это ОТДЕЛЬНЫЙ партнёр, и проверить это должен человек ─────────────────
--
-- По реке Быстрая у нас уже есть оператор «Камчатка Рафтинг» (slug
-- kamchatka-rafting, Катерина и Ярослав, +79247990191, миграция 060) с
-- ОДНОДНЕВНЫМ сплавом. Здесь: другой телефон, другое имя, другой продукт —
-- сплав с ночёвками. Владелец сказал «ещё партнёр», и записано так.
--
-- Но совпадение реки уже один раз стоило дорого: из-за матча по названию
-- карточка сплава месяцами показывала демо-оператора «Рога и Копыта» и одно
-- фото (806). Поэтому слоги разведены явно, а не по случайности, и родство
-- двух операторов остаётся вопросом к человеку, а не выводом из реки.
--
-- Водяной знак на изображениях — «KAMCHATKA RIVER TOURS». Компания это Яны
-- или нет, из материалов не следует: `company_name` оставлен пустым, а не
-- заполнен догадкой.
--
-- ── Чего мы не знаем (NULL здесь — ответ, а не пропуск) ───────────────────
--
--   base_price          — цены в материалах нет НИ ДЛЯ ОДНОГО из двух туров.
--                         Колонка nullable с 690-й именно для этого случая.
--   season_start/end    — сезон не назван. «Сплав, значит лето» — вывод, а не
--                         факт, и в поле его читал бы турист.
--   safety_notes        — правил безопасности оператор не давал. §11 прямо
--                         запрещает подставлять свои: «спасательные жилеты» —
--                         правда для сплава и ложь для вертолётной экскурсии.
--                         Отдельно: в программе второго дня медведи названы
--                         как зрелище («возможность увидеть медведей в
--                         естественной среде обитания»), а это ночёвки в
--                         палаточном лагере. Что оператор делает с едой,
--                         мусором и лагерем — вопрос к Яне, не к нам.
--   meeting_point       — «выезд с места сбора: 8:00» есть, САМО МЕСТО не
--                         названо. Отсюда pickup_type = 'meeting_point'
--                         (встреча в точке — это из материала), а точка —
--                         пусто.
--   max_participants    — колонка NOT NULL DEFAULT 1, и это единственное
--                         место, где миграция вынужденно ЧТО-ТО утверждает.
--                         Единица неверна (рафт вмещает больше), но выбора
--                         тип не даёт. Уточнить у Яны в первую очередь.
--
-- ── Снаряжение: два списка пересекаются, и это не наша описка ─────────────
--
-- В присланном списке личное снаряжение включает палатку, спальный мешок,
-- каремат, сидушку, дождевик и сапоги болотные — и ровно эти шесть строк
-- повторены ниже под словом «ПРЕДОСТАВЛЯЕМ». Разрешено по явному заявлению
-- оператора: что он назвал предоставляемым, то ушло в `included`, остальное —
-- в `what_to_bring`. Догадкой это не разрешалось: «взять палатку» перед
-- туристом, которому её выдадут, — лишние пять килограммов, а обратная
-- ошибка — ночёвка под открытым небом.

