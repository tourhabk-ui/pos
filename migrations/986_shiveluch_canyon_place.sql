-- 986: завести место «Каньон на Шивелуче» и перенести туда снимок каньона.
--
-- ── Откуда координата ─────────────────────────────────────────────────────
--
-- 19.09 владелец прислал снимок каньона у Шивелуча, и я сказал, что завести
-- место не могу: отдельной записи каньона в каталоге нет (проба 533, запрос
-- «каньон» — пять штук, ни одной здесь), а сочинять координату по фотографии
-- значит выдумать географию. Владелец ответил снимком экрана MAPS.ME с
-- карточкой точки «каньон на Шивелуче»:
--
--   56.56557, 161.227291
--
-- Это внешний справочник (OSM через MAPS.ME), поэтому `coord_source` =
-- 'external' — «взята из внешнего справочника» по перечню
-- lib/places/coord-source.ts. Не 'surveyed': прибором на кромке каньона никто
-- не стоял, и записать снятие там, где его не было, значило бы дать
-- координате право на утверждения, которых она не заслужила
-- (coordIsTrustworthy отвечает «да» только на 'surveyed').
--
-- Точка лежит в 9,5 км от вершины Шивелуча (56.636613/161.312207) — это юг
-- вулкана, где реки режут пепловые толщи. Расстояние сходится с кадром: на
-- нём стены из спёкшегося пепла и снежный гребень вдали.
--
-- ── Что РЯДОМ, и почему оно не отменяет эту запись ────────────────────────
--
-- В 780 метрах от этой координаты уже стоят ДВЕ записи, и обе описаны как
-- южные каньоны:
--
--   «Каньон Крылья Гамулов (Дракон)» 56.5665/161.2147, видимая
--       описание: «в окрестностях вулкана Мутновский» — за 498 км отсюда
--   «Каньон Сноубордистов»           56.5665/161.2147, СКРЫТА
--       описание: «р. Половинка, 30 км от Петропавловска» — за 442 км
--
-- Крылья Гамулов — настоящий, известный объект под Мутновским. Значит у той
-- записи неверна КООРДИНАТА, а не имя; либо кто-то привязал к южным именам
-- координату здешнего каньона. Что именно — по данным не видно.
--
-- ЭТА МИГРАЦИЯ ИХ НЕ ТРОГАЕТ, и это не забывчивость. Двигать координату без
-- источника запрещено (§4.1): без него точку прячут, а не переносят. Сверка
-- с OSM (проба 536, kind=valley) источника не дала — среди девяти долин с
-- кандидатами этих двух нет вовсе, то есть тёзки в OSM у них не нашлось.
-- Значит правка их координат остаётся отдельной задачей с отдельным
-- источником, а каньон на Шивелуче существует независимо от того, как
-- разрешится та путаница.
--
-- ── Описание не пишется ───────────────────────────────────────────────────
--
-- `description` остаётся NULL. Соседи по списку как раз и показывают, чем
-- кончается сочинение: у «Каньона Опасного» описание называет вулкан
-- Карымский, хотя сама точка (сверено с OSM, совпадение имени 1.0,
-- расстояние 0 км) стоит у Мутновского — за 180 км от Карымского. Текст был
-- придуман, координата верна. Пустое поле честнее.
--
-- ── Перенос снимка ────────────────────────────────────────────────────────
--
-- Кадр Андрея Запорожца (миграция 984) лежал на карточке ВУЛКАНА, потому что
-- своей записи у каньона не было. Теперь есть, и снимок переезжает к своему
-- объекту: UPDATE route_id, а не новая вставка — байты остаются те же, копии
-- не возникает, подпись автора едет вместе со строкой.
--
-- Следствие названо вслух: у карточки вулкана Шивелуч снимка НЕ ОСТАЁТСЯ,
-- будет градиентная заглушка. Это правда о наших данных — фотографии самого
-- конуса у нас нет, — и она лучше, чем один кадр, висящий в двух местах под
-- двумя именами (тот же довод, по которому гамулы уехали с вулкана на
-- перевал, миграция 980).
--
-- ── Третий исход ──────────────────────────────────────────────────────────
--
-- Оба шага могут не состояться: место уже заведено вручную, снимка на
-- вулкане уже нет. Молчать об этом нельзя (урок 976: ноль вставленных строк
-- выглядел успехом), падать тоже нельзя — накат идёт при старте сервера.
-- Поэтому в конце проверка, называющая исход словами в лог выката.
--
-- ПОСЛЕ ВЫКАТА нужен перезалив статичных пакетов карты
-- (`map-places-build.yml`, upload:true): полевая карта читает пакеты из
-- хранилища, а не живую таблицу, и до перезалива новой точки на телефоне не
-- будет (§4.1).
--
-- IDEMPOTENT

BEGIN;

-- ── 1. Место ──────────────────────────────────────────────────────────────
-- Тип `valley` — как у всех каньонов каталога (Опасный, Студёной, Крылья
-- Гамулов, Сноубордистов). Зона `northern` взята у самого Шивелуча, а не
-- назначена: девять километров по зональной сетке ничего не меняют.
INSERT INTO places (id, name, ark_id, lat, lng, location_type, zone,
                    is_visible, coord_source, coord_source_at,
                    source_name, source_url, created_at, updated_at)
VALUES ('002f9a4f-8833-4ee7-8dc4-290b30092cb7',
        'Каньон на Шивелуче',
        'b3d7eb6c-2ac4-41d9-89fe-52d073c3488d',
        56.56557, 161.227291,
        'valley', 'northern',
        TRUE, 'external', NOW(),
        'OpenStreetMap (через MAPS.ME)',
        'https://www.openstreetmap.org/#map=17/56.56557/161.227291',
        NOW(), NOW())
ON CONFLICT (id) DO NOTHING;

-- ── 2. Снимок каньона переезжает к каньону ────────────────────────────────
-- Джойн ark_id ↔ route_id — документированная связь §9 «фото точки»; обе
-- колонки uuid, приведение к тексту здесь только потеряло бы индекс.
UPDATE ai_route_images ai
   SET route_id = 'b3d7eb6c-2ac4-41d9-89fe-52d073c3488d'
  FROM places p
 WHERE p.id::text = '77e5d9e1-4746-45fc-bb1a-8527003edf5f'
   AND ai.route_id = p.ark_id
   AND ai.prompt = 'снимок Андрея Запорожца: каньон у вулкана Шивелуч (миграция 984)';

-- ── Исход называется вслух ────────────────────────────────────────────────
DO $$
DECLARE
  v_place_ok  boolean;
  v_photo_ark uuid;
BEGIN
  SELECT TRUE INTO v_place_ok
    FROM places
   WHERE id::text = '002f9a4f-8833-4ee7-8dc4-290b30092cb7'
     AND is_visible
     AND ark_id IS NOT NULL;

  IF v_place_ok IS NOT TRUE THEN
    RAISE WARNING '[986] место «Каньон на Шивелуче» не заведено или скрыто — снимку ехать некуда';
    RETURN;
  END IF;

  SELECT route_id INTO v_photo_ark
    FROM ai_route_images
   WHERE prompt = 'снимок Андрея Запорожца: каньон у вулкана Шивелуч (миграция 984)';

  IF v_photo_ark IS NULL THEN
    RAISE WARNING '[986] снимок каньона не найден ВООБЩЕ — ни на вулкане, ни на новом месте';
  ELSIF v_photo_ark <> 'b3d7eb6c-2ac4-41d9-89fe-52d073c3488d' THEN
    RAISE WARNING '[986] снимок каньона остался на прежней записи (route_id=%)', v_photo_ark;
  END IF;
END $$;

COMMIT;
