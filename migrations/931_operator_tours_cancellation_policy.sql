-- Migration 931: условия отмены и возврата у тура
--
-- Перепись готовности к чужой витрине (channel-readiness, 23.08) назвала
-- cancellation_policy одним из трёх полей, которых нет в схеме ВООБЩЕ: правило
-- отмены жило только в коде крона (24 часа без оплаты). Сверка с blueprint
-- commerce-agents (03.09): у шопинг-агента вопрос про отмену и возврат — один
-- из пяти базовых потоков, и отвечать на него он обязан из данных каталога.
-- Кузьмичу на «а если отменю» сегодня отвечать нечем, кроме выдумки (§4.0).
--
-- Поле TEXT, свободная формулировка оператора («бесплатная отмена за 48 ч,
-- позже удерживается 30%»). Пусто — значит «не записано», и карточка блок не
-- рисует, а Кузьмич говорит, что условий у него нет, и направляет к оператору.
-- Никому ничего не выдумываем и не проставляем по умолчанию.

ALTER TABLE operator_tours ADD COLUMN IF NOT EXISTS cancellation_policy TEXT;

COMMENT ON COLUMN operator_tours.cancellation_policy IS
  'Условия отмены и возврата от оператора, свободный текст. NULL — не записано (не «без условий»).';

INSERT INTO _migrations (name)
VALUES ('931_operator_tours_cancellation_policy.sql')
ON CONFLICT (name) DO NOTHING;
