-- 13.10 (решение владельца «согласен, перенеси в S3»): байты снимков вынесены в
-- хранилище — ключ migrations/photos/<sha256>.jpg из маркера
-- .github/triggers/migration-photos-to-s3.json (sha256 тех же байтов). Миграция
-- пишет s3_key, image_data пуст; прод переведён по хэшу байтов миграцией 1228.
--
-- 1039: Вилючинский вулкан с озера Микижа — кадр заменён на лучший из новых.
--
-- 27.09 владелец прислал ещё два снимка того же вида: «тоже вилючинский
-- вулкан вид с озера Микижа, выбери фото, если эти лучше — поставь».
--
-- Взят горизонтальный: на нём, в отличие от стоявшего (1036/1037), виден
-- сам берег озера — вода внизу кадра, осенний лес, вулкан над лесом. Прежний
-- кадр был крупным планом вулкана над деревьями, и воды на нём не было:
-- подпись «с озера Микижа» он не подтверждал. Вертикальный из новых в окно
-- 16:9 не ложится — пришлось бы резать либо вершину, либо воду.
--
-- Обрезка: исходник 1280x960, окно 16:9 полной ширины со смещением 200
-- сверху (1280x720), JPEG q80. Людей в кадре нет.
--
-- Меняются ровно две строки, положенные 1036 и 1037, — по месту, позиции,
-- подписи и автору. Чужой кадр не трогается. Не совпало две — WARNING.
-- s3_url обнуляется: уборщик cron-images-to-s3 увезёт новые байты (§4.1).
--
-- IDEMPOTENT

DO $$
DECLARE
  v_n int;
BEGIN
  UPDATE place_gallery_photos g
     SET image_data = NULL, s3_key = 'migrations/photos/2a3ed3fe611c1f0be0a0bc878f12b956b0798bf2c52569981149aa1ea0cdf26b.jpg',
         mime_type  = 'image/jpeg',
         width      = 1280,
         height     = 720,
         s3_url     = NULL,
         created_at = NOW()
    FROM places p
   WHERE g.ark_id = p.ark_id
     AND p.merged_into_id IS NULL
     AND g.author = 'владелец платформы'
     AND (
           (p.id::text = '164f612c-32da-4f0f-b261-c45c09dc2933'
            AND p.name = 'Вулкан Вилючинский'
            AND g.position = 1
            AND g.caption = 'Вилючинский вулкан с озера Микижа')
        OR (p.name = 'Озеро Микижа'
            AND abs(p.lat::float8 - 53.01045) < 0.001
            AND abs(p.lng::float8 - 158.26904) < 0.001
            AND g.position = 3
            AND g.caption = 'Озеро Микижа: вид на Вилючинский вулкан')
         );
  GET DIAGNOSTICS v_n = ROW_COUNT;

  IF v_n <> 2 THEN
    RAISE WARNING '[1039] кадр Вилючинского с Микижи заменён в % строках вместо двух (галереи вулкана и озера)', v_n;
  END IF;
END $$;
