-- 13.10 (решение владельца «согласен, перенеси в S3»): байты снимков вынесены в
-- хранилище — ключ migrations/photos/<sha256>.jpg из маркера
-- .github/triggers/migration-photos-to-s3.json (sha256 тех же байтов). Миграция
-- пишет s3_key, image_data пуст; прод переведён по хэшу байтов миграцией 1228.
--
-- 985: «Корякская сопка» — второй снимок владельца, вечерний.
--
-- ── Что за кадр ───────────────────────────────────────────────────────────
--
-- 19.09 владелец прислал второй снимок того же вулкана: закатный свет, конус
-- розовый от последнего солнца, поле и лес уже в тёплой охре. На вопрос о
-- правах ответил «наша фото место тоже» — то есть снимок его, и снят с того
-- же поля, что дневной кадр (миграция 983) и Авачинский (981).
--
-- ── Почему в галерею, а не героем ─────────────────────────────────────────
--
-- Героя карточки уже занимает ЕГО ЖЕ дневной снимок (983, подтверждён на
-- проде пробой 532). Класть второй кадр героем значило бы вытеснить первый —
-- а он никуда не девается только в том случае, если его байты перед этим
-- куда-то переложить. Переложить их уже нечем: после переезда в хранилище
-- (§4.1) `image_data` у героя ПУСТ, там остались только `s3_key`/`s3_url`,
-- и SQL-копия «из героя в галерею» скопировала бы пустоту.
--
-- Поэтому нетравмирующий порядок: вечерний кадр — позиция 1 галереи, дневной
-- остаётся героем. Видны оба. Захочет владелец поменять их местами — это
-- отдельная правка, и делать её надо осознанно, с переносом байтов из
-- хранилища, а не «заодно».
--
-- Сторож этого решения не нужен: защита героя от перезаписи чужого ручного
-- снимка уже стоит в самой вставке 983 и сработала бы здесь сама. Запись
-- оставлена словами, потому что причина не в коде, а в состоянии данных.
--
-- ── Размер ────────────────────────────────────────────────────────────────
--
-- Исходник 1200x1600. Окно 16:9 полной ширины (1200x675) со смещением 28%
-- сверху: вершина не срезана, в кадре остаётся полоса леса и поле. Записан
-- РОДНОЙ размер, без растягивания до 1280x720 — канон описывает потолок, а
-- не обязанность дорисовывать резкость.
--
-- ── Как ложится ───────────────────────────────────────────────────────────
--
-- `ON CONFLICT (ark_id, position) DO UPDATE` (уникальный индекс миграции
-- 968): повтор не плодит строк и не сдвигает позиции. `s3_url` гасится —
-- старый объект этим байтам не соответствует.
--
-- Байты пишутся в базу, а не в хранилище: миграция накатывается при старте
-- сервера, сетевой вызов оттуда стопорил бы весь накат; увезёт уборщик.
--
-- Третий исход назван вслух: нет ark_id — RAISE WARNING в лог выката, а не
-- молчаливые ноль строк (урок миграции 976).
--
-- IDEMPOTENT

BEGIN;

INSERT INTO place_gallery_photos (ark_id, position, image_data, mime_type, width, height, caption, author, s3_key)
SELECT p.ark_id,
       1,
       NULL::bytea,
       'image/jpeg',
       1200,
       675,
       'Корякская сопка в вечернем свете',
       'владелец платформы',
       'migrations/photos/804cf57c49320b6be83b40eaf2e7052a14ef08afda5e98abd950b6ed1a015ee2.jpg'
  FROM places p
 WHERE p.id::text = 'dea99549-5ecb-41fe-af19-15f216eeac68'
   AND p.ark_id IS NOT NULL
 LIMIT 1
ON CONFLICT (ark_id, position) DO UPDATE
   SET image_data = EXCLUDED.image_data,
       s3_key     = EXCLUDED.s3_key,
       mime_type  = EXCLUDED.mime_type,
       width      = EXCLUDED.width,
       height     = EXCLUDED.height,
       caption    = EXCLUDED.caption,
       author     = EXCLUDED.author,
       s3_url     = NULL,
       created_at = NOW();

-- ── Отказ называется вслух ────────────────────────────────────────────────
DO $$
DECLARE
  v_ark uuid;
  v_cap text;
BEGIN
  SELECT ark_id INTO v_ark FROM places WHERE id::text = 'dea99549-5ecb-41fe-af19-15f216eeac68';

  IF v_ark IS NULL THEN
    RAISE WARNING '[985] у «Корякской сопки» нет ark_id — вечерний снимок НЕ лёг, галерея пуста';
    RETURN;
  END IF;

  SELECT caption INTO v_cap FROM place_gallery_photos WHERE ark_id = v_ark AND position = 1;

  IF v_cap IS DISTINCT FROM 'Корякская сопка в вечернем свете' THEN
    RAISE WARNING '[985] в галерее Корякской сопки на позиции 1 не вечерний снимок (caption=%)', COALESCE(v_cap, 'строки нет');
  END IF;
END $$;

COMMIT;
