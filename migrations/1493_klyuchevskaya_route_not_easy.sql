-- 1493_klyuchevskaya_route_not_easy.sql
--
-- Маршрут «Вулкан Ключевская сопка» — не «лёгкий» (#3566 п.1, слово
-- владельца 21.11: «Вулкан Ключевская сопка самый коварный вулкан и очень
-- сложный там каждый год гибнут люди»).
--
-- ── Повод ─────────────────────────────────────────────────────────────────
--
-- Сверка дублей #3566 (MCP fetch, 21.11): у маршрута
-- /routes/vulkan-klyuchevskaya-sopka-413a7499 описание говорит о восхождении
-- на 4750 м с альпинистской подготовкой, а поля — «лёгкий», 3,5 км, набор
-- 19 м. Эти цифры видят карточка маршрута, каталог, Кузьмич и MCP, и человек
-- выбирает по ним: «лёгкий» у самого высокого действующего вулкана края —
-- ложь, опасная для жизни.
--
-- ── Что делает миграция ───────────────────────────────────────────────────
--
-- 1. Сложность — 'extreme' (высшая ступень шкалы lib/routes/difficulty-scale),
--    источник — слово владельца (difficulty_source = 'owner-decision').
-- 2. Дистанция и набор высоты — NULL, «не записано» (§4.0): у восхождения на
--    4750 м 3,5 км и 19 м неверны, а верных цифр с источником нет. Выдумывать
--    замену нельзя.
-- Фразу «каждый год гибнут люди» в данные не пишем: числа без источника на
-- карточке нет; это решение — за текстом с источником.
--
-- Идемпотентна: правка только там, где стоят ровно прежние значения
-- (сложность — кодом 'easy' или словом, как её писал импорт).

UPDATE kamchatka_routes
SET difficulty = 'extreme',
    difficulty_source = 'owner-decision',
    distance_km = NULL,
    distance_note = NULL,
    elevation_gain_m = NULL,
    updated_at = NOW()
WHERE slug = 'vulkan-klyuchevskaya-sopka-413a7499'
  AND merged_into_id IS NULL
  AND lower(difficulty) IN ('easy', 'лёгкий', 'легкий')
  AND distance_km = 3.5
  AND elevation_gain_m = 19;
