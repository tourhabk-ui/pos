--
-- Владелец 09.10: «ИП Миронова Нина Васильевна, ИНН 250302356113, лицензия
-- есть и адрес — перевозка 24» и прислал снимок объявления на perevozka24.com,
-- где тот же перевозчик назван тем же именем и тем же номером телефона.
-- На борту вахтовки наклейка «ЗАКАЗНОЙ» с теми же именем и ИНН (снимок,
-- присланный владельцем вместе с остальными): три источника сходятся.
--
-- ── Что записано ──────────────────────────────────────────────────────────
--
--   • company_name и legal_info.companyName — «ИП Миронова Нина Васильевна»;
--   • legal_info.inn — 250302356113 (двенадцать цифр, ИНН предпринимателя);
--   • legal_info.license — «есть»: так сказал владелец. Номера лицензии он не
--     называл, и в карточку попадает слово, а не число, прочитанное мной с
--     наклейки на снимке: цифру с картинки легко прочесть неверно.
--
-- ── Чего НЕТ ──────────────────────────────────────────────────────────────
--
--   • Адреса. «Адрес — перевозка 24» указывает на объявление, где перевозчик
--     стоит в разделе Петропавловска-Камчатского, но улицы и дома там на
--     снимке нет; город раздела — не адрес перевозчика, и в legal_info.address
