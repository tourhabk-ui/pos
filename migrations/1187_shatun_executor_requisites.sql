--   • ОГРНИП, регистрационных дат: не названы.
--   • Отметки «проверено»: is_verified остаётся FALSE — реквизиты со слов
--     владельца платформа по реестру не сверяла, отметку даёт только
--     администратор. registry_status не трогается.
--   • Цен и условий с perevozka24: там 7 000 ₽/час и 70 000 ₽/смена, способ
--     оплаты «наличные/безнал», расчёт «предоплата», «24+2» места, «6 лет
--     опыта». Это чужая площадка и другая единица цены, чем у прайса 2026
--     года, который владелец прислал отдельно; два прайса на одной карточке
--     разошлись бы. Прайс — только из transfer_charter_prices.
--
-- Пишется только туда, где реквизитов ещё нет: правку администратора из
-- кабинета не затираем.
--
-- IDEMPOTENT

BEGIN;

UPDATE partners
   SET company_name = 'ИП Миронова Нина Васильевна',
       legal_info = jsonb_build_object(
         'companyName', 'ИП Миронова Нина Васильевна',
         'inn',         '250302356113',
         'license',     'есть'
       ),
       updated_at = NOW()
 WHERE slug = 'shatun'
   AND (company_name IS NULL OR company_name = '')
   AND (legal_info IS NULL OR legal_info = '{}'::jsonb OR legal_info = 'null'::jsonb);

DO $$
DECLARE
  v_n int;
BEGIN
  SELECT count(*) INTO v_n FROM partners
   WHERE slug = 'shatun' AND legal_info->>'inn' = '250302356113'
     AND company_name = 'ИП Миронова Нина Васильевна';
  IF v_n <> 1 THEN
    RAISE WARNING '[1187] реквизиты «Шатуна»: найдено % записей (нужна одна; реквизиты могли быть заполнены раньше из админки)', v_n;
  END IF;
END $$;

COMMIT;
