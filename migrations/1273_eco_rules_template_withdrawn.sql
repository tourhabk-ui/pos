-- 1273: Шаблонные правила режима (169/170) — с карточек в архивную колонку
-- Created: 2026-10-15
--
-- ── Почему ────────────────────────────────────────────────────────────────
--
-- Миграции 169 и 170 записали в places.eco_rules ОДИН абзац на род
-- охраняемой территории — каждому месту, чей eco_zone совпал по ILIKE с
-- именем, зоной или описанием. Правила одного парка, раздела положения или
-- приказа за этим текстом нет: «Домашние животные допускаются на поводке» и
-- «сбор ягод разрешён в личных объёмах» — каждому природному парку края,
-- «в период нереста посещение только с инспектором» и «не ближе 100 м» —
-- каждому заказнику, «температура до 900°C» и «съёмка без ограничений» —
-- каждому месту, где в описании мелькнуло «ЮНЕСКО».
--
-- Карточка показывала абзац блоком «Правила посещения» как записанные у
-- места правила (PlaceEco). 15.10 владелец дал карт-бланш снять экошаблон
-- (§0 «честность»): шаблон в коде снят тем же днём, это — его половина в
-- данных. Места, чей режим переписан по источникам (1240–1257), получили
-- свои правила и шаблона не несут — их миграция не трогает.
--
-- ── Как — прячем, не удаляем (как дневники, 1247) ─────────────────────────
--
-- Текст переезжает в places.eco_rules_withdrawn с причиной и временем, а
-- eco_rules становится NULL: все читатели (карточка, кабинет администратора)
-- перестают показывать его разом. Карточка говорит словами: «Правила
-- посещения этого места на платформе пока не записаны — уточните их у
-- дирекции охраняемой территории» (PlaceEco).
--
-- Снимается только ДОКАЗАННЫЙ шаблон: текст, совпавший целиком с одним из
-- шести абзацев 169/170 (они собраны здесь теми же выражениями, что там).
-- Правленный рукой текст не совпадёт и останется — ошибка в эту сторону
-- стоит лишнего абзаца, в другую — правил, которые кто-то записал.
--
-- Режим (eco_zone) и пропуск (eco_permit_*) не трогаются: это отдельный
-- разбор, у него свои исходы.
--
-- IDEMPOTENT: повтор — no-op, перенесённое уже пусто.

BEGIN;

ALTER TABLE places ADD COLUMN IF NOT EXISTS eco_rules_withdrawn TEXT;
ALTER TABLE places ADD COLUMN IF NOT EXISTS eco_rules_withdrawn_reason TEXT;
ALTER TABLE places ADD COLUMN IF NOT EXISTS eco_rules_withdrawn_at TIMESTAMPTZ;

COMMENT ON COLUMN places.eco_rules_withdrawn IS
