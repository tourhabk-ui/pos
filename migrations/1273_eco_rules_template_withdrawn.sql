UPDATE places p
   SET eco_rules_withdrawn = p.eco_rules,
       eco_rules_withdrawn_reason = 'шаблон 169/170 на род охраняемой территории, а не правила места; снят по карт-бланшу владельца 15.10 (§0 «честность»)',
       eco_rules_withdrawn_at = NOW(),
       eco_rules = NULL
  FROM template t
 WHERE p.eco_rules = t.txt
   AND p.eco_rules_withdrawn IS NULL;

-- ── Исход называется вслух ────────────────────────────────────────────────
DO $$
DECLARE
  v_withdrawn int;
  v_left int;
BEGIN
  SELECT count(*) INTO v_withdrawn FROM places WHERE eco_rules_withdrawn IS NOT NULL;
  SELECT count(*) INTO v_left FROM places WHERE eco_rules IS NOT NULL AND is_visible = TRUE AND merged_into_id IS NULL;
  RAISE NOTICE '[1273] правил режима в архиве: %, записанных правил у видимых мест осталось: %', v_withdrawn, v_left;
END $$;

COMMIT;

