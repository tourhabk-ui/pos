-- 950_hide_avacha_viewpoint_bad_coords.sql
--
-- «Смотровая у Авачинского вулкана» (3cd79015-eed6-40ff-8e4c-eb49a8c7ff3a)
-- скрыта 10.09 — долг миграции 947, где она была названа прямо: «она НЕ
-- трогается здесь: там независимый источник ещё не проверялся отдельно».
-- Теперь проверен.
--
-- Что видно: координата (53.0483638,158.6679826) лежит в черте
-- Петропавловска-Камчатского, на высоте городских кварталов, в ~25 км от
-- Авачинского вулкана (53.2554,158.8362 — эта запись как раз на месте).
-- Собственное описание записи ей противоречит: «у подножия Авачинского
-- вулкана на высоте ~600 м». Свидетелем описание при этом НЕ является —
-- в нём повторена та же координата («53.05°N, 158.67°E»), то есть оно
-- писалось ПО ней и подтверждает не факт, а самого себя.
--
-- Источника для правки нет. Сплошная сверка всех живых мест с OSM
-- (GET /api/cron/places-osm-crosscheck, run 4 от 10.09: 377 мест против
-- 8379 именованных объектов края) не нашла этой смотровой ни одного
-- сильного тёзки — в OpenStreetMap такого объекта нет. Ставить координату
-- «примерно у подножия» значило бы выдумать её: у подножия Авачинского
-- смотровых площадок несколько, и какая из них эта — неизвестно.
--
-- Поэтому скрытие, а не правка и не удаление: is_visible = false убирает
-- запись с карты и из каталога, но не рвёт FK и оставляет путь назад, если
-- источник найдётся. Тот же ход, что 947 и 948.
--
-- Идемпотентно: отсутствующая запись — no-op с NOTICE, не ошибка.

DO $$
DECLARE
  pid text := '3cd79015-eed6-40ff-8e4c-eb49a8c7ff3a';
  pname text;
BEGIN
  SELECT name INTO pname FROM places WHERE id = pid;

  IF pname IS NULL THEN
    RAISE NOTICE '[950] % — уже отсутствует в places, делать нечего', pid;
    RETURN;
  END IF;

  UPDATE places SET is_visible = false, updated_at = NOW() WHERE id = pid;
  RAISE NOTICE '[950] скрыто (is_visible=false): % (%)', pname, pid;
END $$;
