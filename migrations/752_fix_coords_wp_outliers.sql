-- Партия 2 ремонта координат (после 751). Диагностика waypoints (Шаг 10,
-- run 9) показала знаменитые места в десятках-сотнях км от одноимённых
-- маршрутов: «Курильское озеро» 461 км, «Экструзия Верблюд» 161 км,
-- «Вулкан Бакенинг» 99 км, «Кутхины баты» 40 км от Курильского озера
-- (реально ~4 км) — у мест битые координаты. Верифицированные значения
-- из открытых источников:
--   Курильское озеро   51°27'18"N 157°05'54"E — ru.wikipedia
--   Кутхины баты       51.508701, 156.996493 — volcanoesland.ru, kamchatkaland.ru
--   Вулкан Корякский   N53.32337 E158.71113  — peakfinder.ru, wikipoints.ru
--   Вулкан Жупановский N53.590385 E159.111658 — peakfinder.ru
--   Вулкан Бакенинг    53°53'35"N 158°09'40"E — карточка ООПТ (озёра у вулкана,
--                      точность ~2 км — лучше текущей ошибки в 99 км)
--   Экструзия Верблюд  N53.27238 E158.76429  — tonkosti.ru, volcanoesland.ru
--
-- Обновляем ТОЛЬКО если текущая координата дальше ~2 км от верифицированной
-- — ручные правки через админку не перетираются. Идемпотентна.
--
-- БЕЗ чисел в открытых источниках (партия 3, не трогаем): Карымшинские
-- источники, Налычевские источники/«Термальные источники Нальчева»,
-- Налычевская долина, Озерновские терм., Озеро Срединное, кластер Эссо
-- (Дыгерен-Оленгенде и соседи), Толмачёвский кластер, северные пары.

UPDATE places SET lat = 51.4550, lng = 157.0983, updated_at = NOW()
 WHERE name = 'Курильское озеро'
   AND (lat IS NULL OR abs(lat - 51.4550) > 0.02 OR abs(lng - 157.0983) > 0.03);

