-- 13.10 (решение владельца «согласен, перенеси в S3»): байты снимков вынесены в
-- хранилище — ключ migrations/photos/<sha256>.jpg из маркера
-- .github/triggers/migration-photos-to-s3.json (sha256 тех же байтов). Миграция
-- пишет s3_key, image_data пуст; прод переведён по хэшу байтов миграцией 1228.
--
-- 967: Дикие озерки (ЭмЖо) — снимок владельца, уточнения по источнику
--     и нормализация coord_source в трёх местах.
--
-- ── Место уже есть, и координата уже верна ────────────────────────────────
--
-- Владелец прислал координату 53°16'01.1"N 158°23'14.6"E = 53.266972 /
-- 158.387389. В базе с 21.08 (миграция 893) стоит 53.2669 / 158.3874 —
-- совпадение до четвёртого знака. Координату НЕ трогаем: она подтвердилась
-- вторым независимым источником, и это ровно то, ради чего происхождение и
-- записывают.
--
-- ── Что добавляется в описание ────────────────────────────────────────────
--
-- Описание 893 собрано из полевых постов владельца и остаётся. Дописывается
-- то, чего в нём не было: глубина скважины, температура НА ВЫХОДЕ, кремниевая
-- кислота, контрастное купание в Пиначевке и подъезд со стороны Зеленовских.
--
-- ТЕМПЕРАТУРЫ ДВЕ, И ОНИ НЕ ПРОТИВОРЕЧАТ ДРУГ ДРУГУ. В 893 записано 38-42 —
-- это вода в ванне, где сидит человек. Новый источник даёт «более 50» — это
-- вода из скважины. Соединять их в одно число нельзя: в ванне 50 не бывает,
-- а у трубы 40 не бывает, и человеку важны обе цифры по разным причинам.
--
-- ── Нормализация coord_source (три места) ─────────────────────────────────
--
-- Колонка свободная, а перечень в lib/places/coord-source.ts закрытый, и
-- миграции писали в неё свои слова: osm_organic_930 (починено в 960),
-- track_fix_880, track_fix_883, owner_field_893. Каждое такое значение не
-- совпадает ни с одной веткой coordSourceLabel — в поле человек читал бы
-- «Координата точки: происхождение не записано», хотя оно записано.
--
-- Все три сводятся к 'surveyed' — «снята на месте», и это правда в каждом
-- случае: 880 и 883 перенесли места к финишу НАСТОЯЩЕГО трека из Pro-выгрузки
-- владельца, 893 взяла координату из его же полевых постов и сверила по двум
-- расстояниям. Во всех трёх число происходит от человека, физически бывшего
-- в точке. 'external' было бы ложью (не справочник), 'unknown' — тоже
-- (записано).
--
-- Следствие осознанное: coordIsTrustworthy отвечает 'да' только на
-- 'surveyed', то есть эти три точки становятся пригодными для утверждений.
-- Так и должно быть — они сняты на месте.
--
-- Идемпотентно: guard по старому значению у каждого UPDATE.

-- ── 1. coord_source к перечню ────────────────────────────────────────────
UPDATE places SET coord_source = 'surveyed', updated_at = NOW()
 WHERE coord_source IN ('track_fix_880', 'track_fix_883', 'owner_field_893');

-- ── 2. Описание: дописать то, чего не было ───────────────────────────────
UPDATE places
   SET description = description || E'\n\nСкважина глубиной около 60 метров: на выходе вода горячее 50 градусов, в ванне — те самые 38-42. Минерализация сероводородная, кремниевой кислоты больше 50 мг/л, в газовом составе преобладает метан. В ста метрах течёт Пиначевка, и купание здесь контрастное: из горячей воды в холодную речную и обратно.\n\nПодъезд со стороны Зеленовских озерков (до них 3,4 км): от парковки базы объехать её слева, около километра по полю, дальше лесная дорога ещё примерно 3,5 км. Состояние дороги меняется — уточняйте перед выездом.',
       updated_at = NOW()
 WHERE id::text = '36214e49-de02-4d1b-8f71-1926a1b319fa'
   AND description NOT LIKE '%60 метров%';

-- ── 3. Снимок владельца ──────────────────────────────────────────────────
-- Взята правая часть кадра: оголовок скважины, парящая земля, вулкан за
-- перелеском. Левая половина отброшена не по красоте — на ней люди в ваннах
-- крупно и узнаваемо, один практически без одежды. Согласия этих людей у нас
-- нет, а карточка публичная. Заодно правый кадр честнее показывает, что это
-- за место: труба, ржавчина, болото — дикий источник, а не база отдыха.
INSERT INTO ai_route_images (route_id, image_data, mime_type, prompt, model, width, height, author, s3_key)
SELECT p.ark_id,
       NULL::bytea,
       'image/jpeg',
       'снимок владельца: Дикие озерки (ЭмЖо), миграция 967',
       'manual-upload',
       1280,
       720,
       'владелец платформы',
       'migrations/photos/dc582b7dc43681c7a5070a7605dbe89299e0070674c7c60d007436e812a2702c.jpg'
  FROM places p
 WHERE p.id::text = '36214e49-de02-4d1b-8f71-1926a1b319fa'
   AND p.ark_id IS NOT NULL
 LIMIT 1
ON CONFLICT (route_id) DO UPDATE
   SET image_data = EXCLUDED.image_data,
       s3_url     = NULL,
       s3_key     = EXCLUDED.s3_key,
       mime_type  = EXCLUDED.mime_type,
       prompt     = EXCLUDED.prompt,
       model      = EXCLUDED.model,
       width      = EXCLUDED.width,
       height     = EXCLUDED.height,
       author     = EXCLUDED.author,
       created_at = NOW()
 WHERE ai_route_images.model NOT IN ('wikimedia', 'manual-upload');
