-- 892: скрыть два имени-заглушки — «удалить мусор» (владелец 20.08).
--
-- «Зимняя сказка» и «Чудеса Камчатки» — последние два нарушителя стандарта
-- имён (§13) после четырёх партий переименований (888-891). У обоих ни
-- координаты, ни привязанных мест, ни объекта в описании (generic-текст,
-- судя по стилю — переписан Editor'ом поверх пустоты). Имя вывести не из
-- чего, а маршрут без места, пути и содержания — не маршрут; выдумывать
-- объект запрещено правилом третьего состояния (CLAUDE.md 4.0).
--
-- Скрытие, не DELETE: как все чистки кампании (160, 762, 859) — обратимо,
-- запись остаётся для истории. Guard по имени — идемпотентно, и если
-- запись успели переименовать/наполнить, она не трогается.

UPDATE kamchatka_routes r
SET is_visible = false, updated_at = NOW()
FROM (VALUES
  ('02222c1f-e3d1-47ca-952e-90ae01b21349', 'Зимняя сказка'),
  ('1a90ce1d-ec48-4b34-84ba-10365d6cd081', 'Чудеса Камчатки')
) AS p(route_id, title)
WHERE r.id::text = p.route_id
  AND r.title = p.title
  AND r.is_visible = true
  AND r.merged_into_id IS NULL;
