-- 945: отметка «в МЧС сообщили сами»
--
-- Возврат группы и обращение в МЧС — РАЗНЫЕ события, и раньше их было нечем
-- различить: единственной отметкой на регистрации была completed_at, то есть
-- «маршрут закрыт». Экстренный контакт, позвонивший в 112, не мог сообщить
-- об этом платформе иначе как закрыв маршрут — то есть соврав, что группа
-- вернулась, и выключив сторожа ровно в тот момент, когда он нужен.
--
-- Отметка НЕ гасит шаг МЧС: самоотчёт человека — не подтверждение того, что
-- заявку приняли. Она только предупреждает дежурного о возможном дубле.
ALTER TABLE route_registrations
  ADD COLUMN IF NOT EXISTS mchs_informed_at TIMESTAMPTZ;

COMMENT ON COLUMN route_registrations.mchs_informed_at IS
  'Когда экстренный контакт или руководитель отметил, что сам сообщил в МЧС. Не гасит эскалацию.';
