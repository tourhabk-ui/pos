-- 926: опечатка в имени вулкана Крашенинникова.
--
-- ── Что чинится ────────────────────────────────────────────────────────────
--
-- В каталоге записано «Вулкан Крашенникова» — без «ин». Вулкан назван по
-- фамилии Степана Петровича Крашенинникова, и правильно она пишется
-- «Крашенинников»; OSM (через MAPS.ME) тоже даёт «Крашенинникова».
--
-- Опечатка не косметическая. KVERT называет вулкан «KRASHENINNIKOV», и
-- сопоставление с точкой каталога идёт по основе имени
-- (lib/services/safety/volcano-match.ts). Основы «крашенников» и
-- «крашенинников» не совпадают, поэтому вулкан не привязывался к месту,
-- а значит НЕ ПОКАЗЫВАЛСЯ НА РАДАРЕ безопасности — даже при опасном коде.
--
-- Смягчать сравнение до «похоже» вместо правки данных нельзя: тогда статус
-- может уехать на соседний конус, и человек увидит оранжевый код не над тем
-- вулканом. Правило отказывает верно — чинится опечатка.
--
-- Опечатка же скрыла запись и от разбора: проба 02.09 искала «Крашенин» и
-- вернула ноль, из чего был сделан неверный вывод «места в каталоге нет».
--
-- Идемпотентна: повторный прогон ничего не найдёт и ничего не сделает.

UPDATE places
   SET name = 'Вулкан Крашенинникова',
       updated_at = NOW()
 WHERE name = 'Вулкан Крашенникова'
   AND location_type = 'volcano';
