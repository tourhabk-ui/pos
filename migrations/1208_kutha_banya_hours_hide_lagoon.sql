-- 1208: «Кутха» — баня по часам и доска цен; «Голубая лагуна» скрыта.
-- Слово владельца 10.10 (снимок доски «Гостевой домик Кутха» и «голубую
-- лагуну пока спрячем»).
--
-- 1. Доска в доме, нынешняя: «Наличные, переводом на карту. До 4 человек —
--    2000 р. 1 час, до 8 — 3000 р., до 12 — 4000 р. Дни рождения,
--    корпоративы. Сутки до 8 человек — 24000 р. Веник дубовый — 500 р.»
--    Сутки на 8 мест совпадают с 1205 — доска подтверждает, а не спорит.
--    Новое — баня отдельно по часам и способ оплаты. Описание переписывается
--    только поверх текста 1205; правка администратора цела.
--    Снимок доски встаёт последним: цены на нём те же, что в описании (в
--    отличие от старой доски с 20 000 ₽, которую не взяли в 1207).
--
-- 2. «Голубая лагуна» (1109) — is_active = false: витрина, поиск, планер и
--    Кузьмич читают жильё через publicModeratedSql (is_active AND approved),
--    объект пропадает отовсюду разом. «Пока» — строка не удаляется, вернуть —
--    is_active = true. Только если объект сейчас показан.
--
-- Идемпотентна.

UPDATE accommodations
   SET description = 'Гостевой дом в посёлке Пионерский сдаётся целиком: 8 спальных мест и ещё 2 раскладушки, до 10 человек. В доме баня с парной, крытый бассейн с подогревом, кухня в гостиной; во дворе беседки и парковка. '
       || 'За сутки за весь дом: 24 000 ₽ на 8 спальных мест, 28 000 ₽ с двумя раскладушками. Баня входит в цену. Принимает гостей круглый год. '
       || 'Баню можно заказать и отдельно, по часам: до 4 человек — 2 000 ₽, до 8 — 3 000 ₽, до 12 — 4 000 ₽ в час; дни рождения и корпоративы. Дубовый веник — 500 ₽. '
       || 'Свободные даты и условия заселения подтверждает владелец по телефону. '
       || 'Бронь и оплата идут напрямую с объектом — наличными или переводом на карту; платформа оплату не принимает и номеров не продаёт.',
       updated_at = NOW()
 WHERE LOWER(name) = 'кутха'
   AND description LIKE '%28 000 ₽ с двумя раскладушками%'
   AND description NOT LIKE '%по часам%';

WITH k AS (
  SELECT a.id
    FROM accommodations a
   WHERE LOWER(a.name) = 'кутха'
     AND EXISTS (SELECT 1 FROM accommodation_assets aa WHERE aa.accommodation_id::text = a.id::text)
),
ins AS (
  INSERT INTO assets (url, mime_type, sha256, size, width, height, alt)
  SELECT '/images/kutha/kutha-22.jpg', 'image/jpeg',
         '40e73a5069756fa3727c6c4959c593c36978e55d607e5f98ccf55c58973fbeb7', 118604, 590, 1280,
         'Доска с ценами в доме: сутки до 8 человек — 24 000 ₽, баня по часам'
   WHERE EXISTS (SELECT 1 FROM k)
     AND NOT EXISTS (SELECT 1 FROM assets s WHERE s.url = '/images/kutha/kutha-22.jpg')
  RETURNING id
)
INSERT INTO accommodation_assets (accommodation_id, asset_id)
SELECT k.id, ins.id FROM k CROSS JOIN ins;

UPDATE accommodations
   SET is_active = FALSE,
       updated_at = NOW()
 WHERE LOWER(name) IN ('голубая лагуна', 'лагуна')
   AND is_active = TRUE;
