DECLARE
  v_parks int;
  v_places int;
BEGIN
  SELECT count(*) INTO v_parks FROM parks
   WHERE slug IN ('klyuchevskoy', 'yuzhno-kamchatsky') AND display_name LIKE 'Национальный парк — %';
  SELECT count(*) INTO v_places FROM places
   WHERE eco_zone = 'national_park'
