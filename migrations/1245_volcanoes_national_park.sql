--   судьба Налычево, Быстринского и Вилючинского — в сообщении о них нет
--     ничего, их записи не трогаются.
--
-- ── Какие места — по контуру, не по имени ─────────────────────────────────
--
-- Контуры парков — отношения OpenStreetMap 21624151 («Ключевской») и
-- 21624150 («Южно-Камчатский»), Nominatim lookup (проба 840); места — экспорт
-- слоя мест по шести клеткам вокруг них (пробы 841, 842), проверка «точка в
-- контуре». Контур «Ключевского» по площади сходится с источником: 369 502 га
-- против 371 022 га по Википедии. Контур «Южно-Камчатского» — 104 326 га,
-- и полноту его подтвердить нечем; поэтому он только ДОБАВЛЯЕТ места, а
-- место вне контура (Ходутка, Ксудач, Асача) не трогается — «не установлено»
-- не равно «не в парке».
--
-- Внутри: 40 мест «Ключевского» и 8 «Южно-Камчатского». Из восьми не
-- трогается запись «Природный парк Южно-Камчатский» (d9059e8a): её описание
-- рассказывает о федеральном заказнике с тем же именем (миграции 104, 116) —
-- менять ей режим, не разобрав текст, значило бы спрятать путаницу под новой
-- подписью.
--
-- Режим места: «Национальный парк», разрешение нужно, своей ссылки на
-- разрешение нет (прежние kamchatkaparks.ru и kronoki.ru/visit у объектов
-- ЮНЕСКО — первый не наш адрес парка, второй — Кроноцкий заповедник, к этим
-- паркам не относящийся). Правила посещения — две строки фактов вместо
-- шаблонных абзацев 170-й, источника у которых не было. Меняется режим,
-- только пока он прежний: природный парк, заказник, «нет», ЮНЕСКО или пусто.
