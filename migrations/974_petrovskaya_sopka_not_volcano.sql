-- 974_petrovskaya_sopka_not_volcano.sql
--
-- Второй и ПОСЛЕДНИЙ городской холм в разделе вулканов. То же, что 972+973
-- сделали для Никольской, здесь делается для Сопки Петровской — одной
-- миграцией, потому что тип и профиль испорчены одним и тем же образом.
--
-- ── Почему стало известно, что он последний ──────────────────────────────
--
-- Перепись раздела целиком (prod-check run 53, 15.09 10:39 UTC, 118 записей
-- location_type='volcano'), отсортированная по расстоянию до центра
-- Петропавловска-Камчатского:
--
--   2.4 км  Сопка Петровская    <- эта запись
--   2.8 км  Сопка Никольская    <- исправлена 972/973
--  25.8 км  Козельский          <- настоящий вулкан
--  26.6 км  Вулкан Авачинский
--  31.0 км  Корякская сопка
--
-- Между второй и третьей строкой обрыв в двадцать три километра. Городских
-- холмов в разделе ровно два, и оба теперь названы поимённо. Это не оценка
-- «похоже, больше нет» — это прочитанный список из 118 строк.
--
-- Петровская и Никольская стоят в 841 метре друг от друга, обе у Авачинской
-- бухты в черте города. Описание Петровской упоминает вид на Елизово с
-- четырёхсот метров — это приукрашивание сгенерированного текста, а не
-- другая координата: до Елизова отсюда около тридцати километров.
--
-- ── Что чинится ──────────────────────────────────────────────────────────
--
-- 1. location_type: 'volcano' -> 'mountain'. Как и у Никольской, спор идёт
--    не с геологией (описание само называет её старым вулканическим
--    куполом, и это остаётся в тексте), а с КАТЕГОРИЕЙ: по location_type
--    собирается фильтр «вулканы», бейдж карточки и маркер карты. Турист,
--    открывший раздел, ищет восхождение с регистрацией в МЧС, а получает
--    прогулку по каменной берёзе над городом.
--
-- 2. Профиль безопасности. Живой MCP платформы отдаёт про неё:
--
--      Сопка Петровская [КРАСНЫЙ]
--      Опасности: лавины, камнепад, термальные поля, высотная болезнь.
--
--    Высотная болезнь начинается не с четырёхсот метров; термальных полей
--    и лавин на городской сопке с каменной берёзой нет. Источник тот же,
--    что у Никольской, — шаблон миграции 070 по location_type='volcano'.
--    Ставится NULL, а не пустой список: пустой читался бы как «проверено,
--    опасностей нет», а обследования не было (§4.0).
--
-- ── Чего НЕ делает ───────────────────────────────────────────────────────
--
-- Не трогает [КРАСНЫЙ]: его ставит safety-ingest всем местам зоны, поймавшей
-- алерт severity >= 2. В тревогах Петровской висит чужая дорога к
-- Халактырскому пляжу и землетрясения за 195-244 км — это устройство зон,
-- вопрос шире двух записей и решается владельцем.
--
-- Не трогает terrain_type и capacity_per_day по той же причине, что в 973:
-- 'mountain' для сопки не ложь, а вместимость участвует в пороге
-- красного/жёлтого — менять её без замера значило бы выдумать другое число.
--
-- Не трогает ОСТАЛЬНЫЕ 116 записей: у настоящих вулканов шаблон 070 верен.
-- Проверено на Халактырском пляже тем же MCP — там «дикие животные, резкая
-- смена погоды» и законный красный по алерту про саму дорогу.
--
-- ── Безопасность правки ──────────────────────────────────────────────────
--
-- Тип правится, только если он сейчас 'volcano'; опасности — только если в
-- них лежит ровно шаблон вулкана. Чужая ручная правка не затирается ни в
-- одном из двух шагов. Идемпотентно: повторный прогон выходит с NOTICE.

DO $$
DECLARE
  pid   text := '8b372eca-87a2-440e-bfc1-c5d3f92327ac';
  pname text;
  ptype text;
  park  uuid;
  cur   text[];
  tmpl  text[] := ARRAY['avalanche','rockfall','thermal','altitude']::text[];
BEGIN
  SELECT name, location_type, ark_id INTO pname, ptype, park FROM places WHERE id = pid;

  IF pname IS NULL THEN
    RAISE NOTICE '[974] % — записи нет в places, делать нечего', pid;
    RETURN;
  END IF;

  -- Шаг 1: раздел каталога.
  IF ptype IS DISTINCT FROM 'volcano' THEN
    RAISE NOTICE '[974] % — тип уже %, не трогаем', pname, COALESCE(ptype, 'NULL');
  ELSE
    UPDATE places SET location_type = 'mountain', updated_at = NOW() WHERE id = pid;
    RAISE NOTICE '[974] % — location_type: volcano -> mountain', pname;
  END IF;

  -- Шаг 2: опасности. Отдельно от типа: профиль мог быть испорчен и без него.
  IF park IS NULL THEN
    RAISE NOTICE '[974] % — ark_id пуст, профиль не связать', pname;
    RETURN;
  END IF;

  SELECT hazard_types INTO cur
    FROM location_safety_profile WHERE agent_route_id = park;

  IF NOT FOUND THEN
    RAISE NOTICE '[974] % — профиля безопасности нет', pname;
    RETURN;
  END IF;

  IF cur IS DISTINCT FROM tmpl THEN
    RAISE NOTICE '[974] % — hazard_types уже не шаблон вулкана (%), не трогаем',
      pname, COALESCE(array_to_string(cur, ','), 'NULL');
    RETURN;
  END IF;

  UPDATE location_safety_profile
     SET hazard_types = NULL, difficulty_level = NULL
   WHERE agent_route_id = park;

  RAISE NOTICE '[974] % — сняты опасности шаблона вулкана и сложность 4', pname;
END $$;

INSERT INTO _migrations (name)
VALUES ('974_petrovskaya_sopka_not_volcano.sql')
ON CONFLICT (name) DO NOTHING;
