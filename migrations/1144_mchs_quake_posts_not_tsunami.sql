-- 1144: два поста МЧС о толчках 02-03.10 — не тревога цунами
--
-- Посты «Два ощущаемых сейсмособытия зарегистрированы в акватории Тихого
-- океана» (02.10 18:29 UTC) и «…рано утром 3 октября…» (21:25 UTC) записаны
-- тревогой цунами важности 3 и стояли верхним предупреждением края. В самой
-- статье МЧС (41.mchs.gov.ru, оперативная информация, 5836160) сказано
-- обратное: «Угроза цунами не объявлялась». Глагол «объявл» стоял в общем
-- вето на понижение, и фраза читалась как «отбой не объявлен».
--
-- Правило починено в коде (tsunamiStatus, ae286a5a), но уже вставленные
-- строки оно не трогает: приём пишет ON CONFLICT (external_id) DO NOTHING.
-- Решение владельца 02.10: переразметить, а не ждать истечения срока.
-- Строки не удаляются — остаются для аудита как информация без важности.
--
-- Отбор по id И по заголовку И по типу: чужую строку с тем же id миграция не
-- тронет, а повторный прогон ничего не найдёт.

UPDATE external_alerts
   SET alert_type = 'info',
       severity   = 0,
       updated_at = NOW()
 WHERE id IN (425440, 425470)
   AND alert_type = 'tsunami_warning'
   AND title LIKE 'Два ощущаемых сейсмособытия%';

DO $$
DECLARE
  v_left int;
BEGIN
  SELECT count(*) INTO v_left FROM external_alerts
   WHERE id IN (425440, 425470) AND alert_type = 'tsunami_warning';
  IF v_left > 0 THEN
    RAISE WARNING '[1144] тревог цунами по постам МЧС 02-03.10 осталось: %', v_left;
  END IF;
END $$;
