-- Снимок владельца: cover/centre. Кадр горизонтальный, кекуры по краям, между
-- ними отлив и вулкан за губой — attention ушло бы в светлое небо (урок 958).
INSERT INTO ai_route_images (route_id, image_data, mime_type, prompt, model, width, height, author, s3_key)
SELECT p.ark_id,
       NULL::bytea,
       'image/jpeg',
       'снимок владельца: Кекур Чёртов палец, миграция 966',
       'manual-upload',
       1280,
       720,
       'владелец платформы',
       'migrations/photos/2f5a23d2a5fee814216e0664034c2c615ec4a776af41691074af705c3d3baf85.jpg'
  FROM places p
 WHERE (p.name ILIKE '%чертов палец%' OR p.name ILIKE '%чёртов палец%')
   AND p.ark_id IS NOT NULL
ON CONFLICT (route_id) DO UPDATE
   SET image_data = EXCLUDED.image_data,
       s3_url     = NULL,
       s3_key     = EXCLUDED.s3_key,
       mime_type  = EXCLUDED.mime_type,
       prompt     = EXCLUDED.prompt,
       model      = EXCLUDED.model,
       width      = EXCLUDED.width,
       height     = EXCLUDED.height,
       author     = EXCLUDED.author,
       created_at = NOW()
 WHERE ai_route_images.model NOT IN ('wikimedia', 'manual-upload');
