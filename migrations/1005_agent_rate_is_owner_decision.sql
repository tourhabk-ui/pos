-- 1005: ставку агентской ссылки назначает платформа, а не агент.
--
-- ── Что было ──────────────────────────────────────────────────────────────
--
-- `POST /api/hub/agent/referral` принимал `commissionRate` ТЕЛОМ ЗАПРОСА от
-- самого агента (Zod: `min(1).max(30).default(10)`), писал его в ссылку, и
-- кабинет показывал агенту «заработано» = оплаченные брони × эта же ставка.
-- То есть сторона сделки назначала себе вознаграждение.
--
-- Правило платформы на этот счёт однозначно и оплачено делом (§7, разбор
-- денежного пути 11.09): ставку назначает владелец, и её не меняет никакой
-- автомат. Там речь шла о функции, тихо уводившей ставку по лестнице за
-- объём; здесь хуже — не автомат, а контрагент.
--
-- ── Почему это чинится СЕЙЧАС и дёшево ────────────────────────────────────
--
-- Перепись `GET /api/cron/referral-census` (прогон 561, с прода) показала
-- по всем строкам ноль: ссылок 0, агентов 0, кликов 0, атрибутированных
-- броней 0, обещано 0 ₽. Ни одной ставки никто себе не назначил.
--
-- Значит переназначать нечего и объясняться не с кем. Дефект найден до
-- того, как им воспользовались, — и это единственный момент, когда такую
-- правку можно сделать без разговора с людьми, которым меняют условия.
--
-- ── Что меняет эта миграция ───────────────────────────────────────────────
--
-- 1. Снимает умолчание `DEFAULT 10` у `commission_rate`.
--
--    Умолчание здесь опаснее пустоты. Писатель, не указавший ставку, получал
--    десять процентов МОЛЧА — то есть платформа принимала денежное решение
--    за владельца, не спросив никого. Теперь не указал — значит NULL, и это
--    читается как «ставка не назначена» (§4.0: у поля есть исход «не знаю»).
--
--    Колонка и раньше допускала NULL — менять тип не нужно, и это важно:
--    `NOT NULL` здесь был бы той же ловушкой, что `total_rooms NOT NULL` у
--    витрины жилья — поле, которое нечем заполнить, заполняется выдумкой.
--
-- 2. Заводит АВТОРА решения: кто назначил ставку, когда и на каком
--    основании. Ставка без автора — то же обещание без источника: через
--    месяц никто не скажет, откуда взялись эти проценты.
--
--    Причина хранится текстом и требуется роутом (не базой): проверку длины
--    делает Zod там же, где проверяются подтверждения переводов
--    (`/api/admin/finance/refunds`). Ставить CHECK на длину в схеме значило
--    бы завести второе место для одного правила.
--
-- Существующие строки не трогаются вовсе — их нет. Если к накату они
-- появятся, их ставки останутся как есть: миграция снимает умолчание для
-- БУДУЩИХ вставок, а не переписывает чужие решения.
--
-- IDEMPOTENT

BEGIN;

ALTER TABLE agent_referral_links ALTER COLUMN commission_rate DROP DEFAULT;

ALTER TABLE agent_referral_links
  ADD COLUMN IF NOT EXISTS rate_set_by  UUID REFERENCES users(id),
  ADD COLUMN IF NOT EXISTS rate_set_at  TIMESTAMPTZ,
  ADD COLUMN IF NOT EXISTS rate_reason  TEXT;

COMMENT ON COLUMN agent_referral_links.commission_rate IS
  'Процент вознаграждения по ссылке. NULL — НЕ НАЗНАЧЕНА (не ноль и не десять). Назначает только администратор через POST /api/admin/agent-referral/rate; агент задать её не может.';
COMMENT ON COLUMN agent_referral_links.rate_set_by IS
  'Кто назначил ставку. Пусто, пока ставки нет.';
COMMENT ON COLUMN agent_referral_links.rate_reason IS
  'На каком основании назначена ставка. Обязательна при назначении (проверяет роут).';

-- ── Исход называется вслух ────────────────────────────────────────────────
DO $$
DECLARE
  v_default text;
  v_cols    int;
BEGIN
  SELECT column_default INTO v_default
    FROM information_schema.columns
   WHERE table_name = 'agent_referral_links' AND column_name = 'commission_rate';

  IF v_default IS NOT NULL THEN
    RAISE WARNING '[1005] умолчание у commission_rate ОСТАЛОСЬ (%) — новая ссылка снова получит ставку без решения человека', v_default;
  END IF;

  SELECT COUNT(*) INTO v_cols
    FROM information_schema.columns
   WHERE table_name = 'agent_referral_links'
     AND column_name IN ('rate_set_by', 'rate_set_at', 'rate_reason');

  IF v_cols <> 3 THEN
    RAISE WARNING '[1005] колонок авторства ставки завелось %, а не 3 — назначить ставку будет некому подписать', v_cols;
  END IF;
END $$;

COMMIT;
