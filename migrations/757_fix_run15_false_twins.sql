-- 757_fix_run15_false_twins.sql
--
-- Run 15 (Шаг 1b) починил 18 мест из idilesom-треков — механика
-- подтверждена кросс-чеком (Экструзия Верблюд и Корякский совпали с
-- независимой верификацией до сотен метров). Но strong-матч имён дал
-- трёх ложных доноров (в коде уже ужесточено до полного совпадения
-- набора слов):
--
-- 1. «Авачинский вулкан» получил битый финиш трека-тёзки (52.48, 158.13 —
--    район Паратунки). Верифицированная вершина: 53°15'20"N 158°50'00"E —
--    ru.wikipedia «Авачинская Сопка».
-- 2. «Природный парк «Быстринский»» получил финиш трека «ПП Налычево»
--    (250 км). Парк огромный, честный пин — визит-центр в Эссо
--    (55°55'50"N 158°41'41"E, село Эссо, инфоцентр на Ленина 8).
-- 3. «Каньон Сноубордистов» получил трек «Каньона Крылья Гамулов»
--    (700 км, Шивелуч). Своей открытой координаты у каньона нет —
--    скрываем до ручной проверки (политика «не знаем — не рисуем»).
--
-- Guard ~2 км: ручные правки не перетираются. Идемпотентна.

UPDATE places SET lat = 53.2556, lng = 158.8333, updated_at = NOW()
 WHERE name = 'Авачинский вулкан'
   AND (lat IS NULL OR abs(lat - 53.2556) > 0.02 OR abs(lng - 158.8333) > 0.033);

UPDATE places SET lat = 55.9306, lng = 158.6947, updated_at = NOW()
 WHERE name = 'Природный парк «Быстринский»'
   AND (lat IS NULL OR abs(lat - 55.9306) > 0.02 OR abs(lng - 158.6947) > 0.035);

UPDATE places SET is_visible = FALSE, updated_at = NOW()
 WHERE name = 'Каньон Сноубордистов' AND is_visible = TRUE
   AND abs(lat - 56.5665) < 0.02 AND abs(lng - 161.2147) < 0.035;
