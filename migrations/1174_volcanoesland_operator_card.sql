-- 1174: карточка компании «Край Вулканов» (volcanoesland.ru) с логотипом.
--
-- Владелец 07.10, после ответа оператора «Да давай попробуем»: «Эдуарда заводим
-- сами, но сначала создаём карточку его компании с лого». Логотип прислал сам
-- (файл public/images/volcanoesland/logo.png). Дальше по #2245: привязка
-- Telegram через ссылку из админки, цены и ступени — после подтверждения.
--
-- ── Что это, а чем НЕ является ────────────────────────────────────────────
--
-- Только запись `partners` БЕЗ пользователя (`user_id` пуст): так заведены
-- импортированные операторы (образец — 955, River Tours Kamchatka). Аккаунт
-- человека не создаётся, и согласие на обработку его персональных данных за
-- него не ставится: согласие даёт только он сам, а карточка его личных данных
-- не хранит. Контакты — те, что компания сама публикует на своём сайте:
-- телефон, почта, Telegram, адрес офиса. Имён людей в карточке нет.
--
-- Что карточка НЕ делает:
--   • не подтверждена: `is_verified` остаётся FALSE, отметка проверки платформы
--     не выставляется — мы компанию не проверяли;
--   • туров у неё нет: цены и даты подтверждает оператор (#2245), ступени цены
--     (1173) заводятся после этого;
--   • ставку комиссии не трогает (§7): её назначает владелец, действует
--     умолчание колонки;
--   • реквизитов (ИНН, ОГРН) нет: источника у меня нет, выдумывать их нельзя.
--
-- `is_public = TRUE`: страница /operators/volcanoesland читает только публичные
-- записи, а владелец хочет проверить карточку глазами.
--
-- Логотип: исходник 165x101 с прозрачным фоном и тёмной надписью. На тёмной
-- теме такая надпись пропала бы, поэтому файл лежит на белой подложке с полями
-- (189x125); показывается он на странице в рамке 80x80 с object-contain.
--
-- IDEMPOTENT

BEGIN;

INSERT INTO partners (
  slug, name, company_name, category,
  short_description, description,
  contact, contacts, location, website,
  logo_image, is_public, created_at
)
SELECT
  'volcanoesland',
  'Край Вулканов',
  'ООО «Край Вулканов»',
  'operator',
  'Туроператор из Петропавловска-Камчатского: вулканы, Долина гейзеров, Курильское озеро.',
  'Туры по Камчатке: Плоский Толбачик, Ключевская группа вулканов, Долина гейзеров и кальдера Узон, Курильское озеро, '
    || 'автомобильные туры, трекинги и сплавы. Даты и цены называет оператор.',
  jsonb_build_object('phone', '+79140291112', 'email', 'mail@volcanoesland.ru'),
  jsonb_build_object(
    'phone', '+79140291112',
    'telegram_contact', '@Volcanoesland',
    'email', 'mail@volcanoesland.ru',
    'website', 'https://volcanoesland.ru',
    'address', 'Петропавловск-Камчатский, пр-т 50 лет Октября, 4/2, офис 19'
  ),
  jsonb_build_object('region', 'Камчатский край', 'city', 'Петропавловск-Камчатский'),
  'https://volcanoesland.ru',
  '/images/volcanoesland/logo.png',
  TRUE,
  NOW()
WHERE NOT EXISTS (SELECT 1 FROM partners WHERE slug = 'volcanoesland');

-- Запись могла уже существовать (заведена из админки): логотип ставится только
-- туда, где его нет, чужой выбор не перетирается.
UPDATE partners
   SET logo_image = '/images/volcanoesland/logo.png'
 WHERE slug = 'volcanoesland'
   AND (logo_image IS NULL OR logo_image = '');

-- Исход называется вслух.
DO $$
DECLARE
  v_n int;
BEGIN
  SELECT count(*) INTO v_n FROM partners
   WHERE slug = 'volcanoesland' AND logo_image = '/images/volcanoesland/logo.png';
  IF v_n <> 1 THEN
    RAISE WARNING '[1174] карточка «Край Вулканов» с логотипом: найдено % записей (нужна ровно одна)', v_n;
  END IF;
END $$;

COMMIT;
