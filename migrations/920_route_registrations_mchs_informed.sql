-- 920: «Вернулись» и «сообщили в МЧС о завершении» — разные события.
--
-- Разбор реального журнала МЧС (владелец 28.08, расшифровка видео учёта
-- туристских групп): фактическое возвращение группы и подтверждение
-- территориальному органу о завершении маршрута — два разных поля с разными
-- датами, которые могут расходиться во времени (человек дошёл до дома во
-- вторник, а руководитель позвонил в МЧС только в среду).
--
-- До этой миграции у нас было одно поле `completed_at`, и POST
-- /api/safety/return ставил его же, отвечая туристу «маршрут закрыт» — то
-- есть заявлял то, чего платформа не знает: сообщил ли кто-то в МЧС.
-- `completed_at` остаётся «фактическое возвращение подтверждено» (так его
-- уже читает checkin-watchdog — переименовывать не стали, чтобы не менять
-- смысл поля, которое держит боевую эскалацию). Новое поле — отдельное
-- «сообщили в МЧС», ставится отдельным действием.
--
-- Идемпотентно.

ALTER TABLE route_registrations
  ADD COLUMN IF NOT EXISTS mchs_informed_at TIMESTAMPTZ;
