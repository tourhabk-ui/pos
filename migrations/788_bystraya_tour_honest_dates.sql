-- Migration 788: «Сплав по реке Быстрая» — честные даты и правильная категория
--
-- Тур завела миграция 060 (21.03.2026) вместе с партнёром kamchatka-rafting.
-- При разборе перед продвижением всплыли две вещи, каждая из которых ломает
-- обещание платформы «не врать цифрами»:
--
-- 1. ДАТЫ. Миграция 060 засеяла доступность generate_series по КАЖДОМУ дню
--    с 1 июля по 31 октября — 123 дня по 4 места. Оператор же объявляет
--    сплавы через день и только по 31 августа: 28.07, 30.07, 1.08, 3.08 …
--    31.08 — восемнадцать дат. То есть турист мог забронировать 29 июля,
--    которого у оператора нет, и узнать об этом уже после оплаты.
--    Придуманные даты удаляем — но только те, где никто ещё не бронировал.
--
-- 2. КАТЕГОРИЯ. Тур записан как boat_trip («Морские прогулки»). Это сплав по
--    реке, а не морская прогулка; в фильтре «Сплав» (rafting) его не видно.
--    Для продвижения это значит, что тур не находится там, где его ищут.
--
-- Флаг is_published НЕ трогаем намеренно: публикация коммерческого
-- предложения на живом сайте — решение владельца, а не побочный эффект
-- миграции. Тур останется скрытым, пока его не опубликуют осознанно.
--
-- Идемпотентна: повторный прогон ничего не меняет.

-- ── 1. Категория: сплав по реке, а не морская прогулка ──────────────────────
UPDATE operator_tours t
   SET activity_type = 'rafting',
       updated_at    = NOW()
  FROM partners p
 WHERE p.id = t.operator_id
   AND p.slug = 'kamchatka-rafting'
   AND t.title = 'Однодневная экскурсия СПЛАВ ПО РЕКЕ БЫСТРАЯ'
   AND t.activity_type IS DISTINCT FROM 'rafting';

-- ── 2. Даты: только те, что оператор объявил ────────────────────────────────
-- Сначала убираем выдуманные дни. Условие booked_slots = 0 — страховка:
-- если на такой день кто-то всё же забронировал, строку не трогаем, чтобы
-- бронь не осиротела; такие случаи разбираются вручную.
DELETE FROM tour_availability ta
 USING operator_tours t
  JOIN partners p ON p.id = t.operator_id
 WHERE ta.operator_tour_id = t.id
   AND p.slug = 'kamchatka-rafting'
   AND t.title = 'Однодневная экскурсия СПЛАВ ПО РЕКЕ БЫСТРАЯ'
   AND COALESCE(ta.booked_slots, 0) = 0
   AND ta.date NOT IN (
     DATE '2026-07-28', DATE '2026-07-30',
     DATE '2026-08-01', DATE '2026-08-03', DATE '2026-08-05', DATE '2026-08-07',
     DATE '2026-08-09', DATE '2026-08-11', DATE '2026-08-13', DATE '2026-08-15',
     DATE '2026-08-17', DATE '2026-08-19', DATE '2026-08-21', DATE '2026-08-23',
     DATE '2026-08-25', DATE '2026-08-27', DATE '2026-08-29', DATE '2026-08-31'
   );

-- Затем добираем объявленные даты, если какой-то из них не оказалось.
INSERT INTO tour_availability (id, operator_tour_id, date, available_slots, booked_slots, created_at)
SELECT gen_random_uuid(), t.id, d::date, 4, 0, NOW()
  FROM operator_tours t
  JOIN partners p ON p.id = t.operator_id
  CROSS JOIN (VALUES
    (DATE '2026-07-28'), (DATE '2026-07-30'),
    (DATE '2026-08-01'), (DATE '2026-08-03'), (DATE '2026-08-05'), (DATE '2026-08-07'),
    (DATE '2026-08-09'), (DATE '2026-08-11'), (DATE '2026-08-13'), (DATE '2026-08-15'),
    (DATE '2026-08-17'), (DATE '2026-08-19'), (DATE '2026-08-21'), (DATE '2026-08-23'),
    (DATE '2026-08-25'), (DATE '2026-08-27'), (DATE '2026-08-29'), (DATE '2026-08-31')
  ) AS dates(d)
 WHERE p.slug = 'kamchatka-rafting'
   AND t.title = 'Однодневная экскурсия СПЛАВ ПО РЕКЕ БЫСТРАЯ'
   AND NOT EXISTS (
     SELECT 1 FROM tour_availability ex
      WHERE ex.operator_tour_id = t.id AND ex.date = d::date
   );
