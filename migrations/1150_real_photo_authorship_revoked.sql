-- Migration 1150: подпись «владелец платформы» снята с пачки real-photo
-- Created: 2026-10-03
--
-- Владелец 03.10, увидев в переписи автора у снимков термальных источников:
-- «почему записан владелец платформы, я их точно не загружал».
--
-- Как подпись появилась. Миграция 978 (18.09) поставила author = 'владелец
-- платформы' всем 81 строкам рода real-photo — пачке, залитой 28.03 без
-- автора и источника, — сославшись на слово владельца «это мои фото влиты».
-- Слово было о ДРУГИХ снимках: в те же дни 14-18.09 владелец присылал свои
-- кадры, и они легли миграциями 958-977 родом manual-upload с той же
-- подписью. Автор 978 отнёс фразу к пачке 28.03, а не к сентябрьским
-- загрузкам, и вывод записал как факт. Тот же дефект, что выдуманный
-- рейтинг (§4.0): место, где нельзя было сказать «не знаю», заполнилось
-- догадкой — и догадка оказалась подписью чужих кадров (на части из них
-- водяной знак фотостока, замер владельца 20.09 и 03.10).
--
-- Что делает миграция: снимает подпись ровно там, где её поставила 978 —
-- род real-photo и автор «владелец платформы». Снимки manual-upload с той же
-- подписью не трогаются: там подпись — слово владельца о своих кадрах.
-- Показ рода real-photo выключается в коде (SHOWN_MODELS, lib/images/origin):
-- без автора и источника показывать нельзя — правило то же, что у
-- wikimedia-commons с 18.09. Сами строки остаются: их разбирает аудит
-- снимков (1146), и решение по каждой — за человеком.

BEGIN;

UPDATE ai_route_images
   SET author = NULL
 WHERE model = 'real-photo'
   AND author = 'владелец платформы';

COMMIT;

