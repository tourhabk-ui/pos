-- 978: снимкам рода `real-photo` — авторство владельца.
--
-- ── Чей это снимок ────────────────────────────────────────────────────────
--
-- 18.09 владелец спросил, почему почти все места без фото. Перепись с прода
-- (`GET /api/cron/images-oversize`) ответила числами: снимков 657, карточка
-- показывает 50. Из скрытых 173 — машинные генерации (не показываются по
-- решению владельца 17.07), 331 — скачанное с чужого сайта, а 103 —
-- НАСТОЯЩИЕ фотографии, скрытые лишь потому, что их род не совпал со строкой
-- в фильтре показа: `real-photo` (81) и `wikimedia-commons` (22).
--
-- То же самое перепись назвала ещё 14.09, и тогда исправить было нечем: у
-- скрытых строк пусты `author` и `license`, а без них публиковать чужое
-- нельзя. На прямой вопрос о правах владелец ответил 18.09: «это мои фото
-- влиты».
--
-- Это и есть источник: не догадка по данным, а слово человека, которому
-- снимки принадлежат. Записано здесь дословно, потому что из самих строк
-- происхождение не выводится — они залиты одной пачкой 28.03 без автора.
--
-- ── Что делает миграция ───────────────────────────────────────────────────
--
-- Проставляет `author` там, где его НЕТ, и только у рода `real-photo`.
-- Лицензия не ставится: снимок собственный, лицензировать его платформе не у
-- кого и не за чем, а выдумывать строку лицензии — то же враньё, что
-- выдуманный рейтинг (§4.0).
--
-- `wikimedia-commons` НЕ трогается намеренно. Те 22 снимка чужие; их лицензия
-- требует имени автора, а имени в строках нет. Приписать им владельца значило
-- бы присвоить чужую работу. Пока подписать нечем — показывать нельзя, и это
-- отдельное решение, не сегодняшнее.
--
-- Строки с УЖЕ заполненным автором не трогаются: там кто-то подписан, и
-- перезаписывать его именем владельца нельзя по той же причине.
--
-- Показ включается не здесь, а в коде: `SHOWN_MODELS` в lib/images/origin.ts
-- (единый список вместо тринадцати литералов), сторож
-- tests/unit/photo-shown-single-source.test.ts.
--
-- IDEMPOTENT

BEGIN;

UPDATE ai_route_images
   SET author = 'владелец платформы'
 WHERE model = 'real-photo'
   AND (author IS NULL OR btrim(author) = '');

COMMIT;
