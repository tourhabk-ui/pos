-- Migration 1428: ключи заявок убраны из журнала вызовов MCP
-- Created: 2026-11-12
--
-- Журнал `mcp_tool_calls` пишет «главный» аргумент вызова: имя и — у читающих
-- инструментов — значение (1143). У get_request_status аргумент один, `key`,
-- и значение пряталось только при семи цифрах подряд: три ключа из четырёх
-- ложились в `arg_value` целиком (ключ — 32 знака, колонка — 40). Журнал читают
-- админка (/hub/admin/mcp), разбивка по дням и перепись mcp-census.
--
-- Ключ в открытом виде в базе — второй ключ от заявки: по нему читают её
-- статус и пишут адресату, а со следующим шагом (change_request) — отменяют и
-- переносят. Запись закрыта в lib/mcp/call-reason; здесь — уже записанное.
--
-- Правило то же, что в коде:
--   - у get_request_status — любое значение: его единственный секрет — ключ,
--     и агент, перепутавший поле, присылал его под чужим именем аргумента;
--   - значение аргумента `key` — у любого инструмента;
--   - значение, в котором есть отрезок, похожий на ключ, где бы он ни стоял
--     (в кавычках, с приставкой «key: »): 20+ знаков base64url подряд с цифрой
--     либо любой такой отрезок от 32 знаков (ключ — ровно 32 знака, и без
--     цифр он тоже бывает).
-- Имя аргумента, инструмент, исход и время не трогаются. Повторный прогон
-- строк не находит.

BEGIN;

UPDATE mcp_tool_calls
   SET arg_value = '[скрыто]'
 WHERE arg_value IS NOT NULL
   AND arg_value <> '[скрыто]'
   AND (tool = 'get_request_status'
        OR arg_key = 'key'
        OR arg_value ~ '[A-Za-z0-9_-]{32,}'
        OR EXISTS (
             SELECT 1 FROM regexp_matches(arg_value, '[A-Za-z0-9_-]{20,}', 'g') AS m(run)
              WHERE m.run[1] ~ '[0-9]'));

COMMIT;

