-- 992: «Каньон Сноубордистов» — перевал над Эссо, а не ущелье под городом.
--
-- ── Что было записано ────────────────────────────────────────────────────
--
-- Живой MCP, 20.09:
--
--   Каньон Сноубордистов (долина) [ЗЕЛЁНЫЙ]
--   Опасности: горные реки, пороги.
--   «...узкое ущелье в нижнем течении реки Половинка, расположенное в 30
--   километрах от Петропавловска-Камчатского... отвесными стенами высотой
--   до 40 метров... каньон сформирован потоками воды, пробившими путь через
--   лавовые поля... тропа не требует специального снаряжения, а перепад
--   высот не превышает 100 метров...»
--
-- Ни одно из этих утверждений не относится к месту. Это третий за два дня
-- случай одной болезни, и все три одинаковы по механизму: описание сочинено
-- моделью, а читается как факт. «Каньон Опасный» называл Карымский при
-- координате у Мутновского; «Крылья Гамулов» — Мутновский, будучи на
-- Шивелуче; здесь — река Половинка под Петропавловском вместо Быстринского
-- парка над Эссо, разница около пятисот километров.
--
-- Опаснее прочего последняя фраза выдумки: «тропа не требует специального
-- снаряжения, перепад высот не превышает 100 метров». Настоящий маршрут —
-- радиальный подъём на 850 метров, и парк не пускает туда без разрешения.
-- Сочинённая лёгкость на карточке места — не неопрятность, а приглашение
-- выйти неподготовленным.
--
-- ── Откуда взята правда ──────────────────────────────────────────────────
--
-- Сообщение владельца 20.09 целиком: перевал в Быстринском природном парке
-- (входит в парк «Вулканы Камчатки») над селом Эссо; название закрепилось
-- из-за фрирайда; виды на Срединный и Козыревский хребты, вулкан Ичинский,
-- в ясную погоду — Ключевскую группу, долину Быстрой и само Эссо; домик
-- «Сноубордистов» с печным отоплением, выше — домик «Перевальный»; посещение
-- по разрешению дирекции парка с рекреационным сбором; дирекция закрывает
-- маршрут по погоде; возможны встречи с медведями; высота перевала около
-- 1200 м, домик по паспорту маршрута — около 1350 м.
--
-- Чего в описании НЕТ и почему: длины маршрута, точки старта, запрета идти
-- одному и возрастной границы. Это инструкция, а инструкция — свойство
-- МАРШРУТА (§10), не места (§9). Маршрут у нас есть отдельной записью
-- (875fae03, связан с этим местом миграцией 653), и правится он отдельно.
--
-- ── Координата здесь НЕ трогается ────────────────────────────────────────
--
-- Она правится своим путём — POST /api/cron/place-coords, где обязателен
-- источник на партию и причина на каждую правку, старая координата
-- возвращается в ответе и служит откатом, а сухой прогон идёт по умолчанию
-- (§4.1). Маркер на сухой прогон лежит тем же PR. Двигать координату
-- миграцией значило бы обойти ровно тот порядок, который заведён, чтобы
-- правку можно было отменить.
--
-- IDEMPOTENT

BEGIN;

-- ── 1. Род места: это перевал, а не долина ───────────────────────────────
--
-- Слово «Перевал» у слага уже есть (lib/places/location-types.ts), и лист
-- карты его теперь знает — иначе на карточке стояло бы английское «pass».
UPDATE places
   SET location_type = 'pass',
       updated_at    = NOW()
 WHERE id::text = 'abf90315-7a15-4fda-bb08-632b0f5e744b'
   AND location_type IS DISTINCT FROM 'pass';

-- ── 2. Описание — из сообщения владельца, и только из него ───────────────
UPDATE places
   SET description = 'Каньон Сноубордистов — перевал в Быстринском природном парке, входящем в парк «Вулканы Камчатки», над селом Эссо. Название закрепилось из-за фрирайда: здешние склоны катают вне трасс. С перевала видны Срединный и Козыревский хребты, вулкан Ичинский — высшая точка Срединного хребта, долина реки Быстрая и само Эссо; в ясную погоду — Ключевская группа вулканов. На перевале стоит домик «Сноубордистов» с печным отоплением: в нём пережидают погоду и ночуют, выше по пути — домик «Перевальный». Сам перевал лежит примерно на 1200 метрах, домик по паспорту маршрута — на 1350. Посещение — по разрешению дирекции парка «Вулканы Камчатки» и с оплатой рекреационного сбора; при плохой погоде дирекция маршрут закрывает.',
       updated_at  = NOW()
 WHERE id::text = 'abf90315-7a15-4fda-bb08-632b0f5e744b'
   AND description IS DISTINCT FROM 'Каньон Сноубордистов — перевал в Быстринском природном парке, входящем в парк «Вулканы Камчатки», над селом Эссо. Название закрепилось из-за фрирайда: здешние склоны катают вне трасс. С перевала видны Срединный и Козыревский хребты, вулкан Ичинский — высшая точка Срединного хребта, долина реки Быстрая и само Эссо; в ясную погоду — Ключевская группа вулканов. На перевале стоит домик «Сноубордистов» с печным отоплением: в нём пережидают погоду и ночуют, выше по пути — домик «Перевальный». Сам перевал лежит примерно на 1200 метрах, домик по паспорту маршрута — на 1350. Посещение — по разрешению дирекции парка «Вулканы Камчатки» и с оплатой рекреационного сбора; при плохой погоде дирекция маршрут закрывает.';

-- ── 3. Опасности: реки и пороги — из той же выдумки ──────────────────────
--
-- `water` и `rapids` описывали ущелье с потоком, которого здесь нет. На их
-- место идут ровно те две, что названы в источнике: медведи и резкая смена
-- погоды (по ней парк и закрывает маршрут). Ни «высота», ни «нет тропы» не
-- ставятся: источник о них не говорит, а выдуманная опасность на safety-поле
-- ничем не лучше выдуманной лёгкости.
UPDATE location_safety_profile
   SET hazard_types = ARRAY['bears', 'weather']::text[],
       updated_at   = NOW()
 WHERE agent_route_id = (SELECT ark_id FROM places WHERE id::text = 'abf90315-7a15-4fda-bb08-632b0f5e744b')
   AND (SELECT ark_id FROM places WHERE id::text = 'abf90315-7a15-4fda-bb08-632b0f5e744b') IS NOT NULL
   AND hazard_types IS DISTINCT FROM ARRAY['bears', 'weather']::text[];

-- ── Исход называется вслух ───────────────────────────────────────────────
DO $$
DECLARE
  v_ark    uuid;
  v_type   text;
  v_descr  text;
  v_haz    text[];
BEGIN
  SELECT ark_id, location_type, description
    INTO v_ark, v_type, v_descr
    FROM places WHERE id::text = 'abf90315-7a15-4fda-bb08-632b0f5e744b';

  IF v_type IS NULL THEN
    RAISE WARNING '[992] записи «Каньон Сноубордистов» по этому id нет — ничего не исправлено';
    RETURN;
  END IF;

  IF v_type IS DISTINCT FROM 'pass' THEN
    RAISE WARNING '[992] род остался «%» вместо «pass»', v_type;
  END IF;

  IF v_descr LIKE '%Половинка%' OR v_descr LIKE '%Петропавловск%' THEN
    RAISE WARNING '[992] в описании всё ещё сочинённая река или город — правка не легла';
  END IF;

  IF v_ark IS NULL THEN
    RAISE WARNING '[992] у места нет ark_id — профиль безопасности не связан, опасности не тронуты';
  ELSE
    SELECT hazard_types INTO v_haz FROM location_safety_profile WHERE agent_route_id = v_ark;
    IF v_haz IS NULL THEN
      RAISE WARNING '[992] профиля безопасности у места нет — опасности задать негде';
    ELSIF 'water' = ANY(v_haz) OR 'rapids' = ANY(v_haz) THEN
      RAISE WARNING '[992] опасности всё ещё от сочинённого ущелья: %', v_haz;
    END IF;
  END IF;

  RAISE NOTICE '[992] дальше — координата: сухой прогон place-coords (маркер тем же PR), потом решение владельца.';
END $$;

COMMIT;
