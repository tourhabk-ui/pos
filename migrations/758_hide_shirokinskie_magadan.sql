-- 758: Скрыть «Широкинские источники» — это не Камчатка (решение владельца 2026-07-18).
--
-- Владелец: «Широкинские источники нужно удалить это ближе магадан».
-- Реальные Широкинские горячие источники находятся в Магаданской области
-- (бассейн реки Широкая). Описание из миграции 090 («крайний север
-- Камчатки») — AI-сгенерированная ошибка. По платформенной практике не
-- удаляем, а скрываем (is_visible = FALSE) и отвязываем от маршрутов —
-- обратимо и не ломает FK.
--
-- Идемпотентно: повторный прогон ничего не меняет.

BEGIN;

-- 1. Отвязать место от маршрутов (иначе останется невидимым waypoint'ом)
DELETE FROM route_waypoints
WHERE place_id IN (
  SELECT id FROM places WHERE name ILIKE '%Широкинские%'
);

-- 2. Скрыть само место
UPDATE places
SET is_visible = FALSE, updated_at = NOW()
WHERE name ILIKE '%Широкинские%'
  AND is_visible = TRUE;

-- 3. Скрыть маршруты-тёзки, если такие есть (маршрут к не-камчатской точке)
UPDATE kamchatka_routes
SET is_visible = FALSE, updated_at = NOW()
WHERE title ILIKE '%Широкинские%'
  AND is_visible = TRUE;

COMMIT;
