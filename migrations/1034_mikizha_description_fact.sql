-- 1034: «Озеро Микижа» — описание из фактов вместо сочинённого.
--
-- ── Повод (26.09) ──────────────────────────────────────────────────────────
--
-- MCP get_place_info отдавал об озере:
--
--   «...километр в обхвате, но дно уходит круто, вода стоит плотная,
--    темно-изумрудная... микижа здесь ходит косяками... тишина стоит
--    густая... Дорога от города — два часа тряски по грейдеру...»
--
-- Владелец, посмотрев ответ вместе со своими снимками: «два часа тряски по
-- грейдеру — сюда асфальт, на берегу база отдыха Голубая лагуна». Текст
-- сочинён тем же способом, что Ключевская (987) и Авачинский (детектор
-- голоса, lib/places/description-voice): модель просили писать «как будто вернулась оттуда», а
-- данных о дороге, глубине и рыбе у неё не было.
--
-- Для туриста это не слог, а неверная логистика: «два часа грейдера» — это
-- другой транспорт, другое время и другой риск, чем асфальт до базы.
--
-- ── Из чего новый текст ───────────────────────────────────────────────────
--
--   - асфальтовая дорога, база «Голубая лагуна» на берегу — слово владельца;
--   - сопки вокруг, берёзовый берег, причал с лодками и водными велосипедами,
--     бассейн базы, галечный спуск к воде — снимки владельца того же дня
--     (миграция 1033).
--
-- Не вошло то, чему источника нет: размер, глубина, цвет воды, рыба, время в
-- пути. Название озера рыбу не доказывает. Пустое место в тексте честнее
-- придуманного (§4.0).
--
-- База упомянута как ориентир на берегу, без цены и ссылки: карточка места —
-- не витрина (§9).
--
-- ── Границы правки ─────────────────────────────────────────────────────────
--
-- Правится только запись, где лежит ровно тот сочинённый текст — отбор по его
-- началу. Успел кто-то поправить раньше — миграция не делает ничего.
--
-- Идемпотентна.

WITH old AS (
  SELECT id, LENGTH(description) AS prev_chars
    FROM places
   WHERE name = 'Озеро Микижа'
     AND description LIKE 'Озеро Микижа — километр в обхвате%'
),
upd AS (
  UPDATE places p
     SET description = 'Озеро в долине среди сопок, берега заросли берёзовым лесом. К озеру ведёт асфальтированная дорога. На берегу стоит база отдыха «Голубая лагуна» с причалом и бассейном; у причала — лодки и водные велосипеды. К воде ведёт галечный спуск.',
         updated_at = NOW()
    FROM old
   WHERE p.id::text = old.id::text
  RETURNING p.ark_id, p.name, p.description, old.prev_chars
)
INSERT INTO description_provenance
  (entity_id, entity_kind, entity_title, written_by, facts_given, facts_count,
   chars, previous_chars)
SELECT
  upd.ark_id,
  'place',
  upd.name,
  'owner-decision',
  '["асфальтированная дорога (слово владельца)","база отдыха «Голубая лагуна» на берегу (слово владельца)","сопки и берёзовый берег (снимки владельца 26.09)","причал с лодками и водными велосипедами (снимки владельца 26.09)","галечный спуск к воде (снимки владельца 26.09)"]'::jsonb,
  5,
  LENGTH(upd.description),
  upd.prev_chars
FROM upd
WHERE upd.ark_id IS NOT NULL;
