-- 767: Убрать утечку атрибуции стороннего источника «ИдиЛесом» из контента.
--
-- Баг (кейс владельца «Бухта Асача», /routes/604f8c47-…): при скрейпе
-- idilesom.com в description/title/name попадала реклама конкурента —
-- «Маршрут и все подробности на ИдиЛесом», суффикс « — ИдиЛесом», голое
-- упоминание. Турист на карточке маршрута/места видел это как факт о месте.
--
-- Код починен в этом же PR: детерминированный lib/text/source-attribution.ts
-- чистит на read-time (карточка), write-time (импортёр idilesom) и в стороже
-- постов канала (post-validation). Здесь — разовый ремонт уже испорченных
-- строк, чтобы источник-истины был чист и для AI-промпта Кузьмича, и для SEO.
--
-- Пишем в master-таблицы напрямую (§4.1), не в VIEW agent_route_knowledge.
-- Каждый UPDATE идемпотентен: WHERE ~* по имени источника — повторный прогон
-- не найдёт строк. Порядок regexp_replace повторяет порядок правил в TS.

-- ── Общая чистка описаний ────────────────────────────────────────────────────
-- Вложенные regexp_replace (снаружи внутрь читается как последовательность):
--   1) хвост «(все )подробности на ИдиЛесом(.)» → убрать
--   2) хвост «на ИдиЛесом» → убрать
--   3) сепаратор «— | · :» + имя → убрать
--   4) любое голое упоминание → убрать
--   5) схлопнуть пробелы и пробел перед пунктуацией, снять двойные точки

UPDATE kamchatka_routes
SET description = NULLIF(trim(regexp_replace(regexp_replace(regexp_replace(regexp_replace(regexp_replace(regexp_replace(regexp_replace(
      description,
      '[.,;!?]?\s*маршрут\s+и\s+вс[её]\s+подробност[а-яё]*\s+на\s+(иди\s*лесом|идилесом)\.?', '.', 'gi'),
      '(вс[её]\s+)?подробност[а-яё]*\s+на\s+(иди\s*лесом|идилесом)\.?', '', 'gi'),
      '\s*на\s+(иди\s*лесом|идилесом)', '', 'gi'),
      '\s*[—\-|·:]\s*(иди\s*лесом|идилесом)', '', 'gi'),
      '(иди\s*лесом|идилесом)', '', 'gi'),
      '\s+([.,;:!?])', '\1', 'g'),
      '\s{2,}', ' ', 'g')), '')
WHERE description ~* '(иди\s*лесом|идилесом)';

