-- Координата «Дранкинских термальных источников» — от владельца
-- (Артём Клоков, 2026-07-20): 56.9169, 162.0553. Карагинский район,
-- побережье у с. Дранка — сходится с названием.
--
-- Инвентаризация (#594, run 17) нашла их наложенными в одну точку с
-- «Кордоном озеро Паланское» (0.00 км) — след сломанного геокодинга.
-- Разводим: Дранкинские встают на свою верифицированную точку, Кордон
-- остаётся на месте. Обновляем ТОЛЬКО если текущая координата дальше ~2 км
-- от целевой — ручные правки через админку не перетираем. Идемпотентна.

UPDATE places
   SET lat = 56.9169, lng = 162.0553, updated_at = NOW()
 WHERE name = 'Дранкинские термальные источники'
   AND (lat IS NULL OR abs(lat - 56.9169) > 0.02 OR abs(lng - 162.0553) > 0.035);
