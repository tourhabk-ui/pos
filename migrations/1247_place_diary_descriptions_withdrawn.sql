-- 1247: описания-дневники — с карточек в архивную колонку, до переписи по
--       источникам (решение владельца 14.10: «2 да»).
-- Created: 2026-10-14
--
-- ── Почему ────────────────────────────────────────────────────────────────
--
-- Перепись голоса описаний (GET /api/cron/place-description-geo, блок voice,
-- проба 850): 111 из 382 видимых мест описаны путевой заметкой от первого
-- лица — «я стою у подножия», «идёшь не меньше недели», «вчера поднялся».
-- Такой текст читается как наблюдение о сегодняшнем состоянии места, а
-- наблюдения не было: на карточке, по которой решают, идти ли, это
-- выдуманный статус. Агентам (Кузьмич, MCP) дневники уже не отдаются
-- (lib/places/description-voice → describeForAgent), а людям их показывали
-- больше двадцати поверхностей: карточка, мета и JSON-LD, GPX и PDF, лист и
-- попап карты, каталог, главная, подборки, посты канала, подсказка Кузьмичу
-- в каждом чате.
--
-- Владелец на вопрос «пока скрыть с карточки и переписывать по источникам
-- партиями, как Вачкажец?» ответил «да».
--
-- ── Как — прячем, не удаляем ──────────────────────────────────────────────
--
-- Текст переезжает в places.description_withdrawn (с причиной и временем), а
-- description становится NULL — и все поверхности перестают его показывать
-- разом, без правки каждой. Карточка говорит словами, что описание убрано и
-- переписывается (PlaceDescription). Переписанное по источникам ложится в
-- description как обычно; архивная колонка остаётся историей.
--
-- Очередь моделей пустое описание не заполняет: писатель enrich-routes и
-- enrich-places выводят такие места из отбора — иначе дыру закрыл бы текст
-- по одному названию, и место выглядело бы переписанным.
--
-- ── Какие места — поимённо ────────────────────────────────────────────────
--
-- Список — ровно 111 мест, которые перепись назвала дневником (то же
-- правило descriptionVoice, а не его копия на SQL). Сторож строки — начало
-- описания (60 знаков, как в переписи): если текст с тех пор правили, место
-- не трогается. Повтор — no-op: перенесённое уже пусто.
--
-- IDEMPOTENT

