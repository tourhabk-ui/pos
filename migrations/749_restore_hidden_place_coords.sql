-- 749_restore_hidden_place_coords.sql
--
-- Ремонт данных (run 6/7) скрыл 10 мест с фейковыми координатами из
-- bogus-кластеров («координата не восстановилась — скрыто до ручной проверки»).
-- Владелец поручил взять координаты проблемных мест из открытых источников
-- (2ГИС/OSM/официальные). Восстановлены ТОЛЬКО места с подтверждённым
-- источником; остальные остаются скрытыми до точных данных:
--   БЕЗ координат: Долина изваяний (Ключевской кластер, точных нет),
--   Африканский терм. ист., Сторожевские терм. ист. (Щапинский грабен,
--   Кроноцкий — без чисел), Говенские терм. ист. (лагуна Тинтикун — без
--   чисел), Скала Дырявый камень (в открытых источниках — только башкирский
--   тёзка), Гора Кэнгынэй, Водопад Фата Невесты (каскад р. Тахколоч —
--   вероятный дубль «Водопада, горный массив Вачкажец», ждёт дедупа).
--
-- Обновляем ТОЛЬКО скрытые ремонтом строки (is_visible = FALSE) — ручные
-- правки через админку не перетираются. Идемпотентна.

-- Водопад горного массива Вачкажец — каскады р. Тахколоч.
-- Источник: 53°03'40" N 157°55'40" E (массив; nast.travel, visitkamchatka.ru).
-- Точность — долина массива (~1-2 км), тропа к каскадам одна.
UPDATE places
   SET lat = 53.0611, lng = 157.9278, is_visible = TRUE, updated_at = NOW()
 WHERE name = 'Водопад, горный массив Вачкажец' AND is_visible = FALSE;

-- Сосновские (Киселевские) водопады — р. Водопадная, ~40 км от Петропавловска.
-- Источник: 53°04' N 158°00' E (ru.wikivoyage «Природные памятники России/
-- Камчатский край», rutraveller). Точность до минуты (~1.5 км).
UPDATE places
   SET lat = 53.0667, lng = 158.0000, is_visible = TRUE, updated_at = NOW()
 WHERE name = 'Сосновские (Киселевские) водопады' AND is_visible = FALSE;

-- Каменные поленницы — памятник природы «Каменные поленницы в системе конусов
-- Плотина вулкана Безымянного». Источник: официальная карточка ООПТ,
-- kamchatsky-krai.ru: 55°59'42" N 160°37'20" E.
UPDATE places
   SET lat = 55.9950, lng = 160.6222, is_visible = TRUE, updated_at = NOW()
 WHERE name = 'Каменные поленницы' AND is_visible = FALSE;
