-- 973_nikolskaya_safety_profile_not_volcano.sql
--
-- Продолжение 972. Та миграция сняла с Сопки Никольской бейдж «ВУЛКАН»,
-- но опасности живут в другой таблице, и правка была половинчатой.
--
-- ── Что видит турист СЕЙЧАС ──────────────────────────────────────────────
--
-- Запрос к живому MCP платформы (get_guardian_context, 15.09) про стометровый
-- холм в центре Петропавловска, где городской парк и чугунные пушки обороны
-- 1854 года:
--
--   Сопка Никольская [КРАСНЫЙ]
--   Опасности: лавины, камнепад, термальные поля, высотная болезнь.
--
-- Высотная болезнь на ста метрах. Лавины и термальные поля в городском парке.
-- Это не «данных не хватает» — это четыре конкретных утверждения, каждое из
-- которых ложно, на платформе, которая существует ради безопасности.
--
-- ── Откуда они взялись ───────────────────────────────────────────────────
--
-- Миграция 070 заполняла location_safety_profile ПАКЕТНО ПО ТИПУ МЕСТА:
--
--   CASE WHEN location_type = 'volcano'
--        THEN ARRAY['avalanche','rockfall','thermal','altitude']
--
-- и там же difficulty_level = 4 для вулканов. Для Ключевской это верно. А
-- Никольская числилась вулканом (исправлено 972) — и получила набор
-- настоящего вулкана целиком. Один неверный тип породил четыре неверных
-- факта о безопасности: шаблон по типу разносит ошибку типа дальше, чем
-- видно с места правки.
--
-- ── Почему NULL, а не пустой список ──────────────────────────────────────
--
-- Пустой массив читается как «проверено, опасностей нет» — это утверждение,
-- и делать его мы права не имеем: обследования не было. NULL — «не знаю»,
-- третий исход по §4.0. Разница не косметическая: «нет опасностей» на
-- незнакомом месте — то же враньё, только с другим знаком.
--
-- То же с difficulty_level: четвёрка досталась от шаблона вулкана, а своей
-- оценки сложности у городской тропы к памятнику у нас нет. Ставить единицу
-- значило бы заменить чужую выдумку своей.
--
-- ── Чего эта миграция НЕ делает ──────────────────────────────────────────
--
-- 1. НЕ трогает [КРАСНЫЙ]. Это не поле места: safety-ingest красит в красный
--    ВСЕ места зоны, поймавшей алерт severity >= 2. Зона Никольской —
--    avachinsky, а в её алертах разлив рек, Вилючинский перевал за 60 км и
--    землетрясения за 195-244 км. Региональная тревога на городском парке —
--    вопрос устройства зон, он шире одной записи и решается владельцем
--    (в том же файле 15.09 уже правили соседний симптом — порядок алертов,
--    жалоба про «Раздолье»).
-- 2. НЕ трогает terrain_type и capacity_per_day. 'mountain' для сопки не
--    ложь, а вместимость 30/день хоть и мала для городского парка, но
--    участвует в пороге красного/жёлтого: менять её без замера посещаемости
--    значит выдумать другое число вместо этого.
-- 3. НЕ трогает остальные записи раздела. Тот же шаблон 070 лежит на всех
--    118, и у настоящих вулканов он ВЕРЕН. Перепись раздела идёт отдельно
--    (prod-check run 53); правки — поимённо, по улике.
--
-- ── Безопасность правки ──────────────────────────────────────────────────
--
-- Правим ТОЛЬКО если в hazard_types по-прежнему лежит ровно шаблон вулкана
-- из 070. Если кто-то уже разобрал профиль руками — не трогаем: своя правка
-- поверх чужой работы хуже, чем её отсутствие.
--
-- Профиль связан с местом через places.ark_id, а не через places.id —
-- ark_id берём подзапросом, чтобы не переписывать сюда ещё один uuid
-- вручную (урок семи перепутанных volcanoNumber в gvp-confirmed-pairs).
--
-- Идемпотентно: повторный прогон видит NULL вместо шаблона и выходит.

DO $$
DECLARE
  pid      text := '51598b80-6b92-48d9-beb4-019f824524c9';
  pname    text;
  park     uuid;
  cur      text[];
  tmpl     text[] := ARRAY['avalanche','rockfall','thermal','altitude']::text[];
BEGIN
  SELECT name, ark_id INTO pname, park FROM places WHERE id = pid;

  IF pname IS NULL THEN
    RAISE NOTICE '[973] % — записи нет в places, делать нечего', pid;
    RETURN;
  END IF;

  IF park IS NULL THEN
    RAISE NOTICE '[973] % (%) — ark_id пуст, профиль не связать', pname, pid;
    RETURN;
  END IF;

  SELECT hazard_types INTO cur
    FROM location_safety_profile WHERE agent_route_id = park;

  IF NOT FOUND THEN
    RAISE NOTICE '[973] % — профиля безопасности нет, делать нечего', pname;
    RETURN;
  END IF;

  IF cur IS DISTINCT FROM tmpl THEN
    RAISE NOTICE '[973] % — hazard_types уже не шаблон вулкана (%), не трогаем',
      pname, COALESCE(array_to_string(cur, ','), 'NULL');
    RETURN;
  END IF;

  UPDATE location_safety_profile
     SET hazard_types     = NULL,
         difficulty_level = NULL
   WHERE agent_route_id = park;

  RAISE NOTICE '[973] % — сняты опасности шаблона вулкана (лавины/камнепад/термальные/высота) и сложность 4', pname;
END $$;

INSERT INTO _migrations (name)
VALUES ('973_nikolskaya_safety_profile_not_volcano.sql')
ON CONFLICT (name) DO NOTHING;
