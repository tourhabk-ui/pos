-- 1265: Снимки «Края Вулканов» сняты с карточек мест до согласия партнёра
-- Created: 2026-10-15
--
-- ── Почему ────────────────────────────────────────────────────────────────
--
-- 14.10 кадры с туров «Края Вулканов» легли на карточки мест: парк
-- «Ключевской» национального парка «Вулканы Камчатки» (1250), Южно-Камчатский
-- заказник, Курильское озеро и Кутхины Баты (1252) — с подписью «с
-- разрешения туроператора». Разрешение было другим: слово владельца 08.10
-- «публикуй фото и туры» (1177) — о турах партнёра на его же карточках,
-- права на снимки у оператора.
--
-- 15.10 владелец на тот же вопрос о «Местечке Камчатка», у которого было даже
-- прямое «ДА» на туры (1217), ответил: «пока нет получим согласе востановим»
-- (1263). У «Края Вулканов» согласия на карточки мест нет тем более, и
-- подпись «с разрешения туроператора» под таким кадром утверждает то, чего
-- не было. Решено тем же порядком, по карт-бланшу владельца 15.10 («ты уже
-- лучше меня всё знаешь»).
--
-- ── Как спрятано ──────────────────────────────────────────────────────────
--
-- Тем же механизмом, что 1263, — ничего не удаляется:
--   главный кадр (ai_route_images) — род `partner-no-consent`
--     (lib/images/origin.ts): карточка его не показывает, раздача по прямому
--     адресу не отдаёт, сборщик Commons не перезаписывает;
--   галерея (place_gallery_photos) — `hidden_reason`: карточка, фото путевых
--     точек маршрута и раздача кадра читают только строки без причины.
-- Отбор — по автору «Край Вулканов»: так подписан каждый их кадр в 1250 и
-- 1252. Снимки туров (operator_tours.photos) и карточка оператора в этих
-- таблицах не лежат и остаются как есть.
--
-- Что остаётся на карточках. Заказнику — снимки владельца из его галереи
-- (958: Курильское озеро, Кутхины Баты; карточка берёт первый оставшийся
-- кадр главным). Курильскому озеру и Кутхиным Батам — их главные кадры
-- владельца. Парк «Ключевской» остаётся без снимка: своих кадров Ключевской
-- группы у платформы нет, кадры «Местечка» там спрятаны 1263, — карточка
-- показывает заставку по типу места.
--
-- Главный кадр статьи летописи «Южно-Камчатский заказник» заменён снимком
-- владельца — это код (lib/chronicle/articles.ts), не эта миграция.
--
-- IDEMPOTENT: каждая правка — только поверх ещё не спрятанного.

BEGIN;

UPDATE place_gallery_photos
   SET hidden_reason = 'снимок партнёра «Край Вулканов»: слово владельца «публикуй фото и туры» (1177) — о его турах; согласия на показ на карточках мест пока нет (15.10) — вернётся вместе с согласием'
 WHERE author = 'Край Вулканов'
   AND hidden_reason IS NULL;

UPDATE ai_route_images
   SET model = 'partner-no-consent'
 WHERE author = 'Край Вулканов'
   AND model = 'manual-upload';

-- ── Исход называется вслух ────────────────────────────────────────────────
DO $$
DECLARE
  v_gallery_hidden int;
  v_gallery_shown int;
  v_hero_hidden int;
  v_hero_shown int;
BEGIN
  SELECT count(*) FILTER (WHERE hidden_reason IS NOT NULL),
         count(*) FILTER (WHERE hidden_reason IS NULL)
    INTO v_gallery_hidden, v_gallery_shown
    FROM place_gallery_photos WHERE author = 'Край Вулканов';
  SELECT count(*) FILTER (WHERE model = 'partner-no-consent'),
         count(*) FILTER (WHERE model IN ('wikimedia', 'manual-upload'))
    INTO v_hero_hidden, v_hero_shown
    FROM ai_route_images WHERE author = 'Край Вулканов';

  IF v_gallery_shown > 0 OR v_hero_shown > 0 THEN
    RAISE WARNING '[1265] кадры «Край Вулканов» ещё показываются: галерея %, главные %', v_gallery_shown, v_hero_shown;
  END IF;
  IF v_gallery_hidden + v_hero_hidden = 0 THEN
    RAISE WARNING '[1265] не спрятано ни одного кадра «Край Вулканов» — их нет в базе или подпись другая?';
  END IF;
END $$;

COMMIT;

