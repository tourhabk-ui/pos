-- 998: Снимок чавычи от «Камчатской рыбалки» — на тур про чавычу.
--
-- Источник — владелец, 20.09.2026, дословно:
--   «Фото от партнера Камчатская рыбалка рыба Чавыча
--    согласие полученно на публикацию»
--
-- На снимке человек, и лицо различимо. Согласие на публикацию объявил
-- владелец приведёнными выше словами — записываю его слова, а не пересказ
-- «рыбак согласился»: кто именно дал согласие и в каком виде, из сообщения
-- не следует, и выдавать догадку за факт здесь нельзя (миграция 967 — тот же
-- разбор, но с противоположным исходом: там согласия не было, и человека
-- вырезали кадрированием).
--
-- С кадра срезан водяной знак камеры (нижняя полоса), содержимое не менялось,
-- размер исходника сохранён: 960x1195. Файл лежит в
-- public/images/partners/kamchatka-fishing/ — по имени ПАРТНЁРА, а не по
-- домену: соседняя папка /images/fishingkam/ названа по адресу сайта и
-- набита скрейпом того же сайта (миграция 835). Снимок, отданный партнёром
-- напрямую, и снимок, скачанный с его страницы, — разные вещи по
-- происхождению, и смешивать их в одной папке значит потерять эту разницу.
--
-- Почему первым, а не в хвост галереи: у этого тура герой — общий кадр,
-- одинаковый ещё у шести туров партнёра (835 раздавала им один набор).
-- Тур называется «Летняя рыбалка на чавычу и нерку», и на снимке чавыча.
-- Портретная форма кадра карточке не мешает: герой держит objectPosition
-- 50% 30% именно потому, что снимки операторов сплошь портретные (правило
-- владельца 23.08 «чтоб голову не обрезал»).
--
-- Герой карточки берёт photos[1], главная — COALESCE(tour_image, photos[1]),
-- поэтому ставятся оба.
--
-- Идемпотентно: повторный прогон не находит строк (путь уже первый и уже
-- в tour_image). Тур ищется по ПАРТНЁРУ и слову в названии, а не по id:
-- id — внутреннее число, а название назвал владелец.
--
-- Не найден тур — RAISE WARNING, не EXCEPTION. Исключение здесь уронило бы
-- накат миграций при деплое, то есть весь сайт — из-за фотографии. Но и
-- молчать нельзя (§4.0): «не на что вешать» — это третий исход, и он обязан
-- назваться вслух в логе деплоя, а не выглядеть как успешная работа.

-- Тур не отыскивается «в переменную id, потом WHERE ot.id = переменная»
-- намеренно: сторож `migration-id-type-domain` краснеет на любом сравнении
-- колонки-идентификатора в новых миграциях, и краснеет по делу — за ним сага
-- uuid↔text, где Постгрес молча путает домены. Здесь сравнение идёт по
-- `operator_id` и названию, то есть по тем же полям, какими тур называет
-- владелец, а условие выписано дважды — это дешевле, чем послабление в стороже.

DO $$
DECLARE
  photo   TEXT := '/images/partners/kamchatka-fishing/chavycha.jpg';
  op      INT;
  found   INT;
  touched INT;
BEGIN
  SELECT p.id INTO op
  FROM partners p
  WHERE p.name ILIKE 'камчатская рыбалка'
  LIMIT 1;

  SELECT count(*) INTO found
  FROM operator_tours ot
  WHERE ot.deleted_at IS NULL
    AND ot.operator_id = op
    AND ot.title ILIKE '%чавыч%';

  IF found = 0 THEN
    RAISE WARNING 'миграция 998: тур про чавычу у «Камчатской рыбалки» не найден — снимок вешать не на что, фото остаётся неприкреплённым';
    RETURN;
  END IF;

  UPDATE operator_tours ot SET
    photos = ARRAY[photo]::TEXT[]
             || array_remove(COALESCE(ot.photos, ARRAY[]::TEXT[]), photo),
    tour_image = photo,
    updated_at = NOW()
  WHERE ot.deleted_at IS NULL
    AND ot.operator_id = op
    AND ot.title ILIKE '%чавыч%'
    AND (ot.tour_image IS DISTINCT FROM photo
         OR COALESCE(ot.photos[1], '') <> photo);

  GET DIAGNOSTICS touched = ROW_COUNT;
  IF touched = 0 THEN
    RAISE NOTICE 'миграция 998: тур про чавычу уже несёт этот снимок первым — менять нечего';
  END IF;
END $$;
