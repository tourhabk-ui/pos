-- 1124: закрытие маршрутов парка — свой род тревоги с привязкой к парку (#2133).
--
-- 30.09 «приостановлено посещение маршрутов в природных парках „Налычево“ и
-- „Южно-Камчатский“» из-за циклона не дошло до статуса ни одного места:
-- get_guardian_context("Природный парк Налычево") отвечал [ЗЕЛЁНЫЙ]. У
-- классификатора не было ветки для закрытия парка, а у тревоги — способа
-- сказать, КАКОЙ парк закрыт: зона «avachinsky» — это и Налычево, и город.
--
-- 1. external_alerts.affected_parks — слаги парков (parks.slug), названных в
--    тексте. Пусто/NULL — парк не установлен, и такая тревога никого не красит
--    (тот же принцип, что у дорожных: «не установлено» ≠ «везде»).
-- 2. Южно-Камчатский природный парк — в справочник. Без строки здесь его
--    закрытие нечем сопоставить с маршрутами (kamchatka_routes.park_name).
--    Телефон, сайт и адрес разрешения не заполняются: проверенного источника
--    для них в этой правке нет, а выдуманный телефон хуже пустого (§4.0).
--    Поэтому is_active = false: строка служит привязке тревог, а публичной
--    страницы /park/yuzhno-kamchatsky без контактов не появляется. Привязка
--    тревог is_active не смотрит — закрытый парк закрыт и без страницы.
--
-- Идемпотентна.

BEGIN;

ALTER TABLE external_alerts ADD COLUMN IF NOT EXISTS affected_parks TEXT[];

INSERT INTO parks (slug, display_name, description, search_term, is_active)
VALUES (
  'yuzhno-kamchatsky',
  'Южно-Камчатский природный парк',
  'Природный парк на юге Камчатки, входит в объект Всемирного наследия ЮНЕСКО «Вулканы Камчатки».',
  'Южно-Камчат',
  false
)
ON CONFLICT (slug) DO NOTHING;

COMMIT;

