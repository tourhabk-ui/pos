  v_place record;
  v_profile text;
  v_regime int;
  v_free int;
  v_texts int;
  v_heroes int;
  v_gallery int;
  v_park record;
BEGIN
  SELECT name, location_type, lat, lng, eco_zone, description, kuzmich_review,
         essence IS NOT NULL AS has_essence, access_info IS NOT NULL AS has_access
    INTO v_place
    FROM places WHERE id::text = 'ce59fcc5-0e85-487c-9acf-5cbbb46d2e1e';
  SELECT lsp.profile_source INTO v_profile
    FROM location_safety_profile lsp JOIN places p ON lsp.agent_route_id = p.ark_id
   WHERE p.id::text = 'ce59fcc5-0e85-487c-9acf-5cbbb46d2e1e';
  SELECT count(*) INTO v_regime FROM places
   WHERE eco_zone = 'natural_park' AND eco_permit_required
     AND eco_rules LIKE '%без разрешения — только территория Авачинского перевала, зона свободного посещения%';
  SELECT count(*) INTO v_free FROM places
   WHERE eco_zone = 'natural_park' AND NOT eco_permit_required
     AND eco_rules LIKE 'Территория Авачинского перевала — зона свободного посещения%';
  SELECT count(*) INTO v_texts FROM places
   WHERE id::text IN ('4732f58e-63e5-4ec1-902e-f0f531391193', 'c7c9f572-5e78-4d4f-a9ee-d0182eb313d6')
     AND description LIKE 'Налычевск%' AND essence IS NOT NULL;
  SELECT description, permit_email INTO v_park FROM parks WHERE slug = 'nalychevo';
