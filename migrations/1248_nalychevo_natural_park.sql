     AND i.prompt LIKE '%(миграция 1248)';
  SELECT count(*) INTO v_gallery
    FROM place_gallery_photos g JOIN places p ON g.ark_id = p.ark_id
   WHERE p.id::text = 'ce59fcc5-0e85-487c-9acf-5cbbb46d2e1e'
     AND (g.s3_key LIKE 'photos/nalychevo/mestechko-%'
