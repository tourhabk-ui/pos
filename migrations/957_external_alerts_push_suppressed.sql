-- Migration 957: почему пуш НЕ ушёл — отдельное поле, а не молчание
--
-- 14.09 владелец получил ТРИ уведомления об одном паводке в одну минуту
-- (10:12), все с заголовком «Паводок — Камчатка»: тело первого — экстренное
-- предупреждение, второго — фраза про достижение опасного уровня, третьего —
-- новость о выезде спасателей МЧС в Соболево. Для человека это одно событие;
-- для конвейера — три строки external_alerts, потому что контент-дедуп
-- (seismic-parser.saveEvent) сверяет заголовок с описанием, а у трёх разных
-- постов МЧС они и правда разные.
--
-- Дальше срабатывает механика доставки: dispatchPushAlerts шлёт ровно один
-- push на строку и ставит каждому свой `tag: alert-<id>`. Разные теги не
-- заменяют друг друга на телефоне — они ложатся стопкой.
--
-- Правило, которое вводится вместе с этой колонкой: пока действует уже
-- разосланный алерт ТОГО ЖЕ типа не меньшей тяжести, второй push не уходит.
-- Ничего при этом не теряется: в push нет ни района, ни подробностей —
-- заголовок называет тип и край целиком, а инструкция у типа одна на всех
-- («Не пересекайте реки вброд»). Второе уведомление не несло НИ ОДНОГО
-- сведения, которого не было в первом. Сам алерт остаётся видимым на /safety
-- полностью — глушится звонок, а не факт.
--
-- Колонка нужна, чтобы «не отправляли нарочно» не выдавалось за «отправили»
-- (§4.0): push_sent_at здесь ставить нельзя — это была бы ложь в данных, и
-- она спрятала бы недоставку от сторожа, который следит за молчащим push.
-- Третий исход обязан называться своим именем и нести причину.
--
-- IDEMPOTENT

BEGIN;

ALTER TABLE external_alerts ADD COLUMN IF NOT EXISTS push_suppressed_at     TIMESTAMPTZ;
ALTER TABLE external_alerts ADD COLUMN IF NOT EXISTS push_suppressed_reason TEXT;

COMMENT ON COLUMN external_alerts.push_suppressed_at IS
  'Push намеренно не отправлен (дубль по типу при действующем алерте). NULL — решения не принималось; не путать с push_sent_at.';
COMMENT ON COLUMN external_alerts.push_suppressed_reason IS
  'Почему push не отправлен, словами. Без причины запись бессмысленна: через месяц «почему тихо» не восстановить.';

-- Выборка на рассылку идёт по push_sent_at IS NULL; заглушённые строки
-- остаются в ней навсегда и перебирались бы каждым прогоном. Индекс держит
-- их отсев дешёвым.
CREATE INDEX IF NOT EXISTS idx_external_alerts_push_pending
  ON external_alerts (expires_at)
  WHERE push_sent_at IS NULL AND push_suppressed_at IS NULL;

COMMIT;
