-- 1044_alert_volcano_anchor.sql
--
-- Пепел Шивелуча красил Ключевской. Алерту нужен вулкан, а не зона.
--
-- ── Что видит турист ─────────────────────────────────────────────────────
--
-- Замер владельца с прода (дайджест 27.09, MCP `get_guardian_context`):
--
--   Ключевская сопка [КРАСНЫЙ]
--   активный алерт: «Извержение вулкана Шивелуч — высота 5.0 км»
--   KVERT по Ключевскому при этом ЖЁЛТЫЙ, сейсмичность фоновая
--
-- Шивелуч и Ключевской — разные вулканы в семидесяти километрах друг от
-- друга. Красный вердикт Ключевскому дало чужое извержение.
--
-- ── Откуда это ──────────────────────────────────────────────────────────
--
-- Сейсмо-парсер (`lib/services/safety/seismic-parser.ts`) при разборе сводки
-- KVERT знает ИМЯ вулкана — `volcano_name` лежит в разобранном событии. Но в
-- `external_alerts` этого поля нет, и имя терялось при записи. Оставалась
-- только зона (`VOLCANO_ZONES[volcanoRaw]`), а сопоставление алерта с местом
-- (`ALERT_MATCH_SQL` в `app/api/cron/safety-ingest/route.ts`) для всех родов,
-- кроме пожара и перекрытой дороги, идёт ИМЕННО ПО ЗОНЕ. Северная зона — это
-- Шивелуч, Ключевской, Безымянный, Толбачик, Кизимен и всё вокруг них: одно
-- извержение красило их разом.
--
-- ── Что заводит миграция ────────────────────────────────────────────────
--
--   volcano_name    — имя вулкана из сводки, как его назвал источник.
--                     Производитель: сейсмо-парсер, тем же коммитом.
--   volcano_ark_id  — точка каталога, к которой привязано событие.
--                     Производитель: проход привязки в safety-ingest
--                     (`anchorVolcanoAlerts`), детерминированный матчер
--                     `lib/services/safety/volcano-match.ts` с тремя
--                     исходами: нашли / несколько / в каталоге нет.
--
-- Два поля, а не одно, намеренно: имя — факт источника, точка — наш вывод из
-- него. Свалив их вместе, мы потеряли бы возможность сказать «источник назвал
-- вулкан, а в нашем каталоге его нет» — а это самый частый и самый полезный
-- третий исход (§4.0).
--
-- Привязка не гадает: основы имён сравниваются детерминированно, несколько
-- кандидатов — отказ. Привязать извержение к ЧУЖОМУ конусу хуже, чем не
-- привязать вовсе; ровно это и починено.
--
-- Идемпотентно.

ALTER TABLE external_alerts
  ADD COLUMN IF NOT EXISTS volcano_name TEXT,
  ADD COLUMN IF NOT EXISTS volcano_ark_id UUID;

CREATE INDEX IF NOT EXISTS idx_external_alerts_volcano_ark
  ON external_alerts (volcano_ark_id)
  WHERE volcano_ark_id IS NOT NULL;

COMMENT ON COLUMN external_alerts.volcano_name IS
  'Имя вулкана из сводки источника (KVERT/МЧС), как он его назвал. Пишет сейсмо-парсер.';
COMMENT ON COLUMN external_alerts.volcano_ark_id IS
  'places.ark_id вулкана, к которому привязано событие. Пишет проход привязки в safety-ingest через детерминированный матчер. NULL — источник вулкан назвал, а в каталоге его нет либо кандидатов несколько; такой алерт места не красит и остаётся в общекраевой ленте.';
