-- ── ПРАВКА 30.08: миграция падала на проде девять деплоев подряд ─────────
--
-- Watchdog: «insert or update on table location_safety_profile violates
-- foreign key constraint fk_lsp_place» (попыток 9). Ограничение —
-- `agent_route_id REFERENCES places(ark_id)`.
--
