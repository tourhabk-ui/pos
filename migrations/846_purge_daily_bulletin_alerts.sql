-- 846_purge_daily_bulletin_alerts.sql
--
-- Перепись вердиктов на проде 10.08 дала «Не сегодня» на 144 маршрутах из 421,
-- и причина у всех была одна: «На контроле ЦУКС ГУ МЧС России по Камчатскому
-- краю по состоянию на 06.00». Это суточная сводка — она приходит КАЖДЫЙ ДЕНЬ,
-- то есть запрет срабатывал бы ежедневно и вердикт стал бы вечно красным.
-- Рядом лежал репортаж «спасатели окажут помощь тургруппе в наведении
-- верёвочной переправы»: опасность там уже наступила и ею уже занимаются.
--
-- Классификатор оба жанра теперь отбрасывает на входе (isDailyBulletin,
-- isRescueOperationReport в lib/services/safety/seismic-parser.ts), но СТАРЫЕ
-- строки остались в external_alerts и продолжают красить маршруты, пока не
-- истекут. Тот же случай, что учения в миграции 750 — и лечение то же:
-- чистим и источник, и уже разложенные по точкам массивы.
--
-- Содержательного не теряем: проба показала, что всё, о чём говорит сводка,
-- приходит тем же фидом отдельными предупреждениями — экстренное
-- метеопредупреждение, оползни с Мутновского, классы пожарной опасности,
-- подъём уровней воды. Их условия ниже НЕ трогают.
--
-- Идемпотентна.

DELETE FROM external_alerts
 WHERE title ~* 'на контроле цукс'
    OR title ~* 'оперативн[а-яё]*[[:space:]]+ежедневн[а-яё]*[[:space:]]+прогноз'
    OR title ~* 'ежедневн[а-яё]*[[:space:]]+оперативн[а-яё]*[[:space:]]+прогноз'
    OR (
      title ~* '(окаж[еу]т|оказал[аи]?|оказана)[[:space:]]+помощь|эвакуирова|деблокирова'
      AND title !~* 'экстренное предупреждение|штормовое предупреждение|прогнозирует|ожидается|приближает'
    );

UPDATE location_real_time_status
   SET active_alerts = (
     SELECT COALESCE(array_agg(a), ARRAY[]::TEXT[])
     FROM unnest(active_alerts) AS a
     WHERE NOT (
       a ~* 'на контроле цукс'
       OR a ~* 'оперативн[а-яё]*[[:space:]]+ежедневн[а-яё]*[[:space:]]+прогноз'
       OR a ~* 'ежедневн[а-яё]*[[:space:]]+оперативн[а-яё]*[[:space:]]+прогноз'
       OR (
         a ~* '(окаж[еу]т|оказал[аи]?|оказана)[[:space:]]+помощь|эвакуирова|деблокирова'
         AND a !~* 'экстренное предупреждение|штормовое предупреждение|прогнозирует|ожидается|приближает'
       )
     )
   )
 WHERE EXISTS (
   SELECT 1 FROM unnest(active_alerts) AS a
   WHERE a ~* 'на контроле цукс'
      OR a ~* 'оперативн[а-яё]*[[:space:]]+ежедневн[а-яё]*[[:space:]]+прогноз'
      OR a ~* 'ежедневн[а-яё]*[[:space:]]+оперативн[а-яё]*[[:space:]]+прогноз'
      OR (
        a ~* '(окаж[еу]т|оказал[аи]?|оказана)[[:space:]]+помощь|эвакуирова|деблокирова'
        AND a !~* 'экстренное предупреждение|штормовое предупреждение|прогнозирует|ожидается|приближает'
      )
 );
