--                   заявлено входящим в стоимость, а в составе не было.
--   what_to_bring — список из объявления, дословно по смыслу: одежда,
--                   обувь, запасной комплект, купальник для источников,
--                   медикаменты, репелленты.
--   base_price    — 13 000 (подтверждено владельцем).
--   duration_hours— 12: в шапке объявления стояло «5 ч», а в его же
--                   программе 07:30-19:30; владелец подтвердил 12.
--
-- program и meeting_point НЕ трогаем: программа выверена миграциями
-- 809/814/817 и совпадает с днём из объявления; meeting_point записан со
-- слов оператора (797) с километрами трассы — точка старта не менялась.
--
-- Матч по содержанию, ровно один тур, без INSERT. Идемпотентна.

WITH canonical AS (
  SELECT ot.id
    FROM operator_tours ot
   WHERE ot.deleted_at IS NULL
     AND ot.title ILIKE '%быстр%'
     AND (ot.title ILIKE '%сплав%' OR ot.activity_type IN ('rafting', 'boat_trip'))
   ORDER BY
     CASE WHEN ot.title = 'Сплав по реке Быстрая' THEN 0 ELSE 1 END,
     ot.created_at ASC
   LIMIT 1
)
UPDATE operator_tours ot
   SET description = 'Спокойный семейный сплав по реке Быстрая — день среди камчатской природы без городской суеты. Это не спортивный рафтинг: течение ровное, без опасных порогов, маршрут комфортен для новичков и детей от 2 лет. По пути — остановки на берегу: прогулки, фото на фоне сопок, наблюдение за птицами и дикой природой с безопасного расстояния. Любители рыбалки в сезон могут попробовать поймать лосося. Это день не про экстрим, а про время вместе — с брызгами воды, смехом детей и видами камчатских сопок. Детям до 14 лет — скидки, размер уточняйте у оператора.',
       included = ARRAY[
         'Рафт и снаряжение',
         'Инструктор',
         'Обед на берегу',
         'Трансфер с места проживания — туда и обратно',
         'Спасательные жилеты',
         'Купание в Малкинских горячих источниках',
         'Рыболовные снасти'
       ]::text[],
       what_to_bring = ARRAY[
         'Влаго- и ветрозащитная одежда',
         'Головной убор',
         'Солнцезащитные очки',
         'Удобная обувь',
         'Запасной комплект сухой одежды',
         'Купальник и полотенце — для горячих источников',
         'Личные медикаменты',
         'Средства от насекомых'
       ]::text[],
       base_price = 13000,
       duration_hours = 12,
       duration_type = 'day',
       updated_at = NOW()
  FROM canonical c
 WHERE ot.id::text = c.id::text;
