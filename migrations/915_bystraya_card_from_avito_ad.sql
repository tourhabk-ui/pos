--                   нигде: скидка детям до 14 лет (817) и — новое,
--                   подтверждено владельцем — возраст участия от 2 лет.
--   included      — «Трансфер из Елизово» противоречил и объявлению
--                   («трансфер туда и обратно»), и шагу 7 программы
