-- 971: форма снятой записи — чтобы её было видно, а не только измерено
--
-- Очередь треков (904) хранила ИЗМЕРЕНИЯ файла — точек, длина, размах, доля
-- высот — и ссылку на файл в S3. Самой линии не хранила нигде. Поэтому экран
-- очереди мог показать человеку только столбец чисел: «1240 точек, 8.3 км,
-- pending». По ним свой выход не узнаёт никто: те же числа даёт и подъём на
-- вулкан, и круг по посёлку. Отвечает на вопрос «это моя запись?» только
-- форма линии, а её взять было неоткуда.
--
-- Колонка держит ПОКАЗ, а не данные маршрута:
--   * линия прорежена (потолок точек на запись) — рисовать тысячи вершин на
--     карточке незачем, и `preview_line.shown` / `of` говорят это вслух;
--   * куски записи и провалы сигнала лежат раздельно (§12: прямая через
--     молчание прибора — построение, а не снятый путь);
--   * применение трека к маршруту её НЕ читает: линия для маршрута всегда
--     считается заново из файла в S3. Иначе прореженная копия однажды
--     подменила бы оригинал, и маршрут получил бы огрубление вместо записи.
--
-- Заполняется лениво, при первом показе записи (GET /api/admin/track-imports/
-- [id]/line): файл скачивается и разбирается один раз, дальше берётся отсюда.
-- NULL — «ещё не смотрели», а не «линии нет»: у нечитаемого файла показ
-- отвечает отказом с причиной, а не пустой картой.

ALTER TABLE route_track_imports
  ADD COLUMN IF NOT EXISTS preview_line JSONB;

COMMENT ON COLUMN route_track_imports.preview_line IS
  'Прореженная форма записи для показа в очереди: {pieces, gaps, shown, of, bounds}. '
  'НЕ источник геометрии маршрута — применение считает линию заново из файла.';
