-- 933: слово паспорта о регистрации в МЧС и маршрут-призрак (решение
-- владельца 05.09).
--
-- ИСТОРИЯ. Слияния 04-05.09 (пробы 437 и 440) донесли на выжившие записи
-- паспортные поля дублей: «Бабий камень» → «Водопад Бабий камень»,
-- «Гейзеры Кроноцкого заповедника» → «Долина гейзеров». Правило переноса —
-- «заполнить только пустое, никогда не перезаписывать», — и оно честно
-- оставило на keep флаг mchs_registration_required = false, потому что
-- false — значение, а не пустота: «регистрация не требуется» сказано так же
-- явно, как «требуется».
--
-- Но в обеих парах это false НИКТО НЕ ГОВОРИЛ. У колонки DEFAULT false
-- (baseline), а выжившие записи пришли скрейпом idilesom/extraguide, где
-- флага нет вовсе. Паспорт visitkamchatka — официальный документ, и он
-- говорит true; его слово было записано в дубль импортёром паспортов
-- (import-route-passports), а выживший через импортёр не проходил. В итоге
-- карточка показывала телефон МЧС из паспорта и молчала о том, что
-- регистрация обязательна. По безопасности (§10) это хуже, чем наоборот.
--
-- Отличить «сказано false» от «дефолт false» по базе нельзя — оба
-- выглядят одинаково. Поэтому здесь не общее правило, а две записи
-- поимённо, с уликой: у каждой pdf_url указывает на паспорт visitkamchatka,
-- принесённый слиянием, и в этом паспорте флаг стоял в true.
--
-- Второе действие — «Долина Гейзеров-Долина Смерти» (f447bbe2). Слово
-- владельца 04.09: «нет маршрута». Координаты записи совпадают с «Долиной
-- Смерти» (миграция 856 оставила их под подозрением), линии нет, паспорта
-- нет. Сторож двойников (route-twins-hide) её не берёт: у неё есть дистанция
-- 16 км и одна путевая точка. Скрытие, не удаление: на kamchatka_routes
-- смотрят FK, а is_visible обратим.
--
-- Идемпотентно: каждый UPDATE сужен условием на текущее состояние.

-- ── 1. Флаг регистрации в МЧС — по слову паспорта, две записи поимённо ──
UPDATE kamchatka_routes
SET mchs_registration_required = true, updated_at = NOW()
WHERE id::text IN (
  'be1c6c4a-33d8-4b3f-8025-2230654758f2',  -- Водопад Бабий камень ← babiy_summer.PDF
  '385d1c98-14d2-4173-bdb6-03eb5d596db0'   -- Долина гейзеров ← geyzers_kron.pdf
)
  AND pdf_url ILIKE '%visitkamchatka.ru%'
  AND mchs_registration_required IS DISTINCT FROM true;

-- ── 2. Маршрут-призрак уходит с витрины ──────────────────────────────────
UPDATE kamchatka_routes
SET is_visible = false, updated_at = NOW()
WHERE id::text = 'f447bbe2-37ef-4858-b5eb-d8014fbf50d2'  -- Долина Гейзеров-Долина Смерти
  AND merged_into_id IS NULL
  AND is_visible = true;
