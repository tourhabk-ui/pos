-- Точечное сообщение на карточке пляжа (alert_message читает
-- /api/places/[id] -> realtime.alertMessage). is_open не трогаем:
-- пляж открыт, перекрыт один из подъездов.
UPDATE location_real_time_status lrts
SET alert_message    = 'Дорога со стороны Дальнего перекрыта (реконструкция, сроки не объявлены; фото/видеофиксация, штрафы за проезд). Объезд — по старой дороге через мыс Толстый.',
    alert_source     = 'manual',
    alert_expires_at = '2027-07-01 00:00:00',
    updated_at       = NOW()
FROM places p
WHERE p.ark_id = lrts.agent_route_id
  AND p.name ILIKE '%халактырск%';

