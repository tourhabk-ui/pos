  1,
  'Халактырский пляж: дорога со стороны Дальнего перекрыта',
  'Дорога к Халактырскому пляжу на участке со стороны посёлка Дальний полностью перекрыта — началась масштабная реконструкция (новое полотно, тротуары, освещение). Сроки завершения не объявлены. На закрытом участке ведётся фото- и видеофиксация, за проезд под запрет — административная ответственность. Проезд к пляжу сохраняется по старой дороге через мыс Толстый — закладывайте время на объезд.',
