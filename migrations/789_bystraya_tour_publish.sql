-- Migration 789: опубликовать «Сплав по реке Быстрая»
--
-- Решение владельца 29.07.2026 («публикуй»).
--
-- Тур лежал в базе с 21.03.2026 (миграция 060) с is_published = FALSE — то
-- есть существовал, но не показывался никому. Именно поэтому продвижение
-- партнёра не давало результата: раскручивать было нечего, ссылка вела в
-- пустоту.
--
-- Публикуется ПОСЛЕ 788, и порядок здесь существенный: 788 убирает из
-- календаря выдуманные дни (060 засеяла все 123 дня подряд, оператор водит
-- через день по 31 августа) и переносит тур из «Морских прогулок» в «Сплав».
-- Опубликовать раньше — значит на несколько минут выставить наружу календарь
-- с датами, которых у оператора нет.
--
-- Каталог требует три условия: deleted_at IS NULL, is_active, is_published
-- (lib/search/tour-search.ts). Первые два уже верны — is_active идёт по
-- умолчанию TRUE, — но проставляем явно: полагаться на умолчание там, где от
-- флага зависит видимость коммерческого предложения, незачем.
--
-- Прошедшие даты специально НЕ удаляем: каталог отсекает их сам
-- (ta.date >= CURRENT_DATE), а список остаётся точной записью того, что
-- оператор объявил.
--
-- Идемпотентна.

UPDATE operator_tours t
   SET is_published = TRUE,
       is_active    = TRUE,
       updated_at   = NOW()
  FROM partners p
 WHERE p.id = t.operator_id
   AND p.slug = 'kamchatka-rafting'
   AND t.title = 'Однодневная экскурсия СПЛАВ ПО РЕКЕ БЫСТРАЯ'
   AND t.deleted_at IS NULL
   AND (t.is_published IS DISTINCT FROM TRUE OR t.is_active IS DISTINCT FROM TRUE);
