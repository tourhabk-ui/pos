-- 1028: причина отмены брони жилья владельцем.
--
-- Решение владельца 26.09 (пакет «бронь жилья»): гость узнаёт о
-- подтверждении и отмене своей брони. Отменяя, владелец может назвать
-- причину — она уходит гостю письмом и остаётся в брони, чтобы гость видел
-- её в «Моих проживаниях», а не только в почте.
--
-- refund_reason для этого не годится: там формулировка политики возврата
-- (что положено гостю по деньгам), а здесь — слова владельца. Смешать их
-- значило бы потерять одно из двух.
--
-- NULL — «причина не названа», а не пустая строка.

ALTER TABLE accommodation_bookings
  ADD COLUMN IF NOT EXISTS cancellation_reason TEXT;

COMMENT ON COLUMN accommodation_bookings.cancellation_reason IS
  'Причина отмены словами владельца/администратора (PATCH /api/stay/bookings/[id]); NULL — не названа.';
