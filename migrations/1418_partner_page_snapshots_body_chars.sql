-- 1418: partner_page_snapshots.body_chars — сколько знаков страницы прочитано
-- Created: 2026-11-10
--
-- ── Почему ────────────────────────────────────────────────────────────────
--
-- Отчёт наблюдения 10.11 назвал «пропавшими» строки двух страниц туров
-- laguna-expedition.ru («Проживание в спа-отеле…», «Номер реестровой
-- записи…»), которые никуда не девались. Страницы выросли с календарём
-- выездов до 741 тыс. знаков, чтение обрезало тело на 600 тыс., и хвост
-- страницы в снимок не попал. Признак обрезки при этом не читался и нигде не
-- записывался: по строке таблицы нельзя было сказать, вся ли это страница.
--
-- ── Что здесь ─────────────────────────────────────────────────────────────
--
-- body_chars — сколько знаков HTML прочитано при этом чтении. Потолок чтения
-- поднят (lib/partners/site-watch.ts: WATCH_BODY_LIMIT, TEXT_CAP); страница
-- больше потолка теперь пишется исходом failed с причиной, а не ok.
--
-- NULL — не записано: чтение до этой миграции либо до тела не дошло (404,
-- отказ сети, запрет robots.txt). Снимок ok с NULL снят старым чтением с его
-- потолками (600 тыс. знаков тела, 60 тыс. текста): если страница сейчас
-- больше них, в снимке не вся страница, и первое полное чтение сравнивается с
-- ним только там, куда старое чтение доставало (site-watch.ts,
-- cutSnapshotDiff).
--
-- Строк миграция не меняет. Персональных данных здесь нет.
--
-- IDEMPOTENT: ADD COLUMN IF NOT EXISTS.

ALTER TABLE partner_page_snapshots ADD COLUMN IF NOT EXISTS body_chars INTEGER;

COMMENT ON COLUMN partner_page_snapshots.body_chars IS
  'Сколько знаков HTML прочитано (1418). NULL — не записано: чтение до 1418 или до тела не дошло. Снимок ok с NULL снят с потолком 600 тыс. знаков и мог быть обрезан.';
