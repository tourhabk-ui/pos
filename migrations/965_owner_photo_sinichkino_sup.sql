-- 13.10 (решение владельца «согласен, перенеси в S3»): байты снимков вынесены в
-- хранилище — ключ migrations/photos/<sha256>.jpg из маркера
-- .github/triggers/migration-photos-to-s3.json (sha256 тех же байтов). Миграция
-- пишет s3_key, image_data пуст; прод переведён по хэшу байтов миграцией 1228.
--
-- 965: озеро Синичкино — снимок владельца ЗАМЕНЯЕТСЯ на его же новый.
--
-- ── Почему тут снята защита ON CONFLICT ───────────────────────────────────
--
-- У места уже лежит manual-upload: миграция 930 положила снимок владельца от
-- 02.09. Все миграции этой серии (958-964) кончаются условием
-- `WHERE ai_route_images.model NOT IN ('wikimedia', 'manual-upload')` —
-- настоящий снимок не перезаписывается автоматом. Здесь условие СНЯТО
-- намеренно, и это не обход правила, а тот случай, ради которого правило и
-- написано: защита стоит против автоматической подмены человеческого выбора,
-- а меняет снимок сам владелец, на свой же.
--
-- Старый кадр извлечён из миграции 930 и просмотрен, а не отвергнут на слово:
-- на нём та же панорама с тремя вулканами, но ветку берёзы несёт поперёк
-- середины кадра, и дымка съедает контраст. Новый резче, и на нём видно то,
-- чего карточка озера не говорила вовсе: здесь ходят на сапе.
--
-- ── Обрезка ───────────────────────────────────────────────────────────────
--
-- Исходник 1476x3280 — отношение 0.45, полоса 16:9 берёт четверть высоты.
-- Проверено тремя прогонами на самом файле: на 44% и 50% вершина Корякского
-- срезается, на 38% в кадр попадают ОБА — и вулкан целиком, и доска у берега.
-- Штатный cover/attention на таком кадре ушёл бы в облачное небо (урок 958).
--
-- Идемпотентно: повторный прогон кладёт те же байты.

INSERT INTO ai_route_images (route_id, image_data, mime_type, prompt, model, width, height, author, s3_key)
SELECT p.ark_id,
       NULL::bytea,
       'image/jpeg',
       'снимок владельца: озеро Синичкино (сап), миграция 965',
       'manual-upload',
       1280,
       720,
       'владелец платформы',
       'migrations/photos/22f7baa32019a1bbe442e6f10db9db78ce5bf5d32a4d8786f959b2f2357d710a.jpg'
  FROM places p
 WHERE (p.id::text = '9330b39d-7afd-491b-9eaa-11d190c52c8c'
     OR p.ark_id::text = '9330b39d-7afd-491b-9eaa-11d190c52c8c')
   AND p.ark_id IS NOT NULL
 LIMIT 1
ON CONFLICT (route_id) DO UPDATE
   SET image_data = EXCLUDED.image_data,
       s3_url     = NULL,
       s3_key     = EXCLUDED.s3_key,
       mime_type  = EXCLUDED.mime_type,
       prompt     = EXCLUDED.prompt,
       model      = EXCLUDED.model,
       width      = EXCLUDED.width,
       height     = EXCLUDED.height,
       author     = EXCLUDED.author,
       created_at = NOW();
