-- 947_hide_ovalnoe_lake_bad_coords.sql
--
-- «Озеро Овальное» (c3a29662-7b2f-44b6-91de-f3a51cd54e5a) скрыто решением
-- владельца 10.09 — не удалено, потому что запись, возможно, честная, а
-- ошибка только в координате.
--
-- Найдено по жалобе с телефона: «На маршруте» вёл к точке в 3 км от центра
-- Петропавловска-Камчатского под именем места у подножия Авачинского
-- вулкана. В той же базе «Вулкан Авачинский» (53.2554,158.8362) и
-- «Авачинский перевал» (53.2083,158.5896) стоят в ~19-25 км от записи —
-- внутреннее противоречие с соседями по домену. Independent-проверка через
-- Nominatim (озеро «Овальное» на Камчатке, оба варианта запроса) не нашла
-- НИЧЕГО — по правилу §4.1 («Разбирать можно только глазами», источник
-- обязателен) правку координаты сделать не на чем.
--
-- Тем же именем страдает соседняя запись «Смотровая у Авачинского вулкана»
-- (3cd79015-eed6-40ff-8e4c-eb49a8c7ff3a, 53.0484,158.6680) — она НЕ
-- трогается здесь: там независимый источник ещё не проверялся отдельно.
--
-- Скрытие, не удаление: is_visible = false убирает запись с карты и из
-- каталога (витрина читает только is_visible = true), но не рвёт возможные
-- FK (route_waypoints и т.п.) и оставляет путь назад, если найдётся источник
-- правды и координату можно будет поправить, а не прятать.
--
-- Идемпотентно: отсутствующая запись — no-op с NOTICE, не ошибка.

DO $$
DECLARE
  pid text := 'c3a29662-7b2f-44b6-91de-f3a51cd54e5a';
  pname text;
BEGIN
  SELECT name INTO pname FROM places WHERE id = pid;

  IF pname IS NULL THEN
    RAISE NOTICE '[947] % — уже отсутствует в places, делать нечего', pid;
    RETURN;
  END IF;

  UPDATE places SET is_visible = false, updated_at = NOW() WHERE id = pid;
  RAISE NOTICE '[947] скрыто (is_visible=false): % (%)', pname, pid;
END $$;
