-- 1040: «Малкинские горячие источники» — описание из фактов вместо дневника.
--
-- ── Повод (27.09) ──────────────────────────────────────────────────────────
--
-- Владелец: «Малкинские горячие источники — проверь описание». На проде
-- (проба 614) лежало:
--
--   «Вышел к реке Ключёвке — пар, как от огромного чайника, стелется по
--    долине. Вода из шести ключей бьёт под восемьдесят градусов, бетонные
--    чаши врезаны в траву — это сейчас, а раньше, говорят, были каменные,
--    природные. Сижу по горло в горячем, смотрю на зелёные сопки, река шумит
--    рядом — и чувствуешь, как внутри что-то распрямляется, медленно, как
--    трава после дождя. Воздух пахнет серой и прелой листвой, но запах не
--    резкий, а уютный, домашний.»
--
-- и отзыв Кузьмича:
--
--   «Вода восемьдесят, пар по долине — сидеть по горло, но берегись ожогов от
--    перегретых камней и паровых струй. Вокруг сопки и река, воздух серой
--    пахнет, зато душа отдыхает.»
--
-- Это путевая заметка от первого лица — той же породы, что Авачинский и
-- Ключевская (lib/places/description-voice; детектор до сегодняшнего дня
-- её пропускал, потому что рассказчик обходится без «я»: «Сижу», «смотрю»).
--
-- Опасна здесь не манера, а цифра. «Восемьдесят градусов» и «сидеть по горло»
-- рядом — прямое противоречие: в воде восьмидесяти градусов сидеть нельзя, и
-- какая из двух половин верна, текст не говорит. Проверить нечем: в самом
-- репозитории температура источников названа ТРИЖДЫ и трижды по-разному —
-- «44–62 °C» (105), «+36–45 °С» (090), «восемьдесят» (эта карточка). Ни у
-- одной нет источника. «Шесть ключей», «река Ключёвка», «бетонные чаши» —
-- тоже без источника.
--
-- ── Из чего новый текст ───────────────────────────────────────────────────
--
--   - посёлок Малки в Елизовском районе, долина между горами, 120 км к
--     северо-западу от Петропавловска-Камчатского; санаторий-профилакторий
--     на выходах термальных вод; первая лечебница — врач И. В. Любарский,
--     1818 год; рядом Малкинский завод по розливу минеральной воды —
--     Википедия, статья «Малки (Камчатский край)» (проба 617);
--   - купели у реки, пар над водой, лагерь на дальнем берегу — снимки
--     владельца 24.09 (миграция 1008).
--
-- Температуры в тексте нет, и об этом сказано прямо: турист, который ищет
-- число, должен узнать, что его у нас нет, а не решить, что мы забыли.
--
-- Отзыв Кузьмича обнуляется (NULL — блока на карточке нет): он повторяет ту
-- же непроверенную цифру и то же «сидеть по горло», а переписать его «из
-- фактов» значило бы сочинить новый. Старые тексты — выше, дословно: это и
-- есть откат.
--
-- ── Границы правки ─────────────────────────────────────────────────────────
--
-- Правится только запись, где лежит ровно тот текст — отбор по его началу.
-- Успел кто-то поправить раньше — миграция не делает ничего.
--
-- Идемпотентна.

WITH old AS (
  SELECT id, LENGTH(description) AS prev_chars
    FROM places
   WHERE id::text = '284c862f-a339-409d-988a-da4107324b60'
     AND description LIKE 'Вышел к реке Ключёвке%'
),
upd AS (
  UPDATE places p
     SET description = 'Горячие источники у посёлка Малки в Елизовском районе — в долине между горами, примерно в 120 км к северо-западу от Петропавловска-Камчатского. На выходах термальных вод работает санаторий-профилакторий; первую лечебницу здесь открыл врач И. В. Любарский в 1818 году. Недалеко от посёлка — Малкинский завод по розливу минеральной воды. На снимках владельца платформы — купели у реки, пар над водой, лагерь на дальнем берегу. Температуры воды в наших данных нет: в разных справочниках она названа по-разному, и поручиться ни за одну цифру нельзя. Вода горячая — проверяйте её, прежде чем входить.',
         updated_at = NOW()
    FROM old
   WHERE p.id::text = old.id::text
  RETURNING p.ark_id, p.name, p.description, old.prev_chars
)
INSERT INTO description_provenance
  (entity_id, entity_kind, entity_title, written_by, facts_given, facts_count,
   chars, previous_chars)
SELECT
  upd.ark_id,
  'place',
  upd.name,
  'owner-decision',
  '["посёлок Малки, Елизовский район, долина между горами (Википедия)","120 км к северо-западу от Петропавловска-Камчатского (Википедия)","санаторий-профилакторий на выходах термальных вод (Википедия)","первая лечебница — врач И. В. Любарский, 1818 (Википедия)","Малкинский завод по розливу минеральной воды рядом (Википедия)","купели у реки, пар, лагерь на дальнем берегу (снимки владельца 24.09)"]'::jsonb,
  6,
  LENGTH(upd.description),
  upd.prev_chars
FROM upd
WHERE upd.ark_id IS NOT NULL;

UPDATE places
   SET kuzmich_review = NULL,
       updated_at     = NOW()
 WHERE id::text = '284c862f-a339-409d-988a-da4107324b60'
   AND kuzmich_review LIKE 'Вода восемьдесят, пар по долине%';
