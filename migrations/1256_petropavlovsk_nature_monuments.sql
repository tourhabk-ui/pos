--     карточки внутри его контура, не трогается;
--   описание тура «Остров Старичков (морская прогулка)» партнёра «Местечко
--     Камчатка» (1217) — виды птиц и тюленей острова, со ссылкой на него в
--     тексте.
--
-- ── Где источники молчат ─────────────────────────────────────────────────
--
-- Положения о памятниках (границы, запреты, нужно ли разрешение) на платформе
