--   «Сопка Никольская» — описание-дневник снято 1247, на карточке пусто;
--     режима нет, хотя сопка — памятник природы с 1983 года;
--   «Никольская сопка — мемориал Петропавловской обороны 1854» — описание снято
--     1247, точка (53.002, 158.639) — в 1,6 км к югу от памятников;
--   «Батарея Максутова — позиция 1854 года» — справка по Википедии (1149, 1154)
--     верна, а точка (53.0203, 158.6422) — координата статьи о самой сопке
--     (53.02028, 158.64222, проба 920), то есть её вершина, а не перешеек;
--   «Скалы Три Брата» — «базальтовые скалы высотой 15–20 м»: высоты нет ни в
--     одном источнике, а скалы, по Википедии, не магматические — это останцы
--     осадочных базальтовых туфов; режима нет, хотя скалы — памятник природы;
--   «Остров Старичков» — сочинение («лодка подошла к скалистой стене», калан
--     «прямо под бортом»), заметка Кузьмича — его пересказ, режим «нет», хотя
--     остров — особо охраняемая природная территория.
--
-- ── Источники ────────────────────────────────────────────────────────────
--
--   Википедия — «Никольская сопка» (пробы 913, 915), «Три Брата (Камчатка)»
--     (913), «Остров Старичков» (914), категория «Памятники природы
--     Камчатского края» (918): сопка и скалы в ней есть, острова — нет;
--   OpenStreetMap (проба 916): вершина сопки — node 2111959809 (103 м, «Сопка
--     Любви»), часовня 1912 года — way 1188381839, макет «Смертельной» батареи
