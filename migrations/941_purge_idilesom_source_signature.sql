--
-- Решение владельца 07.09: «нужно вычистить idilesom». Скрейпер, импортёры и
-- сверки удалены отдельно; здесь — подпись, оставшаяся в данных.
--
-- ЧТО ОСТАЁТСЯ НА МЕСТЕ (осознанно):
--   1. Сам контент — маршруты, описания, геометрия. Владелец выбрал чистку
--      подписи, а не удаление скачанного: снос геометрии стоил бы ~257 линий
--      из 301, то есть карта осталась бы почти без треков.
--   2. source_url. Он остаётся в базе для проверки фактов и авторских прав —
--      ровно та же причина, по которой его оставили 17.08 (миграция 871,
--      см. components/places/PlaceFooter.tsx). Стереть происхождение значит
--      не убрать чужое, а перестать знать, что оно чужое.
--
-- ПОЧЕМУ ПЕРЕИМЕНОВАНИЕ, А НЕ NULL — это главное в файле.
--
-- Метка `geometry->>'source'` не украшение: по ней lib/map/line-standard.ts
-- решает ВИД ЛИНИИ на карте. Слог 'idilesom' входит в UNVERIFIED_SOURCES —
-- скрейп рисуется пунктиром «записан, но никем не подтверждён». Линия без
-- метки проваливается в плотностную эвристику, а у скрейпа вершины частые:
-- угадыватель вернул бы такой линии звание СНЯТОГО ТРЕКА — сплошную зелёную,
-- которая на языке карты означает «здесь идут». Обнуление метки ради чистоты
-- превратило бы 257 непроверенных линий в обещание вести по ним человека в
-- поле. Поэтому слог меняется на 'external' — тот же смысл без имени
-- (решение владельца 17.08, §12 CLAUDE.md), и он уже в UNVERIFIED_SOURCES.
--
-- Идемпотентна: повторный прогон не находит строк.

-- 1. Подпись источника у маршрутов — род без имени, как у мест с 871.
UPDATE kamchatka_routes
   SET source_name = 'сторонний источник'
 WHERE source_name IN ('idilesom', 'idilesom.com');

-- 2. Тот же слог у мест, если где-то остался мимо 871.
UPDATE places
   SET source_name = 'сторонний источник'
 WHERE source_name IN ('idilesom', 'idilesom.com');

-- 3. Метка происхождения линии: имя → нейтральный слог. НЕ NULL (см. шапку).
UPDATE kamchatka_routes
   SET geometry = jsonb_set(geometry, '{source}', '"external"')
 WHERE geometry IS NOT NULL
   AND geometry->>'source' = 'idilesom';

-- 4. Ключ дедупликации нёс имя в самом значении ('idilesom:<id>').
--    Читателей у него не осталось — импортёр и сверки удалены, — но имя
--    лежало бы в базе. Пропускаем строку, если целевой ключ уже занят:
--    уникальный индекс важнее косметики, и упавшая миграция хуже остатка.
UPDATE kamchatka_routes r
   SET dedupe_key = 'external:' || substring(r.dedupe_key from 10)
 WHERE r.dedupe_key LIKE 'idilesom:%'
   AND NOT EXISTS (
     SELECT 1 FROM kamchatka_routes x
      WHERE x.dedupe_key = 'external:' || substring(r.dedupe_key from 10)
   );
