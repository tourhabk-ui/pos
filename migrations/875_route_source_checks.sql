-- 875: результат сверки с источником живёт в базе, а не в логе прогона.
--
-- ── Зачем ─────────────────────────────────────────────────────────────────
--
-- План «Порядок в маршрутах», Ф1. Решение A даёт линии право вести без
-- путевых точек при трёх уликах, и вторая из них — «наша копия совпадает с
-- оригиналом на странице-источнике». Сегодня эта улика существует ровно
-- столько, сколько живёт лог прогона: сверка печатает отчёт и ничего не
-- сохраняет. Спросить её правило не может.
--
-- ── Почему у улики есть дата и версия ─────────────────────────────────────
--
-- Сверка сравнивает нашу копию со страницей НА СЕГОДНЯ. Источник перепишет её
-- завтра — и «совпадает» станет исторической фразой, продолжая выдавать право
-- вести. Поэтому строка хранит момент проверки: `checked_at`.
--
-- И вторую половину того же вопроса: с ЧЕМ сравнивали. Если наша геометрия
-- после проверки изменилась (переимпорт, чистка, правка руками), прежний
-- вердикт относится к другой линии. `geometry_hash` — отпечаток той линии,
-- которую проверяли; при расхождении улика считается отсутствующей, а не
-- устаревшей.
--
-- ── Чего здесь нет ────────────────────────────────────────────────────────
--
-- Ни оценки, ни балла, ни «доверия» числом. Только факт: что сравнивали,
-- когда, с чем и что получилось. Решение принимает правило (Ф2), а не эта
-- таблица.

CREATE TABLE IF NOT EXISTS route_source_checks (
  route_id        UUID PRIMARY KEY,
  -- same | ours_truncated | ours_extra | elevation_lost | line_moved
  -- | source_has_no_track | ours_empty | unreachable
  verdict         VARCHAR(32) NOT NULL,
  -- Адрес страницы, с которой сверялись: улика без источника не улика.
  donor_url       TEXT,
  -- Отпечаток НАШЕЙ линии на момент проверки.
  geometry_hash   TEXT,
  our_points      INT,
  their_points    INT,
  our_elevation   BOOLEAN,
  their_elevation BOOLEAN,
  start_shift_m   INT,
  end_shift_m     INT,
  -- Сходятся ли имя записи и заголовок страницы-донора.
  titles_agree    BOOLEAN,
  -- Версия способа сравнения: правило ещё будет меняться, и вердикты,
  -- полученные разными версиями, нельзя молча складывать.
  method_version  INT NOT NULL DEFAULT 1,
  checked_at      TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS idx_route_source_checks_verdict ON route_source_checks (verdict);
CREATE INDEX IF NOT EXISTS idx_route_source_checks_checked_at ON route_source_checks (checked_at DESC);

