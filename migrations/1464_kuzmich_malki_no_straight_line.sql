-- Migration 1464: заметка Кузьмича о Малкинских источниках — без «по прямой 120 км» (#3514)
-- Created: 2026-11-19
--
-- Слово владельца 19.11 в #3514: «убери по прямой 120 км».
--
-- Миграция 1462 записала заметку malkinskie-springs фактами из источников
-- 1377: «около 130 км … по трассе на Мильково, источники в 4 км от трассы;
-- по прямой — 120 км к северо-западу». Число «по прямой» в 1377 взято из
-- Википедии, а по координатам места (Малки ≈ 53,33° с. ш., 157,55° в. д.,
-- Петропавловск 53,02° с. ш., 158,65° в. д.) по прямой выходит около 81 км;
-- шапка карточки места пишет 82 км по прямой (замечание в #3514). 120 км у
-- Википедии, по-видимому, дорога, а не прямая. Остальной текст заметки и её
-- источники не меняются.
--
-- Та же фраза снята из справки о дороге Кузьмича (lib/kuzmich/travel-facts.ts)
-- тем же коммитом.
--
-- Идемпотентно: правится только запись, где фраза ещё есть. Прежний текст
-- 1462 не теряется: он восстановим из этой миграции (фраза ниже — дословно).

UPDATE agent_knowledge
   SET compiled_truth = replace(compiled_truth, '; по прямой — 120 км к северо-западу', ''),
       metadata = metadata || jsonb_build_object(
         'edited_at', '2026-11-19',
         'edit_note', 'снято «по прямой — 120 км к северо-западу»: по координатам около 81 км (#3514, миграция 1464)'
       ),
       updated_at = NOW()
 WHERE slug = 'malkinskie-springs'
   AND agent_id = 'kuzmich'
   AND compiled_truth LIKE '%; по прямой — 120 км к северо-западу%';

