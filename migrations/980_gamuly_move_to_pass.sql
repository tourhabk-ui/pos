-- 13.10 (решение владельца «согласен, перенеси в S3»): байты снимков вынесены в
-- хранилище — ключ migrations/photos/<sha256>.jpg из маркера
-- .github/triggers/migration-photos-to-s3.json (sha256 тех же байтов). Миграция
-- пишет s3_key, image_data пуст; прод переведён по хэшу байтов миграцией 1228.
--
-- 980: гамулы переезжают со склона вулкана на «Вилючинский перевал».
--
-- ── Почему перенос ────────────────────────────────────────────────────────
--
-- Миграция 979 положила два кадра владельца на запись «Вулкан Вилючинский»
-- (164f612c): вулкан героем, гамулы галереей. В её же шапке записано, что
-- гамулы стоят НЕ на склоне вулкана, а у дороги на перевале, и что перенос —
-- отдельная правка по слову владельца, а не догадка за него.
--
-- Слово сказано 19.09: «гамулы перенеси где должны быть». Записываю дословно,
-- потому что источник здесь — человек, снимавший кадр, а не вывод из данных:
-- по самой фотографии перевал от склона не отличить.
--
-- Перевал — ОТДЕЛЬНОЕ живое место (8bad8fe6-c7ec-4403-b956-948706649ca8,
-- mountain, 52.739923/158.201184), а не синоним вулкана и не слитая запись.
-- Значит у снимка появляется своя карточка, а не вторая строка на чужой.
--
-- ── Что делает миграция ───────────────────────────────────────────────────
--
--   1) кладёт гамулов ГЕРОЕМ перевала (те же байты, второй раз не режутся);
--   2) убирает их из галереи вулкана — иначе один кадр висел бы в двух
--      местах, и следующий читатель не знал бы, какое из них правда.
--
-- Удаление адресное: позиция 1 И подпись «Гамулы на фоне хребта». По одной
-- позиции удалять нельзя — туда мог лечь другой снимок, и мы снесли бы его
-- молча.
--
-- ── Третий исход ──────────────────────────────────────────────────────────
--
-- Герой ставится с той же защитой, что в 979: чужой ручной снимок
-- (`wikimedia` / `manual-upload`) не перезаписывается. Значит возможен исход
-- «не лёг» — если у перевала нет `ark_id` или там уже чей-то ручной кадр.
-- Молча этого оставлять нельзя: миграция 976 ровно так вставила ноль строк и
-- выглядела успешной. Поэтому в конце стоит проверка, называющая отказ вслух
-- в логе деплоя (RAISE WARNING), а не падающая: боевую загрузку сервера
-- снимок не стоит.
--
-- Байты пишутся в базу, а не в хранилище: миграция в S3 ходить не может
-- (сетевой вызов в момент старта сервера стопорит весь накат). Их увезёт
-- уборщик cron-images-to-s3 — правило §4.1.
--
-- IDEMPOTENT

BEGIN;

-- ── Герой перевала: гамулы на фоне хребта ─────────────────────────────────
INSERT INTO ai_route_images (route_id, image_data, mime_type, prompt, model, width, height, author, s3_key)
SELECT p.ark_id,
       NULL::bytea,
       'image/jpeg',
       'снимок владельца: гамулы на Вилючинском перевале (миграция 980)',
       'manual-upload',
       1280,
       720,
       'владелец платформы',
       'migrations/photos/aca97f853e5d79667d908e18fec5b7b0762d7ec113a7be82da843a6713bc4c38.jpg'
  FROM places p
 WHERE p.id::text = '8bad8fe6-c7ec-4403-b956-948706649ca8'
   AND p.ark_id IS NOT NULL
 LIMIT 1
ON CONFLICT (route_id) DO UPDATE
   SET image_data = EXCLUDED.image_data,
       mime_type  = EXCLUDED.mime_type,
       prompt     = EXCLUDED.prompt,
       model      = EXCLUDED.model,
       width      = EXCLUDED.width,
       height     = EXCLUDED.height,
       author     = EXCLUDED.author,
       s3_url     = NULL,
       s3_key     = EXCLUDED.s3_key,
       created_at = NOW()
 WHERE ai_route_images.model NOT IN ('wikimedia', 'manual-upload')
    OR ai_route_images.prompt = 'снимок владельца: гамулы на Вилючинском перевале (миграция 980)';

-- ── Снять гамулов с галереи вулкана ───────────────────────────────────────
--
-- Адресно: и позиция, И подпись. По одной позиции снесли бы чужой снимок.
--
-- И только ПОСЛЕ того, как кадр подтверждённо лёг на перевал. Перенос — это
-- копия плюс снятие, и снятие без копии оставило бы кадр нигде: герой
-- защищён от перезаписи чужого ручного снимка, значит вставка может не
-- состояться, и тогда галерею вулкана трогать нельзя. Тот же порядок, что у
-- переезда в S3: сначала прочитать, что объект на месте, потом обнулить.
DELETE FROM place_gallery_photos g
 USING places p
 WHERE p.id::text = '164f612c-32da-4f0f-b261-c45c09dc2933'
   AND g.ark_id   = p.ark_id
   AND g.position = 1
   AND g.caption  = 'Гамулы на фоне хребта'
   AND EXISTS (
         SELECT 1
           FROM ai_route_images ai
           -- Обе стороны приведены к тексту явно: сторож
           -- migration-id-type-domain требует этого от сверки id разных
           -- таблиц, и требует по делу — у places есть и id (text), и
           -- ark_id (uuid), и перепутать их в JOIN легче, чем кажется.
           JOIN places pass ON pass.ark_id::text = ai.route_id::text
          WHERE pass.id::text = '8bad8fe6-c7ec-4403-b956-948706649ca8'
            AND ai.prompt = 'снимок владельца: гамулы на Вилючинском перевале (миграция 980)'
       );

-- ── Отказ называется вслух ────────────────────────────────────────────────
DO $$
DECLARE
  v_ark    uuid;
  v_prompt text;
BEGIN
  SELECT ark_id INTO v_ark FROM places WHERE id::text = '8bad8fe6-c7ec-4403-b956-948706649ca8';

  IF v_ark IS NULL THEN
    RAISE WARNING '[980] у «Вилючинского перевала» нет ark_id — снимок гамулов НЕ лёг, карточка осталась без фото';
    RETURN;
  END IF;

  SELECT prompt INTO v_prompt FROM ai_route_images WHERE route_id = v_ark;

  IF v_prompt IS DISTINCT FROM 'снимок владельца: гамулы на Вилючинском перевале (миграция 980)' THEN
    RAISE WARNING '[980] герой перевала НЕ стал гамулами: строку держит другой ручной снимок (prompt=%)', COALESCE(v_prompt, 'строки нет');
  END IF;
END $$;

COMMIT;
