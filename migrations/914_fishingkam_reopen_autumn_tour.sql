-- 914: Вернуть на витрину осенний тур «Камчатской рыбалки».
--
-- Источник: 837 сняла тур id=4 («Осенняя рыбалка, октябрь-ноябрь») с витрины
-- 07.08.2026 вместе с четырьмя другими — «оставим пока только актуальные».
-- Владелец 24.08.2026 попросил вернуть именно осенний тур, остальные четыре
-- (7 семейный выходного дня, 9-11 многодневные) решение не затрагивает и
-- остаются скрытыми.
--
-- Матчим по id И операторy — тот же якорь, что у 837, чтобы не задеть
-- совпадение id у чужого партнёра. Идемпотентна.

UPDATE operator_tours ot
   SET is_published = TRUE,
       updated_at   = NOW()
 WHERE ot.id = 4
   AND ot.deleted_at IS NULL
   AND ot.is_published = FALSE
   AND ot.operator_id = (SELECT id FROM partners WHERE name ILIKE 'камчатская рыбалка' LIMIT 1);
