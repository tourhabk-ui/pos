--
-- Ключевская сопка: описание из фактов вместо сочинённого.
--
-- ── Повод (19.09) ──────────────────────────────────────────────────────────
--
-- Владелец показал пост канала про Ключевскую и спросил: «что за сочинение,
-- вулкан потухший». Пост оказался ни при чём — он дословно перепечатал
-- `places.description`. Текст лежал в базе:
--
--   «...запах серы и остывающего камня... над головой курится вершина, где
--    лава выходит наружу раз в несколько лет... Кто добирается до верха, тот
--    запоминает не панораму, а тишину...»
--
-- Ни запаха, ни звука, ни частоты извержений в наших данных нет. Сочинил это
-- промпт `POST /api/admin/enrich-places`: модели дают имя, тип, район,
-- координаты и высоту, а в конце просят «напиши описание так, БУДТО ТЫ ТОЛЬКО
-- ЧТО ВЕРНУЛСЯ ОТТУДА». Требование, которое нечем выполнить, выполняется
-- выдумкой — тот же корень, что у «секрета места» в посте 19.08 и у рейтинга
-- 4.5 у неоценённого перевозчика (CLAUDE.md §4.0).
--
-- ── Почему это не вопрос вкуса ─────────────────────────────────────────────
--
-- Выдумка испортила не слог, а ЦЕНТРАЛЬНЫЙ ФАКТ. Ключевская — самый активный
-- вулкан Камчатки и один из самых активных на планете: извержения идут почти
-- ежегодно, часто месяцами подряд. «Остывающий камень» и «лава раз в несколько
-- лет» описывают затухающий вулкан. Турист, читающий нашу карточку, получал
-- обратное представление об опасности места — на платформе, которая
-- существует ради его безопасности.
--
-- ── Что здесь заменяется, и чем ────────────────────────────────────────────
--
-- Новый текст собран из проверяемого: высота и её изменчивость, частота
-- извержений, пепел на авиационных эшелонах (по нему KVERT присваивает
-- цветовой код — у нас для этого есть крон `kvert-acc`), охранный статус
-- ЮНЕСКО, сложность восхождения. Сенсорных утверждений в нём нет ни одного:
-- у нас нет источника, который позволил бы их сделать.
--
-- ── Два факта — со слов владельца, и это названный источник ────────────────
--
-- «Ключевская самый опасный вулкан, погода меняется за секунды» — поправка
-- владельца к первой редакции этого текста. Оба факта в неё не попали: я
-- написал про техническую сложность восхождения и умолчал о том, ради чего
-- человек вообще читает карточку опасного места.
--
-- Это не выдумка и не догадка: у утверждения есть источник — человек, который
-- живёт на Камчатке и отвечает за платформу. Так же записаны подвоз туристов
-- (миграция 934) и условия отмены (935): владелец сказал — записали дословно
-- по смыслу и назвали, чьё это слово. Разница между таким фактом и сочинённым
-- «запахом остывающего камня» именно в этом, а не в правдоподобии.
--
-- Перечень опасностей места живёт не здесь, а в `location_safety_profile`
-- (§9, блок «Что знать»). Описание не подменяет его: оно говорит о характере
-- места, а не выдаёт себя за инструкцию.
--
-- Последняя фраза отправляет за текущим состоянием к живым данным платформы,
-- а не замораживает его в тексте: обстановка на действующем вулкане меняется
-- чаще, чем описание.
--
-- ── Границы правки ─────────────────────────────────────────────────────────
--
-- Правится ОДНО место и только если там лежит ровно тот сочинённый текст:
-- отбор идёт по его началу, а не по имени. Успел кто-то поправить раньше —
-- миграция не делает ничего. Соседние записи («Ключевской природный парк»,
-- «Ключевская группа вулканов») не затрагиваются по построению.
--
-- Машину, которая это написала, миграция НЕ чинит: промпт живёт в коде, и его
-- правка — отдельная работа. Это починка одной самой заметной записи, а не
-- решение задачи.
--
-- Идемпотентна.

WITH upd AS (
  UPDATE places
     SET description = 'Действующий вулкан Ключевской группы и самый высокий действующий вулкан Евразии: около 4750 метров, причём высота меняется после извержений. Один из самых активных вулканов планеты — извержения случаются почти ежегодно, с лавовыми потоками и пепловыми выбросами; пепел поднимается до авиационных эшелонов, поэтому вулкану присваивают авиационный цветовой код. Это самый опасный вулкан края. Погода на склоне меняется за секунды, восхождение технически сложное и требует подготовки, а в периоды активности подходы закрывают. Входит в объект Всемирного наследия ЮНЕСКО «Вулканы Камчатки». Текущее состояние смотрите в статусе места и в предупреждениях платформы: оно меняется чаще, чем это описание.',
         updated_at = NOW()
   WHERE description LIKE 'К подножию Ключевской подходишь уже издали%'
  RETURNING ark_id, name, description, 570 AS prev_chars
)
INSERT INTO description_provenance
  (entity_id, entity_kind, entity_title, written_by, facts_given, facts_count,
   chars, previous_chars)
SELECT
  upd.ark_id,
  'place',
  upd.name,
  -- Не 'editor-ai': текст написан человеком по решению владельца, и в журнале
  -- это должно быть видно. Машинный и решённый текст — разные вещи.
  'owner-decision',
  '["высота и её изменчивость","частота извержений","пепел на авиационных эшелонах (KVERT)","самый опасный вулкан края (слово владельца)","погода меняется за секунды (слово владельца)","сложность восхождения","ЮНЕСКО"]'::jsonb,
  7,
  LENGTH(upd.description),
  upd.prev_chars
FROM upd
WHERE upd.ark_id IS NOT NULL;
