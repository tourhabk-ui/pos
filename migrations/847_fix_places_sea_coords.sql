-- Партия ремонта координат №4 (после 751/752/753): точки в открытом море.
-- Скрин владельца 14.08: фильтр «Источники» на карте показал термальные
-- источники посреди Охотского моря. Перепись всех 419 точек с координатами
-- по контуру берега (lib/geo/land.ts, probe runs 34-38, отчёт
-- data/audit/places-coords-census-2026-08-15.json): 13 точек в море дальше
-- 2 км от берега, из них 7 с публично верифицируемыми координатами — они
-- здесь. Подпись битых координат одна и та же: долгота уехала на 3-5°
-- (Нижне-Семячикские: 155.08 вместо 160.04 при точной широте) либо круглые
-- рукозабитые числа («53, 158.6»).
--
-- Источники координат (Wikipedia API, prop=coordinates, сняты probe 35-38):
--   Паужетка (посёлок)                    51.46472 156.80694
--   Нижне-Семячикские горячие источники   54.2094  160.0419
--   Паланские Ключи (посёлок при ист.)    58.8451  161.325
--   Паланское (озеро, исток р. Паланы)    58.8261  160.8163
--   Налычево (природный парк)             53.5     159.0
--   Никольская сопка                      53.02028 158.64222
--   Жупанова (река, устье)                53.6719  159.8411
--
-- Каждая замена проверена контуром берега: все новые точки на суше (озеро
-- Паланское — 63 км вглубь, Паланские Ключи — 65 км), кроме устья Жупановой
-- (0.3 км от кромки — это устье, ему положено).
--
-- Правило то же, что в 751: обновляем ТОЛЬКО если текущая координата дальше
-- ~2 км от верифицированной — ручные правки админкой не перетираем.
-- Идемпотентна.
--
-- НЕ трогаем (сознательно, перепись их видела):
--   Озеро Нерпичье          — координаты ВЕРНЫ (вики-центр в 3 км); «морем»
--                             его читает упрощение контура, съевшее косу
--                             Усть-Камчатска. Ограничение задокументировано
--                             тестом land-check.
--   Остров Старичков        — координаты верны, остров мал для контура.
--   Река Авача — рыбалка    — вики-точка реки = устье в Авачинской бухте,
--                             переезд из воды в воду смысла не имеет; где
--                             рыбацкое место — решение владельца.
--   Бухты, лиманы, мысы,
--   лежбища, маяки          — вода/кромка по природе, не дефект.
--   Командорский заповедник — морская ООПТ, точка в акватории осмысленна.
--   Корякский заповедник    — вики-точка сама в 2.4 км в море; из моря в
--                             море не переезжаем, нужен другой источник.
--   Дубли на одной точке (решение владельца, не координаты):
--     «Шишель» + «Гора Шишель» (57.45, 160.37);
--     «Природный парк «Налычево»» + «Природный парк Налычево» — два разных
--     ряда об одном парке;
--     «Налычевская долина» + «Налычевские горячие источники» (53.2308,
--     158.6817) — источники сидят на точке долины, своей точной нет.

UPDATE places SET lat = 51.4647, lng = 156.8069, updated_at = NOW()
 WHERE name = 'Паужетские термальные источники'
   AND (lat IS NULL OR abs(lat - 51.4647) > 0.02 OR abs(lng - 156.8069) > 0.03);

