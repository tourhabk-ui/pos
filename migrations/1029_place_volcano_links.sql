--
-- Радиус опасной зоны у вулканологов в открытых источниках не найден (пробы
-- 596-602: парк пишет «не приближаться», МЧС и KVERT числа не дают), а связи
-- маршрутов к вулкану размечены как «рядом». Поэтому привязка — поимённая:
-- перепись упоминаний (scripts/volcano-affinity-scan.ts, 185 совпадений у 36
-- вулканов) → отбор мест у самого вулкана → «да» владельца 26.09.
-- Выводить привязку из расстояния ЗАПРЕЩЕНО тем же правилом, что род связи
-- маршрута (§4.1): число без источника — выдумка.
--
-- place_id / volcano_place_id — TEXT без FK: places.id на проде TEXT (см.
-- шапку 849). Целостность держит вставка ниже — строка ложится, только если
-- обе записи есть и названия совпадают с ожидаемыми.

CREATE TABLE IF NOT EXISTS place_volcano_links (
  place_id         TEXT NOT NULL,
  volcano_place_id TEXT NOT NULL,
  -- Почему место относится к вулкану — словами. Пустой причины не бывает.
  reason           TEXT NOT NULL CHECK (length(trim(reason)) > 0),
  created_at       TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  PRIMARY KEY (place_id, volcano_place_id)
);

CREATE INDEX IF NOT EXISTS idx_place_volcano_links_volcano ON place_volcano_links (volcano_place_id);

