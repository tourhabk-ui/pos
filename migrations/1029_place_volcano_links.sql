-- 1029: место относится к вулкану — привязка поимённо, по решению владельца.
--
-- 26.09 статус места стал подниматься кодами вулкана (safety-ingest: KVERT и
-- КФ ЕГС). Шивелуч стал красным, Мутновский — жёлтым, а места у самого
