-- 1180: у «Кутхи» не записаны часы заезда и выезда (#2238).
--
-- Проба 717 (08.10) показала на карточке «заезд с 14:00 · выезд до 12:00».
-- Этих часов не называл никто: колонки check_in_time / check_out_time
-- заполняются умолчанием базы (14:00 и 12:00) у любой строки, где их не
-- задали, и миграция 1179 их не задавала. Выглядит как условие объекта,
-- а это число из схемы — ровно то место, где нельзя сказать «не знаю» и
-- оно заполняется враньём (§4.0). Турист мог бы приехать к 14:00 к
-- владельцу, который об этом не договаривался.
--
-- «Не записано» — NULL: карточка в этом случае строки про заезд не рисует
-- (toHHMM(null) → null). Условие узкое: только если у «Кутхи» стоят
-- ровно прежние умолчания. Если администратор уже записал другие часы,
-- строка не тронута.
--
-- Идемпотентна: повтор не находит строк с этими значениями.

UPDATE accommodations
   SET check_in_time = NULL,
       check_out_time = NULL
 WHERE LOWER(name) = 'кутха'
   AND check_in_time = TIME '14:00'
   AND check_out_time = TIME '12:00';
