-- ── Из чего новый текст ───────────────────────────────────────────────────
--
-- Только из статьи Википедии «Памятник Витусу Берингу», снятой с раннера
-- пробой 675 (статья ссылается на В. П. Мартыненко, «Памятники
-- Петропавловска-Камчатского», 1989). Чего в статье нет — нет и здесь:
-- автора проекта, высоты, «старейшего памятника края».
--
-- Отзыв Кузьмича — пустая строка, не NULL: агент kuzmich-place-enricher
-- берёт только NULL и написал бы новый на месте старого. Пустая строка лучше
-- придуманной (§4.0); карточка пустой отзыв не показывает.
--
-- Координата (53.011, 158.653) не трогается: проверенного эталона в этой
-- правке нет, а без эталона координаты не двигают (§4.1).
--
-- Отбор — по id и по самим сочинённым оборотам: переписано руками раньше —
-- no-op. Идемпотентна.

BEGIN;

WITH old AS (
  SELECT id, LENGTH(description) AS prev_chars
    FROM places
   WHERE id::text = 'c4d5e6f7-a8b9-4012-defa-123456789012'
     AND description LIKE '%Сырой ветер с Авачинской бухты%'
),
upd AS (
  UPDATE places p
     SET description = 'Памятник Витусу Берингу стоит в центре Петропавловска-Камчатского, на улице Ленинской. Это не скульптура: на небольшом цоколе — двухметровая металлическая колонна, похожая на орудийный ствол, с капителью; её венчает цветок лотоса, в раскрытых лепестках которого лежит пушечное ядро. На четырёх гранях металлического цоколя — барельефы лавровых венков со скрещёнными факелами. Основание — массивный тёсаный камень, на нём чугунная плита с надписью «Основателю Петропавловска в 1740 году мореплавателю Витусу Берингу».

Беринг руководил Второй Камчатской экспедицией: место для зимовки её команды и стало поводом заложить Петропавловск в 1740 году. Первым памятник упоминает английский мореплаватель Фредерик Уильям Бичи, побывавший в порту в 1827 году: тогда он стоял в саду губернатора, напротив памятника капитану Клерку. Потом его не раз переносили — к городскому собору, в 1930-е годы напротив кинотеатра «Полярная звезда» на нынешней улице Ленинской. На нынешнее место памятник поставлен по распоряжению исполкома Петропавловского горсовета от 16 октября 1945 года. Объект культурного наследия.

Источник: статья Википедии «Памятник Витусу Берингу» (по книге В. П. Мартыненко «Памятники Петропавловска-Камчатского», 1989).',
         updated_at = NOW()
    FROM old
   WHERE p.id::text = old.id::text
  RETURNING p.ark_id, p.name, p.description, old.prev_chars
)
INSERT INTO description_provenance
  (entity_id, entity_kind, entity_title, written_by, facts_given, facts_count,
   chars, previous_chars)
SELECT
  upd.ark_id,
  'place',
  upd.name,
  'owner-decision',
  '["в центре города, на улице Ленинской (Википедия, «Памятник Витусу Берингу»)","двухметровая металлическая колонна в виде орудийного ствола с капителью, лотос с пушечным ядром; барельефы лавровых венков со скрещёнными факелами; основание из тёсаного камня; чугунная плита с надписью «Основателю Петропавловска в 1740 году мореплавателю Витусу Берингу» (там же)","Беринг — руководитель Второй Камчатской экспедиции; зимовка её команды — повод закладки Петропавловска в 1740 году (там же)","первое упоминание — Ф. У. Бичи, 1827: в саду губернатора напротив памятника Клерку (там же)","переносы: к собору, в 1930-е — напротив кинотеатра «Полярная звезда»; нынешнее место — по распоряжению горисполкома от 16.10.1945 (там же)","объект культурного наследия, № 251410017600006 (там же)"]'::jsonb,
  6,
  LENGTH(upd.description),
  upd.prev_chars
FROM upd
WHERE upd.ark_id IS NOT NULL;

-- Отзыв Кузьмича — пустой, а не придуманный (см. шапку).
UPDATE places
   SET kuzmich_review = '', updated_at = NOW()
 WHERE id::text = 'c4d5e6f7-a8b9-4012-defa-123456789012'
   AND kuzmich_review LIKE '%Гляди на Беринга%';

COMMIT;

