-- Владелец 03.10, снимок карточки: «сочинение, любой местный опровергнет, он
-- стоит в центральной части города». На проде лежало: «Сырой ветер с
-- Авачинской бухты… Чайки сидят на мокром граните парапета, косо глядя на
-- бронзовую фигуру. Беринг повёрнут к океану — туда, где в последний раз
-- уходил его пакетбот…». Бронзовой фигуры нет: памятник — металлическая
-- колонна в виде орудийного ствола с ядром на цветке лотоса, и стоит он не на
-- берегу, а на улице Ленинской. Отзыв Кузьмича того же рода («Гляди на
-- Беринга — он глядит туда…»). Запись 103 тоже ошибалась («на набережной»,
-- «бронзовый бюст»).
