-- 13.10 (решение владельца «согласен, перенеси в S3»): байты снимков вынесены в
-- хранилище — ключ migrations/photos/<sha256>.jpg из маркера
-- .github/triggers/migration-photos-to-s3.json (sha256 тех же байтов). Миграция
-- пишет s3_key, image_data пуст; прод переведён по хэшу байтов миграцией 1228.
--
-- 984: «Шивелуч» — каньон, снимок гида-партнёра.
--
-- ── Чей снимок и на каком основании он здесь ──────────────────────────────
--
-- Кадр ЧУЖОЙ, и это главное отличие от миграций 977/979/981/983, где владелец
-- сказал «фото моё». Здесь он сказал другое, и записываю дословно:
--
--   «Андрей гид с нами сторудничает, @andrei_zaporozhets вот его тг»
--   «@andrei_zaporozhets автор фото»
--
-- Я дважды сказал вслух, что сотрудничество само по себе не есть разрешение
-- на публикацию: права остаются у снимавшего. Владелец на это ответил не
-- отменой, а подписью — то есть распорядился публиковать с кредитом автора.
-- Это ЕГО решение как владельца платформы, и оно записано здесь именно так,
-- а не превращено в «автор разрешил»: письменного согласия самого Андрея у
-- меня нет, и делать вид, что есть, значило бы выдумать источник права
-- (§4.0). Появится его слово — оно дописывается сюда, а не заменяет это.
--
-- `author` — ИМЯ, а не телеграм-адрес. Сначала владелец назвал автора слогом
-- «@andrei_zaporozhets», и я сказал, что адрес — не подпись: турист на
-- карточке должен прочитать человека. Имя он прислал следом: «Андрей
-- Запорожец». Оно и стоит в поле.
--
-- Вывести это имя из слога адреса было бы можно и без вопроса — но это была
-- бы догадка о живом человеке на публичной странице, а в той истории, откуда
-- пришёл кадр, он подписан ещё и «Андрей Виртус». Два известных написания не
-- сходились, и спросить стоило дешевле, чем угадать. Адрес остаётся здесь как
-- способ связи, а не как подпись.
--
-- Лицензия не ставится: её никто не называл. Пустое поле честнее выдуманной
-- строки — ровно по тому же правилу, по которому 22 снимка с Викимедии до сих
-- пор скрыты (у них нет автора, и подписать их нечем).
--
-- ── Почему именно эта запись ──────────────────────────────────────────────
--
-- Проба 533 (GET /api/cron/place-audit?q=шивелуч):
--
--   77e5d9e1  «Шивелуч»         56.636613/161.312207  ЖИВАЯ            ← сюда
--   9ed17d44  «Вулкан Шивелуч»  скрыта, слита в 77e5d9e1
--
-- Четвёртый случай подряд, когда живой оказывается НЕ та запись, что выглядит
-- очевидной по имени (Вилючинский, Авачинский, Корякский, теперь Шивелуч).
--
-- Кадр — каньон, а не конус, и по-хорошему ему полагается своя запись.
-- Отдельной записи каньона у Шивелуча в каталоге НЕТ (та же проба, запрос
-- «каньон»: пять каньонов, ни одного здесь). Поэтому снимок ложится на
-- карточку вулкана, а не заводит место: заводить географический объект по
-- одной фотографии — это сочинить его координаты, которых у меня нет.
--
-- ── Размер ────────────────────────────────────────────────────────────────
--
-- Исходник 1080x1637 — заметно меньше сегодняшних кадров владельца
-- (4000x3000) и похож на кадр вертикального видео. Окно 16:9 полной ширины
-- со смещением 12% сверху: стены каньона, русло с пеплом, снежный гребень на
-- заднем плане.
--
-- Записывается РОДНОЙ размер 1080x608, а не канонные 1280x720. Растянуть
-- 1080 до 1280 значило бы дорисовать резкость, которой в кадре нет: файл
-- потяжелел бы, а картинка — нет. Канон описывает потолок, а не обязанность
-- увеличивать.
--
-- ── Как ложится ───────────────────────────────────────────────────────────
--
-- Герой карточки. Машинная картинка и скрейп заменяются, чужой РУЧНОЙ снимок
-- — нет. Байты пишутся в базу, а не в хранилище: миграция накатывается при
-- старте сервера, сетевой вызов оттуда стопорил бы весь накат; увезёт
-- уборщик cron-images-to-s3 (§4.1). s3_url/s3_key гасятся — старый объект
-- этим байтам не соответствует.
--
-- Третий исход назван вслух: нет ark_id или строку держит чужой ручной кадр —
-- RAISE WARNING в лог выката, а не молчание (урок миграции 976) и не падение
-- (снимок не стоит боевой загрузки сервера).
--
-- IDEMPOTENT

BEGIN;

INSERT INTO ai_route_images (route_id, image_data, mime_type, prompt, model, width, height, author, s3_key)
SELECT p.ark_id,
       NULL::bytea,
       'image/jpeg',
       'снимок Андрея Запорожца: каньон у вулкана Шивелуч (миграция 984)',
       'manual-upload',
       1080,
       608,
       'Андрей Запорожец',
       'migrations/photos/05fb32b4059e65311aa8f53fdce6349f912a54ffb6b668673f12b53802fee6c7.jpg'
  FROM places p
 WHERE p.id::text = '77e5d9e1-4746-45fc-bb1a-8527003edf5f'
   AND p.ark_id IS NOT NULL
 LIMIT 1
ON CONFLICT (route_id) DO UPDATE
   SET image_data = EXCLUDED.image_data,
       mime_type  = EXCLUDED.mime_type,
       prompt     = EXCLUDED.prompt,
       model      = EXCLUDED.model,
       width      = EXCLUDED.width,
       height     = EXCLUDED.height,
       author     = EXCLUDED.author,
       s3_url     = NULL,
       s3_key     = EXCLUDED.s3_key,
       created_at = NOW()
 WHERE ai_route_images.model NOT IN ('wikimedia', 'manual-upload')
    OR ai_route_images.prompt = 'снимок Андрея Запорожца: каньон у вулкана Шивелуч (миграция 984)';

-- ── Отказ называется вслух ────────────────────────────────────────────────
DO $$
DECLARE
  v_ark    uuid;
  v_prompt text;
BEGIN
  SELECT ark_id INTO v_ark FROM places WHERE id::text = '77e5d9e1-4746-45fc-bb1a-8527003edf5f';

  IF v_ark IS NULL THEN
    RAISE WARNING '[984] у «Шивелуча» нет ark_id — снимок каньона НЕ лёг, карточка осталась с прежним фото';
    RETURN;
  END IF;

  SELECT prompt INTO v_prompt FROM ai_route_images WHERE route_id = v_ark;

  IF v_prompt IS DISTINCT FROM 'снимок Андрея Запорожца: каньон у вулкана Шивелуч (миграция 984)' THEN
    RAISE WARNING '[984] герой Шивелуча НЕ стал снимком каньона: строку держит другой ручной снимок (prompt=%)', COALESCE(v_prompt, 'строки нет');
  END IF;
END $$;

COMMIT;
