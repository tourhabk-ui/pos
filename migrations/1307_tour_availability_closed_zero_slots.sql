-- 1307: закрытая дата тура держит ноль мест (аудит 15.10, пункт 1.15, P3-14).
--
-- Блокировка дат оператором (POST /api/operator/calendar/block) пишет закрытую
-- дату с available_slots = 0, а CHECK slots_valid (040) требовал больше нуля.
-- PostgreSQL проверяет CHECK у предлагаемой строки ДО разбора ON CONFLICT,
-- поэтому отказ 23514 получала любая блокировка — и новой даты, и уже открытой:
-- роут отвечал 500 с самого заведения. Найдено проверкой на настоящем
-- PostgreSQL при переводе блокировки на одно выражение
-- (tests/integration/tour-availability-batch.pg.test.ts).
--
-- Закрытая дата мест не продаёт, и ноль у неё — правда. Придумывать ей
-- «одно место», чтобы пройти проверку, — та самая выдумка, от которой §4.0.
-- Открытая дата по-прежнему обязана иметь хотя бы одно место. NULL в
-- is_cancelled считается открытой датой (умолчание колонки — false).
--
-- Идемпотентно: снять и поставить заново одно и то же условие безопасно.
-- Ослабление: строки, прошедшие прежнюю проверку, проходят и эту.

ALTER TABLE tour_availability DROP CONSTRAINT IF EXISTS slots_valid;
ALTER TABLE tour_availability
  ADD CONSTRAINT slots_valid CHECK (available_slots > 0 OR COALESCE(is_cancelled, FALSE));
