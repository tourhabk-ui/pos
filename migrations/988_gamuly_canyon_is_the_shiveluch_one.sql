-- 13.10 (решение владельца «согласен, перенеси в S3»): байты снимков вынесены в
-- хранилище — ключ migrations/photos/<sha256>.jpg из маркера
-- .github/triggers/migration-photos-to-s3.json (sha256 тех же байтов). Миграция
-- пишет s3_key, image_data пуст; прод переведён по хэшу байтов миграцией 1228.
--
-- 988: каньон на Шивелуче — это «Крылья Гамулов». Дубль снимается, снимки
--      и описание переезжают к настоящей записи.
--
-- ── Я ошибся, и вот в чём ─────────────────────────────────────────────────
--
-- Миграцией 986 я завёл место «Каньон на Шивелуче» по координате из MAPS.ME
-- (56.56557/161.227291) и в её же шапке написал, что стоящая в 780 метрах
-- запись «Каньон Крылья Гамулов (Дракон)» (56.566506/161.214709) имеет
-- НЕВЕРНУЮ КООРДИНАТУ, потому что «Крылья Гамулов — настоящий, известный
-- объект под Мутновским».
--
-- Это утверждение неверно, и взято оно было из памяти, а не из источника.
-- Владелец поправил: Крылья Гамулов, он же каньон Дракона, находится в
-- окрестностях вулкана ШИВЕЛУЧ. То есть координата записи ВЕРНА, а выдумано
-- было её описание — ровно как у соседнего «Каньона Опасного», где текст
-- называл Карымский при координате у Мутновского.
--
-- Следствие: две записи об ОДНОМ каньоне, и лишняя — моя. Настоящая старше,
-- у неё собственное имя с алиасом, тип и профиль безопасности; новая не
-- несёт ничего, кроме координаты, которая от старой отличается на 780 м —
-- то есть на длину самого каньона.
--
-- Урок записан сюда, а не в переписку: я судил по памяти там, где у соседней
-- записи уже был ответ в данных, и уверенность была тем выше, чем меньше я
-- проверял. Предыдущая миграция при этом ЧЕСТНО оговаривала, что сверка с
-- OSM источника не дала, — и всё равно вынесла приговор координате. Правило
-- §4.1 «улика — не приговор» нарушено мной в тот же день, когда я на него
-- ссылался.
--
-- ── Что делает миграция ───────────────────────────────────────────────────
--
--   1) описание Крыльев Гамулов заменяется на слова владельца (было — про
--      Мутновский, за 498 км);
--   2) снимок каньона (Андрей Запорожец, миграция 984) переезжает с дубля на
--      настоящую запись: UPDATE route_id, байты те же, копии нет;
--   3) два новых кадра того же автора ложатся в галерею;
--   4) дубль скрывается и помечается слитым в Крылья Гамулов — НЕ удаляется:
--      у записи уже есть id, на который мог сослаться кто угодно, и удаление
--      превратило бы ссылку в пустоту вместо перенаправления.
--
-- Координату Крыльев Гамулов НЕ трогаю: владелец подтвердил её дословно
-- («56.566506N 161.214709E»), и она же стоит в записи.
--
-- ── Права на снимки ───────────────────────────────────────────────────────
--
-- Автор всех трёх кадров — Андрей Запорожец, гид-партнёр; публикация с его
-- подписью — решение владельца, записанное в шапке 984 и здесь не
-- переигрывается.
--
-- ТРЕТИЙ КАДР В ЭТУ МИГРАЦИЮ НЕ ВОШЁЛ. На нём у подножия скалы стоит
-- РЕБЁНОК, и лицо различимо. Согласия на публикацию лица у нас нет, а
-- карточка публичная. Это не моя осторожность, а уже принятое в этом
-- репозитории правило: миграция 967 отбросила половину кадра ровно поэтому —
-- «согласия этих людей у нас нет, а карточка публичная». Кадр придержан до
-- слова владельца.
--
-- ── Форма кадров ──────────────────────────────────────────────────────────
--
-- Оба пришли снимками экрана сторис: сверху шапка мессенджера, снизу подпись
-- и строка ответа. Обрезано ровно лишнее, само фото не кадрировалось.
-- Размеры записаны РОДНЫЕ, вертикальные: растягивать до канона 1280x720
-- значило бы дорисовать резкость и срезать стены каньона, ради которых кадр
-- и снят.
--
-- IDEMPOTENT

BEGIN;

-- ── 1. Описание: слова владельца вместо выдуманного Мутновского ───────────
UPDATE places
   SET description = 'Каньон «Крылья Гамулов» (второе название — каньон Дракона) — это уникальный природный объект на Камчатке, расположенный в окрестностях активного вулкана Шивелуч.',
       updated_at  = NOW()
 WHERE id::text = 'c03b364f-55c3-4944-8505-3e86058999fa'
   AND description IS DISTINCT FROM 'Каньон «Крылья Гамулов» (второе название — каньон Дракона) — это уникальный природный объект на Камчатке, расположенный в окрестностях активного вулкана Шивелуч.';

-- ── 2. Снимок каньона переезжает с дубля на настоящую запись ──────────────
UPDATE ai_route_images
   SET route_id = (SELECT ark_id FROM places WHERE id::text = 'c03b364f-55c3-4944-8505-3e86058999fa')
 WHERE route_id = 'b3d7eb6c-2ac4-41d9-89fe-52d073c3488d'
   AND prompt = 'снимок Андрея Запорожца: каньон у вулкана Шивелуч (миграция 984)'
   AND (SELECT ark_id FROM places WHERE id::text = 'c03b364f-55c3-4944-8505-3e86058999fa') IS NOT NULL;

-- ── 3. Ещё два кадра того же автора — в галерею ───────────────────────────
INSERT INTO place_gallery_photos (ark_id, position, image_data, mime_type, width, height, caption, author, s3_key)
SELECT p.ark_id,
       1,
       NULL::bytea,
       'image/jpeg',
       1080,
       1580,
       'Дно каньона между пепловыми стенами',
       'Андрей Запорожец',
       'migrations/photos/2b582e090a76b2ac7436f9fc90377d6fe4b6c8234e7ef87b75dc23211469001f.jpg'
  FROM places p
 WHERE p.id::text = 'c03b364f-55c3-4944-8505-3e86058999fa'
   AND p.ark_id IS NOT NULL
 LIMIT 1
ON CONFLICT (ark_id, position) DO UPDATE
   SET image_data = EXCLUDED.image_data,
       s3_key     = EXCLUDED.s3_key,
       mime_type  = EXCLUDED.mime_type,
       width      = EXCLUDED.width,
       height     = EXCLUDED.height,
       caption    = EXCLUDED.caption,
       author     = EXCLUDED.author,
       s3_url     = NULL,
       created_at = NOW();

INSERT INTO place_gallery_photos (ark_id, position, image_data, mime_type, width, height, caption, author, s3_key)
SELECT p.ark_id,
       2,
       NULL::bytea,
       'image/jpeg',
       1080,
       1290,
       'Скала-останец на пепловом поле, за ней Шивелуч в облаках',
       'Андрей Запорожец',
       'migrations/photos/e6e7ac71d60bee449fa9a7aa14606608f839f5b1846c4d721bc1761fc0c87b00.jpg'
  FROM places p
 WHERE p.id::text = 'c03b364f-55c3-4944-8505-3e86058999fa'
   AND p.ark_id IS NOT NULL
 LIMIT 1
ON CONFLICT (ark_id, position) DO UPDATE
   SET image_data = EXCLUDED.image_data,
       s3_key     = EXCLUDED.s3_key,
       mime_type  = EXCLUDED.mime_type,
       width      = EXCLUDED.width,
       height     = EXCLUDED.height,
       caption    = EXCLUDED.caption,
       author     = EXCLUDED.author,
       s3_url     = NULL,
       created_at = NOW();

-- ── 4. Дубль скрывается и помечается слитым ───────────────────────────────
--
-- ТОЛЬКО ПОСЛЕ того, как снимок подтверждённо уехал. Скрытие дубля само по
-- себе безобидно, но если переезд не состоялся (у настоящей записи нет
-- ark_id), кадр остаётся на СКРЫТОЙ карточке — то есть исчезает с глаз,
-- оставаясь в базе. Проверено на настоящем PostgreSQL: без этого условия
-- ровно так и выходило.
--
-- Тот же порядок, что в миграции 980 и у переезда снимков в хранилище:
-- сначала убедиться, что копия на месте, потом убирать исходное.
UPDATE places
   SET is_visible     = FALSE,
       merged_into_id = 'c03b364f-55c3-4944-8505-3e86058999fa',
       merged_at      = NOW(),
       updated_at     = NOW()
 -- Без явного ::uuid: тип берётся у колонки merged_into_id, а приведение к
 -- uuid запрещено сторожем доменов — places.id это TEXT, и такое приведение
 -- падает на первой же не-uuid записи.
 WHERE id::text = '002f9a4f-8833-4ee7-8dc4-290b30092cb7'
   AND (is_visible OR merged_into_id IS NULL)
   AND EXISTS (
         SELECT 1 FROM ai_route_images ai
          WHERE ai.route_id = (SELECT ark_id FROM places WHERE id::text = 'c03b364f-55c3-4944-8505-3e86058999fa')
            AND ai.prompt = 'снимок Андрея Запорожца: каньон у вулкана Шивелуч (миграция 984)'
       );

-- ── Исход называется вслух ────────────────────────────────────────────────
DO $$
DECLARE
  v_gam_ark uuid;
  v_photos  int;
  v_dup_vis boolean;
BEGIN
  SELECT ark_id INTO v_gam_ark FROM places WHERE id::text = 'c03b364f-55c3-4944-8505-3e86058999fa';

  IF v_gam_ark IS NULL THEN
    RAISE WARNING '[988] у «Крыльев Гамулов» нет ark_id — ни снимок, ни галерея не легли';
    RETURN;
  END IF;

  SELECT count(*) INTO v_photos FROM ai_route_images WHERE route_id = v_gam_ark;
  IF v_photos = 0 THEN
    RAISE WARNING '[988] снимок каньона не переехал на «Крылья Гамулов» — карточка осталась без главного фото';
  END IF;

  SELECT is_visible INTO v_dup_vis FROM places WHERE id::text = '002f9a4f-8833-4ee7-8dc4-290b30092cb7';
  IF v_dup_vis IS TRUE THEN
    RAISE WARNING '[988] дубль «Каньон на Шивелуче» всё ещё виден — на карте останутся два каньона в 780 метрах';
  END IF;
END $$;

COMMIT;
