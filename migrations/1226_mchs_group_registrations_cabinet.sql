-- Список «Регистрации групп в МЧС» (app/api/operator/mchs-registrations)
-- читает строки кабинета по operator_partner_id. Строка без кабинета
-- (operator_partner_id IS NULL) находилась только по аккаунту автора
-- (operator_user_id): владелец её видел, менеджер его команды (миграция 1223)
-- — нет. Шаг 2г-3 плана команды (#2313): менеджер видит то же, что владелец.
--
-- Кабинет ставится по профилю оператора автора. Профиль оператора у
-- человека один — уникальный индекс idx_partners_user_category
-- (user_id, category) в baseline, — так что строке достаётся ровно один
-- кабинет или ни одного. Автор без профиля оператора остаётся как был:
-- угадывать кабинет не из чего.
--
-- Сколько таких строк на проде, не известно: роут с мая пишет кабинет в
-- каждую новую строку, и пустых может не быть вовсе. Миграция от этого не
-- зависит — трогает только строки без кабинета и повторный прогон ничего
-- не меняет.

BEGIN;

UPDATE mchs_group_registrations m
   SET operator_partner_id = p.id
  FROM partners p
 WHERE m.operator_partner_id IS NULL
   AND m.operator_user_id IS NOT NULL
   AND p.user_id = m.operator_user_id
   AND p.category = 'operator';

COMMIT;

