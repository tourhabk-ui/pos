-- 754_unlink_junk_waypoints.sql
--
-- Решение владельца (скрин 2026-07-18, «рыболовная база далеко от этих
-- точек»): у карточки «Рыболовная база «Камчатская Рыбалка»» (статья
-- fishingkam.ru про стационарную базу) автопривязка навесила городские
-- музеи, смотровые и Налычевские источники за 65 км — это не точки её
-- маршрута. Убираем ВСЕ её waypoints: карточка честно остаётся без
-- «Точек маршрута».
--
-- Заодно рвём доказуемо-мусорные связки «Термальные источники Нальчева»
-- (65-75 км, wp_outlier runs 9-14) с городскими обзорными маршрутами —
-- тот же след автопривязки. Морские прогулки, многодневку Курильского и
-- парк Налычево НЕ трогаем: там дальние связки — правда маршрута.
-- Идемпотентна (повторный прогон — 0 строк).

DELETE FROM route_waypoints rw
USING kamchatka_routes kr
WHERE rw.route_id = kr.id
  AND kr.title = 'Рыболовная база «Камчатская Рыбалка»';

DELETE FROM route_waypoints rw
USING kamchatka_routes kr, places p
WHERE rw.route_id = kr.id
  AND rw.place_id = p.id
  AND p.name = 'Термальные источники Нальчева'
  AND kr.title IN (
    'Авачинская бухта',
    'Рыбалка на Камчатке',
    'Побережье Тихого океана',
    'Горные вершины',
    'Смотровая с видом на Тихий океан',
    'Озеро Приливное – Халактырский пляж'
  );
