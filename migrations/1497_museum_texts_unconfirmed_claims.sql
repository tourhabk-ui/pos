   'Музей истории АО «Океанрыбфлот» находится в Петропавловске-Камчатском, на улице Ключевской, 32, в реконструированном здании бывшего ресторана «Вулкан» рядом с управлением компании.
Корпоративный музей открылся 1 апреля 2022 года: три зала общей площадью 306 м². За неполный первый год его посетили около 7 тысяч человек.
Экспозиция рассказывает о Камчатке и промышленном рыболовстве, об истории промысла и технологиях компании — весь путь от обучения рыбаков до готовой продукции; отдельный блок посвящён супертраулеру «Георгий Мещеряков». Ещё один зал — о людях предприятия и его работе. Режим работы и запись — у самого музея.',
