--   по-прежнему называет учреждение районным. Кто прав — сайт сейчас или
--   скачанная 21.11 страница, — из этой правки проверить нечем: сайт музея
--   и страница премии отсюда не открываются. Чего не знаем — не утверждаем
--   (CLAUDE.md §0): фраза о переименовании снимается целиком.
--
--   «Музей истории АО «Океанрыбфлот» — первый на Камчатке интерактивный
--   промышленный музей». По сверке страница премии «Корпоративный музей»
--   называет его «первым на Камчатке интерактивным корпоративным» — это
--   слова самой компании, и слова «промышленный» там нет. Первенство
--   независимым источником не подтверждено: снимается оценка, остаётся
--   факт — где музей стоит.
--
-- Остальной текст обоих мест — слово в слово 1488. Правка ложится, только
-- если описание до сих пор ровно то, что записала 1488 (md5): текст, который
-- с тех пор поменял человек или владелец, не трогается; повтор — no-op.
-- Журнал происхождения (911): писатель 'fact-check', источники — те же, что
-- у 1488.

