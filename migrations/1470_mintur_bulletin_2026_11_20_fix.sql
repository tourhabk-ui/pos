-- 1470: Сводка Минтура 20.11 в ленте — так, как её написал источник.
-- Created: 2026-11-20
--
-- ── Повод ────────────────────────────────────────────────────────────
--
-- 20.11 владелец прислал еженедельную сводку министерства туризма о
-- доступности туристических объектов (канал турпортала t.me/visitkamchatka41).
-- Сверка ленты с текстом сводки (страж MCP safety_status, 20.11 02:55 UTC) и
-- прогон разбора на том же тексте показали четыре расхождения:
--
--   1. «Шивелуч — разрешено приближение радиусе не более, чем на 10 км от
--      вершины» стояло в ленте как «Вулкан Шивелуч: не приближаться» уровня 2.
--      Запрет соседней фразы («Не рекомендуется приближаться к вулканам
--      Мутновский, Безымянный, Ключевской, Крашенинникова») разбор раздавал
--      всем вулканам строки, включая Шивелуч.
--   2. Описания всех пяти вулканических строк начинались словами «Природный
--      парк Не рекомендуется…»: строка вулканов стоит в разделе «Природные
--      парки», и разбор приписал ей слово из заголовка раздела.
--   3. «Проезд „п. Термальный — Вилючинский перевал“: строго по пропускам»
--      потеряла следующую строку сводки — «График работы КПП: 07:00–08:00,
--      13:00–14:00, 19:00–20:00».
--   4. Заголовок «Автодорога „Палана — аэропорт“: подмыв у моста через р»
--      оборван на сокращении «р.».
--
-- И пятое, не из этой сводки: запреты подходить к вулкану, которые пишет
-- разбор, ложились с охватом по умолчанию — кольцом 25 км. Решение владельца
-- 16.10 (миграция 1301): «запретов министерства красить только сам вулкан и
-- места, привязанные к нему поимённо». Тогда 1301 перевела ручные записи
-- сводки 16.10, а разбор так и писал кольцо.
--
-- Разбор исправлен в том же PR (lib/services/safety/seismic-parser). Но
-- запись ленты делается ON CONFLICT DO NOTHING, а Шивелуч и Палана читаются
-- тем же ключом, что и до правки: уже записанные строки повторное чтение
-- канала не перепишет. Поэтому здесь они приводятся к тому, что теперь пишет
-- разбор. Трогаются только живые строки (срок не вышел, не сняты).
--
-- Шивелуч — уровень 1 и охват named, как запись той же фразы сводки 16.10
-- (1298, 1301): граница — разрешение, а не запрет; оранжевый KVERT красит
-- карточку вулкана и без этой строки.
--
-- Пуш миграция не шлёт: уведомления уходят только при вставке строки.
-- Идемпотентна: каждое условие перестаёт выполняться после первой правки.
-- Время тревог — стенное UTC (#2495).

-- 1. Шивелуч: граница у вершины, описание — его фраза.
UPDATE external_alerts
   SET title         = 'Вулкан Шивелуч: не ближе 10 км к вершине',
       severity      = 1,
       volcano_scope = 'named',
       description   = COALESCE(
         substring(description from '(Шивелуч\s+\S\s+разрешено приближение[^.]*км от вершины\.)'),
         description),
       updated_at    = (NOW() AT TIME ZONE 'UTC')
 WHERE alert_type = 'volcanic_eruption'
   AND volcano_name = 'Шивелуч'
   AND title = 'Вулкан Шивелуч: не приближаться'
   AND description LIKE '%разрешено приближение%10 км от вершины%'
   AND ended_by IS NULL
   AND expires_at > (NOW() AT TIME ZONE 'UTC');

-- 2. Запреты остальных вулканов: без чужого слова «Природный парк» и без
--    фразы о Шивелуче, которая к ним не относится.
UPDATE external_alerts
   SET description = btrim(regexp_replace(
         regexp_replace(description, '^Природный парк ', ''),
         '\s*Шивелуч\s+\S\s+разрешено приближение[^.]*\.', '')),
       updated_at  = (NOW() AT TIME ZONE 'UTC')
 WHERE alert_type = 'volcanic_eruption'
   AND description LIKE 'Природный парк Не рекомендуется%'
   AND ended_by IS NULL
   AND expires_at > (NOW() AT TIME ZONE 'UTC');

-- 3. Запрет подходить к вулкану красит вулкан и места, привязанные к нему
--    поимённо (1301), а не кольцо.
UPDATE external_alerts
   SET volcano_scope = 'named',
       updated_at    = (NOW() AT TIME ZONE 'UTC')
 WHERE alert_type = 'volcanic_eruption'
   AND volcano_name IS NOT NULL
   AND title ~ ': (не приближаться|не ближе \d+(,\d+)? км к вершине)$'
   AND volcano_scope <> 'named'
   AND ended_by IS NULL
   AND expires_at > (NOW() AT TIME ZONE 'UTC');

-- 4. Вилючинский перевал: график КПП из той же сводки. Заголовок — первая
--    фраза без точки, как его теперь строит разбор.
UPDATE external_alerts
   SET description = btrim(description) || ' График работы КПП: 07:00–08:00, 13:00–14:00, 19:00–20:00',
       title       = regexp_replace(btrim(title), '[.!?]+$', ''),
       updated_at  = (NOW() AT TIME ZONE 'UTC')
 WHERE alert_type = 'road_closure'
   AND title LIKE 'Проезд «п. Термальный%Вилючинский перевал»: строго по пропускам%'
   AND description NOT ILIKE '%КПП%'
   AND source_url LIKE 'https://t.me/visitkamchatka41/%'
   AND COALESCE(last_published_at, created_at) >= TIMESTAMP '2026-11-19 12:00:00'
   AND ended_by IS NULL
   AND expires_at > (NOW() AT TIME ZONE 'UTC');

-- 5. Палана: заголовок — вся фраза, а не обрывок до «р.». Фраза в описании
--    одна; иначе заголовок не трогается.
UPDATE external_alerts
   SET title      = regexp_replace(btrim(description), '[.!?]+$', ''),
       updated_at = (NOW() AT TIME ZONE 'UTC')
 WHERE alert_type = 'road_closure'
   AND title ~ '^Автодорога «Палана.* через р$'
   AND description LIKE title || '. Палана%'
   AND btrim(substr(description, length(title) + 3)) !~ '[.!?]\s'
   AND length(btrim(description)) <= 200
   AND ended_by IS NULL
   AND expires_at > (NOW() AT TIME ZONE 'UTC');

