-- Migration 943: своя ссылка у каждой брони вместо порядкового номера
--
-- ЧТО БЫЛО (разбор 08.09, подтверждён кодом четырёх файлов)
--
-- `operator_bookings.id` — BIGSERIAL, то есть 1, 2, 3. Роут
-- GET /api/hub/bookings/[id] стоит в реестре публичных, владения не
-- проверяет (`WHERE b.id = $1`) и отдаёт имя туриста, дату, цену, статус
-- оплаты и контакты оператора. Перебором по номеру — вся книга броней.
--
-- Хуже другое. Тот же ответ содержал `pdf_token` — HMAC, задуманный ИМЕННО
-- как защита PDF от перебора номеров (так написано в шапке
-- lib/pdf/pdf-token.ts). Замок выдавался тому, от кого он защищал, а PDF по
-- этому токену отдаёт договор с телефоном и почтой туриста.
--
-- ПОЧЕМУ ИМЕННО ТОКЕН, А НЕ СЕССИЯ
--
-- Гостевая бронь — решение по устройству: турист оформляет заявку без
-- регистрации, и страница подтверждения открывается сразу после отправки
-- формы. Потребовать вход значит сломать поток, ради которого он и сделан.
-- Поэтому ссылка становится capability-ссылкой: 122 бита случайности вместо
-- порядкового номера — подобрать нельзя, а поделиться ею турист по-прежнему
-- волен сам.
--
-- Тот же приём уже живёт у поездок (`user_trips.share_token`, миграция 664) и
-- у брифинга похода (`trip_preparation_shares.token`, миграция 870).
--
-- ЗАСЫПКА СТАРЫХ СТРОК
--
-- DEFAULT здесь ВОЛАТИЛЬНЫЙ: PostgreSQL вычисляет его для каждой строки
-- отдельно при переписывании таблицы, поэтому у всех существующих броней
-- появятся РАЗНЫЕ токены, а не один общий. Отдельный UPDATE не нужен.
--
-- Цена: прежние ссылки вида /booking-success/42 перестанут открываться —
-- ровно потому, что теперь их не может открыть и посторонний. Турист берёт
-- новую ссылку из письма или из чата с оператором.

ALTER TABLE operator_bookings
  ADD COLUMN IF NOT EXISTS access_token UUID NOT NULL DEFAULT gen_random_uuid();

CREATE UNIQUE INDEX IF NOT EXISTS idx_operator_bookings_access_token
  ON operator_bookings(access_token);

COMMENT ON COLUMN operator_bookings.access_token IS
  'Ключ доступа к брони для гостя: подтверждение и PDF открываются по нему, а не по порядковому id (миграция 943).';
