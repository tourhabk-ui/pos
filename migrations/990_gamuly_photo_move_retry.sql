-- 990: доделать переезд снимка каньона — и снять дубль с карты.
--
-- ── Что не сработало в 988 и ПОЧЕМУ ──────────────────────────────────────
--
-- Миграция 988 доехала до прода и применилась почти вся: описание «Крыльев
-- Гамулов» стало словами владельца, два кадра Андрея Запорожца легли в
-- галерею. НЕ применился ровно один шаг — переезд ГЕРОЙСКОГО снимка с моего
-- дубля на настоящую запись. Проба 538 показала это тремя фактами:
--
--   c03b364f «Каньон Крылья Гамулов»  описание владельца · галерея 2 · photoUrl NULL
--   b3d7eb6c «Каньон на Шивелуче»     ВИДИМ · photoCount 1 · автор Андрей Запорожец
--   77e5d9e1 «Шивелуч»                photoCount 1 · автор «владелец платформы» (989)
--
-- Молчания при этом не было ни в одном звене, и цепочка сторожей отработала
-- как задумано: шаг скрытия дубля в 988 условен — он требует ПОДТВЕРЖДЁННОГО
-- переезда, — поэтому дубль остался видимым, а не стал скрытой карточкой с
-- единственным кадром внутри. Следом прогон 17 пакетов карты отказался
-- заливать что-либо, потому что проверка «этого быть не должно» теперь
-- задаётся ДО заливки и нашла дубль в ответах экспорта.
--
-- Причина пропуска — в накатчике, и она общая, а не про этот файл.
-- `scripts/migrate-standalone.js` применяет выражения по одному под
-- SAVEPOINT и считает «уже существует» (`isAlreadyExistsError`) в том числе
-- **duplicate key**. Для INSERT это оправдано: повторный накат не должен
-- падать. Но у UPDATE столкновение уникальности — не идемпотентность, а
-- настоящий конфликт: у `ai_route_images` колонка `route_id` уникальна, у
-- ark «Крыльев Гамулов» строка уже была, и переезд получил 23505, был
-- записан в лог выката как `[skip-exists]` и пропущен. Остальные выражения
-- файла применились.
--
-- ── Как это чинится здесь ────────────────────────────────────────────────
--
-- Не повтором того же UPDATE: он снова упрётся в ту же строку и снова будет
-- пропущен — в этом и ловушка «повторить и посмотреть».
--
-- Шаг 1 убирает препятствие, но только если оно ПУСТОЕ: строка, у которой
-- нет ни байтов, ни объекта в хранилище, не показывает ничего (ровно счётчик
-- `neither` переписи /api/cron/images-in-s3). Строку с настоящим снимком —
-- чужим ручным, машинным, каким угодно — не трогаем: удалять фотографию
-- ради перемещения другой никто не просил.
--
-- Шаг 2 переезжает с дубля и защищён `NOT EXISTS` по целевому ark. Это не
-- перестраховка, а прямое следствие разбора: выражение, которое МОЖЕТ
-- получить duplicate key, будет молча пропущено накатчиком — значит оно
-- обязано не мочь. Если препятствие осталось (шаг 1 его не снял, потому что
-- там настоящий снимок), UPDATE честно ничего не делает, и об этом скажет
-- проверка в конце.
--
-- Отбор строки на переезд — по ark дубля и автору, а НЕ по `prompt`. Подпись
-- «(миграция 984)» дожила до сегодня, но привязываться к ней в третий раз
-- значит делать успех зависимым от строки, которую может переписать любой
-- следующий шаг; ark дубля и имя автора — то, что о снимке известно точно.
--
-- Шаг 3 скрывает дубль — снова ТОЛЬКО после подтверждённого переезда. Ровно
-- то условие из 988, которое сегодня уберегло кадр от скрытой карточки.
--
-- ПОСЛЕ ВЫКАТА нужен перезалив пакетов карты (`map-places-build.yml`,
-- upload:true): полевая карта читает статичные пакеты, и до перезалива на
-- телефоне остаются два каньона в 780 метрах друг от друга.
--
-- IDEMPOTENT

BEGIN;

-- ── 1. Убрать ПУСТУЮ строку снимка с настоящей записи, если она там ───────
DELETE FROM ai_route_images
 WHERE route_id = (SELECT ark_id FROM places WHERE id::text = 'c03b364f-55c3-4944-8505-3e86058999fa')
   AND image_data IS NULL
   AND s3_key IS NULL
   AND s3_url IS NULL;

-- ── 2. Снимок Андрея переезжает с дубля ──────────────────────────────────
UPDATE ai_route_images
   SET route_id = (SELECT ark_id FROM places WHERE id::text = 'c03b364f-55c3-4944-8505-3e86058999fa')
 WHERE route_id = 'b3d7eb6c-2ac4-41d9-89fe-52d073c3488d'
   AND author = 'Андрей Запорожец'
   AND (SELECT ark_id FROM places WHERE id::text = 'c03b364f-55c3-4944-8505-3e86058999fa') IS NOT NULL
   -- Без этого условия выражение может получить duplicate key, а накатчик
   -- пропустит его молча — как случилось с 988.
   AND NOT EXISTS (
         SELECT 1 FROM ai_route_images busy
          WHERE busy.route_id = (SELECT ark_id FROM places WHERE id::text = 'c03b364f-55c3-4944-8505-3e86058999fa')
       );

-- ── 3. Дубль скрывается — только при подтверждённом переезде ──────────────
UPDATE places
   SET is_visible     = FALSE,
       merged_into_id = 'c03b364f-55c3-4944-8505-3e86058999fa',
       merged_at      = NOW(),
       updated_at     = NOW()
 WHERE id::text = '002f9a4f-8833-4ee7-8dc4-290b30092cb7'
   AND (is_visible OR merged_into_id IS NULL)
   AND EXISTS (
         SELECT 1 FROM ai_route_images ai
          WHERE ai.route_id = (SELECT ark_id FROM places WHERE id::text = 'c03b364f-55c3-4944-8505-3e86058999fa')
            AND ai.author = 'Андрей Запорожец'
       );

-- ── Исход называется вслух ────────────────────────────────────────────────
DO $$
DECLARE
  v_gam_ark  uuid;
  v_hero     text;
  v_dup_live boolean;
BEGIN
  SELECT ark_id INTO v_gam_ark FROM places WHERE id::text = 'c03b364f-55c3-4944-8505-3e86058999fa';

  IF v_gam_ark IS NULL THEN
    RAISE WARNING '[990] у «Крыльев Гамулов» нет ark_id — снимку ехать некуда, дубль ОСТАЁТСЯ видимым';
    RETURN;
  END IF;

  SELECT author INTO v_hero FROM ai_route_images WHERE route_id = v_gam_ark;
  SELECT is_visible INTO v_dup_live FROM places WHERE id::text = '002f9a4f-8833-4ee7-8dc4-290b30092cb7';

  IF v_hero IS DISTINCT FROM 'Андрей Запорожец' THEN
    RAISE WARNING '[990] снимок НЕ переехал: на ark «Крыльев Гамулов» сейчас %; дубль намеренно оставлен видимым',
      COALESCE('строка автора «' || v_hero || '»', 'строки снимка нет');
  END IF;

  IF v_dup_live IS TRUE THEN
    RAISE WARNING '[990] дубль «Каньон на Шивелуче» всё ещё видим — перезалив пакетов карты ничего не исправит, пока это так';
  END IF;
END $$;

COMMIT;
