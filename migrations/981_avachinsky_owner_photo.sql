-- 13.10 (решение владельца «согласен, перенеси в S3»): байты снимков вынесены в
-- хранилище — ключ migrations/photos/<sha256>.jpg из маркера
-- .github/triggers/migration-photos-to-s3.json (sha256 тех же байтов). Миграция
-- пишет s3_key, image_data пуст; прод переведён по хэшу байтов миграцией 1228.
--
-- 981: «Вулкан Авачинский» — снимок владельца.
--
-- ── Что за кадр ───────────────────────────────────────────────────────────
--
-- 19.09 владелец прислал свой снимок со словами «Авачинский вулкан только что
-- сам сфотографировал»: вулкан целиком — снежный конус в облачном воротнике,
-- вся сомма с ледниками и распадками, за полосой леса скошенное поле с
-- валками. Снят в тот же день, тем же человеком, что и кадры Вилючинского.
--
-- ── Почему именно эта запись ──────────────────────────────────────────────
--
-- Записей с этим именем в каталоге ДВЕ, и по имени их не различить. Проба 528
-- (GET /api/cron/place-audit?q=авачин) назвала состояние каждой:
--
--   3a98a68d  «Вулкан Авачинский»  53.255368/158.836209  видимая, не слитая  ← сюда
--   b0dbd6c3  «Авачинский вулкан»  53.2556/158.8333      СКРЫТА и СЛИТА в 3a98a68d
--
-- Это не придирка: у скрытой записи УЖЕ лежит снимок (wikimedia-commons), и
-- положи мы кадр владельца туда — он попал бы на карточку, которую платформа
-- не открывает, а на живой карточке ничего бы не изменилось. Ровно та же
-- развилка была у Вилючинского, где из трёх одноимённых записей живой
-- оказалась одна.
--
-- ── Обрезка ───────────────────────────────────────────────────────────────
--
-- Исходник 4000x3000 с меткой поворота EXIF 6, то есть по-настоящему он
-- 3000x4000 — вертикальный. Окно 16:9 полной ширины (3000x1688) взято со
-- смещением 32% сверху: выше срезалась бы облачная гряда, ниже — вершина.
-- Внутри окна остаются все три плана кадра: небо, вулкан от вершины до
-- подножия, лес и поле. Штатный cover/attention увёл бы окно в самое
-- контрастное место — в светлое небо (урок 958).
--
-- ── Как ложится ───────────────────────────────────────────────────────────
--
-- Герой карточки: ON CONFLICT (route_id) DO UPDATE, но НЕ поверх чужого
-- ручного снимка — wikimedia и manual-upload не перезаписываются, кроме
-- повтора этой же миграции. Машинная картинка заменяется, и s3_url/s3_key
-- при этом гасятся: старый объект в хранилище этим байтам не соответствует и
-- показывал бы прежнюю картинку.
--
-- Байты пишутся в базу, а не в хранилище: миграция накатывается при старте
-- сервера, и сетевой вызов оттуда стопорил бы весь накат. Увезёт их уборщик
-- cron-images-to-s3 — правило §4.1 «снимок живёт в хранилище».
--
-- Права: автор указан, лицензия не ставится — снимок собственный.
--
-- Третий исход назван вслух в конце: нет ark_id или строку держит чужой
-- ручной кадр — RAISE WARNING в лог выката. Молчать нельзя (миграция 976 так
-- вставила ноль строк и выглядела успешной), падать тоже нельзя — снимок не
-- стоит боевой загрузки сервера.
--
-- IDEMPOTENT

BEGIN;

INSERT INTO ai_route_images (route_id, image_data, mime_type, prompt, model, width, height, author, s3_key)
SELECT p.ark_id,
       NULL::bytea,
       'image/jpeg',
       'снимок владельца: Авачинский вулкан с поля (миграция 981)',
       'manual-upload',
       1280,
       720,
       'владелец платформы',
       'migrations/photos/9709aadfdd86fc17b70cc652c386b05711800fb50f57c839464d8821bc09e07f.jpg'
  FROM places p
 WHERE p.id::text = '3a98a68d-76c8-4835-8d6d-24f7dd867cb8'
   AND p.ark_id IS NOT NULL
 LIMIT 1
ON CONFLICT (route_id) DO UPDATE
   SET image_data = EXCLUDED.image_data,
       mime_type  = EXCLUDED.mime_type,
       prompt     = EXCLUDED.prompt,
       model      = EXCLUDED.model,
       width      = EXCLUDED.width,
       height     = EXCLUDED.height,
       author     = EXCLUDED.author,
       s3_url     = NULL,
       s3_key     = EXCLUDED.s3_key,
       created_at = NOW()
 WHERE ai_route_images.model NOT IN ('wikimedia', 'manual-upload')
    OR ai_route_images.prompt = 'снимок владельца: Авачинский вулкан с поля (миграция 981)';

-- ── Отказ называется вслух ────────────────────────────────────────────────
DO $$
DECLARE
  v_ark    uuid;
  v_prompt text;
BEGIN
  SELECT ark_id INTO v_ark FROM places WHERE id::text = '3a98a68d-76c8-4835-8d6d-24f7dd867cb8';

  IF v_ark IS NULL THEN
    RAISE WARNING '[981] у «Вулкана Авачинского» нет ark_id — снимок НЕ лёг, карточка осталась с прежним фото';
    RETURN;
  END IF;

  SELECT prompt INTO v_prompt FROM ai_route_images WHERE route_id = v_ark;

  IF v_prompt IS DISTINCT FROM 'снимок владельца: Авачинский вулкан с поля (миграция 981)' THEN
    RAISE WARNING '[981] герой Авачинского НЕ стал снимком владельца: строку держит другой ручной снимок (prompt=%)', COALESCE(v_prompt, 'строки нет');
  END IF;
END $$;

COMMIT;
