-- Migration 824: снасти входят в стоимость, аренды нет
--
-- Ярослав («Камчатка Семейный Рафтинг», через владельца 05.08): «я никакие
-- снасти не даю в аренду, я их просто бесплатно даю». Отдельно попросил не
-- указывать количество — сколько снастей, столько и нужно, это не позиция
-- прайса.
--
-- На карточке при этом стоит «Рыболовные снасти (аренда 500 руб)» в блоке
-- «не входит». Турист, прочитав это, привезёт с собой деньги за то, что ему и
-- так дают даром, — или, что хуже, поверит, что своих снастей у оператора нет.
--
-- Это ТРЕТЬЯ попытка убрать строку. Первые две (819 и снятая 821) падали молча:
-- писали `ARRAY[...]` в колонку типа json. Причину назвал сам Postgres, когда
-- владелец нажал «Сохранить» и увидел «invalid input syntax for type json» —
-- до этого роут отдавал пустую пятисотку, и ошибка не доезжала ни до кого.
-- Тип колонок чинит 823; здесь — только содержимое, отдельным файлом: раннер
-- выполняет файл одной транзакцией, и падение состава не должно откатывать
-- смену типа.
--
-- Правим ВСЕ активные туры оператора, без выбора «канонического» подзапросом:
-- ровно такой выбор через `ORDER BY ... LIMIT 1` и промахивался молча. Границу
-- по оператору держим обязательно — у «Камчатской Рыбалки» в «не входит»
-- честно стоит аренда снастей, и это ИХ условия.
--
-- Массивы не переписываем целиком: убираем только строки про аренду и прокат
-- снастей, порядок остальных сохраняем — остального состава я не видел и
-- трогать его не вправе. Идемпотентна.

UPDATE operator_tours ot
   SET not_included = COALESCE((
         SELECT array_agg(x ORDER BY ord)
           FROM unnest(COALESCE(ot.not_included, ARRAY[]::text[])) WITH ORDINALITY AS t(x, ord)
          WHERE x !~* '(аренд|прокат)'
             OR x !~* '(снаст|удоч|спиннинг)'
       ), ARRAY[]::text[]),
       included = CASE
         WHEN NOT EXISTS (
           SELECT 1
             FROM unnest(COALESCE(ot.included, ARRAY[]::text[])) AS y
            WHERE y ILIKE '%снаст%' OR y ILIKE '%удоч%'
         )
         -- Без количества: «по количеству человек» — это про организацию, а не
         -- про состав, и в списке читается как ограничение.
         THEN COALESCE(ot.included, ARRAY[]::text[]) || 'Рыболовные снасти'::text
         ELSE ot.included
       END,
       updated_at = NOW()
  FROM partners p
 WHERE p.id = ot.operator_id
   AND p.slug = 'kamchatka-rafting'
   AND ot.deleted_at IS NULL
   AND (
     EXISTS (
       SELECT 1
         FROM unnest(COALESCE(ot.not_included, ARRAY[]::text[])) AS x
        WHERE x ~* '(аренд|прокат)' AND x ~* '(снаст|удоч|спиннинг)'
     )
     OR NOT EXISTS (
       SELECT 1
         FROM unnest(COALESCE(ot.included, ARRAY[]::text[])) AS y
        WHERE y ILIKE '%снаст%' OR y ILIKE '%удоч%'
     )
   );
