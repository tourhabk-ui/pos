-- 1198: цена гостевого дома «Кутха» — слово владельца 09.10.
--
-- В 1179 цена осталась NULL: в 2ГИС стояло «от 28 000 ₽» без единицы, и число
-- в price_per_night_from было бы выдумкой единицы (§4.0). 09.10 владелец назвал
-- её: «28000 это за сутки весь дом, баня включена». Теперь единица известна —
-- сутки за весь дом, — и число уходит в цену: карточка, поиск жилья по цене и
-- планер видят его так же, как у остальных объектов.
--
-- Описание переписывается только там, где в нём ещё стоит фраза 1179 про
-- неизвестную единицу: правку администратора поверх неё миграция не трогает.
-- Цена — только туда, где её нет. Идемпотентна.

UPDATE accommodations
   SET price_per_night_from = 28000,
       currency = 'RUB',
       updated_at = NOW()
 WHERE LOWER(name) = 'кутха'
   AND price_per_night_from IS NULL;

UPDATE accommodations
   SET description = 'Гостевой дом в посёлке Пионерский. По данным 2ГИС: до 8 мест, баня, беседки, парковка, крытый бассейн с подогревом. '
       || '28 000 ₽ за сутки за весь дом, баня входит в цену. '
       || 'Свободные даты и условия заселения уточняйте у владельца по телефону. '
       || 'Бронь и оплата идут напрямую с объектом: платформа оплату не принимает и номеров не продаёт.',
       updated_at = NOW()
 WHERE LOWER(name) = 'кутха'
   AND description LIKE '%без единицы%';
