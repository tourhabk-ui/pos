-- 1303: журнал общения A2A — IP клиента и User-Agent целиком.
--
-- Решение владельца 21.10 («да» на «добавить в журнал IP и страну»): серия
-- внешних Python-urllib 20.10 23:21 и 21.10 11:03–15:57 (Камчатка) гоняла
-- Кузьмича по тест-сценарию, и по журналу нельзя было сказать, кто это.
-- Пишется адрес из доверенного заголовка прокси (x-real-ip → cf-connecting-ip
-- → первый X-Forwarded-For; нет ни одного — NULL, не 127.0.0.1) и заголовок
-- User-Agent целиком до 512 знаков. Страна не хранится: своей GeoIP-базы нет,
-- а внешний сервис получал бы адрес на каждый вопрос — в админке у адреса
-- ссылка на ipinfo.io, по которой страну и сеть смотрят руками.
-- Срок — тот же, что у текста (90 суток, уборка в lib/a2a/dialog-log).
-- Старые строки остаются с NULL: задним числом адреса нет.

ALTER TABLE a2a_dialogs ADD COLUMN IF NOT EXISTS client_ip  VARCHAR(64);
ALTER TABLE a2a_dialogs ADD COLUMN IF NOT EXISTS user_agent VARCHAR(512);

COMMENT ON TABLE a2a_dialogs IS
  'Журнал общения A2A: вопрос агента и ответ Кузьмича после redactPII (телефоны и почты вычищены), IP клиента и User-Agent (с 1303), 90 суток; contextId в открытом виде не хранится';
