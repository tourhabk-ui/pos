-- Created: 2026-08-14
--
-- «Скалы три брата» — главный природный символ Петропавловска — стояли в
-- каталоге в 5.9 км от себя, внутри города (52.9466/158.6786). Проба 93
-- принесла эталон из ruwiki «Три Брата (Камчатка)» (pageid 961494):
-- 52.8937 / 158.6879 — у входа в Авачинскую бухту, где скалы и стоят.
-- Скрытый тёзка в типе «бухта» (fd3feffa, 52.8930/158.6890) стоял в 100
-- метрах от эталона — его координаты были верными; сам тёзка сливается в
-- эту запись отдельной пробой (проба 94), псевдоним запишет слияние.
--
-- Координаты правятся ТОЛЬКО потому, что появился проверяемый эталон —
-- правило прежнее: без эталона координаты не трогаем (Паланское озеро и
-- Долина Смерти ждут своего).
--
-- Гейт по точным текущим значениям: если координаты уже поправлены руками
-- или другим путём — миграция не делает ничего.

UPDATE places
   SET lat = 52.8937, lng = 158.6879
 WHERE id = 'e265d0f0-8187-4d7a-b0e4-fe9be5a2d9e0'
   AND lat = 52.94662920 AND lng = 158.67862180;

