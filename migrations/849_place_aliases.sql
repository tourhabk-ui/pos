-- Migration 849: у места одно имя и много псевдонимов
-- Created: 2026-08-14
--
-- ── Откуда взялась нужда ────────────────────────────────────────────────────
--
-- Слово владельца 14.08: «в разных источниках одно и то же место называется
-- по-разному, из-за этого и путаница». Проверка подтвердила буквально: у места
-- нет ни таблицы псевдонимов, ни колонки под них. Есть `places.source_name` —
-- ОДИН источник на строку. Значит когда второй источник приносит «Авачинский
-- вулкан» к уже имеющемуся «Вулкан Авачинский», положить второе имя некуда, и
-- платформа заводит вторую строку.
--
-- То есть дубли здесь — не сбой импорта, а единственный доступный способ
-- хранить второе название. Пока это так, любая дедупликация будет вычерпывать
-- воду, не закрывая кран.
--
-- ── Что теряло слияние ──────────────────────────────────────────────────────
--
-- Слияние дублей (merged_into_id) записывало, что место — дубль, но НЕ
-- записывало его имя. 14.08 так ушли «Авачинский вулкан», «Гора Шишель»,
-- «Вулкан Шивелуч», «Кутхины Баты» — все живые названия, которыми люди
-- пользуются. Эта миграция их возвращает: раздел бэкфилла ниже поднимает имена
-- ВСЕХ ранее слитых мест и делает их псевдонимами того места, которое
-- осталось.
--
-- ── Почему без внешнего ключа ───────────────────────────────────────────────
--
-- `place_id` — TEXT, и FK на `places(id)` здесь НЕТ намеренно. Причина
-- установлена 14.08 пробой прода: `places.id` имеет тип TEXT (UUID у места
-- лежит в отдельной колонке `ark_id`), а inline-FK `REFERENCES places(id)` из-за
-- этого падает. На этом уже погибли миграции 675 (таблица так и не создалась)
-- и 706/731/733/734 (пока 737 не выбросила FK). Повторять четвёртый раз
-- незачем: целостность держит прикладной слой, как и у merged_into_id.

BEGIN;

-- ============================================================
-- Таблица псевдонимов
-- ============================================================

CREATE TABLE IF NOT EXISTS place_aliases (
  id          UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  -- TEXT и без FK — см. шапку.
  place_id    TEXT NOT NULL,
  alias       TEXT NOT NULL,
  -- Откуда это имя. NULL — источник неизвестен (напр. бэкфилл старых слияний,
  -- где source_name у слитой строки не был заполнен). Пустая строка вместо
  -- NULL здесь была бы враньём: «источник назван» и «источника нет» — разные
  -- состояния.
  source_name TEXT,
  created_at  TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- Один и тот же псевдоним у одного места — один раз. Сравнение без учёта
-- регистра и краевых пробелов: «Кутхины Баты» и «кутхины баты » — одно имя.
CREATE UNIQUE INDEX IF NOT EXISTS ux_place_aliases_place_alias
  ON place_aliases (place_id, LOWER(TRIM(alias)));

-- Поиск точного совпадения по псевдониму.
CREATE INDEX IF NOT EXISTS idx_place_aliases_alias_lower
  ON place_aliases (LOWER(TRIM(alias)));

-- Нечёткий поиск: тем же триграммным механизмом, каким ищутся имена мест.
CREATE INDEX IF NOT EXISTS idx_place_aliases_alias_trgm
  ON place_aliases USING gin (alias gin_trgm_ops);

CREATE INDEX IF NOT EXISTS idx_place_aliases_place
  ON place_aliases (place_id);

-- ============================================================
-- Бэкфилл: вернуть имена, проглоченные прошлыми слияниями
-- ============================================================
--
-- Имя слитого места становится псевдонимом того, что осталось. Имена,
-- совпадающие с именем оставшегося места, не берём: «Курильское озеро» →
-- «Курильское озеро» — не псевдоним, а шум.

INSERT INTO place_aliases (place_id, alias, source_name)
SELECT k.id, m.name, m.source_name
  FROM places m
  JOIN places k ON k.id = m.merged_into_id::text
 WHERE m.merged_into_id IS NOT NULL
   AND m.name IS NOT NULL
   AND TRIM(m.name) <> ''
   AND LOWER(TRIM(m.name)) <> LOWER(TRIM(COALESCE(k.name, '')))
ON CONFLICT DO NOTHING;

COMMIT;

