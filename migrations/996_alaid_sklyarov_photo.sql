-- 13.10 (решение владельца «согласен, перенеси в S3»): байты снимков вынесены в
-- хранилище — ключ migrations/photos/<sha256>.jpg из маркера
-- .github/triggers/migration-photos-to-s3.json (sha256 тех же байтов). Миграция
-- пишет s3_key, image_data пуст; прод переведён по хэшу байтов миграцией 1228.
--
-- 996: «Алаид» — снимок Андрея Склярова.
--
-- ── Чей кадр и на каком основании он публикуется ──────────────────────────
--
-- 20.09 владелец прислал снимок со словами, записанными дословно:
--
--   «Алаид Фото Андрея Склярова
--    публиковать можно»
--
-- Автор назван, разрешение дано владельцем. Это то же основание, что у
-- кадров Андрея Запорожца (миграции 984, 988): письменного согласия самого
-- автора у меня нет, и делать вид, что оно есть, я не буду — здесь записано
-- РЕШЕНИЕ ВЛАДЕЛЬЦА публиковать с указанием автора. Появится слово автора —
-- дописывается сюда, а не заменяет это.
--
-- Лицензия не ставится: её никто не называл. Пустое поле честнее выдуманной
-- строки — то же правило, по которому 22 снимка с Викимедии до сих пор
-- скрыты (у них нет автора, и подписать их нечем).
--
-- ── Куда ложится ──────────────────────────────────────────────────────────
--
-- Запись есть и живая (проба 551): c962d02c «Алаид», volcano,
-- 50.857716/155.557385 — остров Атласова, северные Курилы. Описание у неё
-- вулканологическое и подробное, фотографии не было.
--
-- Кадр снят с моря: симметричный снежный конус над водой, птицы, у кромки
-- воды тёмная полоса берега. Именно так вулкан и видит тот, кто идёт мимо
-- на судне, — а других способов увидеть Алаид у туриста почти нет.
--
-- ── Размер ────────────────────────────────────────────────────────────────
--
-- Исходник 1280x960. Окно 16:9 полной ширины со смещением 90 пикселей
-- сверху: срезан чёрный угол (край козырька или иллюминатора) в левом
-- верхнем углу. Записывается 1280x720 — ровно канон, без растягивания.
--
-- ── Как ложится ───────────────────────────────────────────────────────────
--
-- Герой карточки. Машинная картинка заменяется, чужой РУЧНОЙ снимок — нет
-- (граница та же, что в 981/983/984/994). Байты пишутся в базу, а не в
-- хранилище: миграция накатывается при старте сервера, и сетевой вызов
-- оттуда стопорил бы весь накат; увезёт уборщик cron-images-to-s3 (§4.1).
--
-- Третий исход назван вслух: нет ark_id или строку держит чужой ручной
-- кадр — RAISE WARNING в лог выката, а не молчание и не падение.
--
-- IDEMPOTENT

BEGIN;

INSERT INTO ai_route_images (route_id, image_data, mime_type, prompt, model, width, height, author, s3_key)
SELECT p.ark_id,
       NULL::bytea,
       'image/jpeg',
       'снимок Андрея Склярова: Алаид с моря (миграция 996)',
       'manual-upload',
       1280,
       720,
       'Андрей Скляров',
       'migrations/photos/6b4c7452bce2806b480474c175439d67649c6e24237a615f5b253fda78e1c799.jpg'
  FROM places p
 WHERE p.id::text = 'c962d02c-ce85-4d9f-aa54-272944de56f2'
   AND p.ark_id IS NOT NULL
 LIMIT 1
ON CONFLICT (route_id) DO UPDATE
   SET image_data = EXCLUDED.image_data,
       mime_type  = EXCLUDED.mime_type,
       prompt     = EXCLUDED.prompt,
       model      = EXCLUDED.model,
       width      = EXCLUDED.width,
       height     = EXCLUDED.height,
       author     = EXCLUDED.author,
       s3_url     = NULL,
       s3_key     = EXCLUDED.s3_key,
       created_at = NOW()
 WHERE ai_route_images.model NOT IN ('wikimedia', 'manual-upload')
    OR ai_route_images.prompt = 'снимок Андрея Склярова: Алаид с моря (миграция 996)';

-- ── Отказ называется вслух ────────────────────────────────────────────────
DO $$
DECLARE
  v_ark    uuid;
  v_author text;
BEGIN
  SELECT ark_id INTO v_ark FROM places WHERE id::text = 'c962d02c-ce85-4d9f-aa54-272944de56f2';

  IF v_ark IS NULL THEN
    RAISE WARNING '[996] у «Алаида» нет ark_id — снимок НЕ лёг, карточка осталась без фото';
    RETURN;
  END IF;

  SELECT author INTO v_author FROM ai_route_images WHERE route_id = v_ark;

  IF v_author IS DISTINCT FROM 'Андрей Скляров' THEN
    RAISE WARNING '[996] герой «Алаида» НЕ стал снимком Склярова: там %', COALESCE('автор «' || v_author || '»', 'строки снимка нет');
  END IF;
END $$;

COMMIT;
