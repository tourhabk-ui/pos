  SELECT left(description, 40) INTO v_upper FROM places WHERE id::text = '14999081-db57-43d3-8aad-f6c8361b69ac';
  SELECT left(description, 40), name INTO v_lower, v_lower_name FROM places WHERE id::text = 'e7cc9f9d-479e-432f-8d1c-adcf6b62a1d8';
  IF v_lower_name IS DISTINCT FROM 'Нижне-Кошелевское термальное поле' THEN
    RAISE WARNING '[1264] вторая карточка не переименована (имя: %)', COALESCE(v_lower_name, 'записи нет');
