  IF v_upper IS NULL OR v_lower IS NULL THEN
    RAISE WARNING '[1264] справка легла не у обеих: верхнее — %, нижнее — %',
      COALESCE(v_upper, 'нет'), COALESCE(v_lower, 'нет');
  END IF;
