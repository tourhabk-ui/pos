-- 1264: Кошелевские термальные поля — какая карточка какое поле (владелец 15.10:
--       «Гремучие ключи» и «Верхне-Кошелевские» — «поправь»)
-- Created: 2026-10-15
--
-- ── Что было ──────────────────────────────────────────────────────────────
--
-- У платформы две карточки в 6 км друг от друга: «Верхне-Кошелевские
-- парогидротермальные источники» (14999081, 51.362141/156.721956) и «Гремучие
-- ключи» (e7cc9f9d, 51.3624965/156.6336277). Описания обеих — дневники, сняты
-- 1247. Кроноцкий заповедник (kronoki.ru, «Вулкан Кошелева и Кошелевские
-- термальные источники», пробы 888–889) пишет, что полей в массиве два:
--   Верхнекошелевское («известное как «Гремучие ключи»») — в кратере вулкана
--     Валентин, на высоте 1250–1400 м;
--   Нижнекошелевское — на склоне кальдеры Западно-Кошелевского вулкана, на
--     750–800 м, вдоль узкого глубокого оврага широтного направления.
--
-- ── Что показали источники (проба 938) ────────────────────────────────────
--
-- Высота точек по рельефу (opentopodata, SRTM 30 м): карточка «Верхне-
-- Кошелевских» — 1263 м, ровно в отметках верхнего поля; карточка «Гремучих
-- ключей» — 760 м, в отметках НИЖНЕГО. Её точка — узел OpenStreetMap
-- 5140732311 с подписью «Гремучие ключи» (Nominatim), к западу от массива —
-- там, где Global Volcanism Program (Смитсоновский институт; по нему описано
-- место «Кошелева») помещает второе поле: «на западных склонах западного
-- вулкана Кошелева». То есть точки
-- обеих карточек стоят верно — неверно было имя второй: OpenStreetMap
-- подписал «Гремучими ключами» нижнее поле, заповедник так зовёт верхнее.
--
-- ── Что делается ──────────────────────────────────────────────────────────
--
-- Координаты не двигаются — обе точки подтверждены рельефом. Вторая карточка
-- получает имя по заповеднику: «Нижне-Кошелевское термальное поле». Имя
-- «Гремучие ключи» остаётся поиску у ОБЕИХ карточек: у нижнего поля — по
-- подписи OpenStreetMap, у верхнего — по заповеднику. Два источника называют
-- им разные поля, и поиск по нему честно показывает оба, каждое под своим
-- однозначным именем. Старое имя уходит в псевдонимы ДО смены (порядок 1168);
-- адрес карточки (slug) не меняется.
--
-- Справки обеих — по тексту заповедника, только поверх снятого 1247 (пустое
-- описание с архивом): то, что кто-то уже переписал, не трогается.
-- Температура струй у заповедника записана с опечаткой («120–1530 °С») — её
-- в справке нет: числа, в котором источник ошибся, не повторяем.
--
-- ПОСЛЕ ВЫКАТА: полевая карта читает имена из статичных пакетов — нужен
-- перезалив map-places-build с новой версией слоя.
--
-- IDEMPOTENT

BEGIN;

-- ── Псевдонимы — до смены имени ───────────────────────────────────────────
INSERT INTO place_aliases (place_id, alias, source_name)
SELECT p.id::text, v.alias, v.src
  FROM places p
  JOIN (VALUES
    ('e7cc9f9d-479e-432f-8d1c-adcf6b62a1d8', 'Гремучие ключи', 'OpenStreetMap, узел 5140732311'),
    ('14999081-db57-43d3-8aad-f6c8361b69ac', 'Гремучие ключи', 'kronoki.ru — «Вулкан Кошелева и Кошелевские термальные источники»'),
    ('14999081-db57-43d3-8aad-f6c8361b69ac', 'Верхнекошелевское термальное поле', 'kronoki.ru — «Вулкан Кошелева и Кошелевские термальные источники»'),
    ('e7cc9f9d-479e-432f-8d1c-adcf6b62a1d8', 'Нижнекошелевское термальное поле', 'kronoki.ru — «Вулкан Кошелева и Кошелевские термальные источники»')
  ) AS v(id, alias, src) ON v.id = p.id::text
ON CONFLICT DO NOTHING;

-- ── Нижнее поле: имя по заповеднику ───────────────────────────────────────
UPDATE places
   SET name = 'Нижне-Кошелевское термальное поле',
       updated_at = NOW()
 WHERE id::text = 'e7cc9f9d-479e-432f-8d1c-adcf6b62a1d8'
   AND name = 'Гремучие ключи';

