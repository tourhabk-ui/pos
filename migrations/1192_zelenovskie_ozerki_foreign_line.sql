-- 1192: «Зеленовские озерки» — чужая линия снята, происхождение точки записано.
--
-- Скрин владельца 09.10 (полевой экран): над маршрутом «Зеленовские озерки»
-- «Данные маршрута не сходятся» и «Точка не проверена», и вопрос «вроде должен
-- был исправить?». 03.10 владелец сказал, что место «не на своём месте», и
-- координату поправили (place-coords run 26) — но поправили ТОЛЬКО точку. У
-- маршрута осталась своя линия, и вот что показал прод (пробы 740-742):
--
--   • путевая точка (place f31f3774): 53.287721, 158.348899 — у посёлка
--     Раздольный, где источники и стоят (описание 1157, стенды на месте);
--   • запись самого маршрута (kamchatka_routes.lat/lng, сторонний источник):
--     53.2833053, 158.3079886 — в 2,7 км от точки, то есть там же;
--   • линия (geometry, source «gpx», три вершины, 0,57 км):
--     (53.07791, 158.629878) → (53.078989, 158.635923) → (53.08001, 158.637284)
--     — в 29,9 км от точки и от записи маршрута, в другом месте края.
--
-- Полевой экран сверил линию с единственной точкой и сказал то, что видел:
-- данные не сходятся (DATA_CONFLICT_KM = 2). Это не ошибка экрана, а чужая
-- линия под чужой подписью «снято» (grade surveyed): три вершины, которые
-- к этому месту не относятся, шли в паспорте как снятый трек.
--
-- Что делается — тем же приёмом, что 902 (две чужие линии):
--
--   • geometry = NULL — линия снимается; она НЕ теряется: триггер 901 кладёт её
--     в route_geometry_archive до записи NULL, возврат — один UPDATE из архива;
--   • distance_km и elevation_gain_m = NULL вместе с линией: оба посчитаны по
--     этой ломаной и без неё превращаются в числа ниоткуда («мы не знаем»
--     честнее, как в 902). Длительность и прочее не трогаются: из линии они не
--     выводились.
--
-- Приговор вынесен по двум независимым сведениям, а не по одному: и точка, и
-- запись маршрута (разные происхождения) лежат у Раздольного, а линия — в 30 км
-- от обеих. Порог размаха приговором не служил (правило 22.08).
--
-- UPDATE гейтится самой линией (её координаты в тексте): если линию уже
-- заменили — не трогаем. Выбор по id И по ark_id: API отдаёт COALESCE(ark_id, id).
--
-- ── Точка: что записано, что нет ──────────────────────────────────────────
--
-- coord_source у места лежал 'unknown' («происхождение не записано»): правка
-- run 26 колонку не трогает. Происхождение известно: объект OSM, показанный
-- владельцем в приложении (MAPS.ME), и его слово — тот же род источника, что
-- у правок 03.10 «Гора Замок» и 1168. Записывается 'external' (внешний
-- справочник), и ТОЛЬКО так: 'surveyed' («снята на месте») не ставится — на
-- месте её никто не снимал.
--
-- Что от этого НЕ изменится, и это намеренно: плашка «Точка не проверена —
-- сверяйтесь с картой» остаётся. Правило (lib/places/coord-source,
-- coordIsTrustworthy) принимает как проверенную только снятую на месте
-- координату, и у каждой точки из внешнего справочника плашка такая же. Менять
-- ли правило для внешнего справочника — решение владельца, не побочный эффект
-- этой миграции. Меняется подсказка под плашкой: вместо «происхождение не
-- записано» там теперь «взята из внешнего справочника».
--
-- ПОСЛЕ ВЫКАТА: полевая карта читает статичные пакеты мест (map-places-build,
-- upload:true) — линия маршрута из таблицы, а не из пакета, пакет трогать не
-- нужно; координата места не менялась.
--
-- IDEMPOTENT

BEGIN;

UPDATE kamchatka_routes
   SET geometry = NULL,
       distance_km = NULL,
       elevation_gain_m = NULL,
       updated_at = NOW()
 WHERE (id::text = 'cf257914-fff2-4a72-baba-4a4381d7a83d'
        OR ark_id::text = 'cf257914-fff2-4a72-baba-4a4381d7a83d')
   AND geometry IS NOT NULL
   AND geometry::text LIKE '%53.07791%'
   AND geometry::text LIKE '%158.629878%'
   AND geometry::text LIKE '%158.637284%';

UPDATE places
   SET coord_source = 'external',
       updated_at = NOW()
 WHERE id::text = 'f31f3774-65d4-47b7-a03e-4e3d4a575100'
   AND coord_source = 'unknown';

DO $$
DECLARE
  v_line int;
  v_src  text;
BEGIN
  SELECT count(*) INTO v_line FROM kamchatka_routes
   WHERE (id::text = 'cf257914-fff2-4a72-baba-4a4381d7a83d' OR ark_id::text = 'cf257914-fff2-4a72-baba-4a4381d7a83d')
     AND geometry IS NOT NULL;
  SELECT coord_source INTO v_src FROM places WHERE id::text = 'f31f3774-65d4-47b7-a03e-4e3d4a575100';
  IF v_line <> 0 THEN
    RAISE WARNING '[1192] у «Зеленовских озерок» линия осталась (%): её заменили до миграции или маршрут не найден', v_line;
  END IF;
  IF v_src IS DISTINCT FROM 'external' THEN
    RAISE WARNING '[1192] coord_source места «Зеленовские озерки»: % (ожидалось external; запись могла быть правлена раньше)', v_src;
  END IF;
END $$;

COMMIT;
