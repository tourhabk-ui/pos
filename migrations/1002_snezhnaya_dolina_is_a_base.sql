-- ── Что было написано на карточке ─────────────────────────────────────────
--
-- Прежнее описание — сшитая из трёх разных мест выдумка, и опровергается оно
-- собственной координатой записи (52.787419 / 158.175348):
--
--   «примерно в 70 километрах от Петропавловска-Камчатского» — до города по
--      этим координатам порядка сорока, а не семидесяти;
--   «у подножия вулканов Корякский и Авачинский» — они стоят в шестидесяти
--      с лишним километрах к северо-востоку, ни о каком подножии речи нет;
--   «вид на Тихий океан и остров Старичков» — одновременно с подножием
--      Корякского это невозможно физически;
--   «часть природного парка Налычево», «разрешение в дирекции парка»,
--   «пеший поход от кордона Центральный», «инфраструктуры на маршруте нет»,
--   «связь на большей части пути отсутствует» — всё это про другое место.
--
-- Цена такого текста не в неопрятности. Человек читает «пеший поход,
-- разрешение, связи нет» и либо готовится к походу туда, куда можно доехать,
-- либо не едет вовсе. Описание места — это инструкция, и выдуманная
-- инструкция опаснее её отсутствия.
--
-- ── На чём стоит новое ────────────────────────────────────────────────────
--
-- Владелец 20.09, дословно: «Снежная долина этт база отдыха» (и раньше:
-- «Снежная долина тур база фото мое»). OpenStreetMap, по присланному
-- владельцем экрану Organic Maps, знает объект как ГОСТИНИЦУ на
-- 52.786036 / 158.170046 — это 380 метров от нашей записи, то есть координата
-- у нас верна, а врал только текст.
--
-- Новый текст описывает ровно то, что видно на снимках владельца и названо
-- его словами. Ни расстояний, ни принадлежности парку, ни разрешений в нём
-- нет: чего не знаем — того не пишем (§4.0). Отдельной фразой сказано, чего
-- у нас нет вовсе, чтобы следующий читатель не принял пустоту за забывчивость.
--
-- ── Тип: valley → other ───────────────────────────────────────────────────
--
-- `valley` — прямая ложь: это не форма рельефа, а база. Своего типа под
-- жильё в `places` нет и быть не должно (§9: точка — географический факт,
-- коммерция живёт отдельно), поэтому ставится `other` — честное «у нас нет
-- для этого типа». В счётчиках стихий на главной оба типа и так лежат в
-- исключениях (`EXCLUDED_TYPES`), так что перепись не сдвинется.
--
-- НАСТОЯЩЕЕ место этой записи — витрина жилья, а не карта мест. Перенести её
-- туда сегодня нельзя: `accommodations` требует NOT NULL у `total_rooms`,
-- `price_per_night_from` и `address`, а `rating` по умолчанию 0. Ни числа
-- номеров, ни цены, ни адреса владелец не называл, и завести запись значило
-- бы выдумать четыре факта разом — ровно то, от чего предостерегает §4.0.
-- Пока схема этого требует, витрина жилья пуста не по лени, а по честности.
--
-- ── Снимок ────────────────────────────────────────────────────────────────
--
-- Владелец 20.09: «Снежная долина тур база фото мое» — три кадра. Ставится
-- один (у `ai_route_images` уникальный `route_id`, на карточку идёт один).
--
-- Выбран кадр с бассейном и хребтом, и он КАДРИРОВАН: в правой трети
-- исходника купались двое детей. Согласия на публикацию их изображений никто
-- не давал, и владелец о них не говорил — значит их в кадре быть не должно
-- (тот же разбор, что в миграции 967). Срез по x=2350 из 4032 убирает их
-- целиком; содержимое оставшейся части не менялось. Дальняя фигура в глубине
-- кадра неразличима и человека не опознаёт.
--
-- Второй кадр (красный дом, каменная терраса, очаг) людей не содержит вовсе и
-- годится как есть — он ляжет в галерею, когда у места будет галерея; третий
-- (общий план бассейнов) publicаble не в полном виде по той же причине.
--
-- Записывается 1400x1132 — то, что осталось после среза, уменьшенное. До
-- канона 16:9 не растягивается: дорисовывать нечего.
--
-- Автор — владелец платформы, он же принял решение публиковать. Даты нет:
