DO $$
DECLARE
  v_ark  uuid;
  v_type text;
  v_desc text;
BEGIN
  SELECT ark_id, location_type, description INTO v_ark, v_type, v_desc
    FROM places WHERE id::text = 'f4545c9b-e701-4305-86fc-ab0d7c318afc';

  IF v_ark IS NULL AND v_type IS NULL THEN
    RAISE WARNING '[1002] записи «Снежная долина» нет — ни текст, ни снимок не легли';
    RETURN;
  END IF;

  IF v_desc LIKE '%Налычево%' THEN
    RAISE WARNING '[1002] выдуманное описание ОСТАЛОСЬ на карточке: условие не совпало';
  END IF;

  IF v_type IS DISTINCT FROM 'other' THEN
    RAISE WARNING '[1002] тип «Снежной долины» остался %, а не other', v_type;
  END IF;

  IF v_ark IS NULL THEN
    RAISE WARNING '[1002] у «Снежной долины» нет ark_id — текст поправлен, снимок вешать некуда';
  END IF;
