-- затрёт чужую работу.
UPDATE places
   SET description = 'База отдыха с тёплыми бассейнами. Чаши выложены камнем и стоят на террасах, вокруг каменные дорожки и ограды, берёзовый лес и молодые ели; за деревьями виден снежный хребет. На территории жилые корпуса и домики, беседки и открытый очаг.

Сюда приезжают, а не идут походом: это обустроенное место с дорогой и постройками, а не дикая котловина.

Чем это место является, сказал владелец платформы; OpenStreetMap знает его как гостиницу. Цен, числа мест и условий заезда у нас не записано — этого в карточке нет намеренно, выдумывать их нельзя.',
       location_type = 'other',
       updated_at = NOW()
 WHERE id::text = 'f4545c9b-e701-4305-86fc-ab0d7c318afc'
   AND (description IS NULL
        OR description LIKE '%Налычево%'
        OR description LIKE '%70 километрах%');

