-- Migration 851: тип «вулкан» перестаёт быть свалкой
-- Created: 2026-08-14
--
-- ── Что лежало в типе volcano (перепись 14.08, пробы 77-78) ─────────────────
--
-- Помимо 130+ настоящих вулканов: электростанция, водопад, две лавовые
-- пещеры, смотровая точка и семь названий туров/событий («Скитур на
-- Мутновский вулкан», «Гонка "Берингия"», «Камчатка глазами детей…»).
--
-- Слово владельца: «им менять тип, не сливать». Это верно по сути: ГеоЭС —
-- не дубль вулкана, это другой объект с неверным типом. Слияние стёрло бы
-- его как самостоятельное место, смена типа — ставит на своё место.
--
-- Цена мусорного типа не косметическая: срез по виду сравнивает вулканы с
-- вулканами, и «Водопад Опасный» в этом срезе занимал место ближайшего
-- соседа настоящего вулкана; подборка «Вулканы Камчатки», если её строить,
-- показала бы туристу электростанцию.
--
-- ── Правила ─────────────────────────────────────────────────────────────────
--
-- 1. Каждый UPDATE прицелен по id И по текущему типу volcano: если запись
--    уже перетипирована (руками или повторным прогоном) — no-op. Миграция
--    идемпотентна по построению.
-- 2. Видимость не трогается: скрытые названия туров остаются скрытыми,
--    видимый водопад — видимым. Это правка ТИПА, не витрины.
-- 3. Типы берутся из живого словаря платформы (cave/waterfall/viewpoint/
--    other есть в LOCATION_LABELS) — тип-сирота без подписи не заводится.
--
-- ── Ходутка ─────────────────────────────────────────────────────────────────
--
-- «Вулкан Ходутка — затерянный мир» (id a1b2c3d4-e5f6-7890-abcd-ef0123456789,
-- рукописный тестовый uuid) — единственная запись настоящего вулкана Ходутка,
-- и координаты у неё верные. Удалять нельзя — потеряем вулкан. Оставляем
-- запись, снимаем рекламный хвост из имени; старое имя сохраняется
-- псевдонимом, чтобы поиск по нему не умер.

BEGIN;

-- Не-вулканы: объект настоящий, тип неверный
UPDATE places SET location_type = 'other'
 WHERE id = '84f12e37-fd15-44e7-b60e-063f176d059e' AND location_type = 'volcano'; -- Мутновская ГеоЭС

UPDATE places SET location_type = 'waterfall'
 WHERE id = 'fa3653ac-3cd5-4d24-a611-ff7a75859be1' AND location_type = 'volcano'; -- Водопад Опасный (Мутновский)

UPDATE places SET location_type = 'cave'
 WHERE id IN (
   'f0ecf463-c804-44de-9b51-7a1642eaccc3',  -- Лавовые пещеры вулкана Горелый
   '204c7379-6eff-4e61-9320-4293866c5ba3'   -- Лавовые пещеры вулкана Толбачик
 ) AND location_type = 'volcano';

UPDATE places SET location_type = 'viewpoint'
 WHERE id = '4dbbbef6-100b-46fa-8721-41ed9fe377a4' AND location_type = 'volcano'; -- Вид на вулкан Шмидта с Гамченского дола

-- Названия туров и событий: не места вовсе, все уже скрыты — уводим из
-- вулканов в other, чтобы не мешались в срезах и подборках
UPDATE places SET location_type = 'other'
 WHERE id IN (
   '172edd62-7d1d-4d56-a1a6-f4550bd18f1f',  -- Скитур на Мутновский вулкан
   '6513c6b6-935b-4e7c-b9f8-1f977f92275d',  -- Авачинский вулкан: путь на вершину
   '811b6b0e-0800-4ad3-8cf8-1b12e58302b7',  -- Гонка «Берингия. Авача»
   '3edfddd0-7115-48f7-b064-58a1fffc54fa',  -- Камчатка глазами детей. 100 км до ГеоТЭС
   '67c97276-d2e7-4960-b829-1bb8bd019cfe',  -- Пока дремлют вулканы
   'de4cab89-ddf9-4d3e-9f1b-d91689b8f5b1',  -- Долина гейзеров. Курильское озеро. Горелый и Авача
   '5f66eb6c-0fd9-41b2-81e2-2c5e48d8153e'   -- Самые высокие вулканы Камчатки и Долина гейзеров
 ) AND location_type = 'volcano';

-- Ходутка: имя без рекламного хвоста, старое — в псевдонимы
INSERT INTO place_aliases (place_id, alias, source_name)
SELECT 'a1b2c3d4-e5f6-7890-abcd-ef0123456789', name, source_name
  FROM places
 WHERE id = 'a1b2c3d4-e5f6-7890-abcd-ef0123456789'
   AND name = 'Вулкан Ходутка — затерянный мир'
ON CONFLICT DO NOTHING;

UPDATE places SET name = 'Вулкан Ходутка'
 WHERE id = 'a1b2c3d4-e5f6-7890-abcd-ef0123456789'
   AND name = 'Вулкан Ходутка — затерянный мир';

COMMIT;

