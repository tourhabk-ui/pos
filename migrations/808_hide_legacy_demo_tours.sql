-- Migration 808: спрятать старые демо-туры (не от наших партнёров)
--
-- Диагностика прода (03.08) показала: почти все туры приписаны к оператору
-- «Камчатская рыбалка», в т.ч. явно старые демо-попытки, к рыбалке не
-- относящиеся, с недействительными ценами и маркетинговым текстом. Партнёрский
-- фильтр (807) их НЕ ловит — они висят на реальном партнёре.
--
-- Решение владельца: показываем только актуальные туры двух партнёров:
--   • Камчатская Рыбалка — рыболовные туры (речной лосось);
--   • Камчатка Рафтинг — сплав по Быстрой.
-- Всё прочее — старые попытки, скрываем.
--
-- Прячем по НАЗВАНИЮ (устойчиво между окружениями; демо-название = тот же демо-
-- тур). ОБРАТИМО: is_published/is_active=FALSE, deleted_at не трогаем — вернуть =
-- снова выставить флаги. Идемпотентна: трогает только сейчас-видимые.
--
-- «Морская рыбалка в Авачинской бухте» тоже сюда: это не речной продукт
-- «Камчатской Рыбалки», а демо (треска/палтус, катер, тот же рекламный стиль).
-- Если партнёр реально её проводит — вернём одной строкой.

UPDATE operator_tours ot
   SET is_published = FALSE,
       is_active    = FALSE,
       updated_at   = NOW()
 WHERE ot.deleted_at IS NULL
   AND (ot.is_published = TRUE OR ot.is_active = TRUE)
   AND (
        ot.title ILIKE '%Авачинский вулкан%'
     OR ot.title ILIKE '%Вулкан Горелый%'
     OR ot.title ILIKE '%Медведи Курильского%'
     OR ot.title ILIKE '%Долина гейзеров%'
     OR ot.title ILIKE '%Термальные источники Паратунки%'
     OR ot.title ILIKE '%Дачные горячие источники%'
     OR ot.title ILIKE '%Морская рыбалка%'
     OR ot.title ILIKE '%хребет Вачкажец%'
   );
