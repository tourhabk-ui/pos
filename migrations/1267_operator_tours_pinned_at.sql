-- 1267: оператор закрепляет туры наверху своей страницы на Ведаре.
--
-- Владелец 15.10 переслал просьбу Павла («Местечко Камчатка»): «нужен упор на
-- вертолётные экскурсии». Порядок туров на странице оператора
-- (/operators/<slug>, короткий адрес vedarai.ru/<slug>) задавался только датой
-- начала сезона, и «Курильское озеро (вертолёт)» стояло пятнадцатым из
-- пятнадцати. Своего порядка у оператора не было вовсе.
--
-- pinned_at — момент закрепления: NULL — не закреплён; закреплённые идут
-- первыми в порядке закрепления (кого закрепили раньше — выше), остальные —
-- как прежде, по сезону. Флаг ставит оператор в редакторе тура
-- (PATCH /api/hub/operator/tours/[id], поле pinned).
--
-- Идемпотентно; данных не трогает.

ALTER TABLE operator_tours ADD COLUMN IF NOT EXISTS pinned_at TIMESTAMPTZ;

COMMENT ON COLUMN operator_tours.pinned_at IS
  'Когда оператор закрепил тур наверху своей страницы; NULL — не закреплён (1267)';
