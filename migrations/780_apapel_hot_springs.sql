  'Апапельские горячие источники',
  'Апапельские горячие источники — минеральные геотермальные источники в Быстринском районе Камчатки, в среднем течении реки Анавгай на северном склоне сопки Чемпура. Девять грифонов расположены по обоим берегам крутопадающего ручья Апапель, высоко над дном долины: кипящие грифоны, парящие площадки, грязевые котлы и термальные болота. Температура воды — от 56 до 97 градусов, суммарный дебит около 10 л/с; горячие ручейки собираются в небольшие озерки и стекают по склону, окрашивая его отложениями красноватых оттенков. Памятник природы на территории Быстринского природного парка (объект ЮНЕСКО «Вулканы Камчатки»); рядом — ландшафтный памятник природы «Аппапельская Каменная баба», каменный столб, почитаемый коренными жителями. Купание не предусмотрено: вода у грифонов близка к кипению, подходить к парящим площадкам и котлам опасно. Район удалённый, медвежий; посещение — в составе группы, тропа со стороны долины Анавгая.',
