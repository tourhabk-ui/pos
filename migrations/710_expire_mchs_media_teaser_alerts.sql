-- 710: чистка ложных safety-алертов из медиа-анонсов МЧС
--
-- Владелец увидел на проде «Активных предупреждений: 20 — Эксперименты сотрудников
-- испытательной пожарной лаборатории — в новом выпуске программы «МЧС. Экстренный
-- вызов»» — это тизер телепрограммы, ошибочно классифицированный как fire_danger
-- (слово «пожарной» совпало с regex опасности пожара). Код-фикс в
-- classifyMchsItem (lib/services/seismic-parser.ts) не трогает уже вставленные
-- строки — ON CONFLICT (external_id) DO NOTHING не переклассифицирует. Гасим
-- такие строки истечением срока действия (не удаляем — оставляем для аудита).
--
-- Идемпотентно: WHERE expires_at > NOW() — повторный прогон ничего не найдёт.

UPDATE external_alerts
SET expires_at = NOW()
WHERE expires_at > NOW()
  AND (
    (title ILIKE '%выпуск%программ%' OR description ILIKE '%выпуск%программ%')
    OR title ILIKE '%телепередач%' OR description ILIKE '%телепередач%'
    OR title ILIKE '%телепрограмм%' OR description ILIKE '%телепрограмм%'
  );
