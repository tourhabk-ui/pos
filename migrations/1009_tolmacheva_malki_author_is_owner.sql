-- 1009: Толмачёва и Малки — автор снимков назван: владелец платформы.
--
-- ── Повод ─────────────────────────────────────────────────────────────────
--
-- Миграции 1007 (озеро Толмачёва: герой и пять кадров галереи) и 1008
-- (Малкинские источники: герой и купель) легли с author = NULL — владелец
-- прислал кадры с одним лишь именем места, и приписывать авторство по
-- привычке значило бы записать то, чего никто не говорил (§4.0).
--
-- 24.09 владелец ответил на прямой вопрос: «это мои фотографии из личных
-- поездок». Теперь источник есть, и имя ставится то же, что у прежних его
-- кадров (999, 1002, 979): «владелец платформы».
--
-- ── Что именно и как ──────────────────────────────────────────────────────
--
-- Строки находятся по СВОИМ меткам, не по месту: герои — по prompt, который
-- 1007/1008 записали дословно; галерея — по ark_id и позициям, которые
-- заняли те же миграции. Подпись ставится только туда, где автора нет
-- (author IS NULL): если к этому моменту кто-то положил на то же место свой
-- подписанный кадр, чужое имя не затирается — правило 1001 в обе стороны.
--
-- Байты не трогаются: это правка одной колонки, снимки не переезжают, и
-- s3_url/s3_key остаются как есть — уборщик S3 их не перекладывает.
--
-- Неопубликованный четвёртый кадр Толмачёва (в нём сам владелец, снимал
-- спутник) этой миграции не касается: его в базе нет.
--
-- IDEMPOTENT

BEGIN;

-- ── Герои ─────────────────────────────────────────────────────────────────
UPDATE ai_route_images
   SET author = 'владелец платформы'
 WHERE author IS NULL
   AND model = 'manual-upload'
   AND prompt IN (
     'снимок владельца: озеро Толмачёва, снежная вершина над водой (миграция 1007)',
     'снимок владельца: Малкинские горячие источники, пар над купелями в сумерках (миграция 1008)'
   );

-- ── Галереи ───────────────────────────────────────────────────────────────
UPDATE place_gallery_photos g
   SET author = 'владелец платформы'
  FROM places p
 WHERE g.ark_id = p.ark_id
   AND g.author IS NULL
   AND (
        (p.id::text = '2512ca75-547c-4348-a219-86c7e6937940' AND g.position BETWEEN 1 AND 5)
     OR (p.id::text = '284c862f-a339-409d-988a-da4107324b60' AND g.position = 1)
   );

-- ── Исход называется вслух ────────────────────────────────────────────────
DO $$
DECLARE
  v_heroes  int;
  v_gallery int;
BEGIN
  SELECT COUNT(*) INTO v_heroes
    FROM ai_route_images
   WHERE author = 'владелец платформы'
     AND prompt IN (
       'снимок владельца: озеро Толмачёва, снежная вершина над водой (миграция 1007)',
       'снимок владельца: Малкинские горячие источники, пар над купелями в сумерках (миграция 1008)'
     );
  IF v_heroes <> 2 THEN
    RAISE WARNING '[1009] подписано героев % из 2 — на чьём-то месте лежит другой снимок или 1007/1008 не применились', v_heroes;
  END IF;

  SELECT COUNT(*) INTO v_gallery
    FROM place_gallery_photos g
    JOIN places p ON p.ark_id = g.ark_id
   WHERE g.author = 'владелец платформы'
     AND (
          (p.id::text = '2512ca75-547c-4348-a219-86c7e6937940' AND g.position BETWEEN 1 AND 5)
       OR (p.id::text = '284c862f-a339-409d-988a-da4107324b60' AND g.position = 1)
     );
  IF v_gallery <> 6 THEN
    RAISE WARNING '[1009] подписано кадров галереи % из 6', v_gallery;
  END IF;
END $$;

COMMIT;
