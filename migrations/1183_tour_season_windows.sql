-- 1183: даты туров — только по сезону (решения владельца 08.10, #2244, #2245).
--
-- Правило окна живёт в коде (lib/tours/request-window): дата без строки
-- календаря принимается только внутри записанного сезона тура, и поездка
-- должна закончиться в сезоне. Здесь — данные, к которым оно применяется.
--
-- Каждая правка гейтится текущим значением: кабинет оператора пишет те же
-- колонки, и миграция трогает только то, что записала сама.

-- ═══ 1. «Край Вулканов» — предварительная бронь на сезон 2027 (#2245) ══════
--
-- Владелец 08.10: «Край вулканов на предварительную бронь сезона 27 года с
-- мая по 1 октября». Расписания у оператора нет (1176 дат не переносила),
-- поэтому туры остаются без календаря: заявка уходит оператору, а дата
-- ограничена сезоном 01.05.2027–01.10.2027. Многодневный тур должен
-- закончиться к 1 октября — выезд не позже 1 октября минус (дней − 1).
-- Записывается только туда, где сезона нет: свой сезон, поставленный
-- оператором, миграция не перетирает.
UPDATE operator_tours t
   SET season_start = DATE '2027-05-01',
       season_end   = DATE '2027-10-01',
       updated_at   = NOW()
  FROM partners p
 WHERE p.slug = 'volcanoesland'
   AND t.operator_id::text = p.id::text
   AND t.deleted_at IS NULL
   AND t.season_start IS NULL
   AND t.season_end IS NULL;

-- ═══ 2. «Камчатская рыбалка», туры 6 и 9 — только летний сезон (#2244) ═════
--
-- «Летняя рыбалка на кижуча» (6) и «Многодневный летний тур» (9) продавались
-- на октябрь. Сезон 25.08–30.10.2026 поставила наша сессия 29.09 (1106, п. 2.8),
-- а сам оператор пишет о себе «летний сезон — с июня по сентябрь».
-- Владелец 08.10: «только по сезону», даты — до 30.09.
--
-- Сезон 2026 к 08.10 уже прошёл. Записать его концом 30.09.2026 значило бы
-- оставить тур без окна вовсе: прошедший сезон правило не применяет, и тур
-- снова принимал бы заявку на любой день. Поэтому записывается следующий
-- сезон — 25.08–30.09.2027, тем же началом, что стоял.
-- Тур 11 («Недельный рыболовный тур») сезона в названии не несёт — не
-- трогается (разбор #2244).
UPDATE operator_tours ot
   SET season_start = DATE '2027-08-25',
       season_end   = DATE '2027-09-30',
       updated_at   = NOW()
 WHERE ot.id IN (6, 9)
   AND ot.operator_id::text = '0aaa4f05-b479-418b-9d54-2b909783dfd7'
   AND ot.season_start = DATE '2026-08-25'
   AND ot.season_end   = DATE '2026-10-30';

-- Октябрьские даты 2026, открытые 1106, закрываются: поездка должна была
-- кончиться к 30.09. Дата, на которую кто-то уже записан, остаётся открытой —
-- чужую бронь миграция не трогает; занятость считается по броням
-- (operator_bookings, многодневная — всем своим диапазоном), а не по
-- счётчику booked_slots, который растёт только при оплате.
UPDATE tour_availability ta
   SET is_cancelled = TRUE,
       cancellation_reason = 'Вне сезона тура: летний сезон оператора — по 30.09 (1183, #2244)',
       updated_at = NOW()
  FROM operator_tours t
 WHERE ta.operator_tour_id = t.id
   AND t.id IN (6, 9)
   AND t.operator_id::text = '0aaa4f05-b479-418b-9d54-2b909783dfd7'
   AND ta.date >= CURRENT_DATE
   AND ta.date >  DATE '2026-09-30' - (COALESCE(t.multi_day_count, 1) - 1)
   AND ta.date <  DATE '2027-01-01'
   AND ta.deleted_at IS NULL
   AND COALESCE(ta.is_cancelled, FALSE) = FALSE
   AND COALESCE(ta.booked_slots, 0) = 0
   AND NOT EXISTS (
     SELECT 1 FROM operator_bookings b
      WHERE b.operator_tour_id = ta.operator_tour_id
        AND b.booking_status NOT IN ('cancelled', 'rejected')
        AND b.deleted_at IS NULL
        AND ta.date BETWEEN b.booking_date AND COALESCE(b.end_date, b.booking_date)
   );
