-- ── Исход называется вслух ────────────────────────────────────────────────
DO $$
DECLARE
  v_ark    uuid;
  v_author text;
BEGIN
  SELECT ark_id INTO v_ark FROM places
   WHERE id::text = '7c1f0a53-2f4e-4c7a-9b6d-0e5a1d8c4b21' AND is_visible;

  IF v_ark IS NULL THEN
    RAISE WARNING '[997] место стелы не заведено или скрыто — снимку ехать некуда';
    RETURN;
  END IF;

  SELECT author INTO v_author FROM ai_route_images WHERE route_id = v_ark;

  IF v_author IS DISTINCT FROM 'владелец платформы' THEN
    RAISE WARNING '[997] снимок стелы НЕ встал: там %', COALESCE('автор «' || v_author || '»', 'строки снимка нет');
  END IF;
END $$;

COMMIT;
