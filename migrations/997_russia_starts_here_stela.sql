--
-- 997: стела «Здесь начинается Россия» у Елизово — новое место и снимок владельца.
--
-- ── Почему нельзя было поставить фото на существующую карточку ────────────
--
-- Владелец прислал свой снимок со словами «здесь начинаеться Россия фото
-- мое», а позже уточнил: «„Здесь начинается Россия" это в Елизово стелла».
--
-- Запись с ТАКИМ ЖЕ именем в каталоге есть, и она про другое: мыс Лопатка,
-- южная оконечность полуострова, где сходятся два моря, — за четыреста
-- километров отсюда. Снимок стелы на той карточке был бы ровно тем, что
-- вчера стоило четырёх миграций с каньоном: кадр одного объекта под именем
-- другого.
--
-- ── Откуда координата ─────────────────────────────────────────────────────
--
-- Из OpenStreetMap, узел 2531794165 (проба 550, зеркало maps.mail.ru):
--
--   53.1883258 / 158.4255164
--   tourism=artwork · artwork_type=statue · material=metal
--   name «Камчатский медведь»
--   inscription «здесь начинается Россия Камчатка»
--
-- Совпало ТРИ вещи: слово владельца (стела в Елизово), надпись в тегах OSM
-- дословно с таблички на снимке, и положение узла — въезд в Елизово со
-- стороны аэропорта. Поэтому `coord_source` = 'external': координата взята
-- из внешнего справочника, а не снята прибором, и права утверждать больше,
-- чем «так записано в OSM», у неё нет.
--
-- Nominatim по названию не знал ничего (проба 549, три пустых ответа) —
-- нашлось только запросом по тегам и площади. Это стоит помнить: «поиск не
-- нашёл» и «объекта нет» — разные вещи.
--
-- ── Имя ───────────────────────────────────────────────────────────────────
--
-- «Камчатский медведь (Здесь начинается Россия)». Первым — имя объекта из
-- OSM, в скобках — фраза, которой место зовут люди и по которой его ищут.
-- Назвать карточку просто «Здесь начинается Россия» нельзя: в каталоге уже
-- есть запись с этим именем (мыс Лопатка), и два одинаковых имени — прямая
-- дорога к тому же дублю.
--
-- ── Род места ─────────────────────────────────────────────────────────────
--
-- `viewpoint`. Типа «памятник» в перечне lib/places/location-types нет, а
-- заводить новый значит трогать иконки карты и сторожа форм — отдельная
-- работа ради одной записи. Из существующих ближе всего смотровая: сюда
-- сворачивают с трассы, чтобы посмотреть и сфотографировать, и именно
-- панораму вулканов за стелой видно на снимке. `historical` было бы хуже:
-- «Историческое место» обещает возраст, которого у скульптуры нет.
--
-- ── Описание ──────────────────────────────────────────────────────────────
--
-- Только то, что видно на снимке и стоит в тегах OSM: что изображено, что
-- написано на камне, что за вулканы позади. Ни года установки, ни автора
-- скульптуры, ни высоты — этого я не знаю, и выдумывать не стану (урок
-- «Каньона Опасного», где описание называло чужой вулкан).
--
-- ── Снимок ────────────────────────────────────────────────────────────────
--
-- Кадр владельца. Окно 16:9 со смещением: срезано пустое небо сверху и
-- часть льда снизу. Человек в кадре есть, но мелко и спиной — лицо не
-- читается; по правилу миграции 967 кадр с узнаваемым лицом без согласия не
-- публикуется, здесь узнавания нет.
--
-- ПОСЛЕ ВЫКАТА — перезалив пакетов карты (`map-places-build.yml`,
-- upload:true): полевая карта читает статичные пакеты, и до перезалива
-- новой точки на телефоне не будет (§4.1).
--
-- IDEMPOTENT

