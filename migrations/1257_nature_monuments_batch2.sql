SELECT p.id::text, w.alias, w.src
  FROM wanted w
  JOIN places p ON p.id::text = w.place_id::text
 WHERE p.merged_into_id IS NULL
ON CONFLICT (place_id, LOWER(TRIM(alias))) DO NOTHING;

-- ── Исход называется вслух ────────────────────────────────────────────────
DO $$
DECLARE
  v_texts int;
  v_view record;
  v_regime int;
  v_kuzmich int;
  v_bears int;
  v_aliases int;
BEGIN
  SELECT count(*) INTO v_texts FROM places
   WHERE id::text IN ('6227b295-44de-4148-9571-48c185f86735', '15bf29b0-9b1b-49c5-be1f-4c8d5d185f4e',
                      '7498601a-86b8-4560-bf58-e6e2e751b7a8')
     AND source_name LIKE 'Википедия — %'
     AND description IS NOT NULL;
  SELECT description IS NULL AS empty, description_withdrawn IS NOT NULL AS archived INTO v_view
    FROM places WHERE id::text = 'be84e54c-f63d-4737-a6cc-8494fcd1a0eb';
  SELECT count(*) INTO v_regime FROM places
   WHERE id::text IN ('15bf29b0-9b1b-49c5-be1f-4c8d5d185f4e', '7498601a-86b8-4560-bf58-e6e2e751b7a8')
     AND eco_zone = 'nature_monument' AND eco_permit_required IS NULL;
  SELECT count(*) INTO v_kuzmich FROM places
   WHERE id::text IN ('6227b295-44de-4148-9571-48c185f86735', 'be84e54c-f63d-4737-a6cc-8494fcd1a0eb',
                      '15bf29b0-9b1b-49c5-be1f-4c8d5d185f4e', '7498601a-86b8-4560-bf58-e6e2e751b7a8',
                      'a2b3c4d5-e6f7-4890-bcde-f01234567890')
     AND kuzmich_review = '';
  SELECT count(*) INTO v_bears
    FROM location_safety_profile lsp JOIN places p ON lsp.agent_route_id = p.ark_id
   WHERE p.id::text = '6227b295-44de-4148-9571-48c185f86735'
     AND lsp.profile_source = 'manual' AND 'bears' = ANY(lsp.hazard_types);
  SELECT count(*) INTO v_aliases FROM place_aliases
   WHERE place_id IN ('15bf29b0-9b1b-49c5-be1f-4c8d5d185f4e', '7498601a-86b8-4560-bf58-e6e2e751b7a8')
     AND lower(alias) IN ('тимоновские источники', 'тимоновские ключи', 'ажабачье', 'азабачье');

  IF v_texts < 3 THEN
    RAISE WARNING '[1257] справки по Википедии легли у % мест из 3 — тексты уже переписаны кем-то?', v_texts;
  END IF;
  IF v_view.empty IS DISTINCT FROM TRUE OR v_view.archived IS DISTINCT FROM TRUE THEN
    RAISE WARNING '[1257] выдумка о видовой точке Голубых озёр не снята (пусто: %, в архиве: %)', v_view.empty, v_view.archived;
  END IF;
  IF v_regime < 2 THEN
    RAISE WARNING '[1257] режим «памятник природы» с разрешением «не записано» — у % мест из 2', v_regime;
  END IF;
  IF v_kuzmich < 5 THEN
    RAISE WARNING '[1257] пустая заметка Кузьмича у % мест из 5 — у остальных записан другой текст', v_kuzmich;
  END IF;
  IF v_bears < 1 THEN
    RAISE WARNING '[1257] медведи в профиле Голубых озёр не записаны — профиль уже ручной или его нет';
  END IF;
  IF v_aliases < 4 THEN
    RAISE WARNING '[1257] другие имена легли не все: % из 4', v_aliases;
  END IF;
END $$;

COMMIT;

