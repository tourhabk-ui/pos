-- 1257: Памятники природы, партия 2 — Голубые озёра без «тёплой воды»,
--       Тимоновские источники с мышьяком, озеро Ажабачье; справки по
--       Википедии вместо сочинений, режим там, где он назван.
-- Created: 2026-10-14
--
-- ── Почему ────────────────────────────────────────────────────────────────
--
-- Владелец 14.10: «Бери по порядку схему»; вторая партия памятников природы
-- края (категория Википедии «Памятники природы Камчатского края», проба 918).
-- Здесь сочинения не просто без источника — они спорят с ним там, где от
-- этого зависит безопасность (пробы 921–924):
--   «Голубые озёра» — «можно окунуться — вода пощипывает кожу, градусов
--     шестнадцать», «белеет осадок кальцита»; по Википедии вода в озёрах
--     снегового происхождения и даже летом близка к нулю;
--   «Вид на долину Голубых озёр» — «термально-минеральные озёра», «цвет от
--     растворённых минералов», «полтора часа по дороге на Мутновский»;
--     тропа к озёрам — от базы «Гора Морозная», и у самой видовой точки
--     источника нет: текст снимается, вместо него — ничего;
--   «Тимоновские» — «вода под пятьдесят градусов», «раздеваешься прямо на
--     траве», «рядом ледяная Авача»; по источнику — до 46 °C, долина Пади
--     Тимоновской, и главное, чего в карточке не было: из некоторых
--     источников пить нельзя, мышьяка в воде слишком много;
--   «Озеро Ажабачье» — «вода здесь мутновата от взвеси»; по источнику вода
--     чистая, высокой прозрачности. Заметка Кузьмича — английское «wildlife».
-- Попутно: заметка Кузьмича у «Батареи Максутова» — впечатление от первого
-- лица («с подъёма сразу в лицо — океанский ветер с горькой полынью»), её
-- 1256 не тронула, потому что снимала только пустые.
--
-- ── Источники ────────────────────────────────────────────────────────────
--
--   Википедия — «Голубые озёра (Камчатский край)», «Тимоновские источники»,
--     «Ажабачье» (проба 923, координаты статей — 921);
--   OpenStreetMap — Голубые озёра, way 379892277 (Nominatim, проба 924):
--     точка карточки совпадает с центром контура, не трогается.
--
-- ── Режим ────────────────────────────────────────────────────────────────
--
-- Тимоновские источники и Ажабачье — памятники природы регионального
-- значения с 1981 года (Википедия): режим «Памятник природы», разрешение —
-- NULL, положение о памятниках на платформе не записано (как в 1256). Голубым
-- озёрам режим не ставится: статья называет их природным парком областного
-- значения, категория Википедии — памятником природы; из двух записей,
-- спорящих друг с другом, не выбираем. Статус — словами в справке.
--
-- ── Точка Тимоновских источников — не здесь ──────────────────────────────
--
-- Точка карточки (53.8032775, 158.1567997) — в 770 м к юго-западу от точки
-- статьи Википедии (53.8089, 158.1644), а ровно в точке статьи лежит скрытый
-- дубль «Тимоновский», слитый с этой карточкой. В OSM объекта нет (Nominatim,
-- проба 924), и какая из двух точек верна, по одной статье не сказать —
-- точка сверяется отдельно (высота 700 м по статье против рельефа) и
-- правится своей миграцией, если сверка её опровергнет.
--
