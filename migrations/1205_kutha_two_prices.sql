-- 1205: «Кутха» — две цены и десять мест, слово хозяина дома (10.10).
--
-- Владелец платформы переслал сообщение хозяина «Кутхи»: «8 спальных мест
-- 24 т.р., плюс 2 раскладушки 28 т.р. Баня включена.» Это уточняет и 1198
-- (одна цена 28 000 ₽), и 1204 («до 12 человек»): хозяин знает свой дом
-- точнее пересказа.
--
-- Цена: от 24 000 ₽ (8 спальных мест) до 28 000 ₽ (с двумя раскладушками,
-- 10 человек), за сутки за весь дом, баня в цене. Нижняя — в
-- price_per_night_from (по ней каталог и планер сортируют), верхняя — в
-- price_per_night_to. Обе только поверх прежних значений 1198 (28 000 и
-- пусто): цену, исправленную администратором, миграция не трогает.
--
-- Тексты переписываются только там, где ещё стоит 1204. Идемпотентна.

UPDATE accommodations
   SET price_per_night_from = 24000,
       price_per_night_to = 28000,
       updated_at = NOW()
 WHERE LOWER(name) = 'кутха'
   AND price_per_night_from = 28000
   AND price_per_night_to IS NULL;

UPDATE accommodations
   SET description = 'Гостевой дом в посёлке Пионерский сдаётся целиком: 8 спальных мест и ещё 2 раскладушки, до 10 человек. В доме баня с парной, крытый бассейн с подогревом, кухня в гостиной; во дворе беседки и парковка. '
       || 'За сутки за весь дом: 24 000 ₽ на 8 спальных мест, 28 000 ₽ с двумя раскладушками. Баня входит в цену. Принимает гостей круглый год. '
       || 'Свободные даты и условия заселения подтверждает владелец по телефону. '
       || 'Бронь и оплата идут напрямую с объектом: платформа оплату не принимает и номеров не продаёт.',
       updated_at = NOW()
 WHERE LOWER(name) = 'кутха'
   AND description LIKE '%до 12 человек%'
   AND description LIKE '%28 000 ₽ за сутки за весь дом%';

UPDATE accommodations
   SET short_description = 'Дом целиком: 8 мест и 2 раскладушки, баня, крытый бассейн',
       updated_at = NOW()
 WHERE LOWER(name) = 'кутха'
   AND short_description = 'Дом целиком до 12 человек: баня, крытый бассейн, пос. Пионерский';
