-- 1312: отметка «сайт партнёра ведём мы» (слово владельца 22.10:
--       «http://fishingkam.ru/ теперь под нашим управлением»).
-- Created: 2026-10-22
--
-- ── Почему ────────────────────────────────────────────────────────────────
--
-- Сайт «Камчатской рыбалки» (fishingkam.ru, Tilda) передан платформе целиком:
-- на вопрос «какой доступ» владелец ответил «сайт целиком передан нам» и
-- попросил это записать. 1103 (29.09) уже говорила о полном доступе к сайту,
-- но только комментарием — ни один экран и ни один крон этого не знал.
--
-- Отметка меняет смысл изменения на сайте. Чужой сайт поменялся — устарели
-- наши карточки, сверять их с сайтом. Сайт, который ведём мы, поменялся —
-- это наша правка или правка того, у кого остался доступ; правда — наши
-- карточки, и сверяется с ними сайт, а не наоборот. Читатель —
-- наблюдение за сайтами партнёров (1311, lib/partners/site-watch-run.ts):
-- такой сайт читается всегда, а сообщения о нём подписаны «сайт ведём мы».
--
-- FALSE — «сайт не наш»: это знание о себе, а не пробел. Какие сайты ведёт
-- платформа, она знает сама; ставит отметку только слово владельца.
-- «Я Камчатка» (iamkam.ru, слово 02.10 «будем администрировать после 20
-- октября», доступ только к хостингу) здесь НЕ отмечена: что передача
-- состоялась, владелец не говорил.
--
-- IDEMPOTENT: ADD COLUMN IF NOT EXISTS; UPDATE только там, где отметки ещё нет.

BEGIN;

ALTER TABLE partners
  ADD COLUMN IF NOT EXISTS site_managed_by_platform BOOLEAN NOT NULL DEFAULT FALSE;

COMMENT ON COLUMN partners.site_managed_by_platform IS
  'Сайт партнёра ведёт платформа (слово владельца). Наблюдение за сайтами читает его всегда и подписывает изменения «сайт ведём мы» (1312).';

-- «Камчатская рыбалка», id из 863.
UPDATE partners
   SET site_managed_by_platform = TRUE
 WHERE id::text = '0aaa4f05-b479-418b-9d54-2b909783dfd7'::text
   AND site_managed_by_platform = FALSE;

COMMIT;

