-- Migration 790: вместимость сплава по Быстрой — 29 человек, а не 4
--
-- Цифра 4 (available_slots) и 6 (max_participants) достались от миграции 060
-- и были приняты на веру: в анонсе оператора вместимость не указана, а 788
-- лишь перенесла существующее число на исправленные даты. Владелец назвал
-- настоящую — 29 человек на выезд (29.07.2026).
--
-- Почему это не косметика. Заниженная вместимость на витрине означает, что
-- каждый выезд «распродаётся» после четвёртого туриста, а остальные видят
-- закрытую дату там, где мест полно. Тур опубликован, значит счётчик уже
-- работает на реального покупателя.
--
-- Никогда не опускаем available_slots ниже уже забронированного: если на
-- дату почему-то набрано больше 29, оставляем как есть — разбирается вручную,
-- а не молча урезается под новую цифру.
--
-- Идемпотентна.

-- ── Вместимость выезда ──────────────────────────────────────────────────────
UPDATE tour_availability ta
   SET available_slots = 29
  FROM operator_tours t
  JOIN partners p ON p.id = t.operator_id
 WHERE ta.operator_tour_id = t.id
   AND p.slug = 'kamchatka-rafting'
   AND t.title = 'Однодневная экскурсия СПЛАВ ПО РЕКЕ БЫСТРАЯ'
   AND ta.available_slots IS DISTINCT FROM 29
   AND COALESCE(ta.booked_slots, 0) <= 29;

-- ── Потолок группы на самом туре ────────────────────────────────────────────
-- max_participants = 6 противоречил бы витрине: календарь предлагал бы 29
-- мест, а форма брони упиралась в шестерых.
UPDATE operator_tours t
   SET max_participants = 29,
       updated_at       = NOW()
  FROM partners p
 WHERE p.id = t.operator_id
   AND p.slug = 'kamchatka-rafting'
   AND t.title = 'Однодневная экскурсия СПЛАВ ПО РЕКЕ БЫСТРАЯ'
   AND t.deleted_at IS NULL
   AND t.max_participants IS DISTINCT FROM 29;
