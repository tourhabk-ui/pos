-- Migration 1397: сохранённая поездка помнит, что человек просил и о чём план
-- предупреждал; повтор сохранения не плодит копий (аудит планировщика 07.11,
-- волна 2.3–2.4: H6, H7, H12).
--
-- H6. Галочки «Жильё» и «Машина напрокат» в форме планировщика были, а в
-- поездку уходил только трансфер аэропорта (needs_airport_transfer, 061).
-- Сохранённый план не помнил, что человек просил машину, и заявка со страницы
-- поездки о ней молчала. Колонки — без умолчания: NULL — «не записано»
-- (поездки до 07.11), а не «не просили» (§4.0).
--
-- H7. Предупреждения плана (МЧС, безопасность, разрешения, сезон, недобор
-- дней) не хранились вовсе: страница сохранённой поездки их не показывала.
-- Хранятся снимком на день сохранения — страница так и подписывает их.
-- Предупреждения дня лежат в самих днях (days, JSONB) и миграции не требуют.
--
-- H12. Ключа повтора у сохранения не было: ответ потерялся в сети, человек
-- нажал «Сохранить» ещё раз — вторая поездка. Ключ даёт планировщик на
-- сессию плана; уникальность — у живых поездок человека (удалённая не мешает
-- сохранить заново).
--
-- Повтор миграции — без изменений.

BEGIN;

ALTER TABLE user_trips
  ADD COLUMN IF NOT EXISTS needs_lodging BOOLEAN,
  ADD COLUMN IF NOT EXISTS needs_car     BOOLEAN,
  ADD COLUMN IF NOT EXISTS warnings      JSONB,
  ADD COLUMN IF NOT EXISTS save_key      UUID;

COMMENT ON COLUMN user_trips.needs_lodging IS 'Просил жильё в планировщике; NULL — не записано (поездка до 07.11)';
COMMENT ON COLUMN user_trips.needs_car IS 'Просил машину напрокат в планировщике; NULL — не записано (поездка до 07.11)';
COMMENT ON COLUMN user_trips.warnings IS 'Предупреждения плана снимком на день сохранения: [{type,severity,message}]; NULL — не записано';
COMMENT ON COLUMN user_trips.save_key IS 'Ключ повтора сохранения из планировщика: повтор POST с тем же ключом обновляет поездку, а не создаёт вторую';

CREATE UNIQUE INDEX IF NOT EXISTS uq_user_trips_save_key
  ON user_trips (user_id, save_key)
  WHERE save_key IS NOT NULL AND deleted_at IS NULL;

COMMIT;
