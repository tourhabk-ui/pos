-- 1439: подпись таблицы переписки — слова адресата читает и ИИ-агент.
--
-- Слово владельца 13.11: «когда иностранцы обращаются к оператору, то нужно
-- для оператора переводить на русский, а ответ оператора должен быть наоборот
-- на языке обратившегося»; отдавать ли текст ответа ИИ-агенту — «карт-бланш».
--
-- Подпись 1350 говорила: «в промпты моделей и в ответы инструментов MCP не
-- уходит». Вторая половина с этого дня неверна: последние сообщения АДРЕСАТА
-- (author = owner) get_request_status отдаёт агенту, оставившему заявку, —
-- полем partner_messages (lib/mcp/partner-messages). Перевести ответ человеку
-- на его язык может только тот, кто его видит, а ключ и раньше открывал ту же
-- переписку на странице заявки.
--
-- Что осталось как было: слова клиента (author = guest) в ответы инструментов
-- не уходят; модели Ведара текста переписки не видят.
--
-- Схема не меняется: только подпись, чтобы она не обещала того, чего код уже
-- не делает (§4.0, «объявленное без исполнения»).

BEGIN;

COMMENT ON TABLE request_messages IS
  'Переписка адресата заявки (владелец жилья, туроператор, гид, перевозчик, прокат) и клиента (1349, 1350). Цель — заявка на жильё или лид, ровно одна. author owner — сторона адресата. Текст — слова людей. Слова адресата по ключу новой заявки читает и ИИ-агент, оставивший заявку (get_request_status, partner_messages, 1439); слова клиента в ответы инструментов не уходят. В промпты моделей Ведара текст не уходит.';

COMMIT;

