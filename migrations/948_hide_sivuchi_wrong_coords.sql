-- 948_hide_sivuchi_wrong_coords.sql
--
-- «Лежбище сивучей» (684857c0-defa-49c9-b5df-29ea9b8baf4d) скрыто решением
-- владельца 10.09 — та же логика, что у 947 (Овальное): запись, вероятно,
-- честная, ошибка только в координате.
--
-- Найдено по жалобе с телефона: точка стоит на грунтовой дороге посреди
-- дачного массива, 3.7 км от Петропавловска-Камчатского. Описание в БД
-- называет место «Мыс Сивучий», а координата (53.0190080,158.6476740)
-- лежит в черте города, не на побережье.
--
-- Independent-проверка через Nominatim нашла настоящий «мыс Сивучий» в
-- OSM — но он в Усть-Камчатском муниципальном округе (56.7367779,
-- 163.2255911), в 506 км от записи в БД. Либо координата скопирована не с
-- того мыса, либо у places-записи вообще другой (безымянный/неучтённый в
-- OSM) реальный сивучий лежбище, а координата — заглушка. В обоих случаях
-- источника для правки нет (§4.1 — без источника не правим).
--
-- Скрытие, не удаление: is_visible = false убирает запись с карты и из
-- каталога, но не рвёт FK и оставляет путь назад, если источник найдётся.
--
-- Идемпотентно: отсутствующая запись — no-op с NOTICE, не ошибка.

DO $$
DECLARE
  pid text := '684857c0-defa-49c9-b5df-29ea9b8baf4d';
  pname text;
BEGIN
  SELECT name INTO pname FROM places WHERE id = pid;

  IF pname IS NULL THEN
    RAISE NOTICE '[948] % — уже отсутствует в places, делать нечего', pid;
    RETURN;
  END IF;

  UPDATE places SET is_visible = false, updated_at = NOW() WHERE id = pid;
  RAISE NOTICE '[948] скрыто (is_visible=false): % (%)', pname, pid;
END $$;
