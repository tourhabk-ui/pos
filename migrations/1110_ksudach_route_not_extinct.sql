-- 1110_ksudach_route_not_extinct.sql
--
-- Маршрут «Вулкан Ксудач»: не «потухший».
--
-- ── Повод (аудит SEO и MCP 29.09) ─────────────────────────────────────────
--
-- Описание маршрута начинается словами «Ксудач (1079 м) — потухший вулкан
-- Южной Камчатки». Этот текст с 29.09 стоит в meta description карточки и
-- в выдаче Яндекса по запросу «Ксудач», а агенты MCP получают его как
-- справку. Записала его миграция 089 (`id 7a645b02-…`).
--
-- Слово неверно, и опровергает его наша же база: миграция 113 пишет о
-- месте «Последнее крупное извержение — 1907 год, одно из крупнейших в
-- XX веке на Камчатке». Вулкан, извергавшийся в историческое время, потухшим
-- не называют; Каталог вулканов мира (Smithsonian GVP, «Ksudach») числит
-- последнее извержение в 1907 году. Для туриста разница не в слоге:
-- «потухший» обещает, что опасности извержения здесь нет.
--
-- ── Границы правки ────────────────────────────────────────────────────────
--
-- Меняется одно слово в одной записи и только если там лежит ровно тот
-- текст: отбор по id И по началу описания. Успели поправить раньше —
-- миграция ничего не делает. Остальной текст не трогается, хотя в нём есть
-- расхождение, которое правкой слова не решить: 089 даёт кальдере 6 км, 113 —
-- 8 км. Какое верно, из наших данных не следует, и выбирать наугад нельзя.
--
-- `metadata.active = false` из той же 089 не правится: его не читает ни
-- один файл (проверено поиском 29.09), и правка мёртвого поля выглядела бы
-- починкой, не будучи ею.
--
-- Идемпотентна.

WITH upd AS (
  UPDATE kamchatka_routes
     SET description = regexp_replace(description, '^Ксудач \(1079 м\) — потухший вулкан', 'Ксудач (1079 м) — действующий вулкан'),
         updated_at = NOW()
   WHERE id::text = '7a645b02-4574-4f99-b2c5-56f34dfd91e5'
     AND description LIKE 'Ксудач (1079 м) — потухший вулкан%'
  RETURNING id, title, description
)
INSERT INTO description_provenance
  (entity_id, entity_kind, entity_title, written_by, facts_given, facts_count,
   chars, previous_chars)
SELECT
  upd.id::uuid,
  'route',
  upd.title,
  -- Не 'owner-decision': слово владельца здесь не давалось, правка по
  -- источнику, названному выше.
  'fact-correction',
  '["последнее извержение 1907 года (миграция 113; Smithsonian GVP, Ksudach)"]'::jsonb,
  1,
  LENGTH(upd.description),
  LENGTH(upd.description) - 3
FROM upd;
