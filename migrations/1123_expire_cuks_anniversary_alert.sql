-- 1123: гасим пост о 16-летии ЦУКС, записанный «извержением вулкана».
--
-- 01.10 верхней тревогой края — в ленте сайта, в MCP safety_status и в
-- карточке «Главное сегодня» главной — стоял пост МЧС «Центру управления в
-- кризисных ситуациях ГУ МЧС России по Камчатскому краю исполнилось 16 лет»
-- с типом volcanic_eruption. Рассказ о работе ЦУКС называет вулканы и
-- сейсмику, и вулканическая ветка классификатора приняла его за извержение.
--
-- Классификатор исправлен тем же PR (isAnniversaryPost в seismic-parser):
-- новые такие посты в ленту не попадут. Уже записанные строки сами истекли бы
-- в течение суток, но до тех пор оставались бы верхней тревогой — поэтому
-- срок им закрывается сейчас.
--
-- Строки не удаляются: expires_at = NOW() убирает их из активной обстановки и
-- оставляет след для разбора. Условие узкое — точный оборот заголовка и
-- ошибочный тип; настоящие вулканические тревоги не задеваются.
-- Идемпотентна: повторный прогон обновит ноль строк.

BEGIN;

UPDATE external_alerts
   SET expires_at = NOW(),
       updated_at = NOW()
 WHERE alert_type = 'volcanic_eruption'
   AND title ILIKE 'Центру управления в кризисных ситуациях%исполнилось 16 лет%'
   AND expires_at > NOW();

COMMIT;

-- Rollback: не требуется — строки истекли бы сами в течение суток.
