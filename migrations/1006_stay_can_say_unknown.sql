-- 1006: витрина жилья учится говорить «не знаю».
--
-- ── Повод ─────────────────────────────────────────────────────────────────
--
-- 20.09 владелец сказал про «Снежную долину»: «это база отдыха». Завести её
-- на витрину жилья не вышло — и не по лени, а потому что схема ТРЕБУЕТ того,
-- чего никто не называл:
--
--   total_rooms          NOT NULL, CHECK (> 0)
--   price_per_night_from NOT NULL
--   address              NOT NULL
--   rating               DEFAULT 0
--
-- Ни числа номеров, ни цены, ни адреса владелец не давал. Чтобы завести
-- запись, их пришлось бы ВЫДУМАТЬ — ровно тот механизм, про который в §4.0
-- сказано прямо: место, где нельзя сказать «не знаю», заполняется враньём.
--
-- Витрина жилья пуста не потому, что некому завести первую запись, а потому
-- что честную запись схема не принимает.
--
-- ── Почему каждое поле смягчается ─────────────────────────────────────────
--
-- ЦЕНА. `price_per_night_from` — это ВЫВЕСКА («от скольки»), а не источник
-- истины: бронирование считает по цене КОМНАТЫ
-- (`accommodation_rooms.price_per_night`, NOT NULL, и она такой остаётся).
-- Требовать вывеску раньше настоящей цены — требовать числа до того, как
-- есть что им называть. Проверено по коду: `book`-роут к этой колонке не
-- обращается вовсе.
--
-- ЧИСЛО НОМЕРОВ. `CHECK (> 0)` запрещал даже ноль, а «сколько номеров» у
-- базы отдыха может быть просто не записано. Проверка не снимается совсем,
-- а переписывается: неизвестно — можно, отрицательно — нельзя.
--
-- АДРЕС. У базы за городом адреса в привычном виде может не быть вовсе —
-- есть координата, и она осталась обязательной (`coordinates NOT NULL`).
-- Пустая строка вместо адреса — та же выдумка, только незаметная.
--
-- РЕЙТИНГ. Умолчание НОЛЬ — худшее из четырёх, и вредит оно дважды.
--
-- Во-первых, объект без единого отзыва получает оценку. `review_count` при
-- этом честно ноль — то есть строка сама себе противоречит: отзывов нет, а
-- оценка есть. Отзывы ставят от 1 до 5, значит ноль не может быть ничьей
-- оценкой; это «не знаю», записанное цифрой.
--
-- Во-вторых — и это уже сработало, — планер поездки отбирает жильё условием
-- `a.rating >= 3.5` (`app/api/trip/plan/route.ts`). Ноль меньше трёх с
-- половиной, значит НИ ОДИН объект без отзывов в подбор не попадал никогда.
-- А отзывы берутся из броней, брони — из подбора: круг замкнут, и увидеть
-- это можно было только чтением SQL, потому что строка не падала, а молча
-- выпадала из выдачи.
--
-- NULL вместо нуля этого сам по себе не чинит (`NULL >= 3.5` — тоже не
-- истина), поэтому условие в планере правится тем же коммитом: «не оценён»
-- не равно «оценён плохо».
--
-- ── Чего миграция НЕ делает ───────────────────────────────────────────────
--
-- Не трогает существующие строки. Там, где стоит ноль или адрес, они
-- остаются: отличить «владелец так решил» от «схема заставила» задним
-- числом нечем, а стирать чужие данные по догадке нельзя.
--
-- Не смягчает цену КОМНАТЫ и не трогает `coordinates`: по комнате считается
-- реальная сумма брони, по координате место находят на карте. Это поля, без
-- которых сущность не работает, а не вывески.
--
-- IDEMPOTENT

BEGIN;

ALTER TABLE accommodations
  ALTER COLUMN price_per_night_from DROP NOT NULL,
  ALTER COLUMN total_rooms          DROP NOT NULL,
  ALTER COLUMN address              DROP NOT NULL;

-- Рейтинг: умолчание снимается, чтобы новый объект появлялся БЕЗ оценки.
ALTER TABLE accommodations ALTER COLUMN rating DROP DEFAULT;

-- Проверка числа номеров переписывается: неизвестно — можно, отрицательно —
-- нельзя. Имя ограничения у CHECK, заданного инлайном, порождает Postgres
-- (`accommodations_total_rooms_check`), поэтому снимаем по имени и заводим
-- своё, говорящее.
ALTER TABLE accommodations DROP CONSTRAINT IF EXISTS accommodations_total_rooms_check;
ALTER TABLE accommodations DROP CONSTRAINT IF EXISTS accommodations_total_rooms_known_or_positive;
ALTER TABLE accommodations
  ADD CONSTRAINT accommodations_total_rooms_known_or_positive
  CHECK (total_rooms IS NULL OR total_rooms > 0);

COMMENT ON COLUMN accommodations.price_per_night_from IS
  'Витринное «от скольки» за ночь. NULL — цена не объявлена (не ноль). Источник истины для брони — accommodation_rooms.price_per_night.';
COMMENT ON COLUMN accommodations.total_rooms IS
  'Число номеров. NULL — не записано (не ноль).';
COMMENT ON COLUMN accommodations.address IS
  'Адрес. NULL — адреса в привычном виде нет; место находят по coordinates.';
COMMENT ON COLUMN accommodations.rating IS
  'Средняя оценка по видимым отзывам. NULL — НЕ ОЦЕНЁН (не ноль): отзывы ставят от 1 до 5, нулевой оценки не бывает.';

-- ── Исход называется вслух ────────────────────────────────────────────────
DO $$
DECLARE
  v_required int;
  v_default  text;
BEGIN
  SELECT COUNT(*) INTO v_required
    FROM information_schema.columns
   WHERE table_name = 'accommodations'
     AND column_name IN ('price_per_night_from', 'total_rooms', 'address')
     AND is_nullable = 'NO';

  IF v_required > 0 THEN
    RAISE WARNING '[1006] обязательными остались % из трёх колонок — честную запись жилья по-прежнему не завести', v_required;
  END IF;

  SELECT column_default INTO v_default
    FROM information_schema.columns
   WHERE table_name = 'accommodations' AND column_name = 'rating';

  IF v_default IS NOT NULL THEN
    RAISE WARNING '[1006] умолчание у rating ОСТАЛОСЬ (%) — новый объект снова получит оценку, которой никто не ставил', v_default;
  END IF;
END $$;

COMMIT;
