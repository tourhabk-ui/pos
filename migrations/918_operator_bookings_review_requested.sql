-- 918: Гостевой опыт в брони, часть 1 — запрос отзыва после завершённой брони.
--
-- Источник: разведданные из разбора эволюции #1418 (27.08), issue #1422,
-- решение владельца 28.08 «карт-бланш».
--
-- Флаг "отзыв уже запрошен" — по аналогии с уже существующим
-- reminder_sent_24h (040): без него cron слал бы одному и тому же туристу
-- просьбу оставить отзыв на каждом прогоне.
--
-- Триггер запроса — переход booking_status → 'completed' (ставит оператор
-- вручную через PATCH /api/hub/operator/bookings/[id]), а не расчётная дата
-- "тур прошёл + N часов": ничего в кодовой базе не переводит бронь в
-- 'completed' автоматически, и подделывать этот переход датой было бы
-- обещанием, что тур завершён, когда мы этого не знаем (CLAUDE.md §4.0).
--
-- Идемпотентно.

ALTER TABLE operator_bookings
  ADD COLUMN IF NOT EXISTS review_requested_at TIMESTAMPTZ;
