BEGIN;

UPDATE ai_route_images i
   SET image_data = NULL, s3_key = 'migrations/photos/f399943c6d623cb2979ec96b6d65ca1236e965a0c40c3043cf079f545199fdb8.jpg',
       mime_type  = 'image/jpeg',
       prompt     = 'снимок Алины Гусаковой: цирк массива Вачкажец со снежниками, кадр 3:4 (миграция 1127)',
       model      = 'manual-upload',
       width      = 960,
       height     = 1280,
       author     = 'Алина Гусакова',
       license    = NULL,
       license_url = NULL,
       source_url = NULL,
       s3_url     = NULL,
       created_at = NOW()
  FROM places p
 WHERE p.id::text = 'c4310d06-2b6c-4b6e-af3a-b0c7cd678ebe'
   AND i.route_id = p.ark_id
   AND (i.author IS NULL OR btrim(i.author) = '' OR i.prompt = 'снимок Алины Гусаковой: цирк массива Вачкажец со снежниками, кадр 3:4 (миграция 1127)');

-- ── Исход называется вслух ────────────────────────────────────────────────
DO $$
DECLARE
  v_author text;
BEGIN
  SELECT i.author INTO v_author
    FROM ai_route_images i JOIN places p ON i.route_id = p.ark_id
   WHERE p.id::text = 'c4310d06-2b6c-4b6e-af3a-b0c7cd678ebe';
  IF v_author IS DISTINCT FROM 'Алина Гусакова' THEN
    RAISE WARNING '[1127] герой «Вачкажца» НЕ сменён: там %', COALESCE('автор «' || v_author || '»', 'строки снимка нет');
  END IF;
END $$;

COMMIT;
