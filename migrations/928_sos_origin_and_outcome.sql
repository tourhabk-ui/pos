--
-- У SOS-сигнала появляется способ сказать «не знаю» — в двух местах, где его
-- сейчас нет, и где вместо него говорится неправда.
--
-- 1. origin_class — что известно об ИСТОЧНИКЕ сигнала.
--
--    02.09 в канал пришла тревога «SOS! ЭКСТРЕННЫЙ СИГНАЛ» без имени, без
--    телефона, без координат и без типа, с IP дата-центра в США. Она легла
--    активной, и Watchdog с этой минуты каждые полчаса требовал звонить 112
--    по поводу, о котором неизвестно даже, человек ли его послал.
--
--    Отклонять такое нельзя: наша страница /sos при отказе GPS шлёт ровно
--    такое же тело. Поэтому судится не содержимое, а происхождение запроса
--    (lib/safety/sos-origin.ts). NULL здесь — честное «класс не считался»:
--    у строк, записанных до этой миграции, признаков уже не спросить.
--
-- 2. outcome — чем ДЕЙСТВИТЕЛЬНО кончился сигнал.
--
--    /api/cron/sos-events-bridge закрывает сигналы старше 24 часов как
--    status = 'resolved' с примечанием «Авто-закрыт: нет ответа 24ч».
--    «Resolved» читается как «с человеком всё в порядке». На деле это
--    означает ровно обратное: сутки никто не пришёл, и что стало с человеком
--    — неизвестно. Самый громкий из возможных отказов записывался как успех
--    и переставал быть виден.
--
--    Колонка разводит эти состояния. Статус не трогаем (на нём висят чтения
--    и, возможно, CHECK, которого нет ни в одной миграции — таблица
--    sos_events в реестре схемы отсутствует, см. schema-coverage).

ALTER TABLE sos_events
  ADD COLUMN IF NOT EXISTS origin_class TEXT,
  ADD COLUMN IF NOT EXISTS outcome      TEXT,
  ADD COLUMN IF NOT EXISTS outcome_at   TIMESTAMPTZ;

COMMENT ON COLUMN sos_events.origin_class IS
  'authenticated | from_app | has_content | unattributed. NULL — не считался (строки до миграции 928)';

COMMENT ON COLUMN sos_events.outcome IS
  'resolved_by_human | false_alarm | unknown_no_response. NULL — исход ещё не подведён. '
  'unknown_no_response НЕ равно resolved: сутки никто не ответил, что с человеком — неизвестно';

-- Когда исход подведён. Нужно, чтобы «сигнал брошен» объявлялось СОБЫТИЕМ
-- (один-два раза сразу после), а не стояло вечным долгом в каждой сводке:
-- вечный долг в тревоге читается ровно так же, как отсутствие тревоги.
COMMENT ON COLUMN sos_events.outcome_at IS
  'Момент подведения исхода. По нему Watchdog объявляет свежие брошенные сигналы';

-- Разбор висящих сигналов и перепись по классам источника идут по этим двум
-- колонкам, поэтому индекс частичный: интересны только незакрытые.
CREATE INDEX IF NOT EXISTS idx_sos_events_open_origin
  ON sos_events (origin_class, created_at DESC)
  WHERE status NOT IN ('resolved', 'false_alarm');
