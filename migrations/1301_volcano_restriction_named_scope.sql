-- 1301: Запрет подходить к вулкану красит только сам вулкан и места, привязанные к нему поимённо.
-- Created: 2026-10-16
--
-- ── Слово владельца ──────────────────────────────────────────────────
--
-- 16.10: «запретов министерства красить только сам вулкан и места,
-- привязанные к нему поимённо».
--
-- ── Почему ───────────────────────────────────────────────────────────
--
-- Привязанная вулканическая тревога накрывала сам вулкан, места, привязанные к
-- нему поимённо (1029), и всё ближе 25 км (VOLCANO_SCOPED_SQL). Кольцо
-- заведено под извержение: пепел и лахары расходятся от вулкана во все
-- стороны. Сводка министерства туризма от 16.10 (1298) говорит о другом:
-- «не рекомендуется приближаться» к вулкану. Проба 144 (16.10): кольцо
-- Мутновского покрасило 23 места, вплоть до мыса Кекурного на берегу в
-- 24,6 км. Запись о Крашенинникова пришлось держать уровнем 1, иначе кольцо
-- написало бы «Сегодня там опасно» Долине гейзеров (19,8 км).
--
-- ── Что меняется ─────────────────────────────────────────────────────
--
-- У тревоги появляется охват `volcano_scope`:
--   ring  — как было: вулкан, поимённые связи, всё ближе 25 км. По умолчанию:
--           так пишут разбор КБГС, ЕГС и KVERT, их тревоги не меняются;
--   named — запрет подходить к вулкану: сам вулкан, места, привязанные к нему
--           поимённо (1029), и маршруты, которые идут через них (путевая
--           точка, не «рядом»). Правило — lib/services/safety/alert-place-scope.ts.
--
-- Пять вулканических записей сводки 1298 получают named. После этого
-- Мутновский красит себя и семь мест из 1029 (водопад и каньон Опасный,
-- Дачные источники, ГеоЭС, две фумаролы, скитур). Ключевской красит себя и
-- четыре места, Шивелуч — себя и каньон Крылья Гамулов. У Безымянного и
-- Крашенинникова поимённых связей нет, они красят только себя.
--
-- Крашенинникова — уровень 2, как остальные «не рекомендуется приближаться»
-- (ветка вулканов разбора Минтура: «не рекомендует» → 2). Уровень 1 стоял
-- только из-за кольца, а без кольца Долину гейзеров он не задевает.
-- Пуш по нему погашен ещё в 1298, поэтому подъём уровня рассылки не вызовет.
--
-- Идемпотентна: колонка и ограничение — IF NOT EXISTS, правки строк — только
-- там, где значение ещё прежнее.

BEGIN;

ALTER TABLE external_alerts ADD COLUMN IF NOT EXISTS volcano_scope TEXT NOT NULL DEFAULT 'ring';

DO $$
BEGIN
  IF NOT EXISTS (
    SELECT 1 FROM pg_constraint WHERE conname = 'external_alerts_volcano_scope_check'
  ) THEN
    ALTER TABLE external_alerts
      ADD CONSTRAINT external_alerts_volcano_scope_check CHECK (volcano_scope IN ('ring', 'named'));
  END IF;
END $$;

UPDATE external_alerts
   SET volcano_scope = 'named',
       updated_at = (NOW() AT TIME ZONE 'UTC')
 WHERE external_id IN (
         'manual-mintur-2026-10-16-mutnovsky',
         'manual-mintur-2026-10-16-bezymianny',
         'manual-mintur-2026-10-16-klyuchevskoy',
         'manual-mintur-2026-10-16-krasheninnikov',
         'manual-mintur-2026-10-16-shiveluch'
       )
   AND volcano_scope <> 'named';

UPDATE external_alerts
   SET severity = 2,
       updated_at = (NOW() AT TIME ZONE 'UTC')
 WHERE external_id = 'manual-mintur-2026-10-16-krasheninnikov'
   AND severity = 1;

COMMIT;

