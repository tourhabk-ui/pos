-- 1262: «Скала Орлиное крыло» скрыта — решение владельца 15.10 («4 скрой»)
-- Created: 2026-10-15
--
-- ── Почему ────────────────────────────────────────────────────────────────
--
-- Карточка (0fa4286f-d7e6-4083-814c-9121b3ef3a87) завела миграция 095:
-- «скальный выступ характерной формы на побережье Южной Камчатки (51.52°N,
-- 156.74°E)… разворачивается над морем как крыло орла… высота ~25 м…
-- гнездятся белоплечие орланы». Ни один пункт источника не имеет. При
-- разборе Южно-Камчатского заказника (1252) выяснилось, что точка стоит
-- больше чем в 15 км от берега — «над морем» она быть не может; описание и
-- заметка Кузьмича тогда сняты, а сама карточка осталась на карте без текста.
--
-- Где на самом деле такая скала и есть ли она, из наших данных не следует:
-- у записи нет источника, и разбор 1252 его не нашёл. Правки координаты
-- взять неоткуда, а по правилу 23.08 (CLAUDE.md §4.1) без источника
-- координату не двигают — прячут, как 947 и 948. Владелец 15.10 на вопрос о
-- ней ответил «скрой».
--
-- ── Как ───────────────────────────────────────────────────────────────────
--
-- is_visible = false: запись уходит с карты, из каталога, поиска, Кузьмича
-- и MCP (все они читают только видимые), но не удаляется — связи
-- (route_waypoints и прочие) не рвутся, и путь назад остаётся, если найдётся
-- источник. Сторож строки — id и имя: другую запись эта правка не тронет.
-- Повтор — no-op.
--
-- IDEMPOTENT

BEGIN;

UPDATE places
   SET is_visible = false,
       updated_at = NOW()
 WHERE id::text = '0fa4286f-d7e6-4083-814c-9121b3ef3a87'
   AND name = 'Скала Орлиное крыло'
   AND is_visible = true;

DO $$
DECLARE
  v_visible boolean;
BEGIN
  SELECT is_visible INTO v_visible
    FROM places WHERE id::text = '0fa4286f-d7e6-4083-814c-9121b3ef3a87';
  IF v_visible IS NULL THEN
    RAISE NOTICE '[1262] «Скалы Орлиное крыло» в places нет — делать нечего';
  ELSIF v_visible THEN
    RAISE WARNING '[1262] «Скала Орлиное крыло» осталась видимой — имя записи другое?';
  ELSE
    RAISE NOTICE '[1262] «Скала Орлиное крыло» скрыта';
  END IF;
END $$;

COMMIT;

