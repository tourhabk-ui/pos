-- 1041: «Озеро Микижа» — вернуть описание по слову владельца.
--
-- ── Что случилось (26–27.09) ─────────────────────────────────────────────────
--
-- Миграция 1034 положила озеру текст из слова владельца и его снимков (235
-- знаков) и записала происхождение `owner-decision`. Утром 27.09 MCP
-- get_place_info отдал другой текст — те же факты, дописанные моделью:
--
--   «...поэтому добраться сюда можно на автомобиле... Это место подходит для
--    спокойного отдыха у воды, прогулок и рыбалки. Посещать озеро комфортнее
--    в тёплое время года...»
--
-- Про рыбалку и сезон владелец не говорил, на снимках этого нет. Короткий
-- текст попал в очередь машинного описания как «недописанный»; очереди
-- исключали свой прежний текст, но не решение человека. Сама дыра закрыта
-- кодом (lib/places/owner-decided.ts) — эта миграция возвращает текст.
--
-- ── Границы правки ─────────────────────────────────────────────────────────
--
-- Правится только запись, где лежит ровно дописанный текст — отбор по его
-- началу. Поправил кто-то ещё — миграция не делает ничего. Журнал
-- происхождения получает новую запись `owner-decision`, чтобы было видно:
-- текст возвращён, а не написан заново.
--
-- Идемпотентна.

WITH old AS (
  SELECT id, LENGTH(description) AS prev_chars
    FROM places
   WHERE name = 'Озеро Микижа'
     AND description LIKE 'Озеро Микижа находится в долине среди сопок%'
),
upd AS (
  UPDATE places p
     SET description = 'Озеро в долине среди сопок, берега заросли берёзовым лесом. К озеру ведёт асфальтированная дорога. На берегу стоит база отдыха «Голубая лагуна» с причалом и бассейном; у причала — лодки и водные велосипеды. К воде ведёт галечный спуск.',
         updated_at = NOW()
    FROM old
   WHERE p.id::text = old.id::text
  RETURNING p.ark_id, p.name, p.description, old.prev_chars
)
INSERT INTO description_provenance
  (entity_id, entity_kind, entity_title, written_by, facts_given, facts_count,
   chars, previous_chars)
SELECT
  upd.ark_id,
  'place',
  upd.name,
  'owner-decision',
  '["возврат текста миграции 1034 после машинной дописки (рыбалка, сезон — без источника)"]'::jsonb,
  1,
  LENGTH(upd.description),
  upd.prev_chars
FROM upd
WHERE upd.ark_id IS NOT NULL;
