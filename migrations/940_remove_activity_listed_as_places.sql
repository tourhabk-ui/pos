-- 940_remove_activity_listed_as_places.sql
--
-- Три коммерческие активности убраны из `places` (решение владельца 07.09,
-- продолжение 939): «Река Авача — рыбалка» уже скрыта миграцией 939, но
-- перепись GET /api/cron/place-activity-census (lib/places/activity-name-judge.ts)
-- нашла в живой базе ещё четыре записи с тем же дефектом — тур или
-- коммерческая рыбалка заведены строкой `places`, хотя это не факт
-- местности (§9 CLAUDE.md: «Точка = место. Тур = коммерция. Не смешивать»).
--
-- Из четырёх найденных — три удаляются здесь, они не наши:
--   Озеро Толмачёво — рыбалка и медведи (ff6d6ee6-…) — route_titles пуст,
--     зависимых путевых точек нет;
--   Река Жупанова — рыбалка (da5755cb-…) — привязана к маршруту «Мыс
--     Жупанова» через route_waypoints (place_id), поэтому DELETE может
--     упереться в FK — на этот случай ниже есть отступление к скрытию;
--   Река Опала — спортивная рыбалка (1208a109-…) — route_titles пуст.
--
-- Четвёртая находка переписи, «Река Камчатка — рыбалка» (9ad01c57-…),
-- НЕ трогается: она привязана к маршруту «Рыболовная база Камчатская
-- Рыбалка» — это наш партнёр (владелец 07.09, «оставить как есть — не
-- трогать вовсе»). Разбор её карточки (место vs тур партнёра) — отдельный
-- вопрос, не эта миграция.
--
-- Удаление, не скрытие — прямое слово владельца («удаляй»), в отличие от
-- 939 (там было «скрой») и от 933 («маршрут-призрак», где скрытие выбрано
-- из-за FK). Здесь FK всё равно уважается: DELETE, а при foreign_key_violation
-- — тот же отступ к is_visible=false, что и в 920/933, с явным WARNING —
-- «не смог удалить» не должно выглядеть как «удалил» или пройти молча.
--
-- Идемпотентно: отсутствующая запись — no-op с NOTICE, не ошибка.

DO $$
DECLARE
  ids text[] := ARRAY[
    'ff6d6ee6-e81a-4f9c-bbf6-6e119e1cafdb', -- Озеро Толмачёво — рыбалка и медведи
    'da5755cb-aa5a-4c50-b6c5-ddbcdceab55c', -- Река Жупанова — рыбалка
    '1208a109-c78c-41b3-8f21-4db06d4a13ca'  -- Река Опала — спортивная рыбалка
  ];
  pid text;
  pname text;
BEGIN
  FOREACH pid IN ARRAY ids LOOP
    SELECT name INTO pname FROM places WHERE id = pid;

    IF pname IS NULL THEN
      RAISE NOTICE '[940] % — уже отсутствует в places, делать нечего', pid;
      CONTINUE;
    END IF;

    BEGIN
      DELETE FROM places WHERE id = pid;
      RAISE NOTICE '[940] удалено из places: % (%)', pname, pid;
    EXCEPTION WHEN foreign_key_violation THEN
      UPDATE places SET is_visible = false, updated_at = NOW() WHERE id = pid;
      RAISE WARNING '[940] % (%) держат зависимые строки (скорее всего route_waypoints) — не удалено, а скрыто (is_visible=false)', pname, pid;
    END;
  END LOOP;
END $$;
