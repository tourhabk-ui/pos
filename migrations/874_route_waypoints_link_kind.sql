-- 874: у связи «маршрут — место» появляется СМЫСЛ.
--
-- ── Что вскрылось ─────────────────────────────────────────────────────────
--
-- Перепись 18.08 показала у двадцати маршрутов «точку в N км от линии» и на
-- этом остановилась. Когда стали печататься ВСЕ точки, картина оказалась
-- другой: у «Скал Три Брата» среди двадцати трёх «путевых точек» — краевой
-- музей, Вулканариум, памятник Берингу и батарея Максутова; у похода к
-- Авачинскому — Музей лосося и Халактырский пляж; у двух авачинских
-- маршрутов набор точек совпадает до единой.
--
-- Причину написала о себе сама миграция 167:
--
--   "Populate route_waypoints via geographic proximity — links routes to
--    NEARBY PLACES (within 15km) so that place cards show related routes and
--    route cards show waypoints"
--
-- То есть связи заводились как «что рядом», а платформа читает их как
-- «маршрут здесь проходит». Одна таблица, два несовместимых смысла. Отсюда и
-- «position»: у 167 это ранг по удалённости от ЦЕНТРА маршрута, а не порядок
-- прохождения, и `is_start` доставался ближайшему к центру месту.
--
-- Порогами это не лечится: расстояние не отличает украшение от пути.
--
-- ── Почему разметка по УЛИКЕ, а не по расстоянию ──────────────────────────
--
-- Соблазн разметить по близости к линии («далеко — значит рядом-объект»)
-- обязан быть отвергнут: тогда каждый маршрут пройдёт черту автоматически,
-- потому что всё неудобное переименуется в «рядом». Это не починка данных, а
-- выключение сигнализации.
--
-- Улика лежит в происхождении связи, и она поимённая:
--
--   653/654/657 — совпадение имени маршрута и места (109 точных, 4 по
--                 порядку слов, 27 вхождений). Место, чьё имя носит маршрут,
--                 к маршруту относится — это точка пути.
--   655/656     — точки МНОГОЭТАПНЫХ маршрутов со страниц источника,
--                 position 0..N в порядке прохождения. Это и есть путь.
--   167         — «в 15 км от центра». Это «рядом».
--
-- Пары 653-657 перечислены в самих файлах миграций — 238 штук, они и
-- размечаются как `waypoint`. Всё остальное, что воспроизводит предикат 167
-- (место в 15 км от центра маршрута), помечается `nearby`.
--
-- Остаток честно остаётся `unknown`: связь, заведённую вручную позже, мы
-- объявить не вправе ни тем, ни другим. `unknown` черта судит как раньше —
-- поэтому ничего не улучшится молча.
--
--   waypoint — точка ПУТИ: по ней сверяется линия, ею меряется расхождение
--   nearby   — контекст: «это рядом, загляните». Черта её не считает вовсе
--   unknown  — не установлено; ведёт себя как прежде

