-- Migration 1313: след переименования карточки клиента CRM партнёром (#2327)
-- Created: 2026-10-22
--
-- ── Зачем ─────────────────────────────────────────────────────────────────
-- Удаление аккаунта стирает карточку клиента CRM целиком, только если она
-- доказанно его (PROVEN_HIS_CARD, lib/account/erase.ts): каждая связь — его
-- бронь, аренда или заказ, и записей партнёра о клиенте в ней нет. Заметку,
-- метки, задачи и касания видно по строкам, а переименование — нет:
-- updateContact писал только updated_at, который двигает и склейка.
--
-- Номер у партнёра — одна карточка: мать звонит с семейного номера, ручное
-- добавление отвечает «клиент уже есть» с карточкой сына, и партнёр
-- переименовывает её в «Мария Ивановна (мама Андрея)». Удаление аккаунта сына
-- стирало такую карточку целиком — и с ней запись партнёра о матери.
--
-- ── Что ───────────────────────────────────────────────────────────────────
-- renamed_by_partner_at — когда партнёр последний раз сменил имя карточки
-- (updateContact, lib/crm/contact-queries.ts — экран, Кузьмич и MCP
-- партнёра). Пишет только смена имени, а не повтор того же. Карточка со
-- следом доказанно его не бывает. Переименования до этой миграции следа не
-- оставили, и задним числом его не выдумать: колонка для них NULL.
--
-- Идемпотентна.

ALTER TABLE crm_contacts ADD COLUMN IF NOT EXISTS renamed_by_partner_at TIMESTAMPTZ;

COMMENT ON COLUMN crm_contacts.renamed_by_partner_at IS
  'Когда партнёр сменил имя карточки (updateContact). Не NULL — имя записал партнёр, и удаление аккаунта клиента не считает карточку доказанно его (PROVEN_HIS_CARD, #2327). Переименования до миграции 1313 следа не имеют.';
