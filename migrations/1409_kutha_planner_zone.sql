-- 1409: зона планера у «Кутхи» — Авачинская (слово владельца 08.11).
--
-- 1031 оставила зону планера у всех объектов жилья пустой: по тексту и
-- координатам зону не угадывают, её называет владелец. «Кутха» (1179, пос.
-- Пионерский) — единственный объект на витрине, и планер его на ночёвку не
-- предлагал: объект без зоны в подбор не встаёт (lib/planner/trip-extras-data),
-- план только считает его строкой «без разметки зоны».
--
-- Владелец 08.11 на вопрос, в какую зону поставить «Кутху»: «авачинскую».
-- Ключ движка — avachinsky (ZoneId, lib/planner/constants.ts; CHECK 1031).
--
-- Только там, где зона не записана: поставленную в кабинете или на
-- модерации миграция не перезаписывает. Идемпотентна.

UPDATE accommodations
   SET planner_zone = 'avachinsky',
       updated_at = NOW()
 WHERE LOWER(name) = 'кутха'
   AND planner_zone IS NULL;
