-- «Ходуткинские горячие источники» — ЗЕЛЁНЫМИ. Живой ответ
-- get_guardian_context 14.11: Ксудач — green, строки о закрытии парка у него
-- нет. Зелёный читается «можно идти».
--
-- Слово владельца 14.11 на план по открытым задачам: «карт-бланш тебе делай
-- как правильно и главное не врать».
--
-- ── Причина ───────────────────────────────────────────────────────────────
--
-- Связь «место — парк» (1407) у «Южно-Камчатского» записана только по контуру
-- OpenStreetMap — отношению 21624150. Проба 1028 (14.11, Overpass и Nominatim):
-- рамка этого отношения — 52.228–52.611° с. ш., 157.944–158.570° в. д. Это
-- северный кластер: Мутновский, Горелый, берег до мыса Кекурного. Парк же
-- двухкластерный — справочник краевого Минприроды 2013 года: «природный парк
-- стал 2-кластерным… уменьшена его площадь до 486,9 тыс. га» (kamchatsky-
-- krai.ru, проба 1028). Контура южного кластера в OSM нет вовсе: в рамке юга
-- полуострова других отношений парка Overpass не вернул. Поэтому Ксудач
-- (51.81° с. ш.) и Ходутка (52.06° с. ш.) связи не получили, и 1245 это
-- оговорила: «не установлено» не равно «не в парке».
--
-- ── Источники — что именно названо частью парка ───────────────────────────
--
--   сайт сети природных парков «Вулканы Камчатки», раздел «Территория /
--     Природный парк „Южно-Камчатский“», страница «Вулканы» (проба 871,
--     14.10.2026, vulcanikamchatki.ru/territoriya/klaster_yuzhnokamchatskij/
--     vulkany/): Горелый, Мутновский, «Сопка Асача», «Сопка Ходутка»,
--     «Ксудач (вулкан Штубеля, гора Ксудач, Вонючий хребет)», «Желтовская
--     сопка». Шесть вулканов; справочник 2013 года насчитывает в парке семь,
--     поимённо их не называя;
--   справочник краевого Минприроды «Особо охраняемые природные территории
--     Камчатского края» (2013), справка на kamchatsky-krai.ru (проба 1028,
--     14.11.2026): «В границах природного парка отмечается разнообразие
--     термоминеральных источников: Родниковые, Жировские, Ходуткинские».
--
-- 14.11 те же страницы сайта парка раннеру не ответили (301 без тела), поэтому
-- цитата сайта — по чтению 14.10; лог того прогона сохранён в Actions.
--
-- ── Что НЕ связывается, и почему ──────────────────────────────────────────
--
--   «Северная видовка на Ксудач» — точка в 15 км к северу от кальдеры (1288);
--     источник её не называет, а границы кластера нет: «не установлено»;
--   «Видовка с горы Каменистая» — источника, что эта точка в парке, под рукой
--     нет;
--   Асачинские и Саванские источники — сайт парка перечисляет их на странице
--     источников, но справочник называет «в границах» только Родниковые,
--     Жировские и Ходуткинские, а Асачинское месторождение из парка вычленено
--     (тот же справочник). Страница источников сайта — не перечень «внутри
--     границы»: на ней же стоят Вилючские источники другого парка;
--   остальные места юга — без источника связь не пишется. По расстоянию связь
--     не выводится (§4.1).
--
-- Режим посещения этих мест (нужно ли разрешение) миграция не трогает: у
-- национального парка порядок ещё не объявлен (1245), а Ксудач — ещё и
-- памятник природы со своей записью (1288). Меняется одно: закрытие парка
-- теперь доходит до этих пяти мест.
