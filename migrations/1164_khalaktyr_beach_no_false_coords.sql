-- 1164: Халактырский пляж — из описания убрана ложная координата
-- Created: 2026-10-04
--
-- Владелец 04.10: «посъезжали точки». Координата места исправлена
-- place-coords run 28 по Maps.me владельца (52.994759/158.857237; стояло
-- 53.095/158.813 — в лесу в 11.5 км от берега). Но в САМОМ описании жила
-- третья координата: «Координаты: 52.9931° N, 158.5472° E» — это черта
-- Петропавловска, а не океанский берег. Текст называл человеку точку, куда
-- ехать, и она была ложной.
--
-- Убирается ровно эта фраза и markdown-заголовок «### Халактырский пляж»
-- в начале (он повторял название и выводился решётками). Остальной текст не
-- трогается: переписывать его без источника — та же выдумка (§4.0).
-- Отбор — по id и самой фразе: убрано раньше — no-op.

BEGIN;

UPDATE places
   SET description = btrim(regexp_replace(
         regexp_replace(description, '^\s*###\s*Халактырский пляж\s*', ''),
         '\s*Координаты:\s*52\.9931°\s*N,\s*158\.5472°\s*E\.?', '')),
       updated_at = NOW()
 WHERE id::text = '49a1d46a-704b-4307-bb6a-fea5988ec4f8'
   AND description LIKE '%158.5472%';

COMMIT;
