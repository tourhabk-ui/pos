-- Migration 1489: Долина гейзеров — факты карточек ID45 и ID40 (#3487)
-- Created: 2026-11-21
--
-- Комментарий к issue #3487 от 21.11.2026: расхождения на карточках
-- «Экскурсия в Долину гейзеров и кальдеру вулкана Узон»
-- (volcanoesland-dolina-geyzerov-kaldera-uzon) и «Курильское озеро, Долина
-- гейзеров, вулканы Горелый и Авача»
-- (volcanoesland-kurilskoe-ozero-dolina-geyzerov-gorelyy-avacha), плюс та же
-- длительность долины в составе ещё одного тура «Края Вулканов».
--
-- Первоисточники, сверены 21.11.2026:
--   • пребывание в долине — 2–2,5 часа, тропа около 1 км; в мае–июне
--     «месячник тишины»:
--     https://kronoki.ru/ru/visit/information-for-all/excursions/147.html
--   • кальдера Узона — котловина 9×12 км, экскурсия 1 час:
--     https://kronoki.ru/ru/visit/information-for-all/excursions/158.html
--   • основной сезон с начала июля: новость заповедника 19.06.2026,
--     https://kronoki.ru/ru/news/newswire/3879.html
--
-- Что меняется. На карточках стояли «полтора часа» / «около 1,5 часа» в
-- долине и «около 50 минут» / «около 40 мин» в Узоне — это противоречит
-- заповеднику. «Гигантская впадина 9–12 км» читается как диапазон, у
-- заповедника — стороны котловины 9×12 км. «Одно из крупнейших гейзерных
-- полей мира» заповедник так не формулирует (говорит о компактности и
-- уникальности) — формулировка уходит из описания. Сезонное окно оператора
-- (1 мая — 1 октября) не переписывается: это рамка дат, не режим
-- заповедника; к предупреждениям добавляется оговорка про «месячник
-- тишины» и основной сезон с начала июля.
--
-- Часы в заголовках программы однодневной экскурсии (12:00–13:30 и т.д.)
-- не трогаются: это слоты с сайта оператора, новый график за него не
-- выдумывается. В тексте шага — длительность по данным заповедника и то,
-- что время в день вылета подтверждает оператор.
--
-- Идемпотентна: каждая правка — по точной фразе и только там, где фраза
-- ещё стоит; повтор ничего не меняет.

BEGIN;

-- ═══ Однодневная экскурсия (карточка ID45) ═══════════════════════════════

UPDATE operator_tours
   SET short_description = replace(short_description,
         'полтора часа в Долине гейзеров',
         '2–2,5 часа в Долине гейзеров по данным заповедника'),
       updated_at = NOW()
 WHERE slug = 'volcanoesland-dolina-geyzerov-kaldera-uzon'
   AND deleted_at IS NULL
   AND COALESCE(short_description, '') LIKE '%полтора часа в Долине гейзеров%';

UPDATE operator_tours
   SET description = replace(
         replace(description,
           'каньон с одним из крупнейших гейзерных полей мира, спрятанный в труднодоступном ущелье Кроноцкого биосферного заповедника',
           'каньон реки Гейзерной в Кроноцком государственном биосферном заповеднике'),
         'гигантская впадина 9–12 км',
         'гигантская котловина 9×12 км'),
       updated_at = NOW()
 WHERE slug = 'volcanoesland-dolina-geyzerov-kaldera-uzon'
   AND deleted_at IS NULL
   AND (COALESCE(description, '') LIKE '%одним из крупнейших гейзерных полей мира%'
        OR COALESCE(description, '') LIKE '%гигантская впадина 9–12 км%');

UPDATE operator_tours
   SET program = replace(
         replace(program::text,
           'Экскурсия в Долине гейзеров.',
           'Экскурсия в Долине гейзеров. По данным заповедника пребывание в долине — 2–2,5 часа; время в день вылета подтверждает оператор.'),
         'Перелёт (10 минут) в кальдеру вулкана Узон и экскурсия по ней.',
         'Перелёт (10 минут) в кальдеру вулкана Узон и экскурсия по ней. По данным заповедника экскурсия по кальдере — 1 час; время в день вылета подтверждает оператор.'
       )::jsonb,
       updated_at = NOW()
 WHERE slug = 'volcanoesland-dolina-geyzerov-kaldera-uzon'
   AND deleted_at IS NULL
   AND program::text LIKE '%Экскурсия в Долине гейзеров.%';

UPDATE operator_tours
   SET included = array_replace(included,
         'экскурсия по Долине гейзеров (около 1,5 часа) и по кальдере Узон (около 50 минут) с гидом-экскурсоводом',
         'экскурсия по Долине гейзеров (по данным заповедника — 2–2,5 часа) и по кальдере Узон (по данным заповедника — 1 час) с гидом-экскурсоводом'),
       updated_at = NOW()
 WHERE slug = 'volcanoesland-dolina-geyzerov-kaldera-uzon'
   AND deleted_at IS NULL
   AND included IS NOT NULL
   AND 'экскурсия по Долине гейзеров (около 1,5 часа) и по кальдере Узон (около 50 минут) с гидом-экскурсоводом' = ANY(included);

-- ═══ Многодневный тур (карточка ID40) ════════════════════════════════════

UPDATE operator_tours
   SET program = replace(program::text,
         'Экскурсия (около 1,5 часов) по Долине гейзеров, перелёт в кальдеру Узон и осмотр её геотермальных проявлений (около 40 мин)',
         'Экскурсия по Долине гейзеров (по данным заповедника пребывание в долине — 2–2,5 часа), перелёт в кальдеру Узон и осмотр её геотермальных проявлений (по данным заповедника экскурсия — 1 час)'
       )::jsonb,
       updated_at = NOW()
 WHERE slug = 'volcanoesland-kurilskoe-ozero-dolina-geyzerov-gorelyy-avacha'
   AND deleted_at IS NULL
   AND program::text LIKE '%Экскурсия (около 1,5 часов) по Долине гейзеров%';

-- ═══ Тот же факт о длительности в долине у соседнего тура оператора ══════

UPDATE operator_tours
   SET included = array_replace(included,
         'вертолётная экскурсия: Долина гейзеров (около 1,5 часа) и кальдера вулкана Узон (около 1 часа), затем перелёт в Мильково',
         'вертолётная экскурсия: Долина гейзеров (по данным заповедника — 2–2,5 часа) и кальдера вулкана Узон (по данным заповедника — 1 час), затем перелёт в Мильково'),
       updated_at = NOW()
 WHERE slug = 'volcanoesland-oblet-klyuchevskoy-gruppy-dolina-geyzerov'
   AND deleted_at IS NULL
   AND included IS NOT NULL
   AND 'вертолётная экскурсия: Долина гейзеров (около 1,5 часа) и кальдера вулкана Узон (около 1 часа), затем перелёт в Мильково' = ANY(included);

-- ═══ Оговорка про сезон: рамка оператора ≠ режим заповедника ═════════════

UPDATE operator_tours
   SET safety_notes = COALESCE(safety_notes, ARRAY[]::text[]) || ARRAY[
         'Сезонное окно на карточке — рамка дат оператора; в мае–июне в долине действует «месячник тишины» заповедника, основной сезон начинается в начале июля. Режим в эти месяцы уточняйте у оператора.'
       ]::text[],
       updated_at = NOW()
 WHERE slug IN (
         'volcanoesland-dolina-geyzerov-kaldera-uzon',
         'volcanoesland-kurilskoe-ozero-dolina-geyzerov-gorelyy-avacha'
       )
   AND deleted_at IS NULL
   AND NOT COALESCE(safety_notes, ARRAY[]::text[]) @>
         ARRAY['Сезонное окно на карточке — рамка дат оператора; в мае–июне в долине действует «месячник тишины» заповедника, основной сезон начинается в начале июля. Режим в эти месяцы уточняйте у оператора.']::text[];

COMMIT;
