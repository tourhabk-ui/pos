-- ═══ п.2. Костакан: 752,2 м в сути ═══════════════════════════════════════

WITH old AS (
  SELECT id, LENGTH(essence) AS prev_chars
    FROM places
   WHERE id::text = '1d427c44-9f54-47da-99ff-12231705746b'
), upd AS (
  UPDATE places p
     SET essence = replace(p.essence, 'на высоте 752 метра', 'на высоте 752,2 метра'),
         updated_at = NOW()
    FROM old
   WHERE p.id::text = old.id::text
     AND p.essence LIKE '%на высоте 752 метра%'
  RETURNING p.ark_id, p.name, p.essence, old.prev_chars
)
INSERT INTO description_provenance
  (entity_id, entity_kind, entity_title, written_by, facts_given, facts_count, chars, previous_chars)
SELECT upd.ark_id, 'place', upd.name, 'owner-decision',
       '["суть 1288 с высотой 752,2 м вместо 752 м — как в описании и в источнике (Википедия «Костакан (озеро)»), одно значение на карточке (#3473, п.2)"]'::jsonb,
       1, LENGTH(upd.essence), upd.prev_chars
  FROM upd
 WHERE upd.ark_id IS NOT NULL;

