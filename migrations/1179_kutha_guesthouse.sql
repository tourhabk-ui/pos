-- 1179: гостевой дом «Кутха» (пос. Пионерский) — карточка партнёра со звонком (#2238).
--
-- Решение владельца 08.10: первое своё жильё заводится как «Голубая лагуна»
-- (1109) — карточка, цены и свободные даты у объекта, платформа ничего не
-- продаёт. Отличие одно: у «Кутхи» нет своего сайта брони, есть телефон.
-- Владелец прислал карточку 2ГИС (координаты 53.094924, 158.543200) и
-- телефон объекта: «это его номер». Оплата платформой выключена (05.10),
-- турист договаривается и платит объекту сам.
--
-- Новая колонка contact_phone — телефон ОБЪЕКТА для связи, не аккаунта
-- партнёра: у объекта нет ни аккаунта, ни сайта. Формат +7 и десять цифр
-- проверяется базой (по построению tel:-ссылка не получит мусор). В ответ
-- AI-инструментов (Кузьмич, MCP) номер не уходит — только признак, что он
-- есть, и ссылка на карточку (pd-guard: модели зарубежные).
--
-- Записано только то, что назвали, и у каждого факта есть источник:
--   - имя, координаты, телефон — слово владельца 08.10 (карточка 2ГИС);
--   - «до 8 мест, баня, беседки, парковка, крытый бассейн с подогревом,
--     цена от 28 000 ₽» — перечень из #2238 со ссылкой на 2ГИС, с самой
--     карточкой 2ГИС НЕ сверен (проба 716 с раннера не дождалась ответа);
--   - тип «гостевой дом» — так назван в #2238 («не отель»).
-- Цена NULL: «от 28 000 ₽» — без единицы (за сутки? за дом?), и число в
-- price_per_night_from было бы выдумкой единицы (§4.0). Текст карточки
-- говорит это словами. Свободные даты не рисуются: их нет в системе.
-- Зона планера НЕ ставится (1031: зону не угадывают). is_verified=false:
-- договора с объектом нет; опубликован сразу (approved), как 1109.
--
-- Идемпотентна: колонка IF NOT EXISTS, объект — по имени; повтор ничего не
-- плодит и не перетирает правки администратора.

ALTER TABLE accommodations
  ADD COLUMN IF NOT EXISTS contact_phone TEXT;

DO $$
BEGIN
  IF NOT EXISTS (
    SELECT 1 FROM pg_constraint WHERE conname = 'accommodations_contact_phone_format'
  ) THEN
    ALTER TABLE accommodations
      ADD CONSTRAINT accommodations_contact_phone_format
      CHECK (contact_phone IS NULL OR contact_phone ~ '^\+7[0-9]{10}$');
  END IF;
END $$;

INSERT INTO accommodations
  (name, type, description, short_description, address, coordinates, location_zone,
   amenities, is_active, is_verified, moderation_status, moderated_at, contact_phone)
SELECT
  'Кутха',
  'guesthouse',
  'Гостевой дом в посёлке Пионерский. По данным 2ГИС: до 8 мест, баня, беседки, парковка, крытый бассейн с подогревом. '
  || 'Цена в 2ГИС указана «от 28 000 ₽» без единицы — за сутки или за дом, неизвестно. '
  || 'Цену, свободные даты и условия заселения уточняйте у владельца по телефону. '
  || 'Бронь и оплата идут напрямую с объектом: платформа оплату не принимает и номеров не продаёт.',
  'Гостевой дом в пос. Пионерский: баня, беседки, крытый бассейн',
  'пос. Пионерский',
  jsonb_build_object('lat', 53.094924, 'lng', 158.5432),
  'Пионерский',
  jsonb_build_array('Баня', 'Беседки', 'Парковка', 'Крытый бассейн с подогревом'),
  true, false, 'approved', NOW(),
  '+79622152777'
WHERE NOT EXISTS (
  SELECT 1 FROM accommodations WHERE LOWER(name) IN ('кутха', 'гостевой дом кутха')
);
