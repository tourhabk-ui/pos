-- Партия ремонта координат №5: Бархатная сопка.
--
-- Прочёс кластеров 15.08 нашёл «Озеро Тополовое» точь-в-точь на точке
-- «Вулкана Бархатная сопка» (52.89676, 158.18933) — след геокодера-заглушки.
-- Проверка по Википедии показала неожиданное: битой оказалась САМА
-- Бархатная — её статья даёт 52.8184278, 158.2267861, наша запись стояла
-- в 9 км севернее. После починки кластер распадается сам: Тополовое
-- остаётся на прежней точке одно.
--
-- Тополовое озеро НЕ трогаем: своего числа в открытых источниках не
-- нашлось (правило партии 752 — без верифицированного источника координату
-- не выдумываем). Если у озера точка тоже битая — это отдельная находка
-- со своим источником.
--
-- Правило то же, что в 751: обновляем ТОЛЬКО если текущая координата дальше
-- ~2 км от верифицированной — ручные правки админкой не перетираем.
-- Идемпотентна.

UPDATE places SET lat = 52.8184, lng = 158.2268, updated_at = NOW()
 WHERE name = 'Вулкан Бархатная сопка'
   AND merged_into_id IS NULL
   AND (lat IS NULL OR abs(lat - 52.8184) > 0.02 OR abs(lng - 158.2268) > 0.03);

INSERT INTO _migrations (name)
VALUES ('864_barhatnaya_sopka_coords.sql')
ON CONFLICT (name) DO NOTHING;
