-- Migration 848: у статей появляется своя таблица
--
-- ── Откуда взялась нужда ────────────────────────────────────────────────────
--
-- Перепись 11.08 (пробы 43-53): из 421 маршрута 97 не имеют ни координат, ни
-- линии, ни путевых точек. Разбор по адресу источника разложил их начисто:
--
--   /upload   67   «5 стройка–Центральный», «SUP-маршрут Полуостров Завойко»
--   /note     26   «Флора Камчатки», «Растения Камчатки», «Поселок Эссо»
--   /routes    4   латинские слаги
--
-- Раздел «note» — слово самого источника: он опубликовал ЗАМЕТКУ. Двадцать
-- шесть таких лежали в справочнике маршрутов видимыми, то есть «Растения
-- Камчатки» предлагались туристу как маршрут.
--
-- ── Почему таблица, а не флаг в маршрутах ───────────────────────────────────
--
-- Флаг «это на самом деле не маршрут» внутри таблицы маршрутов — способ
-- сохранить беспорядок, оформив его. Ровно из-за такой экономии половину дня
-- ушло на то, чтобы отличить статью от маршрута по названию: они лежали в
-- одном месте и выглядели одинаково.
--
-- В §4.1 три сущности — точка, маршрут, тур; у каждой своя таблица, потому
-- что это разные вещи. Статья — четвёртая: у неё нет ни координат, ни пути,
-- ни цены, зато есть текст и тема. Значит и место у неё своё.
--
-- ── Что делает эта миграция и чего не делает ────────────────────────────────
--
-- Только создаёт таблицу. Перенос строк живёт в шаге ремонта
-- (`lib/services/data-repair.ts`, шаг source_note), потому что правило
-- «что считать заметкой» уже описано там и на TypeScript, а второе описание
-- того же правила на SQL разошлось бы с первым — за сутки это случилось
-- трижды (SQL-чистка алертов против TS-стража, линия на трёх экранах,
-- список родовых слов против длины среза).
--
-- Идемпотентна.

BEGIN;

CREATE TABLE IF NOT EXISTS articles (
  id          UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  slug        VARCHAR(80) UNIQUE NOT NULL,
  title       TEXT NOT NULL,
  body        TEXT,
  -- Откуда взята: без этого через месяц не отличить нашу редакцию от
  -- затянутой скрейпером, а редактировать их надо по-разному.
  source_url  TEXT,
  source_name VARCHAR(120),
  -- Тема даёт разделу оглавление: «природа», «край», «сезон». Не обязательна:
  -- пустая тема честнее выдуманной.
  topic       VARCHAR(60),
  is_visible  BOOLEAN NOT NULL DEFAULT TRUE,
  created_at  TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at  TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS idx_articles_visible ON articles (is_visible, title);

COMMIT;
