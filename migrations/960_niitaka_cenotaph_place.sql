--
-- ── Координата и её точность ──────────────────────────────────────────────
--
-- 51°30'00" с.ш., 156°29'00" в.д. → 51.5, 156.483333. Источник назван
-- владельцем: Wikimedia Commons.
--
-- Точность честно НЕВЫСОКАЯ, и это записано в coord_source, а не замолчано:
-- градусы-минуты-секунды даны с нулевыми секундами, то есть округлены до
-- целой угловой минуты. Минута широты — 1.85 км, минута долготы на 51.5° —
-- около 1.15 км. Значит точка указывает памятник с погрешностью порядка
-- километра, и вести по ней человека «в ноль» нельзя.
--
-- coord_source — 'external': координата взята из внешнего справочника, а не
-- снята прибором и не угадана по названию. Значение добавлено в перечень
-- lib/places/coord-source.ts этой же правкой, и вот почему: колонка свободный
-- текст, а перечень был закрытым, и миграция 930 записала Синичкину своё
-- слово 'osm_organic_930'. Такая строка не совпадала ни с одной веткой switch,
-- а default не было — на полевом экране человек читал «Координата точки:
-- undefined — не полагайтесь только на азимут». Ниже той же миграцией это
-- значение приводится к 'external'.
--
-- Конверт края пройден (KRAI_*), и это тоже не доказательство правды, а
-- грубый фильтр от нулей и перепутанных широты с долготой — урок Тюшевских
-- источников (156.2 на широте 54.6 лежит внутри конверта и при этом в море).
-- Здесь проверка другая, содержательная: 51.5/156.48 — западное побережье
-- у Озерновского, в паре километров от посёлка, и «Ниитака» погибла именно
-- там в 1922 году. Снимок владельца это подтверждает: прибой и открытое море
-- за памятником.
--
-- ── Имя ───────────────────────────────────────────────────────────────────
--
-- «Кенотаф крейсера «Ниитака»» — по §13: назван объект, без эпитетов и
-- восклицаний, четыре слова.
--
-- ── Чего в описании НЕТ ───────────────────────────────────────────────────
--
-- Ни числа погибших, ни даты с точностью до дня, ни текста японской надписи
-- на обелиске. Всё это легко найти правдоподобным, но проверить отсюда
-- нечем, а выдуманная цифра на памятнике — худший вид выдумки (§4.0).
-- Сказано только то, что стоит за источником и за снимком.
--
-- Идемпотентно: место — по WHERE NOT EXISTS на имя, снимок — ON CONFLICT по
-- route_id, и уже лежащий настоящий снимок не перезаписывается.

