-- 753_fix_route_coords_curated.sql
--
-- wp_outlier (run 11): у мест координаты уже верифицированы (751-752), но
-- одноимённые МАРШРУТЫ стоят в десятках-сотнях км — биты kamchatka_routes.
-- lat/lng, треков у них нет (Шаг 9b пуст). Автоправило «маршрут наследует
-- координату места» отвергнуто: оно ломало бы легитимные морские старты
-- (Остров Старичков 59 км, Бухта Русская 95 — пин в порту, это правда).
-- Поэтому — курируемый список: только маршруты, чей объект верифицирован
-- миграциями 751-752, и только если текущая координата дальше 30 км от
-- целевой (осмысленные старты и ручные правки не перетираются).
--
-- Целевые координаты — из тех же источников, что 751-752.
-- НЕ трогаем: «Озеро Срединное» (место не верифицировано), морские
-- прогулки, городские обзорные маршруты. Идемпотентна.

-- Вулкан Бакенинг: маршрут в 93 км от вулкана (53.8931, 158.1611 — ООПТ)
UPDATE kamchatka_routes SET lat = 53.8931, lng = 158.1611, updated_at = NOW()
 WHERE title = 'Вулкан Бакенинг' AND is_visible = TRUE
   AND (abs(lat - 53.8931) > 0.27 OR abs(lng - 158.1611) > 0.45);

-- Экструзия Верблюд: маршрут в 161 км (53.2724, 158.7643 — tonkosti/volcanoesland)
UPDATE kamchatka_routes SET lat = 53.2724, lng = 158.7643, updated_at = NOW()
 WHERE title = 'Экструзия Верблюд' AND is_visible = TRUE
   AND (abs(lat - 53.2724) > 0.27 OR abs(lng - 158.7643) > 0.45);

-- Авачинский перевал: маршрут в 36 км от Корякского, а перевал — это точка
-- экструзии Верблюд (перевал между Авачинским и Корякским)
UPDATE kamchatka_routes SET lat = 53.2724, lng = 158.7643, updated_at = NOW()
 WHERE title = 'Авачинский перевал' AND is_visible = TRUE
   AND (abs(lat - 53.2724) > 0.27 OR abs(lng - 158.7643) > 0.45);

-- Курильское озеро (вертолётные карточки): пин продукта — само озеро
-- (51.4550, 157.0983 — Wikipedia); вертодром — деталь логистики, не пин
UPDATE kamchatka_routes SET lat = 51.4550, lng = 157.0983, updated_at = NOW()
 WHERE title IN ('Курильское озеро (вертолет)', 'Озеро Курильское', 'Курильское озеро')
   AND is_visible = TRUE
   AND (abs(lat - 51.4550) > 0.27 OR abs(lng - 157.0983) > 0.45);
