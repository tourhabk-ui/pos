-- 1302: Токен сессии не обрезается длиной колонки.
-- Created: 2026-10-20
--
-- ── Почему ───────────────────────────────────────────────────────────
--
-- 20.10 регистрация туриста на проде отвечала 500 «Ошибка регистрации».
-- Причина — `user_sessions.token character varying(255)`: регистрация
-- выпускает JWT с массивом ролей (`roles`), и вместе с email и подписью он
-- длиннее 255 знаков. INSERT строки сессии падал с SQLSTATE 22001
-- (value too long), транзакция откатывалась, аккаунт не создавался.
-- Вход (/api/auth/signin) кладёт в токен меньше полей и в предел пока
-- укладывался — поэтому вход работал, а регистрация нет.
--
-- Длина JWT зависит от email и набора ролей, предела у неё нет. Колонка
-- становится text. varchar → text в PostgreSQL не переписывает таблицу,
-- уникальный ключ user_sessions_token_key и индекс остаются.
--
-- Сторож: tests/integration/register.pg.test.ts.

ALTER TABLE user_sessions ALTER COLUMN token TYPE text;
