-- 978_hide_river_tours_three_day_raft.sql
--
-- Снять с витрины тур «Сплав по реке Быстрая (три дня)» (id 34, оператор
-- River Tours Kamchatka). Решение владельца 18.09: «тур спрячь».
--
-- ── Что с ним не так ─────────────────────────────────────────────────────
--
-- Замер с прода через MCP (`get_tours` / `get_tour_details`, 18.09):
--
--   ID34 «Сплав по реке Быстрая (три дня)» — от 0 р/чел
--   Условия отмены и возврата у этого тура НЕ ЗАПИСАНЫ
--
-- Ноль в базе НЕ ЗАПИСАН и записан быть не мог: у `base_price` стоит CHECK
-- `base_price > 0`, а сама колонка NULLABLE. Проверено на схеме — попытка
-- вставить ноль отвергается ограничением `price_positive`. Значит у тура
-- цена просто НЕ УКАЗАНА, а ноль на витрине родил показ: `Number(null)` в
-- JavaScript это `0`.
--
-- То есть врала не запись, а её печать. Это тот же механизм, что стоил
-- разбора денежного пути (§7, 11.09), и чинится он отдельно от этой
-- миграции — форматом `lib/tours/price-label.ts`. Сама причина прятать тур
-- от этого не исчезает: цены у него нет, продавать его нечем.
--
-- Второй пробел — `cancellation_policy`. Миграция 935 внесла условия отмены
-- живым турам 05.09 дословно со слов владельца, но этот тур появился позже
-- и под неё не попал. То есть §4.1 «готовых к выкладке 8 из 8» на сегодня
-- уже не про весь каталог.
--
-- ── Почему is_published, а не is_active и не deleted_at ──────────────────
--
-- Три флага значат разное, и подменять их друг другом нельзя:
--
--   is_published = FALSE  — «есть, но не показываем»: тур цел, оператор
--                           может доописать его и вернуть на витрину;
--   is_active = FALSE     — «оператор больше его не водит»;
--   deleted_at            — «записи не должно быть».
--
-- Владелец сказал «спрячь» — это ровно первое. Остальные два сказали бы о
-- туре неправду.
--
-- Снятие с публикации действует везде, где это важно, а не только в
-- каталоге: фиды Авито и Яндекса (`is_active AND is_published`), бронь
-- (`/api/tours/[id]/book`), цена и занятость. То есть тур перестаёт быть и
-- покупаемым, а не только видимым.
--
-- ── Чего эта миграция НЕ делает ──────────────────────────────────────────
--
-- Не ставит цену и не пишет условия отмены. И то и другое — договорённость
-- с оператором, которой у нас нет; сочинить их значило бы повторить ту же
-- ошибку, из-за которой тур и прячется. Вернуть его на витрину — отдельное
-- решение, когда цена и условия придут от человека.
--
-- ── Безопасность правки ──────────────────────────────────────────────────
--
-- Сверяются ТРИ признака сразу: id, название и имя оператора. Любое
-- расхождение — отказ с NOTICE, а не правка соседней записи: id 34 в
-- bigint-последовательности легко станет чужим на другой базе.
-- Идемпотентно: тур, уже снятый с витрины, не трогается.

-- Два замечания о форме запроса ниже, оба — следствие сторожа доменов
-- идентификаторов (`tests/unit/migration-id-type-domain.test.ts`):
--
--   * id тура стоит ЦЕЛЫМ ЛИТЕРАЛОМ, а не переменной. `operator_tours.id` —
--     bigint, и сравнение с целым литералом выведено из-под правила самим
--     сторожем: путаница uuid↔text, ради которой он писался, к числу не
--     относится. Переменная же неотличима от нетипизированной стороны;
--   * имя оператора берётся ОТДЕЛЬНЫМ запросом по уже прочитанному
--     `operator_id`, а не джойном `p.id = ot.operator_id`. Обе колонки uuid,
--     но доказать это сторожу нечем, а приводить их к тексту значило бы
--     потерять индекс ради формальности. Проще не заводить сравнение вовсе.

DO $$
DECLARE
  want_name text := 'Сплав по реке Быстрая (три дня)';
  want_op   text := 'River Tours Kamchatka';
  got_name  text;
  got_op    text;
  op_id     uuid;
  pub       boolean;
  price     numeric;
  policy    text;
BEGIN
  SELECT ot.title, ot.operator_id, ot.is_published, ot.base_price, ot.cancellation_policy
    INTO got_name, op_id, pub, price, policy
    FROM operator_tours ot
   WHERE ot.id = 34 AND ot.deleted_at IS NULL;

  IF got_name IS NULL THEN
    RAISE NOTICE '[978] тура 34 нет (или удалён) — делать нечего';
    RETURN;
  END IF;

  SELECT name INTO got_op FROM partners WHERE id = op_id;

  IF got_name IS DISTINCT FROM want_name THEN
    RAISE NOTICE '[978] под id 34 лежит «%», а не «%» — не трогаем',
      got_name, want_name;
    RETURN;
  END IF;

  IF got_op IS DISTINCT FROM want_op THEN
    RAISE NOTICE '[978] тур «%» принадлежит «%», а не «%» — не трогаем',
      got_name, COALESCE(got_op, 'NULL'), want_op;
    RETURN;
  END IF;

  IF pub IS FALSE THEN
    RAISE NOTICE '[978] «%» уже снят с витрины', got_name;
    RETURN;
  END IF;

  UPDATE operator_tours
     SET is_published = FALSE, updated_at = NOW()
   WHERE id = 34;

  -- Состояние на момент снятия — в журнал прогона: по нему видно, ушла ли
  -- причина, когда тур однажды будут возвращать.
  RAISE NOTICE '[978] «%» снят с витрины (цена была %, условия отмены %)',
    got_name,
    COALESCE(price::text, 'NULL'),
    CASE WHEN policy IS NULL OR btrim(policy) = '' THEN 'не записаны' ELSE 'записаны' END;
END $$;

-- Своей записи в `_migrations` здесь нет: её ставит раннер
-- (`lib/database/migrate.ts`, `scripts/migrate-standalone.js`) по имени файла.
-- Соседние миграции дублируют её вручную — это безвредно, но проверить такую
-- строку нечем: она не может ни сработать иначе, ни отказать.
