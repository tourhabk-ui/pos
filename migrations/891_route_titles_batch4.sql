-- 891: переименование маршрутов, партия 4 (6 имён от соседей по координате) —
-- «все названия маршрутов привести к стандарту» (владелец 20.08).
--
-- У этих шести объекта не было ни в имени, ни в описании — канон взят от
-- БЛИЖАЙШИХ ЖИВЫХ МЕСТ по координате маршрута (перепись v7, проба 113,
-- nearest_places) с сюжетом из описания:
--   «Жизнь. Прогулка по лесу.»      — Снежная долина ~1.1 км, «прогулка по лесу»;
--   «Зимние приключения»            — оз. Начикинское ~4.3 км, зимний треккинг;
--   «Идеальный выходной»            — видовка на сопке Острая ~4.9 км,
--                                     однодневный треккинг (коорд. из описания);
--   «Камчатка. На дальних берегах.» — о. Старичков ~10.3 км, «отдалённые
--                                     участки побережья» — морская прогулка;
--   «Камчатка. Такие места»         — прорыв им. Меняйлова ~1.3 км (Толбачик);
--   «Настоящие приключения...»      — Узон ~6.4 км + Долина гейзеров ~11 км.
-- Судья прогнан по новым именам заранее; guard по старому имени — идемпотентно.
--
-- Оставшиеся два нарушителя («Зимняя сказка», «Чудеса Камчатки») не тронуты:
-- ни координаты, ни соседей, ни объекта в описании — имя вывести не из чего,
-- решение по ним за владельцем отдельно.

UPDATE kamchatka_routes r
SET title = p.new_title, updated_at = NOW()
FROM (VALUES
  ('89fcef38-a72d-4d6f-bec7-ca9dc52efd2e', 'Жизнь. Прогулка по лесу.', 'Прогулка по лесу (Снежная долина)'),
  ('9c5358b7-6355-4b7e-bee1-3bf0c318388c', 'Зимние приключения', 'Озеро Начикинское (зимний)'),
  ('24b6fb14-7658-4e3f-ba58-6a4ea2187002', 'Идеальный выходной', 'К видовке на сопке Острая'),
  ('59c55981-a6b2-4124-9707-e4d9afe4f1f9', 'Камчатка. На дальних берегах.', 'К острову Старичков'),
  ('fec63f0e-aad6-4866-a8a7-6271d26760b8', 'Камчатка. Такие места', 'Прорыв имени Меняйлова'),
  ('4c2d40c3-84e6-4312-92b2-d9e812e054e6', 'Настоящие приключения начинаются на Камчатке!', 'Кальдера Узон — Долина гейзеров')
) AS p(route_id, old_title, new_title)
WHERE r.id::text = p.route_id
  AND r.title = p.old_title
  AND r.is_visible = true
  AND r.merged_into_id IS NULL;
