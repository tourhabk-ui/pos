-- 13.10 (решение владельца «согласен, перенеси в S3»): байты снимков вынесены в
-- хранилище — ключ migrations/photos/<sha256>.jpg из маркера
-- .github/triggers/migration-photos-to-s3.json (sha256 тех же байтов). Миграция
-- пишет s3_key, image_data пуст; прод переведён по хэшу байтов миграцией 1228.
--
-- 983: «Корякская сопка» — снимок владельца.
--
-- ── Что за кадр ───────────────────────────────────────────────────────────
--
-- 19.09 владелец прислал свой снимок со словами «Корякский вулкан только что
-- сфотографировал»: правильный конус в вечернем свете, снежная шапка с
-- облачным шлейфом у западного склона, ниже — полоса леса и скошенное поле с
-- валками. Снят в тот же день и, судя по кадру, с того же поля, что и
-- Авачинский (миграция 981).
--
-- ── Почему именно эта запись ──────────────────────────────────────────────
--
-- Записей об этом вулкане в каталоге ЧЕТЫРЕ, и три из них скрыты. Проба 531
-- (GET /api/cron/place-audit?q=коряк) назвала состояние каждой:
--
--   dea99549  «Корякская сопка»        53.320473/158.711565  ЖИВАЯ           ← сюда
--   1d609315  «Вулкан Корякская сопка» скрыта, слита в dea99549
--   52441bc8  «Вулкан Корякский»       скрыта, слита в dea99549
--   49e47b6f  «Корякский Вулкан»       скрыта, слита в 1d609315 (цепочкой)
--
-- Владелец называет его «Корякский вулкан», а живая запись зовётся
-- «Корякская сопка» — это один и тот же объект, и снимок ложится к нему.
-- Именно поэтому записи и выбираются пробой, а не поиском по имени: три из
-- четырёх имён здесь ведут на карточку, которую платформа не открывает.
--
-- Замечено по дороге и НЕ исправляется здесь: у скрытой записи 52441bc8
-- описание про СЕВЕРНЫЙ Корякский — остров Говена, долина Куюла, бухта
-- Лаврова, — то есть про другой объект за тысячу километров. Запись скрыта,
-- вреда сейчас нет; разбор чужого текста в слитой записи — отдельная задача,
-- и трогать её попутно значило бы смешать две правки.
--
-- ── Обрезка ───────────────────────────────────────────────────────────────
--
-- Исходник 4000x3000 с меткой поворота EXIF 6, настоящий размер 3000x4000.
-- Окно 16:9 полной ширины (3000x1688) со смещением 35% сверху: выше в кадр
-- лезет пустое небо, ниже срезается вершина. Внутри окна остаются все три
-- плана: облака, вулкан от вершины до подножия, лес и поле.
--
-- ── Как ложится ───────────────────────────────────────────────────────────
--
-- Герой карточки: ON CONFLICT (route_id) DO UPDATE, но НЕ поверх чужого
-- ручного снимка — wikimedia и manual-upload не перезаписываются, кроме
-- повтора этой же миграции. Машинная картинка заменяется, s3_url/s3_key
-- гасятся: старый объект в хранилище этим байтам не соответствует.
--
-- Байты пишутся в базу, а не в хранилище: миграция накатывается при старте
-- сервера, и сетевой вызов оттуда стопорил бы весь накат. Увезёт уборщик
-- cron-images-to-s3 — правило §4.1.
--
-- Права: автор указан, лицензия не ставится — снимок собственный.
--
-- Третий исход назван вслух: нет ark_id или строку держит чужой ручной кадр —
-- RAISE WARNING в лог выката. Молчать нельзя (миграция 976 так вставила ноль
-- строк и выглядела успешной), падать тоже нельзя — снимок не стоит боевой
-- загрузки сервера.
--
-- IDEMPOTENT

BEGIN;

INSERT INTO ai_route_images (route_id, image_data, mime_type, prompt, model, width, height, author, s3_key)
SELECT p.ark_id,
       NULL::bytea,
       'image/jpeg',
       'снимок владельца: Корякский вулкан с поля (миграция 983)',
       'manual-upload',
       1280,
       720,
       'владелец платформы',
       'migrations/photos/f29a7db12f8529b6378c42971f67e9086fd60ff3101065cff0acfa3effa64b37.jpg'
  FROM places p
 WHERE p.id::text = 'dea99549-5ecb-41fe-af19-15f216eeac68'
   AND p.ark_id IS NOT NULL
 LIMIT 1
ON CONFLICT (route_id) DO UPDATE
   SET image_data = EXCLUDED.image_data,
       mime_type  = EXCLUDED.mime_type,
       prompt     = EXCLUDED.prompt,
       model      = EXCLUDED.model,
       width      = EXCLUDED.width,
       height     = EXCLUDED.height,
       author     = EXCLUDED.author,
       s3_url     = NULL,
       s3_key     = EXCLUDED.s3_key,
       created_at = NOW()
 WHERE ai_route_images.model NOT IN ('wikimedia', 'manual-upload')
    OR ai_route_images.prompt = 'снимок владельца: Корякский вулкан с поля (миграция 983)';

-- ── Отказ называется вслух ────────────────────────────────────────────────
DO $$
DECLARE
  v_ark    uuid;
  v_prompt text;
BEGIN
  SELECT ark_id INTO v_ark FROM places WHERE id::text = 'dea99549-5ecb-41fe-af19-15f216eeac68';

  IF v_ark IS NULL THEN
    RAISE WARNING '[983] у «Корякской сопки» нет ark_id — снимок НЕ лёг, карточка осталась с прежним фото';
    RETURN;
  END IF;

  SELECT prompt INTO v_prompt FROM ai_route_images WHERE route_id = v_ark;

  IF v_prompt IS DISTINCT FROM 'снимок владельца: Корякский вулкан с поля (миграция 983)' THEN
    RAISE WARNING '[983] герой Корякской сопки НЕ стал снимком владельца: строку держит другой ручной снимок (prompt=%)', COALESCE(v_prompt, 'строки нет');
  END IF;
END $$;

COMMIT;
