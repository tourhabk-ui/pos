--
-- Ярослав («Камчатка Семейный Рафтинг», через владельца 05.08):
--   1. «я так и не смог выйти на свой телефон, чтобы самому себе позвонить —
--      там левый указан». На карточке стоит +7 924 799-01-91. Этот номер я
--      вписал в миграцию 060 и с тех пор он кочевал по 806 и 810 как факт,
--      хотя фактом никогда не был.
--   2. «Камчатка Рафтинг» — тоже моё название из 060. Оператор называет себя
--      семейным рафтингом, и это не косметика: тур и есть спокойный семейный
--      сплав, а не спортивный рафтинг (так и написано в описании).
--
-- Цена ошибки в телефоне выше, чем в названии. Это safety-платформа: турист
-- звонит оператору, когда что-то пошло не так — не доехал трансфер, изменилась
-- погода, он опаздывает к выезду. Чужой номер в такой момент хуже, чем его
-- отсутствие: человек уверен, что дозвонился до тех, кто за него отвечает.
--
-- ПОЧЕМУ ЭТА МИГРАЦИЯ НЕ ТРОГАЕТ СОСТАВ ТУРА. Снасти («даю бесплатно, никакой
-- аренды») правятся в operator_tours.included/not_included — а всё, что писало
-- в эти три колонки массивами (796, 806, 819), на проде молча не применилось.
-- Раннер выполняет файл ОДНОЙ транзакцией: положи я состав сюда, падение на нём
-- откатило бы и телефон. Поэтому здесь только partners и users — туда правки
-- доезжают, это подтвердили 810 и 815. Состав — отдельной миграцией, после
-- того как диагностика назовёт тип колонок.
--
-- Матч по slug, без INSERT (INSERT в partners уронил 806 и стоил трёх суток).
-- Идемпотентна: срабатывает, только пока есть что менять.

-- ── 1. Имя и телефон партнёра ────────────────────────────────────────────────
-- company_name синхронизируется триггером из 052, отдельно его не трогаем.
UPDATE partners
   SET name     = 'Камчатка Семейный Рафтинг',
       contacts = COALESCE(contacts, '{}'::jsonb) || jsonb_build_object(
                    'phone', '+79147817114'
                  )
 WHERE slug = 'kamchatka-rafting'
   AND (
     name IS DISTINCT FROM 'Камчатка Семейный Рафтинг'
     OR contacts->>'phone' IS DISTINCT FROM '+79147817114'
   );

-- ── 2. Имя в чате ────────────────────────────────────────────────────────────
-- Чат берёт имя собеседника не из partners, а из users (other_p.name в
-- lib/services/operators/chat.service.ts). 815 уже чинила это место — тогда
-- имя было демо-заглушкой; теперь меняем на настоящее. Правим ровно тот
-- аккаунт, который стоит за партнёром.
UPDATE users u
   SET name       = 'Камчатка Семейный Рафтинг',
       updated_at = NOW()
  FROM partners p
 WHERE p.slug = 'kamchatka-rafting'
   AND u.id = p.user_id
   AND u.name IS DISTINCT FROM 'Камчатка Семейный Рафтинг';
