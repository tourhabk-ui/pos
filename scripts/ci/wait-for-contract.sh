#!/usr/bin/env bash
#
# Дождаться прод-роута НУЖНОЙ версии контракта — и различить три исхода.
#
# ── Зачем ────────────────────────────────────────────────────────────────────
#
# Диагностические роуты запускаются маркером: правка файла в .github/triggers
# пушится в main, и тот же push везёт сам роут. Timeweb выкладывает контейнер
# около двенадцати минут, поэтому спрашивающий приходит раньше отвечающего.
#
# Исходов три, а не два (§4.0):
#   найдено          — 200 и версия контракта не ниже ожидаемой;
#   не смогли спросить — 404, обрыв связи или 200 от ПРЕЖНЕЙ версии: отвечает
#                      не тот код, которого мы ждём. Это повод подождать в
#                      границах известного времени выкладки, а не приговор;
#   приговор         — любой иной код: это ответ приложения, ждать нечего.
#
# Проверка версии заведена по прогону 4 приёмки ledger: роут БЫЛ, но уехал
# прошлым коммитом — ответил 200 мгновенно, и воркфлоу напечатал устаревшие
# данные как свежие. Достижимость отвечающего и нужность его версии — разные
# вопросы, и второй надо задавать вслух. Обычный ответ (сверить коммит через
# /version.json) закрыт: там `commit: "unknown"`, причина `no_git_head`.
#
# ── Почему скрипт, а не блок в каждом воркфлоу ──────────────────────────────
#
# Второй пользователь появился у этой логики через сутки после первого. Две
# копии цикла разошлись бы, и одна из них тихо перестала бы ждать версию —
# в этом репозитории расхождение копий уже было корнем худших дефектов
# (карточка тура, SOS-кнопка). Цикл один, и сторож у него один.
#
# ── Переменные ──────────────────────────────────────────────────────────────
#
#   WAIT_URL       адрес роута (обязательно)
#   CRON_SECRET    секрет (обязательно)
#   WAIT_CONTRACT  минимальная версия контракта, по умолчанию 1
#   WAIT_ATTEMPTS  попыток, по умолчанию 30
#   WAIT_DELAY     пауза между попытками, с, по умолчанию 30
#   WAIT_OUT       куда положить тело ответа, по умолчанию /tmp/response.json
#
# Умолчания боевые; ATTEMPTS/DELAY переопределяет только сторож, который
# исполняет этот же скрипт и не может ждать пятнадцать минут.

set -e

if [ -z "$CRON_SECRET" ]; then
  echo "::error::CRON_SECRET secret не задан."
  exit 1
fi
if [ -z "$WAIT_URL" ]; then
  echo "::error::WAIT_URL не задан — нечего спрашивать."
  exit 1
fi

ATTEMPTS="${WAIT_ATTEMPTS:-30}"
DELAY="${WAIT_DELAY:-30}"
EXPECT_CONTRACT="${WAIT_CONTRACT:-1}"
OUT="${WAIT_OUT:-/tmp/response.json}"

i=0
LAST="не спрашивали"
while :; do
  i=$((i + 1))

  # --max-time обязателен: без него отказ висит до таймаута джоба, и «не смогли
  # спросить» приходит через минуты вместо секунды. Ровно это и случилось в
  # первом прогоне приёмки ledger с psql (2.5 минуты молчания).
  CURL_RC=0
  HTTP=$(curl -sS -o "$OUT" -w "%{http_code}" \
    --max-time 45 \
    "$WAIT_URL" \
    -H "Authorization: Bearer $CRON_SECRET") || CURL_RC=$?

  if [ "$CURL_RC" = "0" ] && [ "$HTTP" = "200" ]; then
    # sed, а не python3 -c: многострочный питон внутри блочного скаляра YAML
    # обрывает сам скаляр (его первая строка встаёт левее отступа блока). Эта
    # яма в репозитории уже случалась — см. шапку timeweb-deploy-logs.yml,
    # прогоны 3/4 с IndentationError. Здесь скаляра нет, но правило остаётся:
    # разбор одной строкой не требует интерпретатора вовсе.
    # Отсутствие поля читается как 0 — то есть как прежняя версия.
    GOT=$(sed -n 's/.*"contract_version"[[:space:]]*:[[:space:]]*\([0-9][0-9]*\).*/\1/p' "$OUT" | head -1)
    [ -z "$GOT" ] && GOT=0
    if [ "$GOT" -ge "$EXPECT_CONTRACT" ]; then
      break
    fi
    LAST="контракт $GOT < $EXPECT_CONTRACT (прод отвечает прежней версией)"
  elif [ "$CURL_RC" != "0" ]; then
    # Во время выкладки контейнер перезапускается, и обрыв связи здесь ожидаем
    # ровно так же, как 404. Отличать «прод лежит» от «прод переезжает» одним
    # запросом нельзя — различает их только время.
    LAST="curl $CURL_RC"
  elif [ "$HTTP" = "404" ]; then
    LAST="HTTP 404 (роута ещё нет)"
  else
    # Любой иной код — про сам роут, а не про выкладку: ждать нечего.
    echo "::error::Роут ответил $HTTP — тело ниже. Это ответ приложения, а не отсутствие выкладки, поэтому ждать нечего."
    cat "$OUT" 2>/dev/null || true
    exit 1
  fi

  if [ "$i" -ge "$ATTEMPTS" ]; then
    echo "::error::За $((ATTEMPTS * DELAY)) с нужного ответа не дождались, последний исход: $LAST. Это «не смогли спросить», а не ответ роута: он либо не отвечал вовсе, либо отвечал прежней версией контракта. Смотреть надо выкладку контейнера на Timeweb, а не то, что роут диагностирует."
    exit 1
  fi

  echo "$LAST — попытка $i из $ATTEMPTS, ждём ${DELAY}с (выкладка Timeweb идёт около 12 минут)"
  sleep "$DELAY"
done

echo "HTTP 200 с попытки $i"
