#!/usr/bin/env bash
#
# Прогнать ВСЕ тесты на настоящем PostgreSQL — и сначала доказать, что они
# выбраны.
#
# ── Зачем шаг, а не просто `vitest run` ─────────────────────────────────────
#
# 01.09 джоб kernel-pg запускал ОДИН файл по имени, как было при заведении, и
# три соседних `*.pg.test.ts` не исполнялись ни разу: в джобе `ci` переменной
# KERNEL_PG_TEST_URL нет и они пропускаются, а сюда не попадали. Пропуск
# выглядел успехом (§4.0).
#
# Первая починка поставила glob — и он не выбрал НИ ОДНОГО файла: позиционный
# аргумент vitest это подстрока пути, а не шаблон. Джоб упал за 51 секунду.
# То есть «CI не запускает файл» превратилось в «CI запускает пустоту»:
# болезнь поднялась на слой выше, механизм остался прежним.
#
# Поэтому селектор объявлен здесь ОДИН раз, и перед прогоном скрипт спрашивает
# сам vitest, что он по нему выберет, сверяя с каталогом. Пустая выборка и
# недостающий файл — приговор до того, как прогон отчитается успехом.
#
# ── Почему это не юнит-тест ────────────────────────────────────────────────
#
# Сторож, живший в `tests/unit/`, запускал второй vitest ИЗНУТРИ прогона. На
# локальной машине это стоило 1.3 с, а на двухъядерном раннере шаг «Run tests»
# встал: 25+ минут против семи. Проверка, ради которой прогон не заканчивается,
# не проверка. Здесь тот же вопрос задаётся тем же механизмом, но снаружи и
# один раз.

set -euo pipefail

# Единственное место, где живёт селектор. Подстрока, а не glob.
SELECTOR="pg.test.ts"
DIR="tests/integration"

echo "Селектор: $SELECTOR"

SELECTED=$(npx vitest list --filesOnly "$SELECTOR" | grep -E '\.test\.tsx?$' || true)

if [ -z "$SELECTED" ]; then
  echo "::error::По селектору '$SELECTOR' vitest не выбрал ни одного файла. Команда выглядит рабочей, но прогон не проверит ничего."
  exit 1
fi

echo "Выбрано:"
echo "$SELECTED" | sed 's/^/  /'

MISSED=""
for f in "$DIR"/*.pg.test.ts; do
  [ -e "$f" ] || continue
  base=$(basename "$f")
  echo "$SELECTED" | grep -q "$base" || MISSED="$MISSED $base"
done

if [ -n "$MISSED" ]; then
  echo "::error::Эти pg-тесты не попадают в выборку и пропускаются везде:$MISSED"
  exit 1
fi

echo "Все pg-тесты каталога $DIR попали в выборку — запускаю."

# --no-file-parallelism обязателен: база ОДНА на все файлы, и они делят в ней
# таблицы. `safety-ledger.pg.test.ts` заводит `safety_decision_events`
# миграцией и пишет в неё, а `ledger-check-recent-order.pg.test.ts` сеет туда
# 10005 строк и ДРОПАЕТ таблицу в afterAll. Параллельно это гонка: дроп
# приходит, пока сосед пишет, и appendSafetyEvent возвращает {ok:false}.
#
# Гонка была всегда, но не проявлялась: до 01.09 CI запускал только
# agent-kernel, а эти файлы вместе не работали НИ РАЗУ. Первый же общий прогон
# в CI прошёл зелёным по удаче — замер локально: параллельно 2 успеха из 3,
# последовательно 9 из 9.
#
# Последовательность выбрана вместо схем-песочниц намеренно: файлов четыре,
# весь прогон 3 секунды, а изоляция по схемам потребовала бы править каждый
# тест и переносить в них имя таблицы — цена выше пользы, пока база одна.
npx vitest run "$SELECTOR" --no-file-parallelism
