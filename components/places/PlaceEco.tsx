/*
 * Шаблонного «Экологического календаря» и шаблонных «Правил посещения» здесь
 * больше нет (15.10, карт-бланш владельца на разбор: «ты уже лучше меня всё
 * знаешь»).
 *
 * Оба были одним списком на режим охраны — без источника и одинаковые для
 * всех мест режима, — и правила места на карточке заменяли, когда своих у
 * места не было. Разбор показал, что это не обобщение, а выдумка о
 * конкретных местах:
 *   - Корякскому заповеднику календарь писал «зимой доступ ограничен, часть
 *     маршрутов закрыта», а туристических маршрутов там нет вовсе;
 *   - Курильскому озеру (заказник) — «в нерест вход только с инспектором»,
 *     а у Кроноцкого заповедника, который им ведает, правило другое:
 *     посещение по заявке и разрешению (kronoki.ru, миграция 1252);
 *   - Налычеву (природный парк) — «зимнее закрытие части маршрутов» и
 *     «лучший сезон июль–сентябрь» без единого источника;
 *   - объекту ЮНЕСКО — «пик сезона, бронируйте заранее»: это реклама, а не
 *     правило охраны;
 *   - в правилах — «лицензированный гид» (лицензии гида в России нет) и
 *     «термальные выходы до 900 °C».
 * Обязательное поле, которому нечем быть, заполняется враньём (§4.0). Теперь
 * правила — только записанные у места (eco_rules, с источником в миграции),
 * а где их нет, карточка так и говорит. Календарь, если понадобится, — данными
 * места по документам (положение о территории, сезон работы кордонов), не
 * шаблоном.
 */

function parseRules(rules: string): string[] {
  return rules
    .split(/\.\s+|\n/)
    .map(s => s.trim().replace(/^[-•·]\s*/, ''))
    .filter(s => s.length > 8);
}

export default function PlaceEco({ eco, placeName, locationType }: Props) {
  if (!eco.zone || eco.zone === 'none') return null;

  const label    = ZONE_LABELS[eco.zone] ?? eco.zone;
  const desc     = ZONE_DESCRIPTIONS[eco.zone];
  const isStrict = eco.zone === 'UNESCO' || eco.zone === 'federal_reserve';

  // Только правила, записанные у места. Шаблона по режиму нет (см. выше).
  const ruleList: string[] = eco.rules ? parseRules(eco.rules) : [];

  return (
    <section>
      <div className="overflow-hidden rounded-lg bg-[var(--bg-card)]">

        {/* ── Header ─────────────────────────────────────────────────────────── */}
        <div className={`px-5 py-4 flex items-center gap-3 ${isStrict ? 'bg-[var(--success)]/8' : 'bg-[var(--ocean)]/6'}`}>
          <div className={`p-2 rounded-lg ${isStrict ? 'bg-[var(--success)]/18 text-[var(--success)]' : 'bg-[var(--ocean)]/14 text-[var(--ocean)]'}`}>
            <Leaf size={18} strokeWidth={2} />
          </div>
          <div>
            <p className="text-xs font-medium text-[var(--text-muted)]">Экология и охрана природы</p>
            <p className="font-semibold text-[var(--text-primary)] leading-tight">{label}</p>
          </div>
          {eco.permitRequired && (
            <span className="ml-auto text-xs font-semibold px-2.5 py-1 rounded-full bg-[var(--warning)]/15 text-[var(--warning)] shrink-0">
              Нужен пропуск
            </span>
          )}
        </div>

        <div className="px-5 py-4 space-y-5">

          {/* ── Zone description ───────────────────────────────────────────────── */}
          {desc && (
            <p className="text-sm text-[var(--text-secondary)] leading-relaxed">{desc}</p>
          )}

          {/* ── Visitor rules ──────────────────────────────────────────────────── */}
          {ruleList.length === 0 && (
            <p className="text-sm text-[var(--text-muted)] leading-relaxed">
              Правила посещения этого места на платформе пока не записаны — уточните их у дирекции
              охраняемой территории.
            </p>
          )}
          {ruleList.length > 0 && (
            <div>
              <p className="text-xs font-semibold text-[var(--text-muted)] mb-2.5">Правила посещения</p>
              <ul className="space-y-1.5">
                {ruleList.map((rule, i) => (
                  <li key={i} className="flex items-start gap-2 text-sm text-[var(--text-secondary)]">
                    <ShieldCheck size={14} className="shrink-0 mt-0.5 text-[var(--success)]" />
                    <span>{rule}</span>
                  </li>
                ))}
              </ul>
            </div>
          )}

          {/* ── Permit link ────────────────────────────────────────────────────── */}
          {eco.permitRequired && eco.permitUrl && (
            <a
              href={eco.permitUrl}
              target="_blank"
              rel="noopener noreferrer"
              className="inline-flex items-center gap-2 text-sm font-medium text-[var(--ocean)] hover:underline"
            >
              <ExternalLink size={14} />
              {/* Не «онлайн»: у Кроноцкого заповедника это форма заявки на почту
                  (kronoki.ru), и обещание онлайн-пропуска было неправдой. */}
              Как получить разрешение
            </a>
          )}

          {eco.permitRequired && !eco.permitUrl && (
            <div className="flex items-start gap-2 p-3 rounded-lg bg-[var(--warning)]/8 text-sm text-[var(--text-secondary)]">
              <Info size={14} className="shrink-0 mt-0.5 text-[var(--warning)]" />
              <span>Требуется разрешение на посещение. Уточните у гида или местной администрации.</span>
            </div>
          )}

        </div>
      </div>
    </section>
  );
}
