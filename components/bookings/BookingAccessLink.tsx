'use client';

/**
 * Ключ к брони на экране — сразу после того, как заявка создана.
 *
 * ── Зачем (issue #1889) ───────────────────────────────────────────────────
 *
 * `operator_bookings.access_token` (миграция 943) выдаётся ОДИН раз и живёт
 * только в ссылке `?t=`. Без него `/booking-success/[id]` отвечает 404 — по
 * одному номеру бронь не открывается, и это сделано намеренно (перебор
 * BIGSERIAL отдавал бы чужие имя, дату и статус оплаты).
 *
 * Значит у ключа обязан быть носитель. Письмо им было ровно одно, и только
 * когда почта есть. Замер 14.09 по всем клиентам `POST /api/hub/bookings/create`:
 *
 *   форма тура          — почта обязательна, redirect с ключом      — ключ доходит
 *   корзина             — почта НЕобязательна, redirect с ключом    — ключ доходит
 *   Кузьмич в чате      — почты нет, ссылка с ключом уходит в чат    — ключ доходит
 *   Кузьмич на сайте    — читал из ответа только `id`               — ключ ВЫБРАСЫВАЛСЯ
 *   `/p/[code]`         — почту не шлёт вовсе, читал только `error` — ключ ВЫБРАСЫВАЛСЯ
 *
 * У двух последних турист видел «Заявка отправлена» и терял доступ к
 * собственной заявке НАВСЕГДА — не в редком случае, а всегда. У `/p/[code]`
 * почты нет в форме, то есть письмо там не спасало никогда. А Кузьмич на
 * сайте вдобавок писал «проверьте детали на странице бронирования» — про
 * страницу, ключ от которой сам же и выкинул.
 *
 * За тем же ключом лежит PDF с телефоном и почтой самого человека: теряется
 * не «посмотреть статус», а доступ к своим персональным данным.
 *
 * ── Почему ссылка, а не «мы отправим потом» ───────────────────────────────
 *
 * Отправить потом нечем: у `/p/[code]` контакта, кроме телефона, нет, а
 * отправка по телефону — это верификация владения номером, отдельная работа
 * (пункт 3 issue, решение владельца). Пока её нет, честный ход один: отдать
 * ключ там, где он уже есть — на экране, — и сказать вслух, что второй раз
 * его не покажут. Молча показать «Заявка отправлена» дешевле для нас и
 * дороже для туриста.
 */

import { useState } from 'react';
import { Link2, Copy, Check } from 'lucide-react';

interface Props {
  bookingId: number | string;
  accessToken: string;
  /** Письмо с этой же ссылкой ушло — тогда «сохрани сейчас» звучит мягче. */
  emailSent?: boolean;
}

export default function BookingAccessLink({ bookingId, accessToken, emailSent }: Props) {
  const [copied, setCopied] = useState(false);

  // Ключа нет — показывать нечего, и придумывать ссылку нельзя: она откроет
  // 404 и научит туриста, что ссылки платформы не работают (§4.0).
  if (!accessToken) return null;

  const path = `/booking-success/${bookingId}?t=${encodeURIComponent(accessToken)}`;
  const absolute = typeof window === 'undefined' ? path : `${window.location.origin}${path}`;

  const copy = () => {
    void (async () => {
      try {
        await navigator.clipboard.writeText(absolute);
        setCopied(true);
        setTimeout(() => setCopied(false), 2000);
      } catch {
        // Буфер недоступен (нет разрешения, http, старый браузер) — ссылка
        // всё равно на экране и выделяется руками. Молчаливое «скопировано»
        // при несработавшем копировании было бы хуже отсутствия кнопки.
        setCopied(false);
      }
    })();
  };

  return (
    <div className="ds-card p-4 text-left">
      <div className="flex items-center gap-2 mb-2">
        <Link2 className="w-4 h-4 text-[var(--ocean)] flex-none" />
        <span className="text-sm font-semibold text-[var(--text-primary)]">
          Ссылка на вашу заявку
        </span>
      </div>

      <p className="text-xs text-[var(--text-secondary)] mb-3">
        {emailSent
          ? 'Эта же ссылка ушла вам на почту. Сохраните её и здесь — по одному номеру заявка не открывается, и восстановить доступ нам нечем, если письмо не дойдёт.'
          : 'Сохраните её сейчас. По одному номеру заявка не открывается, и другого способа вернуться к ней нет: по этой ссылке вы увидите статус, условия и документы по заявке.'}
      </p>

      <a
        href={path}
        className="block break-all text-xs text-[var(--ocean)] underline mb-3"
      >
        {absolute}
      </a>

      <button type="button" onClick={copy} className="ds-btn ds-btn-secondary text-sm">
        {copied ? <Check className="w-4 h-4" /> : <Copy className="w-4 h-4" />}
        {copied ? 'Скопировано' : 'Скопировать ссылку'}
      </button>
    </div>
  );
}
