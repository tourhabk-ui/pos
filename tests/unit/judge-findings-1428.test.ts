/**
 * Две находки судьи эволюции (#1428, состав отчёта от 13.09) — и то, чем они
 * оказались при проверке в живом коде.
 *
 * Обе стоило проверять глазами: вердикт судьи не совпал ни с одной. Он видит
 * фрагмент, а не систему, и называет форму, а не механизм.
 *
 * ── 1. Архивация зависших SOS ──────────────────────────────────────────────
 *
 * Судья: «SELECT и UPDATE выполняются без транзакции». Форма верна, вывод —
 * нет: транзакция здесь лечит слабее предиката. Настоящая цена была в том,
 * что UPDATE шёл по списку id, БЕЗ повторной проверки статуса. Между выборкой
 * «не отвечали сутки» и записью спасатель успевает принять сигнал — и приём
 * затирался: событие получало `archived` и наши заметки поверх настоящих.
 * Принятый SOS помечался как непринятый, на слое безопасности.
 *
 * Один UPDATE с предикатом и RETURNING убирает окно ПО ПОСТРОЕНИЮ и попутно
 * чинит счёт: в отчёт владельцу уходит число записанных строк, а не число
 * задуманных (§4.0 — измеренное вместо предполагаемого).
 *
 * ── 2. Избранное ───────────────────────────────────────────────────────────
 *
 * Судья: «в catch возвращается ok: true — вызывающий покажет успех без
 * подтверждения сервера». Следствие названо верно, механизм — нет. `ok: true`
 * в офлайн-ветке осознан (offline-first, CLAUDE.md), и рядом честно стоит
 * `localOnly`.
 *
 * Дефект был в потребителе, которого нет: перепись дала у `localOnly` одно
 * присваивание и ноль чтений, а `error` не читала ни одна из шести карточек —
 * при том что шапка интерфейса обещала «показывается рядом с кнопкой». Все
 * три исхода выглядели одинаково; при отказе сервера сердце не заполнялось и
 * молчало. Это жалоба владельца 09.08 («избранное так и не работает») слоем
 * выше: хук починил её внутри себя, а наружу никто не подключил.
 *
 * Правило 10.09: объявленный исход без потребителя зеленеет ровно там, где
 * механизма нет. Поэтому сторож держит СВЯЗКУ — не то, что поле объявлено, а
 * то, что исход доходит до человека.
 */
import { describe, it, expect } from 'vitest';
import { readFileSync } from 'node:fs';
import { join } from 'node:path';

function src(rel: string): string {
  return readFileSync(join(process.cwd(), rel), 'utf-8');
}

/** Код без комментариев: прежнее поведение в них описано намеренно. */
function code(rel: string): string {
  return src(rel).replace(/\/\*[\s\S]*?\*\//g, '').replace(/^\s*\/\/.*$/gm, '');
}

const EXECUTOR = 'lib/agents/execution/initiative-executor.ts';
const HOOK = 'hooks/use-wishlist.ts';
const CLIENT = 'lib/wishlist/client.ts';

describe('архивация SOS не затирает принятый сигнал', () => {
  const body = (() => {
    const all = code(EXECUTOR);
    const start = all.indexOf('async function executeArchiveSOS');
    expect(start, 'исполнитель архивации SOS не найден').toBeGreaterThan(-1);
    const end = all.indexOf('async function executeSendNotification', start);
    expect(end).toBeGreaterThan(start);
    return all.slice(start, end);
  })();

  it('запись обусловлена статусом, а не списком id', () => {
    // Суть находки. Без этого предиката UPDATE архивирует то, что за время
    // между выборкой и записью уже приняли.
    expect(body).toMatch(/UPDATE sos_events[\s\S]*?WHERE status = 'sent'/);
    expect(body).not.toMatch(/WHERE id = ANY\(\$2::uuid\[\]\)/);
  });

  it('порог «сутки» остался в том же операторе, что и запись', () => {
    // Иначе предикат статуса вернулся бы, а возрастной — уехал в отдельный
    // запрос, и окно открылось бы заново с другой стороны.
    expect(body).toMatch(/WHERE status = 'sent'[\s\S]{0,120}created_at < NOW\(\) - INTERVAL '24 hours'/);
  });

  it('в отчёт идёт записанное, а не задуманное', () => {
    // RETURNING — источник числа. `ids.length` от отдельного SELECT называл
    // бы количество строк, которые СОБИРАЛИСЬ тронуть.
    expect(body).toMatch(/RETURNING id, created_at::text/);
    expect(body).toMatch(/archived\.rows/);
  });

  it('имя туриста из запроса не тянется — это ПД', () => {
    // Прежний SELECT брал tourist_name и не использовал его ни разу.
    expect(body).not.toMatch(/tourist_name/);
  });
});

describe('избранное: у отказа и у «только локально» есть потребитель', () => {
  it('клиент по-прежнему РАЗЛИЧАЕТ офлайн и успех', () => {
    // Предпосылка всего остального. Если `localOnly` перестанут выставлять,
    // хуку будет нечего доводить до человека.
    expect(code(CLIENT)).toMatch(/return \{ ok: true, localOnly: true \}/);
  });

  it('хук доводит отказ до человека сам, не надеясь на карточку', () => {
    const c = code(HOOK);
    expect(c).toMatch(/from 'react-hot-toast'/);
    expect(c).toMatch(/toast\.error\(message\)/);
  });

  it('«сохранено только здесь» тоже слышно, и это не ошибка', () => {
    // Отдельный вызов, а не toast.error: связи нет — это состояние, а не сбой,
    // и красный текст врал бы о том, что действие не удалось.
    const c = code(HOOK);
    expect(c).toMatch(/if \(res\.localOnly\)/);
    expect(c).toMatch(/toast\(`\$\{next \? 'Добавлено' : 'Убрано'\}/);
  });

  it('оба исхода отданы и наружу — для надписи рядом с кнопкой', () => {
    const c = code(HOOK);
    expect(c).toMatch(/return \{ on, busy, error, localOnly, toggle \}/);
  });

  it('обещание шапки не шире того, что код делает', () => {
    // Прежняя строка обещала показ «рядом с кнопкой» — этого не делала ни
    // одна из шести поверхностей. Докстрока, обещающая несуществующий путь,
    // — дефект кода (правило 10.09), поэтому она переписана на правду.
    const doc = src(HOOK);
    expect(doc).not.toMatch(/Причина отказа словами — её показывают рядом с кнопкой/);
    expect(doc).toMatch(/доставку человеку берёт на себя сам хук|Исход доходит до человека ЗДЕСЬ/);
  });
});
