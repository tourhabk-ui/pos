/**
 * Запрос выплаты комиссий агента нельзя выполнить дважды на одни деньги.
 *
 * Находка эволюции #1238, подтверждена чтением кода 17.08. Обработчик шёл
 * тремя отдельными запросами: читаем `pending`-комиссии, создаём выплату,
 * переводим комиссии в `processing`. Между первым и третьим — окно, в которое
 * помещается второй такой же запрос: он видит те же строки, ещё не ставшие
 * `processing`, и создаёт вторую выплату на те же комиссии.
 *
 * Это не теоретическая гонка. Кнопку «запросить выплату» нажимают дважды
 * буднично — подвисла сеть, показалось, что не сработало. Цена ошибки —
 * двойная выплата живых денег.
 *
 * Замок нужен именно `FOR UPDATE`, без `SKIP LOCKED`: второй запрос обязан
 * ДОЖДАТЬСЯ и получить честный отказ «нечего выплачивать», а не пропустить
 * занятые строки и создать пустую выплату. (В кроне `payouts` SKIP LOCKED
 * уместен — там разгребают очередь параллельно, а не отвечают человеку на
 * одно нажатие. Разные задачи — разные замки.)
 */
import { describe, it, expect } from 'vitest';
import { readFileSync } from 'node:fs';
import { join } from 'node:path';

const SRC = readFileSync(
  join(process.cwd(), 'app/api/agent/commissions/request-payout/route.ts'),
  'utf-8',
);
/** Код без комментариев: прежний дефект в них описан намеренно. */
const CODE = SRC.replace(/\/\*[\s\S]*?\*\//g, '').replace(/^\s*\/\/.*$/gm, '');

describe('чтение, создание и перевод статуса — одна транзакция', () => {
  it('обработчик работает через transaction(), а не отдельными query()', () => {
    expect(CODE).toMatch(/await transaction\(async \(client\) =>/);
    // Свободный query() рядом с транзакцией вернул бы то самое окно.
    expect(CODE).not.toMatch(/\bawait query\(/);
  });

  it('все три запроса идут через клиент транзакции', () => {
    const calls = CODE.match(/client\.query</g) ?? [];
    const plain = CODE.match(/client\.query\(/g) ?? [];
    expect(calls.length + plain.length).toBeGreaterThanOrEqual(3);
  });
});

describe('строки берутся под замок', () => {
  it('pending-комиссии читаются FOR UPDATE', () => {
    expect(CODE).toMatch(/status = 'pending'[\s\S]{0,80}FOR UPDATE/);
  });

  it('без SKIP LOCKED — второй запрос ждёт и получает отказ', () => {
    // SKIP LOCKED дал бы второму запросу пропустить занятые строки и создать
    // пустую выплату вместо честного «нечего выплачивать».
    expect(CODE).not.toMatch(/FOR UPDATE SKIP LOCKED/);
  });
});

describe('отказ остаётся отказом', () => {
  it('пустой список комиссий — 400 с понятным текстом', () => {
    expect(CODE).toMatch(/Нет ожидающих комиссионных для выплаты/);
    expect(CODE).toMatch(/status: 400/);
  });
});
