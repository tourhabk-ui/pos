/**
 * Одна точка — это место, а не маршрут.
 *
 * Полевая проверка 16.08 нашла в выдаче поиска «Восхождение на Авачинский
 * вулкан»: в списке подписано «14 км · Средний», а в превью — «1 точек ·
 * Вулкан Авачинский → Вулкан Авачинский». То есть экран предлагал идти из
 * точки в неё же и давал кнопку старта. Для планировщика это ровно тот
 * «ложно готов», который запрещён в плане FCN: расстояние из описания
 * подтверждает маршрут, которого в данных нет.
 *
 * Два места, где это чинится, и оба нужны:
 *   1. Каталог рекомендаций (`has_waypoints=true`) — такие записи не должны
 *      попадать в выдачу вовсе. Прежнее условие было EXISTS «есть хоть одна
 *      точка», а «есть точка» и «есть путь» — разные факты.
 *   2. Превью выбранного варианта — поиск по названию остаётся путём
 *      восстановления и может привести к той же записи. Там её не прячут,
 *      а честно объясняют, почему вести по ней нельзя, и не дают старт.
 *
 * Отдельно здесь же держится провал загрузки карточки: раньше все ветки
 * отказа делали молчаливый return, и нажатие «На карте» просто ничего не
 * делало — человек не мог отличить сломанную связь от сломанного маршрута.
 */
import { describe, it, expect } from 'vitest';
import { readFileSync } from 'node:fs';
import { join } from 'node:path';

const read = (p: string) => readFileSync(join(process.cwd(), p), 'utf-8');

const CATALOG = read('lib/routes/catalog-query.ts');
const PLANNING = read('app/planning/_PlanningClient.tsx');

describe('каталог не рекомендует запись с одной точкой', () => {
  it('условие has_waypoints требует не меньше двух точек', () => {
    expect(CATALOG).toMatch(/COUNT\(\*\) >= 2/);
  });

  it('голого EXISTS «есть хоть одна точка» больше нет', () => {
    // Прежнее условие пропускало одноточечные записи в поле.
    expect(CATALOG).not.toMatch(/EXISTS \(SELECT 1 FROM kamchatka_routes kw\s+JOIN route_waypoints/);
  });

  it('считаются только точки с координатами', () => {
    // Точка без lat/lng на карте не существует: пара, где одна половина
    // безкоординатная, — это та же одна точка.
    const block = CATALOG.slice(CATALOG.indexOf('COUNT(*) >= 2'));
    expect(block.slice(0, 600)).toMatch(/p\.lat IS NOT NULL AND p\.lng IS NOT NULL/);
  });

  it('компактность bbox сохранена — мега-сборники по-прежнему отсеиваются', () => {
    expect(CATALOG).toMatch(/MAX\(p\.lat\) - MIN\(p\.lat\)\) <= 0\.5/);
    expect(CATALOG).toMatch(/MAX\(p\.lng\) - MIN\(p\.lng\)\) <= 0\.8/);
  });
});

describe('превью не предлагает старт по одной точке', () => {
  it('одноточечное превью распознаётся отдельным признаком', () => {
    expect(PLANNING).toMatch(/const singlePoint = preview\.wps\.length < 2/);
  });

  it('кнопка старта скрыта, когда записью нельзя пользоваться как маршрутом', () => {
    // 17.08 правило переехало в lib/routes/navigability: экран больше не судит
    // сам. Прежние проверки (разброс, одна точка) остались ФОЛБЭКОМ на случай
    // старого кэша ответа, а решение приходит вердиктом с сервера — только там
    // видно и линию, и точки, то есть и расхождение между ними.
    expect(PLANNING).toMatch(/navigabilityCtaLabel\(/);
    expect(PLANNING).toMatch(/'not_a_route' : 'orientation_only'/);
    expect(PLANNING).toMatch(/if \(!label\) return null;/);
  });

  it('причина отказа сказана словами, а не только отсутствием кнопки', () => {
    // Пропавшая кнопка без объяснения читается как поломка приложения.
    expect(PLANNING).toMatch(/navigability\.reasons\.map/);
    expect(PLANNING).toMatch(/Вести по этой записи нельзя/);
  });

  it('линия по одной вершине не рисуется', () => {
    // Полилиния из одной точки — это ничто, но маркер «маршрут» рядом с ней
    // обещает путь. Ни линии, ни обещания.
    expect(PLANNING).toMatch(/scattered \|\| singlePoint \? \[\] : \[\{/);
  });

  it('счёт точек склоняется по-русски', () => {
    // «1 точек» — тот же класс небрежности, что и «1 событий» на /safety.
    expect(PLANNING).toMatch(/plural\(preview\.wps\.length, 'точка', 'точки', 'точек'\)/);
  });
});

describe('провал загрузки маршрута — состояние, а не пустота', () => {
  it('у каждой ветки отказа есть текст для человека', () => {
    const fn = PLANNING.slice(
      PLANNING.indexOf('function openPreview'),
      PLANNING.indexOf('function openRouteModal'),
    );
    // Ветки: сервер вернул не-success, точек нет вовсе, у точек нет координат,
    // запрос упал. Каждая обязана объяснить себя.
    const errors = fn.match(/setPreviewError\(/g) ?? [];
    expect(errors.length).toBeGreaterThanOrEqual(4);
    expect(fn).not.toMatch(/остаёмся на списке/);
  });

  it('ошибка привязана к своей строке, а не подменяет список', () => {
    expect(PLANNING).toMatch(/previewError\?\.id === r\.id/);
  });
});
