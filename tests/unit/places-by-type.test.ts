/**
 * Срез мест по виду.
 *
 * Разбор 460 мест подряд — работа, на которой глаз замыливается. По видам
 * проще, но список из ста строк это всё ещё работа глазами, поэтому у каждого
 * места считается ближайший сосед того же вида и строки идут по расстоянию:
 * кандидаты в дубли собираются наверху сами.
 *
 * Главное, что здесь охраняется, — соседа считают только между настоящими
 * координатами. Места без GPS сидят в 0,0 либо в плейсхолдере 53.0444/158.6483
 * (центр Петропавловска, миграция 660), расстояние между двумя такими равно
 * нулю, и без условия они возглавили бы список, не будучи дублями. На этом
 * уже обожглись в /api/admin/places/duplicates — там «Плато Антарктида» и
 * «Маяк» оказывались парой.
 */
import { describe, it, expect } from 'vitest';
import { readFileSync } from 'node:fs';
import { join } from 'node:path';

const SRC = readFileSync(
  join(process.cwd(), 'app/api/cron/places-by-type/route.ts'),
  'utf-8',
);
const CODE = SRC.replace(/\/\*[\s\S]*?\*\//g, '').replace(/^[ \t]*\/\/.*$/gm, '');

describe('только чтение', () => {
  it('ничего не пишет', () => {
    // Срез — это взгляд. Решение о слиянии принимает человек, и применяет его
    // поимённый places-dedup, мягко и обратимо.
    expect(CODE).not.toMatch(/\b(UPDATE|INSERT|DELETE)\b/);
  });

  it('закрыт тем же секретом, что и остальные cron-роуты', () => {
    expect(CODE).toMatch(/timingSafeCompare\(secret, process\.env\.CRON_SECRET/);
  });

  it('параметры проходят через Zod', () => {
    expect(CODE).toMatch(/QuerySchema\.safeParse/);
  });
});

describe('сосед считается честно', () => {
  it('плейсхолдер-координаты не участвуют', () => {
    // Иначе десятки мест без GPS оказались бы «в нуле метров друг от друга».
    expect(CODE).toMatch(/53\.0444/);
    expect(CODE).toMatch(/158\.6483/);
    expect(CODE).toMatch(/lat = 0 AND .*\.lng = 0/);
  });

  it('условие настоящих координат применяется к ОБЕИМ сторонам пары', () => {
    // Проверить только одну сторону — значит починить половину: место с GPS
    // получило бы в соседи место без GPS.
    expect(CODE).toMatch(/REAL_COORDS\('p'\)/);
    expect(CODE).toMatch(/REAL_COORDS\('q'\)/);
  });

  it('слитые места в срез не попадают', () => {
    // Их уже разобрали; показывать их снова — предлагать сделать работу дважды.
    expect(CODE.match(/merged_into_id IS NULL/g)?.length).toBe(2);
  });
});

describe('отсутствие соседа — это ответ, а не пустота', () => {
  it('near отдаётся как null, а не пропадает', () => {
    // Место без соседей рядом — законный и полезный исход: значит дубля нет.
    // Схлопнуть его с «не посчитали» значило бы повторить подмену, из-за
    // которой сейсмо-канал полтора месяца выглядел свежим.
    expect(CODE).toMatch(/near: r\.near_id/);
    expect(CODE).toMatch(/: null,/);
    expect(CODE).toMatch(/NULLS LAST/);
  });
});

describe('различители тождества', () => {
  it('высота и источник приходят в срез', () => {
    // По одному расстоянию нельзя отличить дубль с испорченной геопозицией от
    // двух разных объектов с похожими именами. Для вулкана высота — самый
    // надёжный признак: у Камня 4585 м, у Хангара около двух тысяч. Источник
    // говорит, какой импорт принёс запись.
    expect(CODE).toMatch(/altM: r\.altitude_m/);
    expect(CODE).toMatch(/src: r\.source_name/);
  });

  it('высота берётся из профиля безопасности, а не выдумывается', () => {
    expect(CODE).toMatch(/lsp\.altitude_m/);
  });
});

describe('без типа — перепись видов', () => {
  it('пустой тип назван словами, а не потерян', () => {
    expect(CODE).toMatch(/\(не указан\)/);
  });
});
