/**
 * Сторож: отчётная статистика службы — не предупреждение (07.09).
 *
 * Экран владельца: на главной, в блоке тревог, висели две строки —
 * «К тушению техногенных пожаров сотрудники МЧС России привлекались один раз»
 * (5 сентября) и «…два раза» (4 сентября). Это отчёт ведомства о собственной
 * работе за сутки: ни места, ни времени впереди, ни действия для человека.
 * Турист читает его как угрозу — потому что стоит он там, где стоят угрозы.
 *
 * Прежние жанровые фильтры этого не ловили: пост целиком отбрасывался как
 * суточный бюллетень, но разбор сводки классифицирует КАЖДУЮ строку заново, и
 * статистическая строка проходила все проверки.
 *
 * Второй дефект того же экрана: заголовок тащил в интерфейс значок из поста
 * («📌К тушению…»), а эмодзи в UI запрещены.
 */
import { describe, it, expect } from 'vitest';
import { isServiceStatistics, titleFromText, classifyMchsItem } from '@/lib/services/safety/seismic-parser';

const ownerLines = [
  'К тушению техногенных пожаров сотрудники МЧС России привлекались один раз',
  'К тушению техногенных пожаров сотрудники МЧС России привлекались два раза',
];

describe('статистика службы отсеивается', () => {
  it('строки с экрана владельца признаны отчётом', () => {
    for (const l of ownerLines) expect(isServiceStatistics(l), l).toBe(true);
  });

  it('другие формы того же жанра — тоже', () => {
    for (const l of [
      'За прошедшие сутки зарегистрировано 3 пожара',
      'Совершено 12 выездов подразделений',
      'Спасено два человека, пострадавших нет',
    ]) expect(isServiceStatistics(l), l).toBe(true);
  });

  it('настоящее событие без счёта проходит дальше', () => {
    for (const l of [
      'Произошёл пожар на базе отдыха в Паратунке',
      'На маршруте к Мутновскому зафиксирован выход медведя',
    ]) expect(isServiceStatistics(l), l).toBe(false);
  });

  it('счёт рядом со взглядом вперёд отчётом НЕ считается', () => {
    // «Три очага ликвидировано, ожидается усиление ветра» — вторая половина
    // делает текст предупреждением, и отбрасывать его нельзя.
    expect(isServiceStatistics('Ликвидировано три очага, ожидается усиление ветра до 25 м/с')).toBe(false);
    expect(isServiceStatistics('Зарегистрировано 2 пожара, выход на маршруты не рекомендуется')).toBe(false);
  });

  it('классификатор отбрасывает такую строку целиком', () => {
    for (const l of ownerLines) {
      expect(classifyMchsItem('x', '', l, '2026-09-05T00:00:00Z', 'https://t.me/x'), l).toBeNull();
    }
  });
});

describe('заголовок алерта без значков', () => {
  it('ведущий значок в заголовок не попадает', () => {
    expect(titleFromText('\u{1F4CC}К тушению техногенных пожаров привлекались один раз'))
      .toBe('К тушению техногенных пожаров привлекались один раз');
  });

  it('обычный заголовок не портится', () => {
    expect(titleFromText('Штормовое предупреждение: ветер до 30 м/с'))
      .toBe('Штормовое предупреждение: ветер до 30 м/с');
  });
});
