/**
 * Снятый в поле трек может стать НОВЫМ маршрутом, а не только переписать старый.
 *
 * ── Что нашлось 15.09 ─────────────────────────────────────────────────────
 *
 * Владелец: «я сам записывал трек» — а на карточке «Раздолья Камчатки»
 * ссылка «Пройти сюда с компасом и GPS» отвечала «ничего не нашлось».
 *
 * Разбор цепочки показал, что трек не потерян и всё работает как написано:
 * запись уходит в `POST /api/field-check/track`, файл целиком ложится в S3,
 * строка — в очередь `route_track_imports` со статусом pending. Ничего не
 * применяется само: трек становится геометрией только явным решением
 * человека (решение владельца 30.08).
 *
 * Но применить его было НЕКУДА. Очередь умела ровно одно — переписать
 * геометрию СУЩЕСТВУЮЩЕГО маршрута (`route_id` или `route_title`). У
 * «Раздолья» маршрута нет вовсе: есть место, а пути к нему никто не заводил,
 * и завести его из трека код не умел. Очередь без выхода: человек сходил,
 * снял путь — и путь остался лежать.
 *
 * ── Почему имя обязательно приходит от человека ───────────────────────────
 *
 * Сочинять имя маршрута код не вправе (§13): стандарт требует называть
 * ОБЪЕКТ или ПУТЬ — «Вулкан Горелый», «Пиначево — Центральный», — а
 * автоматическое «Трек от 15.09» завело бы в каталог мусор, который не
 * находится ни поиском, ни сверкой имён при чистке дублей.
 *
 * Поэтому `new_route_title` обязателен, проходит судью §13 и проверяется на
 * занятость: если маршрут с таким именем уже есть, ответ называет его id —
 * применять надо к нему, а не плодить двойника.
 *
 * Проверено на настоящем PostgreSQL: запись создаётся, линия ложится
 * источником `gpx`, длина и число точек на месте.
 */
import { describe, it, expect } from 'vitest';
import { readFileSync } from 'node:fs';
import { join } from 'node:path';

const SRC = readFileSync(
  join(process.cwd(), 'app/api/cron/track-import-queue/route.ts'),
  'utf-8',
);

describe('очередь треков умеет заводить новый маршрут', () => {
  it('в теле запроса есть new_route_title', () => {
    expect(SRC).toMatch(/new_route_title: z\.string\(\)/);
  });

  it('цель по-прежнему называется РОВНО одна', () => {
    // Иначе появилась бы запись, которая и переписывает старый маршрут, и
    // создаёт новый — два разных действия под одним вызовом.
    expect(SRC).toMatch(/\[d\.route_id, d\.route_title, d\.new_route_title\]\.filter\(Boolean\)\.length === 1/);
  });

  it('имя проходит судью стандарта §13', () => {
    expect(SRC).toMatch(/judgeRouteTitle\(title\)/);
    expect(SRC).toMatch(/стандарт §13/);
  });

  it('занятое имя — отказ с id существующего маршрута', () => {
    // «Уже есть» это не ошибка человека, а указание, куда применять: ответ
    // обязан дать id, иначе следующий шаг придётся искать руками.
    expect(SRC).toMatch(/уже есть — применяйте к нему через route_id/);
    expect(SRC).toMatch(/route_id: taken\.rows\[0\]!\.id/);
  });

  it('маршрут создаётся внутри той же транзакции, что и линия', () => {
    // Иначе при отказе записи линии остался бы пустой маршрут-призрак.
    const at = SRC.indexOf("await client.query('BEGIN')");
    const commit = SRC.indexOf("await client.query('COMMIT')");
    const insert = SRC.indexOf('INSERT INTO kamchatka_routes');
    expect(at).toBeGreaterThan(-1);
    expect(insert).toBeGreaterThan(at);
    expect(insert).toBeLessThan(commit);
  });

  it('id созданного маршрута возвращается человеку', () => {
    expect(SRC).toMatch(/created_route_id: createdRouteId/);
  });

  it('правило старшинства к новому маршруту не применяется', () => {
    // Линии у него нет по определению — перезаписывать нечего.
    expect(SRC).toMatch(/creating\s*\n?\s*\?\s*\{ allowed: true/);
  });

  it('сухой прогон остался по умолчанию', () => {
    // Создание маршрута — не менее серьёзное действие, чем замена линии.
    expect(SRC).toMatch(/dry_run: z\.boolean\(\)\.default\(true\)/);
  });
});
