/**
 * Код, читающий новую колонку, обязан переживать её отсутствие.
 *
 * 18.08 карточка маршрута перестала открываться НА ПРОДЕ. В поле это выглядело
 * так: «Маршрут не открылся — сервер не отдал данные», и человек, ищущий путь
 * на Козельский, не получил ничего.
 *
 * Механизм: код с `rw.link_kind` уехал раньше миграции 874, а та не
 * применилась (сначала из-за запятых внутри комментария, потом по причине,
 * которая ещё выясняется). Запрос падал с «column rw.link_kind does not
 * exist», и карточка честно отказывалась открываться без путевых точек —
 * строгая проверка сработала правильно, сломал её я.
 *
 * Между мержем и миграцией ВСЕГДА есть зазор: код деплоится атомарно, а
 * миграция может не пройти. Значит чтение новой колонки обязано быть
 * терпимым — `to_jsonb(row)->>'col'` вернёт NULL вместо падения, и поведение
 * останется прежним.
 *
 * Сторож ищет прямое чтение свежих колонок в боевых запросах.
 */
import { describe, it, expect } from 'vitest';
import { readFileSync } from 'node:fs';
import { join } from 'node:path';

/**
 * Колонки, заведённые недавними миграциями. Пополнять при добавлении новых —
 * пока миграция не применена на проде хотя бы одним успешным деплоем.
 */
const FRESH_COLUMNS = ['link_kind'];

/** Файлы, чей отказ виден человеку в поле. */
const HOT_PATHS = [
  'app/api/routes/[id]/route.ts',
  'lib/routes/geometry-audit.ts',
  'app/api/cron/route-popularity/route.ts',
];

const read = (p: string) => readFileSync(join(process.cwd(), p), 'utf-8');

describe('новая колонка не роняет запрос', () => {
  for (const path of HOT_PATHS) {
    it(`${path.split('/').pop()}: свежая колонка читается терпимо`, () => {
      const src = read(path);
      // Код без комментариев: прежний дефект в них описан намеренно.
      const code = src.replace(/\/\*[\s\S]*?\*\//g, '').replace(/^\s*\/\/.*$/gm, '');

      const queries = code.match(/`[^`]*`/g) ?? [];
      for (const col of FRESH_COLUMNS) {
        for (const q of queries) {
          if (!q.includes(col)) continue;
          // Прямая ссылка вида `rw.link_kind` в SQL — падение, пока миграция
          // не доехала. Обращение к полю результата в TypeScript (`w.link_kind`)
          // законно: там колонка уже стала свойством строки.
          expect(
            new RegExp(`\\b[a-z_]+\\.${col}\\b`).test(q),
            `${path}: SQL читает ${col} напрямую — запрос упадёт без миграции`,
          ).toBe(false);
          expect(
            q.includes('to_jsonb'),
            `${path}: запрос читает ${col} мимо to_jsonb`,
          ).toBe(true);
        }
      }
    });
  }
});
