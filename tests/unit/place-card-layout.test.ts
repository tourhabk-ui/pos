/**
 * Ширину и поля карточки места решает РАСКЛАДКА, а не каждый блок сам.
 *
 * ── Что нашлось 14.09 ─────────────────────────────────────────────────────
 *
 * Владелец сравнил карточку места с другими ресурсами: «мы очень хреного
 * выглядим». Разбор показал не вкусовое расхождение, а механическое.
 *
 * `max-w-3xl mx-auto px-4` стояло в ДЕВЯТНАДЦАТИ компонентах карточки, а
 * родитель половину из них оборачивал в такой же контейнер ещё раз. Отсюда
 * три следствия, и все видны глазом:
 *
 *  1. **Поля разной ширины.** У блока со своим контейнером внутри чужой
 *     отступ удваивался: 32 пикселя против 16 у соседа. Колонка текста
 *     «дышала» неровно сверху вниз.
 *  2. **Два блока выпадали из колонки совсем.** `PlaceCharacteristics` и
 *     `PlaceNearby` контейнера не имели вовсе и растягивались во всю ширину
 *     монитора, пока соседи стояли лентой посередине.
 *  3. **Правило, написанное двадцать раз, — это двадцать правил.** Они уже
 *     разошлись; тот же урок, что со стандартом линии (§12 CLAUDE.md) и
 *     с картой маршрута, которую три экрана рисовали трижды.
 *
 * Теперь контейнер один — в `_PlaceDetailClient`, и он же держит вторую
 * колонку «как добраться» на широком экране.
 *
 * ── Что держит сторож ─────────────────────────────────────────────────────
 *
 * Блок карточки не назначает себе ширину. Исключения — три полноширинных
 * элемента, которые по построению идут ВНЕ колонки и центруют содержимое
 * сами: герой (фото на всю ширину), липкий бар действий и баннер статуса.
 * Список исключений может только сокращаться: каждая новая запись означает
 * ещё одно место, где ширина решается заново.
 */
import { describe, it, expect } from 'vitest';
import { readdirSync, readFileSync } from 'node:fs';
import { join } from 'node:path';

const ROOT = process.cwd();
const PLACES = join(ROOT, 'components', 'places');
const CLIENT = readFileSync(join(ROOT, 'app', 'places', '[id]', '_PlaceDetailClient.tsx'), 'utf-8');

/**
 * Полноширинные по построению: идут вне колонки и центруют содержимое сами.
 * Может только СОКРАЩАТЬСЯ.
 */
const FULL_BLEED = new Set([
  'PlaceHero.tsx',          // фото на всю ширину окна
  'PlaceActionBar.tsx',     // липкий бар под шапкой
  'PlaceRealtimeStatus.tsx', // баннер тревоги, прилипает к верху
]);

function componentFiles(): string[] {
  return readdirSync(PLACES).filter((f) => f.endsWith('.tsx'));
}

describe('блоки карточки места не решают ширину сами', () => {
  it('ни один блок колонки не назначает max-w', () => {
    const guilty = componentFiles()
      .filter((f) => !FULL_BLEED.has(f))
      .filter((f) => /max-w-(\d|xs|sm|md|lg|xl|screen|full|prose|\[)/.test(
        readFileSync(join(PLACES, f), 'utf-8'),
      ));
    expect(
      guilty,
      'ширину держит раскладка карточки (_PlaceDetailClient), а не блок: ' +
        'своя max-w здесь — это второе правило ширины, и оно разойдётся с первым',
    ).toEqual([]);
  });

  it('проверка не пустая — блоки есть', () => {
    expect(componentFiles().length).toBeGreaterThan(10);
  });
});

describe('раскладка карточки — одна и в одном месте', () => {
  it('контейнер колонки объявлен в клиенте карточки', () => {
    expect(CLIENT).toMatch(/max-w-3xl px-4 lg:max-w-6xl/);
  });

  it('на широком экране колонок две', () => {
    expect(CLIENT).toMatch(/lg:grid-cols-\[minmax\(0,1fr\)_340px\]/);
  });

  it('столбец «как добраться» идёт в DOM ПЕРЕД основным', () => {
    // На телефоне сетки нет, блоки идут подряд — и свой путь обязан остаться
    // сразу под шапкой (решение владельца 07.09). Вправо его переносит
    // явная расстановка по колонкам, а не порядок в разметке.
    const aside = CLIENT.indexOf('lg:col-start-2 lg:row-start-1');
    const main = CLIENT.indexOf('lg:col-start-1 lg:row-start-1');
    expect(aside).toBeGreaterThan(-1);
    expect(main).toBeGreaterThan(-1);
    expect(aside, 'переставив их местами, свой путь уедет на телефоне вниз')
      .toBeLessThan(main);
  });

  it('свой путь не задвоен — компонент на карточке один', () => {
    // Вторая копия ради второй колонки расходится поведением: это уже
    // случалось с кнопкой SOS (#887).
    expect(CLIENT.match(/<PlaceOwnRoute\b/g)?.length ?? 0).toBe(1);
  });
});
