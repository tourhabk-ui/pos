/**
 * Ссылка «Пройти сюда с компасом и GPS» ведёт К ЭТОМУ месту, а не к прежнему.
 *
 * ── Что нашлось 15.09 ─────────────────────────────────────────────────────
 *
 * Владелец: «при переходе по ссылке "Пройти сюда с компасом и GPS"
 * открывается не Раздолье Камчатки, а последняя сохранённая точка».
 *
 * Механизм. Карточка места ведёт на `/planning?mode=trail&q=<имя>&auto=1`.
 * Параметр `q` кладётся в поле поиска цели, но сам поиск работает ТОЛЬКО
 * пока выбор цели виден:
 *
 *     pickerVisible = showRouteModal || (нет активного маршрута)
 *
 * У человека с сохранённым активным маршрутом выбор не показан → поиск не
 * запускается → `q` лежит в невидимом поле → полевой экран честно
 * навигирует по ПРЕЖНЕМУ маршруту. Снаружи это «ссылка ведёт не туда», а в
 * поле это опаснее неработающей ссылки: компас уверенно указывает на чужую
 * точку, и человек идёт по нему.
 *
 * ── Почему именно так починено ────────────────────────────────────────────
 *
 * Открывается выбор цели, а сохранённый маршрут НЕ стирается: человек мог
 * быть на нём прямо сейчас, и стереть его молча — отобрать навигацию у того,
 * кто в поле. Решение остаётся за человеком, как и требовало решение
 * владельца 30.08: автовыбор доводит до цели, но не отменяет «Изменить».
 *
 * Проверено в браузере с заранее сохранённым активным маршрутом: до правки
 * открывался прежний маршрут, после — «Пути к „Раздолье Камчатки“».
 */
import { describe, it, expect } from 'vitest';
import { readFileSync } from 'node:fs';
import { join } from 'node:path';

const PLANNING = readFileSync(
  join(process.cwd(), 'app/planning/_PlanningClient.tsx'),
  'utf-8',
);
const PLACE = readFileSync(
  join(process.cwd(), 'app/places/[id]/_PlaceDetailClient.tsx'),
  'utf-8',
);

describe('карточка места шлёт имя и просит довести до цели', () => {
  it('ссылка несёт mode=trail, q и auto=1', () => {
    expect(PLACE).toMatch(/\/planning\?mode=trail&q=\$\{encodeURIComponent\(place\.name\)\}&auto=1/);
  });
});

describe('планер по такой ссылке открывает выбор цели', () => {
  it('auto=1 поднимает выбор, иначе поиск не запустится', () => {
    // Без этого `q` остаётся в невидимом поле: поиск живёт под
    // pickerVisible, а он выключен, пока есть активный маршрут.
    const at = PLANNING.indexOf("params.get('auto') === '1'");
    expect(at, 'ветка auto=1 не найдена').toBeGreaterThan(-1);
    const tail = PLANNING.slice(at, at + 1600);
    expect(tail, 'выбор цели должен открыться').toContain('setShowRouteModal(true)');
  });

  it('сохранённый маршрут не стирается', () => {
    // Человек мог быть на нём прямо сейчас — стереть значит отобрать
    // навигацию у того, кто в поле.
    const at = PLANNING.indexOf("params.get('auto') === '1'");
    const tail = PLANNING.slice(at, at + 1600);
    expect(tail).not.toContain("removeItem('active_trail_route_id')");
  });

  it('поиск по-прежнему завязан на видимость выбора', () => {
    // Смысл правки в том, чтобы ВКЛЮЧИТЬ выбор, а не обойти условие:
    // обход завёл бы вторую ветку поиска рядом с первой.
    expect(PLANNING).toMatch(/const pickerVisible = showRouteModal \|\|/);
    expect(PLANNING).toMatch(/if \(!pickerVisible \|\| q\.length < 2\)/);
  });

  it('цель выбирается автоматически, когда пути нашлись', () => {
    expect(PLANNING).toMatch(/cameFromPlaceRef\.current/);
    expect(PLANNING).toMatch(/setSelectedDestination\(destinations\[0\]\)/);
  });
});
