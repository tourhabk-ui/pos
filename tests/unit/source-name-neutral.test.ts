/**
 * Имя стороннего поставщика переименовано в «наши партнёры» и не ведёт наружу.
 *
 * Решение владельца 17.08. Полевой скрин показал «источник: idilesom» в
 * карточке качества данных; подвал карточки места печатал «Источник:
 * idilesom.com» кликабельной ссылкой.
 *
 * Про этот же источник миграция 767 писала прямым текстом: реклама конкурента,
 * которую вычищали из описаний. Турист, дочитавший нашу карточку места,
 * получал в конце дорогу к конкуренту.
 *
 * Переименование затрагивает ЗНАЧЕНИЯ, а не структуру (миграция 871):
 * in-band маркер геометрии становится 'partners', `source_name` — «наши
 * партнёры». Ссылка при этом обязана исчезнуть: подпись «наши партнёры»
 * поверх ссылки на чужой сайт обещает одно, а ведёт в другое.
 */
import { describe, it, expect } from 'vitest';
import { readFileSync } from 'node:fs';
import { join } from 'node:path';
import { gradeFromSource } from '@/lib/map/line-standard';

const MIGRATION = readFileSync(
  join(process.cwd(), 'migrations/871_source_name_neutral.sql'),
  'utf-8',
);
const FOOTER = readFileSync(join(process.cwd(), 'components/places/PlaceFooter.tsx'), 'utf-8');
/** Код без комментариев: прежнее решение в них разобрано намеренно. */
const FOOTER_CODE = FOOTER.replace(/\/\*[\s\S]*?\*\//g, '').replace(/^\s*\/\/.*$/gm, '');

describe('новый слог знают, но снятым треком не считают', () => {
  /**
   * Первая редакция этого сторожа требовала обратного: `external` обязан был
   * остаться снятым треком, потому что обезличивание не должно менять род
   * линии. Для ПЕРЕИМЕНОВАНИЯ это верно и сейчас — миграция 871 меняет только
   * написание, и понижать род она права не имеет.
   *
   * Понизил его не она, а отдельное решение владельца в тот же день, по
   * другой причине: скрейп с чужого сайта не доказывает, что по линии кто-то
   * прошёл. Таких линий 259 из 301, и все они давали право обещать ведение.
   *
   * Разница существенна: сторож продолжает следить, чтобы переименование не
   * трогало род, — просто род у этого источника теперь другой.
   */
  it('external — импорт, а не снятый путь', () => {
    expect(gradeFromSource('external')).toBe('unknown');
  });

  it('прежний слог узнаётся так же — ради полевых пакетов на телефонах', () => {
    // Снимок, сохранённый ДО миграции, лежит в IndexedDB и уже не изменится.
    // Забыв слог, мы отдали бы сохранённую линию плотностной эвристике — то
    // есть вернули бы ей звание трека ровно там, где связи нет и переспросить
    // нечего.
    expect(gradeFromSource('idilesom')).toBe('unknown');
  });

  it('оба написания судятся одинаково — это один и тот же поставщик', () => {
    expect(gradeFromSource('idilesom')).toBe(gradeFromSource('external'));
  });

  it('незнакомый источник — по-прежнему «не спрашивали»', () => {
    // null и 'unknown' здесь разные ответы: первый — «судить нечем», второй —
    // «знаем откуда и знаем, что это не доказательство».
    expect(gradeFromSource('какой-то-новый')).toBeNull();
  });
});

describe('миграция переименовывает значения, а не режет происхождение', () => {
  it('маркер геометрии становится обезличенным', () => {
    expect(MIGRATION).toMatch(/jsonb_build_object\('source', 'external'\)/);
  });

  it('видимое имя источника обезличено во всех написаниях', () => {
    // Написаний накопилось несколько: слог импортёра, домен (его подставил
    // data-repair), русское имя из скрейпа.
    expect(MIGRATION).toMatch(/source_name = 'сторонний источник'/);
    expect(MIGRATION).toMatch(/иди\\s\*лесом\|идилесом\|idilesom/);
    expect(MIGRATION).toMatch(/UPDATE kamchatka_routes/);
    expect(MIGRATION).toMatch(/UPDATE places/);
  });

  it('source_url остаётся — это проверяемость, а не витрина', () => {
    expect(MIGRATION).not.toMatch(/SET source_url\s*=\s*NULL/i);
  });

  it('идемпотентна и регистрируется', () => {
    expect(MIGRATION).toMatch(/871_source_name_neutral\.sql/);
    expect(MIGRATION).toMatch(/ON CONFLICT \(name\) DO NOTHING/);
  });
});

describe('подвал карточки места не ведёт к чужому сайту под нашей подписью', () => {
  it('сторонний источник печатается текстом, без ссылки', () => {
    expect(FOOTER).toMatch(/const EXTERNAL_SOURCE_NAME = 'сторонний источник'/);
    expect(FOOTER).toMatch(/externalSource \? \(/);
  });

  it('чужое имя не подменяется другим именем', () => {
    // «Наши партнёры» решило бы задачу бренда и создало бы новую: утверждение
    // об отношениях, которых нет. Миграция 767 называет этот источник
    // конкурентом.
    expect(FOOTER_CODE).not.toMatch(/партнёр/i);
    expect(MIGRATION).not.toMatch(/source_name = 'наши партнёры'/);
  });

  it('ссылка остаётся для прочих источников', () => {
    // Атрибуция источника сама по себе честна — запрет адресный.
    expect(FOOTER).toMatch(/href=\{sourceUrl\}/);
  });
});
