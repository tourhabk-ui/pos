/**
 * Протокол «AI Спасателя» — полевые правки владельца 01.08.
 *
 * Скриншот с прода: на «Встретил медведя» модель спросила «Бурый/камчатский,
 * гризли?» и пообещала, что 112 «работает без связи». Оба — импровизация
 * поверх протокола: гризли на Камчатке не водится (вид один — бурый,
 * камчатский подвид), а 112 без сети ЛЮБОГО оператора не работает — в тайге
 * такое обещание стоит жизни. Протокол теперь фиксирует оба факта явно.
 */
import { describe, it, expect } from 'vitest';
import { readFileSync } from 'node:fs';
import { join } from 'node:path';

const SRC = readFileSync(join(process.cwd(), 'app/api/safety/rescue-chat/route.ts'), 'utf-8');

describe('протокол МЕДВЕДЬ знает фауну Камчатки', () => {
  it('вид зафиксирован: бурый, камчатский подвид — и вопрос о виде запрещён', () => {
    expect(SRC, 'из протокола пропал факт о единственном виде — модель снова спросит про гризли')
      .toMatch(/Вид на Камчатке ОДИН — бурый \(камчатский подвид\)/);
    expect(SRC).toMatch(/вопросов о виде не задавай/);
  });

  it('гризли в протоколе не упоминается как вариант', () => {
    expect(SRC.toLowerCase()).not.toMatch(/гризли\?/);
  });
});

describe('обещание про 112 — честное', () => {
  it('прямо сказано: без сети звонок не пройдёт, «без связи» не обещать', () => {
    expect(SRC, 'из промпта пропала честная оговорка про сеть — модель снова пообещает «без связи»')
      .toMatch(/Совсем без сети звонок не пройдёт/);
    expect(SRC).toMatch(/сеть ЛЮБОГО оператора/);
  });
});
