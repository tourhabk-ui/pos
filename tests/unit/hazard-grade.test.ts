/**
 * Сторож: источник назвал свой ВЫСШИЙ разряд — платформа обязана это услышать.
 *
 * Повод — сводка Камчатского УГМС от 13.09.2026: на реке Большой Воровской в
 * районе села Соболево уровень воды «может достигнуть опасного явления», и при
 * этом ожидается «размыв устоев и опор мостовых переходов». Для туриста на
 * западном побережье это не мокрые ноги, а исчезнувшая дорога назад.
 *
 * ЧТО БЫЛО. Классификатор разбирал сводку ВЕРНО: тип `flood`, зона `western`.
 * Но severity единица — она прошита в ветку паводка для ВСЕХ паводков сразу, и
 * для весеннего половодья, и для ОЯ. А ниже двойки нет ни пуша
 * (`severity >= 2 OR alert_type = 'tsunami_warning'`), ни красного статуса
 * (`max_severity >= 2 THEN 'red'`), ни запрета в go-verdict. Предупреждение о
 * смытом мосте уходило ТИШЕ, чем «сильный ветер», у которого severity 2.
 *
 * Термина «опасное явление» в коде не было вовсе — замер 13.09 по всему
 * репозиторию дал одно совпадение, и то в `lib/weather/ensemble.ts` как подпись
 * погодного кода, к шкале Росгидромета отношения не имеющая. То есть слово,
 * которым агентство маркирует высшую опасность, платформе было неизвестно.
 *
 * ПОЧЕМУ ПОРОГ НЕ ВЫДУМАН. У Росгидромета две ступени: НЯ — неблагоприятное
 * явление, ОЯ — опасное, верхняя. Повышение идёт по словарю САМОГО источника, а
 * не потому, что текст звучит страшно: иначе красным станет всё, и красное
 * перестанет значить что-либо.
 */
import { describe, it, expect } from 'vitest';
import { readFileSync } from 'node:fs';
import { join } from 'node:path';
import { classifyMchsItem, declaresHazardGrade } from '@/lib/services/safety/seismic-parser';

/** Настоящий текст сводки 13.09 — не пересказ. */
const UGMS_TITLE = 'Экстренное предупреждение: подъём уровня воды на реке Большой Воровской';
const UGMS_BODY =
  'УГМС уточнило: в связи с увеличением интенсивности подъёма уровня воды дождевого паводка, ' +
  'в первой половине дня 14 сентября на реке Большой Воровской, в районе села Соболево, ' +
  'уровень воды может достигнуть опасного явления. При достижении уровня опасного явления ' +
  'возможно частичное подтопление придомовых и дворовых территорий, расположенных в прибрежной ' +
  'зоне реки, межпоселковых дорог, размыв устоев и опор мостовых переходов.';

function classify(title: string, body: string) {
  return classifyMchsItem('t', title, body, new Date().toUTCString(), 'https://41.mchs.gov.ru/x');
}

describe('сводка УГМС 13.09 — настоящий текст', () => {
  const r = classify(UGMS_TITLE, UGMS_BODY);

  it('разобрана как паводок на западном побережье', () => {
    expect(r?.alert_type).toBe('flood');
    expect(r?.affected_zones).toContain('western');
  });

  it('severity 2 — иначе ни пуша, ни красного статуса', () => {
    // Ровно то число, которого не хватало: пороги пуша и статуса стоят на 2.
    expect(r?.severity).toBeGreaterThanOrEqual(2);
  });

  it('срок паводка НЕ укорочен до запретных 48 часов', () => {
    // ОЯ живёт столько, сколько живёт явление. Обрезав 120 до 48, мы сняли бы
    // красный статус с ещё не спавшей воды — в отличие от запрета тургруппам,
    // который снимают отдельным сообщением.
    expect(r?.expires_hours).toBe(120);
  });
});

describe('разряд читается по словарю источника', () => {
  it('ОЯ в любой падежной форме', () => {
    expect(declaresHazardGrade('уровень воды может достигнуть опасного явления')).toBe(true);
    expect(declaresHazardGrade('объявлено опасное явление по ветру')).toBe(true);
    expect(declaresHazardGrade('в связи с опасным явлением закрыт перевал')).toBe(true);
    expect(declaresHazardGrade('ОЯ по уровню воды')).toBe(true);
  });

  it('НЯ — соседняя НИЖНЯЯ ступень, по ней не поднимаем', () => {
    // Спутав их, мы подняли бы до красного обычный дождь.
    expect(declaresHazardGrade('ожидается неблагоприятное явление — дождь')).toBe(false);
    expect(declaresHazardGrade('НЯ по осадкам')).toBe(false);
  });

  it('обе ступени в одной сводке — ОЯ настоящее', () => {
    expect(declaresHazardGrade('НЯ по ветру, ОЯ по уровню воды на реке Быстрой')).toBe(true);
  });

  it('объяснение термина — не объявление опасности', () => {
    // Памятка МЧС не должна красить маршруты в красный.
    expect(declaresHazardGrade('Что такое опасное явление и чем оно отличается от НЯ')).toBe(false);
    expect(declaresHazardGrade('памятка: опасное явление называется так, если...')).toBe(false);
  });

  it('обычный текст без разряда не повышается', () => {
    expect(declaresHazardGrade('на реках ожидается подъём уровня воды')).toBe(false);
    expect(declaresHazardGrade('опасность схода лавин сохраняется')).toBe(false);
  });

  it('отрицание не поднимает: «неопасного явления» — это не ОЯ', () => {
    // Без левой границы `опасного явлени` совпадает ВНУТРИ слова, и отрицание
    // повышало бы severity вместо того, чтобы её не трогать.
    expect(declaresHazardGrade('явление отнесено к категории неопасного явления')).toBe(false);
    expect(declaresHazardGrade('малоопасного явления не зарегистрировано')).toBe(false);
  });

  it('аббревиатура не ловится внутри слов', () => {
    // Кириллическую границу приходится ставить руками: JS \b её не знает, и
    // первая редакция этой проверки (`\bоя\b`) не совпадала НИ С ЧЕМ — молча.
    expect(declaresHazardGrade('стоя на берегу, наблюдали подъём воды')).toBe(false);
    expect(declaresHazardGrade('оядерный полигон')).toBe(false);
  });
});

describe('порог стоит поверх категорий, а не внутри паводка', () => {
  it('погодная сводка с ОЯ тоже поднимается', () => {
    // Разряд источника одинаково весом под паводком и под циклоном; правило,
    // написанное внутри одной ветки, стало бы правилом только для неё.
    const r = classify(
      'Экстренное предупреждение по ветру',
      'По южным районам края ожидается сильный ветер, достигающий критериев опасного явления.',
    );
    expect(r?.severity).toBeGreaterThanOrEqual(2);
  });

  it('обычный паводок без разряда остаётся единицей', () => {
    // Иначе повышение съело бы смысл: красным стало бы каждое половодье.
    const r = classify(
      'Информация о паводковой обстановке',
      'На реках края ожидается подъём уровня воды в связи с дождями. Ситуация под контролем.',
    );
    expect(r?.alert_type).toBe('flood');
    expect(r?.severity).toBe(1);
  });
});

describe('пороги, ради которых всё это делается', () => {
  const ROOT = process.cwd();
  const ingest = readFileSync(join(ROOT, 'app/api/cron/safety-ingest/route.ts'), 'utf-8');

  it('пуш и красный статус действительно стоят на двойке', () => {
    // Если пороги когда-нибудь сдвинут, этот сторож обязан покраснеть вместе с
    // ними: повышение до 2 имеет смысл ровно потому, что 2 — граница.
    expect(ingest).toMatch(/severity >= 2 OR alert_type = 'tsunami_warning'/);
    expect(ingest).toMatch(/max_severity >= 2 THEN 'red'/);
  });
});
