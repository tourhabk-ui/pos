/**
 * Первым у места стоит САМОЕ ОПАСНОЕ предупреждение, а не первое по алфавиту.
 *
 * ── Что увидел владелец (15.09) ───────────────────────────────────────────
 *
 * Карточка «Раздолья Камчатки» — база с термальными ваннами под Елизово:
 *
 *   «Кузьмич — сегодня здесь: Сегодня сюда — нет»
 *   «Активное предупреждение: Вилючинский перевал: проезд по пропускам»
 *
 * Перевал — в шестидесяти километрах, и опасность у того алерта 1, то есть
 * красный вердикт давал НЕ ОН. Вердикт считается по `alert_severity`
 * (максимум по зоне), а показывался `activeAlerts[0]` — первый элемент
 * массива, собранного `array_agg(DISTINCT title)`, то есть первый ПО
 * АЛФАВИТУ. «Вилючинский» стоял раньше «Паводка», у которого опасность 2.
 *
 * Объяснение, не относящееся к выводу, хуже отсутствия объяснения: человек
 * сверяет одно с другим, видит несовпадение и перестаёт верить обоим — а
 * это слой безопасности, где доверие и есть весь смысл.
 *
 * ── Что держит сторож ─────────────────────────────────────────────────────
 *
 * Агрегат в `safety-ingest` обязан упорядочивать заголовки по убыванию
 * опасности. Дедуп при этом сохраняется: RSS-перепубликации одного
 * предупреждения размножали алерт шестикратно на карточках — он вынесен
 * отдельным шагом (DISTINCT ON), потому что у `array_agg(DISTINCT ...)`
 * порядок задать нечем, кроме самого заголовка.
 *
 * Проверено на настоящем PostgreSQL с данными того же вида: по алфавиту
 * первым шёл «Вилючинский перевал» (severity 1), по опасности — «Паводок»
 * (severity 2).
 */
import { describe, it, expect } from 'vitest';
import { readFileSync } from 'node:fs';
import { join } from 'node:path';

const SRC = readFileSync(
  join(process.cwd(), 'app/api/cron/safety-ingest/route.ts'),
  'utf-8',
);

describe('порядок предупреждений места', () => {
  it('заголовки собираются по убыванию опасности', () => {
    expect(SRC).toMatch(/array_agg\(title ORDER BY severity DESC/);
  });

  it('алфавитного агрегата больше нет', () => {
    // Именно он ставил впереди слабый алерт с буквой раньше по алфавиту.
    expect(SRC).not.toMatch(/array_agg\(DISTINCT title\)/);
  });

  it('дедуп сохранён — отдельным шагом', () => {
    // Без него одно предупреждение из шести RSS-перепубликаций снова
    // размножится на карточке.
    expect(SRC).toMatch(/SELECT DISTINCT ON \(lrs_id, title\)/);
  });

  it('вердикт по-прежнему считается по максимуму опасности', () => {
    // Порядок показа менялся, порог тревоги — нет.
    expect(SRC).toMatch(/MAX\(severity\)/);
  });
});

describe('карточка показывает первый элемент как главное предупреждение', () => {
  const ADVISORY = readFileSync(
    join(process.cwd(), 'lib/kuzmich/place-advisory.ts'),
    'utf-8',
  );

  it('совет Кузьмича берёт activeAlerts[0]', () => {
    // Ради этого читателя и наводится порядок в агрегате: он показывает
    // ОДИН заголовок и выдаёт его за причину вердикта.
    expect(ADVISORY).toMatch(/activeAlerts\[0\]/);
  });
});
