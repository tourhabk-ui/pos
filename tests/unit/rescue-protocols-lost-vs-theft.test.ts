/**
 * Перебор по словарям модуля (их держит снимок ниже): каждое подлежащее с
 * каждым глаголом шаблона, которого нет в его числе, и каждое притяжательное
 * с каждой вещью чужого рода или числа — не фраза языка.
 */
const R11_AGREEMENT = ((): string[] => {
  const g = ITEM_GRAMMAR;
  const cases: string[] = [];
  for (const [who, verbs] of Object.entries(g.ruSubject)) {
    const mine: readonly string[] = verbs;
    for (const v of g.ruVerb) if (!mine.includes(v)) cases.push(`${who} ${v} паспорт`, `${who} ${v} мои документы в такси`);
  }
  const kinds = [g.ruThing.m, g.ruThing.f, g.ruThing.p];
  for (const a of kinds) {
    for (const b of kinds) {
      if (a === b) continue;
      for (const own of a.own) for (const t of b.things) cases.push(`потерял ${own} ${t}`, `я потеряла ${own} ${t}`, `${own} ${t} украли`);
    }
  }
  return finding(cases);
})();

