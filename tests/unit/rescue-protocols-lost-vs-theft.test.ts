/**
 * Своя нормализация теста — по шапке модуля, не его кодом: регистр, ё → е,
 * типографский апостроф, пробелы, один «.» или «!» в конце. null — в
 * реплике есть иная пунктуация, перевод строки, цифра или значок.
 */
const normalize = (q: string): string | null => {
  if (/[\n\r\u2028\u2029]/.test(q)) return null;
  const t = q.normalize('NFC').toLowerCase().replace(/ё/g, 'е').replace(/[\u2019\u02bc]/g, "'")
    .split(/[ \t\u00a0]+/).filter(Boolean).join(' ')
    .replace(/[.!]$/, '').replace(/ $/, '');
  return /^[a-zа-я' ]+$/.test(t) ? t : null;
};
/** Фраза языка — по своему перечню теста. */
const inLanguage = (q: string): boolean => {
  const t = normalize(q);
  return t !== null && LANGUAGE.has(t);
};
