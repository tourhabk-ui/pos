describe('(е) опасное слово рядом с утерей вещи — прежний ответ', () => {
  const danger = Object.values(DANGER_WORDS).flatMap((s) => s.split(/\s+/));
  const BASES = [
    'потерял паспорт', 'украли кошелек', 'I lost my passport', 'у меня украли телефон', 'я потерял свой паспорт', 'lost my passport',
  ] as const;
  const phrases = danger.flatMap((w) => [
    `${BASES[0]} ${w}`, `${w} ${BASES[1]}`, `${BASES[2]} ${w}`, `${w}, ${BASES[3]}`, `${w} ${BASES[4]}`, `${BASES[5]} ${w}`,
  ]);

  it('основа фраз — фраза языка: без опасного слова протокол вещей', () => {
    for (const q of BASES) expect(isPureItemLoss(q), q).toBe(true);
  });

  it('с каждым опасным словом фраза не чистая, и ответ ровно прежний', () => {
    expect(phrases.length).toBe(danger.length * BASES.length);
    expect(phrases.filter((q) => isPureItemLoss(q))).toEqual([]);
    expect(phrases.filter((q) => getLocalProtocol(q) !== before(q))).toEqual([]);
  });
});

