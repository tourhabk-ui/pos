/**
 * У судьи faithfulness есть исход «верно, но не место-специфично» (#1818).
 *
 * Прогон 12 (11.09) показал самопротиворечие в пределах одного прогона:
 * live-10 «горная болезнь — спускайся» получил 5 («общепринятый протокол
 * безопасности, а не выдумка»), live-8 «звони 112» и live-9 «кипяти воду» —
 * по 1 («факта нет в контексте»). Три ответа одного класса — три разных
 * вердикта. Судья умел отличать выдумку от не-выдумки, но не умел отличать
 * «факт про ЭТО место» от «общее знание, верное про любое место» — и место,
 * где нельзя сказать «не знаю», заполнялось произволом (§4.0).
 *
 * Живой прогон судьи здесь не тестируется (LLM недетерминирован, сети нет в
 * CI) — сторож держит текст РУБРИКИ: у неё обязана быть явная граница между
 * этими двумя классами, и обязаны быть названы ИМЕННО те три случая, что
 * разошлись в прогоне 12. Абстрактное «учитывай контекст» сторож не примет:
 * оно уже стояло в прежней рубрике и не спасло от противоречия.
 */
import { describe, it, expect } from 'vitest';
import { readFileSync } from 'node:fs';
import { join } from 'node:path';

const SRC = readFileSync(
  join(process.cwd(), 'lib/agents/eval/kuzmich-faithfulness.ts'),
  'utf-8',
);

function promptBody(): string {
  const start = SRC.indexOf('const FAITHFULNESS_JUDGE_SYSTEM = `');
  expect(start, 'константа промпта не найдена').toBeGreaterThan(-1);
  const end = SRC.indexOf('`;', start);
  expect(end, 'промпт не закрыт').toBeGreaterThan(start);
  return SRC.slice(start, end);
}

describe('рубрика судьи: третий исход для общего знания вне контекста', () => {
  const prompt = promptBody();

  it('называет границу явно: место-специфичное против общего', () => {
    expect(prompt).toMatch(/МЕСТО-СПЕЦИФИЧН/);
    expect(prompt).toMatch(/ОБЩЕИЗВЕСТН/);
  });

  it('приводит ИМЕННО те три случая, что разошлись в прогоне 12 — не абстракцию', () => {
    // Не проверяем точную формулировку — судья не читает регэксп — но каждый
    // из трёх сценариев обязан быть узнаваем в примерах рубрики.
    expect(prompt).toMatch(/112/);
    expect(prompt).toMatch(/горн[а-яё]* болезн/i);
    expect(prompt).toMatch(/кипят[а-яё]* вод/i);
  });

  it('пункт 5 прямо говорит не штрафовать общий совет за отсутствие в контексте', () => {
    const five = prompt.slice(prompt.indexOf('5 —'), prompt.indexOf('3 —'));
    expect(five).toMatch(/не штрафуй/);
  });

  it('пункт 1 явно исключает общий совет, а не оставляет случай неназванным', () => {
    const one = prompt.slice(prompt.indexOf('1 —'));
    expect(one).toMatch(/НИКОГДА не попадает|никогда не попадает/i);
  });

  it('жёсткий штраф (§ОСОБО ЖЁСТКО) сужен до место-специфичных фактов', () => {
    // До правки штрафовалась ЛЮБАЯ выдумка безопасности — в том числе то
    // самое общее знание, которое пункт 5 теперь прямо разрешает. Останься
    // штраф широким, он противоречил бы пункту 5 в том же промпте.
    const penalty = prompt.slice(prompt.indexOf('ОСОБО ЖЁСТКО'), prompt.indexOf('Честное'));
    expect(penalty).toMatch(/МЕСТО-СПЕЦИФИЧН/);
  });
});
