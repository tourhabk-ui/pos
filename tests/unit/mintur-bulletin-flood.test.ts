/**
 * Сводка Минтура 25.09 — паводок и запрет сплавов доходят до ленты.
 *
 * Текст ниже — ЖИВАЯ еженедельная сводка о доступности туристических объектов,
 * переданная владельцем 25.09 (эмодзи источника оставлены как есть: разборщик
 * обязан их пережить). До правки из пяти пунктов разборщик достал ОДИН —
 * медведей. Паводок на четырёх реках, «опасное гидрологическое явление» и
 * прямое «сплавы на рафтах … необходимо исключить» терялись целиком: список
 * знал «уровень воды», но не «уровней воды», не знал «разлив» и
 * «гидрологическое явление», а в запрете не было ни слова «турист», ни
 * глагола из списка.
 *
 * Сторож держит:
 * 1. паводковые пункты распознаны как flood;
 * 2. запрет сплавов приложен к паводку: красный уровень и текст запрета;
 * 3. пункт с Большой Воровской получает западную зону — река в карте;
 * 4. медведи по-прежнему на месте, а косатки (правило поведения, не угроза)
 *    тревогой не становятся;
 * 5. ложные друзья: «не исключается сход лавин» и «разлив нефтепродуктов» —
 *    не запрет и не паводок.
 */
import { describe, it, expect } from 'vitest';
import {
  classifyMchsItems, classifyMchsItem, addressesTouristsWithBan, declaresHazardGrade, mchs_zones,
} from '@/lib/services/safety/seismic-parser';

const TITLE = 'Еженедельная оперативная сводка о доступности туристических объектов';
const BULLETIN = `Перед поездкой по Камчатке обязательно проверьте актуальную обстановку.

\u{1F4A7}25–27 сентября на отдельных территориях края ожидаются осадки. На реках сохраняется подъём уровней воды.

Ожидаются разливы на реках Начилова и Большая Быстрая. На Амчигаче прогнозируется уровень категории неблагоприятного гидрологического явления, на Большой Воровской – уровень, близкий к критерию опасного гидрологического явления.

❗️Сплавы на рафтах и резиновых лодках по рекам зоны предупреждения необходимо исключить.

В Авачинском заливе при морских экскурсиях необходимо соблюдать дистанцию не менее 200 метров до косаток. Преследовать животных и перекрывать им путь запрещено.

В Петропавловск-Камчатском, Вилючинском и Елизовском округах сохраняется режим повышенной готовности из-за угрозы выхода медведей в населённые пункты.

ВАЖНО!
Планируя путешествие, будьте внимательны, соблюдайте рекомендации спасательных служб и не пренебрегайте действующими ограничениями. Ответственное отношение к безопасности – важная часть любого путешествия.

Полная оперативная информация о доступности туристических объектов – на сайте министерства туризма Камчатского края.`;

const events = classifyMchsItems('kamgov/2509', TITLE, BULLETIN, '2026-09-25T10:00:00Z', 'https://kamgov.ru/mintur', 'kamgov');
const floods = events.filter((e) => e.alert_type === 'flood');

describe('живая сводка 25.09', () => {
  it('паводок распознан, а не потерян', () => {
    expect(floods.length).toBeGreaterThanOrEqual(1);
    expect(floods.some((e) => /Воровск/.test(e.description))).toBe(true);
  });

  it('пункт о реках — западная зона (Большая Воровская в карте)', () => {
    const rivers = floods.find((e) => /Воровск/.test(e.description))!;
    expect(rivers.affected_zones).toContain('western');
    // Петропавловск в этом пункте не упоминается — чужой зоны быть не должно.
    expect(rivers.affected_zones).not.toContain('avachinsky');
  });

  it('запрет сплавов приложен к пункту о реках: красный уровень и сам текст', () => {
    const rivers = floods.find((e) => /Воровск/.test(e.description))!;
    expect(rivers.severity).toBe(2);
    expect(rivers.description).toMatch(/Сплавы на рафтах .* исключить/);
  });

  it('пункт без зоны («осадки на отдельных территориях») запрет не забирает — один пуш, не два', () => {
    const general = floods.filter((e) => e.affected_zones.length === 0);
    for (const g of general) {
      expect(g.description).not.toMatch(/Сплавы/);
      expect(g.severity).toBeLessThan(2);
    }
    expect(floods.filter((e) => e.severity >= 2)).toHaveLength(1);
  });

  it('медведи на месте, косатки тревогой не стали', () => {
    const bear = events.find((e) => e.alert_type === 'bear');
    expect(bear?.affected_zones).toContain('avachinsky');
    expect(events.some((e) => /косат/i.test(`${e.title} ${e.description}`))).toBe(false);
  });
});

describe('слова паводка и запрета', () => {
  it('«подъём уровней воды», «разливы на реках», «гидрологическое явление» — flood', () => {
    for (const t of [
      'На реках сохраняется подъём уровней воды.',
      'Ожидаются разливы на реках Начилова и Большая Быстрая.',
      'На Амчигаче прогнозируется уровень категории неблагоприятного гидрологического явления.',
    ]) {
      expect(classifyMchsItem('x', '', t, '2026-09-25T10:00:00Z', '', 'kamgov')?.alert_type, t).toBe('flood');
    }
  });

  it('«опасного гидрологического явления» — высший разряд; «неблагоприятного» — нет', () => {
    expect(declaresHazardGrade('уровень, близкий к критерию опасного гидрологического явления')).toBe(true);
    expect(declaresHazardGrade('уровень категории неблагоприятного гидрологического явления')).toBe(false);
  });

  it('«сплавы … исключить» — запрет; «не исключается» и «за исключением» — нет', () => {
    expect(addressesTouristsWithBan('Сплавы на рафтах по рекам зоны предупреждения необходимо исключить.')).toBe(true);
    expect(addressesTouristsWithBan('Туристам: не исключается сход лавин на склонах.')).toBe(false);
    expect(addressesTouristsWithBan('Маршруты открыты для туристов, за исключением района вулкана.')).toBe(false);
    expect(addressesTouristsWithBan('Сплав возможен, не исключить подъём воды к выходным.')).toBe(false);
  });

  it('разлив нефтепродуктов — не паводок', () => {
    const ev = classifyMchsItem('x', '', 'В бухте произошёл разлив нефтепродуктов, ведутся работы.', '2026-09-25T10:00:00Z', '', 'kamgov');
    expect(ev?.alert_type).not.toBe('flood');
  });

  it('река без источника места зоны не получает — не угадываем', () => {
    // Просто «Быстрая» — тёзка у Эссо: зона по одному имени была бы догадкой.
    expect(mchs_zones('Ожидаются разливы на реке Быстрой.')).toEqual([]);
    expect(mchs_zones('Разлив на реке Большая Воровская.')).toEqual(['western']);
  });

  it('Амчигача (и «Амчагача»), Начилова, Большая Быстрая — Усть-Большерецкий район, западная зона (владелец 25.09)', () => {
    for (const t of [
      'На Амчигаче прогнозируется подъём', 'уровень на реке Амчагача', 'разливы на реке Начилова',
      'разливы на реке Большая Быстрая', 'уровень воды в Большой Быстрой растёт',
    ]) {
      expect(mchs_zones(t), t).toEqual(['western']);
    }
  });
});

describe('реки без зоны — запрет всё равно не теряется', () => {
  it('паводок только на невнесённой реке — запрет ложится на пункт без зоны', () => {
    const text = [
      'Ожидаются разливы на реке Быстрой, уровень воды растёт.',
      'Сплавы на рафтах по рекам зоны предупреждения необходимо исключить.',
    ].join('\n');
    const ev = classifyMchsItems('kamgov/y', TITLE, text, '2026-09-25T10:00:00Z', '', 'kamgov');
    const f = ev.find((e) => e.alert_type === 'flood');
    expect(f?.affected_zones).toEqual([]);
    expect(f?.severity).toBe(2);
    expect(f?.description).toMatch(/исключить/);
  });
});

describe('запрет без паводка ни к чему не прикладывается', () => {
  it('сводка с одним запретом сплава и медведями — паводка не появляется', () => {
    const text = [
      'Сплавы на рафтах по рекам края необходимо исключить до особого распоряжения.',
      'В Елизовском округе сохраняется режим повышенной готовности из-за выхода медведей в населённые пункты.',
    ].join('\n');
    const ev = classifyMchsItems('kamgov/x', TITLE, text, '2026-09-25T10:00:00Z', '', 'kamgov');
    expect(ev.some((e) => e.alert_type === 'flood')).toBe(false);
  });
});
