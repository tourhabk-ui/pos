/**
 * Маршрут против подборки: разделение до сведения данных.
 *
 * Аудит 11.08 дал отрывы точек от собственной линии в 357–368 км — это длина
 * полуострова. «Горные вершины», «Побережье Тихого океана», «Рыбалка на
 * Камчатке» с двадцатью двумя точками по всему краю — не маршруты, а
 * тематические подборки мест. У них нет пути по смыслу, и проецировать их
 * точки на линию бессмысленно: линия описывает один район, точки — весь край.
 *
 * Разделять надо ДО единого слоя. Иначе реестр честно запишет геометрию
 * объекту, у которого пути нет вовсе, и закрепит бессмыслицу вместо того,
 * чтобы её убрать.
 *
 * Правило берётся существующее — то самое, что уже не даёт предлагать «идти
 * по маршруту» на экране выбора. Второе правило об одном и том же разошлось бы
 * с первым: это мы уже проходили с чисткой алертов, где SQL-копия отстала от
 * TS-стража на один глагол и держала запрет на трети справочника.
 */
import { describe, it, expect } from 'vitest';
import { readFileSync } from 'node:fs';
import { join } from 'node:path';
import {
  isScatteredCollection, boundingSpanKm, maxSegmentKm,
} from '@/lib/routes/geometry-compact';

/** Компактный пеший маршрут: Авачинский перевал, всё в пределах десятка км. */
const REAL_ROUTE: Array<[number, number]> = [
  [53.2560, 158.8300], [53.2600, 158.8340], [53.2650, 158.8390],
  [53.2700, 158.8450], [53.2760, 158.8520], [53.2820, 158.8600],
];

/** Подборка: Петропавловск, Эссо, Ключи, Курильское озеро — весь край. */
const COLLECTION: Array<[number, number]> = [
  [53.0195, 158.6483], [55.9300, 158.6900], [56.3200, 160.8400], [51.4500, 157.1200],
];

/**
 * Растянутый набор без длинных прыжков: пляж → визит-центр → смотровая.
 * Каждый шаг меньше порога, а край накрывает шире — случай владельца.
 */
const STRETCHED: Array<[number, number]> = [
  [53.0200, 158.6500], [53.1000, 158.7500], [53.1800, 158.8600], [53.2500, 158.9800],
];

describe('правило отличает путь от набора мест', () => {
  it('компактный маршрут — не подборка', () => {
    expect(isScatteredCollection(REAL_ROUTE)).toBe(false);
  });

  it('точки по всему краю — подборка', () => {
    expect(isScatteredCollection(COLLECTION)).toBe(true);
    // Габарит соизмерим с полуостровом — ровно то, что показал аудит.
    expect(boundingSpanKm(COLLECTION)).toBeGreaterThan(300);
  });

  it('ловится и без единого длинного прыжка — по габариту', () => {
    // Иначе «каждый шаг короткий» проходило бы за маршрут, накрывая полкрая.
    expect(maxSegmentKm(STRETCHED)).toBeLessThan(25);
    expect(isScatteredCollection(STRETCHED)).toBe(true);
  });

  it('одна точка и пустота — не подборка и не маршрут, судить не о чем', () => {
    // Пустое множество, объявленное подборкой, — то же «0 вместо неизвестно».
    expect(isScatteredCollection([])).toBe(false);
    expect(isScatteredCollection([[53, 158]])).toBe(false);
    expect(isScatteredCollection(null)).toBe(false);
  });
});

describe('перепись судит подборки тем же правилом, что и экран', () => {
  const audit = readFileSync(join(process.cwd(), 'lib/routes/geometry-audit.ts'), 'utf-8');

  it('аудит зовёт существующее правило, а не заводит свой порог', () => {
    expect(audit).toMatch(/from '@\/lib\/routes\/geometry-compact'/);
    // Своих километровых порогов в аудите быть не должно: разойдутся.
    expect(audit).not.toMatch(/25\s*\)/);
  });

  it('подборка определяется РАНЬШЕ расхождения линии и точек', () => {
    // Иначе объект без пути по смыслу попадёт в «конфликтующие маршруты» и
    // будет числиться чинимым — а чинить там нечего, там другая сущность.
    const collIdx = audit.indexOf('collections += 1');
    const conflIdx = audit.indexOf('conflicting += 1');
    expect(collIdx).toBeGreaterThan(-1);
    expect(conflIdx).toBeGreaterThan(-1);
    expect(collIdx).toBeLessThan(conflIdx);
  });

  it('в переписи видно, по чему опознана подборка', () => {
    // «Подборок 40» без разбора не даёт решить, что с ними делать: разброс
    // точек и разброс самой линии — разные починки.
    expect(audit).toMatch(/collections_by_waypoints/);
    expect(audit).toMatch(/collections_by_geometry/);
  });
});
