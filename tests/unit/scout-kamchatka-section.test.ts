/**
 * tests/unit/scout-kamchatka-section.test.ts
 *
 * Раздел «Камчатка» не расширяется до Дальнего Востока.
 *
 * ── Что видно в выпуске 08.09 ──────────────────────────────────────────────
 *
 * Впервые с 06.09 раздел «Камчатка» не пуст. Единственный пункт в нём —
 * «Правительство России: расширение границ территорий опережающего развития на
 * Дальнем Востоке». Источник этого сигнала — `tg_government_rus`, и он заведён
 * с категорией `travel`, а не `kamchatka`: в камчатский раздел его перенёс
 * синтез, а не разметка источников.
 *
 * Само по себе это не выдумка: федеральное решение по ДФО МОЖЕТ касаться края.
 * Но в сигнале Камчатка не названа, и «может касаться» — это домысел, поданный
 * под заголовком раздела как факт о регионе.
 *
 * ── Почему это не мелочь ───────────────────────────────────────────────────
 *
 * Живых источников камчатской категории осталось ДВА: `tg_mchs_official`
 * (МЧС России — федеральный) и наш собственный safety-слой (сейсмика, вулканы,
 * дороги, пожары — настоящие камчатские данные, но только события
 * безопасности). Все четыре региональные ленты умерли: kamgov и 41.mchs сняли
 * RSS 01.08, kamchatka.aif.ru отдаёт HTML вместо ленты.
 *
 * То есть новостного источника о крае у нас нет вовсе. Раздел, который в такой
 * ситуации наполняется соседним регионом, сообщает владельцу «в крае что-то
 * происходит» вместо правды «нам нечем смотреть за краем» — и снимает вопрос,
 * который на самом деле открыт. Пустой раздел был честнее.
 *
 * ── Что держит сторож ──────────────────────────────────────────────────────
 *
 * Запрет подмены региона в промпте синтеза и явное указание, что пустой раздел
 * лучше расширенного. Разрешение промолчать здесь уже было (правило про
 * нулевой раздел) — не было запрета дотянуться до соседа.
 */
import { describe, it, expect } from 'vitest';
import { readFileSync } from 'node:fs';
import { join } from 'node:path';

const SRC = readFileSync(join(process.cwd(), 'lib/agents/scout-digest.ts'), 'utf-8');
// Состав переехал в чистый модуль 08.09 (§12: копия списка в раннере подбора
// разошлась с оригиналом за сутки). Утверждения про разметку источников
// остаются теми же — меняется только файл, где их проверять.
const ROSTER = readFileSync(join(process.cwd(), 'lib/agents/scout-sources.ts'), 'utf-8');

/** Системный промпт синтеза — судим его, а не комментарии вокруг. */
const PROMPT = SRC.slice(
  SRC.indexOf('Ты разведчик туристической платформы TourHab'),
  SRC.indexOf('Формат ответа — только HTML для Telegram'),
);

describe('подмена региона запрещена явно', () => {
  it('сказано, что соседний регион — не Камчатка', () => {
    expect(PROMPT).toMatch(/СОСЕДНИЙ РЕГИОН — НЕ КАМЧАТКА/);
  });

  it('перечислены именно те формулировки, которыми подмена и происходит', () => {
    expect(PROMPT).toMatch(/Дальний Восток/);
    expect(PROMPT).toMatch(/федеральный округ/);
    expect(PROMPT).toMatch(/ДФО/);
  });

  it('запрещено додумывать вхождение края в округ', () => {
    // «Наверняка Камчатка входит» — это домысел, поданный как факт о регионе.
    expect(PROMPT).toMatch(/не додумывай, что край сюда входит/);
  });

  it('пустой раздел назван честнее расширенного', () => {
    expect(PROMPT).toMatch(/Пустой раздел уже разрешён выше и честнее расширенного/);
  });

  it('прежнее разрешение промолчать не потеряно', () => {
    // Запрет дотягиваться до соседа имеет смысл только вместе с правом
    // оставить раздел пустым. Одно без другого — тупик для синтеза.
    expect(PROMPT).toMatch(/Раздел, в котором буквально ноль материалов, НЕ ПИШИ ВОВСЕ/);
  });
});

describe('источники камчатской категории — то, чем раздел живёт на самом деле', () => {
  it('федеральные каналы заведены как travel, а не как камчатские', () => {
    // Разметка верная, и менять её нельзя: новость Правительства не становится
    // камчатской оттого, что нам нужен раздел.
    expect(ROSTER).toMatch(/key: 'tg_government_rus'[^}]*category: 'travel'/);
    expect(ROSTER).toMatch(/key: 'tg_mintrans'[^}]*category: 'travel'/);
  });

  it('свой safety-слой остаётся камчатским источником', () => {
    // Единственный источник в этом разделе, который правда о крае и правда наш.
    expect(ROSTER).toMatch(/SAFETY_LAYER_SOURCE[\s\S]{0,200}category: 'kamchatka'/);
  });
});
