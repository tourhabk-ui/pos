/**
 * Сторож реестра невлитых веток (docs/BRANCH_REGISTRY.md).
 *
 * ── Зачем реестр вообще ────────────────────────────────────────────────────
 *
 * Невлитых веток накопилось 44, и по имени ветки отличить брошенную работу от
 * одноразового пульта нельзя. Пока это неизвестно, каждая читается как
 * «где-то лежит несделанное»; по факту из 34 разобранных несделанным
 * оказалось ровно одно.
 *
 * Ветки при этом НЕ удалены — удалён вопрос о них. Реестр и есть закрытие
 * вопроса.
 *
 * ── Зачем сторож ───────────────────────────────────────────────────────────
 *
 * Документ, который никто не проверяет, живёт дольше кода и начинает врать
 * молча — тот же класс, что докстрока `s3.ts` про несуществующий fallback на
 * /tmp. Здесь держатся две связки, обе самоустаревающие.
 *
 * 1. У КАЖДОЙ строки есть SHA. SHA — единственный способ вернуть ветку, если
 *    её всё же снесут (`git push origin <sha>:refs/heads/<имя>`). Строка без
 *    него превращает реестр из механизма в перечень имён.
 *
 * 2. Раздел «НЕ УДАЛЯТЬ» перечисляет файлы, которых в `main` НЕТ — этим он и
 *    обоснован. Появится хоть один — значит идея дошла, и запись обязана
 *    уйти. Тест краснеет ИМЕННО тогда, когда реестр перестал быть правдой, а
 *    не когда кто-то тронул документ.
 */
import { describe, it, expect } from 'vitest';
import { existsSync, readFileSync } from 'node:fs';
import { join } from 'node:path';

const ROOT = process.cwd();
const DOC = 'docs/BRANCH_REGISTRY.md';
const md = readFileSync(join(ROOT, DOC), 'utf-8');

/** Строки таблиц: | `ветка` | `sha` | дата | */
function rows(): Array<{ branch: string; sha: string }> {
  const out: Array<{ branch: string; sha: string }> = [];
  for (const line of md.split('\n')) {
    const m = /^\|\s*`([^`]+)`\s*\|\s*`([^`]+)`\s*\|/.exec(line);
    if (m) out.push({ branch: m[1]!, sha: m[2]! });
  }
  return out;
}

/**
 * Файлы, отсутствие которых в `main` и есть основание раздела «НЕ УДАЛЯТЬ».
 * Список ЗАМОРОЖЕН и может только сокращаться — вместе с самой записью.
 */
const IDEA_FILES_ABSENT_FROM_MAIN = [
  'lib/navigation/handoff.ts',
  'lib/routes/unify.ts',
  'components/shared/NavigateTo.tsx',
  'migrations/847_route_geometry_registry.sql',
  'tests/unit/navigation-handoff.test.ts',
];

describe('реестр веток остаётся механизмом, а не перечнем имён', () => {
  it('реестр не опустел', () => {
    // Пустой реестр зеленел бы на всех проверках ниже — и это была бы
    // «проверка без исхода „не смог“».
    expect(rows().length).toBeGreaterThan(30);
  });

  it('у каждой строки есть SHA — путь возврата', () => {
    const bad = md.split('\n')
      .filter((l) => /^\|\s*`/.test(l))
      .filter((l) => !/^\|\s*`[^`]+`\s*\|\s*`[0-9a-f]{7,40}`\s*\|/.test(l));
    expect(bad, `строка реестра без SHA — ветку по ней не вернуть:\n${bad.join('\n')}`).toEqual([]);
  });

  it('имена веток не повторяются', () => {
    const names = rows().map((r) => r.branch);
    expect(names.length).toBe(new Set(names).size);
  });

  it('сказано, что ветки НЕ удалены, и почему', () => {
    // Реестр, потерявший это, прочитается как отчёт об удалении.
    expect(md).toMatch(/не удалены/i);
    expect(md).toMatch(/403/);
  });
});

describe('запись «НЕ УДАЛЯТЬ» самоустаревающая', () => {
  it('раздел на месте, пока идея не дошла', () => {
    expect(md).toContain('wip/unified-route-geometry');
  });

  it('названные файлы действительно отсутствуют в main', () => {
    /**
     * Появился файл — идея дошла, и запись «работа НЕ дошла» стала ложью.
     * Тогда её убирают из реестра ВМЕСТЕ с записью в списке выше: реестр,
     * который только растёт, через полгода снова станет вопросом.
     */
    const landed = IDEA_FILES_ABSENT_FROM_MAIN.filter((f) => existsSync(join(ROOT, f)));
    expect(
      landed,
      'эти файлы появились в main — значит идея unified-route-geometry дошла, '
      + 'и запись «НЕ УДАЛЯТЬ» должна уйти из docs/BRANCH_REGISTRY.md вместе с ними: '
      + landed.join(', '),
    ).toEqual([]);
  });

  it('основание записи названо, а не подразумевается', () => {
    for (const f of IDEA_FILES_ABSENT_FROM_MAIN.slice(0, 3)) {
      expect(md, `${f} не назван в реестре — основание записи непроверяемо`).toContain(f);
    }
  });
});
