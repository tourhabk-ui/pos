/**
 * Сторож номеров миграций.
 *
 * ── Что нашлось 15.09 ─────────────────────────────────────────────────────
 *
 * В `migrations/` оказались ДВЕ миграции с номером 969: `969_booking_pd_
 * consent.sql` и `969_razdolie_repair_live_record.sql`. Написаны они разными
 * сессиями в один день, и каждая честно взяла «max + 1» — просто max на
 * момент написания у них был один и тот же.
 *
 * Перепись показала, что случай не первый: одинаковый номер носят 26 групп
 * файлов, от 060 до 969. То есть это не свежая ошибка, а привычка, которую
 * до сих пор ничто не ловило.
 *
 * ── Чем это опасно ────────────────────────────────────────────────────────
 *
 * Раннер применяет файлы по ИМЕНИ, и при равном номере порядок между
 * тёзками решает алфавит суффикса — то есть случайность. Пока тёзки трогают
 * разные таблицы, порядок не значит ничего. Но пара, где вторая заполняет
 * колонку, добавленную первой, сломается молча и ТОЛЬКО на чистой базе: на
 * проде, где обе давно применены, всё выглядит рабочим.
 *
 * ── Почему прошлое заморожено списком, а не разобрано ─────────────────────
 *
 * Каждая из 26 пар уже применена на проде и записана в `_migrations` по
 * имени. Переименование завело бы там вторую строку и прогнало миграцию
 * заново — безвредно (идемпотентность обязательна), но это правка истории
 * ради красоты номера.
 *
 * Причин к каждой паре здесь НЕТ намеренно. Я их не знаю: пары написаны
 * разными сессиями в разные месяцы, и сочинить по строке объяснения к
 * каждой значило бы заполнить выдумкой место, где честный ответ — «не
 * знаю» (§4.0). Список — это перепись факта, а не реестр решений.
 *
 * Список может только СОКРАЩАТЬСЯ: новый номер-тёзка обязан краснеть.
 */

import { describe, it, expect } from 'vitest';
import { readdirSync } from 'node:fs';
import { join } from 'node:path';

const DIR = join(process.cwd(), 'migrations');

/** Номера, у которых тёзки уже уехали на прод (перепись 15.09). */
const FROZEN_COLLISIONS = new Set([
  '060', '064', '065', '080', '084', '085', '086', '110', '111',
  '687', '847', '863', '864', '902', '903', '911', '917', '918',
  '919', '920', '925', '928', '940', '943', '961', '969',
]);

function byNumber(): Map<string, string[]> {
  const map = new Map<string, string[]>();
  for (const f of readdirSync(DIR).filter(f => /^\d+_.*\.sql$/.test(f)).sort()) {
    const n = f.slice(0, f.indexOf('_'));
    map.set(n, [...(map.get(n) ?? []), f]);
  }
  return map;
}

function collisions(): Map<string, string[]> {
  return new Map([...byNumber()].filter(([, files]) => files.length > 1));
}

describe('номер миграции уникален', () => {
  it('новых столкновений номеров нет', () => {
    const fresh = [...collisions().entries()]
      .filter(([n]) => !FROZEN_COLLISIONS.has(n))
      .map(([n, files]) => `${n}: ${files.join(', ')}`);

    expect(
      fresh,
      'Номер уже занят. Следующий считают ПОСЛЕ слияния с main '
      + '(`git merge origin/main && ls migrations | tail -1`), а не до: '
      + '15.09 две сессии, увидев занятым 971, независимо шагнули на 972 — '
      + 'каждая по своему устаревшему каталогу. Переименование само по себе '
      + 'от столкновения не спасает, спасает свежий каталог.',
    ).toEqual([]);
  });

  it('перепись не переживает свои файлы: исчезли тёзки — уходит и запись', () => {
    const live = collisions();
    const stale = [...FROZEN_COLLISIONS].filter(n => !live.has(n));
    expect(
      stale,
      'Эти номера записаны как столкновения, но тёзок в каталоге больше нет — '
      + 'уберите их из FROZEN_COLLISIONS.',
    ).toEqual([]);
  });

  it('список столкновений может только сокращаться', () => {
    // Перепись 15.09: двадцать шесть номеров, и список с тех пор не вырос.
    //
    // Столкновение на 972 (две сессии, увидев занятым 971, независимо шагнули
    // на один и тот же следующий) сюда НЕ записано намеренно: оно разрешено
    // переименованием — эта миграция ушла на свободный номер. Дописать его
    // было бы проще и означало бы, что сторож учит обходить себя.
    expect(FROZEN_COLLISIONS.size).toBeLessThanOrEqual(26);
  });
});
