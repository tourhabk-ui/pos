/**
 * Жанр, а не тема: что МЧС публикует каждый день — не запрет.
 *
 * Перепись вердиктов на проде 10.08 дала «Не сегодня» на 144 маршрутах из 421,
 * и причина у всех была одна: «На контроле ЦУКС ГУ МЧС России по Камчатскому
 * краю по состоянию на 06.00». Это суточная сводка. Она приходит каждый день —
 * значит запрет срабатывал бы каждый день, и вердикт стал бы вечно красным.
 * Вердикт одного цвета перестают читать; это тот же дефект, что зелёная плашка
 * из нуля данных, только с обратным знаком.
 *
 * Рядом лежал второй жанр — репортаж «спасатели окажут помощь тургруппе в
 * наведении верёвочной переправы»: опасность там уже наступила, ею уже
 * занимаются, и завтрашнему туристу она ничего не запрещает.
 *
 * Тексты ниже — настоящие, снятые пробой с прода, а не выдуманные.
 */
import { describe, it, expect } from 'vitest';
import {
  classifyMchsItem, addressesTouristsWithBan, isDailyBulletin, isRescueOperationReport,
} from '@/lib/services/safety/seismic-parser';

const PUB = 'Mon, 11 Aug 2026 06:00:00 +1200';
const classify = (title: string, desc: string) =>
  classifyMchsItem('x', title, desc, PUB, 'https://25.mchs.gov.ru/x');

// ── Настоящие заголовки с прода (проба 10.08) ────────────────────────────────

const CUKS = 'На контроле ЦУКС ГУ МЧС России по Камчатскому краю по состоянию на 06.00 (кмч) 11.08.2026 г.';
const CUKS_BODY = [
  'Оперативная обстановка на территории Камчатского края.',
  'Прогнозируется усиление ветра до 20 м/с, очень сильный дождь.',
  'Сохраняется риск схода оползней с вулкана Мутновского.',
  'Тургруппам рекомендовано воздержаться от выхода на маршруты.',
  'Единый номер вызова экстренных служб — 112.',
].join('\n');

const FORECAST = 'ОПЕРАТИВНЫЙ ЕЖЕДНЕВНЫЙ ПРОГНОЗ ЧС на 11 августа 2026 г.';
const FORECAST_BODY =
  'Прогнозируется вероятность возникновения ЧС, связанных с усилением ветра и сильными осадками. '
  + 'Туристам рекомендуется воздержаться от выхода на маршруты в горной местности.';

const RESCUE = 'На Камчатке сводная группировка спасателей окажет помощь тургруппе в наведении '
  + 'верёвочной переправы через реку и обеспечит безопасность при переходе через водную преграду';
const RESCUE_BODY = 'По сообщению заявителя, зарегистрированная тургруппа не может продолжить '
  + 'маршрут из-за подъёма воды. Спасатели окажут помощь в наведении переправы.';

// ── Настоящие предупреждения, которые обязаны выжить ─────────────────────────

const METEO = 'Экстренное предупреждение на 11 августа 2026 г. (опасное метеорологическое явление)';
const METEO_BODY = 'Ожидается очень сильный дождь, местами шквалистое усиление ветра до 25 м/с.';

const MUTNOVSKY = 'Сохраняется риск схода оползней и обвалов с вулкана Мутновского';
const MUTNOVSKY_BODY = 'Спасатели настоятельно рекомендуют не приближаться к исполину.';

const CYCLONE = 'К берегам Камчатки приближается охотоморский циклон: спасатели рекомендуют '
  + 'соблюдать меры предосторожности';
const CYCLONE_BODY = 'Ожидается очень сильный дождь. Тургруппам рекомендуется воздержаться '
  + 'от выхода на маршруты.';

describe('суточный бюллетень не запрет', () => {
  it('сводка ЦУКС не становится событием', () => {
    expect(isDailyBulletin(CUKS)).toBe(true);
    expect(classify(CUKS, CUKS_BODY)).toBeNull();
  });

  it('ежедневный прогноз ЧС — тоже', () => {
    expect(isDailyBulletin(FORECAST)).toBe(true);
    expect(classify(FORECAST, FORECAST_BODY)).toBeNull();
  });

  it('всё содержательное из сводки приходит отдельными предупреждениями', () => {
    // Ради этого её и можно отбросить без потери знания: проба показала, что
    // тем же фидом пришли и метеопредупреждение, и оползни с Мутновского.
    expect(classify(METEO, METEO_BODY)).not.toBeNull();
    expect(classify(MUTNOVSKY, MUTNOVSKY_BODY)).not.toBeNull();
  });

  it('обычное предупреждение бюллетенем не считается', () => {
    expect(isDailyBulletin(METEO)).toBe(false);
    expect(isDailyBulletin(CYCLONE)).toBe(false);
  });
});

describe('репортаж о спасработах не запрет', () => {
  it('помощь тургруппе на переправе — новость, а не угроза', () => {
    expect(isRescueOperationReport(`${RESCUE} ${RESCUE_BODY}`)).toBe(true);
    expect(classify(RESCUE, RESCUE_BODY)).toBeNull();
  });

  it('тот же жанр в прошедшем времени — тоже новость', () => {
    // Найдено пробой на проде: пока правился один заголовок, в ленту пришёл
    // следующий той же породы — «обеспечила безопасность туристической
    // группы» — и стал ПЕРВОЙ причиной запрета. Жанр один, глаголы разные,
    // и список глаголов будет доопределяться, пока МЧС пишет новости.
    const real = [
      'На Камчатке сводная группировка спасателей обеспечила безопасность туристической группы',
      'Спасатели сопроводили туристов до безопасного места',
      'Спасатели вывели из леса заблудившуюся группу',
    ];
    for (const t of real) {
      expect(isRescueOperationReport(t), t).toBe(true);
      expect(classify(t, ''), t).toBeNull();
    }
  });

  it('но «спасатели рекомендуют» под циклоном — настоящее предупреждение', () => {
    // Ключ — глагол операции, а не слово «спасатели». Иначе страж съел бы
    // ровно тот циклон, ради которого весь слой и чинился 10.08.
    expect(isRescueOperationReport(`${CYCLONE} ${CYCLONE_BODY}`)).toBe(false);
    const ev = classify(CYCLONE, CYCLONE_BODY);
    expect(ev).not.toBeNull();
    expect(ev!.severity).toBeGreaterThanOrEqual(2);
  });
});

describe('запрет ищется во фразе, а не по всему документу', () => {
  it('адресат и запрет в одной фразе — это запрет', () => {
    expect(addressesTouristsWithBan(
      'Тургруппам и охотникам рекомендовано воздержаться от выхода на маршруты.',
    )).toBe(true);
  });

  it('в соседних фразах — тоже: МЧС так пишет', () => {
    // Сузить до одной фразы значило бы потерять настоящий запрет — ошибка в
    // опасную сторону.
    expect(addressesTouristsWithBan(
      'Убедительная просьба к тургруппам. Воздержитесь от выхода на маршруты.',
    )).toBe(true);
  });

  it('повелительное наклонение — тоже запрет', () => {
    // Список ловил «воздержаться», но не «воздержитесь»: прямое повеление МЧС
    // проходило мимо порога. Нашлось при сужении окна.
    expect(addressesTouristsWithBan('Туристы, воздержитесь от выхода на маршруты.')).toBe(true);
  });

  it('на разных концах длинного документа — НЕ запрет', () => {
    const far = [
      'Оперативная обстановка на территории Камчатского края стабильная.',
      'Зарегистрированная тургруппа вышла на маршрут в районе Налычево.',
      'Работает горячая линия. Проведены плановые мероприятия.',
      'Населению рекомендовано воздержаться от посещения подвальных помещений.',
    ].join(' ');
    expect(addressesTouristsWithBan(far)).toBe(false);
  });

  it('точка внутри времени и даты не рвёт фразу', () => {
    // «по состоянию на 06.00 (кмч) 11.08.2026 г.» — если бы делили по каждой
    // точке, окно распалось бы и запрет рядом перестал бы находиться.
    expect(addressesTouristsWithBan(
      'По состоянию на 06.00 (кмч) 11.08.2026 г. тургруппам рекомендовано воздержаться от выхода.',
    )).toBe(true);
  });

  it('устойчивые формулы запрета покрыты', () => {
    // Список проверен формулировками владельца 10.08. «Не рекомендуется» —
    // самая частая формула МЧС, и её в списке не было: она жила только внутри
    // вулканической ветки, то есть «выход тургрупп не рекомендуется» под
    // паводком или циклоном красным не становился.
    const real = [
      'Туристам не рекомендуется выход на маршруты.',
      'Выход тургрупп на маршруты не рекомендуется.',
      'Просим тургруппы воздержаться от выхода.',
      'Туристам необходимо воздержаться от выхода на маршруты.',
      'Запрещается выход тургрупп на маршруты.',
    ];
    for (const phrase of real) {
      expect(addressesTouristsWithBan(phrase), phrase).toBe(true);
    }
  });

  it('просьба зарегистрироваться запретом не становится', () => {
    expect(addressesTouristsWithBan(
      'Тургруппам необходимо зарегистрироваться в МЧС перед выходом на маршрут.',
    )).toBe(false);
  });
});

describe('прежние жанровые стражи на месте', () => {
  const cases: Array<[string, string, string]> = [
    ['телеанонс', 'Эксперименты сотрудников лаборатории — в новом выпуске программы «МЧС»', ''],
    ['учение', 'Пожарно-тактическое учение прошло в школе № 40', ''],
    ['памятка', 'При угрозе подтопления дворовых территорий необходимо поднять вещи выше', ''],
  ];
  for (const [name, title, desc] of cases) {
    it(`${name} по-прежнему отбрасывается`, () => {
      expect(classify(title, desc)).toBeNull();
    });
  }
});
