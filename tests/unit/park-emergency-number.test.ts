/**
 * Сторож регионального номера МЧС на экране парка.
 *
 * ── Что случилось (15.09, по снимку владельца) ─────────────────────────────
 *
 * Плитка «112 — Спасение» на карточке парка печатала `МЧС: {park.mchs_phone}`
 * без единой проверки. У Вачкажца (миграция 723) и Кроноцкого (781) номер
 * вставлен как NULL — на экране оставалось «МЧС:» и пустота. Тип этого и не
 * запрещал: API честно объявляет `string | null`, а клиент переписывал поле
 * в `string` (§4.0 — «тип, который не допускает отсутствия, принуждает
 * показать отсутствие как есть»).
 *
 * Пустая подпись оказалась не худшей половиной. У остальных трёх парков в
 * колонке лежат `+7 (4152) 23-53-62` и `+7 (41541) 2-10-33`. Первый назван
 * ПОИМЁННО в шапке `lib/safety/emergency-numbers.ts` среди пяти «номеров
 * МЧС», разъехавшихся по экранам к июлю; владелец 17.07 подтвердить его не
 * смог, и вывод там записан прямо: **показывать неверный номер в ЧП опаснее,
 * чем не показывать ничего** — человек дозвонится не туда и потеряет время.
 *
 * То есть июльская централизация, сделанная ровно из-за этого, до экрана
 * парка не доехала: `parks.mchs_phone` остался ВТОРЫМ источником того же
 * факта. Два источника одного факта — это два разных факта, и здесь цена
 * расхождения измеряется не опрятностью.
 *
 * ── Что держит сторож ─────────────────────────────────────────────────────
 *
 * Не «на экране есть телефон», а то, ОТКУДА он берётся: единственный
 * источник региональных номеров — `VERIFIED_REGIONAL`. Колонка `mchs_phone`
 * из справочника парков в UI не приходит и не печатается; свой номер в
 * разметке не зашит.
 *
 * ── Чего сторож НЕ делает ─────────────────────────────────────────────────
 *
 * Не трогает данные. Значения в `parks.mchs_phone` оставлены как есть:
 * подтвердить телефон экстренной службы может только человек, и стереть
 * запись за него — такое же решение без источника, как её показать.
 * Задача сторожа — чтобы неподтверждённое не доехало до экрана, пока
 * владелец не сказал, что с ним делать.
 */
import { describe, it, expect } from 'vitest';
import { readFileSync } from 'node:fs';
import { join } from 'node:path';
import { VERIFIED_REGIONAL, FEDERAL_EMERGENCY } from '@/lib/safety/emergency-numbers';

const ROOT = process.cwd();
const read = (p: string) => readFileSync(join(ROOT, p), 'utf-8');

/** Исходник без комментариев: разбор в шапке не должен ловиться как код. */
function code(p: string): string {
  return read(p)
    .replace(/\/\*[\s\S]*?\*\//g, '')
    .replace(/\/\/[^\n]*/g, '')
    .replace(/\{\/\*[\s\S]*?\*\/\}/g, '');
}

const CLIENT = code('app/park/[slug]/_ParkClient.tsx');
const API    = code('app/api/parks/[slug]/route.ts');

describe('экран парка берёт номер МЧС из единого источника', () => {
  it('клиент импортирует проверенные региональные номера', () => {
    expect(CLIENT).toMatch(/VERIFIED_REGIONAL.*from '@\/lib\/safety\/emergency-numbers'/);
  });

  it('клиент не читает parks.mchs_phone вовсе', () => {
    // Второй источник того же факта. Именно он показывал неподтверждённый
    // номер трём паркам и пустоту — двум.
    expect(CLIENT).not.toMatch(/mchs_phone/);
  });

  it('API больше не отдаёт эту колонку наружу', () => {
    // Пока поле в ответе, его подхватит следующий экран — и разойдётся
    // ровно так же, как разошлись пять номеров к июлю.
    expect(API).not.toMatch(/mchs_phone/);
  });

  it('номер не зашит в разметку экрана', () => {
    // Захардкоженный телефон — это третий источник, который ещё и не
    // обновится, когда владелец подтвердит настоящий.
    expect(CLIENT).not.toMatch(/\+7\s*\(?\d{4,5}\)?/);
  });
});

describe('пустого исхода на карточке экстренного вызова не бывает', () => {
  it('строка рисуется только при наличии проверенного номера', () => {
    // Условие обязано быть в разметке: без него «МЧС:» и пустота
    // возвращаются при пустом VERIFIED_REGIONAL (§4.0).
    expect(CLIENT).toMatch(/\{REGIONAL_MCHS && \(/);
  });

  it('источник допускает отсутствие, а не притворяется, что номер есть', () => {
    expect(CLIENT).toMatch(/VERIFIED_REGIONAL\[0\] \?\? null/);
  });

  it('112 остаётся на карточке независимо от региональных номеров', () => {
    // Федеральный короткий номер работает без баланса и SIM — он и есть
    // обещание плитки. Региональный номер тут добавка, а не замена.
    expect(CLIENT).toMatch(/112 — Спасение/);
    expect(FEDERAL_EMERGENCY[0]!.phone).toBe('112');
  });
});

describe('источник региональных номеров сам остаётся проверяемым', () => {
  it('в VERIFIED_REGIONAL нет номеров из списка разъехавшихся', () => {
    // Пять номеров, названных в шапке emergency-numbers.ts как показывавшиеся
    // под одной подписью «МЧС». Появление любого из них в проверенном списке
    // означало бы, что июльский разбор отменён молча.
    const DISPUTED = ['235362', '299999', '110505', '411717', '412770'];
    for (const n of VERIFIED_REGIONAL) {
      const digits = n.phone.replace(/\D/g, '');
      for (const bad of DISPUTED) {
        expect(digits.includes(bad), `${n.phone} — номер из спорного списка`).toBe(false);
      }
    }
  });

  it('у каждого проверенного номера названа служба, а не просто «МЧС»', () => {
    // «МЧС: +7...» без указания, чей это пульт, — половина факта: в ЧП важно,
    // попадёшь ты к оперативному дежурному или в приёмную.
    for (const n of VERIFIED_REGIONAL) {
      expect(n.name.length, `${n.phone}: служба не названа`).toBeGreaterThan(10);
    }
  });
});
