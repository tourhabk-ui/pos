/**
 * tests/unit/issue-claim-discipline.test.ts
 *
 * Находку сначала занимают, потом чинят.
 *
 * ── Что случилось 08.09 ────────────────────────────────────────────────────
 *
 * Четыре находки (#1722-#1725) чинились ДВАЖДЫ параллельно, двумя
 * исполнителями. Обе работы дошли до готовых PR: #1728 успел в `main` первым,
 * #1727 остался с конфликтом. Совпали не только правки — совпало имя
 * созданного файла (`tests/unit/kuzmich-no-invention.test.ts`).
 *
 * И это ещё УДАЧНЫЙ исход: оба решения оказались верными и близкими по сути.
 * Разойдись они — в `main` уехало бы одно, а обсуждалось бы другое, и никто
 * не заметил бы подмены.
 *
 * ── Почему правило, а не «быть внимательнее» ───────────────────────────────
 *
 * Соседняя сессия не видит ни твоего плана, ни твоей ветки, ни твоих
 * намерений. «Я же взял» для неё не существует — существует только то, что
 * записано в самой находке. Значит заявка обязана быть комментарием.
 *
 * ── Почему сторож слабый, и это осознанно ──────────────────────────────────
 *
 * Проверить факт заявки в CI нельзя: она живёт в комментариях GitHub, а не в
 * репозитории. Поэтому здесь держится САМО ПРАВИЛО — что оно записано и не
 * потеряется при следующей правке §8, — а столкновение ловит рабочий процесс
 * `issue-claim-check.yml`, который видит другой открытый PR на ту же находку.
 * Он поздний по построению: работа к тому моменту уже сделана. Заявка дешевле,
 * и правило говорит об этом прямо.
 */
import { describe, it, expect } from 'vitest';
import { readFileSync } from 'node:fs';
import { join } from 'node:path';

const CLAUDE_MD = readFileSync(join(process.cwd(), 'CLAUDE.md'), 'utf-8');
const WORKFLOW = readFileSync(join(process.cwd(), '.github/workflows/issue-claim-check.yml'), 'utf-8');

describe('правило записано и не потерялось', () => {
  it('в §8 есть требование занять находку до начала работы', () => {
    expect(CLAUDE_MD).toMatch(/Находку сначала ЗАНИМАЮТ, потом чинят/);
  });

  it('названо, чем это оплачено — иначе правило выглядит бюрократией', () => {
    // Без цены правило снимут при первой же спешке.
    expect(CLAUDE_MD).toMatch(/#1722-#1725/);
    expect(CLAUDE_MD).toMatch(/#1728 успел в `main`\s*\n?\s*первым/);
  });

  it('заявка — комментарием, а не «в голове»', () => {
    expect(CLAUDE_MD).toMatch(/оставить комментарием заявку/);
    expect(CLAUDE_MD).toMatch(/соседняя сессия не видит/);
  });

  it('перед началом положено ПРОЧИТАТЬ чужие заявки', () => {
    // Половина правила без второй половины бесполезна: если заявки только
    // ставят и не читают, столкновения продолжатся.
    expect(CLAUDE_MD).toMatch(/Перед началом.*прочитать комментарии находки/s);
  });

  it('заявка протухает — брошенная не держит находку вечно', () => {
    expect(CLAUDE_MD).toMatch(/Заявка протухает/);
    expect(CLAUDE_MD).toMatch(/Сутки без PR/);
  });
});

describe('поздний сторож существует и знает, что он поздний', () => {
  it('workflow заведён и ищет другой открытый PR на ту же находку', () => {
    expect(WORKFLOW).toMatch(/state=open/);
    expect(WORKFLOW).toMatch(/select\(\.number != \$me\)/);
  });

  it('он предупреждает, а не блокирует', () => {
    // Два PR на одну находку бывают законно: разные части большой задачи,
    // замена заброшенной работы. Решает человек.
    expect(WORKFLOW).toMatch(/::warning::/);
    expect(WORKFLOW).not.toMatch(/::error::/);
    expect(WORKFLOW).not.toMatch(/\bexit 1\b/);
  });

  it('PR без ссылок на находки не поднимает ложную тревогу', () => {
    expect(WORKFLOW).toMatch(/сверять нечего/);
  });

  it('правило и сторож ссылаются друг на друга', () => {
    expect(CLAUDE_MD).toMatch(/issue-claim-check\.yml/);
    expect(WORKFLOW).toMatch(/CLAUDE\.md §8/);
  });
});
