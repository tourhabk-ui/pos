/**
 * Сторож: занятость дня считается ИНТЕРВАЛОМ, и правило одно на всю платформу.
 *
 * ── Как нашлось ────────────────────────────────────────────────────────────
 *
 * Не чтением кода, а вопросом к живому проду через MCP-коннектор. Спросил
 * свободные даты у тура «Многодневный летний тур (5 дней)» — витрина
 * предложила 15, 16, 17, 18 и 19 сентября, каждую по десять мест. Хотя тур,
 * начатый пятнадцатого, занимает всё это окно целиком.
 *
 * Перепись того же дня: из ДЕВЯТИ живых туров ШЕСТЬ многодневные (2, 3, 5, 7
 * и 7 дней), включая недельные по 140-196 тысяч за человека. Речь про две
 * трети каталога, а не про край.
 *
 * ── Почему стало видно только теперь ───────────────────────────────────────
 *
 * До 14.09 обе половины врали ОДИНАКОВО: гейт записывал многодневную бронь
 * однодневной, витрина так же её и считала. Согласованная ложь не бросается в
 * глаза — обе стороны показывали «свободно» и обе пропускали бронь, а платили
 * за это тихой перепродажей мест.
 *
 * #1894 научил считать интервалом ГЕЙТ. Ложь перестала быть согласованной:
 * витрина предлагала дату, гейт на ней отказывал. Строго лучше двойной
 * продажи — но человек видел свободное и упирался в стену.
 *
 * ── Сколько мест оказалось ─────────────────────────────────────────────────
 *
 * ОДИННАДЦАТЬ, а не одно: витрина дат, два листинга доступности, публичное
 * «сейчас», два календаря оператора, поиск туров, планер, агентский подбор,
 * диагностика доступности и внешний канал OCTO. Правило, переписанное
 * одиннадцать раз, — это одиннадцать правил, и они уже разошлись: часть
 * забывала `deleted_at IS NULL`.
 *
 * Календари оператора стоят тут не для полноты: группа на пятидневном
 * маршруте, которой нет в календаре четыре дня из пяти, — это цена, названная
 * ещё в #1894, и на Камчатке она не бухгалтерская.
 *
 * ── Что держится ───────────────────────────────────────────────────────────
 *
 * Не «интервал где-то есть», а ОТСУТСТВИЕ второго правила: ни одного
 * самодельного счёта занятости равенством дат во всей платформе.
 */
import { describe, it, expect } from 'vitest';
import { readdirSync, readFileSync, statSync } from 'node:fs';
import { join } from 'node:path';
import { occupiedOnDaySql, bookingCoversDaySql, FREEING_BOOKING_STATUSES } from '@/lib/bookings/occupancy';

const ROOT = process.cwd();

/** Поверхности, сведённые к общему правилу. Список может только РАСТИ. */
const SURFACES = [
  'app/api/tours/[id]/slots/route.ts',            // витрина дат в форме брони
  'app/api/availability/route.ts',                // листинг доступности
  'app/api/availability/day/route.ts',            // доступность на день
  'app/api/public/now/route.ts',                  // публичное «сейчас»
  'app/api/operator/calendar/route.ts',           // календарь оператора
  'app/api/hub/operator/bookings-calendar/route.ts',
  'app/api/cron/explain-availability/route.ts',   // диагностика «почему занято»
  'app/api/agent/find-tours/route.ts',            // агентский подбор
  'lib/planner/data.ts',                          // планер
  'lib/search/tour-search.ts',                    // поиск туров
  'lib/octo/service.ts',                          // внешний канал
];

describe('правило интервала', () => {
  it('день внутри брони занят, день после — нет', () => {
    const sql = bookingCoversDaySql('ob', 'ta.date');
    expect(sql).toContain('BETWEEN ob.booking_date');
    expect(sql).toContain('COALESCE(ob.end_date, ob.booking_date)');
  });

  it('пустой end_date означает ОДИН день, а не «неизвестно»', () => {
    /**
     * Брони, заведённые до #1894, не имеют `end_date`. Читать их как
     * бесконечные — закрыть календарь навсегда; читать как «не знаем» —
     * выдумать. COALESCE даёт третий, верный ответ: ровно день старта.
     *
     * Проверено на настоящем PostgreSQL 16: бронь без end_date заняла ровно
     * свой день, пятидневная — все пять.
     */
    expect(bookingCoversDaySql('b', '$1::date')).toMatch(/COALESCE\(b\.end_date, b\.booking_date\)/);
  });

  it('счёт возвращает 0, а не NULL, когда броней нет', () => {
    // NULL в сравнении с вместимостью дал бы «мест нет» вместо «все свободны»:
    // отказ там, где всё в порядке.
    expect(occupiedOnDaySql({ booking: 'ob', day: 'ta.date', tourId: 'ta.operator_tour_id' }))
      .toMatch(/COALESCE\(SUM\(ob\.participants\), 0\)/);
  });

  it('снятая бронь места не держит — условие внутри правила, не у вызывающих', () => {
    // Раньше его забывали: часть из одиннадцати мест писала deleted_at, часть нет.
    expect(occupiedOnDaySql({ booking: 'ob', day: 'd', tourId: 't' }))
      .toMatch(/ob\.deleted_at IS NULL/);
  });

  it('предикат статусов — гейта, а не вида', () => {
    /**
     * `v_tour_daily_occupancy` считает только ('new','confirmed').
     * Здесь исключаются лишь отменённые и отклонённые — значит
     * `pending_payment` (оплата начата) место ДЕРЖИТ. Взять предикат вида
     * значило бы показать свободным место, за которое человек в эту минуту
     * платит.
     */
    expect([...FREEING_BOOKING_STATUSES]).toEqual(['cancelled', 'rejected']);
    const sql = occupiedOnDaySql({ booking: 'ob', day: 'd', tourId: 't' });
    expect(sql).toMatch(/NOT IN \('cancelled', 'rejected'\)/);
    expect(sql).not.toMatch(/IN \('new', 'confirmed'\)/);
  });
});

describe('второго правила нет нигде', () => {
  it('все известные поверхности зовут общее правило', () => {
    for (const f of SURFACES) {
      expect(readFileSync(join(ROOT, f), 'utf-8'), `${f} считает занятость сам`)
        .toMatch(/occupiedOnDaySql\(/);
    }
  });

  it('самодельного счёта равенством дат не осталось во всей платформе', () => {
    /**
     * Обход `app/` и `lib/`: подзапрос по `operator_bookings`, где день
     * сравнивается РАВЕНСТВОМ с датой календаря. Именно эта форма и делала
     * многодневную бронь однодневной.
     *
     * Ищется связка «participants + booking_date =», а не одно равенство:
     * `booking_date = $1` в поиске конкретной брони или в напоминании «тур
     * завтра» — законно и к занятости отношения не имеет.
     */
    const bad: string[] = [];
    const walk = (dir: string) => {
      for (const e of readdirSync(join(ROOT, dir), { withFileTypes: true })) {
        const rel = `${dir}/${e.name}`;
        if (e.isDirectory()) { walk(rel); continue; }
        if (!/\.tsx?$/.test(e.name)) continue;
        const src = readFileSync(join(ROOT, rel), 'utf-8');
        if (!/SUM\(\s*\w+\.participants/.test(src)) continue;
        // Равенство дня календаря с booking_date в том же запросе.
        const m = src.match(/\w+\.booking_date\s*=\s*\w+\.date\b/);
        if (m) bad.push(`${rel}: ${m[0]}`);
      }
    };
    walk('app'); walk('lib');
    expect(
      bad,
      'счёт занятости равенством дат — многодневная бронь снова станет однодневной. '
      + 'Правило одно: lib/bookings/occupancy.ts',
    ).toEqual([]);
  });

  it('реестр поверхностей не опустел и не разъехался с файлами', () => {
    // Пустой список зеленел бы на первой проверке, а отсутствующий файл
    // означал бы, что поверхность переименовали и правило за ней не поехало.
    expect(SURFACES.length).toBeGreaterThanOrEqual(11);
    for (const f of SURFACES) {
      expect(statSync(join(ROOT, f)).isFile(), `${f} не найден`).toBe(true);
    }
  });
});
