/**
 * Страница «Связь и навигация» + напоминание про маяк на SOS-экранах.
 *
 * Смысл (31.07): владельцы спутниковых маяков в панике забывают их
 * активировать — напоминание в шагах SOS спасает. Страница подготовки
 * даёт честный рейтинг: «только смартфон без внешней связи — высокий риск».
 *
 * Сторож держит честность обещаний: зону покрытия «Вензора» НЕ рисуем
 * (подтверждённых данных оператора нет), цена аренды — с оговоркой
 * «уточняйте», смартфону не приписывается передача сигнала без сети.
 */
import { describe, it, expect } from 'vitest';
import { readFileSync } from 'node:fs';
import { join } from 'node:path';

const read = (p: string) => readFileSync(join(process.cwd(), p), 'utf-8');

describe('напоминание про маяк на обеих SOS-поверхностях', () => {
  it('/sos: шаг «активируй маяк» есть и стоит до SMS-шага', () => {
    const src = read('app/sos/page.tsx');
    expect(src).toContain('активируй его сейчас');
    expect(src.indexOf('активируй его сейчас')).toBeLessThan(src.indexOf('отправь SMS'));
  });

  it('/emergency: напоминание есть, согласованный баннер не тронут', () => {
    const html = read('public/emergency.html');
    expect(html).toContain('активируй его сейчас');
    // Семантика баннера из #898 — контракт, напоминание её дополняет, не заменяет.
    expect(html).toContain('Позвони 112 и назови координаты или ориентиры.');
    expect(html).toContain('Оставайся на месте и жди помощи.');
  });
});

describe('страница /safety/communication — обещания честные', () => {
  const page = read('app/safety/communication/page.tsx');

  it('зона покрытия «Вензора» не обещается без данных оператора', () => {
    expect(page).toContain('Карту покрытия мы пока не показываем');
    expect(page).toContain('уточняйте у оператора');
  });

  it('смартфону не приписывается передача сигнала без сети', () => {
    expect(page).toContain('Передать сигнал бедствия без покрытия смартфон не может');
  });

  it('«только смартфон» честно назван высоким риском', () => {
    expect(page).toContain('высокий риск');
  });

  it('регистрация МЧС ведёт на официальную форму', () => {
    expect(page).toContain('forms.mchs.gov.ru/registration_tourist_groups/form');
  });

  it('нет скрытой коммерции: страница прямо говорит об отсутствии комиссии', () => {
    expect(page).toContain('не получаем комиссию');
  });
});
