/**
 * PWA открывается полем и не копит кэш без потолка (владелец 13.09).
 *
 * ── Откуда правка ──────────────────────────────────────────────────────────
 *
 * Владелец: «pwa очень тяжелый, зачем там главная страница если используем
 * только для маршрута». Замер `npm run build` в тот же день показал, что
 * главная не при чём: у неё 40.3 КБ своего кода против 62.1 КБ у полевого
 * экрана, и 104 КБ из её First Load — общий для всех страниц baseline.
 * Выкинуть её из прекэша значило бы сэкономить 40 КБ там, где тайлы занимают
 * 6-22 МБ. Тяжесть была в другом, и нашлись ДВА разных дефекта.
 *
 * **Первый — вход.** `start_url` стоял на `/`: приложение, которое ставят
 * ради маршрута, открывалось витриной с «туром недели». Это не килобайты, а
 * то же смешение контуров, которое в тот день чинили с двух других сторон —
 * карта поля показывала весь реестр мест (#1846), приборная строка не знала
 * состояния «ты ещё не на маршруте» (#1847).
 *
 * **Второй — потолок.** У карточек мест, туров и планов эвикция была с самого
 * начала, у `/_next/static/**` — не было вовсе. Имя чанка несёт хеш сборки:
 * после каждого деплоя страница тянет новые файлы, старые остаются навсегда.
 * Единственная уборка — смена `CACHE_NAME` рукой, 22 раза за всю историю.
 * Деплой идёт на каждый пуш в `main`; с прошлой уборки (02.09) их прошло 1301.
 *
 * ── Что держит сторож ──────────────────────────────────────────────────────
 *
 * Не «главная удалена» (её и не надо удалять) — а то, ради чего правка: вход
 * ведёт в поле, стартовый адрес переживает офлайн, у статики есть потолок.
 */
import { describe, it, expect } from 'vitest';
import { readFileSync } from 'node:fs';
import { join } from 'node:path';

const SW = readFileSync(join(process.cwd(), 'public/sw.js'), 'utf-8');
/**
 * Тот же файл без комментариев. Нужен там, где судится ПОВЕДЕНИЕ: первая
 * редакция проверки на `ignoreSearch` поймала слово в пояснении рядом с
 * кодом — то есть покраснела на собственном объяснении, почему его нет.
 */
const SW_CODE = SW.replace(/\/\*[\s\S]*?\*\//g, '').replace(/^\s*\/\/.*$/gm, '');
const MANIFEST = JSON.parse(readFileSync(join(process.cwd(), 'public/manifest.json'), 'utf-8')) as {
  start_url: string;
  scope: string;
};

/** Тело массива по имени — чтобы судить состав, а не совпадение подстроки. */
function arrayBody(name: string): string {
  const start = SW.indexOf(`const ${name} = [`);
  expect(start, `нет массива ${name}`).toBeGreaterThan(-1);
  const end = SW.indexOf('];', start);
  expect(end).toBeGreaterThan(start);
  return SW.slice(start, end);
}

describe('вход в приложение ведёт в поле, а не на витрину', () => {
  it('start_url — полевой экран', () => {
    expect(MANIFEST.start_url).toBe('/planning?mode=trail');
  });

  it('scope остался общим — приложение не заперто в одном экране', () => {
    // Сузить scope до /planning значило бы вышвыривать в браузер переход на
    // карточку места, SOS и каталог. Ставят ради поля, но ходят по всему.
    expect(MANIFEST.scope).toBe('/');
  });

  it('стартовый адрес лежит в прекэше РОВНО в том виде, в каком его просят', () => {
    // `caches.match` зовётся без ignoreSearch (проверено ниже), значит
    // `?mode=trail` — другой ключ кэша. Закэшированный голый `/planning` при
    // запуске с иконки не нашёлся бы, и человек в поле получил бы «нет
    // соединения» вместо кокпита.
    const field = arrayBody('FIELD_URLS');
    expect(field).toMatch(/'\/planning\?mode=trail'/);
    expect(field).toMatch(/'\/planning'/);
  });

  it('полевой вход кэшируется С ПОВТОРАМИ, а не best-effort', () => {
    // FIELD_URLS кладутся с двумя повторами (как критичные), OPTIONAL_URLS —
    // без единого. Стартовому экрану одной попытки мало: сеть моргнула при
    // установке — и входа в приложение офлайн нет вовсе.
    expect(SW).toMatch(/FIELD_URLS\.map\(\(u\) => cacheOne\(cache, u, 2\)\)/);
    expect(arrayBody('OPTIONAL_URLS')).not.toMatch(/'\/planning'/);
  });

  it('поиск в кэше по-прежнему точный — предпосылка проверки выше', () => {
    // Если кто-то добавит ignoreSearch, дубль `/planning?mode=trail` станет
    // лишним, и это надо будет заметить здесь, а не гадать.
    expect(SW_CODE).not.toMatch(/ignoreSearch/);
  });

  it('главная из прекэша НЕ выброшена', () => {
    // Проверено замером: её уникальный код — 40 КБ при 6-22 МБ тайлов.
    // Выбрасывание не дало бы выигрыша, а офлайн-вход по старой иконке
    // (у кого приложение стоит с прежним start_url) сломало бы.
    expect(arrayBody('OPTIONAL_URLS')).toMatch(/'\/'/);
  });
});

describe('кэш статики имеет потолок', () => {
  it('эвикция статики существует и зовётся при каждой укладке чанка', () => {
    expect(SW).toMatch(/async function evictOldStaticAssets\(cache\)/);
    expect(SW).toMatch(/await evictOldStaticAssets\(cache\)/);
  });

  it('потолок взят замером полной сборки, а не на глаз', () => {
    const cap = Number(SW.match(/const MAX_STATIC_ASSETS = (\d+);/)?.[1]);
    // 13.09 `npm run build` дал 1179 файлов .js/.css — это ВСЯ сборка, включая
    // страницы, которые полевой телефон не открывает никогда. Потолок ниже
    // этого числа выбрасывал бы живые чанки текущей сборки; сильно выше —
    // переставал бы быть потолком.
    expect(cap).toBeGreaterThanOrEqual(1179);
    expect(cap).toBeLessThanOrEqual(3000);
  });

  it('чистится ТОЛЬКО статика Next, а не прекэш СОС и не тайлы', () => {
    const body = SW.slice(SW.indexOf('async function evictOldStaticAssets'), SW.indexOf('// LRU-эвикция: удаляем старые карточки мест'));
    expect(body).toMatch(/req\.url\.includes\('\/_next\/static\/'\)/);
    // `/safety/*.js`, Leaflet и иконка лежат вне /_next/static — под нож не
    // попадают по построению. СОС от уборки не зависит.
    expect(body).not.toMatch(/safety|leaflet|emergency/i);
  });

  it('удаляются САМЫЕ СТАРЫЕ записи, а не произвольные', () => {
    // cache.keys() отдаёт в порядке вставки; вставлялись по мере запроса,
    // значит первыми уходят чанки самых старых сборок.
    const body = SW.slice(SW.indexOf('async function evictOldStaticAssets'), SW.indexOf('// LRU-эвикция: удаляем старые карточки мест'));
    expect(body).toMatch(/staticKeys\.slice\(0, staticKeys\.length - MAX_STATIC_ASSETS\)/);
  });

  it('версия кэша поднята — накопленное с прошлой уборки разбирается разово', () => {
    const v = Number(SW.match(/const CACHE_NAME = 'kamchatour-v(\d+)'/)?.[1]);
    expect(v).toBeGreaterThanOrEqual(30);
  });
});
