/**
 * Компас поля — честность и UX (решение владельца 21.08).
 *
 * Четыре черты, которые нельзя потерять правкой:
 *  1. Неподтверждённая стрелка НЕ рисуется — раньше серая стрелка в
 *     абсолютном угле выглядела как живая (прозрачность на солнце не
 *     читается), и человек шёл за ней. Азимут без стрелки говорит число.
 *  2. Курс несёт родословную: «магнитный датчик» или «по движению GPS» —
 *     словами, как род линии на карте (§12).
 *  3. Курс по движению берётся только на ходу и только конечный.
 *  4. Лекарство на приборе: одна кнопка «Включить компас», в строке
 *     статуса второй кнопки того же действия нет (урок SOS #887).
 */
import { describe, it, expect } from 'vitest';
import { readFileSync } from 'node:fs';
import { join } from 'node:path';

const compassSrc = readFileSync(
  join(process.cwd(), 'components/field/FieldCompass.tsx'), 'utf-8',
);
const clientSrc = readFileSync(
  join(process.cwd(), 'app/planning/_PlanningClient.tsx'), 'utf-8',
);

describe('FieldCompass — стрелка только живая', () => {
  it('угол стрелки существует только при подтверждённом азимуте', () => {
    expect(compassSrc).toMatch(/needleAngle = trusted && targetBearing !== null/);
  });

  it('приглушённой стрелки-призрака больше нет', () => {
    expect(compassSrc).not.toMatch(/opacity=\{trusted \? 1 : 0\.3/);
  });

  it('источник курса назван словами', () => {
    expect(compassSrc).toContain('курс — по движению GPS');
    expect(compassSrc).toContain('азимут — магнитный датчик');
    expect(compassSrc).toContain('стрелка скрыта: азимут не подтверждён');
  });
});

describe('полевой экран — курс по движению и одна кнопка', () => {
  it('курс движения берётся только на ходу (порог скорости) и только конечный', () => {
    expect(clientSrc).toMatch(/spd >= 1/);
    expect(clientSrc).toMatch(/Number\.isFinite\(crs\)/);
  });

  it('свежесть курса судится, устаревший не выдаётся за живой', () => {
    expect(clientSrc).toMatch(/nowTick - gpsCourse\.t < 8000/);
  });

  it('кнопка включения — на приборе, и она одна', () => {
    const matches = clientSrc.match(/Включить компас|>\s*Включить\s*</g) ?? [];
    expect(matches).toHaveLength(1);
    expect(clientSrc).toContain('Включить компас');
  });

  it('компас — над картой справа, но НЕ order-хаком и НЕ угаданным fixed-отступом', () => {
    // CSS order-свап (владелец 21.08) снят: компас и геройская цифра
    // больше не делят одно место — у компаса своё постоянное место.
    expect(clientSrc).not.toMatch(/order: figuresLive/);
    // Правка 29.08 №2 (живой скрин владельца): fixed top-28 — угаданный
    // пиксельный отступ — наехал на геройскую цифру, как только плашка
    // статуса оказалась выше предположенного. Обычный поток вместо
    // fixed — высота соседей сама раздвигает компас, коллизия физически
    // невозможна. fixed-угадайка не должна вернуться.
    expect(clientSrc).not.toMatch(/fixed top-28 right-3/);
  });

  it('компас в бейдже — компактный размер, не дефолтный герой-масштаб (300)', () => {
    // size=300 — дефолт FieldCompass, рассчитанный на центр колонки
    // (прежнее место). В бейдже нужен масштаб поменьше, иначе прибор
    // перекрывает половину экрана поверх карты.
    //
    // 01.09: было жёстко 110, владелец в поле — «компас чуть-чуть увеличить,
    // не видно надписей и стрелка теряется». Причина оказалась не в размере:
    // внутри компонента сидели ПИКСЕЛЬНЫЕ константы под эталон 300 (отступ
    // подписей 30, метка курса на y=18, стрелка толщиной 9), и на 110 они
    // занимали втрое большую долю прибора. Геометрия переведена на долю от
    // размера, после чего умеренная прибавка стала осмысленной.
    //
    // Здесь теперь диапазон, а не одно число: точный размер — вопрос вкуса
    // владельца и будет ещё меняться, а важна граница, за которой прибор
    // начинает перекрывать карту.
    const m = clientSrc.match(/<FieldCompass[^>]*size=\{(\d+)\}/);
    expect(m).not.toBeNull();
    const size = Number(m![1]);
    expect(size).toBeGreaterThanOrEqual(100);
    expect(size).toBeLessThanOrEqual(170);
  });

  it('геометрия компаса пропорциональна размеру, а не в пикселях эталона', () => {
    // Сторож самой причины дефекта 01.09. Фиксированный пиксель внутри
    // прибора, который рендерится в разных масштабах, — это скрытая
    // зависимость от единственного размера: на другом он ломает пропорции
    // молча, и «увеличить» одним числом не лечит.
    const compass = readFileSync(
      join(process.cwd(), 'components/field/FieldCompass.tsx'), 'utf-8');
    expect(compass).toMatch(/const k = size \/ 300/);
    // Стрелка, метка курса и радиус подписей — все через k.
    expect(compass).toMatch(/strokeWidth=\{6 \* k\}/);
    expect(compass).toMatch(/rTickOuter - 30 \* k/);
    expect(compass).toMatch(/\$\{c\},\$\{10 \* k\}/);
    // Толщина стрелки больше не пишется строкой-пикселем.
    expect(compass).not.toMatch(/strokeWidth="9"/);
  });

  it('стрелка не сливается со шкалой — под ней тёмная подложка', () => {
    // «Стрелка теряется» (владелец 01.09): зелёная стрелка шла по зелёной
    // засечке севера и по подписям. Тот же приём, что у трека на карте, —
    // тёмный casing под ярким.
    const compass = readFileSync(
      join(process.cwd(), 'components/field/FieldCompass.tsx'), 'utf-8');
    const needle = compass.slice(compass.indexOf('{needleAngle !== null &&'));
    expect(needle.slice(0, 900)).toMatch(/stroke="#0a0e12"/);
  });

  it('азимут читаем на любом масштабе — у числа есть нижний предел', () => {
    // Без стрелки число — единственный честный ответ прибора (правило 21.08).
    // Значит оно обязано оставаться читаемым, а не масштабироваться в ничто.
    const compass = readFileSync(
      join(process.cwd(), 'components/field/FieldCompass.tsx'), 'utf-8');
    expect(compass).toMatch(/fontSize: Math\.max\(17, 26 \* k\)/);
  });
});
