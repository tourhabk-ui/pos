/**
 * Кнопка MAX на карточке тура появляется только по настоящей ссылке.
 *
 * Владелец 09.08: «сейчас все в РФ переходят на MAX, можно добавить MAX
 * +79147822222». Проверка показала: ссылки ПО НОМЕРУ в MAX не существует —
 * max.ru/+7…, max.ru/7… и max.ru/u/+7… отдают 404. Адрес всегда ведёт на
 * профиль (max.ru/u/… или max.ru/ник), и знает его только владелец профиля:
 * в приложении он берётся из QR-кода, «Поделиться».
 *
 * Отсюда правило этого блока: механизм готов, адрес — из данных. Кнопка,
 * собранная из номера, была бы мёртвой ссылкой на карточке проверенного
 * оператора — это хуже, чем отсутствие кнопки.
 */
import { describe, it, expect } from 'vitest';
import { readFileSync } from 'node:fs';
import { join } from 'node:path';

const ROOT = process.cwd();
const CARD = readFileSync(join(ROOT, 'app/marketplace/tours/[id]/_TourDetailClient.tsx'), 'utf-8');

describe('MAX: ссылка только из данных партнёра', () => {
  it('кнопка читает contacts.max и подписана «Написать в MAX»', () => {
    expect(CARD).toMatch(/o\.max/);
    expect(CARD).toMatch(/Написать в MAX/);
  });

  it('принимается только адрес max.ru — чужой хост кнопкой не станет', () => {
    expect(CARD).toMatch(/\^https:\\\/\\\/max\\\.ru\\\//);
  });

  it('адрес нигде не собирается из номера телефона', () => {
    // Ровно та ошибка, которую нельзя допустить: max.ru/+7…, max.ru/u/+7…
    expect(CARD).not.toMatch(/max\.ru\/u?\/?\$\{/);
    expect(CARD).not.toMatch(/max\.ru\/\+?7/);
  });
});

describe('MAX подчиняется дизайн-системе карточки', () => {
  it('кнопка — та же ds-кнопка, что остальные контакты (без своего градиента)', () => {
    // Присланный образец кнопки был с фиолетовым градиентом инлайн-стилем;
    // на карточке контакты живут одним рядом одинаковых ds-кнопок, а цвета —
    // только через токены (CLAUDE.md §2).
    expect(CARD).not.toMatch(/linear-gradient\(135deg, #00D4FF/);
    expect(CARD).toMatch(/c\.icon === 'max' \? <MessageSquare className="w-4 h-4 text-\[var\(--ocean\)\]" \/>/);
  });
});
