// @vitest-environment node
/**
 * План поездки зовёт модель через общий водопад, а не свой fetch.
 *
 * Разбор периметра, партия 3 (07.09). В файле жила своя `callAI`, ходившая
 * ПРЯМО в DeepSeek: `fetch` на его /chat/completions с ключом из конфига.
 * CLAUDE.md §4 запрещает это дословно — «прямые вызовы только в
 * lib/ai/providers.ts и health-probe файлах», — и запрет не формальность:
 *
 *   - мимо водопада нет ни гонки провайдеров, ни отступления: не ответил
 *     DeepSeek — не ответил никто, хотя рядом живут ещё пять стоков;
 *   - мимо водопада расход не виден ни одному счётчику токенов;
 *   - реестр провайдеров (D2) перечисляет хосты, куда уходят данные;
 *     свой fetch в обход реестра — передача, о которой реестр не знает.
 *
 * Отдельно: `catch (error) {}` без единой строки превращал отказ провайдера
 * в «все провайдеры недоступны» без причины (§4.0).
 *
 * Сторож смотрит на файл, а не на поведение: вызов настоящей модели в
 * юните — не проверка, а счёт за электричество.
 */
import { describe, it, expect } from 'vitest';
import { readFileSync } from 'node:fs';
import { join } from 'node:path';

const SRC = readFileSync(join(process.cwd(), 'app/api/trip/plan/route.ts'), 'utf-8');

/**
 * Код без пояснений. Судить надо употребление, а не упоминание: в шапке
 * `callAI` намеренно написано, КУДА ходила прежняя версия, и запрет на этот
 * адрес не должен краснеть от объяснения, почему его убрали. На этом уже
 * спотыкались сегодня дважды — в стороже соли и в стороже кампании.
 */
const CODE = SRC.replace(/\/\*[\s\S]*?\*\//g, '').replace(/\/\/[^\n]*/g, '');

describe('модель зовётся через водопад', () => {
  it('используется общая функция платформы', () => {
    expect(SRC).toContain('callAIWaterfallOrNull');
  });

  it('своего похода к провайдеру нет', () => {
    expect(CODE, 'прямой fetch к DeepSeek в обход водопада и реестра провайдеров')
      .not.toMatch(/chat\/completions/);
    expect(CODE, 'ключ провайдера в роуте означает свой путь мимо водопада')
      .not.toMatch(/deepseek\.apiKey|openrouter\.apiKey/i);
  });

  it('заглушка водопада не выдаётся за план поездки', () => {
    // callAIWaterfall при общем отказе возвращает не исключение, а текст;
    // отдать его человеку как план хуже честной ошибки. Вариант ...OrNull
    // отличает одно от другого за нас.
    expect(SRC).toMatch(/text === null/);
  });
});

describe('отказ не глушится', () => {
  it('пустого catch в вызове модели нет, причина уходит в лог', () => {
    const call = CODE.slice(CODE.indexOf('async function callAI'));
    expect(call, 'пустой catch превращал отказ провайдера в «недоступны все»')
      .not.toMatch(/catch\s*\([^)]*\)\s*\{\s*\n\s*\}/);
    expect(call).toContain('console.error');
  });
});

describe('счётчик частоты остался один', () => {
  /**
   * В файле уже был `tripPlanLimiter`. Разбирая роут, я едва не завёл рядом
   * второй — ровно та беда, которую этот разбор чинит у других: две
   * реализации одного расходятся молча. Сторож держит единственность.
   */
  it('лимитер объявлен ровно один раз', () => {
    const declared = [...CODE.matchAll(/const\s+\w*[Ll]imiter\s*=\s*createRateLimiter/g)];
    expect(declared.length, 'второй счётчик в том же файле разойдётся с первым').toBe(1);
  });

  it('он же и спрашивается перед работой', () => {
    expect(SRC).toMatch(/tripPlanLimiter\.check\(/);
  });
});
