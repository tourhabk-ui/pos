/**
 * Расстояние до города — СЧИТАЕТСЯ и всегда называет способ подсчёта.
 *
 * ── Повод ─────────────────────────────────────────────────────────────────
 *
 * 14.09 разбор чужих карточек мест (Туристер, 2ГИС, Яндекс) показал приём,
 * который у нас производим для ВСЕХ мест, в отличие от цены, часов и
 * рейтинга: «в 130 км от Петропавловска-Камчатского». Координаты у `places`
 * NOT NULL по построению, значит строка есть всегда.
 *
 * ── Чем это отличается от запрещённого ────────────────────────────────────
 *
 * Миграция 925 намеренно НЕ писала расстояние в описании «Раздолья»:
 * бальнеозаключение говорило 22 км, справочники 45, по координатам выходило
 * 36. Три числа на один факт — это «не знаю» (§4.0).
 *
 * Здесь противоречия нет: число не берётся из источника, а считается, и
 * вместе с ним ВСЕГДА едет способ подсчёта. «36 км по прямой» — проверяемое
 * утверждение о двух координатах; «36 км» без оговорки было бы обещанием
 * дороги, которой никто не мерил. На Камчатке дорога до точки в тридцати
 * километрах по прямой бывает вдвое длиннее или отсутствует вовсе.
 *
 * Сторож держит три вещи: подпись не теряет оговорку, точка отсчёта одна на
 * платформу, и «не знаю» выражается отсутствием строки, а не нулём.
 */
import { describe, it, expect } from 'vitest';
import { readFileSync } from 'node:fs';
import { join } from 'node:path';
import { distanceToCity, PKC } from '@/lib/places/distance-to-city';

describe('расстояние до города', () => {
  it('подпись всегда называет способ подсчёта', () => {
    // Без этих слов число читается как расстояние по дороге.
    const d = distanceToCity(53.288, 158.35);
    expect(d).not.toBeNull();
    expect(d?.label).toContain('по прямой');
  });

  it('считает правдоподобно: Раздолье — около 36 км', () => {
    // Значение из разбора миграции 925: по координатам выходит ~36 км, и
    // именно поэтому там отказались писать «22» и «45» из справочников.
    const d = distanceToCity(53.288365, 158.350074);
    expect(d?.km).toBeGreaterThan(30);
    expect(d?.km).toBeLessThan(42);
  });

  it('нет координат — нет строки, а не ноль', () => {
    expect(distanceToCity(null, null)).toBeNull();
    expect(distanceToCity(undefined, 158.3)).toBeNull();
    expect(distanceToCity(Number.NaN, 158.3)).toBeNull();
  });

  it('север края считается, а не отсекается', () => {
    // Порога «дальше N — молчим» нет намеренно: полуостров длиннее тысячи
    // километров, и «810 км от Петропавловска» — именно то, что нужно знать
    // про север. Сломанная координата по той же причине покажет себя числом,
    // а не спрячется за молчанием.
    const d = distanceToCity(60.0, 165.5);
    expect(d).not.toBeNull();
    expect(d?.km).toBeGreaterThan(700);
  });

  it('вплотную к городу не печатает «0 км»', () => {
    const d = distanceToCity(PKC.lat + 0.002, PKC.lng);
    expect(d?.label).not.toMatch(/^0 км/);
  });
});

describe('точка отсчёта одна на платформу', () => {
  it('совпадает с ориентиром планера', () => {
    // Две точки отсчёта дали бы одному месту два разных расстояния на
    // соседних экранах — ровно тот разнобой, от которого §7 про честные цифры.
    const engine = readFileSync(join(process.cwd(), 'lib/planner/engine.ts'), 'utf-8');
    const m = /PKC_COORDS: \[number, number\] = \[([\d.]+), ([\d.]+)\]/.exec(engine);
    expect(m, 'ориентир планера не найден — проверьте, не переименовали ли его').toBeTruthy();
    expect(Number(m?.[1])).toBeCloseTo(PKC.lat, 2);
    expect(Number(m?.[2])).toBeCloseTo(PKC.lng, 2);
  });
});

describe('карточка места показывает строку', () => {
  const CLIENT = readFileSync(
    join(process.cwd(), 'app/places/[id]/_PlaceDetailClient.tsx'),
    'utf-8',
  );

  it('факт собирается для героя', () => {
    expect(CLIENT).toMatch(/distanceToCity\(place\.lat, place\.lng\)/);
    expect(CLIENT).toMatch(/label: 'от Петропавловска'/);
  });

  it('строки нет, когда считать не от чего', () => {
    // `if (toCity)` — а не подстановка прочерка.
    expect(CLIENT).toMatch(/if \(toCity\) heroFacts\.push/);
  });
});
