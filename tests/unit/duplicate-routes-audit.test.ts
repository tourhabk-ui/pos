/**
 * Двойники в справочнике маршрутов.
 *
 * Пересуд привязок 11.08 дал 106 «неоднозначных» треков — рядом с каждым
 * стоял другой маршрут вплотную. Разбор показал, что это в основном не чужие
 * привязки, а наши собственные двойники:
 *
 *   «Маршрут Пиначево - Центральный» ⟷ «Маршрут Пиначево — Центральный»
 *
 * Отличается ВИД ТИРЕ. Совпадение по имени их не склеило, они живут двумя
 * записями, и трек лёг на ту, чей якорь в семидесяти четырёх километрах.
 *
 * Главное, чего здесь нельзя допустить, — объявить дубликатом два маршрута,
 * стоящих в одной точке. На Камчатке это обычная перевалка: из Эссо
 * расходятся и Уксичанские источники, и Ичинская сопка. Ровно на этом
 * сгорела привязка треков, и второй раз наступать не будем.
 */
import { describe, it, expect } from 'vitest';
import { normalizeTitle } from '@/lib/import/kml-inbox';
import { stems, shareStem, SAME_SPOT_KM } from '@/lib/routes/duplicate-audit';

describe('приведение имени складывает то, что для человека одно', () => {
  it('дефис и тире — одно название', () => {
    // Та самая пара из справочника.
    expect(normalizeTitle('Маршрут Пиначево - Центральный'))
      .toBe(normalizeTitle('Маршрут Пиначево — Центральный'));
  });

  it('пробелы вокруг тире не значимы', () => {
    expect(normalizeTitle('Пиначево-Центральный')).toBe(normalizeTitle('Пиначево — Центральный'));
  });

  it('ё и Е — одно', () => {
    expect(normalizeTitle('Озеро Толмачёво')).toBe(normalizeTitle('Озеро Толмачево'));
  });

  it('кавычки и хвостовая пунктуация отбрасываются', () => {
    expect(normalizeTitle('«Вулкан Горелый».')).toBe(normalizeTitle('Вулкан Горелый'));
  });

  it('жанровое слово «Маршрут» в начале не значимо', () => {
    // Оно есть у одних записей и нет у других, а разбор KML снимает его
    // всегда — пока правило жило только там, имена не сходились.
    expect(normalizeTitle('Маршрут Пиначево - Центральный')).toBe(normalizeTitle('Пиначево — Центральный'));
    // Но только в начале и только отдельным словом: «Маршрут выходного дня»
    // теряет жанр, а «Маршрутный перевал» — половину имени.
    expect(normalizeTitle('Перевал Маршрутный')).toBe('перевал маршрутный');
    expect(normalizeTitle('Маршрутный')).toBe('маршрутный');
  });

  it('разные маршруты не склеиваются', () => {
    // Складывать надо написание, а не смысл.
    expect(normalizeTitle('Вулкан Горелый')).not.toBe(normalizeTitle('Вулкан Мутновский'));
  });
});

describe('общая основа: русское словоизменение не должно мешать', () => {
  it('Толмачева и Толмачево — про одно', () => {
    expect(shareStem('Озеро Толмачева', 'На каяках по озеру Толмачево')).toBe(true);
  });

  it('короткие служебные слова в сравнении не участвуют', () => {
    // Иначе «на», «по», «и» склеили бы половину справочника.
    expect(shareStem('На Авачу', 'По Мутновке')).toBe(false);
    expect(stems('На по и с')).toEqual(new Set());
  });

  it('разные предметы общей основы не имеют', () => {
    expect(shareStem('Вулкан Горелый', 'Вулкан Мутновский')).toBe(false);
  });

  it('общее родовое слово одно не роднит', () => {
    // «Вулкан» есть у половины маршрутов; основа должна быть в имени собственном.
    expect(shareStem('Вулкан Горелый', 'Вулкан Ичинская сопка')).toBe(false);
  });
});

describe('одна точка — ещё не один объект (урок Эссо)', () => {
  it('порог близости мал: это «та же точка», а не «тот же район»', () => {
    // Километровый порог объявил бы двойниками всё, что выходит из посёлка.
    expect(SAME_SPOT_KM).toBeLessThanOrEqual(0.5);
  });

  it('разные маршруты от общей перевалки основы не делят', () => {
    // Эссо: отсюда идут и Уксичанские источники, и Ичинская сопка.
    expect(shareStem('Эссовские (Уксичанские) термальные источники', 'Вулкан Ичинская сопка'))
      .toBe(false);
  });
});

describe('перепись зовёт существующее приведение имени', () => {
  it('своего нормализатора не заводит', () => {
    // Второе правило об одном и том же разойдётся с первым — за сутки это
    // случилось дважды (SQL-чистка против стража, линия на трёх экранах).
    const src = require('node:fs').readFileSync(
      require('node:path').join(process.cwd(), 'lib/routes/duplicate-audit.ts'), 'utf-8',
    ) as string;
    expect(src).toMatch(/from '@\/lib\/import\/kml-inbox'/);
    expect(src).not.toMatch(/toLowerCase\(\)[\s\S]{0,80}replace/);
  });
});
