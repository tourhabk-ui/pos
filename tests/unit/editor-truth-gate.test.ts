/**
 * Editor не записывает выдумку (решение владельца 03.10: «Editor не должен
 * выдумывать, только правду»).
 *
 * Проверяется поведение проверки и то, что ОБА пути записи — прод
 * (`runEditor`) и приёмник раннера (`/api/cron/editor-result`) — зовут её до
 * UPDATE. Сторож, проверяющий только функцию, зеленел бы при отключённой
 * проверке на любом из путей (§10.09: держать связку, а не половину).
 */
import { describe, it, expect } from 'vitest';
import { readFileSync } from 'node:fs';
import { judgeGeneratedDescription, extractNumbers, novelContentWords } from '@/lib/agents/editor-truth-gate';

const src = {
  title: 'Вулкан Авачинский',
  facts: ['тип объекта: volcano', 'высота над уровнем моря, м: 2741', 'координаты: 53.2550, 158.8300', 'опасности точки: камнепад'],
  previous: null,
};

describe('проверка правды', () => {
  it('текст только из источника — записывается', () => {
    const v = judgeGeneratedDescription('Вулкан Авачинский высотой 2741 метр. На склонах отмечен камнепад.', src);
    expect(v).toEqual({ ok: true, reasons: [] });
  });

  it('число не из источника — отказ', () => {
    const v = judgeGeneratedDescription('Подъём занимает 6 часов, высота 2741 метр.', src);
    expect(v.ok).toBe(false);
    expect(v.reasons.join(' ')).toContain('6');
  });

  it('округлённая координата из источника не считается выдумкой, а чужое целое — считается', () => {
    expect(judgeGeneratedDescription('Координаты около 53.25 и 158.83.', src).ok).toBe(true);
    // 27 — не префикс-округление 2741: целые сравниваются целиком.
    expect(judgeGeneratedDescription('Высота около 27 метров.', src).ok).toBe(false);
  });

  it('пробел в тысячах и запятая в дробях нормализуются', () => {
    expect(extractNumbers('высота 2 741 м, кратер 0,4 км')).toEqual(['2741', '0.4']);
  });

  it('опасность не из источника — отказ; из источника — можно', () => {
    const bear = judgeGeneratedDescription('На склонах встречаются медведи.', src);
    expect(bear.ok).toBe(false);
    expect(bear.reasons.join(' ')).toContain('медведи');
    expect(judgeGeneratedDescription('Возможен камнепад.', src).ok).toBe(true);
  });

  it('ложное «безопасно» и «для новичков» — тоже выдумка о безопасности', () => {
    expect(judgeGeneratedDescription('Маршрут безопасен и подходит новичкам.', src).ok).toBe(false);
  });

  it('голос путевой заметки — отказ', () => {
    const v = judgeGeneratedDescription('Вчера я поднялся на вулкан Авачинский.', src);
    expect(v.ok).toBe(false);
    expect(v.reasons.join(' ')).toContain('путевая заметка');
  });

  it('ощущения без рассказчика — отказ', () => {
    expect(judgeGeneratedDescription('У вершины стоит тишина и запах серы.', src).ok).toBe(false);
  });

  it('рекламный эпитет — отказ', () => {
    expect(judgeGeneratedDescription('Незабываемый вулкан Авачинский.', src).ok).toBe(false);
  });

  it('«сел» как основа не ловит посёлок', () => {
    const s2 = { ...src, facts: [...src.facts, 'зона: посёлок Елизово'] };
    expect(judgeGeneratedDescription('Ближайший посёлок — Елизово.', s2).ok).toBe(true);
  });
});

// Выдумка без чисел и без слов-опасностей (23.10, владелец: «Editor много
// выдумал»): до этого дня такие тексты проходили проверку целиком.
describe('слова не из источника', () => {
  const route = {
    title: 'Перевал Тестовый',
    facts: [
      'род записи: маршрут',
      'вид активности: треккинг',
      'дистанция маршрута, км: 12',
      'набор высоты, м: 900',
      'сезон: лето',
      'тип маршрута: радиальный',
      'опасности маршрута: броды',
      'снаряжение: треккинговые ботинки',
    ],
    previous: null,
  };

  it('честный пересказ фактов проходит', () => {
    const text = 'Перевал Тестовый — радиальный маршрут для треккинга протяжённостью 12 километров '
      + 'с набором высоты 900 метров. Сезон — лето. На маршруте отмечены броды; '
      + 'требуются треккинговые ботинки.';
    expect(judgeGeneratedDescription(text, route)).toEqual({ ok: true, reasons: [] });
  });

  it.each([
    ['природа', 'Тропа идёт через березняк, с перевала открываются красивые виды на долину.'],
    ['совет', 'Перед выходом стоит взять палки и запас воды, обувь лучше выбрать удобную.'],
    ['оценка', 'Маршрут несложный и подойдёт семьям с детьми, интересен любителям фотографии.'],
    ['дорога', 'Добраться до начала маршрута можно на автомобиле из города.'],
    ['погода', 'Погода здесь переменчива, часто дует сильный ветер и выпадает туман.'],
  ])('выдумка «%s» — отказ с названными словами', (_kind, invented) => {
    const v = judgeGeneratedDescription(`Перевал Тестовый: маршрут 12 километров. ${invented}`, route);
    expect(v.ok).toBe(false);
    expect(v.reasons.join(' ')).toContain('слова не из источника');
  });

  it('одно новое слово-связка допускается, второе — уже факт', () => {
    expect(judgeGeneratedDescription('Перевал Тестовый — пологий маршрут: 12 километров.', route).ok).toBe(true);
    expect(judgeGeneratedDescription('Перевал Тестовый — пологий лесной маршрут: 12 километров.', route).ok)
      .toBe(false);
  });

  it('формы слова и «ё» не считаются новыми словами', () => {
    expect(novelContentWords('Летом на маршрутах отмечены броды; снаряжение — треккинговые ботинки.', route.facts.join(' ')))
      .toEqual([]);
  });

  // Ревью 23.10: слова пересказа по основе пропускали выдумку — «перед»
  // узаконивал «переправу» и «перевал», «часа» — «часто».
  it.each([
    ['переправа и перевал', 'На пути есть переправа и перевал.'],
    ['последний участок', 'Последний участок — переправа.'],
    ['туманы', 'Часты туманы, бывает сильный ветер.'],
    ['требование', 'Требуется регистрация в МЧС.'],
    ['снаряжение не из фактов', 'Нужны палатка и горелка.'],
    ['сопровождение', 'Необходимо сопровождение гида.'],
    ['рассказ о данных', 'НЕТ. Из записанных сведений о маршруте известно только название.'],
  ])('выдумка «%s» не проходит', (_kind, invented) => {
    const v = judgeGeneratedDescription(`Перевал Тестовый: маршрут 12 километров. ${invented}`, route);
    expect(v.ok).toBe(false);
  });

  // Здесь утечка основы решает исход: без неё новых слов два, с ней — одно.
  it.each([
    ['«часа» не узаконивает «часты»', 'Перевал Тестовый: маршрут 12 километров. Часты туманы.'],
    ['«после» не узаконивает «последний»', 'Перевал Тестовый: маршрут 12 километров. Последний участок.'],
  ])('%s', (_kind, text) => {
    expect(judgeGeneratedDescription(text, route).ok).toBe(false);
  });

  it('слово из четырёх букв даёт основу только своим формам: «горы» не узаконивает «городской»', () => {
    const withRelief = { ...route, facts: [...route.facts, 'рельеф: горы'] };
    expect(judgeGeneratedDescription('Перевал Тестовый: маршрут 12 километров. Рядом городской парк.', withRelief).ok)
      .toBe(false);
    expect(novelContentWords('Маршрут проходит через горные склоны.', 'род записи: маршрут; рельеф: горы, склоны')).toEqual([]);
  });

  it('переправа — опасность: без неё в фактах не проходит даже одним словом', () => {
    const v = judgeGeneratedDescription('Перевал Тестовый: маршрут 12 километров, есть переправа.', route);
    expect(v.reasons.join(' ')).toContain('переправы');
  });

  it('порядок точек пути и медицинская помощь пересказываются без новых слов', () => {
    const facts = [
      ...route.facts,
      'точки маршрута по порядку: Парковка → Перевал → Кратер',
      'до ближайшей медицинской помощи, км: 40',
    ];
    const text = 'Маршрут длиной 12 километров начинается у точки Парковка, затем проходит через Перевал '
      + 'и далее ведёт к Кратеру. До ближайшей медицинской помощи — 40 километров.';
    expect(novelContentWords(text, facts.join(' '))).toEqual([]);
  });

  it('короткая общая начальная часть — не основа: «камни» не из «Камчатки»', () => {
    expect(novelContentWords('Камни на склоне.', 'Камчатка')).toEqual(['камни', 'склоне']);
  });
});

describe('оба пути записи зовут проверку до UPDATE', () => {
  for (const file of ['lib/agents/editor.ts', 'app/api/cron/editor-result/route.ts']) {
    it(file, () => {
      const code = readFileSync(file, 'utf8');
      const judge = code.indexOf('judgeGeneratedDescription(');
      const update = code.indexOf('UPDATE agent_route_knowledge SET description');
      expect(judge).toBeGreaterThan(-1);
      expect(update).toBeGreaterThan(-1);
      expect(judge).toBeLessThan(update);
      // Прежний текст в очереди — собственный текст модели (23.10): источником
      // для проверки он не служит, иначе вчерашняя выдумка узаконила бы сегодняшнюю.
      expect(code).not.toMatch(/previous:\s*route\.description/);
    });
  }
});
