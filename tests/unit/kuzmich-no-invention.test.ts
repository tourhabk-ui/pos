/**
 * Промпт Кузьмича не заказывает выдумку, а молчание лент не читается как
 * «тревог нет».
 *
 * ── Issue #1723: заказ на выдумку ──────────────────────────────────────────
 *
 * В роли «ЗНАТОК МЕСТА» стояло обязательное «добавь один факт который турист
 * не найдёт в путеводителе». Источника таких фактов в контексте нет:
 * инструменты отдают статус безопасности, опасности, туры, занятость и погоду
 * — не этнографию. Строкой выше модель прямо приглашалась рассуждать о том,
 * «почему коряки обходили Корякский вулкан», в ответе, где сверху требуется
 * безопасность.
 *
 * Это дословно §4.0 CLAUDE.md: «Просить деталь, которую знают не все, не дав
 * источника, — заказ на выдумку». Тот же механизм уже дал выдуманный «секрет
 * места» в посте канала 19.08 — сторож post-no-invention заведён на него, но
 * на промпт Кузьмича он не смотрит. Этот смотрит.
 *
 * ── Issue #1722: молчание лент ─────────────────────────────────────────────
 *
 * fetchMchsAlerts возвращала пустую строку и при «тревог нет», и при «ни одна
 * лента не ответила», а пустая строка просто не попадала в промпт. Ленты МЧС с
 * прода могут быть гео-закрыты — то есть второе состояние вероятно по
 * умолчанию, и туристу отвечали так, будто предупреждений нет.
 *
 * ── Живой случай 11.09: выдуманные «дубли» вместо признания счётной ошибки ──
 *
 * Турист в Telegram спросил «сколько туров в базе», Кузьмич назвал число,
 * следом попросил перечислить — и правило «никаких списков и перечислений»
 * (перегони в одно предложение через запятую) стало срезать пункты при
 * пересказе длинного каталога прозой. Три подряд ответа разошлись по счёту
 * (11 → 5 → 9), и на прямой вопрос «значит вранье?» модель не признала свою
 * ошибку пересказа, а СОЧИНИЛА данные: заявила, что два тура — «дубли» друг
 * друга, хотя оба пришли из buildTourCatalog() с разными ID и разными
 * названиями («Семейный тур на 2 дня» ≠ «Семейный тур выходного дня»). Это
 * тот же класс, что и заказ на выдумку 19.08: не смог обосновать число —
 * значит выдумал обоснование, вместо честного «сбился, пересчитываю».
 */
import { describe, it, expect } from 'vitest';
import { readFileSync } from 'node:fs';
import { join } from 'node:path';
import { KUZMICH_SYSTEM } from '@/lib/kuzmich/core';
import { travelFactsBlock } from '@/lib/kuzmich/travel-facts';
import { getSystemPrompt, KUZMICH_PROMPT } from '@/lib/ai/prompts';

const SRC = readFileSync(join(process.cwd(), 'lib/kuzmich/core.ts'), 'utf8');

describe('промпт не требует того, чего нет в данных', () => {
  it('нет заказа на «факт, которого нет в путеводителе»', () => {
    expect(SRC).not.toMatch(/не найдёт в путеводителе/);
    expect(SRC).not.toMatch(/секрет,? котор/i);
  });

  it('у знатока места есть разрешение промолчать', () => {
    expect(SRC).toMatch(/Нечего добавить — не добавляй ничего/);
    expect(SRC).toMatch(/ТОЛЬКО из данных ниже и из инструментов/);
  });

  it('структура ответа тоже не требует факта из ниоткуда', () => {
    expect(SRC).toMatch(/один факт ИЗ ДАННЫХ \(нет такого — пропусти\)/);
  });
});

// Слово владельца 15.11 «ответ 1» (#3382): промпт разрешал о реальных местах
// «используй свои знания», и модель называла по памяти «25–30 км до
// Паратунки» и сезон медведей, которых в данных не было. Рядом стояли четыре
// расстояния без источника. Теперь о месте можно сказать, что это за место, а
// расстояния, сезоны, цены и опасности — только из данных; числа дороги живут
// в блоке с источником (lib/kuzmich/travel-facts).
describe('о местах — факты из данных, не по памяти', () => {
  it('промпт не разрешает отвечать о местах своими знаниями', () => {
    expect(KUZMICH_SYSTEM).not.toMatch(/используй свои знания/i);
    expect(KUZMICH_SYSTEM).not.toMatch(/Можешь рассказывать о .* и любых других/i);
  });

  it('и не разрешает «последние известные данные» об объекте', () => {
    // Ревью безопасности #3393: строка «ИНТЕРНЕТ» разрешала отдать режим
    // работы и общие сведения об объекте «последними известными» — то есть
    // по памяти, в споре с правилом выше.
    expect(KUZMICH_SYSTEM).not.toMatch(/последние известные данные/i);
  });

  it('в промпте нет расстояний: числа дороги приходят блоком с источником', () => {
    expect(KUZMICH_SYSTEM).not.toMatch(/\d[\d\s.,–-]*\s*(?:км|километр)/i);
    const block = travelFactsBlock('Сколько ехать до Паратунки?');
    expect(block).toContain('- Паратунка: расстояние: 60 км по автодороге');
    expect(block).toMatch(/\(источник: https:\/\/[^)]+\)/);
  });
});

// Ревью безопасности #3393: когда цикл Кузьмича не ответил, веб-чат и стрим
// отвечают одиночным вызовом с промптом роли (lib/ai/prompts, getSystemPrompt)
// — без KUZMICH_SYSTEM и без блоков данных. Правило о фактах места обязано
// стоять и там, а высот, расстояний и месяцев без источника там быть не должно.
describe('запасной ответ веб-чата — то же правило о фактах места', () => {
  const MONTHS = /(?:январ|феврал|март|апрел|ма[йя]|июн|июл|август|сентябр|октябр|ноябр|декабр)/i;
  const prompts = { tourist: getSystemPrompt('tourist'), kuzmichTelegram: KUZMICH_PROMPT, operator: getSystemPrompt('operator'), guide: getSystemPrompt('guide') };

  it.each(Object.entries(prompts))('%s: факты о месте — только из данных ответа', (_name, prompt) => {
    expect(prompt).toMatch(/Факты о нём — расстояния, время дороги, высоты, сезоны, цены, опасности, открыто ли — только из данных этого ответа/);
  });

  it.each(Object.entries(prompts))('%s: нет высот, расстояний и месяцев без источника', (_name, prompt) => {
    expect(prompt).not.toMatch(/\d{3,4}\s*м\b/);
    expect(prompt).not.toMatch(/\d[\d\s.,–-]*\s*(?:км|километр)/i);
    expect(prompt).not.toMatch(MONTHS);
  });
});

describe('ленты: «не ответили» не равно «тревог нет»', () => {
  it('у чтения лент три исхода', () => {
    expect(SRC).toMatch(/export type FeedOutcome/);
    expect(SRC).toMatch(/'no_feeds'/);
    expect(SRC).toMatch(/'empty'/);
  });

  it('отказ каждой ленты попадает в лог поимённо', () => {
    expect(SRC).toMatch(/logSwallowed\(`лента МЧС \$\{url\}`/);
    expect(SRC).toMatch(/logSwallowed\(`лента новостей \$\{url\}`/);
    expect(SRC).not.toMatch(/catch \{ \/\* feed unavailable/);
  });

  it('недостижимость сводки МЧС говорится в промпте вслух', () => {
    expect(SRC).toMatch(/СВОДКА НЕДОСТУПНА — ни одна лента не ответила/);
    expect(SRC).toMatch(/Это НЕ значит «предупреждений нет»/);
  });
});

describe('перечисление каталога не искажает счёт', () => {
  it('общий каталог из промпта не пересказывается, счёт держится по строкам этого хода', () => {
    expect(SRC).toMatch(/Общий каталог выше списком не пересказывай/);
    expect(SRC).not.toMatch(/перечислить ВЕСЬ каталог целиком/);
    expect(SRC).not.toMatch(/Называешь цену как ориентир/);
    expect(SRC).toMatch(/обязаны совпадать со строками в данных ниже/);
  });

  it('расхождение в счёте — признаётся, а не объясняется выдумкой про данные', () => {
    expect(SRC).toMatch(/ЦЕЛОСТНОСТЬ СЧЁТА/);
    // С 15.11 правило без угрозы, с причиной (#3399, п. 5): смысл тот же.
    expect(SRC).toMatch(/Не объясняй расхождение догадкой/);
    // Живой случай 11.09: модель заявила «это дубли» без основания в данных
    expect(SRC).toMatch(/«это дубли»/);
    expect(SRC).toMatch(/отдельный ID — отдельный реальный тур/);
  });
});
