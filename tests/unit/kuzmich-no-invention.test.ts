/**
 * Промпт Кузьмича не заказывает выдумку, а молчание лент не читается как
 * «тревог нет».
 *
 * ── Issue #1723: заказ на выдумку ──────────────────────────────────────────
 *
 * В роли «ЗНАТОК МЕСТА» стояло обязательное «добавь один факт который турист
 * не найдёт в путеводителе». Источника таких фактов в контексте нет:
 * инструменты отдают статус безопасности, опасности, туры, занятость и погоду
 * — не этнографию. Строкой выше модель прямо приглашалась рассуждать о том,
 * «почему коряки обходили Корякский вулкан», в ответе, где сверху требуется
 * безопасность.
 *
 * Это дословно §4.0 CLAUDE.md: «Просить деталь, которую знают не все, не дав
 * источника, — заказ на выдумку». Тот же механизм уже дал выдуманный «секрет
 * места» в посте канала 19.08 — сторож post-no-invention заведён на него, но
 * на промпт Кузьмича он не смотрит. Этот смотрит.
 *
 * ── Issue #1722: молчание лент ─────────────────────────────────────────────
 *
 * fetchMchsAlerts возвращала пустую строку и при «тревог нет», и при «ни одна
 * лента не ответила», а пустая строка просто не попадала в промпт. Ленты МЧС с
 * прода могут быть гео-закрыты — то есть второе состояние вероятно по
 * умолчанию, и туристу отвечали так, будто предупреждений нет.
 */
import { describe, it, expect } from 'vitest';
import { readFileSync } from 'node:fs';
import { join } from 'node:path';

const SRC = readFileSync(join(process.cwd(), 'lib/kuzmich/core.ts'), 'utf8');

describe('промпт не требует того, чего нет в данных', () => {
  it('нет заказа на «факт, которого нет в путеводителе»', () => {
    expect(SRC).not.toMatch(/не найдёт в путеводителе/);
    expect(SRC).not.toMatch(/секрет,? котор/i);
  });

  it('у знатока места есть разрешение промолчать', () => {
    expect(SRC).toMatch(/Нечего добавить — не добавляй ничего/);
    expect(SRC).toMatch(/ТОЛЬКО из данных ниже и из инструментов/);
  });

  it('структура ответа тоже не требует факта из ниоткуда', () => {
    expect(SRC).toMatch(/один факт ИЗ ДАННЫХ \(нет такого — пропусти\)/);
  });
});

describe('ленты: «не ответили» не равно «тревог нет»', () => {
  it('у чтения лент три исхода', () => {
    expect(SRC).toMatch(/export type FeedOutcome/);
    expect(SRC).toMatch(/'no_feeds'/);
    expect(SRC).toMatch(/'empty'/);
  });

  it('отказ каждой ленты попадает в лог поимённо', () => {
    expect(SRC).toMatch(/logSwallowed\(`лента МЧС \$\{url\}`/);
    expect(SRC).toMatch(/logSwallowed\(`лента новостей \$\{url\}`/);
    expect(SRC).not.toMatch(/catch \{ \/\* feed unavailable/);
  });

  it('недостижимость сводки МЧС говорится в промпте вслух', () => {
    expect(SRC).toMatch(/СВОДКА НЕДОСТУПНА — ни одна лента не ответила/);
    expect(SRC).toMatch(/Это НЕ значит «предупреждений нет»/);
  });
});
