/**
 * Пост — это пост, а не реплика модели нам.
 *
 * 04.09 в канал на 1800 подписчиков ушёл вот такой «дайджест»:
 *
 *   «Не вижу текста статьи в сигнале — только HTML-обёртка Telegram-виджета
 *   без содержимого поста. Не могу написать пост по этому материалу, так как
 *   нет ни одного фактического сигнала для синтеза. Пришли, пожалуйста,
 *   выдержки из статей (текст, который был в самих постах/материалах), и я
 *   соберу дайджест по правилам.»
 *
 * Все ворота пропустили его ЗАКОННО. Числовой фактчек ищет проценты — их нет.
 * Судья ищет неподтверждённые утверждения — их тоже нет: отказ ничего не
 * утверждает, опровергать нечего. Проверка на пустоту не срабатывает: текст
 * связный и нужной длины. Ворота проверяли ПРАВДИВОСТЬ поста, и ни одни не
 * спрашивали, пост ли это вообще.
 */
import { describe, it, expect } from 'vitest';
import { readFileSync } from 'node:fs';
import { join } from 'node:path';
import { modelRefusalIssue, blockingTextIssue } from '@/lib/notifications/post-validation';
import { SKIP_REASON_LABELS } from '@/lib/agents/scout-digest';

const REAL_CASE = 'Не вижу текста статьи в сигнале — только HTML-обёртка Telegram-виджета без содержимого поста. '
  + 'Не могу написать пост по этому материалу, так как нет ни одного фактического сигнала для синтеза.\n\n'
  + 'Пришли, пожалуйста, выдержки из статей (текст, который был в самих постах/материалах), и я соберу дайджест по правилам.';

describe('реплика модели опознаётся как не-пост', () => {
  it('случай 04.09 — дословно', () => {
    const issue = modelRefusalIssue(REAL_CASE);
    expect(issue, 'тот самый текст снова прошёл бы в канал').not.toBeNull();
    expect(issue).toMatch(/реплика нам, а не пост/);
  });

  /**
   * Первая версия гарда писала границы через `\b` и не ловила НИЧЕГО: в JS
   * `\b` кириллицу не знает, и /\bне\s+вижу\b/ не находит «Не вижу» никогда.
   * Тест на живом случае поймал это за минуту; без него в канал уехал бы
   * второй такой же пост при зелёной сборке.
   */
  it('границы слов юникодные — иначе гард молчит на кириллице', () => {
    expect(modelRefusalIssue('Не вижу текста. Пришлите выдержки.')).not.toBeNull();
    expect(modelRefusalIssue('НЕ МОГУ НАПИСАТЬ ПОСТ')).not.toBeNull();
    // Слово внутри другого слова приметой не считается.
    expect(modelRefusalIssue('Вертолётная площадка принесла нам сигналы о погоде на день.')).toBeNull();
  });

  it('три приметы по отдельности: отказ писать, бессилие с просьбой, просьба с кухней', () => {
    expect(modelRefusalIssue('Не могу написать пост: данных нет.')).toMatch(/отказывается писать/);
    expect(modelRefusalIssue('Не вижу содержимого. Пришлите текст, пожалуйста.')).toMatch(/бессилии/);
    expect(modelRefusalIssue('Отправьте выдержки из материалов, и я соберу дайджест.')).toMatch(/просит у человека/);
  });

  it('живой текст не глушится: одной приметы мало', () => {
    // «не вижу» в обычной фразе поста.
    expect(modelRefusalIssue('С перевала не вижу вершины: облака сели на гребень, и тропа теряется.')).toBeNull();
    // «пришлите» в приглашении, без разговора о кухне и без бессилия.
    expect(modelRefusalIssue('Присылайте заявки на сентябрьский выход, группа собирается.')).toBeNull();
    // Настоящий дайджест.
    expect(modelRefusalIssue('<b>AI & Tech</b>\n- DeepMind показала модель прогноза погоды.\n<b>Камчатка</b>\n- Особый противопожарный режим.')).toBeNull();
    expect(modelRefusalIssue('')).toBeNull();
  });

  it('общий гард постов канала тоже её ловит', () => {
    expect(blockingTextIssue(REAL_CASE)).toMatch(/реплика нам, а не пост/);
  });
});

describe('оба выпуска закрыты воротами, и причина названа словами', () => {
  const DIGEST = readFileSync(join(process.cwd(), 'lib/agents/scout-digest.ts'), 'utf-8');

  it('дайджест и AI-пост проверяются до отправки', () => {
    expect(DIGEST).toMatch(/const digestRefusal = modelRefusalIssue\(digest\)/);
    expect(DIGEST).toMatch(/digest_skip_reason: 'model_refusal'/);
    expect(DIGEST).toMatch(/const refusal = modelRefusalIssue\(aiDigest\)/);
    expect(DIGEST).toMatch(/aiSkip = 'ai_model_refusal'/);
  });

  it('у обеих причин есть человеческое имя в словаре', () => {
    expect(SKIP_REASON_LABELS.model_refusal).toMatch(/реплик/);
    expect(SKIP_REASON_LABELS.ai_model_refusal).toMatch(/реплик/);
  });
});
