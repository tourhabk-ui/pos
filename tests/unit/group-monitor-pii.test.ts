/**
 * Текст чужих каналов не уезжает в модель с телефонами.
 *
 * Повод — живой случай 29.07. Владелец добавил нашего бота в канал партнёра,
 * и канал сразу стал источником разведки: `channel_post` → `groupMonitor` →
 * буфер → AI-анализ. А типичный пост оператора выглядит так:
 *
 *     Сплав по реке Быстрой, 13000 рублей с человека.
 *     +79147817114, Ярослав
 *
 * До правки этот текст уходил в `extractIntel` целиком. Все наши модели, кроме
 * одного домашнего стока, живут за границей — то есть телефон партнёра
 * пересекал границу при каждом разборе (152-ФЗ).
 *
 * Почему это не поймал `pii-flow-scanner`: он ищет интерполяцию ПОЛЕЙ
 * (`.phone`, `.email`, `*_name`) — то есть ПД, вытащенные из нашей базы по
 * имени колонки. Здесь номер лежит внутри свободного текста, поля нет и быть
 * не может. Слепое пятно по построению, а не недосмотр. Поэтому граница
 * защищена чисткой в самом месте отправки, а этот тест сторожит её наличие.
 */
import { describe, it, expect } from 'vitest';
import { readFileSync } from 'fs';
import { join } from 'path';
import { redactPII, hasPII } from '@/lib/security/pii-redact';

const ROOT = process.cwd();
const SRC = readFileSync(join(ROOT, 'lib/telegram/group-monitor.ts'), 'utf-8');

/** Код без комментариев: упоминание redactPII в тексте комментария не считается. */
const CODE = SRC.split('\n').filter((l) => !/^\s*(\/\/|\*|\/\*)/.test(l)).join('\n');

describe('монитор каналов чистит ПД перед моделью', () => {
  it('текст сообщений проходит через redactPII до сборки промпта', () => {
    // Ищем именно вызов внутри map по сообщениям, а не любое упоминание.
    expect(CODE, 'сырой m.text снова уезжает в модель').toMatch(/redactPII\(m\.text\)/);
  });

  it('имя отправителя тоже чистится', () => {
    // В каналах `from` — это заголовок канала или подпись, куда оператор
    // спокойно вписывает контактный номер.
    expect(CODE).toMatch(/redactPII\(m\.from\)/);
  });

  it('образцы сообщений в agent_memory сохраняются очищенными', () => {
    // Они оттуда попадают в дайджесты и подсказки агентам — то есть уезжают
    // в модель повторно, уже с другого конца.
    const sample = /sample_messages:[\s\S]{0,300}/.exec(CODE)?.[0] ?? '';
    expect(sample, 'не разобрать блок sample_messages').not.toBe('');
    expect(sample).toMatch(/redactPII/);
  });

  it('сырой шаблон `[${m.from}]: ${m.text}` в файле отсутствует', () => {
    // Точная форма, которая была до правки. Вернётся — упадём.
    expect(CODE).not.toMatch(/\[\$\{m\.from\}\]:\s*\$\{m\.text\}/);
  });
});

describe('чистилка справляется с реальным постом оператора', () => {
  const POST = [
    'Однодневная экскурсия «Сплав по реке Быстрая». Цена: 13000 рублей с человека.',
    'Свободные даты: 30.07; 1.08; 3.08.',
    '+79147817114 , Ярослав',
    '+7 924 790-19-11, Екатерина',
    'почта: operator@example.com',
  ].join('\n');

  it('оба телефона и почта заменены', () => {
    const clean = redactPII(POST);
    expect(clean).not.toMatch(/79147817114/);
    expect(clean).not.toMatch(/790-19-11/);
    expect(clean).not.toContain('operator@example.com');
    expect(hasPII(clean)).toBe(false);
  });

  it('цена и даты остаются — они не персональные данные', () => {
    const clean = redactPII(POST);
    expect(clean).toContain('13000');
    expect(clean).toContain('30.07');
    expect(clean).toContain('Сплав по реке Быстрая');
  });
});
