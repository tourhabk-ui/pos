import { describe, it, expect } from 'vitest';
import { redactPII, hasPII, redactChatPD } from '@/lib/security/pii-redact';

describe('redactPII — режет телефоны и email перед зарубежным LLM', () => {
  it('российский телефон в разных форматах → [телефон]', () => {
    expect(redactPII('звоните +7 999 123-45-67')).toBe('звоните [телефон]');
    expect(redactPII('89991234567 мой номер')).toBe('[телефон] мой номер');
    expect(redactPII('тел 8 (999) 123 45 67')).toContain('[телефон]');
  });

  it('email → [email]', () => {
    expect(redactPII('пишите ivan.petrov@mail.ru пожалуйста')).toBe('пишите [email] пожалуйста');
  });

  it('телефон + email вместе', () => {
    const out = redactPII('Иван, +79991234567, ivan@gmail.com');
    expect(out).toContain('[телефон]');
    expect(out).toContain('[email]');
    expect(out).not.toMatch(/79991234567|ivan@gmail/);
  });

  it('НЕ трогает короткие числа: цены, даты, группу', () => {
    expect(redactPII('бюджет 100000 рублей на 5 человек, даты 2026-07-15')).toBe(
      'бюджет 100000 рублей на 5 человек, даты 2026-07-15',
    );
  });

  // Ревью A20 (аудит 15.10): реплика туриста идёт через redactPII к модели
  // Кузьмича, и прежнее «10–15 цифр, точка — разделитель» съедало даты,
  // координаты и бюджет. Модель обязана их видеть.
  it.each([
    'даты 10-15.08.2026',
    'с 15.07-20.07.2026',
    'бюджет 150 000 - 200 000 руб',
    'бюджет 150000-200000',
    'бюджет 30000-50000 на человека',
    'погода 53.2551 158.8432',
    'точка 53.9551234 158.8432101',
    'даты 2026-07-15 - 2026-07-20',
  ])('не-ПД с цифрами остаётся как есть: %s', (text) => {
    expect(redactPII(text)).toBe(text);
    expect(hasPII(text)).toBe(false);
  });

  it.each([
    ['+7 914 123-45-67', '[телефон]'],
    ['89141234567', '[телефон]'],
    ['8 (4152) 41-23-18', '[телефон]'],
    ['8 (41531) 6-12-34', '[телефон]'],
    ['+86 138 0013 8000', '[телефон]'],
    ['тел.89141234567', 'тел.[телефон]'],
    ['звоните +7 (914) 123-45-67.', 'звоните [телефон].'],
    // дата перед номером не прячет номер и не съедается вместе с ним
    ['Свободные даты: 30.07 89141234567', 'Свободные даты: 30.07 [телефон]'],
    // дефис с пробелом — граница: номер слева, число справа
    ['звоните 8 914 123 45 67 - 2 раза', 'звоните [телефон] - 2 раза'],
    ['89141234567,89141234568', '[телефон],[телефон]'],
    // Один дефис между частями РАЗНОЙ длины — номер, а не диапазон бюджета.
    ['звоните 8914-1234567', 'звоните [телефон]'],
    ['городской 4152-412318', 'городской [телефон]'],
    ['84152-412318', '[телефон]'],
    // Части одной длины, но по убыванию — не диапазон.
    ['2000000-1000000', '[телефон]'],
  ])('настоящий номер вырезается: %s', (text, expected) => {
    expect(redactPII(text)).toBe(expected);
  });

  // Ревью безопасности #3204 (10.11): цепочка цифр судилась целиком, и номер
  // рядом с датой или бюджетом давал больше 15 цифр — уходил модели дословно.
  it.each([
    // Номер одним словом вырезается сам; числа рядом остаются.
    ['звоните +70000000000 10-14 2 дня отдыха', 'звоните [телефон] 10-14 2 дня отдыха'],
    ['звоните 80000000000 10000 рублей', 'звоните [телефон] 10000 рублей'],
    ['+70000000000 10-14 июля', '[телефон] 10-14 июля'],
    ['бюджет 150000-200000 80000000000', 'бюджет 150000-200000 [телефон]'],
    ['2 80000000000 3 80000000001 4', '2 [телефон] 3 [телефон] 4'],
    ['8(900)000-00-00 10000', '[телефон] 10000'],
    // Номер с пробелами — цепочка: вырезается вместе с числами рядом.
    ['звоните 900 000 00 00', 'звоните [телефон]'],
    ['звоните 8 900 000 00 00 10000 рублей', 'звоните [телефон] рублей'],
    ['10 14 8 900 000 00 00 150 000', '[телефон]'],
    // Номер-слово среди слов цепочки: остаток цепочки судится отдельно.
    ['80000000000 8 900 000 00 01', '[телефон] [телефон]'],
    ['8 900 000 00 01 80000000000', '[телефон] [телефон]'],
    ['80000000000 150 000', '[телефон] 150 000'],
  ])('номер рядом с другими числами не проходит: %s', (text, expected) => {
    expect(redactPII(text)).toBe(expected);
    expect(hasPII(text)).toBe(true);
  });

  it('хвост номера для кабинета партнёра — цифры самого номера, а не числа рядом', () => {
    expect(redactPII('найди +70000001234 10-14 2', { keepPhoneTail: true })).toBe('найди [телефон …1234] 10-14 2');
  });

  it('одно слово длиннее 15 цифр — идентификатор, а не номер: вывод инструментов не ломается', () => {
    for (const text of ['запись dddddddd-0000-4000-8000-000000000001', 'счёт 40817810000000000001', '"id":"0000-4000-8000-000000000001","n":2']) {
      expect(redactPII(text)).toBe(text);
      expect(hasPII(text)).toBe(false);
    }
    // Номер рядом с идентификатором всё равно вырезается, а сам он остаётся.
    expect(redactPII('0000-4000-8000-000000000001 80000000000')).toBe('0000-4000-8000-000000000001 [телефон]');
    expect(redactPII('0000-4000-8000-000000000001 8 900 000 00 00')).toBe('0000-4000-8000-000000000001 [телефон]');
    expect(redactPII('запись 0000-4000-8000-000000000001 2 шт')).toBe('запись 0000-4000-8000-000000000001 2 шт');
    // Диапазон бюджета рядом с числом — тоже не цепочка.
    expect(redactPII('бюджет 150000-200000 2 взрослых')).toBe('бюджет 150000-200000 2 взрослых');
  });

  it('цифры вокруг слов — не цепочка: состав, даты и бюджет остаются', () => {
    const text = 'с 10 по 14 августа 2027 года, 2 взрослых и 2 детей 4 и 9 лет, бюджет 300 000';
    expect(redactPII(text)).toBe(text);
  });

  it('чистый текст без ПД не меняется', () => {
    const clean = 'Хочу на вулкан Авачинский в июле, группа 3 человека';
    expect(redactPII(clean)).toBe(clean);
    expect(hasPII(clean)).toBe(false);
  });

  it('hasPII детектит наличие ПД', () => {
    expect(hasPII('мой +7 999 123 45 67')).toBe(true);
    expect(hasPII('a@b.ru')).toBe(true);
    expect(hasPII(null)).toBe(false);
  });

  it('пустой/nullable → пустая строка', () => {
    expect(redactPII(null)).toBe('');
    expect(redactPII(undefined)).toBe('');
    expect(redactPII('')).toBe('');
  });
});

describe('redactChatPD — маска Telegram (разбор 03.11)', () => {
  it('имя, ник, vk и телефон', () => {
    const out = redactChatPD('Здравствуйте, меня зовут Анна Петрова, пишите vk.com/anna_p или @anna_kam, тел +7 999 123-45-67');
    expect(out).not.toMatch(/Анна|Петрова|anna|123-45-67/);
    expect(out).toContain('[ник]');
    expect(out).toContain('[ссылка]');
  });
  it('«Это Иван.», подпись и известное имя', () => {
    expect(redactChatPD('Это Иван. Хотим на Авачинский')).toBe('Это [имя]. Хотим на Авачинский');
    expect(redactChatPD('Добрый день!\n— Ольга')).not.toMatch(/Ольга/);
    expect(redactChatPD('Сергей будет с женой', ['Сергей Иванов'])).toBe('[имя] будет с женой');
  });
  it('места и почту не путает с ником', () => {
    expect(redactChatPD('Едем к Мутновскому 5 ноября')).toBe('Едем к Мутновскому 5 ноября');
    expect(redactChatPD('почта a.b@mail.ru')).toBe('почта [email]');
  });
});
