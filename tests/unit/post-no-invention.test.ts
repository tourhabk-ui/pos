/**
 * Пост Кузьмича не выдумывает и не уводит с тропы.
 *
 * ── Случай 19.08 ───────────────────────────────────────────────────────────
 *
 * Владелец показал пост про маар «Медвежья чаша». В нём:
 *
 *   «местные знают, что если идти НЕ ПО ТРОПЕ, а чуть в сторону — найдёшь
 *    старую консервную банку с запиской от геологов»
 *
 * Ни банки, ни записки в данных нет. Модель их выдумала — и не по своей воле:
 * промпт ТРЕБОВАЛ «конкретную деталь или секрет этого места, которую знают не
 * все», а взять секрет было неоткуда. У модели есть название, тип и триста
 * знаков описания. Требование, которое нечем выполнить, выполняется выдумкой.
 *
 * Это тот же корень, что у рейтинга 4.5 у перевозчика и у выручки как доли от
 * общей суммы: обязательное поле, для которого нет источника, ПРИНУЖДАЕТ его
 * заполнить враньём.
 *
 * ── Почему это не вопрос вкуса ─────────────────────────────────────────────
 *
 * Выдуманный секрет неприятен. Выдуманный секрет, за которым надо СОЙТИ С
 * ТРОПЫ на кромке тридцатиметрового кратера, отправляет человека искать
 * несуществующее в опасном месте. Платформа существует ради безопасности
 * туриста.
 *
 * Детерминированно ловится не выдумка (её не поймать), а СОВЕТ уйти с тропы —
 * он и делает выдумку опасной.
 */
import { describe, it, expect } from 'vitest';
import { readFileSync } from 'node:fs';
import { join } from 'node:path';
import { advisesLeavingTrail } from '@/lib/notifications/post-validation';

const CHANNEL = readFileSync(join(process.cwd(), 'lib/notifications/telegram-channel.ts'), 'utf-8');

describe('совет уйти с тропы не публикуется', () => {
  it('ловит ровно ту фразу, что вышла в канал', () => {
    expect(advisesLeavingTrail(
      'местные знают, что если идти не по тропе, а чуть в сторону — найдёшь старую консервную банку',
    )).toBe(true);
  });

  it('ловит прочие способы сказать то же', () => {
    for (const t of [
      'сойти с тропы и подняться выше',
      'чуть в стороне от тропы стоит балок',
      'сверни с тропы у камня',
      'идти мимо тропы вдоль ручья',
    ]) {
      expect(advisesLeavingTrail(t), t).toBe(true);
    }
  });

  it('не трогает обычный рассказ о тропе', () => {
    for (const t of [
      'тропа набитая, идёт по гребню',
      'от парковки по тропе полтора часа',
      'тропа зимой не читается — нужен трек',
    ]) {
      expect(advisesLeavingTrail(t), t).toBe(false);
    }
  });

  it('отказ безусловный — не зависит от наличия трека', () => {
    // Обещание трека проверяется только у карточек без трека; уход с тропы
    // опасен на любой.
    expect(CHANNEL).toMatch(/const leavesTrail = advisesLeavingTrail\(text\)/);
    expect(CHANNEL).toMatch(/leavesTrail \|\| \(!r\.has_track/);
  });
});

describe('у поста о месте нет модели — выдумывать некому (решение владельца 05.09)', () => {
  // Третий случай подряд: 12.07 обещание трека, 19.08 «секрет» с уходом с
  // тропы, 05.09 озеро Зелёное — «кратер грязевого вулкана», «растворённое
  // железо», «вода тёплая на ощупь», которых нет в записи. Промпт запрещал
  // выдумывать все три раза. Сторож структурный: текст собирает
  // composePlacePost из полей записи, вызова модели в публикаторе нет.
  const body = CHANNEL.match(/export async function postKuzmichRoute[\s\S]*?\n\}/)?.[0] ?? '';

  it('публикатор найден', () => {
    expect(body).not.toBe('');
  });

  it('текст собирается из данных, а не генерируется', () => {
    expect(body).toMatch(/composePlacePost\(/);
    expect(body).not.toMatch(/callAI|getModelForAgent|prompt/);
  });

  it('промпта о месте с «Ты — Кузьмич» больше нет', () => {
    expect(CHANNEL).not.toMatch(/Напиши короткий пост для Telegram-канала о конкретном месте/);
  });
});

describe('чужого снимка у поста о месте нет (решение владельца 05.09)', () => {
  // Оговорка «на фото не это место» была честной и не спасла: владелец снял
  // пост вместе с фото. Место без своего снимка в канал не идёт.
  const body = CHANNEL.match(/export async function postKuzmichRoute[\s\S]*?\n\}/)?.[0] ?? '';

  it('кандидат выбирается только со своим фото — условие в SQL', () => {
    expect(body).toMatch(/EXISTS \(\s*SELECT 1 FROM ai_route_images i\s*WHERE i\.route_id = ark\.id AND i\.model = ANY\(\$2\)/);
    expect(CHANNEL).toMatch(/OWN_PHOTO_MODELS = \['wikimedia', 'manual-upload'\]/);
  });

  it('фото поста — свой кадр, без фолбэка на чужой', () => {
    expect(body).toMatch(/photoUrl: ownPhotoUrl\(r\.id\)/);
    expect(body).toMatch(/fallbackPhotoUrl: null/);
  });

  it('куратор-каскада и оговорки в коде не осталось', () => {
    expect(CHANNEL).not.toMatch(/NOT_THIS_PLACE_NOTE|buildRoutePhotoUrl|resolvePostPhotoUrl|LOCATION_PHOTO|ofThisPlace/);
  });
});

/**
 * Ссылка в ТЕКСТЕ проверяется, а не только идентификатор в параметре.
 *
 * Все прежние проверки спрашивали базу и прод про `routeId`, пришедший
 * параметром. Но в канал уходит текст, и ссылку в нём пишет модель. Обрежь она
 * группу uuid — проверки останутся зелёными, потому что смотрят не туда, а
 * читатель получит ссылку в никуда при полностью исправном посте.
 *
 * Повод: ссылка из поста 19.08 имеет четыре группы вместо пяти
 * (8-4-6-12 вместо 8-4-4-4-12). Может быть и артефактом переноса в сообщение —
 * подтвердить по скриншоту нельзя. Но проверка формы стоит трёх строк и
 * закрывает случай независимо от того, был он сейчас или будет потом.
 */
describe('ссылка в тексте поста цела и ведёт куда надо', () => {
  const VALIDATION = readFileSync(join(process.cwd(), 'lib/notifications/post-validation.ts'), 'utf-8');
  const CANONICAL = /^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$/i;

  it('канонический uuid проходит, урезанный — нет', () => {
    expect(CANONICAL.test('3aa40826-5dac-4d93-9f76-0b3ae9c48c1e')).toBe(true);
    // Ровно та форма, что пришла из канала: одной группы не хватает.
    expect(CANONICAL.test('3aa40826-5dac-4d9376-0b3ae9c48c1e')).toBe(false);
  });

  it('валидация смотрит на текст, а не только на параметр', () => {
    expect(VALIDATION).toMatch(/Ссылка в тексте содержит испорченный идентификатор/);
    expect(VALIDATION).toMatch(/ведёт на ЧУЖОЙ маршрут/);
  });
});

/**
 * Проверка, которая не выполнилась, не отвечает «всё хорошо».
 *
 * По ссылке из поста 19.08 — 404. При этом проверки ссылок СУЩЕСТВОВАЛИ и были
 * подключены: rule 2 бьёт HEAD по странице маршрута, rule 6 — по всем ссылкам
 * текста. Обе падали в «пропустить»:
 *
 *   checkPageAccessible  при любой ошибке возвращала true с пояснением
 *                        «не блокируем»
 *   verifyAllLinks       сетевой отказ (status 0) считала предупреждением
 *
 * Достаточно было крону не достучаться до собственного домена — и любая
 * ссылка проходила. Проверка, которая при отказе отвечает «хорошо», — это не
 * проверка, а её видимость. Ровно то, что мы весь день разбираем: зелёный
 * smoke при мёртвой карточке, панель тревог с проглоченными запросами, немой
 * решатель при успешном джобе.
 *
 * Разделение простое: СВОЯ страница — то, ради чего пост существует, и
 * непроверенность блокирует. Чужие ссылки остаются предупреждением: чужая
 * недоступность не наша вина и не повод молчать вовсе.
 */
describe('непроверенная ссылка не считается проверенной', () => {
  const VALIDATION = readFileSync(join(process.cwd(), 'lib/notifications/post-validation.ts'), 'utf-8');

  it('у проверки страницы три состояния, а не два', () => {
    expect(VALIDATION).toMatch(/Promise<'ok' \| 'bad' \| 'unknown'>/);
    // Прежнее «не блокируем» ушло вместе с `return true`.
    expect(VALIDATION).not.toMatch(/return true; \/\/ не блокируем/);
  });

  it('непроверенная СВОЯ страница блокирует публикацию', () => {
    expect(VALIDATION).toMatch(/pageState === 'unknown'/);
    expect(VALIDATION).toMatch(/не удалось проверить — пост не публикуется/);
  });

  it('битый идентификатор ловится БЕЗ сети — сеть может и не ответить', () => {
    // Единственная проверка ссылки, которая не зависит от достижимости прода.
    expect(VALIDATION).toMatch(/CANONICAL_UUID/);
    expect(VALIDATION).toMatch(/испорченный идентификатор/);
  });
});
