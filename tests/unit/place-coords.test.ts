/**
 * Правка координаты места — обещания актуатора.
 *
 * Координата отвечает на вопрос «где я», и сдвинутая ведёт человека в
 * другое место. Поэтому у правки обязан быть источник, причина, сухой
 * прогон и обратный ход, а конверт края не должен выдаваться за
 * проверку правды: 156.2 на широте 54.6 лежит внутри конверта и при
 * этом в Охотском море.
 */
import { describe, it, expect } from 'vitest';
import { readFileSync } from 'node:fs';
import { join } from 'node:path';

const ROOT = process.cwd();
const SRC = readFileSync(join(ROOT, 'app/api/cron/place-coords/route.ts'), 'utf-8');

describe('актуатор координат места', () => {
  it('источник и причина обязательны — без них правка неотличима от выдумки', () => {
    expect(SRC).toMatch(/source:\s*z\.string\(\)\.min\(8/);
    expect(SRC).toMatch(/why:\s*z\.string\(\)\.min\(8/);
    // Ни у того, ни у другого нет умолчания — умолчание здесь и есть выдумка.
    expect(SRC).not.toMatch(/source:[^\n]*\.default\(/);
    expect(SRC).not.toMatch(/why:[^\n]*\.default\(/);
  });

  it('сухой прогон по умолчанию, боевая партия ограничена десятью', () => {
    expect(SRC).toMatch(/dry_run:\s*z\.boolean\(\)\.default\(true\)/);
    expect(SRC).toContain('LIVE_BATCH_MAX = 10');
    expect(SRC).toMatch(/!data\.dry_run && data\.fixes\.length > LIVE_BATCH_MAX/);
  });

  it('старая координата возвращается — это обратный ход', () => {
    expect(SRC).toMatch(/from:\s*\{\s*lat: oldLat, lng: oldLng\s*\}/);
    expect(SRC).toContain('movedKm');
  });

  it('пишет только в неслитое место и только координату', () => {
    // `is_visible = true` здесь стояло до 20.09 и было снято намеренно:
    // скрытому месту координату править нужно, и как раз ему — скрывают
    // обычно испорченную запись, а показать её обратно нельзя, пока
    // координата не исправлена. Разбор — ниже, в «три положения дел».
    expect(SRC).toMatch(/UPDATE places[\s\S]{0,300}merged_into_id IS NULL/);
    // Никаких попутных полей: правка координаты не переписывает описание.
    expect(SRC).not.toMatch(/UPDATE places[\s\S]{0,200}description\s*=/);
  });

  it('строка, которая не обновилась, попадает в отчёт, а не молчит', () => {
    expect(SRC).toContain('строка не обновилась');
  });

  it('конверт края назван грубым фильтром, а не проверкой правды', () => {
    // Сам конверт есть...
    expect(SRC).toContain('KRAI_LAT_MIN');
    expect(SRC).toContain('KRAI_LNG_MAX');
    // ...и в шапке сказано, что случай Тюшевских он не ловит: место в
    // море, но внутри конверта. Иначе через месяц кто-нибудь решит, что
    // координаты проверены.
    expect(SRC).toMatch(/НЕ ловит|не ловит/);
  });

  it('параметризованный SQL, без конкатенации', () => {
    expect(SRC).toMatch(/\$1/);
    expect(SRC).not.toMatch(/`[^`]*\$\{[^}]*\}[^`]*(WHERE|SET)/);
  });
});

/**
 * Скрытое место — не «места нет» (20.09).
 *
 * ── Чего стоило одно сообщение на три разных случая ───────────────────────
 *
 * Сухой прогон по «Каньону Сноубордистов» отказал словами «живого места с
 * таким id нет». Id был верен: запись существует, не слита и в ту же минуту
 * отвечала живым MCP. Она просто СКРЫТА — а оба условия стояли прямо в JOIN,
 * и любое из трёх положений дел давало одну и ту же строку. Время ушло на
 * поиск ошибки в id, которой не было.
 *
 * Хуже потерянного времени — замкнутый круг, который создавал этот фильтр.
 * Скрывают обычно как раз испорченную запись: миграции 947 и 948 спрятали
 * места, чью координату нечем было подтвердить. Показать такую обратно
 * нельзя, пока координата не исправлена, а исправить было нельзя, пока она
 * скрыта. Инструмент починки отказывал ровно тем, ради кого заводился.
 *
 * Слитая запись из правки НЕ выпущена: это надгробие, указывающее на другую
 * строку, и двигать её координату незачем — но теперь об этом говорится
 * отдельным словом, а не общим отказом.
 */
describe('три положения дел — три разных слова', () => {
  const SRC_V2 = readFileSync(join(process.cwd(), 'app/api/cron/place-coords/route.ts'), 'utf-8');
  /** Код без комментариев: сам разбор объясняет, что здесь стояло раньше. */
  const CODE_V2 = SRC_V2.replace(/\/\*[\s\S]*?\*\//g, '').replace(/(^|[^:])\/\/[^\n]*/g, '$1');

  it('выборка больше не отсеивает скрытые — состояние разбирается в коде', () => {
    expect(CODE_V2).not.toMatch(/LEFT JOIN places p[\s\S]{0,120}is_visible = true/);
    expect(CODE_V2).toContain('p.is_visible');
    expect(CODE_V2).toContain('p.merged_into_id');
  });

  it('«нет вовсе», «слито» и «скрыто» различимы', () => {
    expect(SRC_V2).toContain('места с таким id нет вовсе');
    expect(SRC_V2).toContain('это надгробие');
    // Скрытость не отказ, а пометка в плане: правка разрешена.
    expect(CODE_V2).toMatch(/hidden:\s*r\.is_visible === false/);
  });

  it('боевая правка скрытому месту разрешена, слитому — нет', () => {
    const at = CODE_V2.indexOf('UPDATE places');
    const upd = CODE_V2.slice(at, at + 220);
    expect(upd).toContain('merged_into_id IS NULL');
    expect(upd, 'скрытое место снова заперто: чинить его нечем').not.toContain('is_visible = true');
  });
});
