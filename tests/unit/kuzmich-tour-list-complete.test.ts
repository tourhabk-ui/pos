import { describe, it, expect } from 'vitest';
import { completeTourList, budgetOf } from '@/lib/kuzmich/tour-list-complete';

const T41 = 'ID41: "Вулкан Плоский Толбачик" — Вулкан Плоский Толбачик  тип:trekking 4 дн. от 60 000 ₽/чел. | Оп: Край Вулканов | Расписания в системе нет';
const T73 = 'ID73: "Толбачик: по следам извержений, 4 дня" — Вулкан Плоский Толбачик  тип:volcano 4 дн. от 85 000 ₽/чел. | Оп: Андрей Запорожец | Мест: 4';
const T65 = 'ID65: "Вулкан Толбачик (джип-тур, 4 дня)" — Вулкан Толбачик  тип:jeep_safari 4 дн. от 115 000 ₽/чел. | Оп: Местечко Камчатка';
const OUT = [T41, T73, T65].join('\n');

describe('completeTourList', () => {
  it('дописывает пропущенные туры с компанией и ценой из get_tours', () => {
    const a = 'На Толбачик есть «Вулкан Плоский Толбачик» — Край Вулканов, от 60 000 ₽.';
    const r = completeTourList(a, 'какие туры на Толбачик?', [{ query: 'толбачик', output: OUT }]);
    expect(r).toContain('«Толбачик: по следам извержений, 4 дня» — Андрей Запорожец, от 85 000 ₽/чел.');
    expect(r).toContain('«Вулкан Толбачик (джип-тур, 4 дня)» — Местечко Камчатка, от 115 000 ₽/чел.');
    expect(r).toContain('подтверждает оператор');
  });
  it('дописывает компанию к названному туру без неё', () => {
    const a = '- «Вулкан Плоский Толбачик», от 60 000 ₽\n- «Толбачик: по следам извержений, 4 дня» — Андрей Запорожец\n- «Вулкан Толбачик (джип-тур, 4 дня)» — Местечко Камчатка';
    const r = completeTourList(a, 'туры на Толбачик', [{ query: 'толбачик', output: OUT }]);
    expect(r).toContain('Кто проводит:\n- «Вулкан Плоский Толбачик» — Край Вулканов');
    expect(r).not.toContain('Ещё по запросу');
  });
  it('помечает тур дороже бюджета и не дописывает туры вне бюджета', () => {
    const a = '«Вулкан Плоский Толбачик» (Край Вулканов) от 60 000 ₽ и «Вулкан Толбачик (джип-тур, 4 дня)» (Местечко Камчатка) от 115 000 ₽.';
    const r = completeTourList(a, 'Толбачик до 70 000 ₽', [{ query: 'толбачик', output: OUT }]);
    expect(r).toContain('Дороже бюджета 70 000 ₽');
    expect(r).not.toContain('по следам извержений');
  });
  it('не трогает ответ без туров, весь каталог и уже полный ответ', () => {
    expect(completeTourList('Сейчас на Толбачике опасно.', 'q', [{ query: 'толбачик', output: OUT }])).toBe('Сейчас на Толбачике опасно.');
    const a = '«Вулкан Плоский Толбачик» от 60 000 ₽';
    expect(completeTourList(a, 'q', [{ query: '', output: OUT }])).toBe(a);
    const full = '- «Вулкан Плоский Толбачик» — Край Вулканов\n- «Толбачик: по следам извержений, 4 дня» — Андрей Запорожец\n- «Вулкан Толбачик (джип-тур, 4 дня)» — Местечко Камчатка';
    expect(completeTourList(full, 'q', [{ query: 'толбачик', output: OUT }])).toBe(full);
  });
  it('бюджет — только при «до/бюджет»', () => {
    expect(budgetOf('туры до 50 000 ₽')).toBe(50000);
    expect(budgetOf('на двоих в июле')).toBeNull();
  });
});
