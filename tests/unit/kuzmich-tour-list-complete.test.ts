import { describe, it, expect } from 'vitest';
import { completeTourList, budgetOf, questionQueries } from '@/lib/kuzmich/tour-list-complete';

const T41 = 'ID41: "Вулкан Плоский Толбачик" — Вулкан Плоский Толбачик  тип:trekking 4 дн. от 60 000 ₽/чел. | Оп: Край Вулканов | Расписания в системе нет';
const T73 = 'ID73: "Толбачик: по следам извержений, 4 дня" — Вулкан Плоский Толбачик  тип:volcano 4 дн. от 85 000 ₽/чел. | Оп: Андрей Запорожец | Мест: 4';
const T65 = 'ID65: "Вулкан Толбачик (джип-тур, 4 дня)" — Вулкан Толбачик  тип:jeep_safari 4 дн. от 115 000 ₽/чел. | Оп: Местечко Камчатка';
const OUT = [T41, T73, T65].join('\n');

describe('completeTourList', () => {
  it('дописывает пропущенные туры с компанией и ценой из get_tours', () => {
    const a = 'На Толбачик есть «Вулкан Плоский Толбачик» — Край Вулканов, от 60 000 ₽.';
    const r = completeTourList(a, 'какие туры на Толбачик?', [{ query: 'толбачик', output: OUT }]);
    expect(r).toContain('«Толбачик: по следам извержений, 4 дня» — Андрей Запорожец, от 85 000 ₽/чел.');
    expect(r).toContain('«Вулкан Толбачик (джип-тур, 4 дня)» — Местечко Камчатка, от 115 000 ₽/чел.');
    expect(r).toContain('подтверждает оператор');
  });
  it('дописывает компанию к названному туру без неё', () => {
    const a = '- «Вулкан Плоский Толбачик», от 60 000 ₽\n- «Толбачик: по следам извержений, 4 дня» — Андрей Запорожец\n- «Вулкан Толбачик (джип-тур, 4 дня)» — Местечко Камчатка';
    const r = completeTourList(a, 'туры на Толбачик', [{ query: 'толбачик', output: OUT }]);
    expect(r).toContain('Кто проводит:\n- «Вулкан Плоский Толбачик» — Край Вулканов');
    expect(r).not.toContain('Ещё по запросу');
  });
  it('помечает тур дороже бюджета и не дописывает туры вне бюджета', () => {
    const a = '«Вулкан Плоский Толбачик» (Край Вулканов) от 60 000 ₽ и «Вулкан Толбачик (джип-тур, 4 дня)» (Местечко Камчатка) от 115 000 ₽.';
    const r = completeTourList(a, 'Толбачик до 70 000 ₽', [{ query: 'толбачик', output: OUT }]);
    expect(r).toContain('Дороже бюджета 70 000 ₽');
    expect(r).not.toContain('по следам извержений');
  });
  it('не трогает ответ без туров, весь каталог и уже полный ответ', () => {
    expect(completeTourList('Сейчас на Толбачике опасно.', 'q', [{ query: 'толбачик', output: OUT }])).toBe('Сейчас на Толбачике опасно.');
    const a = '«Вулкан Плоский Толбачик» (Край Вулканов) от 60 000 ₽';
    expect(completeTourList(a, 'q', [{ query: '', output: OUT }])).toBe(a);
    const full = '- «Вулкан Плоский Толбачик» — Край Вулканов\n- «Толбачик: по следам извержений, 4 дня» — Андрей Запорожец\n- «Вулкан Толбачик (джип-тур, 4 дня)» — Местечко Камчатка';
    expect(completeTourList(full, 'q', [{ query: 'толбачик', output: OUT }])).toBe(full);
  });
  it('бюджет — только при «до/бюджет»', () => {
    expect(budgetOf('туры до 50 000 ₽')).toBe(50000);
    expect(budgetOf('на двоих в июле')).toBeNull();
  });
  it('опечатка в вопросе → слово каталога (только из БД)', () => {
    const cat = 'ID12: "Восхождение на вулкан Горелый" — Горелый тип:volcano от 15 000 ₽/чел. | Оп: Андрей Запорожец\nID30: "Курильское озеро" — Курильское озеро тип:bears от 90 000 ₽/чел. | Оп: Лагуна Экспедиция\nID50: "Халактырский пляж" — Халактырский пляж тип:jeep_safari от 7 000 ₽/чел. | Оп: Местечко Камчатка';
    expect(questionQueries('горелай вулкан тур', cat)).toContain('горелый');
    expect(questionQueries('куриское озеро туры какие', cat)).toContain('курильское');
    expect(questionQueries('халактырскй пляж тур', cat)).toContain('халактырский');
    expect(questionQueries('Есть тур на Луну с Камчатки?', cat)).toEqual([]);
  });
  it('компания по каталогу, когда модель брала тур из get_tour_details (бюджет/месяц)', () => {
    const a = 'В июле: «Вулкан Толбачик (джип-тур, 4 дня)» — от 115 000 ₽.';
    const r = completeTourList(a, 'Медведи в июле: какие туры есть?', [], OUT);
    expect(r).toContain('Кто проводит:\n- «Вулкан Толбачик (джип-тур, 4 дня)» — Местечко Камчатка');
    expect(r).not.toContain('Ещё по запросу');
  });
  it('порог 15 — на каждый запрос: широкий запрос не гасит узкий', () => {
    const wide = Array.from({ length: 20 }, (_, i) => `ID${200 + i}: "Тур ${i}" — x тип:volcano от 1 000 ₽/чел. | Оп: Оп${i}`).join('\n');
    const a = 'На Толбачик есть «Вулкан Плоский Толбачик» — Край Вулканов, от 60 000 ₽.';
    const r = completeTourList(a, 'горелай вулкан Толбачик', [{ query: 'вулкан', output: wide }, { query: 'толбачик', output: OUT }]);
    expect(r).toContain('по следам извержений');
    expect(r).not.toContain('Тур 3');
  });
  it('рыбалка до 20 000: цена за группу и за день не сравнивается с бюджетом, а называется', () => {
    const fish = [
      'ID37: "Зимняя рыбалка: январь — март" — Рыболовная база  тип:fishing  от 18 000 ₽/чел. в день | Оп: Камчатская рыбалка | Мест: 10',
      'ID4: "Осенняя рыбалка (октябрь-ноябрь)" — Рыболовная база  тип:fishing  от 25 000 ₽/чел. в день | Оп: Камчатская рыбалка | Мест: 10',
      'ID7: "Семейный тур выходного дня" — Рыболовная база  тип:fishing 2 дн. от 45 000 ₽/группа | Оп: Камчатская рыбалка',
    ].join('\n');
    const a = 'Есть «Зимняя рыбалка: январь — март» — Камчатская рыбалка.';
    const r = completeTourList(a, 'Рыбалка до 20 000 рублей — что есть?', [{ query: 'fishing', output: fish }]);
    expect(r).toContain('Цена не за человека — с бюджетом 20 000 ₽ напрямую не сравнить');
    expect(r).toContain('«Семейный тур выходного дня» — Камчатская рыбалка, от 45 000 ₽/группа — цена за группу, уточните у оператора');
    expect(r).toContain('от 25 000 ₽/чел. в день — цена с человека за день, дороже бюджета уже за один день');
    expect(r).toContain('от 18 000 ₽/чел. в день — цена с человека за день, итог зависит от числа дней');
    // Пересчёта «на человека» нет: состава группы в данных нет.
    expect(r).not.toMatch(/22 500|9 000/);
  });
});

describe('SOS-ответ без дописки (разбор 03.11, п.6)', () => {
  it('экстренный вопрос — ответ не трогается', () => {
    const a = 'Звоните 112. «Вулкан Плоский Толбачик» — оставайтесь на месте.';
    const q = 'помогите, на Толбачике сломал ногу, что делать';
    expect(completeTourList(a, q, [{ query: 'толбачик', output: OUT }])).toBe(a);
  });
});

describe('просьба о плане — без дописки (аудит планировщика 07.11, K1; ai-debug run 22)', () => {
  // Живой ответ run 22: план на июль, а под ним «Ещё по запросу на платформе» —
  // весь список рыбалки, зимняя тоже. Туры плана выбраны по дням и датам.
  const FISH = [
    'ID4: "Летняя рыбалка на чавычу и нерку" — Рыболовная база  тип:fishing  от 28 000 ₽/чел. в день | Оп: Камчатская рыбалка | Мест: 6',
    'ID37: "Зимняя рыбалка: январь — март" — Рыболовная база  тип:fishing  от 18 000 ₽/чел. в день | Оп: Камчатская рыбалка | Мест: 10',
    'ID38: "Осенняя рыбалка (октябрь-ноябрь)" — Рыболовная база  тип:fishing  от 25 000 ₽/чел. в день | Оп: Камчатская рыбалка',
  ].join('\n');
  const PLAN = 'День 4. «Летняя рыбалка на чавычу и нерку» — Камчатская рыбалка, от 28 000 ₽/чел. в день.';

  it('к плану не приклеивается весь список вида', () => {
    const q = 'Составь план на 5 дней в июле 2027 для двоих: рыбалка, вулкан, жильё и машина';
    expect(completeTourList(PLAN, q, [{ query: 'fishing', output: FISH }])).toBe(PLAN);
    expect(completeTourList(PLAN, 'Нас теперь трое, пересобери план', [{ query: 'fishing', output: FISH }])).toBe(PLAN);
  });

  it('к сравнению названных туров не приклеивается список (ai-debug run 23)', () => {
    const compare = '«Летняя рыбалка на чавычу и нерку» — от 28 000 ₽/чел. в день, «Осенняя рыбалка (октябрь-ноябрь)» — от 25 000 ₽/чел. в день.';
    const q = 'Сравни туры «Летняя рыбалка на чавычу и нерку» и «Осенняя рыбалка (октябрь-ноябрь)»: чем отличаются?';
    expect(completeTourList(compare, q, [{ query: 'fishing', output: FISH }])).toBe(compare);
  });

  it('вопрос о турах вида — дописка прежняя', () => {
    const r = completeTourList(PLAN, 'Какая рыбалка есть?', [{ query: 'fishing', output: FISH }]);
    expect(r).toContain('Ещё по запросу на платформе');
    expect(r).toContain('«Зимняя рыбалка: январь — март» — Камчатская рыбалка');
  });
});

describe('completeTourList: группа из мест тура', () => {
  it('цена за группу с местами тура: «до N чел.» и оценка при полной группе (03.11)', () => {
    const fish = [
      'ID37: "Зимняя рыбалка: январь — март" — Рыболовная база  тип:fishing  от 18 000 ₽/чел. в день | Оп: Камчатская рыбалка | Мест: 10',
      'ID7: "Семейный тур выходного дня" — Рыболовная база  тип:fishing 2 дн. от 45 000 ₽/группа (за группу до 14 чел.; при полной группе ≈ 3 214 ₽/чел.) | Оп: Камчатская рыбалка',
    ].join('\n');
    const r = completeTourList('Есть «Зимняя рыбалка: январь — март» — Камчатская рыбалка.', 'Рыбалка до 20 000 рублей — что есть?', [{ query: 'fishing', output: fish }]);
    expect(r).toContain('цена за группу до 14 чел., при полной группе ≈ 3 214 ₽/чел.');
  });
});

describe('completionSources — источник дописки идёт в журнал судьи', () => {
  it('возвращает только строки дописанных туров', async () => {
    const { completionSources } = await import('@/lib/kuzmich/tour-list-complete');
    const a = 'На Толбачик есть «Вулкан Плоский Толбачик» — Край Вулканов, от 60 000 ₽.';
    const r = completeTourList(a, 'какие туры на Толбачик?', [{ query: 'толбачик', output: OUT }]);
    const src = completionSources(a, r, [OUT]);
    expect(src).toContain('ID73');
    expect(src).toContain('ID65');
    expect(src).not.toContain('ID41');
  });
  it('без дописки — пусто', async () => {
    const { completionSources } = await import('@/lib/kuzmich/tour-list-complete');
    expect(completionSources('x', 'x', [OUT])).toBe('');
  });
});
