/**
 * Фраза про даты тура и горизонт витрины — чистые функции (22.10, «Открой
 * даты словами», этап B, правки ревью).
 *
 * - `datesPhraseRefusal`: открывать можно только по фразе с глаголом
 *   открытия, без закрытия, отрицания, исключения и вопроса. Ключ
 *   классификатора «слоты на» ведёт в помощник и «закрой слоты на …», и
 *   «заблокируй слоты на …», и вопрос «есть ли слоты на … для 8 человек» — до
 *   22.10 такие фразы ОТКРЫВАЛИ дату. Список глаголов закрытия всегда неполон,
 *   поэтому решает разрешающий список (глагол открытия), а не запретный.
 *   Границы слов — по буквам Юникода: `\b` JavaScript кириллицу не знает, и
 *   «Горелый» не должен давать «р.», а «открой» — «не откр».
 * - `dayFilterWord`: дни недели и периодичность помощник не разбирает — и
 *   не должен молча открывать каждый день диапазона.
 * - `isoDatesInPhrase`: две даты — диапазон только при явной связке; «A и B»
 *   — ровно две даты (до 22.10 открывались все дни между ними).
 * - `phraseMentionsPrice`: цена во фразе замечается, а не пропускается молча.
 * - `horizonLastDate`: тот же день через год, как `+ INTERVAL '1 year'` у
 *   витрины, а не 365 дней (сверка с PostgreSQL — в
 *   tests/integration/tour-dates-open.pg.test.ts).
 */
import { describe, it, expect } from 'vitest';
import { datesPhraseRefusal, dayFilterWord, isoDatesInPhrase, phraseMentionsPrice } from '@/lib/tours/dates-phrase';
import { horizonLastDate } from '@/lib/tours/availability-open';

describe('datesPhraseRefusal', () => {
  it.each([
    ['закрой слоты на 5 июля', 'close', 'закрой'],
    ['Закрыть даты туру 42', 'close', 'Закрыть'],
    ['убери 3 августа', 'close', 'убери'],
    ['убрать слоты', 'close', 'убрать'],
    ['удали даты', 'close', 'удали'],
    ['сними 3 августа', 'close', 'сними'],
    ['отмени слоты на 3 августа', 'close', 'отмени'],
    // Синонимы закрытия, которые до ревью 22.10 открывали дату.
    ['заблокируй слоты на 2027-07-05, группа 8 человек набрана', 'close', 'заблокируй'],
    ['блокируй 5 июля', 'close', 'блокируй'],
    ['скрой слоты на 5 июля, там уже 8 человек', 'close', 'скрой'],
    ['скрыть даты туру 42', 'close', 'скрыть'],
    ['отключи слоты на 5 июля', 'close', 'отключи'],
    ['выключи 5 июля', 'close', 'выключи'],
    ['останови продажу: слоты на 5 июля', 'close', 'останови'],
    ['приостанови слоты на 5 июля', 'close', 'приостанови'],
    ['стоп слоты на 5 июля, 8 человек', 'close', 'стоп'],
    ['прекрати продажу 5 июля', 'close', 'прекрати'],
    ['уменьши слоты на 5 июля до 8 мест', 'close', 'уменьши'],
    ['сократи места 5 июля до 8', 'close', 'сократи'],
    ['убавь слоты на 5 июля', 'close', 'убавь'],
    ['не открывай 3 августа', 'negation', 'не открывай'],
    ['не надо открывать 3 августа', 'negation', 'не надо открывать'],
    ['НЕ НУЖНО открывать', 'negation', 'НЕ НУЖНО открывать'],
    ['не добавляй слоты', 'negation', 'не добавляй'],
    ['не выставляй 5 июля', 'negation', 'не выставляй'],
    ['открой субботы июля кроме 17-го', 'exception', 'кроме'],
    ['открой июль, не считая 17', 'exception', 'не считая'],
    ['открой июль за исключением 17', 'exception', 'за исключением'],
    ['открой с 1 по 10 без 5', 'exception', 'без 5'],
    // Вопрос — не просьба, даже с глаголом открытия.
    ['есть ли свободные слоты на 2027-07-05 по туру 42 для 8 человек', 'question', 'ли'],
    ['можно открыть даты туру 42 2027-07-05, 8 мест?', 'question', '?'],
    ['сколько слоты на 5 июля', 'question', 'сколько'],
    ['покажи слоты на 5 июля туру 42', 'question', 'покажи'],
  ])('«%s» — %s', (phrase, kind, word) => {
    expect(datesPhraseRefusal(phrase)).toEqual({ kind, word });
  });

  it.each([
    'слоты на 2027-07-05 туру 42, тур Горелый, 8 мест',
    'новые слоты на 2027-07-05 туру 42, 8 мест',
    'туру 42 2027-07-05, 8 мест',
    'даты открыты 2027-07-05',
    'открытые даты туру 42',
  ])('«%s» — нет глагола открытия: не исполняется', (phrase) => {
    expect(datesPhraseRefusal(phrase)).toEqual({ kind: 'no_open_verb' });
  });

  it.each([
    'открой даты туру 42 2027-07-05, 8 мест',
    'добавь слоты туру 42 с 2027-07-01 по 2027-07-31, 8 мест',
    'открой слоты на 2027-07-05 туру 42, тур Горелый, 8 мест',
    'открой субботы июля на сплав, 6 мест',
    'открыть даты без ограничений по дням',
    'открой даты, группа набирается',
    'нужно открыть 5 июля, 8 мест',
    'выставь даты туру 42 2027-07-05, 8 мест',
    'Откройте 3 и 10 июля, сбор у остановки, 8 мест',
  ])('«%s» — открывать можно', (phrase) => {
    expect(datesPhraseRefusal(phrase)).toBeNull();
  });
});

describe('dayFilterWord — дни недели и периодичность', () => {
  it.each([
    ['добавь слоты по субботам с 2027-07-01 по 2027-07-31', 'субботам'],
    ['открой выходные июля', 'выходные'],
    ['открой будни с 1 по 10', 'будни'],
    ['открой сб и вс', 'сб'],
    ['открой даты по средам', 'средам'],
    ['открой по понедельникам', 'понедельникам'],
    ['открой через день с 1 по 10', 'через день'],
    ['открой по чётным', 'четным'],
    ['открой по нечётным', 'нечетным'],
    ['открой раз в неделю', 'раз в неделю'],
    ['открой каждую неделю', 'каждую неделю'],
  ])('«%s» — «%s»', (phrase, word) => {
    expect(dayFilterWord(phrase)).toBe(word);
  });

  it.each([
    'открой даты туру 42 с 2027-07-01 по 2027-07-31, 8 мест',
    'открой даты туру 42 2027-07-05 и 2027-07-12, 8 мест',
    'открой среди лета 2027-07-05, 8 мест',
    'что открыть 2027-07-05',
  ])('«%s» — ограничения нет', (phrase) => {
    expect(dayFilterWord(phrase)).toBeNull();
  });
});

describe('isoDatesInPhrase — диапазон только при явной связке', () => {
  it.each([
    ['с 2027-07-01 по 2027-07-31', '2027-07-01', '2027-07-31'],
    ['от 2027-07-01 до 2027-07-31', '2027-07-01', '2027-07-31'],
    ['2027-07-01 — 2027-07-31', '2027-07-01', '2027-07-31'],
    ['2027-07-01 - 2027-07-31', '2027-07-01', '2027-07-31'],
    ['2027-07-01-2027-07-31', '2027-07-01', '2027-07-31'],
    ['2027-07-01–2027-07-31', '2027-07-01', '2027-07-31'],
  ])('«%s» — диапазон', (phrase, from, to) => {
    expect(isoDatesInPhrase(`открой даты туру 42 ${phrase}, 8 мест`)).toEqual({ kind: 'range', from, to });
  });

  it.each([
    ['2027-08-05 и 2027-08-12', ['2027-08-05', '2027-08-12']],
    ['2027-08-12, 2027-08-05', ['2027-08-05', '2027-08-12']],
    ['2027-08-05, 2027-08-12 и 2027-08-19', ['2027-08-05', '2027-08-12', '2027-08-19']],
    ['2027-08-05, 2027-08-12, и 2027-08-19', ['2027-08-05', '2027-08-12', '2027-08-19']],
    ['2027-08-05', ['2027-08-05']],
    ['на 2027-08-05', ['2027-08-05']],
  ])('«%s» — ровно эти даты', (phrase, dates) => {
    expect(isoDatesInPhrase(`открой даты туру 42 ${phrase}, 8 мест`)).toEqual({ kind: 'list', dates });
  });

  it.each([
    ['2027-08-05 2027-08-12', ['2027-08-05', '2027-08-12']],
    ['2027-08-05 или 2027-08-12', ['2027-08-05', '2027-08-12']],
    ['с 2027-08-05 по 2027-08-12 и 2027-08-19', ['2027-08-05', '2027-08-12', '2027-08-19']],
    ['с 2027-08-05', ['2027-08-05']],
    ['до 2027-08-05', ['2027-08-05']],
    ['начиная с 2027-08-05', ['2027-08-05']],
  ])('«%s» — связь не названа: вопрос, а не догадка', (phrase, dates) => {
    expect(isoDatesInPhrase(`открой даты туру 42 ${phrase}, 8 мест`)).toEqual({ kind: 'unclear', dates });
  });

  it('дат нет — none', () => {
    expect(isoDatesInPhrase('открой даты туру 42, 8 мест')).toEqual({ kind: 'none' });
  });
});

describe('phraseMentionsPrice', () => {
  it.each(['по 15000', 'по 15 000', '500 ₽', '500р.', '500 руб', 'цена 9000', 'стоимость прежняя', 'цену не меняй'])(
    '«%s» — цена', (rest) => {
      expect(phraseMentionsPrice(rest)).toBe(true);
    });

  it.each(['открой даты , ', 'Горелый, сплав', 'на 3 дня', 'с  по  , до 999'])('«%s» — не цена', (rest) => {
    expect(phraseMentionsPrice(rest)).toBe(false);
  });
});

describe('horizonLastDate — тот же день через год, как у витрины', () => {
  it.each([
    ['2026-10-22', '2027-10-22'],
    ['2027-03-01', '2028-03-01'],
    ['2027-02-28', '2028-02-28'],
    ['2028-02-29', '2029-02-28'],
    ['2027-12-31', '2028-12-31'],
  ])('%s → %s', (today, last) => {
    expect(horizonLastDate(today)).toBe(last);
  });

  it('не дата — ошибка вызывающего', () => {
    expect(() => horizonLastDate('2027-02-30')).toThrow(/не дата/);
  });
});
