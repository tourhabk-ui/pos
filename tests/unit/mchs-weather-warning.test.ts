/**
 * Погодное предупреждение МЧС доходит до туриста.
 *
 * 10.08 владелец прислал предупреждение МЧС: охотоморский циклон, очень сильный
 * дождь в ночь на 11 августа, «Тургруппам и охотникам — воздержаться от выхода
 * на маршруты». Классификатор вернул на него пустой список: погодных веток было
 * ровно одна (ветер), и дождь с циклоном не подходил ни под одну категорию.
 * Предупреждение, адресованное буквально нашей аудитории, не доехало ни до
 * ленты безопасности, ни до пуша, ни до Кузьмича — и нигде не было видно, что
 * оно потерялось: тишина выглядела как «угроз нет».
 *
 * Вторая половина той же поломки — категория `info`. Лента безопасности на
 * главной пускает только actionable-типы, и `info` в белый список не входит.
 * То есть штормовые предупреждения (ураган, смерч, сильный ветер) исправно
 * классифицировались, сохранялись в БД и не показывались никому.
 *
 * Фикстура — настоящий текст предупреждения, не пересказ.
 */
import { describe, it, expect } from 'vitest';
import { readFileSync } from 'node:fs';
import { join } from 'node:path';
import {
  classifyMchsItem, classifyMchsItems, mchs_zones,
  addressesTouristsWithBan, isHydrometWarning,
} from '@/lib/services/safety/seismic-parser';

const CYCLONE = `К берегам Камчатки приближается охотоморский циклон. По данным Камчатского гидрометцентра, в первой половине ночи 11 августа в Петропавловске-Камчатском, местами в Елизовском, Усть-Большерецком и на юге Мильковского муниципальных округов прогнозируется очень сильный дождь. Тургруппам и охотникам - воздержаться от выхода на маршруты, особенно в отдалённые и прибрежные районы. Автовладельцам - не пытаться пересечь реки вброд. Владельцам маломерных судов - не выходить на воду.`;

const classify = (text: string, title = '') =>
  classifyMchsItem('mchs/w', title, text, '2026-08-10T10:00:00Z', 'https://t.me/mchs41', 'tg_mchs');

describe('циклон 10.08 — предупреждение больше не теряется', () => {
  it('текст предупреждения вообще классифицируется', () => {
    expect(classifyMchsItems('mchs/w', '', CYCLONE, '2026-08-10T10:00:00Z', 'https://t.me/mchs41', 'tg_mchs'))
      .not.toHaveLength(0);
  });

  it('severity не ниже порога пуша и красного статуса', () => {
    // Ниже двойки нет ни веб-пуша, ни red в recommender_status: предупреждение
    // было бы в базе и не было бы на экране.
    expect(classify(CYCLONE)!.severity).toBeGreaterThanOrEqual(2);
  });

  it('названные округа попадают в зоны, а не уезжают в дефолт', () => {
    const zones = classify(CYCLONE)!.affected_zones;
    // Названы Петропавловск и Елизовский (avachinsky), Усть-Большерецкий
    // (western), Мильковский (центр, ближайшая наша зона — northern).
    expect(zones).toEqual(expect.arrayContaining(['avachinsky', 'western', 'northern']));
  });

  it('живёт часами, а не сутками: погодное окно короткое', () => {
    expect(classify(CYCLONE)!.expires_hours).toBeLessThanOrEqual(48);
  });
});

describe('категория угрозы видна в ленте безопасности', () => {
  // Самая тихая половина поломки: событие классифицировано, сохранено и
  // отфильтровано на выходе. Поэтому проверяем не имя типа, а попадание в тот
  // самый белый список, по которому лента выбирает строки.
  const homeSource = readFileSync(join(process.cwd(), 'app/_home/data.ts'), 'utf-8');
  const whitelist = new Set(
    (homeSource.match(/alert_type IN \(([^)]+)\)/s)?.[1].match(/'([a-z_]+)'/g) ?? [])
      .map((s) => s.replace(/'/g, '')),
  );

  it('белый список ленты вообще найден в исходнике', () => {
    // Если запрос переписали и разметка перестала совпадать — проверки ниже
    // молча стали бы бессодержательными.
    expect(whitelist.size).toBeGreaterThan(3);
  });

  const cases: Array<[string, string]> = [
    ['циклон с ливнем', CYCLONE],
    ['штормовое предупреждение о ветре', 'МЧС предупреждает: ожидается сильный ветер до 25 м/с, порывы в Елизовском округе.'],
  ];

  for (const [name, text] of cases) {
    it(`${name} — тип попадает в ленту`, () => {
      const ev = classify(text);
      expect(ev).not.toBeNull();
      expect(whitelist.has(ev!.alert_type)).toBe(true);
    });
  }
});

describe('порог по адресату работает поверх категорий', () => {
  it('обращение к тургруппам с запретом распознаётся', () => {
    expect(addressesTouristsWithBan(CYCLONE)).toBe(true);
  });

  it('обращение без запрета — не угроза', () => {
    // Просьба зарегистрироваться адресована тем же тургруппам и звучит в
    // каждой второй публикации МЧС. Красного статуса она не заслуживает.
    expect(addressesTouristsWithBan(
      'Тургруппам напоминают: перед выходом зарегистрируйтесь в МЧС.',
    )).toBe(false);
  });

  it('запрет без адресата — не повод поднимать порог', () => {
    expect(addressesTouristsWithBan('Движение по перевалу запрещено для грузового транспорта.')).toBe(false);
  });

  it('порог поднимает severity в чужой категории, а не только в погодной', () => {
    const fire = 'Объявлен особый противопожарный режим. Туристам воздержаться от посещения лесных массивов.';
    const ev = classify(fire)!;
    expect(ev.alert_type).toBe('fire_danger');
    expect(ev.severity).toBeGreaterThanOrEqual(2);
    // И одновременно укорачивает срок: пожарная ветка держит 168 часов, а
    // прямой запрет живёт до следующей сводки, не неделю.
    expect(ev.expires_hours).toBeLessThanOrEqual(48);
  });
});

describe('прогноз отличается от отчёта', () => {
  it('явление в прошедшем времени предупреждением не становится', () => {
    // Иначе «циклон ушёл» повесило бы тревогу на сутки после того, как всё
    // кончилось, — ровно тот дефект, что уже был с новостями о пожарах.
    expect(isHydrometWarning('Циклон покинул полуостров, последствия ливня устранены.')).toBe(false);
  });

  it('явление без прогноза и без обращения — тоже нет', () => {
    expect(isHydrometWarning('За сутки выпало 30 мм осадков.')).toBe(false);
  });

  it('прогноз метели зимой — да', () => {
    expect(isHydrometWarning('Ожидается метель и налипание мокрого снега.')).toBe(true);
  });
});

/**
 * Второй пост владельца 10.08 — инструкция «При угрозе подтопления дворовых
 * территорий необходимо: …». Классификатор вернул пустой список, то есть
 * поступил правильно, — но по неправильной причине: в списке слов стояло
 * `подтопление`, а в тексте `подтоплениЯ`. Правильный ответ по случайности.
 *
 * Та же дыра съедала и настоящее предупреждение с тем же словом в другом
 * падеже, поэтому чинится и то и другое: основы слов вместо словарных форм —
 * и отдельная ветка на жанр памятки.
 */
const ADVISORY = `При угрозе подтопления дворовых территорий необходимо:
Обязательно продумать маршруты эвакуации и места встречи для всех членов семьи.
Если живёшь в частном доме или на первых этажах, поднять электроприборы и ценные вещи на более высокие уровни.
Приготовить мешки с песком для создания временных барьеров против воды.
Позаботься о выводе птиц и сельскохозяйственных животных в безопасные места.
Также необходимо собрать аварийный комплект: запас питьевой воды, фонарь, радиоприёмник на батарейках, аптечку первой помощи.
Единый номер вызова всех экстренных служб - 112.`;

describe('памятка отличается от тревоги', () => {
  it('инструкция «при угрозе …» тревогой не становится', () => {
    // Иначе она уехала бы категорией flood на 120 часов и пять суток висела
    // активной угрозой на карточках маршрутов — как когда-то телеанонс.
    expect(classify(ADVISORY)).toBeNull();
  });

  it('но само слово в другом падеже ловится в настоящем предупреждении', () => {
    // Ровно тот же корень, что в памятке. Правильный ответ на памятку не
    // должен держаться на том, что слово написано в другой форме.
    const ev = classify('Из-за циклона возможны подтопления дорог и низменных участков в Елизовском округе 11 августа.');
    expect(ev).not.toBeNull();
    expect(ev!.alert_type).toBe('flood');
  });

  it('беглая гласная в «паводке» не теряет предупреждение', () => {
    expect(classify('Ожидается прохождение паводка на реках Быстрая и Авача.')).not.toBeNull();
    expect(classify('На реках ожидается паводок.')).not.toBeNull();
  });
});

describe('Мильковский округ знаком карте зон', () => {
  it('не уезжает в дефолт Авачинской группы', () => {
    // Дефолт mchs_zones — ['avachinsky']. Пока округа не было в карте,
    // предупреждение по центру полуострова вешалось на маршруты под ПКГ.
    expect(mchs_zones('на юге Мильковского муниципального округа')).toEqual(['northern']);
  });
});
