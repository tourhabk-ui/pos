/**
 * Сторож: забракованные утверждения видны, а усечение источников — названо.
 *
 * ── Что случилось ─────────────────────────────────────────────────────────
 *
 * Дайджест держался на `unsupported_claims` (24, 25, 28.08), и в отчёт
 * уходил ТОЛЬКО код. Что именно судья забраковал, не видел никто. Разбор
 * молчания канала свёлся к выбору между тремя правдоподобными механизмами —
 * выдумка писателя, усечение источников на входе судьи, разная видимость
 * контекста — при нулевых данных, чтобы этот выбор сделать.
 *
 * Код называет КЛАСС беды, чинят конкретное. Тот же довод, по которому
 * 22.08 к отказу судьи приложили `sample`.
 *
 * ── Второе: судья видел меньше писателя ───────────────────────────────────
 *
 * Расчёт в scout-digest обещал «11200 худшего случая, запас до 16000
 * остаётся», но считал только текст обогащённых статей и забыл заголовки
 * остальных сигналов. При 53 сигналах выходило около 16900 — за потолком.
 * Писатель видит источники целиком, судья — усечённые; утверждение,
 * опирающееся на хвост, честно не находит подтверждения.
 */
import { describe, it, expect } from 'vitest';
import { readFileSync } from 'fs';
import { join } from 'path';
import { describeClaims } from '@/lib/agents/scout-digest';
import { JUDGE_SOURCES_LIMIT } from '@/lib/agents/fact-check';

describe('describeClaims: забракованное читается, а не угадывается', () => {
  it('одно короткое утверждение проходит целиком', () => {
    expect(describeClaims(['ИИ заменил 40% разработчиков'])).toBe('ИИ заменил 40% разработчиков');
  });

  it('несколько утверждений разделены и читаемы', () => {
    const out = describeClaims(['первое утверждение', 'второе утверждение']);
    expect(out).toBe('первое утверждение | второе утверждение');
  });

  it('режет по ЦЕЛЫМ утверждениям и говорит, сколько было всего', () => {
    // Обрубок фразы на середине не даёт понять, к чему судья придрался.
    const claims = ['a'.repeat(90), 'b'.repeat(90), 'c'.repeat(90)];
    const out = describeClaims(claims, 200);
    expect(out).toContain('показано 2 из 3');
    expect(out).not.toContain('c'.repeat(10));
    expect(out.length).toBeLessThanOrEqual(220);
  });

  it('одно утверждение длиннее лимита — режется, но обрез назван', () => {
    const out = describeClaims(['x'.repeat(500)], 200);
    expect(out).toContain('обрезано');
    expect(out).toContain('всего 1');
  });

  it('перенос строки не ломает строку отчёта', () => {
    expect(describeClaims(['первая\nвторая'])).toBe('первая вторая');
  });

  it('пустой список — это отдельный факт, а не пустая строка', () => {
    // «Судья вернул пусто, но выпуск задержан» — состояние, о котором надо
    // знать: молча оно выглядит как отсутствие причины.
    const out = describeClaims([]);
    expect(out.length).toBeGreaterThan(0);
    expect(out).toMatch(/пуст/);
    expect(describeClaims(['   ', ''])).toMatch(/пуст/);
  });
});

describe('судья видит столько же, сколько писатель', () => {
  const FACT = readFileSync(join(process.cwd(), 'lib/agents/fact-check.ts'), 'utf8');

  it('потолок источников поднят выше худшего случая списка сигналов', () => {
    // Худший случай из журнала: 53 сигнала, 16 обогащённых по 700 знаков
    // текста плюс заголовки — порядка 17 тысяч знаков.
    expect(JUDGE_SOURCES_LIMIT).toBeGreaterThan(17_000);
  });

  it('обрез, если он всё же случился, назван вслух внутри промпта', () => {
    // Молчаливый обрез — ложь про полноту: судья считал бы, что видит всё.
    expect(FACT).toMatch(/ИСТОЧНИКИ ОБРЕЗАНЫ/);
    expect(FACT).toMatch(/не записывай его в неподтверждённые/);
  });

  it('лимит — одно число в одном месте, а не литерал в вызове', () => {
    expect(FACT).toMatch(/sources\.slice\(0, JUDGE_SOURCES_LIMIT\)/);
    expect(FACT, 'вернулся зашитый литерал усечения').not.toMatch(/sources\.slice\(0, 16000\)/);
  });
});

describe('отказ по выдумке несёт сами утверждения', () => {
  const SRC = readFileSync(join(process.cwd(), 'lib/agents/scout-digest.ts'), 'utf8');

  it('unsupported_claims сопровождается digest_skip_detail', () => {
    const at = SRC.indexOf("'unsupported_claims'");
    expect(at).toBeGreaterThan(0);
    const around = SRC.slice(at, at + 400);
    expect(around, 'причина снова без содержания: чинить будут вслепую')
      .toContain('describeClaims');
  });
});
