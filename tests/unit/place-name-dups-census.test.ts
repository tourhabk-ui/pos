/**
 * Перепись одноимённых мест: только читает и только сообщает.
 *
 * ── Откуда ────────────────────────────────────────────────────────────────
 *
 * 14.09 владелец прислал десяток своих снимков, и на трёх местах подряд
 * оказалось некуда их положить однозначно: Курильское озеро в каталоге ДВУМЯ
 * записями, Паужетские источники — ЧЕТЫРЬМЯ, у Кутхиных Батов точного id нет
 * вовсе. Снимок каждый раз клался всем одноимённым — поштучно верно, по сути
 * нет.
 *
 * ── Почему не хватало существующего дедупа ────────────────────────────────
 *
 * `POST /api/cron/places-dedup` отбирает пары по БЛИЗОСТИ: окно ±0.02° по
 * широте и ±0.03° по долготе, совпадение `location_type`, похожее имя. Все три
 * условия требуют координат, и в запросе прямо стоит `lat IS NOT NULL` у обеих
 * записей. Значит пару, где координат нет или они врут, он не отберёт ни при
 * каком пороге — а это ровно тот случай, который и мешает: будь координаты у
 * обеих верны, вопрос «какая запись живая» так остро не стоял бы.
 *
 * Перепись группирует по ИМЕНИ и координат не спрашивает. Она не заменяет
 * дедуп: тот чистит то, что видит, эта показывает, чего он не видит.
 *
 * ── Что сторож держит ─────────────────────────────────────────────────────
 *
 * Две вещи, каждая из которых уже стоила репозиторию дорого.
 *
 * ПЕРВОЕ: перепись не пишет. Read-only здесь не стиль, а условие доверия —
 * её зовут, чтобы ПОСМОТРЕТЬ на спорные записи, и запись в этот момент
 * означала бы правку вслепую.
 *
 * ВТОРОЕ: перепись не выносит вердикт «вот эта лишняя». Урок 23.08 стоил бы
 * двадцати одной верной записи из двадцати четырёх: самое сильное согласие в
 * данных принадлежало ПРАВИЛЬНОЙ записи, и автомат испортил бы больше, чем
 * починил. Тёзки существуют — «Видовая точка на горе Верблюд» и та же точка
 * «(нижняя)» суть разные места.
 */
import { describe, it, expect } from 'vitest';
import { readFileSync } from 'node:fs';
import { join } from 'node:path';
import { DECLARED } from '@/lib/agents/cron-schedulers';

const ROUTE = readFileSync(join(process.cwd(), 'app/api/cron/place-name-dups/route.ts'), 'utf-8');
/** Код без комментариев: объяснения в них намеренно говорят о запретах. */
const CODE = ROUTE.replace(/\/\*[\s\S]*?\*\//g, '').replace(/^\s*\/\/.*$/gm, '');

describe('перепись только читает', () => {
  it('ни одной записывающей команды в SQL', () => {
    expect(CODE).not.toMatch(/\b(INSERT|UPDATE|DELETE|TRUNCATE|ALTER|DROP)\b/i);
  });

  it('это GET, а не POST', () => {
    expect(CODE).toMatch(/export async function GET/);
    expect(CODE).not.toMatch(/export async function POST/);
  });

  it('закрыта тем же секретом, что остальные кроны', () => {
    expect(CODE).toMatch(/timingSafeCompare\(secret, process\.env\.CRON_SECRET/);
  });

  it('объявлена в реестре как ручная и НЕ пишущая', () => {
    // Роут без объявления краснеет в cron-scheduler-declared: молчание не ответ.
    const decl = (DECLARED as Record<string, { kind: string; writes?: boolean }>)['place-name-dups'];
    expect(decl, 'place-name-dups не объявлен в cron-schedulers').toBeDefined();
    expect(decl.kind).toBe('manual');
    expect(decl.writes).toBe(false);
  });
});

describe('перепись сообщает факт, а не приговор', () => {
  it('по каждому участнику едет СОСТАВ, по которому решает человек', () => {
    for (const field of ['has_coords', 'has_photo', 'has_safety', 'is_visible', 'merged_into_id']) {
      expect(CODE, `в ответе нет ${field}`).toMatch(new RegExp(field));
    }
  });

  it('разные типы под одним именем названы отдельно', () => {
    // Сильнейший признак «это разные объекты, а не дубль»: озеро и смотровая
    // площадка могут зваться одинаково.
    expect(CODE).toMatch(/distinct_types/);
  });

  it('слова «лишняя» / «удалить» / «keep» в вердикте нет', () => {
    // Дедуп решает, кого оставить (keep/merge). Перепись — нет, и заводить
    // здесь второе такое решение запрещено.
    expect(CODE).not.toMatch(/\bkeep\b/i);
    expect(CODE).not.toMatch(/лишн|удалить/i);
  });
});

describe('группировка по имени, а не по координатам', () => {
  it('имя нормализуется одинаково с контент-дедупом алертов', () => {
    // lower + trim + схлопнутые пробелы: одно правило на платформу.
    expect(CODE).toMatch(/regexp_replace\(lower\(trim\(p\.name\)\), '\\\\s\+', ' ', 'g'\)/);
  });

  it('координаты в отборе НЕ участвуют', () => {
    // Смысл переписи ровно в этом: пары без координат дедупу невидимы.
    const cte = CODE.slice(CODE.indexOf('WITH normed'), CODE.indexOf('ORDER BY n.norm_name'));
    expect(cte).not.toMatch(/BETWEEN p1\.lat|lat IS NOT NULL AND p2/);
    expect(cte).toMatch(/HAVING COUNT\(\*\) > 1/);
  });

  it('невидимые дедупу кластеры считаются отдельным числом', () => {
    // Без этого числа нельзя решить, нужна ли перепись вообще: если их ноль,
    // хватило бы существующего дедупа.
    expect(CODE).toMatch(/clusters_invisible_to_dedup/);
    expect(CODE).toMatch(/live_with_coords < c\.live_total/);
  });
});

describe('отказ не выдаётся за отсутствие дублей', () => {
  it('падение отвечает 502 с причиной, а не пустым списком', () => {
    // Пустой ответ при поломке читался бы как «дублей нет» — третий исход,
    // выданный за первый (§4.0).
    expect(CODE).toMatch(/status: 502/);
    expect(CODE).toMatch(/success: false/);
    expect(CODE).toMatch(/перепись не выполнена/);
  });
});
