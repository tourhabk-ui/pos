/**
 * tests/unit/source-probe-verdict.test.ts
 *
 * Вердикт пробы отвечает на тот вопрос, ради которого спрашивали адрес.
 *
 * ── Что случилось (замер 40, 08.09) ────────────────────────────────────────
 *
 * Все три обычных адреса ленты АиФ-Камчатка ответили `200`, `text/html`,
 * ~9.5 КБ и `looks_like_feed: false` — одинаково обоим обличьям. Проба
 * назвала это «открыт», и формально была права: речь о ХОСТЕ, он ответил.
 *
 * Но адреса спрашивали не за этим. Вопрос был «есть ли у издания рабочая
 * лента», и настоящий ответ лежал в поле `looks_like_feed`, которое надо было
 * догадаться прочитать вторым. Слово вердикта отвечало на другой вопрос, чем
 * тот, ради которого замер и затевался, — и читалось как «нашли ленту».
 *
 * ── Где здесь граница ──────────────────────────────────────────────────────
 *
 * `looks_like_feed === false` — это ИЗМЕРЕННОЕ «нет». `null` — «не смотрели»
 * (тело не дошло, запрос упал). Превращать второе в «не лента» значит выдать
 * незнание за знание (§4.0), поэтому вердикт сужается только при явном
 * `false` у ОБОИХ обличий.
 */
import { describe, it, expect } from 'vitest';
import { readFileSync } from 'node:fs';
import { join } from 'node:path';

const SRC = readFileSync(join(process.cwd(), 'app/api/cron/source-probe/route.ts'), 'utf-8');

describe('словарь вердиктов различает хост и ленту', () => {
  it('«открыт, но не лента» существует как отдельный исход', () => {
    expect(SRC).toMatch(/'открыт, но не лента'/);
  });

  it('прежние исходы не потеряны — они про другие беды', () => {
    // «Отсекают по виду клиента» и «недостижим» чинятся в разных местах, и
    // ради этого различия проба и спрашивает двумя обличьями.
    expect(SRC).toMatch(/'отсекают по виду клиента'/);
    expect(SRC).toMatch(/'ответил только боту'/);
    expect(SRC).toMatch(/'недостижим'/);
  });
});

describe('сужение вердикта — только по измеренному', () => {
  it('нужен явный false у ОБОИХ обличий', () => {
    expect(SRC).toMatch(/browser\.looks_like_feed === false && bot\.looks_like_feed === false/);
  });

  it('сравнение строгое — null не проходит за false', () => {
    // `!looks_like_feed` пропустил бы null и объявил «не лента» там, где мы
    // просто не посмотрели. Ровно та подмена, которую запрещает §4.0.
    expect(SRC).not.toMatch(/!browser\.looks_like_feed && !bot\.looks_like_feed/);
  });

  it('причина сужения записана рядом с кодом, а не только в истории', () => {
    expect(SRC).toMatch(/замеру 40/);
    expect(SRC).toMatch(/АиФ-Камчатка/);
  });
});
