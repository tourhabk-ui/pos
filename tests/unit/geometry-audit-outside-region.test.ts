/**
 * Аудит геометрии видит линию, ушедшую с Камчатки.
 *
 * Полевые скрины 16–17.08 («Авачинский», «Козельский»): на карте навигации
 * сплошная зелёная горизонталь через весь экран. Аудит, которым меряют
 * здоровье маршрутов, этого дефекта НЕ показывал — и по двум причинам сразу.
 *
 *   1. Проверка координат была про ДИАПАЗОНЫ: `|lat| <= 90`, `|lng| <= 180`.
 *      Точка `lat 53, lng 0` их проходит — она существует, просто в
 *      Гвинейском заливе. Именно она и рисует горизонталь.
 *   2. `geometryToTrack` принимал любые конечные числа, поэтому мусорная
 *      точка попадала в трек и портила ВСЁ, что считается дальше: длину,
 *      расстояние точек до линии, вердикт «набросок или снятый трек»,
 *      габарит подборки.
 *
 * Инструмент измерения не может быть слеп к дефекту, найденному в поле.
 * Поэтому «вне края» считается ОТДЕЛЬНО от «вне диапазона» — это разные
 * поломки и чинятся по-разному, — а из трека такая точка убирается, но
 * factum её наличия не теряется: он остаётся в счётчике и в образцах.
 */
import { describe, it, expect } from 'vitest';
import { readFileSync } from 'node:fs';
import { join } from 'node:path';
import { geometryToTrack } from '@/lib/routes/geometry-audit';

const SRC = readFileSync(join(process.cwd(), 'lib/routes/geometry-audit.ts'), 'utf-8');
const CODE = SRC.replace(/\/\*[\s\S]*?\*\//g, '').replace(/^\s*\/\/.*$/gm, '');

describe('точка вне края не попадает в трек аудита', () => {
  it('нормальная линия читается целиком', () => {
    const track = geometryToTrack({
      type: 'LineString',
      coordinates: [[158.65, 53.02], [158.70, 53.05], [158.75, 53.08]],
    });
    expect(track).toHaveLength(3);
  });

  it('нулевая долгота отсекается — та самая горизонталь', () => {
    const track = geometryToTrack({
      type: 'LineString',
      coordinates: [[158.65, 53.02], [0, 53.02], [158.70, 53.05]],
    });
    expect(track).toHaveLength(2);
    expect(track.every(p => p.lng > 154)).toBe(true);
  });

  it('перестановка осей отсекается', () => {
    const track = geometryToTrack({
      type: 'LineString',
      coordinates: [[158.65, 53.02], [53.02, 158.65]],
    });
    expect(track).toHaveLength(1);
  });

  it('валидная, но чужая координата тоже отсекается', () => {
    // Москва и Токио существуют; треком Камчатки они не являются.
    const track = geometryToTrack({
      type: 'LineString',
      coordinates: [[158.65, 53.02], [37.61, 55.75], [139.69, 35.68]],
    });
    expect(track).toHaveLength(1);
  });
});

describe('факт мусора не теряется вместе с точкой', () => {
  it('есть отдельный счётчик «вне края»', () => {
    // Молча отфильтровать значило бы превратить дефект в тишину — та же
    // ошибка, что и глухой catch.
    expect(CODE).toMatch(/outside_kamchatka: number/);
    expect(CODE).toMatch(/shapes\.outside_kamchatka \+= 1/);
  });

  it('он считается ОТДЕЛЬНО от «вне диапазона»', () => {
    // Разные поломки: одна про несуществующие координаты, другая про
    // существующие, но не наши.
    expect(CODE).toMatch(/out_of_range: number/);
    expect(CODE).toMatch(/out_of_range: 0, outside_kamchatka: 0/);
  });

  it('в образцы попадает объяснение, а не только число', () => {
    expect(SRC).toMatch(/точек вне Камчатки при валидных широте\/долготе/);
  });

  it('границы берутся из общего места, своих порогов нет', () => {
    expect(SRC).toMatch(/import \{ isPlausibleTrackPoint \} from '@\/lib\/routes\/track'/);
    // Прежняя проверка диапазонов остаётся — она про другое.
    expect(CODE).toMatch(/v >= -90 && v <= 90/);
  });
});
