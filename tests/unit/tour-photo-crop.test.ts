/**
 * Фото тура не режется по голове.
 *
 * Замечено владельцем 14.08 на главной: в карусели «Исследовать» карточка
 * «Летняя рыбалка на чавычу и нерку» показывала безголовое туловище с
 * лососем. Причина геометрическая, а не случайная: рамки на главной
 * горизонтальные (4:3 у платы, 10/11 у первого выбора, широкая у тура
 * недели), а фотографии рыбалки сплошь вертикальные — человек во весь рост.
 * При `cover` и центрированной привязке кадр срезает СИММЕТРИЧНО сверху и
 * снизу, то есть ровно голову и ноги.
 *
 * Верхняя привязка режет только низ. Голова — то, по чему узнают человека, и
 * витрина коммерческого тура без неё выглядит браком съёмки, хотя снимок
 * целый.
 *
 * Правило записано в трёх местах, потому что поверхности разные (CSS-блок v8
 * и Tailwind), — сторож нужен именно поэтому: он держит их в согласии.
 */
import { describe, it, expect } from 'vitest';
import { readFileSync } from 'node:fs';
import { join } from 'node:path';

const read = (p: string) => readFileSync(join(process.cwd(), p), 'utf-8');
const V8 = read('app/_home/_HomeV8Client.tsx');
const FEATURED = read('components/homepage/FeaturedTour.tsx');

describe('кроп фотографий туров прижат к верху', () => {
  it('плата в карусели «Исследовать»', () => {
    expect(V8).toMatch(/\.plate \.img\{[^}]*center top\/cover/);
  });

  it('первый выбор подбора', () => {
    expect(V8).toMatch(/\.fp-photo\{[^}]*center top\/cover/);
  });

  it('тур недели на десктопе', () => {
    expect(FEATURED).toMatch(/bg-cover bg-top/);
  });
});

describe('центрированный кроп на этих рамках не возвращается', () => {
  it('плата и первый выбор не центрируют фото по вертикали', () => {
    // `center/cover` без `top` — это ровно то состояние, из-за которого на
    // витрине оказалось туловище без головы.
    expect(V8).not.toMatch(/\.plate \.img\{[^}]*background:var\(--bg-hover\) center\/cover/);
    expect(V8).not.toMatch(/\.fp-photo\{[^}]*background:center\/cover/);
  });

  it('тур недели не возвращается к bg-center', () => {
    expect(FEATURED).not.toMatch(/bg-cover bg-center/);
  });
});
