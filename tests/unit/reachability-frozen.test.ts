/**
 * Сторож достижимости: числа переписи не растут молча.
 *
 * Перепись экспортов и перепись достижимости разобрали четыре поверхности и
 * оставили на каждой ровно то, что решено оставить. Но сам СЧЁТ до сих пор не
 * держал никто: новая страница без ссылки, новый компонент без импортёра или
 * новая сирота-функция появились бы завтра и прошли бы незамеченными — ровно
 * так набралось 96 сирот и 15 недостижимых страниц.
 *
 * Тест не запрещает добавлять поверхности. Он запрещает добавлять их МОЛЧА:
 * порог сдвигается тем же коммитом, что и причина, и причина остаётся в
 * истории рядом с числом.
 *
 * Пороги — потолки, а не цели. Уменьшать можно и нужно; тест напомнит, когда
 * фактическое число ушло заметно ниже, чтобы потолок не превратился в обещание
 * держать мусор.
 */
import { describe, it, expect } from 'vitest';
import { execFileSync } from 'child_process';
import { join } from 'path';

const SCRIPT = join(process.cwd(), 'scripts', 'reachability-audit.ts');

/** Потолки на 22.08.2026. Каждый — с причиной, почему не ноль. */
const CEILING = {
  // Было 15, после правок 22.08 — 9, и все девять законны: пять редиректов
  // на сохранённые URL (/cart, /kuzmich/hub, /hub/operator/register,
  // /hub/tourist/eco-points, /tp-verify как верификация TravelPayouts), две
  // токен-ссылки (/briefing, виджет), вход по роли (/hub/gear) и полевой
  // адрес (/field-check). Один слот запаса — на следующий законный редирект.
  // 29.09 → 11 (с 10): две страницы запроса мест — /seat-request/[token]
  // (статус для туриста) и /seat-request/answer/[id] (ответ оператора). Обе
  // открываются только по личной ссылке из сообщения, и ссылки из интерфейса
  // у них быть не должно: ключ в адресе и есть право доступа. Та же порода,
  // что /briefing и виджет. Слот запаса остаётся один.
  // 02.10 → 8 (с 11): перепись страниц. Папки-редиректы (/cart, /kuzmich/hub,
  // /hub/operator/register, /hub/tourist/eco-points и ещё пять) стали строками
  // next.config и из переписи ушли (сторож legacy-redirects). Осталось семь:
  // три токен-ссылки (/briefing, /checkin-ok, виджет), две страницы запроса
  // мест, вход по роли (/hub/gear) и /tp-verify. Слот запаса — один.
  // 13.10 → 9 (с 8): /team/join/[token] — приглашение менеджера в команду
  // оператора (CRM 2г). Открывается только по ссылке, которую владелец
  // кабинета пересылает сам; ключ в адресе и есть право войти в команду,
  // ссылки из интерфейса у неё быть не должно. Та же порода, что /briefing
  // и запрос мест. Запаса на 13.10 нет: перепись того дня — восемь прежних
  // (/auth/reset-password, /briefing, /hub/gear, /oauth/partner/authorize,
  // /request-status, /seat-request/answer, /tp-verify, виджет) и эта.
  // 22.10 → 10 (с 9): /partner-site/[key] — сайт партнёра, который Ведар
  // отдаёт на ЕГО домене (fishingkam.ru): next.config.js переписывает туда
  // главную домена партнёра. Ссылки из интерфейса Ведара у неё быть не
  // должно — это витрина партнёра, а не страница платформы; на vedarai.ru
  // адрес — предпросмотр для владельца, закрытый от поисковиков. Запаса нет.
  // 23.10 → 11 (с 10): /partner-consent — согласие партнёра на материалы его
  // сайта (миграция 1321, владелец 23.10: «нужна форма согласия об
  // использовании матерьялов сайтов партнеров на нашем сайте»). Открывается
  // только по личной ссылке, которую администратор выпускает в карточке
  // партнёра и пересылает в MAX или Telegram; ключ во фрагменте адреса и есть
  // право подписать. Та же порода, что /team/join и /briefing. Запаса нет.
  // +1 24.10: /seat-request/test — тестовый стенд пилота рыбалки, ссылку
  // владелец получает напрямую; страница сама по себе не для туристов.
  // 13 (01.11): /request-resume — вход только из кнопки единственного
  // напоминания о неотправленной заявке в MAX/Telegram, ссылки из интерфейса нет намеренно.
  pages: 13,
  // Ноль. Компонент без импортёра — это либо забытая работа, либо удаление,
  // которое не довели; и то и другое требует решения, а не потолка.
  components: 0,
} as const;

function count(kind: 'pages' | 'components'): { total: number; orphans: string[] } {
  const out = execFileSync('npx', ['tsx', SCRIPT, kind], {
    cwd: process.cwd(), encoding: 'utf8', timeout: 180_000,
  });
  const orphans = out.split('\n').filter((l) => /^\s{2}\S/.test(l)).map((l) => l.trim().split('   ')[0]);
  const m = /всего (\d+)/.exec(out);
  return { total: m ? Number(m[1]) : -1, orphans };
}

describe('перепись достижимости: числа заморожены', () => {
  it('страниц без ссылки из интерфейса не больше потолка', () => {
    const { total, orphans } = count('pages');
    expect(total).toBeGreaterThan(100);          // измерение вообще состоялось
    expect(
      orphans.length,
      `недостижимых страниц ${orphans.length} > ${CEILING.pages}. Новая страница без ссылки — ` +
      `это страница, которую никто не найдёт. Либо дай на неё ссылку, либо сделай ` +
      `редирект, либо подними потолок ЭТИМ же коммитом с причиной: ${orphans.join(', ')}`,
    ).toBeLessThanOrEqual(CEILING.pages);
  }, 200_000);

  it('компонентов без импортёра не больше потолка', () => {
    const { total, orphans } = count('components');
    expect(total).toBeGreaterThan(100);
    expect(
      orphans.length,
      `компонентов без импортёра ${orphans.length} > ${CEILING.components}: ${orphans.join(', ')}`,
    ).toBeLessThanOrEqual(CEILING.components);
  }, 200_000);
});
