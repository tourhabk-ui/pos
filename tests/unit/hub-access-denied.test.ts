/**
 * 403 в кабинете — это «вы не в той роли», а не «загрузка не удалась».
 *
 * Повод: владелец переключился в другую роль через god-mode-переключатель,
 * зашёл в админку и увидел «Ошибка загрузки · Недостаточно прав доступа ·
 * Повторить». Кнопка «Повторить» при 403 не может сработать НИКОГДА: сервер
 * отказывает по роли, а не по случайности. Экран не сообщал ни какая роль
 * активна, ни где выход, — со стороны это выглядело как «доступа нет ни к
 * чему», хотя вернуться можно было одним нажатием.
 *
 * Сторож следит за двумя вещами: 403 разбирается отдельной веткой, и на
 * экране отказа нет «Повторить».
 */
import { describe, it, expect } from 'vitest';
import { readFileSync } from 'node:fs';
import { join } from 'node:path';

const ROOT = process.cwd();

/** Исходник без строк-комментариев: иначе тест ловит собственные пояснения. */
function code(path: string): string {
  return readFileSync(join(ROOT, path), 'utf-8')
    .split('\n')
    .filter((l) => !/^\s*(\/\/|\*|\/\*)/.test(l))
    .join('\n');
}

describe('админский обзор различает 403 и сбой загрузки', () => {
  const SRC = code('app/hub/admin/page.tsx');

  it('403 разбирается отдельно, до общей ветки ошибки', () => {
    expect(SRC, 'статус 403 больше не проверяется — отказ снова попадёт в «Повторить»')
      .toMatch(/res\.status\s*===\s*403/);
  });

  it('на отказ по роли рендерится AccessDeniedCard', () => {
    expect(SRC).toMatch(/AccessDeniedCard/);
    expect(SRC).toMatch(/requiredRole="admin"/);
  });
});

describe('экран отказа ведёт к выходу, а не в тупик', () => {
  const SRC = code('components/hub/AccessDeniedCard.tsx');

  it('не предлагает «Повторить» — повтор при 403 бесполезен', () => {
    expect(SRC, 'вернулась кнопка повтора: она не может помочь при отказе по роли')
      .not.toMatch(/Повторить/);
  });

  it('называет активную роль пользователя', () => {
    // Без этого человек не понимает, почему отказ: роль нигде не видна.
    expect(SRC).toMatch(/ROLE_LABELS/);
  });

  it('переключает роль тем же серверным путём, а не своим', () => {
    // Никакой отдельной «двери» для повышения прав: /api/auth/switch-role
    // проверяет владение ролью на сервере и клиенту не верит.
    expect(SRC).toMatch(/switchRole/);
    expect(SRC).toMatch(/canSwitchTo/);
    expect(SRC, 'появился прямой запрос в обход общей проверки').not.toMatch(/fetch\(/);
  });

  it('не показывает кнопку возврата тем, кому роль не принадлежит', () => {
    expect(SRC).toMatch(/canReturn\s*\?/);
  });
});
