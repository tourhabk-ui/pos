/**
 * Сторож: выезд спасателей во время идущего события — сведение, не тревога.
 *
 * #1861: push «Паводок — Камчатка» ушёл туристу на сообщение «Камчатские
 * спасатели МЧС России выдвинулись в Соболево…» — репортаж о работе службы,
 * из которого не следует никакого действия для человека, а инструкция под
 * пушем («Не пересекайте реки вброд») к этому посту не относится вовсе.
 * `isServiceStatistics` этот жанр не ловил: «выдвинулись» не входит в список
 * глаголов свершившегося факта, а счёта в посте нет.
 *
 * Развилка была за владельцем: отбросить жанр целиком (Reading А) или
 * оставить в ленте /safety, но снять с него тревогу (Reading Б). Решение
 * 14.09 (карт-бланш) — Reading Б: событие остаётся видимым, но не толкает
 * push и не поднимает max_severity.
 */
import { describe, it, expect } from 'vitest';
import { isRescuerDispatchUpdate, isServiceStatistics, classifyMchsItem } from '@/lib/services/safety/seismic-parser';

const OWNER_TEXT = 'Камчатские спасатели МЧС России выдвинулись в Соболево для помощи местным жителям в связи с паводком на реке Воровской.';

describe('isRescuerDispatchUpdate: сведение о выезде, не тревога', () => {
  it('дословный случай владельца распознан', () => {
    expect(isRescuerDispatchUpdate(OWNER_TEXT)).toBe(true);
  });

  it('семейство глаголов выезда целиком', () => {
    for (const l of [
      'Спасатели МЧС направлены в район схода оползня.',
      'Сводная группировка спасателей прибыла к месту происшествия.',
      'В районе паводка развёрнут мобильный пункт МЧС.',
      'Спасатели ЦУКС выдвинулись на маршрут для эвакуации группы туристов.',
    ]) expect(isRescuerDispatchUpdate(l), l).toBe(true);
  });

  it('старый жанровый фильтр этот текст не ловит — отсюда и был дефект', () => {
    expect(isServiceStatistics(OWNER_TEXT)).toBe(false);
  });

  it('без упоминания спасателей/МЧС/ЦУКС — не тот жанр', () => {
    expect(isRescuerDispatchUpdate('Оперативная группа выдвинулась к месту происшествия.')).toBe(false);
  });

  it('без глагола выезда — не тот жанр', () => {
    expect(isRescuerDispatchUpdate('Спасатели МЧС работают в районе паводка.')).toBe(false);
  });

  it('собственный запрет/прогноз в том же посте — это уже не просто сведение', () => {
    for (const l of [
      'Спасатели МЧС выдвинулись в район, тургруппам не рекомендуется выходить на маршруты.',
      'Спасатели выдвинулись к месту циклона — ожидается усиление ветра, штормовое предупреждение.',
    ]) expect(isRescuerDispatchUpdate(l), l).toBe(false);
  });
});

describe('classifyMchsItem: severity обнулена, пост не выброшен', () => {
  it('дословный случай владельца — событие сохранено, severity 0, тип остался предметным', () => {
    const ev = classifyMchsItem('x', '', OWNER_TEXT, '2026-09-14T10:12:00Z', 'https://t.me/x');
    expect(ev).not.toBeNull();
    expect(ev?.severity).toBe(0);
    expect(ev?.alert_type).toBe('flood');
  });

  it('реальный запрет тургруппам при том же тексте выезда — тревога остаётся', () => {
    const ev = classifyMchsItem(
      'x', '',
      'Спасатели МЧС выдвинулись в район паводка, тургруппам не рекомендуется выходить на маршруты.',
      '2026-09-14T10:12:00Z',
      'https://t.me/x',
    );
    expect(ev).not.toBeNull();
    expect(ev?.severity).toBe(2);
  });

  it('обычное предупреждение о паводке без выезда спасателей — тревога без изменений', () => {
    const ev = classifyMchsItem(
      'x', '',
      'На реке Большая Воровская ожидается опасное явление — паводок, размыв опор мостовых переходов.',
      '2026-09-14T10:12:00Z',
      'https://t.me/x',
    );
    expect(ev).not.toBeNull();
    expect(ev?.severity).toBe(2); // declaresHazardGrade (ОЯ) поднимает до 2
  });
});
