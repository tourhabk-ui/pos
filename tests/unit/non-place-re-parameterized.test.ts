/**
 * NON_PLACE_RE уходит в SQL параметром, не интерполяцией (#1321).
 *
 * Константа — не пользовательский ввод, и «инъекцией» это было только в
 * потенциале: апостроф или бэкслеш в будущей правке регулярки молча ломал
 * бы COUNT и выборку геокодера. Правило платформы — параметризация без
 * исключений, и сторож держит его для этой константы во всём дереве.
 */
import { describe, it, expect } from 'vitest';
import { execSync } from 'node:child_process';

describe('NON_PLACE_RE не интерполируется в SQL', () => {
  it('ни одного вхождения ${NON_PLACE_RE} внутри строки запроса', () => {
    // grep возвращает 1 при нуле совпадений — это и есть успех.
    let out = '';
    try {
      out = execSync(
        `grep -rn "\\${NON_PLACE_RE}" --include='*.ts' app lib`,
        { cwd: process.cwd(), encoding: 'utf-8' },
      );
    } catch { /* нет совпадений */ }
    expect(out.trim(), 'регулярка снова вклеена в текст SQL').toBe('');
  });
});
