/**
 * Сторож переписи экспортов: сироты в `lib/` не заводятся молча.
 *
 * Перепись 22.08 разобрала 96 сирот поимённо и оставила три — каждую с
 * причиной, записанной в коде. Но сам СЧЁТ не держал никто: следующая
 * появилась бы завтра, и всё началось бы заново. Так эти 96 и набрались —
 * ни один коммит не добавлял «кучу мёртвого кода», каждый добавлял одну
 * функцию, которую собирался подключить позже.
 *
 * Тест не запрещает сироту. Он запрещает сироту БЕЗ решения: потолок
 * сдвигается тем же коммитом, что и причина, и причина остаётся в истории
 * рядом с числом.
 *
 * Перепись — полноценный проход по 2543 файлам через парсер TypeScript,
 * порядка 17 секунд. Это дороже обычного юнит-теста и дешевле разбора
 * очередной сотни сирот.
 */
import { describe, it, expect } from 'vitest';
import { execFileSync } from 'child_process';
import { join } from 'path';

const SCRIPT = join(process.cwd(), 'scripts', 'export-census.ts');

/**
 * Потолок на 22.08.2026: три сироты, все намеренные.
 *   warmModel          — вызов есть, закомментирован (sharp падает на musl)
 *   decryptInterests   — вторая половина шифрования ПД; читатель не выставлен
 *                        наружу, пока нет законного экрана
 *   mapFileUrl         — заготовка PMTiles, этап 2
 *
 * Четвёртая приехала с main 22.08 вместе с полевым рекордером:
 *   toGeoJson (lib/field/track-recorder.ts) — снятый трек в GeoJSON с высотой
 *   третьим числом. Потребителя пока нет: экран отдаёт GPX. Функция свежая и
 *   принадлежит чужой незаконченной работе — подключать её за автора в
 *   merge-коммите значит выдумать поведение, которого он не задумывал.
 *
 * Пятая приехала 01.09 с заходом удаления мёртвого модуля трансферов:
 *   createBookingWithLock (lib/transfers/booking.ts) — её единственный
 *   вызывающий, app/api/transfers/book, удалён вместе с модулем: он читал
 *   таблицы, которых на проде нет (перепись, прогоны 2-3, канарейка видна).
 *   Сам booking.ts остался НЕ по недосмотру — из него динамически импортирует
 *   cancelBooking приёмник CloudPayments, вынесенный из захода до слова
 *   владельца (§7 «Не трогать»). Удалять функцию отдельно значило бы разнести
 *   одно решение по двум заходам и оставить модуль в полуразобранном виде;
 *   она уйдёт вместе с платёжным шагом, целиком.
 *
 *   Заодно тем же заходом сирота УБЫЛА: requireTransferOperator из
 *   lib/auth/middleware.ts звали только удалённые роуты кабинета, и она ушла
 *   с ними — потолок держит чистое +1, а не +2.
 *
 * Потолок — не цель: уменьшать можно и нужно.
 */
const ORPHAN_CEILING = 5;

describe('перепись экспортов: число сирот заморожено', () => {
  it(`сирот не больше ${ORPHAN_CEILING}`, () => {
    const out = execFileSync('npx', ['tsx', SCRIPT], {
      cwd: process.cwd(), encoding: 'utf8', timeout: 300_000,
    });

    const total = /экспортируемых функций в lib\/: (\d+)/.exec(out);
    expect(total, 'перепись не отдала итог — измерение не состоялось').not.toBeNull();
    expect(Number(total![1])).toBeGreaterThan(500);

    const orphan = /orphan\s+(\d+)/.exec(out);
    expect(orphan, 'в выводе переписи нет строки orphan').not.toBeNull();

    const count = Number(orphan![1]);
    expect(
      count,
      `сирот ${count} > ${ORPHAN_CEILING}. Экспортируемая функция, которую никто ` +
      `не зовёт, — это либо забытая работа, либо лишнее слово export. Подключи, ` +
      `удали, сделай внутренней — или подними потолок ЭТИМ же коммитом, записав ` +
      `причину в коде рядом с функцией. Список: npx tsx scripts/export-census.ts`,
    ).toBeLessThanOrEqual(ORPHAN_CEILING);
  }, 320_000);
});
