/**
 * Суша/море по контуру берега — тесты на местах, которые не спутаешь.
 *
 * Ориентация замыкания материка (через северные углы рамки) проверяется не
 * рассуждением, а городами и морями: если кольцо вывернуто, Петропавловск
 * окажется «в море», и тест скажет это раньше, чем аудит на проде.
 */
import { describe, it, expect } from 'vitest';
import { landVerdict, distanceToCoastKm, ringStats } from '@/lib/geo/land';

describe('сборка колец', () => {
  it('все куски контура собраны в замкнутые кольца', () => {
    const s = ringStats();
    expect(s.allClosed).toBe(true);
    expect(s.rings).toBeGreaterThanOrEqual(5);
    expect(s.points).toBeGreaterThan(1000);
  });
});

describe('суша — города и вулканы', () => {
  // Точки заведомо в глубине суши. Прибрежные посёлки сюда не годятся:
  // Усть-Камчатск стоит на косе в 100 м от упрощённой линии и честно
  // попадает по обе стороны — это ограничение контура, см. тест ниже.
  const LAND: Array<[string, number, number]> = [
    ['Петропавловск-Камчатский', 53.024, 158.643],
    ['Елизово', 53.183, 158.388],
    ['Эссо', 55.928, 158.703],
    ['Ключи', 56.322, 160.845],
    ['Ключевская сопка', 56.056, 160.642],
    ['Мутновский вулкан', 52.453, 158.195],
    ['Толбачик', 55.832, 160.327],
    ['Кроноцкая сопка', 54.753, 160.527],
    ['Корякское нагорье', 61.5, 166.0],
    ['Центр острова Беринга', 55.0, 166.2],
    ['Центр Парамушира', 50.4, 155.7],
  ];
  for (const [name, lat, lng] of LAND) {
    it(name, () => expect(landVerdict(lat, lng)).toBe('land'));
  }
});

describe('море — там, где источников не бывает', () => {
  const SEA: Array<[string, number, number]> = [
    ['Охотское море западнее полуострова', 55.0, 154.8],
    ['Охотское море, средняя часть', 57.5, 155.0],
    ['Тихий океан юго-восточнее Петропавловска', 52.0, 160.5],
    ['Берингово море восточнее полуострова', 57.0, 165.0],
    ['Камчатский залив', 55.6, 163.3],
    ['Южнее мыса Лопатка', 50.3, 157.2],
  ];
  for (const [name, lat, lng] of SEA) {
    it(name, () => expect(landVerdict(lat, lng)).toBe('sea'));
  }
});

describe('вне рамки — отдельный ответ, не «море»', () => {
  it('Магадан', () => expect(landVerdict(59.56, 150.8)).toBe('outside_region'));
  it('нулевые координаты (классический дефект данных)', () => {
    expect(landVerdict(0, 0)).toBe('outside_region');
  });
  it('перепутанные местами lat/lng', () => {
    // Точка (158.6, 53.0) — lat 158 не бывает; после клампа смысла это ловится рамкой
    expect(landVerdict(53.0, 53.0)).toBe('outside_region');
  });
});

describe('расстояние до берега — мера уверенности', () => {
  it('точка в открытом море дальше 30 км от контура', () => {
    expect(distanceToCoastKm(57.5, 155.0)).toBeGreaterThan(30);
  });
  it('Петропавловск ближе 60 км к берегу', () => {
    expect(distanceToCoastKm(53.024, 158.643)).toBeLessThan(60);
  });

  /**
   * Задокументированное ограничение, а не баг: Усть-Камчатск стоит на косе,
   * упрощение контура (~1 км) её съело, и город читается «морем» в сотне
   * метров от линии. Ровно поэтому аудит обязан смотреть на расстояние:
   * «море в 40 км от берега» — битые координаты, «море в 100 м» — коса.
   * Если контур когда-нибудь станет точнее и город «высадится» на сушу —
   * этот тест упадёт, и его нужно будет просто удалить.
   */
  it('Усть-Камчатск (коса): «море», но в сотнях метров от линии', () => {
    expect(landVerdict(56.238, 162.588)).toBe('sea');
    expect(distanceToCoastKm(56.238, 162.588)).toBeLessThan(1);
  });
});
