/**
 * У журнала MCP есть вход в админке.
 *
 * Владелец 17.08: «я в админке не вижу запросы через MCP, хотя это
 * обсуждалось и реализовывалось». Он был прав дважды. Реализовано было почти
 * всё — таблица `mcp_tool_calls` (миграция 861), запись фактов вызова
 * (`lib/mcp/call-log.ts`), срез `/api/admin/analytics/mcp`. Не было ровно
 * одного звена: страницы. Слово `mcp` не встречалось во всей `app/hub/admin`
 * ни разу, и данные, копившиеся неделями, посмотреть можно было только
 * запросом руками.
 *
 * Измерение, которого никто не видит, измерением не является: оно не влияет
 * ни на одно решение. Поэтому сторож стережёт именно ВХОД — страницу и пункт
 * меню, — а не разметку.
 *
 * Отдельно стережётся честность двух чисел. `caller_days` — человеко-дни:
 * хеш вызывающего суточный (152-ФЗ), и «уникальных вызывающих: 40» читалось
 * бы как сорок клиентов, хотя это может быть один за сорок дней. И пустота
 * названа словами: тишина в канале — это факт о канале, а не пустая сетка.
 */
import { describe, it, expect } from 'vitest';
import { readFileSync, existsSync } from 'node:fs';
import { join } from 'node:path';

const PAGE_PATH = join(process.cwd(), 'app/hub/admin/mcp/page.tsx');
const LAYOUT = readFileSync(join(process.cwd(), 'app/hub/admin/layout.tsx'), 'utf-8');

describe('вход в журнал MCP существует', () => {
  it('страница есть', () => {
    expect(existsSync(PAGE_PATH)).toBe(true);
  });

  it('в меню админки есть пункт, ведущий на неё', () => {
    // Страница без пункта меню — тот же невидимый журнал, только этажом выше.
    expect(LAYOUT).toMatch(/href: '\/hub\/admin\/mcp'/);
  });

  it('страница берёт данные из существующего среза, а не своим запросом', () => {
    const page = readFileSync(PAGE_PATH, 'utf-8');
    expect(page).toMatch(/fetch\('\/api\/admin\/analytics\/mcp'\)/);
    // Своего SQL на странице быть не может: она клиентская и за админ-гардом
    // стоит эндпоинт, а не она.
    expect(page).not.toMatch(/SELECT .* FROM mcp_tool_calls/i);
  });
});

describe('страница не обещает того, чего журнал не знает', () => {
  const page = readFileSync(PAGE_PATH, 'utf-8');

  it('человеко-дни названы человеко-днями', () => {
    expect(page).toMatch(/Человеко-дней/);
    expect(page).not.toMatch(/Уникальных вызывающих/i);
  });

  it('аргументы вызовов не показываются — их и не пишут', () => {
    // В аргументах уходят имена, телефоны и даты туристов, а канал внешний.
    expect(page).not.toMatch(/\bargs\b|arguments|payload/);
  });

  it('пустой журнал объяснён словами, а не пустой таблицей', () => {
    expect(page).toMatch(/Канал молчит/);
  });

  it('ошибка загрузки видна, а не проглочена', () => {
    expect(page).toMatch(/setError\(/);
    expect(page).not.toMatch(/catch \{\s*\}/);
  });
});
