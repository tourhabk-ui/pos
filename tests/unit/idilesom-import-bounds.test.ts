/**
 * Импорт треков не записывает в базу то, что не является треком Камчатки.
 *
 * Полевые скрины 16–17.08 («Авачинский», «Козельский»): на карте навигации
 * сплошная зелёная линия шла горизонталью через весь край — от Магаданской
 * области за восточный край экрана. Второй маршрут доказал, что это не одна
 * битая запись, а данные импорта.
 *
 * Механизм — в разборе страницы idilesom:
 *
 *   1. блоки координат ищутся регуляркой по ЛЮБЫМ вложенным числовым
 *      массивам, поэтому под неё попадает и профиль высот
 *      `[[0, 795], [1.2, 810], ...]`;
 *   2. формат определяется по ОДНОЙ точке (`|first[0]| > 90` значит
 *      [lng, lat]) — а у профиля первое число это расстояние, «не больше
 *      90», и массив разворачивается как [lat, lng], давая lng = 795;
 *   3. результат писался `UPDATE kamchatka_routes SET geometry = $1` без
 *      единой проверки.
 *
 * Клиентский фильтр (`isPlausibleTrackPoint` в lib/routes/track) прячет
 * симптом на карте, но геометрия в базе остаётся кривой — и уедет в
 * офлайн-пакет, GPX-экспорт и всё остальное. Поэтому запрет стоит в
 * источнике, и здесь он и стережётся.
 */
import { describe, it, expect } from 'vitest';
import { readFileSync } from 'node:fs';
import { join } from 'node:path';

const SRC = readFileSync(join(process.cwd(), 'scripts/import-idilesom-tracks.ts'), 'utf-8');

/** Код без комментариев: прежний дефект в них описан намеренно. */
const CODE = SRC.replace(/\/\*[\s\S]*?\*\//g, '').replace(/^\s*\/\/.*$/gm, '');

describe('блок координат принимается целиком или не принимается вовсе', () => {
  it('проверяется каждая точка, а не первая', () => {
    // Эвристика уже ошиблась на первой точке; повторять её с другим
    // порогом незачем.
    expect(CODE).toMatch(/coords\.every\(p => isPlausibleTrackPoint\(p\[1\], p\[0\]\)\)/);
  });

  it('негодный блок пропускается, а не «чинится»', () => {
    expect(CODE).toMatch(/if \(!allOnKamchatka\) continue;/);
  });
});

describe('запись в базу защищена отдельно от разбора', () => {
  it('перед UPDATE ищется точка вне края', () => {
    // Дубль намеренный: разбор ещё будет меняться (сайт-источник не наш),
    // а запрет обязан пережить его правки.
    expect(CODE).toMatch(/track\.coordinates\.find\(p => !isPlausibleTrackPoint\(p\[1\], p\[0\]\)\)/);
  });

  it('проверка стоит ДО формирования geojson и UPDATE', () => {
    const check = CODE.indexOf('const badPoint');
    const geojson = CODE.indexOf("type: 'LineString'");
    const update = CODE.indexOf('UPDATE kamchatka_routes SET geometry');
    expect(check).toBeGreaterThan(-1);
    expect(check).toBeLessThan(geojson);
    expect(check).toBeLessThan(update);
  });

  it('отброшенное считается и попадает в итог прогона', () => {
    // Молчаливый пропуск неотличим от «таких страниц не было».
    expect(CODE).toMatch(/rejected\+\+/);
    expect(CODE).toMatch(/отброшено вне края/);
    expect(CODE).toMatch(/точка вне края/);
  });

  it('границы края живут в одном месте с клиентской проверкой', () => {
    // Свой список границ в импортёре разъехался бы с картой — это ровно
    // тот класс, из-за которого линия и рисовалась.
    //
    // Эвристика порядка осей (`|first[0]| > 90`) под запрет НЕ подпадает:
    // она отвечает на другой вопрос — что здесь широта, а что долгота, —
    // и остаётся на месте. Запрещён именно свой перечень границ.
    expect(SRC).toMatch(/import \{ isPlausibleTrackPoint \} from '\.\.\/lib\/routes\/track'/);
    expect(CODE).not.toMatch(/latMin|latMax|lngMin|lngMax/);
  });
});
