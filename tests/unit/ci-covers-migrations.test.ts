/**
 * Сторож: миграция обязана доезжать до прода (18.09).
 *
 * ── Что случилось ─────────────────────────────────────────────────────────
 *
 * Владелец прислал три своих снимка маяка; миграция 977 положила их на
 * карточку. Коммит содержал РОВНО ОДИН файл — `.sql`. CI не запустился:
 * в `ci.yml` список `paths` перечислял только код. Выкат идёт по завершении
 * CI (`deploy.yml`, `workflow_run`), значит не было и его, а миграции
 * накатывает `start.js` при старте контейнера — то есть только на выкате.
 *
 * Итог: миграция лежала в `main` и на прод не попадала НИКОГДА. Не «иногда»,
 * не «с задержкой». При этом ни одна проверка не покраснела — проверять было
 * нечего, прогон просто не создавался. Молчание читалось как «всё прошло».
 *
 * Прежние миграции доезжали СЛУЧАЙНО: их коммиты попутно трогали `.ts`
 * (976 шла вместе с правкой `lib/map/pack-source.ts` и потому применилась).
 * Стоило отправить миграцию отдельным коммитом — и механизм отказывал.
 *
 * ── Что держит сторож ─────────────────────────────────────────────────────
 *
 * Связку, а не половину (правило 10.09): путь `migrations/**` должен стоять
 * в `paths` ОБОИХ событий, и выкат должен по-прежнему запускаться от CI.
 * Уберут первое — миграции снова перестанут доезжать молча; уберут второе —
 * список путей потеряет смысл, и этот файл обязан краснеть, а не зеленеть.
 */
import { describe, it, expect } from 'vitest';
import { readFileSync } from 'node:fs';
import { join } from 'node:path';
import { load } from 'js-yaml';

const ROOT = process.cwd();
const read = (p: string) => readFileSync(join(ROOT, p), 'utf-8');

interface Triggers {
  push?: { paths?: string[] };
  pull_request?: { paths?: string[] };
  workflow_run?: { workflows?: string[] };
}
/** В YAML `on:` разбирается как булево true — это не опечатка. */
const triggersOf = (file: string): Triggers => {
  const doc = load(read(file)) as Record<string, unknown>;
  return (doc['on'] ?? doc[true as unknown as string]) as Triggers;
};

describe('миграция доезжает до прода', () => {
  const ci = triggersOf('.github/workflows/ci.yml');

  it('CI запускается на изменение migrations/ при пуше', () => {
    expect(ci.push?.paths, 'без этого коммит с одним .sql не собирается и не выкатывается').toContain('migrations/**');
  });

  it('CI запускается на изменение migrations/ в PR', () => {
    // Иначе миграция проходит ревью непроверенной: тот же разрыв, только
    // раньше по течению.
    expect(ci.pull_request?.paths).toContain('migrations/**');
  });

  it('выкат по-прежнему привязан к завершению CI — иначе список путей ни при чём', () => {
    // Этот факт и делает `paths` решающим: он превращает «что проверяем» в
    // «что доедет». Развяжут — сторож обязан краснеть и быть переписан, а не
    // молча охранять пустоту.
    const deploy = triggersOf('.github/workflows/deploy.yml');
    expect(deploy.workflow_run?.workflows).toContain('CI');
  });
});
