// @vitest-environment node
/**
 * Карточка места говорит с человеком, а не показывает приборы.
 *
 * Направление D, решение владельца 19.09: «нужно всё-таки UX и более
 * дружественный интерфейс карточки». Выбрано после трёх вариантов, которые
 * отвечали на вопрос «как это выглядит» — а спрошено было другое.
 *
 * Это СРЕЗ 1 — только речь. Ни один блок не переставлен, ни один компонент не
 * удалён; сторож заведён сразу, чтобы речь не откатилась обратно, пока едут
 * следующие срезы (одно главное действие, факты из героя, свёрнутые
 * подробности).
 *
 * ── Что держит сторож ─────────────────────────────────────────────────────
 *
 * 1. КАПС. В русском тексте `uppercase` читается как приборная панель, а не
 *    как разговор, и на 10-11 пикселях кириллица в капсе ещё и плохо
 *    разбирается. Исключения перечислены поимённо и с причиной — реестр
 *    самоустаревающий, как KNOWN_UNPRODUCED в alert-types-produced: ушла
 *    причина, тест требует убрать запись.
 *
 * 2. СТАТУС ОТВЕЧАЕТ НА ВОПРОС. Человек спрашивает «мне туда сегодня можно?».
 *    Прежние подписи отвечали не ему: «Открыто, без предупреждений» — выписка
 *    из реестра, «Внимание» и «Ограничения» — ярлыки уровня, по которым ещё
 *    надо догадаться, что делать.
 *
 * 3. СВЕЖЕСТЬ ВИДНА НА ТЕЛЕФОНЕ. Время проверки стояло под `hidden sm:block` —
 *    то есть ровно на том устройстве, с которым человек стоит в поле, его не
 *    было вовсе. Статус без времени читается как «сейчас», хотя запись может
 *    быть трёхдневной. Нет времени в записи — так и сказано словами: «не
 *    знаем, когда проверяли» и «проверяли только что» — разные состояния
 *    (§4.0).
 *
 * 4. УРОВЕНЬ ОПАСНОСТИ НЕ ТРОНУТ. Переписаны слова, а не решение: `getLevel`
 *    по-прежнему считает уровень по `isOpen` и `alertSeverity`, красный и
 *    оранжевый по-прежнему липкие. Сторож это проверяет отдельно — «сделали
 *    дружелюбнее» не должно однажды означать «убрали тревогу».
 */
import { describe, it, expect } from 'vitest';
import { readdirSync, readFileSync } from 'node:fs';
import { join } from 'node:path';

const ROOT = process.cwd();
const PLACES = join(ROOT, 'components', 'places');
const STATUS_FULL = readFileSync(join(PLACES, 'PlaceRealtimeStatus.tsx'), 'utf-8');

/**
 * Код без комментариев. Отрицания проверяются ТОЛЬКО по нему.
 *
 * Первая редакция этого сторожа покраснела на собственном объяснении: в шапке
 * компонента дословно приведены прежние подписи («Открыто, без предупреждений»)
 * и прежний класс (`hidden sm:block`) — именно затем, чтобы читающий понимал,
 * что и почему заменено. Запрет, прочитавший это как нарушение, требует стереть
 * причину правки — то есть ровно тот дефект, который сам же и лечит.
 *
 * Ловушка в этом репозитории известна и стоила времени дважды: то же записано в
 * dev-tools-db («сторож не должен падать на собственном объяснении») и в
 * migration-id-type-domain. Третий раз — уже привычка, поэтому вырезание
 * комментариев здесь заведено сразу и явно.
 */
function codeOnly(src: string): string {
  return src.replace(/\/\*[\s\S]*?\*\//g, '').replace(/(^|[^:])\/\/[^\n]*/g, '$1');
}

const STATUS = codeOnly(STATUS_FULL);

/**
 * Капс, оставленный НАМЕРЕННО. Каждая запись — файл и причина; список может
 * только сокращаться.
 */
const CAPS_ALLOWED: Record<string, string> = {
  // SOS — критичное действие с фиксированным видом (§11, сторож
  // sos-always-reachable). Слово латиницей, и трогать его стиль нельзя.
  'PlaceSOS.tsx': 'SOS — критичное действие, вид фиксирован §11',
};

/**
 * Карточка МАРШРУТА — та же правка речи (19.09, владелец: «нужно сделать очень
 * грамотно и аккуратно, это одно из основных, что будет смотреть турист»).
 *
 * Капсов там было 32 против 13 на карточке места, и ни один не стоял поверх
 * фото — все на сплошных фонах, то есть без единого смягчающего обстоятельства.
 *
 * Заголовки разделов подняты в голос края (Playfair) и в размер НАМЕРЕННО.
 * Снять капс, не тронув размер, значило бы повторить «муть» 14.09: тогда
 * деликатный заголовок на тёмном фоне исчез, и страница осталась ровным полем
 * без точки опоры. Капс держал эти заголовки видимыми — убирая его, надо
 * вернуть видимость другим способом, а не просто отнять.
 */
describe('капс-ярлыков на карточке маршрута нет', () => {
  const ROUTE_CARD = readFileSync(join(ROOT, 'app', 'routes', '[id]', '_RouteDetailClient.tsx'), 'utf-8');

  it('ни одного uppercase', () => {
    expect(
      (ROUTE_CARD.match(/\buppercase\b/g) ?? []).length,
      'капс в русском тексте читается как прибор, а не как разговор',
    ).toBe(0);
  });

  it('разрядки под капс тоже не осталось', () => {
    // `tracking-widest` на строчной кириллице растягивает слово без причины:
    // приём существовал ради капса и вместе с ним уходит.
    expect(ROUTE_CARD).not.toContain('tracking-widest');
    expect(ROUTE_CARD).not.toContain('tracking-[0.2em]');
  });

  it('заголовки разделов заговорили голосом края и остались видимыми', () => {
    expect(ROUTE_CARD).toContain('font-playfair');
    // Заголовок не мельче 18px: 12-14px строчными — это «муть» 14.09.
    expect(ROUTE_CARD).not.toMatch(/text-(xs|sm)[^"]*font-playfair/);
  });
});

describe('капс-ярлыков на карточке места нет', () => {
  const files = readdirSync(PLACES).filter(f => f.endsWith('.tsx'));

  it('файлы карточки найдены', () => {
    expect(files.length).toBeGreaterThan(15);
  });

  it('uppercase встречается только там, где он объявлен намеренно', () => {
    const offenders: string[] = [];
    for (const f of files) {
      const src = readFileSync(join(PLACES, f), 'utf-8');
      if (!/\buppercase\b/.test(src)) continue;
      if (f in CAPS_ALLOWED) continue;
      offenders.push(f);
    }
    expect(
      offenders,
      'капс в русском тексте читается как прибор, а не как разговор; '
      + 'нужен намеренно — внесите файл в CAPS_ALLOWED с причиной',
    ).toEqual([]);
  });

  it('реестр исключений самоустаревающий: запись без капса обязана уйти', () => {
    const stale: string[] = [];
    for (const [f, why] of Object.entries(CAPS_ALLOWED)) {
      const src = readFileSync(join(PLACES, f), 'utf-8');
      if (!/\buppercase\b/.test(src)) stale.push(`${f} (${why})`);
    }
    expect(
      stale,
      'капса в файле больше нет — запись в CAPS_ALLOWED пора удалить, '
      + 'иначе реестр начнёт разрешать то, чего уже не делают',
    ).toEqual([]);
  });
});

describe('строка статуса отвечает на вопрос человека', () => {
  it('ответ, а не ярлык уровня', () => {
    expect(STATUS).toContain('Сегодня можно идти');
    expect(STATUS).toContain('Сегодня туда нельзя');
    // Прежние выписки из реестра не должны вернуться.
    expect(STATUS).not.toContain('Открыто, без предупреждений');
    expect(STATUS).not.toMatch(/answer: 'Внимание'|answer: 'Ограничения'/);
    expect(STATUS).not.toContain('Закрыто / Опасно');
  });

  it('открытое место с сильной тревогой не называется закрытым', () => {
    expect(STATUS).toContain("level === 'red' && realtime.isOpen ? 'Сегодня там опасно'");
  });

  it('причина от источника идёт отдельной строкой, а не склеивается двоеточием', () => {
    expect(STATUS).not.toMatch(/\$\{cfg\.\w+\}: \$\{realtime\.alertMessage\}/);
    expect(STATUS).toContain('realtime.alertMessage?.trim() ||');
  });

  it('нет причины — сказано, что её не сообщили, а не что всё в порядке', () => {
    expect(STATUS).toContain('Причина не указана');
  });
});

describe('свежесть статуса', () => {
  it('время проверки не спрятано от телефона', () => {
    expect(
      STATUS.includes('hidden sm:block'),
      'время проверки снова скрыто на малых экранах — то есть на том устройстве, '
      + 'с которым человек стоит в поле',
    ).toBe(false);
  });

  it('нет времени в записи — сказано словами, а не пропущено', () => {
    expect(STATUS).toContain('Когда проверяли — у нас не записано');
    // Пропуск целиком (`: null`) читался бы как «проверено сейчас».
    expect(STATUS).not.toMatch(/updatedStr = realtime\.updatedAt[\s\S]{0,200}: null;/);
  });
});

/**
 * Срез 2: незнание названо словами там, где молчание успокаивает.
 *
 * Правило «не знаем — отсутствие строки, а не прочерк» остаётся для фактов,
 * чьё отсутствие ничего не обещает. Но у двух отсутствие читается как хорошая
 * новость: пустая «Сложность» — «ничего сложного», пустая «До медпомощи» —
 * «видимо, недалеко». Оба нужны, чтобы решить, идти ли и с кем.
 *
 * Факты из героя в этом срезе НЕ переезжают, и это решение, а не недоделка:
 * их завели 14.09 потому, что до этого первый экран телефона показывал четыре
 * кнопки навигации и ни одного факта о месте. Пока кнопки не сведены к одной
 * (срез 3), вынос фактов вернул бы тот дефект — промежуточное состояние вышло
 * бы хуже обоих концов.
 */
describe('незнание сказано словами, а не пропущено', () => {
  const FACTS = codeOnly(readFileSync(join(PLACES, 'PlaceFacts.tsx'), 'utf-8'));

  it('сложность без значения названа, а не пропущена', () => {
    expect(FACTS).toContain("label: 'Сложность', value: 'у нас не записана'");
  });

  it('расстояние до медпомощи без значения названо, а не пропущено', () => {
    expect(FACTS).toContain("label: 'До медпомощи', value: 'у нас не записано'");
  });

  it('прочерк по-прежнему запрещён — он читается как ноль', () => {
    expect(FACTS).not.toMatch(/value: '[—–-]'/);
  });

  it('незнание не красится тревогой: не знаем — не то же, что опасно', () => {
    const start = FACTS.indexOf('const UNKNOWN_TONE');
    expect(start).toBeGreaterThan(0);
    const line = FACTS.slice(start, FACTS.indexOf('\n', start));
    expect(line).not.toContain('--warning');
    expect(line).not.toContain('--danger');
    expect(line).toContain('--text-secondary');
  });

  it('вес шрифта в тоне не задаётся — иначе исход решала бы сборка', () => {
    const start = FACTS.indexOf('const UNKNOWN_TONE');
    const line = FACTS.slice(start, FACTS.indexOf('\n', start));
    expect(line).not.toMatch(/font-(normal|medium|semibold|bold)/);
  });
});

/**
 * Срез 3: одно действие-кнопка, один фиксированный слой.
 *
 * На телефоне поверх содержимого висели ТРИ постоянных слоя: липкая шапка
 * действий, фиксированный бар со скачиванием GPX и фиксированный SOS. Бар GPX
 * держался от SOS константой 52 пикселя, списанной с чужого компонента, —
 * наехать друг на друга они уже успели однажды, и закрыт тогда оказался бы
 * SOS.
 */
describe('одно действие-кнопка, один фиксированный слой', () => {
  const CLIENT = codeOnly(readFileSync(join(ROOT, 'app', 'places', '[id]', '_PlaceDetailClient.tsx'), 'utf-8'));
  const BAR = codeOnly(readFileSync(join(PLACES, 'PlaceActionBar.tsx'), 'utf-8'));

  it('в карточке не осталось своего фиксированного бара — SOS единственный', () => {
    expect(CLIENT).not.toMatch(/className="[^"]*\bfixed\b[^"]*"/);
    expect(CLIENT).not.toContain('MobileBottomBar');
  });

  it('константы «высота SOS» больше нет — слои не держатся друг за друга числом', () => {
    expect(CLIENT).not.toMatch(/env\(safe-area-inset-bottom\)\s*\+\s*\d+px/);
  });

  it('GPX места остался достижим и ровно одной ссылкой', () => {
    const hits = CLIENT.match(/\/api\/places\/\$\{place\.id\}\/gpx/g) ?? [];
    expect(hits.length, 'вторая копия действия расходится поведением (#887)').toBe(1);
    expect(CLIENT).toContain('Скачать точку (GPX)');
  });

  it('главное действие названо тем, что делает, а не «Навигация»', () => {
    // «Навигация» исторически означала выбор ЧУЖОГО навигатора; с 13.09 кнопка
    // будит наш расчёт по дорожному графу, и имя должно говорить об этом.
    expect(BAR).toContain('Проложить путь');
    expect(BAR).not.toMatch(/>\s*Навигация\s*</);
  });

  it('акцентная кнопка в шапке действий одна', () => {
    const accent = BAR.match(/background:\s*'var\(--accent\)'/g) ?? [];
    expect(accent.length, 'акцент, употреблённый дважды, перестаёт быть акцентом').toBe(1);
  });
});

describe('дружелюбие не отменило тревогу', () => {
  it('уровень по-прежнему считается по isOpen и alertSeverity', () => {
    expect(STATUS).toContain('function getLevel');
    expect(STATUS).toContain('if (!rt.isOpen) return');
    expect(STATUS).toContain('rt.alertSeverity');
  });

  it('красный и оранжевый по-прежнему липкие', () => {
    expect(STATUS).toContain("level === 'red' || level === 'orange'");
    expect(STATUS).toContain('sticky top-0');
  });

  it('цвета остались семантическими токенами', () => {
    expect(STATUS).toContain('var(--danger)');
    expect(STATUS).toContain('var(--success)');
    expect(STATUS).toContain('var(--warning)');
  });
});
