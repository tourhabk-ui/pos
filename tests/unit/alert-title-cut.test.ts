/**
 * Заголовок алерта из поста без заголовка не рвётся на полуслове (#2293).
 *
 * 08.10 гидро-алерт ушёл в get_guardian_context заголовком «…до 40
 * сантиметров в сутки, на»: первая фраза поста резалась ровно на 200-м знаке.
 * Обрыв на полуслове читается как сбой, а не как сокращение, и предупреждение
 * перестаёт читаться предупреждением.
 *
 * Сторож держит:
 * 1. длинная фраза режется по границе слова и кончается многоточием;
 * 2. короткая фраза и прежние случаи (значок в начале) не меняются;
 * 3. external_id поста без заголовка — прежний: отпечаток считается по старому
 *    ключу, иначе тот же пост на следующем приёме лёг бы второй строкой.
 */
import { describe, it, expect } from 'vitest';
import {
  classifyMchsItem, titleFingerprint, titleFromText, titleKeyFromText,
} from '@/lib/services/safety/seismic-parser';

// Первая фраза пункта сводки 08.10 (заголовок — из #2293), длиннее 200 знаков.
const HYDRO =
  'Так, на реках Елизовского округа ожидается подъём уровня воды интенсивностью до 20 сантиметров в сутки, '
  + 'на реках Усть-Большерецкого, Соболевского и Тигильского округов — до 40 сантиметров в сутки, '
  + 'на реках Мильковского округа — до 30 сантиметров в сутки. Возможен выход воды на пойму.';

/** Как заголовок брался до 09.10 — ровно та обрезка, что дала «…, на». */
function legacyTitle(text: string): string {
  const clean = text.replace(/\s+/g, ' ').replace(/^[^\p{L}\p{N}]+/u, '').trim();
  return (/^[^.!?]{10,200}/.exec(clean)?.[0] ?? clean).trim().slice(0, 200);
}

describe('заголовок длинной фразы', () => {
  it('прежняя обрезка давала обрыв на полуслове — тот самый случай #2293', () => {
    expect(legacyTitle(HYDRO)).toMatch(/в сутки, на$/);
  });

  it('режется по слову, кончается многоточием, не длиннее 200', () => {
    const t = titleFromText(HYDRO);
    expect(t.length).toBeLessThanOrEqual(200);
    expect(t.endsWith('…')).toBe(true);
    expect(t).toBe(
      'Так, на реках Елизовского округа ожидается подъём уровня воды интенсивностью до 20 сантиметров в сутки, '
      + 'на реках Усть-Большерецкого, Соболевского и Тигильского округов — до 40 сантиметров в сутки…',
    );
  });

  it('перед многоточием нет висящей запятой и обрывка слова', () => {
    const t = titleFromText(`${'Слово '.repeat(40)}конец.`);
    expect(t).toMatch(/Слово…$/);
    expect(t.length).toBeLessThanOrEqual(200);
  });
});

describe('короткие фразы не меняются', () => {
  it('фраза до 200 знаков — как есть, без многоточия', () => {
    expect(titleFromText('На вулкане Шивелуч произошёл пепловый выброс. Высота 10 км.'))
      .toBe('На вулкане Шивелуч произошёл пепловый выброс');
  });

  it('значок в начале по-прежнему снимается', () => {
    expect(titleFromText('\u{1F4CC}К тушению техногенных пожаров привлекались один раз'))
      .toBe('К тушению техногенных пожаров привлекались один раз');
  });

  it('ключ отпечатка — прежняя обрезка', () => {
    expect(titleKeyFromText(HYDRO)).toBe(legacyTitle(HYDRO));
  });
});

describe('external_id поста без заголовка не меняется', () => {
  it('отпечаток по прежнему ключу, заголовок — новый', () => {
    const ev = classifyMchsItem('vk-1', '', HYDRO, '2026-10-08T03:00:00Z', 'https://vk.com/wall-1_1', 'vk_mchs');
    expect(ev).not.toBeNull();
    expect(ev?.source_id).toBe(`vk_mchs/2026-10-08/t${titleFingerprint(legacyTitle(HYDRO))}`);
    expect(ev?.title).toBe(titleFromText(HYDRO));
  });
});
