/**
 * Маршрут строится ОТ ЧЕЛОВЕКА, и человек виден на карте выбора.
 *
 * Два полевых скрина 17.08, один заход:
 *
 *   1. «Куда идём?», превью «Вулкан Козельский» — три кружка на карте края и
 *      вопрос владельца: «где точка моего местонахождения?». Решение идти или
 *      не идти принимают именно на этом экране, а принять его, не видя себя,
 *      нельзя: рядом это или за перевалом — по трём кружкам не понять.
 *   2. Кокпит того же маршрута — «3 из 3» при том, что до маршрута десятки
 *      километров. Кокпит при первом фиксе брал БЛИЖАЙШУЮ точку без вопроса,
 *      на маршруте человек или нет; ближайшей случайно оказалась последняя.
 *      Прибор объявил пройденным то, к чему не подошли.
 *
 * Второе — не косметика. Полный прогресс и «точек впереди нет» на маршруте,
 * который не начат, — это ложное показание навигационного прибора, того же
 * рода, что линия через весь край: экран уверенно сообщает о пути то, чего не
 * знает.
 *
 * «Ближайшая точка» значит «продолжайте отсюда» и осмысленна только для того,
 * кто уже на тропе. Для всех остальных маршрут начинается с начала, а дорога
 * до него называется подходом.
 */
import { describe, it, expect } from 'vitest';
import { readFileSync } from 'node:fs';
import { join } from 'node:path';
import { ON_ROUTE_ENTRY_KM, DATA_CONFLICT_KM } from '@/lib/on-route/approach';

const SRC = readFileSync(join(process.cwd(), 'app/planning/_PlanningClient.tsx'), 'utf-8');
/** Код без комментариев: прежнее поведение в них описано намеренно. */
const CODE = SRC.replace(/\/\*[\s\S]*?\*\//g, '').replace(/^\s*\/\/.*$/gm, '');

describe('порог «уже на маршруте» — величина полевая, а не произвольная', () => {
  it('это радиус видимости точки, а не десятки километров', () => {
    // С километра точку видно и на километр сходят с тропы. Всё, что больше,
    // — уже не «продолжайте отсюда».
    expect(ON_ROUTE_ENTRY_KM).toBeGreaterThan(0);
    expect(ON_ROUTE_ENTRY_KM).toBeLessThanOrEqual(2);
  });

  it('он не строже порога расхождения данных', () => {
    // Иначе получилось бы, что человек «на маршруте» там, где сама платформа
    // считает точку и линию разными данными.
    expect(ON_ROUTE_ENTRY_KM).toBeLessThanOrEqual(DATA_CONFLICT_KM);
  });
});

describe('кокпит не объявляет пройденным то, к чему не подошли', () => {
  it('прыжок к ближайшей точке обусловлен близостью', () => {
    // Голый setCurrentWpIdx(best) — ровно тот дефект: ближайшая точка бралась
    // всегда, включая случай «человек в городе».
    expect(CODE).toMatch(/bestD <= ON_ROUTE_ENTRY_KM \? best : 0/);
    expect(CODE).not.toMatch(/setCurrentWpIdx\(best\);/);
  });

  it('порог берётся из общего места, своего числа в экране нет', () => {
    expect(SRC).toMatch(/import \{ approachPlan, ON_ROUTE_ENTRY_KM \} from '@\/lib\/on-route\/approach'/);
  });

  it('далеко от маршрута — начало маршрута, а не его конец', () => {
    // Фолбэк именно 0: последняя точка как «вход» означала бы обратный обход,
    // а трек и его накопленные расстояния (trackDm) при этом остались бы
    // прямыми — прогресс считался бы по одному направлению, а ноги шли по
    // другому. Разворот маршрута — отдельная работа, не побочный эффект.
    expect(CODE).toMatch(/setCurrentWpIdx\(bestD <= ON_ROUTE_ENTRY_KM \? best : 0\)/);
    expect(CODE).not.toMatch(/\? best : waypoints\.length - 1/);
  });
});

describe('на превью видно, где я', () => {
  it('карта выбора маршрута показывает положение человека', () => {
    expect(CODE).toMatch(/markers=\{previewMap\.markers\}[\s\S]{0,120}showUserLocation/);
  });

  it('полноэкранная карта его показывает по-прежнему', () => {
    expect(CODE).toMatch(/markers=\{mapMarkers\}[\s\S]{0,200}showUserLocation/);
  });
});
