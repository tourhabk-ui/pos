/**
 * До кнопок шапки можно дотронуться — их не перекрывает собственное меню.
 *
 * ── Что нашлось 12.09 ─────────────────────────────────────────────────────
 *
 * Центральная навигация стояла `position:absolute; left:50%` поверх ряда
 * кнопок справа. Позиционированный элемент красится выше статического, и та
 * половина её ширины, что дотягивалась до кнопок, забирала их клики себе.
 * Замер headless-браузером (`elementFromPoint` по центру каждой кнопки):
 *
 *   1024px — перехвачены ВСЕ шесть, включая SOS (его накрывали «Операторы»);
 *   1280px — поиск, гео, тема;
 *   1440px — поиск;
 *   1536px и шире — чисто.
 *
 * То есть на любом ноутбуке поиск и смена темы не работали, а на 1024-1150 не
 * работал SOS: человек жал красную кнопку и уходил в «Операторы». §7 и §11
 * требуют, чтобы SOS был доступен всегда, — кнопка под чужим меню этого не
 * даёт, как бы правильно она ни выглядела на скриншоте.
 *
 * Дефект дожил до сегодня потому, что ни один вид проверки его не искал:
 * разметка верная, стили верные, скриншот верный. Виден он ровно одним
 * способом — спросить браузер, чей элемент лежит в точке клика.
 *
 * ── Разделение труда ──────────────────────────────────────────────────────
 *
 * ФАКТ держит браузер: `test/e2e/seo-flows.spec.ts`, «кнопки шапки не
 * перекрыты на ширине N» — хит-тест на живом проде, три ширины. Он и нашёл
 * бы дефект снова.
 *
 * ФОРМУ держит этот файл: e2e ходит ночью и по проду, а вернуть absolute в
 * шапку можно сегодня и локально. Сторож на исходнике краснеет в момент
 * коммита — до того, как правка доедет до людей. Он НЕ доказывает, что
 * кнопки достижимы (статикой это недоказуемо), он запрещает ровно ту
 * конструкцию, которой они были перекрыты, и требует, чтобы живая проверка
 * существовала.
 */
import { describe, it, expect } from 'vitest';
import { readFileSync } from 'node:fs';
import { join } from 'node:path';

const ROOT = process.cwd();
const HEADER = join(ROOT, 'components/layout/Header.tsx');
const E2E = join(ROOT, 'test/e2e/seo-flows.spec.ts');

/** Код без комментариев: процитированный в пояснении дефект — не дефект. */
function code(path: string): string {
  return readFileSync(path, 'utf-8')
    .replace(/\/\*[\s\S]*?\*\//g, ' ')
    .replace(/^[ \t]*\/\/.*$/gm, ' ')
    .replace(/\{\/\*[\s\S]*?\*\/\}/g, ' ');
}

describe('шапка: меню не лежит поверх кнопок', () => {
  it('шапка разложена дорожками, а не flex с накладкой', () => {
    const src = code(HEADER);
    expect(src, 'шапка больше не grid — накладка снова возможна').toContain("display: 'grid'");
    expect(src, 'у шапки не три дорожки: логотип / навигация / кнопки').toContain(
      "gridTemplateColumns: '1fr auto 1fr'",
    );
  });

  it('центральная навигация не позиционирована поверх соседей', () => {
    const src = code(HEADER);
    const navBlock = src.slice(src.indexOf('<nav'), src.indexOf('</nav>'));
    expect(navBlock.length, 'в шапке не нашлось <nav> — проверять нечего').toBeGreaterThan(50);
    expect(navBlock, "навигация снова absolute — она накроет кнопки, включая SOS").not.toMatch(
      /position:\s*'absolute'/,
    );
    expect(navBlock, 'навигация снова сдвигается трансформом от середины').not.toMatch(
      /translateX\(-50%\)/,
    );
  });

  it('навигация показывается там, где помещается (xl), а не с lg', () => {
    // Замер: десять пунктов — 896-970px (два разных гротеска, живой шрифт
    // между ними), ряд кнопок — 274px; на дорожках всё вместе требует ~1180px.
    // lg (1024) меньше этого — ниже порога кнопки выталкивались бы за край.
    const navBlock = code(HEADER).slice(code(HEADER).indexOf('<nav'), code(HEADER).indexOf('</nav>'));
    expect(navBlock, 'навигация вернулась на lg — на 1024px она не помещается').not.toContain('lg:flex');
    expect(navBlock, 'порог показа навигации не xl').toContain('xl:flex');
  });

  it('живая проверка существует и спрашивает браузер, а не разметку', () => {
    // Правило 10.09: у объявления обязан быть механизм. Сторож выше
    // запрещает форму; факт достижимости доказывает только хит-тест.
    const e2e = readFileSync(E2E, 'utf-8');
    expect(e2e, 'хит-тест кнопок шапки пропал — форму стережём, факт никто').toContain(
      'elementFromPoint',
    );
    for (const width of [1024, 1280, 1440]) {
      expect(e2e, `ширина ${width}px выпала из хит-теста`).toContain(String(width));
    }
  });

  it('SOS в шапке — общий компонент, а не своя копия', () => {
    // §11: копия расходится поведением. Проверка здесь потому, что именно
    // SOS был перекрыт: если его однажды заменят локальной кнопкой, разбор
    // «почему SOS не нажимается» начнётся заново и с другого места.
    const src = code(HEADER);
    expect(src, 'SOS в шапке больше не EmergencyAction').toContain('<EmergencyAction />');
  });
});
