/**
 * tests/unit/kuzmich-refusal.test.ts
 *
 * Отказ модели виден: он не «нет ответа» и не «плохой ответ».
 *
 * ── Что было (issue #1730) ─────────────────────────────────────────────────
 *
 * Грейдер отсекал всё короче 50 знаков — «пропускаем очень короткие ответы
 * (ошибки, перебои)». Против обрывов порог верен, но **отказ короток по
 * природе**: «не могу помочь с этим вопросом» — 32 знака. Значит отказ не
 * попадал в оценку ВООБЩЕ: ни балла, ни записи, ни следа, и был неотличим от
 * обрыва связи и от того, что ответа не было.
 *
 * Своего списка запрещённых тем у платформы нет — отказ выносит ПРОВАЙДЕР, а
 * водопад меняет провайдера молча. Кузьмич при этом советник по безопасности в
 * поле, и наши законные вопросы лежат ровно в темах, по которым модели
 * отказывают целиком: медведь и чем его отпугнуть, кровь, переохлаждение,
 * оружие в разрешённом промысловом районе. Со стороны это выглядит как
 * «Кузьмич иногда странный».
 *
 * ── Что держит сторож ──────────────────────────────────────────────────────
 *
 * Три границы, каждая из которых при потере возвращает исходную беду:
 *  1. отказ доходит до записи, а не гибнет на пороге длины;
 *  2. отказ и обрыв — РАЗНЫЕ исходы (чинятся в разных местах);
 *  3. отказ не смешивается с низким баллом в сводке и не считается
 *     «оценённым»: оценивать было нечего.
 *
 * ── Чего сторож НЕ утверждает ──────────────────────────────────────────────
 *
 * Что кто-то из наших провайдеров на этих темах действительно отказывает.
 * Замера нет, и сама находка честно помечает это как непроверенное. Здесь
 * чинится СЛЕПОТА к отказу, а не отказ.
 */
import { describe, it, expect } from 'vitest';
import { readFileSync } from 'node:fs';
import { join } from 'node:path';
import { classifyResponse, isRefusal, REFUSAL_MAX_LEN } from '@/lib/kuzmich/refusal-detector';

const GRADER = readFileSync(join(process.cwd(), 'lib/agents/managed/kuzmich-outcomes.ts'), 'utf-8');
const PROVIDERS = readFileSync(join(process.cwd(), 'lib/ai/providers.ts'), 'utf-8');

describe('отказ узнаётся', () => {
  it('короткий русский отказ — тот самый случай из находки', () => {
    const v = classifyResponse('Извините, я не могу помочь с этим вопросом.');
    expect(v.kind).toBe('refusal');
    expect(v.signals.length).toBeGreaterThan(0);
  });

  it('отказ короче прежнего порога в 50 знаков', () => {
    // Ровно поэтому его и не было видно.
    const text = 'Не могу помочь.';
    expect(text.length).toBeLessThan(50);
    expect(isRefusal(text)).toBe(true);
  });

  it('английский отказ считается отказом — водопад многоязычен', () => {
    expect(isRefusal("I'm sorry, but I cannot help with that request.")).toBe(true);
    expect(isRefusal('As an AI language model, I cannot provide this.')).toBe(true);
  });

  it('отсылка к специалисту без ответа — тоже отказ', () => {
    expect(isRefusal('Обратитесь к специалисту.')).toBe(true);
  });
});

describe('отказ отличается от обрыва — это разные починки', () => {
  it('заглушка водопада — обрыв, а не отказ', () => {
    // Провайдеры молчали, модель не отвечала ничего. Записать это провайдеру
    // как отказ по теме значило бы чинить промпт при мёртвых ключах — ровно
    // тот урок, что уже выучен на судье фактчека 22.08.
    const v = classifyResponse('Извините, сервис временно недоступен. Попробуйте позже.');
    expect(v.kind).toBe('outage');
  });

  it('строка заглушки сверена с той, что реально возвращает водопад', () => {
    // Копия строки в детекторе разошлась бы с оригиналом молча.
    expect(PROVIDERS).toMatch(/Извините, сервис временно недоступен/);
  });

  it('пустой ответ — обрыв, а не отказ', () => {
    expect(classifyResponse('').kind).toBe('outage');
    expect(classifyResponse('   ').kind).toBe('outage');
  });
});

describe('ложных срабатываний нет там, где они дороже всего', () => {
  it('настоящий длинный ответ с оговоркой — ответ, а не отказ', () => {
    // Самый опасный ложный случай: осторожный, но ПОЛЕЗНЫЙ ответ про травму.
    // Пометить его отказом — значит позвать разбираться с провайдером, который
    // ни при чём, и заодно испортить среднюю оценку.
    const long = 'При переохлаждении первым делом убери человека с ветра и смени мокрое на сухое. '
      + 'Грелку и горячее питьё давай постепенно, растирать снегом нельзя. Я не врач, поэтому при '
      + 'спутанной речи и потере координации звони 112 сразу — это уже не то состояние, которое '
      + 'лечат в палатке. Обратитесь к специалисту при первой возможности, а до его приезда следи '
      + 'за дыханием и держи человека в тепле, не давая ему уснуть на холоде.';
    expect(long.length).toBeGreaterThan(REFUSAL_MAX_LEN);
    expect(classifyResponse(long).kind).toBe('answer');
  });

  it('короткий полезный ответ про медведя отказом не считается', () => {
    expect(classifyResponse('Фальшфейер держи наготове, шуми и отходи не поворачиваясь спиной.').kind)
      .toBe('answer');
  });

  it('порог поиска отказа выше прежнего порога грейдера', () => {
    // Иначе отказ с вежливым хвостом снова проскочит мимо.
    expect(REFUSAL_MAX_LEN).toBeGreaterThan(50);
  });
});

describe('грейдер: отказ доходит до записи', () => {
  it('род ответа определяется РАНЬШЕ порога длины', () => {
    const kindAt = GRADER.indexOf('const kind = classifyResponse(botResponse)');
    const lenAt = GRADER.indexOf('if (botResponse.length < 50) return');
    expect(kindAt).toBeGreaterThan(-1);
    expect(lenAt).toBeGreaterThan(-1);
    expect(kindAt).toBeLessThan(lenAt);
  });

  it('отказ уходит в запись, а не в return', () => {
    expect(GRADER).toMatch(/if \(kind\.kind === 'refusal'\) \{\s*\n\s*await recordRefusal\(/);
  });

  it('обрыв по-прежнему мимо оценки — и это отдельная ветка', () => {
    expect(GRADER).toMatch(/if \(kind\.kind === 'outage'\) return;/);
  });

  it('в записи отказа есть провайдер — ради него всё и затевалось', () => {
    expect(GRADER).toMatch(/outcome_kind:\s*'refusal'/);
    expect(GRADER).toMatch(/provider:\s*opts\?\.provider \?\? null/);
    expect(GRADER).toMatch(/refusal_signals:\s*signals/);
  });

  it('балла у отказа нет и он не выдумывается', () => {
    // Условная единица смешала бы отказ с плохим ответом в одной средней.
    expect(GRADER).toMatch(/Балла нет: модель не отвечала на вопрос/);
  });

  it('сорванная запись отказа не молчит', () => {
    expect(GRADER).toMatch(/logSwallowedFailure\('kuzmich-outcomes', 'запись отказа модели'/);
  });
});

describe('сводка: отказы отдельно от низких баллов', () => {
  it('у сводки есть свой счёт отказов', () => {
    expect(GRADER).toMatch(/refusal_count: number/);
    expect(GRADER).toMatch(/metadata->>'outcome_kind' = 'refusal'/);
  });

  it('отказ не считается «оценённым» — оценивать было нечего', () => {
    // Прежний COUNT(*) завысил бы объём проверки ровно на непроверенное.
    expect(GRADER).toMatch(/COUNT\(\*\) FILTER \(WHERE compiled_truth ~ 'Оценка/);
    expect(GRADER).not.toMatch(/COUNT\(\*\) AS total,/);
  });
});
