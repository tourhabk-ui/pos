/**
 * Сторож: основной дайджест отбирает то, что касается нас (решение владельца
 * 26.09, «новости мимо» → «2 да»).
 *
 * Выпуск 25.09 — двадцать четыре пункта: налог Мальдив, символ Абрау-Дюрсо,
 * Суперкубок в Стамбуле, дожди в Турции. Промпт просил «3-5 инсайтов» и тут
 * же «широкие правила — лучше включить лишнее», с «другими регионами» в
 * туриндустрии. Модель исполнила второе.
 *
 * Держится принцип, а не перечень: три адресата, потолок пунктов и перевес
 * в сторону «не включать». Список чужих курортов в промпте рос бы вечно.
 */
import { describe, it, expect } from 'vitest';
import { readFileSync } from 'node:fs';
import { join } from 'node:path';

const SRC = readFileSync(join(process.cwd(), 'lib/agents/scout-digest.ts'), 'utf8');
const PROMPT = SRC.slice(SRC.indexOf('Ты разведчик туристической платформы'), SRC.indexOf('Кратко и по делу. Без воды.'));

describe('отбор основного дайджеста', () => {
  it('промпт найден', () => {
    expect(PROMPT.length).toBeGreaterThan(500);
  });

  it('прежнее «лучше включить лишнее» ушло целиком', () => {
    expect(PROMPT).not.toMatch(/лучше включить лишнее/);
    expect(PROMPT).not.toMatch(/даже косвенно полезное включай/);
    expect(PROMPT).not.toMatch(/Другие регионы — допустимы/);
  });

  it('потолок пунктов на весь выпуск назван числом', () => {
    expect(PROMPT).toMatch(/от 3 до 7 пунктов на все разделы вместе/);
  });

  it('три адресата — Камчатка, платформа, мы как разработчики', () => {
    expect(PROMPT).toMatch(/туристу или оператору на Камчатке/);
    expect(PROMPT).toMatch(/нашей платформе/);
    expect(PROMPT).toMatch(/нам как разработчикам/);
  });

  it('сомнение решается в пользу «не включать»', () => {
    expect(PROMPT).toMatch(/Сомневаешься — не включай/);
  });

  it('правила честности на месте', () => {
    expect(PROMPT).toMatch(/НЕ ВРАТЬ/);
    expect(PROMPT).toMatch(/СОСЕДНИЙ РЕГИОН — НЕ КАМЧАТКА/);
  });
});
