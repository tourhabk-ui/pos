/**
 * tests/unit/scout-kamchatka-live-sources.test.ts
 *
 * У раздела «Камчатка» снова есть чем жить — и это проверено сервером.
 *
 * ── Что было к вечеру 08.09 ────────────────────────────────────────────────
 *
 * Живых новостных источников о крае не осталось ни одного: kamgov и 41.mchs
 * сняли RSS 01.08, kamchatka.aif.ru отдаёт HTML по всем трём обычным адресам
 * (замер 40: HTTP 200, `text/html`, `looks_like_feed: false`, одна и та же
 * страница на 9.5 КБ). В камчатской категории оставались два источника, и оба
 * не про новости края: МЧС России (федеральный) и наш собственный safety-слой
 * (сейсмика, вулканы, дороги, пожары).
 *
 * Раздел при этом не пустовал — синтез брал федеральную новость про Дальний
 * Восток и ставил её под краевой заголовок. Формально не выдумка, фактически
 * подмена региона соседним.
 *
 * ── Что внесено (09.09) ────────────────────────────────────────────────────
 *
 * Два источника, подтверждённые ПЕРЕПИСЬЮ, а не предложением модели:
 *
 *   poluostrov-kamchatka.ru — RSS, 48 КБ, свежайший материал в день замера,
 *     региональность 15 заголовков из 19;
 *   t.me/s/kamchatinfo — 330 постов в превью, последний в день замера.
 *
 * Региональность мерялась отдельно и намеренно: лента бывает живой, свежей и
 * НЕ О КРАЕ — ровно так раздел и получил новость про ДФО.
 *
 * ── Что держит сторож ──────────────────────────────────────────────────────
 *
 * Что краевая категория опирается не только на федеральные каналы и на нашу
 * же базу. Если оба новых источника однажды удалят, тест покраснеет — и это
 * верно: возврат к прежнему состоянию должен быть виден, а не случиться тихо.
 */
import { describe, it, expect } from 'vitest';
import { RSS_SOURCES } from '@/lib/agents/scout-sources';

const kamchatka = RSS_SOURCES.filter(s => s.category === 'kamchatka');

describe('краевые новостные источники внесены', () => {
  it('RSS краевого издания на месте', () => {
    const one = kamchatka.find(s => s.key === 'poluostrov_kamchatka');
    expect(one, 'источник poluostrov_kamchatka пропал из состава').toBeDefined();
    expect(one?.kind).toBe('rss');
  });

  it('телеграм краевого агентства на месте', () => {
    const one = kamchatka.find(s => s.key === 'tg_kamchatinfo');
    expect(one, 'источник tg_kamchatinfo пропал из состава').toBeDefined();
    expect(one?.kind).toBe('telegram');
    // Читать можно только публичное превью: t.me/s/<канал>.
    expect(one?.url).toMatch(/^https:\/\/t\.me\/s\/[A-Za-z0-9_]+$/);
  });

  it('в краевой категории есть источник НОВОСТЕЙ, а не только безопасности', () => {
    // Прежнее состояние: МЧС России (федеральный) плюс наш safety-слой. По
    // ним нельзя узнать, что происходит в крае, — только что там тряхнуло.
    const newsy = kamchatka.filter(s => s.key !== 'safety_layer' && s.key !== 'tg_mchs_official');
    expect(newsy.length, 'краевая категория снова держится только на МЧС и своей базе').toBeGreaterThan(0);
  });
});

describe('надзорные каналы внесены, а объём — нет', () => {
  it('Ространснадзор и Роспотребнадзор на месте', () => {
    const keys = RSS_SOURCES.map(s => s.key);
    expect(keys).toContain('tg_rostransnadzor');
    expect(keys).toContain('tg_rospotrebnadzor');
  });

  it('общеминистерский канал Минэка НЕ внесён — у нас есть отраслевой', () => {
    // Проверку он прошёл, но отвечает на другой вопрос: про туризм говорит
    // tg_minec_tourism, а объём в разведке уже наказывал нас тем, что в нём
    // тонули редкие сигналы. Пройденная проверка — не повод вносить.
    const urls = RSS_SOURCES.map(s => s.url);
    expect(urls).toContain('https://t.me/s/minec_tourism');
    expect(urls).not.toContain('https://t.me/s/minec_russia');
  });
});

describe('состав остаётся читаемым машиной', () => {
  it('ключи уникальны', () => {
    const keys = RSS_SOURCES.map(s => s.key);
    expect(new Set(keys).size, `дубли ключей: ${keys.length - new Set(keys).size}`).toBe(keys.length);
  });

  it('адреса уникальны — один источник не заводится дважды', () => {
    const urls = RSS_SOURCES.map(s => s.url.replace(/\/+$/, '').toLowerCase());
    expect(new Set(urls).size).toBe(urls.length);
  });
});
