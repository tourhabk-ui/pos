/**
 * Заголовок поста без заголовка не склеивается со следующим предложением (#3216).
 *
 * 10.11 пост ГИМС про осенний лёд открывался строкой-заголовком без точки.
 * Переносы строк схлопывались, заголовок брался до первой точки, и в ленту
 * лёг «…об опасности осеннего льда То и дело можно заметить жителей…» — на
 * карточке каждого места рядом со своей короткой копией.
 *
 * Сторож держит:
 * 1. строка-заголовок без конца фразы, за которой идёт новая фраза, — заголовок;
 * 2. перенос посреди фразы, строка со знаком конца фразы, двоеточие,
 *    однострочный пост — прежнее правило первой фразы;
 * 3. external_id поста не меняется: отпечаток — по прежнему ключу.
 */
import { describe, it, expect } from 'vitest';
import {
  classifyMchsItem, titleFingerprint, titleFromText, titleKeyFromText,
} from '@/lib/services/safety/seismic-parser';

const HEAD = 'Инспекторы Центра ГИМС МЧС России предупреждают камчатцев об опасности осеннего льда';
const ICE = `${HEAD}\n\nТо и дело можно заметить жителей и гостей полуострова, которые с энтузиазмом катаются на коньках на водоёмах. Лёд в ноябре тонкий.`;

describe('строка-заголовок', () => {
  it('пост ГИМС 10.11 даёт заголовок без приклеенного предложения', () => {
    expect(titleFromText(ICE)).toBe(HEAD);
  });

  it('значок и приветствие перед заголовком снимаются', () => {
    expect(titleFromText(`Доброе утро!\n\u{1F4CC}${ICE}`)).toBe(HEAD);
  });
});

describe('прежнее правило первой фразы', () => {
  it('перенос посреди фразы — фраза целиком', () => {
    const t = 'На реках Елизовского округа ожидается\nподъём уровня воды. Будьте осторожны.';
    expect(titleFromText(t)).toBe('На реках Елизовского округа ожидается подъём уровня воды');
  });

  it('первая строка с точкой — до точки', () => {
    expect(titleFromText('На вулкане Шивелуч произошёл пепловый выброс. Высота 10 км.\nПодробности ниже.'))
      .toBe('На вулкане Шивелуч произошёл пепловый выброс');
  });

  it('строка с двоеточием вводит список и заголовком не считается', () => {
    const t = 'Закрыты для проезда участки дорог:\nМильково — Ключи. Усть-Камчатск.';
    expect(titleFromText(t)).toBe('Закрыты для проезда участки дорог: Мильково — Ключи');
  });

  it('однострочный пост — как раньше', () => {
    expect(titleFromText('Штормовое предупреждение: ветер до 30 м/с'))
      .toBe('Штормовое предупреждение: ветер до 30 м/с');
  });
});

// Пост той же формы, который классификатор принимает предупреждением.
const WIND_HEAD = 'Экстренное предупреждение по Камчатскому краю';
const WIND = `${WIND_HEAD}\nОжидается сильный ветер до 30 м/с в южных районах края. Будьте осторожны.`;

describe('external_id не меняется', () => {
  it('отпечаток по прежнему ключу, заголовок — строка-заголовок', () => {
    const ev = classifyMchsItem('vk-2', '', WIND, '2026-11-10T03:00:00Z', 'https://vk.com/wall-1_2', 'vk_mchs');
    expect(ev).not.toBeNull();
    expect(ev?.source_id).toBe(`vk_mchs/2026-11-10/t${titleFingerprint(titleKeyFromText(WIND))}`);
    expect(titleKeyFromText(WIND).startsWith(`${WIND_HEAD} Ожидается`)).toBe(true);
    expect(ev?.title).toBe(WIND_HEAD);
  });
});
