import { describe, expect, it } from 'vitest';
import { classifyMchsItem, classifyMchsItems, tsunamiStatus } from '@/lib/services/safety/seismic-parser';

// Разбор 43 пушей за 60 дней (журнал traveller_notified, перепись 20.10).
// Порог пуша: severity >= 2 или tsunami_warning (safety-ingest dispatchPushAlerts).
const PUB = new Date().toISOString();
const pushes = (title: string, text: string) =>
  classifyMchsItems('t', title, text, PUB, '', 'vk_mchs').filter((e) => e.severity >= 2 || e.alert_type === 'tsunami_warning');

const KNDR = `МЧС России и КНДР укрепляют партнерство в сфере защиты от чрезвычайных ситуаций
В Пхеньянском дворце съездов состоялась двусторонняя встреча делегации МЧС России во главе с Министром РФ Александром Куренковым и Министром по делам стихийных бедствий КНДР Ким Чхоль Намом.
«КНДР заинтересована в изучении российского опыта мониторинга и оценки рисков стихийных бедствий, включая наводнения, оползни и цунами. Сотрудничество с МЧС России позволит нам совершенствовать собственные механизмы прогнозирования и реагирования», – отметил Министр.
Важным итогом встречи стало подписание плана совместных мероприятий до 2029 года.`;

const SUMMARY_19_10 = `Доброе утро!
📌 За прошедшие сутки к тушению техногенных пожаров и ликвидации последствий ДТП сотрудники МЧС России не привлекались.
📌 От Камчатского филиала геофизической службы РАН в адрес ГУ МЧС России по Камчатскому краю официально поступала информация об одном сейсмособытии, которое ощущалось в населенных пунктах силой до 2 баллов. Угрозы цунами не объявлялось.
📌 Остаётся закрытым проезд для всех видов транспорта на участке автодороги в Усть-Большерецком округе.
📌 Остаются ограничения для пассажирского транспорта на дороге мыс Левашова – посёлок Октябрьский в Усть-Большерецком округе.
Период сводки — с 06:00 18.10. по 06:00 19.10.`;

const WEEK_06_09 = `Друзья! Началась новая трудовая неделя, и самое время подвести итоги минувшей.
🔵 За семь дней, с 24 по 30 августа, пожарно-спасательные подразделения 12 раз выезжали на тушение пожаров.
🔵 Остаются ограничения для пассажирского транспорта на дороге мыс Левашова – посёлок Октябрьский. Закрыт проезд на участке автодороги в Усть-Большерецком округе.`;

describe('ложные пуши из истории — на новом коде не уходят', () => {
  it('12.10 «МЧС России и КНДР…» — не цунами', () => {
    expect(tsunamiStatus(KNDR)).toBeNull();
    expect(pushes('', KNDR)).toEqual([]);
    expect(pushes('МЧС России и КНДР укрепляют партнерство в сфере защиты от чрезвычайных ситуаций', KNDR)).toEqual([]);
  });
  it('19.10 «Доброе утро!» + суточная сводка — без пуша, заголовок не приветствие', () => {
    expect(pushes('', SUMMARY_19_10)).toEqual([]);
    for (const e of classifyMchsItems('t', '', SUMMARY_19_10, PUB, '', 'vk_mchs')) expect(e.title).not.toMatch(/Доброе утро/);
  });
  it('06.09 «Друзья! Началась новая трудовая неделя…» — без пуша', () => {
    expect(pushes('', WEEK_06_09)).toEqual([]);
  });
  it('20.10 сводка «к тушению техногенных пожаров…» — без пуша', () => {
    expect(pushes('', `📌 За прошедшие сутки к тушению техногенных пожаров сотрудники МЧС России привлекались 1 раз. Горел мусор.\n📌 Остаётся закрытым проезд для всех видов транспорта на участке автодороги в Усть-Большерецком округе.`)).toEqual([]);
  });
});

describe('настоящие тревоги из истории — на новом коде уходят', () => {
  const real: Array<[string, string]> = [
    ['road_closure', 'Внимание! Ограничение движения для всех видов транспорта! Закрыт участок автодороги Начикинский совхоз — село Усть-Большерецк — посёлок Октябрьский с подъездом к пристани Косоево'],
    ['weather', 'Штормовое предупреждение: в акваториях Тихого океана и Берингова моря прогнозируется штормовой ветер. По данным Камчатского управления по гидрометеорологии и мониторингу окружающей среды, 8 и 9 октября ожидается штормовой ветер.'],
    // Пересказ: полный текст поста в журнале не хранится, заголовок — дословно.
    ['flood', 'Экстренное предупреждение на 14 сентября 2026 г. (ухудшение гидрологической обстановки). Ожидается подъём уровня воды в реке Большая Воровская в районе села Соболево до уровня опасного явления (ОЯ).'],
    ['volcanic_eruption', 'На Камчатке зафиксирован пепловый выброс из вулкана Шивелуч: в Тигильском округе не исключается выпадение незначительного количества пепла. Туристам не рекомендуется приближаться к вулкану.'],
  ];
  for (const [type, text] of real) {
    it(`${type}: ${text.slice(0, 50)}…`, () => {
      const out = pushes('', text);
      expect(out.map((e) => e.alert_type)).toContain(type);
    });
  }
});

describe('цунами: реальное оповещение не глушится', () => {
  it('объявленная угроза — пуш', () => {
    const ev = classifyMchsItem('t', '', 'Внимание! Объявлена угроза цунами для восточного побережья Камчатки. Уйдите от берега на возвышенность.', PUB, '', 'vk_mchs');
    expect(ev?.alert_type).toBe('tsunami_warning');
  });
  it('«Это не учения» рядом с угрозой — всё равно пуш', () => {
    const ev = classifyMchsItem('t', '', 'Внимание! Это не учения! Объявлена угроза цунами. Ожидается волна высотой до 1 метра.', PUB, '', 'vk_mchs');
    expect(ev?.alert_type).toBe('tsunami_warning');
  });
  it('оповещение о цунами в посте, где упомянута тренировка, — пуш', () => {
    const ev = classifyMchsItem('t', '', 'Объявлена угроза цунами! Тренировка, назначенная на сегодня, отменена. Покиньте прибрежную зону.', PUB, '', 'vk_mchs');
    expect(ev?.alert_type).toBe('tsunami_warning');
  });
  it('учения «отработали действия при угрозе цунами» — не пуш', () => {
    const out = pushes('', 'В Петропавловске прошли учения: спасатели отработали действия при угрозе цунами.');
    expect(out).toEqual([]);
  });
});
