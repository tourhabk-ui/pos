/**
 * Сторож: в текст, уходящий на чужую витрину, не попадает смесь алфавитов.
 *
 * ── Что нашлось (15.09) ────────────────────────────────────────────────────
 *
 * Перед тем как владелец вставит URL лент в кабинеты Авито и Яндекса, ленты
 * были собраны настоящими генераторами и прочитаны глазами. В карте категорий
 * Яндекса фототуры назывались `Фototуры` — три латинские буквы внутри
 * русского слова (проверено на уровне байтов: Ф-o-t-o-t-у-р-ы).
 *
 * Глазами в коде это не отличить от «Фототуры» вовсе: начертание совпадает.
 * Заметно становится там, где уже поздно, — на чужой витрине, в имени
 * категории, под которым выложены наши туры.
 *
 * ── Почему сторож, а не просто правка ──────────────────────────────────────
 *
 * Потому что класс ошибки — невидимый. Буквы `а е о р с у х А В Е К М Н О Р
 * С Т Х` в кириллице и латинице выглядят одинаково, и опечатка переживает
 * любое вычитывание. Одна правка лечит один случай; правило ловит следующий.
 *
 * Проверяется ВЕСЬ слой каналов, а не одна карта: смешение одинаково вредно
 * в названии категории, в шапке магазина и в подписи параметра — всё это
 * уезжает наружу.
 *
 * ── Границы правила ────────────────────────────────────────────────────────
 *
 * Красным считается ПРЯМОЕ соседство кириллицы и латиницы внутри слова.
 * Законные соседства через разделитель (`XML-импорт`, `Wi-Fi роутер`,
 * `Яндекс.Услуги`) не трогаются — и это не теория: правило прогнано по всему
 * `lib/channels`, ложных срабатываний ноль.
 */
import { describe, it, expect } from 'vitest';
import { readdirSync, readFileSync } from 'node:fs';
import { join } from 'node:path';

const DIR = join(process.cwd(), 'lib/channels');

/** Кириллица вплотную к латинице — внутри одного слова, без разделителя. */
const MIXED_SCRIPT = /[А-Яа-яЁё][A-Za-z]|[A-Za-z][А-Яа-яЁё]/;

/** Строковые литералы файла: одинарные, двойные и простые шаблонные. */
function stringLiterals(src: string): Array<{ line: number; value: string }> {
  const out: Array<{ line: number; value: string }> = [];
  src.split('\n').forEach((line, i) => {
    for (const m of line.matchAll(/'([^'\\]*)'|"([^"\\]*)"|`([^`\\$]*)`/g)) {
      out.push({ line: i + 1, value: m[1] ?? m[2] ?? m[3] ?? '' });
    }
  });
  return out;
}

/** Русские строки файла со смесью алфавитов. */
export function mixedScriptStrings(src: string): Array<{ line: number; value: string }> {
  return stringLiterals(src)
    .filter((s) => /[А-Яа-яЁё]/.test(s.value))
    .filter((s) => MIXED_SCRIPT.test(s.value));
}

describe('правило ловит ровно то, ради чего заведено', () => {
  it('опечатка 15.09 опознана', () => {
    // Ф + латинские o,t,o,t + у,р,ы — ровно то, что лежало в карте Яндекса.
    const was = `name: 'Фototуры',`;
    expect(mixedScriptStrings(was)).toHaveLength(1);
  });

  it('починенное написание чисто', () => {
    expect(mixedScriptStrings(`name: 'Фототуры',`)).toEqual([]);
  });

  it('законная смесь через разделитель не трогается', () => {
    // Иначе сторож начнут обходить, а обойдённый сторож хуже отсутствующего.
    for (const ok of ['XML-импорт', 'Wi-Fi роутер', 'Яндекс.Услуги', 'Авито Автозагрузка']) {
      expect(mixedScriptStrings(`const s = '${ok}';`), ok).toEqual([]);
    }
  });

  it('чисто латинские строки не проверяются вовсе', () => {
    expect(mixedScriptStrings(`const s = 'yml_catalog';`)).toEqual([]);
  });
});

describe('слой каналов не отдаёт наружу смесь алфавитов', () => {
  const files = readdirSync(DIR).filter((f) => f.endsWith('.ts'));

  it('файлы каналов найдены', () => {
    expect(files.length).toBeGreaterThan(0);
  });

  it('ни в одном файле канала нет смешанного слова', () => {
    const bad: string[] = [];
    for (const f of files) {
      for (const s of mixedScriptStrings(readFileSync(join(DIR, f), 'utf-8'))) {
        bad.push(`${f}:${s.line}: «${s.value}»`);
      }
    }
    expect(
      bad,
      'кириллица вплотную к латинице — это уедет на чужую витрину и там будет видно',
    ).toEqual([]);
  });
});
