// @vitest-environment node
/**
 * Цунами: угроза, отбой или «угрозы нет» — одно правило на КБГС и МЧС.
 *
 * ── Повод (24.09) ─────────────────────────────────────────────────────────
 *
 * Владелец: «бери цунами из MAX kbgsras». Прежде чем подключать новый
 * источник, прочитал правило, по которому источник объявляет цунами, — и оно
 * ошибалось в сторону ТРЕВОГИ у обоих классификаторов:
 *
 *   МЧС  — любое слово «цунами» → tsunami_warning, важность 3. После каждого
 *          заметного толчка МЧС Камчатки пишет «угрозы цунами нет», и такой
 *          пост становился тревогой цунами для всех туристов;
 *   КБГС — «угроза цунами отменена», «угроза цунами снята» и «угроза цунами
 *          не ожидается» давали важность 3: отбоем считались только «отбой»,
 *          «снята угроза» (строго в этом порядке) и «all clear».
 *
 * Подключи новый канал поверх этого — и он только прибавил бы ложных тревог.
 *
 * Ложная тревога цунами — не перестраховка: это эвакуация без причины и
 * выученное недоверие, из-за которого настоящую тревогу прочтут как ошибку.
 * Но и обратная ошибка недопустима — поэтому ниже держатся ОБЕ стороны:
 * отрицание, стоящее не рядом со словом «цунами», тревогу не снимает.
 */
import { describe, it, expect } from 'vitest';
import { readFileSync } from 'node:fs';
import { join } from 'node:path';
import {
  tsunamiStatus,
  classifyMessage,
  classifyMchsItem,
} from '@/lib/services/safety/seismic-parser';

const AT = '2026-09-24T05:00:00Z';

describe('угроза остаётся угрозой', () => {
  const WARNINGS = [
    'Объявлена угроза цунами на побережье.',
    'УГРОЗА ЦУНАМИ! Жителям побережья подняться на высоту не менее 30 м.',
    'Ожидается подход волн цунами высотой до 1 м в 10:20.',
    'Tsunami warning for Kamchatka.',
    // «Нет» стоит в ДРУГОМ предложении — к цунами оно отношения не имеет.
    'Объявлена угроза цунами. Если нет возможности эвакуироваться, поднимитесь на верхние этажи.',
    // Обещание отбоя — текст действующего предупреждения, а не отбой.
    'Объявлена угроза цунами. Отбой угрозы цунами будет объявлен дополнительно.',
    // То же, но обещание — ЕДИНСТВЕННОЕ предложение про цунами. Строка выше
    // этого не проверяет: её первое предложение даёт тревогу само, и до
    // второго дело не доходит. Контроль мутацией это и показал — снятая
    // проверка «отбой будет позже» выжила.
    'Сохраняйте готовность к эвакуации. Отбой угрозы цунами будет объявлен дополнительно.',
    // «Не отменена» — не отбой.
    'Угроза цунами не отменена.',
    // Смешанное: одному пункту угрозы нет, другому — есть. Тревога.
    'Для Петропавловска угроза цунами не ожидается. Для Усть-Камчатска объявлена угроза цунами.',
  ];
  for (const text of WARNINGS) {
    it(text, () => {
      expect(tsunamiStatus(text)).toBe('warning');
    });
  }
});

describe('«угрозы нет» — не тревога', () => {
  const NO_THREAT = [
    'Землетрясение магнитудой 5.8. Угрозы цунами нет.',
    'Угроза цунами для побережья Камчатки не ожидается.',
    'Цунами не прогнозируется.',
    'Землетрясение произошло без угрозы возникновения цунами.',
    'Угроза цунами отсутствует.',
  ];
  for (const text of NO_THREAT) {
    it(text, () => {
      expect(tsunamiStatus(text)).toBe('no_threat');
    });
  }
});

describe('отбой — отбой в любом порядке слов', () => {
  const ALL_CLEAR = [
    'Отбой угрозы цунами.',
    'Угроза цунами отменена.',
    'Угроза цунами снята.',
    'Снята угроза цунами для Петропавловска.',
    'Угроза цунами миновала.',
  ];
  for (const text of ALL_CLEAR) {
    it(text, () => {
      expect(tsunamiStatus(text)).toBe('all_clear');
    });
  }
});

it('без слова «цунами» — не про цунами', () => {
  expect(tsunamiStatus('Землетрясение магнитудой 4.2')).toBeNull();
});

describe('классификатор МЧС', () => {
  it('«угрозы цунами нет» больше НЕ тревога цунами', () => {
    const e = classifyMchsItem('mchs/q', 'Землетрясение', 'Произошло землетрясение магнитудой 5.8. Угрозы цунами нет.', AT, 'https://x');
    expect(e?.alert_type).not.toBe('tsunami_warning');
  });

  it('настоящая угроза — по-прежнему важность 3', () => {
    const e = classifyMchsItem('mchs/t', 'Угроза цунами', 'Объявлена угроза цунами на побережье.', AT, 'https://x');
    expect(e?.alert_type).toBe('tsunami_warning');
    expect(e?.severity).toBe(3);
  });

  it('отбой — информация, а не тревога', () => {
    const e = classifyMchsItem('mchs/c', 'Отбой', 'Угроза цунами отменена.', AT, 'https://x');
    expect(e?.alert_type).toBe('info');
    expect(e?.severity).toBe(0);
  });
});

describe('классификатор КБГС', () => {
  it('«угроза цунами не ожидается» — сообщение о толчке, а не тревога', () => {
    const e = classifyMessage('t.me/kbgsras/1', 'Землетрясение ML=5.8. Угроза цунами не ожидается.', AT);
    expect(e?.alert_type).toBe('earthquake');
  });

  it('«угроза цунами отменена» — отбой, а не важность 3', () => {
    const e = classifyMessage('t.me/kbgsras/2', 'Угроза цунами отменена.', AT);
    expect(e?.alert_type).toBe('info');
    expect(e?.severity).toBe(0);
  });

  it('настоящая угроза — важность 3', () => {
    const e = classifyMessage('t.me/kbgsras/3', 'Объявлена угроза цунами для восточного побережья Камчатки.', AT);
    expect(e?.alert_type).toBe('tsunami_warning');
    expect(e?.severity).toBe(3);
  });
});

it('правило одно: второго разбора цунами в классификаторах нет', () => {
  // Два правила об одном уже разошлись — МЧС «любое слово», КБГС «узкий
  // отбой». Третье разошлось бы так же (§12).
  const src = readFileSync(join(process.cwd(), 'lib/services/safety/seismic-parser.ts'), 'utf-8');
  expect(src, 'снова «любое слово цунами — тревога»').not.toMatch(/if \(\/цунами\/\.test\(text\)\)/);
  expect(src, 'снова свой узкий отбой у КБГС').not.toMatch(/const isAllClear = \/отбой/);
});

describe('вето на понижение: угроза не снята — это предупреждение (разбор 24.09)', () => {
  // Девять живых формулировок, которые правило читало как отбой или «угрозы
  // нет» при действующей угрозе. Пропущенное цунами дороже ложного.
  for (const text of [
    'Угроза цунами не была снята.',
    'Угроза цунами не  отменена.',
    'Отбой угрозы цунами пока не объявлен.',
    'Отбой угрозы цунами объявлен не был.',
    'Отмена угрозы цунами не планируется.',
    'Снятие угрозы цунами не ожидается.',
    'Угроза цунами сохраняется, отмены пока нет.',
    'Предупреждение о цунами для Командорских островов отменено, для восточного побережья сохраняется.',
    'Волны цунами не зарегистрированы, но угроза сохраняется',
  ]) {
    it(text, () => {
      expect(tsunamiStatus(text)).toBe('warning');
    });
  }

  it('отрицание не при слове отбоя — отбой остаётся отбоем', () => {
    expect(tsunamiStatus('Отбой угрозы цунами, волна не зафиксирована.')).toBe('all_clear');
  });
});
