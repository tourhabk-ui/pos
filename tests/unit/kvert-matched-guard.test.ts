/**
 * Коды KVERT должны доехать до карточки места, а не просто разобраться.
 *
 * ── Откуда правка ──────────────────────────────────────────────────────────
 *
 * 14.09 владелец прислал страницу Смитсоновского института по Шивелучу:
 * извержение продолжается, авиационный код Orange, еженедельный отчёт за
 * 3-9 сентября. Естественный вопрос — знает ли это платформа. Прогоны
 * `cron-kvert-acc` зелёные каждые шесть часов, 259 подряд.
 *
 * Оказалось, зелёный этого не подтверждал. Роут краснел на `fetched === 0` —
 * «источник отдал не VONA», — и та проверка стоит по делу: её завели после
 * 26-28.07, когда слой стоял мёртвым ровно тогда, когда Шивелуч выбросил
 * пепел на 12 км.
 *
 * Но разбор кодов — половина работы. Вторая половина — сопоставить вулкан с
 * точкой `places` и записать в `volcano_status`. Её результат считался
 * (`matched`, `places_indexed`) и НЕ ПРОВЕРЯЛСЯ ничем. При живом источнике,
 * полностью разобранном выпуске и нуле обновлённых карточек прогон был бы
 * зелёным.
 *
 * У `places_indexed` в типе прямо написано: «Ноль — сопоставлять не с чем, и
 * это отказ». Написано — и не исполнено: правило 10.09 в чистом виде, где
 * объявление живёт дольше механизма, а сторож зеленеет ровно там, где
 * механизма нет.
 *
 * ── Почему два отказа, а не один ───────────────────────────────────────────
 *
 * Пустой индекс — это каталог или запрос к нему. Ноль сопоставлений при живом
 * индексе — это таблица алиасов и матчер. Разные места починки, значит разные
 * сообщения: слитые в одно, они послали бы разбирающего не туда.
 */
import { describe, it, expect } from 'vitest';
import { readFileSync } from 'node:fs';
import { join } from 'node:path';

const ROUTE = readFileSync(join(process.cwd(), 'app/api/cron/kvert-acc/route.ts'), 'utf-8');
/** Код без комментариев: прежнее поведение в них описано намеренно. */
const CODE = ROUTE.replace(/\/\*[\s\S]*?\*\//g, '').replace(/^\s*\/\/.*$/gm, '');
const SYNC = readFileSync(join(process.cwd(), 'lib/agents/kvert-sync.ts'), 'utf-8');

describe('разобрать — не значит доставить', () => {
  it('ноль сопоставленных с местами — отказ, а не тихий день', () => {
    expect(CODE).toMatch(/if \(result\.matched === 0\)/);
  });

  it('пустой индекс точек-вулканов — отдельный отказ', () => {
    // Его собственная докстрока в типе это и утверждает; до правки утверждение
    // не было исполнено ничем.
    expect(CODE).toMatch(/if \(result\.places_indexed === 0\)/);
    expect(SYNC).toMatch(/Ноль — сопоставлять не с чем, и это отказ/);
  });

  it('оба отказа отвечают 502 и пишутся в историю как failed', () => {
    // 200 с телом «success: false» прошёл бы мимо workflow: тот проверяет
    // только код ответа.
    const matchedBlock = CODE.slice(CODE.indexOf('result.matched === 0'));
    expect(matchedBlock).toMatch(/recordCronRun\('kvert-acc', startedAt, 'failed'/);
    expect(matchedBlock).toMatch(/\{ status: 502 \}/);
    const indexBlock = CODE.slice(CODE.indexOf('result.places_indexed === 0'), CODE.indexOf('result.matched === 0'));
    expect(indexBlock).toMatch(/recordCronRun\('kvert-acc', startedAt, 'failed'/);
    expect(indexBlock).toMatch(/\{ status: 502 \}/);
  });

  it('сообщения РАЗНЫЕ — чинятся эти отказы в разных местах', () => {
    expect(CODE).toMatch(/в каталоге ноль точек-вулканов/);
    expect(CODE).toMatch(/сопоставлено с местами 0/);
  });

  it('прежняя проверка источника не снята', () => {
    // Она про другое: «источник отдал не VONA». Новые проверки её дополняют,
    // а не заменяют — между ними лежит случай «разобрали, но не доставили».
    expect(CODE).toMatch(/if \(result\.fetched === 0\)/);
  });
});

describe('в телеметрию идёт доведённая работа', () => {
  it('успех считается сопоставленными, а не разобранными', () => {
    // Иначе сторож холостых прогонов охраняет чтение чужой страницы, а не
    // нашу пользу от неё.
    expect(CODE).toMatch(/recordCronRun\('kvert-acc', startedAt, 'success', \{ items: result\.matched \}\)/);
    expect(CODE).not.toMatch(/'success', \{ items: result\.fetched \}/);
  });
});
