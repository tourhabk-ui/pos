describe('пятый ревью 22.10: мелкое — каждое слово на своём месте', () => {
  it('«включительно» у отрезка и «по 8 мест на каждую дату» — часть фразы, а не отказ', () => {
    expect(proposal('открой с 1 по 10 июля включительно, 8 мест').dates).toHaveLength(10);
    expect(proposal('открой 1-10 июля включительно, 8 мест').dates).toHaveLength(10);
    expect(proposal('открой 3 и 5 августа по 8 мест на каждую дату')).toMatchObject({ dates: ['2027-08-03', '2027-08-05'], seats: 8 });
    expect(proposal('открой субботы июля, по 8 мест на каждый выезд').seats).toBe(8);
  });

  it('«утро», «вечер» — только в приветствии', () => {
    expect(proposal('доброе утро! открой 3 августа, 8 мест').dates).toEqual(['2027-08-03']);
    expect(proposal('добрый вечер, открой 3 августа, 8 мест').dates).toEqual(['2027-08-03']);
    // Приветствие посреди фразы — вне языка (шестой ревью).
    expect(parse('открой 3 августа, добрый вечер, 8 мест')).toMatchObject({ kind: 'refused', reason: 'off_pattern' });
    expect(parse('открой 3 августа на утро и на вечер, 8 мест')).toMatchObject({ reason: 'unknown_words', words: ['утро', 'вечер'] });
  });

  it('«каждый», «все» — согласованно с днём недели; «каждый вторник» у отдельной даты — отказ', () => {
    expect(proposal('открой каждую субботу июля, 8 мест').dates).toHaveLength(5);
    expect(proposal('открой каждый вторник июля, 8 мест').dates).toHaveLength(4);
    expect(proposal('открой по всем субботам июля, 8 мест').dates).toHaveLength(5);
    expect(proposal('открой каждые выходные июля, 8 мест').dates).toHaveLength(9);
    expect(parse('открой каждый субботы июля, 8 мест').kind).toBe('refused');
    expect(parse('открой 3 августа, каждый вторник, 8 мест')).toEqual({ kind: 'refused', reason: 'weekday_scope', seats: 8 });
  });

  it('отрезок короче недели с днями недели: концы — эти дни, иначе отказ («выходные 2-4 июля» — пятница)', () => {
    expect(parse('открой выходные 2-4 июля, 8 мест')).toEqual({ kind: 'refused', reason: 'weekday_mismatch', date: '2027-07-02' });
    expect(proposal('открой выходные с 3 по 4 июля, 8 мест').dates).toEqual(['2027-07-03', '2027-07-04']);
    expect(proposal('открой субботы с 1 по 10 июля, 8 мест').dates).toEqual(['2027-07-03', '2027-07-10']);
  });

  it('отрезок не тянется через конец предложения: «3 августа. - 10 августа» — отказ, а не восемь дней', () => {
    expect(parse('открой 3 августа. - 10 августа, 8 мест')).toMatchObject({ kind: 'refused', reason: 'bad_char', char: '-' });
    expect(proposal('открой 3 августа - 10 августа, 8 мест').dates).toHaveLength(8);
  });

  it('фамилия — по суффиксу и окончанию: «Горелову» — человек, «Авачинскому» — прилагательное места', () => {
    expect(parse('открой 5 августа 2 места Горелову')).toEqual({ kind: 'not_dates' });
    expect(parse('открой 3 августа на Горелову, 8 мест').kind).not.toBe('proposal');
    const avacha: ChatTour = { id: '21', title: 'Вулкан Авача', active: true };
    expect(proposal('открой 5 августа на Авачу, 8 мест', [avacha]).tour).toEqual({ kind: 'one', id: '21' });
    // «Авачинскому» — другое слово (суффикс), не тур «Вулкан Авача»; «по» — не место тура в языке.
    expect(parse('открой по Авачинскому 5 августа 8 мест', [avacha]).kind).not.toBe('proposal');
  });
});

describe('шестой ревью 22.10: принимает язык', () => {
  const COMBO: ChatTour[] = [
    { id: '1', title: 'Вулкан Горелый', active: true },
    { id: '2', title: 'Вулкан Мутновский', active: true },
    { id: '3', title: 'Горелый и Мутновский за 2 дня', active: true },
  ];
  it('составной тур рядом с двумя названными — выбор кнопками, а не молча составной; название целиком — он', () => {
    expect(proposal('открой 3 августа на Горелый и Мутновский, 8 мест', COMBO).tour).toEqual({ kind: 'choose', ids: ['3', '1', '2'] });
    expect(proposal('открой 3 августа на Горелый и Мутновский за 2 дня, 8 мест', COMBO).tour).toEqual({ kind: 'one', id: '3' });
  });
  it('«за 5000» без единицы — не цена и не начало названия тура «…за 2 дня»: «не по образцу»', () => {
    expect(parse('открой 3 августа за 5000, 8 мест', COMBO)).toEqual({ kind: 'refused', reason: 'off_pattern', seats: 8 });
    expect(parse('открой 3 августа от 5000, 8 мест', COMBO)).toMatchObject({ kind: 'refused', reason: 'unknown_words', words: ['от'] });
    expect(proposal('открой 3 августа за 5000 ₽ на Горелый, 8 мест', COMBO)).toMatchObject({ priceMentioned: true, dates: ['2027-08-03'] });
  });
  it('нестандартные цифры и невидимые знаки — NFKC: «1５» — 15, «８ мест» — 8, пробел нулевой ширины не мешает', () => {
    expect(proposal('открой 1５ августа, 8 мест').dates).toEqual(['2027-08-15']);
    expect(proposal('открой 3 августа, ８ мест').seats).toBe(8);
    expect(proposal('открой 3 августа,​ 8 мест﻿').dates).toEqual(['2027-08-03']);
  });
  it('«…» — не точка: отказ «знак», а не 10 декабря', () => {
    expect(parse('открой 10…12, 8 мест')).toEqual({ kind: 'refused', reason: 'bad_char', char: '…', seats: 8 });
    expect(parse('открой 3...5 августа, 8 мест')).toEqual({ kind: 'refused', reason: 'bad_char', char: '…', seats: 8 });
  });
  it('«на месяц», «на час», «на лето» рядом с датой — длительность, отказ', () => {
    for (const w of ['месяц', 'час', 'лето']) {
      expect(parse(`открой 3 августа на ${w}, 8 мест`)).toMatchObject({ kind: 'refused', reason: 'date_relation', word: w });
    }
  });
  it('дефис вплотную, связка между датами, точка, скобки — вне языка, ни одной даты', () => {
    for (const text of [
      'открой весь июль-сб, 8 мест', 'открой 3 августа, только 5 августа, 8 мест', 'открой весь июль. Субботы тоже, 8 мест',
      'открой весь июль (субботы), 8 мест', 'открой продажи 1 августа, на 5 сентября, 8 мест',
    ]) expect(parse(text).kind, text).toBe('refused');
  });
});

