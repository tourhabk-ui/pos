/**
 * Реквизиты партнёра в миграции обязаны иметь названный источник.
 *
 * Разбор с владельцем 05.08. Миграция `060_rafting_tour_kamchatka.sql` от
 * 21 марта завела партнёра так:
 *
 *     'Камчатка Рафтинг',
 *     jsonb_build_object('phone', '+79247990191', ...)
 *
 * Ни имя, ни телефон никто не сообщал — они были придуманы и вписаны как факт.
 * Номер прожил четыре с половиной месяца: всё это время турист, звонящий
 * оператору, попадал к постороннему человеку. Ярослав обнаружил это, попытавшись
 * дозвониться сам себе. Дальше выдуманное было СКОПИРОВАНО в 806 и 810 — каждая
 * копия делала его похожим на установленный факт.
 *
 * Правило проекта существовало и раньше (CLAUDE.md §8): критичные факты —
 * безопасность, цены, телефоны, наличие мест — только из инструментов и БД,
 * самоотчётам модели не верить. Но сторожа у правила не было: `no-hardcoded-
 * partner-contacts` смотрит `app/` и `lib/`, а миграции — нет. Через эту дыру
 * и прошла 060.
 *
 * Здесь дыра закрыта. Правило простое и проверяемое: если миграция пишет
 * контакты или имя партнёра, в её комментариях должно быть сказано, ОТКУДА эти
 * данные. Не «правильные ли они» — это машине недоступно, — а есть ли у них
 * названный человеческий источник. Выдумка источника не имеет и потому падает.
 */
import { describe, it, expect } from 'vitest';
import { readdirSync, readFileSync } from 'node:fs';
import { join } from 'node:path';

const ROOT = process.cwd();
const DIR = join(ROOT, 'migrations');

const FILES = readdirSync(DIR).filter((f) => f.endsWith('.sql')).sort();

/** Мобильный номер. Короткие служебные (112) под шаблон не попадают. */
const PHONE = /\+79\d{9}/;

/**
 * Маркер источника: миграция называет, от кого пришли данные.
 * Не формальность — именно отсутствие этой строки отличает выдумку от факта.
 */
const SOURCE = /--[^\n]*(источник|со слов|по словам|подтвердил|подтверждён|подтверждено|прислал|передал|через владельца|от оператора|из кабинета)/i;

/**
 * Долги, а не разрешения.
 *
 * Эти три файла — сама выдумка и её копии. Они уже применены на проде, поэтому
 * не редактируются: историю миграций переписывать нельзя. Их данные исправлены
 * миграцией 822 по номеру, который дал Ярослав. Список существует, чтобы факт
 * не потерялся, и не должен пополняться — новая запись здесь означает, что
 * выдумка повторилась.
 */
const LEGACY = new Map<string, string>([
  ['060_rafting_tour_kamchatka.sql', 'исходная выдумка: имя и телефон вписаны без источника; исправлено 822'],
  ['806_bystraya_tour_consolidate.sql', 'копия выдуманного телефона из 060; исправлено 822'],
  ['810_bystraya_restore_visibility.sql', 'копия выдуманного телефона из 060; исправлено 822'],
]);

/** Пишет ли миграция реквизиты партнёра. */
function writesPartnerContacts(sql: string): boolean {
  if (PHONE.test(sql)) return true;
  const touchesPartners = /INSERT INTO partners|UPDATE partners/i.test(sql);
  return touchesPartners && /'phone'/.test(sql);
}

describe('миграции не вписывают выдуманные реквизиты', () => {
  it('каждая миграция с контактами партнёра называет источник', () => {
    const offenders: string[] = [];
    for (const file of FILES) {
      if (LEGACY.has(file)) continue;
      const sql = readFileSync(join(DIR, file), 'utf-8');
      if (!writesPartnerContacts(sql)) continue;
      if (!SOURCE.test(sql)) {
        offenders.push(
          `${file}: пишет контакты партнёра, но не сказано, откуда данные. ` +
          'Назовите источник в комментарии (кто сообщил и когда) — ' +
          'телефон без источника это выдумка, а не факт.',
        );
      }
    }
    expect(offenders, offenders.join('\n')).toEqual([]);
  });

  it('список исторических долгов не растёт', () => {
    // Ровно три файла: сама выдумка и две её копии. Четвёртый означал бы,
    // что мы сделали это снова и снова себе разрешили.
    expect(LEGACY.size).toBe(3);
  });

  it('у каждого долга записана причина, а не просто имя файла', () => {
    for (const [file, reason] of LEGACY) {
      expect(reason.length, `${file} без объяснения`).toBeGreaterThan(20);
    }
  });

  it('файлы из списка долгов существуют — мёртвая запись создаёт ложное спокойствие', () => {
    for (const file of LEGACY.keys()) {
      expect(FILES, `в списке долгов файл, которого нет: ${file}`).toContain(file);
    }
  });

  it('исправляющая миграция 822 сама источник называет', () => {
    // Иначе правило проверяло бы всех, кроме того, кто его вводил.
    const sql = readFileSync(join(DIR, '822_rafting_operator_name_and_phone.sql'), 'utf-8');
    expect(PHONE.test(sql), '822 должна содержать настоящий номер').toBe(true);
    expect(SOURCE.test(sql), '822 должна называть, от кого номер').toBe(true);
  });
});
