/**
 * Сторож: поздравление и годовщина службы — не тревога (01.10).
 *
 * 01.10 верхней тревогой края стоял пост «Центру управления в кризисных
 * ситуациях ГУ МЧС России по Камчатскому краю исполнилось 16 лет» с типом
 * `volcanic_eruption`: рассказ о работе ЦУКС называет вулканы и сейсмику, и
 * вулканическая ветка классификатора принимала его за извержение. Пост был
 * первым в ленте сайта, в MCP `safety_status` и в карточке «Главное сегодня».
 */
import { describe, it, expect } from 'vitest';
import { isAnniversaryPost, classifyMchsItem } from '@/lib/services/safety/seismic-parser';

const CUKS_TITLE = 'Центру управления в кризисных ситуациях ГУ МЧС России по Камчатскому краю исполнилось 16 лет';
const CUKS_BODY =
  'Сегодня наш регион отмечает 16-летие со дня создания Центра управления в кризисных ситуациях — оперативной ' +
  'службы, которая круглосуточно следит за обстановкой: вулканическая активность, сейсмическая обстановка, паводки. ' +
  'Поздравляем сотрудников с праздником!';

describe('годовщина службы отсеивается', () => {
  it('пост о 16-летии ЦУКС — не тревога и не извержение', () => {
    expect(isAnniversaryPost(`${CUKS_TITLE} ${CUKS_BODY}`)).toBe(true);
    expect(classifyMchsItem('vk-1', CUKS_TITLE, CUKS_BODY, '2026-10-01T00:00:00Z', 'https://vk.com/x')).toBeNull();
  });

  it('другие формы праздника — тоже', () => {
    for (const t of [
      'Годовщина образования поисково-спасательной службы',
      'Юбилей ветерана МЧС',
      'Поздравляем с Днём спасателя',
      'Сегодня день создания отряда',
    ]) expect(isAnniversaryPost(t), t).toBe(true);
  });

  it('предупреждение в праздничный день остаётся предупреждением', () => {
    const t = 'В День спасателя ожидается сильный ветер до 25 м/с, штормовое предупреждение';
    expect(isAnniversaryPost(t)).toBe(false);
    expect(classifyMchsItem('vk-2', '', t, '2026-10-01T00:00:00Z', 'https://vk.com/y')?.alert_type).toBe('weather');
  });

  it('настоящее предупреждение о вулкане не задето', () => {
    const t = 'Спасатели рекомендуют воздержаться от восхождения на вулкан Мутновский: газопепловый выброс';
    expect(isAnniversaryPost(t)).toBe(false);
    expect(classifyMchsItem('vk-3', '', t, '2026-10-01T00:00:00Z', 'https://vk.com/z')?.alert_type).toBe('volcanic_eruption');
  });

  it('«летний» и «лет» без числа — не годовщина', () => {
    expect(isAnniversaryPost('Летний сезон на вулканах открыт, восхождения разрешены')).toBe(false);
  });
});
