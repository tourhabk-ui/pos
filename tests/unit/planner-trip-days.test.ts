/**
 * Сторож: в поездке столько дней, сколько календарных дат, а не ночей.
 *
 * ── Что нашлось 27.09 (владелец: «подумай над планером ещё») ───────────────
 *
 * `getTripDays` возвращал разницу дат — число НОЧЕЙ, — а называлось это
 * днями. Прогон живого движка на 10-17 июля, до правки:
 *
 *   день 1 = 10.07  arrival    Прилёт днём. Размещение, акклиматизация
 *   день 2 = 11.07  activity   вулканы — Авачинская зона
 *   день 3 = 12.07  rest       День отдыха
 *   день 4 = 13.07  activity   Свободный день
 *   день 7 = 16.07  departure  Сборы утром. Трансфер в аэропорт, вылет днём
 *
 * Рейс у человека 17-го. То есть последняя строка плана — та, которую читают
 * как день своего рейса, — указывала не на ту дату, а последний календарный
 * день поездки не планировался вовсе.
 *
 * Цена ошибки в трёх местах, и все три проверяемы:
 *
 *   1. дата дня вылета (выше);
 *   2. один потерянный день в каждой поездке — при семи днях это седьмая
 *      часть;
 *   3. `trip_days` уходит оператору в лид (`source_data` формы контакта), и
 *      оператор читал «7 дней» о восьмидневной поездке.
 *
 * Прогон после правки: последний день = 8 = 17 июля, тип departure.
 *
 * ── Ночёвки ───────────────────────────────────────────────────────────────
 *
 * Правило одно на оба случая: у ПОСЛЕДНЕГО дня поездки ночи нет — человек
 * либо улетает, либо едет домой. Раньше пропускался только день с типом
 * `departure`, и у жителя края (у которого такого дня нет вовсе) ночей
 * выходило на одну больше, чем он проводит вне дома.
 */
import { describe, it, expect } from 'vitest';
import { readFileSync } from 'node:fs';
import { join } from 'node:path';
import { tripCalendarDays, dateOfTripDay } from '@/lib/planner/flow-balance';

const read = (p: string) => readFileSync(join(process.cwd(), p), 'utf-8');
const code = (src: string) => src.replace(/\/\*[\s\S]*?\*\//g, '').replace(/^\s*\/\/.*$/gm, '');
const ENGINE = read('lib/planner/engine.ts');
const CODE = code(ENGINE);
// Счёт ночей с #2304 живёт в смете (одна формула для движка, экрана и чата).
const ESTIMATE = code(read('lib/planner/estimate.ts'));
const KUZMICH = code(read('lib/kuzmich/trip-plan-tool.ts'));
const API = code(read('app/api/planner/recommend/route.ts'));

describe('дней столько, сколько календарных дат', () => {
  it('10-17 июля — восемь дней, а не семь', () => {
    expect(tripCalendarDays('2027-07-10', '2027-07-17')).toBe(8);
  });

  it('последний день поездки — дата отъезда', () => {
    // Ровно то, что было сломано: день N обязан попадать на дату рейса.
    const n = tripCalendarDays('2027-07-10', '2027-07-17');
    expect(dateOfTripDay('2027-07-10', n)).toBe('2027-07-17');
  });

  it('первый день — дата прилёта', () => {
    expect(dateOfTripDay('2027-07-10', 1)).toBe('2027-07-10');
  });

  it('равные даты — один день, а не ноль', () => {
    // Житель края выезжает утром и возвращается вечером.
    expect(tripCalendarDays('2027-07-10', '2027-07-10')).toBe(1);
  });

  it('отъезд раньше прилёта — ноль, а не отрицательное число', () => {
    expect(tripCalendarDays('2027-07-17', '2027-07-10')).toBe(0);
  });

  it('мусор в дате — ноль, а не NaN', () => {
    expect(tripCalendarDays('чепуха', '2027-07-17')).toBe(0);
    expect(tripCalendarDays('2027-07-10', '')).toBe(0);
  });

  it('перевод дня в дату и счёт дней согласованы на длинной поездке', () => {
    // Разойдясь на единицу, они дали бы день плана без даты или дату без дня.
    const n = tripCalendarDays('2027-06-01', '2027-06-21');
    expect(n).toBe(21);
    expect(dateOfTripDay('2027-06-01', n)).toBe('2027-06-21');
  });
});

describe('движок спрашивает правило, а не считает разницу сам', () => {
  it('getTripDays зовёт tripCalendarDays', () => {
    expect(CODE).toMatch(/return tripCalendarDays\(profile\.arrivalDate, profile\.departureDate\)/);
  });

  it('своей арифметики дат в движке не осталось', () => {
    expect(CODE, 'движок снова делит разницу дат на сутки').not.toMatch(/Math\.round\(diff \/ 86400000\)/);
  });

  it('порог короткой поездки переведён в календарные дни, а не сдвинут', () => {
    // Прежние `< 5` считались по ночам, то есть срабатывали на поездке короче
    // шести календарных дней. `< 6` — тот же рубеж в новых единицах.
    expect(CODE).toMatch(/tripDays > 0 && tripDays < 6/);
  });
});

describe('у последнего дня поездки ночи нет', () => {
  it('ночь не считается ни дню вылета, ни последнему дню', () => {
    expect(ESTIMATE).toMatch(/day\.type === 'departure' \|\| day\.day === lastDayNum/);
  });

  it('прежнее правило «только день вылета» не вернулось', () => {
    const at = ESTIMATE.indexOf('lastDayNum');
    expect(at).toBeGreaterThan(0);
    // Голая проверка на departure без последнего дня давала бы местному
    // лишнюю ночь.
    for (const src of [ESTIMATE, CODE]) {
      expect(src).not.toMatch(/if \(day\.type === 'departure'\) continue;/);
    }
  });
});

describe('соседи считают дни так же', () => {
  it('Кузьмич переводит «N дней» в интервал на N-1 сутки', () => {
    // `arrival + daysNum * сутки` дал бы N+1 календарных дней.
    expect(KUZMICH).toMatch(/\(daysNum - 1\) \* 86400000/);
    expect(KUZMICH, 'Кузьмич снова просит на день больше').not.toMatch(/daysNum \* 86400000/);
  });

  it('сервер не отвергает поездку на один день', () => {
    // Форма её позволяет (min = дата начала), и житель края собирает именно
    // такую. Отвергать разрешённое формой — значит ломать свой же сценарий.
    expect(API).toMatch(/parsed\.departureDate < parsed\.arrivalDate/);
    expect(API, 'равные даты снова отвергаются').not.toMatch(/departureDate <= parsed\.arrivalDate/);
  });
});
