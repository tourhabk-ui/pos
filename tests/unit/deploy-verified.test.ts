/**
 * Деплой подтверждается фактом, а не словом.
 *
 * 04.08. Пять смерженных PR подряд, зелёные галочки везде — и прод сутки
 * отдавал старый контейнер: владелец третий день видел на телефоне баги,
 * исправленные в main. Причина не в коде карточки, а в проверке деплоя: шаг
 * спрашивал статус приложения ЧЕРЕЗ СЕКУНДУ после старта сборки, печатал
 * «Status: deploy» (это «идёт сборка», а не «готово») и завершался зелёным.
 * Чем кончилась сборка, не проверял никто и никогда.
 *
 * Это ровно тот класс, против которого заведены остальные сторожа: зелёное,
 * потому что никто не спросил. Здесь — чтобы шаг не вернулся к одному curl.
 */
import { describe, it, expect } from 'vitest';
import { readFileSync } from 'node:fs';
import { join } from 'node:path';

const DEPLOY = readFileSync(join(process.cwd(), '.github/workflows/deploy.yml'), 'utf-8');

/** Строки без комментариев: пояснения не должны считаться кодом шага. */
const code = DEPLOY.split('\n').filter((l) => !/^\s*#/.test(l)).join('\n');

describe('деплой проверяется до конца', () => {
  it('статус опрашивается в цикле, а не один раз', () => {
    expect(code).toMatch(/for i in \$\(seq 1 \$ATTEMPTS\)/);
    expect(code).toMatch(/ATTEMPTS=\d+/);
  });

  it('промежуточные статусы сборки не считаются успехом', () => {
    // «deploy» — это «идёт сборка». Раньше именно оно печаталось как результат.
    expect(code).toMatch(/deploy\|build\|building\|deploying\|pending\|created/);
  });

  it('несобравшийся деплой красит workflow', () => {
    expect(code).toMatch(/::error::/);
    expect(code).toMatch(/exit 1/);
  });

  it('сверяется коммит: прод должен работать именно на голове main', () => {
    expect(code).toMatch(/EXPECTED_SHA/);
    expect(code).toMatch(/COMMIT:0:7.*=.*EXPECTED_SHA:0:7|EXPECTED_SHA:0:7.*=.*COMMIT:0:7/);
  });

  it('сборке дают начаться — сначала ждём наш коммит, потом его исход', () => {
    // Первый вариант проверки спрашивал статус через секунду после мержа,
    // видел «active» на ПРОШЛОМ коммите, считал это терминальным состоянием и
    // краснел, не дав сборке стартовать (прогон 05.08 00:40 по 822a9b8).
    const waitPhase = code.indexOf('PICKED=1');
    const buildPhase = code.indexOf('deploy|build|building');
    expect(waitPhase, 'нет фазы ожидания коммита').toBeGreaterThan(-1);
    expect(buildPhase, 'ожидание исхода сборки должно идти ПОСЛЕ ожидания коммита')
      .toBeGreaterThan(waitPhase);
  });

  it('невзятый в работу коммит назван своей причиной', () => {
    // «Не доехал» и «автодеплой вообще не сработал» чинятся по-разному.
    // Формулировка уточнена 16.08 (принимается и потомок нашего коммита),
    // поэтому проверяется смысл сообщения, а не его прежняя редакция.
    expect(code).toMatch(/не взял в работу ни .* ни его потомка/);
    expect(code).toMatch(/webhook/);
  });

  it('последнее слово — за сайтом, а не за панелью', () => {
    // Панель отвечает на вопрос «что со сборкой», сайт — «какой контейнер
    // сейчас отдаёт страницы». Три дня разошлись именно между этими вопросами.
    expect(code).toMatch(/vedarai\.ru\/version\.json/);
    expect(code).toMatch(/Контейнер не переключился/);
  });

  it('отсутствие токена — не зелёный прогон', () => {
    // Раньше без токена шаг выходил с 0: «проверить нечем» выглядело как
    // «проверено». Это и есть подтверждение словом.
    //
    // Отрезок берётся от НАЧАЛА шага сверки, а не от первого упоминания
    // токена в файле: 17.08 выше появился шаг «попросить сборку», и он без
    // токена законно выходит с нулём — пропущенная просьба оставляет прежний
    // порядок вещей, тогда как пропущенная сверка выдала бы непроверенное за
    // проверенное. Разные шаги, разная цена молчания.
    const verifyStep = code.slice(code.indexOf('Verify deploy reached production'));
    const noToken = verifyStep.slice(
      verifyStep.indexOf('TIMEWEB_TOKEN" ]'),
      verifyStep.indexOf('Приложение $APP_ID'),
    );
    expect(noToken).toMatch(/exit 1/);
    expect(noToken).not.toMatch(/exit 0/);
  });
});

/**
 * Окно ожидания ответа сайта длиннее сборки (19.09).
 *
 * ── Что случилось ─────────────────────────────────────────────────────────
 *
 * Прогон 1823 покраснел и напечатал: «наш код на прод не доехал, миграции
 * этого деплоя не накатывались». Оба утверждения были ЛОЖНЫ: код доехал
 * через четыре минуты, миграция 986 применилась, новое место открывается на
 * проде. Проверка не ошиблась в измерении — она не дождалась.
 *
 * Арифметика отказа была заложена в сам файл. Цикл сверки ходил `seq 1 20`
 * со сном 15с, то есть пять минут, а рядом, в MIN_BUILD_SECONDS, этот же
 * файл утверждает: меньше десяти минут сборка не длилась ни разу. Ждать
 * вдвое меньше, чем длится ожидаемое, — гарантированный «не дождался».
 *
 * Почему это не ловилось раньше: фазы 1 и 2 спрашивают ПАНЕЛЬ Timeweb, а та
 * отвечает про свой запрос — в 1823 она сказала `status=active` на нашем
 * коммите через ОДНУ секунду. Обе фазы прошли мгновенно, и весь настоящий
 * выкат пришёлся на третью проверку с пятиминутным бюджетом.
 *
 * ── Что держит сторож ─────────────────────────────────────────────────────
 *
 * Не число, а СВЯЗЬ: окно сверки выводится из времени сборки и больше него.
 * Вписать снова литерал — значит вернуть два независимых числа, которые
 * разойдутся при первой же правке одного из них.
 */
describe('проверка не выдаёт «не дождался» за «не доехало»', () => {
  it('окно сверки выведено из времени сборки, а не назначено литералом', () => {
    expect(code).toMatch(/SERVE_ATTEMPTS=.*MIN_BUILD_SECONDS/);
    expect(code).not.toMatch(/for i in \$\(seq 1 20\)/);
  });

  it('ждать сайт дают дольше, чем длится сборка', () => {
    const attempts = code.match(/SERVE_ATTEMPTS=\$\(\(\s*\(MIN_BUILD_SECONDS \* (\d+) \/ (\d+)\) \/ (\d+)\s*\)\)/);
    expect(attempts, 'формула окна сверки не найдена').not.toBeNull();
    const [mul, div, sleep] = attempts!.slice(1).map(Number);
    // Окно = попытки × сон. Оно обязано перекрывать саму сборку, иначе отказ
    // предрешён арифметикой, а не состоянием прода.
    const build = Number(code.match(/MIN_BUILD_SECONDS=(\d+)/)?.[1] ?? 0);
    expect(build).toBeGreaterThan(0);
    const windowSec = Math.floor((build * mul) / div / sleep) * sleep;
    expect(windowSec).toBeGreaterThan(build);
  });

  it('потолок задачи больше суммы окон ожидания', () => {
    // Иначе настоящим окном становится он, а числа внутри — украшение; это
    // сказано в собственной шапке файла, и здесь проверяется, что сказанное
    // осталось правдой после расширения сверки.
    const timeout = Number(code.match(/timeout-minutes:\s*(\d+)/)?.[1] ?? 0);
    expect(timeout).toBeGreaterThanOrEqual(90);
  });

  it('отказ по таймауту не утверждает, что миграции не накатывались', () => {
    // Утверждение о том, чего проверка знать не может. Читающий красный
    // прогон идёт накатывать руками — а код уже на проде.
    expect(code).not.toContain('миграции этого деплоя не накатывались');
    // Вместо приговора — измеренный факт и указание проверить самому.
    expect(code).toMatch(/ПРОВЕРЬТЕ ФАКТОМ/);
  });
});
