/**
 * POST /api/user/delete
 *
 * 152-ФЗ: удаление аккаунта и отзыв согласия на обработку ПД — сразу, а не
 * отметкой «через 30 дней» без исполнителя. Что стирается и что
 * обезличивается — lib/account/erase.ts.
 *
 * Тело: { confirm: true, phrase: 'УДАЛИТЬ', mode?: 'delete' | 'revoke_consent', reason? }.
 * Отказ 409 — есть предстоящая заявка (с аккаунтом — «отмените»; принятая
 * Кузьмичом в Telegram до привязки аккаунта или заведённая запросом мест —
 * «дождитесь поездки или попросите оператора»: отменить её сам он не может),
 * запрос мест в
 * туре, подключённый к его Telegram и ждущий ответа оператора, заказ мест в
 * машине на будущую поездку (запрос без ответа — «попросите отклонить»,
 * подтверждённый — «дождитесь поездки»: отменить его не может никто),
 * аренда снаряжения, срок которой не кончился
 * (заявка без ответа проката — не дольше 48 часов), живая бронь жилья (до заезда — «отмените», после —
 * «дождитесь выезда или напишите в поддержку»),
 * открытый контроль маршрута (нет отметки о возвращении) или закрытый
 * недавно, если сторож мог писать по нему контакту (ждём отбоя), возврат
 * денег по отменённой брони, который ещё не отмечен, или человек —
 * владелец карточки партнёра, через которую к нему идут заявки туристов:
 * карточка на витрине или с окном чата, туры, жильё или прокат на витрине,
 * предстоящие брони, заявки на жильё, заказы мест в его машинах на будущие
 * поездки, незакрытые аренды снаряжения.
 *
 * Ответ не говорит больше, чем сделано: что из ERASE_KEEP у человека осталось
 * (счёт в той же транзакции, после стирания), ответ называет словами — `kept`,
 * `unchecked` (счёт не выполнился), `unlinked` (к аккаунту не привязано),
 * `crm` (сколько карточек клиента у скольких партнёров не доказанно его и
 * остались) и `message` для человека. «Стёрты» — только когда не осталось
 * ничего.
 * Отказ проверки живых дел — 500 «не удалось», ничего не стёрто: «не смог
 * проверить» не равно «можно».
 * Auth: текущий пользователь. Админа так не удалить — роль снимается вручную.
 */
